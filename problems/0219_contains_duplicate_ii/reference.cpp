/*
 * LeetCode 219: 存在重复元素 II (Contains Duplicate II)
 *
 * 【题目本质】
 * 在大小为 k+1 的滑动窗口内检测是否存在重复元素。
 * 把"距离约束 abs(i-j) <= k"转化为"窗口约束"是关键。
 *
 * 【解法总览】
 * 解法1: 暴力双循环      — O(n·k) / O(1)     — 最直觉
 * 解法2: 哈希表(最近索引) — O(n)   / O(n)     — 面试首选 ⭐
 * 解法3: 滑动窗口+哈希集合 — O(n)  / O(min(n,k)) — 空间最优
 *
 * 【系列题对比】
 * 217 存在重复元素 I:   全局查重 → 用 set 即可
 * 219 存在重复元素 II:  距离 ≤ k 内查重 → 哈希表记录最近索引 / 滑动窗口
 * 220 存在重复元素 III: 距离 ≤ k 且值差 ≤ t → 有序集合 / 桶排序
 * 每一题在上一题基础上多加一个约束，解法也相应升级。
 */

// ============================================================
// 解法1: 暴力双循环 — 对每个元素向前扫描 k 个位置
// 时间: O(n·k)  空间: O(1)
//
// 【思路】
// 最直接的想法：对每个 i，检查 [i+1, i+k] 范围内是否有相同元素。
// 瓶颈：每个元素要线性扫描 k 个邻居，总体 O(n·k)。
// 当 n = k = 10^5 时约 10^10 次操作，会 TLE。
//
// 示例: nums = [1,2,3,1], k = 3
//   i=0: 检查 j∈[1,3] → nums[1]=2, nums[2]=3, nums[3]=1 → 1==1 ✓
//   → 返回 true
// ============================================================
class Solution1 {
public:
    bool containsNearbyDuplicate(vector<int>& nums, int k) {
        int n = nums.size();
        for (int i = 0; i < n; i++) {
            // 内层只扫描 [i+1, min(i+k, n-1)]，注意防越界
            for (int j = i + 1; j <= min(i + k, n - 1); j++) {
                if (nums[i] == nums[j]) {
                    return true;
                }
            }
        }
        return false;
    }
};

// ============================================================
// 解法2: 哈希表记录最近索引 — 面试首选 ⭐
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 暴力法瓶颈在于每次都要扫描 k 个元素来查找重复。
// 核心洞察：如果一个值出现了多次，只有"最近一次"出现才可能
// 和当前位置满足距离 ≤ k。更早的出现距离只会更大，不可能更优。
//
// 所以用 unordered_map<值, 最近索引>：
//   - 遍历到 nums[i] 时，查 map 中是否有这个值
//   - 如果有且 i - lastIndex ≤ k → true
//   - 否则更新 map[nums[i]] = i（覆盖为更近的索引）
//
// 示例: nums = [1,2,3,1,2,3], k = 2
//   i=0: map={1:0}
//   i=1: map={1:0, 2:1}
//   i=2: map={1:0, 2:1, 3:2}
//   i=3: val=1, lastIndex=0, |3-0|=3 > 2 → 更新 map={1:3, 2:1, 3:2}
//   i=4: val=2, lastIndex=1, |4-1|=3 > 2 → 更新 map={1:3, 2:4, 3:2}
//   i=5: val=3, lastIndex=2, |5-2|=3 > 2 → 更新
//   → 返回 false
// ============================================================
class Solution2 {
public:
    bool containsNearbyDuplicate(vector<int>& nums, int k) {
        unordered_map<int, int> lastIndex; // 值 → 最近出现的索引
        
        for (int i = 0; i < (int)nums.size(); i++) {
            auto it = lastIndex.find(nums[i]);
            // 之前出现过 且 距离 ≤ k → 找到合法配对
            if (it != lastIndex.end() && i - it->second <= k) {
                return true;
            }
            // 无论如何都更新为最新索引（覆盖旧值）
            // 为什么直接覆盖？因为旧的索引距离只会更大，不再有用
            lastIndex[nums[i]] = i;
        }
        return false;
    }
};

// ============================================================
// 解法3: 滑动窗口 + 哈希集合 — 空间最优
// 时间: O(n)  空间: O(min(n, k))
//
// 【思路】
// 换个视角：abs(i-j) ≤ k 等价于 i 和 j 在同一个大小为 k+1 的窗口内。
// 那问题变成：是否存在某个大小 ≤ k+1 的窗口包含重复元素？
//
// 我们用 unordered_set 维护当前窗口（最近 k 个已访问元素）：
//   1. 如果 nums[i] 已在 set 中 → 窗口内有重复 → true
//   2. 将 nums[i] 加入 set
//   3. 如果 set 大小 > k，移除 nums[i-k]（窗口最左边的元素）
//
// 窗口滑动过程: nums = [1,0,1,1], k = 1
//   i=0: set={}    → 1不在 → 加入 → set={1}   (size=1 ≤ k=1)
//   i=1: set={1}   → 0不在 → 加入 → set={1,0} (size=2 > k=1)
//                   → 删除 nums[0]=1 → set={0}
//   i=2: set={0}   → 1不在 → 加入 → set={0,1} (size=2 > k=1)
//                   → 删除 nums[1]=0 → set={1}
//   i=3: set={1}   → 1在!  → 返回 true ✓
//
// 为什么空间是 O(min(n,k))？
// - set 最多存 k 个元素（窗口大小）
// - 如果 k ≥ n，最多也就 n 个元素
// ============================================================
class Solution3 {
public:
    bool containsNearbyDuplicate(vector<int>& nums, int k) {
        unordered_set<int> window; // 维护窗口内的元素集合
        
        for (int i = 0; i < (int)nums.size(); i++) {
            // 窗口超出大小 k 时，移除最左边的元素
            // 为什么是 i > k 而不是 i >= k？
            // 因为窗口存的是 [i-k, i-1] 范围，最多 k 个元素
            // 当 i > k 时，nums[i-k-1] 已经出了窗口范围
            if (i > k) {
                window.erase(nums[i - k - 1]);
            }
            
            // insert 返回 pair<iterator, bool>
            // .second 为 false 表示元素已存在（插入失败）
            if (!window.insert(nums[i]).second) {
                return true; // 窗口内发现重复
            }
        }
        return false;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法          | 时间    | 空间        | 核心思想     |
// |--------------|---------|-------------|-------------|
// | 暴力双循环    | O(n·k)  | O(1)        | 线性扫描     |
// | 哈希表最近索引 | O(n)    | O(n)        | 空间换时间   |
// | 滑动窗口+set  | O(n)    | O(min(n,k)) | 窗口约束     |
//
// - 面试首选解法2：代码最短（约10行），思路清晰，一遍AC
// - 解法3在空间上更优，且体现"距离→窗口"的思维转换
// - 两者时间复杂度相同，区别在空间：解法2存所有不同值，解法3只存窗口内的值
//
// 【与系列题的代码差异】
// 217 → 219: 从"全局 set 查重"改为"记录最近索引+检查距离"
//             或者"全局 set"缩小为"固定大小窗口 set"
// 219 → 220: 从"set.count(nums[i])"精确匹配，改为
//             "set.lower_bound(nums[i]-t)"范围查找（需要有序 set）
//
// 【易错点】
//
// 1. 滑动窗口删除时机搞混：
//    ✗ if (i >= k) window.erase(nums[i-k]);
//      → 当 i=k 时删除 nums[0]，但 [0, k] 范围内的距离恰好等于 k，
//        是合法的！这会导致漏掉 abs(i-j) == k 的情况。
//    ✓ if (i > k) window.erase(nums[i-k-1]);
//      → 当 i=k+1 时才开始删除 nums[0]，此时 0 和 k+1 的距离已经 > k
//
// 2. 哈希表法忘记更新索引：
//    ✗ if (map.count(nums[i]) && i - map[nums[i]] <= k) return true;
//       // 如果距离 > k 就什么都不做 → 下一次距离只会更大，永远找不到
//    ✓ 无论距离是否满足，都要更新 map[nums[i]] = i
//
// 3. 使用 abs() 的多余性：
//    因为 i 是单调递增的，且 lastIndex < i，所以 i - lastIndex > 0
//    不需要 abs()，但写了也不会错
//
// 4. k = 0 时的行为：
//    k=0 意味着要求 i==j，但题目要求"不同索引"，所以必须返回 false。
//    三种解法都自然处理了这个 case：
//    - 暴力法：内层循环 j <= i+0，不执行
//    - 哈希表法：i - lastIndex ≥ 1 > 0 = k
//    - 滑动窗口法：i > 0 时立即删除，set 始终为空
//
// 【面试追问】
//
// Q1: 暴力法能过吗？复杂度分析？
//   → O(n·k)，最坏 O(n²)，n=10⁵ 时 TLE。
//     瓶颈在于每次线性扫描窗口查找重复。
//
// Q2: 你的哈希表存了所有元素，空间 O(n)。能优化吗？
//   → 用滑动窗口 + set，空间 O(min(n,k))。
//     因为只关心距离 ≤ k 的范围，窗口外的元素可以丢弃。
//
// Q3: 如果条件改成 abs(nums[i]-nums[j]) ≤ t 且 abs(i-j) ≤ k？
//   → LeetCode 220。不能用 unordered_set（不支持范围查找）。
//     方案A: 用 std::set（红黑树），lower_bound 查找 [val-t, val+t]，O(n·log k)。
//     方案B: 桶排序，桶大小 t+1，只查相邻桶，O(n) 时间 O(k) 空间。
//
// Q4: 如果需要返回所有满足条件的 (i,j) 对而不仅仅是 true/false？
//   → 哈希表法不行了（只存最近索引会丢失信息）。
//     需要 unordered_map<int, vector<int>> 存每个值的所有索引，
//     然后对每个值检查相邻索引差。时间 O(n)，空间 O(n)。
// ============================================================
