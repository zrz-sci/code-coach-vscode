/*
 * LeetCode 238: Product of Array Except Self
 * 
 * 【题目本质】
 * 对于每个位置 i，计算除了 nums[i] 以外所有元素的乘积。
 * 不能用除法，要求 O(n) 时间。
 * 核心思想：answer[i] = 左边所有元素的积 × 右边所有元素的积。
 *
 * 【解法总览】
 * 解法1: 暴力        — O(n²) / O(1)  — 直觉理解，会超时
 * 解法2: 前缀积+后缀积 — O(n)  / O(n)  — 面试首选
 * 解法3: 空间优化     — O(n)  / O(1)  — Follow-up 最优
 *
 * 可视化示例 nums = [1, 2, 3, 4]:
 *
 *   索引:      0    1    2    3
 *   nums:     [1,   2,   3,   4]
 *
 *   前缀积:   [1,   1,   2,   6]    ← L[i] = nums[0]*...*nums[i-1]
 *   后缀积:   [24,  12,  4,   1]    ← R[i] = nums[i+1]*...*nums[n-1]
 *
 *   answer:   [24,  12,  8,   6]    ← L[i] * R[i]
 */

// ============================================================
// 解法1: 暴力 — 对每个位置遍历整个数组求积
// 时间: O(n²)  空间: O(1)（不算输出数组）
//
// 【思路】
// 最朴素的做法：对于每个位置 i，遍历整个数组，跳过 i，
// 把其余 n-1 个元素乘在一起。
//
// 瓶颈：n 个位置各做 n-1 次乘法 → O(n²)。
// 对于 n=10^5，约 10^10 次操作，必然超时。
// 关键观察：相邻两个位置的乘积有大量重叠，应该复用。
// ============================================================
class Solution1 {
public:
    vector<int> productExceptSelf(vector<int>& nums) {
        int n = nums.size();
        vector<int> answer(n, 1);
        for (int i = 0; i < n; i++) {
            for (int j = 0; j < n; j++) {
                if (j != i) {
                    answer[i] *= nums[j];
                }
            }
        }
        return answer;
    }
};

// ============================================================
// 解法2: 前缀积 + 后缀积（两个辅助数组）
// 时间: O(n)  空间: O(n)
//
// 【思路】
// answer[i] = (i 左边所有元素之积) × (i 右边所有元素之积)
//
// 怎么想到的？
// - 暴力解中，对每个 i 都重新算整个数组的积，大量重复
// - 如果把"左边的积"和"右边的积"预处理好，每个位置直接 O(1) 查询
// - 类比前缀和：prefix[i] = prefix[i-1] + nums[i]
//   前缀积：L[i] = L[i-1] * nums[i-1]（注意不含 nums[i] 自身）
//
// 填表过程 nums = [1, 2, 3, 4]:
//   L[0]=1  L[1]=1*1=1  L[2]=1*2=2  L[3]=2*3=6
//   R[3]=1  R[2]=1*4=4  R[1]=4*3=12 R[0]=12*2=24
//   ans[0]=1*24=24  ans[1]=1*12=12  ans[2]=2*4=8  ans[3]=6*1=6
// ============================================================
class Solution2 {
public:
    vector<int> productExceptSelf(vector<int>& nums) {
        int n = nums.size();
        vector<int> L(n), R(n), answer(n);
        
        // 从左到右计算前缀积
        // L[i] 表示 nums[0..i-1] 的乘积（i 左边，不含 i）
        L[0] = 1;  // 0 左边没有元素，乘积为 1（乘法单位元）
        for (int i = 1; i < n; i++) {
            L[i] = L[i - 1] * nums[i - 1];
        }
        
        // 从右到左计算后缀积
        // R[i] 表示 nums[i+1..n-1] 的乘积（i 右边，不含 i）
        R[n - 1] = 1;  // n-1 右边没有元素
        for (int i = n - 2; i >= 0; i--) {
            R[i] = R[i + 1] * nums[i + 1];
        }
        
        // 合并：左边积 × 右边积
        for (int i = 0; i < n; i++) {
            answer[i] = L[i] * R[i];
        }
        
        return answer;
    }
};

// ============================================================
// 解法3: 空间优化 — O(1) 额外空间（Follow-up）
// 时间: O(n)  空间: O(1)（output 数组不算额外空间）
//
// 【思路】
// 解法2 的瓶颈：用了两个 O(n) 的辅助数组 L 和 R。
// 优化观察：
//   - L 数组可以直接存到 answer 中（第一趟：answer 暂存前缀积）
//   - R 数组从右到左顺序使用，只需一个滚动变量 suffix 即可
//
// 逐步演示 nums = [1, 2, 3, 4]:
//
// 第一趟（→）answer 存前缀积:
//   answer = [1, 1, 2, 6]
//
// 第二趟（←）suffix 滚动累乘:
//   i=3: answer[3] = 6 × 1 = 6,    suffix = 1 × 4 = 4
//   i=2: answer[2] = 2 × 4 = 8,    suffix = 4 × 3 = 12
//   i=1: answer[1] = 1 × 12 = 12,  suffix = 12 × 2 = 24
//   i=0: answer[0] = 1 × 24 = 24,  suffix = 24 × 1 = 24
//
// 最终 answer = [24, 12, 8, 6] ✓
// ============================================================
class Solution3 {
public:
    vector<int> productExceptSelf(vector<int>& nums) {
        int n = nums.size();
        vector<int> answer(n);
        
        // 第一趟：从左到右，answer[i] 暂存 i 左边所有元素的乘积
        answer[0] = 1;
        for (int i = 1; i < n; i++) {
            // 为什么是 nums[i-1] 而不是 nums[i]？
            // 因为前缀积不含 nums[i] 自身，只含 i 左边的元素
            answer[i] = answer[i - 1] * nums[i - 1];
        }
        
        // 第二趟：从右到左，用 suffix 滚动累乘右边的积
        int suffix = 1;  // 初始：最右边元素右边没有东西，积为 1
        for (int i = n - 1; i >= 0; i--) {
            // 关键：先乘再更新，顺序不能反！
            // 此时 suffix = nums[i+1] * nums[i+2] * ... * nums[n-1]
            answer[i] *= suffix;   // answer[i] = 左边积 × 右边积 → 最终结果
            suffix *= nums[i];     // 把 nums[i] 纳入 suffix，为位置 i-1 准备
        }
        
        return answer;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法   | 时间  | 额外空间 | 核心思想                    |
// |--------|-------|----------|-----------------------------|
// | 暴力   | O(n²) | O(1)    | 对每个位置重新遍历求积       |
// | 两数组 | O(n)  | O(n)    | 预处理前缀积和后缀积         |
// | 空间优化| O(n) | O(1)    | answer 复用为前缀积，suffix 滚动 |
//
// 解法2 vs 解法3：
//   - 算法思路完全相同，都是"左积 × 右积"
//   - 区别在于空间：解法3 把 L 数组复用为 answer，R 数组缩减为一个变量
//   - 面试中先写解法2（清晰），被追问 Follow-up 再优化为解法3
//
// 【易错点】
//
// 1. 初始化用 0 而不是 1：
//    ✗ answer[0] = 0  → 所有结果变成 0
//    ✓ answer[0] = 1  — 乘法的单位元是 1，左边没有元素 = 乘积为 1
//
// 2. 空间优化版第二趟更新顺序颠倒：
//    ✗ suffix *= nums[i]; answer[i] *= suffix;
//      → suffix 包含了 nums[i]，answer[i] 的结果会多乘一个 nums[i]
//    ✓ answer[i] *= suffix; suffix *= nums[i];
//      → suffix 只包含 i 右边的元素，乘完之后再把 nums[i] 加入
//
// 3. 前缀积下标搞错：
//    ✗ answer[i] = answer[i-1] * nums[i]  → 前缀积包含了自身
//    ✓ answer[i] = answer[i-1] * nums[i-1] — 前缀积只含 i 左边的元素
//
// 4. 误用除法：
//    ✗ totalProduct / nums[i] — 题目禁止除法，且 nums[i]=0 时除零
//    ✓ 前缀积 × 后缀积，完全不需要除法
//
// 【面试追问】
//
// Q1（基础理解）: 暴力 O(n²) 的瓶颈是什么？
//   → 每个位置重新遍历整个数组，没有复用已算过的中间结果。
//     相邻位置的乘积只差一个因子，却完全重新计算。
//
// Q2（核心优化）: 为什么不能用"总乘积÷自身"的方法？
//   → 题目禁止除法。即使允许，有 0 时需要分情况讨论：
//     0个0: answer[i] = total / nums[i]
//     1个0: 只有 0 所在位置有非零答案
//     2+个0: 全部为 0
//     逻辑复杂且容易出错。
//
// Q3（Follow-up）: 如何做到 O(1) 额外空间？
//   → 第一趟把前缀积直接写入 answer，第二趟用一个滚动变量 suffix
//     从右到左累乘，边乘边更新 answer。两个数组 → 一个变量。
//
// Q4（变体）: 如果改成"除了自身以外的和"呢？
//   → 同样思路，前缀和 + 后缀和。answer[i] = prefixSum[i] + suffixSum[i]。
//     甚至更简单：totalSum - nums[i] 即可（加法没有除零问题）。
// ============================================================
