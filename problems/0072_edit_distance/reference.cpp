/*
 * LeetCode 72: 编辑距离 (Edit Distance)
 *
 * 【题目本质】
 * 两个字符串之间的最小编辑距离（Levenshtein 距离）。
 * 每步可插入/删除/替换一个字符，求将 word1 变成 word2 的最少操作数。
 * 这是经典的二维字符串 DP 问题。
 *
 * 【解法总览】
 * 解法1: 暴力递归          — O(3^(m+n)) / O(m+n)   — 最直觉，展示递归结构
 * 解法2: 记忆化搜索        — O(m×n) / O(m×n)       — 消除重叠子问题
 * 解法3: 二维 DP (递推)    — O(m×n) / O(m×n)       — 面试首选 ⭐
 * 解法4: 一维 DP (空间优化) — O(m×n) / O(min(m,n))  — 进阶，面试加分
 */


// ============================================================
// 解法1: 暴力递归 — 穷举所有操作组合
// 时间: O(3^(m+n))  空间: O(m+n) 递归栈
//
// 【思路】
// 从两个字符串的末尾开始，比较当前字符：
//   - 相同：不用操作，两个指针都往前移
//   - 不同：尝试三种操作（插入/删除/替换），递归求解，取最小值+1
//
// 这是最自然的思路，但指数级复杂度完全不可行。
// 它的价值在于帮我们理清递归结构，为后面的 DP 打基础。
//
// 递归树 (word1="ab", word2="a" 为例):
//
//                 (2,1)
//              /    |     \
//        插入(2,0) 删除(1,1) 替换(1,0)
//           |      /  |  \       |
//          ...   ...  ... ...   ...
//
// 大量 (i,j) 对被重复计算 → 引出记忆化搜索
// ============================================================
class Solution1 {
public:
    int minDistance(string word1, string word2) {
        return dfs(word1, word2, word1.size(), word2.size());
    }

private:
    // i: 考虑 word1 的前 i 个字符
    // j: 考虑 word2 的前 j 个字符
    int dfs(string& w1, string& w2, int i, int j) {
        // base case: 其中一个字符串已经为空
        if (i == 0) return j;  // word1 为空，需要插入 j 个字符
        if (j == 0) return i;  // word2 为空，需要删除 i 个字符

        if (w1[i - 1] == w2[j - 1]) {
            // 字符相同，无需操作，同时前移
            return dfs(w1, w2, i - 1, j - 1);
        }

        // 字符不同，三种操作取最小
        return 1 + min({
            dfs(w1, w2, i, j - 1),     // 插入：在 word1 插入 word2[j]，匹配 word2[j]
            dfs(w1, w2, i - 1, j),     // 删除：删掉 word1[i]，看剩余部分
            dfs(w1, w2, i - 1, j - 1)  // 替换：word1[i] 换成 word2[j]，两边前移
        });
    }
};


// ============================================================
// 解法2: 记忆化搜索 — 递归 + 备忘录
// 时间: O(m×n)  空间: O(m×n)
//
// 【思路】
// 解法1的瓶颈：大量 (i, j) 对被重复计算。
// 解决方案：用 memo[i][j] 缓存已计算的结果。
// 每个 (i,j) 最多算一次，共 m×n 个状态，每个 O(1)。
//
// 这和自底向上 DP 在计算上完全等价，
// 区别只是遍历顺序：自顶向下(需要什么算什么) vs 自底向上(按顺序填表)。
// ============================================================
class Solution2 {
public:
    int minDistance(string word1, string word2) {
        int m = word1.size(), n = word2.size();
        vector<vector<int>> memo(m + 1, vector<int>(n + 1, -1));
        return dfs(word1, word2, m, n, memo);
    }

private:
    int dfs(string& w1, string& w2, int i, int j, vector<vector<int>>& memo) {
        if (i == 0) return j;
        if (j == 0) return i;
        if (memo[i][j] != -1) return memo[i][j];  // 已计算，直接返回

        if (w1[i - 1] == w2[j - 1]) {
            memo[i][j] = dfs(w1, w2, i - 1, j - 1, memo);
        } else {
            memo[i][j] = 1 + min({
                dfs(w1, w2, i, j - 1, memo),     // 插入
                dfs(w1, w2, i - 1, j, memo),     // 删除
                dfs(w1, w2, i - 1, j - 1, memo)  // 替换
            });
        }
        return memo[i][j];
    }
};


// ============================================================
// 解法3: 二维 DP（自底向上递推）— 面试首选 ⭐
// 时间: O(m×n)  空间: O(m×n)
//
// 【思路】
// 把记忆化搜索翻译成 for 循环填表。
// dp[i][j] = word1 前 i 个字符变成 word2 前 j 个字符的最少操作数。
//
// 状态转移:
//   字符相同: dp[i][j] = dp[i-1][j-1]        (不操作)
//   字符不同: dp[i][j] = 1 + min(
//               dp[i][j-1],     // 插入
//               dp[i-1][j],     // 删除
//               dp[i-1][j-1]    // 替换
//             )
//
// dp 填表过程 (word1="horse", word2="ros"):
//
//        ""   r   o   s
//    ""   0   1   2   3       ← dp[0][j] = j
//     h   1   1   2   3       ← dp[i][0] = i
//     o   2   2   1   2       
//     r   3   2   2   2       dp[i][j] 依赖:
//     s   4   3   3   2         ↖ dp[i-1][j-1] (替换/不操作)
//     e   5   4   4   3         ← dp[i][j-1]   (插入)
//                    ↑          ↑ dp[i-1][j]   (删除)
//                  答案=3
//
// 填表方向: 从左到右, 从上到下
// 保证计算 dp[i][j] 时, 三个依赖都已算好
// ============================================================
class Solution3 {
public:
    int minDistance(string word1, string word2) {
        int m = word1.size(), n = word2.size();
        vector<vector<int>> dp(m + 1, vector<int>(n + 1, 0));

        // 初始化: 空串和非空串之间的编辑距离
        for (int i = 0; i <= m; i++) dp[i][0] = i;  // 删 i 次
        for (int j = 0; j <= n; j++) dp[0][j] = j;  // 插 j 次

        for (int i = 1; i <= m; i++) {
            for (int j = 1; j <= n; j++) {
                // 注意: dp 下标从 1 开始，对应字符串下标 i-1, j-1
                if (word1[i - 1] == word2[j - 1]) {
                    // 字符相同，"免费"匹配，不需要操作
                    dp[i][j] = dp[i - 1][j - 1];
                } else {
                    // 字符不同，三种操作取最小
                    dp[i][j] = 1 + min({
                        dp[i][j - 1],     // 插入: 在 word1 当前位置插入 word2[j]
                        dp[i - 1][j],     // 删除: 跳过 word1[i]
                        dp[i - 1][j - 1]  // 替换: word1[i] → word2[j]
                    });
                }
            }
        }

        return dp[m][n];
    }
};


// ============================================================
// 解法4: 一维 DP（空间优化）— 滚动数组
// 时间: O(m×n)  空间: O(min(m,n))
//
// 【思路】
// 解法3中 dp[i][j] 只依赖:
//   - dp[i-1][j-1] (左上)
//   - dp[i-1][j]   (正上)
//   - dp[i][j-1]   (左边)
//
// 因此只需要一行数组。但有个陷阱:
//   当我们从左到右更新 dp[j] 时, dp[j] 的旧值(=上一行的 dp[i-1][j])
//   在更新后就丢失了。而下一个位置 dp[j+1] 还需要它作为"左上角"。
//   所以需要一个额外变量 prev 在更新前保存旧值。
//
// 滚动过程示意:
//   dp[]: [0, 1, 2, 3]  ← 初始，对应第0行
//
//   处理 'h' (i=1):
//     prev=dp[0]=0, dp[0]=1
//     j=1: temp=dp[1]=1, dp[1]=min(dp[0]+1,dp[1]+1,prev+1)=1, prev=1
//     j=2: temp=dp[2]=2, dp[2]=min(dp[1]+1,dp[2]+1,prev+1)=2, prev=2
//     j=3: temp=dp[3]=3, dp[3]=min(dp[2]+1,dp[3]+1,prev+1)=3, prev=3
//     dp[]: [1, 1, 2, 3]
//
//   处理 'o' (i=2):
//     prev=dp[0]=1, dp[0]=2
//     j=1: temp=1, dp[1]=min(2+1,1+1,1+1)=2, prev=1
//     j=2: temp=2, dp[2]=min(dp[1]+1,2+1,prev)=1 (o==o,不操作), prev=2
//     j=3: temp=3, dp[3]=min(dp[2]+1,3+1,prev+1)=2, prev=3
//     dp[]: [2, 2, 1, 2]
//
//   ... 继续处理 r, s, e ...
//   最终 dp[n] = 3
// ============================================================
class Solution4 {
public:
    int minDistance(string word1, string word2) {
        int m = word1.size(), n = word2.size();

        // 优化：让短的字符串作为"列"，节省空间
        if (m < n) return minDistance(word2, word1);

        vector<int> dp(n + 1);
        for (int j = 0; j <= n; j++) dp[j] = j;  // 初始化第0行

        for (int i = 1; i <= m; i++) {
            int prev = dp[0];  // prev = dp[i-1][0]，即左上角起始
            dp[0] = i;         // dp[i][0] = i

            for (int j = 1; j <= n; j++) {
                int temp = dp[j];  // 先保存 dp[i-1][j]（旧值），待会作为下一个位置的"左上角"

                if (word1[i - 1] == word2[j - 1]) {
                    dp[j] = prev;  // 字符相同，等于左上角（不操作）
                } else {
                    dp[j] = 1 + min({
                        dp[j - 1],  // 插入（当前行左边，已更新）
                        dp[j],      // 删除（上一行同列，还没被覆盖）
                        prev        // 替换（上一行左列，手动保存的）
                    });
                }

                prev = temp;  // 更新 prev: 下一轮的"左上角"就是本轮的"正上方"旧值
            }
        }

        return dp[n];
    }
};


// ============================================================
// 【解法对比】
//
// | 解法     | 时间       | 空间         | 适用场景                    |
// |---------|-----------|-------------|---------------------------|
// | 暴力递归  | O(3^(m+n))| O(m+n) 栈   | 仅用于理解递归结构            |
// | 记忆化搜索| O(m×n)    | O(m×n)      | 递归写法更直觉时              |
// | 二维 DP  | O(m×n)    | O(m×n)      | ⭐ 面试首选，代码清晰         |
// | 一维 DP  | O(m×n)    | O(min(m,n)) | 面试追问空间优化时            |
//
// 核心递进: 暴力递归 → 发现重叠子问题 → 记忆化 → 翻译成递推 → 空间优化
//
//
// 【易错点】
//
// 1. 下标偏移:
//    ✗ if (word1[i] == word2[j]) — 当 i,j 从 1 开始时越界
//    ✓ if (word1[i-1] == word2[j-1]) — dp 下标比字符串下标大 1
//
// 2. 初始化遗漏:
//    ✗ 只初始化一个方向 dp[0][j]=j，忘了 dp[i][0]=i
//    ✓ 两个方向都要: dp[i][0]=i 表示删 i 次, dp[0][j]=j 表示插 j 次
//
// 3. 空间优化时 prev 更新顺序:
//    ✗ dp[j] = ...; int temp = dp[j]; — 保存的是新值！
//    ✓ int temp = dp[j]; dp[j] = ...; prev = temp; — 先存旧值再更新
//
// 4. 字符相同时多加了 1:
//    ✗ dp[i][j] = 1 + dp[i-1][j-1] (相同字符也算了一步操作)
//    ✓ dp[i][j] = dp[i-1][j-1] (相同字符不需要任何操作)
//
//
// 【面试追问 — 递进链】
//
// Q1: 三种操作分别对应 DP 转移的哪一项？
// A1: dp[i][j-1]+1 = 插入(匹配word2[j])
//     dp[i-1][j]+1 = 删除(跳过word1[i])
//     dp[i-1][j-1]+1 = 替换(word1[i]→word2[j])
//     word1 的插入等价于 word2 的删除，所以两个操作是对称的。
//
// Q2: 能否 O(min(m,n)) 空间？
// A2: 见解法4，用一维数组滚动 + prev 变量保存左上角。
//     关键是确保读取旧值后再写入新值。
//
// Q3: 如果要输出具体操作序列怎么办？
// A3: 保留完整 dp 表，从 dp[m][n] 反向回溯。
//     每步看从哪个方向转移来的（左上=不操作/替换，上=删除，左=插入），
//     记录操作即可。此时空间无法优化，必须 O(m×n)。
//
// Q4: 如果不允许替换，只能插入和删除呢？
// A4: 去掉替换项：dp[i][j] = min(dp[i-1][j]+1, dp[i][j-1]+1)，
//     相同字符仍然 dp[i][j] = dp[i-1][j-1]。
//     等价于 m + n - 2*LCS(word1, word2)。
//
//
// 【相关题型】
// - 583. 两个字符串的删除操作 — 只允许删除，本质 m+n-2*LCS，复用同样的二维 DP
// - 1143. 最长公共子序列 — 编辑距离的姊妹题，dp 定义和填表方向几乎一样
// - 712. 两个字符串的最小 ASCII 删除和 — LCS 变体，+1 变成 +ASCII 值
// - 10/44. 正则/通配符匹配 — 更复杂的字符串匹配 DP，核心二维框架相同
// ============================================================
