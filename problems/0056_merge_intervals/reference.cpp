/*
 * LeetCode 56: 合并区间 (Merge Intervals)
 *
 * 【题目本质】
 * 将一组可能重叠的区间合并为互不重叠的最少区间。
 * 核心观察：排序后，重叠区间一定连续相邻，一次线性扫描即可完成合并。
 *
 * 【解法总览】
 * 解法1: 暴力合并       — O(n³) / O(n) — 两两检查反复合并
 * 解法2: 排序+线性扫描  — O(n log n) / O(n) — ⭐ 面试首选
 */

// ============================================================
// 解法1: 暴力合并 — 两两检查，反复迭代直到无重叠
// 时间: O(n³)  空间: O(n)
//
// 【思路】
// 最直觉的想法：不排序，直接两两检查区间是否重叠。
// 如果重叠就合并成新区间。但合并后可能产生新的重叠，
// 所以需要反复迭代，直到一轮下来没有任何合并发生。
//
// 这个解法的价值在于帮助理解题意和重叠条件，
// 面试中口述即可，不需要真正实现。
//
// 重叠条件（通用）:
// [a,b] 和 [c,d] 重叠 ⟺ a ≤ d && c ≤ b
//
// 示例: [1,3] 和 [2,6]
//   |------|         [1,3]
//      |---------|   [2,6]
//   1 ≤ 6 && 2 ≤ 3 → 重叠 → 合并为 [1,6]
// ============================================================
class Solution1 {
public:
    vector<vector<int>> merge(vector<vector<int>>& intervals) {
        vector<vector<int>> merged = intervals;
        
        bool changed = true;
        while (changed) {
            changed = false;
            vector<vector<int>> next;
            vector<bool> used(merged.size(), false);
            
            for (int i = 0; i < (int)merged.size(); i++) {
                if (used[i]) continue;
                vector<int> cur = merged[i];
                for (int j = i + 1; j < (int)merged.size(); j++) {
                    if (used[j]) continue;
                    // 通用重叠条件：互相有交集
                    if (cur[0] <= merged[j][1] && merged[j][0] <= cur[1]) {
                        cur[0] = min(cur[0], merged[j][0]);
                        cur[1] = max(cur[1], merged[j][1]);
                        used[j] = true;
                        changed = true;
                    }
                }
                next.push_back(cur);
            }
            merged = next;
        }
        return merged;
    }
};

// ============================================================
// 解法2: 排序 + 线性扫描 — ⭐ 面试首选
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 暴力解的瓶颈：无序时必须两两检查，而且合并后还可能产生新重叠。
//
// 关键观察：如果按起点排序，重叠的区间一定是连续相邻的！
// 证明：排序后 start[0] ≤ start[1] ≤ ... ≤ start[n-1]
//   若 end[i] < start[i+1]，则对所有 j > i+1:
//   start[j] ≥ start[i+1] > end[i]，所以 i 和 j 也不重叠。
//   → 一旦断开，后面不可能再和前面重叠。
//
// 算法：
// 1. 按起点排序
// 2. 维护结果数组 merged，逐个扫描区间
// 3. 若当前区间与 merged 最后一个重叠 → 合并(扩展 end)
//    若不重叠 → 加入新区间
//
// 完整扫描过程（示例1）:
//
//  排序后: [1,3], [2,6], [8,10], [15,18]
//
//  数轴:
//  1---3             [1,3]
//    2------6        [2,6] → 重叠(2≤3)，合并为[1,6]
//           8--10    [8,10] → 不重叠(8>6)，新区间
//                15---18  [15,18] → 不重叠(15>10)，新区间
//
//  Step1: merged=[], 加入[1,3]     → merged=[[1,3]]
//  Step2: start=2 ≤ end=3 → 重叠   → merged=[[1,6]]
//  Step3: start=8 > end=6 → 不重叠 → merged=[[1,6],[8,10]]
//  Step4: start=15 > end=10 → 不重叠 → merged=[[1,6],[8,10],[15,18]]
//
// 包含关系的例子:
//  |--------------|     [1,10]
//     |---|             [2,3]
//  → start=2 ≤ end=10 → 重叠
//  → end = max(10, 3) = 10 → 结果仍是 [1,10]
//  （如果不取 max，会错误地把 end 变成 3）
// ============================================================
class Solution2 {
public:
    vector<vector<int>> merge(vector<vector<int>>& intervals) {
        // 按起点排序（起点相同时 end 顺序不影响正确性）
        sort(intervals.begin(), intervals.end());
        
        vector<vector<int>> merged;
        
        for (auto& interval : intervals) {
            // 不重叠条件：当前 start > merged 最后一个区间的 end
            if (merged.empty() || interval[0] > merged.back()[1]) {
                // 不重叠，作为新区间加入
                merged.push_back(interval);
            } else {
                // 重叠，合并 —— 扩展右边界
                // 必须用 max：防止包含关系（如[1,10]和[2,3]）
                merged.back()[1] = max(merged.back()[1], interval[1]);
            }
        }
        
        return merged;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度     | 暴力合并       | 排序+线性扫描     |
// |----------|---------------|-------------------|
// | 时间     | O(n³)         | O(n log n)        |
// | 空间     | O(n)          | O(n) 结果数组     |
// | 核心思想 | 两两检查反复合并 | 排序后一次扫描    |
// | 面试推荐 | ✗ 口述即可     | ✓ 必须写出        |
//
// 排序解法是区间类问题的通用思路起点：
// 排序 → 消除无序性 → 线性扫描处理相邻关系
//
// ============================================================
// 【易错点】
//
// 1. 合并时直接赋值 end，不取 max:
//    ✗ merged.back()[1] = interval[1];
//    ✓ merged.back()[1] = max(merged.back()[1], interval[1]);
//    原因：[1,10] 合并 [2,3]，直接赋值会把 end 从 10 变成 3。
//
// 2. 重叠判断用 >= 而不是 >:
//    ✗ interval[0] >= merged.back()[1]  → [1,4]和[4,5]被判为不重叠
//    ✓ interval[0] > merged.back()[1]   → 端点相切也算重叠
//    题目示例明确 [1,4]和[4,5] 要合并为 [1,5]。
//
// 3. 忘记排序:
//    [4,7],[1,4] 不排序直接扫描会输出两个区间而不是 [1,7]。
//
// 4. 按 end 排序:
//    应该按 start 排序。按 end 排序无法保证重叠区间相邻。
//
// ============================================================
// 【面试追问】（递进链）
//
// Q1（基础理解）: 两个区间重叠的条件？
// A: [a,b]和[c,d]重叠 ⟺ a≤d && c≤b。
//    排序后简化为 c≤b（因为排序保证 a≤c）。
//
// Q2（正确性证明）: 为什么排序后一次扫描就够了？
// A: 排序后起点递增。若 end[i]<start[i+1]，
//    则对所有j>i+1，start[j]≥start[i+1]>end[i]，
//    区间i和后面所有区间都不重叠。重叠区间构成连续段。
//
// Q3（变体）: 如果区间是流式输入的，每次插入一个区间后返回合并结果？
// A: 用 std::map 维护已合并的有序区间集合，
//    每次插入用二分定位可能重叠的区间，合并后删除被覆盖的旧区间。
//    单次插入 O(k log n)，k 是被合并的区间数。
//    参见 LeetCode 57（插入区间）。
//
// Q4（变体）: 只判断是否存在任何重叠，不需要合并？
// A: 排序后一次扫描检查 start[i+1]≤end[i] 即可。O(n log n)。
