/*
 * LeetCode 933: 最近的请求次数 (Number of Recent Calls)
 *
 * 【题目本质】
 * 设计一个计数器，每次 ping(t) 返回 [t-3000, t] 时间窗口内的请求数。
 * 由于时间严格递增，用队列维护滑动窗口即可。
 *
 * 【解法总览】
 * 解法1: 队列         — 均摊O(1) / O(W) — 标准解法 ⭐
 * 解法2: deque        — 均摊O(1) / O(W) — 等价变体
 * 解法3: vector+二分  — O(logN) / O(N)  — 不删除旧数据
 */

// ============================================================
// 解法1: 队列滑动窗口 — 均摊 O(1) 每次 ping ⭐
//
// 【思路】
// 利用"ping 时间严格递增"这个关键条件:
//   - 新请求一定比所有旧请求晚 → 入队尾
//   - 过期请求一定在队首 → 从队首弹出
//   - 这正是队列 (FIFO) 的使用场景!
//
// 每次 ping(t):
//   1. push(t) — 新请求入队
//   2. while(队首 < t-3000) pop — 弹出所有过期请求
//   3. return 队列大小 — 窗口内请求数
//
// 操作过程示意:
//
//   ping(1):
//     push 1 → queue: [1]
//     无过期 → return 1
//
//   ping(100):
//     push 100 → queue: [1, 100]
//     窗口 [-2900,100]: 1 >= -2900 ✓ → 无过期
//     return 2
//
//   ping(3001):
//     push 3001 → queue: [1, 100, 3001]
//     窗口 [1,3001]: 1 >= 1 ✓ → 无过期
//     return 3
//
//   ping(3002):
//     push 3002 → queue: [1, 100, 3001, 3002]
//     窗口 [2,3002]: 1 < 2 → pop 1!
//     queue: [100, 3001, 3002]
//     100 >= 2 ✓ → 停止
//     return 3
//
//   时间线:
//
//     t=1   t=100              t=3001 t=3002
//      |     |                   |     |
//      v     v                   v     v
//     -+-----+---···-------------+--+--→
//                                |     |
//                          t-3000=2    t=3002
//                          ←── 窗口 ──→
//
//     t=1 出窗口 (1 < 2) → 弹出
//     t=100, 3001, 3002 在窗口内 → 保留
//     答案 = 3
//
// 均摊分析:
//   每个元素至多入队1次 + 出队1次 = O(2) 操作
//   N 次 ping 总操作 O(2N) = O(N), 均摊每次 O(1)
//
// ============================================================
class RecentCounter {
    queue<int> q;  // 存储窗口内所有请求的时间戳

public:
    RecentCounter() {}

    int ping(int t) {
        // Step 1: 新请求入队
        q.push(t);

        // Step 2: 弹出所有过期请求 (时间 < t-3000)
        // 注意: 窗口是 [t-3000, t] 闭区间, 等于 t-3000 的要保留
        // 由于刚 push 了 t, 队列不可能为空, 不需要检查 empty
        while (q.front() < t - 3000) {
            q.pop();
        }

        // Step 3: 返回窗口内请求数 = 队列大小
        return q.size();
    }
};

// ============================================================
// 解法2: deque 变体 — 功能更灵活
//
// 和队列版本等价，但 deque 支持两端操作，在更复杂的场景中更灵活。
// 例如需要查看队尾元素时 deque 有 back()，queue 没有。
// ============================================================
class RecentCounter2 {
    deque<int> dq;

public:
    RecentCounter2() {}

    int ping(int t) {
        dq.push_back(t);
        // 弹出队首过期元素
        while (!dq.empty() && dq.front() < t - 3000) {
            dq.pop_front();
        }
        return dq.size();
    }
};

// ============================================================
// 解法3: vector + 二分查找 — 不删除旧数据
//
// 【思路】
// 将所有请求时间追加到 vector 末尾（天然有序，因为时间递增）。
// 每次 ping(t) 用 lower_bound 找到第一个 >= t-3000 的位置，
// 从该位置到末尾的元素就是窗口内的请求。
//
// 优点: 每次 ping 是严格 O(log N)（不是均摊）
// 缺点: 不删除旧数据，空间 O(N) 而不是 O(W)
//
// 面试中作为追问的备选方案提及。
// ============================================================
class RecentCounter3 {
    vector<int> times;

public:
    RecentCounter3() {}

    int ping(int t) {
        times.push_back(t);
        // 二分查找: 第一个 >= t-3000 的位置
        int left = lower_bound(times.begin(), times.end(), t - 3000) - times.begin();
        // 窗口内请求数 = 从 left 到末尾
        return times.size() - left;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 单次时间     | 空间   | 面试推荐 |
// |------------|-------------|--------|---------|
// | 队列        | 均摊 O(1)  | O(W)   | ⭐⭐⭐    |
// | deque       | 均摊 O(1)  | O(W)   | ⭐⭐⭐    |
// | vector+二分 | O(log N)   | O(N)   | 追问备选  |
//
// W = 窗口大小 (最多 3001 个元素), N = 总调用次数
// 队列和 deque 等价，推荐使用更简洁的 queue
//
// ============================================================
// 【易错点】
//
// 1. while 条件用 <= 误排除边界:
//    ✗ while (q.front() <= t - 3000) — 把恰好 t-3000 的也弹了
//    ✓ while (q.front() < t - 3000)  — [t-3000, t] 是闭区间
//
// 2. 先 pop 再 push 导致空队列:
//    ✗ while (!q.empty() && q.front() < t-3000) q.pop(); q.push(t);
//    虽然功能上等价 (因为 t 比所有旧元素大, 不会被弹出),
//    但逻辑上"先入队再清理"更自然, 且不需要 empty 检查
//
// 3. 混淆"均摊 O(1)"和"严格 O(1)":
//    单次 ping 最坏可能弹出 O(N) 个元素
//    但 N 次总操作 O(N), 均摊每次 O(1)
//    面试时一定说 "amortized O(1)", 不说 "O(1)"
//
// ============================================================
// 【面试追问 Interview Follow-ups】
//
// Q1: 均摊 O(1) 是什么意思?
// A1: 每个元素生命周期只入队1次、出队1次。N次ping总操作O(2N)。
//     虽然某次ping可能弹出O(N)个，但这N个之后不再被操作。
//
// Q2: 如果时间不严格递增 (允许 t' <= t)?
// A2: 队列不再天然有序，不能只从队首弹出。
//     方案1: 用 multiset, 每次 erase begin()~lower_bound(t-3000)，O(log N)
//     方案2: 维护有序数据结构
//
// Q3: 如果窗口大小不固定，需要支持 setWindow(k)?
// A3: 队列方案不变，只需将 3000 替换为可配置的 k。
//     弹出条件变为 q.front() < t - k。
//
// Q4: 这道题和 LC 239 Sliding Window Maximum 的关系?
// A4: 都是滑动窗口题。本题只需计数 → 普通队列。
//     LC 239 需要取窗口最大值 → 单调递减 deque。
//     本题是滑动窗口的入门，239 是进阶。
// ============================================================
