/*
 * LeetCode 253: 会议室 II (Meeting Rooms II)
 *
 * 【题目本质】
 * 给定若干时间区间，求任意时刻最大重叠数（即同时进行的会议数）。
 * 这个最大值就是所需的最少会议室数量。
 *
 * 【解法总览】
 * 解法1: 排序+双指针     — O(n log n) / O(n)  — 最简洁，面试首选
 * 解法2: 排序+最小堆     — O(n log n) / O(n)  — 模拟分配，直觉最强
 * 解法3: 差分/扫描线     — O(n log n) / O(n)  — 最通用，可推广到加权
 * 解法4: 差分数组(值域)  — O(n + T) / O(T)    — 时间范围小时最优
 */

// ============================================================
// 解法1: 排序 + 双指针 — 面试首选
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 关键观察：开始时间和结束时间可以分开处理！
// 我们不关心"哪个开始对应哪个结束"，只关心在时间轴上
// "又有一个会议开始了"还是"有一个会议结束了"。
//
// 把所有 start 和 end 分别排序，用两个指针模拟扫描：
// - 如果当前最早的 start < 当前最早的 end → 有新会议但没房释放 → rooms++
// - 否则 → 有房释放 → rooms--, 结束指针前进
//
// 为什么分离排序是正确的？
// 因为排序后第 i 个 end 不一定是第 i 个 start 对应的会议的结束时间，
// 但这不影响计数——我们只需要知道"到目前为止有几个开始、几个结束"。
//
// 双指针扫描过程 (示例1: [[0,30],[5,10],[15,20]]):
//   starts: [0, 5, 15]    ends: [10, 20, 30]
//            ↑s                  ↑e
//
//   s=0  < e=10 → rooms=1, s++    maxRooms=1
//   s=5  < e=10 → rooms=2, s++    maxRooms=2
//   s=15 >= e=10 → rooms=1, e++
//   s=15 < e=20 → rooms=2, s++    maxRooms=2
//   s用完 → 答案=2
// ============================================================
class Solution1 {
public:
    int minMeetingRooms(vector<vector<int>>& intervals) {
        int n = intervals.size();
        vector<int> starts(n), ends(n);
        for (int i = 0; i < n; i++) {
            starts[i] = intervals[i][0];
            ends[i] = intervals[i][1];
        }
        sort(starts.begin(), starts.end());
        sort(ends.begin(), ends.end());

        int rooms = 0, maxRooms = 0;
        int s = 0, e = 0;
        while (s < n) {
            if (starts[s] < ends[e]) {
                // 新会议已经开始，但最早的结束还没到 → 必须开新房间
                rooms++;
                maxRooms = max(maxRooms, rooms);
                s++;
            } else {
                // 有会议已经结束（或恰好结束），释放一间房
                rooms--;
                e++;
            }
        }
        return maxRooms;
    }
};

// ============================================================
// 解法2: 排序 + 最小堆 — 模拟真实分配过程
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 按开始时间排序后，逐个分配会议到房间。
// 用最小堆维护"所有正在使用的房间的结束时间"。
// 堆顶 = 最早结束的房间。
//
// 对于新来的会议 [start, end]:
// - 如果堆顶 <= start → 最早的房间已经空了 → 复用它（弹出旧，压入新end）
// - 否则 → 没有空房间 → 开新房间（直接压入end）
// 堆的大小就是当前同时使用的房间数。
//
// 最小堆过程 (示例1):
//   排序后: [0,30], [5,10], [15,20]
//
//   处理[0,30]:  堆空 → 开新房间        堆={30}        rooms=1
//   处理[5,10]:  堆顶30 > 5 → 开新房间  堆={10, 30}    rooms=2
//   处理[15,20]: 堆顶10 <= 15 → 复用！  堆={20, 30}    rooms=2
//                弹出10, 压入20
//   答案 = 堆最大size = 2
// ============================================================
class Solution2 {
public:
    int minMeetingRooms(vector<vector<int>>& intervals) {
        // 按开始时间排序，模拟时间推进
        sort(intervals.begin(), intervals.end());

        // 最小堆：每个元素是某间房的"最早空闲时刻"（即结束时间）
        priority_queue<int, vector<int>, greater<int>> pq;

        for (auto& iv : intervals) {
            // 贪心：尝试复用最早结束的房间
            if (!pq.empty() && pq.top() <= iv[0]) {
                pq.pop();  // 释放这间房
            }
            // 无论复用还是新开，都要记录当前会议的结束时间
            pq.push(iv[1]);
        }

        // 堆的大小 = 需要的最少房间数
        return pq.size();
    }
};

// ============================================================
// 解法3: 差分/扫描线 — 最通用的区间重叠计数方法
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 每个区间 [s, e) 在时间轴上产生两个事件：
//   时刻 s: +1（开始，需要一间房）
//   时刻 e: -1（结束，释放一间房）
//
// 把所有事件按时间排序（时间相同时结束排前面），
// 然后做前缀和，最大值就是最大并发数。
//
// 为什么结束排前面？
// 因为 [5,10] 和 [10,15]，时刻10时先释放再分配，可以复用。
// 如果先+1后-1，会在时刻10瞬间多算一间房。
//
// 扫描过程 (示例1):
//   事件: (0,+1), (5,+1), (10,-1), (15,+1), (20,-1), (30,-1)
//   前缀和:  1,     2,      1,       2,       1,       0
//   最大值 = 2
// ============================================================
class Solution3 {
public:
    int minMeetingRooms(vector<vector<int>>& intervals) {
        vector<pair<int, int>> events;
        for (auto& iv : intervals) {
            events.push_back({iv[0], 1});   // 开始 +1
            events.push_back({iv[1], -1});  // 结束 -1
        }

        // 排序：时间升序；时间相同时 -1 排在 +1 前面
        sort(events.begin(), events.end(), [](auto& a, auto& b) {
            if (a.first != b.first) return a.first < b.first;
            return a.second < b.second;  // -1 < 1
        });

        int rooms = 0, maxRooms = 0;
        for (auto& [time, delta] : events) {
            rooms += delta;
            maxRooms = max(maxRooms, rooms);
        }
        return maxRooms;
    }
};

// ============================================================
// 解法4: 差分数组 (值域直接标记) — 时间范围小时最优
// 时间: O(n + T)  空间: O(T)  T = 最大时间值
//
// 【思路】
// 如果时间范围 T 较小（题目说 end <= 10⁶），
// 可以直接用数组做差分，避免排序的 O(n log n)。
//
// diff[start]++, diff[end]--，然后扫一遍求前缀最大值。
// 当 n 远大于 T 时（如 n=10⁸, T=10⁶），这比排序更快。
//
// 注意：本题 n <= 10⁴，T <= 10⁶，所以空间偏大，
// 面试中主要作为 Follow-up 思路讨论。
// ============================================================
class Solution4 {
public:
    int minMeetingRooms(vector<vector<int>>& intervals) {
        // 找到最大结束时间，确定差分数组大小
        int maxTime = 0;
        for (auto& iv : intervals) {
            maxTime = max(maxTime, iv[1]);
        }

        vector<int> diff(maxTime + 1, 0);
        for (auto& iv : intervals) {
            diff[iv[0]]++;   // 开始时刻 +1
            diff[iv[1]]--;   // 结束时刻 -1
        }

        // 扫一遍做前缀和，取最大值
        int rooms = 0, maxRooms = 0;
        for (int t = 0; t <= maxTime; t++) {
            rooms += diff[t];
            maxRooms = max(maxRooms, rooms);
        }
        return maxRooms;
    }
};

