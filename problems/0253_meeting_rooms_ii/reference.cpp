// 【解法对比】
//
// | 维度         | 双指针(解法1) | 最小堆(解法2) | 扫描线(解法3) | 差分数组(解法4) |
// |-------------|--------------|--------------|--------------|----------------|
// | 时间         | O(n log n)   | O(n log n)   | O(n log n)   | O(n + T)       |
// | 空间         | O(n)         | O(n)         | O(n)         | O(T)           |
// | 代码简洁度    | ★★★★★       | ★★★★         | ★★★★         | ★★★★           |
// | 直觉理解      | 需要想通     | 最直觉       | 数学化       | 最简单         |
// | 可扩展性      | 仅计数       | 可追踪分配   | 可加权       | 可加权         |
// | 面试推荐      | ⭐首选       | ⭐必须会     | 加分项       | Follow-up      |
//
// 选择建议：
// - 面试默认写解法1（双指针）或解法2（最小堆），看面试官偏好
// - 如果被问"还有其他方法吗"，给出解法3（扫描线）
// - 如果被问"数据量极大怎么办"，讨论解法4（差分数组）
//
// 【易错点】
//
// 1. 双指针: starts[s] < ends[e] 必须用 <，不能用 <=
//    ✗ if (starts[s] <= ends[e]) rooms++   → [5,10],[10,15] 多算一间房
//    ✓ if (starts[s] < ends[e]) rooms++    → 相等时先释放再分配
//
// 2. 最小堆: pq.top() <= iv[0] 必须用 <=，不能用 <
//    ✗ if (pq.top() < iv[0]) pq.pop()  → 结束==开始时不复用，多开一间
//    ✓ if (pq.top() <= iv[0]) pq.pop() → 恰好结束可以复用
//    注意：这两个易错点的不等号方向相反！根源是同一个语义的不同表达。
//
// 3. 扫描线排序: 同一时刻的结束事件必须排在开始事件前面
//    ✗ 仅按 time 排序 → 同时刻先 +1 后 -1，瞬间多算一间
//    ✓ 时间相同时 delta=-1 排在 delta=+1 前面
//
// 4. 最小堆忘记对 intervals 排序
//    ✗ 不排序直接逐个处理 → 先处理了晚开始的会议，逻辑错误
//    ✓ 必须按 start 升序排列，保证按时间顺序分配
//
// 【面试追问】
//
// Q1(基础): "暴力解怎么做？复杂度多少？"
// → 对每个时刻统计并发会议数，O(T × n)。或者对每对会议检查重叠，O(n²)。
//   瓶颈：遍历了大量无意义的时刻/配对。
//
// Q2(优化): "双指针为什么把 start 和 end 分离后排序仍然正确？"
// → 因为我们只需要计数"到目前为止有多少开始、多少结束"，
//   不需要知道哪个开始和哪个结束配对。分离后排序不影响计数结果，
//   因为任意时刻的"正在进行数 = 已开始数 - 已结束数"。
//
// Q3(变体): "如果要返回每个会议分配到哪间房间？"
// → 用最小堆解法，堆中存 {结束时间, 房间编号}。
//   复用时弹出的就是可用房间号；开新房间时分配新编号。
//   双指针和扫描线无法追踪分配关系。
//
// Q4(进阶): "如果 n 极大（10⁸）但时间范围 T 较小（10⁶），怎么优化？"
// → 差分数组：diff[start]++, diff[end]--，O(n) 标记 + O(T) 扫描。
//   总体 O(n + T)，避免了排序的 O(n log n)。
// ============================================================
