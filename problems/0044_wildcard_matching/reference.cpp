/*
 * LeetCode 44: Wildcard Matching (通配符匹配)
 *
 * 【题目本质】
 * 双序列匹配问题：s 和 p 逐步匹配，难点在于 * 可以匹配 0~任意多个字符。
 * 需要判定 p 能否完全覆盖 s。
 *
 * 【解法总览】
 * 解法1: 暴力递归        — O(2^(m+n)) / O(m+n)  — 最直觉
 * 解法2: 记忆化搜索      — O(mn) / O(mn)         — 消除重叠子问题
 * 解法3: 二维 DP         — O(mn) / O(mn)         — 面试首选
 * 解法4: 一维 DP (滚动)  — O(mn) / O(n)          — 空间优化
 * 解法5: 贪心双指针      — O(mn) 最坏 / O(1)     — 最优空间
 */

// ============================================================
// 解法1: 暴力递归 — 遇到 * 分两支递归
// 时间: O(2^(m+n)) 最坏  空间: O(m+n) 递归栈
//
// 【思路】
// 用两个指针 i、j 分别扫描 s 和 p：
// - 普通字符/? ：必须匹配当前字符，双方各前进一步
// - *         ：两种选择——匹配0个(j+1) 或 至少匹配1个(i+1,j不动)
// 瓶颈：多个 * 时分支指数爆炸。
// ============================================================
class Solution1 {
public:
    bool isMatch(string s, string p) {
        return dfs(s, p, 0, 0);
    }

private:
    bool dfs(const string& s, const string& p, int i, int j) {
        if (j == (int)p.size()) return i == (int)s.size();

        if (p[j] == '*') {
            // * 匹配空序列 || * 至少吃掉 s[i] 一个字符
            return dfs(s, p, i, j + 1) ||
                   (i < (int)s.size() && dfs(s, p, i + 1, j));
        }

        // 普通字符或 ?
        if (i < (int)s.size() && (p[j] == '?' || s[i] == p[j])) {
            return dfs(s, p, i + 1, j + 1);
        }
        return false;
    }
};

// ============================================================
// 解法2: 记忆化搜索 — 加 memo 消除重叠子问题
// 时间: O(mn)  空间: O(mn)
//
// 【思路】
// 解法1的瓶颈：不同递归路径可能到达相同的 (i, j) 状态，
// 而递归参数只有 (i, j)，状态空间 = (m+1)×(n+1)，
// 用 memo 缓存结果即可从指数降到多项式。
// ============================================================
class Solution2 {
public:
    bool isMatch(string s, string p) {
        int m = s.size(), n = p.size();
        // 0=未计算, 1=true, -1=false
        vector<vector<int>> memo(m + 1, vector<int>(n + 1, 0));
        return dfs(s, p, 0, 0, memo);
    }

private:
    bool dfs(const string& s, const string& p, int i, int j,
             vector<vector<int>>& memo) {
        if (memo[i][j] != 0) return memo[i][j] == 1;

        bool res;
        if (j == (int)p.size()) {
            res = (i == (int)s.size());
        } else if (p[j] == '*') {
            res = dfs(s, p, i, j + 1, memo) ||
                  (i < (int)s.size() && dfs(s, p, i + 1, j, memo));
        } else if (i < (int)s.size() && (p[j] == '?' || s[i] == p[j])) {
            res = dfs(s, p, i + 1, j + 1, memo);
        } else {
            res = false;
        }

        memo[i][j] = res ? 1 : -1;
        return res;
    }
};

// ============================================================
// 解法3: 二维 DP — 自底向上填表（⭐ 面试首选）
// 时间: O(mn)  空间: O(mn)
//
// 【思路】
// 状态定义: dp[i][j] = s 的前 i 个字符是否能被 p 的前 j 个字符匹配
//
// 状态转移:
//   p[j-1] 是字母或 '?':
//     dp[i][j] = dp[i-1][j-1] && (s[i-1]==p[j-1] || p[j-1]=='?')
//
//   p[j-1] 是 '*':
//     dp[i][j] = dp[i][j-1]    // * 匹配空序列（跳过 *）
//             || dp[i-1][j]     // * 至少吃一个字符（* 保留继续吃）
//
// 为什么 dp[i-1][j] 就够了（不需要枚举 * 吃了多少个）？
// 因为 dp[i-1][j] 内部又会展开为 dp[i-2][j] || dp[i-1][j-1]，
// 递推链自然覆盖了 * 吃 0,1,2,...,i 个字符的所有情况。
//
// DP 填表示例: s = "adceb", p = "*a*b"
//
//        ""   *    a    *    b
//   ""  [ T] [ T] [ F] [ F] [ F]
//    a  [ F] [ T] [ T] [ T] [ F]
//    d  [ F] [ T] [ F] [ T] [ F]
//    c  [ F] [ T] [ F] [ T] [ F]
//    e  [ F] [ T] [ F] [ T] [ F]
//    b  [ F] [ T] [ F] [ T] [ T] ← 答案 dp[5][4] = true
//
// 填表方向: 从左到右，从上到下
// 依赖关系: dp[i][j] ← dp[i-1][j-1](左上), dp[i-1][j](上), dp[i][j-1](左)
// ============================================================
class Solution3 {
public:
    bool isMatch(string s, string p) {
        int m = s.size(), n = p.size();
        vector<vector<bool>> dp(m + 1, vector<bool>(n + 1, false));

        // base case: 空串 vs 空模式
        dp[0][0] = true;

        // base case: 空串 vs p 的前 j 个字符
        // 只有连续的 * 才能匹配空串
        for (int j = 1; j <= n; j++) {
            // 一旦 p[j-1] 不是 *，后面全是 false（默认值）
            dp[0][j] = (p[j - 1] == '*') && dp[0][j - 1];
        }

        for (int i = 1; i <= m; i++) {
            for (int j = 1; j <= n; j++) {
                if (p[j - 1] == '*') {
                    // * 匹配空(跳过*) || * 至少吃一个(s退一步,*保留)
                    dp[i][j] = dp[i][j - 1] || dp[i - 1][j];
                } else {
                    // 当前字符必须匹配，且前缀也必须匹配
                    dp[i][j] = dp[i - 1][j - 1] &&
                               (p[j - 1] == '?' || s[i - 1] == p[j - 1]);
                }
            }
        }

        return dp[m][n];
    }
};

// ============================================================
// 解法4: 一维 DP (空间优化) — 滚动数组
// 时间: O(mn)  空间: O(n)
//
// 【思路】
// 解法3中 dp[i][j] 只依赖：
//   - dp[i-1][j-1] (左上角 = 上一行前一列)
//   - dp[i-1][j]   (正上方 = 上一行同列)
//   - dp[i][j-1]   (左边 = 当前行前一列，已更新)
//
// 因此只需一维数组 dp[j]，用 prev 变量保存"左上角"。
//
// 关键：每行开始时 dp[0] 必须设为 false（非空串不能被空模式匹配），
// 同时 prev 初始化为旧的 dp[0]。
// ============================================================
class Solution4 {
public:
    bool isMatch(string s, string p) {
        int m = s.size(), n = p.size();
        vector<bool> dp(n + 1, false);
        dp[0] = true;

        // 初始化第0行: 空串 vs p 前缀
        for (int j = 1; j <= n; j++) {
            dp[j] = (p[j - 1] == '*') && dp[j - 1];
        }

        for (int i = 1; i <= m; i++) {
            // prev = dp[i-1][0]，即上一行的 dp[0]
            bool prev = dp[0];
            // 非空串 vs 空模式 = false
            dp[0] = false;

            for (int j = 1; j <= n; j++) {
                // 保存当前 dp[j]（= 上一行的 dp[i-1][j]），
                // 因为马上要被覆盖
                bool temp = dp[j];

                if (p[j - 1] == '*') {
                    // dp[j-1] = 当前行左边（已更新） = dp[i][j-1]
                    // temp    = 上一行同列（未更新） = dp[i-1][j]
                    dp[j] = dp[j - 1] || temp;
                } else {
                    // prev = 上一行前一列 = dp[i-1][j-1]
                    dp[j] = prev && (p[j - 1] == '?' || s[i - 1] == p[j - 1]);
                }

                // 为下一轮内循环准备：下一轮的 prev = 本轮的旧 dp[j]
                prev = temp;
            }
        }

        return dp[n];
    }
};

// ============================================================
// 解法5: 贪心双指针 — O(mn) 最坏 / O(1) 空间
//
// 【思路】
// 完全不同于 DP 的贪心思路：
// 用 i, j 分别扫描 s 和 p。遇到 * 时记下位置（starJ, matchI），
// 先假设 * 匹配 0 个字符继续走。
// 如果后面匹配失败，回到最后一个 * 的位置，让它多吃一个字符。
//
// 为什么只需记最后一个 *？
// 如果有多个 *，前面的 * 匹配了多少在之前已经通过贪心确定。
// 当前只需调整最后一个 *，因为它是"最近的弹性点"。
//
// 过程示例: s = "adceb", p = "*a*b"
//
// Step  i  j  动作
//   1   0  0  p[0]='*' → starJ=0, matchI=0, j=1（* 暂匹配0个）
//   2   0  1  p[1]='a'==s[0]='a' → i=1, j=2
//   3   1  2  p[2]='*' → starJ=2, matchI=1, j=3（新 * 暂匹配0个）
//   4   1  3  p[3]='b'!=s[1]='d' → 回溯: matchI=2, i=2, j=3
//   5   2  3  p[3]='b'!=s[2]='c' → 回溯: matchI=3, i=3, j=3
//   6   3  3  p[3]='b'!=s[3]='e' → 回溯: matchI=4, i=4, j=3
//   7   4  3  p[3]='b'==s[4]='b' → i=5, j=4
//   8   i=5=m, j=4=n → p 无剩余 → return true
// ============================================================
class Solution5 {
public:
    bool isMatch(string s, string p) {
        int m = s.size(), n = p.size();
        int i = 0, j = 0;
        int starJ = -1;   // 最后一个 * 在 p 中的位置
        int matchI = -1;   // 遇到该 * 时 s 的匹配起始位置

        while (i < m) {
            if (j < n && (p[j] == '?' || s[i] == p[j])) {
                // 当前字符匹配，双方前进
                i++;
                j++;
            } else if (j < n && p[j] == '*') {
                // 遇到 *，记录位置，假设 * 匹配 0 个字符
                starJ = j;
                matchI = i;
                j++;    // 跳过 *
                // i 不动，因为 * 暂时匹配 0 个
            } else if (starJ != -1) {
                // 匹配失败，但之前有 *：让 * 多吃一个字符
                matchI++;
                i = matchI;
                j = starJ + 1;  // 从 * 后面重新尝试匹配
            } else {
                // 匹配失败且无 * 可回溯
                return false;
            }
        }

        // s 已扫完，p 剩余部分必须全是 *
        while (j < n && p[j] == '*') j++;
        return j == n;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间         | 空间    | 特点               |
// |-----------|-------------|--------|-------------------|
// | 暴力递归   | O(2^(m+n))  | O(m+n) | 展示问题结构       |
// | 记忆化     | O(mn)       | O(mn)  | 自顶向下 DP        |
// | 二维 DP    | O(mn)       | O(mn)  | ⭐面试首选，最清晰  |
// | 一维 DP    | O(mn)       | O(n)   | 空间优化，追问时给  |
// | 贪心双指针 | O(mn) 最坏  | O(1)   | 最优空间，需解释正确性 |
//
// 面试建议:
//   先写二维 DP → 追问空间优化 → 一维 DP
//   追问 O(1) 空间 → 贪心双指针（需解释为什么贪心正确）
//
// 【易错点】
// 1. dp[0][j] 初始化: 连续 * 才为 true，一旦遇到非 * 后面全 false
//    ✗ 只设 dp[0][0]=true → p="**" 匹配空串返回 false
//    ✓ dp[0][j] = (p[j-1]=='*') && dp[0][j-1]
//
// 2. * 的转移方程:
//    ✗ dp[i][j] = dp[i-1][j-1]（当成 ? 了）
//    ✓ dp[i][j] = dp[i][j-1] || dp[i-1][j]
//
// 3. 一维 DP 中每行 dp[0] 必须重置:
//    ✗ 忘记 dp[0]=false → 从第2行开始 dp[0] 还是 true（继承了第0行）
//    ✓ 进入每行循环时: prev=dp[0]; dp[0]=false;
//
// 4. 一维 DP 中 prev 的维护顺序:
//    ✗ 先更新 dp[j] 再保存 temp → 左上角值已被覆盖
//    ✓ 先 temp=dp[j]，再更新 dp[j]，最后 prev=temp
//
// 5. 贪心解法 s 扫完后忘记检查 p 尾部:
//    ✗ 直接 return true → s="a", p="a*b" 返回 true
//
//    ✓ s 扫完后检查 p 剩余部分是否全是 '*'
//
// 【面试追问 Interview Follow-ups】
// Q1: 这道题和 LC 10 Regular Expression Matching 的区别？
// A1: '?' 匹配单个字符（同 '.'），'*' 匹配任意序列（LC 10 中 '*' 是重复前一个字符）。
//     DP 转移方程不同：本题 '*' 可以独立匹配，LC 10 的 '*' 依赖前一个字符。
//
// Q2: 贪心解法的时间复杂度最坏是多少？
// A2: O(m·n)，当 p="*a*b*c*...*z" 这种多个 '*' 间夹单字符时，每次 mismatch
//     都要回溯到上一个 '*' 重试。但平均情况远快于 DP。
//
// Q3: 如果 pattern 中没有 '*'，复杂度是多少？
// A3: O(min(m,n))，只需逐字符比较，遇到 '?' 直接匹配。没有 '*' 时 m 必须等于 n。
// ============================================================
