/*
 * 【题目本质】
 * 灯泡开关：n个灯泡经过n轮切换后，求亮着的灯泡数
 * 本质是数论问题：灯泡k被切换次数 = k的因子个数
 * 只有完全平方数有奇数个因子，所以答案 = floor(sqrt(n))
 *
 * 【解法总览】
 * Solution1: 数学公式 O(1) — 直接 sqrt(n)
 * Solution2: 逐个枚举完全平方数 O(sqrt(n))
 */

// ===================== Solution1: 数学公式 =====================
// 思路：灯泡k最终亮着 <=> k的因子个数为奇数 <=> k是完全平方数
// 1~n中完全平方数个数 = floor(sqrt(n))
// 时间 O(1), 空间 O(1)
class Solution1 {
public:
    int bulbSwitch(int n) {
        return (int)sqrt((double)n);
    }
};

// ===================== Solution2: 枚举完全平方数 =====================
// 思路：逐个检查 1^2, 2^2, 3^2, ... 是否 <= n
// 时间 O(sqrt(n)), 空间 O(1)
class Solution2 {
public:
    int bulbSwitch(int n) {
        int count = 0;
        for (long long i = 1; i * i <= (long long)n; i++) {
            count++;
        }
        return count;
    }
};

/*
 * 【解法对比】
 * | 解法 | 时间 | 空间 | 优势 |
 * |------|------|------|------|
 * | Solution1 数学公式 | O(1) | O(1) | 最优，代码最简 |
 * | Solution2 枚举平方数 | O(sqrt(n)) | O(1) | 避免浮点精度问题 |
 *
 * 【推导过程】
 * 灯泡k在第d轮被切换 <=> d是k的因子
 * => 灯泡k被切换次数 = k的因子个数
 * => 灯泡k最终亮 <=> 因子个数为奇数
 * 因子总是成对 (d, k/d)，只有 d=k/d 时合并 => k是完全平方数
 * => 答案 = 1~n中完全平方数的个数 = floor(sqrt(n))
 *
 * 【易错点】
 * 1. sqrt 返回 double，需要强转 int，注意精度
 * 2. n 可达 10^9，不能暴力模拟 O(n^2)
 * 3. 枚举法中 i*i 可能溢出 int，用 long long
 * 4. n=0 边界：sqrt(0)=0 自然处理
 *
 * 【面试追问】
 * Q1: 为什么完全平方数因子个数是奇数？
 *     因子成对 (d, n/d)，只有 d=n/d 时不成对
 * Q2: n极大时 sqrt 精度问题？
 *     可用二分或对结果微调验证 x*x<=n && (x+1)*(x+1)>n
 * Q3: 扩展到灯泡开关II/III有什么变化？
 *     II: 4种操作组合，数学分析状态数
 *     III: 统计"亮矩"的时刻数
 */
