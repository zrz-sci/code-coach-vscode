// ============================================================
// 639. Decode Ways II
// ============================================================
// 在 Decode Ways (LC91) 基础上加入 '*' 通配符 (代表 1-9)
// dp[i] = ways1(s[i]) * dp[i-1] + ways2(s[i-1], s[i]) * dp[i-2]
// 约束: 1 <= s.length <= 10^5, s[i] 是数字或 '*'
// ============================================================


// ============================================================
// 解法一：线性 DP + 空间优化（推荐）
// ============================================================
// 思路：
//   dp[i] = 前 i 个字符的解码方案数
//   转移: dp[i] = ways1(s[i]) * dp[i-1] + ways2(s[i-1], s[i]) * dp[i-2]
//
//   ways1(c): 单字符解码方案数
//     '0' -> 0, '1'-'9' -> 1, '*' -> 9
//
//   ways2(c1, c2): 双字符组成 10-26 的方案数
//     需要分类讨论所有 9 种 (c1, c2) 组合
//
// 时间: O(n)  空间: O(1)
class Solution {
public:
    int numDecodings(string s) {
        const int MOD = 1e9 + 7;
        int n = s.size();

        // dp[i-2] 和 dp[i-1]
        long long prev2 = 1; // dp[-1] = 1 (空字符串，哨兵)
        long long prev1 = ways1(s[0]);

        if (prev1 == 0) return 0;

        for (int i = 1; i < n; ++i) {
            long long curr = (ways1(s[i]) * prev1 % MOD
                            + ways2(s[i - 1], s[i]) * prev2 % MOD) % MOD;
            prev2 = prev1;
            prev1 = curr;
        }

        return (int)prev1;
    }

private:
    // 单字符解码方案数
    // '0' 不能单独解码 -> 0
    // '1'-'9' -> 1
    // '*' 代表 1-9 -> 9
    long long ways1(char c) {
        if (c == '0') return 0;
        if (c == '*') return 9;
        return 1;
    }

    // 双字符解码方案数 (两字符组成 10-26)
    // 完整分类讨论:
    long long ways2(char c1, char c2) {
        // 情况 1: 两个都是 '*'
        // *,* -> 11-19(9种) + 21-26(6种) = 15
        if (c1 == '*' && c2 == '*') return 15;

        // 情况 2: 第一个是 '*', 第二个是数字
        if (c1 == '*') {
            // *,0-6 -> 10,20 / 11,21 / ... / 16,26 -> 2 种
            // *,7-9 -> 17 / 18 / 19 -> 只有 1x 合法 -> 1 种
            if (c2 >= '0' && c2 <= '6') return 2;
            return 1; // c2 is '7', '8', or '9'
        }

        // 情况 3: 第一个是数字, 第二个是 '*'
        if (c2 == '*') {
            // 1,* -> 11-19 -> 9 种
            if (c1 == '1') return 9;
            // 2,* -> 21-26 -> 6 种
            if (c1 == '2') return 6;
            // 3-9,* 或 0,* -> 不能组成合法双字符 -> 0
            return 0;
        }

        // 情况 4: 两个都是数字
        int num = (c1 - '0') * 10 + (c2 - '0');
        if (num >= 10 && num <= 26) return 1;
        return 0;
    }
};


// ============================================================
// 解法二：线性 DP 数组版
// ============================================================
// 思路：
//   与解法一逻辑完全相同，用数组存储所有状态
//   便于理解和调试
//
// 时间: O(n)  空间: O(n)
class Solution2 {
public:
    int numDecodings(string s) {
        const int MOD = 1e9 + 7;
        int n = s.size();

        // dp[i] = 前 i+1 个字符的解码方案数
        vector<long long> dp(n + 1);
        dp[0] = 1; // 空字符串哨兵

        // 第一个字符
        if (s[0] == '0') return 0;
        dp[1] = (s[0] == '*') ? 9 : 1;

        for (int i = 2; i <= n; ++i) {
            char c = s[i - 1];    // 当前字符
            char p = s[i - 2];    // 前一个字符

            // 单字符贡献
            long long w1 = 0;
            if (c == '*') w1 = 9;
            else if (c != '0') w1 = 1;

            // 双字符贡献
            long long w2 = computeWays2(p, c);

            dp[i] = (w1 * dp[i - 1] % MOD + w2 * dp[i - 2] % MOD) % MOD;
        }

        return (int)dp[n];
    }

private:
    long long computeWays2(char c1, char c2) {
        if (c1 == '*' && c2 == '*') return 15;

        if (c1 == '*') {
            return (c2 <= '6') ? 2 : 1;
        }

        if (c2 == '*') {
            if (c1 == '1') return 9;
            if (c1 == '2') return 6;
            return 0;
        }

        int num = (c1 - '0') * 10 + (c2 - '0');
        return (num >= 10 && num <= 26) ? 1 : 0;
    }
};


// ============================================================
// ways2 分类讨论完整参考表
// ============================================================
//
// c1 \\ c2 |  '0'  | '1'-'6' | '7'-'9' |  '*'
// ---------|-------|---------|---------|------
//   '0'    |   0   |    0    |    0    |   0
//   '1'    |   1   |    1    |    1    |   9
//   '2'    |   1   |    1    |    0    |   6
//  '3'-'9' |   0   |    0    |    0    |   0
//   '*'    |   2   |    2    |    1    |  15
//
// 解释：
//   '*','*' = 15: 第一个*取1时可配1-9(9种), 取2时可配1-6(6种) -> 15
//   '*','0' = 2:  10 和 20 两种
//   '*','1'-'6' = 2: 1x 和 2x 都合法
//   '*','7'-'9' = 1: 只有 1x 合法 (27, 28, 29 > 26)
//   '1','*' = 9: 11-19 共 9 种
//   '2','*' = 6: 21-26 共 6 种
//
// 验证示例：
//   s = "*"   -> dp = 9
//   s = "1*"  -> w1=9, w2=9 -> dp = 9*1 + 9*1 = 18
//   s = "2*"  -> w1=9, w2=6 -> dp = 9*1 + 6*1 = 15
//   s = "**"  -> w1=9, w2=15 -> dp = 9*9 + 15*1 = 96
