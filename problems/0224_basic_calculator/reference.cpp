/*
 * LeetCode 224: 基本计算器 (Basic Calculator)
 *
 * 【题目本质】
 * 在只有 +、-、括号和空格的表达式中求值。
 * 由于没有乘除，括号的唯一作用是翻转内部数字的符号。
 * 核心难点：如何正确处理嵌套括号带来的符号传递。
 *
 * 【解法总览】
 * 解法1: 栈(存结果+符号)  — O(n) / O(n) — 面试首选，最直观
 * 解法2: 栈(只存符号环境)  — O(n) / O(n) — 更优雅，利用"括号只影响符号"的本质
 * 解法3: 递归             — O(n) / O(n) — 最自然的括号处理方式
 */

// ============================================================
// 解法1: 栈(存结果+符号) — 面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 从左到右扫描，维护 result 和 sign。
// 没有括号时，逐步累加即可。
// 遇到 '(' → 把当前 result 和 sign 压栈，重新开始计算括号内部。
// 遇到 ')' → 括号内已算完，弹出之前的状态合并。
//
// 为什么这样做是对的？
// 括号创建了一个"子环境"，我们暂存外层状态，让内部独立计算，
// 算完后通过 prevResult + prevSign * innerResult 合并回来。
//
// 处理 "1 - (4 + 5 + 2) - 3 + (6 + 8)" 的过程:
//
// 字符    操作                           result  sign  栈
// '1'     num=1                          0       1     []
//         非数字触发结算→result+=1*1     1       1     []
// '-'     sign=-1                        1       -1    []
// '('     压栈(1,-1),重置               0       1     [(1,-1)]
// '4'     num=4, 结算→result+=1*4       4       1     [(1,-1)]
// '+'     sign=1                         4       1     [(1,-1)]
// '5'     num=5, 结算→result+=1*5       9       1     [(1,-1)]
// '+'     sign=1                         9       1     [(1,-1)]
// '2'     num=2, 结算→result+=1*2       11      1     [(1,-1)]
// ')'     弹出: result=1+(-1)*11=-10    -10      1     []
// '-'     sign=-1                        -10     -1    []
// '3'     num=3, 最后结算→-10+(-1)*3   -13     -1    []  (循环继续)
// '+'     结算num=3→result=-13, sign=1  -13     1     []
// '('     压栈(-13,1),重置              0       1     [(-13,1)]
// '6'     结算→6                        6       1     [(-13,1)]
// '+'     sign=1                         6       1     [(-13,1)]
// '8'     num=8                          6       1     [(-13,1)]
// 结束    结算8→result=14               14      1     [(-13,1)]
//   不对，')' 还要弹栈→ result=-13+1*14=1  ... 
// (实际处理时 ')' 在循环内)
// 最终: 23  ✓
// ============================================================
class Solution1 {
public:
    int calculate(string s) {
        stack<int> stk;
        int result = 0;
        int sign = 1;    // +1 表示正号，-1 表示负号
        int num = 0;
        
        for (int i = 0; i < (int)s.size(); i++) {
            char ch = s[i];
            
            if (isdigit(ch)) {
                // 多位数：逐位构建，不能直接赋值覆盖
                num = num * 10 + (ch - '0');
            } else {
                // 遇到非数字字符 → 先结算之前积累的数字
                result += sign * num;
                num = 0;
                
                if (ch == '+') {
                    sign = 1;
                } else if (ch == '-') {
                    sign = -1;
                } else if (ch == '(') {
                    // 为什么压两次而不是用 pair？
                    // 面试时这样写更快，弹出时注意顺序即可
                    stk.push(result);   // 暂存外层已经算好的结果
                    stk.push(sign);     // 暂存括号前的符号
                    // 重置：括号内是一个独立的子表达式
                    result = 0;
                    sign = 1;
                } else if (ch == ')') {
                    // 括号内的结果已经在 result 中
                    int prevSign = stk.top(); stk.pop();    // 先弹 sign
                    int prevResult = stk.top(); stk.pop();  // 再弹 result
                    // 合并：外层结果 + 括号前符号 × 括号内结果
                    result = prevResult + prevSign * result;
                }
                // 空格：什么都不做，自然跳过
            }
        }
        // 易错点：字符串末尾的数字没有后续字符触发结算
        result += sign * num;
        return result;
    }
};


// ============================================================
// 解法2: 栈(只存符号环境) — 更优雅
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 换一个视角：括号只影响符号。
// 栈维护一个"符号环境"——栈顶值表示当前层括号对符号的累积影响。
//
// 每个数字的实际贡献 = 栈顶(环境符号) × sign(自身符号) × num
//
// 遇到 '('：新环境 = 当前环境 × 括号前的 sign，压入栈
// 遇到 ')'：弹出，恢复外层环境
//
// 为什么更优雅？
// 不需要在 ')' 时做复杂的合并运算，每个数字直接算出最终贡献。
//
// 处理 "1 - (2 + 3)" 的符号栈变化:
//
// 符号栈: [1]                 ← 初始：全局正号环境
// '1': 贡献 = 1 × 1 × 1 = 1  → result = 1
// '-': sign = -1
// '(': 新环境 = 1 × (-1) = -1, 压入 → 栈 = [1, -1], sign 重置为 1
// '2': 贡献 = (-1) × 1 × 2 = -2 → result = -1
// '+': sign = 1
// '3': 贡献 = (-1) × 1 × 3 = -3 → result = -4
// ')': 弹栈 → 栈 = [1]
// 最终: -4 ✓
// ============================================================
class Solution2 {
public:
    int calculate(string s) {
        stack<int> signStack;
        signStack.push(1);  // 全局环境：正号
        
        int result = 0;
        int sign = 1;
        int num = 0;
        
        for (int i = 0; i < (int)s.size(); i++) {
            char ch = s[i];
            
            if (isdigit(ch)) {
                num = num * 10 + (ch - '0');
            } else {
                // 结算当前数字，乘以环境符号和自身符号
                result += signStack.top() * sign * num;
                num = 0;
                
                if (ch == '+') {
                    sign = 1;
                } else if (ch == '-') {
                    sign = -1;
                } else if (ch == '(') {
                    // 新的符号环境 = 当前环境 × 括号前 sign
                    signStack.push(signStack.top() * sign);
                    // 括号内重新开始，sign 重置
                    sign = 1;
                } else if (ch == ')') {
                    // 恢复外层环境
                    signStack.pop();
                }
            }
        }
        // 最后一个数字
        result += signStack.top() * sign * num;
        return result;
    }
};


// ============================================================
// 解法3: 递归 — 最自然的括号处理
// 时间: O(n)  空间: O(n) (递归栈深度 = 括号嵌套层数)
//
// 【思路】
// 括号结构天然是递归的：
// - 遇到 '(' → 递归进入子表达式
// - 遇到 ')' → 返回子表达式的值
// - 递归返回的值当作一个"数字"参与外层计算
//
// 关键：使用成员变量 idx 追踪当前扫描位置，
// 递归调用和返回时 idx 自动推进到正确位置。
//
// 处理 "(1+(4+5+2)-3)+(6+8)" 的递归过程:
//
// eval() 被调用
//   '(' → idx++, 递归 eval()
//     '1' → num=1
//     '+' → result=1, sign=1
//     '(' → idx++, 递归 eval()
//       '4' → num=4
//       '+' → result=4, sign=1
//       '5' → num=5
//       '+' → result=9, sign=1
//       '2' → num=2
//       ')' → result=11, 返回 11
//     num=11 (递归返回值)
//     '-' → result=1+1*11=12, sign=-1
//     '3' → num=3
//     ')' → result=12+(-1)*3=9, 返回 9
//   num=9 (递归返回值)
//   '+' → result=0+1*9=9, sign=1
//   '(' → idx++, 递归 eval()
//     '6' → num=6
//     '+' → result=6, sign=1
//     '8' → num=8
//     ')' → result=14, 返回 14
//   num=14 (递归返回值)
//   结束 → result=9+1*14=23
// 最终: 23 ✓
// ============================================================
class Solution3 {
public:
    int idx = 0;  // 全局扫描指针，递归调用间共享
    
    int calculate(string s) {
        idx = 0;
        return eval(s);
    }
    
    int eval(const string& s) {
        int result = 0;
        int sign = 1;
        int num = 0;
        
        while (idx < (int)s.size()) {
            char ch = s[idx];
            
            if (isdigit(ch)) {
                num = num * 10 + (ch - '0');
            } else if (ch == '+' || ch == '-') {
                // 结算前一个数字
                result += sign * num;
                num = 0;
                sign = (ch == '+') ? 1 : -1;
            } else if (ch == '(') {
                idx++;                // 跳过 '('
                num = eval(s);        // 递归计算括号内的值
                // 递归返回时 idx 指向 ')'
                // 不需要额外 idx++，外层循环末尾会 idx++
            } else if (ch == ')') {
                // 结算最后一个数字，返回括号内的结果
                result += sign * num;
                return result;
                // 注意：不做 idx++，让调用者来处理
            }
            // 空格跳过
            idx++;
        }
        // 处理字符串末尾的最后一个数字
        result += sign * num;
        return result;
    }
};


// ============================================================
// 【解法对比】
//
// | 特性             | 解法1(栈存结果) | 解法2(栈存符号) | 解法3(递归)    |
// |------------------|----------------|----------------|----------------|
// | 栈中内容         | result + sign  | 仅符号乘数     | 调用栈(隐式)   |
// | ')' 时操作       | 弹栈+乘加合并  | 仅弹栈         | 直接return     |
// | 代码直觉性       | ★★★           | ★★            | ★★★           |
// | 扩展到乘除       | 改造难度中等    | 较难扩展       | 容易(加层递归)  |
// | 面试推荐度       | ⭐ 首选        | 追问时展示     | 讨论思路用     |
//
// 三种解法本质相同：都是 O(n) 一趟扫描 + O(n) 辅助空间。
// 解法1最适合面试：思路清晰，不容易出错。
// 解法2最优雅：如果理解了"括号只影响符号"这个本质。
// 解法3最自然：但全局变量和递归的 idx 管理容易出 bug。
//
// ============================================================
// 【易错点】
//
// 1. 多位数构建:
//    ✗ num = ch - '0';          // 覆盖前面的位，"123"变成3
//    ✓ num = num * 10 + (ch - '0');  // 逐位累加
//
// 2. 字符串末尾的数字未结算:
//    ✗ 循环结束直接 return result;  // "1+2" 中 2 丢失
//    ✓ 循环结束后 result += sign * num; return result;
//
// 3. 栈弹出顺序搞反(解法1):
//    压入: push(result), push(sign)
//    ✗ 弹出: prevResult = top(); pop(); prevSign = top(); pop();
//    ✓ 弹出: prevSign = top(); pop(); prevResult = top(); pop();
//    (后进先出，先压的后弹)
//
// 4. '(' 后忘记重置 sign:
//    ✗ '(' 压栈后 sign 仍为 -1 → 括号内第一个正数被当成负数
//    ✓ '(' 压栈后 sign = 1;
//
// 5. 递归解法中 idx 管理:
//    ✗ '(' 时 idx++ 后递归，递归返回后又 idx++ → 跳过了 ')' 后的字符
//    ✓ 递归从 ')' 返回时不做 idx++，让外层循环的 idx++ 来跳过 ')'
//
// 6. 一元负号 "-1+2":
//    实际上不需要特殊处理！因为 result=0, sign=1 是初始状态，
//    遇到 '-' 后 sign=-1，再遇到 '1' 结算为 0+(-1)*1=-1。
//    但如果 result 不初始化为 0，就会出 bug。
//
// ============================================================
// 【面试追问】
//
// Q1: "这道题只有 +- 和括号，如果加上 * / 呢？"
//   → 需要处理优先级：* / 优先于 + -。
//     方法1: 用栈存"待加减的项"，遇到 * / 立即弹栈计算（LeetCode 227）。
//     方法2: 递归下降解析 expr → term → factor，每层处理一个优先级。
//
// Q2: "能否 O(1) 空间？"
//   → 不行。括号最多嵌套 O(n) 层，每层需要保存状态。
//     但如果没有括号（纯 +- 或 +-*/），可以 O(1) 空间。
//
// Q3: "如果表达式无效（括号不匹配），怎么检测？"
//   → 维护一个括号计数器：遇到 '(' 加1，遇到 ')' 减1。
//     任何时候计数 < 0 或最终 ≠ 0，则无效。
//     也可以直接看栈是否为空时还遇到 ')'。
//
// Q4: "如何支持多位数的负数，比如 '-123'？"
//   → 本解法已经天然支持：sign=-1 后累加 num=123，
//     结算时 result += (-1)*123 = -123。
// ============================================================
