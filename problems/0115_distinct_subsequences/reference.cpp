/*
 * LeetCode 115: 不同的子序列 (Distinct Subsequences)
 *
 * 【题目本质】
 * 在 s 中选若干字符（保持相对顺序）组成 t 的方案数 — 经典双字符串 DP 计数问题。
 *
 * 【解法总览】
 * 解法1: 暴力递归 (DFS)          — O(2^m) / O(m)      — 理解决策过程
 * 解法2: 记忆化搜索 (自顶向下 DP) — O(m×n) / O(m×n)   — 消除重叠子问题
 * 解法3: 二维 DP (自底向上递推)   — O(m×n) / O(m×n)   — 面试首选
 * 解法4: 一维 DP (空间优化)       — O(m×n) / O(n)     — 追问加分
 *
 * 其中 m = len(s), n = len(t)
 */

// ============================================================
// 解法1: 暴力递归 — 穷举"选/不选"每个 s 的字符
// 时间: O(2^m)  空间: O(m) 递归栈
//
// 【思路】
// 从 s 和 t 的末尾开始逐字符考虑：
//   - 若 s[i] == t[j]: 可以用 s[i] 匹配 t[j]（i-1, j-1），
//                       也可以跳过 s[i]（i-1, j），两种方案数相加。
//   - 若 s[i] != t[j]: 只能跳过 s[i]（i-1, j）。
//   - j < 0: t 匹配完 → 找到 1 种方案。
//   - i < 0 且 j >= 0: s 用完但 t 未匹配完 → 0 种方案。
//
// 决策树示意 (s="abb", t="ab"):
//              dfs(2,1)
//             s[2]='b'==t[1]='b'
//            /                \
//     dfs(1,0)              dfs(1,1)
//    s[1]='b',t[0]='a'    s[1]='b'!=t[1]='b'... wait
//    b!=a, skip            等等让我重新画
//
// 更清晰地：s="abb", t="ab"
//              dfs(i=2,j=1)   s[2]='b'==t[1]='b'
//              /           \
//   匹配: dfs(1,0)      不匹配: dfs(1,1)
//   s[1]='b',t[0]='a'   s[1]='b'==t[1]='b'
//   b!=a → dfs(0,0)      /           \
//   s[0]='a',t[0]='a'  dfs(0,0)    dfs(0,1)
//   a==a → dfs(-1,-1)  j<0→1     i=0,j=1→dfs(-1,1)→0
//         +dfs(-1,0)                       
//   j<0→1  j<0→1                
//   = 2      = 1
//
// 总计 = 2 + 1... 不对，让我重新算
// 实际 s="abb" t="ab" 答案应该是 2: a_b_ 和 a__b
// dfs(2,1): s[2]='b'==t[1]='b' → dfs(1,0) + dfs(1,1)
//   dfs(1,0): s[1]='b'!=t[0]='a' → dfs(0,0)
//     dfs(0,0): s[0]='a'==t[0]='a' → dfs(-1,-1) + dfs(-1,0)
//       dfs(-1,-1): j<0 → 1
//       dfs(-1,0):  j<0 → 1    (j=-1<0)
//     dfs(0,0) = 1+1 = 2   ... 这也不对, dp[0][0]应该是1
// 
// 重新想: dfs(0,0)中 s[0]='a'==t[0]='a' 
//   → dfs(-1,-1) + dfs(-1,0) = 1 + 1 = 2?
// 不, dfs(-1,0): i<0且j>=0? j=-1+1=0, j=0-1=-1, 
// 等等这里 j=0 对应 t[0]='a', 调用 dfs(-1, -1) 时 j=-1 < 0 → 1
// 而 dfs(-1, 0) 时 i=-1 < 0 且 j=0 >= 0 → 0
// 所以 dfs(0,0) = 1 + 0 = 1 ✓
// dfs(1,0) = 1
//   dfs(1,1): s[1]='b'==t[1]='b' → dfs(0,0) + dfs(0,1)
//     dfs(0,0) = 1 (如上)
//     dfs(0,1): s[0]='a'!=t[1]='b' → dfs(-1,1): i<0,j>=0 → 0
//   dfs(1,1) = 1 + 0 = 1
// dfs(2,1) = 1 + 1 = 2 ✓
// ============================================================
class Solution1 {
public:
    int numDistinct(string s, string t) {
        return dfs(s, t, (int)s.size() - 1, (int)t.size() - 1);
    }

private:
    int dfs(const string& s, const string& t, int i, int j) {
        if (j < 0) return 1;   // t 全部匹配完，找到一种方案
        if (i < 0) return 0;   // s 用完但 t 还有未匹配的字符

        // 选择1: 跳过 s[i]
        int result = dfs(s, t, i - 1, j);

        // 选择2: 用 s[i] 匹配 t[j]（仅当相等时）
        if (s[i] == t[j]) {
            result += dfs(s, t, i - 1, j - 1);
        }

        return result;
    }
};

// ============================================================
// 解法2: 记忆化搜索 — 在递归基础上加缓存
// 时间: O(m×n)  空间: O(m×n)
//
// 【思路】
// 解法1中 (i,j) 的组合只有 m×n 种，但存在大量重复计算。
// 加一个 memo 数组：memo[i][j] 记录 dfs(i,j) 的结果，
// 遇到已计算过的直接返回，避免重复递归。
// 这就是"自顶向下"的动态规划。
// ============================================================
class Solution2 {
public:
    int numDistinct(string s, string t) {
        int m = s.size(), n = t.size();
        // -1 表示未计算过
        vector<vector<int>> memo(m, vector<int>(n, -1));
        return dfs(s, t, m - 1, n - 1, memo);
    }

private:
    int dfs(const string& s, const string& t, int i, int j,
            vector<vector<int>>& memo) {
        if (j < 0) return 1;
        if (i < 0) return 0;
        if (memo[i][j] != -1) return memo[i][j];

        int result = dfs(s, t, i - 1, j, memo);  // 跳过 s[i]
        if (s[i] == t[j]) {
            result += dfs(s, t, i - 1, j - 1, memo);  // 用 s[i] 匹配 t[j]
        }

        return memo[i][j] = result;
    }
};

// ============================================================
// 解法3: 二维 DP (递推) — 面试首选
// 时间: O(m×n)  空间: O(m×n)
//
// 【思路】
// 将记忆化搜索翻译为自底向上的递推。
//
// 状态定义:
//   dp[i][j] = s 的前 i 个字符的子序列中，等于 t 的前 j 个字符的方案数
//
// 状态转移:
//   s[i-1] == t[j-1]: dp[i][j] = dp[i-1][j-1] + dp[i-1][j]
//                      (用 s[i-1] 匹配)  +  (不用 s[i-1])
//   s[i-1] != t[j-1]: dp[i][j] = dp[i-1][j]
//                      (只能跳过 s[i-1])
//
// 初始化:
//   dp[i][0] = 1  (任何前缀匹配空串 t，方案数 = 1: 什么都不选)
//   dp[0][j] = 0  (j > 0, 空串 s 无法匹配非空 t)
//
// DP 填表示例 (s="rabbbit", t="rabbit"):
//
//         ""  r  a  b  b  i  t
//    ""    1  0  0  0  0  0  0
//    r     1  1  0  0  0  0  0
//    a     1  1  1  0  0  0  0
//    b     1  1  1  1  0  0  0
//    b     1  1  1  2  1  0  0
//    b     1  1  1  3  3  0  0
//    i     1  1  1  3  3  3  0
//    t     1  1  1  3  3  3  3  ← 答案
//
// 填表方向: 从上到下，从左到右
// dp[i][j] 依赖:
//   ↑ dp[i-1][j]     (正上方)
//   ↖ dp[i-1][j-1]   (左上方, 仅当字符相等时)
// ============================================================
class Solution3 {
public:
    int numDistinct(string s, string t) {
        int m = s.size(), n = t.size();
        // 用 unsigned long long 防止中间累加溢出
        // （题目保证最终结果在 int 范围，但中间值可能超）
        vector<vector<unsigned long long>> dp(m + 1, vector<unsigned long long>(n + 1, 0));

        // base case: s 的任何前缀匹配空串 t → 1 种方案（不选任何字符）
        for (int i = 0; i <= m; i++) {
            dp[i][0] = 1;
        }
        // dp[0][j>0] 默认为 0，空串 s 无法匹配非空 t

        for (int i = 1; i <= m; i++) {
            for (int j = 1; j <= n; j++) {
                // 不管是否相等，都可以跳过 s[i-1]
                dp[i][j] = dp[i - 1][j];

                // 如果字符相等，还可以用 s[i-1] 匹配 t[j-1]
                if (s[i - 1] == t[j - 1]) {
                    dp[i][j] += dp[i - 1][j - 1];
                }
            }
        }

        return (int)dp[m][n];
    }
};

// ============================================================
// 解法4: 一维 DP (空间优化) — 面试追问加分
// 时间: O(m×n)  空间: O(n)
//
// 【思路】
// 解法3中 dp[i][j] 只依赖 dp[i-1][j] (正上方) 和 dp[i-1][j-1] (左上方)，
// 即只依赖上一行。因此可以压缩成一维数组。
//
// 关键: 内层循环必须从右到左遍历！
// 原因: dp[j] 更新时需要 dp[j-1] 是"上一行"的值。
//       如果从左到右，dp[j-1] 已被当前行覆盖 → 错误。
//       从右到左，dp[j-1] 还没被动过，仍是上一行的值 → 正确。
//
// 这和 0/1 背包的空间优化原理完全一致:
//   0/1 背包: 每个物品只能用一次 → 容量从大到小
//   本题: 每个 s[i] 只能用一次 → j 从大到小
//
// 一维滚动过程 (s="babgbag", t="bag"):
//
//          j:  0  1  2  3
//              "" b  a  g
// 初始 dp:     1  0  0  0
//
// i=1, s[0]='b':  从 j=3→1 扫描
//   j=3: 'b'!='g', skip
//   j=2: 'b'!='a', skip
//   j=1: 'b'=='b', dp[1] += dp[0] → dp[1] = 0+1 = 1
//   dp: [1, 1, 0, 0]
//
// i=2, s[1]='a':
//   j=3: 'a'!='g', skip
//   j=2: 'a'=='a', dp[2] += dp[1] → dp[2] = 0+1 = 1
//   j=1: 'a'!='b', skip
//   dp: [1, 1, 1, 0]
//
// i=3, s[2]='b':
//   j=3: 'b'!='g', skip
//   j=2: 'b'!='a', skip
//   j=1: 'b'=='b', dp[1] += dp[0] → dp[1] = 1+1 = 2
//   dp: [1, 2, 1, 0]
//
// i=4, s[3]='g':
//   j=3: 'g'=='g', dp[3] += dp[2] → dp[3] = 0+1 = 1
//   j=2: 'g'!='a', skip
//   j=1: 'g'!='b', skip
//   dp: [1, 2, 1, 1]
//
// i=5, s[4]='b':
//   j=1: 'b'=='b', dp[1] += dp[0] → dp[1] = 2+1 = 3
//   dp: [1, 3, 1, 1]
//
// i=6, s[5]='a':
//   j=2: 'a'=='a', dp[2] += dp[1] → dp[2] = 1+3 = 4
//   dp: [1, 3, 4, 1]
//
// i=7, s[6]='g':
//   j=3: 'g'=='g', dp[3] += dp[2] → dp[3] = 1+4 = 5
//   dp: [1, 3, 4, 5]
//
// 答案 = dp[3] = 5 ✓
// ============================================================
class Solution4 {
public:
    int numDistinct(string s, string t) {
        int m = s.size(), n = t.size();
        vector<unsigned long long> dp(n + 1, 0);
        dp[0] = 1;  // 匹配空串 t 的方式永远是 1

        for (int i = 1; i <= m; i++) {
            // 从右到左! 保证 dp[j-1] 是上一轮（上一行）的值
            for (int j = n; j >= 1; j--) {
                if (s[i - 1] == t[j - 1]) {
                    dp[j] += dp[j - 1];
                }
                // 不等时 dp[j] 保持不变 = dp[i-1][j]，天然实现了"跳过 s[i-1]"
            }
        }

        return (int)dp[n];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间 | 空间 | 特点 |
// |------|------|------|------|
// | 暴力递归 | O(2^m) | O(m) | 理解决策树，不能通过 |
// | 记忆化搜索 | O(mn) | O(mn) | 自顶向下，便于理解 |
// | 二维 DP | O(mn) | O(mn) | 自底向上，面试首选 |
// | 一维 DP | O(mn) | O(n) | 空间最优，追问加分 |
//
// 推荐路径: 面试先写解法3（二维 DP），被追问空间优化时给解法4。
// 如果不确定转移方程，先写解法1（递归）再翻译。
//
// 【易错点】
//
// 1. dp[i][0] 忘记初始化为 1:
//    ✗ dp[i][0] = 0 (默认) → 整张表全是 0
//    ✓ dp[i][0] = 1 → s 的任何前缀都能以"不选"的方式匹配空串 t
//
// 2. 一维 DP 内层循环方向写反:
//    ✗ for (int j = 1; j <= n; j++) → dp[j-1] 被当前行覆盖，结果偏大
//    ✓ for (int j = n; j >= 1; j--) → dp[j-1] 保持上一行的值
//    原理同 0/1 背包空间优化
//
// 3. 中间结果溢出:
//    ✗ vector<vector<int>> dp → 中间累加可能超 INT_MAX
//    ✓ 用 unsigned long long，最后 cast 回 int
//    题目只保证最终答案在 32 位范围，不保证中间值
//
// 4. 下标偏移:
//    ✗ if (s[i] == t[j]) 在 1-indexed DP 中 → 越界访问
//    ✓ if (s[i-1] == t[j-1]) → dp 多一行一列用于 base case
//
// 【面试追问】
//
// Q1: 解释转移方程的含义?
// A1: 当 s[i-1]==t[j-1] 时，两种互斥选择:
//     (1) 用 s[i-1] 匹配 t[j-1] → 方案数 dp[i-1][j-1]
//     (2) 不用 s[i-1] → 方案数 dp[i-1][j]
//     总方案数 = 两者之和。不等时只有选择(2)。
//
// Q2: 为什么空间优化要从右到左?
// A2: dp[j] 更新时依赖 dp[j-1]（上一行的值）。从左到右遍历时
//     dp[j-1] 已被当前行覆盖，不再是上一行的值。
//     从右到左遍历时 dp[j-1] 还没被动过，保持上一行的值。
//     这和 0/1 背包空间优化的原理完全一致。
//
// Q3: 和编辑距离(LC 72)、最长公共子序列(LC 1143)有什么异同?
// A3: 三者都是"两个字符串 → 二维 DP"的框架:
//     - LCS: dp[i][j] = max(左, 上, 左上+1)，求最大长度
//     - 编辑距离: dp[i][j] = min(左+1, 上+1, 左上+cost)，求最小操作数
//     - 本题: dp[i][j] = 上 + (相等时)左上，求方案计数
//     状态定义和填表框架相同，只是转移方程中的运算不同(max/min/sum)。
//
// Q4: 如果 s 极长(10^5)而 t 很短(10)，有没有比 O(mn) 更快的方法?
// A4: 可以预处理 s 中每个字符的出现位置列表，然后用 DFS + 二分查找
//     在位置列表中找下一个合法位置。当 t 很短时递归深度很小，
//     配合记忆化可以显著减少实际计算量。但最坏情况仍是 O(mn)。
// ============================================================
