/*
 * LeetCode 179: 最大数 (Largest Number)
 * 
 * 【题目本质】
 * 给一组非负整数，找到一种排列顺序使得拼接后数值最大。
 * 核心是自定义比较规则：对任意两个数 a, b，比较 "ab" 和 "ba" 的大小来决定谁在前。
 *
 * 【解法总览】
 * 解法1: 暴力全排列 — O(n! × n) / O(n)    — 仅作思路起点，面试中说出来表示理解
 * 解法2: 自定义排序(贪心) — O(nk logn) / O(nk) — 面试首选，必须掌握
 */

// ============================================================
// 解法1: 暴力全排列 — 枚举所有排列找最大拼接结果
// 时间: O(n! × n)  空间: O(n)
// 
// 【思路】
// 最直接的想法：n 个数有 n! 种排列，每种排列拼接起来看哪个最大。
// 这帮助我们理解题目本质，但 n=100 时 n! 天文数字，完全不可行。
// 瓶颈：我们在盲目枚举，没有利用"两两比较就能确定顺序"这个性质。
// ============================================================
class Solution1 {
public:
    string largestNumber(vector<int>& nums) {
        vector<string> strs;
        for (int x : nums) strs.push_back(to_string(x));
        
        sort(strs.begin(), strs.end()); // 字典序排序，用于 next_permutation
        string result = "";
        do {
            string candidate = "";
            for (auto& s : strs) candidate += s;
            if (candidate > result) result = candidate;
        } while (next_permutation(strs.begin(), strs.end()));
        
        // 全零特判
        if (result[0] == '0') return "0";
        return result;
    }
};

// ============================================================
// 解法2: 自定义排序（贪心） — 面试首选 ⭐
// 时间: O(nk log n)  空间: O(nk)  (k 为数字字符串平均长度，≤10)
// 
// 【思路】
// 核心洞察：对于任意两个数 a 和 b，我们只需比较 "ab" 和 "ba" 
// 两种拼接方式，就能确定谁应该排在前面。
//
// 例如 a="3", b="30":
//   "3"+"30" = "330"
//   "30"+"3" = "303"
//   "330" > "303" → 所以 "3" 排在 "30" 前面
//
// 为什么这个贪心是正确的？
// 关键是证明传递性：如果 ab > ba 且 bc > cb，能推出 ac > ca。
// 设 a 表示数值 A，长 la。ab 的数值 = A × 10^lb + B。
// ab > ba 等价于 A/(10^la - 1) > B/(10^lb - 1)。
// 定义 f(X) = X/(10^lx - 1)，则比较等价于比 f 值，天然有传递性。
//
// 排序后按顺序拼接即为答案。
//
// 以 [3, 30, 34, 5, 9] 为例展示比较过程：
//
//   比较 "3" vs "30":  "330" > "303"  → 3 在 30 前
//   比较 "3" vs "34":  "334" < "343"  → 34 在 3 前
//   比较 "34" vs "30": "3430" > "3034" → 34 在 30 前
//   比较 "5" vs "9":   "59" < "95"    → 9 在 5 前
//   ...
//
//   最终排序: ["9", "5", "34", "3", "30"]
//   拼接结果: "9534330" ✓
// ============================================================
class Solution2 {
public:
    string largestNumber(vector<int>& nums) {
        // Step 1: 数字转字符串
        // 为什么要转字符串？因为我们需要拼接后比较，字符串拼接最自然
        vector<string> strs;
        for (int x : nums) {
            strs.push_back(to_string(x));
        }
        
        // Step 2: 自定义排序 —— 整道题的核心就在这个 lambda
        // 比较规则：如果 a 拼 b 比 b 拼 a 大，a 排前面（降序）
        sort(strs.begin(), strs.end(), [](const string& a, const string& b) {
            // 字符串拼接后做字典序比较
            // 字典序比较对于等长字符串等价于数值比较
            // a+b 和 b+a 长度相同（都是 la+lb），所以字典序比较就是数值比较
            return a + b > b + a;
        });
        
        // Step 3: 特判全零
        // 排序后最大的都是 "0"，说明所有数字都是 0
        // 不特判的话 [0, 0] 会输出 "00" 而不是 "0"
        if (strs[0] == "0") return "0";
        
        // Step 4: 按排好的顺序拼接
        string result;
        for (const string& s : strs) {
            result += s;
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
// 
// 解法1 (暴力全排列):
//   - 时间 O(n! × n)，只适合 n ≤ 8
//   - 价值：帮助理解题目本质是"在所有排列中找最大拼接"
//
// 解法2 (自定义排序):
//   - 时间 O(nk log n)，k≤10 可视为 O(n log n)
//   - 利用"两两比较 ab vs ba"确定全局顺序
//   - 面试中唯一需要写出的解法
//
// 选择建议：面试直接写解法2。如果面试官问"怎么想到的"，
// 可以先描述解法1的全排列思路，然后说"我们不需要枚举所有排列，
// 因为两两比较就能确定相对顺序"，自然过渡到解法2。
//
// ============================================================
// 【易错点】
// 
// 1. 比较方向写反：
//    ✗ return a + b < b + a;  // 这排成最小数了
//    ✓ return a + b > b + a;  // 降序，大的在前
//
// 2. 忘记全零特判：
//    ✗ [0, 0] → "00"
//    ✓ [0, 0] → "0"  (排序后第一个是 "0" 就直接返回 "0")
//
// 3. 用数值比较代替拼接比较：
//    ✗ return stoi(a) > stoi(b);  // 3 vs 30: 30>3, 排成 "303" 错误
//    ✓ return a + b > b + a;       // "330" > "303", 排成 "330" 正确
//
// 4. 比较函数用 >= 而非 >：
//    ✗ return a + b >= b + a;  // 违反严格弱序，sort 行为未定义
//    ✓ return a + b > b + a;   // 严格大于，满足 C++ sort 要求
//
// 5. 拼接时字符串可能很长导致担心溢出：
//    实际上我们比较的是字符串，不是转成整数比较，不存在溢出问题。
//
// ============================================================
// 【面试追问】
// 
// Q1(基础理解): 为什么不能按数字本身的大小排序？
//    → 反例 [3, 30]: 30 > 3 但 "330" > "303"。位数不同时数值大小
//      不能反映拼接后的优劣。
//
// Q2(正确性证明): 如何证明这个比较规则具有传递性？
//    → ab > ba 等价于 A × 10^lb + B > B × 10^la + A，
//      整理为 A/(10^la - 1) > B/(10^lb - 1)。
//      令 f(X) = X/(10^lx - 1)，比较就是比 f 值，天然传递。
//
// Q3(变体): 如果要拼成最小数呢？
//    → 把比较函数改成 a + b < b + a（升序排列），其余完全一样。
//      同样需要全零特判。（对应 剑指 Offer 45）
//
// Q4(复杂度): 排序的比较函数内有字符串拼接，真实复杂度是多少？
//    → 每次比较 O(k)，k 是字符串长度（≤10）。排序 O(n log n) 次比较，
//      总计 O(nk log n)。由于 k 是常数级别，实际复杂度 O(n log n)。
// ============================================================
