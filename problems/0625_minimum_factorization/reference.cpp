// ============================================================
// 625. Minimum Factorization (最小因式分解)
// 难度: Medium | 标签: Greedy, Math
// ============================================================
// 题意: 给定正整数 num, 找最小正整数 x 使 x 的每位数字之积 == num
//       如果无解或超出 32 位有符号整数范围, 返回 0
// ============================================================

// ============================================================
// 解法一: 贪心分解 + vector 收集因子 (推荐)
// ============================================================
// 思路: 从 9 到 2 贪心提取因子, 大因子减少位数
//       提取完后反转(小到大)组成最小数
// 时间: O(log num) | 空间: O(log num)
// ============================================================

class Solution {
public:
    int smallestFactorization(int num) {
        // 特殊情况: num == 1, 答案就是 1
        if (num == 1) return 1;

        vector<int> digits;

        // 从 9 到 2 贪心提取因子
        // 大因子先提取 -> 减少位数 -> 数更小
        for (int d = 9; d >= 2; d--) {
            while (num % d == 0) {
                digits.push_back(d);
                num /= d;
            }
        }

        // 如果 num > 1, 说明包含大于 9 的质因子, 无解
        if (num > 1) return 0;

        // digits 中因子按从大到小排列 (先提取的 9, 后提取的 2)
        // 反转后从小到大排列, 组成最小的十进制数
        long result = 0;
        for (int i = (int)digits.size() - 1; i >= 0; i--) {
            result = result * 10 + digits[i];
            if (result > INT_MAX) return 0;  // 溢出检测
        }

        return (int)result;
    }
};

