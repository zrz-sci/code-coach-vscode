//     其他方式: 加 n (mod n 恢复), 交换到正确位置。
//
// Q4: 和 LeetCode 448 (找缺失数) 的关系?
//     448 只找缺失 (取负+扫正), 本题多了 "找重复" (取负时检测已负)。
