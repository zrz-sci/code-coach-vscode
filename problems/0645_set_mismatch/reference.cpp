// 【解法对比】
//
// | 解法        | 时间      | 空间  | 修改原数组 | 优势                  |
// |-------------|----------|-------|-----------|----------------------|
// | 哈希计数    | O(n)     | O(n)  | 否        | 最简单，不会出错       |
// | 原地标记    | O(n)     | O(1)  | 是        | O(1)空间，技巧性强     |
// | 数学法      | O(n)     | O(1)  | 否        | O(1)空间+不修改数组    |
// | 排序法      | O(nlogn) | O(1)  | 是        | 简单但慢              |
