//
// 2. 返回顺序搞反:
//    ✗ return {missing, dup};  → 题目要求 [重复, 缺失]
//    ✓ return {dup, missing};
//
// 3. 数学法溢出:
//    ✗ int sum_n2 = n*(n+1)*(2*n+1)/6;  → n=10^4 时 int 溢出
//    ✓ long long sum_n2 = ...
//
// 4. 原地标记中 nums[i] 可能为 0:
//    本题 nums[i] >= 1 不存在 0。但如果值域包含 0,
//    取负标记失效 (-0 == 0)。改用 "加 n" 标记法。
//
// ============================================================
