/*
 * LeetCode 645: Set Mismatch (错误的集合)
 *
 * 【题目本质】
 * 集合 {1,..,n} 中一个数重复、一个数缺失。找出 [重复数, 缺失数]。
 * 核心挑战：能否 O(1) 额外空间。
 *
 * 【解法总览】
 * 解法1: 哈希计数           — O(n) / O(n)      — 最简单直接
 * 解法2: 原地标记(取负)     — O(n) / O(1)      — 面试首选 ⭐
 * 解法3: 数学法(求和+平方和) — O(n) / O(1)      — 不修改数组
 * 解法4: 排序法             — O(n log n) / O(1) — 朴素方案
 */

// ============================================================
// 解法1: 哈希计数
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 建一个 count 数组 [1..n]，遍历 nums 计数。
// count[i] == 2 → 重复数
// count[i] == 0 → 缺失数
//
// 示例: nums = [1,2,2,4]
//   count = [1, 2, 0, 1]  (索引1..4)
//             ↑  ↑  ↑  ↑
//             1  2  3  4
//   count[2]=2 → dup=2,  count[3]=0 → missing=3
// ============================================================
class Solution1 {
public:
    vector<int> findErrorNums(vector<int>& nums) {
        int n = nums.size();
        vector<int> count(n + 1, 0);
        int dup = -1, missing = -1;

        for (int num : nums) {
            count[num]++;
        }

        for (int i = 1; i <= n; i++) {
            if (count[i] == 2) dup = i;
            if (count[i] == 0) missing = i;
        }

        return {dup, missing};
    }
};

// ============================================================
// 解法2: 原地标记 (取负) — 面试首选 ⭐
// 时间: O(n)  空间: O(1) (修改原数组)
//
// 【思路】
// 值域 [1,n] → 索引 [0,n-1]，完美映射!
// 遍历数组，对每个 abs(nums[i])-1 位置取负:
//   - 如果目标位置已经是负 → 这个值之前出现过 → 重复!
//   - 否则取负标记 "已访问"
// 第二遍: 仍为正的位置 i → 值 i+1 从未出现 → 缺失!
//
// 为什么必须用 abs(nums[i])?
//   因为前面的步骤可能已经把某些位置取负了。
//   如果不取 abs，nums[i] 可能已经是负数，idx 会是负数 → 越界!
//
// 示例: nums = [1,2,2,4]
//
//   i=0: val=|1|=1, idx=0
//     nums[0]=1 > 0 → 取负, nums=[-1, 2, 2, 4]
//
//   i=1: val=|2|=2, idx=1
//     nums[1]=2 > 0 → 取负, nums=[-1, -2, 2, 4]
//
//   i=2: val=|2|=2, idx=1
//     nums[1]=-2 < 0 → 已标记! dup = 2 ✓
//
//   i=3: val=|4|=4, idx=3
//     nums[3]=4 > 0 → 取负, nums=[-1, -2, 2, -4]
//
//   第二遍:
//   i=0: nums[0]=-1 < 0 → OK
//   i=1: nums[1]=-2 < 0 → OK
//   i=2: nums[2]= 2 > 0 → 未标记! missing = 2+1 = 3 ✓
//   i=3: nums[3]=-4 < 0 → OK
//
//   return [2, 3] ✓
// ============================================================
class Solution2 {
public:
    vector<int> findErrorNums(vector<int>& nums) {
        int dup = -1, missing = -1;
        int n = nums.size();

        // 第一遍: 标记 + 找重复
        for (int i = 0; i < n; i++) {
            int idx = abs(nums[i]) - 1;   // 值→索引映射
            if (nums[idx] < 0) {
                dup = abs(nums[i]);        // 已标记 → 重复!
            } else {
                nums[idx] = -nums[idx];    // 取负标记
            }
        }

        // 第二遍: 找缺失
        for (int i = 0; i < n; i++) {
            if (nums[i] > 0) {
                missing = i + 1;           // 未标记 → 缺失!
            }
        }

        return {dup, missing};
    }
};

// ============================================================
// 解法3: 数学法 (求和 + 平方和) — 不修改数组
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 设重复数 = d, 缺失数 = m
//
// 等式1: sum(nums) - sum(1..n) = d - m        ... (1)
// 等式2: sum(nums^2) - sum(1^2..n^2) = d^2 - m^2
//       = (d+m)(d-m)                          ... (2)
//
// 从 (1): diff1 = d - m
// 从 (2): diff2 = d^2 - m^2
//         d + m = diff2 / diff1               ... (3)
//
// 解出:
//   d = (diff1 + (diff2/diff1)) / 2
//   m = d - diff1
//
// 示例: nums = [1,2,2,4], n = 4
//   sum(nums)  = 9,   sum(1..4) = 10  → diff1 = -1
//   sum(nums²) = 25,  sum(1²..4²) = 30 → diff2 = -5
//   d + m = -5 / -1 = 5
//   d - m = -1
//   d = (5 + (-1)) / 2 = 2 ✓
//   m = 2 - (-1) = 3     ✓
//
// 注意: 必须用 long long 防溢出!
//   n 最大 10^4, n^3 约 10^12, 超出 int 范围
// ============================================================
class Solution3 {
public:
    vector<int> findErrorNums(vector<int>& nums) {
        long long n = nums.size();
        long long sum_n = n * (n + 1) / 2;
        long long sum_n2 = n * (n + 1) * (2 * n + 1) / 6;

        long long sum_nums = 0, sum_nums2 = 0;
        for (int num : nums) {
            sum_nums += num;
            sum_nums2 += (long long)num * num;
        }

        long long diff1 = sum_nums - sum_n;    // d - m
        long long diff2 = sum_nums2 - sum_n2;  // d^2 - m^2
        long long sum_dm = diff2 / diff1;       // d + m

        int dup = (int)(diff1 + sum_dm) / 2;
        int missing = dup - (int)diff1;

        return {dup, missing};
    }
};

// ============================================================
// 解法4: 排序法
// 时间: O(n log n)  空间: O(1) (原地排序) 或 O(log n) (排序栈)
//
// 【思路】
// 排序后: 相邻相同 → 重复数
// 缺失数: 通过 期望总和 - 实际总和 + 重复数 得到
//
// 示例: nums = [1,2,2,4] → 排序后 [1,2,2,4]
//   nums[2] == nums[1] = 2 → dup = 2
//   expected = 10, actual = 9, missing = 10 - 9 + 2 = 3 ✓
// ============================================================
class Solution4 {
public:
    vector<int> findErrorNums(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        int dup = -1;
        int n = nums.size();

        for (int i = 1; i < n; i++) {
            if (nums[i] == nums[i - 1]) {
                dup = nums[i];
                break;
            }
        }

        long long sum = 0;
        for (int num : nums) sum += num;
        long long expected = (long long)n * (n + 1) / 2;
        int missing = (int)(expected - sum + dup);

        return {dup, missing};
    }
};

