/*
 * LeetCode 735: 小行星碰撞 (Asteroid Collision)
 *
 * 【题目本质】
 * 模拟一维空间中小行星的碰撞过程：向右飞的正数和向左飞的负数相遇会碰撞，
 * 大的存活，等大同归于尽。用栈维护存活小行星，逐个处理碰撞。
 *
 * 【解法总览】
 * 解法1: 栈模拟      — O(n) / O(n)   — 面试首选，逻辑清晰
 * 解法2: 原地双指针  — O(n) / O(1)   — 空间优化，用数组本身当栈
 */

// ============================================================
// 解法1: 栈模拟 — 面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 从左到右遍历每颗小行星，用 vector 当栈维护当前存活的小行星。
// 
// 碰撞只发生在一种情况：栈顶 > 0（向右飞）且 新来 < 0（向左飞）
// 其余三种组合（正正、负负、负正）都不会碰撞。
//
// 碰撞时，用 while 循环持续处理（一颗大负数可能连续撞毁多颗正数）：
//   - 栈顶 < |新| → 栈顶被毁，弹出，继续检查
//   - 栈顶 == |新| → 同归于尽，弹出栈顶，新的也死
//   - 栈顶 > |新| → 新的被毁，停止
//
// 碰撞过程可视化（以 [3, 5, -6, 2, -1, 4] 为例）：
//
//   处理 3:   栈 = [3]              ← 正数，直接入栈
//   处理 5:   栈 = [3, 5]           ← 正数，直接入栈
//   处理 -6:
//     碰 5:   |5| < |-6| → 弹出5    栈 = [3]
//     碰 3:   |3| < |-6| → 弹出3    栈 = []
//     -6存活: 栈 = [-6]
//   处理 2:   栈 = [-6, 2]          ← 栈顶为负，不碰
//   处理 -1:
//     碰 2:   |2| > |-1| → -1被毁   栈 = [-6, 2]
//   处理 4:   栈 = [-6, 2, 4]       ← 正数，直接入栈
//   结果: [-6, 2, 4] ✓
//
// 均摊分析：每颗小行星最多入栈1次、出栈1次 → 总操作 ≤ 2n → O(n)
// ============================================================
class Solution1 {
public:
    vector<int> asteroidCollision(vector<int>& asteroids) {
        vector<int> stk; // 用 vector 当栈，方便直接返回结果
        
        for (int ast : asteroids) {
            bool alive = true; // 追踪当前小行星是否存活
            
            // 碰撞条件：栈顶向右(>0) 且 当前向左(<0)
            // 四个条件缺一不可：alive、非空、栈顶正、当前负
            while (alive && !stk.empty() && stk.back() > 0 && ast < 0) {
                if (stk.back() < -ast) {
                    // 栈顶更小 → 栈顶被毁，弹出
                    // 当前小行星继续存活，while 继续检查下一个栈顶
                    stk.pop_back();
                } else if (stk.back() == -ast) {
                    // 等大 → 同归于尽
                    stk.pop_back();  // 栈顶被毁
                    alive = false;   // 当前小行星也被毁
                } else {
                    // 栈顶更大 → 当前小行星被毁
                    alive = false;
                }
            }
            
            // 如果当前小行星还活着，入栈
            if (alive) {
                stk.push_back(ast);
            }
        }
        
        return stk;
    }
};

// ============================================================
// 解法2: 原地双指针 — 空间优化版
// 时间: O(n)  空间: O(1) 额外空间
//
// 【思路】
// 解法1 的瓶颈：使用了 O(n) 额外栈空间。
// 优化思路：直接在原数组上操作，用 top 指针模拟栈顶。
// asteroids[0..top] 就是当前栈中的内容。
//
// 核心逻辑和解法1 完全一致，只是：
//   stk.back()    → asteroids[top]
//   stk.pop_back() → top--
//   stk.push_back() → asteroids[++top] = ast
//
// 注意：这种写法会修改输入数组。
// ============================================================
class Solution2 {
public:
    vector<int> asteroidCollision(vector<int>& asteroids) {
        int top = -1; // 栈顶指针，-1 表示栈空
        
        for (int i = 0; i < (int)asteroids.size(); i++) {
            int ast = asteroids[i];
            bool alive = true;
            
            // 逻辑与解法1 完全一致
            while (alive && top >= 0 && asteroids[top] > 0 && ast < 0) {
                if (asteroids[top] < -ast) {
                    top--; // 栈顶被毁
                } else if (asteroids[top] == -ast) {
                    top--;          // 栈顶被毁
                    alive = false;  // 当前也被毁
                } else {
                    alive = false;  // 当前被毁
                }
            }
            
            if (alive) {
                asteroids[++top] = ast; // 入栈：写入数组，top 前进
            }
        }
        
        // 截断数组，只保留栈中的元素
        asteroids.resize(top + 1);
        return asteroids;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 解法1: 栈模拟  | 解法2: 原地双指针 |
// |------------|---------------|-------------------|
// | 时间       | O(n)          | O(n)              |
// | 额外空间   | O(n)          | O(1)              |
// | 代码清晰度 | ★★★★★       | ★★★★            |
// | 修改输入   | 否            | 是                |
// | 面试推荐   | ⭐ 首选       | 追问优化时给出     |
//
// 两者核心逻辑完全一致，每颗小行星最多入栈出栈各一次，
// 均摊 O(n)。面试建议先写解法1，被追问空间优化再给解法2。
//
// ============================================================
// 【易错点】
//
// 1. 用 if 代替 while 处理碰撞：
//    ✗ if (!stk.empty() && stk.back() > 0 && ast < 0) { ... }
//    ✓ while (alive && !stk.empty() && stk.back() > 0 && ast < 0) { ... }
//    原因: [5, 10, -15] 中 -15 要先毁10再毁5，需要循环
//
// 2. 同归于尽后仍入栈：
//    ✗ 等大时只 pop_back() 但忘了 alive = false → 被毁的小行星仍入栈
//    ✓ 等大时必须 pop_back() + alive = false
//
// 3. 碰撞方向写反：
//    ✗ stk.back() < 0 && ast > 0  ← 栈顶向左、新来向右 = 背对背，不碰！
//    ✓ stk.back() > 0 && ast < 0  ← 栈顶向右、新来向左 = 面对面碰撞
//
// 4. 大小比较忘记处理符号：
//    ✗ stk.back() < ast   ← 正数 vs 负数直接比较，逻辑混乱
//    ✓ stk.back() < -ast  ← 拿栈顶的值和新小行星绝对值比
//
// ============================================================
// 【面试追问】
//
// Q1: "碰撞只在什么情况下发生？为什么四种方向组合只有一种碰？"
//     → 只有"栈顶正(→) + 新来负(←)"面对面飞才碰。
//       正正/负负同向不碰，负正背对背越飞越远不碰。
//
// Q2: "内层有 while 循环，时间复杂度真的是 O(n) 吗？怎么证明？"
//     → 均摊分析：每颗小行星最多入栈1次出栈1次。
//       虽然某次迭代 while 可能执行多次（如 -15 连毁多颗），
//       但总弹出次数 ≤ n，所以总操作 ≤ 2n = O(n)。
//
// Q3: "能否不用额外空间？"
//     → 解法2：用数组本身当栈，top 指针模拟栈顶，O(1) 额外空间。
//
// Q4: "如果小行星速度不同（值代表速度），怎么判断谁先碰？"
//     → 这变成了一个事件驱动模拟问题。需要计算每对可能碰撞的
//       小行星相遇时间，用优先队列按时间排序处理。复杂度升至
//       O(n log n)。
// ============================================================
