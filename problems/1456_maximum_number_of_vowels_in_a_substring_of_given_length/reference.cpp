/*
 * LeetCode 1456: Maximum Number of Vowels in a Substring of Given Length
 * (定长子串中元音的最大数目)
 *
 * 【题目本质】
 * 在字符串中滑动一个大小固定为 k 的窗口，找窗口内元音字母的最大数量。
 * 经典"定长滑动窗口"问题。
 *
 * 【解法总览】
 * 解法1: 暴力枚举       — O(n*k) / O(1)  — 理解题意用
 * 解法2: 定长滑动窗口    — O(n)   / O(1)  — 面试必须写出 ⭐
 * 解法3: 双指针显式写法  — O(n)   / O(1)  — 更清晰的变体
 */

// ============================================================
// 解法1: 暴力枚举 — 对每个长度为 k 的子串，重新统计元音数量
// 时间: O(n*k)  空间: O(1)
//
// 【思路】
// 枚举所有起始位置 i = 0, 1, ..., n-k，
// 对每个子串 s[i..i+k-1] 统计元音数。
//
// 【瓶颈】
// n=10^5, k=50000 时约 5*10^9 次操作，超时。
// 相邻两个窗口共享 k-1 个字符，却都重新统计了。
// 优化方向：增量更新，只处理变化的那一个字符。
// ============================================================
class Solution1 {
public:
    int maxVowels(string s, int k) {
        int n = s.size(), ans = 0;
        for (int i = 0; i <= n - k; i++) {
            int cnt = 0;
            for (int j = i; j < i + k; j++) {
                char c = s[j];
                if (c == 'a' || c == 'e' || c == 'i' || c == 'o' || c == 'u') {
                    cnt++;
                }
            }
            ans = max(ans, cnt);
        }
        return ans;
    }
};

// ============================================================
// 解法2: 定长滑动窗口 — 增量式更新元音计数
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 维护窗口内的元音计数 cnt。
// 遍历字符串时：
//   - 新字符 s[i] 滑入窗口 → 如果是元音，cnt++
//   - 当 i >= k 时，旧字符 s[i-k] 滑出窗口 → 如果是元音，cnt--
//   - 更新 ans = max(ans, cnt)
//
// 滑动窗口过程 (s = "abciiidef", k = 3):
//
//   索引:  0  1  2  3  4  5  6  7  8
//   字符:  a  b  c  i  i  i  d  e  f
//   元音:  Y  N  N  Y  Y  Y  N  Y  N
//
//   i=0: +a(Y), cnt=1    窗口: [a]           (未满)
//   i=1: +b(N), cnt=1    窗口: [a b]         (未满)
//   i=2: +c(N), cnt=1    窗口: [a b c]       ans=1
//   i=3: -a(Y), +i(Y)    窗口: [b c i]       ans=1, cnt=1
//   i=4: -b(N), +i(Y)    窗口: [c i i]       ans=2, cnt=2
//   i=5: -c(N), +i(Y)    窗口: [i i i]       ans=3, cnt=3 ← max
//   i=6: -i(Y), +d(N)    窗口: [i i d]       ans=3, cnt=2
//   i=7: -i(Y), +e(Y)    窗口: [i d e]       ans=3, cnt=2
//   i=8: -i(Y), +f(N)    窗口: [d e f]       ans=3, cnt=1
//
//   答案: 3
//
// 【为什么 O(n)】
// 单层 for 循环，每个字符恰好被处理两次（滑入 + 滑出），总操作 2n。
// ============================================================
class Solution2 {
public:
    int maxVowels(string s, int k) {
        // lambda 判断元音（简洁写法）
        auto isVowel = [](char c) {
            return c == 'a' || c == 'e' || c == 'i' || c == 'o' || c == 'u';
        };

        int cnt = 0, ans = 0;

        for (int i = 0; i < (int)s.size(); i++) {
            // 右端字符滑入窗口
            if (isVowel(s[i])) cnt++;

            // 窗口满了后（i >= k），左端字符滑出
            // i=k 时，窗口 [1, k]，需要滑出 s[0] = s[i-k]
            if (i >= k && isVowel(s[i - k])) cnt--;

            // 更新最大元音数
            ans = max(ans, cnt);

            // 可选优化：如果已经全是元音，不可能更大
            // if (ans == k) return k;
        }

        return ans;
    }
};

// ============================================================
// 解法3: 双指针显式写法 — 先构建初始窗口，再滑动
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 和解法2 逻辑完全相同，但分两个阶段写，更容易理解：
//   阶段1: 构建第一个窗口 [0, k-1]
//   阶段2: 窗口从位置 1 滑动到 n-k
//
// 滑动窗口过程 (s = "leetcode", k = 3):
//
//   索引:  0  1  2  3  4  5  6  7
//   字符:  l  e  e  t  c  o  d  e
//   元音:  N  Y  Y  N  N  Y  N  Y
//
//   阶段1: 初始窗口 [l e e], cnt=2, ans=2
//
//   阶段2:
//   right=3: -l(N), +t(N) → cnt=2  窗口:[e e t]  ans=2
//   right=4: -e(Y), +c(N) → cnt=1  窗口:[e t c]  ans=2
//   right=5: -e(Y), +o(Y) → cnt=1  窗口:[t c o]  ans=2
//   right=6: -t(N), +d(N) → cnt=1  窗口:[c o d]  ans=2
//   right=7: -c(N), +e(Y) → cnt=2  窗口:[o d e]  ans=2
//
//   答案: 2
// ============================================================
class Solution3 {
public:
    int maxVowels(string s, int k) {
        // 用 string::npos 的 find 技巧判断元音
        // "aeiou" 中找 c，找到则 != npos
        string vowels = "aeiou";
        auto isVowel = [&](char c) {
            return vowels.find(c) != string::npos;
        };

        // 阶段1: 构建初始窗口 [0, k-1]
        int cnt = 0;
        for (int i = 0; i < k; i++) {
            if (isVowel(s[i])) cnt++;
        }
        int ans = cnt;

        // 提前终止：初始窗口全是元音
        if (ans == k) return k;

        // 阶段2: 滑动窗口
        for (int right = k; right < (int)s.size(); right++) {
            int left = right - k;   // 滑出的字符索引
            if (isVowel(s[right])) cnt++;  // 新字符滑入
            if (isVowel(s[left]))  cnt--;  // 旧字符滑出
            ans = max(ans, cnt);
            if (ans == k) return k;  // 提前终止
        }

        return ans;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 写法特点           | 时间   | 空间 |
// |------------|--------------------|--------|------|
// | 暴力       | 双层循环，直观      | O(n*k) | O(1) |
// | 滑窗(单指针) | 一个 for，隐式左端 | O(n)   | O(1) |
// | 滑窗(双指针) | 两阶段，显式左右   | O(n)   | O(1) |
//
// 推荐：解法2（单指针写法）最简洁。
// 解法3 如果你更习惯"先建窗口再滑动"的思维模式也很好。
//
// ============================================================
// 【易错点】
//
// 1. 窗口左端索引算错：
//    ✗ s[i - k + 1]  或 s[i - k - 1]
//    ✓ s[i - k]
//    验证：i=k 时窗口 [1,k]，滑出 s[0] = s[k-k] = s[0] ✓
//
// 2. 不检查滑出字符是否是元音就减 cnt：
//    ✗ if (i >= k) cnt--;   // 不管是不是元音都减
//    ✓ if (i >= k && isVowel(s[i-k])) cnt--;
//
// 3. 元音判断遗漏：
//    ✗ 漏掉 'u' 或错误地包含 'y'
//    ✓ 只有 a, e, i, o, u 五个
//
// 4. 初始窗口阶段忘记更新 ans：
//    双指针写法中，初始窗口建完后必须设 ans = cnt
//    否则如果最优窗口恰好是第一个窗口，会返回 0
//
// ============================================================
// 【面试追问】
//
// Q1: "定长滑动窗口和变长滑动窗口的区别？"
//     定长：窗口大小固定为 k，滑动时同时加一个减一个。
//     变长：窗口大小可变，用 while 循环收缩到满足条件。
//     本题是定长，LC 3 是变长。
//
// Q2: "如果 k = 1 呢？"
//     窗口大小 1，就是找字符串中是否存在元音字母。
//     如果有，返回 1；否则返回 0。我们的代码自然处理。
//
// Q3: "如果 k = n（整个字符串）呢？"
//     只有一个窗口，统计整个字符串的元音数。
//     代码中 for 循环只执行一轮，正确处理。
//
// Q4: "能否用前缀和做？"
//     可以。prefix[i] = s[0..i-1] 中元音数量。
//     窗口 [l, r] 的元音数 = prefix[r+1] - prefix[l]。
//     时间 O(n)，空间 O(n)。滑动窗口更好（空间 O(1)）。
//
// ============================================================
