/*
 * LeetCode 1005: K 次取反后最大化的数组和
 * 
 * 【题目本质】
 * 对数组做恰好 k 次取反操作（可重复选同一元素），使总和最大。
 * 贪心策略：优先翻绝对值最大的负数，用完负数后剩余 k 看奇偶。
 *
 * 【解法总览】
 * 解法1: 排序 + 贪心        — O(n log n) / O(1) — 面试首选 ⭐
 * 解法2: 最小堆贪心          — O(k log n) / O(n) — 最直觉
 * 解法3: 计数排序(桶)优化    — O(n + C) / O(C)   — 值域有限时的线性解
 */

// ============================================================
// 解法1: 排序 + 贪心 — 面试首选
// 时间: O(n log n)  空间: O(1)
//
// 【思路】
// 排序后，负数在前面且按从小到大排列（最负的在最前）。
// 贪心策略：
//   1. 从最小（最负）的数开始翻转，每翻一个负数，总和增加 2|x|
//   2. 负数翻完后，如果 k 还有剩余：
//      - k 为偶数：对同一个数翻偶数次等于没翻，无影响
//      - k 为奇数：必须翻一次，翻绝对值最小的数损失最少
//
// 示例: nums = [2, -3, -1, 5, -4], k = 2
//   排序: [-4, -3, -1, 2, 5]
//   翻 -4 → [4, -3, -1, 2, 5], k=1
//   翻 -3 → [4, 3, -1, 2, 5],  k=0  → 总和=13
// ============================================================
class Solution1 {
public:
    int largestSumAfterKNegations(vector<int>& nums, int k) {
        sort(nums.begin(), nums.end());
        
        // 贪心：优先翻转负数，从最小（最负）的开始
        for (int i = 0; i < (int)nums.size() && k > 0 && nums[i] < 0; i++, k--) {
            nums[i] = -nums[i];
        }
        
        // 翻转后数组不再有序，需要重新找最小值
        // 为什么不能用 nums[0]？因为 -4 翻成 4 后，4 > -3，顺序乱了
        int minVal = *min_element(nums.begin(), nums.end());
        
        int sum = 0;
        for (int x : nums) sum += x;
        
        // 剩余 k 为奇数：翻一次最小值，总和减少 2 * minVal
        // 剩余 k 为偶数：翻偶数次抵消，总和不变
        if (k % 2 == 1) {
            sum -= 2 * minVal;
        }
        
        return sum;
    }
};

// ============================================================
// 解法2: 最小堆贪心 — 最直觉的模拟
// 时间: O(k log n)  空间: O(n)
//
// 【思路】
// 不需要分析负数/正数/奇偶等各种情况。
// 核心观察：每次操作都应该翻转当前最小的数。
//   - 如果最小的是负数，翻转后变正，总和增加最多
//   - 如果最小的是正数（所有数都非负了），翻转最小的正数损失最少
// 用最小堆 O(log n) 取最小值，执行 k 次。
//
// 示例: nums = [3, -1, 0, 2], k = 3
//   堆: [-1, 0, 2, 3]
//   Step1: 弹出-1, 放入1 → 堆: [0, 1, 2, 3], k=2
//   Step2: 弹出0,  放入0 → 堆: [0, 1, 2, 3], k=1  ← 0翻转还是0
//   Step3: 弹出0,  放入0 → 堆: [0, 1, 2, 3], k=0
//   总和 = 0+1+2+3 = 6
//
// 注意：当 k 非常大时（如 10^9），这个方法会超时！
// 但题目 k ≤ 10^4，所以可以通过。
// ============================================================
class Solution2 {
public:
    int largestSumAfterKNegations(vector<int>& nums, int k) {
        // 小顶堆：堆顶是最小值
        priority_queue<int, vector<int>, greater<int>> pq(nums.begin(), nums.end());
        
        while (k-- > 0) {
            int smallest = pq.top();
            pq.pop();
            pq.push(-smallest);  // 取反后放回
        }
        
        int sum = 0;
        while (!pq.empty()) {
            sum += pq.top();
            pq.pop();
        }
        return sum;
    }
};

// ============================================================
// 解法3: 计数排序(桶)优化 — 线性时间
// 时间: O(n + C)  空间: O(C)，C = 201（值域 [-100, 100]）
//
// 【思路】
// 题目约束 nums[i] ∈ [-100, 100]，只有 201 种可能值。
// 用计数数组代替排序，直接在桶上操作翻转：
//   1. 从 val=-100 到 -1 遍历，把负数翻成正数（桶之间转移）
//   2. k 用完或负数翻完后，处理剩余 k 的奇偶性
//   3. 如果 k 为奇数，找绝对值最小的非零值翻转一次
//
// 优势：避免 O(n log n) 排序，当 n 很大、值域有限时更快
// ============================================================
class Solution3 {
public:
    int largestSumAfterKNegations(vector<int>& nums, int k) {
        // cnt[val + 100] = 值 val 的出现次数
        int cnt[201] = {};
        for (int x : nums) cnt[x + 100]++;
        
        // 第一步：贪心翻转负数，从 -100（绝对值最大的负数）开始
        for (int val = -100; val < 0 && k > 0; val++) {
            if (cnt[val + 100] > 0) {
                // 该值最多翻 min(出现次数, 剩余k) 个
                int flip = min(cnt[val + 100], k);
                cnt[val + 100] -= flip;    // val 减少 flip 个
                cnt[-val + 100] += flip;   // -val 增加 flip 个
                k -= flip;
            }
        }
        
        // 第二步：k 还有剩余且为奇数，翻转绝对值最小的数
        if (k % 2 == 1) {
            // 从 0 开始找绝对值最小的值
            for (int val = 0; val <= 100; val++) {
                if (cnt[val + 100] > 0) {
                    // val=0 时翻转无影响（0 取反还是 0），直接 break
                    cnt[val + 100]--;
                    cnt[-val + 100]++;
                    break;
                }
            }
        }
        
        // 第三步：统计总和
        int sum = 0;
        for (int val = -100; val <= 100; val++) {
            sum += val * cnt[val + 100];
        }
        return sum;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 时间        | 空间   | 适用场景              |
// |-------------|-------------|--------|-----------------------|
// | 排序+贪心   | O(n log n)  | O(1)   | 通用，面试首选 ⭐      |
// | 最小堆      | O(k log n)  | O(n)   | k 较小时，代码最简     |
// | 计数排序    | O(n + C)    | O(C)   | 值域有限，追问优化时用  |
//
// 面试建议：先给解法1（排序+贪心），被追问 O(n) 时再给解法3。
// 解法2 作为"第一反应的暴力贪心"口述即可。
//
// 【易错点】
// 1. 翻转负数后数组不再有序：
//    ✗ sum -= 2 * nums[0];  // nums[0] 可能是翻转后的大正数
//    ✓ sum -= 2 * *min_element(nums.begin(), nums.end());
//
// 2. for 循环条件遗漏 nums[i] < 0：
//    ✗ for(int i=0; i<n && k>0; i++) nums[i]=-nums[i];
//      → 会把刚翻正的数又翻回负数！
//    ✓ for(int i=0; i<n && k>0 && nums[i]<0; i++) nums[i]=-nums[i];
//
// 3. 忘记处理剩余 k 的奇偶性：
//    翻完负数后直接求和 → 当 k=5 翻了 2 个负数，还剩 3 次被忽略
//
// 4. 计数排序中负数翻转方向搞反：
//    ✗ cnt[val + 100]++;  cnt[-val + 100]--;  // 方向反了
//    ✓ cnt[val + 100]--;  cnt[-val + 100]++;  // 从 val 转移到 -val
//
// 【面试追问】
// Q1: 贪心策略为什么正确？
//     → 翻负数收益正（+2|x|），翻正数收益负（-2x）。
//       优先翻绝对值最大的负数收益最高，这是局部最优=全局最优。
//
// Q2: k 高达 10^9 怎么办？解法2 的最小堆还能用吗？
//     → 不能，O(k log n) 超时。但解法1/3 不受影响，
//       因为翻完负数后只判断 k%2，不需要执行 k 次。
//
// Q3: 值域不限（如 [-10^9, 10^9]），能否 O(n)？
//     → 计数排序不可行。但可以 O(n) 用 nth_element 找最小绝对值，
//       配合一次遍历翻负数。不过面试中 O(n log n) 排序已经足够好。
// ============================================================
