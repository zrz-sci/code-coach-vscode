/*
 * LeetCode 773: Sliding Puzzle (滑动谜题)
 *
 * 【题目本质】
 * 2x3 棋盘上有 0-5 六个数字，0 可以和相邻位置交换。
 * 求从初始状态到目标 [[1,2,3],[4,5,0]] 的最少移动次数。
 * 核心：BFS 状态空间搜索，状态空间仅 6!=720，极小。
 *
 * 【解法总览】
 * 解法1: BFS 状态空间搜索    — O(6!*6) / O(6!) — 面试首选
 * 解法2: 双向 BFS            — O(6!*6) / O(6!) — 进阶优化
 */

// ============================================================
// 解法1: BFS 状态空间搜索 — 面试首选 ⭐
// 时间: O(6! * 6) ≈ O(4320)  空间: O(6!) ≈ O(720)
//
// 【思路】
// 1. 将 2x3 棋盘展平为字符串作为状态 (如 "412503")
// 2. 预定义每个位置的邻居表 (2x3 网格是固定的)
// 3. BFS 层序遍历: 每层=一步, 找到 "123450" 返回步数
//
// 邻居表推导:
//   ┌───┬───┬───┐
//   │ 0 │ 1 │ 2 │
//   ├───┼───┼───┤
//   │ 3 │ 4 │ 5 │
//   └───┴───┴───┘
//   pos 0: 右=1, 下=3       → {1, 3}
//   pos 1: 左=0, 右=2, 下=4 → {0, 2, 4}
//   pos 2: 左=1, 下=5       → {1, 5}
//   pos 3: 上=0, 右=4       → {0, 4}
//   pos 4: 上=1, 左=3, 右=5 → {1, 3, 5}
//   pos 5: 上=2, 左=4       → {2, 4}
//
// BFS 搜索过程 (board=[[4,1,2],[5,0,3]]):
//
//   Layer 0: "412503" (0在pos4)
//     ├→ swap(4,1)="402513"
//     ├→ swap(4,3)="412053"  ← 这条路径最终5步到达目标
//     └→ swap(4,5)="412530"
//
//   Layer 1-4: 继续展开...
//
//   Layer 5: 某状态swap后得到 "123450" → return 5
//
//   完整路径:
//     "412503" → "412053" → "012453" → "102453" → "120453" → "123450"
//     ┌───┬───┬───┐   ┌───┬───┬───┐   ┌───┬───┬───┐
//     │ 4 │ 1 │ 2 │   │ 4 │ 1 │ 2 │   │ 0 │ 1 │ 2 │
//     ├───┼───┼───┤ → ├───┼───┼───┤ → ├───┼───┼───┤ → ...
//     │ 5 │ 0 │ 3 │   │ 0 │ 5 │ 3 │   │ 4 │ 5 │ 3 │
//     └───┴───┴───┘   └───┴───┴───┘   └───┴───┴───┘
//     step 0           step 1           step 2
//
//     ┌───┬───┬───┐   ┌───┬───┬───┐   ┌───┬───┬───┐
//     │ 1 │ 0 │ 2 │   │ 1 │ 2 │ 0 │   │ 1 │ 2 │ 3 │
//     ├───┼───┼───┤ → ├───┼───┼───┤ → ├───┼───┼───┤
//     │ 4 │ 5 │ 3 │   │ 4 │ 5 │ 3 │   │ 4 │ 5 │ 0 │
//     └───┴───┴───┘   └───┴───┴───┘   └───┴───┴───┘
//     step 3           step 4           step 5 ✓
// ============================================================
class Solution1 {
public:
    int slidingPuzzle(vector<vector<int>>& board) {
        // Step 1: 展平棋盘为字符串
        string start;
        for (auto& row : board)
            for (int x : row)
                start += to_string(x);

        string target = "123450";
        if (start == target) return 0;  // 特判

        // Step 2: 预定义每个位置的邻居
        // 位置编号: 0 1 2
        //           3 4 5
        vector<vector<int>> neighbors = {
            {1, 3},       // pos 0 的邻居
            {0, 2, 4},    // pos 1 的邻居
            {1, 5},       // pos 2 的邻居
            {0, 4},       // pos 3 的邻居
            {1, 3, 5},    // pos 4 的邻居
            {2, 4}        // pos 5 的邻居
        };

        // Step 3: BFS 层序遍历
        unordered_set<string> visited;
        queue<string> q;
        q.push(start);
        visited.insert(start);
        int steps = 0;

        while (!q.empty()) {
            steps++;  // 进入新的一层 = 多走一步
            int sz = q.size();

            while (sz--) {
                string curr = q.front();
                q.pop();

                // 找到 0 的位置
                int zeroPos = curr.find('0');

                // 尝试和每个邻居交换
                for (int nb : neighbors[zeroPos]) {
                    // ⚠️ 必须拷贝再交换，不能在 curr 上直接操作
                    string next = curr;
                    swap(next[zeroPos], next[nb]);

                    // 检查是否到达目标
                    if (next == target) return steps;

                    // 未访问过则入队
                    if (!visited.count(next)) {
                        visited.insert(next);
                        q.push(next);
                    }
                }
            }
        }

        // BFS 穷尽所有可达状态，未找到目标
        return -1;
    }
};

// ============================================================
// 解法2: 双向 BFS — 进阶优化
// 时间: O(6! * 6)  空间: O(6!)
//
// 【思路】
// 从起点和终点同时搜索，当两端"相遇"时路径找到。
// 每次扩展较小的那一端，保持两端搜索均衡。
//
// 对于本题（720个状态），双向 BFS 优化效果不明显。
// 但对于更大的状态空间（如 3x3 的8-puzzle, 9!=362880），
// 双向 BFS 可以显著减少搜索量。
//
// 核心改变:
//   单向 BFS: 一个队列，从起点向终点搜
//   双向 BFS: 两个集合(frontSet, backSet)，交替扩展
//   相遇条件: 一端生成的新状态在另一端的集合中
// ============================================================
class Solution2 {
public:
    int slidingPuzzle(vector<vector<int>>& board) {
        string start;
        for (auto& row : board)
            for (int x : row)
                start += to_string(x);

        string target = "123450";
        if (start == target) return 0;

        vector<vector<int>> neighbors = {
            {1, 3}, {0, 2, 4}, {1, 5}, {0, 4}, {1, 3, 5}, {2, 4}
        };

        // 两个方向的搜索前沿
        unordered_set<string> frontSet = {start};
        unordered_set<string> backSet = {target};
        unordered_set<string> visited = {start, target};
        int steps = 0;

        while (!frontSet.empty() && !backSet.empty()) {
            steps++;

            // 优化: 总是扩展较小的一端
            if (frontSet.size() > backSet.size()) {
                swap(frontSet, backSet);
            }

            unordered_set<string> nextSet;
            for (const string& curr : frontSet) {
                int zeroPos = curr.find('0');
                for (int nb : neighbors[zeroPos]) {
                    string next = curr;
                    swap(next[zeroPos], next[nb]);

                    // 和另一端相遇 → 找到最短路径
                    if (backSet.count(next)) return steps;

                    if (!visited.count(next)) {
                        visited.insert(next);
                        nextSet.insert(next);
                    }
                }
            }
            frontSet = nextSet;
        }

        return -1;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 时间         | 空间    | 实现难度 | 适用场景        |
// |------------|-------------|---------|---------|----------------|
// | BFS        | O(6!*6)     | O(6!)   | 简单    | 本题首选         |
// | 双向 BFS   | O(6!*6) 更快 | O(6!)   | 中等    | 状态空间更大时    |
// | A*         | O(6!*6) 最快 | O(6!)   | 较难    | 3x3以上棋盘     |
//
// 本题状态空间仅 720，任何方法都瞬间完成。面试写 BFS 即可。
//
// ============================================================
// 【易错点】
//
// 1. 邻居表写错:
//    最常见: pos4 的邻居应该是 {1,3,5} (上左右)
//    调试: 画 2x3 网格，手动列每个位置的上下左右
//
// 2. 在 curr 上直接 swap 而不是拷贝:
//    ✗ swap(curr[zeroPos], curr[nb]); → 修改了当前状态，后续邻居出错
//    ✓ string next = curr; swap(next[zeroPos], next[nb]);
//
// 3. steps 计数放错位置:
//    ✗ 出队时 steps++ → 同一层节点步数不一致
//    ✓ 每层开始时 steps++（层序遍历模板）
//
// 4. 忘记起点特判:
//    ✗ 初始状态=目标但 BFS 至少走一步 → 返回1而非0
//    ✓ BFS 前检查 if (start == target) return 0
//
// 5. 目标检查放在出队时而非入队时:
//    ✗ 出队后检查 → 多一层延迟
//    ✓ 生成新状态时立即检查（更快，虽然正确性相同）
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么 BFS 而不是 DFS?
//     BFS 天然找最短路径。DFS 找到解不保证最短。
//
// Q2: 状态空间有多大?
//     6! = 720 种排列，约一半(360)可达。极小。
//
// Q3: 3x3 棋盘(8-puzzle)怎么办?
//     9! = 362880, BFS 仍可行但慢。用 A* + 曼哈顿距离更优。
//
// Q4: 如何不用BFS直接判断是否有解?
//     计算逆序数的奇偶性。起始和目标奇偶性相同才有解。
//
// ============================================================
