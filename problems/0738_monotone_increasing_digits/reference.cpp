/*
 * LeetCode 738: 单调递增的数字 (Monotone Increasing Digits)
 *
 * 【题目本质】
 * 给定整数 n，找 ≤ n 的最大整数，使得其各位数字从左到右非递减。
 * 核心：找到最左边需要"退位"的地方，退位后后面全填 9。
 *
 * 【解法总览】
 * 解法1: 暴力枚举 — O(n×d) / O(d) — 逐个检查（超时，理解题意用）
 * 解法2: 贪心（从右向左扫描） — O(d) / O(d) — 面试首选
 */

// ============================================================
// 解法1: 暴力枚举 — 从 n 往下逐个检查
// 时间: O(n × d)  空间: O(1) (不算输出)
//
// 【思路】
// 最直觉的想法：从 n 开始递减，每次检查当前数是否单调递增。
// 第一个满足条件的就是答案。
//
// 为什么想到：题目就是在一个范围内找最大的满足条件的数，
// 从大到小枚举是最自然的穷举策略。
//
// 瓶颈：n 最大 10^9，最坏情况（如 1000000000 → 999999999）
// 需要枚举 10^9 次，每次检查 O(d)，总计 ~10^10，远超时限。
// ============================================================
class Solution1 {
public:
    int monotoneIncreasingDigits(int n) {
        for (int i = n; i >= 0; i--) {
            if (isMonotone(i)) return i;
        }
        return 0;
    }
private:
    bool isMonotone(int num) {
        // 从个位往高位检查，prev 记录上一个（更低位的）数字
        int prev = 9;
        while (num > 0) {
            int digit = num % 10;
            if (digit > prev) return false; // 高位 > 低位 → 不单调
            prev = digit;
            num /= 10;
        }
        return true;
    }
};

// ============================================================
// 解法2: 贪心（从右向左扫描） — 找最左退位点，后面全填 9
// 时间: O(d)  空间: O(d)   d = 位数，最多 10
//
// 【思路】
// 暴力法不知道该在哪里"做手脚"，贪心法精确定位。
//
// 关键观察：
//   如果 s[i] > s[i+1]，那么从 i 这个位置开始就"太大了"。
//   要让结果 ≤ n，必须把 s[i] 减 1。
//   减 1 后，为了让结果尽可能大，i+1 及后面全填 9。
//
// 为什么从右向左扫描？
//   退位可能连锁！s[i]减1 后可能导致 s[i-1] > s[i]，需要继续退。
//   从右向左扫，每遇到一次违规就退位，mark 不断左移，
//   最终 mark 就是最左边的退位点。
//
// 示例推导 (n = 332):
//
//   字符串: "3 3 2"
//            0 1 2
//
//   从右向左扫描:
//     i=1: s[1]='3' > s[2]='2' → 退位! s[1]='2', mark=2
//     i=0: s[0]='3' > s[1]='2' → 连锁退位! s[0]='2', mark=1
//
//   扫描结束: s = "2 ? ?"
//   从 mark=1 开始填 9: s = "2 9 9"
//   结果: 299 ✓
//
// 再看 n = 1234:
//   从右向左扫描: 无任何 s[i] > s[i+1] 的情况
//   mark 保持初始值 = s.size() = 4
//   不需要填任何 9，结果就是 1234 本身 ✓
//
// 再看 n = 10:
//   字符串: "1 0"
//     i=0: s[0]='1' > s[1]='0' → 退位! s[0]='0', mark=1
//   从 mark=1 填 9: s = "0 9" → "09" → stoi = 9 ✓
// ============================================================
class Solution2 {
public:
    int monotoneIncreasingDigits(int n) {
        string s = to_string(n);
        int len = s.size();
        
        // mark: 从这个位置开始往后全填 9
        // 初始为 len（即不需要填 9，n 本身就合法）
        int mark = len;
        
        // 从右向左扫描，寻找所有违规点
        for (int i = len - 2; i >= 0; i--) {
            if (s[i] > s[i + 1]) {
                // s[i] 比右边大 → 违反单调递增
                // 贪心：s[i] 减 1，后面全填 9 是最大的合法方案
                s[i]--;
                mark = i + 1;  // 更新 mark 为更左的位置
                // 注意：不 break！继续向左检查连锁退位
            }
        }
        
        // 从 mark 开始，后面全部填 9
        for (int i = mark; i < len; i++) {
            s[i] = '9';
        }
        
        return stoi(s);
    }
};

// ============================================================
// 【解法对比】
//
// | 维度     | 暴力枚举            | 贪心扫描          |
// |----------|---------------------|-------------------|
// | 时间     | O(n×d)，最坏 10^10  | O(d)，最多 10     |
// | 空间     | O(1)                | O(d) 字符串       |
// | 思路难度 | 简单                | 中等（要想到退位） |
// | 面试     | 说明理解题意        | 必须写出          |
//
// 贪心是唯一能 AC 的方案，暴力只用于建立直觉。
//
// ============================================================
// 【易错点】
//
// 1. mark 初始值:
//    ✗ int mark = len - 1;
//      → 即使 n 本身单调递增（如 1234），也会把最后一位改成 9
//    ✓ int mark = len;
//      → "不需要填 9" 的安全初始值
//
// 2. 忘记连锁退位（遇到第一个违规就 break）:
//    ✗ if (s[i] > s[i+1]) { s[i]--; mark = i+1; break; }
//      → n=332 得到 329（只退了一次），正确答案是 299
//    ✓ 不 break，继续向左扫描
//
// 3. 循环起始位置:
//    ✗ for (int i = len - 1; i >= 0; i--) // 会访问 s[len] 越界
//    ✓ for (int i = len - 2; i >= 0; i--) // 从倒数第二位开始
//
// 4. 退位导致前导零:
//    n = 10 → s = "10" → 退位后 s = "09" → stoi("09") = 9
//    stoi 自动处理前导零，所以这里没问题。但如果自己手动转，要注意。
//
// ============================================================
// 【面试追问】
//
// Q1: 暴力能过吗？瓶颈在哪？
//     不能过。n = 10^9 时最坏枚举 10^9 次，每次 O(10) 检查。
//     瓶颈在于"不知道该退到哪"，只能一个一个试。
//
// Q2: 贪心的正确性怎么证？
//     当 s[i] > s[i+1] 时，当前数已经 > 任何单调递增的 d 位数
//     以 s[0..i] 开头的，所以 s[i] 至少要减 1。
//     减 1 后，i+1 到末尾放最大值（全 9）保证了结果最大。
//     从右向左扫保证了连锁退位被完整处理。
//
// Q3: 如果要求严格递增（相邻位不能相等）怎么改？
//     条件改为 s[i] >= s[i+1] 就退位。但填 9 的策略要变：
//     后缀不能全是 9，而要是类似 ...6789 的严格递增序列。
//     如果从 mark 到末尾有 k 位，需要填 (10-k), ..., 8, 9，
//     如果 k > 9（不可能，最多 10 位数字）或者填出来比退位后
//     的那一位还小，需要继续调整。
//
// Q4: 不用字符串，纯数学能做吗？
//     可以。用 / 和 % 提取每一位到数组，操作后再拼回来。
//     但代码更复杂，字符串版本更清晰，面试推荐字符串写法。
// ============================================================
