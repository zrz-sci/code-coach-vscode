//   解法1/2: 直接模拟，理解题意
//   → 解法3: 发现 mod 9 同余性质，一步到位
//
// 面试策略:
//   1. 先写解法1（展示编码能力，2分钟）
//   2. 面试官问 follow-up O(1)
//   3. 从 10≡1(mod 9) 推导数字根公式
//   4. 讨论 9 的倍数的修正技巧
//
// ============================================================
// 【易错点】
//
// 1. num=0 时公式给出错误结果:
//    ✗ 直接 return 1 + (num-1)%9;  // num=0 → 1+(-1%9)
//      C++ 中 -1%9 = -1, 所以结果是 0, 恰好对
//      但 Python 中 -1%9 = 8, 结果是 9, 错了!
//    ✓ 安全写法: if(num==0) return 0;
//
// 2. 用 num%9 而忘记处理 9 的倍数:
//    ✗ return num % 9;  // num=9 → 0, 应该是 9!
//    ✓ return 1 + (num-1) % 9;
//
// 3. 模拟循环条件 num > 0 而非 num >= 10:
//    ✗ while(num > 0) { sum += num%10; num /= 10; }
//      当 num 已经是一位数时还会多进入一次外层循环
//    ✓ while(num >= 10) { ... }  // 一位数直接返回
//
// 4. 不同语言中负数取模的行为不同:
//    C++/Java: -1 % 9 = -1 (truncated division)
//    Python:   -1 % 9 = 8  (floored division)
//    安全做法: 显式处理 num=0
//
// ============================================================
// 【面试追问 Interview Follow-ups】
//
// Q1: 为什么 10≡1(mod 9) 能推出数字根和 mod 9 相关？
// A1: 因为 10^k ≡ 1 (mod 9), 所以 num = Σ(d_i * 10^i) ≡ Σ(d_i) (mod 9)。
//     各位求和不改变 mod 9 余数，反复执行到一位数就是数字根。
//
// Q2: 如果换成各位数字之积（直到一位数），有 O(1) 公式吗？
// A2: 没有简单公式（乘法没有 mod 9 的性质）。只能模拟。
//     但有趣的是: multiplicative digital root 总是 0 或一位数。
//     如果某一步有 0，之后永远是 0。
//
// Q3: 数字根在实际中的应用？
// A3: 校验码(ISBN)、整除性判定(能被9整除⟺数字根为9)、
//     Casting out nines（九余数检验法）、Kaprekar 常数。
//
// Q4: 在 base-b 进制中，类似公式是什么？
// A4: digitalRoot_b(num) = 1 + (num-1) % (b-1)
//     因为 b ≡ 1 (mod b-1)，所以 num ≡ 各位之和 (mod b-1)。
//     十进制 b=10 → mod 9; 十六进制 b=16 → mod 15。
//
// Q5: 时间复杂度 O(log²n) 怎么得到的？
// A5: 内层循环 O(log n) 取各位。外层循环: k位数的各位和 <= 9k,
//     k = O(log n), 所以下一轮位数 = O(log k) = O(log log n)。
//     总轮数 O(log* n) ≈ O(1)（迭代对数），但严格上界 O(log n) 轮,
//     每轮 O(log n), 总计 O(log²n)。实际32位整数最多2-3轮。
