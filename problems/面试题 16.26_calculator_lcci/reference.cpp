/*
 * 【解法对比】
 * | 解法         | 时间   | 空间   | 适用场景                |
 * |-------------|--------|--------|------------------------|
 * | 栈(解法1/3) | O(n)   | O(n)   | 面试默认写法，逻辑清晰    |
 * | 双变量(解法2)| O(n)  | O(1)   | 空间优化追问时给出        |
 * | vector(解法3)| O(n)  | O(n)   | accumulate求和更简洁     |
 *
 * 面试首选: 解法3(vector) 或 解法1(stack)。
 * 如果面试官追问 O(1) 空间 → 切换解法2(双变量)。
 *
 * 【易错点清单】
 * 1. 多位数连续累积: num = num*10 + (s[i]-'0')，别漏了
 * 2. 末尾触发: 字符串最后一个字符是数字，没有运算符触发计算
 *    → 必须加 i == s.size()-1 条件
 * 3. 空格陷阱: 空格既不是数字也不是运算符，不能触发计算
 *    → 条件中必须排除 s[i] == ' '
 * 4. 符号传递: "-3*2" → 栈中推入 -3，乘 2 得 -6，符号自动正确
 * 5. 整数除法方向: C++ 向零截断(-7/2=-3)，Python 向负无穷(-7//2=-4)
 *
 * 【面试追问链】
 * Q1: 不含括号的四则运算怎么做？（本题）
 *     → 栈/双变量，延迟加减、即时乘除
 * Q2: 如果加上括号呢？（LC 224 / LC 772）
 *     → 递归下降 or 遇到 '(' 递归调用 calculate，
 *       遇到 ')' 返回结果；或者用双栈（运算符栈+数字栈）
 * Q3: 如何支持一元负号、函数调用(sin/cos)、变量？
 *     → 完整表达式求值: Shunting-Yard 算法或递归下降解析器
 *       一元负号：在开头或左括号后的 '-' 前插入 0
 */
