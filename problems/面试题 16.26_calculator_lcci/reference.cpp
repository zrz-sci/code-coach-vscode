/*
 * 面试题 16.26: 计算器 (Calculator LCCI) — 同主站 LC 227
 *
 * 【题目本质】
 * 给定一个包含非负整数、+、-、*、/ 和空格的字符串表达式，
 * 计算其结果。整数除法向零截断。不含括号。
 *
 * 核心挑战：处理运算符优先级 (* / 优先于 + -)
 *
 * 【解法总览】
 * 解法1: 栈（延迟加减，即时乘除）— O(n) / O(n) — 面试首选
 * 解法2: 双变量（无栈优化）    — O(n) / O(1) — 空间优化
 * 解法3: vector 替代 stack     — O(n) / O(n) — 求和更方便
 */

// ============================================================
// 解法1: 栈 — 面试首选 ⭐
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 用一个栈来存放"待加的数"。
//   - 遇到 + : 把 num 压栈
//   - 遇到 - : 把 -num 压栈 (把减法变成加负数)
//   - 遇到 * : 弹出栈顶 t，压回 t * num (立即计算)
//   - 遇到 / : 弹出栈顶 t，压回 t / num (立即计算)
// 最后栈中所有数求和就是答案。
//
// 关键设计：
//   - op 记录上一个运算符，初始化为 '+'
//   - 遇到运算符或字符串末尾时，用 op 决定如何处理 num
//   - 空格既不是数字也不是运算符，直接跳过
//
// 示例: "3+2*2"
//   i=0 '3': num=3
//   i=1 '+': op='+' → push(3), stack=[3], op='+'(新), num=0
//   i=2 '2': num=2
//   i=3 '*': op='+' → push(2), stack=[3,2], op='*'(新), num=0
//   i=4 '2': num=2, 末尾触发
//            op='*' → pop(2), push(2*2=4), stack=[3,4]
//   求和: 3+4=7 ✓
//
// 示例: " 3/2 "
//   跳过空格, '3': num=3
//   '/': op='+' → push(3), stack=[3], op='/', num=0
//   跳过空格, '2': num=2
//   跳过空格, 末尾触发
//        op='/' → pop(3), push(3/2=1), stack=[1]
//   求和: 1 ✓
// ============================================================
class Solution1 {
public:
    int calculate(string s) {
        stack<int> stk;
        int num = 0;
        char op = '+'; // 上一个运算符，初始化为 '+'

        for (int i = 0; i < (int)s.size(); i++) {
            // 解析多位数
            if (isdigit(s[i])) {
                num = num * 10 + (s[i] - '0');
            }

            // 遇到运算符或字符串末尾：用上一个运算符处理 num
            // 注意：空格不触发计算！所以条件中有 s[i] != ' '
            if ((!isdigit(s[i]) && s[i] != ' ') || i == (int)s.size() - 1) {
                if (op == '+') {
                    stk.push(num);
                } else if (op == '-') {
                    stk.push(-num);
                } else if (op == '*') {
                    int top = stk.top(); stk.pop();
                    stk.push(top * num);
                } else if (op == '/') {
                    int top = stk.top(); stk.pop();
                    stk.push(top / num); // C++ 整数除法向零截断
                }
                op = s[i]; // 更新运算符
                num = 0;   // 重置数字
            }
        }

        // 栈中所有数求和
        int result = 0;
        while (!stk.empty()) {
            result += stk.top();
            stk.pop();
        }
        return result;
    }
};

// ============================================================
// 解法2: 双变量（无栈，O(1) 空间）
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 栈中的数最终都要求和。我们可以用两个变量替代栈：
//   - result: 已经确定不会再参与乘除的部分和
//   - prevNum: 最近一个可能还要参与乘除的数
//
// 处理逻辑：
//   - 遇到 + : result += prevNum, prevNum = num
//   - 遇到 - : result += prevNum, prevNum = -num
//   - 遇到 * : prevNum *= num (立即计算，不更新 result)
//   - 遇到 / : prevNum /= num (立即计算，不更新 result)
// 最后: result += prevNum
//
// 示例: "3+2*2"
//   '3','+': result += prevNum(0)=0, prevNum=3       → r=0, p=3
//   '2','*': result += prevNum(3)=3, prevNum=2       → r=3, p=2
//   '2',end: prevNum = 2*2 = 4                       → r=3, p=4
//   最终: result + prevNum = 3 + 4 = 7 ✓
//
// 示例: "1-2*3+4"
//   '1','-': r += p(0)=0, p=1       → r=0, p=1
//   '2','*': r += p(1)=1, p=-2      → r=1, p=-2   (注意这里是 -num)
//   '3','+': p = -2*3 = -6          → r=1, p=-6
//   '4',end: r += p(-6)=-5, p=4     → r=-5, p=4
//   最终: -5 + 4 = -1
//   验证: 1-2*3+4 = 1-6+4 = -1 ✓
// ============================================================
class Solution2 {
public:
    int calculate(string s) {
        int result = 0;     // 已确定的部分和
        int prevNum = 0;    // 可能参与乘除的待定数
        int num = 0;        // 当前正在解析的数
        char op = '+';      // 上一个运算符

        for (int i = 0; i < (int)s.size(); i++) {
            if (isdigit(s[i])) {
                num = num * 10 + (s[i] - '0');
            }

            if ((!isdigit(s[i]) && s[i] != ' ') || i == (int)s.size() - 1) {
                if (op == '+') {
                    result += prevNum;  // 之前的 prevNum 已确定
                    prevNum = num;      // 当前数成为新的 prevNum
                } else if (op == '-') {
                    result += prevNum;
                    prevNum = -num;     // 减法：存负数
                } else if (op == '*') {
                    prevNum *= num;     // 乘法：立即和 prevNum 运算
                } else if (op == '/') {
                    prevNum /= num;     // 除法：立即和 prevNum 运算
                }
                op = s[i];
                num = 0;
            }
        }

        return result + prevNum; // 别忘了加上最后的 prevNum
    }
};

// ============================================================
// 解法3: 用 vector 代替 stack（便于求和）
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 逻辑与解法1完全相同，只是用 vector 代替 stack。
// 好处是最后求和可以用 accumulate，代码更简洁。
// 在面试中这是最推荐的写法。
// ============================================================
class Solution3 {
public:
    int calculate(string s) {
        vector<int> nums;
        int num = 0;
        char op = '+';

        for (int i = 0; i < (int)s.size(); i++) {
            if (isdigit(s[i])) {
                num = num * 10 + (s[i] - '0');
            }
            if ((!isdigit(s[i]) && s[i] != ' ') || i == (int)s.size() - 1) {
                if (op == '+') nums.push_back(num);
                else if (op == '-') nums.push_back(-num);
                else if (op == '*') { nums.back() *= num; }
                else if (op == '/') { nums.back() /= num; }
                op = s[i];
                num = 0;
            }
        }

        return accumulate(nums.begin(), nums.end(), 0);
    }
};

/*
 * 易错点总结:
 * 1. 多位数解析: "42" 是一个数, 不是 4 和 2
 *    num = num * 10 + (s[i] - '0') 连续累积
 * 2. 最后一个数字: 字符串末尾没有运算符触发
 *    必须加 i == s.size()-1 条件
 * 3. 空格不是运算符: 不能触发计算
 *    条件中必须有 s[i] != ' '
 * 4. 减号后跟乘除: "-3*2" 时栈中是 -3, 乘 2 得 -6, 符号正确
 * 5. 整数除法方向: C++ 向零截断 (正确)
 *    -7/2 = -3 (不是 -4)
 *
 * 面试追问:
 * Q: 有括号怎么办?
 *    → LC 224/772, 递归处理括号或双栈
 * Q: 能否 O(1) 空间?
 *    → 解法2 双变量, prevNum + result
 * Q: 如何支持一元负号?
 *    → 在字符串开头或左括号后的 '-' 视为负号
 * Q: 如何处理除零?
 *    → 题目保证输入有效, 实际中需要检查
 */

