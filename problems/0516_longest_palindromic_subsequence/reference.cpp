/*
 * LeetCode 516: 最长回文子序列 (Longest Palindromic Subsequence)
 *
 * 【题目本质】
 * 在字符串 s 中找一个最长的子序列（可不连续），使其正读反读一样。
 * 本质是区间 DP：对于 s[i..j]，根据两端字符是否相等做决策，递归缩小区间。
 * 等价视角：s 和 reverse(s) 的最长公共子序列 (LCS)。
 *
 * 【解法总览】
 * 解法1: 暴力递归         — O(2^n) / O(n)   — 展示递归结构
 * 解法2: 记忆化搜索       — O(n²) / O(n²)  — 消除重叠子问题
 * 解法3: 区间 DP (递推)   — O(n²) / O(n²)  — 面试标准解
 * 解法4: 空间优化区间 DP  — O(n²) / O(n)   — 追问空间优化
 * 解法5: LCS 转化         — O(n²) / O(n)   — 展示联想能力
 */

// ============================================================
// 解法1: 暴力递归 — 直接按区间两端做决策
// 时间: O(2^n)  空间: O(n) 递归栈
//
// 【思路】
// 回文的特征是两端对称。对于 s[i..j]:
//   - 如果 s[i] == s[j]，两端都选，答案 = 2 + solve(i+1, j-1)
//   - 如果 s[i] != s[j]，至少去掉一端，答案 = max(solve(i+1,j), solve(i,j-1))
//
// 为什么是指数级？因为每次分裂两个子问题，没有缓存，大量重复计算。
//
// 决策树示意 (s = "bbbab"):
//                      solve(0,4)
//                 s[0]='b'==s[4]='b' → 2 + solve(1,3)
//                                        s[1]='b' != s[3]='a'
//                                       /                   \
//                                solve(2,3)             solve(1,2)
//                            s[2]='b'!=s[3]='a'     s[1]='b'==s[2]='b'
//                            /           \            → 2 + solve(2,1)=0
//                      solve(3,3)   solve(2,2)        = 2
//                         =1           =1
//   最终: dp(0,4) = 2 + max(max(1,1), 2) = 2 + 2 = 4  → "bbbb"
// ============================================================
class Solution1 {
public:
    int longestPalindromeSubseq(string s) {
        return solve(s, 0, s.size() - 1);
    }
private:
    int solve(const string& s, int i, int j) {
        if (i > j) return 0;   // 空区间，没有字符
        if (i == j) return 1;  // 单个字符就是回文
        
        if (s[i] == s[j])
            // 两端相等，都选上，向内缩小区间
            return 2 + solve(s, i + 1, j - 1);
        else
            // 两端不等，尝试去掉左端或右端，取较大值
            return max(solve(s, i + 1, j), solve(s, i, j - 1));
    }
};

// ============================================================
// 解法2: 记忆化搜索 — 暴力递归 + memo 消除重叠子问题
// 时间: O(n²)  空间: O(n²)
//
// 【思路】
// 解法1的瓶颈：同一个 (i, j) 被反复计算。
// 例如 solve(2,3) 可能从 solve(1,4) 和 solve(2,4) 两条路径到达。
// 加 memo[i][j] 缓存：第一次计算后记住结果，后续直接返回。
// 状态总数 O(n²)，每个状态 O(1) 计算 → 总时间 O(n²)。
// ============================================================
class Solution2 {
public:
    int longestPalindromeSubseq(string s) {
        int n = s.size();
        // -1 表示未计算
        vector<vector<int>> memo(n, vector<int>(n, -1));
        return solve(s, 0, n - 1, memo);
    }
private:
    int solve(const string& s, int i, int j, vector<vector<int>>& memo) {
        if (i > j) return 0;
        if (i == j) return 1;
        if (memo[i][j] != -1) return memo[i][j]; // 已缓存，直接返回
        
        if (s[i] == s[j])
            memo[i][j] = 2 + solve(s, i + 1, j - 1, memo);
        else
            memo[i][j] = max(solve(s, i + 1, j), solve(s, i, j - 1, memo));
        
        return memo[i][j];
    }
};

// ============================================================
// 解法3: 区间 DP (递推) — 自底向上填表
// 时间: O(n²)  空间: O(n²)
//
// 【思路】
// 将记忆化搜索翻译成递推：
//   dp[i][j] = s[i..j] 的最长回文子序列长度
//
// 状态转移:
//   s[i] == s[j] → dp[i][j] = dp[i+1][j-1] + 2
//   s[i] != s[j] → dp[i][j] = max(dp[i+1][j], dp[i][j-1])
//
// 依赖关系和填表方向:
//   dp[i][j] 依赖:
//     dp[i+1][j-1]  ← 左下方 (↙)
//     dp[i+1][j]    ← 正下方 (↓)
//     dp[i][j-1]    ← 左方   (←)
//
//   因此 i 从下往上遍历，j 从左往右遍历。
//
// dp 表填充过程 (s = "bbbab"):
//
//        j: 0   1   2   3   4
//   i: 0 [  1   2   3   3   4 ]  ← dp[0][4]=4 就是答案
//      1 [  .   1   2   2   3 ]
//      2 [  .   .   1   1   3 ]
//      3 [  .   .   .   1   1 ]
//      4 [  .   .   .   .   1 ]  ← 对角线 dp[i][i]=1
//
//   . 表示 i>j 的位置，不需要填
// ============================================================
class Solution3 {
public:
    int longestPalindromeSubseq(string s) {
        int n = s.size();
        vector<vector<int>> dp(n, vector<int>(n, 0));
        
        // base case: 每个单字符是长度为 1 的回文
        for (int i = 0; i < n; i++)
            dp[i][i] = 1;
        
        // i 从下往上（因为需要 dp[i+1][...] 已经计算好）
        for (int i = n - 2; i >= 0; i--) {
            // j 从 i+1 往右（因为需要 dp[...][j-1] 已经计算好）
            for (int j = i + 1; j < n; j++) {
                if (s[i] == s[j])
                    // 两端相等：内部回文长度 + 2
                    dp[i][j] = dp[i + 1][j - 1] + 2;
                else
                    // 两端不等：去掉一端，取较大值
                    dp[i][j] = max(dp[i + 1][j], dp[i][j - 1]);
            }
        }
        
        // 整个字符串 s[0..n-1] 的最长回文子序列
        return dp[0][n - 1];
    }
};

// ============================================================
// 解法4: 空间优化区间 DP — 一维滚动数组
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 解法3中 dp[i][j] 只依赖第 i+1 行和第 i 行（当前行）。
// 压缩到一维数组 dp[j]:
//   - dp[j] 在更新前代表 dp[i+1][j]（上一行）
//   - dp[j-1] 在更新后代表 dp[i][j-1]（当前行左边）
//   - 问题：dp[i+1][j-1] 已经被 dp[i][j-1] 覆盖了！
//   - 解决：用 prev 变量在覆盖前保存旧值
//
// 变量对应关系:
//   dp[j]（更新前） = dp[i+1][j]
//   dp[j-1]（更新后）= dp[i][j-1]
//   prev             = dp[i+1][j-1]  （上一轮保存的 temp）
// ============================================================
class Solution4 {
public:
    int longestPalindromeSubseq(string s) {
        int n = s.size();
        vector<int> dp(n, 0);
        
        for (int i = n - 1; i >= 0; i--) {
            dp[i] = 1;     // dp[i][i] = 1
            int prev = 0;  // dp[i+1][j-1]，初始时 j=i+1，所以 dp[i+1][i]=0
            
            for (int j = i + 1; j < n; j++) {
                int temp = dp[j]; // 保存旧值 dp[i+1][j]，下一轮变成 prev
                
                if (s[i] == s[j])
                    dp[j] = prev + 2;           // dp[i+1][j-1] + 2
                else
                    dp[j] = max(dp[j], dp[j - 1]); // max(dp[i+1][j], dp[i][j-1])
                
                prev = temp; // 为下一轮的 j+1 准备：dp[i+1][(j+1)-1] = dp[i+1][j]
            }
        }
        
        return dp[n - 1];
    }
};

// ============================================================
// 解法5: LCS 转化 — s 和 reverse(s) 的最长公共子序列
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 关键洞察：回文 = 正着读和反着读一样。
// 如果从 s 中选出一个子序列 P 是回文的，那么:
//   - P 是 s 的子序列（显然）
//   - P 正反读一样，所以 P 也是 reverse(s) 的子序列
//   - 因此 P 是 s 和 reverse(s) 的公共子序列
// 反之，s 和 reverse(s) 的任意公共子序列也一定是回文。
//
// 所以：最长回文子序列长度 = LCS(s, reverse(s))
//
// 这里直接用一维空间优化的 LCS（复用 LeetCode 1143 的模板）。
//
// dp 填表过程 (s="bbbab", t="babbb"):
//         ""  b  a  b  b  b
//     ""   0  0  0  0  0  0
//      b   0  1  1  1  1  1
//      b   0  1  1  2  2  2
//      b   0  1  1  2  3  3
//      a   0  1  2  2  3  3
//      b   0  1  2  3  3  4  ← 答案 = 4
// ============================================================
class Solution5 {
public:
    int longestPalindromeSubseq(string s) {
        string t(s.rbegin(), s.rend()); // 反转 s
        int n = s.size();
        
        // 一维空间优化的 LCS
        vector<int> dp(n + 1, 0);
        
        for (int i = 1; i <= n; i++) {
            int prev = 0; // dp[i-1][j-1]
            for (int j = 1; j <= n; j++) {
                int temp = dp[j]; // 保存旧 dp[i-1][j]
                
                if (s[i - 1] == t[j - 1])
                    dp[j] = prev + 1;           // 匹配：dp[i-1][j-1] + 1
                else
                    dp[j] = max(dp[j], dp[j - 1]); // 不匹配：max(上, 左)
                
                prev = temp;
            }
        }
        
        return dp[n];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间   | 空间   | 特点                          |
// |-------------|--------|--------|-------------------------------|
// | 暴力递归     | O(2^n) | O(n)   | 展示递归结构，会 TLE          |
// | 记忆化搜索   | O(n²)  | O(n²)  | 递归思路清晰，面试可快速写出   |
// | 区间 DP 递推 | O(n²)  | O(n²)  | 面试标准解，容易讲清楚         |
// | 空间优化     | O(n²)  | O(n)   | 追问优化时给出                 |
// | LCS 转化     | O(n²)  | O(n)   | 展示联想能力，复用 LCS 模板    |
//
// 面试策略：
//   1. 先说解法2或3（标准区间 DP）
//   2. 被追问空间优化 → 解法4
//   3. 被追问其他思路 → 解法5（LCS 转化）
//
// ============================================================
// 【易错点】
//
// 1. 遍历方向写反:
//    ✗ for (int i = 0; i < n; i++) — dp[i+1][...] 还没算
//    ✓ for (int i = n - 2; i >= 0; i--) — 保证依赖已就绪
//
// 2. 空间优化忘记保存 prev:
//    ✗ if (s[i]==s[j]) dp[j] = dp[j-1] + 2;
//      此时 dp[j-1] 是当前行的值（dp[i][j-1]），不是 dp[i+1][j-1]
//    ✓ 用 prev 保存上一轮的 dp[j]，它就是 dp[i+1][j-1]
//
// 3. base case 遗漏:
//    ✗ dp 全初始化为 0，忘记 dp[i][i] = 1
//    ✓ 单字符是长度 1 的回文，必须显式设置
//
// 4. 空间优化中 prev 的初始值:
//    ✗ prev 不初始化或初始化为 1
//    ✓ prev = 0，因为初始时对应 dp[i+1][i] = 0（i > j 的空区间）
//
// 5. 解法5 中字符串下标:
//    ✗ s[i] == t[j]（dp 下标从 1 开始，字符串下标从 0 开始）
//    ✓ s[i-1] == t[j-1]
//
// ============================================================
// 【面试追问】
//
// Q1: 暴力递归的时间复杂度怎么分析？为什么是指数级？
//   → solve(i,j) 分裂成两个子问题 solve(i+1,j) 和 solve(i,j-1)，
//     类似斐波那契的递归树，不加 memo 就是 O(2^n)。
//     状态空间只有 O(n²) 个 (i,j) 对，加 memo 立刻降到 O(n²)。
//
// Q2: 能否将空间从 O(n²) 优化到 O(n)？具体怎么做？
//   → dp[i][j] 只依赖第 i+1 行和第 i 行。用一维数组 + prev 变量
//     保存被覆盖的 dp[i+1][j-1]。见解法4。
//
// Q3: 如果要输出具体的最长回文子序列（不仅是长度），怎么做？
//   → 从 dp[0][n-1] 回溯：
//     如果 s[i]==s[j]，把 s[i] 加到结果前半部分，走到 (i+1, j-1)；
//     否则走到 dp 较大的方向。最后拼接前半部分 + 中间字符(如果有) + 反转前半部分。
//
// Q4: 这道题和最长回文子串 (LeetCode 5) 有什么区别？
//   → 子串要求连续，可以用中心扩展 O(n²) 或 Manacher O(n)。
//     子序列不要求连续，必须用 DP 记录不连续选择的状态。
//
// Q5: 和 LeetCode 1216（验证回文串 III）是什么关系？
//   → 1216 问能否删最多 k 个字符使之回文。
//     等价于 n - LPS(s) <= k，直接复用本题结果。
// ============================================================
