/*
 * LeetCode 830: Positions of Large Groups (较大分组的位置)
 *
 * 【题目本质】
 * 在字符串中找所有连续相同字符组成的分组，返回长度 >= 3 的分组区间。
 * 经典的线性扫描分组问题。
 *
 * 【解法总览】
 * 解法1: 双指针分组          — O(n) / O(1) — 面试首选 ⭐
 * 解法2: 单指针 + 起点追踪   — O(n) / O(1) — 等价写法
 */

// ============================================================
// 解法1: 双指针分组 — 面试首选 ⭐
// 时间: O(n)  空间: O(1)（不计输出）
//
// 【思路】
// 用 i 标记分组起点，j 向右扩展直到遇到不同字符。
// 分组为 [i, j-1]，长度为 j - i。
// 如果长度 >= 3，加入结果。然后 i = j 跳到下一组。
//
// 示例 "abcdddeeeeaabbbcd":
//
// i=0:  j扫到1, "a" 长度1 → 跳过
// i=1:  j扫到2, "b" 长度1 → 跳过
// i=2:  j扫到3, "c" 长度1 → 跳过
// i=3:  j扫到6, "ddd" 长度3 → 加入 [3,5] ✓
// i=6:  j扫到10, "eeee" 长度4 → 加入 [6,9] ✓
// i=10: j扫到12, "aa" 长度2 → 跳过
// i=12: j扫到15, "bbb" 长度3 → 加入 [12,14] ✓
// i=15: j扫到16, "c" 长度1 → 跳过
// i=16: j扫到17, "d" 长度1 → 跳过
// 结果: [[3,5], [6,9], [12,14]]
// ============================================================
class Solution1 {
public:
    vector<vector<int>> largeGroupPositions(string s) {
        vector<vector<int>> result;
        int n = s.size();
        int i = 0;

        while (i < n) {
            // j 从 i 开始，向右扩展到第一个不同字符
            int j = i;
            while (j < n && s[j] == s[i]) {
                j++;
            }

            // [i, j-1] 是一个分组，长度 = j - i
            if (j - i >= 3) {
                result.push_back({i, j - 1});
            }

            // 跳到下一个分组的起点
            i = j;
        }

        return result;
    }
};

// ============================================================
// 解法2: 单指针 + 起点追踪
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 维护当前组的起始位置 start。逐个遍历字符，
// 当 s[i] != s[i-1] 或到达末尾时，说明一组结束：
//   分组为 [start, i-1]，长度 i - start。
// 然后更新 start = i。
//
// 技巧：循环到 i = n（超出字符串一位），
// 这样最后一组也能被统一处理，不需要循环后特判。
//
// 示例 "abbxxxxzzy":
//
// start=0, i=1: s[1]='b' != s[0]='a' → 组[0,0]长度1, skip. start=1
// start=1, i=2: s[2]='x' != s[1]='b' → 组[1,1]长度1, skip. start=2
// ... (i=3,4,5,6 都是 'x'，不触发)
// start=2, i=6: s[6]='x' == s[5]='x' → 不触发
// start=2, i=7: s[7]='z' != s[6]='x' → 组[3,6]长度4, add [3,6] ✓. start=7
//   (wait, 实际 start=2 后面 s[2]='x'，所以组是 [2,6]?
//    不对，s="abbxxxxzzy", s[2]='x' 没错，但 s[1]='b'，所以:
//    start=0 → s[1]!=s[0] → 组[0,0], start=1
//    start=1 → s[2]!=s[1] → 组[1,1], start=2
//    s[2..6] 都是 'x'，在 i=7 时触发 → 组[2,6]?
//    但题目说输出是 [3,6]，原来 s = "abbxxxxzzy"
//    s[0]='a', s[1]='b', s[2]='b', s[3]='x', ...
//    所以 start=1 → s[2]='b'==s[1]='b' → 不触发
//    start=1, i=3 → s[3]='x' != s[2]='b' → 组[1,2]长度2, skip. start=3
//    start=3, i=7 → s[7]='z' != s[6]='x' → 组[3,6]长度4, add ✓)
// ============================================================
class Solution2 {
public:
    vector<vector<int>> largeGroupPositions(string s) {
        vector<vector<int>> result;
        int n = s.size();
        int start = 0;

        for (int i = 1; i <= n; i++) {
            // 到达末尾 或 字符发生变化 → 一组结束
            if (i == n || s[i] != s[i - 1]) {
                // 分组 [start, i-1]，长度 = i - start
                if (i - start >= 3) {
                    result.push_back({start, i - 1});
                }
                start = i; // 下一组从 i 开始
            }
        }

        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间 | 空间 | 优缺点 |
// |------|------|------|--------|
// | 双指针 | O(n) | O(1) | 逻辑清晰，容易理解 |
// | 单指针 | O(n) | O(1) | 代码更短，但需要 i<=n 技巧 |
//
// 两种写法本质相同，面试中任选一种即可。
// 双指针版更直观（"找到一组"的语义明确），推荐首选。
//
// 【易错点】
//
// 1. 分组右端点是 j-1 而不是 j:
//    ✗ result.push_back({i, j});  // j 已经指向下一组的第一个字符
//    ✓ result.push_back({i, j - 1});  // 分组的最后一个字符在 j-1
//
// 2. 忘记处理最后一组:
//    ✗ for (i = 1; i < n; i++) 内部检查 s[i]!=s[i-1]
//       → 最后一组不会触发（因为没有"下一个不同字符"）
//    ✓ for (i = 1; i <= n; i++) 或循环后额外检查
//
// 3. 阈值理解错误:
//    ✗ if (j - i > 3)  // 严格大于3，漏掉长度恰好为3的组
//    ✓ if (j - i >= 3) // 大于等于3
//
// 4. 返回类型错误:
//    ✗ 返回 vector<pair<int,int>>
//    ✓ 返回 vector<vector<int>>（题目要求的格式）
//
// 【面试追问】
//
// Q1: "如果输入是字符流（streaming），怎么处理？"
//   → 维护状态：当前字符 curChar、组起点 start、当前位置 pos。
//     每来一个字符：如果和 curChar 相同，pos++；
//     如果不同，检查 pos - start >= 3 则输出，然后重置。
//
// Q2: "如果要求返回最大的分组呢？"
//   → 在遍历时维护 maxLen 和对应的 [start, end]。
//
// Q3: "能否用正则表达式？"
//   → 可以：正则 (.)\1{2,} 匹配连续相同字符 ≥ 3 次。
//     但面试中一般期望手写算法。
// ============================================================
