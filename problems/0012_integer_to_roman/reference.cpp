/*
 * LeetCode 12: Integer to Roman (整数转罗马数字)
 * 
 * 【题目本质】
 * 把一个整数按照罗马数字的规则"找零"——从最大面值开始，贪心地减去面值并拼接对应符号。
 * 关键洞察：把6个减法形式(4,9,40,90,400,900)也当作独立面额，统一处理。
 *
 * 【解法总览】
 * 解法1: 贪心映射表   — O(1) / O(1) — 面试首选，思路清晰
 * 解法2: 逐位查表     — O(1) / O(1) — 代码最短，纯硬编码
 * 解法3: 贪心(除法优化) — O(1) / O(1) — 解法1的微调，用除法替代while
 */

// ============================================================
// 解法1: 贪心映射表 — 面试首选
// 时间: O(1)  空间: O(1)
// （num ≤ 3999，循环总次数有上界约15次，所以是常数时间）
//
// 【思路】
// 罗马数字本质是一种"找零"问题：
//   手里有 13 种面额：1000, 900, 500, 400, 100, 90, 50, 40, 10, 9, 5, 4, 1
//   从最大面额开始，尽可能多用，然后用下一个面额处理剩余。
//
// 为什么把 900/400/90/40/9/4 也当面额？
//   因为这些是"减法形式"，如果不把它们加入表中，就需要额外的 if-else
//   判断当前数位是否以4或9开头。加入表后，贪心逻辑自动处理了减法形式。
//
// 贪心过程示例 (num = 1994):
//   num=1994, 面值1000: 用1次 → "M",    剩余994
//   num=994,  面值900:  用1次 → "CM",   剩余94
//   num=94,   面值90:   用1次 → "XC",   剩余4
//   num=4,    面值4:    用1次 → "IV",   剩余0
//   结果: "MCMXCIV" ✓
// ============================================================
class Solution1 {
public:
    string intToRoman(int num) {
        // 13个面值从大到小排列（必须从大到小，否则贪心不正确）
        int values[]    = {1000, 900, 500, 400, 100, 90, 50, 40, 10, 9, 5, 4, 1};
        string syms[]   = {"M","CM","D","CD","C","XC","L","XL","X","IX","V","IV","I"};
        
        string result;
        for (int i = 0; i < 13; i++) {
            // 贪心：当前面值能用几次就用几次
            // 为什么用 while 而不是 if？因为同一面值可能用多次（如 3000 = M+M+M）
            while (num >= values[i]) {
                result += syms[i];
                num -= values[i];
            }
            // 小优化：num 已经为 0 就可以提前退出
            if (num == 0) break;
        }
        return result;
    }
};

// ============================================================
// 解法2: 逐位查表（硬编码）
// 时间: O(1)  空间: O(1)
//
// 【思路】
// 换一个角度：num 最多4位数，每个数位的0-9对应的罗马写法是固定的。
// 千位只有 0~3（因为 num ≤ 3999），百/十/个位各有 0~9。
// 直接为每个数位建一张查表，取出对应位的数字查表拼接。
//
// 每个数位的模式（以个位为例，用 I/V/X 三个字符）:
//   0: ""     1: "I"    2: "II"   3: "III"
//   4: "IV"   5: "V"    6: "VI"   7: "VII"
//   8: "VIII" 9: "IX"
// 十位用 X/L/C, 百位用 C/D/M, 千位只有 M/MM/MMM
//
// 优点：代码极简，没有循环。
// 缺点：硬编码量大，面试中可能被追问"如何避免硬编码"。
// ============================================================
class Solution2 {
public:
    string intToRoman(int num) {
        // 千位查表 (num ≤ 3999，所以千位最多为3)
        string thousands[] = {"", "M", "MM", "MMM"};
        // 百位查表 (0~9)
        string hundreds[]  = {"", "C", "CC", "CCC", "CD", "D", "DC", "DCC", "DCCC", "CM"};
        // 十位查表 (0~9)
        string tens[]      = {"", "X", "XX", "XXX", "XL", "L", "LX", "LXX", "LXXX", "XC"};
        // 个位查表 (0~9)
        string ones[]      = {"", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX"};
        
        // 分别取千/百/十/个位，查表拼接
        // 注意：百位要先 %1000 去掉千位，十位要先 %100 去掉百位
        return thousands[num / 1000]
             + hundreds[(num % 1000) / 100]
             + tens[(num % 100) / 10]
             + ones[num % 10];
    }
};

// ============================================================
// 解法3: 贪心（除法优化版）— 解法1的微调
// 时间: O(1)  空间: O(1)
//
// 【思路】
// 与解法1相同，但用除法代替 while 循环，更清晰地表达"用几次"。
// count = num / values[i] 就是当前面值使用的次数，
// 然后用循环拼接 count 次对应符号。
//
// 本质上和解法1完全等价，只是代码风格不同。
// ============================================================
class Solution3 {
public:
    string intToRoman(int num) {
        int values[]    = {1000, 900, 500, 400, 100, 90, 50, 40, 10, 9, 5, 4, 1};
        string syms[]   = {"M","CM","D","CD","C","XC","L","XL","X","IX","V","IV","I"};
        
        string result;
        for (int i = 0; i < 13; i++) {
            int count = num / values[i];   // 当前面值使用几次
            num %= values[i];              // 取余得到剩余值
            // 拼接 count 次当前符号
            while (count-- > 0) {
                result += syms[i];
            }
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 解法1(贪心while) | 解法2(逐位查表) | 解法3(贪心除法) |
// |-----------|-----------------|----------------|----------------|
// | 核心思想   | 贪心找零         | 每位独立查表     | 贪心找零        |
// | 代码量     | ~10行           | ~8行(表很长)     | ~10行          |
// | 可扩展性   | 高(加面值即可)   | 低(需重写表)     | 高             |
// | 面试推荐度 | ⭐⭐⭐           | ⭐⭐             | ⭐⭐⭐          |
//
// 面试首选解法1或解法3（贪心思路），解法2作为补充提及。
//
// 【易错点】
// 1. 面值表从小到大排列 → 贪心先用小面额，结果全是 "I"
//    ✗ int values[] = {1, 4, 5, 9, 10, ...};
//    ✓ int values[] = {1000, 900, 500, 400, ...}; // 必须从大到小
//
// 2. 遗漏减法形式的6个面值（900,400,90,40,9,4）
//    ✗ 只写7个基本符号 → 无法处理 4(IV), 9(IX) 等
//    ✓ 写满13个面值，包含所有减法形式
//
// 3. 解法2中取百位时忘记先取模
//    ✗ hundreds[num / 100]         // num=3749时，3749/100=37，越界！
//    ✓ hundreds[(num % 1000) / 100] // 先去掉千位：749/100=7 ✓
//
// 4. syms 和 values 数组长度不一致或顺序不对应
//    values[i] 和 syms[i] 必须严格一一对应
//
// 【面试追问】
// Q1(基础): "贪心为什么正确？会不会出现'凑不出'的情况？"
//     → 罗马数字规则保证了面值之间的关系：每种面值的最大使用次数（3次或1次）
//       恰好由下一个面值覆盖。比如 4 个 I 用 IV 代替，不会出现需要4个I但没有IV的情况。
//       这和纸币找零类似，面额设计合理时贪心总是对的。
//
// Q2(逆问题): "反过来，罗马数字转整数（LC 13）怎么做？"
//     → 从左到右扫描，如果当前字符代表的值 < 右边字符的值（如 I 在 V 前），
//       则减去当前值；否则加上当前值。一次遍历 O(n)。
//
// Q3(变体): "如果要求不用映射表，能否用纯数学方法？"
//     → 可以。对每个数位 d（0-9），用 one/five/ten 三个字符描述：
//       0-3: one×d, 4: one+five, 5: five, 6-8: five+one×(d-5), 9: one+ten
//       每个数位用不同的字符组(I/V/X, X/L/C, C/D/M, M/-/-)，
//       但代码较长且不如映射表直观。
// ============================================================
