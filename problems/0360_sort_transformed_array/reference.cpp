/*
 * LeetCode 360: Sort Transformed Array (有序转化数组)
 *
 * 【题目本质】
 * 对有序数组每个元素施加二次函数变换后，利用抛物线的数学性质，
 * 用双指针在 O(n) 时间内得到有序结果。
 *
 * 【解法总览】
 * 解法1: 暴力计算+排序 — O(n log n) / O(n) — 最直觉
 * 解法2: 双指针(抛物线性质) — O(n) / O(n) — 最优，面试首选
 */

// ============================================================
// 解法1: 暴力计算 + 排序
// 时间: O(n log n)  空间: O(n)（排序开销）
//
// 【思路】
// 最朴素的做法：对每个 nums[i] 计算 f(nums[i])，存入数组，排序。
// 完全没有利用输入已排序的条件，但对于 n ≤ 200 绰绰有余。
// 瓶颈：排序是 O(n log n)，能否利用输入有序性做到 O(n)？
// ============================================================
class Solution1 {
public:
    vector<int> sortTransformedArray(vector<int>& nums, int a, int b, int c) {
        int n = nums.size();
        vector<int> result(n);
        for (int i = 0; i < n; i++) {
            int x = nums[i];
            result[i] = a * x * x + b * x + c;
        }
        sort(result.begin(), result.end());
        return result;
    }
};

// ============================================================
// 解法2: 双指针（利用抛物线性质）⭐ 面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 二次函数 f(x) = ax² + bx + c 的图像是抛物线，对称轴 x = -b/(2a)。
//
// 关键数学性质：
//   a > 0（开口向上）: 离对称轴越远，f(x) 越大 → 两端大、中间小
//   a < 0（开口向下）: 离对称轴越远，f(x) 越小 → 两端小、中间大
//   a = 0（线性函数）: f(x) = bx + c，归入 a >= 0 分支即可
//
// 可视化 (a > 0, 开口向上):
//
//   f(x)
//    |         *           *
//    |       *               *       ← 两端最大
//    |      *                 *
//    |     *                   *
//    |      *       *                ← 中间最小（靠近对称轴）
//    +------|------|------|------→ x
//         nums[0]  axis  nums[n-1]
//
//   输入:  nums = [-4, -2, 2, 4], 对称轴 x = -1.5
//   f(x):         [ 9,   3, 15, 33]
//
//   双指针过程 (a=1, 从结果末尾填):
//   left=0, right=3: f(-4)=9 vs f(4)=33 → 33大 → result[3]=33, right--
//   left=0, right=2: f(-4)=9 vs f(2)=15 → 15大 → result[2]=15, right--
//   left=0, right=1: f(-4)=9 vs f(-2)=3 →  9大 → result[1]=9,  left++
//   left=1, right=1: f(-2)=3            →       → result[0]=3,  done
//   结果: [3, 9, 15, 33] ✓
//
// 可视化 (a < 0, 开口向下):
//
//   f(x)
//    |          *   *   *
//    |        *           *          ← 中间最大（靠近对称轴）
//    |      *               *
//    |    *                   *      ← 两端最小
//    +------|------|------|------→ x
//
//   此时双指针从结果开头填，每次取较小的。
//
// 为什么双指针正确？
//   输入有序 → 两端是离对称轴最远的点 → 它们的 f(x) 一定是极值
//   取走一个后，剩余部分的两端仍然是剩余中离对称轴最远的
//   归纳法：每一步取到的都是剩余中的极值，所以最终结果有序
// ============================================================
class Solution2 {
public:
    vector<int> sortTransformedArray(vector<int>& nums, int a, int b, int c) {
        int n = nums.size();
        vector<int> result(n);
        int left = 0, right = n - 1;
        
        // a >= 0: 两端f(x)大 → 从结果末尾往前填（先确定最大值）
        // a <  0: 两端f(x)小 → 从结果开头往后填（先确定最小值）
        int idx = (a >= 0) ? n - 1 : 0;
        
        // left <= right 确保所有元素都被处理（等号不能漏！）
        while (left <= right) {
            int fL = f(nums[left], a, b, c);
            int fR = f(nums[right], a, b, c);
            
            if (a >= 0) {
                // 开口向上（或线性）：两端大，取较大者放末尾
                if (fL >= fR) {
                    result[idx--] = fL;
                    left++;
                } else {
                    result[idx--] = fR;
                    right--;
                }
            } else {
                // 开口向下：两端小，取较小者放开头
                if (fL <= fR) {
                    result[idx++] = fL;
                    left++;
                } else {
                    result[idx++] = fR;
                    right--;
                }
            }
        }
        return result;
    }
    
private:
    // 计算二次函数值 f(x) = ax² + bx + c
    int f(int x, int a, int b, int c) {
        return a * x * x + b * x + c;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度           | 解法1: 暴力排序     | 解法2: 双指针       |
// |----------------|---------------------|---------------------|
// | 时间           | O(n log n)          | O(n)                |
// | 空间           | O(n)                | O(n)                |
// | 利用输入有序   | ✗                   | ✓                   |
// | 利用数学性质   | ✗                   | ✓（抛物线对称性）   |
// | 代码复杂度     | 极简                | 中等                |
//
// 面试中：先说暴力 O(n log n)，再分析二次函数性质推导出 O(n) 双指针。
//
// ============================================================
// 【易错点】
//
// 1. while(left < right) 漏了等号
//    ✗ while (left < right) → left==right 时退出，漏掉最后一个元素
//    ✓ while (left <= right) → 确保所有 n 个元素都被处理
//
// 2. idx 初始值和方向搞反
//    ✗ a > 0 时 idx=0, idx++ → 最大值填到开头，结果是降序
//    ✓ a > 0 时 idx=n-1, idx-- → 最大值填到末尾，结果是升序
//
// 3. a=0 时忘记处理
//    ✗ 只写 a>0 和 a<0 两个分支，a=0 时没有进入任何分支
//    ✓ 用 a>=0 和 a<0 分支，a=0 自然归入 a>=0（线性函数，双指针逻辑正确）
//
// 4. fL >= fR 中等号归属
//    两端相等时放哪边都行（另一端下一轮会被处理），但等号归属要一致，
//    不能 a>0 时写 fL > fR 而忘记处理 fL == fR 的情况（会导致某个元素被跳过）
//
// ============================================================
// 【面试追问】
//
// Q1: 暴力解复杂度？瓶颈在哪？
// → O(n log n)，瓶颈在排序。输入有序没被利用。
//
// Q2: 为什么双指针能保证正确？
// → 抛物线性质：a>0时离对称轴越远f(x)越大，两端一定是全局最大。
//    每次取走一个最大后，新的两端仍是剩余中最远的点，归纳成立。
//
// Q3: 如果是三次函数 f(x)=ax³+bx²+cx+d，还能 O(n) 吗？
// → 三次函数可能有两个极值点（一个极大一个极小），不再是简单的
//    "两端大中间小"模式。需要找到极值点把数组分成最多3个单调段，
//    然后做3路归并，仍然是 O(n)，但实现复杂度更高。
//
// ============================================================
