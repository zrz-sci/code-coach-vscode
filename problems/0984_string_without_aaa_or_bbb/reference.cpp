/*
 * LeetCode 984: 不含 AAA 或 BBB 的字符串 (String Without AAA or BBB)
 *
 * 【题目本质】
 * 构造长度 a+b 的字符串，包含恰好 a 个 'a' 和 b 个 'b'，
 * 且不含子串 "aaa" 或 "bbb"。贪心：优先放多的字符。
 *
 * 【解法总览】
 * 解法1: 贪心（块构造）    — O(a+b) / O(a+b) — 面试首选 ⭐
 * 解法2: 贪心（逐字符构造）— O(a+b) / O(a+b) — 逻辑直观
 */

// ============================================================
// 解法1: 贪心（块构造） — 面试首选 ⭐
// 时间: O(a+b)  空间: O(a+b)
//
// 【思路】
// 为什么贪心有效？
// 1. 两种字符，约束是不能连续三个相同
// 2. 如果 a > b，需要更快地消耗 'a'，所以每轮放两个 'a' + 一个 'b'
// 3. 如果 a == b，交替放 "ab" 即可
// 4. 对称处理 b > a 的情况
//
// 示例: a=5, b=2
//   轮1: a>b → "aa", a=3; b>0 → "b", b=1  → "aab"
//   轮2: a>b → "aa", a=1; b>0 → "b", b=0  → "aab" + "aab"
//   轮3: a>b → "a",  a=0              → "aab" + "aab" + "a"
//   结果: "aabaaba" ✓ (无 "aaa" 或 "bbb")
//
// 示例: a=1, b=2
//   轮1: b>a → "bb", b=0; a>0 → "a", a=0  → "bba"
//   结果: "bba" ✓
//
// 示例: a=4, b=1
//   轮1: a>b → "aa", a=2; b>0 → "b", b=0  → "aab"
//   轮2: a>b → "aa", a=0                    → "aab" + "aa"
//   结果: "aabaa" ✓
// ============================================================
class Solution1 {
public:
    string strWithout3a3b(int a, int b) {
        string result;
        while (a > 0 || b > 0) {
            if (a > b) {
                // a 更多：放 2 个 a（或 1 个如果只剩 1）
                int takeA = min(2, a);
                result += string(takeA, 'a');
                a -= takeA;
                // 穿插 1 个 b（如果还有）
                if (b > 0) {
                    result += 'b';
                    b--;
                }
            } else if (b > a) {
                // b 更多：对称处理
                int takeB = min(2, b);
                result += string(takeB, 'b');
                b -= takeB;
                if (a > 0) {
                    result += 'a';
                    a--;
                }
            } else {
                // a == b：各放一个，交替进行
                // 不会产生三连因为每次只放一个
                if (a > 0) { result += 'a'; a--; }
                if (b > 0) { result += 'b'; b--; }
            }
        }
        return result;
    }
};

// ============================================================
// 解法2: 贪心（逐字符构造）
// 时间: O(a+b)  空间: O(a+b)
//
// 【思路】
// 每步只放一个字符，决策逻辑:
// 1. 如果末尾已有 2 个连续 'a' → 必须放 'b'
// 2. 如果末尾已有 2 个连续 'b' → 必须放 'a'
// 3. 否则优先放剩余数量更多的字符
//
// 为什么优先放多的？
// 防止多的字符堆积到最后，被迫连续放三个以上。
// 优先消耗多的字符，让两者趋于平衡。
//
// 示例: a=4, b=1
//   步1: 末尾无 → a>=b → 放'a', a=3, "a"
//   步2: 末尾1个a → a>=b → 放'a', a=2, "aa"
//   步3: 末尾2个a → 必须放'b', b=0, "aab"
//   步4: 末尾1个b → a>=b → 放'a', a=1, "aaba"
//   步5: 末尾1个a → a>=b → 放'a', a=0, "aabaa"
//   结果: "aabaa" ✓
//
// 示例: a=2, b=5
//   步1: 末尾无 → b>a → 放'b', b=4, "b"
//   步2: 末尾1个b → b>a → 放'b', b=3, "bb"
//   步3: 末尾2个b → 必须放'a', a=1, "bba"
//   步4: 末尾1个a → b>a → 放'b', b=2, "bbab"
//   步5: 末尾1个b → b>a → 放'b', b=1, "bbabb"
//   步6: 末尾2个b → 必须放'a', a=0, "bbabba"
//   步7: 末尾1个a → b>0 → 放'b', b=0, "bbabbab"
//   结果: "bbabbab" ✓
// ============================================================
class Solution2 {
public:
    string strWithout3a3b(int a, int b) {
        string result;
        while (a > 0 || b > 0) {
            int n = result.size();
            // 检查末尾两个字符是否相同
            bool lastTwoA = (n >= 2 && result[n-1] == 'a' && result[n-2] == 'a');
            bool lastTwoB = (n >= 2 && result[n-1] == 'b' && result[n-2] == 'b');

            if (lastTwoA) {
                // 已有两个连续 'a'，必须放 'b'
                result += 'b';
                b--;
            } else if (lastTwoB) {
                // 已有两个连续 'b'，必须放 'a'
                result += 'a';
                a--;
            } else if (a >= b) {
                // 两者都安全，优先放多的
                result += 'a';
                a--;
            } else {
                result += 'b';
                b--;
            }
        }
        return result;
    }
};

// ============================================================
// 解法1的简化写法（利用对称性）
// 通过始终让 a >= b 来避免 if-else 分支
// ============================================================
class Solution3 {
public:
    string strWithout3a3b(int a, int b) {
        string result;
        // 用变量追踪 'a' 和 'b' 的实际字符
        char ca = 'a', cb = 'b';
        // 保证 a >= b，如果不是则交换
        if (a < b) {
            swap(a, b);
            swap(ca, cb);
        }

        while (a > 0 || b > 0) {
            if (a > b) {
                int take = min(2, a);
                result += string(take, ca);
                a -= take;
                if (b > 0) {
                    result += cb;
                    b--;
                }
            } else {
                // a == b 时各放一个
                if (a > 0) { result += ca; a--; }
                if (b > 0) { result += cb; b--; }
            }
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间 | 空间 | 代码量 | 推荐场景 |
// |------|------|------|--------|----------|
// | 块构造 | O(a+b) | O(a+b) | 中等 | ⭐面试首选 |
// | 逐字符 | O(a+b) | O(a+b) | 中等 | 逻辑更直观 |
// | 简化版 | O(a+b) | O(a+b) | 较少 | 追求简洁 |
//
// 【易错点】
//
// 1. a == b 时多放了两个导致三连
//    ✗ a==b 时按 a>b 逻辑放 "aa" → 如果上一轮末尾也是 'a'，产生 "aaa"
//    ✓ a==b 时各放一个交替进行
//
// 2. 块构造时忘记 min(2, a)
//    ✗ 直接放两个 'a' → 如果 a=1 会把 a 减到 -1
//    ✓ int take = min(2, a); result += string(take, 'a');
//
// 3. 逐字符构造时 a==0 但被迫放 'a'
//    ✗ 末尾两个 'b' 且 a==0 → 放 'a' 会让 a=-1
//    ✓ 题目保证有解，所以这种情况不会出现
//       但防御性编程可以在前面加 if (a == 0) 检查
//
// 4. 构造结果字符数量不对
//    ✗ 块构造中多放或少放了字符
//    ✓ 循环条件 while (a > 0 || b > 0) 保证所有字符都被用完
//
// 【面试追问】
//
// Q1: 贪心的正确性证明？
// → 每轮多的字符放 ≤ 2 个后立刻穿插少的 1 个，
//    任何位置连续相同字符 ≤ 2。数学归纳: 每轮结束后
//    末尾至多 2 个相同字符，下一轮开始放另一种或放 1 个。
//
// Q2: 什么输入下无解？
// → 题目保证有解。实际上只要 a ≥ 0 且 b ≥ 0 就总能构造
//    （空串也是合法的当 a=b=0）。
//
// Q3: 扩展到三种字符？
// → 变成 LC 1405 最长快乐字符串。用堆维护三种字符的剩余计数，
//    每次贪心选最多的（检查末尾约束），O((a+b+c) * log 3) = O(n)。
//
// Q4: 如果要求输出所有合法字符串？
// → 回溯搜索：每步尝试放 'a' 或 'b'（如果不违反约束），
//    递归到 a=b=0 时记录结果。时间指数级，适合小输入。
// ============================================================
