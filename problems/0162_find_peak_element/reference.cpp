/*
 * LeetCode 162: 寻找峰值 (Find Peak Element)
 *
 * 【题目本质】
 * 在两端为 -∞、相邻元素不等的数组中，找到任意一个"山顶"（比左右邻居都大的元素）。
 * 关键约束：要求 O(log n)，暗示二分查找。
 *
 * 【为什么一定存在峰值？】
 * nums[-1] = nums[n] = -∞，数组从 -∞ 开始到 -∞ 结束。
 * 如果整个数组单调递增，最后一个元素就是峰值（右边是 -∞）。
 * 如果整个数组单调递减，第一个元素就是峰值（左边是 -∞）。
 * 否则某处"上升然后下降"，转折点就是峰值。
 *
 * 【解法总览】
 * 解法1: 线性扫描     — O(n)     / O(1) — 最直觉，找第一个下降点
 * 解法2: 二分查找     — O(log n) / O(1) — 面试首选，朝更高方向收缩
 */

// ============================================================
// 解法1: 线性扫描 — 找第一个"开始下降"的位置
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 因为 nums[-1] = -∞，从数组左端"进入"时相当于在上坡。
// 沿着数组从左往右走，一直在上坡就继续走。
// 第一次遇到 nums[i] > nums[i+1]（开始下坡），i 就是峰值。
//   - 在 i 之前一直在上坡，所以 nums[i-1] < nums[i]（或 i=0 时左边是 -∞）
//   - nums[i] > nums[i+1]，满足峰值定义
// 如果从头到尾都在上坡，最后一个元素就是峰值（右边是 -∞）。
//
// 示例: nums = [1, 2, 1, 3, 5, 6, 4]
//   i=0: nums[0]=1 < nums[1]=2 → 上坡，继续
//   i=1: nums[1]=2 > nums[2]=1 → 下坡！返回 1
// ============================================================
class Solution1 {
public:
    int findPeakElement(vector<int>& nums) {
        int n = nums.size();
        for (int i = 0; i < n - 1; i++) {
            // 找到第一个"下坡"的位置：它就是峰值
            // 因为从左端(-∞)到这里一直在上坡
            if (nums[i] > nums[i + 1]) {
                return i;
            }
        }
        // 整个数组单调递增 → 最后一个元素是峰值
        return n - 1;
    }
};

// ============================================================
// 解法2: 二分查找 — 朝更高的方向收缩搜索区间
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 解法1 是 O(n)，题目要求 O(log n)，自然想到二分。
// 但数组没有排序，怎么二分？
//
// 关键洞察：二分不需要有序，只需要"每次能确定性地排除一半"。
//
// 站在 mid 处，看 nums[mid] 和 nums[mid+1] 的关系：
//
// 情况1: nums[mid] < nums[mid+1]  — mid 到 mid+1 在"上坡"
//   从 mid+1 出发往右走，要么一直上坡直到末尾（末尾元素是峰值，因为右边是-∞），
//   要么中途开始下坡（下坡前那个点是峰值）。
//   → 右半边 [mid+1, right] 一定有峰值
//   → left = mid + 1  （mid 自己不是峰值，因为右邻居比它大）
//
// 情况2: nums[mid] > nums[mid+1]  — mid 到 mid+1 在"下坡"
//   同理，左半边 [left, mid] 一定有峰值。
//   → right = mid  （mid 可能就是峰值，不能排除）
//
// 最终 left == right 时，该点就是峰值。
//
// 【搜索空间收缩过程】
// 示例: nums = [1, 2, 1, 3, 5, 6, 4]
//                0  1  2  3  4  5  6
//
// Round1: left=0, right=6, mid=3
//         nums[3]=3 < nums[4]=5 → 上坡 → left=4
//         搜索空间: [4, 5, 6]
//                    ↓  ↓  ↓
//                    5  6  4
//
// Round2: left=4, right=6, mid=5
//         nums[5]=6 > nums[6]=4 → 下坡 → right=5
//         搜索空间: [4, 5]
//                    ↓  ↓
//                    5  6
//
// Round3: left=4, right=5, mid=4
//         nums[4]=5 < nums[5]=6 → 上坡 → left=5
//         搜索空间: [5]
//
// left == right == 5 → 返回 5 (nums[5]=6 是峰值 ✓)
// ============================================================
class Solution2 {
public:
    int findPeakElement(vector<int>& nums) {
        int left = 0, right = nums.size() - 1;
        
        // 用 left < right：区间收缩到一个点时结束
        // 不用 left <= right：因为当 left == right 时答案已经确定
        while (left < right) {
            int mid = left + (right - left) / 2;
            
            if (nums[mid] < nums[mid + 1]) {
                // mid 处在上坡：右边一定有峰值
                // mid 本身不可能是峰值（右邻居比它大），安全排除
                left = mid + 1;
            } else {
                // mid 处在下坡（或是局部最大）：左边（含 mid）一定有峰值
                // mid 可能就是峰值，所以 right = mid，不能 mid - 1
                right = mid;
            }
        }
        
        // left == right，这个位置就是峰值
        return left;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 时间     | 空间 | 核心思想           | 面试价值 |
// |----------|----------|------|--------------------|----------|
// | 线性扫描 | O(n)     | O(1) | 找第一个下降点     | 展示理解 |
// | 二分查找 | O(log n) | O(1) | 朝更高方向二分收缩 | 必须掌握 |
//
// 面试策略：先说线性扫描展示理解，再给二分展示算法功底。
//
// 【易错点】
// 1. ✗ right = mid - 1
//    ✓ right = mid
//    原因：nums[mid] > nums[mid+1] 时，mid 本身可能是峰值。
//    如果写 mid-1，测试 [1,2] 会返回 0 而不是 1。
//
// 2. ✗ 比较 nums[mid] 和 nums[mid-1]
//    ✓ 比较 nums[mid] 和 nums[mid+1]
//    原因：mid = left + (right-left)/2 向下取整，所以 mid < right，
//    nums[mid+1] 一定有效。但 mid 可能等于 0，nums[mid-1] 会越界。
//
// 3. ✗ while (left <= right) 然后访问 nums[mid+1]
//    ✓ while (left < right)
//    原因：left == right 时 mid == left == right，
//    若 mid == nums.size()-1，访问 nums[mid+1] 越界。
//
// 4. ✗ 特判数组长度为 1
//    ✓ 不需要特判
//    原因：left=0, right=0, 不进入循环，直接返回 0，正确。
//
// 【面试追问】
// Q1: 数组没有排序，为什么能用二分？
//     → 二分的本质是"每次排除一半"，不是"数组有序"。
//       这里的排除依据是：上坡方向一定有峰值（因为边界是-∞）。
//
// Q2: 如果去掉 "nums[i] != nums[i+1]" 的限制，相邻元素可以相等，还能 O(log n) 吗？
//     → 不能。当 nums[mid] == nums[mid+1] 时无法判断峰值在哪一侧。
//       最坏情况（如全相等）退化为 O(n)。类似 LC 81 的情况。
//
// Q3: 如果要找所有峰值怎么办？
//     → 必须 O(n) 扫描。锯齿数组 [1,3,1,3,1,3,1] 有 O(n) 个峰值，
//       光输出就需要 O(n)。
//
// Q4: 二维矩阵中找峰值（LC 1901）怎么做？
//     → 对某一维二分（如对行二分），在 mid 行找最大值，
//       然后比较上下邻居决定往上半部分还是下半部分收缩。O(n log m) 或 O(m log n)。
//
