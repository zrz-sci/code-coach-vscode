/*
 * LeetCode 665: 非递减数列 (Non-decreasing Array)
 * 难度: Medium
 * 标签: Array
 *
 * 【题目本质】
 * 判断能否通过最多修改一个元素使数组非递减。
 * 核心在于遇到违规时贪心选择修改哪个元素。
 *
 * 【解法总览】
 * 解法一: 贪心 - 模拟修改  O(n) / O(1)
 * 解法二: 贪心 - 条件判断  O(n) / O(1)
 */


/*
 * ============================================================
 * 解法一: 贪心 - 模拟修改
 * ============================================================
 *
 * 思路:
 *   遍历数组，遇到 nums[i] > nums[i+1] 时:
 *   1. 如果 i==0 或 nums[i-1] <= nums[i+1]: 降低 nums[i] = nums[i+1]
 *   2. 否则: 升高 nums[i+1] = nums[i]
 *   允许最多一次修改，第二次违规直接返回 false
 *
 * 示例: [4, 2, 3]
 *   i=0: nums[0]=4 > nums[1]=2, 违规!
 *     i==0, 降低 nums[0]=2 -> [2, 2, 3]
 *     count=1
 *   i=1: nums[1]=2 <= nums[2]=3, OK
 *   返回 true
 *
 * 示例: [3, 4, 2, 3]
 *   i=1: nums[1]=4 > nums[2]=2, 违规!
 *     nums[0]=3 > nums[2]=2, 升高 nums[2]=4 -> [3, 4, 4, 3]
 *     count=1
 *   i=2: nums[2]=4 > nums[3]=3, 违规!
 *     count=2 > 1, 返回 false
 *
 * 时间: O(n), 空间: O(1)
 */
class Solution1 {
public:
    bool checkPossibility(vector<int>& nums) {
        int count = 0;
        for (int i = 0; i + 1 < (int)nums.size(); i++) {
            if (nums[i] > nums[i + 1]) {
                count++;
                if (count > 1) return false;

                if (i > 0 && nums[i - 1] > nums[i + 1]) {
                    // 不能降低 nums[i]，因为会破坏与 nums[i-1] 的关系
                    nums[i + 1] = nums[i];
                } else {
                    // 优先降低 nums[i]，对后续影响最小
                    nums[i] = nums[i + 1];
                }
            }
        }
        return true;
    }
};


/*
 * ============================================================
 * 解法二: 贪心 - 不修改数组，条件判断
 * ============================================================
 *
 * 思路:
 *   找到第一个违规位置 pos (nums[pos] > nums[pos+1])
 *   如果有第二个违规，返回 false
 *   否则判断能否通过删除 nums[pos] 或 nums[pos+1] 修复:
 *   - 删 nums[pos]: 需要 pos==0 || nums[pos-1] <= nums[pos+1]
 *   - 删 nums[pos+1]: 需要 pos+2>=n || nums[pos] <= nums[pos+2]
 *
 * 时间: O(n), 空间: O(1)
 */
class Solution2 {
public:
    bool checkPossibility(vector<int>& nums) {
        int n = nums.size();
        int pos = -1;

        for (int i = 0; i + 1 < n; i++) {
            if (nums[i] > nums[i + 1]) {
                if (pos != -1) return false; // 第二次违规
                pos = i;
            }
        }

        // 没有违规
        if (pos == -1) return true;

        // 违规在首/尾，总是可以修复
        if (pos == 0 || pos == n - 2) return true;

        // 尝试两种修改
        // 方案A: 删除 nums[pos]，需要 nums[pos-1] <= nums[pos+1]
        // 方案B: 删除 nums[pos+1]，需要 nums[pos] <= nums[pos+2]
        return nums[pos - 1] <= nums[pos + 1] || nums[pos] <= nums[pos + 2];
    }
};


/*
 * ============================================================
 * 【解法对比】
 *
 * | 解法           | 时间 | 空间 | 特点                    |
 * |---------------|------|------|------------------------|
 * | 模拟修改 (解法一) | O(n) | O(1) | 直觉清晰，修改后继续验证  |
 * | 条件判断 (解法二) | O(n) | O(1) | 不修改原数组，纯逻辑判断  |
 *
 * 面试推荐: 解法一最容易写对，解法二作为 follow-up 讨论
 *
 * ============================================================
 * 【易错点】
 *
 * 1. 只计数不验证:
 *    ✗ count <= 1 就返回 true
 *    ✓ 还需确认修改后整体非递减 (如 [3,4,2,3] 有1次违规但无法修复)
 *
 * 2. 修改方向错误:
 *    ✗ 总是降低 nums[i] → [3,4,2,5] 降低4→2，但 nums[0]=3>2 违规
 *    ✓ 当 nums[i-1] > nums[i+1] 时，必须升高 nums[i+1]
 *
 * 3. 边界遗漏:
 *    ✗ 不处理 i==0 或 i==n-2 的特殊情况
 *    ✓ 首尾违规总是可以通过修改边界元素修复
 *
 * ============================================================
 * 【面试追问】
 *
 * Q1: 贪心为什么正确？
 * → 遇到违规时，降低 nums[i] 比升高 nums[i+1] 更优，
 *   因为较小的值给后续元素留更多空间。只有当降低会
 *   破坏前面的非递减关系时，才退而求其次升高 nums[i+1]。
 *
 * Q2: 如果不允许修改原数组怎么做？
 * → 用解法二的思路：找到违规位置后，通过比较 nums[pos-1]
 *   与 nums[pos+1]、nums[pos] 与 nums[pos+2] 来判断。
 *
 * Q3: 推广到"最多修改 k 个"怎么做？
 * → 问题等价于找最长非递减子序列 (LIS 变体)，
 *   若 LIS 长度 >= n-k 则可行。时间 O(n log n)。
 * ============================================================
 */
