// 【解法对比】
//
// | 解法       | 时间  | 空间  | 优势             | 适用场景         |
// |-----------|-------|-------|-----------------|----------------|
// | 栈模拟     | O(n)  | O(n)  | 直观，通用性强     | 面试首选         |
// | 深度计数法 | O(n)  | O(1)  | 空间最优           | 知道数学性质时    |
// | 递归解析   | O(n)  | O(n)  | 直接对应定义       | 递归思维强时     |
//
// 面试建议：先写栈解法（稳健），再讲深度法（展示洞察力）。
//
// ============================================================
// 【易错点】
//
// 1. 栈底没有哨兵:
//    ✗ 空栈开始 → 最外层 ')' 弹出后 stk.top() 未定义
//    ✓ stk.push(0) 作为基座
//
// 2. 深度法 depth 更新顺序:
//    ✗ 检测 "()" 后再 depth-- → depth 多了1
//    ✓ 先 depth--，再检测 s[i-1]=='(' → depth 正确
//
// 3. inner==0 时得分写成 0:
//    ✗ score = inner == 0 ? 0 : 2*inner → "()" 没分
//    ✓ score = inner == 0 ? 1 : 2*inner → "()" 得1分
//
// 4. 递归解法 pos 用局部变量:
//    ✗ int pos 传值 → 递归返回后 pos 没更新
//    ✓ pos 做类成员或传引用
//
// ============================================================
// 【面试追问】
//
// Q1: 深度法为什么只看 "()" 对？
//     所有分数源自叶子 "()"。嵌套只翻倍，并列只相加。
//     每个叶子嵌套 d 层，贡献 2^d。总分=所有叶子贡献之和。
//
// Q2: 如果规则改为 (A)=3*A 怎么办？
//     栈法: score = inner==0 ? 1 : 3*inner
//     深度法: ans += pow(3, depth) (3^d 代替 2^d)
