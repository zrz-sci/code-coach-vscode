/*
 * LeetCode 1512: Number of Good Pairs (好数对的数目)
 *
 * 【题目本质】
 * 好数对 (i, j) 满足 nums[i] == nums[j] 且 i < j。
 * 核心问题：对于每个值出现 c 次，好数对数 = C(c,2) = c*(c-1)/2。
 *
 * 【解法总览】
 * 解法1: 暴力双循环      — O(n^2) / O(1)      — 最直觉
 * 解法2: 边遍历边计数    — O(n)   / O(n)      — 面试首选 ⭐
 * 解法3: 后处理组合数    — O(n)   / O(n)      — 等价写法
 * 解法4: 数组计数        — O(n)   / O(maxVal) — 常数最小
 */


// ============================================================
// 解法1: 暴力双循环
// 时间: O(n^2)  空间: O(1)
//
// 【思路】
// 枚举所有可能的 (i, j) 对，检查 nums[i] == nums[j]。
// n <= 100，完全能过。面试中先说这个表明理解题意。
//
// 示例: nums = [1,2,3,1,1,3]
//   (0,3): 1==1 ✓  (0,4): 1==1 ✓  (2,5): 3==3 ✓  (3,4): 1==1 ✓
//   共 4 个好数对
// ============================================================
class Solution1 {
public:
    int numIdenticalPairs(vector<int>& nums) {
        int res = 0;
        int n = nums.size();
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                if (nums[i] == nums[j]) {
                    res++;
                }
            }
        }
        return res;
    }
};

// ============================================================
// 解法2: 边遍历边计数（哈希表）— 面试首选 ⭐
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 遍历到 nums[i] 时，之前已经出现了 count[nums[i]] 个相同值，
// 每一个都能和当前元素构成一个好数对。
//
// 这就是经典的"边遍历边查表"模式：
//   - 先查表：当前元素能和多少个历史元素配对？
//   - 再更新表：把当前元素加入历史记录。
//
// 数学验证：如果值 v 出现 c 次（位置 p0, p1, ..., p_{c-1}）
//   遍历 p0: count=0, 贡献 0
//   遍历 p1: count=1, 贡献 1
//   遍历 p2: count=2, 贡献 2
//   ...
//   遍历 p_{c-1}: count=c-1, 贡献 c-1
//   总贡献: 0+1+2+...+(c-1) = c*(c-1)/2 = C(c,2) ✓
//
// 示例: nums = [1,2,3,1,1,3]
//   i=0, x=1: res += 0 → count={1:1}          res=0
//   i=1, x=2: res += 0 → count={1:1, 2:1}     res=0
//   i=2, x=3: res += 0 → count={1:1, 2:1, 3:1} res=0
//   i=3, x=1: res += 1 → count={1:2, ...}      res=1
//   i=4, x=1: res += 2 → count={1:3, ...}      res=3
//   i=5, x=3: res += 1 → count={..., 3:2}      res=4 ✓
// ============================================================
class Solution2 {
public:
    int numIdenticalPairs(vector<int>& nums) {
        unordered_map<int, int> count;
        int res = 0;
        for (int x : nums) {
            // 当前 x 能和之前的 count[x] 个 x 组成好数对
            res += count[x];
            count[x]++;
        }
        return res;
    }
};

// ============================================================
// 解法3: 后处理组合数
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 先统计每个值的出现频率，再用组合数公式 C(c,2) = c*(c-1)/2。
// 数学上完全等价于解法2。
//
// 示例: nums = [1,2,3,1,1,3]
//   频率: {1:3, 2:1, 3:2}
//   结果: C(3,2) + C(1,2) + C(2,2) = 3 + 0 + 1 = 4 ✓
// ============================================================
class Solution3 {
public:
    int numIdenticalPairs(vector<int>& nums) {
        unordered_map<int, int> freq;
        for (int x : nums) freq[x]++;

        int res = 0;
        for (auto& [val, cnt] : freq) {
            res += cnt * (cnt - 1) / 2; // C(cnt, 2)
        }
        return res;
    }
};

// ============================================================
// 解法4: 数组计数（利用值域 1-100）
// 时间: O(n)  空间: O(101) = O(1)
//
// 【思路】
// 题目约束 1 <= nums[i] <= 100，用固定大小数组代替哈希表。
// 数组访问比 unordered_map 更快（无哈希计算和冲突处理）。
//
// 这是面试中的"加分项"：展示你能利用题目约束优化常数。
// ============================================================
class Solution4 {
public:
    int numIdenticalPairs(vector<int>& nums) {
        int count[101] = {0}; // 值域 [1, 100]
        int res = 0;
        for (int x : nums) {
            res += count[x]; // 之前出现了 count[x] 个 x
            count[x]++;
        }
        return res;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间   | 空间     | 遍历次数 | 常数 |
// |-------------|--------|---------|---------|------|
// | 暴力双循环   | O(n^2) | O(1)    | 1       | 大   |
// | 边遍历边计数 | O(n)   | O(n)    | 1       | 中   |
// | 后处理组合数 | O(n)   | O(n)    | 2       | 中   |
// | 数组计数     | O(n)   | O(101)  | 1       | 小   |
//
// ============================================================
// 【易错点】
//
// 1. unordered_map 的 [] 自动插入:
//    在本题中 count[x] 不存在时返回 0 并创建，恰好是需要的行为。
//    但在 Two Sum 等题目中，[] 会污染哈希表，需要用 count() 或 find()。
//
// 2. 组合数公式整数溢出:
//    cnt * (cnt-1) 在 cnt 很大时可能溢出 int。
//    本题 n<=100 不会溢出，但一般场景下用 (long long)cnt * (cnt-1) / 2。
//
// 3. 暴力解内层起点:
//    ✗ for (int j = 0; j < n; j++) → 包含 j==i 自身配对
//    ✓ for (int j = i+1; j < n; j++) → 保证 i < j
//
// ============================================================
// 【面试追问】
//
// Q1: 暴力能过但面试考点是什么？
//     O(n) 的"边遍历边查表"模式。这是很多配对计数题的通用技巧。
//
// Q2: 如果问好三元组 (i,j,k)？
//     C(c, 3) = c*(c-1)*(c-2)/6。或者两层计数（遍历时维护 count1
//     和 count2，分别表示之前出现的单个元素数和已组成的配对数）。
//
// Q3: 这个模式还能用在哪？
//     Two Sum, 560. 和为K的子数组, 逆序对, 等等。核心都是
//     "遍历时查历史状态"。
//
// ============================================================
// 【相关题型】
//
// - 1. Two Sum: 同样"边遍历边查表"，查找 target - nums[i]
// - 560. 和为 K 的子数组: 前缀和 + 哈希表计数
// - 2001. 可互换矩形的组数: 配对计数，key 是宽高比
// - 2506. 统计相似字符串对的数目: C(c,2) 计数，key 是字符集 bitmask
// ============================================================
