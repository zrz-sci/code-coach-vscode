/*
 * LeetCode 1758: 生成交替二进制字符串的最少操作数
 * Minimum Changes To Make Alternating Binary String
 *
 * 【题目本质】
 * 交替二进制字符串只有两种形态: "010101..." 和 "101010..."。
 * 分别计算变成这两种目标各需要多少次修改，取较小值。
 * 核心观察: 两种目标互补 —— cost1 + cost2 = n。
 *
 * 【解法总览】
 * 解法1: 一次遍历 (标准写法)   — O(n) / O(1) — 面试首选 ⭐
 * 解法2: 一次遍历 (异或写法)   — O(n) / O(1) — 竞赛简洁
 * 解法3: 两次遍历 (不利用互补) — O(n) / O(1) — 作为对比理解互补性质
 */

// ============================================================
// 解法1: 一次遍历 (标准写法) — 面试首选 ⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 交替字符串只有两种可能的目标:
//   pattern1 = "010101..." (偶数位'0', 奇数位'1')
//   pattern2 = "101010..." (偶数位'1', 奇数位'0')
//
// 计算 cost1 = 把 s 变成 pattern1 需要修改的位数。
// 由于互补性: cost2 = n - cost1。
// 答案 = min(cost1, n - cost1)。
//
// 【互补性证明】
// 对于每个位置 i:
//   pattern1[i] 和 pattern2[i] 恰好相反 (一个'0'一个'1')
//   所以 s[i] 要么匹配 pattern1 (不匹配 pattern2)
//        要么匹配 pattern2 (不匹配 pattern1)
//   每个位置恰好贡献 1 给 cost1 或 cost2，故 cost1 + cost2 = n
//
// 示例 s = "0100":
//   与 "0101" 比较: 位置3不匹配 → cost1 = 1
//   cost2 = 4 - 1 = 3
//   答案 = min(1, 3) = 1
//
// 示例 s = "1111":
//   与 "0101" 比较: 位置0,2不匹配 → cost1 = 2
//   cost2 = 4 - 2 = 2
//   答案 = min(2, 2) = 2
// ============================================================
class Solution1 {
public:
    int minOperations(string s) {
        int n = s.size();
        int cost1 = 0; // 变成 "0101..." 需要修改的次数

        for (int i = 0; i < n; i++) {
            // pattern1 期望: 偶数位 '0'，奇数位 '1'
            char expected = (i % 2 == 0) ? '0' : '1';
            if (s[i] != expected) {
                cost1++;
            }
        }

        // pattern2 的修改次数 = n - cost1 (互补)
        // 答案取两者较小值
        return min(cost1, n - cost1);
    }
};

// ============================================================
// 解法2: 一次遍历 (异或写法) — 竞赛简洁
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 利用异或的性质来判断"是否需要修改":
//   s[i] 的实际值: s[i] - '0' (得到 0 或 1)
//   pattern1 的期望值: i % 2 (偶数位 0, 奇数位 1)
//   XOR: 相同为 0, 不同为 1 —— 恰好是"需要修改 = 1, 不需要 = 0"
//
// 这种写法更短，但可读性稍低。
//
// 示例 s = "0100":
//   i=0: (0)^(0) = 0  不需修改
//   i=1: (1)^(1) = 0  不需修改
//   i=2: (0)^(0) = 0  不需修改
//   i=3: (0)^(1) = 1  需要修改 → cost1 = 1
// ============================================================
class Solution2 {
public:
    int minOperations(string s) {
        int n = s.size();
        int cost1 = 0;

        for (int i = 0; i < n; i++) {
            // XOR: 实际值 vs 期望值, 不同则为1(需要修改)
            cost1 += (s[i] - '0') ^ (i % 2);
        }

        return min(cost1, n - cost1);
    }
};

// ============================================================
// 解法3: 两次遍历 (不利用互补) — 作为对比
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 如果没有观察到互补性质, 最直觉的做法:
// 分别计算变成两种 pattern 的代价, 取较小值。
// 时间复杂度不变, 但多了一遍遍历, 常数因子翻倍。
// 理解这种做法有助于反过来理解为什么互补优化是成立的。
//
// 对比:
//   解法1: 一遍遍历, cost2 = n - cost1
//   解法3: 两遍遍历, 独立计算 cost1 和 cost2
//   结果相同, 但解法1 展示了更深的理解
// ============================================================
class Solution3 {
public:
    int minOperations(string s) {
        int n = s.size();
        int cost1 = 0; // 变成 "0101..." 的代价
        int cost2 = 0; // 变成 "1010..." 的代价

        for (int i = 0; i < n; i++) {
            // pattern1: 偶数位 '0', 奇数位 '1'
            char expect1 = (i % 2 == 0) ? '0' : '1';
            if (s[i] != expect1) cost1++;

            // pattern2: 偶数位 '1', 奇数位 '0'
            char expect2 = (i % 2 == 0) ? '1' : '0';
            if (s[i] != expect2) cost2++;
        }

        return min(cost1, cost2);
        // 验证: cost1 + cost2 == n 始终成立
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 写法特点   | 遍历次数 | 时间 | 空间 |
// |----------|-----------|----------|------|------|
// | 标准写法  | 清晰易读  | 1        | O(n) | O(1) |
// | 异或写法  | 简洁      | 1        | O(n) | O(1) |
// | 双遍历   | 直觉对比  | 1(合并)  | O(n) | O(1) |
//
// 三种写法本质相同, 面试推荐标准写法, 竞赛推荐异或写法。
//
// ============================================================
// 【易错点】
//
// 1. 字符比较 vs 整数比较:
//    ✗ if (s[i] != i % 2)  // s[i] 是 '0'(ASCII 48), i%2 是 0
//    ✓ if (s[i] != '0' + i % 2)  // 统一为字符比较
//    ✓ if ((s[i] - '0') != i % 2) // 统一为整数比较
//
// 2. 忘记取 min:
//    ✗ return cost1;  // cost1 可能 > n/2, 另一种更优
//    ✓ return min(cost1, n - cost1);
//
// 3. 混淆偶数位/奇数位期望值:
//    其实无所谓 —— 无论选哪种作 pattern1, 最终取 min 结果一样。
//    但在面试中需要能清楚说明你选的是哪种 pattern。
//
// ============================================================
// 【面试追问】
//
// Q1: "互补性质为什么成立? 能严格证明吗?"
//     对每个位置 i, pattern1[i] 和 pattern2[i] 互补。
//     s[i] 只能等于其中一个, 所以每个位置贡献 1 给 cost1 或 cost2,
//     但不会同时贡献给两者。故 cost1 + cost2 = n。
//
// Q2: "如果字符串不是二进制, 而是 k 种字符的交替, 怎么办?"
//     交替模式变为 k 种(从 k 种排列中选取), 不能再用互补。
//     需要枚举所有排列, 对每种排列计算代价。
//     时间复杂度 O(k! * n)。
//
// Q3: "能不能 O(1) 空间 O(n) 时间, 同时获得需要修改的位置列表?"
//     不能, 位置列表本身可能有 O(n) 个元素, 存储就需要 O(n)。
//     但如果只需要输出位置而不存储, 可以在第二遍遍历时输出。
//
// ============================================================
