// ============================================================
// LeetCode 976: Largest Perimeter Triangle (三角形的最大周长)
//
// 【解法】贪心 + 排序 — O(n log n) / O(1)
//
// 排序后从大到小检查相邻三元组
// 第一组满足三角不等式 a+b > c 的就是最大周长
// ============================================================

/*
 * 三角不等式简化:
 *
 * 排序后 a <= b <= c, 只需检查 a + b > c
 * 因为:
 *   a + c > b  ← c >= b, 所以 a+c >= a+b > b (如果a>0)
 *   b + c > a  ← b >= a, 所以 b+c >= a+a > a (如果a>0)
 *
 * 所以两个不等式自动满足, 只需一个检查!
 */

/*
 * 贪心正确性:
 *
 * 排序后: nums[0] <= nums[1] <= ... <= nums[n-1]
 *
 * 如果 nums[i-2] + nums[i-1] <= nums[i]:
 *   那么 nums[j] + nums[i-1] <= nums[i] 对所有 j < i-2
 *   (因为 nums[j] <= nums[i-2])
 *   → nums[i] 作为最大边时, 没有任何两个更小的边能满足条件
 *   → 排除 nums[i], 继续检查下一组
 *
 * 第一组满足条件的三元组周长最大:
 *   所有 k > i 的 nums[k] 已被排除 (无法形成三角形)
 *   所有 j < i-2 的 nums[j] 更小, 周长只会更小
 */

/*
 * 示例1: nums = [2, 1, 2]
 *
 * 排序后: [1, 2, 2]
 * i=2: 1+2=3 > 2? YES → 周长 = 1+2+2 = 5
 *
 * 示例2: nums = [1, 2, 1, 10]
 *
 * 排序后: [1, 1, 2, 10]
 * i=3: 1+2=3 > 10?  NO
 * i=2: 1+1=2 > 2?   NO (等于不行, 面积为零)
 * → 返回 0
 */

class Solution {
public:
    int largestPerimeter(vector<int>& nums) {
        // Step 1: 排序
        sort(nums.begin(), nums.end());

        // Step 2: 从最大的三元组开始, 向左扫描
        for (int i = nums.size() - 1; i >= 2; i--) {
            // 三角不等式: 两小边之和 > 最大边
            if (nums[i - 2] + nums[i - 1] > nums[i]) {
                return nums[i - 2] + nums[i - 1] + nums[i];
            }
        }

        // 没有任何三元组能构成三角形
        return 0;
    }
};


// ============================================================
// 【解法2】partial_sort 优化 (当 n 很大但答案在最大端)
//
// 如果只需要检查最大的几组, 可以用 partial_sort
// 但最坏情况仍需全排序, 所以渐近复杂度不变
// ============================================================

class Solution_PartialSort {
public:
    int largestPerimeter(vector<int>& nums) {
        // nth_element 只保证第 k 大在正确位置, 不保证顺序
        // 所以这里还是需要排序

        // 一种优化: 先用 nth_element 找到前 k 大
        // 然后只排序前 k 个 (k 足够大以覆盖答案)
        // 但实际中直接 sort 更简洁

        sort(nums.begin(), nums.end(), greater<int>()); // 降序

        for (int i = 0; i + 2 < (int)nums.size(); i++) {
            // nums[i] >= nums[i+1] >= nums[i+2]
            // 检查 nums[i+1] + nums[i+2] > nums[i]
            if (nums[i + 1] + nums[i + 2] > nums[i]) {
                return nums[i] + nums[i + 1] + nums[i + 2];
            }
        }
        return 0;
    }
};


// ============================================================
// 【数学分析】什么时候返回 0?
// ============================================================

/*
 * 排序后, 如果对所有相邻三元组都有 nums[i-2]+nums[i-1] <= nums[i],
 * 则 nums 的增长速度至少像斐波那契数列.
 *
 * 例如: [1, 1, 2, 3, 5, 8, 13, 21, 34, ...]
 *       每个数 >= 前两个数之和 → 没有三元组能形成三角形
 *
 * 斐波那契数列增长是指数级的 (~1.618^n),
 * 所以在 nums[i] <= 10^6 的约束下, 最多约 30 个数就会超出范围.
 * 因此如果 n > ~30, 几乎一定存在满足条件的三元组.
 */


// ============================================================
// 【扩展】611. Valid Triangle Number (有效三角形个数)
//
// 不是找最大周长, 而是计算所有能形成三角形的三元组数量
// 排序后, 固定最大边 c, 双指针找 a+b > c 的 (a,b) 对数
// ============================================================

class Solution_611 {
public:
    int triangleNumber(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        int n = nums.size(), count = 0;

        // 固定最大边 nums[i]
        for (int i = n - 1; i >= 2; i--) {
            int left = 0, right = i - 1;
            while (left < right) {
                if (nums[left] + nums[right] > nums[i]) {
                    // nums[left..right-1] + nums[right] 都满足
                    count += right - left;
                    right--;
                } else {
                    left++;
                }
            }
        }
        return count;
    }
};


