// 主解法:
//   时间: O(n log n) — 排序是瓶颈, 扫描 O(n)
//   空间: O(1) — 原地排序, 常数额外空间
//
// 最坏情况扫描次数: O(n), 但由于斐波那契性质,
// 在 nums[i] <= 10^6 时最多约 30 次就能找到答案.


