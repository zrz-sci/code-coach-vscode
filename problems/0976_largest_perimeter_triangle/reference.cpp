// 【解法对比】
// ┌───────────────────┬────────────┬────────┬─────────────────────────────┐
// │ 解法               │ 时间       │ 空间   │ 适用场景                    │
// ├───────────────────┼────────────┼────────┼─────────────────────────────┤
// │ 1. 排序+相邻扫描   │ O(nlogn)   │ O(1)   │ 面试首选, 代码极简          │
// │ 2. 降序partial     │ O(nlogn)   │ O(1)   │ 写法变体, 无渐近优势        │
