// └───────────────────┴────────────┴────────┴─────────────────────────────┘
//
// 【易错点】
// 1. 三角不等式是 a+b > c (严格大于), 等于时面积为 0, 不构成三角形
// 2. 排序后只需检查 nums[i-2]+nums[i-1] > nums[i], 另两个不等式自动满足
// 3. 必须从最大三元组开始向左扫 → 第一组满足的就是最大周长
// 4. 返回的是周长 (三边之和), 不是最大边 → 不要少加
// 5. 数组长度 < 3 时直接返回 0, 边界要提前处理
//
// 【面试追问】
// Q1: 如果不要求最大周长, 而是要求最大面积的三角形?
//     → 最大周长不等于最大面积. 需要用海伦公式 S=√(s(s-a)(s-b)(s-c))
//       对所有合法三元组计算面积, 排序+剪枝可以减少计算量.
//
// Q2: 如果要找最小周长的合法三角形?
//     → 仍然排序, 从最小三元组 (i=2) 开始向右扫描.
//       第一组满足 nums[i-2]+nums[i-1]>nums[i] 的就是最小周长.
//
// Q3: 如何不排序, 在 O(n) 时间内解决? (理论题)
//     → 不存在严格 O(n) 解. 但可以利用斐波那契性质:
//       如果 n>~30 且值域有限, 鸽巢原理保证一定存在合法三元组.
//       用 partial_sort 或 nth_element 只取最大的 ~30 个元素再扫描.
