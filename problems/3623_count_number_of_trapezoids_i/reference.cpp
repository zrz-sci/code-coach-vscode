/*
 * LeetCode 3623: Count Number of Trapezoids I (统计梯形的数目 I)
 *
 * 难度: Medium | 标签: Geometry, Array, Hash Table, Math
 *
 * 【解法】按 y 坐标分组 + 组合计数 -- O(n) / O(n)
 *
 * 核心观察:
 *   水平梯形 = 至少有一对水平边(平行于 x 轴)的凸四边形
 *   水平边 = 两端点 y 坐标相同
 *
 *   构造方法: 从两个不同 y 层各取 2 个点
 *   - y 层 y1 有 c1 个点 -> C(c1, 2) 种选法
 *   - y 层 y2 有 c2 个点 -> C(c2, 2) 种选法
 *   - 这四个点来自两层，两条水平线段 -> 天然形成水平梯形(至少一对水平边)
 *
 *   答案 = sum_{所有 y 层对 (i,j), i<j} C(ci, 2) * C(cj, 2)
 *
 *   数学优化:
 *   设 v_i = C(c_i, 2), S = sum(v_i), Q = sum(v_i^2)
 *   sum_{i<j} v_i * v_j = (S^2 - Q) / 2
 *
 * 示例: points = [[1,0],[2,0],[3,0],[2,2],[3,2]]
 *   y=0: 3点, v=C(3,2)=3
 *   y=2: 2点, v=C(2,2)=1
 *   S=4, Q=9+1=10
 *   答案 = (16-10)/2 = 3 ✓
 */


class Solution {
public:
    int countTrapezoids(vector<vector<int>>& points) {
        const int MOD = 1e9 + 7;

        // ==================== Step 1: 按 y 坐标分组 ====================
        // 统计每个 y 值上有多少个点
        // 使用 unordered_map 实现 O(1) 查找/插入
        unordered_map<int, long long> cnt;
        for (auto& p : points) {
            cnt[p[1]]++;  // p[1] 是 y 坐标
        }

        // ==================== Step 2: 计算每层的 C(c, 2) ====================
        // v_i = C(c_i, 2) = c_i * (c_i - 1) / 2
        // 同时累加 S = sum(v_i) 和 Q = sum(v_i^2)
        //
        // 注意: c*(c-1) 一定是偶数，所以先除2再取模是安全的
        // 但 v*v 可能溢出 int，需要 long long
        long long S = 0;  // sum of v_i
        long long Q = 0;  // sum of v_i^2

        for (auto& [y, c] : cnt) {
            // C(c, 2) = c * (c - 1) / 2
            // 注意: c 可达 10^5, c*(c-1) 可达 ~10^10, 需要 long long
            long long v = c * (c - 1) / 2 % MOD;
            S = (S + v) % MOD;
            Q = (Q + v % MOD * (v % MOD)) % MOD;
        }

        // ==================== Step 3: 应用公式 ====================
        // 答案 = sum_{i<j} v_i * v_j = (S^2 - Q) / 2
        //
        // 模运算注意:
        // 1. S*S 可能溢出 -> 先取模
        // 2. S^2 - Q 可能为负(模意义下) -> 加 MOD
        // 3. 除以 2 -> 乘以 2 的模逆元

        long long S2 = S % MOD * (S % MOD) % MOD;  // S^2 mod MOD
        long long ans = (S2 - Q % MOD + MOD) % MOD;

        // 2 的模逆元: 当 MOD 是奇素数时, inv2 = (MOD + 1) / 2
        // 验证: 2 * 500000004 = 10^9 + 8 ≡ 1 (mod 10^9 + 7)
        long long inv2 = (MOD + 1) / 2;  // = 500000004
        ans = ans % MOD * inv2 % MOD;

        return (int)ans;
    }
};

/*
 * ==================== 数学推导 ====================
 *
 * 为什么 sum_{i<j} v_i * v_j = (S^2 - Q) / 2 ?
 *
 *   S^2 = (v_1 + v_2 + ... + v_k)^2
 *       = sum_i v_i^2 + 2 * sum_{i<j} v_i * v_j
 *       = Q + 2 * Answer
 *
 *   所以 Answer = (S^2 - Q) / 2
 *
 * 这个恒等式在组合计数中极其常用。
 * 见到 "所有配对的乘积之和" 就想到这个公式。
 *
 * ==================== 模逆元简介 ====================
 *
 * 在模 p 运算中, a/b 不能直接除:
 *   a / b (mod p) = a * b^{-1} (mod p)
 *
 * b 的模逆元 b^{-1} 满足: b * b^{-1} ≡ 1 (mod p)
 *
 * 求法(当 p 是素数时):
 *   方法1: 费马小定理 b^{-1} = b^{p-2} mod p
 *   方法2: 当 b=2 且 p 为奇素数: inv2 = (p+1)/2
 *
 * ==================== 方法对比 ====================
 *
 * 本题的 O(n) 方法 vs 暴力 O(Y^2):
 *
 *   暴力: 双重循环遍历所有 y 层对
 *     for y1 in layers:
 *       for y2 in layers (y2 > y1):
 *         ans += C(cnt[y1], 2) * C(cnt[y2], 2)
 *
 *     Y 层数 = 不同 y 值数量, 最多 n
 *     最坏 O(n^2), n=10^5 时超时
 *
 *   优化: 用 (S^2 - Q) / 2 公式
 *     只需遍历一遍所有层, O(Y) = O(n)
 *
 * ==================== 关键易错点 ====================
 *
 * 1. C(c, 2) 溢出:
 *    c 最大 10^5, c*(c-1) ~ 10^10, 超过 int 范围
 *    必须用 long long: (long long)c * (c-1) / 2
 *
 * 2. 模运算中的负数:
 *    S^2 - Q 在模意义下可能为负
 *    必须 (S2 - Q + MOD) % MOD
 *
 * 3. 除以 2 不能直接除:
 *    模运算中没有除法, 必须乘以 2 的逆元
 *    inv2 = (MOD + 1) / 2 = 500000004
 *
 * 4. 只有一层时答案为 0:
 *    S^2 = Q (只有一个 v_i), (S^2 - Q) / 2 = 0 ✓
 *
 * 5. 层内点数 < 2 时:
 *    C(0, 2) = C(1, 2) = 0, 自动不贡献
 *
 * 6. 凸性不需要额外检查:
 *    从两个不同 y 层各取 2 点, 四点不共线
 *    组成的四边形一定是凸的(上下两条水平线段)
 *
 *
 * ======================== 总结 ========================
 *
 * 【解法对比】
 *   - 暴力枚举所有层对 O(Y^2): 双重循环，Y = 不同 y 值数量
 *     当 Y ~ n = 10^5 时 O(n^2) 超时
 *   - 公式优化 O(n): 利用 sum_{i<j} v_i*v_j = (S^2 - Q) / 2
 *     只需遍历一遍所有层，线性时间
 *   - 这是"所有配对乘积之和"的经典数学优化，面试高频技巧
 *
 * 【易错点】
 *   1. C(c, 2) 溢出: c 最大 10^5，c*(c-1) ~ 10^10，超 int 范围
 *      必须 (long long)c * (c-1) / 2
 *   2. 模运算中 S^2 - Q 可能为负: 必须 (S2 - Q + MOD) % MOD
 *      忘记加 MOD 导致负数取模得到负答案
 *   3. 除以 2 不能直接除: 模运算中 a/2 = a * inv(2) mod p
 *      inv(2) = (MOD+1)/2 = 500000004（当 MOD = 10^9+7）
 *   4. 忽略同一层内点数 < 2 的情况: C(0,2) = C(1,2) = 0，自动不贡献
 *      但如果错误地对 c=1 计算 1*(1-1)/2 = 0 时出现意外逻辑要留心
 *   5. 误以为需要判断四边形凸性: 两个不同 y 层各取 2 点天然构成凸四边形
 *
 * 【面试追问】
 *   Q1: 如果梯形不限于水平（允许任意方向的平行边），怎么做？
 *       → 不再只按 y 分组，而是枚举所有点对的斜率
 *       → 将同斜率的线段分组，再用相同的组合计数思路
 *       → 斜率用 (dy, dx) 的最简分数表示避免浮点误差
 *       → 时间复杂度升至 O(n^2)（枚举所有点对）
 *
 *   Q2: 如果要求是平行四边形而非梯形（两对平行边），怎么改？
 *       → 梯形: 至少一对平行边；平行四边形: 恰好两对
 *       → 需要从答案中减去"只有一对平行边"的情况
 *       → 或者直接枚举: 两层各取 2 点，且上下两条线段等长且中点重合
 *       → 经典几何计数，可用中点哈希实现 O(n^2)
 *
 *   Q3: (S^2 - Q) / 2 这个公式还能用在哪些场景？
 *       → 任何"枚举所有无序对 (i,j) 的 f(i)*f(j) 之和"都能用
 *       → 例: 数组中所有两数之积的总和 = (S^2 - sum(a_i^2)) / 2
 *       → 例: 图论中统计边权乘积（将度数作为 v_i）
 *       → 核心: 展开 (sum v_i)^2 = sum v_i^2 + 2*sum_{i<j} v_i*v_j
 */
