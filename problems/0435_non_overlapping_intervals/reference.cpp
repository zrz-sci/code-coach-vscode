/*
 * LeetCode 435: 无重叠区间 (Non-overlapping Intervals)
 * 
 * 【题目本质】
 * 经典的区间调度问题：从一堆可能重叠的区间中，最多能保留多少个互不重叠的区间？
 * 移除最少 = 保留最多，答案 = 总数 - 最多保留数。
 *
 * 【解法总览】
 * 解法1: 贪心（按结束时间排序）— O(n log n) / O(log n) — 面试首选 ⭐
 * 解法2: 贪心（按开始时间排序）— O(n log n) / O(log n) — 另一个视角
 * 解法3: 动态规划              — O(n²) / O(n)          — 展示 DP 思维
 */

// ============================================================
// 解法1: 贪心（按结束时间排序）— 面试首选 ⭐
// 时间: O(n log n)  空间: O(log n)（排序的栈空间）
//
// 【思路】
// 经典活动选择问题 (Activity Selection Problem)。
// 核心贪心策略：每次选结束时间最早的区间。
// 
// 为什么？结束越早，给后面留的空间越大，能容纳更多区间。
// 
// 证明（交换论证）：
// 假设最优解选了一个不是最早结束的区间 A，我们用最早结束的 B 替换它。
// 因为 B.end <= A.end，后续所有区间的兼容性只好不差，解不会变劣。
//
// 示例: intervals = [[1,2],[2,3],[3,4],[1,3]]
//
// 按结束时间排序后:
//   [1,2)  ████
//   [1,3)  ████████          ← start=1 < end=2, 重叠，跳过（移除）
//   [2,3)      ████          ← start=2 >= end=2, 不重叠，保留！end=3
//   [3,4)          ████      ← start=3 >= end=3, 不重叠，保留！end=4
//   ─────┼───┼───┼───┼───
//         1   2   3   4
//
// 保留 3 个 ([1,2],[2,3],[3,4])，移除 1 个 ([1,3])
// 答案 = 4 - 3 = 1
// ============================================================
class Solution1 {
public:
    int eraseOverlapIntervals(vector<vector<int>>& intervals) {
        // 按结束时间升序排序
        // 为什么按结束时间？结束越早，给后续区间留的空间越大
        sort(intervals.begin(), intervals.end(), [](const vector<int>& a, const vector<int>& b) {
            return a[1] < b[1];
        });
        
        int kept = 1;  // 第一个区间（结束最早）一定保留
        int end = intervals[0][1];  // 上一个保留区间的结束时间
        
        for (int i = 1; i < (int)intervals.size(); i++) {
            if (intervals[i][0] >= end) {
                // 当前区间的起点 >= 上一个保留区间的终点 → 不重叠
                // 注意: >= 而不是 >，因为题目说端点相同不算重叠
                kept++;
                end = intervals[i][1];
            }
            // 重叠的区间直接跳过（等价于移除）
        }
        
        // 移除数 = 总数 - 保留数
        return (int)intervals.size() - kept;
    }
};

// ============================================================
// 解法2: 贪心（按开始时间排序）
// 时间: O(n log n)  空间: O(log n)
//
// 【思路】
// 换一个角度：按开始时间排序后，从左到右扫描。
// 遇到重叠时，移除哪个？移除结束时间更晚的那个。
// 
// 为什么？结束晚的区间"霸占"的时间段更长，更容易与后面的区间冲突。
// 保留结束早的，能给后面更多空间。
//
// 两种重叠情况的处理:
//
// 情况1: 前一个包含当前（前大后小）
//   prev: [=============]
//   curr:    [====]           ← 移除 prev（结束更晚），end = curr.end
//   
// 情况2: 部分重叠
//   prev: [=======]
//   curr:     [=======]      ← 移除 curr（结束更晚），end 不变
//
// 统一写法: end = min(end, intervals[i][1])
// ============================================================
class Solution2 {
public:
    int eraseOverlapIntervals(vector<vector<int>>& intervals) {
        // 按开始时间升序排序（开始相同时按结束时间升序，默认行为）
        sort(intervals.begin(), intervals.end());
        
        int removed = 0;
        int end = intervals[0][1];
        
        for (int i = 1; i < (int)intervals.size(); i++) {
            if (intervals[i][0] < end) {
                // 重叠了！移除结束时间更晚的那个
                removed++;
                // 保留结束更早的区间 → end 取 min
                end = min(end, intervals[i][1]);
            } else {
                // 不重叠，保留当前区间，更新 end
                end = intervals[i][1];
            }
        }
        
        return removed;
    }
};

// ============================================================
// 解法3: 动态规划
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 按结束时间排序后，定义:
//   dp[i] = 以第 i 个区间结尾时，最多能保留多少个不重叠区间
//
// 状态转移:
//   dp[i] = max(dp[j] + 1) for all j < i where intervals[j][1] <= intervals[i][0]
//   如果没有这样的 j，dp[i] = 1（只有自身）
//
// dp 填表过程 (示例1: 排序后 [1,2],[1,3],[2,3],[3,4]):
//
//   i=0: [1,2]  → 无前驱        → dp[0] = 1
//   i=1: [1,3]  → j=0: [1,2] end=2 > start=1 重叠 → dp[1] = 1
//   i=2: [2,3]  → j=0: [1,2] end=2 <= start=2 ✓  → dp[2] = dp[0]+1 = 2
//                  j=1: [1,3] end=3 > start=2 重叠 → 跳过
//   i=3: [3,4]  → j=0: end=2 <= 3 ✓ dp[0]+1=2
//                  j=1: end=3 <= 3 ✓ dp[1]+1=2
//                  j=2: end=3 <= 3 ✓ dp[2]+1=3  → dp[3] = 3
//
//   最大保留 = max(dp) = 3, 移除 = 4 - 3 = 1
//
// 注意: O(n²) 对 n=10^5 可能超时，但展示了 DP 思维。
// 优化: 内层循环可用二分查找替代（找最后一个不重叠的 j），变为 O(n log n)。
// ============================================================
class Solution3 {
public:
    int eraseOverlapIntervals(vector<vector<int>>& intervals) {
        int n = intervals.size();
        
        // 按结束时间排序
        sort(intervals.begin(), intervals.end(), [](const vector<int>& a, const vector<int>& b) {
            return a[1] < b[1];
        });
        
        // dp[i] = 以第 i 个区间结尾的最大不重叠区间数
        vector<int> dp(n, 1);
        
        int maxKept = 1;
        for (int i = 1; i < n; i++) {
            for (int j = 0; j < i; j++) {
                // 第 j 个区间的结束时间 <= 第 i 个区间的开始时间 → 不重叠
                if (intervals[j][1] <= intervals[i][0]) {
                    dp[i] = max(dp[i], dp[j] + 1);
                }
            }
            maxKept = max(maxKept, dp[i]);
        }
        
        return n - maxKept;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 解法1 (贪心-结束时间) | 解法2 (贪心-开始时间) | 解法3 (DP)    |
// |------------|----------------------|----------------------|---------------|
// | 时间       | O(n log n)           | O(n log n)           | O(n²)         |
// | 空间       | O(log n)             | O(log n)             | O(n)          |
// | 代码量     | 最简洁               | 稍复杂(min处理)      | 最多          |
// | 面试推荐   | ⭐ 首选              | 备选                 | 展示DP能力    |
//
// 解法1 vs 解法2: 本质相同（都是保留结束更早的），只是排序维度不同。
// 按结束时间排序更自然——排好后，不重叠的直接保留，重叠的直接跳过。
// 按开始时间排序需要额外处理"重叠时保留谁"的逻辑（end = min）。
//
// 解法3 的价值: 面试官如果追问"如果区间有权重"，DP 方法可以扩展，贪心不行。
//
// ============================================================
// 【易错点】
//
// 1. 排序方向搞错:
//    ✗ 解法1中按开始时间排序 → 反例 [[1,100],[2,3],[3,4]]
//      按开始时间排序后保留 [1,100]，但最优是保留 [2,3]+[3,4]
//    ✓ 解法1必须按结束时间排序
//
// 2. 不重叠判断写成严格大于:
//    ✗ intervals[i][0] > end  → [1,2] 和 [2,3] 被判为重叠
//    ✓ intervals[i][0] >= end → 题目说端点接触不算重叠
//
// 3. 返回值搞反:
//    ✗ return kept;          → 这是保留的数量，不是移除的
//    ✓ return n - kept;      → 移除数 = 总数 - 保留数
//
// 4. 解法2中重叠时 end 更新错误:
//    ✗ end = intervals[i][1]; → 当 prev 包含 curr 时，本应保留更短的 curr
//    ✓ end = min(end, intervals[i][1]); → 保留结束更早的那个
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么贪心"选结束最早的"是正确的？
// A1: 交换论证。假设最优解第一个选的不是结束最早的区间 A，而是 B。
//     因为 A.end <= B.end，用 A 替换 B 后，后续区间的兼容性只好不差，
//     所以替换后的解 >= 原最优解。逐步替换可证贪心 = 最优。
//
// Q2: 如果每个区间有一个权重，要求保留的区间权重和最大，怎么办？
// A2: 贪心失效（结束早但权重低的不一定好）。需要带权区间调度 DP：
//     按结束时间排序，dp[i] = max(dp[i-1], dp[j]+w[i])，
//     j = 最后一个不与 i 重叠的区间（用二分查找），O(n log n)。
//     → 参考 LeetCode 1235. 规划兼职工作
//
// Q3: 如果区间是环形排列（首尾相连），怎么处理？
// A3: 类似 House Robber II 的"拆环"思路：
//     分两种情况——包含第一个区间 / 不包含第一个区间，
//     分别做一次线性的贪心，取较优结果。
// ============================================================
