/*
 * LeetCode 217: 存在重复元素 (Contains Duplicate)
 * 
 * 【题目本质】
 * 判断数组中是否存在重复元素。核心操作是"快速判断某个值是否已经出现过"。
 *
 * 【解法总览】
 * 解法1: 暴力枚举    — O(n²) / O(1)     — 最直觉，但超时
 * 解法2: 排序+相邻比较 — O(n log n) / O(1) — 不用额外空间
 * 解法3: 哈希集合    — O(n) / O(n)       — 面试首选，最优时间
 */

// ============================================================
// 解法1: 暴力枚举 — 检查所有元素对
// 时间: O(n²)  空间: O(1)
// 
// 【思路】
// 最直接的想法：对每个元素 nums[i]，在它后面的元素中找有没有相同的。
// 两层循环枚举所有 (i, j) 配对，i < j。
// 
// 瓶颈：n = 10^5 时，10^10 次比较，远超时间限制。
// 但这是理解题意的出发点，也是面试中展示思路的第一步。
// ============================================================
class Solution1 {
public:
    bool containsDuplicate(vector<int>& nums) {
        int n = nums.size();
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                if (nums[i] == nums[j]) {
                    return true;  // 找到一对重复
                }
            }
        }
        return false;  // 所有元素互不相同
    }
};

// ============================================================
// 解法2: 排序 + 相邻比较
// 时间: O(n log n)  空间: O(1)（原地排序，但修改了原数组）
// 
// 【思路】
// 解法1的瓶颈：在无序数组中查找重复需要 O(n)。
// 关键观察：排序后，相同的元素一定相邻。
// 所以排序后只需一次线性扫描，比较相邻元素即可。
// 
// 优点：不需要额外空间。
// 缺点：会修改原数组；排序本身 O(n log n)，不是最优时间。
// ============================================================
class Solution2 {
public:
    bool containsDuplicate(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        
        // 排序后相同元素相邻，只需比较 nums[i] 和 nums[i-1]
        for (int i = 1; i < (int)nums.size(); i++) {
            if (nums[i] == nums[i - 1]) {
                return true;
            }
        }
        return false;
    }
};

// ============================================================
// 解法3: 哈希集合 — 边遍历边查 ⭐ 面试首选
// 时间: O(n)  空间: O(n)
// 
// 【思路】
// 解法1的真正瓶颈是："查找某个值是否出现过"需要 O(n)。
// 哈希集合（unordered_set）把这个操作降到 O(1)。
// 
// 做法：遍历数组，对每个元素：
//   1. 先查集合 — 如果存在，说明之前遍历过相同值 → 返回 true
//   2. 再插入集合 — 记录当前值，供后续元素查找
// 
// 为什么边遍历边查就能覆盖所有配对？
// 当处理 nums[i] 时，集合中已有 nums[0..i-1]。
// 如果 nums[i] 在集合中，说明存在某个 j < i 使得 nums[j] == nums[i]。
// 遍历完所有 i 就等价于检查了所有 (i, j) 配对。
//
// 示意（以 nums = [1,2,3,1] 为例）：
//   i=0: num=1, seen={},      1不在 → 插入 → seen={1}
//   i=1: num=2, seen={1},     2不在 → 插入 → seen={1,2}
//   i=2: num=3, seen={1,2},   3不在 → 插入 → seen={1,2,3}
//   i=3: num=1, seen={1,2,3}, 1在！ → 返回 true
// ============================================================
class Solution3 {
public:
    bool containsDuplicate(vector<int>& nums) {
        unordered_set<int> seen;
        for (int num : nums) {
            // 关键：先查再插入，避免自己跟自己比
            if (seen.count(num)) {
                return true;   // num 之前出现过 → 重复
            }
            seen.insert(num);  // 记录 num，供后续元素查找
        }
        return false;
    }
};

// ============================================================
// 解法3b: 利用集合大小判断（一行写法）
// 时间: O(n)  空间: O(n)
// 
// 【思路】
// 集合自动去重。如果去重后元素个数 < 原数组长度，说明有重复。
// 缺点：必须处理完所有元素才能判断，无法提前终止。
//       解法3 在第一个重复处就返回，实际更快。
// ============================================================
class Solution3b {
public:
    bool containsDuplicate(vector<int>& nums) {
        return unordered_set<int>(nums.begin(), nums.end()).size() < nums.size();
    }
};

// ============================================================
// 【解法对比】
// 
// | 解法       | 时间       | 空间  | 改原数组 | 提前终止 |
// |-----------|-----------|------|---------|---------|
// | 暴力枚举   | O(n²)     | O(1) | 否      | 能      |
// | 排序       | O(n log n)| O(1) | 是      | 能      |
// | 哈希集合   | O(n)      | O(n) | 否      | 能      |
// | 集合大小   | O(n)      | O(n) | 否      | 不能    |
//
// 面试首选解法3（哈希集合）：时间最优，代码简洁，逻辑清晰。
// 如果面试官追问"不用额外空间"→ 给解法2（排序）。
// 
// 【易错点】
// 1. 排序解法循环从 i=0 开始 → nums[i-1] 越界！
//    ✗ for (int i = 0; i < n; i++) if (nums[i] == nums[i-1])
//    ✓ for (int i = 1; i < n; i++) if (nums[i] == nums[i-1])
//
// 2. 哈希解法先 insert 再 count → 自己跟自己比，永远 true！
//    ✗ seen.insert(num); if (seen.count(num)) return true;
//    ✓ if (seen.count(num)) return true; seen.insert(num);
//
// 3. 用 set 代替 unordered_set → O(log n) 查找，总时间退化为 O(n log n)
//    对本题影响不大，但面试时说清楚两者区别是加分项。
//
// 【面试追问】
// Q1: 暴力法时间复杂度多少？能通过 n=10^5 吗？
//     → O(n²) = 10^10，远超 10^8 的通常限制，会超时。
//
// Q2: 如果不允许使用额外空间（O(1) space），怎么做？
//     → 排序后检查相邻元素。O(n log n) 时间，O(1) 空间。
//       代价是修改了原数组。如果也不能改原数组，需要拷贝一份。
//
// Q3: 变体 — 如果要判断"存在 nums[i] == nums[j] 且 |i-j| <= k"？
//     → LeetCode 219。用滑动窗口 + 哈希集合，
//       集合只保留最近 k 个元素，超出窗口的移除。
//
// Q4: 进一步变体 — 存在 |nums[i]-nums[j]| <= t 且 |i-j| <= k？
//     → LeetCode 220。需要有序集合(set) + 滑动窗口，
//       或者桶排序思想，每个桶大小 t+1。
// ============================================================
