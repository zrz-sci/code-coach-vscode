/*
 * 面试题 01.04: 回文排列 (Palindrome Permutation LCCI)
 * 同主站 266. Palindrome Permutation
 *
 * 题意: 判断字符串的某个排列能否构成回文
 * 核心性质: 回文串中, 最多只有一个字符出现奇数次
 *
 * 多种解法:
 * 1. HashMap 频次统计 - 最直观
 * 2. 数组频次统计 - 常数更小
 * 3. 位运算 (bitset) - 最巧妙
 * 4. Set Toggle - 一次遍历
 */

// ============================================================
// 解法一: HashMap 频次统计 (最直观)
// 时间: O(n)  空间: O(k), k为不同字符种类数
// ============================================================
class Solution {
public:
    bool canPermutePalindrome(string s) {
        unordered_map<char, int> freq;

        // 统计每个字符的出现频次
        for (char c : s) {
            freq[c]++;
        }

        // 统计出现奇数次的字符个数
        int oddCount = 0;
        for (auto& [ch, cnt] : freq) {
            if (cnt % 2 != 0) {
                oddCount++;
                // 优化: 提前退出
                if (oddCount > 1) return false;
            }
        }

        // 回文排列: 最多一个字符出现奇数次
        return true; // oddCount <= 1 已由提前退出保证
    }
};

// ============================================================
// 解法二: 数组频次统计 (ASCII 范围, 常数更小)
// 时间: O(n)  空间: O(1) (固定128大小数组)
// ============================================================
class Solution_Array {
public:
    bool canPermutePalindrome(string s) {
        int freq[128] = {0}; // ASCII 字符集

        for (char c : s) {
            freq[(unsigned char)c]++;
        }

        int oddCount = 0;
        for (int i = 0; i < 128; i++) {
            if (freq[i] & 1) { // 等价于 freq[i] % 2 != 0
                oddCount++;
                if (oddCount > 1) return false;
            }
        }

        return true;
    }
};

// ============================================================
// 解法三: 位运算 bitset (最巧妙)
// 时间: O(n)  空间: O(1)
//
// 原理: 对每个字符翻转对应位 (XOR)
// 出现偶数次 → 位回到0; 出现奇数次 → 位为1
// 最终至多一个位为1 → 可构成回文
// ============================================================
class Solution_Bitset {
public:
    bool canPermutePalindrome(string s) {
        bitset<128> bits; // 覆盖所有 ASCII 字符

        for (char c : s) {
            bits.flip(c); // 翻转第 c 位
        }

        // count() 返回为1的位数
        return bits.count() <= 1;
    }
};

// ============================================================
// 解法四: Set Toggle (一次遍历, 思路清晰)
// 时间: O(n)  空间: O(k)
//
// 遇到字符: 不在集合中 → 加入; 已在集合中 → 移除
// 最终集合中剩余的就是出现奇数次的字符
// ============================================================
class Solution_Set {
public:
    bool canPermutePalindrome(string s) {
        unordered_set<char> oddChars;

        for (char c : s) {
            if (oddChars.count(c)) {
                oddChars.erase(c);  // 第偶数次出现 → 移除
            } else {
                oddChars.insert(c); // 第奇数次出现 → 加入
            }
        }

        return oddChars.size() <= 1;
    }
};

// ============================================================
// 解法五: 位运算 (仅限小写字母, 用 int)
// 如果题目保证只有小写字母, 可以用一个 int (32位) 完成
// ============================================================
class Solution_BitInt {
public:
    bool canPermutePalindrome(string s) {
        int bits = 0;

        for (char c : s) {
            // 注意: 如果有非小写字母字符, 需要更大的位宽
            bits ^= (1 << (c - 'a'));
        }

        // 判断至多一个位为1
        // n & (n-1) 消除最低位的1, 如果结果为0说明最多一个1
        return (bits & (bits - 1)) == 0;
    }
};

/*
 * 复杂度分析:
 *
 * 所有解法时间复杂度: O(n), 遍历字符串一次
 *
 * 空间复杂度:
 *   解法1 (HashMap): O(k), k为不同字符数, 最大128
 *   解法2 (数组):    O(1), 固定128大小
 *   解法3 (bitset):  O(1), 固定128位
 *   解法4 (Set):     O(k)
 *   解法5 (int):     O(1), 仅适用于小写字母
 *
 * 关键测试用例:
 *   "tactcoa" → true  (排列 "tacocat" 是回文)
 *   "code"    → false (c:1,o:1,d:1,e:1 四个奇数)
 *   ""        → true  (空串, 0个奇数频次)
 *   "a"       → true  (1个奇数频次)
 *   "aa"      → true  (0个奇数频次)
 *   "ab"      → false (2个奇数频次)
 *   "aab"     → true  (b:1, 放中间)
 *   "  "      → true  (空格出现2次, 偶数)
 *
 * 易错点:
 *   1. 空格也是字符, 不能过滤掉
 *   2. 判断条件是 <= 1 不是 == 1 (偶数长度字符串0个奇数也行)
 *   3. 位运算 int 只有32位, 不够覆盖 ASCII (需128位)
 *   4. (unsigned char)c 防止负值字符导致数组越界
 *
 * 面试技巧:
 *   1. 先说核心性质: "回文最多一个字符奇数次"
 *   2. 给出最简单的HashMap解法
 *   3. 优化: 提到位运算方法展示算法功底
 *   4. Follow-up: 构造所有回文排列 (LC 267, 回溯法)
 *
 * 位运算技巧 n & (n-1):
 *   n     = 01010000
 *   n-1   = 01001111
 *   n&n-1 = 01000000  (消除最低位的1)
 *
 *   如果 n & (n-1) == 0, 说明 n 最多有一个 1
 *   应用: 判断2的幂, 判断至多一个奇数频次字符
 */

// ============================================================
// 【解法对比】
//
// | 解法             | 时间  | 空间  | 优势                           |
// |-----------------|------|------|-------------------------------|
// | HashMap (解法一)  | O(n) | O(k) | 最直观, 面试首选                 |
// | 数组 (解法二)     | O(n) | O(1) | 常数因子小, 适合 ASCII           |
// | bitset (解法三)   | O(n) | O(1) | 最巧妙, 展示位运算功底            |
// | Set Toggle (解法四)| O(n) | O(k) | 一次遍历思路清晰                 |
// | int位运算 (解法五) | O(n) | O(1) | 最紧凑, 仅限小写字母             |
//
// 面试策略: 先写 HashMap 解法, 然后主动提出位运算优化。
// 面试官通常期待从简单到优化的思路递进。
//
// ============================================================
// 【易错点】
//
// 1. 判断条件写成 == 1 而非 <= 1:
//    ✗ return oddCount == 1;  → 偶数长度全配对时 oddCount=0, 误判
//    ✓ return oddCount <= 1;
//
// 2. 忘记空格也算字符:
//    ✗ 过滤掉空格 → "  " 应该返回 true
//    ✓ 空格参与统计
//
// 3. 位运算 int 只有 32 位:
//    ✗ 用 int 存所有 ASCII → 字符值 > 31 时越界
//    ✓ 用 bitset<128> 或 long long (仅限小写字母用 int)
//
// 4. (c - 'a') 对非小写字母字符产生负数:
//    ✗ bits ^= (1 << (c - 'a'));  → 大写或数字会出负偏移
//    ✓ 题目明确字符范围后才能用, 否则用 bitset<128>
//
// ============================================================
// 【面试追问】
//
// Q1: 如果不只判断, 还要构造一个回文排列, 怎么做?
// → LC 267 Palindrome Permutation II
//   统计频次后, 将每个字符取一半做回溯全排列,
//   拼接 "左半 + 中心(如有) + 翻转左半"。
//   注意去重: 排序后跳过重复字符。
//
// Q2: 如果字符串很长 (10^9), 且以流式输入, 怎么优化?
// → 只需维护一个 bitset, 每读一个字符 flip 对应位。
//   读完后 count() <= 1 即可。空间 O(1), 时间 O(n) 一趟扫描,
//   不需要存储整个字符串。
//
// Q3: 如何判断一个字符串的某个子串能否排列成回文?
// → 前缀异或 + 区间查询。预计算 prefix[i] = XOR(s[0..i-1]),
//   则 s[l..r] 的字符奇偶性 = prefix[r+1] ^ prefix[l]。
//   判断该值是否最多一个 bit 为 1: val & (val-1) == 0。
//   单次查询 O(1), 预处理 O(n)。
// ============================================================
