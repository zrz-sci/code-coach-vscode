/*
 * LeetCode 343: Integer Break (整数拆分)
 * 
 * 【题目本质】
 * 把正整数 n 拆成至少 2 个正整数之和，使乘积最大。
 * 本质是一个"最优拆分"问题，每次拆分决策影响后续最优解 → 典型 DP / 数学贪心。
 *
 * 【解法总览】
 * 解法1: 暴力递归          — O(n!) / O(n)  — 最直觉，展示递归结构
 * 解法2: 记忆化搜索        — O(n²) / O(n)  — 从解法1加 memo 优化
 * 解法3: 自底向上 DP       — O(n²) / O(n)  — 面试首选 ⭐
 * 解法4: 数学贪心(拆3策略) — O(1) / O(1)   — 最优，加分项
 */

// ============================================================
// 解法1: 暴力递归 — 枚举所有拆法
// 时间: O(n!) — 每层最多 n-1 个分支，深度不确定
// 空间: O(n) — 递归栈深度
//
// 【思路】
// 最自然的想法: 从 n 中拆出第一个数 j (1 ≤ j < n)，
// 剩余 n-j 有两种选择:
//   1. 不再拆 → 乘积 = j * (n-j)
//   2. 继续拆 → 乘积 = j * integerBreak(n-j)
// 取所有情况的最大值。
//
// 瓶颈: 大量重叠子问题，比如 integerBreak(5) 被不同路径重复计算。
// ============================================================
class Solution1 {
public:
    int integerBreak(int n) {
        int maxProduct = 0;
        for (int j = 1; j < n; j++) {
            // j*(n-j): 只拆两份，剩余部分不再拆
            // j*integerBreak(n-j): 拆出 j 后，剩余继续最优拆分
            maxProduct = max(maxProduct, max(j * (n - j), j * integerBreak(n - j)));
        }
        return maxProduct;
    }
};

// ============================================================
// 解法2: 记忆化搜索 — 自顶向下 DP
// 时间: O(n²) — 每个子问题算一次，每个子问题内层 O(n)
// 空间: O(n) — memo 数组 + 递归栈
//
// 【思路】
// 解法1的瓶颈是重叠子问题。加一个 memo 数组缓存已算过的结果。
// 这是从"暴力递归"到"DP"的自然过渡。
// ============================================================
class Solution2 {
public:
    int integerBreak(int n) {
        vector<int> memo(n + 1, -1);
        return dfs(n, memo);
    }
    
private:
    int dfs(int n, vector<int>& memo) {
        if (memo[n] != -1) return memo[n];
        
        int maxProduct = 0;
        for (int j = 1; j < n; j++) {
            maxProduct = max(maxProduct, max(j * (n - j), j * dfs(n - j, memo)));
        }
        
        memo[n] = maxProduct;
        return maxProduct;
    }
};

// ============================================================
// 解法3: 自底向上 DP — 面试首选 ⭐
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 将记忆化搜索翻译成自底向上的填表。
//
// 状态定义: dp[i] = 将正整数 i 拆成至少2个正整数之和的最大乘积
// 
// 状态转移: dp[i] = max over j in [1, i-1] of { max(j*(i-j), j*dp[i-j]) }
//   - j*(i-j): 只拆两份，i-j 不再拆
//   - j*dp[i-j]: 拆出 j 后，i-j 继续最优拆分
//
// 初始化: dp[2] = 1 (2=1+1, 乘积=1)
//
// DP 填表过程:
//   i:   2  3  4  5  6  7  8  9  10
//   dp:  1  2  4  6  9  12 18 27 36
//
//   dp[4] = max(1×3, 1×dp[3], 2×2, 2×dp[2], 3×1, 3×dp[1])
//         = max(  3,    2,      4,     2,      3,     3   ) = 4
//                              ↑ 来自 j*(i-j), 即 2×2 不再拆
//
//   dp[10] = max(..., 3×7, 3×dp[7], ...) = max(..., 21, 36, ...) = 36
//                          ↑ 来自 3×dp[7]=3×12=36
//
// 填表方向: 从小到大 (dp[i] 依赖 dp[1..i-1])
//   dp[2] → dp[3] → dp[4] → ... → dp[n]
// ============================================================
class Solution3 {
public:
    int integerBreak(int n) {
        vector<int> dp(n + 1, 0);
        dp[2] = 1; // 2 = 1+1, 乘积 = 1 (必须拆)
        
        for (int i = 3; i <= n; i++) {
            for (int j = 1; j < i; j++) {
                // 为什么要取 j*(i-j) 和 j*dp[i-j] 两者的 max?
                // 因为 dp[i-j] 是"i-j 拆分后的最大乘积"
                // 但 i-j 本身不拆可能更大! (如 i-j=3, dp[3]=2, 但 3>2)
                dp[i] = max(dp[i], max(j * (i - j), j * dp[i - j]));
            }
        }
        return dp[n];
    }
};

// ============================================================
// 解法3 优化版: 内层只枚举 j=2 和 j=3
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 数学上可以证明最优拆分因子只有 2 和 3:
//   - 因子 1: 乘1没用，绝不能出现
//   - 因子 ≥5: 一定可以拆得更优 (如 5→2+3, 2×3=6>5)
//   - 因子 4: 拆不拆一样 (4=2+2, 2×2=4)
//   - 因子 3 优于 2: 3+3→9 > 2+2+2→8 (同样的和6)
// 因此 j 只需要枚举 2 和 3。
// ============================================================
class Solution3_Optimized {
public:
    int integerBreak(int n) {
        vector<int> dp(n + 1, 0);
        dp[2] = 1;
        
        for (int i = 3; i <= n; i++) {
            // 只枚举 j=2 和 j=3
            dp[i] = max({
                2 * (i - 2),      // 拆出2, 剩余不拆
                2 * dp[i - 2],    // 拆出2, 剩余继续拆
                3 * (i - 3),      // 拆出3, 剩余不拆 (i>=3 保证 i-3>=0)
                3 * dp[i - 3]     // 拆出3, 剩余继续拆 (i-3=0 时 dp[0]=0 不影响)
            });
        }
        return dp[n];
    }
};

// ============================================================
// 解法4: 数学贪心 — 尽量拆出3
// 时间: O(1)  空间: O(1)
//
// 【思路】
// 完整数学推导:
//   1. 拆分因子不该有 1 (乘1没增益)
//   2. 拆分因子不该 ≥ 5 (5→2+3 更优, 2×3=6>5)
//   3. 因子只能是 2, 3, 4; 但 4=2×2, 所以等价于只用 2 和 3
//   4. 3 比 2 更高效: 用相同的"和"，3 能贡献更多乘积
//      证明: 将 6 分成 3+3 → 9; 分成 2+2+2 → 8; 9 > 8
//   5. 策略: 尽量多拆 3
//
// 处理余数:
//   n % 3 == 0: 全部拆3       → 3^(n/3)
//   n % 3 == 1: 拿回一个3, 和余数1组成4=2×2 → 3^(n/3-1) × 4
//   n % 3 == 2: 多一个2       → 3^(n/3) × 2
//
// 例子:
//   n=10: 10/3=3 余 1 → 3^2 × 4 = 9 × 4 = 36 ✓
//   n=8:  8/3=2  余 2 → 3^2 × 2 = 9 × 2 = 18 ✓  
//   n=9:  9/3=3  余 0 → 3^3 = 27 ✓
//   n=7:  7/3=2  余 1 → 3^1 × 4 = 3 × 4 = 12 ✓
// ============================================================
class Solution4 {
public:
    int integerBreak(int n) {
        // 必须特判: n ≤ 3 时被强制拆成2份，不能整个留着
        if (n == 2) return 1; // 2 = 1+1, 1×1 = 1
        if (n == 3) return 2; // 3 = 1+2, 1×2 = 2
        
        int quotient = n / 3;
        int remainder = n % 3;
        
        if (remainder == 0) {
            return intPow(3, quotient);
        } else if (remainder == 1) {
            // 余1时: 3+1=4, 拆成2+2更优
            // 退回一个3, 换成两个2: 3^(q-1) × 2 × 2 = 3^(q-1) × 4
            return intPow(3, quotient - 1) * 4;
        } else { // remainder == 2
            return intPow(3, quotient) * 2;
        }
    }
    
private:
    // 整数幂, 避免浮点精度问题
    int intPow(int base, int exp) {
        int result = 1;
        while (exp > 0) {
            result *= base;
            exp--;
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间   | 空间  | 适用场景                      |
// |-----------|--------|-------|------------------------------|
// | 暴力递归   | O(n!)  | O(n)  | 理解递归结构                  |
// | 记忆化搜索 | O(n²)  | O(n)  | 递归→DP 的过渡                |
// | 自底向上DP | O(n²)  | O(n)  | 面试首选, 通用性强 ⭐         |
// | DP(j=2,3) | O(n)   | O(n)  | DP + 数学优化                 |
// | 数学贪心   | O(1)   | O(1)  | 最优, 但需要数学证明          |
//
// 面试建议:
// - 先讲 DP 解法(解法3), 展示对"拆/不拆"选择的理解
// - 如果面试官追问优化, 给出 j=2,3 优化或数学解法
// - 数学解法需要能解释"为什么尽量拆3"
//
// 【易错点】
// 1. 漏掉 j*(i-j):
//    ✗ dp[i] = max(dp[i], j * dp[i-j]);
//    ✓ dp[i] = max(dp[i], max(j*(i-j), j*dp[i-j]));
//    原因: dp[i-j] 是"i-j拆分后的最大乘积", 可能 < i-j 本身
//    比如 dp[3]=2 但 3 本身=3>2, dp[4]=4 但 4 本身也=4
//
// 2. dp[2] 初始化为 2 而不是 1:
//    ✗ dp[2] = 2;  // 2 本身是2, 但题目要求必须拆
//    ✓ dp[2] = 1;  // 2 = 1+1, 乘积 = 1
//
// 3. 数学解法忘记特判 n ≤ 3:
//    ✗ n=3 时 3/3=1 余0, pow(3,1)=3, 但答案是 2
//    ✓ 特判 n==2 返回 1, n==3 返回 2
//
// 4. 使用浮点 pow 的精度问题:
//    ✗ return (int)pow(3, q) * 2;  // pow 可能返回 8.9999... 
//    ✓ 使用整数幂函数, 或 round() 后再转 int
//
// 【面试追问】
// Q1(基础): 为什么 dp 转移要同时考虑 j*(i-j) 和 j*dp[i-j]?
//     → 因为 dp[i-j] 是"拆分后的最大乘积", 但 i-j 本身不拆可能更大。
//       例如 i-j=3 时, dp[3]=2, 但 3>2, 不拆更好。
//
// Q2(优化): 能否将 O(n²) DP 优化到 O(n) 或 O(1)?
//     → O(n): 内层只枚举 j=2 和 j=3 (数学证明最优因子只有 2 和 3)
//     → O(1): 直接用数学公式, 根据 n%3 的余数决定策略
//
// Q3(变体): 如果要输出具体的拆分方案呢?
//     → DP: 额外记录 choice[i] = 让 dp[i] 最优的 j, 从 choice[n] 回溯
//     → 数学: 直接构造 — 尽量多个3, 余1换成两个2, 余2多一个2
//
// Q4(扩展): 如果 n 很大(如 10^9), 且要对 10^9+7 取模?
//     → 不能用 DP (n 太大), 只能用数学解法 + 快速幂取模
//     → 这就是剑指 Offer 14-II 的问题
// ============================================================
