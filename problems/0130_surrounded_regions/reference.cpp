/*
 * LeetCode 130: 被围绕的区域 (Surrounded Regions)
 *
 * 【题目本质】
 * 把所有不与边界相连的 'O' 区域翻转成 'X'。
 * 逆向思维：从边界 'O' 出发标记安全区域，剩下的 'O' 就是被围绕的。
 *
 * 【解法总览】
 * 解法1: DFS 边界标记       — O(m×n) / O(m×n) — 最直觉，代码最简洁
 * 解法2: BFS 边界标记       — O(m×n) / O(m×n) — 更稳健，无栈溢出风险
 * 解法3: 并查集(Union-Find) — O(m×n·α) / O(m×n) — 展示并查集应用
 *
 * 【矩阵示意 — 示例1的处理过程】
 *
 *  原始矩阵:          从边界DFS标记:       最终结果:
 *  X X X X            X X X X             X X X X
 *  X O O X      →     X O O X       →     X X X X
 *  X X O X            X X O X             X X X X
 *  X O X X            X # X X             X O X X
 *                       ↑
 *              (3,1)是边界O，标记为#
 *              它没有相邻O可扩展
 *
 *  (1,1)(1,2)(2,2)的O不与边界相连 → 全部变X
 *  (3,1)的# → 恢复为O
 */

// ============================================================
// 解法1: DFS 边界标记
// 时间: O(m×n)  空间: O(m×n) 最坏情况递归栈深度
//
// 【思路】
// 关键洞察：正向判断"是否被围绕"需要搜完整个区域才知道答案，
// 但逆向从边界出发，能确定性地标记所有"安全"的O。
//
// 三步走：
// 1. 扫描四条边界，对每个边界'O'发起DFS
// 2. DFS过程中把所有与边界相连的'O'标记为'#'（安全）
// 3. 最终遍历：'O'→'X'（被围绕）, '#'→'O'（恢复安全区域）
//
// 为什么用'#'而不是visited数组？
// 因为我们本来就要原地修改board，用第三种字符一举两得：
// 既充当visited标记，又区分"安全O"和"被围绕O"。
// ============================================================
class Solution1 {
public:
    void solve(vector<vector<char>>& board) {
        int m = board.size(), n = board[0].size();

        // 第一步：从四条边界的'O'出发DFS标记
        for (int i = 0; i < m; i++) {
            if (board[i][0] == 'O')     dfs(board, i, 0, m, n);     // 左边界
            if (board[i][n-1] == 'O')   dfs(board, i, n - 1, m, n); // 右边界
        }
        for (int j = 0; j < n; j++) {
            if (board[0][j] == 'O')     dfs(board, 0, j, m, n);     // 上边界
            if (board[m-1][j] == 'O')   dfs(board, m - 1, j, m, n); // 下边界
        }

        // 第二步：遍历整个矩阵，执行最终翻转
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (board[i][j] == 'O')       board[i][j] = 'X';  // 没被标记的O = 被围绕
                else if (board[i][j] == '#')   board[i][j] = 'O';  // '#'恢复为安全的O
            }
        }
    }

private:
    void dfs(vector<vector<char>>& board, int i, int j, int m, int n) {
        // 越界检查必须在访问board[i][j]之前（短路求值）
        if (i < 0 || i >= m || j < 0 || j >= n || board[i][j] != 'O') return;

        // 标记为安全（同时充当visited）
        board[i][j] = '#';

        // 四个方向扩展
        dfs(board, i + 1, j, m, n);
        dfs(board, i - 1, j, m, n);
        dfs(board, i, j + 1, m, n);
        dfs(board, i, j - 1, m, n);
    }
};

// ============================================================
// 解法2: BFS 边界标记
// 时间: O(m×n)  空间: O(m×n) 队列最大可能存储整个矩阵的格子
//
// 【思路】
// 与解法1的核心逻辑完全一致，唯一区别是用BFS替代DFS。
//
// 为什么要有这个解法？
// DFS递归在极端情况下（如200×200全是O）递归深度达40000，
// 可能导致栈溢出。BFS用队列，内存在堆上分配，没有这个问题。
//
// BFS关键细节：入队时立即标记为'#'，不是出队时标记！
// 否则同一个格子可能被多个邻居重复入队，浪费时间空间。
//
// 【BFS扩展过程示意（以示例1为例）】
//
// 边界扫描：只有(3,1)是边界上的O → 入队并标记为'#'
// BFS第1轮：弹出(3,1)，检查四邻居(2,1)(3,0)(3,2)均为X → 队列空，结束
//
// 结果：只有(3,1)被标记为'#'
//       (1,1)(1,2)(2,2)仍为O → 全部翻转为X
// ============================================================
class Solution2 {
public:
    void solve(vector<vector<char>>& board) {
        int m = board.size(), n = board[0].size();
        queue<pair<int, int>> q;

        // 第一步：收集所有边界上的'O'作为BFS起点
        for (int i = 0; i < m; i++) {
            if (board[i][0] == 'O')     { board[i][0] = '#'; q.push({i, 0}); }
            if (board[i][n-1] == 'O')   { board[i][n-1] = '#'; q.push({i, n-1}); }
        }
        for (int j = 0; j < n; j++) {
            if (board[0][j] == 'O')     { board[0][j] = '#'; q.push({0, j}); }
            if (board[m-1][j] == 'O')   { board[m-1][j] = '#'; q.push({m-1, j}); }
        }

        // BFS扩展标记所有与边界相连的'O'
        int dx[] = {0, 0, 1, -1};
        int dy[] = {1, -1, 0, 0};
        while (!q.empty()) {
            auto [x, y] = q.front();
            q.pop();
            for (int d = 0; d < 4; d++) {
                int nx = x + dx[d], ny = y + dy[d];
                // 越界检查 + 只处理未标记的'O'
                if (nx >= 0 && nx < m && ny >= 0 && ny < n && board[nx][ny] == 'O') {
                    board[nx][ny] = '#';   // 入队时就标记，防止重复入队
                    q.push({nx, ny});
                }
            }
        }

        // 第二步：统一翻转
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (board[i][j] == 'O')       board[i][j] = 'X';  // 被围绕
                else if (board[i][j] == '#')   board[i][j] = 'O';  // 恢复安全区域
            }
        }
    }
};

// ============================================================
// 解法3: 并查集 (Union-Find)
// 时间: O(m×n·α(m×n)) ≈ O(m×n)  空间: O(m×n)
//
// 【思路】
// 完全不同的视角——不做搜索，而是维护连通性。
//
// 核心设计：
// - 每个格子用 i*n+j 作为编号
// - 创建一个虚拟节点 dummy = m*n，代表"边界安全区"
// - 遍历每个'O'：
//   - 如果在边界上 → 与dummy合并
//   - 与右边和下边的'O' → 互相合并
// - 最后：不与dummy连通的'O' → 翻转为'X'
//
// 为什么只合并右边和下边？
// 因为从左上到右下遍历时，左边和上边的合并已经在之前处理了。
// 两个方向足以覆盖所有相邻关系（无向图边只需遍历一次）。
//
// 虚拟节点dummy的妙处：
// 如果没有dummy，需要记录所有边界O的代表元，然后逐个比较。
// 有了dummy，所有边界O都连到同一个集合，一次find就能判断。
// ============================================================
class Solution3 {
public:
    vector<int> parent, rank_;

    int find(int x) {
        // 路径压缩：递归时将沿途节点直接挂到根上
        if (parent[x] != x) parent[x] = find(parent[x]);
        return parent[x];
    }

    void unite(int x, int y) {
        int px = find(x), py = find(y);
        if (px == py) return;
        // 按秩合并：矮树挂到高树下面，保持树高平衡
        if (rank_[px] < rank_[py]) swap(px, py);
        parent[py] = px;
        if (rank_[px] == rank_[py]) rank_[px]++;
    }

    void solve(vector<vector<char>>& board) {
        int m = board.size(), n = board[0].size();
        int dummy = m * n;  // 虚拟节点编号 = m*n（不和任何真实格子冲突）

        parent.resize(m * n + 1);
        rank_.resize(m * n + 1, 0);
        iota(parent.begin(), parent.end(), 0);  // 初始化：每个节点的父亲是自己

        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (board[i][j] != 'O') continue;

                int id = i * n + j;

                // 边界上的'O' → 与dummy合并，标记为安全
                if (i == 0 || i == m - 1 || j == 0 || j == n - 1) {
                    unite(id, dummy);
                }

                // 与右边的'O'合并
                if (j + 1 < n && board[i][j + 1] == 'O') {
                    unite(id, i * n + j + 1);
                }
                // 与下边的'O'合并
                if (i + 1 < m && board[i + 1][j] == 'O') {
                    unite(id, (i + 1) * n + j);
                }
            }
        }

        // 最终判定：不与dummy连通的'O'就是被围绕的
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (board[i][j] == 'O' && find(i * n + j) != find(dummy)) {
                    board[i][j] = 'X';
                }
            }
        }
    }
};

// ============================================================
// 【解法对比】
//
// DFS vs BFS：
//   - 核心逻辑完全相同（从边界出发标记安全O）
//   - DFS代码更简洁，但有栈溢出风险
//   - BFS更稳健，面试推荐BFS
//
// DFS/BFS vs 并查集：
//   - DFS/BFS是搜索思路：从边界"蔓延"标记
//   - 并查集是连通性思路：维护集合关系，最后查询
//   - 并查集代码更多，但展示了不同的问题建模能力
//   - 如果面试官追问"还有别的方法吗？"，并查集是好答案
//
// 【易错点】
//
// 1. DFS越界检查顺序：
//    ✗ if (board[i][j] != 'O' || i < 0 || ...)  → 越界后访问board[i][j]是UB
//    ✓ if (i < 0 || i >= m || j < 0 || j >= n || board[i][j] != 'O')
//    原因：C++的&&/||是短路求值，越界检查必须放在最前面
//
// 2. BFS标记时机：
//    ✗ 出队时标记 board[x][y] = '#'
//      → 格子(2,3)可能被(1,3)和(2,2)两次入队
//    ✓ 入队时立即标记 board[nx][ny] = '#'
//      → 每个格子最多入队1次，时空复杂度才是O(m×n)
//
// 3. 翻转阶段的逻辑互斥：
//    ✗ 用两个独立的if:
//       if (board[i][j] == '#') board[i][j] = 'O';
//       if (board[i][j] == 'O') board[i][j] = 'X';  // 刚恢复的O又被翻转了！
//    ✓ 用 if-else if 保证互斥，或者先处理O→X再处理#→O
//
// 4. 并查集忘记路径压缩：
//    不加路径压缩，find()最坏O(n)，40000个节点可能TLE
//    加了路径压缩+按秩合并，find()均摊O(α(n))≈O(1)
//
// 5. 并查集中二维坐标转一维编号：
//    ✗ id = i * m + j （用了行数m而不是列数n）
//    ✓ id = i * n + j （乘以列数n才能保证唯一映射）
//
// 【面试追问】
//
// Q1(基础): 为什么从边界出发而不是从内部O出发？
//   → 从内部出发需要搜完整个区域才能判断是否被围绕，
//     如果发现碰到边界还需要撤销标记。
//     从边界出发是确定性的标记，不需要撤销。
//
// Q2(优化): 矩阵非常大时DFS有什么问题？
//   → 递归深度可达m×n，栈溢出。用BFS或显式栈替代。
//
// Q3(变体): 如果改成统计被围绕的O的数量？
//   → 同样的标记方法，最后统计仍为'O'的格子数量即可。
//
// Q4(进阶): 能否用并查集解决？优势是什么？
//   → 可以，见解法3。优势：如果之后有多次动态修改
//     （如新增/删除O），并查集可以增量维护，DFS/BFS需要重新搜索。
//
// 【相关题型】
// - 200. 岛屿数量 — 复用BFS/DFS矩阵遍历框架，
//   区别：200统计所有连通块数量，130区分边界连通块和内部连通块
// - 417. 太平洋大西洋水流问题 — 同样的"从边界反向搜索"逆向思维，
//   区别：417有两组边界分别搜索后取交集
// - 1020. 飞地的数量 — 本题的翻版，
//   区别：1020返回被围绕的陆地数量而非原地修改
// ============================================================
