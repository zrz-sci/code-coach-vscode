-- ============================================================
-- 612. Shortest Distance in a Plane (平面上的最近距离)
-- 难度: Medium | 标签: Database
-- ============================================================

-- ============================================================
-- 解法一: CROSS JOIN + SQRT + MIN (推荐, 最直观)
-- 思路: 枚举所有不同点对, 算欧几里得距离, 取最小值
--   距离 = SQRT((x2-x1)^2 + (y2-y1)^2)
-- 排除自身配对: (p1.x, p1.y) != (p2.x, p2.y)
-- 时间复杂度: O(n^2)  空间: O(1)
-- ============================================================
SELECT
    ROUND(
        MIN(SQRT(POW(p1.x - p2.x, 2) + POW(p1.y - p2.y, 2))),
        2
    ) AS shortest
FROM Point2D p1
CROSS JOIN Point2D p2
WHERE (p1.x, p1.y) != (p2.x, p2.y);

-- ============================================================
-- 解法二: 先比较距离平方, 最后开方 (性能优化)
-- 思路: SQRT 是单调递增函数
--   MIN(SQRT(d)) = SQRT(MIN(d))
--   这样只做 1 次 SQRT 而非 n^2 次
-- 时间复杂度: O(n^2) 但常数项更小
-- ============================================================
SELECT
    ROUND(
        SQRT(
            MIN(POW(p1.x - p2.x, 2) + POW(p1.y - p2.y, 2))
        ),
        2
    ) AS shortest
FROM Point2D p1
CROSS JOIN Point2D p2
WHERE (p1.x, p1.y) != (p2.x, p2.y);

-- ============================================================
-- 解法三: 元组比较避免重复 (计算量减半)
-- 思路: 用 (x1,y1) < (x2,y2) 字典序比较, 每对只算一次
--   C(n,2) 对 而非 n^2 - n 对
-- 时间复杂度: O(n^2) 但实际减半
-- ============================================================
SELECT
    ROUND(
        SQRT(
            MIN(POW(p1.x - p2.x, 2) + POW(p1.y - p2.y, 2))
        ),
        2
    ) AS shortest
FROM Point2D p1
JOIN Point2D p2
    ON (p1.x, p1.y) < (p2.x, p2.y);

-- ============================================================
-- 解法四: 使用乘法替代 POW 函数 (兼容性更好)
-- 思路: (x2-x1)*(x2-x1) 替代 POW(x2-x1, 2)
--   某些数据库不支持 POW, 乘法更通用
-- ============================================================
SELECT
    ROUND(
        SQRT(
            MIN(
                (p1.x - p2.x) * (p1.x - p2.x)
                + (p1.y - p2.y) * (p1.y - p2.y)
            )
        ),
        2
    ) AS shortest
FROM Point2D p1, Point2D p2
WHERE p1.x != p2.x OR p1.y != p2.y;
