/*
 * LCR 185: 统计结果概率 (n个骰子的点数)
 *
 * 【题目本质】
 * n 个骰子, 求所有可能总和的概率分布。
 * 经典 DP: 逐个骰子累加概率, 每增加一个骰子从旧概率转移到新概率。
 *
 * 【解法总览】
 * 解法1: DP + 滚动数组 — O(n^2) / O(n) — 面试首选 ⭐
 * 解法2: DP + 二维数组 — O(n^2) / O(n^2) — 清晰易懂
 * 解法3: DP + 逆向填表 — O(n^2) / O(n) — 另一种思路
 */


// ============================================================
// 解法1: DP + 滚动数组 — 面试首选 ⭐
// 时间: O(n * 5n * 6) = O(30n^2) = O(n^2)
// 空间: O(5n) = O(n) (只保留当前轮的概率数组)
//
// 【状态定义】
// dp[j] = 当前骰子数下, 总和为 (j + 当前骰子数) 的概率
// 使用 0-indexed: dp[0] 对应最小总和, dp[5*i] 对应最大总和
//
// 【初始化 — 1个骰子】
// dp = [1/6, 1/6, 1/6, 1/6, 1/6, 1/6]
// dp[0]=1/6 对应总和1, dp[5]=1/6 对应总和6
//
// 【状态转移 — 从 i-1 个骰子到 i 个骰子】
// 对于旧 dp 中的每个状态 j (概率 dp[j]):
//   新骰子出 1-6, 偏移 0-5:
//   tmp[j+0] += dp[j] / 6.0  (新骰子出1)
//   tmp[j+1] += dp[j] / 6.0  (新骰子出2)
//   tmp[j+2] += dp[j] / 6.0  (新骰子出3)
//   tmp[j+3] += dp[j] / 6.0  (新骰子出4)
//   tmp[j+4] += dp[j] / 6.0  (新骰子出5)
//   tmp[j+5] += dp[j] / 6.0  (新骰子出6)
//
// 骰子概率表 (DP 转移过程):
//
// === 1个骰子 ===
// 总和:  1      2      3      4      5      6
// 概率: 1/6    1/6    1/6    1/6    1/6    1/6
//
// === 从1个到2个 ===
// dp[0]=1/6 → tmp[0..5] 各 += 1/36
// dp[1]=1/6 → tmp[1..6] 各 += 1/36
// dp[2]=1/6 → tmp[2..7] 各 += 1/36
// dp[3]=1/6 → tmp[3..8] 各 += 1/36
// dp[4]=1/6 → tmp[4..9] 各 += 1/36
// dp[5]=1/6 → tmp[5..10] 各 += 1/36
//
// 结果 tmp:
// 总和:  2      3      4      5      6      7
// 概率: 1/36   2/36   3/36   4/36   5/36   6/36
// 总和:  8      9     10     11     12
// 概率: 5/36   4/36   3/36   2/36   1/36
//
// === 从2个到3个 (题目示例 num=3) ===
// 总和:  3       4       5       6       7       8
// 概率: 1/216   3/216   6/216  10/216  15/216  21/216
// 总和:  9      10      11      12      13      14
// 概率: 25/216  27/216  27/216  25/216  21/216  15/216
// 总和: 15      16      17      18
// 概率: 10/216  6/216   3/216   1/216
//
// 概率分布关于 3.5n 对称 (骰子面值关于 3.5 对称)
// ============================================================
class Solution1 {
public:
    vector<double> statisticsProbability(int num) {
        // 初始化: 1个骰子, 6面各 1/6
        vector<double> dp(6, 1.0 / 6.0);

        // 逐个增加骰子 (从第2个到第num个)
        for (int i = 2; i <= num; i++) {
            // i 个骰子: 总和范围 [i, 6i], 共 5i+1 个值
            vector<double> tmp(5 * i + 1, 0.0);

            // 对旧 dp 中的每个状态
            for (int j = 0; j < (int)dp.size(); j++) {
                // 新骰子出 1-6 (偏移 0-5)
                for (int k = 0; k < 6; k++) {
                    tmp[j + k] += dp[j] / 6.0;
                }
            }

            dp = tmp; // 滚动替换
        }

        return dp;
    }
};

// ============================================================
// 解法2: DP + 二维数组 — 清晰易懂
// 时间: O(n^2)  空间: O(n^2)
//
// 【思路】
// 显式保留每个阶段的 dp 数组, 方便调试和理解。
// dp[i][j] = i 个骰子总和为 (j + i) 的概率。
//
// 与解法1 逻辑完全一致, 只是不做空间优化。
// 好处: 可以回溯查看任意阶段的概率分布。
// ============================================================
class Solution2 {
public:
    vector<double> statisticsProbability(int num) {
        // dp[i] = 第 i 个骰子的概率数组
        vector<vector<double>> dp(num + 1);

        // 基础: 1个骰子
        dp[1].assign(6, 1.0 / 6.0);

        // 递推: 从第2个骰子到第num个
        for (int i = 2; i <= num; i++) {
            dp[i].assign(5 * i + 1, 0.0);

            for (int j = 0; j < (int)dp[i - 1].size(); j++) {
                for (int k = 0; k < 6; k++) {
                    dp[i][j + k] += dp[i - 1][j] / 6.0;
                }
            }
        }

        return dp[num];
    }
};

// ============================================================
// 解法3: DP + 逆向填表 — 另一种思路
// 时间: O(n^2)  空间: O(n)
//
// 【思路】
// 解法1 是"正向推": 对旧 dp 的每个状态, 向新数组散播贡献。
// 解法3 是"逆向拉": 对新数组的每个状态 j, 从旧 dp 中拉取贡献。
//
// tmp[j] = sum(dp[j-k] / 6.0) for k = 0..5, 且 j-k 在合法范围内
//
// 两种思路的结果完全一致, 只是遍历方向不同。
// 正向推更直观 (推荐), 逆向拉在某些问题中更方便加约束。
// ============================================================
class Solution3 {
public:
    vector<double> statisticsProbability(int num) {
        vector<double> dp(6, 1.0 / 6.0);

        for (int i = 2; i <= num; i++) {
            int newSize = 5 * i + 1;
            vector<double> tmp(newSize, 0.0);

            // 对新数组的每个位置, 从旧数组拉取
            for (int j = 0; j < newSize; j++) {
                for (int k = 0; k < 6; k++) {
                    int prev = j - k;
                    // prev 必须在旧 dp 的合法范围内
                    if (prev >= 0 && prev < (int)dp.size()) {
                        tmp[j] += dp[prev] / 6.0;
                    }
                }
            }

            dp = tmp;
        }

        return dp;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法      | 填表方向 | 时间  | 空间   | 推荐       |
// |-----------|---------|-------|--------|-----------|
// | 滚动(正推) | 正向推  | O(n²) | O(n)  | 面试首选 ⭐|
// | 二维(正推) | 正向推  | O(n²) | O(n²) | 理解用     |
// | 滚动(逆拉) | 逆向拉  | O(n²) | O(n)  | 变体       |
//
// ============================================================
// 【DP 空间优化总结】
//
// 从二维到一维 (滚动数组):
// - 原始: dp[i][j], 依赖 dp[i-1][...]
// - 因为第 i 轮只依赖第 i-1 轮, 不需要更早的数据
// - 所以只保留两个数组 (dp 和 tmp), 每轮交替使用
// - 本题更简洁: 每轮创建 tmp, 结束后 dp = tmp
//
// 为什么不能在 dp 上原地修改?
// - 正向推时, dp[j] 的值在 j 被处理后仍被后续 j+k 使用
// - 如果覆盖了 dp[j], 后续使用的就是被污染的值
// - 所以必须用单独的 tmp 数组
//
// ============================================================
// 【易错点】
//
// 1. 在旧数组上原地修改:
//    ✗ for(j) for(k) dp[j+k] += dp[j]/6.0;  // dp[j]被覆盖!
//    ✓ 必须用新数组 tmp, 转移完后 dp = tmp
//
// 2. 新数组大小错误:
//    ✗ tmp 大小 = 6*i  (总和最大是 6i, 但最小是 i, 所以只需 5i+1)
//    ✗ tmp 大小 = 5*i  (少1, 数组越界)
//    ✓ tmp 大小 = 5*i + 1
//
// 3. 初始化用整数除法:
//    ✗ dp(6, 1/6)      // 整数除法 = 0!
//    ✓ dp(6, 1.0/6.0)  // 浮点除法 ≈ 0.1667
//
// 4. 转移公式中 k 的范围:
//    ✗ for(k=1; k<=6; k++) tmp[j+k] += ...  // 偏移了1
//    ✓ for(k=0; k<6; k++) tmp[j+k] += ...
//    因为 0-indexed 下 dp[0] 对应最小总和,
//    新骰子出1对应偏移0, 出6对应偏移5
//
// ============================================================
// 【面试追问】(递进链)
//
// Q1: "时间复杂度为什么是 O(n^2)?"
//     外层 n 轮 (骰子数), 内层 O(5n) (dp 数组大小),
//     最内层 6 次 (常数)。总计 n * 5n * 6 = 30n² = O(n²)。
//
// Q2: "概率分布为什么对称?"
//     骰子面值 {1,2,3,4,5,6} 关于 3.5 对称。
//     P(总和=s) = P(总和=7n-s)。
//     因为把每个骰子的值 x 替换为 7-x,
//     总和从 s 变为 7n-s, 但概率不变 (每面等概)。
//
// Q3: "如果骰子不是6面而是k面?"
//     把6替换为k: 初始 dp 大小 k, 概率 1.0/k,
//     tmp 大小 (k-1)*i+1, 内层循环 k 次。
//
// Q4: "能不能用数学公式直接算?"
//     可以, 但更复杂。n个骰子总和为s的方案数:
//     f(n,s) = Σ(-1)^j * C(n,j) * C(s-6j-1, n-1)
//     其中 j 从 0 到 floor((s-n)/6)。
//     这是容斥原理, 但实现比 DP 更容易出错。
//
// Q5: "这个DP和'爬楼梯'有什么关系?"
//     爬楼梯: 每步走 1 或 2 → dp[j] = dp[j-1] + dp[j-2]
//     骰子: 每步走 1-6 → dp[j] = Σdp[j-k] for k=1..6
//     本质相同: 有限选择的路径计数/概率问题。
//
// ============================================================
