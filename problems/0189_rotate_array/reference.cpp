/*
 * LeetCode 189: 轮转数组 (Rotate Array)
 *
 * 【题目本质】
 * 把数组的后 k 个元素搬到前面来，要求原地 O(1) 空间。
 *
 * 【解法总览】
 * 解法1: 暴力模拟      — O(n×k) / O(1) — 最直觉但会 TLE
 * 解法2: 额外数组      — O(n) / O(n)   — 直接计算目标位置
 * 解法3: 三次翻转法    — O(n) / O(1)   — 面试首选 ⭐
 * 解法4: 环状替换      — O(n) / O(1)   — 数学思维，加分项
 */

// ============================================================
// 解法1: 暴力模拟 — 每次右移一步，重复 k 次
// 时间: O(n×k)  空间: O(1)
//
// 【思路】
// 最朴素的理解：右轮转 1 步 = 把末尾元素放到开头，其余后移。
// 重复 k 次即可。瓶颈：每次移动 O(n)，做 k 次就是 O(n×k)。
// 当 n=10⁵, k=10⁵ 时约 10¹⁰ 次操作，会超时。
//
// 过程示意 (nums=[1,2,3,4,5,6,7], k=3):
// Step1: 取出7, 全部右移 → [7,1,2,3,4,5,6]
// Step2: 取出6, 全部右移 → [6,7,1,2,3,4,5]
// Step3: 取出5, 全部右移 → [5,6,7,1,2,3,4] ✓
// ============================================================
class Solution1 {
public:
    void rotate(vector<int>& nums, int k) {
        int n = nums.size();
        k %= n; // k >= n 时取模，轮转 n 次等于不转
        for (int step = 0; step < k; step++) {
            int last = nums[n - 1];
            // 从后往前移，避免覆盖（不能从前往后！）
            for (int i = n - 1; i > 0; i--) {
                nums[i] = nums[i - 1];
            }
            nums[0] = last;
        }
    }
};

// ============================================================
// 解法2: 额外数组 — 直接计算每个元素的目标位置
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 每个元素 nums[i] 轮转后的位置是 (i + k) % n，
// 直接算出来放到新数组对应位置即可。
// 缺点：需要 O(n) 额外空间，不满足进阶要求。
//
// 位置映射示意 (n=7, k=3):
// i=0 → (0+3)%7=3    i=1 → 4    i=2 → 5    i=3 → 6
// i=4 → (4+3)%7=0    i=5 → 1    i=6 → 2
//
// 原数组:  [1, 2, 3, 4, 5, 6, 7]
// 新数组:  [5, 6, 7, 1, 2, 3, 4]  ← 位置0放的是i=4的元素(5)
// ============================================================
class Solution2 {
public:
    void rotate(vector<int>& nums, int k) {
        int n = nums.size();
        k %= n;
        vector<int> temp(n);
        for (int i = 0; i < n; i++) {
            // 元素 i 的新位置 = (i + k) % n
            temp[(i + k) % n] = nums[i];
        }
        nums = temp;
    }
};

// ============================================================
// 解法3: 三次翻转法 — O(n) / O(1) ⭐ 面试首选
//
// 【思路】
// 核心观察：轮转 k 步的结果 = [后k个元素 | 前n-k个元素]
// 即把 [A | B] 变成 [B | A]。
//
// 怎么原地交换两段？三次翻转！
// 设 A = nums[0..n-k-1], B = nums[n-k..n-1]
//
// 数学证明:
//   原始:    [A | B]
//   全翻:    [B^r | A^r]    (翻转整体 = 反转拼接顺序 + 各段反转)
//   前k翻:   [B | A^r]      (B^r 翻回来)
//   后n-k翻: [B | A]        (A^r 翻回来)
//
// 具体过程 (nums=[1,2,3,4,5,6,7], k=3):
//   原数组:     [1, 2, 3, 4 | 5, 6, 7]
//                  A(n-k=4个)  B(k=3个)
//
//   Step1 全翻:  [7, 6, 5, 4, 3, 2, 1]
//                 ←————————————————→
//   Step2 前k翻: [5, 6, 7, 4, 3, 2, 1]
//                 ←——→
//   Step3 后翻:  [5, 6, 7, 1, 2, 3, 4]  ✓
//                          ←———————→
// ============================================================
class Solution3 {
public:
    void rotate(vector<int>& nums, int k) {
        int n = nums.size();
        k %= n; // 必须先取模！否则 begin()+k 可能越界
        if (k == 0) return;
        
        // 三次翻转，每次 O(n)，总共 O(n)
        reverse(nums.begin(), nums.end());        // 全翻
        reverse(nums.begin(), nums.begin() + k);  // 翻前 k 个 [0, k)
        reverse(nums.begin() + k, nums.end());    // 翻后 n-k 个 [k, n)
    }
};

// 手写 reverse 版本（面试官可能要求）
class Solution3_Manual {
public:
    void rotate(vector<int>& nums, int k) {
        int n = nums.size();
        k %= n;
        if (k == 0) return;
        
        // lambda: 翻转闭区间 [left, right]
        auto rev = [&](int left, int right) {
            while (left < right) {
                swap(nums[left++], nums[right--]);
            }
        };
        
        rev(0, n - 1);   // 全翻: 闭区间 [0, n-1]
        rev(0, k - 1);   // 前k: 闭区间 [0, k-1]  ← 注意是 k-1 不是 k!
        rev(k, n - 1);   // 后n-k: 闭区间 [k, n-1]
    }
};

// ============================================================
// 解法4: 环状替换 — O(n) / O(1)
//
// 【思路】
// 直接把每个元素送到目标位置 (i+k)%n。
// 被覆盖的元素不会丢失——它继续往下个位置放，形成一条"环"。
//
// 关键问题：一条环可能不覆盖所有元素！
// 环的数量 = gcd(n, k)，每条环长 = n / gcd(n, k)
//
// 示意 (nums=[1,2,3,4,5,6], k=2, n=6, gcd=2):
//
// 环1 (从 i=0 出发):
//   0 →(+2) 2 →(+2) 4 →(+2) 0  (回到起点，环结束)
//   移动: 1→pos2, 3→pos4, 5→pos0
//   结果: [5, 2, 1, 4, 3, 6]
//
// 环2 (从 i=1 出发):
//   1 →(+2) 3 →(+2) 5 →(+2) 1  (回到起点)
//   移动: 2→pos3, 4→pos5, 6→pos1
//   结果: [5, 6, 1, 2, 3, 4]  ✓
//
// 一共 gcd(6,2)=2 条环，每条 3 个元素，共搬 6 个 = n
// ============================================================
class Solution4 {
public:
    void rotate(vector<int>& nums, int k) {
        int n = nums.size();
        k %= n;
        if (k == 0) return;
        
        int count = 0; // 已归位的元素总数
        // 外层循环：每次开启一条新的环
        for (int start = 0; count < n; start++) {
            int cur = start;
            int prev_val = nums[start]; // 手里"拿着"的值
            
            // do-while: 沿环移动，直到回到起点
            // 不能用 while，因为初始 cur == start 会直接退出
            do {
                int next = (cur + k) % n;   // 目标位置
                int temp = nums[next];       // 先保存目标位置的值
                nums[next] = prev_val;       // 把手里的值放入
                prev_val = temp;             // 被覆盖的值成为手里新拿的值
                cur = next;                  // 移动到目标位置
                count++;                     // 又一个元素归位
            } while (cur != start);          // 回到环的起点 → 这条环结束
        }
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间    | 空间 | 特点                    |
// |-----------|---------|------|------------------------|
// | 暴力模拟   | O(n×k)  | O(1) | 直觉简单但会超时         |
// | 额外数组   | O(n)    | O(n) | 简单正确但不满足进阶要求   |
// | 三次翻转⭐ | O(n)    | O(1) | 代码最短，面试首选        |
// | 环状替换   | O(n)    | O(1) | 数学思维强，加分项        |
//
// 面试推荐路线:
// 1. 先提暴力 → 2. 额外数组确保正确 → 3. 三次翻转优化空间 → 4. 追问时讲环状替换
//
// 【易错点】
// 1. 忘记 k %= n:
//    ✗ 直接用 k → k=10, n=7 时 begin()+k 越界
//    ✓ k %= n; 放在最前面
//
// 2. 手写 reverse 闭区间边界:
//    ✗ rev(0, k) → 多翻了位置 k 的元素
//    ✓ rev(0, k-1) → 闭区间 [0, k-1]
//
// 3. 环状替换用 while 而非 do-while:
//    ✗ while (cur != start) { ... } → 循环体一次都不执行
//    ✓ do { ... } while (cur != start); → 至少执行一次
//
// 4. k==0 不特判:
//    三次翻转法不受影响（翻0个等于不翻），但环状替换会死循环
//    ✓ if (k == 0) return;
//
// 【面试追问】
// Q1: 暴力解能过吗？→ O(n×k) 最坏 10^10，不能过。
// Q2: 用额外数组后，能否优化到 O(1) 空间？
//     → 三次翻转法。全翻 + 前k翻 + 后n-k翻。
// Q3: 为什么三次翻转正确？
//     → [A|B] 全翻得 [B^r|A^r]，分别翻回得 [B|A]。
// Q4: 左旋 k 步怎么做？
//     → 左旋 k = 右旋 n-k。或翻转顺序改为：前k翻 → 后n-k翻 → 全翻。
// Q5: 环状替换有几条环？
//     → gcd(n,k) 条，每条长 n/gcd(n,k)，总共恰好 n 次移动。
// ============================================================
