/*
 * LCR 126. 斐波那契数
 * 难度: Easy
 * 标签: Memoization, Math, Dynamic Programming
 *
 * 题目:
 *   F(0)=0, F(1)=1, F(n)=F(n-1)+F(n-2) (n>1)
 *   给定 n，求 F(n) mod 1000000007。
 *   0 <= n <= 100
 *
 * 核心思路:
 *   经典DP入门题。递推关系 F(n) = F(n-1) + F(n-2)，
 *   关键在于每步取模防止溢出，以及空间优化到 O(1)。
 *
 * 解法概览:
 *   解法1 - 记忆化递归: O(n) 时间, O(n) 空间，自顶向下
 *   解法2 - 迭代DP+空间优化 ⭐: O(n) 时间, O(1) 空间，面试首选
 *   解法3 - 矩阵快速幂: O(log n) 时间, O(1) 空间，进阶
 */

// ============================================================
// 解法 1: 记忆化递归（自顶向下）
// ============================================================
// 思路: 按定义递归，用 memo 数组消除重叠子问题
// 时间: O(n)  空间: O(n)
//
// 思考过程:
//   1. 直接递归有 O(2^n) 重复计算
//   2. 用 memo[] 缓存已算过的值，每个子问题只算一次
//   3. 加法时取模，防止溢出
class Solution1 {
public:
    static const int MOD = 1000000007;
    int memo[101];

    int fib(int n) {
        memset(memo, -1, sizeof(memo));
        return helper(n);
    }

    int helper(int n) {
        if (n <= 1) return n;                    // base case
        if (memo[n] != -1) return memo[n];       // 已缓存，直接返回
        // 递归计算，注意 long long 避免加法溢出
        memo[n] = ((long long)helper(n - 1) + helper(n - 2)) % MOD;
        return memo[n];
    }
    // 关键点:
    //   - memset(memo, -1, ...) 对 int 数组有效（-1 的每个字节都是 0xFF）
    //   - 递归深度最大 100，不会栈溢出
    //   - (long long) 强转防止两个 int 相加超 INT_MAX
};

// ============================================================
// 解法 2: 迭代 DP + 空间优化（推荐）⭐
// ============================================================
// 思路: F(i) 只依赖前两项，用两个滚动变量代替数组
// 时间: O(n)  空间: O(1)
//
// DP 表模拟 (n=6):
//   i:    0  1  2  3  4  5  6
//   F(i): 0  1  1  2  3  5  8
//
//   滚动过程:
//   初始:      a=0, b=1
//   i=2: sum=1, a=1, b=1  -> F(2)=1
//   i=3: sum=2, a=1, b=2  -> F(3)=2
//   i=4: sum=3, a=2, b=3  -> F(4)=3
//   i=5: sum=5, a=3, b=5  -> F(5)=5
//   i=6: sum=8, a=5, b=8  -> F(6)=8
//
// 空间优化原理:
//   dp[i] 只依赖 dp[i-1] 和 dp[i-2]
//   -> 不需要存整个数组，两个变量交替滚动即可
class Solution2 {
public:
    int fib(int n) {
        if (n <= 1) return n;                    // 边界: F(0)=0, F(1)=1
        const int MOD = 1000000007;
        int a = 0, b = 1;                        // a=F(i-2), b=F(i-1)
        for (int i = 2; i <= n; i++) {
            int sum = (a + b) % MOD;             // F(i) = F(i-1) + F(i-2)
            a = b;                                // 滚动: a 前移
            b = sum;                              // 滚动: b 前移
        }
        return b;                                 // b = F(n)
    }
    // 关键点:
    //   - 必须用临时变量 sum，否则 a 被覆盖后 b 算错
    //   - (a + b) 最大约 2e9，不溢出 int
    //   - 这个滚动模式可复用于所有"只依赖前 k 项"的 DP
};

// ============================================================
// 解法 3: 矩阵快速幂
// ============================================================
// 思路: 利用矩阵表示递推: [F(n+1), F(n)] = [[1,1],[1,0]]^n * [1, 0]
//       用快速幂在 O(log n) 时间算出矩阵的 n 次方
// 时间: O(log n)  空间: O(1) (矩阵大小固定 2x2)
//
// 思考过程:
//   1. 递推关系 F(n) = F(n-1) + F(n-2) 可写成矩阵形式
//   2. |F(n+1)|   |1 1|   |F(n)  |
//      |F(n)  | = |1 0| * |F(n-1)|
//   3. 因此 |F(n)| = M^(n-1) * |F(1)| , 其中 M = [[1,1],[1,0]]
//              F(n) = M^(n-1)[0][0]
//   4. 快速幂: M^n = (M^(n/2))^2, O(log n) 次矩阵乘法
class Solution3 {
public:
    static const int MOD = 1000000007;

    // 2x2 矩阵乘法
    vector<vector<long long>> multiply(vector<vector<long long>>& A,
                                       vector<vector<long long>>& B) {
        int sz = A.size();
        vector<vector<long long>> C(sz, vector<long long>(sz, 0));
        for (int i = 0; i < sz; i++)
            for (int j = 0; j < sz; j++)
                for (int k = 0; k < sz; k++)
                    C[i][j] = (C[i][j] + A[i][k] * B[k][j]) % MOD;
        return C;
    }

    // 矩阵快速幂: 求 M^p
    vector<vector<long long>> matPow(vector<vector<long long>>& M, int p) {
        int sz = M.size();
        // 初始化为单位矩阵（矩阵的"1"）
        vector<vector<long long>> result(sz, vector<long long>(sz, 0));
        for (int i = 0; i < sz; i++) result[i][i] = 1;

        while (p > 0) {
            if (p & 1) result = multiply(result, M); // 奇数: 乘一次 M
            M = multiply(M, M);                       // M 自乘
            p >>= 1;                                  // p 减半
        }
        return result;
    }

    int fib(int n) {
        if (n <= 1) return n;
        vector<vector<long long>> M = {{1, 1}, {1, 0}};
        auto result = matPow(M, n - 1);
        return result[0][0];                          // F(n) = M^(n-1)[0][0]
    }
    // 关键点:
    //   - 矩阵乘法中必须用 long long（两个 < MOD 的数相乘可达 ~10^18）
    //   - 快速幂 O(log n) 次 2x2 矩阵乘法，每次乘法 O(8) 常数
    //   - 当 n 可达 10^18 时，这是唯一可行的方法
};

/*
 * ============================================================
 * 解法对比
 * ============================================================
 * | 维度       | 解法1 记忆化    | 解法2 迭代优化 ⭐ | 解法3 矩阵快速幂 |
 * |-----------|----------------|-------------------|-----------------|
 * | 时间       | O(n)           | O(n)              | O(log n)        |
 * | 空间       | O(n)           | O(1)              | O(1)            |
 * | 代码量     | 中等            | 最少              | 较多             |
 * | 面试推荐   | 思路过渡        | 首选              | 加分项           |
 *
 * ============================================================
 * 易错点
 * ============================================================
 * 1. 忘记每步取模 -> n=100 时溢出
 *    错: b = a + b;
 *    对: b = (a + b) % MOD;
 *
 * 2. 滚动变量更新顺序错误
 *    错: a = b; b = a + b;  // a 已被覆盖!
 *    对: sum = (a+b)%MOD; a = b; b = sum;
 *
 * 3. 边界遗漏 n=0 -> 没有 if(n<=1) return n 时返回错误值
 *
 * 4. 矩阵乘法中忘记用 long long
 *    -> A[i][k]*B[k][j] 两个 <10^9 的数相乘溢出 int
 *
 * ============================================================
 * 面试追问
 * ============================================================
 * Q1: 不取模时 long long 最大支持到 F(?) ?
 * A1: F(92)=7540113804746346429, F(93) 溢出 long long。
 *
 * Q2: n 可达 10^18 怎么办?
 * A2: 矩阵快速幂 O(log n)。
 *
 * Q3: 和爬楼梯的关系? 推广到一次走 1~k 步?
 * A3: 爬楼梯 = 斐波那契。k 步时用 k*k 矩阵快速幂 O(k^3 log n)，
 *     或滑动窗口+前缀和 O(n)。
 */
