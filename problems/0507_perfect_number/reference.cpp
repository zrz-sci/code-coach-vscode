/*
 * 【题目本质】
 * 数论判断：num 是否等于其所有真因子之和。
 * 核心优化：因子成对出现，只需枚举到 sqrt(num)。
 *
 * 【解法总览】
 * 解法1: 枚举因子到 sqrt(n)     O(sqrt(n)) / O(1)  ⭐推荐
 * 解法2: 欧几里得-欧拉定理      O(1) / O(1)        数学特解
 */

// ===================== 解法1: 枚举因子 =====================
// 思路：从 2 到 sqrt(num) 枚举因子，累加因子对，检查和 == num
class Solution1 {
public:
    bool checkPerfectNumber(int num) {
        if (num <= 1) return false;

        int sum = 1; // 1 是所有 >1 数的因子
        for (int i = 2; i * i <= num; i++) {
            if (num % i == 0) {
                sum += i;
                if (i != num / i) { // 避免完全平方时重复加
                    sum += num / i;
                }
            }
        }

        return sum == num;
    }
};

// ===================== 解法2: 欧几里得-欧拉定理 =====================
// 思路：所有偶完美数 = 2^(p-1) * (2^p - 1)，其中 2^p-1 是梅森素数
// 10^8 范围内只有 5 个完美数，直接穷举
class Solution2 {
public:
    bool checkPerfectNumber(int num) {
        // p=2: 6, p=3: 28, p=5: 496, p=7: 8128, p=13: 33550336
        return num == 6 || num == 28 || num == 496 ||
               num == 8128 || num == 33550336;
    }
};

/*
 * 【解法对比】
 * 解法1（因子枚举）：通用方法，适用于任意类似问题，O(sqrt(n))
 * 解法2（数学公式）：利用数论结论直接判断，O(1) 但不够通用
 * 面试推荐解法1，展示算法能力；提及解法2体现数学功底
 *
 * 【易错点】
 * 1. num=1 不是完美数（真因子和为 0），必须特判
 * 2. i 从 2 开始枚举，不能从 1（否则 num/1=num 会被错误加入）
 * 3. 完全平方时 i == num/i，不能加两次
 * 4. sum 初始为 1（因子 1 提前计入），而非 0
 *
 * 【面试追问】
 * Q1: 为何只枚举到 sqrt(n) → 因子成对：i 和 num/i 同时找到
 * Q2: 是否存在奇完美数 → 数论未解问题，至今未发现
 * Q3: 找范围内所有完美数 → 检查梅森素数 2^p-1（Lucas-Lehmer 测试）
 */
