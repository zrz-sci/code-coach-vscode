/*
 * LeetCode 454: 四数相加 II (4Sum II)
 *
 * 【题目本质】
 * 从四个独立数组各选一个元素，使四数之和为 0，求合法四元组的数量。
 * 本质是 Two Sum 的扩展：把 a+b+c+d=0 拆成 (a+b) = -(c+d)，
 * 用哈希表存一半的和，查另一半的互补值。
 *
 * 【解法总览】
 * 解法1: 暴力四重循环      — O(n⁴) / O(1)   — 理解题意
 * 解法2: 2+2 分组哈希表    — O(n²) / O(n²)  — ⭐ 面试首选
 * 解法3: 1+3 分组哈希表    — O(n³) / O(n)   — 过渡理解
 */

// ============================================================
// 解法1: 暴力四重循环 — 枚举所有四元组
// 时间: O(n⁴)  空间: O(1)
//
// 【思路】
// 最直觉的做法：四层嵌套循环枚举 (i,j,k,l)，判断四数之和是否为0。
// n=200 时约 1.6×10⁹ 次运算，会超时。
// 但它帮助我们看清瓶颈：四层循环太多了，能否减少？
// ============================================================
class Solution1 {
public:
    int fourSumCount(vector<int>& nums1, vector<int>& nums2,
                     vector<int>& nums3, vector<int>& nums4) {
        int n = nums1.size();
        int count = 0;
        for (int i = 0; i < n; i++)
            for (int j = 0; j < n; j++)
                for (int k = 0; k < n; k++)
                    for (int l = 0; l < n; l++)
                        if (nums1[i] + nums2[j] + nums3[k] + nums4[l] == 0)
                            count++;
        return count;
    }
};

// ============================================================
// 解法2: 2+2 分组哈希表 — ⭐ 最优解 / 面试首选
// 时间: O(n²)  空间: O(n²)
//
// 【思路】
// 核心等式变换: a + b + c + d = 0  →  (a + b) = -(c + d)
//
// 这和 Two Sum 完全一样的思路！
//   Two Sum:  a + b = target  →  存 a, 查 target - b
//   本题:    (a+b) + (c+d) = 0  →  存 (a+b), 查 -(c+d)
//
// 第一阶段: O(n²) 枚举 nums1×nums2 的所有和，
//           用哈希表记录 {和: 出现次数}
// 第二阶段: O(n²) 枚举 nums3×nums4 的所有和 s，
//           查哈希表中 -s 的出现次数，累加到答案
//
// 为什么 2+2 分组最优？
// 分成 k 和 4-k: 总时间 O(n^k + n^(4-k))
//   k=1: O(n + n³) = O(n³)
//   k=2: O(n² + n²) = O(n²)  ← 最优！均分原理
//   k=3: O(n³ + n) = O(n³)
//
// 示例过程:
//   nums1=[1,2], nums2=[-2,-1], nums3=[-1,2], nums4=[0,2]
//
//   第一阶段: 枚举 nums1 + nums2:
//     1+(-2)=-1, 1+(-1)=0, 2+(-2)=0, 2+(-1)=1
//     哈希表 sumAB = {-1:1, 0:2, 1:1}
//
//   第二阶段: 枚举 nums3 + nums4:
//     (-1)+0=-1 → 查 sumAB[1]=1  → count += 1
//     (-1)+2= 1 → 查 sumAB[-1]=1 → count += 1
//     2+0   = 2 → 查 sumAB[-2]   → 不存在
//     2+2   = 4 → 查 sumAB[-4]   → 不存在
//
//   最终 count = 2 ✓
// ============================================================
class Solution2 {
public:
    int fourSumCount(vector<int>& nums1, vector<int>& nums2,
                     vector<int>& nums3, vector<int>& nums4) {
        unordered_map<int, int> sumAB;
        
        // 第一阶段: 存储前两个数组所有两数之和及其出现次数
        // 为什么要记次数？因为不同的 (i,j) 可能产生相同的和，
        // 每一对都能独立地和后两个数组的 (k,l) 组合
        for (int a : nums1)
            for (int b : nums2)
                sumAB[a + b]++;
        
        int count = 0;
        
        // 第二阶段: 枚举后两个数组的和，查找互补值
        for (int c : nums3)
            for (int d : nums4) {
                int target = -(c + d);
                // 用 find 而不是 []，避免在哈希表中插入不存在的 key
                auto it = sumAB.find(target);
                if (it != sumAB.end())
                    count += it->second;  // 累加次数，不是 count++！
            }
        
        return count;
    }
};

// ============================================================
// 解法3: 1+3 分组哈希表 — 过渡解法，帮助理解优化过程
// 时间: O(n³)  空间: O(n)
//
// 【思路】
// 从暴力四重循环出发，最容易想到的优化：
// 把最内层循环用哈希表替代。
// 先存 nums4 的值和次数，然后三重循环查找 -(a+b+c)。
// 
// 这比暴力好（O(n³) vs O(n⁴)），但不如 2+2 分组（O(n²)）。
// 体现了"分组越均匀，复杂度越低"的原则。
// ============================================================
class Solution3 {
public:
    int fourSumCount(vector<int>& nums1, vector<int>& nums2,
                     vector<int>& nums3, vector<int>& nums4) {
        // 只存一个数组
        unordered_map<int, int> mapD;
        for (int d : nums4)
            mapD[d]++;
        
        int count = 0;
        // 三重循环枚举前三个数组
        for (int a : nums1)
            for (int b : nums2)
                for (int c : nums3) {
                    int target = -(a + b + c);
                    auto it = mapD.find(target);
                    if (it != mapD.end())
                        count += it->second;
                }
        return count;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 分组方式 | 时间   | 空间   | 核心区别                       |
// |------|---------|--------|--------|-------------------------------|
// | 1    | 0+4    | O(n⁴) | O(1)  | 纯暴力，无哈希优化              |
// | 3    | 1+3    | O(n³) | O(n)  | 哈希表替代最内层1层循环          |
// | 2    | 2+2    | O(n²) | O(n²) | 哈希表替代最内层2层循环 ⭐最优   |
//
// 面试直接写解法2。解法3可以作为"如果只想到先优化一层"的过渡思路。
//
// 【易错点】
//
// 1. count += it->second 而不是 count++
//    ✗ if (sumAB.count(target)) count++;
//    ✓ if (sumAB.count(target)) count += sumAB[target];
//    原因：哈希表中同一个和可能由多对 (i,j) 产生，每一对都是独立的四元组。
//    反例：nums1=[0,0], nums2=[0,0] → 和为0出现4次不是1次。
//
// 2. 用 [] 操作符访问不存在的 key 会插入默认值 0
//    ✗ count += sumAB[target];  // key不存在时会插入 {target, 0}，污染哈希表
//    ✓ auto it = sumAB.find(target); if (it != sumAB.end()) count += it->second;
//    虽然最终结果相同（加了0不影响），但哈希表会膨胀，在极端情况下影响性能。
//
// 3. 不需要去重！
//    和 LeetCode 18 (4Sum) 不同，本题四个数组完全独立，
//    每个合法的 (i,j,k,l) 都是唯一四元组，不存在重复计数问题。
//
// 【面试追问】
//
// Q1(基础): "暴力解 O(n⁴) 能过吗？瓶颈在哪？"
//   → n=200, 1.6×10⁹次，超时。瓶颈是四层循环，
//     每多一层就 ×n，需要用哈希表减少循环层数。
//
// Q2(优化): "为什么 2+2 分组比 1+3 好？"
//   → 总复杂度 O(n^k + n^(4-k))，k=2 时均分取最小。
//     直觉上：把工作量均匀分到两边，任何一边都不会成为瓶颈。
//
// Q3(扩展): "如果是 k 个数组呢？"
//   → 同样的 Meet in the Middle 思想，分成 k/2 + k/2。
//     每边 O(n^(k/2))，总时间 O(n^(k/2))，空间 O(n^(k/2))。
//     这把指数级搜索空间缩减了一半的指数。
//
// Q4(关联): "这和 Two Sum 是什么关系？"
//   → 完全相同的范式。Two Sum: 存 a, 查 target-b。
//     本题: 存 (a+b), 查 -(c+d)。"元素"从单个数变成了两数之和。
//
// 【相关题型】
// - LeetCode 1 (Two Sum): 本题的基础版，复用"哈希表存互补值"
// - LeetCode 18 (4Sum): 同一数组选4个元素，需排序+双指针+去重，思路不同
// - LeetCode 15 (3Sum): 同一数组选3个元素，排序+双指针
// - Meet in the Middle 算法: 本题是 MITM 在求和问题上的经典应用
// ============================================================
