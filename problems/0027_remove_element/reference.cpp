/*
 * LeetCode 27: 移除元素 (Remove Element)
 *
 * 【题目本质】
 * 原地把数组分成两部分：前面放不等于 val 的元素，返回前部长度。
 * 本质是"数组原地分区"问题。
 *
 * 【解法总览】
 * 解法1: 暴力移位          — O(n²) / O(1) — 最直觉，模拟真正的删除
 * 解法2: 快慢双指针（同向） — O(n)  / O(1) — 面试首选，通用模板
 * 解法3: 首尾双指针（相向） — O(n)  / O(1) — 赋值次数最少，不保序
 */

// ============================================================
// 解法1: 暴力移位 — 遇到 val 就把后面元素整体前移
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 最直觉的想法：遍历数组，遇到等于 val 的元素，
// 把它后面的所有元素往前移一位，模拟"真正删除"。
// 
// 瓶颈：每次删除都要移动后面所有元素，最坏 O(n²)。
//
// 示意 (nums=[3,2,2,3], val=3):
//   i=0: nums[0]=3==val → 前移: [2,2,3,_], n=3
//   i=0: nums[0]=2!=val → i++
//   i=1: nums[1]=2!=val → i++
//   i=2: nums[2]=3==val → 前移: [2,2,_,_], n=2
//   返回 2
// ============================================================
class Solution1 {
public:
    int removeElement(vector<int>& nums, int val) {
        int n = nums.size();
        for (int i = 0; i < n; ) {
            if (nums[i] == val) {
                // 瓶颈所在：后面所有元素前移一位，O(n)
                for (int j = i; j < n - 1; j++) {
                    nums[j] = nums[j + 1];
                }
                n--;
                // 关键：i 不动，因为新的 nums[i] 是移过来的，还没检查
            } else {
                i++;
            }
        }
        return n;
    }
};

// ============================================================
// 解法2: 快慢双指针（同向）— 非 val 元素收集到前面 ⭐ 面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1的瓶颈：每次删除要移动后面所有元素。
// 关键观察：我们不需要"删除"，只需要把非 val 元素收集到前面。
//
// 用两个指针：
//   fast —— 遍历每个元素（探路者）
//   slow —— 指向下一个要放元素的位置（收集者）
//
// 不变量：nums[0..slow-1] 始终是已确认的非 val 元素
//
// 示意 (nums=[0,1,2,2,3,0,4,2], val=2):
//
//   fast: 0  1  2  3  4  5  6  7
//   nums: 0  1  2  2  3  0  4  2
//         ↑
//        slow
//
//   fast=0: 0!=2 → nums[0]=0, slow=1
//   fast=1: 1!=2 → nums[1]=1, slow=2
//   fast=2: 2==2 → 跳过
//   fast=3: 2==2 → 跳过
//   fast=4: 3!=2 → nums[2]=3, slow=3
//   fast=5: 0!=2 → nums[3]=0, slow=4
//   fast=6: 4!=2 → nums[4]=4, slow=5
//   fast=7: 2==2 → 跳过
//
//   结果: nums=[0,1,3,0,4,...], 返回 slow=5
// ============================================================
class Solution2 {
public:
    int removeElement(vector<int>& nums, int val) {
        int slow = 0;
        for (int fast = 0; fast < (int)nums.size(); fast++) {
            if (nums[fast] != val) {
                // 非 val 元素放到 slow 位置
                // 为什么直接覆盖不会丢数据？因为 slow <= fast，
                // slow 指向的位置要么已经处理过，要么就是 fast 自己
                nums[slow] = nums[fast];
                slow++;
            }
        }
        return slow;
    }
};

// ============================================================
// 解法3: 首尾双指针（相向）— 用末尾元素覆盖 val 元素
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法2的问题：如果 val 很少出现，几乎每个元素都"自己赋值给自己"，
// 赋值次数 = n - k（k 为 val 出现次数），当 k 很小时接近 n 次。
//
// 优化：题目说顺序可以改变！
// 遇到 nums[left]==val 时，用数组最后一个元素覆盖它，
// 然后缩短有效长度（right--）。
// 这样赋值次数 = k 次（只有 val 元素才触发赋值）。
//
// 示意 (nums=[3,2,2,3], val=3):
//
//   left=0, right=4
//   [3, 2, 2, 3]
//    L           R(开区间)
//
//   left=0: nums[0]=3==val → nums[0]=nums[3]=3, right=3
//   [3, 2, 2, | 3]     注意换过来的还是3，下轮继续检查
//    L        R
//
//   left=0: nums[0]=3==val → nums[0]=nums[2]=2, right=2
//   [2, 2, | 2, 3]
//    L     R
//
//   left=0: nums[0]=2!=val → left=1
//   left=1: nums[1]=2!=val → left=2
//   left==right → 结束，返回 2
// ============================================================
class Solution3 {
public:
    int removeElement(vector<int>& nums, int val) {
        int left = 0, right = nums.size();
        // right 用开区间：避免空数组时 size()-1 导致无符号溢出
        while (left < right) {
            if (nums[left] == val) {
                // 用末尾元素覆盖当前 val 元素
                nums[left] = nums[right - 1];
                right--;
                // 关键：left 不动！换过来的元素可能也是 val，需要再检查
            } else {
                left++;
            }
        }
        return left;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间  | 赋值次数      | 保持顺序 | 适用场景       |
// |------------|-------|---------------|----------|---------------|
// | 暴力移位   | O(n²) | 最多 O(n²)    | ✅       | 理解题意       |
// | 快慢双指针 | O(n)  | n-k 次        | ✅       | 通用首选       |
// | 首尾双指针 | O(n)  | k 次          | ❌       | val少时更优    |
//
// 其中 k = val 出现的次数
//
// 【易错点】
//
// 1. 暴力解中删除后 i 不能自增：
//    ✗ for(int i=0; i<n; i++) { if(==val) { 移位; n--; } }
//      → 移位后 nums[i] 是新元素，i++ 会跳过它
//    ✓ 只在 nums[i]!=val 时才 i++
//
// 2. 首尾双指针的 right 初始值：
//    ✗ right = nums.size() - 1
//      → 空数组时 nums.size()=0，size()-1 = 4294967295（无符号溢出！）
//    ✓ right = nums.size()，用开区间，空数组直接不进循环
//
// 3. 首尾双指针覆盖后 left 不能移动：
//    ✗ nums[left] = nums[right-1]; right--; left++;
//      → 换过来的可能也是 val（如示例中 [3,2,2,3] val=3）
//    ✓ 覆盖后 left 不动，下一轮重新检查
//
// 【面试追问】
//
// Q1（基础）: 暴力解时间复杂度？瓶颈在哪？
//   → O(n²)，瓶颈是每次删除后面元素要整体前移 O(n)
//
// Q2（优化）: 快慢双指针赋值了多少次？能否更少？
//   → 赋值 n-k 次。如果 val 很少（k 很小），几乎赋值 n 次。
//     首尾双指针只赋值 k 次，但不保序。
//
// Q3（变体）: 如果必须保持相对顺序呢？
//   → 只能用快慢双指针。首尾双指针会打乱顺序。
//
// Q4（拓展）: 这道题和 26题(删除重复项)、283题(移动零) 有什么关系？
//   → 都是快慢双指针模板：
//     - 27题: if(nums[fast] != val) → 收集非 val
//     - 26题: if(nums[fast] != nums[slow-1]) → 收集非重复
//     - 283题: 收集非零元素后，剩余位置填 0
// ============================================================
