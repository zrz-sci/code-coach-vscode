/*
 * LeetCode 983: Minimum Cost For Tickets (最低票价)
 *
 * 思路: 决策型 DP, 每个旅行日选 1/7/30 天票, 取最小花费
 *
 * 时间: O(365) = O(1)   空间: O(365) = O(1)
 */

// ═══════════════════════════════════════════════════════
// 解法一: DP 从后往前（推荐）
// ═══════════════════════════════════════════════════════

class Solution {
public:
    int mincostTickets(vector<int>& days, vector<int>& costs) {
        unordered_set<int> travelDays(days.begin(), days.end());
        int lastDay = days.back();

        // dp[i] = 从第 i 天到最后一天的最低花费
        // 多开 30 个位置避免 i+30 越界
        vector<int> dp(lastDay + 31, 0);

        for (int i = lastDay; i >= 1; i--) {
            if (travelDays.count(i) == 0) {
                dp[i] = dp[i + 1];  // 非旅行日直接跳过
            } else {
                dp[i] = min({
                    costs[0] + dp[i + 1],   // 买 1 天票
                    costs[1] + dp[i + 7],   // 买 7 天票
                    costs[2] + dp[i + 30]   // 买 30 天票
                });
            }
        }

        return dp[1];
    }
};


// ═══════════════════════════════════════════════════════
// 解法二: DP 从前往后（以旅行日索引为状态）
// ═══════════════════════════════════════════════════════
//
// dp[i] = 覆盖前 i 个旅行日的最低花费
// 对第 i 个旅行日, 尝试三种票, 向前找覆盖起点
//
// 时间: O(n * 30)   空间: O(n)

class Solution_Forward {
public:
    int mincostTickets(vector<int>& days, vector<int>& costs) {
        int n = days.size();
        vector<int> dp(n + 1, 0);
        int durations[] = {1, 7, 30};

        for (int i = 1; i <= n; i++) {
            dp[i] = INT_MAX;
            for (int k = 0; k < 3; k++) {
                // 这张票覆盖 [days[i-1] - durations[k] + 1, days[i-1]]
                // 找到第一个不被覆盖的旅行日索引 j
                int j = i - 1;
                while (j > 0 && days[j - 1] >= days[i - 1] - durations[k] + 1) {
                    j--;
                }
                dp[i] = min(dp[i], costs[k] + dp[j]);
            }
        }

        return dp[n];
    }
};


// ═══════════════════════════════════════════════════════
// 解法三: 记忆化递归
// ═══════════════════════════════════════════════════════
//
// dfs(idx) = 覆盖 days[idx..n-1] 的最低花费
// 时间: O(n)   空间: O(n)

class Solution_Memo {
public:
    int mincostTickets(vector<int>& days, vector<int>& costs) {
        int n = days.size();
        vector<int> memo(n, -1);
        int durations[] = {1, 7, 30};

        function<int(int)> dfs = [&](int idx) -> int {
            if (idx >= n) return 0;
            if (memo[idx] != -1) return memo[idx];

            int res = INT_MAX;
            for (int k = 0; k < 3; k++) {
                // 买 durations[k] 天票, 覆盖 [days[idx], days[idx]+durations[k]-1]
                int next = idx;
                while (next < n && days[next] < days[idx] + durations[k]) {
                    next++;
                }
                res = min(res, costs[k] + dfs(next));
            }

            return memo[idx] = res;
        };

        return dfs(0);
    }
};


