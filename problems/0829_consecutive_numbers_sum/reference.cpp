/*
 * LeetCode 829: 连续整数求和 (Consecutive Numbers Sum)
 *
 * 【题目本质】
 * 将正整数 n 表示为连续正整数之和，问有多少种表示方式。
 * 数学上等价于：对等差数列求和公式 n = k*a + k*(k-1)/2，
 * 枚举 k（连续个数），判断 a（起点）是否为正整数。
 *
 * 【解法总览】
 * 解法1: 暴力枚举起点     — O(n)    / O(1) — 直觉但超时
 * 解法2: 枚举连续个数 k   — O(√n)   / O(1) — 面试首选 ⭐
 * 解法3: 奇因子计数       — O(√n)   / O(1) — 数论进阶
 */

// ============================================================
// 解法1: 暴力枚举起点 — 直觉做法
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 最朴素的想法：枚举连续序列的起点 a (从1到n)，
// 从 a 开始累加，看能否恰好凑到 n。
// n 最大 10^9，实际会超时，但帮助理解题意。
//
// 示例 n=15:
//   a=1: 1+2+3+4+5 = 15 ✓
//   a=2: 2+3+4+5 = 14, +6=20 > 15 ✗
//   a=3: 3+4+5 = 12, +6=18 > 15 ✗
//   a=4: 4+5+6 = 15 ✓
//   a=7: 7+8 = 15 ✓
//   a=15: 15 ✓
//   共 4 种
// ============================================================
class Solution1 {
public:
    int consecutiveNumbersSum(int n) {
        int count = 0;
        for (int a = 1; a <= n; a++) {
            int sum = 0;
            for (int j = a; sum < n; j++) {
                sum += j;
            }
            if (sum == n) count++;
        }
        return count;
    }
};

// ============================================================
// 解法2: 枚举连续个数 k — 等差数列公式 ⭐ 面试首选
// 时间: O(√n)  空间: O(1)
//
// 【思路】
// 核心数学推导：
//   连续 k 个从 a 开始的正整数之和:
//   S = a + (a+1) + ... + (a+k-1) = k*a + k*(k-1)/2
//
//   令 S = n:
//     k*a = n - k*(k-1)/2
//     a = (n - k*(k-1)/2) / k
//
//   两个条件使 a 是合法的正整数:
//     ① n - k*(k-1)/2 > 0     (保证 a > 0)
//     ② (n - k*(k-1)/2) % k == 0  (保证 a 是整数)
//
//   从 ① 推出 k 的上界: k*(k-1)/2 < n → k < √(2n) ≈ O(√n)
//
// 示例 n=15 枚举过程:
//   k=1: remain=15-0=15,  15%1==0, a=15  → [15]        ✓
//   k=2: remain=15-1=14,  14%2==0, a=7   → [7,8]       ✓
//   k=3: remain=15-3=12,  12%3==0, a=4   → [4,5,6]     ✓
//   k=4: remain=15-6=9,   9%4!=0                        ✗
//   k=5: remain=15-10=5,  5%5==0, a=1    → [1,2,3,4,5] ✓
//   k=6: remain=15-15=0,  a=0 不是正整数 → 停止
//   答案: 4
// ============================================================
class Solution2 {
public:
    int consecutiveNumbersSum(int n) {
        int count = 0;
        for (int k = 1; (long long)k * (k - 1) / 2 < n; k++) {
            // remain = n - k*(k-1)/2 就是 k*a
            int remain = n - k * (k - 1) / 2;
            // a 必须是正整数，remain > 0 已由循环条件保证
            if (remain % k == 0) {
                count++;
            }
        }
        return count;
    }
};

// ============================================================
// 解法3: 奇因子计数 — 数论视角
// 时间: O(√n)  空间: O(1)
//
// 【思路】
// 从解法2的公式继续推导:
//   n = k*a + k*(k-1)/2
//   2n = k*(2a + k - 1)
//
//   令 m = 2a + k - 1，则 2n = k * m
//   注意: m - k = 2a - 1 (奇数) → k 和 m 一奇一偶
//   且 a ≥ 1 → m = 2a+k-1 ≥ k+1 → m > k
//
//   所以每种合法分解 2n = k * m (k<m, k和m一奇一偶)
//   对应一种连续整数求和方式。
//
//   等价于: 找 n 的所有奇因子的个数。
//
//   证明思路:
//   - 2n = k * m，k和m一奇一偶
//   - 设奇数的那个是 d，则 d | 2n 且 d 是奇数 → d | n（因为 d 和 2 互素）
//   - 反之 n 的每个奇因子 d 都能构造出一组 (k,m)
//
//   所以答案 = n 去掉所有因子2后的因子个数
//   用质因数分解: n = 2^a * p1^e1 * p2^e2 * ...
//   答案 = (e1+1) * (e2+1) * ...（只取奇素因子）
//
// 示例 n=15:
//   15 = 3^1 * 5^1 (没有因子2)
//   奇因子个数 = (1+1)*(1+1) = 4
//   对应: 1, 3, 5, 15 这四个奇因子
//     d=1:  k=1, m=30 → a=(30-1+1)/2=15   → [15]
//     d=3:  k=3, m=10 → a=(10-3+1)/2=4    → [4,5,6]
//     d=5:  k=5, m=6  → a=(6-5+1)/2=1     → [1,2,3,4,5]
//     d=15: k=2, m=15 → a=(15-2+1)/2=7    → [7,8]
//   答案: 4 ✓
// ============================================================
class Solution3 {
public:
    int consecutiveNumbersSum(int n) {
        // 第一步：去掉 n 的所有因子 2（我们只关心奇因子）
        while (n % 2 == 0) {
            n /= 2;
        }
        
        // 第二步：对剩余的奇数部分做质因数分解，统计因子个数
        // 因子个数公式: 若 n = p1^e1 * p2^e2 * ...
        // 则因子个数 = (e1+1) * (e2+1) * ...
        int count = 1;
        for (int d = 3; (long long)d * d <= n; d += 2) {
            // 只枚举奇数因子
            int exp = 0;
            while (n % d == 0) {
                n /= d;
                exp++;
            }
            // 这个素因子 d 出现了 exp 次，贡献 (exp+1) 种选择
            count *= (exp + 1);
        }
        // 如果 n > 1，说明剩余的 n 本身是一个大于 √原始n 的素因子
        // 它的指数为 1，贡献 (1+1) = 2
        if (n > 1) {
            count *= 2;
        }
        return count;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 时间   | 空间 | 核心操作       | 面试推荐 |
// |----------|--------|------|----------------|----------|
// | 暴力枚举 | O(n)   | O(1) | 逐个累加       | ✗ 超时   |
// | 枚举 k   | O(√n)  | O(1) | 等差公式+整除  | ✓ 首选   |
// | 奇因子   | O(√n)  | O(1) | 质因数分解     | ✓ 加分   |
//
// 解法2 和 解法3 复杂度相同，但解法3 常数更小（只遍历奇数）。
// 面试中推荐解法2（推导自然），能讲清解法3 是额外加分。
//
// 【易错点】
//
// 1. 循环上界写错导致 O(n):
//    ✗ for (int k = 1; k <= n; k++)  — 循环 n 次
//    ✓ for (int k = 1; (long long)k*(k-1)/2 < n; k++) — 只循环 O(√n) 次
//
// 2. 忘记 k=1（n 本身单独一个数也算一组）:
//    循环从 k=1 开始，k=1 时 remain=n，n%1==0，自动包含。
//
// 3. 整数溢出:
//    ✗ k * (k - 1) 在 k ≈ 45000 时约 2×10^9，int 可能溢出
//    ✓ 使用 (long long)k * (k - 1) / 2 < n
//
// 4. 解法3 忘记处理最后剩余的大素因子:
//    ✗ 循环结束后直接 return count
//    ✓ if (n > 1) count *= 2; 然后 return count
//
// 5. 解法3 中去因子2时误改了原始 n 的奇数部分:
//    只去因子2，然后对奇数部分分解。不要在去2之后又从 d=2 开始分解。
//
// 【面试追问】
//
// Q1: 暴力怎么做？瓶颈在哪？
//     枚举起点 a，从 a 累加。O(n) 级别，n=10^9 时超时。
//     瓶颈：对每个起点都要累加到超过 n 才能停。
//
// Q2: 怎么优化到 O(√n)？
//     用等差数列公式，固定连续个数 k，直接算出起点 a。
//     由 a≥1 推出 k=O(√n)，只枚举 k 并检查整除性。
//
// Q3: 答案和 n 的因子有什么关系？能否从数论角度解释？
//     答案 = n 的奇因子个数。推导：2n = k*m，k 和 m 一奇一偶，
//     等价于找 n 的奇因子。用质因数分解后，指数+1 相乘即可。
//
// Q4: 如果允许起点为 0（连续非负整数），怎么改？
//     将 a ≥ 1 改为 a ≥ 0，循环条件从 k*(k-1)/2 < n
//     改为 k*(k-1)/2 <= n（允许等号，对应 a=0）。
// ============================================================
