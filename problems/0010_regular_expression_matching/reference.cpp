/*
 * LeetCode 10: 正则表达式匹配 (Regular Expression Matching)
 *
 * 【题目本质】
 * 双序列匹配问题：s 和 p 从头到尾能否完全匹配。
 * 难点在于 x* 可以匹配 0 次或多次，形成分支选择 → 递归/DP。
 *
 * 【解法总览】
 * 解法1: 暴力递归      — O(2^(m+n)) / O(m+n)    — 最直觉，展示决策分支
 * 解法2: 记忆化搜索    — O(m×n) / O(m×n)         — 递归+缓存，面试首选
 * 解法3: 自底向上 DP   — O(m×n) / O(m×n)         — 填表法，面试首选
 * 解法4: DP 空间优化   — O(m×n) / O(n)           — 滚动数组，追问加分
 */

// ============================================================
// 解法1: 暴力递归 — 穷举所有匹配方式
// 时间: O(2^(m+n)) 最坏  空间: O(m+n) 递归栈
//
// 【思路】
// 从 s[i] 和 p[j] 开始匹配：
//   - 如果 p[j+1] == '*'，面临选择：
//     选择A: x* 匹配 0 次 → 跳过 p 的 j, j+1
//     选择B: x* 匹配 1+ 次 → 当前字符必须匹配，i 前进，j 不动
//   - 否则：当前字符必须匹配，i++, j++
//
// 决策树示例: s="aab", p="c*a*b"
//
//                    (i=0,j=0) p[0..1]="c*"
//                   c*匹配0次 ↓ (c!=a, 匹配1+次不可行)
//                  (i=0,j=2) p[2..3]="a*"
//           a*匹配0次 /           \ a*匹配1次 (a==a ✓)
//         (i=0,j=4)             (i=1,j=2)
//         p[4]='b'             a*匹配0次 /  \ a*匹配1次 (a==a ✓)
//         s[0]='a'≠'b' ✗    (i=1,j=4)    (i=2,j=2)
//                            s[1]='a'≠'b' ✗  a*匹配0次 / \ (a≠b ✗)
//                                           (i=2,j=4)
//                                           s[2]='b'==p[4]='b' ✓
//                                           → (i=3,j=5) 都到尾 → TRUE!
// ============================================================
class Solution1 {
public:
    bool isMatch(string s, string p) {
        return dfs(s, p, 0, 0);
    }

private:
    bool dfs(const string& s, const string& p, int i, int j) {
        // 模式用完 → 字符串也必须用完
        if (j == (int)p.size()) return i == (int)s.size();

        // 当前位置字符是否匹配（i 未越界 且 字符相同或 '.'）
        bool firstMatch = (i < (int)s.size()) &&
                          (s[i] == p[j] || p[j] == '.');

        if (j + 1 < (int)p.size() && p[j + 1] == '*') {
            // x* 模式：匹配 0 次 || (当前匹配 && 匹配 1+ 次)
            // 注意 j 不动 —— x* 可能还要继续消耗更多字符
            return dfs(s, p, i, j + 2) ||
                   (firstMatch && dfs(s, p, i + 1, j));
        } else {
            // 普通字符/'.': 必须匹配，双方各前进一步
            return firstMatch && dfs(s, p, i + 1, j + 1);
        }
    }
};

// ============================================================
// 解法2: 记忆化搜索 — 递归 + memo 缓存重叠子问题
// 时间: O(m×n)  空间: O(m×n)
//
// 【思路】
// 解法1的瓶颈：同一个 (i,j) 从不同路径被反复计算。
// 加 memo[i][j] 缓存，每个状态只算一次。
// 状态数 (m+1)×(n+1)，每个状态 O(1) 转移 → 总时间 O(m×n)。
// ============================================================
class Solution2 {
public:
    bool isMatch(string s, string p) {
        int m = s.size(), n = p.size();
        // 0=未算, 1=true, -1=false（三态避免额外 visited 数组）
        vector<vector<int>> memo(m + 1, vector<int>(n + 1, 0));
        return dfs(s, p, 0, 0, memo);
    }

private:
    bool dfs(const string& s, const string& p, int i, int j,
             vector<vector<int>>& memo) {
        if (memo[i][j] != 0) return memo[i][j] == 1;

        bool result;
        if (j == (int)p.size()) {
            result = (i == (int)s.size());
        } else {
            bool firstMatch = (i < (int)s.size()) &&
                              (s[i] == p[j] || p[j] == '.');

            if (j + 1 < (int)p.size() && p[j + 1] == '*') {
                result = dfs(s, p, i, j + 2, memo) ||
                         (firstMatch && dfs(s, p, i + 1, j, memo));
            } else {
                result = firstMatch && dfs(s, p, i + 1, j + 1, memo);
            }
        }

        memo[i][j] = result ? 1 : -1;
        return result;
    }
};

// ============================================================
// 解法3: 自底向上 DP — 二维填表
// 时间: O(m×n)  空间: O(m×n)
//
// 【思路】
// dp[i][j] = s 的前 i 个字符 与 p 的前 j 个字符是否匹配
// （多出一维方便处理空串：dp[0][0] = 空串匹配空模式 = true）
//
// 状态转移:
//   p[j-1] != '*':
//     dp[i][j] = (s[i-1] 匹配 p[j-1]) && dp[i-1][j-1]
//
//   p[j-1] == '*':
//     匹配0次: dp[i][j] = dp[i][j-2]    (跳过 x* 两个字符)
//     匹配1+次: dp[i][j] |= (s[i-1] 匹配 p[j-2]) && dp[i-1][j]
//
// 填表方向: 从上到下、从左到右（依赖左上、上方、左两格）
//
// DP 填表示例: s = "aab", p = "c*a*b"
//
//        ""  c   *   a   *   b     (p 的字符)
//   ""  [ T  F   T   F   T   F ]
//   a   [ F  F   F   T   T   F ]
//   a   [ F  F   F   F   T   F ]
//   b   [ F  F   F   F   F   T ] ← dp[3][5] = 答案
//
// 初始化关键: dp[0][2]=T 因为 c* 匹配0次→dp[0][0]=T
//             dp[0][4]=T 因为 a* 匹配0次→dp[0][2]=T
// ============================================================
class Solution3 {
public:
    bool isMatch(string s, string p) {
        int m = s.size(), n = p.size();
        vector<vector<bool>> dp(m + 1, vector<bool>(n + 1, false));

        dp[0][0] = true;

        // 第一行初始化: 空串 s="" 可能匹配 "x*y*z*..."
        // 只有 p[j-1]=='*' 且 dp[0][j-2]==true 时才为 true
        for (int j = 2; j <= n; j++) {
            if (p[j - 1] == '*') {
                dp[0][j] = dp[0][j - 2];
            }
        }

        for (int i = 1; i <= m; i++) {
            for (int j = 1; j <= n; j++) {
                if (p[j - 1] == '*') {
                    // x* 匹配 0 次: 完全跳过这两个字符
                    dp[i][j] = dp[i][j - 2];
                    // x* 匹配 1+ 次: s[i-1] 必须和 x(=p[j-2]) 匹配
                    // 然后看 s 去掉这个字符后是否仍能匹配（x* 保留）
                    if (s[i - 1] == p[j - 2] || p[j - 2] == '.') {
                        dp[i][j] = dp[i][j] || dp[i - 1][j];
                    }
                } else {
                    // 普通字符或 '.': 当前位匹配 + 前缀匹配
                    if (s[i - 1] == p[j - 1] || p[j - 1] == '.') {
                        dp[i][j] = dp[i - 1][j - 1];
                    }
                    // 不匹配则保持 false
                }
            }
        }

        return dp[m][n];
    }
};

// ============================================================
// 解法4: DP 空间优化 — 滚动一维数组
// 时间: O(m×n)  空间: O(n)
//
// 【思路】
// dp[i][j] 的依赖关系:
//   - dp[i-1][j-1] (左上) ← 用 prev 变量保存
//   - dp[i-1][j]   (上方) ← 覆盖前用 temp 保存
//   - dp[i][j-2]   (左两格) ← 当前行已更新的值，直接用
//
// 关键技巧: 在更新 dp[j] 之前，temp = dp[j]（旧值=上一行），
// 更新后 prev = temp（下一列的"左上"就是这一列的"上"）。
// ============================================================
class Solution4 {
public:
    bool isMatch(string s, string p) {
        int m = s.size(), n = p.size();
        vector<bool> dp(n + 1, false);
        dp[0] = true;

        // 初始化: 空串 vs 模式
        for (int j = 2; j <= n; j++) {
            if (p[j - 1] == '*') dp[j] = dp[j - 2];
        }

        for (int i = 1; i <= m; i++) {
            bool prev = dp[0]; // prev = 上一行的 dp[0] = dp[i-1][0]
            dp[0] = false;     // 非空串 vs 空模式 = false

            for (int j = 1; j <= n; j++) {
                bool temp = dp[j]; // 保存 dp[i-1][j]（旧值）

                if (p[j - 1] == '*') {
                    // 匹配0次: dp[j-2] 是当前行已更新的值 ✓
                    dp[j] = dp[j - 2];
                    // 匹配1+次: temp 是 dp[i-1][j]（上方旧值）
                    if (s[i - 1] == p[j - 2] || p[j - 2] == '.') {
                        dp[j] = dp[j] || temp;
                    }
                } else {
                    // 普通匹配: prev 是 dp[i-1][j-1]（左上旧值）
                    if (s[i - 1] == p[j - 1] || p[j - 1] == '.') {
                        dp[j] = prev;
                    } else {
                        dp[j] = false; // 不匹配，必须显式置 false
                    }
                }

                prev = temp; // 本列旧值 → 下一列的"左上"
            }
        }

        return dp[n];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间 | 空间 | 特点 |
// |------|------|------|------|
// | 暴力递归 | O(2^(m+n)) | O(m+n) | 直觉清晰，展示决策分支 |
// | 记忆化搜索 | O(m×n) | O(m×n) | 递归+缓存，最好写 |
// | 自底向上DP | O(m×n) | O(m×n) | 无递归开销，便于空间优化 |
// | DP空间优化 | O(m×n) | O(n) | 追问加分，prev维护要细心 |
//
// 面试建议: 先讲暴力思路说明理解，再写记忆化或DP，被追问再优化空间。
//
// 【易错点】
// 1. ✗ 把 * 当独立字符处理（如"匹配任意字符"）
//    ✓ * 和前一个字符绑定，x* 是一个整体
//
// 2. ✗ dp[0][j] 全部初始化为 false
//    ✓ p="a*b*" 时 dp[0][2]=true, dp[0][4]=true（每个 x* 匹配0次）
//
// 3. ✗ x* 匹配多次时写 dp[i][j] = dp[i-1][j-1]（j 也前进了）
//    ✓ 应该是 dp[i][j] = dp[i-1][j]，j 不动，x* 保留继续匹配
//
// 4. ✗ p[j-1]=='*' 时取前面字符用 p[j-1]
//    ✓ 应该用 p[j-2]（dp 维度偏移，* 在 p 的 j-1 位置，前面字符在 j-2）
//
// 5. ✗ 空间优化中先更新 dp[j] 再保存 temp
//    ✓ 必须先 temp = dp[j]，再覆盖 dp[j]，最后 prev = temp
//
// 6. ✗ 空间优化中普通字符不匹配时忘记 dp[j] = false
//    ✓ 一维数组复用，旧值残留，不匹配时必须显式置 false
//
// 【面试追问】
// Q1: 暴力递归的时间复杂度为什么是指数级？
//     → 每遇到 x*，分两个分支（0次 / 1+次），最坏 O(2^(m+n))。
//        例如 s="aaa...a", p="a*a*a*..." 每个 * 都需要决策多少次匹配。
//
// Q2: 记忆化和自底向上 DP 有什么区别？什么时候选哪个？
//     → 逻辑等价。记忆化只访问需要的状态（稀疏时更快），
//        自底向上无递归栈开销且更容易做空间优化。面试选更熟的。
//
// Q3: 能否 O(n) 空间？怎么维护 prev？
//     → 见解法4。关键：每列更新前 temp 保存旧值，更新后 prev=temp。
//        * 分支中 dp[j-2] 用当前行新值（匹配0次），temp 用旧值（匹配1+次）。
//
// Q4: 如果增加 '+' (匹配一个或多个)，怎么改？
//     → x+ 等价于先匹配一个 x 再 x*。DP 中 x+ 不能"匹配0次"，
//        只保留 (s[i-1] 匹配 x) && dp[i-1][j] 这条路，去掉 dp[i][j-2]。
//
// Q5: 如果模式中有 '?'（匹配 0 个或 1 个前面的元素），怎么改？
//     → x? = 匹配 0 次或 1 次。DP 转移:
//        匹配0次: dp[i][j] = dp[i][j-2]
//        匹配1次: dp[i][j] |= (s[i-1] 匹配 p[j-2]) && dp[i-1][j-2]
//        注意：不再有 dp[i-1][j]（不能匹配多次）。
// ============================================================
