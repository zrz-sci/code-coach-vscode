/*
 * 【解法对比】
 *
 * | 解法                | 时间         | 空间  | 适用场景             |
 * |---------------------|-------------|-------|----------------------|
 * | 数学循环(推荐)      | O(sqrt(n))  | O(1)  | 面试首选，简洁明了   |
 * | 公式法              | O(1)        | O(1)  | 极简，但浮点精度风险 |
 * | DP                  | O(n^2)      | O(n)  | 理解原理，推导规律   |
 * | 一般化(k枚蛋)       | O(t*k)      | O(k)  | 推广到LeetCode 887   |
 *
 * 【易错点】
 * 1. DP 转移中用 min 而非 max — 最坏情况(碎/不碎)要取 max，
 *    不同的选择 x 才取 min。写反会得到最好情况而非最坏情况。
 * 2. x-1 写成 x — 碎了之后检查 1~(x-1) 共 x-1 层，不是 x 层。
 *    根源: 从第 x 层扔，碎了说明 f < x，只需查 x-1 层。
 * 3. 以为 1 枚蛋能二分 — 1 枚蛋只能线性扫描！碎了就没了。
 * 4. 数学解忘记上取整 — t*(t+1)/2 >= n 要取最小整数 t，
 *    用 while 循环或 ceil() 确保正确。
 * 5. 公式法浮点精度 — sqrt 和 ceil 的浮点运算可能有精度误差，
 *    建议用循环法更稳妥，或对公式结果 ±1 验证。
 *
 * 【面试追问】
 * Q1: 为什么间隔递减 1？
 *     → 每扔一次，"已用次数"加 1，为保证总次数 = t，
 *       "线性扫描次数"必须减 1。所以间隔从 t-1 递减到 0。
 *
 * Q2: 如果有 k 枚蛋呢？
 *     → 用 f(t, k) = C(t,1) + C(t,2) + ... + C(t,k)
 *       计算 t 次能覆盖的层数。对 k=2 退化为 t(t+1)/2。
 *       一般情况通过二分 t 或递推求解 (LeetCode 887)。
 *
 * Q3: DP 能优化到 O(n) 吗？
 *     → 可以。最优 x 随 i 增大而单调不减 (决策单调性)，
 *       可以避免内层枚举。但对 n<=1000 没必要优化。
 */
