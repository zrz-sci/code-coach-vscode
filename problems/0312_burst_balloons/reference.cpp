/*
 * LeetCode 312: 戳气球 (Burst Balloons)
 *
 * 【题目本质】
 * 有 n 个气球，每次戳破第 i 个得到 nums[i-1]*nums[i]*nums[i+1] 硬币，
 * 戳完后邻居拼接。求戳破所有气球能获得的最大硬币数。
 * 
 * 核心难点：戳破一个气球后邻居关系变化，"正向模拟"无法让子问题独立。
 * 逆向思维：在区间 (i,j) 中选"最后"被戳的气球 k，此时 k 的左右邻居
 * 确定为 val[i] 和 val[j]（因为区间内其他气球已全部戳完），
 * 子区间 (i,k) 和 (k,j) 互相独立 —— 完美满足 DP 的无后效性。
 *
 * 【解法总览】
 * 解法1: 暴力回溯          — O(n! * n) / O(n)   — 理解题意
 * 解法2: 记忆化搜索(区间DP) — O(n³)    / O(n²)  — 面试首选
 * 解法3: 区间DP递推         — O(n³)    / O(n²)  — 面试首选
 */

// ============================================================
// 解法1: 暴力回溯 — 枚举所有戳破顺序
// 时间: O(n! * n)  空间: O(n)（递归深度 + 每层 erase/insert O(n)）
//
// 【思路】
// 最直觉的做法：每次从剩余气球中选一个戳破，递归处理剩下的。
// 这就是枚举全排列，n=300 时完全不可行。
// 但这个解法清楚展示了"正向模拟"的困境：
// 戳破一个气球后数组结构变化，无法定义可复用的子问题。
// ============================================================
class Solution1 {
public:
    int maxCoins(vector<int>& nums) {
        return dfs(nums);
    }
    
    int dfs(vector<int>& nums) {
        int n = nums.size();
        if (n == 0) return 0;
        
        int best = 0;
        for (int i = 0; i < n; i++) {
            // 戳破 nums[i] 获得的硬币
            int left = (i - 1 >= 0) ? nums[i - 1] : 1;
            int right = (i + 1 < n) ? nums[i + 1] : 1;
            int coins = left * nums[i] * right;
            
            // 从数组中移除 nums[i]
            int saved = nums[i];
            nums.erase(nums.begin() + i);
            
            best = max(best, coins + dfs(nums));
            
            // 回溯：恢复
            nums.insert(nums.begin() + i, saved);
        }
        return best;
    }
};

// ============================================================
// 解法2: 记忆化搜索（区间 DP 自顶向下）
// 时间: O(n³)  空间: O(n²)
//
// 【思路】
// 暴力解的根本困境：正向戳破导致邻居变化，子问题不独立。
// 
// 逆向突破：在开区间 (i, j) 内，选"最后"被戳的气球 k。
// 此时 (i,k) 和 (k,j) 内的气球都已经戳完了，
// k 戳破时的左右邻居确定为 val[i] 和 val[j]，
// 收益 = val[i] * val[k] * val[j]。
// 两个子区间完全独立，可以递归求解。
//
// 为什么用"开区间"？
// 开区间 (i,j) 中 i 和 j 本身不参与戳破，它们是"墙壁/边界"。
// 这样 k 最后被戳时，它看到的就是两面"墙" i 和 j。
//
// 虚拟边界：在 nums 两端各加一个值为 1 的虚拟气球，
// 原问题 = dp(0, n+1)
//
// 逆向思维的可视化（以 nums = [3,1,5,8] 为例）：
//
//   val = [1, 3, 1, 5, 8, 1]   下标 0~5
//
//   求 dp(0, 5): 在 (0,5) 内选最后戳的
//     假设 k=4（气球8最后戳）:
//       先解决 (0,4): 戳完 3,1,5
//       先解决 (4,5): 区间内无气球 → 0
//       最后戳 k=4: val[0]*val[4]*val[5] = 1*8*1 = 8
//       总计 = dp(0,4) + 8 + dp(4,5) = dp(0,4) + 8
//
//     假设 k=1（气球3最后戳）:
//       先解决 (0,1): 无气球 → 0
//       先解决 (1,5): 戳完 1,5,8
//       最后戳 k=1: val[0]*val[1]*val[5] = 1*3*1 = 3
//       总计 = 0 + 3 + dp(1,5)
//
//     ... 取所有 k 中的最大值
// ============================================================
class Solution2 {
public:
    int maxCoins(vector<int>& nums) {
        int n = nums.size();
        // 构造带虚拟边界的数组
        vector<int> val(n + 2);
        val[0] = val[n + 1] = 1;
        for (int i = 0; i < n; i++) val[i + 1] = nums[i];
        
        vector<vector<int>> memo(n + 2, vector<int>(n + 2, -1));
        return solve(val, memo, 0, n + 1);
    }
    
private:
    int solve(vector<int>& val, vector<vector<int>>& memo, int i, int j) {
        // 开区间 (i,j) 内不足1个气球 → 无法戳，收益为0
        if (j - i < 2) return 0;
        if (memo[i][j] != -1) return memo[i][j];
        
        int best = 0;
        // 枚举 k: 开区间 (i,j) 内最后被戳破的气球
        for (int k = i + 1; k < j; k++) {
            // k 最后被戳时，(i,k) 和 (k,j) 已清空
            // k 的左右邻居确定为 i 和 j
            int coins = val[i] * val[k] * val[j];
            int total = solve(val, memo, i, k)   // 左子区间
                      + coins                      // 戳破 k 的收益
                      + solve(val, memo, k, j);    // 右子区间
            best = max(best, total);
        }
        return memo[i][j] = best;
    }
};

// ============================================================
// 解法3: 区间 DP 递推（自底向上）
// 时间: O(n³)  空间: O(n²)
//
// 【思路】
// 把解法2的递归翻译成循环。
// 关键是遍历方向：区间长度从小到大枚举。
// dp[i][j] 依赖 dp[i][k] 和 dp[k][j]，它们的区间长度都更短，
// 所以只要按长度递增枚举，依赖的状态一定已经计算完毕。
//
// DP 填表过程（nums = [3,1,5,8]）：
//
//   val = [1, 3, 1, 5, 8, 1]   下标 0~5
//   dp[i][j] = 开区间 (i,j) 内最大硬币
//
//   len=2 (区间内1个气球):
//     dp[0][2]: k=1 → 1*3*1=3                          → 3
//     dp[1][3]: k=2 → 3*1*5=15                         → 15
//     dp[2][4]: k=3 → 1*5*8=40                         → 40
//     dp[3][5]: k=4 → 5*8*1=40                         → 40
//
//   len=3 (区间内2个气球):
//     dp[0][3]: k=1 → 0+1*3*5+15=30
//               k=2 → 3+1*1*5+0=8                      → 30
//     dp[1][4]: k=2 → 0+3*1*8+40=64
//               k=3 → 15+3*5*8+0=135                   → 135
//     dp[2][5]: k=3 → 0+1*5*1+40=45
//               k=4 → 40+1*8*1+0=48                    → 48
//
//   len=4 (区间内3个气球):
//     dp[0][4]: k=1 → 0+1*3*8+135=159
//               k=2 → 3+1*1*8+40=51
//               k=3 → 30+1*5*8+0=70                    → 159
//     dp[1][5]: k=2 → 0+3*1*1+48=51
//               k=3 → 15+3*5*1+40=70
//               k=4 → 135+3*8*1+0=159                  → 159
//
//   len=5 (全部4个气球):
//     dp[0][5]: k=1 → 0+1*3*1+159=162
//               k=2 → 3+1*1*1+48=52
//               k=3 → 30+1*5*1+40=75
//               k=4 → 159+1*8*1+0=167                  → 167 ✓
// ============================================================
class Solution3 {
public:
    int maxCoins(vector<int>& nums) {
        int n = nums.size();
        
        // 构造带虚拟边界的数组
        vector<int> val(n + 2);
        val[0] = val[n + 1] = 1;
        for (int i = 0; i < n; i++) val[i + 1] = nums[i];
        
        // dp[i][j] = 开区间 (i,j) 内戳破所有气球能获得的最大硬币
        // 初始化全为0（开区间内无气球时硬币为0）
        vector<vector<int>> dp(n + 2, vector<int>(n + 2, 0));
        
        // 外层: 按区间长度从小到大枚举
        // len 表示 j - i 的值
        // len=0,1 时 (i,j) 内无气球，dp 已为 0
        // len=2 开始有意义（区间内恰好1个气球）
        for (int len = 2; len <= n + 1; len++) {
            // 内层: 枚举左端点 i
            for (int i = 0; i + len <= n + 1; i++) {
                int j = i + len;
                // 最内层: 枚举 k = 区间 (i,j) 内最后被戳的气球
                for (int k = i + 1; k < j; k++) {
                    // dp[i][k]: 左子区间已全部戳完的最大收益
                    // dp[k][j]: 右子区间已全部戳完的最大收益
                    // val[i]*val[k]*val[j]: 最后戳 k 时的收益
                    int total = dp[i][k] + val[i] * val[k] * val[j] + dp[k][j];
                    dp[i][j] = max(dp[i][j], total);
                }
            }
        }
        
        // 答案: 开区间 (0, n+1) 内的最大硬币
        return dp[0][n + 1];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 时间      | 空间   | 特点                          |
// |------------|-----------|--------|-------------------------------|
// | 暴力回溯    | O(n!*n)   | O(n)   | 仅用于理解题意                  |
// | 记忆化搜索  | O(n³)     | O(n²)  | 自顶向下，代码直觉，不怕遍历方向 |
// | 区间DP递推  | O(n³)     | O(n²)  | 自底向上，需要正确的遍历方向      |
//
// 记忆化搜索 vs 递推：
// - 记忆化搜索更容易写对（不需要想遍历方向），面试中推荐
// - 递推在某些场景可以进一步做空间优化（但本题区间DP难以优化空间）
// - 两者本质完全相同，时间空间复杂度一致
//
// ============================================================
// 【易错点】
//
// 1. 正向 vs 逆向思维：
//    ✗ 枚举"第一个戳的"气球 → 戳完后邻居变化，左右不独立
//    ✓ 枚举"最后一个戳的"气球 k → k 戳时邻居确定为 val[i] 和 val[j]
//
// 2. 忘记虚拟边界：
//    ✗ 直接在原 nums 上做，边界处 nums[-1] 和 nums[n] 的处理混乱
//    ✓ 构造 val = [1, nums[0], ..., nums[n-1], 1]，统一处理
//
// 3. 开区间 vs 闭区间搞混：
//    ✗ dp[i][j] 定义为闭区间 [i,j]，则 k 最后戳时邻居不是 i/j 本身
//       而是 i 外面和 j 外面的气球，状态定义和转移都会很混乱
//    ✓ 用开区间 (i,j)，i 和 j 是"墙"不参与戳破，k∈(i,j) 最后戳时
//       看到的就是墙 i 和墙 j
//
// 4. k 的枚举范围：
//    ✗ for (int k = i; k <= j; k++)  // k 包含了边界 i 和 j
//    ✓ for (int k = i + 1; k < j; k++)  // 开区间内部
//
// 5. 记忆化搜索的 base case：
//    ✗ 忘记 j - i < 2 返回 0 → 递归没有终止条件
//    ✓ j - i < 2 时开区间内无气球，返回 0
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么贪心不行？比如每次戳当前能获得最多硬币的气球？
// A1: 反例 [1,5,1]：贪心先戳 5（得 1*5*1=5），再戳两个 1（各得 1），
//     总共 7。但最优是先戳两个 1（各得 5），再戳 5（得 5），总共 15。
//     贪心的局部最优不等于全局最优，因为戳破一个气球会改变其他气球的收益。
//
// Q2: 这道题的子问题为什么要用"开区间"来定义？
// A2: 开区间的边界 i 和 j 充当"墙"的角色。当 k 是区间内最后被戳的，
//     k 左右已清空，其邻居就是两面墙 i 和 j，收益确定为 val[i]*val[k]*val[j]。
//     如果用闭区间，k 最后戳时看到的邻居是闭区间外面的元素，而那些元素
//     可能属于外层的其他子问题，定义会很混乱。
//
// Q3: 本题能否进一步优化到 O(n²)？
// A3: 一般来说不行。区间 DP 的三重循环（区间长度、左端点、分割点）
//     在本题中无法避免。Knuth 优化需要满足四边形不等式，
//     而本题的代价函数 val[i]*val[k]*val[j] 不满足此条件。
//     O(n³) 对于 n=300 约 2.7*10^7，可以通过。
//
// Q4: 如果改成环形排列（首尾相连）怎么做？
// A4: 经典"环形→线性"技巧：将数组复制一份拼接（或枚举断开点），
//     对每个线性版本做区间 DP，取所有结果的最大值。
//     时间复杂度变为 O(n⁴)，但可以用一些技巧优化。
// ============================================================
