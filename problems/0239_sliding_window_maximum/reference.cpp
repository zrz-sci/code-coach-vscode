/*
 * LeetCode 239: 滑动窗口最大值 (Sliding Window Maximum)
 *
 * 【题目本质】
 * 在一个固定大小 k 的滑动窗口中，高效维护最大值。
 * 核心挑战：窗口每次只变化一个元素，如何避免重复扫描 k 个元素？
 *
 * 【解法总览】
 * 解法1: 暴力法        — O(nk) / O(1)     — 每个窗口扫描k个元素
 * 解法2: 最大堆+懒删除 — O(n log n) / O(n) — 堆顶取最大，过期懒删除
 * 解法3: 单调队列      — O(n) / O(k)      — 维护递减双端队列（面试首选）
 */

// ============================================================
// 解法1: 暴力法 — 每个窗口位置扫描 k 个元素取最大值
// 时间: O(nk)  空间: O(1)（不算输出数组）
//
// 【思路】
// 最直觉的做法：对每个可能的窗口起始位置 i，遍历 [i, i+k-1] 找最大值。
// 瓶颈：窗口滑动一步只变了 1 个元素，但我们重新扫描了 k 个元素。
// n=10^5, k=10^5 时约 10^10 次操作，必然超时。
// ============================================================
class Solution1 {
public:
    vector<int> maxSlidingWindow(vector<int>& nums, int k) {
        int n = nums.size();
        vector<int> result;
        result.reserve(n - k + 1);
        
        for (int i = 0; i <= n - k; i++) {
            int maxVal = nums[i];
            for (int j = i + 1; j < i + k; j++) {
                maxVal = max(maxVal, nums[j]);
            }
            result.push_back(maxVal);
        }
        return result;
    }
};

// ============================================================
// 解法2: 最大堆 + 懒删除
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 暴力解的瓶颈是"每次重新找最大值"。最大堆能 O(1) 返回最大值。
// 
// 难点：窗口滑动时，滑出的元素可能埋在堆的中间，标准堆不支持
// 删除任意位置的元素。
//
// 解决方案 — 懒删除：
// 不主动删除滑出窗口的元素，而是在取堆顶时检查：
// 如果堆顶元素的下标已经不在窗口 [i-k+1, i] 内，就弹掉。
// 这样堆中可能有 > k 个元素，但不影响正确性。
//
// 为什么是 O(n log n) 而不是 O(n log k)？
// 考虑递增序列 [1,2,3,...,n]：没有元素会被懒删除提前弹出，
// 堆的大小会增长到 n，每次插入 O(log n)。
// ============================================================
class Solution2 {
public:
    vector<int> maxSlidingWindow(vector<int>& nums, int k) {
        int n = nums.size();
        vector<int> result;
        result.reserve(n - k + 1);
        
        // 最大堆，存 (值, 下标)，pair 默认先比较 first（值大的在堆顶）
        priority_queue<pair<int, int>> pq;
        
        for (int i = 0; i < n; i++) {
            // 新元素入堆
            pq.push({nums[i], i});
            
            // 懒删除：堆顶如果已滑出窗口（下标 < i-k+1），弹掉
            // 注意是 while 不是 if —— 可能连续多个堆顶都过期
            while (pq.top().second < i - k + 1) {
                pq.pop();
            }
            
            // 当窗口满了（已有 k 个元素）时开始收集答案
            if (i >= k - 1) {
                result.push_back(pq.top().first);
            }
        }
        return result;
    }
};

// ============================================================
// 解法3: 单调队列（双端队列） — 面试首选 ⭐
// 时间: O(n)  空间: O(k)
//
// 【思路】
// 核心洞察：
// 如果 nums[j] <= nums[i] 且 j < i（j 在 i 左边），
// 那么在任何包含 i 的窗口中，j 永远不可能是最大值：
//   - j 比 i 更早滑出窗口（j 下标更小）
//   - j 的值还不如 i 大
// 所以 j 是"无用"的，可以直接丢弃。
//
// 基于此，维护一个双端队列（deque），存储下标：
//   - 队列中对应的值从队首到队尾 **严格递减**
//   - 队首元素就是当前窗口的最大值
//
// 三个操作（每次循环按顺序执行）：
// 1. 弹队首过期元素：下标 < i-k+1 的已滑出窗口
// 2. 弹队尾无用元素：值 <= nums[i] 的旧元素没有存在价值
// 3. 新元素从队尾入队
//
// 摊还分析：每个元素最多入队 1 次、出队 1 次 → 总操作 O(2n) = O(n)
//
// 工作过程示意 (nums = [1,3,-1,-3,5,3,6,7], k=3):
//
// i=0: nums[0]=1
//      deque: [] → 入队 → [0]
//      队列对应值: [1]
//      窗口 [1] 未满, 不输出
//
// i=1: nums[1]=3
//      弹队尾: nums[0]=1 <= 3, 弹出0 → deque=[]
//      入队 → [1]
//      队列对应值: [3]
//      窗口 [1,3] 未满, 不输出
//
// i=2: nums[2]=-1
//      弹队尾: nums[1]=3 > -1, 不弹
//      入队 → [1, 2]
//      队列对应值: [3, -1]   ← 单调递减 ✓
//      窗口 [1,3,-1] 已满 → 输出 nums[1]=3
//
// i=3: nums[3]=-3
//      弹队首: 1 >= 3-3+1=1, 不弹（还在窗口内）
//      弹队尾: nums[2]=-1 > -3, 不弹
//      入队 → [1, 2, 3]
//      队列对应值: [3, -1, -3] ← 单调递减 ✓
//      窗口 [3,-1,-3] → 输出 nums[1]=3
//
// i=4: nums[4]=5
//      弹队首: 1 < 4-3+1=2, 弹出1 → [2, 3]
//      弹队尾: nums[3]=-3 <= 5, 弹3 → [2]
//              nums[2]=-1 <= 5, 弹2 → []
//      入队 → [4]
//      队列对应值: [5]
//      窗口 [-1,-3,5] → 输出 nums[4]=5
//
// i=5: nums[5]=3
//      弹队首: 4 >= 5-3+1=3, 不弹
//      弹队尾: nums[4]=5 > 3, 不弹
//      入队 → [4, 5]
//      队列对应值: [5, 3] ← 单调递减 ✓
//      窗口 [-3,5,3] → 输出 nums[4]=5
//
// i=6: nums[6]=6
//      弹队首: 4 >= 6-3+1=4, 不弹
//      弹队尾: nums[5]=3 <= 6, 弹5 → [4]
//              nums[4]=5 <= 6, 弹4 → []
//      入队 → [6]
//      队列对应值: [6]
//      窗口 [5,3,6] → 输出 nums[6]=6
//
// i=7: nums[7]=7
//      弹队首: 6 >= 7-3+1=5, 不弹
//      弹队尾: nums[6]=6 <= 7, 弹6 → []
//      入队 → [7]
//      队列对应值: [7]
//      窗口 [3,6,7] → 输出 nums[7]=7
//
// 最终结果: [3, 3, 5, 5, 6, 7] ✓
// ============================================================
class Solution3 {
public:
    vector<int> maxSlidingWindow(vector<int>& nums, int k) {
        int n = nums.size();
        vector<int> result;
        result.reserve(n - k + 1);
        
        // 双端队列存下标（不是值！）
        // 不变量：队列中下标对应的值从队首到队尾严格递减
        deque<int> dq;
        
        for (int i = 0; i < n; i++) {
            // Step 1: 移除过期元素
            // 窗口范围 [i-k+1, i]，队首下标如果 < i-k+1 就过期了
            while (!dq.empty() && dq.front() < i - k + 1) {
                dq.pop_front();
            }
            
            // Step 2: 维护单调性
            // 队尾所有值 <= nums[i] 的元素都永远不可能成为最大值
            // 因为 nums[i] 比它们大且存活时间更长（下标更大）
            // 用 <= 而不是 <：相等时弹掉旧的，保留新的（存活更久）
            while (!dq.empty() && nums[dq.back()] <= nums[i]) {
                dq.pop_back();
            }
            
            // Step 3: 新元素入队
            dq.push_back(i);
            
            // Step 4: 窗口形成后（至少 k 个元素），队首就是最大值
            if (i >= k - 1) {
                result.push_back(nums[dq.front()]);
            }
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 时间       | 空间  | 核心思想           | 适用场景          |
// |----------|------------|-------|--------------------|-------------------|
// | 暴力     | O(nk)      | O(1)  | 直接扫描           | k很小时可接受     |
// | 最大堆   | O(n log n) | O(n)  | 堆顶取极值+懒删除  | 通用动态极值问题  |
// | 单调队列 | O(n)       | O(k)  | 淘汰无用候选       | 滑动窗口极值专用  |
//
// 面试推荐：单调队列。如果想不到，先说堆解法也能通过。
//
// 堆 vs 单调队列：
// - 堆更通用，任何需要动态维护极值的场景都能用
// - 单调队列利用了"滑动窗口"的特殊结构（元素按顺序过期），更高效
// - 单调队列本质是"淘汰永远不可能成为答案的元素"
//
// ============================================================
// 【易错点】
//
// 1. 队列存值而不存下标：
//    ✗ dq.push_back(nums[i])  → 无法判断队首是否已过期
//    ✓ dq.push_back(i)        → 用 dq.front() < i-k+1 判断过期
//
// 2. 弹出条件用 < 而不是 <=：
//    ✗ nums[dq.back()] < nums[i]  → 相等元素不弹，旧的可能过期后仍在队列
//    ✓ nums[dq.back()] <= nums[i] → 相等时弹旧保新，因为新的存活时间更长
//
// 3. 堆解法用 if 而不是 while 做懒删除：
//    ✗ if (pq.top().second < i - k + 1) pq.pop();
//       → 只弹一个，但堆顶下面可能连续多个都过期
//    ✓ while (pq.top().second < i - k + 1) pq.pop();
//
// 4. 窗口形成的条件判断错误：
//    ✗ if (i >= k)     → 少输出第一个窗口的结果
//    ✓ if (i >= k - 1) → 第 k-1 个元素进来时窗口恰好满
//
// 5. 结果数组忘记 reserve：
//    不影响正确性，但 n=10^5 时频繁 push_back 扩容有性能影响。
//    结果长度为 n-k+1，提前 reserve 更好。
//
// ============================================================
// 【面试追问】
//
// Q1: 暴力解瓶颈在哪？堆怎么优化？
//     → 暴力 O(nk)，瓶颈在每次重新扫描 k 个元素找最大值。
//       堆 O(1) 取最大值，O(log n) 插入，总 O(n log n)。
//       难点在删除：用懒删除，取堆顶时检查是否过期。
//
// Q2: 单调队列的核心洞察是什么？为什么不会漏解？
//     → 如果 a 在 b 左边且 a <= b，a 永远不可能是包含 b 的窗口的最大值。
//       被弹出的元素一定不会是任何未来窗口的答案，所以不会漏。
//
// Q3: 严格证明单调队列的时间复杂度是 O(n)？
//     → 摊还分析：每个下标最多入队 1 次（push_back），最多出队 1 次
//       （pop_front 或 pop_back），总操作 ≤ 2n。
//
// Q4: 如果改成求滑动窗口最小值？
//     → 维护单调递增队列：队尾弹出条件改为 >= nums[i]。
//
// Q5: 如果需要同时维护最大值和最小值？（如 LeetCode 1438）
//     → 同时维护两个单调队列，一个递减（跟踪最大），一个递增（跟踪最小）。
//       当 max - min > limit 时收缩左边界。
//
// Q6: 单调队列还能解决哪些问题？
//     → "下一个更大元素"（单调栈，和单调队列同族）
//     → 前缀和 + 单调队列求最短子数组（LeetCode 862）
//     → DP 优化：当转移方程中有 max/min 且范围是滑动窗口时
// ============================================================
