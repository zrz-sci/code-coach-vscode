/*
 * LeetCode 2841: 几乎唯一子数组的最大和
 * Maximum Sum of Almost Unique Subarray
 *
 * 【题目本质】
 * 在数组中找长度为 k 的子数组，要求包含至少 m 个不同元素（"几乎唯一"），
 * 返回所有满足条件的子数组中最大的和。不存在则返回 0。
 *
 * 【核心技巧】
 * 固定长度滑动窗口 + 哈希表维护频率
 * - 窗口右移时：加入右端新元素，移除左端旧元素
 * - freq.size() = 窗口内不同元素个数
 * - 频率降为 0 时必须 erase，否则 size 不准
 *
 * 【解法总览】
 * 解法1: 滑动窗口（统一写法）  — O(n) / O(k) — 面试首选
 * 解法2: 滑动窗口（两阶段写法）— O(n) / O(k) — 逻辑更清晰的变体
 */

// ============================================================
// 解法1: 滑动窗口 — 统一写法 ⭐
// 时间: O(n)  空间: O(k)
//
// 【思路】
// 维护长度为 k 的窗口在数组上滑动。
// 用 unordered_map<int,int> freq 记录窗口内每个值的出现次数。
// freq.size() 就是不同元素的个数。
// 窗口和 sum 也用增量更新，避免重复求和。
//
// 【窗口滑动过程详解】
//
// 示例: nums = [2, 6, 7, 3, 1, 7], m = 3, k = 4
//
// i=0: 加入2  窗口[2]        freq={2:1}            sum=2
// i=1: 加入6  窗口[2,6]      freq={2:1,6:1}        sum=8
// i=2: 加入7  窗口[2,6,7]    freq={2:1,6:1,7:1}    sum=15
// i=3: 加入3  窗口[2,6,7,3]  freq={2:1,6:1,7:1,3:1}
//      ┌─────────────┐
//      │ 2  6  7  3 │ 1  7   distinct=4>=3 ✓ sum=18 → res=18
//      └─────────────┘
// i=4: 加入1, 移除2(freq=0→erase)
//         ┌─────────────┐
//      2 │ 6  7  3  1 │ 7    freq={6:1,7:1,3:1,1:1}
//         └─────────────┘     distinct=4>=3 ✓ sum=17 → res=18
// i=5: 加入7, 移除6(freq=0→erase)
//            ┌─────────────┐
//      2  6 │ 7  3  1  7 │  freq={7:2,3:1,1:1}
//            └─────────────┘ distinct=3>=3 ✓ sum=18 → res=18
//
// 答案: 18
//
// 示例: nums = [1,2,1,2,1,2,1], m = 3, k = 3
// 所有窗口: [1,2,1] [2,1,2] [1,2,1] [2,1,2] [1,2,1]
// 每个窗口只有 2 个不同元素 < 3 → res 始终为 0
//
// 【为什么 erase 不能省？】
// 假设窗口 [5,9,9] 移除左端 5 时：
//   freq[5]-- → freq[5]=0
//   如果不 erase：freq = {5:0, 9:2}，size=2（包含了"幽灵键"5）
//   如果 erase：  freq = {9:2}，size=1（正确！）
// ============================================================
class Solution1 {
public:
    long long maxSum(vector<int>& nums, int m, int k) {
        int n = nums.size();
        unordered_map<int, int> freq;  // 值 → 窗口内出现次数
        long long sum = 0;  // 当前窗口和（必须 long long！）
        long long res = 0;  // 答案（初始0：不存在满足条件的窗口时返回0）

        for (int i = 0; i < n; i++) {
            // ---- Step 1: 右端元素加入窗口 ----
            freq[nums[i]]++;
            sum += nums[i];

            // ---- Step 2: 窗口超过 k，移除左端 ----
            if (i >= k) {
                int left = nums[i - k];  // 刚被移出窗口的元素
                freq[left]--;
                // 频率降为 0 时必须 erase！否则 freq.size() 不准确
                if (freq[left] == 0) {
                    freq.erase(left);
                }
                sum -= left;
            }

            // ---- Step 3: 窗口大小恰好为 k 时判断 ----
            // i >= k-1 表示窗口已有 k 个元素
            if (i >= k - 1 && (int)freq.size() >= m) {
                res = max(res, sum);
            }
        }
        return res;
    }
};

// ============================================================
// 解法2: 滑动窗口 — 两阶段写法
// 时间: O(n)  空间: O(k)
//
// 【思路】
// 把"建立初始窗口"和"窗口右移"分成两个阶段。
// 逻辑和解法1 完全等价，但更直观。
//
// 阶段1: 先把前 k 个元素放入窗口，建立初始状态
// 阶段2: 窗口每右移一步，加入 nums[i]，移除 nums[i-k]
//
// 示例: nums = [5,9,9,2,4,5,4], m = 1, k = 3
//
// 阶段1: 建立窗口 [5,9,9]
//   freq={5:1,9:2}, sum=23, distinct=2>=1 → res=23
//
// 阶段2:
//   i=3: 加入2, 移除5 → [9,9,2]  sum=20 distinct=2>=1 → res=23
//   i=4: 加入4, 移除9 → [9,2,4]  sum=15 distinct=3>=1 → res=23
//   i=5: 加入5, 移除9 → [2,4,5]  sum=11 distinct=3>=1 → res=23
//   i=6: 加入4, 移除2 → [4,5,4]  sum=13 distinct=2>=1 → res=23
//
// 答案: 23
// ============================================================
class Solution2 {
public:
    long long maxSum(vector<int>& nums, int m, int k) {
        int n = nums.size();
        unordered_map<int, int> freq;
        long long sum = 0, res = 0;

        // ---- 阶段1: 建立初始窗口 [0, k-1] ----
        for (int i = 0; i < k; i++) {
            freq[nums[i]]++;
            sum += nums[i];
        }
        // 检查初始窗口是否满足条件
        if ((int)freq.size() >= m) {
            res = sum;
        }

        // ---- 阶段2: 窗口从位置 k 开始右移 ----
        for (int i = k; i < n; i++) {
            // 加入右端新元素
            freq[nums[i]]++;
            sum += nums[i];

            // 移除左端旧元素
            int left = nums[i - k];
            freq[left]--;
            if (freq[left] == 0) {
                freq.erase(left);
            }
            sum -= left;

            // 判断当前窗口
            if ((int)freq.size() >= m) {
                res = max(res, sum);
            }
        }

        return res;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法                  | 时间 | 空间 | 代码风格    |
// |----------------------|------|------|------------|
// | 统一写法 (Solution1)  | O(n) | O(k) | 简洁紧凑   |
// | 两阶段写法 (Solution2) | O(n) | O(k) | 逻辑清晰   |
//
// 两种写法等价，选择看个人偏好。面试中两种都能得满分。
//
// ============================================================
// 【固定长度滑动窗口模板】
//
// for (int i = 0; i < n; i++) {
//     // 1. 加入右端
//     add(nums[i]);
//
//     // 2. 超过窗口大小时移除左端
//     if (i >= k) {
//         remove(nums[i - k]);
//     }
//
//     // 3. 窗口大小达到 k 时更新答案
//     if (i >= k - 1) {
//         update_answer();
//     }
// }
//
// 这个模板适用于所有"固定窗口大小"的问题：
// - 本题: add/remove 操作频率哈希表 + 窗口和
// - 438题: add/remove 操作字符频率数组
// - 1343题: add/remove 操作窗口和 + 判断均值
//
// ============================================================
// 【易错点】
//
// 1. 频率为 0 时不 erase:
//    ✗ freq[left]--; 完事 → freq.size() 包含频率为 0 的键
//    ✓ if (freq[left] == 0) freq.erase(left);
//
// 2. sum 用 int:
//    ✗ int sum = 0; → 溢出！k=20000, nums[i]=10^9, sum 最大 2*10^13
//    ✓ long long sum = 0;
//
// 3. 判断时机搞错:
//    ✗ if (i >= k)    → 漏掉第一个窗口 [0..k-1]
//    ✓ if (i >= k - 1) → 窗口刚填满时就判断
//
// 4. 移除元素的索引算错:
//    ✗ nums[i - k + 1] → 这是窗口内的左端点
//    ✓ nums[i - k]     → 这是刚被移出窗口的元素
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 为什么用 unordered_map 而不是 map？
//     unordered_map 增删查平均 O(1)，map 是 O(log k)。
//     总时间 O(n) vs O(n log k)。
//
// Q2: 能不能不用 erase？
//     可以。维护额外变量 distinctCount：
//     加入时 if(++freq[x]==1) distinctCount++;
//     移除时 if(--freq[x]==0) distinctCount--;
//     这样 freq 中有冗余键但不影响 distinctCount 的准确性。
//
// Q3: 窗口大小不固定（找和最大且不同元素>=m 的最长子数组）？
//     变成可变长度窗口问题，需要前缀和+滑动窗口的组合。
//
// Q4: 如果 k 比 n 大？
//     不会出现。题目约束 1 <= m <= k <= nums.length。
//
// ============================================================
// 【相关题型】
//
// - 3. 无重复字符的最长子串:
//   可变长度窗口 + 哈希表。本题的 freq 维护手法完全适用。
//
// - 438. 找到字符串中所有字母异位词:
//   固定长度窗口 + 频率数组比较。和本题结构非常相似。
//
// - 567. 字符串的排列:
//   判断 s1 的排列是否是 s2 的子串。固定窗口 + 频率匹配。
//
// - 992. K 个不同整数的子数组:
//   用"至多K个 - 至多K-1个"转化，可变窗口解决。
