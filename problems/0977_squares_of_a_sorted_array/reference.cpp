/*
 * LeetCode 977: 有序数组的平方 (Squares of a Sorted Array)
 *
 * 【题目本质】
 * 有序数组含负数，平方后"两头大中间小"(V形)，
 * 利用这个结构用双指针 O(n) 排好序。
 *
 * 【解法总览】
 * 解法1: 暴力排序        — O(n log n) / O(1)   — 最直觉，没利用有序性
 * 解法2: 双指针(两端→中间) — O(n) / O(n)        — ⭐面试首选
 * 解法3: 双指针(归并思想)   — O(n) / O(n)        — 展示归并merge能力
 */

// ============================================================
// 解法1: 暴力排序 — 平方后直接排序
// 时间: O(n log n)  空间: O(1)（不算返回数组）或 O(n)
//
// 【思路】
// 最朴素的翻译题意：先平方，再排序。
// 完全没利用"原数组有序"的信息，所以有优化空间。
// 面试中作为起点，然后主动说"瓶颈在排序，可以利用有序性优化到 O(n)"。
// ============================================================
class Solution1 {
public:
    vector<int> sortedSquares(vector<int>& nums) {
        for (int i = 0; i < (int)nums.size(); i++) {
            nums[i] = nums[i] * nums[i];
        }
        sort(nums.begin(), nums.end());
        return nums;
    }
};

// ============================================================
// 解法2: 双指针（从两端到中间）— ⭐ 面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 关键观察：原数组有序（含负数），平方后形成 V 形结构:
//
//   原数组:   [-4, -1, 0, 3, 10]
//   绝对值:   [ 4,  1, 0, 3, 10]
//              ↑               ↑
//             left           right
//
//   绝对值最大的一定在两端之一！
//
// 所以用左右双指针，每次比较两端绝对值，
// 把大的那个的平方放到结果数组末尾（从后往前填），
// 然后对应指针向内收缩。
//
// 可视化过程: nums = [-4, -1, 0, 3, 10]
//
// pos=4: |10|>|-4| → result[4]=100, right--    result=[_,_,_,_,100]
// pos=3: |-4|>|3|  → result[3]=16,  left++     result=[_,_,_,16,100]
// pos=2: |3|>|-1|  → result[2]=9,   right--    result=[_,_,9,16,100]
// pos=1: |-1|>|0|  → result[1]=1,   left++     result=[_,1,9,16,100]
// pos=0: left==right, result[0]=0               result=[0,1,9,16,100] ✓
// ============================================================
class Solution2 {
public:
    vector<int> sortedSquares(vector<int>& nums) {
        int n = nums.size();
        vector<int> result(n);
        int left = 0, right = n - 1;

        // 从后往前填——因为每次取到的是当前最大值
        for (int pos = n - 1; pos >= 0; pos--) {
            if (abs(nums[left]) >= abs(nums[right])) {
                // 左端绝对值更大（或相等），取左端的平方
                result[pos] = nums[left] * nums[left];
                left++;
            } else {
                // 右端绝对值更大，取右端的平方
                result[pos] = nums[right] * nums[right];
                right--;
            }
        }
        return result;
    }
};

// ============================================================
// 解法3: 双指针（从中间到两端，归并思想）
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 另一个角度：原数组可以在"正负分界点"处切成两段：
//   负数段（向左走，平方递增）和 非负段（向右走，平方递增）
// 这就是两个有序数组，做一次归并 merge 即可。
//
// 示例: [-4, -1, 0, 3, 10]
//              ↑  ↑
//            left right (分界点: 第一个非负数=0)
//
// 左段平方（向左递增）: 0² → (-1)² → (-4)²  = [0, 1, 16]
// 右段平方（向右递增）: 0² → 3² → 10²       = [0, 9, 100]
//
// 注意: 分界点的元素可以归入任一段，这里 right=pivot 指向它。
//
// 归并过程：每次取两段头部较小的放入结果，本质和 merge sort 的 merge 步骤一样。
// ============================================================
class Solution3 {
public:
    vector<int> sortedSquares(vector<int>& nums) {
        int n = nums.size();

        // 找到第一个非负数的位置（正负分界点）
        int pivot = 0;
        while (pivot < n && nums[pivot] < 0) {
            pivot++;
        }

        // left: 最后一个负数，向左走（绝对值递增 → 平方递增）
        // right: 第一个非负数，向右走（值递增 → 平方递增）
        int left = pivot - 1, right = pivot;
        vector<int> result;
        result.reserve(n);

        // 归并两段
        while (left >= 0 && right < n) {
            int lsq = nums[left] * nums[left];
            int rsq = nums[right] * nums[right];
            if (lsq <= rsq) {
                result.push_back(lsq);
                left--;   // 负数段向左 → 绝对值变大
            } else {
                result.push_back(rsq);
                right++;  // 正数段向右 → 值变大
            }
        }

        // 处理左段剩余
        while (left >= 0) {
            result.push_back(nums[left] * nums[left]);
            left--;
        }
        // 处理右段剩余
        while (right < n) {
            result.push_back(nums[right] * nums[right]);
            right++;
        }

        return result;
    }
};

// ============================================================
// 【解法对比】
//
// |          | 解法1 暴力排序     | 解法2 双指针(两端) | 解法3 双指针(归并) |
// |----------|-------------------|-------------------|-------------------|
// | 时间     | O(n log n)        | O(n)              | O(n)              |
// | 空间     | O(1)              | O(n)              | O(n)              |
// | 代码量   | 最少(3行)         | 适中(10行)        | 较多(20行)        |
// | 核心思路 | 无技巧            | 最大在两端,后→前填 | 找分界点做归并     |
// | 推荐场景 | 快速写出/说出即可  | ⭐ 面试首选        | 展示归并思想       |
//
// 面试建议：先说解法1表示理解题意，然后直接写解法2。
// 解法2代码最精炼：一个 for 循环、一个 if-else，逻辑清晰。
//
// 【易错点】
//
// 1. 填充方向搞反：
//    ✗ for(int pos=0; pos<n; pos++) — 每次取的是最大值，从前往后填会把大的放前面
//    ✓ for(int pos=n-1; pos>=0; pos--) — 最大值放末尾，逐步向前填
//
// 2. 比较时忘记取绝对值：
//    ✗ if(nums[left] >= nums[right]) — 当 nums[left]=-4 < nums[right]=3，
//      但 |-4|=4 > |3|=3，应该取左端
//    ✓ if(abs(nums[left]) >= abs(nums[right]))
//
// 3. 解法3分界点边界：
//    ✗ while(pivot<n && nums[pivot]<=0) — 把 0 归入负数段，虽然不影响正确性
//      但概念上 0 应归入非负段
//    ✓ while(pivot<n && nums[pivot]<0) — 严格找第一个非负数
//
// 4. 全正/全负数组不需特判：
//    全正: left=0 不会被选中（right端绝对值总是更大），正确
//    全负: right=n-1 不会被选中（left端绝对值总是更大），正确
//    空数组: 题目约束 n>=1，不用处理
//
// 【面试追问】
//
// Q1: "暴力解能过吗？瓶颈在哪？"
//     → 能过(n≤10⁴)，瓶颈在排序 O(n log n)，没利用原数组有序的性质。
//
// Q2: "能否 O(n)？为什么双指针能做到？"
//     → 平方后绝对值最大的在两端，左右指针每次处理一个元素，
//       总共 n 次，所以 O(n)。
//
// Q3: "如果不允许额外空间（原地），能 O(n) 吗？"
//     → 不能。双指针填充需要新数组，否则会覆盖未处理元素。
//       要么 O(n) 空间 + O(n) 时间，要么 O(1) 空间 + O(n log n) 时间。
//
// Q4: "如果数组全是正数或全是负数，你的代码需要改吗？"
//     → 不需要。全正时 right 一直被选中，全负时 left 一直被选中，
//       逻辑自然覆盖，这正是好代码的体现。
// ============================================================
