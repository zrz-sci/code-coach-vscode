/*
 * LeetCode 190: Reverse Bits (颠倒二进制位)
 *
 * 【题目本质】
 * 将32位整数的二进制位完全反转。
 * 核心问题：如何高效地把第i位放到第(31-i)位？
 *
 * 【解法总览】
 * 解法1: 逐位翻转      — O(1) / O(1)     — 面试首选，循环32次逐位取放
 * 解法2: 分治位操作    — O(1) / O(1)     — 进阶，5步mask交换
 * 解法3: 查找表        — O(1) / O(256)   — Follow-up最佳，预计算8位翻转
 */

// ============================================================
// 解法1: 逐位翻转 — 面试首选 ⭐
// 时间: O(1)  空间: O(1)  (固定32次迭代)
//
// 【思路】
// 把32位整数想象成长度为32的bit数组，要做的就是逆序。
// 每次迭代：
//   1. res 左移1位，腾出最低位
//   2. 取 n 的最低位 (n & 1)，放到 res 的最低位
//   3. n 右移1位，准备取下一位
// 循环32次，所有位都被翻转。
//
// 为什么必须循环恰好32次？
//   如果用 while(n)，n=1 时只循环1次，结果是1。
//   但正确结果应该是 1<<31（最低位翻转到最高位），
//   高位的0也要参与翻转。
//
// 示例: n = 43261596 (00000010100101000001111010011100)
//   第1次: 取末位0, res=0
//   第2次: 取末位0, res=0
//   第3次: 取末位1, res=1
//   ...32次后...
//   res = 964176192 (00111001011110000010100101000000) ✓
// ============================================================
class Solution1 {
public:
    int reverseBits(int n) {
        int res = 0;
        for (int i = 0; i < 32; i++) {
            // 先左移res腾出空间，再把n的末位拼上去
            res = (res << 1) | (n & 1);
            // n右移，下一轮取下一位
            n >>= 1;
        }
        return res;
    }
};

// ============================================================
// 解法2: 分治位操作
// 时间: O(1)  空间: O(1)  (5步常数操作)
//
// 【思路】
// 类似归并排序的逆操作，分层交换bit组：
//   第1步: 交换所有相邻的1位对  (01和10位交换, 23和32位交换, ...)
//   第2步: 交换所有相邻的2位组  (0-1和2-3交换, 4-5和6-7交换, ...)
//   第3步: 交换所有相邻的4位组  (nibble交换)
//   第4步: 交换所有相邻的8位组  (byte交换)
//   第5步: 交换高16位和低16位
//
// mask的含义:
//   0x55555555 = 01010101 01010101 01010101 01010101  → 奇数位mask
//   0x33333333 = 00110011 00110011 00110011 00110011  → 每2位中低位mask
//   0x0f0f0f0f = 00001111 00001111 00001111 00001111  → 每4位中低位mask
//   0x00ff00ff = 00000000 11111111 00000000 11111111  → 每8位中低位mask
//   0x0000ffff = 00000000 00000000 11111111 11111111  → 低16位mask
//
// 8位简化示例: abcdefgh
//   步骤1 (交换相邻1位): badcfehg
//   步骤2 (交换相邻2位): dcbahgfe
//   步骤3 (交换相邻4位): hgfedcba ✓
// ============================================================
class Solution2 {
public:
    int reverseBits(int n) {
        // 第1步：交换相邻的单个bit
        n = ((n & 0x55555555) << 1)  | ((n >> 1)  & 0x55555555);
        // 第2步：交换相邻的2-bit组
        n = ((n & 0x33333333) << 2)  | ((n >> 2)  & 0x33333333);
        // 第3步：交换相邻的4-bit组（nibble）
        n = ((n & 0x0f0f0f0f) << 4)  | ((n >> 4)  & 0x0f0f0f0f);
        // 第4步：交换相邻的字节（byte）
        n = ((n & 0x00ff00ff) << 8)  | ((n >> 8)  & 0x00ff00ff);
        // 第5步：交换高低16位
        n = ((n & 0x0000ffff) << 16) | ((n >> 16) & 0x0000ffff);
        return n;
    }
};

// ============================================================
// 解法3: 查找表 — Follow-up 多次调用优化
// 时间: O(1)  空间: O(256)  (预计算表)
//
// 【思路】
// Follow-up 问"如果多次调用怎么优化"。
// 核心思想：预计算所有 0~255 的8位翻转值，
// 然后把32位拆成4个字节，查表拼接。
//
// 为什么选8位一组？
//   - 4位一组：表只需16项，但每次要查8次 → 查表次数多
//   - 8位一组：表需256项，每次查4次 → 平衡点
//   - 16位一组：表需65536项，占内存太大
//
// 拼接逻辑：
//   原始: [byte3][byte2][byte1][byte0]  (byte0是最低8位)
//   翻转: [rev(byte0)][rev(byte1)][rev(byte2)][rev(byte3)]
//   即: rev(byte0)放到最高8位，rev(byte3)放到最低8位
// ============================================================
class Solution3 {
    int table[256];

    // 预计算所有8位值的翻转结果
    void buildTable() {
        for (int i = 0; i < 256; i++) {
            int rev = 0, val = i;
            for (int j = 0; j < 8; j++) {
                rev = (rev << 1) | (val & 1);
                val >>= 1;
            }
            table[i] = rev;
        }
    }

public:
    Solution3() { buildTable(); }

    int reverseBits(int n) {
        // 拆成4个字节，各自查表翻转，然后交换位置拼接
        return (table[n & 0xff] << 24)              // byte0 翻转后放到最高位
             | (table[(n >> 8)  & 0xff] << 16)       // byte1 翻转后放到次高位
             | (table[(n >> 16) & 0xff] << 8)        // byte2 翻转后放到次低位
             | (table[(n >> 24) & 0xff]);             // byte3 翻转后放到最低位
    }
};

// ============================================================
// 【解法对比】
//
// | 解法      | 时间  | 空间    | 优势                         | 劣势                     |
// |-----------|-------|---------|------------------------------|-------------------------|
// | 逐位翻转  | O(1)  | O(1)   | 最直觉，容易写对               | 32次循环，有分支          |
// | 分治操作  | O(1)  | O(1)   | 无循环，硬件友好               | mask难记，容易写错        |
// | 查找表    | O(1)  | O(256) | 多次调用最快，4次查表           | 需要预处理，占额外空间     |
//
// 面试选择：先写逐位翻转，追问优化再讲分治或查找表。
//
// ============================================================
// 【易错点】
//
// 1. while(n) 提前终止:
//    ✗ while (n) { res = (res<<1)|(n&1); n>>=1; }
//      → n=1时只循环1次，结果是1而不是2^31
//    ✓ for (int i = 0; i < 32; i++)
//      → 固定32次，高位的0也参与翻转
//
// 2. res左移位置不对:
//    ✗ res |= (n & 1); res <<= 1;
//      → 最后多左移一次，结果是正确值的2倍
//    ✓ res = (res << 1) | (n & 1);
//      → 先移再加，最后一次不会多移
//
// 3. 有符号右移补1:
//    ✗ 对int做 n >>= 1，如果n为负数（最高位为1），
//      高位会补1而不是0（算术右移）
//    ✓ 用 (unsigned)n >> 1 确保逻辑右移
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 时间复杂度是多少？
//     严格说是 O(32) = O(1)，位数固定。不依赖输入值大小。
//
// Q2: Follow-up: 多次调用怎么优化？
//     方法一：查找表。预计算256项，每次查4次。
//     方法二：记忆化。用 map 缓存已经计算过的结果。
//     方法三：分治法本身就很快（5次位运算，无循环）。
//
// Q3: 分治法的5个mask能推导出来吗？
//     第k步(0-indexed)的mask模式是：每 2^(k+1) 位中
//     低 2^k 位为1，高 2^k 位为0，然后重复铺满32位。
//
