/*
 * LeetCode 806: Number of Lines To Write String (写字符串需要的行数)
 *
 * 【题目本质】
 * 给定每个小写字母的像素宽度和一个字符串，按顺序写字符，每行最多100像素。
 * 返回总行数和最后一行的宽度。
 * 纯粹的模拟题，逐字符处理即可。
 *
 * 【解法总览】
 * 解法1: 直接模拟 — O(n) / O(1) — 唯一解法，简洁明了
 * 解法2: 稍微变体 — O(n) / O(1) — 用 accumulate 思维写，本质相同
 */

// ============================================================
// 解法1: 直接模拟 — 唯一解法 ⭐
// 时间: O(n)  空间: O(1)  n = s.length()
//
// 【思路】
// 模拟手写过程：
// - 维护当前行数 lines（初始1）和当前行已用宽度 width（初始0）
// - 对字符串中的每个字符：
//   - 查找字符宽度: widths[c - 'a']
//   - 如果当前行放不下（width + w > 100）：换行，width 重置
//   - 否则：累加到当前行
//
// 示例1: widths 全10, s = "abcdefghijklmnopqrstuvwxyz" (26个字母)
//   每个字母占10像素，一行最多放10个 (10*10=100)
//   行1: abcdefghij (100)
//   行2: klmnopqrst (100)
//   行3: uvwxyz (60)
//   答案: [3, 60] ✓
//
// 示例2: widths[0]=4, 其他=10, s = "bbbcccdddaaa"
//   b=10: 10,20,30
//   c=10: 40,50,60
//   d=10: 70,80,90
//   a=4:  94, 98 → 下一个a: 98+4=102>100 → 换行
//   行1: bbbcccdddaa (98)
//   行2: a (4)
//   答案: [2, 4] ✓
// ============================================================
class Solution1 {
public:
    vector<int> numberOfLines(vector<int>& widths, string s) {
        int lines = 1;   // 至少有一行
        int width = 0;    // 当前行已用宽度

        for (char c : s) {
            int w = widths[c - 'a'];  // 当前字符的宽度

            if (width + w > 100) {
                // 放不下，换到新行
                lines++;
                width = w;  // 当前字符写到新行的开头
            } else {
                // 放得下，累加
                width += w;
            }
        }

        return {lines, width};
    }
};

// ============================================================
// 解法2: 等价写法 — 先累加再判断
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 另一种等价的写法：先累加，如果超过100就换行。
// 逻辑和解法1完全相同，只是代码组织略有不同。
//
// 有些人更喜欢这种"先做后判断"的风格。
// ============================================================
class Solution2 {
public:
    vector<int> numberOfLines(vector<int>& widths, string s) {
        int lines = 1;
        int width = 0;

        for (char c : s) {
            int w = widths[c - 'a'];
            width += w;

            if (width > 100) {
                // 超出了，说明需要换行
                lines++;
                width = w;  // 这个字符放到新行
            }
            // width == 100 时不换行，恰好满了
        }

        return {lines, width};
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间  | 空间  | 优势           | 劣势          |
// |-----------|-------|-------|---------------|---------------|
// | 先判后累加  | O(n)  | O(1)  | 逻辑清晰       | 无            |
// | 先累加后判  | O(n)  | O(1)  | 代码更紧凑      | 可读性略差     |
//
// 两种写法本质完全相同，选择自己更顺手的即可。
//
// ============================================================
// 【易错点】
//
// 1. 行数初始化为 0:
//    ✗ int lines = 0;
//      → 第一个字符写入时不会触发换行，最终行数少1
//    ✓ int lines = 1;
//      → 至少有一行，第一个字符写在第一行
//
// 2. 换行条件用 >= 100:
//    ✗ if (width + w >= 100) → 当 width+w 恰好等于100时也换行
//      → 比如10个宽度为10的字符，应该写满一行(100)而不是换行
//    ✓ if (width + w > 100)  → 只有超过100才换行
//
// 3. 换行后 width 忘记设为当前字符宽度:
//    ✗ lines++; width = 0;
//      → 当前字符"消失了"，没有被计入任何行
//    ✓ lines++; width = w;
//      → 当前字符是新行的第一个字符
//
// 4. 字符索引越界:
//    ✗ widths[c]  → c 是 char 类型，值在 97-122 (ASCII)
//    ✓ widths[c - 'a']  → 转换为 0-25 的索引
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 如果字符集不是小写字母而是 Unicode，怎么处理？
//     widths 从固定26长的数组改为 unordered_map<char, int>
//     或 unordered_map<wchar_t, int>。查找方式从 widths[c-'a']
//     改为 widths[c]。其他逻辑完全不变。
//
// Q2: 如果要支持单词级别换行（不拆单词），怎么改？
//     先按空格分词，对每个单词计算总宽度。如果当前行放不下
//     整个单词，就换行。这就是 LeetCode 68 (Text Justification) 的简化版。
//
// Q3: 如果每行允许的宽度不同（比如第一行120，后续100），怎么处理？
