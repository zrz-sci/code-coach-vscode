/*
 * LeetCode 668: 乘法表中第k小的数 (Kth Smallest Number in Multiplication Table)
 * 难度: Hard
 * 标签: Math, Binary Search
 *
 * 【题目本质】
 * 在 m*n 的乘法表中找第 k 小的数。
 * 乘法表太大无法直接排序，使用二分答案 + 计数。
 *
 * 【解法总览】
 * 解法一: 二分答案 + 逐行计数       O(m * log(m*n)) / O(1)
 * 解法二: 二分答案 + 优化计数(提前终止) O(m * log(m*n)) / O(1)
 */


/*
 * ============================================================
 * 解法一: 二分答案 + 逐行计数
 * ============================================================
 *
 * 思路:
 *   在 [1, m*n] 上二分猜答案 x，统计乘法表中 <= x 的个数。
 *   第 i 行 (i, 2i, 3i, ..., ni) 中 <= x 的有 min(x/i, n) 个。
 *   找满足 count(x) >= k 的最小 x。
 *
 * 示例: m=3, n=3, k=5
 *   乘法表: [1,2,3], [2,4,6], [3,6,9]
 *   排序: 1,2,2,3,3,4,6,6,9 -> 第5小=3
 *
 *   二分:
 *     lo=1, hi=9, mid=5: count=3+2+1=6>=5 -> hi=5
 *     lo=1, hi=5, mid=3: count=3+1+1=5>=5 -> hi=3
 *     lo=1, hi=3, mid=2: count=2+1+0=3<5  -> lo=3
 *     lo=3=hi -> 答案=3
 *
 * 时间: O(m * log(m*n)), 空间: O(1)
 */
class Solution1 {
public:
    int findKthNumber(int m, int n, int k) {
        int lo = 1, hi = m * n;

        while (lo < hi) {
            int mid = lo + (hi - lo) / 2;
            if (countLessEqual(m, n, mid) >= k) {
                hi = mid;
            } else {
                lo = mid + 1;
            }
        }
        return lo;
    }

private:
    // 统计乘法表中 <= x 的元素个数
    int countLessEqual(int m, int n, int x) {
        int cnt = 0;
        for (int i = 1; i <= m; i++) {
            cnt += min(x / i, n);
        }
        return cnt;
    }
};


/*
 * ============================================================
 * 解法二: 二分答案 + 提前终止优化
 * ============================================================
 *
 * 思路:
 *   与解法一相同，但在 count 过程中:
 *   1. 当 x/i >= n 时，后面所有行都整行 <= x，直接算
 *   2. 当 x/i == 0 时，后面所有行都没有 <= x 的，直接返回
 *
 * 时间: O(m * log(m*n)), 最坏情况同解法一，但常数更小
 * 空间: O(1)
 */
class Solution2 {
public:
    int findKthNumber(int m, int n, int k) {
        int lo = 1, hi = m * n;

        while (lo < hi) {
            int mid = lo + (hi - lo) / 2;
            if (countLessEqual(m, n, mid) >= k) {
                hi = mid;
            } else {
                lo = mid + 1;
            }
        }
        return lo;
    }

private:
    int countLessEqual(int m, int n, int x) {
        int cnt = 0;
        for (int i = 1; i <= m; i++) {
            int q = x / i;
            if (q == 0) break;          // 后面的行更大，都是0
            if (q >= n) {
                cnt += (long long)n * (m - i + 1); // 剩余所有行都整行 <= x
                break;
            }
            cnt += q;
        }
        return cnt;
    }
};


/*
 * ============================================================
 * 【解法对比】
 *
 * | 解法              | 时间              | 空间 | 特点               |
 * |------------------|-------------------|------|-------------------|
 * | 基础二分 (解法一)   | O(m*log(m*n))    | O(1) | 简洁，面试首选       |
 * | 优化计数 (解法二)   | O(m*log(m*n))    | O(1) | 常数优化，讨论加分    |
 *
 * 面试推荐: 写解法一，口头讨论解法二的优化思路
 *
 * ============================================================
 * 【易错点】
 *
 * 1. 二分判断条件写反:
 *    ✗ count(mid) > k 时 hi = mid
 *    ✓ count(mid) >= k 时 hi = mid (找左边界，因为可能有重复值)
 *
 * 2. 整数溢出:
 *    ✗ int mid = (lo + hi) / 2
 *    ✓ int mid = lo + (hi - lo) / 2 (m*n 可达 9*10^8)
 *
 * 3. count 上限遗漏:
 *    ✗ cnt += x / i (没有和 n 取 min)
 *    ✓ cnt += min(x / i, n) (第 i 行最多 n 个元素)
 *
 * ============================================================
 * 【面试追问】
 *
 * Q1: 答案为什么一定在乘法表中？
 * → 若 x 不在乘法表中，则 count(x)==count(x-1)，
 *   x-1 也满足 count>=k，x 不可能是最小的满足者。
 *   所以左边界二分保证答案一定在乘法表中。
 *
 * Q2: 和 LC 378 (有序矩阵第k小) 的区别？
 * → 378 的矩阵行列都有序，计数用 O(m+n) 的双指针；
 *   668 是乘法表，计数用 O(m) 的逐行除法。
 *   二分框架完全相同，区别在 count 函数。
 *
 * Q3: 能否用堆来做？
 * → 可以用最小堆维护每行的最小值，类似合并 k 个有序列表。
 *   时间 O(k * log m)，当 k 很大时 (接近 m*n) 比二分慢很多。
 *   二分方法的时间和 k 无关，更优。
 * ============================================================
 */
