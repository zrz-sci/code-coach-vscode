/*
 * LeetCode 66: Plus One (加一)
 * 
 * 【题目本质】
 * 模拟竖式加法中的进位传播：从最低位加 1，处理可能的连续进位。
 * 不能转成整数（最多100位，溢出），必须在数组上原地操作。
 *
 * 【解法总览】
 * 解法1: 通用进位模拟   — O(n) / O(1) — 加法通用模板，扩展性好
 * 解法2: 提前终止优化   — O(n) / O(1) — 面试首选，简洁高效
 * 解法3: 全9特判技巧    — O(n) / O(1) — 最简洁写法
 */

// ============================================================
// 解法1: 通用进位模拟 — 加法的通用模板
// 时间: O(n)  空间: O(1) (不算返回值)
//
// 【思路】
// 完全模拟小学竖式加法：
//   初始 carry = 1 (要加的那个1)
//   从末尾往前: sum = digit + carry
//               digit = sum % 10
//               carry  = sum / 10
//   循环结束若 carry > 0，头部插入 carry
//
// 这是通用加法模板，改初始 carry 就能加任意数。
// 也适用于两数组相加（LeetCode 2, 415）。
//
// 模拟过程 (以 [2, 9, 9] 为例):
//   初始carry=1
//   i=2: sum=9+1=10, digits[2]=0, carry=1  → [2, 9, 0]
//   i=1: sum=9+1=10, digits[1]=0, carry=1  → [2, 0, 0]
//   i=0: sum=2+1=3,  digits[0]=3, carry=0  → [3, 0, 0]
//   carry=0, 无需扩展 → 返回 [3, 0, 0] ✓
//
// 模拟过程 (以 [9, 9] 为例):
//   初始carry=1
//   i=1: sum=9+1=10, digits[1]=0, carry=1  → [9, 0]
//   i=0: sum=9+1=10, digits[0]=0, carry=1  → [0, 0]
//   carry=1, 头部插入1 → [1, 0, 0] ✓
// ============================================================
class Solution1 {
public:
    vector<int> plusOne(vector<int>& digits) {
        int n = digits.size();
        int carry = 1; // 初始进位就是我们要加的 1
        
        for (int i = n - 1; i >= 0; i--) {
            int sum = digits[i] + carry;
            digits[i] = sum % 10;  // 当前位新值
            carry = sum / 10;      // 进位传给更高位
        }
        
        // 循环结束还有进位 → 原数全是9 → 在头部插入1
        if (carry > 0) {
            digits.insert(digits.begin(), carry);
        }
        
        return digits;
    }
};

// ============================================================
// 解法2: 提前终止优化 — 面试首选 ⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1的"浪费"在于：即使不再有进位，也要遍历完所有位。
// 观察：我们加的是 1，进位也只能是 1。
//   - 如果当前位 < 9：+1 后一定 < 10，不会进位 → 立即返回
//   - 如果当前位 == 9：变成 10，置为 0，进位 1 继续
// 所以不需要 carry 变量！能进入下一轮循环，进位一定是 1。
//
// 关键优化：没有进位时直接 return，跳过对高位的无用遍历。
// 虽然最坏仍是 O(n)，但平均情况只改最后一两位就结束。
// ============================================================
class Solution2 {
public:
    vector<int> plusOne(vector<int>& digits) {
        int n = digits.size();
        
        for (int i = n - 1; i >= 0; i--) {
            digits[i] += 1;          // 加上进位 (首轮是+1, 后续也是+1因为进位)
            
            if (digits[i] < 10) {
                return digits;        // 没有新进位 → 高位全不变 → 直接返回!
            }
            
            digits[i] = 0;           // digits[i]==10: 当前位置0, 进位1继续
            // 不需要 carry 变量：能走到下一轮，carry 一定是 1
        }
        
        // 所有位都进位了(原来全是9) → 结果是 1 后面跟 n 个 0
        digits.insert(digits.begin(), 1);
        return digits;
    }
};

// ============================================================
// 解法3: 全9特判技巧 — 最简洁写法
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 进一步简化解法2：
//   - 当前位 < 9: 直接 +1 返回 (不会进位)
//   - 当前位 == 9: 置 0, 继续 (会进位)
// 循环结束说明全是9 → 不用 insert, 直接构造 [1, 0, 0, ..., 0]
//
// 和解法2的区别：
//   解法2: digits[i] += 1, 然后判断 < 10
//   解法3: 先判断 < 9, 再 ++        (等价, 但避免了一次无用加法)
//   解法2: insert(begin(), 1)       需要移动 n 个元素
//   解法3: 构造新 vector(n+1, 0)    直接分配, 更干净
// ============================================================
class Solution3 {
public:
    vector<int> plusOne(vector<int>& digits) {
        int n = digits.size();
        
        for (int i = n - 1; i >= 0; i--) {
            if (digits[i] < 9) {
                digits[i]++;          // 不是9, 加1不进位, 直接返回
                return digits;
            }
            digits[i] = 0;           // 是9, 变成0, 进位继续传播
        }
        
        // 能走到这里 → 原来全是9 → 结果是 100...0 (n+1位)
        // 直接构造新数组，避免 insert 的元素移动
        vector<int> result(n + 1, 0);
        result[0] = 1;               // 第一位是1, 其余已经是0
        return result;
    }
};

