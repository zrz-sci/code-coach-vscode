// 【解法对比】
//
// | 维度         | 解法1 通用模拟    | 解法2 提前终止   | 解法3 全9特判    |
// |-------------|------------------|-----------------|-----------------|
// | 时间         | O(n) 全遍历      | O(n) 最坏       | O(n) 最坏       |
// | 平均行为     | 总是遍历所有位    | 大概率只改末位   | 大概率只改末位   |
// | 需要carry变量 | 是               | 否              | 否              |
// | 扩展性       | 易改成加任意数    | 仅适用于加1     | 仅适用于加1     |
// | 面试推荐     | 追问泛化时用      | ⭐ 首选         | 展示技巧        |
//
// 面试策略: 
//   先写解法2(简洁高效), 如果追问"加任意数怎么办", 切到解法1的carry模板
//
// 【易错点】
// 1. ✗ 把数组转 int/long 再加: 100位会溢出, 必须原地模拟
// 2. ✗ 忘处理全9的情况: [9,9] → [0,0](错), 应该 → [1,0,0]
//    具体: 循环结束后忘了 insert 或构造新数组
// 3. ✗ 遍历方向从 i=0 开始: 加法从最低位开始, 应该 i=n-1 递减
// 4. ✗ insert 位置写成 end(): 进位是在最高位(begin), 不是末尾
//
// 【面试追问】
// Q1(基础): "为什么不能把数组转成数字加1再转回来?"
//     → 数组最长100位, 远超 long long 的 19 位上限, 会溢出
//
// Q2(优化): "解法2中为什么不需要 carry 变量?"
//     → 因为加的是1, 进位也只能是1. 
//        digits[i]==10 时进位必为1, 而能进入下一轮的前提就是发生了进位
//        所以下一轮的 += 1 等价于 += carry
//
// Q3(泛化): "如果不是加1而是加任意整数k, 怎么改?"
//     → 用解法1的 carry 模板:
//        初始 carry = k
//        每一位: sum = digits[i] + carry % 10
//                carry = carry / 10 + sum / 10
//        (其实就是 LeetCode 989 的思路)
//
// Q4(系列): "两个大整数数组相加呢?"
//     → 双指针从两个数组末尾同时往前走
//        sum = a[i] + b[j] + carry
//        同样的进位传播模板 (LeetCode 415 字符串相加)
// ============================================================
