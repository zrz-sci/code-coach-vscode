/*
 * LeetCode 7: 整数反转 (Reverse Integer)
 *
 * 【题目本质】
 * 逐位提取数字并重新组装成反转后的整数。
 * 核心难点不在反转，而在于不使用64位整数的前提下检测32位溢出。
 *
 * 【解法总览】
 * 解法1: 数学逐位反转 + 提前溢出检测 — O(log x) / O(1) — ⭐ 面试首选（完全符合题目约束）
 * 解法2: 用 long long 简化溢出检测   — O(log x) / O(1) — 作为中间理解步骤（违反题目约束）
 * 解法3: 字符串反转                   — O(log x) / O(log x) — 最直觉（违反约束，空间也更大）
 */

// ============================================================
// 解法1: 数学逐位反转 + 提前溢出检测
// 时间: O(log x)  空间: O(1)
//
// 【思路】
// 反转数字的经典方法：不断取末位 (x%10)，去掉末位 (x/10)，
// 然后把取出的位累积到 result 上 (result = result*10 + digit)。
//
// 关键在于：result*10 + digit 可能溢出 32 位！
// 而题目要求不能用 64 位整数，所以必须在做乘法 **之前** 检测。
//
// 检测逻辑：
//   正数方向: result > INT_MAX/10 → 必溢出
//             result == INT_MAX/10 且 digit > 7 → 溢出 (INT_MAX = 2147483647)
//   负数方向: result < INT_MIN/10 → 必溢出
//             result == INT_MIN/10 且 digit < -8 → 溢出 (INT_MIN = -2147483648)
//
// 为什么正负数可以统一处理？
//   C++ 保证: -123 % 10 = -3, -123 / 10 = -12
//   所以负数取模得到负的 digit，除法得到向零截断的商，循环逻辑不变。
//
// 反转过程示意 (x = -123):
// ┌────────┬────────┬─────────────────────┬────────┐
// │  x     │ digit  │      计算           │ result │
// ├────────┼────────┼─────────────────────┼────────┤
// │ -123   │  -3    │ 0*10 + (-3) = -3    │   -3   │
// │ -12    │  -2    │ -3*10 + (-2) = -32  │  -32   │
// │ -1     │  -1    │ -32*10 + (-1) = -321│  -321  │
// │  0     │  end   │                     │  -321  │
// └────────┴────────┴─────────────────────┴────────┘
//
// 溢出检测示意 (x = 1534236469, 反转应该是 9646324351 > INT_MAX):
// 当 result = 964632435, digit = 1 时:
//   result (964632435) > INT_MAX/10 (214748364) → 返回 0!
// ============================================================
class Solution1 {
public:
    int reverse(int x) {
        int result = 0;
        while (x != 0) {
            int digit = x % 10;   // 负数取模结果也为负，如 -123%10 = -3
            x /= 10;              // 向零截断，如 -123/10 = -12
            
            // 在执行 result = result*10 + digit 之前检测正数方向溢出
            // 为什么是 > 而不是 >=：如果 result > INT_MAX/10，
            // 那么 result*10 已经 > INT_MAX - 9，加任何正 digit 都溢出
            if (result > INT_MAX / 10 || 
                (result == INT_MAX / 10 && digit > 7)) {
                return 0;
            }
            
            // 检测负数方向溢出
            if (result < INT_MIN / 10 || 
                (result == INT_MIN / 10 && digit < -8)) {
                return 0;
            }
            
            result = result * 10 + digit;
        }
        return result;
    }
};

// ============================================================
// 解法2: 用 long long 简化溢出检测
// 时间: O(log x)  空间: O(1)
//
// 【思路】
// 反转逻辑和解法1完全相同，唯一区别是用 long long 存储中间结果，
// 最后检查是否在 int 范围内。
//
// 为什么单独列出这个解法？
// 面试中的常见策略：先写一版简洁的展示核心逻辑，
// 然后面试官追问"如果不能用64位"时，再优化为解法1。
// 这个过渡展示了你的工程思维。
//
// 注意：严格来说违反题目"不允许存储64位整数"的约束。
// ============================================================
class Solution2 {
public:
    int reverse(int x) {
        long long result = 0;  // 用64位暂存，乘10后不会溢出
        while (x != 0) {
            result = result * 10 + x % 10;
            x /= 10;
        }
        // 反转完成后统一检查：是否超出32位范围
        if (result > INT_MAX || result < INT_MIN) return 0;
        return (int)result;
    }
};

// ============================================================
// 解法3: 字符串反转
// 时间: O(log x)  空间: O(log x) — 额外字符串空间
//
// 【思路】
// 最直觉的方法：把数字当字符串处理。
// 步骤：记住符号 → 取绝对值转字符串 → 反转字符串 → 转回数字 → 检查溢出。
//
// 局限：
// 1. INT_MIN 取绝对值会溢出（-2147483648 → 2147483648 超 int 范围）
// 2. 依赖 long 检测溢出，违反题目约束
// 3. 面试中不推荐作为最终方案，但适合作为思路铺垫
// ============================================================
class Solution3 {
public:
    int reverse(int x) {
        // INT_MIN 的绝对值超出 int 范围，且 INT_MIN 反转后必然溢出
        if (x == INT_MIN) return 0;
        
        int sign = (x < 0) ? -1 : 1;
        string s = to_string(abs(x));            // abs 安全，因为排除了 INT_MIN
        std::reverse(s.begin(), s.end());         // 反转字符串
        
        // stol 返回 long，用于检测溢出
        long val = stol(s);
        if (val > INT_MAX) return 0;              // 正数不可能小于 INT_MIN（因为取了abs）
        
        return sign * (int)val;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法                    | 时间     | 空间     | 符合题意 | 面试推荐 |
// |-------------------------|----------|----------|----------|----------|
// | 1. 提前溢出检测         | O(log x) | O(1)     | ✅ 完全  | ⭐ 首选  |
// | 2. long long 简化       | O(log x) | O(1)     | ❌ 64位  | 中间步骤 |
// | 3. 字符串反转           | O(log x) | O(log x) | ❌ 64位  | 思路铺垫 |
//
// 三种方法的反转逻辑完全相同（取末位 → 累积），
// 唯一区别在于如何处理溢出：
//   解法1: 在32位范围内提前判断（最严谨）
//   解法2: 用更大的类型暂存（最简洁但违反约束）
//   解法3: 转字符串绕过数学运算（最直觉但开销最大）
//
// 【易错点】
//
// 1. 在乘法后检测溢出 —— 未定义行为！
//    ✗: result = result * 10 + digit;  // 此时如果溢出，行为未定义
//        if (result 异常) return 0;     // 太晚了
//    ✓: if (result > INT_MAX / 10) return 0;  // 乘之前拦截
//        result = result * 10 + digit;
//
// 2. 对 INT_MIN 取绝对值 —— 溢出！
//    ✗: if (x < 0) x = -x;  // x = -2147483648 时, -x = 2147483648 超出 int
//    ✓: 不取绝对值，利用 C++ 负数 %/÷ 的特性统一处理
//
// 3. 循环条件写 while(x > 0) —— 负数无法处理！
//    ✗: while (x > 0) { ... }   // x=-123 直接跳过循环
//    ✓: while (x != 0) { ... }  // 正负数都能进入循环
//
// 4. 忘记 digit > 7 / digit < -8 的边界判断
//    虽然对合法 int 输入此条件永远不会触发
//    （因为 int 范围最高位只能是 1 或 2，反转后变成末位不超过 2），
//    但写出来表明你理解了完整的溢出逻辑，面试加分。
//
// 【面试追问】
//
// Q1: "你用了 long long，如果不能用64位怎么办？"
// → 在做 result*10+digit 之前提前检测：比较 result 和 INT_MAX/10 的大小关系。
//   这是从解法2到解法1的核心转变。
//
// Q2: "digit > 7 这个条件真的会触发吗？"
// → 不会。输入本身在 int 范围内，最多10位，最高位最大是 2。
//   反转后 2 变成末位 digit，不可能超过 7。
//   但写出来展示对溢出的完整理解。
//
// Q3: "如果要反转64位整数呢？不能用128位。"
// → 同样的提前检测方法，把 INT_MAX/INT_MIN 换成 LLONG_MAX/LLONG_MIN，
//   判断 result > LLONG_MAX/10 等。没有更大类型可用，必须用提前检测。
//
// Q4: "如何判断一个整数是回文数？和这题什么关系？"
// → LeetCode 9。可以只反转后半部分数字，和前半部分比较。
//   只反转一半就不需要溢出检测，因为反转一半不会超过原数的一半。
//   这是本题技巧的巧妙变体。
// ============================================================
