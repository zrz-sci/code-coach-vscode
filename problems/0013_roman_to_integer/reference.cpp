/*
 * LeetCode 13: 罗马数字转整数 (Roman to Integer)
 *
 * 【题目本质】
 * 将罗马数字字符串解析为整数。核心在于发现"减法规则"的统一判断条件：
 * 当前字符的值 < 下一个字符的值时，当前值应该被减去。
 *
 * 【解法总览】
 * 解法1: 双字符优先匹配  — O(n) / O(1) — 最直觉，枚举所有组合
 * 解法2: 左右比较法      — O(n) / O(1) — 最优雅，面试首选 ⭐
 * 解法3: 从右往左累加    — O(n) / O(1) — 换个方向思考，无需越界检查
 */

// ============================================================
// 解法1: 双字符优先匹配
// 时间: O(n)  空间: O(1)  (映射表大小固定为13，视为常数)
//
// 【思路】
// 最直觉的想法：罗马数字有7个单字符和6个双字符组合（IV,IX,XL,XC,CD,CM）。
// 遍历时优先尝试匹配两字符组合，匹配上则跳两步，否则匹配单字符跳一步。
// 这样不需要思考任何"规律"，纯模式匹配。
//
// 以 "MCMXCIV" 为例:
// i=0: "MC" 不在双字符表中 → 匹配 "M"(1000), i→1
// i=1: "CM" 在表中 → 匹配 "CM"(900), i→3
// i=3: "XC" 在表中 → 匹配 "XC"(90), i→5
// i=5: "IV" 在表中 → 匹配 "IV"(4), i→7
// 结果: 1000 + 900 + 90 + 4 = 1994 ✓
// ============================================================
class Solution1 {
public:
    int romanToInt(string s) {
        // 13个映射：7个单字符 + 6个双字符减法组合
        unordered_map<string, int> mp = {
            {"I", 1}, {"V", 5}, {"X", 10}, {"L", 50},
            {"C", 100}, {"D", 500}, {"M", 1000},
            {"IV", 4}, {"IX", 9}, {"XL", 40}, {"XC", 90},
            {"CD", 400}, {"CM", 900}
        };

        int result = 0;
        int i = 0;
        while (i < (int)s.size()) {
            // 优先匹配双字符（这是正确性的关键：先看长的再看短的）
            if (i + 1 < (int)s.size() && mp.count(s.substr(i, 2))) {
                result += mp[s.substr(i, 2)];
                i += 2;
            } else {
                result += mp[s.substr(i, 1)];
                i += 1;
            }
        }
        return result;
    }
};

// ============================================================
// 解法2: 左右比较法 ⭐ 面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1需要维护13个映射项，有点笨重。能不能只用7个基本映射？
//
// 观察减法规则的共性:
//   IV(4) = V(5) - I(1)     → I 比 V 小，I 被减
//   IX(9) = X(10) - I(1)    → I 比 X 小，I 被减
//   XL(40) = L(50) - X(10)  → X 比 L 小，X 被减
//   ...
// 
// 规律: 当 value[当前字符] < value[下一个字符] 时，减去当前值；否则加上。
//
// 手动验证 MCMXCIV:
//   M(1000) C(100) M(1000) X(10) C(100) I(1)  V(5)
//   1000>100 100<1000 1000>10 10<100 100>1  1<5  最后
//    +1000   -100    +1000   -10    +100   -1   +5
//   = 1000 - 100 + 1000 - 10 + 100 - 1 + 5 = 1994 ✓
// ============================================================
class Solution2 {
public:
    int romanToInt(string s) {
        // 只需要7个基本字符的映射
        unordered_map<char, int> mp = {
            {'I', 1}, {'V', 5}, {'X', 10}, {'L', 50},
            {'C', 100}, {'D', 500}, {'M', 1000}
        };

        int result = 0;
        for (int i = 0; i < (int)s.size(); i++) {
            // 核心判断：当前值 < 下一个值 → 这是减法组合的"小值"部分
            // 例如 IV 中的 I：I(1) < V(5)，所以 result -= 1
            // 之后遍历到 V 时会 result += 5，总效果 = -1 + 5 = 4 ✓
            if (i + 1 < (int)s.size() && mp[s[i]] < mp[s[i + 1]]) {
                result -= mp[s[i]];
            } else {
                // 正常情况：当前值 >= 下一个值（或者是最后一个字符）→ 加上
                result += mp[s[i]];
            }
        }
        return result;
    }
};

// ============================================================
// 解法3: 从右往左累加
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 换个方向：从右往左遍历，用 prev 记录右边已处理的字符值。
// 如果当前值 < prev，说明当前字符是某个减法组合的"小值"，减去它。
// 否则加上它。
//
// 好处：不需要检查 i+1 是否越界，因为 prev 天然存储了"右邻居"的信息。
//
// 从右往左看 MCMXCIV:
//   V(5)  I(1)  C(100)  X(10)  M(1000)  C(100)   M(1000)
//   prev=0 prev=5 prev=1 prev=100 prev=10 prev=1000 prev=100
//   5>=0  1<5    100>=1  10<100  1000>=10  100<1000  1000>=100
//   +5    -1     +100    -10     +1000     -100      +1000
//   = 5 - 1 + 100 - 10 + 1000 - 100 + 1000 = 1994 ✓
// ============================================================
class Solution3 {
public:
    int romanToInt(string s) {
        unordered_map<char, int> mp = {
            {'I', 1}, {'V', 5}, {'X', 10}, {'L', 50},
            {'C', 100}, {'D', 500}, {'M', 1000}
        };

        int result = 0;
        int prev = 0;  // 右边字符的值（初始为0，比任何罗马数字值都小）

        for (int i = (int)s.size() - 1; i >= 0; i--) {
            int curr = mp[s[i]];
            // 当前值比右边小 → 减法组合中的"小值"，减去
            if (curr < prev) {
                result -= curr;
            } else {
                result += curr;
            }
            prev = curr;  // 更新 prev 为当前值，供下一轮（左边的字符）使用
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 特点         | 解法1: 双字符优先    | 解法2: 左右比较 ⭐ | 解法3: 从右往左    |
// |-------------|---------------------|-------------------|-------------------|
// | 映射项数     | 13个               | 7个               | 7个               |
// | 遍历方向     | 左→右，变步长       | 左→右，步长1       | 右→左，步长1       |
// | 越界检查     | 需要 (i+1<n)       | 需要 (i+1<n)      | 不需要            |
// | 代码行数     | 最多               | 最少              | 中等              |
// | 面试推荐度   | 不推荐             | ⭐ 首选           | 备选              |
//
// 三种解法时间空间复杂度完全相同 O(n)/O(1)。
// 面试优先写解法2：代码最短，体现对规律的理解。
//
// 【易错点】
// 1. 解法2/3：mp 的 key 类型必须是 char，不是 string。
//    ✗ unordered_map<string, int> mp; mp[s[i]] → 编译错误
//    ✓ unordered_map<char, int> mp; mp[s[i]] → 正确
//
// 2. 解法2：忘记检查 i+1 < s.size() 就访问 s[i+1]，导致越界。
//    ✗ if (mp[s[i]] < mp[s[i+1]])  // i 为最后一个时越界
//    ✓ if (i+1 < (int)s.size() && mp[s[i]] < mp[s[i+1]])
//
// 3. 解法1：先匹配单字符再匹配双字符，导致 "IV" 被解析为 I+V=6 而非 4。
//    ✗ 先查单字符，再查双字符
//    ✓ 必须优先匹配双字符组合
//
// 4. s.size() 返回 size_t (无符号)，与 int 比较时可能有隐患。
//    ✗ for (int i = s.size() - 1; i >= 0; i--)  // 如果 s 为空，s.size()-1 下溢
//    ✓ for (int i = (int)s.size() - 1; i >= 0; i--)  // 显式转 int
//
// 【面试追问】
// Q1(基础理解): "罗马数字的减法规则有什么统一的判断条件？"
//   → 当前字符的值 < 右边字符的值时，当前值被减去。
//
// Q2(不用哈希表): "能不能不用 unordered_map，进一步降低常数开销？"
//   → 用 switch-case 将字符映射到数值，查找是 O(1) 且没有哈希的常数开销。
//     或者用大小为 128 的数组做直接映射：int val[128]; val['I']=1; ...
//
// Q3(逆问题): "整数转罗马数字（LeetCode 12）怎么做？"
//   → 贪心法：把 [1000,900,500,400,100,90,50,40,10,9,5,4,1] 和对应字符串
//     从大到小排列，每次减去能减的最大值，拼接对应字符串。
//
// 【相关题型】
// - LeetCode 12: 整数转罗马数字 — 本题的逆操作，复用同样的映射表，
//   但从"解析"变成"贪心构造"。
// - LeetCode 8: 字符串转换整数 (atoi) — 同为字符串解析类题目，
//   但需要处理符号、溢出、非法字符等更多边界条件。
