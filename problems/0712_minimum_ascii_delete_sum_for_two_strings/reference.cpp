/*
 * LeetCode 712: 两个字符串的最小ASCII删除和 (Minimum ASCII Delete Sum for Two Strings)
 *
 * 【题目本质】
 * 给定 s1 和 s2，各删除若干字符使两串相等，要求被删字符的 ASCII 之和最小。
 * 本质是 LCS（最长公共子序列）的变体：代价从"个数"变成"ASCII值"。
 * 最小删除和 = 总ASCII和 - 2 * 最大ASCII公共子序列和。
 *
 * 【解法总览】
 * 解法1: 二维 DP(直接定义)     — O(m*n) / O(m*n)      — dp[i][j]最小删除和 ⭐面试首选
 * 解法2: 一维 DP(空间优化)     — O(m*n) / O(min(m,n))  — 滚动数组
 * 解法3: 等价转化(最大ASCII LCS) — O(m*n) / O(m*n)      — 反向思考
 */


// ============================================================
// 解法1: 二维 DP — 直接定义最小删除和
// 时间: O(m*n)  空间: O(m*n)
//
// 【状态定义】
// dp[i][j] = 使 s1[0..i-1] 和 s2[0..j-1] 相等所需的最小删除 ASCII 和
//
// 【状态转移】
// 当 s1[i-1] == s2[j-1]:
//   dp[i][j] = dp[i-1][j-1]
//   理由: 这对字符匹配，保留它们（不用删任何字符）一定是最优的
//
// 当 s1[i-1] != s2[j-1]:
//   dp[i][j] = min(
//     dp[i-1][j] + s1[i-1],   // 删除 s1[i-1]，代价为其ASCII值
//     dp[i][j-1] + s2[j-1]    // 删除 s2[j-1]，代价为其ASCII值
//   )
//   注意: 不需要考虑同时删两个的情况（dp[i-1][j-1]+两者），
//   因为那一定 >= 只删一个的情况
//
// 【边界条件】
// dp[0][0] = 0          (两个空串已经相等)
// dp[i][0] = Σ ASCII(s1[0..i-1])  (s2为空，需要删完s1前i个字符)
// dp[0][j] = Σ ASCII(s2[0..j-1])  (s1为空，需要删完s2前j个字符)
//
// 【DP 填表过程】 s1 = "sea", s2 = "eat"
// ASCII: s=115, e=101, a=97, t=116
//
//          ""(j=0)  "e"(j=1)  "ea"(j=2)  "eat"(j=3)
// ""(i=0)     0      101       198         314
// "s"(i=1)   115     216       313         429
// "se"(i=2)  216     115       212         328
// "sea"(i=3) 313     212       115         231  ← 答案
//
// 填表详解:
//   dp[0][0]=0, dp[1][0]=115, dp[2][0]=216, dp[3][0]=313  (删s1前缀)
//   dp[0][1]=101, dp[0][2]=198, dp[0][3]=314               (删s2前缀)
//   dp[1][1]: 's'!='e' → min(dp[0][1]+115, dp[1][0]+101) = min(216,216) = 216
//   dp[2][1]: 'e'=='e' → dp[1][0] = 115
//   dp[2][2]: 'e'!='a' → min(dp[1][2]+101, dp[2][1]+97) = min(414,212) = 212
//   dp[3][2]: 'a'=='a' → dp[2][1] = 115
//   dp[3][3]: 'a'!='t' → min(dp[2][3]+97, dp[3][2]+116) = min(425,231) = 231
//
// 最终保留公共子序列 "ea", 删除 s1的's'(115) + s2的't'(116) = 231 ✓
// ============================================================
class Solution1 {
public:
    int minimumDeleteSum(string s1, string s2) {
        int m = s1.size(), n = s2.size();
        vector<vector<int>> dp(m + 1, vector<int>(n + 1, 0));

        // 边界: s2 为空，需要删完 s1 的前 i 个字符
        for (int i = 1; i <= m; i++)
            dp[i][0] = dp[i - 1][0] + s1[i - 1];

        // 边界: s1 为空，需要删完 s2 的前 j 个字符
        for (int j = 1; j <= n; j++)
            dp[0][j] = dp[0][j - 1] + s2[j - 1];

        // 填表: 逐行逐列
        for (int i = 1; i <= m; i++) {
            for (int j = 1; j <= n; j++) {
                if (s1[i - 1] == s2[j - 1]) {
                    // 匹配: 保留这对字符，不用删
                    dp[i][j] = dp[i - 1][j - 1];
                } else {
                    // 不匹配: 删 s1[i-1] 或删 s2[j-1]，取代价小的
                    dp[i][j] = min(
                        dp[i - 1][j] + s1[i - 1],  // 删 s1[i-1]
                        dp[i][j - 1] + s2[j - 1]   // 删 s2[j-1]
                    );
                }
            }
        }

        return dp[m][n];
    }
};

// ============================================================
// 解法2: 一维 DP（空间优化）— 滚动数组
// 时间: O(m*n)  空间: O(n)
//
// 【空间优化原理】
// dp[i][j] 只依赖三个位置:
//   dp[i-1][j-1] ← 左上（上一行的前一列）
//   dp[i-1][j]   ← 正上（上一行的同列）
//   dp[i][j-1]   ← 正左（同行的前一列）
//
// 压缩为一维 dp[j]:
//   "正上" dp[i-1][j] = dp[j]（尚未被当前行更新）
//   "正左" dp[i][j-1] = dp[j-1]（已被当前行更新）
//   "左上" dp[i-1][j-1] 需要 prev 变量保存
//
// 变量关系图:
//   更新前 dp[j]:   [已更新...] [prev] [dp[j]] [...]
//                                  ↑      ↑
//                               "左上"  "正上"
//   更新后 dp[j-1] = "正左"
//
// 遍历方向: j 从左到右（需要"正左"已更新）
// 每步: temp = dp[j]; 计算新dp[j]; prev = temp;
// ============================================================
class Solution2 {
public:
    int minimumDeleteSum(string s1, string s2) {
        int m = s1.size(), n = s2.size();
        vector<int> dp(n + 1, 0);

        // 边界: 第0行 (s1为空, 删完s2前缀)
        for (int j = 1; j <= n; j++)
            dp[j] = dp[j - 1] + s2[j - 1];

        // 逐行更新
        for (int i = 1; i <= m; i++) {
            int prev = dp[0];            // 保存 dp[i-1][0]（"左上"起始值）
            dp[0] += s1[i - 1];         // 更新 dp[i][0] = dp[i-1][0] + s1[i-1]

            for (int j = 1; j <= n; j++) {
                int temp = dp[j];        // 保存 dp[i-1][j]（"正上"，即将被覆盖）

                if (s1[i - 1] == s2[j - 1]) {
                    dp[j] = prev;        // 匹配: 用"左上" dp[i-1][j-1]
                } else {
                    dp[j] = min(
                        dp[j] + s1[i - 1],   // "正上" + 删s1[i-1]
                        dp[j - 1] + s2[j - 1] // "正左" + 删s2[j-1]
                    );
                }

                prev = temp;  // 下一列的"左上" = 当前列的"正上"
            }
        }

        return dp[n];
    }
};

// ============================================================
// 解法3: 等价转化 — 最大 ASCII 公共子序列
// 时间: O(m*n)  空间: O(m*n)
//
// 【思路】
// 换一个角度: 保留的部分是公共子序列，被删除的是其余部分。
// 最小删除和 = totalASCII(s1) + totalASCII(s2) - 2 * maxLCS_ASCII
//
// 所以等价于求"最大 ASCII 值的公共子序列"。
// 这和经典 LCS 完全一样，只是长度变成了 ASCII 值。
//
// 状态: dp[i][j] = s1[0..i-1] 和 s2[0..j-1] 的最大ASCII公共子序列和
// 转移:
//   s1[i-1] == s2[j-1]: dp[i][j] = dp[i-1][j-1] + s1[i-1]  (加上ASCII值)
//   否则:                dp[i][j] = max(dp[i-1][j], dp[i][j-1])
// 边界: dp[0][j] = dp[i][0] = 0 (空串的LCS ASCII和为0)
//
// 验证: s1="sea", s2="eat"
//   totalASCII(s1) = 115+101+97 = 313
//   totalASCII(s2) = 101+97+116 = 314
//   最大ASCII公共子序列 = "ea" = 101+97 = 198
//   答案 = 313 + 314 - 2*198 = 627 - 396 = 231 ✓
// ============================================================
class Solution3 {
public:
    int minimumDeleteSum(string s1, string s2) {
        int m = s1.size(), n = s2.size();

        // 计算总 ASCII 和
        int totalSum = 0;
        for (char c : s1) totalSum += c;
        for (char c : s2) totalSum += c;

        // dp[i][j] = s1[0..i-1] 和 s2[0..j-1] 的最大ASCII公共子序列和
        vector<vector<int>> dp(m + 1, vector<int>(n + 1, 0));

        for (int i = 1; i <= m; i++) {
            for (int j = 1; j <= n; j++) {
                if (s1[i - 1] == s2[j - 1]) {
                    // 匹配: 加上该字符的 ASCII 值
                    dp[i][j] = dp[i - 1][j - 1] + s1[i - 1];
                } else {
                    // 不匹配: 继承更大的子序列和
                    dp[i][j] = max(dp[i - 1][j], dp[i][j - 1]);
                }
            }
        }

        // 最小删除和 = 总和 - 2 * 最大公共子序列ASCII和
        return totalSum - 2 * dp[m][n];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法              | 时间    | 空间        | 状态定义           | 面试推荐 |
// |------------------|---------|------------|-------------------|---------|
// | 二维DP(直接定义)   | O(m*n) | O(m*n)    | 最小删除和          | ⭐⭐⭐   |
// | 一维DP(空间优化)   | O(m*n) | O(min(m,n))| 同上，压缩一维      | 加分项   |
// | 等价转化(最大LCS)  | O(m*n) | O(m*n)    | 最大ASCII公共子序列  | 思维分   |
//
// 演进关系:
//   解法1: 标准二维DP，状态定义和题目直接对应
//   → 解法2: 观察到只依赖上一行，空间优化到O(n)
//   解法3: 换角度（最小化删除 ↔ 最大化保留），和经典LCS结构一致
//
// 面试策略:
//   1. 先说清状态定义和转移方程
//   2. 画 DP 表验证（至少画小例子 "sea" vs "eat"）
//   3. 写出解法1
//   4. 追问空间优化 → 解法2（解释 prev 变量的作用）
//   5. 追问和 LCS 关系 → 解法3
//
// ============================================================
// 【易错点】
//
// 1. 边界初始化为 0 而非 ASCII 累计和:
//    ✗ dp[i][0] = 0; // s1前i个字符呢？它们需要全删！
//    ✓ dp[i][0] = dp[i-1][0] + s1[i-1]; // 累计ASCII和
//
// 2. 不匹配时多算一个 dp[i-1][j-1]+两者:
//    ✗ dp[i][j] = min({dp[i-1][j]+s1[i-1], dp[i][j-1]+s2[j-1],
//                      dp[i-1][j-1]+s1[i-1]+s2[j-1]});
//    ✓ 第三项多余: 删两个 >= 只删一个, 因为 dp[i-1][j] <= dp[i-1][j-1]+s2[j-1]
//
// 3. 空间优化忘记保存 prev:
//    ✗ if(s1[i-1]==s2[j-1]) dp[j] = dp[j-1]; // dp[j-1]已被当前行更新!
//    ✓ 用 prev 保存更新前的 dp[j] 作为下一列的"左上"
//
// 4. 下标偏移混淆:
//    ✗ if(s1[i]==s2[j]) // dp 从 1 开始，字符串从 0 开始
//    ✓ if(s1[i-1]==s2[j-1]) // dp 索引比字符串索引多 1
//
// 5. 等价转化忘记乘 2:
//    ✗ return totalSum - dp[m][n]; // 公共子序列在两个串里各占一份
//    ✓ return totalSum - 2 * dp[m][n];
//
// ============================================================
// 【面试追问 Interview Follow-ups】
//
// Q1: 和 LC 583 (Delete Operation for Two Strings) 的区别？
// A1: LC 583 每次删除代价为 1（最少操作次数），本题代价为ASCII值。
//     LC 583: 答案 = m + n - 2*LCS长度
//     本题: 答案 = totalASCII - 2*最大ASCII公共子序列和
//     DP结构完全相同，只是代价函数不同。
//
// Q2: 能不能用记忆化搜索？
// A2: 可以。dfs(i,j) = s1[i..] 和 s2[j..] 的最小删除和。
//     用 memo[i][j] 缓存。时间空间复杂度相同。
//     有些人觉得 top-down 更直觉（从大问题分解到小问题）。
//
// Q3: 如果要输出具体删了哪些字符？
// A3: 填完DP表后回溯: 从dp[m][n]开始，
//     匹配则保留、走(i-1,j-1); 不匹配则看哪边更小、走对应方向。
//     注意: 空间优化后无法回溯（丢失了完整DP表）。
//
// Q4: 空间优化后还能回溯路径吗？
// A4: 不能。空间优化后只保留了一行数据。
//     如果需要路径，要么保留完整二维DP，要么用 Hirschberg 算法
//     （O(n) 空间 + 路径恢复，但代码很复杂）。
//
// Q5: 如果字符串很长（比如 10^6），怎么优化？
// A5: O(m*n) 的DP无法避免。但可以:
//     - 空间优化到 O(min(m,n))
//     - 如果两串相似度高，用 Hunt-Szymanski 算法 O(r*log n)
//       其中 r 是匹配对数（适合差异小的情况）
//     - 实际工程中用 diff 算法（Myers' algorithm）
