/* ============================================================
 * 知识点总结
 * ============================================================
 *
 * 1. 构造题的思考方式:
 *    - 先看极端情况 (k=1 和 k=n-1)
 *    - 找到产生差值种类的"生成器" (交替放置)
 *    - 用"不产生新差值"的方式填充剩余 (顺序放置)
 *
 * 2. 交替放置的差值性质:
 *    m 个连续整数交替放 → 产生 m-1 种不同差值
 *    差值依次为 m-1, m-2, ..., 1
 *
 * 3. 双指针交替的模板:
 *    lo = start, hi = end
 *    while (lo <= hi) {
 *        take(lo++);
 *        if (lo <= hi) take(hi--);
 *    }
 *
 * 4. 时间 O(n), 空间 O(n) (输出数组)
 *    无法优化到 O(1) 空间因为必须输出长度 n 的数组
 *
 * 5. 相关:
 *    LC 526  优美的排列 (回溯, 不同问题)
 *    LC 280  摆动排序 (交替放置)
 *    LC 376  摆动序列 (DP)
 */

/*
 * ============================================================
 * 总结
 * ============================================================
 *
 * 【解法对比】
 * ┌──────────────────────────────┬────────┬────────┬──────────────────────────┐
 * │ 解法                         │ 时间   │ 空间   │ 特点                     │
 * ├──────────────────────────────┼────────┼────────┼──────────────────────────┤
 * │ 1. 顺序+交替 (后段交替) ⭐   │ O(n)   │ O(n)   │ 最直观，面试首选         │
 * │ 2. 交替+顺序 (前段交替)      │ O(n)   │ O(n)   │ 交替段在前，本质相同     │
 * │ 3. Flag控制方向               │ O(n)   │ O(n)   │ 用 bool 切换，写法清晰   │
 * └──────────────────────────────┴────────┴────────┴──────────────────────────┘
 *   (空间 O(n) 是输出数组本身，无法优化)
 *
 * 【易错点】
 * 1. Phase1 放 n-k-1 个数而非 n-k 个: 交替段需要 k+1 个数才能产生
 *    k 种不同差值 (m 个数交替产生 m-1 种差值)。
 * 2. lo <= hi 循环中第二次 push 前要检查 lo <= hi，否则 k 为偶数时
 *    会多 push 一个重复值。
 * 3. 解法2中交替段放在前面时，顺序段接续的差值 |a[k] - (k+2)| 可能
 *    引入新差值种类——实际不会，因为交替段最后一个数和 k+2 相邻，差值=1，
 *    而 1 已经在交替段中出现过。但面试时需要解释清楚。
 * 4. k=1 时整个数组顺序放即可，不需要交替段（Phase2 只有两个数 lo=hi-1）。
 * 5. 构造题容易忘记验证: 面试时建议手动带入 2-3 个例子验证差值种类数。
 *
 * 【面试追问】
 * Q1: 能否判定给定排列有多少种不同差值? 怎么做?
 *     → 遍历一次，计算相邻差的绝对值，放入 set，返回 set.size()。O(n)。
 *
 * Q2: 如果要求字典序最小的满足条件的排列呢?
 *     → 解法1天然接近字典序最小: Phase1 顺序放尽可能多的小数，
 *       Phase2 从最小的可用数开始交替。可以证明解法1的输出就是字典序最小的。
 *
 * Q3: 如果把"恰好 k 种"改成"至少 k 种"，有更简单的构造吗?
 *     → "恰好 k 种"已经是最简单的了。"至少 k 种"等价于构造恰好 k 种
 *       (因为可以把不需要的种类数用顺序段消除，但不能凭空增加)。
 *       实际上两者构造方法完全一样。
 */
