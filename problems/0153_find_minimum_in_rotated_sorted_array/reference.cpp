/*
 * -------- 解法对比一览 --------
 *
 * | 解法          | 时间     | 空间 | 适用场景             | 面试推荐 |
 * |--------------|----------|------|---------------------|---------|
 * | 二分(比较hi)  | O(log n) | O(1) | 无重复元素，最简洁   | ⭐首选  |
 * | 二分(比较lo)  | O(log n) | O(1) | 需额外有序检查       | 可以     |
 * | 线性扫描      | O(n)     | O(1) | 暴力起点，不满足要求  | 讨论用  |
 *
 * -------- 易错点 --------
 *
 * 1. hi = mid 不是 hi = mid-1 -- mid 可能就是最小值，不能跳过
 * 2. 循环条件 lo < hi 不是 lo <= hi -- 终止时 lo==hi 即为答案
 * 3. 比较对象选 nums[hi] 不选 nums[lo] -- 选 lo 需要额外判断
 *    数组是否已有序，否则未旋转数组 [1,2,3] 会出错
 * 4. 不要和固定值比较 -- nums[0] 在搜索空间收缩后可能不再有效
 * 5. 空数组保护 -- 虽然题目保证 n>=1，但 hi=nums.size()-1
 *    在空数组时会下溢
 *
 * -------- 面试追问链 --------
 *
 * Q1: 有重复元素怎么办? (LC 154)
 *     -> nums[mid]==nums[hi] 时无法判断方向，hi-- 保守缩小
 *        最坏退化 O(n)，如 [1,1,1,0,1,1]
 *
 * Q2: 在旋转数组中搜索目标值? (LC 33)
 *     -> 方法A: 先本题找旋转点，再在正确半段标准二分
 *        方法B: 直接一次二分，判断 mid/target 与有序段的关系
 *
 * Q3: 如何求旋转了多少次?
 *     -> 旋转次数 = 最小值的索引 = 本题返回的 lo
 *        最大值索引 = (lo - 1 + n) % n
 */
