/*
 * LeetCode 153: 寻找旋转排序数组中的最小值
 *               (Find Minimum in Rotated Sorted Array)
 *
 * 难度: Medium
 * 标签: Array, Binary Search
 *
 * 核心思想: 二分搜索 -- 比较 nums[mid] 和 nums[hi]
 *           判断最小值在左半还是右半，逐步收缩搜索空间
 */



// ============================================================
// 解法1: 二分搜索（比较 mid 和 hi）  ⭐ 标准做法
// 时间: O(log n)  空间: O(1)
//
// 搜索空间收缩图解:
//
// 旋转数组结构: [大段...|小段...]
//                       ^最小值在这
//
// 情况A: nums[mid] > nums[hi]
//   [...大段... mid ...] [小段... hi]
//                 ↓
//   断裂点在 mid 右边 → lo = mid + 1
//
// 情况B: nums[mid] <= nums[hi]
//   [大段] [小段... mid ... hi]
//                    ↓
//   mid 在小段(或无旋转) → hi = mid (不是mid-1!)
//
// 示例: [4, 5, 6, 7, 0, 1, 2]
//
// Round 1: lo=0  hi=6  mid=3  nums[3]=7 > nums[6]=2
//          → lo = 4
//          搜索空间: [0, 1, 2]
//
// Round 2: lo=4  hi=6  mid=5  nums[5]=1 <= nums[6]=2
//          → hi = 5
//          搜索空间: [0, 1]
//
// Round 3: lo=4  hi=5  mid=4  nums[4]=0 <= nums[5]=1
//          → hi = 4
//          搜索空间: [0]
//
// 退出: lo=hi=4 → nums[4]=0 ✓
// ============================================================
class Solution_Standard {
public:
    int findMin(vector<int>& nums) {
        int lo = 0, hi = nums.size() - 1;

        while (lo < hi) {
            int mid = lo + (hi - lo) / 2;

            if (nums[mid] > nums[hi]) {
                // mid 在"大段"，最小值在右半 [mid+1, hi]
                // mid 一定不是最小值（右边有更小的），可以安全跳过
                lo = mid + 1;
            } else {
                // mid 在"小段"或数组未旋转
                // mid 可能就是最小值，不能跳过 → hi = mid
                hi = mid;
            }
        }

        // lo == hi，搜索空间缩小到一个点，就是最小值
        return nums[lo];
    }
};

// ============================================================
// 解法2: 二分搜索（比较 mid 和 lo）
// 时间: O(log n)  空间: O(1)
//
// 不太推荐，因为需要额外检查数组是否已经有序
//
// 为什么比较 lo 有问题:
//   nums = [1, 2, 3] (未旋转)
//   lo=0, mid=1, nums[mid]=2 > nums[lo]=1
//   如果执行 lo = mid+1 → 跳过了最小值 nums[0]=1!
//
// 解决方案: 先检查 nums[lo] < nums[hi] 是否整段有序
// ============================================================
class Solution_CompareLo {
public:
    int findMin(vector<int>& nums) {
        int lo = 0, hi = nums.size() - 1;

        while (lo < hi) {
            // 额外检查: 如果 [lo, hi] 已经有序，lo 就是最小值
            if (nums[lo] < nums[hi]) return nums[lo];

            int mid = lo + (hi - lo) / 2;

            if (nums[mid] >= nums[lo]) {
                // mid 在大段 → 最小值在右半
                lo = mid + 1;
            } else {
                // mid 在小段 → 最小值在左半(含mid)
                hi = mid;
            }
        }

        return nums[lo];
    }
};

// ============================================================
// 解法3: 线性扫描（作为对比基线）
// 时间: O(n)  空间: O(1)
//
// 虽然不满足 O(log n) 要求，但作为面试讨论的起点
// "先说暴力 O(n)，再优化到 O(log n)"
//
// 观察: 旋转点就是第一个比前一个元素小的位置
//       nums[i] < nums[i-1] → nums[i] 是最小值
//       如果没有这样的点，说明没旋转，nums[0] 是最小值
// ============================================================
class Solution_Linear {
public:
    int findMin(vector<int>& nums) {
        for (int i = 1; i < (int)nums.size(); i++) {
            if (nums[i] < nums[i - 1]) {
                return nums[i]; // 找到断裂点
            }
        }
        return nums[0]; // 没有断裂 = 没有旋转
    }
};

// ============================================================
// 解法对比分析
// ============================================================
/*
 * | 解法            | 时间      | 空间 | 优点            | 缺点                    |
 * |-----------------|----------|------|-----------------|-------------------------|
 * | 二分(比较hi)    | O(log n) | O(1) | 最简洁，无额外判断| 需理解为什么用hi        |
 * | 二分(比较lo)    | O(log n) | O(1) | 直觉上更自然    | 需要额外有序检查         |
 * | 线性扫描        | O(n)     | O(1) | 最简单          | 不满足题目要求           |
 *
 * 面试建议: 写解法1(比较hi)，这是业界标准写法。
 *
 * 循环不变量 (Loop Invariant):
 *   "最小值始终在 [lo, hi] 范围内"
 *
 * 证明:
 * - 初始: lo=0, hi=n-1，最小值在数组中 ✓
 * - lo = mid+1: 只在 nums[mid]>nums[hi] 时执行，
 *   此时 mid 不可能是最小值(右边有更小的)，排除安全 ✓
 * - hi = mid: nums[mid]<=nums[hi]，mid 可能是最小值，
 *   所以保留 mid 在范围内 ✓
 * - 终止: lo==hi，范围缩到一点，就是最小值 ✓
 *
 * 为什么 hi = mid 而不是 hi = mid - 1?
 *
 *   反例: nums = [2, 1]
 *   lo=0, hi=1, mid=0
 *   nums[0]=2 > nums[1]=1 → lo = mid+1 = 1
 *   lo==hi==1 → return nums[1]=1 ✓ (没问题)
 *
 *   反例: nums = [1, 2]
 *   lo=0, hi=1, mid=0
 *   nums[0]=1 <= nums[1]=2 → hi = mid = 0
 *   lo==hi==0 → return nums[0]=1 ✓
 *
 *   如果 hi = mid-1:
 *   lo=0, hi=1, mid=0
 *   nums[0]=1 <= nums[1]=2 → hi = mid-1 = -1
 *   lo > hi → return nums[0]? 逻辑崩了!
 */

