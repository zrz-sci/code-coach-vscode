/*
 * LeetCode 205: 同构字符串 (Isomorphic Strings)
 *
 * 【题目本质】
 * 判断两个字符串是否具有相同的"字符出现结构"，即 s→t 的映射必须是双射（一一对应）。
 *
 * 【解法总览】
 * 解法1: 双哈希表       — O(n) / O(字符集) — 最直觉，显式维护双向映射
 * 解法2: 首次出现位置    — O(n) / O(字符集) — 换角度，比较结构模式
 * 解法3: 定长数组+上次位置 — O(n) / O(1)    — 最优，用数组替代哈希表
 */

// ============================================================
// 解法1: 双哈希表 — 维护 s→t 和 t→s 两个方向的映射
// 时间: O(n)  空间: O(字符集大小), 最多 256 个 ASCII 字符
//
// 【思路】
// 同构要求双射：不同字符不能映射到同一字符。
// 所以"只检查 s→t"是不够的（反例: s="ab", t="aa"）。
// 必须同时维护两个方向的映射，任一方向冲突就不同构。
//
// 遍历过程示例:
//   s = "egg", t = "add"
//   i=0: s2t 空, t2s 空 → 建立 e→a, a→e
//   i=1: s2t 无 g → 建立 g→d, d→g
//   i=2: s2t[g]=d == t[2]=d ✓, t2s[d]=g == s[2]=g ✓
//   结果: true
//
//   s = "foo", t = "bar"
//   i=0: f→b, b→f
//   i=1: o→a, a→o
//   i=2: s2t[o]=a ≠ t[2]=r → return false
// ============================================================
class Solution1 {
public:
    bool isIsomorphic(string s, string t) {
        unordered_map<char, char> s2t, t2s;
        for (int i = 0; i < (int)s.size(); i++) {
            char a = s[i], b = t[i];
            // s→t 方向：a 之前映射的目标不是 b → 冲突
            if (s2t.count(a) && s2t[a] != b) return false;
            // t→s 方向：b 之前被映射的来源不是 a → 多对一冲突
            if (t2s.count(b) && t2s[b] != a) return false;
            s2t[a] = b;
            t2s[b] = a;
        }
        return true;
    }
};

// ============================================================
// 解法2: 首次出现位置对比 — 比较两字符串的"结构模式"
// 时间: O(n)  空间: O(字符集大小)
//
// 【思路】
// 不存储显式映射，换个角度：
// 两个字符串同构 ⟺ 每个位置上，s[i] 首次出现的位置 == t[i] 首次出现的位置。
//
// 例:
//   s = "paper" → 首次出现位置: [0, 1, 0, 3, 4]
//                  p=0, a=1, p→已有0, e=3, r=4
//   t = "title" → 首次出现位置: [0, 1, 0, 3, 4]
//                  t=0, i=1, t→已有0, l=3, e=4
//   模式一致 → 同构 ✓
//
//   s = "ab"    → [0, 1]
//   t = "aa"    → [0, 0]
//   位置1: 1 ≠ 0 → 不同构 ✗
//
// 为什么这个方法天然保证双射？
// 因为它不关心具体映射到谁，只关心"结构"。
// 如果两个不同的 s 字符映射到同一个 t 字符，那 t 字符的首次出现
// 位置只有一个，但两个 s 字符的首次出现位置不同，必然不匹配。
// ============================================================
class Solution2 {
public:
    bool isIsomorphic(string s, string t) {
        unordered_map<char, int> firstS, firstT;
        for (int i = 0; i < (int)s.size(); i++) {
            // 首次出现则记录位置
            if (!firstS.count(s[i])) firstS[s[i]] = i;
            if (!firstT.count(t[i])) firstT[t[i]] = i;
            // 首次出现位置不同 → 结构不匹配
            if (firstS[s[i]] != firstT[t[i]]) return false;
        }
        return true;
    }
};

// ============================================================
// 解法3: 定长数组 + 上次出现位置 — 最优实现
// 时间: O(n)  空间: O(1) (ASCII 字符集固定 256)
//
// 【思路】
// 和解法2同一思想，但有两个优化:
// 1. 用 int[256] 代替 unordered_map，直接用字符 ASCII 码做索引
//    → 消除哈希计算和冲突处理的常数开销
// 2. 记录"上次出现位置"而不是"首次出现位置"
//    → 效果等价：如果两个字符在之前的所有位置都匹配，
//      那么它们的上次出现位置必然相同
//
// 关键细节: 初始值必须是 -1，不能是 0
//   因为索引 0 是合法位置。如果初始值为 0:
//   s = "ab", t = "aa", i=1:
//   lastS['b'] = 0(初始值) == lastT['a'] = 0(i=0时更新)
//   会误判为匹配！但实际上 'b' 从未出现过，'a' 在位置0出现过。
//
// 正确流程 (初始值 = -1):
//   s = "ab", t = "aa"
//   i=0: lastS['a']=-1 == lastT['a']=-1 ✓  → 更新 lastS['a']=0, lastT['a']=0
//   i=1: lastS['b']=-1 ≠ lastT['a']=0  ✗  → return false ✓
// ============================================================
class Solution3 {
public:
    bool isIsomorphic(string s, string t) {
        int lastS[256], lastT[256];
        memset(lastS, -1, sizeof(lastS));  // 初始化为 -1，表示"未出现过"
        memset(lastT, -1, sizeof(lastT));

        for (int i = 0; i < (int)s.size(); i++) {
            unsigned char a = s[i], b = t[i]; // unsigned char 防止负索引
            // 两个字符的"上次出现位置"不同 → 结构不匹配
            if (lastS[a] != lastT[b]) return false;
            // 更新上次出现位置为当前索引
            lastS[a] = i;
            lastT[b] = i;
        }
        return true;
    }
};

