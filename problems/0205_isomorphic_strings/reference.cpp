// 【解法对比】
//
// | 解法 | 核心思想         | 时间 | 空间       | 代码量 | 推荐场景       |
// |------|-----------------|------|-----------|--------|---------------|
// | 解法1 | 双向映射检查      | O(n) | O(字符集)  | 中等   | 面试首选讲解   |
// | 解法2 | 首次出现位置对比   | O(n) | O(字符集)  | 中等   | 展示思维深度   |
// | 解法3 | 定长数组+上次位置  | O(n) | O(1)常数   | 最少   | 追问优化时给出 |
//
// 解法1 最直觉，容易向面试官解释清楚"为什么需要两个 map"。
// 解法3 最快（数组访问 vs 哈希表），写法也最简洁。
// 建议：先讲解法1的思路，代码写解法3。
//
// 【易错点】
// 1. ✗ 只用一个 map (s→t) 而不检查反向 (t→s)
//    → s="ab", t="aa" 会误判为 true
//    ✓ 必须双向检查，或用位置对比方法
//
// 2. ✗ 上次出现位置数组初始化为 0
//    int lastS[256] = {0};
//    → s="ab", t="aa" 在 i=1 时 lastS['b']=0 == lastT['a']=0，误判
//    ✓ 初始化为 -1 (memset(lastS, -1, sizeof(lastS)))
//
// 3. ✗ lastS[s[i]] 当 s[i] 为 signed char 且值 > 127 时索引为负
//    ✓ 转换为 unsigned char: lastS[(unsigned char)s[i]]
//
// 4. ✗ 遗漏"字符可以映射到自己"的情况（这不需要特殊处理，但要理解）
//    ✓ s="abc", t="abc" 自然满足同构，代码不需要额外逻辑
//
// 【面试追问】
// Q1(基础理解): 为什么只用一个 map 不够？
//   → 只检查 s→t 无法防止多对一映射。s="ab", t="aa" 中 a→a 和 b→a 
//     在 s→t 方向都不冲突，但违反了双射要求。
//
// Q2(优化): 能否不用哈希表，进一步优化常数？
//   → ASCII 字符集只有 256 个，用 int[256] 数组，直接下标访问 O(1)，
//     避免哈希计算和碰撞处理。
//
// Q3(变体): 如果不是字符到字符的映射，而是单词到单词呢？(LeetCode 290)
//   → 思路完全一样，把 char 换成 string。用 unordered_map<string, string>
//     做双向映射，或者用单词的首次出现索引做模式对比。
//     290 的代码只需先按空格 split，然后和本题逻辑一模一样。
//
// 【相关题型】
// - 290. 单词规律 — 完全复用双哈希表框架，s 的每个字符变成 pattern 的
//   每个字符，t 的每个字符变成 str 按空格分割的每个单词。
// - 890. 查找和替换模式 — 对 words 中每个单词和 pattern 调用本题的
//   isIsomorphic，返回所有 true 的单词。
// - 49. 字母异位词分组 — 另一种"等价关系"的分组：异位词按排序后的
//   字符串分组，同构按结构模式分组，思维方式类似。
// ============================================================
