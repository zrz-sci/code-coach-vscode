/*
 * LeetCode 8: 字符串转换整数 (atoi) / String to Integer (atoi)
 *
 * 【题目本质】
 * 按照明确的规则逐字符解析字符串为整数，核心难点是"如何在溢出发生之前检测溢出"。
 * 这不是算法优化题，而是工程细节题——考察对整数溢出、边界条件的处理。
 *
 * 【解法总览】
 * 解法1: 线性扫描 (long long)      — O(n) / O(1) — 最简单直觉
 * 解法2: 线性扫描 (纯 int 溢出检测) — O(n) / O(1) — 面试首选 ⭐
 * 解法3: 有限状态机 (DFA)           — O(n) / O(1) — 工程最佳实践
 */

// ============================================================
// 解法1: 线性扫描 (long long) — 用更大类型避免中间溢出
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 最直觉的做法：按题目规则逐步处理（跳空格 → 读符号 → 读数字）。
// 用 long long 存储中间结果，这样 int 范围内的累加不会溢出。
// 但要注意：即使是 long long，如果输入有 200 个数字字符也会溢出，
// 所以每步仍需检查是否越界并提前截断。
//
// 处理流程示意（以 " -042" 为例）:
//   " -042"
//    ^       Step1: 跳过空格, i=0→1→2→3
//       ^    Step2: 读取'-', sign=-1, i=3→4
//        ^   Step3: 读'0', result=0; 读'4', result=4; 读'2', result=42
//   最终返回 42 * (-1) = -42
// ============================================================
class Solution1 {
public:
    int myAtoi(string s) {
        int i = 0, n = s.size();

        // Step 1: 跳过前导空格
        while (i < n && s[i] == ' ') i++;

        // Step 2: 读取符号（最多一个 '+' 或 '-'）
        int sign = 1;
        if (i < n && (s[i] == '+' || s[i] == '-')) {
            sign = (s[i] == '-') ? -1 : 1;
            i++;
        }

        // Step 3: 逐位读取数字
        long long result = 0;
        while (i < n && s[i] >= '0' && s[i] <= '9') {
            result = result * 10 + (s[i] - '0');

            // 为什么每步都要检查？
            // 因为如果输入是 "99999...9"（很多个9），long long 也会溢出
            // 所以一旦超出 int 范围就立刻截断
            if (result * sign <= INT_MIN) return INT_MIN;
            if (result * sign >= INT_MAX) return INT_MAX;
            i++;
        }

        return (int)(result * sign);
    }
};

// ============================================================
// 解法2: 线性扫描 (纯 int 溢出检测) — 面试首选 ⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 面试官常追问："如果不允许用 long long 怎么办？"
// 核心技巧：在做 result = result * 10 + digit 之前，通过数学不等式
// 检测这个操作是否会导致溢出。
//
// 溢出检测逻辑:
//   INT_MAX = 2147483647
//   INT_MAX / 10 = 214748364
//   INT_MAX % 10 = 7
//
//   如果 result > 214748364:
//     则 result * 10 > 2147483640，再加任何 digit 都 > INT_MAX → 溢出
//   如果 result == 214748364 且 digit > 7:
//     则 result * 10 + digit > 2147483647 → 溢出
//
// 对于负数 INT_MIN = -2147483648:
//   当 digit == 8 且 sign == -1 时，结果 = -2147483648 = INT_MIN，合法！
//   但我们检测 digit > 7 会返回 INT_MIN，恰好也是正确答案。
//   所以用正数上界统一检测，对正负数都正确。
//
// 溢出检测可视化（以 "2147483648" 为例）:
//   i=0: result=0,  digit=2, 0<=214748364       → result=2
//   i=1: result=2,  digit=1, 2<=214748364       → result=21
//   ...
//   i=8: result=214748364, digit=4, ==但 4<=7   → result=2147483644
//   i=9: result=2147483644, digit=8
//        2147483644 > 214748364 → 溢出! 返回 INT_MAX
// ============================================================
class Solution2 {
public:
    int myAtoi(string s) {
        int i = 0, n = s.size();

        // Step 1: 跳过前导空格
        while (i < n && s[i] == ' ') i++;

        // Step 2: 读取符号
        int sign = 1;
        if (i < n && (s[i] == '+' || s[i] == '-')) {
            sign = (s[i] == '-') ? -1 : 1;
            i++;
        }

        // Step 3: 逐位读取数字，在乘法前检测溢出
        int result = 0;
        while (i < n && s[i] >= '0' && s[i] <= '9') {
            int digit = s[i] - '0';

            // 为什么在 result*10+digit 之前检测？
            // 因为 C++ 有符号整数溢出是未定义行为(UB)，
            // 一旦 result*10 溢出，程序行为不可预测
            if (result > INT_MAX / 10 ||
                (result == INT_MAX / 10 && digit > INT_MAX % 10)) {
                return (sign == 1) ? INT_MAX : INT_MIN;
            }

            result = result * 10 + digit;
            i++;
        }

        return result * sign;
    }
};

// ============================================================
// 解法3: 有限状态机 (DFA) — 工程上最健壮的写法
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1/2用了多个 if-else 按步骤处理，逻辑分散。
// 当解析规则变复杂时（如支持十六进制、科学计数法），if-else 会变得难以维护。
//
// 状态机把所有逻辑浓缩到一张状态转移表中:
// - 定义4个状态: start(初始), signed(读到符号), number(读数字中), end(结束)
// - 定义4种输入: 空格, 符号, 数字, 其他
// - 查表决定下一个状态，根据状态执行相应动作
//
// 状态转移表:
//   ┌──────────┬───────┬────────┬────────┬───────┐
//   │ 当前状态  │ 空格  │ +/-    │ 数字   │ 其他  │
//   ├──────────┼───────┼────────┼────────┼───────┤
//   │ start    │ start │ signed │ number │  end  │
//   │ signed   │  end  │  end   │ number │  end  │
//   │ number   │  end  │  end   │ number │  end  │
//   │ end      │  end  │  end   │  end   │  end  │
//   └──────────┴───────┴────────┴────────┴───────┘
//
// 好处：如果规则变了（比如允许数字中间有逗号），只需修改表，不改代码结构。
// 这是编译器词法分析（Lexer）的基本原理。
// ============================================================
class Solution3 {
public:
    int myAtoi(string s) {
        // 状态编号: 0=start, 1=signed, 2=number, 3=end
        // 输入编号: 0=空格, 1=符号, 2=数字, 3=其他
        int table[4][4] = {
            {0, 1, 2, 3},  // start:  空格→start, 符号→signed, 数字→number, 其他→end
            {3, 3, 2, 3},  // signed: 只有数字→number，其余→end
            {3, 3, 2, 3},  // number: 只有数字→number，其余→end
            {3, 3, 3, 3},  // end:    吸收态，什么输入都留在 end
        };

        int state = 0;   // 从 start 开始
        int sign = 1;
        int result = 0;

        for (char c : s) {
            // 将字符分类为4种输入类型
            int input;
            if (c == ' ')                   input = 0;  // 空格
            else if (c == '+' || c == '-')  input = 1;  // 符号
            else if (c >= '0' && c <= '9')  input = 2;  // 数字
            else                            input = 3;  // 其他

            // 查表进行状态转移
            state = table[state][input];

            // 根据新状态执行动作
            if (state == 1) {
                // 进入 signed 状态：记录符号
                sign = (c == '-') ? -1 : 1;
            } else if (state == 2) {
                // 进入 number 状态：累加数字（含溢出检测）
                int digit = c - '0';
                if (result > INT_MAX / 10 ||
                    (result == INT_MAX / 10 && digit > INT_MAX % 10)) {
                    return (sign == 1) ? INT_MAX : INT_MIN;
                }
                result = result * 10 + digit;
            } else if (state == 3) {
                // 进入 end 状态：不需要继续扫描
                break;
            }
        }

        return result * sign;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度         | 解法1 (long long) | 解法2 (纯int) | 解法3 (DFA)   |
// |-------------|-------------------|---------------|---------------|
// | 溢出检测方式 | 用大类型比较       | 乘法前数学预判 | 同解法2       |
// | 代码可读性   | 最简单直白         | 中等          | 结构最清晰    |
// | 可扩展性     | 差                | 差            | 好(改表即可)  |
// | 面试推荐     | 初版快速过题       | ⭐ 标准答案   | 追问时加分    |
//
// 三种解法的核心区别只在于"怎么组织代码逻辑"和"怎么检测溢出"。
// 算法本质是一样的: 一次线性扫描，O(n) 时间，O(1) 空间。
//
// ============================================================
// 【易错点】
//
// 1. 溢出检测放在 result*10+digit 之后:
//    ✗ result = result * 10 + digit; if (result > INT_MAX) ...
//      → 有符号整数溢出是 UB，此时 result 的值不可预测
//    ✓ if (result > INT_MAX/10 || ...) return ...; result = result*10+digit;
//
// 2. 只检查 result > INT_MAX/10 而忘了检查 result == INT_MAX/10 && digit > 7:
//    ✗ if (result > INT_MAX/10) return ...;
//      → 漏掉了 result==214748364, digit=8 的情况 (2147483648 > INT_MAX)
//    ✓ if (result > INT_MAX/10 || (result == INT_MAX/10 && digit > INT_MAX%10))
//
// 3. 认为 "+-12" 应该返回 -12:
//    ✗ 连续读取多个符号
//    ✓ 最多读取一个符号字符，读完后如果下一个不是数字则 result=0
//
// 4. 用 isdigit() 但忘了 isdigit 可能对负值 char 产生 UB:
//    ✗ isdigit(s[i])  — 如果 s[i] 是负值 char（某些平台），行为未定义
//    ✓ s[i] >= '0' && s[i] <= '9'  — 安全且明确
//
// 5. long long 版本不在循环内检查:
//    ✗ 输入 "999...999" (200个9)，long long 也溢出了
//    ✓ 每步都检查 result*sign 是否越界
//
// ============================================================
// 【面试追问】（递进链）
//
// Q1: "你的代码能处理空字符串吗？'   ' 全空格呢？'+' 单独一个符号呢？"
//   → 能。空字符串/全空格: while循环不进入, result=0。
//     单独'+': sign=1, 数字循环不进入, return 0。
//
// Q2: "为什么不能先计算再检测溢出？C++ 溢出会怎样？"
//   → C++ 标准规定有符号整数溢出是未定义行为(UB)。
//     编译器可能优化掉溢出后的检查，导致永远检测不到溢出。
//     所以必须在溢出发生之前检测。
//
// Q3: "不用 long long，不用 INT_MAX/10 这个技巧，还有别的方法吗？"
//   → 可以：先用字符串比较判断位数是否超过 10 位。
//     如果不超过 10 位，转成 int 一定安全。
//     如果恰好 10 位，逐字符和 "2147483647"/"2147483648" 比较。
//     但这种方法代码更复杂，不推荐。
//
// Q4: "如果解析规则变得更复杂（支持浮点数、科学计数法），你会怎么改？"
//   → 用 DFA（解法3），定义更多状态和输入类型，修改状态转移表。
//     代码框架不变，只改表。这是编译器前端词法分析器的标准做法。
//
// Q5: "INT_MIN 的绝对值比 INT_MAX 大1，你的代码对 '-2147483648' 正确吗？"
//   → 正确。当 result==214748364, digit==8 时，检测条件 digit>7 成立，
//     返回 INT_MIN = -2147483648，恰好就是正确答案。
// ============================================================
