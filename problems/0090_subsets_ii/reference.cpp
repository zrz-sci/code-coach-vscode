/*
 * LeetCode 90: 子集 II (Subsets II)
 *
 * 【题目本质】
 * 给定含重复元素的数组，生成所有不重复的子集。
 * 核心问题：如何在子集枚举过程中高效去重。
 *
 * 【解法总览】
 * 解法1: 回溯 + 排序去重 — O(n·2^n) / O(n) — 面试首选 ⭐
 * 解法2: 迭代构建       — O(n·2^n) / O(1)额外 — 不同思路
 * 解法3: 位掩码 + 去重   — O(n·2^n) / O(n) — 组合数学视角
 *
 * 【与 78. Subsets 的关系】
 * 78 题：无重复元素 → 直接回溯/迭代/位掩码
 * 90 题：有重复元素 → 排序 + 同层跳过重复（仅多了一行判断）
 */

// ============================================================
// 解法1: 回溯 + 排序去重 — 面试首选 ⭐
// 时间: O(n·2^n)  空间: O(n) 递归栈深度
//
// 【思路】
// 1) 先排序，让相同元素相邻
// 2) 回溯模板和 78 题完全相同
// 3) 唯一区别：同一层递归中，如果 nums[i] == nums[i-1]
//    且 i > start（不是当前层第一个选择），则跳过
//
// 【决策树 (nums = [1,2,2])】
//                         []
//                  /       |        \
//               [1]       [2]      [2] ← skip! (i=2 > start=0, nums[2]==nums[1])
//              / \         |
//          [1,2] [1,2]   [2,2]
//            |   ↑skip!
//         [1,2,2]
//
// 结果: [], [1], [1,2], [1,2,2], [2], [2,2]
//
// 【为什么 i > start 而不是 i > 0？】
// i > start: 只跳过"同一层"的重复，允许"同一条路径"选多个相同值
// i > 0:     连"同一条路径"的重复也跳过了，[2,2] 就生成不了
// ============================================================
class Solution1 {
public:
    vector<vector<int>> subsetsWithDup(vector<int>& nums) {
        vector<vector<int>> result;
        vector<int> path;
        sort(nums.begin(), nums.end()); // 排序：去重的前提
        backtrack(nums, 0, path, result);
        return result;
    }

private:
    void backtrack(vector<int>& nums, int start, vector<int>& path,
                   vector<vector<int>>& result) {
        // 每个递归节点都对应一个合法子集（包括空集）
        result.push_back(path);

        for (int i = start; i < (int)nums.size(); i++) {
            // 同层去重：跳过和前一个相同的元素
            // i > start 确保只在"同层"跳过，不影响"同枝"深入
            if (i > start && nums[i] == nums[i - 1]) continue;

            path.push_back(nums[i]);       // 做选择
            backtrack(nums, i + 1, path, result); // 递归（i+1：每个元素只用一次）
            path.pop_back();                // 撤销选择
        }
    }
};

// ============================================================
// 解法2: 迭代构建 — 逐元素扩展已有子集
// 时间: O(n·2^n)  空间: O(1) 额外空间（不算结果数组）
//
// 【思路】
// 78 题迭代法：每来一个新数，追加到所有已有子集末尾。
// 90 题改进：遇到重复数时，只追加到"上一轮新增的子集"末尾。
//
// 【过程演示 (nums = [1,2,2])】
// 初始:        [[]]
// 加 1 (新数): 对全部追加 → [[], [1]]
//              新增区间: index 1..1
// 加 2 (新数): 对全部追加 → [[], [1], [2], [1,2]]
//              新增区间: index 2..3
// 加 2 (重复): 只对上一轮新增(index 2..3)追加
//              [2]→[2,2], [1,2]→[1,2,2]
//              结果: [[], [1], [2], [1,2], [2,2], [1,2,2]]
//
// 【为什么只追加上一轮新增的子集？】
// 上一轮新增的子集 = 包含前一个相同元素的子集
// 对它们再追加一个相同元素 = 多选一个相同元素，产生新的合法子集
// 对更早的子集追加 = 不包含前一个相同元素，等价于之前已经生成过的子集
// ============================================================
class Solution2 {
public:
    vector<vector<int>> subsetsWithDup(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        vector<vector<int>> result = {{}};
        int prevNewStart = 0; // 上一轮新增子集在 result 中的起始索引

        for (int i = 0; i < (int)nums.size(); i++) {
            int size = result.size();

            // 重复元素：只从上一轮新增部分开始追加
            // 非重复元素：从全部已有子集开始追加
            int start = (i > 0 && nums[i] == nums[i - 1]) ? prevNewStart : 0;

            // 记录本轮新增子集的起始位置（必须在追加前记录）
            prevNewStart = size;

            for (int j = start; j < size; j++) {
                vector<int> subset = result[j];
                subset.push_back(nums[i]);
                result.push_back(subset);
            }
        }
        return result;
    }
};

// ============================================================
// 解法3: 位掩码枚举 + 去重 — 组合数学视角
// 时间: O(n·2^n)  空间: O(n)
//
// 【思路】
// 用 0 到 2^n-1 的二进制掩码枚举所有子集。
// 排序后，对于相同的元素，要求"必须从左到右连续选取"。
// 即：如果选了 nums[i]（bit i = 1），且 nums[i] == nums[i-1]，
//     则 nums[i-1] 也必须被选（bit i-1 = 1），否则跳过这个掩码。
//
// 【为什么这个规则能去重？】
// 两个2：选法有 {00, 01, 10, 11}
// 01 和 10 都代表"选一个2"，是重复的
// 规则：必须从左连续选 → 只保留 10（选第1个）和 11（选两个）
// 01（跳过第1个选第2个）被过滤掉
// ============================================================
class Solution3 {
public:
    vector<vector<int>> subsetsWithDup(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        int n = nums.size();
        vector<vector<int>> result;

        for (int mask = 0; mask < (1 << n); mask++) {
            bool duplicate = false;
            vector<int> subset;

            for (int i = 0; i < n; i++) {
                if (mask & (1 << i)) {
                    // 选了 i，但没选 i-1，且 nums[i]==nums[i-1] → 重复掩码
                    if (i > 0 && nums[i] == nums[i - 1] && !(mask & (1 << (i - 1)))) {
                        duplicate = true;
                        break;
                    }
                    subset.push_back(nums[i]);
                }
            }

            if (!duplicate) {
                result.push_back(subset);
            }
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度         | 解法1 回溯       | 解法2 迭代       | 解法3 位掩码     |
// |-------------|-----------------|-----------------|-----------------|
// | 时间         | O(n·2^n)        | O(n·2^n)        | O(n·2^n)        |
// | 空间(额外)   | O(n) 栈         | O(1)            | O(n)            |
// | 去重方式     | 同层跳过         | 限制追加范围     | 跳过等价掩码     |
// | 面试推荐     | ⭐ 首选          | 变体考察         | 能说出加分       |
// | 代码量       | 最少             | 中等             | 中等             |
// | 与78题差异   | +排序+1行skip   | +1个变量         | +1个if判断       |
//
// 面试中首选解法1，因为：
// - 和 78 题模板一致，改动最小
// - 去重逻辑清晰（一行代码），容易解释
// - 同样的去重技巧直接复用到 40. Combination Sum II
//
// ============================================================
// 【易错点】
//
// 1. 去重条件写错: i > 0 vs i > start
//    ✗ if (i > 0 && nums[i] == nums[i-1]) continue;
//      → 这会让 [2,2] 无法生成，因为在选了第一个2后进入下一层，
//        i=2, i-1=1, nums[2]==nums[1], i>0 成立 → 跳过!
//    ✓ if (i > start && nums[i] == nums[i-1]) continue;
//      → 在下一层 start=2, i=2, i > start 不成立 → 不跳过 → [2,2] 正常生成
//
// 2. 忘记排序
//    ✗ 不排序直接回溯
//      → nums=[2,1,2] 时, nums[i]==nums[i-1] 检测不到第1个2和第3个2相同
//    ✓ 必须先 sort, 保证相同元素相邻
//
// 3. 迭代法中 prevNewStart 更新位置错误
//    ✗ 在内层循环后更新: for(j...) {...} prevNewStart = size;
//      → 此时 result 已经变大, size 值对但意义变了
//    ✓ 在内层循环前更新: prevNewStart = size; for(j...) {...}
//      → 本轮新增从 size 位置开始, 下一轮据此判断
//
// 4. 位掩码解法: 注意 1<<n 在 n>=31 时溢出 int
//    本题 n<=10 无此问题, 但养成用 1LL<<n 的习惯
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 和 78. Subsets 相比, 代码改了哪里?
//     → 两处: ① sort ② 回溯中加 if(i>start && nums[i]==nums[i-1]) continue
//
// Q2: 为什么去重条件是 i > start 而不是 i > 0? 举例说明.
//     → [1,2,2]: 选了第一个2后进入下一层(start=2), 要选第二个2(i=2)
//       i > 0 会跳过 → [2,2]生成不了; i > start 时 2 > 2 为 false → 正常选
//
// Q3: 如果数组非常大(n=20), 哪种解法更好?
//     → 回溯法: 通过剪枝跳过大量分支, 实际运行快
//       位掩码: 必须遍历全部 2^20 ≈ 100万个掩码, 无法剪枝
//       迭代法: 也无法剪枝, 但常数较小
//       综合首选回溯
//
// Q4: 如果改成"返回所有不重复的排列"(47题), 去重逻辑怎么变?
//     → 排列用 used[] 数组标记已选元素
//       去重条件: nums[i]==nums[i-1] && !used[i-1]
//       含义: 前一个相同元素没被选 → 说明是同层重复(前一个刚被撤销)
//       注意和子集去重的 i > start 是完全不同的机制
// ============================================================
