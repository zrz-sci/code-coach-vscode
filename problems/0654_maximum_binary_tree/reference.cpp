/*
 * LeetCode 654: 最大二叉树 (Maximum Binary Tree)
 * 
 * 【题目本质】
 * 给定无重复数组，用"每次选最大值做根、左右递归"的规则构建二叉树。
 * 本质是构建数组的笛卡尔树（Cartesian Tree）。
 * 
 * 【解法总览】
 * 解法1: 分治递归     — O(n²)/O(n)   — 直接翻译题意，面试首选
 * 解法2: 单调递减栈   — O(n)/O(n)    — 最优，笛卡尔树经典构建法
 */

// ============================================================
// 解法1: 分治递归 — 直接翻译题目定义
// 时间: O(n²) 最坏 / O(n log n) 平均
// 空间: O(n) 递归栈深度
//
// 【思路】
// 题目本身就是递归定义:
//   1. 在 [left, right) 区间找最大值索引 maxIdx
//   2. nums[maxIdx] 作为当前根
//   3. [left, maxIdx) 递归建左子树
//   4. [maxIdx+1, right) 递归建右子树
//
// 类比快排: 每次选 pivot 把数组分两半，这里选最大值分两半。
// 最坏情况和快排一样: 数组有序时每次只切一个元素 → O(n²)。
//
// 构建过程示例 (nums = [3,2,1,6,0,5]):
//
//   build([3,2,1,6,0,5])  → max=6(idx=3), 根=6
//          /           \
//   build([3,2,1])    build([0,5])
//   max=3(idx=0)      max=5(idx=1)
//   根=3               根=5
//     \                /
//   build([2,1])    build([0])
//   max=2            根=0
//   根=2
//     \
//   build([1])
//   根=1
//
// 最终树:
//         6
//        / \
//       3   5
//        \ /
//        2 0
//         \
//          1
// ============================================================
class Solution1 {
public:
    TreeNode* constructMaximumBinaryTree(vector<int>& nums) {
        return build(nums, 0, nums.size());
    }

private:
    // 在 nums[left..right) 区间上构建最大二叉树
    TreeNode* build(vector<int>& nums, int left, int right) {
        // 空区间 → 空节点
        if (left >= right) return nullptr;

        // 找区间内最大值的索引（这是每层递归的主要开销）
        int maxIdx = left;
        for (int i = left + 1; i < right; i++) {
            if (nums[i] > nums[maxIdx]) maxIdx = i;
        }

        // 最大值做根，左右分别递归
        TreeNode* root = new TreeNode(nums[maxIdx]);
        root->left  = build(nums, left, maxIdx);       // 最大值左边的子数组
        root->right = build(nums, maxIdx + 1, right);  // 最大值右边的子数组
        return root;
    }
};

// ============================================================
// 解法2: 单调递减栈 — O(n) 一次扫描构建
// 时间: O(n)   每个元素入栈出栈各一次
// 空间: O(n)   栈空间
//
// 【思路】
// 换一个视角: 不自顶向下分治，而是从左到右逐个插入元素。
//
// 关键观察 — 对于最大二叉树中的任意节点 X:
//   - X 的左孩子 = X 左边的子数组中的最大值（且比 X 小）
//   - X 的右孩子 = X 右边的子数组中的最大值（且比 X 小）
//
// 维护一个单调递减栈（从栈底到栈顶值递减），栈中存节点指针。
// 栈代表从根到最右叶节点的路径。
//
// 对于新元素 num:
//   (a) 比栈顶小 → 成为栈顶的右孩子（它在栈顶右边且更小）
//   (b) 比栈顶大 → 弹出栈顶，最后弹出的成为 num 的左孩子
//       （这些被弹出的在 num 左边且更小）
//
// 扫描过程 (nums = [3,2,1,6,0,5]):
//
// i=0, num=3: 栈空，直接入栈
//   栈: [3]
//   树: 3
//
// i=1, num=2: 2 < 3(栈顶), 2成为3的右孩子
//   栈: [3, 2]
//   树: 3
//        \
//         2
//
// i=2, num=1: 1 < 2(栈顶), 1成为2的右孩子
//   栈: [3, 2, 1]
//   树: 3
//        \
//         2
//          \
//           1
//
// i=3, num=6: 6 > 1, 弹出1; 6 > 2, 弹出2; 6 > 3, 弹出3
//   最后弹出的是3, 3成为6的左孩子
//   栈: [6]
//   树:     6
//          /
//         3
//          \
//           2
//            \
//             1
//
// i=4, num=0: 0 < 6(栈顶), 0成为6的右孩子
//   栈: [6, 0]
//   树:     6
//          / \
//         3   0
//          \
//           2
//            \
//             1
//
// i=5, num=5: 5 > 0, 弹出0; 5 < 6, 停止
//   0成为5的左孩子, 5成为6的右孩子(替代0)
//   栈: [6, 5]
//   树:     6
//          / \
//         3   5
//          \ /
//          2 0
//           \
//            1
//
// 扫描结束，栈底 = 根节点 6 ✓
// ============================================================
class Solution2 {
public:
    TreeNode* constructMaximumBinaryTree(vector<int>& nums) {
        // 单调递减栈: 栈底到栈顶值递减
        vector<TreeNode*> stk;

        for (int num : nums) {
            TreeNode* node = new TreeNode(num);
            TreeNode* lastPopped = nullptr;

            // 弹出所有比当前值小的节点
            // 为什么最后弹出的做左孩子？
            // 因为最后弹出的是这些被弹节点中最大的，
            // 它是 num 左边子数组的最大值，恰好是左子树的根
            while (!stk.empty() && stk.back()->val < num) {
                lastPopped = stk.back();
                stk.pop_back();
            }
            // 最后弹出的节点成为当前节点的左孩子
            node->left = lastPopped;

            // 栈非空说明栈顶比当前节点大
            // 当前节点在栈顶右边且更小 → 成为栈顶的右孩子
            if (!stk.empty()) {
                stk.back()->right = node;
            }

            stk.push_back(node);
        }

        // 栈底元素就是最大值（根节点）
        return stk.front();
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 分治递归          | 单调递减栈       |
// |-----------|------------------|-----------------|
// | 时间       | O(n²) 最坏       | O(n)            |
// | 空间       | O(n) 递归栈      | O(n) 栈         |
// | 思维方向   | 自顶向下(分治)    | 从左到右(增量)   |
// | 代码难度   | 简单直觉         | 需理解单调栈     |
// | 面试首选   | ⭐ 先写这个       | 追问时再给       |
//
// 面试策略: 先写分治递归（2分钟写完），然后主动分析"最坏 O(n²)"，
// 引出单调栈优化到 O(n)。
//
// ============================================================
// 【易错点】
//
// 1. maxIdx 初始化错误:
//    ✗ int maxIdx = 0;    ← 应该从 left 开始搜索
//    ✓ int maxIdx = left;
//
// 2. 区间边界:
//    ✗ build(nums, left, maxIdx - 1) 配合 left > right 做终止条件
//      当 maxIdx == left 时 right = left-1，容易产生 off-by-one bug
//    ✓ 统一用左闭右开 [left, right)，配合 left >= right 终止，简洁不易错
//
// 3. 单调栈左孩子赋值:
//    ✗ 在 while 循环里每次弹出都 node->left = popped
//      （实际上这样做结果也是对的，因为最后一次赋值覆盖了前面的）
//    ✓ 用 lastPopped 只记录最后弹出的节点更清晰
//
// 4. 单调栈忘记处理右孩子:
//    ✗ 只处理了弹出逻辑（左孩子），忘了 stk.back()->right = node
//    ✓ while 弹出完后，还要检查栈是否非空，设置右孩子关系
//
// 5. 返回值搞错:
//    ✗ return stk.back();   ← 返回的是栈顶（最右叶），不是根
//    ✓ return stk.front();  ← 栈底才是最大值（根节点）
//
// ============================================================
// 【面试追问】
//
// Q1(基础): 分治解法的最坏时间复杂度是多少？什么输入会触发？
//    → O(n²)，数组递增或递减时，每次只切掉一个元素。
//      类比快排选到最小/最大值做 pivot。
//
// Q2(优化): 能否做到 O(n)？
//    → 单调递减栈。核心思想: 栈维护根到最右叶的路径（值递减）。
//      新元素比栈顶大就弹出做左孩子，比栈顶小就成为右孩子。
//      每个元素入栈出栈各一次，总 O(n)。
//
// Q3(变体 - LeetCode 998): 已有最大二叉树，在数组末尾追加一个元素，
//    怎么 O(h) 更新树？
//    → 新元素在所有已有元素右边，只会出现在根→最右叶的路径上。
//      沿右链找第一个比新元素小的节点，新元素插到那个位置，
//      原节点变成新元素的左孩子。
//      这正是单调栈中"处理一个新元素"的单步操作。
//
// Q4(深入): 这棵树有什么特殊性质？和什么经典数据结构等价？
//    → 这是笛卡尔树(Cartesian Tree)。满足两个性质:
//      ①堆性质: 父节点值 > 子节点值（最大堆）
//      ②BST 的中序遍历 = 原数组顺序
//      单调栈 O(n) 建树是笛卡尔树的经典构建算法。
// ============================================================
