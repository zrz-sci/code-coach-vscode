/*
 * LeetCode 22: 括号生成 (Generate Parentheses)
 * 
 * 【题目本质】
 * 在长度为 2n 的字符串中放置 n 个 '(' 和 n 个 ')'，
 * 要求任意前缀中 '(' 数量 ≥ ')' 数量，列出所有满足条件的字符串。
 * 合法括号序列的数量恰好是第 n 个卡特兰数。
 *
 * 【解法总览】
 * 解法1: 暴力生成+验证  — O(2^(2n)·n) / O(n)    — 最直觉，效率最低
 * 解法2: 回溯+剪枝     — O(4^n/√n)  / O(n)     — 面试首选 ⭐
 * 解法3: 动态规划       — O(4^n/√n)  / O(4^n/√n) — 展示DP视角
 */

// ============================================================
// 解法1: 暴力生成+验证
// 时间: O(2^(2n) · n)  空间: O(n)
// 
// 【思路】
// 2n 个位置，每个位置放 '(' 或 ')'，共 2^(2n) 种序列。
// 生成每个序列后，用 O(n) 验证是否合法。
// 这是最笨的方法，但帮助理解合法括号的判定条件：
//   遍历时维护 balance（遇'('加1，遇')'减1），
//   任何时刻 balance < 0 则非法，最终 balance != 0 也非法。
// 
// 瓶颈：生成了大量非法序列（如 ")))((("），验证后丢弃，浪费严重。
// ============================================================
class Solution1 {
public:
    vector<string> generateParenthesis(int n) {
        vector<string> result;
        string current(2 * n, ' ');
        generateAll(current, 0, result);
        return result;
    }
    
private:
    void generateAll(string& current, int pos, vector<string>& result) {
        if (pos == (int)current.size()) {
            if (isValid(current)) {
                result.push_back(current);
            }
            return;
        }
        // 每个位置尝试放 '(' 或 ')'，不做任何约束
        current[pos] = '(';
        generateAll(current, pos + 1, result);
        current[pos] = ')';
        generateAll(current, pos + 1, result);
    }
    
    bool isValid(const string& s) {
        int balance = 0;
        for (char c : s) {
            if (c == '(') balance++;
            else balance--;
            // 任意前缀中 ')' 多于 '(' → 非法
            if (balance < 0) return false;
        }
        // 最终 '(' 和 ')' 数量必须相等
        return balance == 0;
    }
};

// ============================================================
// 解法2: 回溯 + 剪枝 — 面试首选 ⭐
// 时间: O(4^n/√n)  空间: O(n) 递归栈深度
// 
// 【思路】
// 核心优化：不是先生成再验证，而是在构建过程中就保证合法。
// 
// 维护两个计数器:
//   open  = 已放的 '(' 数量
//   close = 已放的 ')' 数量
// 
// 在每一步只做"合法"的选择:
//   ① open < n       → 可以放 '('（左括号还没用完）
//   ② close < open   → 可以放 ')'（右括号不超过已有的左括号）
// 
// 当 path 长度 == 2n 时，一定是合法的（因为每步都合法）。
//
// 决策树 (n=2):
//
//                        ""
//                   open=0,close=0
//                        |
//                       "("          ← 只能放 '(' (close<open不满足)
//                   open=1,close=0
//                   /          \
//                "(("          "()"
//            o=2,c=0        o=1,c=1
//              |            /
//            "(()"       "()(""
//           o=2,c=1     o=2,c=1
//              |            |
//           "(())"       "()()"
//           o=2,c=2     o=2,c=2
//             ✓              ✓
//
// 结果: ["(())", "()()"]
// ============================================================
class Solution2 {
public:
    vector<string> generateParenthesis(int n) {
        vector<string> result;
        string path;
        path.reserve(2 * n);  // 预分配避免频繁扩容
        backtrack(result, path, 0, 0, n);
        return result;
    }
    
private:
    void backtrack(vector<string>& result, string& path,
                   int open, int close, int n) {
        // 终止条件：已经放了 2n 个字符，一定合法
        if ((int)path.size() == 2 * n) {
            result.push_back(path);
            return;
        }
        
        // 选择1: 放左括号
        // 为什么 open < n？总共只有 n 个左括号可用
        if (open < n) {
            path.push_back('(');
            backtrack(result, path, open + 1, close, n);
            path.pop_back();  // 撤销选择，回溯
        }
        
        // 选择2: 放右括号
        // 为什么 close < open 而不是 close < n？
        // 因为 close < open 保证任意前缀中 '(' >= ')'，即括号始终合法
        // 如果只检查 close < n，会产生 ")(" 这种非法前缀
        if (close < open) {
            path.push_back(')');
            backtrack(result, path, open, close + 1, n);
            path.pop_back();  // 撤销选择，回溯
        }
    }
};

// ============================================================
// 解法3: 动态规划
// 时间: O(4^n/√n)  空间: O(4^n/√n)（存储所有中间结果）
// 
// 【思路】
// 换一个角度：已知 i-1 对括号的所有合法组合，能否推出 i 对的？
// 
// 关键观察：i 对合法括号一定可以表示为:
//     "(" + [j 对括号] + ")" + [i-1-j 对括号]
//     其中 j = 0, 1, ..., i-1
// 
// 为什么这样分解是完备且不重复的？
// - 第一个字符一定是 '('，它一定和某个 ')' 配对
// - 假设配对的 ')' 在位置 2j+1（0-indexed），
//   则中间有 2j 个字符（j 对括号），后面有 2(i-1-j) 个字符
// - 不同的 j 对应不同的分割位置，所以不重复
// - 所有 j 覆盖了第一个 '(' 的配对 ')' 的所有可能位置，所以完备
//
// 递推过程:
// dp[0] = [""]
// dp[1] = ["(" + "" + ")" + ""]
//       = ["()"]
// dp[2] = ["(" + "" + ")" + "()", "(" + "()" + ")" + ""]
//       = ["()()", "(())"]
// dp[3] = ["(" + "" + ")" + dp[2],
//          "(" + dp[1] + ")" + dp[1],
//          "(" + dp[2] + ")" + ""]
//       = ["()(())", "()()()", "(())()", "((()))", "(()())"]
// ============================================================
class Solution3 {
public:
    vector<string> generateParenthesis(int n) {
        // dp[i] 存储 i 对括号的所有合法组合
        vector<vector<string>> dp(n + 1);
        
        // base case: 0 对括号 = 一个空字符串（不是空数组！）
        // 如果 dp[0] 为空，后续所有双重循环都不会执行
        dp[0] = {""};
        
        for (int i = 1; i <= n; i++) {
            // j 对放在第一个 '(' 和配对的 ')' 之间
            for (int j = 0; j < i; j++) {
                // i-1-j 对放在配对的 ')' 之后
                for (const string& inner : dp[j]) {
                    for (const string& tail : dp[i - 1 - j]) {
                        dp[i].push_back("(" + inner + ")" + tail);
                    }
                }
            }
        }
        
        return dp[n];
    }
};

// ============================================================
// 【解法对比】
// 
// | 维度         | 暴力(解法1)        | 回溯(解法2)       | DP(解法3)          |
// |-------------|--------------------|--------------------|-------------------|
// | 核心思想     | 先穷举再筛选        | 边构建边约束        | 递推拼接           |
// | 时间         | O(2^(2n)·n)       | O(4^n/√n)          | O(4^n/√n)         |
// | 空间(不算结果)| O(n)              | O(n) 递归栈        | O(4^n/√n) 中间dp  |
// | 适用场景     | 理解题意           | 面试首选            | 展示DP思维         |
// 
// 解法2 vs 解法3:
// - 回溯是"流式生成"，递归栈只用 O(n)，内存友好
// - DP 需要存储所有中间 dp[0]...dp[n-1]，空间开销大
// - 两者生成的结果数量相同（卡特兰数），本质上只是生成策略不同
// - 面试中优先写回溯，如果追问"还有别的方法吗"再给 DP
//
// ============================================================
// 【易错点】
// 
// 1. 回溯时右括号条件写成 close < n 而不是 close < open
//    ✗ if (close < n)   → 会产生 ")(" 等非法前缀
//    ✓ if (close < open) → 保证任意前缀 '(' >= ')'
// 
// 2. 忘记 pop_back()（撤销选择）
//    ✗ path.push_back('(');
//      backtrack(...);
//      // 漏了 pop_back → path 被污染，后续分支全部错误
//    ✓ 每个 push_back 后面必须紧跟 pop_back
// 
// 3. DP 的 dp[0] 初始化为空数组而不是含空字符串的数组
//    ✗ dp[0] = {};      → 后续所有 for(const string& inner : dp[j]) 都不执行
//    ✓ dp[0] = {""};    → 空字符串代表 0 对括号的唯一合法组合
// 
// 4. DP 内层循环 j 的范围写成 j <= i
//    ✗ for (int j = 0; j <= i; j++)  → 越界访问 dp[i-1-j] 即 dp[-1]
//    ✓ for (int j = 0; j < i; j++)   → j 最大 i-1，此时 tail 取 dp[0]
//
// ============================================================
// 【面试追问】
// 
// Q1: 合法括号序列的数量有公式吗？不枚举能直接算吗？
// → 第 n 个卡特兰数: C(2n, n) / (n + 1)
//   n=3 时 = C(6,3)/4 = 20/4 = 5，和示例一致
//   O(n) 时间可算，不需要枚举
//
// Q2: 回溯中 path 用引用传递 vs 值传递有什么区别？
// → 引用传递 + push_back/pop_back：避免每层递归拷贝字符串，
//   时间节省 O(n) per call。值传递每次拷贝 O(n)。
//   面试中推荐引用传递 + 显式撤销，展示对回溯的深入理解。
//
// Q3: 如果要生成含多种括号 ()[]{} 的合法组合呢？
// → 回溯框架不变，选择列表从 2 种变 6 种（3 左 + 3 右）。
//   放右括号条件改为：维护一个栈，栈顶的左括号必须和当前右括号类型匹配。
//   剪枝：各类型左括号各自不超过给定数量，右括号总数不超过对应左括号。
//
// ============================================================
// 【空间优化说明】
//
// 本题用回溯生成所有合法括号组合，不是传统 DP 填表问题，没有"空间优化"
// 的概念。
//
// - 解法2（回溯）：递归栈深度 O(n)，已是最优工作空间
// - 解法3（DP）：dp[i] = 所有 i 对括号的字符串集合，dp[i] 依赖 dp[0]..dp[i-1]
//   的所有组合拼接，无法用滚动变量替代——必须保留全部中间结果
//
// 结论：回溯天然空间最优；DP 解法的空间瓶颈在于存储所有字符串，无法压缩。
// ============================================================
