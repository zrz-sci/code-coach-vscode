/*
 * LeetCode 32: 最长有效括号 (Longest Valid Parentheses)
 *
 * 【题目本质】
 * 在只含 '(' 和 ')' 的字符串中，找最长的连续子串使得括号完全匹配。
 * 难点：相邻的有效段可以合并 ()()=4，嵌套也算 (())=4。
 *
 * 【解法总览】
 * 解法1: 暴力枚举     — O(n³) / O(1)   — 理解题意
 * 解法2: 动态规划      — O(n) / O(n)    — DP 经典应用
 * 解法3: 栈(存索引)    — O(n) / O(n)    — 最直觉、面试首选
 * 解法4: 双向扫描      — O(n) / O(1)    — 空间最优、加分项
 */


// ============================================================
// 解法1: 暴力枚举 — 枚举所有偶数长度子串并验证
// 时间: O(n³)  空间: O(1)
//
// 【思路】
// 最朴素的想法：枚举所有子串的起点和终点，检查是否有效。
// 有效括号串长度必为偶数，所以只枚举偶数长度。
// 检查有效性用 balance 计数器：遇 '(' 加1，遇 ')' 减1，
// 过程中 balance < 0 则无效，最终 balance == 0 则有效。
//
// 瓶颈：O(n²) 个子串 × O(n) 验证 = O(n³)，n=30000 时不可行。
// ============================================================
class Solution1 {
public:
    int longestValidParentheses(string s) {
        int n = s.size(), ans = 0;
        for (int i = 0; i < n; i++) {
            for (int j = i + 2; j <= n; j += 2) {
                if (isValid(s, i, j)) {
                    ans = max(ans, j - i);
                }
            }
        }
        return ans;
    }
    
private:
    bool isValid(const string& s, int start, int end) {
        int balance = 0;
        for (int i = start; i < end; i++) {
            balance += (s[i] == '(' ? 1 : -1);
            if (balance < 0) return false;
        }
        return balance == 0;
    }
};


// ============================================================
// 解法2: 动态规划 — dp[i] = 以 s[i] 结尾的最长有效括号长度
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 从暴力的"枚举子串"转变为"对每个位置直接算答案"。
// 
// 定义 dp[i] = 以 s[i] 结尾的最长有效括号子串长度
// 
// 只有 s[i] == ')' 时 dp[i] 才可能 > 0（以 '(' 结尾不可能有效）
//
// 分两个 case：
//
// Case 1: s[i-1] == '('
//   形如 ...()
//   dp[i] = dp[i-2] + 2
//   直接配对，再加上 i-2 位置可能紧邻的有效段
//
// Case 2: s[i-1] == ')'
//   形如 ...))
//   需要跳过内层的有效段 dp[i-1]，看 s[i - dp[i-1] - 1] 是否是 '('
//   如果是：dp[i] = dp[i-1] + 2 + dp[i - dp[i-1] - 2]
//                    ↑内层长度  ↑配对  ↑左括号前面紧邻的有效段
//
// DP 填表方向: 从左到右，dp[i] 依赖 dp[i-1], dp[i-2] 或更前面
//
// 示例: s = "()(())"
//
// 索引:    0    1    2    3    4    5
// 字符:    (    )    (    (    )    )
// dp:      0    2    0    0    2    6
//
// i=1: s[0]='(' → Case1: dp[1] = 0+2 = 2
// i=4: s[3]='(' → Case1: dp[4] = dp[2]+2 = 0+2 = 2
// i=5: s[4]=')' → Case2: 跳过dp[4]=2, s[5-2-1]=s[2]='(' ✓
//      dp[5] = 2+2+dp[1] = 6
// ============================================================
class Solution2 {
public:
    int longestValidParentheses(string s) {
        int n = s.size(), ans = 0;
        vector<int> dp(n, 0);
        
        for (int i = 1; i < n; i++) {
            if (s[i] == ')') {
                if (s[i - 1] == '(') {
                    // Case 1: ...() 直接配对
                    // i>=2 时加上 dp[i-2]（前面紧邻的有效段）
                    dp[i] = (i >= 2 ? dp[i - 2] : 0) + 2;
                } else {
                    // Case 2: ...)) 跳过内层有效段
                    int j = i - dp[i - 1] - 1;  // 可能与当前 ')' 配对的位置
                    if (j >= 0 && s[j] == '(') {
                        dp[i] = dp[i - 1] + 2
                               + (j >= 1 ? dp[j - 1] : 0);
                        // dp[j-1]：配对的 '(' 前面紧邻的有效段
                        // 这一项极易遗漏！没有它 "()(())" 会算成 4 而非 6
                    }
                }
                ans = max(ans, dp[i]);
            }
            // s[i] == '(' 时 dp[i] = 0，已由初始化保证
        }
        return ans;
    }
};


// ============================================================
// 解法3: 栈（存索引）— 括号匹配的经典栈用法，额外维护分界点
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 括号匹配天然适合栈，但普通栈只能判断是否匹配，要算长度需要存索引。
//
// 核心 insight：栈底始终保留一个"分界点"——最后一个无法匹配的 ')' 的位置。
// 初始时没有这样的 ')'，所以用 -1 作为哨兵。
//
// 算法：
// 1. push(-1) 作为初始分界点
// 2. 遇到 '('：push 索引
// 3. 遇到 ')'：pop
//    - 栈空：这个 ')' 无法匹配，push 它作为新分界点
//    - 栈不空：有效长度 = i - stk.top()
//
// 为什么 i - stk.top() 而不是 i - stk.top() + 1？
// 因为栈顶是"分界点"或未匹配的 '(' 的索引，有效段从 stk.top()+1 开始
// 长度 = i - (stk.top()+1) + 1 = i - stk.top()
//
// 示例: ")()())"
//
// 索引:  0  1  2  3  4  5
// 字符:  )  (  )  (  )  )
//
// 栈变化:
//   初始:            [-1]
//   i=0 ')': pop -1, 栈空 → push 0     [0]
//   i=1 '(': push 1                      [0, 1]
//   i=2 ')': pop 1, 栈不空 → 2-0=2     [0]       ans=2
//   i=3 '(': push 3                      [0, 3]
//   i=4 ')': pop 3, 栈不空 → 4-0=4     [0]       ans=4
//   i=5 ')': pop 0, 栈空 → push 5      [5]
//
//   答案 = 4
// ============================================================
class Solution3 {
public:
    int longestValidParentheses(string s) {
        int ans = 0;
        stack<int> stk;
        stk.push(-1);  // 哨兵：初始分界点，不能省略！
        
        for (int i = 0; i < (int)s.size(); i++) {
            if (s[i] == '(') {
                stk.push(i);
            } else {
                stk.pop();
                if (stk.empty()) {
                    // 当前 ')' 无法配对，成为新的分界点
                    stk.push(i);
                } else {
                    // 有效长度 = 当前位置 - 分界点位置
                    ans = max(ans, i - stk.top());
                }
            }
        }
        return ans;
    }
};


// ============================================================
// 解法4: 双向扫描（计数器）— O(n) 时间，O(1) 空间
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 追求极致的空间优化。用两个变量 left/right 代替栈。
//
// 正向扫描（左→右）：
//   left 计数 '('，right 计数 ')'
//   left == right 时：有效段长度 = left + right，更新答案
//   right > left 时：右括号多了，无法挽回，归零重新计数
//
// 问题：正向扫描漏掉 "(()" 这种左括号偏多的情况
//   因为 left 始终 > right，永远不会相等
//
// 解决：反向再扫一遍（右→左），交换归零条件
//   left > right 时归零
//
// 为什么正反两趟合起来是完备的？
// - 任何有效段，它的左边界要么是字符串开头，要么左边是多余的 ')'
//   这种情况正向扫描能捕获（右括号多了会归零，重新开始计数）
// - 它的右边界要么是字符串末尾，要么右边是多余的 '('
//   这种情况反向扫描能捕获
// - 所以不会漏掉任何有效段
// ============================================================
class Solution4 {
public:
    int longestValidParentheses(string s) {
        int n = s.size(), ans = 0;
        
        // 正向扫描：左→右
        int left = 0, right = 0;
        for (int i = 0; i < n; i++) {
            if (s[i] == '(') left++;
            else right++;
            
            if (left == right) {
                ans = max(ans, left + right);
            } else if (right > left) {
                // 右括号多了，这些字符不可能属于有效段了
                left = right = 0;
            }
            // left > right 时不动作，继续看后面的字符
        }
        
        // 反向扫描：右→左，处理 "(()" 类左括号偏多的情况
        left = right = 0;
        for (int i = n - 1; i >= 0; i--) {
            if (s[i] == '(') left++;
            else right++;
            
            if (left == right) {
                ans = max(ans, left + right);
            } else if (left > right) {
                // 反方向：左括号多了，归零
                left = right = 0;
            }
        }
        
        return ans;
    }
};


// ============================================================
// 【解法对比】
//
// | 解法     | 时间   | 空间  | 核心思想           | 代码难度 |
// |----------|--------|-------|--------------------|----------|
// | 暴力     | O(n³)  | O(1)  | 枚举+验证          | 简单     |
// | DP       | O(n)   | O(n)  | 以每个位置结尾的最优| 中等     |
// | 栈       | O(n)   | O(n)  | 栈存索引+分界点    | 简单     |
// | 双向扫描 | O(n)   | O(1)  | 正反计数器互补     | 简单     |
//
// 面试推荐顺序：栈 > DP > 双向扫描
// - 栈：思路清晰，代码短，不容易写错
// - DP：展示DP能力，但Case分析多，容易漏项
// - 双向扫描：O(1)空间加分，但需要解释完备性
//
// ============================================================
// 【易错点】
//
// 1. DP 遗漏合并项:
//    ✗ dp[i] = dp[i-1] + 2
//    ✓ dp[i] = dp[i-1] + 2 + dp[i - dp[i-1] - 2]
//    原因: "()(())" 最后的 ')' 配对后还要加上前面的 "()" 长度
//
// 2. DP 索引越界:
//    ✗ dp[i] = dp[i-2] + 2    // 当 i==1 时 dp[-1] 越界
//    ✓ dp[i] = (i >= 2 ? dp[i-2] : 0) + 2
//
// 3. 栈忘记初始哨兵:
//    ✗ stack 初始为空
//    ✓ stk.push(-1)
//    原因: "()" 弹出0后栈空，无法计算 i - stk.top()
//
// 4. 栈长度计算多加1:
//    ✗ ans = max(ans, i - stk.top() + 1)
//    ✓ ans = max(ans, i - stk.top())
//    原因: 栈顶是分界点(不属于有效段)，长度 = i - stk.top()
//
// 5. 双向扫描只做一趟:
//    ✗ 只正向扫描
//    ✓ 正反各一趟
//    原因: "(()" 正向 left 始终 > right，永远不相等，漏掉长度2
//
// ============================================================
// 【面试追问】
//
// Q1: 暴力解复杂度多少？瓶颈在哪？
// → O(n³)。瓶颈在枚举 O(n²) 个子串且每次验证 O(n)。
//   可以优化枚举过程（DP 思路）或用栈一次遍历完成。
//
// Q2: 栈里为什么存索引而不是字符？为什么初始放 -1？
// → 存字符只能判断匹配与否，无法算长度。存索引可以通过
//   "当前位置 - 栈顶位置" 得到有效段长度。
//   -1 是初始分界点，没有它则第一个匹配 "()" 弹出后栈空
//   无法计算长度。
//
// Q3: 能否 O(1) 空间？
// → 双向扫描法：正向 left/right 计数器，left==right 更新答案，
//   right>left 归零。反向补上左括号偏多的情况。
//   两个方向互补，保证不漏。
//
// Q4: 如果题目改成返回最长有效括号子串本身（而不是长度）？
// → 在更新 ans 时同时记录起始位置。栈解法中 start = stk.top()+1，
//   DP 解法中 start = i - dp[i] + 1。最后用 s.substr(start, ans)。
//
// Q5: DP 解法中 dp[i] 只依赖前面几项，能空间优化吗？
// → 不容易。dp[i] 可能依赖 dp[i - dp[i-1] - 2]，跳跃距离不固定，
//   不像经典的滚动数组只依赖 dp[i-1]/dp[i-2]。所以无法简单降到 O(1)。
//   要 O(1) 空间应使用双向扫描法。
// ============================================================
