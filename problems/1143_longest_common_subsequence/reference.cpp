/*
 * LeetCode 1143: 最长公共子序列 (Longest Common Subsequence)
 *
 * 【题目本质】
 * 给定两个字符串，求它们最长的公共子序列长度。
 * 子序列保持相对顺序但不要求连续。
 * 这是二维 DP 的经典入门题。
 *
 * 【解法总览】
 * 解法1: 暴力递归       — O(2^(m+n)) / O(m+n)  — 理解递归结构
 * 解法2: 记忆化搜索     — O(m·n) / O(m·n)      — 消除重叠子问题
 * 解法3: 二维 DP 递推   — O(m·n) / O(m·n)      — 面试首选 ⭐
 * 解法4: 一维 DP 空间优化 — O(m·n) / O(min(m,n)) — 面试追问加分
 */

// ============================================================
// 解法1: 暴力递归 — 直接翻译问题定义
// 时间: O(2^(m+n))  空间: O(m+n) 递归栈
//
// 【思路】
// 从两个字符串的末尾开始看：
// - 末尾字符相同 → 它一定在 LCS 中，两个字符串同时往前缩一位
// - 末尾字符不同 → 要么丢掉 text1 末尾，要么丢掉 text2 末尾
//   取两种选择中较大的那个
//
// 递归树（text1="abc", text2="ac" 为例）:
//              (3,2)
//             /     \
//      a1[2]='c'==a2[1]='c' → 1+(2,1)
//                               /     \
//                    a1[1]='b'≠a2[0]='a'
//                        /           \
//                     (1,1)         (2,0)=0
//                    /     \
//             a1[0]='a'==a2[0]='a' → 1+(0,0)=1
//
// 可以看到子问题会重复出现 → 引出记忆化
// ============================================================
class Solution1 {
public:
    int longestCommonSubsequence(string text1, string text2) {
        return solve(text1, text2, text1.size(), text2.size());
    }

private:
    int solve(string& s1, string& s2, int i, int j) {
        // base case: 任一字符串为空，LCS 长度为 0
        if (i == 0 || j == 0) return 0;

        if (s1[i - 1] == s2[j - 1]) {
            // 末尾字符匹配，加入 LCS，同时缩小两个字符串
            return 1 + solve(s1, s2, i - 1, j - 1);
        } else {
            // 不匹配，分两种情况取较大值
            return max(solve(s1, s2, i - 1, j),
                       solve(s1, s2, i, j - 1));
        }
    }
};

// ============================================================
// 解法2: 记忆化搜索 — 给暴力递归加缓存
// 时间: O(m·n)  空间: O(m·n)
//
// 【思路】
// 解法1的瓶颈：(i,j) 状态最多 m×n 种，但暴力递归会反复计算
// 同一个 (i,j)。加一个 memo 表，算过的直接返回。
//
// 关键：memo 必须用 -1 初始化而非 0，
// 因为 LCS=0 是合法结果（两个完全不同的字符串），
// 必须区分"未计算"和"计算结果为0"。
// ============================================================
class Solution2 {
public:
    int longestCommonSubsequence(string text1, string text2) {
        int m = text1.size(), n = text2.size();
        vector<vector<int>> memo(m + 1, vector<int>(n + 1, -1));
        return solve(text1, text2, m, n, memo);
    }

private:
    int solve(string& s1, string& s2, int i, int j,
              vector<vector<int>>& memo) {
        if (i == 0 || j == 0) return 0;
        if (memo[i][j] != -1) return memo[i][j];  // 已缓存

        if (s1[i - 1] == s2[j - 1]) {
            memo[i][j] = 1 + solve(s1, s2, i - 1, j - 1, memo);
        } else {
            memo[i][j] = max(solve(s1, s2, i - 1, j, memo),
                             solve(s1, s2, i, j - 1, memo));
        }
        return memo[i][j];
    }
};

// ============================================================
// 解法3: 二维 DP（递推）— 面试首选 ⭐
// 时间: O(m·n)  空间: O(m·n)
//
// 【思路】
// 把记忆化搜索翻译成 for 循环填表。
// dp[i][j] = text1 前 i 个字符与 text2 前 j 个字符的 LCS 长度
//
// 状态转移:
//   text1[i-1] == text2[j-1]: dp[i][j] = dp[i-1][j-1] + 1
//   text1[i-1] != text2[j-1]: dp[i][j] = max(dp[i-1][j], dp[i][j-1])
//
// 依赖关系（每个格子依赖左上、上方、左方）:
//   dp[i-1][j-1]  dp[i-1][j]
//        ↘            ↓
//   dp[i][j-1]  →  dp[i][j]
//
// 填表方向: 从上到下、从左到右（保证依赖的都已计算）
//
// 示例: text1 = "abcde", text2 = "ace"
//
//     ""  a  c  e
// ""   0  0  0  0
//  a   0  1  1  1     ← text1[0]='a'==text2[0]='a' → dp[0][0]+1=1
//  b   0  1  1  1     ← 'b'≠所有，取max(上,左)
//  c   0  1  2  2     ← text1[2]='c'==text2[1]='c' → dp[1][1]+1=2
//  d   0  1  2  2     ← 'd'≠所有
//  e   0  1  2  3     ← text1[4]='e'==text2[2]='e' → dp[4][2]+1=3
//
// 答案: dp[5][3] = 3
// ============================================================
class Solution3 {
public:
    int longestCommonSubsequence(string text1, string text2) {
        int m = text1.size(), n = text2.size();
        // 多开一行一列作为 base case: dp[0][j]=0, dp[i][0]=0
        vector<vector<int>> dp(m + 1, vector<int>(n + 1, 0));

        for (int i = 1; i <= m; i++) {
            for (int j = 1; j <= n; j++) {
                if (text1[i - 1] == text2[j - 1]) {
                    // 末尾字符匹配: 在"两个都去掉末尾"的LCS基础上+1
                    dp[i][j] = dp[i - 1][j - 1] + 1;
                } else {
                    // 不匹配: 取"去掉text1末尾"或"去掉text2末尾"中较大值
                    dp[i][j] = max(dp[i - 1][j], dp[i][j - 1]);
                }
            }
        }
        return dp[m][n];
    }
};

// ============================================================
// 解法4: 一维 DP（空间优化）— 面试追问加分
// 时间: O(m·n)  空间: O(min(m,n))
//
// 【思路】
// 解法3中 dp[i][j] 只依赖三个位置:
//   dp[i-1][j-1] (左上), dp[i-1][j] (上方), dp[i][j-1] (左方)
// 即只需要上一行和当前行 → 可以压缩为一维数组。
//
// 但有个陷阱：一维数组 dp[j] 更新后，旧值（上一行的 dp[j]）就丢了。
// 特别是 dp[j-1] 在处理 j 时已经被更新为当前行的值，
// 而匹配时我们需要的是"上一行的 dp[j-1]"即左上角值。
// → 用变量 prev 在更新 dp[j] 之前保存旧的 dp[j]
//
// 一维数组更新过程 (text1="abcde", text2="ace"):
//
// 初始:        dp = [0, 0, 0, 0]  (索引0~3对应""和"a","c","e")
//
// i=1 ('a'):   遍历j: prev 保存旧值
//   j=1: 'a'=='a', dp[1]=prev(0)+1=1, dp=[0,1,0,0]
//   j=2: 'a'≠'c', dp[2]=max(dp[2]=0, dp[1]=1)=1, dp=[0,1,1,0]
//   j=3: 'a'≠'e', dp[3]=max(dp[3]=0, dp[2]=1)=1, dp=[0,1,1,1]
//
// i=3 ('c'):
//   j=1: 'c'≠'a', dp[1]=max(1,0)=1
//   j=2: 'c'=='c', dp[2]=prev(1)+1=2, dp=[0,1,2,1]
//   j=3: 'c'≠'e', dp[3]=max(1,2)=2, dp=[0,1,2,2]
//
// ... 最终 dp[3]=3
// ============================================================
class Solution4 {
public:
    int longestCommonSubsequence(string text1, string text2) {
        int m = text1.size(), n = text2.size();
        // 让较短的字符串对应内层循环，进一步节省空间
        if (m < n) return longestCommonSubsequence(text2, text1);

        vector<int> dp(n + 1, 0);

        for (int i = 1; i <= m; i++) {
            // prev = dp[i-1][0] = 0（每行开头的"左上角"为0）
            int prev = 0;
            for (int j = 1; j <= n; j++) {
                int temp = dp[j];  // 保存旧的 dp[j]（即二维中的 dp[i-1][j]）
                if (text1[i - 1] == text2[j - 1]) {
                    // 匹配: 用左上角值+1（prev 就是旧的 dp[j-1]）
                    dp[j] = prev + 1;
                } else {
                    // 不匹配: dp[j] 已经是"上方"值，dp[j-1] 是"左方"值
                    dp[j] = max(dp[j], dp[j - 1]);
                }
                // 更新 prev: 下一轮的"左上角"就是本轮更新前的 dp[j]
                prev = temp;
            }
        }
        return dp[n];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间       | 空间        | 适用场景       |
// |-----------|-----------|------------|---------------|
// | 暴力递归   | O(2^(m+n))| O(m+n)     | 理解递归结构    |
// | 记忆化搜索 | O(m·n)    | O(m·n)     | 自顶向下思维   |
// | 二维 DP   | O(m·n)    | O(m·n)     | 面试首选 ⭐    |
// | 一维 DP   | O(m·n)    | O(min(m,n))| 追问空间优化   |
//
// 解法3 vs 解法4:
//   - 二维 DP 代码清晰，不容易出错，面试时优先写
//   - 一维 DP 空间从 O(m·n) 降到 O(min(m,n))，代价是需要
//     仔细处理 prev 变量，容易写错
//   - 如果面试官不追问空间，写解法3就够了
//
// 解法2 vs 解法3:
//   - 本质相同，一个自顶向下一个自底向上
//   - 递推版不需要递归栈，常数因子更小
//   - 记忆化搜索的优势：不需要关心填表顺序，适合状态转移复杂的题
//
// ============================================================
// 【易错点】
//
// 1. 下标偏移:
//    ✗ dp[i][j] 与 text1[i], text2[j] 对应 (越界!)
//    ✓ dp[i][j] 与 text1[i-1], text2[j-1] 对应
//    因为 dp 多开了一行一列作为 base case
//
// 2. 空间优化时丢失左上角:
//    ✗ dp[j] = dp[j-1] + 1 (dp[j-1]已是当前行的值，不是上一行的)
//    ✓ dp[j] = prev + 1，其中 prev 在更新 dp[j] 前保存了旧的 dp[j-1]
//
// 3. prev 重置位置:
//    ✗ prev 只在外层循环外初始化一次
//    ✓ 每轮外层循环开始时 prev = 0
//    因为 dp[i-1][0] 永远是 0
//
// 4. 记忆化搜索 memo 初始化:
//    ✗ memo 初始化为 0，检查 memo[i][j] != 0
//    ✓ memo 初始化为 -1，检查 memo[i][j] != -1
//    因为 LCS=0 是合法结果
//
// ============================================================
// 【面试追问】
//
// Q1: 暴力法多少复杂度？瓶颈在哪？
// → 枚举子序列 O(2^m)，每个检查 O(n)，共 O(n·2^m)。
//   瓶颈: 指数级枚举。递归版虽然更自然，但有大量重叠子问题。
//
// Q2: 能否输出具体的 LCS 字符串？
// → 先填完 dp 表，然后从 dp[m][n] 回溯:
//   - text1[i-1]==text2[j-1]: 加入结果，i--,j--
//   - 否则: dp[i-1][j] >= dp[i][j-1] 则 i--, 否则 j--
//   最后反转得到 LCS 字符串。时间 O(m+n)。
//
// Q3: 如果 text1 长度远大于 text2 (如 m=10^6, n=100)？
// → 一维 DP 以 n 为内层，空间 O(n)=O(100)，时间 O(m·n)。
//   也可考虑 Hunt-Szymanski 算法 (转化为 LIS)，
//   在匹配点稀疏时更快 O(r·log n)。
//
// Q4: 这题和编辑距离 (LC 72) 的关系？
// → 同样的二维 DP 框架。区别:
//   - LCS: 不匹配时 dp[i][j] = max(上, 左)
//   - 编辑距离: 不匹配时 dp[i][j] = 1 + min(上, 左, 左上)
//   掌握 LCS 后编辑距离只需改一行转移方程。
//
// 【相关题型】
// - 583. 两个字符串的删除操作: ans = m + n - 2*LCS，代码完全复用
// - 1092. 最短公共超序列: 先求LCS，再回溯路径合并两个字符串
// - 72. 编辑距离: 同框架，转移方程从max改成min+三种操作
// - 718. 最长重复子数组: 要求连续子数组，不匹配时dp[i][j]=0（只改一行）
// - 300. 最长递增子序列: 单序列版本的子序列DP
// ============================================================
