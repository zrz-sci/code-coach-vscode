/*
 * LeetCode 802: Find Eventual Safe States (找到最终的安全状态)
 *
 * 【题目本质】
 * 在有向图中，找出所有"安全"节点——即从该节点出发的所有路径最终都到达
 * 终端节点（出度为0）的节点。等价于：找出不在任何环上、且不能到达环的节点。
 *
 * 【解法总览】
 * 解法1: DFS + 三色标记   — O(V+E) / O(V)   — 面试首选，经典图环检测
 * 解法2: 反向拓扑排序(BFS) — O(V+E) / O(V+E) — 进阶方案，反向传播安全性
 */

// ============================================================
// 解法1: DFS + 三色标记 — 面试首选 ⭐
// 时间: O(V+E)  空间: O(V)
//
// 【思路】
// 用经典的三色标记法检测有向图中的环：
//   - 白色(0): 未访问
//   - 灰色(1): 在当前 DFS 路径上（正在访问中）
//   - 黑色(2): 已确认安全
//
// DFS 过程：
//   1. 将当前节点标灰（加入当前路径）
//   2. 遍历所有邻居：
//      - 邻居是灰色 → 发现环 → 当前节点不安全
//      - 邻居已确认不安全 → 当前节点也不安全
//      - 邻居是黑色 → 跳过（已确认安全）
//   3. 所有邻居都安全 → 当前节点标黑（确认安全）
//
// 关键：每个节点最多被完整 DFS 一次。第二次遇到时直接看颜色：
//   灰色 → 环 → false
//   黑色 → 安全 → true
//   这保证了 O(V+E) 复杂度。
//
// 示例: graph = [[1,2],[2,3],[5],[0],[5],[],[]]
//
//   DFS(0): 0→灰 → DFS(1): 1→灰 → DFS(2): 2→灰 → DFS(5): 5→灰
//           5无邻居 → 5→黑(安全) → 回到2 → 2→黑(安全)
//           → 回到1 → DFS(3): 3→灰 → DFS(0): 0是灰色!发现环!
//           → 3不安全 → 1不安全 → 0不安全
//   DFS(4): 4→灰 → DFS(5): 5已黑 → 4→黑(安全)
//   DFS(5): 已黑(安全)
//   DFS(6): 6→灰 → 无邻居 → 6→黑(安全)
//
//   安全节点: {2, 4, 5, 6} ✓
// ============================================================
class Solution1 {
public:
    vector<int> eventualSafeNodes(vector<vector<int>>& graph) {
        int n = graph.size();
        // 0=白(未访问), 1=灰(当前路径), 2=黑(已确认安全)
        vector<int> color(n, 0);
        vector<int> result;

        // 按 0..n-1 顺序遍历，结果天然有序
        for (int i = 0; i < n; i++) {
            if (isSafe(graph, i, color)) {
                result.push_back(i);
            }
        }
        return result;
    }

private:
    // 返回 true: 节点 u 是安全的
    // 返回 false: 节点 u 不安全（在环上或能到达环）
    bool isSafe(vector<vector<int>>& graph, int u, vector<int>& color) {
        // 已有颜色：灰色=不安全（环），黑色=安全
        if (color[u] != 0) {
            return color[u] == 2;
        }

        // 标灰：进入当前 DFS 路径
        color[u] = 1;

        for (int v : graph[u]) {
            // 如果邻居不安全，那么当前节点也不安全
            if (!isSafe(graph, v, color)) {
                // 注意：这里不标黑，保持灰色
                // 后续遇到灰色会直接返回 false
                return false;
            }
        }

        // 所有邻居都安全 → 当前节点安全 → 标黑
        color[u] = 2;
        return true;
    }
};

// ============================================================
// 解法2: 反向拓扑排序 (BFS)
// 时间: O(V+E)  空间: O(V+E)  额外空间用于反图
//
// 【思路】
// 换个角度看：安全节点最终都通向出度为0的终端节点。
// 如果我们从终端节点出发，反向传播"安全性"，那么所有能被
// 反向到达的节点都是安全的。
//
// 具体做法：
//   1. 建反图 rg：原图 u→v 变成 rg 中 v→u
//   2. 记录每个节点在原图中的出度 outDeg[u]
//   3. 将出度为0的终端节点入队
//   4. BFS：每处理一个安全节点 u，遍历 rg[u]（即原图中指向 u 的节点 v）
//      - outDeg[v]--（v 的一个后继已确认安全）
//      - 如果 outDeg[v] == 0（v 的所有后继都安全）→ v 也是安全节点，入队
//
// 为什么 outDeg 减到 0 就安全？
//   outDeg[v] 表示 v 还有多少后继"不确定安全"。当所有后继都被
//   确认安全后，v 自然也安全了（从 v 出发的所有路径都通向安全节点）。
//
// 示例: graph = [[1,2],[2,3],[5],[0],[5],[],[]]
//   出度: [2, 2, 1, 1, 1, 0, 0]
//   终端: {5, 6} 入队
//
//   处理5: rg[5]={2,4} → outDeg[2]=0(入队), outDeg[4]=0(入队)
//   处理6: rg[6]={} → 无影响
//   处理2: rg[2]={0,1} → outDeg[0]=1, outDeg[1]=1 (还没减到0)
//   处理4: rg[4]={} → 无影响
//
//   安全: {2, 4, 5, 6} ✓  (0和1的出度没有减到0，因为它们有边指向环)
// ============================================================
class Solution2 {
public:
    vector<int> eventualSafeNodes(vector<vector<int>>& graph) {
        int n = graph.size();

        // 反向图：rg[v] 存储原图中所有指向 v 的节点
        vector<vector<int>> rg(n);
        // 原图中每个节点的出度
        vector<int> outDeg(n, 0);

        for (int u = 0; u < n; u++) {
            outDeg[u] = graph[u].size();
            for (int v : graph[u]) {
                rg[v].push_back(u);
            }
        }

        // 出度为0的终端节点入队
        queue<int> q;
        for (int i = 0; i < n; i++) {
            if (outDeg[i] == 0) {
                q.push(i);
            }
        }

        // BFS 反向传播安全性
        vector<bool> safe(n, false);
        while (!q.empty()) {
            int u = q.front();
            q.pop();
            safe[u] = true;

            // 遍历原图中指向 u 的节点（u 的前驱）
            for (int v : rg[u]) {
                outDeg[v]--;
                if (outDeg[v] == 0) {
                    q.push(v);
                }
            }
        }

        // 收集安全节点，按升序排列
        vector<int> result;
        for (int i = 0; i < n; i++) {
            if (safe[i]) {
                result.push_back(i);
            }
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间   | 空间    | 优势                        | 劣势              |
// |-------------|--------|---------|----------------------------|-------------------|
// | DFS三色标记  | O(V+E) | O(V)   | 空间少，代码简洁，经典方法    | 递归深度可能大      |
// | 反向拓扑排序  | O(V+E) | O(V+E) | 无递归，天然处理拓扑结构      | 需要建反图，空间多   |
//
// 面试策略：DFS 三色标记是标准答案，简洁易写。
// 如果面试官问"还有其他方法吗？"，拿出反向拓扑排序作为进阶方案。
//
// ============================================================
// 【易错点】
//
// 1. DFS 中灰色节点被错误标黑:
//    ✗ 发现环时仍然执行 color[u] = 2
//      → 在环上的节点被标为安全，后续访问到不再检测环
//    ✓ 只有所有邻居都安全时才标黑，发现环时保持灰色并返回 false
//
// 2. 忘记处理自环:
//    ✗ 假设 graph[i] 不包含 i → 自环节点被当成安全的
//    ✓ DFS 中自环天然被灰色检测捕获：DFS(u) 遍历邻居遇到 u 自己是灰色 → false
//
// 3. 反向拓扑排序中出度和入度搞混:
//    ✗ 用反图的出度做判断 → 概念错误，应该用原图的出度
//    ✓ outDeg[u] = graph[u].size() (原图出度)，减到0表示所有后继都安全
//
// 4. 结果未排序:
//    ✗ DFS 以完成时间顺序收集节点 → 不是升序
//    ✓ 按 0 到 n-1 遍历收集，天然有序
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: DFS 的时间复杂度为什么是 O(V+E) 而不是 O(V*E)?
//     每个节点最多被完整 DFS 一次（之后有颜色直接返回）。
//     所以每个节点被访问 O(1) 次，每条边被遍历 O(1) 次。
//
// Q2: 如果要输出所有环中的节点（而非安全节点），怎么改？
//     DFS 中不安全的节点就是在环上或能到达环的节点。
//     可以用一个额外标记（如 color=3 表示不安全），DFS 返回 false
//     时标记 color[u]=3，最后收集所有 color=3 的节点。
//
// Q3: Tarjan 强连通分量和本题的关系？
//     SCC 可以找到所有强连通分量。非平凡SCC（大小>1）中的节点
//     都在环上，能到达非平凡SCC的节点也不安全。
//     SCC 是更通用的算法，但对本题来说 DFS 三色标记更简洁。
//
