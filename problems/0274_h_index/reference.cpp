/*
 * LeetCode 274: H-Index (H 指数)
 *
 * 找最大的 h 使得至少有 h 篇论文被引用了至少 h 次。
 * 关键洞察：h 的范围是 [0, n]，引用次数 > n 的论文和 = n 的等价。
 *
 * 难度：Medium
 * 标签：Array, Counting Sort, Sorting
 */


/* ============================================================
 * 解法1: 排序 + 线性扫描 — O(n log n) / O(1)
 *
 * 排序后从大到小检查：
 *   citations[n-1-i] 是第 i+1 大的引用次数
 *   如果第 i+1 大的引用 >= i+1 → 至少有 i+1 篇论文引用 >= i+1
 *   如果第 i+1 大的引用 <  i+1 → h = i（上一个满足的位置）
 *
 * 模拟 [3,0,6,1,5] → 排序 [0,1,3,5,6]:
 *   i=0: [6] >= 1? Yes → 至少 1 篇论文引用 >= 1
 *   i=1: [5] >= 2? Yes → 至少 2 篇论文引用 >= 2
 *   i=2: [3] >= 3? Yes → 至少 3 篇论文引用 >= 3
 *   i=3: [1] >= 4? No  → h = 3
 * ============================================================ */

class Solution_Sort {
public:
    int hIndex(vector<int>& citations) {
        sort(citations.begin(), citations.end());
        int n = citations.size();

        // 从最大引用开始，逐一检查
        for (int i = 0; i < n; i++) {
            // citations[n-1-i] 是第 i+1 大的引用
            if (citations[n - 1 - i] < i + 1) {
                return i;  // 第 i+1 大的引用不够，h = i
            }
        }

        return n;  // 所有论文引用都 >= n，h = n
    }
};


/* ============================================================
 * 解法2: 计数排序 — O(n) / O(n) ⭐ 最优解
 *
 * 核心洞察：h <= n，所以引用 > n 和引用 = n 等价。
 *
 * 算法：
 *   1. 建立 count[0..n] 桶
 *      count[i] = 恰好被引用 i 次的论文数
 *      引用 >= n 的全部归入 count[n]
 *
 *   2. 从 i=n 到 i=0，累加 total（引用 >= i 的论文数）
 *      第一个 total >= i 的位置就是 h-index
 *
 * 模拟 [3,0,6,1,5], n=5:
 *
 *   Step 1 建桶:
 *     引用次数:    0    1    2    3    4    5(含>=5)
 *     count[]:   [1,   1,   0,   1,   0,   2]
 *                 ↑    ↑         ↑         ↑
 *                c=0  c=1       c=3      c=5,c=6
 *
 *   Step 2 后缀累加:
 *     i=5: total = 0+2 = 2,  2 >= 5? No  (不够 5 篇引用 >= 5)
 *     i=4: total = 2+0 = 2,  2 >= 4? No  (不够 4 篇引用 >= 4)
 *     i=3: total = 2+1 = 3,  3 >= 3? Yes! 有 3 篇引用 >= 3
 *     → h = 3
 *
 * ============================================================ */

class Solution {
public:
    int hIndex(vector<int>& citations) {
        int n = citations.size();

        // Step 1: 建立计数桶
        // count[i] = 恰好被引用 i 次的论文数
        // 引用次数 >= n 的全部归入 count[n]
        vector<int> count(n + 1, 0);
        for (int c : citations) {
            count[min(c, n)]++;
            // 为什么用 min(c, n)？
            // 因为 h 最大只能是 n，引用 100 次和引用 n 次对 h 的贡献一样
            // 同时也避免了数组越界
        }

        // Step 2: 从后往前累加
        // total = 引用次数 >= i 的论文总数
        int total = 0;
        for (int i = n; i >= 0; i--) {
            total += count[i];

            // 至少有 total 篇论文引用 >= i 次
            // 如果 total >= i，满足 h-index 定义
            // 因为从大到小遍历，第一个满足的 i 就是最大的 h
            if (total >= i) {
                return i;
            }
        }

        return 0;  // 理论上不会走到这里（i=0 时 total=n >= 0 必定满足）
    }
};


/* ============================================================
 * 解法3: 排序 + 二分查找 — O(n log n) / O(1)
 *
 * 排序后利用有序性二分查找 h-index。
 * 在排序后的数组中，二分找最大的 h 使得 citations[n-h] >= h。
 *
 * 二分思路：
 *   对 h 在 [0, n] 二分
 *   检查条件：citations[n - mid] >= mid
 *   如果满足：说明 mid 是可行的 h，尝试更大 → lo = mid
 *   如果不满足：mid 不可行 → hi = mid - 1
 *
 * 注意：lo = mid 时需要上取整避免死循环
 * ============================================================ */

class Solution_Binary {
public:
    int hIndex(vector<int>& citations) {
        sort(citations.begin(), citations.end());
        int n = citations.size();

        int lo = 0, hi = n;
        while (lo < hi) {
            // 上取整：避免 lo=mid 时死循环
            int mid = lo + (hi - lo + 1) / 2;

            // citations[n - mid] 是第 mid 大的引用次数
            if (citations[n - mid] >= mid) {
                lo = mid;       // mid 可行，尝试更大的 h
            } else {
                hi = mid - 1;   // mid 不可行，缩小搜索范围
            }
        }

        return lo;
    }
};


/* ============================================================
 * 附：h-index 的几何直觉
 *
 * 把论文按引用次数从大到小排列，画成柱状图：
 *
 *   citations = [3,0,6,1,5] → 排序后 [6,5,3,1,0]
 *
 *   引用次数
 *     6 |#
 *     5 |##
 *     4 |##
 *     3 |###        ← h=3 的位置：3x3 的正方形
 *     2 |###
 *     1 |####
 *     0 |#####
 *       +---------
 *        1 2 3 4 5  ← 论文编号（从引用最多的开始）
 *
 *   h-index = 3 就是能画出的最大正方形的边长！
 *   至少 3 根柱子高度 >= 3。
 *
 * ============================================================
 *
 * 边界情况测试：
 *
 * 1. citations = [0]       → count=[1], i=0: total=1>=0 → h=0
 * 2. citations = [100]     → count=[0,1], i=1: total=1>=1 → h=1
 * 3. citations = [0,0,0]   → count=[3,0,0,0], i=0: total=3>=0 → h=0
 * 4. citations = [1,1,1]   → count=[0,3,0,0], i=1: total=3>=1 → h=1
 * 5. citations = [10,8,5,4,3] → count=[0,0,0,1,1,3],
 *    i=5: 3>=5?No, i=4: 4>=4?Yes → h=4
 *
 * ============================================================ */


// ============================================================
// 【解法对比】
// ============================================================
// 排序+线性扫描  O(n log n)/O(1) — 代码最直观，不需额外空间
// 计数排序       O(n)/O(n)       — 时间最优，利用 h<=n 的性质，面试首选
// 排序+二分查找  O(n log n)/O(1) — 展示二分思维，但不如计数排序优
//
// 选用场景:
//   面试 → 计数排序（O(n) + 讲"引用>n 等价于 n"的洞察）
//   快速实现 → 排序+线性扫描（代码短）
//   练习二分模板 → 排序+二分（注意上取整避免死循环）

// ============================================================
// 【易错点】
// ============================================================
// ✗ count[c]++  不做 min(c, n)  → 引用次数超大时数组越界
// ✓ count[min(c, n)]++          → 引用 > n 的全部归入 count[n]
//
// ✗ 计数排序从 i=0 开始向 i=n 累加 → 找的是"引用<=i"的论文数，逻辑反了
// ✓ 从 i=n 向 i=0 后缀累加 → total 表示"引用>=i"的论文数
//
// ✗ 二分时用 mid = lo + (hi-lo)/2 且 lo = mid → 死循环(lo永远等于mid)
// ✓ lo = mid 时必须上取整: mid = lo + (hi - lo + 1) / 2

// ============================================================
// 【面试追问 Interview Follow-ups】
// ============================================================
// Q1: 如果引用数组已经排好序(LeetCode 275)，能否做到 O(log n)？
// A1: 可以直接二分查找。在已排序数组中，二分找最大 h 使得
//     citations[n-h] >= h。无需计数排序，时间 O(log n)。
//
// Q2: H-Index 的实际应用场景是什么？为什么不直接用平均引用次数？
// A2: H-Index 兼顾了论文数量和引用质量，不受极端值影响。
//     比如 1 篇论文被引用 1000 次，其他都是 0 → 平均高但 h=1。
//     h-index 反映的是"稳定的学术产出"，比均值更鲁棒。
//
// Q3: 如果要支持动态插入新论文并实时查询 H-Index，怎么设计？
// A3: 维护一个计数数组 count[0..maxH] 和当前 total。
//     插入新论文时更新 count[min(c,n)]++，然后从当前 h 向上检查
//     能否增大 h。均摊 O(1) 更新，因为 h 单调不减且最多增长到 n。
