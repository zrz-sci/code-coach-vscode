/*
 * LeetCode 1314: Matrix Block Sum (矩阵区域和)
 *
 * 【题目本质】
 * 对 m x n 矩阵中每个位置 (i,j)，计算以它为中心、半径 k 的矩形区域内
 * 所有元素之和。经典的二维前缀和应用题。
 *
 * 【解法总览】
 * 解法1: 暴力             — O(m*n*k^2) / O(m*n) — 对每个位置遍历区域
 * 解法2: 二维前缀和       — O(m*n) / O(m*n)     — 预处理 + O(1) 查询 ⭐推荐
 */

// ============================================================
// 解法1: 暴力 — 对每个位置遍历 (2k+1)x(2k+1) 区域求和
// 时间: O(m*n*k^2)  空间: O(m*n)
//
// 【思路】
// 最直观做法：对每个 (i,j)，用双重循环遍历 [i-k,i+k] x [j-k,j+k]
// 的所有合法位置求和。
// 当 m=n=k=100 时约 10^8，可能刚好超时或勉强通过。
// ============================================================
class Solution1 {
public:
    vector<vector<int>> matrixBlockSum(vector<vector<int>>& mat, int k) {
        int m = mat.size(), n = mat[0].size();
        vector<vector<int>> ans(m, vector<int>(n, 0));

        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                // 遍历以 (i,j) 为中心的矩形区域
                for (int r = max(0, i - k); r <= min(m - 1, i + k); r++) {
                    for (int c = max(0, j - k); c <= min(n - 1, j + k); c++) {
                        ans[i][j] += mat[r][c];
                    }
                }
            }
        }

        return ans;
    }
};

// ============================================================
// 解法2: 二维前缀和 — 预处理 + O(1) 查询 ⭐推荐
// 时间: O(m*n)  空间: O(m*n)
//
// 【思路】
// 二维前缀和把子矩阵求和从 O(k^2) 优化到 O(1)。
//
// Step 1: 构建前缀和数组 pre[m+1][n+1]（多一行一列避免边界）
//   pre[i+1][j+1] = mat[i][j] + pre[i][j+1] + pre[i+1][j] - pre[i][j]
//
//   含义: pre[i][j] = mat 中 (0,0) 到 (i-1,j-1) 的矩形区域和
//
//   构建过程 (容斥原理):
//
//   ┌─────────┬────────┐
//   │ pre[i][j] │        │    pre[i+1][j+1] = mat[i][j]    ← 新元素
//   │    A      │   B    │                  + pre[i][j+1]   ← A+B (上面)
//   ├──────────┼────────┤                  + pre[i+1][j]   ← A+C (左边)
//   │    C      │ (i,j)  │                  - pre[i][j]     ← A (被加了两次)
//   └──────────┴────────┘
//
// Step 2: 对每个 (i,j) 用容斥公式查询子矩阵和
//   r1 = max(0, i-k),   c1 = max(0, j-k)     ← 矩形左上角(clamp到合法)
//   r2 = min(m-1, i+k), c2 = min(n-1, j+k)   ← 矩形右下角(clamp到合法)
//
//   ans[i][j] = pre[r2+1][c2+1] - pre[r1][c2+1] - pre[r2+1][c1] + pre[r1][c1]
//
//   查询过程 (容斥原理):
//
//   ┌──────┬──────────┬───┐
//   │  D   │    E     │   │    sum = pre[r2+1][c2+1]  (D+E+F+目标)
//   ├──────┼──────────┤   │        - pre[r1][c2+1]    (D+E)
//   │  F   │  目标区域  │   │        - pre[r2+1][c1]    (D+F)
//   │      │ (r1,c1)  │   │        + pre[r1][c1]      (D, 被减两次加回一次)
//   │      │  至(r2,c2)│   │
//   └──────┴──────────┴───┘
//
// 手动推演 mat=[[1,2,3],[4,5,6],[7,8,9]], k=1:
//
//   前缀和:
//     pre:  0   0   0   0
//           0   1   3   6
//           0   5  12  21
//           0  12  27  45
//
//   answer[0][0]:
//     r1=0, c1=0, r2=1, c2=1
//     = pre[2][2] - pre[0][2] - pre[2][0] + pre[0][0]
//     = 12 - 0 - 0 + 0 = 12 ✓
//
//   answer[1][1]:
//     r1=0, c1=0, r2=2, c2=2
//     = pre[3][3] - pre[0][3] - pre[3][0] + pre[0][0]
//     = 45 - 0 - 0 + 0 = 45 ✓ (k=1时中心(1,1)覆盖整个3x3矩阵)
// ============================================================
class Solution2 {
public:
    vector<vector<int>> matrixBlockSum(vector<vector<int>>& mat, int k) {
        int m = mat.size(), n = mat[0].size();

        // Step 1: 构建二维前缀和
        // pre[i+1][j+1] 存储 mat[0..i][0..j] 的区域和
        // 多一行一列(初始为0)避免 i-1<0 的边界判断
        vector<vector<int>> pre(m + 1, vector<int>(n + 1, 0));
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                pre[i + 1][j + 1] = mat[i][j]
                    + pre[i][j + 1]     // 上方区域
                    + pre[i + 1][j]     // 左方区域
                    - pre[i][j];        // 左上角被加了两次，减掉
            }
        }

        // Step 2: 对每个位置用容斥公式查询
        vector<vector<int>> ans(m, vector<int>(n));
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                // clamp 坐标到合法范围 [0, m-1] x [0, n-1]
                int r1 = max(0, i - k),     c1 = max(0, j - k);
                int r2 = min(m - 1, i + k), c2 = min(n - 1, j + k);

                // 容斥公式: +总区域 -上方 -左方 +左上角
                ans[i][j] = pre[r2 + 1][c2 + 1]
                          - pre[r1][c2 + 1]
                          - pre[r2 + 1][c1]
                          + pre[r1][c1];
            }
        }

        return ans;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法          | 时间         | 空间    | 代码复杂度 | 面试推荐 |
// |--------------|-------------|---------|-----------|---------|
// | 暴力          | O(m*n*k^2)  | O(m*n)  | 简单       | ❌ 低效  |
// | 二维前缀和    | O(m*n)      | O(m*n)  | 中等       | ⭐⭐⭐  |
//
// 暴力 → 前缀和: 将每次子矩阵求和从 O(k^2) 降到 O(1)
// 代价是 O(m*n) 的预处理时间和空间（构建前缀和数组）
//
// 面试策略:
//   1. 先说暴力思路，分析时间复杂度 O(m*n*k^2)
//   2. 指出瓶颈在子矩阵求和 O(k^2)
//   3. 用二维前缀和优化到 O(1)
//   4. 画容斥公式的图解（面试加分）
//
// ============================================================
// 【易错点】
//
// 1. 边界 clamp 遗漏:
//    ✗ int r1 = i - k;  → r1 可能为负数
//    ✓ int r1 = max(0, i - k);
//
// 2. 前缀和查询时忘记 +1:
//    ✗ ans[i][j] = pre[r2][c2] - ...  → 少算了 r2 行和 c2 列
//    ✓ ans[i][j] = pre[r2+1][c2+1] - ...
//    因为 pre 数组偏移了一位, pre[r2+1] 才对应 mat 的第 r2 行
//
// 3. 构建前缀和时忘记减去 pre[i][j]:
//    ✗ pre[i+1][j+1] = mat[i][j] + pre[i][j+1] + pre[i+1][j]
//    ✓ pre[i+1][j+1] = mat[i][j] + pre[i][j+1] + pre[i+1][j] - pre[i][j]
//    不减 pre[i][j] 会导致左上区域被重复计算
//
// 4. 查询容斥符号错误:
//    正确: +pre[r2+1][c2+1] - pre[r1][c2+1] - pre[r2+1][c1] + pre[r1][c1]
//    四项: +总 -上 -左 +左上
//    如果把最后的 + 写成 -，结果会全部偏小
// ============================================================

// ============================================================
// 【面试追问】
//
// Q1: 如果只需要查询一次子矩阵和（不是对每个位置都查），
//     还值得建前缀和吗？
// A1: 一次查询 → 暴力 O(k^2) 更划算，不需要 O(m*n) 预处理。
//     前缀和的价值在于「多次查询」，本题对每个 (i,j) 都查一次，
//     共 m*n 次查询，预处理的代价被摊平。
//
// Q2: 如何把空间从 O(m*n) 优化到 O(n)？
// A2: 可以用「滑动窗口 + 一维前缀和」：
//     先对每一行做一维前缀和 row_pre[i][j]，
//     然后用大小为 (2k+1) 的滑动窗口在列方向累加行前缀和差值。
//     但代码复杂度上升，面试中二维前缀和已是最优答案。
//
// Q3: 如果矩阵支持单点修改（mat[r][c] += val），
//     如何高效维护子矩阵和查询？
// A3: 二维前缀和不支持动态修改（修改后需 O(m*n) 重建）。
//     方案: 二维树状数组（BIT）或二维线段树。
//     二维 BIT: 修改 O(log m * log n)，查询 O(log m * log n)。
//     这是经典的「静态前缀和 → 动态数据结构」升级路线。
// ============================================================
