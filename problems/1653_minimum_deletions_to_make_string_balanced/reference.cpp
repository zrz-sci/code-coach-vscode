/*
 * LeetCode 1653: 使字符串平衡的最少删除次数
 * 
 * 【题目本质】
 * 字符串只含 'a' 和 'b'，删最少字符使其变成 "aaa...bbb..." 的形态。
 * 等价于：在某个位置切一刀，左边删所有 b，右边删所有 a，总删除最少。
 *
 * 【解法总览】
 * 解法1: 枚举分割点 + 前缀/后缀统计 — O(n) / O(n) — 最直观
 * 解法2: DP（滚动变量）              — O(n) / O(1) — 面试首选 ⭐
 * 解法3: 栈消除逆序对（计数器优化）    — O(n) / O(1) — 加分项
 */

// ============================================================
// 解法1: 枚举分割点 + 前缀/后缀统计
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 平衡字符串 = "aaa...bbb..."，一定存在一个分割位置：
//   位置 i 左边全是 a（有 b 就删），右边全是 b（有 a 就删）
// 代价 = prefixB[i] + suffixA[i]
// 预处理后缀 a 的计数，遍历时维护前缀 b 的计数，O(1) 查询每个分割点。
//
// 示例 s = "aababbab":
//   位置:      0 1 2 3 4 5 6 7
//   prefixB:   0 0 1 1 2 2 3 3
//   suffixA:   3 2 2 2 1 1 1 0
//   分割点0: 0+3=3, 分割点4: 2+1=3... 最优在某个位置得到 2
// ============================================================
class Solution1 {
public:
    int minimumDeletions(string s) {
        int n = s.size();
        
        // suffixA[i] = s[i..n-1] 中 'a' 的个数
        vector<int> suffixA(n + 1, 0);
        for (int i = n - 1; i >= 0; i--) {
            suffixA[i] = suffixA[i + 1] + (s[i] == 'a' ? 1 : 0);
        }
        
        int ans = n;
        int prefixB = 0;
        // 枚举 n+1 个分割点（0 到 n）
        for (int i = 0; i <= n; i++) {
            // 分割点 i: 左边 [0, i) 删所有 b，右边 [i, n) 删所有 a
            ans = min(ans, prefixB + suffixA[i]);
            if (i < n && s[i] == 'b') {
                prefixB++;
            }
        }
        return ans;
    }
};

// ============================================================
// 解法2: DP（滚动变量优化）— 面试首选 ⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// dp = 处理完当前字符后，使已扫描部分平衡的最少删除次数
// countB = 已扫描部分中 'b' 的个数
//
// 转移:
//   遇到 'b': b 放在末尾合法，dp 不变，countB++
//   遇到 'a': 两个选择取最小
//     选择1: 删掉这个 a → dp + 1
//     选择2: 保留 a，但把前面所有 b 都删掉 → countB
//
// 为什么选择2是 countB 而不是 dp + 某个值?
//   因为如果保留了当前的 a，那么 a 前面不能有任何 b，
//   所以必须删掉前面所有 b，代价恰好是 countB。
//   此时所有 a 都保留，不需要额外删 a，所以不加 dp。
//
// DP 填表过程 (s = "aababbab"):
//   i=0 'a': dp = min(0+1, 0) = 0, countB = 0
//   i=1 'a': dp = min(0+1, 0) = 0, countB = 0
//   i=2 'b': dp = 0,               countB = 1
//   i=3 'a': dp = min(0+1, 1) = 1, countB = 1
//   i=4 'b': dp = 1,               countB = 2
//   i=5 'b': dp = 1,               countB = 3
//   i=6 'a': dp = min(1+1, 3) = 2, countB = 3
//   i=7 'b': dp = 2,               countB = 4
//   答案: 2 ✓
// ============================================================
class Solution2 {
public:
    int minimumDeletions(string s) {
        int dp = 0;
        int countB = 0;
        
        for (char c : s) {
            if (c == 'b') {
                // b 追加到末尾不破坏平衡性
                countB++;
            } else {
                // c == 'a'
                // 选择1: 删掉这个 a，代价 dp + 1
                // 选择2: 保留这个 a，删掉前面所有 b，代价 countB
                dp = min(dp + 1, countB);
            }
        }
        return dp;
    }
};

// ============================================================
// 解法3: 栈消除逆序对（计数器优化）
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 不平衡的根源是 "ba" 逆序对。类似括号匹配：
//   - 遇到 'b': 入栈（等待后续是否形成逆序对）
//   - 遇到 'a': 如果栈顶有 'b'，弹出 'b'，计一次删除（消除逆序对）
//              如果栈空，a 在前面是合法的，不需要处理
//
// 因为栈里只会存 'b'，所以用一个 bCount 计数器代替栈。
//
// 模拟 s = "aababbab":
//   'a': bCount=0, 栈空不处理              del=0
//   'a': bCount=0, 栈空不处理              del=0
//   'b': bCount=1                          del=0
//   'a': bCount>0! bCount=0, del++         del=1  (消掉了位置2的b和位置3的a)
//   'b': bCount=1                          del=1
//   'b': bCount=2                          del=1
//   'a': bCount>0! bCount=1, del++         del=2  (消掉了位置4/5的某个b和位置6的a)
//   'b': bCount=2                          del=2
//   答案: 2 ✓
//
// 为什么贪心消除逆序对是对的?
// 每个逆序对至少需要删一个字符(b或a)。遇到逆序对就消除，
// 每次消耗1次删除且消除1个逆序对，不会产生新的逆序对，
// 所以总删除次数是最优的。
// ============================================================
class Solution3 {
public:
    int minimumDeletions(string s) {
        int deletions = 0;
        int bCount = 0;
        
        for (char c : s) {
            if (c == 'b') {
                bCount++;
            } else {
                // c == 'a'
                if (bCount > 0) {
                    // 存在 b...a 逆序对，消除它
                    bCount--;     // "删掉"一个 b
                    deletions++;  // 记一次删除
                }
                // bCount == 0 说明前面没有 b，这个 a 是安全的
            }
        }
        return deletions;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间  | 空间  | 核心思维         |
// |-------------|-------|-------|-----------------|
// | 枚举分割点   | O(n)  | O(n)  | 几何切割         |
// | DP 滚动变量  | O(n)  | O(1)  | 逐步最优决策      |
// | 栈消除逆序对  | O(n)  | O(1)  | 匹配消除         |
//
// 面试推荐: 解法2（DP）代码最短、空间最优，且容易解释转移方程。
// 解法1 适合作为起始思路向面试官展示理解。
// 解法3 展示多角度思维能力，是加分项。
//
// 【易错点】
// 1. DP 中遇到 'b' 时忘了 countB++
//    ✗ if (c == 'b') { /* nothing */ }
//    ✓ if (c == 'b') { countB++; }
//    countB 代表"保留当前 a 时需要删多少 b"，必须持续更新
//
// 2. 分割点只枚举 n 个而不是 n+1 个
//    ✗ for (int i = 0; i < n; i++) — 漏掉"全在左边"的情况
//    ✓ for (int i = 0; i <= n; i++) — 分割点从 0 到 n
//
// 3. 栈解法忘记检查 bCount > 0
//    ✗ 遇到 'a' 直接 bCount--; deletions++; 
//      → 当 bCount==0 时变成负数，结果错误
//    ✓ if (bCount > 0) { bCount--; deletions++; }
//
// 4. DP 中把 a 和 b 的逻辑搞反
//    遇到 'b' 时 dp 不变（合法追加），遇到 'a' 才需要决策。
//    如果反过来，等价于求 "bbb...aaa..." 形态，答案错误。
//
// 【面试追问】
// Q1: 暴力解复杂度？→ 枚举每个字符删/不删 O(2^n)，不可行。
//     但枚举分割点只有 n+1 个，配合前缀和 O(n)，这是好的起点。
//
// Q2: DP 中 min(dp+1, countB) 两项分别代表什么？
//     → dp+1: 删当前 a，沿用之前最优方案
//     → countB: 保留当前 a，把前面所有 b 都删掉
//
// Q3: 推广到多种字符（要求非递减）怎么做？
//     → 变成 n - LIS(非递减版) 问题，O(n log n) 解决。
//     → 本题是只有2种字符的特化，分割点枚举更高效。
//
// Q4: 926题（翻转到单调递增）和本题的关系？
//     → 几乎相同！926 是 0/1 字符串翻转，本题是 a/b 删除。
//     → 枚举分割点的思路完全复用，代码改动：
//       本题: prefixB + suffixA（删除次数）
//       926:  prefix1 + suffix0（翻转次数，把左边的1翻成0 + 右边的0翻成1）
// ============================================================
