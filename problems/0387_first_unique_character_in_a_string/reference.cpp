/*
 * LeetCode 387: 字符串中的第一个唯一字符 (First Unique Character in a String)
 *
 * 【题目本质】
 * 统计字符频次，按原始顺序找第一个频次为1的字符的索引。
 *
 * 【解法总览】
 * 解法1: 暴力双循环       — O(n²) / O(1)   — 最直觉，面试中展示理解
 * 解法2: 计数数组两遍遍历 — O(n)  / O(1)   — 面试首选 ⭐
 * 解法3: 队列+计数(流式)  — O(n)  / O(n)   — Follow-up: 数据流场景
 */

// ============================================================
// 解法1: 暴力双循环 — 对每个字符扫全串检查唯一性
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 最自然的想法：对每个位置 i，遍历整个字符串看有没有
// 另一个位置 j≠i 使得 s[j]==s[i]。如果没有，i 就是答案。
// 
// 瓶颈：每个字符都要扫一遍全串，n=10^5 时约 10^10 操作，太慢。
// ============================================================
class Solution1 {
public:
    int firstUniqChar(string s) {
        int n = s.size();
        for (int i = 0; i < n; i++) {
            bool unique = true;
            for (int j = 0; j < n; j++) {
                if (i != j && s[i] == s[j]) {
                    unique = false;
                    break;  // 发现重复，提前终止内层循环
                }
            }
            if (unique) return i;
        }
        return -1;
    }
};

// ============================================================
// 解法2: 计数数组 + 两遍遍历 — 面试首选 ⭐
// 时间: O(n)  空间: O(1)  (字符集固定26个，数组大小为常数)
//
// 【思路】
// 解法1的瓶颈：判断每个字符是否唯一需要 O(n)。
// 突破：先用一遍遍历把所有字符的出现次数统计好（存入大小为26的数组），
// 之后判断任意字符是否唯一只需 O(1) 查表。
// 
// 关键：第二遍必须按原字符串顺序遍历（不是遍历计数数组），
// 这样第一个找到的 count==1 的位置就是答案。
//
// 示例: s = "loveleetcode"
//
// 第一遍统计:
//   l:2, o:2, v:1, e:4, t:1, c:1, d:1
//
// 第二遍按原始顺序:
//   index 0: 'l' → count=2, 跳过
//   index 1: 'o' → count=2, 跳过
//   index 2: 'v' → count=1, ✅ 返回 2
// ============================================================
class Solution2 {
public:
    int firstUniqChar(string s) {
        // 26个小写字母的频次数组，比 unordered_map 更快
        int count[26] = {0};
        
        // 第一遍：统计频次
        for (char c : s) {
            count[c - 'a']++;
        }
        
        // 第二遍：按原始顺序找第一个频次为1的
        // 为什么不遍历 count 数组？因为 count 的索引是字母序(a,b,c...)
        // 不是原始出现顺序，会找错
        for (int i = 0; i < (int)s.size(); i++) {
            if (count[s[i] - 'a'] == 1) {
                return i;
            }
        }
        
        return -1;  // 所有字符都有重复
    }
};

// ============================================================
// 解法3: 队列 + 计数数组（流式处理）
// 时间: O(n)  空间: O(n) 最坏情况队列存 n 个索引
//
// 【思路】
// Follow-up 场景：如果字符是一个一个流式到来的，
// 每来一个字符都需要能查询"当前第一个唯一字符"。
//
// 核心想法：
// - 队列维护"候选唯一字符"的索引，先进先出保证顺序
// - 频次表记录每个字符出现了多少次
// - 每次新字符到来：更新频次、入队
// - 查询时：如果队首字符频次 > 1（已不唯一），弹出
// - 队首就是第一个唯一字符
//
// 为什么每个元素最多入队出队一次？
// 因为一旦某字符频次 > 1，它会被弹出，永远不会再被考虑。
//
// 模拟 s = "leetcode":
//   读 'l': q=[0]        count={l:1}      队首 l(1) → 唯一
//   读 'e': q=[0,1]      count={e:1}      队首 l(1) → 唯一
//   读 'e': q=[0,1,2]    count={e:2}      队首 l(1) → 唯一
//   读 't': q=[0,1,2,3]  count={t:1}      队首 l(1) → 唯一
//   读 'c': q=[0,1,2,3,4]                 队首 l(1) → 唯一
//   读 'o': q=[0,1,2,3,4,5]               队首 l(1) → 唯一
//   读 'd': q=[0,1,2,3,4,5,6]             队首 l(1) → 唯一
//   读 'e': q=[0,1,2,3,4,5,6,7] count={e:3}
//     清理: 队首 idx=0 'l' count=1 → 不弹出 → 答案 idx=0
// ============================================================
class Solution3 {
public:
    int firstUniqChar(string s) {
        int count[26] = {0};
        queue<int> q;  // 存索引，维护候选唯一字符的先后顺序
        
        for (int i = 0; i < (int)s.size(); i++) {
            count[s[i] - 'a']++;
            q.push(i);
            
            // 延迟删除：弹出队首中已经不唯一的字符
            // 为什么是 while 不是 if？因为可能连续多个队首都不唯一
            while (!q.empty() && count[s[q.front()] - 'a'] > 1) {
                q.pop();
            }
        }
        
        return q.empty() ? -1 : q.front();
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间  | 空间 | 核心操作        | 适用场景      |
// |------|-------|------|-----------------|---------------|
// | 暴力 | O(n²) | O(1) | 双循环逐个检查  | 理解题意      |
// | 计数 | O(n)  | O(1) | 数组频次统计    | 面试首选 ⭐    |
// | 队列 | O(n)  | O(n) | 队列+延迟删除   | 数据流场景    |
//
// 解法2 vs 解法3:
// - 解法2 需要完整字符串才能开始（两遍遍历），更简洁
// - 解法3 支持流式处理，每来一个字符就能给出当前答案
// - 面试中先写解法2，被追问流式场景再给解法3
//
// 【易错点】
// 1. 遍历计数数组找结果（而不是遍历原字符串）：
//    ✗ for(int i=0;i<26;i++) if(count[i]==1) return s.find('a'+i);
//    这样找到的是字母序最小的唯一字符，不是位置最前的。
//    比如 s="dc"，应返回0('d')，但上面代码返回1('c')
//    ✓ 第二遍遍历原字符串 s，按索引顺序查 count
//
// 2. 用 unordered_map 遍历取结果：
//    ✗ for(auto& [c,cnt] : mp) if(cnt==1) ...
//    unordered_map 遍历顺序不确定，无法保证"第一个"
//    ✓ 遍历原字符串 s
//
// 3. 队列解法中用 if 而不是 while 清理队首：
//    ✗ if(!q.empty() && count[s[q.front()]-'a'] > 1) q.pop();
//    可能连续多个队首都已不唯一，只弹一个不够
//    ✓ 用 while 循环弹出所有不唯一的队首
//
// 4. 忘记 return -1：全部字符都有重复时没有返回值
//
// 【面试追问】
// Q1(基础): 为什么需要两遍遍历？一遍行不行？
//   → 不行。遍历到位置 i 时，无法知道后面是否还会出现 s[i]。
//     除非用队列做延迟判断（解法3），但那本质也是"先收集再检查"。
//
// Q2(优化): 如果字符串极长（10^9）但字符集很小，有什么好处？
//   → 计数数组只有26个元素，空间 O(1)。第二遍遍历可以提前终止。
//     但时间仍是 O(n)，无法突破——必须至少看一遍所有字符才能确定频次。
//
// Q3(Follow-up): 如果是数据流，字符一个个到来，随时要查询第一个唯一字符？
//   → 解法3：队列+频次表。入队 O(1)，查询 O(1) 摊还（弹出的元素不会再入队）。
//
// Q4(变体): 如果要找最后一个唯一字符呢？
//   → 第二遍从后往前遍历即可，代码只改 for 循环方向。
//
// Q5(扩展): 如果字符不限于小写字母（任意 Unicode）？
//   → 把 int count[26] 换成 unordered_map<char,int>，逻辑完全相同。
// ============================================================
