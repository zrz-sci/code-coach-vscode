/*
 * 【题目本质】
 * 给定链表中一个节点的指针（非尾节点），在不知道 head 的情况下删除该节点。
 * 核心技巧：无法删除自身就"冒名顶替"——复制后继节点的值，再删除后继节点。
 *
 * 【解法总览】
 * 解法1: 值覆盖 + 删除后继  - O(1) 时间, O(1) 空间 ⭐唯一解法
 * 解法2: 带内存释放的版本   - O(1) 时间, O(1) 空间
 */

// ==================== 解法1: 值覆盖 + 删除后继 ====================
// 思路: 把 next 节点的值复制到当前节点，然后跳过 next 节点
//
// Before: ... -> [node:5] -> [next:1] -> [9] -> NULL
// Copy:   ... -> [node:1] -> [next:1] -> [9] -> NULL
// Skip:   ... -> [node:1] ------------> [9] -> NULL
class Solution1 {
public:
    void deleteNode(ListNode* node) {
        // Step 1: 复制后继节点的值
        node->val = node->next->val;
        // Step 2: 跳过后继节点
        node->next = node->next->next;
    }
};

// ==================== 解法2: 带内存释放 ====================
// 思路: 同解法1，但额外释放被跳过的节点内存
// 在 LeetCode 中不需要，但实际工程中应考虑内存管理
class Solution2 {
public:
    void deleteNode(ListNode* node) {
        ListNode* toDelete = node->next;  // 保存待删除节点
        node->val = toDelete->val;         // 复制值
        node->next = toDelete->next;       // 跳过
        delete toDelete;                   // 释放内存
    }
};

/*
 * 【解法对比】
 * ┌────────────────┬──────────┬──────────┬──────────────────────────┐
 * │ 解法           │ 时间     │ 空间     │ 特点                     │
 * ├────────────────┼──────────┼──────────┼──────────────────────────┤
 * │ 值覆盖(基本)   │ O(1)     │ O(1)    │ LeetCode 提交用           │
 * │ 值覆盖(释放)   │ O(1)     │ O(1)    │ 工程实践中更规范          │
 * └────────────────┴──────────┴──────────┴──────────────────────────┘
 *
 * 【易错点】
 * 1. 试图修改局部指针: node = node->next 不改变链表结构！
 *    - 必须修改 node->val 和 node->next（修改节点内容和指针域）
 * 2. 对尾节点使用会导致 node->next 为 NULL -> 段错误
 *    - 题目保证 node 不是尾节点
 * 3. 不要尝试遍历找 head/prev，因为只给了 node 指针
 *
 * 【面试追问】
 * Q: 这种方法的局限性？
 * A:
 *   1. 不能处理尾节点（next 为 NULL）
 *   2. 如果有外部引用指向 next 节点，这些引用会悬空
 *   3. 如果节点数据量大，复制开销高
 *   4. 实际系统中节点可能有唯一 ID/地址标识，复制值会破坏这种映射
 *
 * Q: 真正删除当前节点的方法？
 * A: 必须知道前驱节点。只有一个指针时，唯一安全做法就是值覆盖。
 *    在双向链表中，有 prev 指针则可以真正删除当前节点。
 *
 * Q: 倒数第K个节点如何删除？(LC 19)
 * A: 快慢指针法：快指针先走K步，然后同步走，快到尾时慢在目标前驱处。
 */
