/*
 * LeetCode 78: 子集 (Subsets)
 *
 * 【题目本质】
 * 对于 n 个互不相同的元素，枚举所有 2^n 个子集（幂集）。
 * 每个元素只有"选"或"不选"两种状态。
 *
 * 【解法总览】
 * 解法1: 回溯（选/不选）    — O(n·2^n) / O(n)     — 二叉决策树，最直觉
 * 解法2: 回溯（枚举 start） — O(n·2^n) / O(n)     — ⭐面试首选，万能模板
 * 解法3: 位运算枚举         — O(n·2^n) / O(1)额外  — 最简洁
 * 解法4: 迭代扩展           — O(n·2^n) / O(1)额外  — 数学归纳思路
 */

// ============================================================
// 解法1: 回溯（选/不选）— 二叉决策树
// 时间: O(n · 2^n)  空间: O(n) 递归栈深度
//
// 【思路】
// 对每个元素只做两件事：选它 or 不选它。
// 这形成一棵二叉决策树，叶子节点就是所有子集。
//
// 决策树 (nums = [1, 2, 3]):
//
//                        []
//                   /          \
//              选1 /            \ 不选1
//              [1]              []
//            /     \          /     \
//       选2 /       \不选2  选2/       \不选2
//        [1,2]     [1]      [2]       []
//        / \       / \      / \       / \
//      选3 不选3 选3 不选3 选3 不选3 选3 不选3
//  [1,2,3][1,2][1,3][1] [2,3] [2] [3]  []
//
// 8 个叶子 = 2^3 = 8 个子集
// ============================================================
class Solution1 {
public:
    vector<vector<int>> subsets(vector<int>& nums) {
        vector<vector<int>> result;
        vector<int> path;
        dfs(nums, 0, path, result);
        return result;
    }

private:
    void dfs(vector<int>& nums, int i, vector<int>& path,
             vector<vector<int>>& result) {
        // 所有元素都决策完毕 → 叶子节点，收集结果
        if (i == (int)nums.size()) {
            result.push_back(path);
            return;
        }

        // 分支1：选 nums[i]
        path.push_back(nums[i]);
        dfs(nums, i + 1, path, result);
        path.pop_back();  // 回溯：撤销选择

        // 分支2：不选 nums[i]
        dfs(nums, i + 1, path, result);
    }
};

// ============================================================
// 解法2: 回溯（逐个枚举 + start 控制）— ⭐ 面试首选
// 时间: O(n · 2^n)  空间: O(n) 递归栈深度
//
// 【思路】
// 换一个视角：不是对每个元素做"选/不选"，
// 而是"当前位置后面还能选哪些元素"。
// 用 start 保证只往后选，天然避免重复。
//
// 关键区别：每个递归节点（包括根）都是一个合法子集！
// 所以进入函数就收集，不需要等到叶子。
//
// 决策树 (nums = [1, 2, 3]):
//                    []               ← 收集
//               /     |     \
//             [1]    [2]    [3]       ← 都收集
//            / \      |
//        [1,2] [1,3] [2,3]           ← 都收集
//          |
//       [1,2,3]                       ← 收集
//
// 这个模板是"子集/组合/排列"类的万能框架：
// - 子集：每个节点都收集
// - 组合(77)：path.size()==k 时收集
// - 子集II(90)：加 if(i>start && nums[i]==nums[i-1]) continue
// - 组合总和(39)：递归传 i 而非 i+1（允许重复选）
// ============================================================
class Solution2 {
public:
    vector<vector<int>> subsets(vector<int>& nums) {
        vector<vector<int>> result;
        vector<int> path;
        backtrack(nums, 0, path, result);
        return result;
    }

private:
    void backtrack(vector<int>& nums, int start, vector<int>& path,
                   vector<vector<int>>& result) {
        // 每个节点都是合法子集，立刻收集
        result.push_back(path);

        // 从 start 开始枚举可选元素
        for (int i = start; i < (int)nums.size(); i++) {
            path.push_back(nums[i]);            // 做选择
            backtrack(nums, i + 1, path, result); // 注意是 i+1，不是 start+1！
            path.pop_back();                     // 撤销选择（回溯）
        }
        // for 循环结束自然返回，不需要额外终止条件
    }
};

// ============================================================
// 解法3: 位运算枚举
// 时间: O(n · 2^n)  空间: O(1) 额外（不算输出）
//
// 【思路】
// 核心观察：n 个元素各有选/不选两种状态 → 对应 n 位二进制数。
// 从 0(000...0) 到 2^n - 1(111...1) 枚举，每个整数解码为一个子集。
//
// nums = [1, 2, 3]:
// mask=0 (000) → []         mask=4 (100) → [1]
// mask=1 (001) → [3]        mask=5 (101) → [1,3]
// mask=2 (010) → [2]        mask=6 (110) → [1,2]
// mask=3 (011) → [2,3]      mask=7 (111) → [1,2,3]
//
// 为什么选位运算？
// - 代码极简，一个双重循环搞定
// - 缺点：不如回溯灵活，加约束（如去重、大小限制）时改动大
// ============================================================
class Solution3 {
public:
    vector<vector<int>> subsets(vector<int>& nums) {
        int n = nums.size();
        int total = 1 << n;  // 2^n，n<=10 时最大 1024，安全
        vector<vector<int>> result;

        for (int mask = 0; mask < total; mask++) {
            vector<int> subset;
            for (int i = 0; i < n; i++) {
                // 第 i 位为 1 → 选 nums[i]
                if (mask & (1 << i)) {
                    subset.push_back(nums[i]);
                }
            }
            result.push_back(subset);
        }
        return result;
    }
};

// ============================================================
// 解法4: 迭代扩展（数学归纳）
// 时间: O(n · 2^n)  空间: O(1) 额外（不算输出）
//
// 【思路】
// 数学归纳法：
// - 已有前 k 个元素的所有子集
// - 加入第 k+1 个元素时，把它追加到每个已有子集后面
// - 新产生的子集 + 原有子集 = 前 k+1 个元素的所有子集
//
// 演示 nums = [1, 2, 3]:
// 初始:  [[]]
// 加入1: [[], [1]]                                 ← []加1→[1]
// 加入2: [[], [1], [2], [1,2]]                     ← []加2→[2], [1]加2→[1,2]
// 加入3: [[], [1], [2], [1,2], [3], [1,3], [2,3], [1,2,3]]
//
// 优点：不需要递归，逻辑最直觉
// 注意：内层循环必须先保存 result.size()，否则会死循环！
// ============================================================
class Solution4 {
public:
    vector<vector<int>> subsets(vector<int>& nums) {
        vector<vector<int>> result = {{}};  // 从空集开始

        for (int num : nums) {
            // 必须先保存当前大小！否则 result 在循环中增长会死循环
            int size = result.size();
            for (int i = 0; i < size; i++) {
                vector<int> newSubset = result[i];  // 复制已有子集
                newSubset.push_back(num);            // 追加当前元素
                result.push_back(newSubset);         // 加入结果
            }
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 思维模型 | 模板复用性 | 代码简洁度 | 面试推荐 |
// |------|----------|-----------|-----------|---------|
// | 选/不选   | 二叉决策树 | 中   | 中    | 可以     |
// | 枚举start | N叉决策树  | ⭐高 | 中    | ⭐首选  |
// | 位运算    | 二进制编码 | 低   | 最简洁 | 加分项   |
// | 迭代扩展  | 数学归纳   | 低   | 简洁   | 能说即可 |
//
// 面试首选解法2（枚举start），因为同一个框架直接用于：
// - 77.组合（收集条件改为 path.size()==k）
// - 90.子集II（排序 + 同层去重）
// - 39.组合总和（递归传 i 而非 i+1）
// - 46.全排列（去掉 start，改用 used[] 数组）
//
// ============================================================
// 【易错点】
//
// 1. 回溯忘记 pop_back：
//    ✗ path.push_back(nums[i]); backtrack(...);
//      → 漏了撤销，后续分支全部带着错误选择
//    ✓ path.push_back(nums[i]); backtrack(...); path.pop_back();
//
// 2. 解法2中递归参数写错：
//    ✗ backtrack(nums, start + 1, ...)
//      → 不管选了哪个 i，下一层都从 start+1 开始，会重复
//    ✓ backtrack(nums, i + 1, ...)
//      → 下一层从"当前选择的位置+1"开始
//
// 3. 迭代法内层循环边界：
//    ✗ for (int i = 0; i < result.size(); i++)
//      → result.size() 在循环中增长 → 死循环
//    ✓ int size = result.size();
//      for (int i = 0; i < size; i++)
//
// 4. 位运算法 n 较大时 1<<n 溢出 int：
//    ✗ int total = 1 << n;  // n>30 时溢出
//    ✓ long long total = 1LL << n;
//    （本题 n<=10 不影响，但要有意识）
//
// ============================================================
// 【面试追问】
//
// Q1(基础): 这道题的时间复杂度下界是多少？能不能比 O(n·2^n) 更快？
//    → 不能。输出本身有 2^n 个子集，每个平均长度 n/2，
//      光写出结果就需要 O(n·2^n)，这是信息论下界。
//
// Q2(变体): 如果 nums 有重复元素？（LeetCode 90）
//    → 先排序，回溯时同一层跳过重复：
//      if (i > start && nums[i] == nums[i-1]) continue;
//      改动仅一行，框架完全不变。
//
// Q3(扩展): 如果要求只输出大小为 k 的子集？（LeetCode 77. 组合）
//    → 用解法2的框架，把无条件收集改为 if (path.size() == k) 收集，
//      并加剪枝：if (path.size() + (n - i) < k) return;
//
// Q4(深入): 回溯的两种写法（选/不选 vs 枚举start）本质区别是什么？
//    → 选/不选生成的是完全二叉树（深度n，叶子2^n个），
//      在叶子收集结果。枚举start生成的是N叉树，在每个节点收集。
//      两者遍历的状态空间完全相同，只是组织方式不同。
//
// ============================================================
// 【相关题型】
//
// 90.子集II — 有重复元素，复用解法2，加一行去重：
//    if (i > start && nums[i] == nums[i-1]) continue;
//
// 77.组合 — 复用解法2，收集条件从"每个节点"改为"path.size()==k"
//
// 46.全排列 — 复用回溯框架，去掉 start 参数，
//    改用 used[i] 标记数组（因为排列可以"回头选"）
//
// 39.组合总和 — 复用解法2，递归传 i 而非 i+1（元素可重复使用），
//    加上 target 减到 0 的终止条件
//
// 47.全排列II — 46 + 去重（排序 + used 数组判断）
// ============================================================
