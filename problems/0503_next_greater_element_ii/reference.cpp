/*
 * LeetCode 503: 下一个更大元素 II (Next Greater Element II)
 * 
 * 【题目本质】
 * 在循环数组中，对每个元素找到它之后第一个比它大的元素。
 * = 经典"下一个更大元素"问题 + 循环数组处理技巧。
 *
 * 【解法总览】
 * 解法1: 暴力模拟       — O(n²) / O(1)  — 最直觉
 * 解法2: 单调栈+循环展开 — O(n) / O(n)   — 面试首选 ⭐
 */

// ============================================================
// 解法1: 暴力模拟 — 对每个元素向后扫一圈
// 时间: O(n²)  空间: O(1)（不算结果数组）
//
// 【思路】
// 最朴素的想法：对于 nums[i]，从 i+1 开始往后看，
// 最多看 n-1 个元素（绕一圈回到自己前一个位置），
// 找到第一个比 nums[i] 大的就记录，找不到就是 -1。
//
// 循环索引用 (i + j) % n 实现。
//
// 瓶颈：每个元素独立扫描，大量重复比较。
// 例如 [5, 4, 3, 2, 1, 6]，前5个元素各自都要扫到末尾的6。
// ============================================================
class Solution1 {
public:
    vector<int> nextGreaterElements(vector<int>& nums) {
        int n = nums.size();
        vector<int> res(n, -1);
        for (int i = 0; i < n; i++) {
            for (int j = 1; j < n; j++) {        // 从下一个位置开始，最多看 n-1 个
                int idx = (i + j) % n;            // 循环索引
                if (nums[idx] > nums[i]) {
                    res[i] = nums[idx];
                    break;                         // 找到第一个就停
                }
            }
            // 内层循环走完没 break → res[i] 保持 -1
        }
        return res;
    }
};

// ============================================================
// 解法2: 单调栈 + 循环展开 — O(n) / O(n)  ⭐ 面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法1的瓶颈：每个元素独立扫描后续元素。
// 单调栈的核心：当一个大数出现时，它能"批量回答"栈里所有比它小的元素。
//
// 单调递减栈（栈底到栈顶递减）：
// - 栈存"还没找到下一个更大元素"的索引
// - 遇到当前值 cur > 栈顶对应值 → 栈顶的答案就是 cur，弹出
// - 遇到 cur <= 栈顶 → cur 还需要等待，入栈
//
// 循环数组处理：遍历 2n 次，用 i % n 映射回实际索引。
// 第二圈让"还没找到答案"的元素有机会看到前面的更大值。
//
// 为什么 O(n)？每个索引最多入栈一次、出栈一次，总操作 O(n)。
//
// 过程示意 (nums = [1, 2, 1]):
//
// i=0(val=1): 栈空 → 入栈0            栈: [0]         res: [-1,-1,-1]
// i=1(val=2): 2>nums[0]=1 → 弹0       栈: []          res: [2,-1,-1]
//             栈空 → 入栈1             栈: [1]
// i=2(val=1): 1<nums[1]=2 → 入栈2     栈: [1,2]       res: [2,-1,-1]
// --- 第二圈 ---
// i=3(val=1): 1<nums[2]=1 → 不弹      栈: [1,2]       (不入栈，i>=n)
// i=4(val=2): 2>nums[2]=1 → 弹2       栈: [1]         res: [2,-1,2]
//             2=nums[1]=2 → 不弹      (不入栈，i>=n)
// i=5(val=1): 不弹                     栈: [1]         (不入栈)
//
// 最终 res = [2, -1, 2] ✓
// 索引1(值2)留在栈中没被弹出 → res[1] 保持 -1（它是最大值）
// ============================================================
class Solution2 {
public:
    vector<int> nextGreaterElements(vector<int>& nums) {
        int n = nums.size();
        vector<int> res(n, -1);     // 初始化 -1：找不到更大元素的默认值
        stack<int> stk;              // 存索引，不存值！
        
        for (int i = 0; i < 2 * n; i++) {
            int cur = nums[i % n];
            
            // 当前值比栈顶大 → 栈顶的"下一个更大元素"就是当前值
            // 为什么用 < 不用 <=？因为相等不算"更大"
            while (!stk.empty() && nums[stk.top()] < cur) {
                res[stk.top()] = cur;   // 通过索引写回结果
                stk.pop();
            }
            
            // 只在第一圈入栈，避免同一索引重复入栈
            // （第二圈的作用仅仅是帮第一圈遗留的元素找到答案）
            if (i < n) {
                stk.push(i);
            }
        }
        return res;
    }
};

// ============================================================
// 解法2 变体: 两圈都入栈（更简洁的写法）
// 
// 【思路】
// 和解法2完全相同，只是第二圈也执行 push(i % n)。
// 这不影响正确性，因为 res[stk.top()] 只在出栈时被赋值，
// 而每个原始索引在第一圈已经被赋值过了，第二圈即使重复赋值也是相同的值。
// 缺点：栈的最大大小可能达到 2n 而非 n。
// ============================================================
class Solution2b {
public:
    vector<int> nextGreaterElements(vector<int>& nums) {
        int n = nums.size();
        vector<int> res(n, -1);
        stack<int> stk;
        
        for (int i = 0; i < 2 * n; i++) {
            while (!stk.empty() && nums[stk.top()] < nums[i % n]) {
                res[stk.top()] = nums[i % n];
                stk.pop();
            }
            stk.push(i % n);   // 简洁：两圈都入栈
        }
        return res;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 时间   | 空间  | 特点                       |
// |---------|--------|-------|---------------------------|
// | 暴力模拟 | O(n²)  | O(1)  | 最直觉，面试起点            |
// | 单调栈   | O(n)   | O(n)  | 面试期望解法，每元素入出栈各一次 |
//
// 暴力法适合说明理解题意，单调栈是面试必须掌握的解法。
//
// 解法2 vs 解法2b:
// - 解法2 第二圈不入栈，栈大小上限 n，逻辑更清晰
// - 解法2b 两圈都入栈，代码更简洁，但栈大小上限 2n
// - 正确性相同，面试中哪个顺手写哪个
//
// 【与 LeetCode 496 (下一个更大元素 I) 的区别】
// - 496 是非循环数组 → 只遍历 n 次
// - 503 是循环数组 → 遍历 2n 次，用 i%n 映射
// - 单调栈逻辑完全相同，只多了循环展开这一个技巧
//
// 【易错点】
//
// 1. 栈存值而非索引：
//    ✗ stk.push(nums[i])  → 无法知道更新 res 的哪个位置
//    ✓ stk.push(i)        → res[stk.top()] = cur 靠索引写回
//
// 2. 比较用 <= 而非 <：
//    ✗ nums[stk.top()] <= cur → 相等也弹出，但相等不算"更大"
//      例如 [2,2]：第一个2会被第二个2弹出，res[0]=2 是错的
//      （2不比2大，正确答案是 -1）
//    ✓ nums[stk.top()] < cur  → 严格大于才弹出
//
// 3. 只遍历 n 次：
//    ✗ for (int i = 0; i < n; i++) → 末尾元素可能在前面有更大值
//      例如 [1,2,1]：最后一个1的答案2在前面，不遍历第二圈就漏了
//    ✓ for (int i = 0; i < 2*n; i++)
//
// 4. 结果数组初始化为 0：
//    ✗ vector<int> res(n, 0) → 全局最大值应返回 -1
//    ✓ vector<int> res(n, -1)
//
// 【面试追问】
//
// Q1: 暴力法时间复杂度多少？瓶颈在哪？
// → O(n²)，每个元素独立扫描后续元素，重复比较严重。
//
// Q2: 单调栈 for 里面套 while，为什么是 O(n) 不是 O(n²)？
// → 均摊分析：每个索引最多入栈一次出栈一次，总操作数 ≤ 4n = O(n)。
//    while 的总执行次数不超过总入栈次数。
//
// Q3: 如果要求"下一个更小元素"怎么改？
// → 改一个符号：nums[stk.top()] < cur 改成 nums[stk.top()] > cur。
//    即从单调递减栈变成单调递增栈。
//
// Q4: 如果不是循环数组，怎么简化？
// → 去掉第二圈：for (int i = 0; i < n; i++)，其余完全不变。
//    这就是 LeetCode 496 的核心逻辑。
//
// Q5: 能不能从右往左遍历？
// → 可以。从右往左遍历时，栈维护的是"右边的候选更大值"。
//    对于循环数组同样遍历 2n 次（从 2n-1 到 0）。
//    两种方向都正确，选自己更习惯的写法。
// ============================================================
