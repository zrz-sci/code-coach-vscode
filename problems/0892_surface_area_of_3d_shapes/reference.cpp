/*
 * LeetCode 892: Surface Area of 3D Shapes (三维形体的表面积)
 *
 * 【题目本质】
 * 几何模拟：n x n 网格上每格堆若干方块，求粘合后的总表面积。
 * 关键是计算每根柱子的独立贡献，再减去相邻柱子之间的遮挡面。
 *
 * 【解法总览】
 * 解法1: 逐柱子加法      — O(n^2) / O(1) — 面试首选
 * 解法2: 总面减遮挡       — O(n^2) / O(1) — 等价理解
 */

// ============================================================
// 解法1: 逐柱子加法 — 每根柱子贡献 2+4v，减相邻遮挡
// 时间: O(n^2)  空间: O(1)
//
// 【思路】
// 一根高度为 v 的独立柱子：
//   - 顶面 = 1，底面 = 1
//   - 四个侧面各暴露 v 个单位 → 侧面 = 4v
//   - 独立贡献 = 2 + 4v （当 v > 0 时）
//
// 两根相邻柱子（高度 a, b）：
//   - 较矮的那根有 min(a,b) 层与邻居"面对面"
//   - 每层遮挡 2 个面（各属于两根柱子）
//   - 遮挡量 = 2 * min(a, b)
//
// 为避免重复计算，只看每个格子的右邻居和下邻居。
//
// 示例: grid = [[1,2],[3,4]]
//
//   柱子贡献:
//     (0,0) v=1: 2+4*1 = 6
//     (0,1) v=2: 2+4*2 = 10
//     (1,0) v=3: 2+4*3 = 14
//     (1,1) v=4: 2+4*4 = 18
//     独立总和 = 6 + 10 + 14 + 18 = 48
//
//   相邻遮挡:
//     (0,0)-(0,1): 2*min(1,2) = 2
//     (0,0)-(1,0): 2*min(1,3) = 2
//     (0,1)-(1,1): 2*min(2,4) = 4
//     (1,0)-(1,1): 2*min(3,4) = 6
//     遮挡总和 = 2 + 2 + 4 + 6 = 14
//
//   最终表面积 = 48 - 14 = 34 ✓
// ============================================================
class Solution1 {
public:
    int surfaceArea(vector<vector<int>>& grid) {
        int n = grid.size();
        int area = 0;

        for (int i = 0; i < n; i++) {
            for (int j = 0; j < n; j++) {
                int v = grid[i][j];
                if (v > 0) {
                    // 独立柱子的表面积: 顶+底+四周
                    area += 2 + 4 * v;
                }
                // 减去与右邻居的遮挡面
                // 每对相邻柱子遮挡 2*min(a,b) 个面
                if (j + 1 < n) {
                    area -= 2 * min(v, grid[i][j + 1]);
                }
                // 减去与下邻居的遮挡面
                if (i + 1 < n) {
                    area -= 2 * min(v, grid[i + 1][j]);
                }
            }
        }

        return area;
    }
};

// ============================================================
// 解法2: 总面减遮挡 — 6*总方块数 - 2*所有接触面
// 时间: O(n^2)  空间: O(1)
//
// 【思路】
// 换一个角度理解：
// 每个方块有 6 个面，总面数 = 6 * 方块总数。
// 但凡两个方块有一个面贴在一起，就遮挡掉 2 个面（各 1 个）。
//
// 接触面来源有两种:
// 1. 同柱子内上下堆叠: 高度为 v 的柱子，内部有 (v-1) 个上下接触面
// 2. 相邻柱子水平接触: 高度为 a 和 b 的邻居，有 min(a,b) 个水平接触面
//
// 总表面积 = 6 * totalCubes - 2 * totalOverlap
//
// 验证: grid = [[1,2],[3,4]]
//   totalCubes = 1+2+3+4 = 10 → 6*10 = 60
//   柱子内部: (1-1)+(2-1)+(3-1)+(4-1) = 0+1+2+3 = 6
//   水平接触: min(1,2)+min(1,3)+min(2,4)+min(3,4) = 1+1+2+3 = 7
//   totalOverlap = 6+7 = 13
//   表面积 = 60 - 2*13 = 60 - 26 = 34 ✓
// ============================================================
class Solution2 {
public:
    int surfaceArea(vector<vector<int>>& grid) {
        int n = grid.size();
        int totalCubes = 0;
        int overlap = 0;

        for (int i = 0; i < n; i++) {
            for (int j = 0; j < n; j++) {
                int v = grid[i][j];
                totalCubes += v;

                // 同柱子内部的上下接触面
                // v 个方块纵向堆叠，有 (v-1) 个内部接触面
                if (v > 1) {
                    overlap += v - 1;
                }

                // 与右邻居的水平接触面
                // 两根柱子之间，矮的那根有多少层，就有多少个接触面
                if (j + 1 < n) {
                    overlap += min(v, grid[i][j + 1]);
                }

                // 与下邻居的水平接触面
                if (i + 1 < n) {
                    overlap += min(v, grid[i + 1][j]);
                }
            }
        }

        // 每个接触面遮挡 2 个方块面（各属于两个方块）
        return 6 * totalCubes - 2 * overlap;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间    | 空间  | 特点                    |
// |-------------|--------|------|------------------------|
// | 逐柱子加法   | O(n^2) | O(1) | ⭐面试首选，直觉清晰      |
// | 总面减遮挡   | O(n^2) | O(1) | 等价写法，另一种理解角度   |
//
// 两种解法本质完全相同，只是公式展开方式不同:
//   解法1: sum(2+4v) - sum(2*min(a,b))        （只算水平遮挡）
//   解法2: 6*sum(v) - 2*(sum(v-1) + sum(min))  （算全部遮挡）
//
// 展开后两者数学等价:
//   2+4v = 6v - 2*(v-1)  当 v > 0
//   所以 sum(2+4v) = 6*sum(v) - 2*sum(v-1)
//   最终结果相同。
//
// 面试建议:
//   首选解法1（更简洁）→ 追问时解释解法2（更通用的思维框架）
//
// 【易错点】
// 1. v=0 时不能加 2+4v:
//    ✗ 无条件加 2+4*0=2 → 空格子也贡献了 2 的表面积
//    ✓ 加之前判断 v > 0
//
// 2. 相邻遮挡重复计算:
//    ✗ 每个格子检查上下左右四个邻居 → 每对邻居被计算了两次
//    ✓ 只检查右邻居和下邻居，每对恰好算一次
//
// 3. 遮挡用了 max 而不是 min:
//    ✗ 2*max(a,b) → 遮挡面数超过矮柱子高度
//    ✓ 2*min(a,b) → 只有矮柱子那么多层面对面
//
// 4. 解法2忘记柱子内部堆叠:
//    ✗ 只减水平接触面 → 忘了同柱子内 (v-1) 个上下接触面
//    ✓ overlap 要同时包含纵向和水平两种接触
//
// 5. 总面减遮挡中忘记乘 2:
//    ✗ return 6*totalCubes - overlap → 只减了一半的遮挡面
//    ✓ return 6*totalCubes - 2*overlap → 每个接触遮挡两个面
//
