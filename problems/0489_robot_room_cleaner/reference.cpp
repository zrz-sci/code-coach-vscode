/*
 * LeetCode 489: 扫地机器人 (Robot Room Cleaner)
 *
 * 【题目本质】
 * 在无法访问全局地图的约束下，用回溯 DFS 遍历所有可达空格。
 * 核心难点：机器人有"朝向"概念，移动后必须能回退并恢复状态。
 *
 * 【解法总览】
 * 解法1: 回溯 DFS + 相对坐标 — O(N-M) / O(N-M) — 唯一可行解法
 *   （BFS 不可行，因为机器人无法"传送"到队列中的下一个节点）
 */

// ============================================================
// 解法1: 回溯 DFS + 相对坐标 + 方向同步
// 时间: O(N-M)  空间: O(N-M)
// N = 网格总格子数, M = 障碍物数
//
// 【思路】
// 1. 机器人的起始位置设为相对坐标 (0, 0)，初始方向为"上"（索引 0）
// 2. 在每个格子，先 clean，然后从当前朝向开始尝试 4 个方向：
//    - 计算目标坐标，检查是否已访问
//    - 尝试 move()，成功则递归
//    - 递归返回后，执行 goBack() 回到原位并恢复朝向
//    - turnRight() 切换到下一个方向
// 3. 4 次 turnRight 后，机器人回到进入该函数时的朝向（净旋转 360°= 0°）
//
// 为什么这样想到的？
// - 没有地图 → 不能用全局 BFS/DFS
// - 机器人只能逐步移动 → DFS + 回溯（"走过去→处理→走回来"）
// - 需要判重 → 用相对坐标 + set
// - 需要管理方向 → 方向数组 + 方向变量 d
//
// 决策树示意（从 (0,0) 出发朝上）:
//
//                      (0,0) clean, d=0
//                  /       |       \       \
//           d=0:上     d=1:右   d=2:下   d=3:左
//           尝试move  尝试move  尝试move  尝试move
//              |
//         成功→递归(-1,0), d=0
//              |
//         goBack回(0,0)
//              |
//         turnRight → 尝试d=1...
//
//
// 回退操作 goBack() 详解:
//
//   进入时:  A  [B]→   (机器人在B，面朝进入B时的方向)
//   掉头:    A  [B]←   (turnRight × 2)
//   走回:   [A]← B     (move)
//   掉头:   [A]→ B     (turnRight × 2，恢复朝右)
//   效果: 回到A，朝向和进入B之前一样
//
//
// 示例运行 (3×3 房间):
//
//   房间:        相对坐标:
//   1 1 0        (0,0) (0,1)  wall
//   1 1 1   →    (1,0) (1,1) (1,2)
//   0 1 1        wall  (2,1) (2,2)
//
//   起点(0,0), 朝上
//   DFS路径: (0,0)→(0,1)→(1,1)→(1,0) 回退
//                              →(1,2)→(2,2)→(2,1) 回退...
//   所有空格都被 clean
// ============================================================

/**
 * // This is the robot's control interface.
 * // You should not implement it, or speculate about its implementation
 * class Robot {
 *   public:
 *     bool move();
 *     void turnLeft();
 *     void turnRight();
 *     void clean();
 * };
 */

class Solution {
public:
    // 方向数组: 上(0)、右(1)、下(2)、左(3)
    // 与机器人的初始朝向(上)对应，每次 turnRight 就是索引 +1
    int dirs[4][2] = {{-1, 0}, {0, 1}, {1, 0}, {0, -1}};
    set<pair<int, int>> visited;
    
    void cleanRoom(Robot& robot) {
        dfs(robot, 0, 0, 0);
    }
    
    void dfs(Robot& robot, int row, int col, int d) {
        // 清扫当前格子并标记已访问
        robot.clean();
        visited.insert({row, col});
        
        // 从当前朝向 d 开始，尝试 4 个方向
        // 每次循环：检查 → 可能递归 → turnRight
        // 4 次 turnRight = 360° = 回到原朝向
        for (int i = 0; i < 4; i++) {
            int newD = (d + i) % 4;  // 当前尝试的实际方向
            int newRow = row + dirs[newD][0];
            int newCol = col + dirs[newD][1];
            
            // 未访问 + move成功（不是墙）→ 递归
            // 注意顺序：先查 visited（O(logN)），再尝试 move（API调用）
            if (visited.find({newRow, newCol}) == visited.end() && robot.move()) {
                dfs(robot, newRow, newCol, newD);
                // 递归返回 → 回退到当前位置，恢复朝向
                goBack(robot);
            }
            // 无论是否进入递归，都右转一次准备下一方向
            // 这保证了物理朝向和 newD 的同步
            robot.turnRight();
        }
        // 循环结束时: 4次 turnRight = 转了360° = 朝向恢复为 d
    }
    
    // 回退操作：掉头走回来再掉头
    // 前置条件：机器人在 B，面朝从 A 走到 B 时的方向
    // 后置条件：机器人回到 A，面朝和 goBack 调用前相同的方向
    void goBack(Robot& robot) {
        robot.turnRight();   // 转 90°
        robot.turnRight();   // 再转 90° → 掉头（面朝来的方向）
        robot.move();        // 走回来
        robot.turnRight();   // 转 90°
        robot.turnRight();   // 再转 90° → 恢复原朝向
    }
};


// ============================================================
// 【解法对比】
// 
// 这道题只有一种核心解法：回溯 DFS + 相对坐标。
// BFS 不可行的原因：BFS 需要从队列中取出节点后直接"跳到"该位置处理，
// 但机器人只能通过 move() 逐步移动，无法传送。
// DFS + 回溯天然支持"沿路径深入 → 原路返回"的移动模式。
//
// 可以考虑的变体：
// - 用 unordered_set<string> 代替 set<pair<int,int>>，
//   将坐标编码为字符串，查找从 O(logN) 降到期望 O(1)
// - 也可以用 unordered_set 配合自定义哈希
//
// ============================================================
// 【易错点】
//
// 1. 方向不同步:
//    ✗ for 循环中直接用 i 作为方向索引: int newD = i;
//    ✓ 必须加上当前朝向偏移: int newD = (d + i) % 4;
//    原因: 机器人进入 dfs 时朝向是 d 不是 0，
//          第一次尝试的方向就是 d 本身（i=0 时 newD=d）
//
// 2. goBack 不完整:
//    ✗ turnRight×2 + move （忘了再转回来）
//       → 回到A后朝向反了，后续方向全错
//    ✓ turnRight×2 + move + turnRight×2
//       → 回到A且朝向和调用前一致
//
// 3. 先 move 再查 visited:
//    ✗ robot.move(); if (!visited.count({newRow,newCol})) { ... }
//       → 如果已访问，move已经执行了，机器人位置变了但没递归也没回退
//    ✓ if (!visited.count({newRow,newCol}) && robot.move()) { ... }
//       → 短路求值：已访问就不会调用 move
//
// 4. 忘记在循环末尾 turnRight:
//    ✗ 只在需要尝试新方向时才转 → 逻辑混乱，4个方向后朝向不对
//    ✓ 每次循环末尾无条件 turnRight，保证4次后回原朝向
//
// 5. visited 用绝对坐标:
//    ✗ 试图通过某种方式获取机器人在地图上的绝对坐标
//    ✓ 以起点为(0,0)的相对坐标，完全通过方向推算
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么选 DFS 不选 BFS？
// A1: 机器人只能逐步移动不能传送。DFS+回溯的"深入-返回"模式
//     与机器人"走过去-走回来"的物理约束完美匹配。
//     BFS需要随机访问队列中的节点位置，机器人做不到。
//
// Q2: 时间复杂度怎么算？
// A2: 每个空格作为"当前格"被clean恰好1次。
//     作为邻居被检查最多4次（从4个方向）。
//     每次检查O(1)。回退O(1)。总计O(4(N-M))=O(N-M)。
//
// Q3: 如果递归太深栈溢出怎么办？
// A3: 可以用显式栈将递归改为迭代。但需要在栈中保存
//     "还有哪些方向没尝试"和"当前朝向"的状态，实现更复杂。
//     面试中说明这个trade-off即可，不一定要写出来。
//
// Q4: 能否用 Spiral（螺旋）策略替代DFS？
// A4: 螺旋策略在有障碍物的情况下不保证覆盖所有格子。
//     障碍物可能把空间分成需要绕路才能到达的区域。
//     DFS+回溯保证了只要连通就能到达。
//
// Q5: visited 用什么数据结构最优？
// A5: unordered_set 配合自定义哈希（或编码为 "row,col" 字符串），
//     期望O(1)查找。用 set<pair<int,int>> 是 O(logN)，但常数小。
//     面试中两者都可以接受。
// ============================================================
