/*
 * LeetCode 767: 重构字符串 (Reorganize String)
 *
 * 【题目本质】
 * 重新排列字符串，使相邻字符不同 — 本质是贪心调度：
 * 高频字符优先安排，避免"积压"导致后续无处可放。
 *
 * 【解法总览】
 * 解法1: 最大堆贪心      — O(n log 26) / O(26) — 面试首选，思路最自然
 * 解法2: 排序+间隔填充   — O(n) / O(26)        — 构造法，代码简洁
 * 解法3: 计数+间隔填充   — O(n) / O(26)        — 解法2的简化，无需排序
 *
 * 【可行性判断】
 * 任何字符频率 > ⌈n/2⌉ = (n+1)/2 时，无论怎么排都会有相邻重复 → 返回 ""
 *
 * 示例:
 *   s = "aab" → freq: a=2, b=1, maxFreq=2 <= (3+1)/2=2 → 可行 → "aba"
 *   s = "aaab" → freq: a=3, b=1, maxFreq=3 > (4+1)/2=2 → 不可行 → ""
 */

// ============================================================
// 解法1: 最大堆贪心 — 每轮取频率最高的两个字符交替放置
// 时间: O(n log 26) ≈ O(n)   空间: O(26) ≈ O(1)
//
// 【思路】
// 贪心策略：每一步都"优先消耗频率最高的字符"。
// 为什么？因为如果高频字符不及时消耗，它们会积压到最后，
// 被迫相邻放置。
//
// 关键技巧：每轮从堆中取出频率最高和第二高的两个字符，
// 各放一个到结果中。这样天然保证这两个字符不相同，
// 也不会和下一轮产生冲突。
//
// 示例: s = "aab"
//   堆初始: {(2,'a'), (1,'b')}
//   Round 1: 取 a(2), b(1) → 结果 "ab" → 放回 a(1)
//   Round 2: 堆只剩 a(1) → 结果 "aba"
//   返回 "aba"
// ============================================================
class Solution1 {
public:
    string reorganizeString(string s) {
        int n = s.size();
        vector<int> freq(26, 0);
        for (char c : s) freq[c - 'a']++;

        // 可行性检查
        for (int i = 0; i < 26; i++) {
            if (freq[i] > (n + 1) / 2) return "";
        }

        // 建最大堆: (频率, 字符)
        priority_queue<pair<int, char>> pq;
        for (int i = 0; i < 26; i++) {
            if (freq[i] > 0) {
                pq.push({freq[i], 'a' + i});
            }
        }

        string result;
        // 每轮取两个字符，各放一个 → 天然避免相邻重复
        while (pq.size() >= 2) {
            auto [f1, c1] = pq.top(); pq.pop();  // 频率最高
            auto [f2, c2] = pq.top(); pq.pop();  // 频率第二高

            result += c1;
            result += c2;

            // 频率减1后放回堆（仅频率>0时）
            if (f1 - 1 > 0) pq.push({f1 - 1, c1});
            if (f2 - 1 > 0) pq.push({f2 - 1, c2});
        }

        // n为奇数时，堆中可能还剩一个字符
        // 因为已通过可行性检查，这个字符一定不等于result末尾字符
        if (!pq.empty()) {
            result += pq.top().second;
        }

        return result;
    }
};

// ============================================================
// 解法2: 排序+间隔填充 — 按频率排序后先填偶数位再填奇数位
// 时间: O(n + 26 log 26) ≈ O(n)   空间: O(26) ≈ O(1)
//
// 【思路】
// 解法1用堆动态维护顺序，但其实可以更直接：
// 把所有字符按频率从高到低排序，然后间隔放入结果数组。
//
// 间隔填充策略：
//   - 先填偶数索引位置: 0, 2, 4, 6, ...
//   - 偶数位填满后填奇数索引: 1, 3, 5, 7, ...
//   - 频率最高的字符从偶数位开始，保证它不会溢出
//
// 为什么正确？
//   同一字符被分配到间隔>=2的位置，永远不会相邻。
//   只要 maxFreq <= ⌈n/2⌉（偶数位的个数），最高频字符
//   在偶数位就能放完，不会和奇数位上自己相邻。
//
// 示例: s = "aaabbc" (n=6)
//   频率排序: a(3), b(2), c(1)
//   结果数组: _ _ _ _ _ _
//                 ↕ 间隔填充
//   填 a(3): [a _ a _ a _]  (idx: 0,2,4)
//   填 b(2): [a b a _ a _]  → [a b a b a _]  (idx: 偶数位满, 转1,3)
//            等等, idx=6>=n, 转 idx=1
//            实际: idx 0→2→4→(6>=6, 转1)→1→3
//   填 c(1): [a b a b a c]  (idx: 5)
//   结果: "ababac"
// ============================================================
class Solution2 {
public:
    string reorganizeString(string s) {
        int n = s.size();
        vector<int> freq(26, 0);

        for (char c : s) freq[c - 'a']++;

        // 可行性检查
        for (int i = 0; i < 26; i++) {
            if (freq[i] > (n + 1) / 2) return "";
        }

        // 按频率降序排序字符
        vector<pair<int, int>> charFreq;
        for (int i = 0; i < 26; i++) {
            if (freq[i] > 0) {
                charFreq.push_back({freq[i], i});
            }
        }
        sort(charFreq.begin(), charFreq.end(), greater<>());

        // 间隔填充: 先偶数位(0,2,4,...) 再奇数位(1,3,5,...)
        string result(n, ' ');
        int idx = 0;

        for (auto& [f, ch] : charFreq) {
            for (int i = 0; i < f; i++) {
                result[idx] = 'a' + ch;
                idx += 2;
                // 偶数位填满后切换到奇数位
                if (idx >= n) idx = 1;
            }
        }

        return result;
    }
};

// ============================================================
// 解法3: 计数+间隔填充(无排序) — 只需找到最大频率字符先填
// 时间: O(n)   空间: O(26) ≈ O(1)
//
// 【思路】
// 解法2需要排序，但其实只有一个约束：频率最高的字符必须
// 先填偶数位。其余字符的填充顺序无所谓。
//
// 所以：
// 1. 找到频率最高的字符
// 2. 先把它填入偶数位
// 3. 然后遍历其余字符，继续间隔填充
//
// 这避免了排序步骤，是真正的 O(n)。
// ============================================================
class Solution3 {
public:
    string reorganizeString(string s) {
        int n = s.size();
        vector<int> freq(26, 0);
        int maxFreq = 0, maxIdx = 0;

        for (char c : s) {
            freq[c - 'a']++;
            if (freq[c - 'a'] > maxFreq) {
                maxFreq = freq[c - 'a'];
                maxIdx = c - 'a';
            }
        }

        // 可行性检查: 最大频率不能超过 ⌈n/2⌉
        if (maxFreq > (n + 1) / 2) return "";

        string result(n, ' ');
        int idx = 0;

        // 第一步: 最高频字符优先填偶数位
        // 为什么必须先填？因为它最有可能把偶数位占满，
        // 如果后填，可能偶数位已被其他字符占据，导致它溢出到相邻位置
        while (freq[maxIdx] > 0) {
            result[idx] = 'a' + maxIdx;
            idx += 2;
            freq[maxIdx]--;
        }

        // 第二步: 其余字符继续间隔填充
        for (int i = 0; i < 26; i++) {
            while (freq[i] > 0) {
                // 偶数位填满后切换到奇数位
                if (idx >= n) idx = 1;
                result[idx] = 'a' + i;
                idx += 2;
                freq[i]--;
            }
        }

        return result;
    }
};

// ============================================================
// 【解法对比】
//
// 解法1 (最大堆):
//   - 优点: 思路最直觉，面试好讲
//   - 缺点: priority_queue 虽然 log 因子是 log26 ≈ 5 可忽略，
//           但写堆操作代码稍多
//   - 面试首选 ⭐
//
// 解法2 (排序+间隔填充):
//   - 优点: 代码简洁，构造法一次生成
//   - 缺点: 需要解释"为什么间隔填充正确"
//
// 解法3 (计数+间隔填充):
//   - 优点: 最简洁，真正 O(n)，无排序
//   - 缺点: 同上，需要解释正确性
//
// 【易错点】
//
// 1. 可行性判断公式:
//    ✗ maxFreq > n / 2
//    ✓ maxFreq > (n + 1) / 2
//    n=5 时, maxFreq=3 是可行的 (如 "aXaXa"), n/2=2 会错判
//
// 2. 堆贪心每轮只取1个:
//    ✗ 取1个 → 下一轮堆顶可能还是同一个字符 → 需要额外prev判断
//    ✓ 取2个 → 天然不同，逻辑简洁
//
// 3. 间隔填充忘记切换奇数位:
//    ✗ idx += 2 但没有 if (idx >= n) idx = 1 → 数组越界
//    ✓ 必须在 idx >= n 时切换到 1
//
// 4. 间隔填充没有把最高频字符先填:
//    ✗ 按字母顺序 a→z 填 → 高频字符可能横跨偶奇分界导致相邻重复
//    ✓ 先填最高频字符到偶数位
//
// 5. 堆剩余元素未处理:
//    ✗ while (pq.size() >= 2) 后直接 return → n奇数时少一个字符
//    ✓ 循环后检查 pq.empty()
//
// 【面试追问】
//
// Q1: 什么时候无解？
//     → 最大频率 > (n+1)/2 时无解。因为偶数位最多 ⌈n/2⌉ 个，
//       超过这个数的字符必然在某处相邻。
//
// Q2: 堆贪心为什么每轮取两个？
//     → 取一个的话下一轮堆顶可能相同，需要额外 prev 判断。
//       取两个天然保证本轮两字符不同，且不干扰下一轮。
//
// Q3: 间隔填充为什么正确？
//     → 同一字符在间隔>=2的位置，不可能相邻。只要 maxFreq <= ⌈n/2⌉，
//       最高频字符在偶数位能放完，不会溢出到自己旁边。
//
// Q4 (变体): 如果要求相邻 k 个字符都不同？(k≥2)
//     → 即 LeetCode 358。堆贪心改为每轮取k个，用冷却队列暂存
//       已使用字符。判断条件改为 maxFreq > ⌈n/k⌉。
//       间隔填充改为间隔 k 而不是 2。
//
// 【相关题型】
// - 358. Rearrange String k Distance Apart — 本题泛化(k=2→任意k)，
//     复用堆贪心框架，增加冷却队列
// - 621. Task Scheduler — 同样的"高频优先+间隔"思想，
//     区别: 可插入idle空位，本题必须用实际字符
// - 1054. Distant Barcodes — 几乎同题，保证有解，去掉可行性检查即可
// ============================================================
