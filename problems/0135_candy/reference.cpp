/*
 * LeetCode 135: 分发糖果 (Candy)
 * 
 * 【题目本质】
 * 给定评分数组，在满足"每人至少1颗"和"评分更高的比邻居多"两个约束下，
 * 求最少糖果总数。本质是双向约束的贪心优化问题。
 *
 * 【解法总览】
 * 解法1: 暴力迭代修正    — O(n²) / O(n)  — 最直觉，反复扫描直到稳定
 * 解法2: 两次遍历贪心    — O(n)  / O(n)  — ⭐面试首选，拆解双向约束
 * 解法3: 一次遍历上坡下坡 — O(n)  / O(1)  — 空间最优，追问加分项
 */

// ============================================================
// 解法1: 暴力迭代修正 — 反复扫描，每轮修正不满足约束的位置
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 最直觉的想法：先给每人1颗糖，然后反复检查所有位置。
// 如果某人评分比邻居高却糖果不够多，就调整。
// 重复直到一轮下来没有任何调整（稳定了）。
//
// 【瓶颈】
// 最坏情况（如严格递减 [5,4,3,2,1]），信息从右往左每轮只传播一步，
// 需要 O(n) 轮，每轮 O(n)，总体 O(n²)。
//
// 这个瓶颈引出解法2的思路：能否用两次定向遍历替代多次随机修正？
// ============================================================
class Solution1 {
public:
    int candy(vector<int>& ratings) {
        int n = ratings.size();
        vector<int> candies(n, 1);
        
        bool changed = true;
        while (changed) {
            changed = false;
            for (int i = 0; i < n; i++) {
                // 检查左邻居约束：我评分比左邻居高，糖果却不够多
                if (i > 0 && ratings[i] > ratings[i-1]
                    && candies[i] <= candies[i-1]) {
                    candies[i] = candies[i-1] + 1;
                    changed = true;
                }
                // 检查右邻居约束：我评分比右邻居高，糖果却不够多
                if (i < n - 1 && ratings[i] > ratings[i+1]
                    && candies[i] <= candies[i+1]) {
                    candies[i] = candies[i+1] + 1;
                    changed = true;
                }
            }
        }
        
        int total = 0;
        for (int c : candies) total += c;
        return total;
    }
};

// ============================================================
// 解法2: 两次遍历贪心 — 拆解双向约束为两个单向约束
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 核心洞察：一个孩子的糖果数受到左右两个方向的约束。
// 把双向约束拆成两个独立的单向问题：
//
// 第一遍 左→右：只保证 ratings[i] > ratings[i-1] → candy[i] > candy[i-1]
// 第二遍 右→左：只保证 ratings[i] > ratings[i+1] → candy[i] > candy[i+1]
// 合并：取 max，两个方向的约束同时满足
//
// 【为什么 max 正确且最小？】
// - max 值 ≥ 两个方向各自的值 → 两个约束都满足
// - 每次单向遍历都贪心给最少 → 合并后也是最少
//
// 【示例过程】
// ratings:   [1, 3, 5, 3, 2, 1, 4, 3]
// 
// 左→右:     [1, 2, 3, 1, 1, 1, 2, 1]
//               ↑  ↑                ↑   上升时 +1，否则给1
// 
// 右→左:     [1, 1, 3, 2, 1, 1, 1, 1]  ← 注意[2]位置取 max(3, 3)=3
//                   ↑  ↑
// 
// 取 max:    [1, 2, 3, 2, 1, 1, 2, 1]
// 总计 = 1+2+3+2+1+1+2+1 = 13
// ============================================================
class Solution2 {
public:
    int candy(vector<int>& ratings) {
        int n = ratings.size();
        vector<int> candies(n, 1);
        
        // 第一遍：左→右
        // 只处理"比左邻居评分高"的情况
        for (int i = 1; i < n; i++) {
            if (ratings[i] > ratings[i - 1]) {
                // 贪心：恰好比左邻居多1颗，这是满足约束的最小值
                candies[i] = candies[i - 1] + 1;
            }
            // ratings[i] <= ratings[i-1] 时保持1
            // 注意：相等时不需要更多糖果（题目说"评分更高的"）
        }
        
        // 第二遍：右→左
        // 处理"比右邻居评分高"的情况，同时累加总数
        int total = candies[n - 1];
        for (int i = n - 2; i >= 0; i--) {
            if (ratings[i] > ratings[i + 1]) {
                // 关键：取 max！不能破坏第一遍已建立的左邻居约束
                // 如果直接赋值 candies[i+1]+1，可能比第一遍的值小
                candies[i] = max(candies[i], candies[i + 1] + 1);
            }
            total += candies[i];
        }
        
        return total;
    }
};

// ============================================================
// 解法3: 一次遍历（上坡下坡法） — 追踪上升/下降序列长度
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 把评分序列看作一系列"山峰"：上升段 + 峰值 + 下降段。
//
// 上升段：糖果从1递增，第k个上升位置得 k+1 颗
// 下降段：糖果也递增（从下降终点看），第k个下降位置得 k 颗
// 峰值：取上升段和下降段中较大的那个
//
// 用三个变量追踪：
// - up:   当前连续上升段的长度
// - down: 当前连续下降段的长度  
// - peak: 最近峰值处的上升长度（用于判断是否需要把峰值顶高）
//
// 【为什么 down >= peak 时要 +1？】
//
//   ratings: [1, 3, 5, 4, 3, 2]
//   上升段: 1→3→5, up最终=2, peak=2, 糖果: 1,2,3
//   下降段: 5→4→3→2, down逐步变为1,2,3
//   
//   下降段糖果（从右看）: _, _, 3, 2, 1  ← 下降第3个需要3颗
//   但峰值(5)从上升得到3颗，下降第1个(4)也需要3颗
//   → 峰值被"顶"到4颗，额外+1
//   
//   判断条件：down(=3) >= peak(=3) 时，峰值需要额外+1
// ============================================================
class Solution3 {
public:
    int candy(vector<int>& ratings) {
        int n = ratings.size();
        if (n <= 1) return n;
        
        int total = 1; // 第一个孩子1颗
        int up = 0, down = 0, peak = 0;
        
        for (int i = 1; i < n; i++) {
            if (ratings[i] > ratings[i - 1]) {
                // 上升：延续或开启上升段
                up++;
                down = 0;
                peak = up;          // 记录峰值高度
                total += up + 1;    // 当前孩子得 up+1 颗（从1开始计）
            } else if (ratings[i] < ratings[i - 1]) {
                // 下降：延续或开启下降段
                up = 0;
                down++;
                // down 颗给当前孩子（下降序列中从底部1开始往上累加）
                // 如果下降长度追平了峰值，峰值也要被顶高1颗
                total += down + (down >= peak ? 1 : 0);
            } else {
                // 相等：完全重置，当前孩子给1颗（无约束）
                up = 0;
                down = 0;
                peak = 0;
                total += 1;
            }
        }
        
        return total;
    }
};

// ============================================================
// 【解法对比】
// 
// 解法1 暴力:
//   - 优点：最直觉，容易理解正确性
//   - 缺点：O(n²)，大数据超时
//   - 面试定位：开场口述展示理解
//
// 解法2 两次遍历:
//   - 优点：O(n)时间，逻辑清晰，代码简洁不易出错
//   - 缺点：O(n)空间（存糖果数组）
//   - 面试定位：⭐标准答案，必须能写出
//
// 解法3 一次遍历:
//   - 优点：O(1)空间
//   - 缺点：逻辑较复杂，peak边界容易出错
//   - 面试定位：面试官追问"能否O(1)空间"时口述思路，加分项
//
// 解法2和解法3本质一样：都是分段处理上升和下降。
// 解法2用数组显式记录每人的糖果数，解法3用变量隐式计算总和。
//
// 【易错点】
// 
// 1. 相等评分的处理:
//    ✗ if (ratings[i] >= ratings[i-1]) candies[i] = candies[i-1] + 1;
//    ✓ if (ratings[i] >  ratings[i-1]) candies[i] = candies[i-1] + 1;
//    题目说"评分更高的"才需要更多，相等时无约束，给1即可使总数最小。
//    例 [1,2,2]: 正确答案[1,2,1]=4，错误答案[1,2,3]=6
//
// 2. 第二遍忘记取 max:
//    ✗ candies[i] = candies[i+1] + 1;     // 直接覆盖
//    ✓ candies[i] = max(candies[i], candies[i+1] + 1);
//    直接覆盖会破坏第一遍建立的左邻居约束。
//    例 ratings=[1,5,3,2]: 第一遍 [1,2,1,1]
//    第二遍 i=1: 直接赋值得2，但第一遍已经是2，正好。
//    但 ratings=[1,5,4,3,2]: 第一遍 [1,2,1,1,1]
//    第二遍 i=1: candies[2]+1=3, 但第一遍是2 → 需要max(2,3)=3
//
// 3. 解法3中 down >= peak 写成 down > peak:
//    ✗ total += down + (down > peak ? 1 : 0);   // 少了等于的情况
//    ✓ total += down + (down >= peak ? 1 : 0);
//    当 down == peak 时，下降段最高位和峰值糖果数相同，
//    但峰值评分更高，需要更多糖果，所以必须 +1。
//
// 【面试追问】
//
// Q1: 为什么不能只从左到右扫一遍？
// A1: 只从左到右只保证了左邻居约束。例 [3,2,1] 左→右得 [1,1,1]，
//     第一个孩子评分最高却只有1颗，右邻居约束未满足。
//
// Q2: 两次遍历中第二遍为什么必须取 max 而不是直接赋值？
// A2: 直接赋值可能用更小的值覆盖第一遍的结果，破坏左邻居约束。
//     取 max 保证两个方向的约束同时成立。
//
// Q3: 能否 O(1) 空间？
// A3: 可以，用解法3的上坡-下坡法。追踪上升/下降序列长度和峰值，
//     利用等差数列求和直接计算每段贡献，不需要存储每人的糖果数。
//
// Q4: 这道题的"两次遍历取极值"思想在哪些题中还能用？
// A4: LeetCode 42 接雨水（左→右求左最大，右→左求右最大，取 min）
//     LeetCode 238 除自身以外数组的乘积（左→右前缀积 × 右→左后缀积）
//     这是一种通用的"双向遍历"模式。
// ============================================================
