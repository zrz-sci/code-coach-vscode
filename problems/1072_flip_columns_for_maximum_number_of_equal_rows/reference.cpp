/*
 * LeetCode 1072: Flip Columns For Maximum Number of Equal Rows
 * (按列翻转得到最大值等行数)
 *
 * 【题目本质】
 * 给定 m x n 的二进制矩阵，选任意列翻转(0↔1)，使得"行内所有值相同"的行数最大。
 * 核心洞察：两行能同时通过列翻转变全相同 ⟺ 它们相同或互为取反。
 *
 * 【解法总览】
 * 解法1: 行模式哈希(标准化)  — O(m*n) / O(m*n)  — 面试推荐
 * 解法2: 直接两两比较       — O(m²*n) / O(1)    — 暴力，用于理解
 */

// ============================================================
// 解法1: 行模式哈希 — 标准化 + 计数 ⭐ 面试推荐
// 时间: O(m*n)  空间: O(m*n)
//
// 【思路】
// 关键定理:
//   行A和行B能同时通过列翻转变成全相同
//   ⟺ A和B完全相同 或 A和B互为取反
//
// 证明:
//   设翻转列集合 S 使行A全0:
//     → S = {j | A[j]=1} (即A中值为1的列都需要翻转)
//   对行B应用同样的S:
//     B'[j] = B[j]^1 (j∈S) 或 B[j] (j∉S)
//     B'全0 ⟹ B=A; B'全1 ⟹ B=~A
//
// 做法:
//   1. 对每行"标准化": 如果首元素=1, 取反整行
//      [0,1,0] → "010"
//      [1,0,1] → 取反 → "010"  (和上面相同!)
//   2. 用哈希表统计每种模式出现次数
//   3. 最大计数即为答案
//
// 示例: matrix = [[0,0,0],[0,0,1],[1,1,0]]
//
//   原始行:     标准化后:      模式:
//   [0,0,0]  →  [0,0,0]     →  "000"
//   [0,0,1]  →  [0,0,1]     →  "001"
//   [1,1,0]  →  [0,0,1]     →  "001"  ← 取反后和行2相同!
//
//   哈希表: {"000":1, "001":2}
//   答案 = 2
//
//   验证: 翻转第1,2列 → [1,1,0],[1,1,1],[0,0,0]
//   后两行全相同 ✓
// ============================================================
class Solution {
public:
    int maxEqualRowsAfterFlips(vector<vector<int>>& matrix) {
        unordered_map<string, int> count;
        int res = 0;

        for (auto& row : matrix) {
            string pattern;
            // 标准化: val ^ row[0]
            // row[0]=0 → val^0 = val (不变)
            // row[0]=1 → val^1 = ~val (取反)
            // 效果: 等价行(原行或取反行)产生相同的pattern
            for (int val : row) {
                pattern += (val ^ row[0]) ? '1' : '0';
            }
            // ++count[pattern] 先自增再返回新值
            res = max(res, ++count[pattern]);
        }
        return res;
    }
};

// ============================================================
// 解法2: 暴力两两比较 (用于理解原理)
// 时间: O(m²*n)  空间: O(1)
//
// 【思路】
// 对每一行，统计有多少行和它"相同或互反"。取最大值。
// 这个解法直接验证等价关系，但时间 O(m²*n) 不够优。
//
// 判断两行是否"相同或互反":
//   比较每一位: 如果所有位都相同 → 相同
//              如果所有位都相反 → 互反
//              否则 → 不等价
//
// 简化: 检查 row1[j] ^ row2[j] 对所有 j 是否一致
//   如果全是0 → 相同; 如果全是1 → 互反
// ============================================================
class Solution2 {
public:
    int maxEqualRowsAfterFlips(vector<vector<int>>& matrix) {
        int m = matrix.size(), n = matrix[0].size();
        int res = 0;

        for (int i = 0; i < m; i++) {
            int cnt = 0;
            for (int j = 0; j < m; j++) {
                // 检查行i和行j是否等价(相同或互反)
                // xor_val = row_i[0] ^ row_j[0] 确定是"相同"还是"互反"
                int xor_val = matrix[i][0] ^ matrix[j][0];
                bool equivalent = true;
                for (int k = 0; k < n; k++) {
                    if ((matrix[i][k] ^ matrix[j][k]) != xor_val) {
                        equivalent = false;
                        break;
                    }
                }
                if (equivalent) cnt++;
            }
            res = max(res, cnt);
        }
        return res;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法          | 时间     | 空间    | 说明                          |
// |--------------|---------|---------|------------------------------|
// | 行模式哈希    | O(m*n)  | O(m*n) | 标准化+计数，最优             |
// | 暴力两两比较  | O(m²*n) | O(1)   | 直接验证等价，用于理解原理      |
//
// m,n ≤ 300 → m²*n ≈ 2.7*10⁷ 暴力也能过
// 但面试中应该写哈希解法，展示"问题转化"能力
//
// ============================================================
// 【易错点】
//
// 1. 没有标准化，只统计完全相同的行:
//    ✗ 直接把行转字符串计数 → [0,1]和[1,0]算不同模式
//    ✓ 标准化后 [0,1]→"01", [1,0]→取反→"01", 归为同类
//
// 2. 标准化方向不一致:
//    ✗ 有的行按首位，有的行按末位 → 同一等价类两种模式
//    ✓ 统一按 row[0] 标准化
//
// 3. 用 vector 做 unordered_map 的 key:
//    ✗ unordered_map<vector<int>, int> → 编译错误
//    ✓ 转成 string; 或改用 map<vector<int>, int>
//
// 4. 忘记全1也是"全相同":
//    ✗ 以为只有全0才算 → 丢失互反行的贡献
//    ✓ 全0和全1都算，所以互反的两行一个全0另一个全1
//
// ============================================================
// 【面试追问】
//
// Q1: 如何证明"相同或互反"是充要条件?
//     必要性: 翻转集合S使A全0 → S={j|A[j]=1}
//     对B应用S: B'全0⟹B=A; B'全1⟹B=~A
//     充分性: 如果B=A, 同样的S使B也全0; 如果B=~A, 同样的S使B全1
//
// Q2: 如果要返回具体翻转哪些列?
//     取最大等价类中任一行A, 翻转 S={j|A[j]=1} 即可
//
// Q3: 时间能更优吗?
//     O(m*n)已是最优——必须读取每个元素至少一次
//
