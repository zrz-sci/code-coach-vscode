/*
 * 【题目本质】
 * 统计由非空格字符组成的连续片段数量，本质是检测"段开头"
 *
 * 【解法总览】
 * 解法1: 一次遍历检测段开头 ⭐ — O(n) / O(1) — 最优解
 * 解法2: istringstream 分词 — O(n) / O(n) — 利用标准库
 */

// ============================================================
// 解法1: 一次遍历检测段开头 ⭐
// 思路：当前字符非空格且前一个是空格（或 i==0）时计数
// 时间 O(n)，空间 O(1)
// ============================================================
class Solution1 {
public:
    int countSegments(string s) {
        int count = 0;
        for (int i = 0; i < (int)s.size(); i++) {
            if (s[i] != ' ' && (i == 0 || s[i - 1] == ' ')) {
                count++;
            }
        }
        return count;
    }
};

// ============================================================
// 解法2: istringstream 分词
// 思路：利用 C++ 流自动跳过空格的特性
// 时间 O(n)，空间 O(n)
// ============================================================
class Solution2 {
public:
    int countSegments(string s) {
        istringstream iss(s);
        string word;
        int count = 0;
        while (iss >> word) {
            count++;
        }
        return count;
    }
};

/*
 * 【解法对比】
 * 解法1: 纯遍历，O(1) 空间，面试中最推荐
 * 解法2: 简洁但依赖标准库，面试官可能不接受
 *
 * 【易错点】
 * 1. i=0 时访问 s[i-1] 越界 → 必须短路判断 i==0
 * 2. 空字符串 / 全空格字符串 → 条件自然处理返回 0
 * 3. 连续空格不应重复计数 → 只在段开头计数
 *
 * 【面试追问】
 * Q: 如何处理 \t \n 等空白？ A: 用 isspace() 替代 == ' '
 * Q: 如何同时返回段内容？ A: 双指针记录段的起止位置
 * Q: 能否不用 if 判断？ A: 可以用状态机但无实际收益
 */
