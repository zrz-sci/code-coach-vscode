/*
 * LeetCode 926: 将字符串翻转到单调递增 (Flip String to Monotone Increasing)
 *
 * 【题目本质】
 * 二进制字符串 "单调递增" = 所有 0 在左，所有 1 在右。
 * 找一个分界点使翻转次数最少，或用 DP 逐字符决策。
 *
 * 【解法总览】
 * 解法1: 前缀和枚举分界点 — O(n) / O(n) — 直觉解法
 * 解法2: DP (ones + flips) — O(n) / O(1) — 面试首选
 * 解法3: 二维 DP (dp[i][0/1]) — O(n) / O(1) — 最严谨的 DP
 */

// ============================================================
// 解法1: 前缀和枚举分界点
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 枚举分界点 k (0 <= k <= n):
//   - s[0..k-1] 全变 0: 翻转其中的 1 → 代价 = prefix[k]
//   - s[k..n-1] 全变 1: 翻转其中的 0 → 代价 = (n-k) - (totalOnes - prefix[k])
//   - 总代价 = prefix[k] + (n-k) - (totalOnes - prefix[k])
//
// prefix[i] = s[0..i-1] 中 '1' 的个数
//
// 示意:
// s = "00110"
// prefix = [0, 0, 0, 1, 2, 2]
//
// k=0: leftOnes=0, rightZeros=5-0-(2-0)=3 → 翻3次 (全变1)
// k=1: leftOnes=0, rightZeros=4-0-(2-0)=2 → 翻2次
// k=2: leftOnes=0, rightZeros=3-0-(2-0)=1 → 翻1次
// k=3: leftOnes=1, rightZeros=2-0-(2-1)=1 → 翻2次
// k=4: leftOnes=2, rightZeros=1-0-(2-2)=1 → 翻3次
// k=5: leftOnes=2, rightZeros=0             → 翻2次 (全变0)
// 最小 = 1 (k=2, 即 "00" + "111" → 翻掉末尾的0) ✓
// ============================================================
class Solution1 {
public:
    int minFlipsMonoIncr(string s) {
        int n = s.size();

        // 构建前缀和: prefix[i] = s[0..i-1] 中 '1' 的数量
        vector<int> prefix(n + 1, 0);
        for (int i = 0; i < n; i++) {
            prefix[i + 1] = prefix[i] + (s[i] == '1');
        }

        int totalOnes = prefix[n];
        int result = n;  // 最坏: 全部翻转

        // 枚举分界点 k: [0, k-1] 全0, [k, n-1] 全1
        for (int k = 0; k <= n; k++) {
            int leftOnes = prefix[k];  // 左边需要翻成 0 的 1 的数量
            // 右边 0 的数量 = 右边总字符数 - 右边 1 的数量
            int rightZeros = (n - k) - (totalOnes - prefix[k]);
            result = min(result, leftOnes + rightZeros);
        }

        return result;
    }
};

// ============================================================
// 解法2: DP (ones + flips) — 单变量压缩
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 维护:
//   ones  = 到目前位置遇到的 '1' 的总数
//   flips = 到目前位置使字符串单调递增的最小翻转次数
//
// 每遇到一个字符:
// - '1': ones++, flips 不变 (1 可以直接放在"1区间")
// - '0': 两种选择取 min:
//   选项A: 翻这个0为1 → flips + 1
//   选项B: 保留这个0，把之前所有1翻成0 → ones
//   → flips = min(flips + 1, ones)
//
// 过程示意:
// s = "00011000"
//          ones  flips
// s[0]='0': min(0+1,0)=0  → ones=0, flips=0
// s[1]='0': min(0+1,0)=0  → ones=0, flips=0
// s[2]='0': min(0+1,0)=0  → ones=0, flips=0
// s[3]='1': ones++         → ones=1, flips=0
// s[4]='1': ones++         → ones=2, flips=0
// s[5]='0': min(0+1,2)=1  → ones=2, flips=1
// s[6]='0': min(1+1,2)=2  → ones=2, flips=2
// s[7]='0': min(2+1,2)=2  → ones=2, flips=2
//
// 答案 = 2 ✓ (翻成 "00000000")
// ============================================================
class Solution2 {
public:
    int minFlipsMonoIncr(string s) {
        int ones = 0;   // 到目前为止遇到的 '1' 的数量
        int flips = 0;  // 到目前为止使字符串单调递增的最小翻转数

        for (char c : s) {
            if (c == '1') {
                // '1' 可以直接放在右半边，不需要翻转
                ones++;
            } else {
                // '0' — 有两个选择:
                // 选项A: 翻这个 0 为 1 → 延续之前方案 + 1
                // 选项B: 保留 0，把之前所有 1 翻掉 → 代价 = ones
                flips = min(flips + 1, ones);
            }
        }

        return flips;
    }
};

// ============================================================
// 解法3: 二维 DP — dp[i][0] / dp[i][1]
// 时间: O(n)  空间: O(1) (压缩后)
//
// 【思路】
// dp[i][0] = 使 s[0..i] 以 0 结尾且单调递增的最小翻转数
// dp[i][1] = 使 s[0..i] 以 1 结尾且单调递增的最小翻转数
//
// 转移:
// 如果 s[i] == '0':
//   dp[i][0] = dp[i-1][0]      (0→0, 不翻)
//   dp[i][1] = min(dp[i-1][0], dp[i-1][1]) + 1  (翻0为1)
// 如果 s[i] == '1':
//   dp[i][0] = dp[i-1][0] + 1  (翻1为0)
//   dp[i][1] = min(dp[i-1][0], dp[i-1][1])  (不翻)
//
// 答案 = min(dp[n-1][0], dp[n-1][1])
//
// 注意: dp[i][1] 可以从 dp[i-1][0] 转来，因为 0...01 是单调递增的。
// 但 dp[i][0] 只能从 dp[i-1][0] 转来，因为 ...10 不是单调递增的。
//
// 空间压缩: 只需要前一步的 dp0 和 dp1。
//
// 示意:
// s = "010110"
//         dp0  dp1
// 初始:   0    0
// s[0]='0': dp0=0, dp1=min(0,0)+1=1
// s[1]='1': dp0=0+1=1, dp1=min(0,1)=0
// s[2]='0': dp0=1, dp1=min(1,0)+1=1
// s[3]='1': dp0=1+1=2, dp1=min(1,1)=1
// s[4]='1': dp0=2+1=3, dp1=min(2,1)=1
// s[5]='0': dp0=3, dp1=min(3,1)+1=2
// 答案 = min(3, 2) = 2 ✓
// ============================================================
class Solution3 {
public:
    int minFlipsMonoIncr(string s) {
        int dp0 = 0;  // 以 0 结尾的最小翻转数
        int dp1 = 0;  // 以 1 结尾的最小翻转数

        for (char c : s) {
            if (c == '0') {
                // 以 0 结尾: 前一步也必须以 0 结尾，不翻
                // dp0 = dp0 (不变)
                // 以 1 结尾: 必须翻这个 0 为 1
                dp1 = min(dp0, dp1) + 1;
            } else {
                // c == '1'
                // 以 1 结尾: 不翻，从 0 或 1 结尾都可以转来
                dp1 = min(dp0, dp1);
                // 以 0 结尾: 必须翻这个 1 为 0
                dp0 = dp0 + 1;
            }
        }

        return min(dp0, dp1);
    }
};

// ============================================================
// 【解法对比】
//
// | 解法                | 时间  | 空间  | 特点                      |
// |---------------------|-------|-------|--------------------------|
// | 前缀和枚举分界点   | O(n)  | O(n)  | 直觉清晰，两遍遍历      |
// | DP (ones + flips)   | O(n)  | O(1)  | 最简洁，面试首选          |
// | 二维 DP (dp0/dp1)   | O(n)  | O(1)  | 最严谨，便于解释正确性    |
//
// 解法2 是解法3 的压缩形式:
//   ones 对应 dp0 (在 c=='0' 分支中，flips+1 是 dp1 的更新)
//   flips = min(dp0, dp1) 恰好是 ones+flips 中的 flips
//
// 【易错点】
// 1. 前缀和中 k 的范围漏了端点:
//    ✗ k 从 1 到 n-1 → 漏了"全0"和"全1"
//    ✓ k 从 0 到 n（包含两端）
//
// 2. DP 中 '1' 分支也更新了 flips:
//    ✗ 遇到 '1' 也做 flips = min(flips, ...) → 错误
//    ✓ 遇到 '1' 只 ones++，不动 flips
//
// 3. min 的选项搞反:
//    ✗ min(flips, ones + 1) — ones+1 不是"翻当前0"的代价
//    ✓ min(flips + 1, ones) — flips+1 是翻当前0，ones 是翻前面所有1
//
// 4. 二维 DP 中 dp1 的更新用了新的 dp0:
//    ✗ 先更新 dp0 再用新值算 dp1 → 结果偏大
//    ✓ 注意更新顺序，或用临时变量保存旧值
//
// 【面试追问】
// Q1: ones+flips 和二维 DP 的关系？
//    （ones+flips 是 dp0/dp1 的压缩形式，flips=min(dp0,dp1)）
// Q2: 前缀和和 DP 方法本质等价吗？
//    （是的，DP 是逐步更新最优分界点，前缀和是枚举所有分界点）
// Q3: 如果字符串不是二进制而是 0-9，怎么做？
//    （变成 LIS 问题的变体，需要 DP，O(n*10) 或更高）
// ============================================================
