/*
 * LeetCode 21: 合并两个有序链表 (Merge Two Sorted Lists)
 *
 * 【题目本质】
 * 归并排序中的 merge 步骤：两个有序链表，双指针逐一比较取较小者。
 *
 * 【解法总览】
 * 解法1: 迭代 (Dummy + 双指针) — O(m+n) / O(1)  — 面试首选
 * 解法2: 递归                   — O(m+n) / O(m+n) — 代码最简洁
 */

/**
 * Definition for singly-linked list.
 * struct ListNode {
 *     int val;
 *     ListNode *next;
 *     ListNode() : val(0), next(nullptr) {}
 *     ListNode(int x) : val(x), next(nullptr) {}
 *     ListNode(int x, ListNode *next) : val(x), next(next) {}
 * };
 */

// ============================================================
// 解法1: 迭代 (Dummy + 双指针) — 面试首选
// 时间: O(m+n)  空间: O(1)
//
// 【思路】
// 这道题和归并排序的 merge 完全一样：
// 两个指针分别指向两个链表头，比较大小，取小的接到结果链表尾部。
// 其中一个用完后，剩余的直接接上（因为本身有序且都比已合并部分大）。
//
// 关键技巧：用 dummy 虚拟头节点，统一处理"第一个节点"和"后续节点"，
// 避免 if (head == nullptr) 的特殊判断。
//
// 【指针变化示意图】
//
//  l1: 1 → 2 → 4 → NULL
//  l2: 1 → 3 → 4 → NULL
//  dummy → NULL         tail 指向 dummy
//
//  Step1: l1(1) <= l2(1), 取 l1
//    dummy → 1           tail 指向 1, l1 前进到 2
//
//  Step2: l1(2) > l2(1), 取 l2
//    dummy → 1 → 1       tail 指向第二个1, l2 前进到 3
//
//  Step3: l1(2) < l2(3), 取 l1
//    dummy → 1 → 1 → 2   tail 指向 2, l1 前进到 4
//
//  Step4: l1(4) > l2(3), 取 l2
//    dummy → 1 → 1 → 2 → 3   tail 指向 3, l2 前进到 4
//
//  Step5: l1(4) <= l2(4), 取 l1
//    dummy → 1 → 1 → 2 → 3 → 4   tail 指向 4, l1 = NULL
//
//  Step6: l1 用完，接上 l2 剩余
//    dummy → 1 → 1 → 2 → 3 → 4 → 4
//
//  返回 dummy.next
// ============================================================
class Solution1 {
public:
    ListNode* mergeTwoLists(ListNode* list1, ListNode* list2) {
        // dummy 在栈上分配，避免 new 带来的内存管理问题
        ListNode dummy(0);
        ListNode* tail = &dummy;
        
        // 核心循环：两个链表都有节点时，比较取小
        while (list1 && list2) {
            if (list1->val <= list2->val) {
                tail->next = list1;
                list1 = list1->next;
            } else {
                tail->next = list2;
                list2 = list2->next;
            }
            // 别忘了移动 tail！这是最常见的 bug
            tail = tail->next;
        }
        
        // 剩余部分直接接上：
        // 为什么一行就够？因为剩余的本身就是有序链表，
        // 且所有值 >= 已合并部分的最大值
        tail->next = list1 ? list1 : list2;
        
        return dummy.next;
    }
};

// ============================================================
// 解法2: 递归
// 时间: O(m+n)  空间: O(m+n) — 递归栈深度
//
// 【思路】
// 用递归的视角看：mergeTwoLists(l1, l2) 返回合并后链表的头节点。
// - Base case: 一方为空 → 返回另一方
// - 递归: 比较两个头节点，取较小的作为结果头，
//         它的 next 指向"剩余部分合并的结果"
//
// 这就是数学归纳法：假设子问题已经解决，只处理当前层。
//
// 【递归展开示意】
//
//  merge([1,2,4], [1,3,4])
//  ├─ 1 <= 1, 取 l1 的 1
//  │  1.next = merge([2,4], [1,3,4])
//  │  ├─ 2 > 1, 取 l2 的 1
//  │  │  1.next = merge([2,4], [3,4])
//  │  │  ├─ 2 < 3, 取 l1 的 2
//  │  │  │  2.next = merge([4], [3,4])
//  │  │  │  ├─ 4 > 3, 取 l2 的 3
//  │  │  │  │  3.next = merge([4], [4])
//  │  │  │  │  ├─ 4 <= 4, 取 l1 的 4
//  │  │  │  │  │  4.next = merge([], [4])
//  │  │  │  │  │  └─ l1空 → 返回 [4]
//  │  │  │  │  │  返回 4→4
//  │  │  │  │  返回 3→4→4
//  │  │  │  返回 2→3→4→4
//  │  │  返回 1→2→3→4→4
//  │  返回 1→1→2→3→4→4
//  最终: 1→1→2→3→4→4
// ============================================================
class Solution2 {
public:
    ListNode* mergeTwoLists(ListNode* list1, ListNode* list2) {
        // Base case: 一方为空，直接返回另一方
        if (!list1) return list2;
        if (!list2) return list1;
        
        // 取较小的头节点，递归合并剩余
        if (list1->val <= list2->val) {
            // list1 更小，它做头，它的 next 指向子问题的解
            list1->next = mergeTwoLists(list1->next, list2);
            return list1;
        } else {
            // list2 更小
            list2->next = mergeTwoLists(list1, list2->next);
            return list2;
        }
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 迭代 (解法1)           | 递归 (解法2)         |
// |-----------|----------------------|---------------------|
// | 时间       | O(m+n)               | O(m+n)              |
// | 空间       | O(1) 只用几个指针       | O(m+n) 递归栈        |
// | 代码量     | ~15 行                | ~8 行               |
// | 理解难度   | 低，就是归并排序的 merge  | 中，需要递归思维       |
// | 面试推荐   | ⭐ 首选               | 追问时给出           |
//
// 面试中优先写迭代版：O(1) 空间，不会栈溢出，逻辑清晰。
// 递归版用来展示递归思维，面试官问"还有别的写法吗"时给出。
//
// ============================================================
// 【易错点】
//
// 1. 忘记移动 tail 指针:
//    ✗ tail->next = list1; list1 = list1->next; (缺少 tail = tail->next)
//    → 所有节点都接在同一位置，最终结果只有最后一个节点
//    ✓ 在 if-else 之后加上 tail = tail->next;
//
// 2. dummy 用 new 但没 delete:
//    ✗ ListNode* dummy = new ListNode(0); ... return dummy->next;
//    → 内存泄漏（虽然 LeetCode 不在意，但面试中会被扣分）
//    ✓ ListNode dummy(0); 栈上分配，函数结束自动释放
//
// 3. 递归版传参写错:
//    ✗ list1->next = mergeTwoLists(list1, list2->next);
//    → list1 没有前进，死递归导致栈溢出
//    ✓ list1->next = mergeTwoLists(list1->next, list2);
//
// 4. while 条件用 || 而不是 &&:
//    ✗ while (list1 || list2) { if (list1->val ...) }
//    → 当其中一个为空时访问空指针崩溃
//    ✓ while (list1 && list2) 保证循环内两个都非空
//
// ============================================================
// 【面试追问】
//
// Q1（基础）: 为什么用 dummy 节点？不用可以吗？
// → 不用也行，但需要额外 if 判断第一次赋值头节点。
//   dummy 统一了"建立头节点"和"追加节点"的逻辑，代码更干净。
//
// Q2（空间）: 递归的空间复杂度？能优化吗？
// → O(m+n) 栈空间。不能优化（尾递归优化不适用于此处，
//   因为递归调用后还有赋值操作）。要 O(1) 空间必须用迭代。
//
// Q3（进阶 → LeetCode 23）: K 个有序链表合并怎么做？
// → 方法1: 分治，两两合并，总 O(N log K)，复用本题作为子操作。
//   方法2: 最小堆维护 K 个链表头，每次取最小的，O(N log K)。
//
// Q4（变体）: 如果要求合并后去重呢？
// → 在取节点时加一个判断：如果新节点值等于 tail 的值就跳过。
//   或者合并完后再做一次去重遍历。
//
// ============================================================
// 【相关题型】
//
// - 23. 合并K个升序链表 — 本题是它的基础子操作，23 用分治/堆扩展到 K 路
// - 88. 合并两个有序数组 — 同样的双指针归并，区别：数组可以从后往前填
// - 148. 排序链表 — 链表归并排序 = 快慢指针找中点 + 本题的 merge
// - 2. 两数相加 — 同样双链表同步遍历，操作从"比较取小"变为"加法进位"
// ============================================================
