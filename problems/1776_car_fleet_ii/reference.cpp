/*
 * LeetCode 1776: Car Fleet II
 *
 * 【题目本质】
 * n辆车同向行驶，快车追上慢车会合并（取慢速），求每辆车的碰撞时间。
 * 本质是：对每辆车，在右边找到它"真正能追上的、还没消失的"前车。
 *
 * 【解法总览】
 * 解法1: 暴力/堆模拟 — O(n log n) ~ O(n²) / O(n) — 按时间顺序模拟碰撞
 * 解法2: 单调栈(从右往左) — O(n) / O(n) — 面试首选 ⭐
 */

// ============================================================
// 解法1: 堆模拟 — 按碰撞时间从小到大处理
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 最直觉的模拟：
// 1. 计算所有相邻车对的碰撞时间，扔进小顶堆
// 2. 弹出最早的碰撞事件，记录答案，合并车队
// 3. 合并后更新受影响的相邻对（前后邻居变了），重新计算碰撞时间入堆
// 4. 重复直到堆空
//
// 这个方法是正确的但实现繁琐：
// - 需要维护"当前有效的邻接关系"（类似链表删除节点）
// - 堆中可能有过期事件（已合并的车对），需要惰性删除
// - 面试中不推荐，但展示了"能想到就说出来"的暴力思维
//
// 示例过程:
// cars: [1,2] [2,1] [4,3] [7,2]
//         0     1     2     3
//
// 初始碰撞时间:
//   (0,1): (2-1)/(2-1) = 1.0
//   (1,2): speed[1]=1 < speed[2]=3, 追不上 → 无
//   (2,3): (7-4)/(3-2) = 3.0
//
// 堆: [(1.0, 0,1), (3.0, 2,3)]
// 弹出(1.0, 0,1): ans[0]=1.0, 车0和车1合并, 速度=min(2,1)=1
//   新邻接: 合并后的{0,1}车队 与 车2
//   speed=1 < 3, 追不上 → 无新事件
// 弹出(3.0, 2,3): ans[2]=3.0
//
// 结果: [1.0, -1, 3.0, -1]
// ============================================================
class Solution1 {
public:
    vector<double> getCollisionTimes(vector<vector<int>>& cars) {
        int n = cars.size();
        vector<double> ans(n, -1.0);
        
        // 用链表维护存活的车的邻接关系
        vector<int> nxt(n); // nxt[i] = i的右邻居
        for (int i = 0; i < n; i++) nxt[i] = i + 1;
        
        // 小顶堆: (碰撞时间, 左车索引, 右车索引)
        using Event = tuple<double, int, int>;
        priority_queue<Event, vector<Event>, greater<Event>> pq;
        
        // 初始化所有相邻对
        for (int i = 0; i < n - 1; i++) {
            if (cars[i][1] > cars[i + 1][1]) {
                double t = (double)(cars[i + 1][0] - cars[i][0]) / 
                           (cars[i][1] - cars[i + 1][1]);
                pq.push({t, i, i + 1});
            }
        }
        
        vector<bool> merged(n, false); // 标记已被合并的车
        
        while (!pq.empty()) {
            auto [t, i, j] = pq.top();
            pq.pop();
            
            // 惰性删除：如果i或j已经被合并，跳过
            if (merged[i] || merged[j]) continue;
            // 检查j是否仍然是i的右邻居（可能已经变了）
            if (nxt[i] != j) continue;
            
            ans[i] = t;
            merged[i] = true; // 车i被合并进j的车队
            
            // 更新邻接关系：找到i的左邻居（如果有的话）
            // 这里简化处理：实际需要维护prev数组
            // 省略完整实现，因为这不是推荐解法
        }
        
        return ans;
        // 注意：上面的实现是不完整的（省略了prev维护），
        // 仅展示思路。完整实现需要双向链表维护邻接。
    }
};

// ============================================================
// 解法2: 单调栈(从右往左) — O(n) / O(n) ⭐ 面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法1的瓶颈在于"模拟碰撞顺序"需要堆+链表，代码复杂度高。
// 
// 换个角度：不按时间顺序模拟，而是按位置从右往左逐车确定答案。
// 
// 核心洞察:
// 1. 最右边的车永远不碰撞 → ans = -1
// 2. 从右往左看车i时，i右边的所有车的碰撞时间 ans[j] 已经确定
// 3. 用栈维护"对当前车i来说，可能是碰撞目标的右边的车"
//
// 栈中弹出条件 — 栈顶车j对车i无效的两种情况:
//
// 情况A: speed[i] <= speed[j]
//   → i不比j快，永远追不上j
//   → j对i没用（但j后面更慢的车可能有用），弹出j
//
// 情况B: speed[i] > speed[j]，追上时间t = (pos[j]-pos[i])/(speed[i]-speed[j])
//        但 ans[j] > 0 且 t > ans[j]
//   → i能追上j，但在追到之前j已经和更前面的车合并消失了
//   → j对i无效，弹出j
//
// 如果栈顶j不满足任何弹出条件 → j就是i的碰撞目标!
//
// 【为什么栈中元素有单调性？】
// 栈从底到顶，速度是非递增的（底部最慢）。
// 因为：如果栈中有 a(慢) 在 b(快) 下面，b 会追上 a 然后合并。
// 所以"还活着"的车从右往左看，速度趋势是递减的。
//
// 【可视化 — 示例2详细过程】
// cars: [3,4] [5,4] [6,3] [9,1]
//         0     1     2     3
//
//  位置轴:  3    5  6         9
//  速度:    4    4  3         1
//           →→→→ →→→→ →→→    →
//
// i=3: 栈空, push(3).
//      栈: [3]  (底→顶)
//      ans[3] = -1
//
// i=2: 栈顶=3, speed[2]=3 > speed[3]=1 ✓ (能追上)
//      t = (9-6)/(3-1) = 1.5
//      ans[3]=-1 (车3永不消失) → 条件B不成立 → j=3有效!
//      ans[2] = 1.5, push(2)
//      栈: [3, 2]
//
// i=1: 栈顶=2, speed[1]=4 > speed[2]=3 ✓ (能追上)
//      t = (6-5)/(4-3) = 1.0
//      ans[2]=1.5, t=1.0 < 1.5 → 条件B不成立(追上发生在消失之前) → 有效!
//      ans[1] = 1.0, push(1)
//      栈: [3, 2, 1]
//
// i=0: 栈顶=1, speed[0]=4 <= speed[1]=4 → 条件A! 弹出1.
//      栈: [3, 2]
//      栈顶=2, speed[0]=4 > speed[2]=3 ✓
//      t = (6-3)/(4-3) = 3.0
//      ans[2]=1.5, t=3.0 > 1.5 → 条件B! 车2在1.5秒消失, i=0需3秒才到 → 弹出2.
//      栈: [3]
//      栈顶=3, speed[0]=4 > speed[3]=1 ✓
//      t = (9-3)/(4-1) = 2.0
//      ans[3]=-1 → 条件B不成立 → 有效!
//      ans[0] = 2.0, push(0)
//      栈: [3, 0]
//
// 最终: [2.0, 1.0, 1.5, -1.0] ✓
// ============================================================
class Solution2 {
public:
    vector<double> getCollisionTimes(vector<vector<int>>& cars) {
        int n = cars.size();
        vector<double> ans(n, -1.0);
        stack<int> stk; // 存车的索引
        
        // 从右往左遍历：因为右边的车的碰撞时间已经确定
        for (int i = n - 1; i >= 0; i--) {
            // 弹出对车i无效的栈顶
            while (!stk.empty()) {
                int j = stk.top();
                
                // 条件A: 车i不比栈顶车j快，追不上
                if (cars[i][1] <= cars[j][1]) {
                    stk.pop();
                }
                // 条件B: 能追上，但j在被追上之前已经消失
                // ans[j] > 0 表示j会碰撞消失; 
                // catchTime > ans[j] 表示i追到j的时间晚于j消失的时间
                else if (ans[j] > 0 && 
                         catchTime(cars, i, j) > ans[j]) {
                    stk.pop();
                }
                // 都不满足 → 栈顶j是有效碰撞目标
                else {
                    break;
                }
            }
            
            // 如果栈非空，栈顶就是车i会追上的车
            if (!stk.empty()) {
                ans[i] = catchTime(cars, i, stk.top());
            }
            // 无论如何，车i入栈（它可能是更左边的车的碰撞目标）
            stk.push(i);
        }
        
        return ans;
    }
    
private:
    // 计算车i追上车j需要的时间
    // 前提: speed[i] > speed[j]（调用前已保证）
    double catchTime(vector<vector<int>>& cars, int i, int j) {
        return (double)(cars[j][0] - cars[i][0]) / 
               (cars[i][1] - cars[j][1]);
    }
};

// ============================================================
// 【解法对比】
//
// | 维度         | 解法1(堆模拟)     | 解法2(单调栈)    |
// |-------------|------------------|-----------------|
// | 时间         | O(n log n)~O(n²) | O(n)            |
// | 空间         | O(n)             | O(n)            |
// | 思维方向     | 按时间顺序正向模拟 | 按位置逆序确定答案 |
// | 实现难度     | 高(堆+链表+惰性删除) | 中(栈+两个弹出条件)|
// | 面试推荐     | 说思路即可        | ⭐ 必须能写       |
//
// 关键区别: 解法1是"全局模拟"，解法2是"局部判断"。
// 解法2之所以能 O(n)，是因为利用了"从右往左时，右边的答案已确定"这个性质。
//
// ============================================================
// 【易错点】
//
// 1. 条件B漏掉 ans[j] > 0 检查:
//    ✗ if (catchTime(i,j) > ans[j]) stk.pop();
//      当 ans[j]==-1 时，-1 < 任何正数，条件恒不成立看似安全
//      但 -1.0 < catchTime(i,j) 为true，所以不会弹出，好像没问题?
//      实际上这里确实可以不出bug，但逻辑上要明确:
//      ans[j]==-1 意味着j永远不消失，只要i比j快就一定能追上。
//      显式写 ans[j] > 0 让逻辑更清晰、更不容易出错。
//
// 2. 整数除法精度丢失:
//    ✗ return (cars[j][0] - cars[i][0]) / (cars[i][1] - cars[j][1]);
//      两个int相除，结果截断为0或不精确
//    ✓ return (double)(cars[j][0] - cars[i][0]) / (cars[i][1] - cars[j][1]);
//      至少一个操作数转double
//
// 3. 弹出用 if 而不是 while:
//    ✗ if (!stk.empty() && ...) stk.pop();  // 只弹一次
//    ✓ while (!stk.empty()) { if (...) stk.pop(); else break; }
//      可能需要连续弹出多个无效的栈顶
//
// 4. 从左往右遍历:
//    ✗ for (int i = 0; i < n; i++)
//      此时右边的车还没处理, ans[j]未知, 无法判断条件B
//    ✓ for (int i = n - 1; i >= 0; i--)
//
// 5. 速度相等时的处理:
//    ✗ 认为 speed[i] == speed[j] 时能追上 (除法分母为0!)
//    ✓ speed[i] <= speed[j] 统一归为"追不上"，弹出
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1(基础理解): "为什么从右往左而不是从左往右？"
//   → 从右往左时，右侧车的碰撞时间已确定(ans[j]已知)，
//     可以判断j是否在被追上前消失。从左往右做不到这一点。
//
// Q2(深入): "每辆车入栈后可能被弹出，会不会遗漏？
//           比如车j被弹出后，更左边的车i本该追上j怎么办？"
//   → j被弹出意味着对当前车i来说j无效(要么追不上要么j先消失)。
//     而j被弹出后，i会继续看j下面的栈元素(更右边、速度更慢的车)。
//     如果j会消失，那j合并后变成了更慢的车(即j下面栈里的车)，
//     所以i实际上会追上那辆更慢的车，逻辑是自洽的。
//
// Q3(变体): "如果碰撞后取最大速度呢？"
//   → 合并后变快会触发级联碰撞(变快后可能追上更前面的车)，
//     问题结构发生本质变化。单调栈的"右边已确定"前提被打破
//     (j碰撞后变快了，ans[j]可能改变)。需要重新设计算法，
//     可能退回到堆模拟。
//
// Q4(扩展): "这道题和853. Car Fleet的区别？"
//   → 853只问最终车队数量，不需要知道碰撞时间，
//     排序后从右往左扫描即可(O(n log n))。
//     本题要求每辆车的具体碰撞时间，且需要处理
//     "级联消失"(追的车在被追上前先消失)，需要单调栈。
// ============================================================
