/*
 * LeetCode 459: 重复的子字符串 (Repeated Substring Pattern)
 *
 * 【题目本质】
 * 判断字符串 s 是否能由某个子串重复 k 次（k ≥ 2）拼接而成。
 * 等价于：s 是否存在一个长度为 len 的周期，其中 len 整除 n 且 len < n。
 *
 * 【解法总览】
 * 解法1: 枚举因子长度     — O(n√n) / O(1) — 最直觉，面试首选
 * 解法2: 拼接法 (s+s)     — O(n)   / O(n) — 巧妙，面试首选
 * 解法3: KMP next数组     — O(n)   / O(n) — 加分项，展示算法功底
 */

// ============================================================
// 解法1: 枚举因子长度 — 最直觉的做法
// 时间: O(n√n)  空间: O(1)
//
// 【思路】
// 如果 s 由长度为 len 的子串重复 k 次构成，则 n = len * k，
// 所以 len 必须是 n 的因子，且 len ≤ n/2（至少重复 2 次）。
//
// 对于每个候选长度 len，只需检查 s[i] == s[i % len] 对所有 i 是否成立。
// i % len 巧妙地实现了"循环比较"，无需截取子串。
//
// 示例: s = "abcabc", n = 6
//   len=1: "a" 重复6次? s[1]='b' != s[1%1]='a' → 不行
//   len=2: 6%2=0, "ab" 重复3次? s[2]='c' != s[2%2]='a' → 不行
//   len=3: 6%3=0, "abc" 重复2次? 
//          s[3]='a'==s[0]='a' ✓, s[4]='b'==s[1]='b' ✓, s[5]='c'==s[2]='c' ✓
//          → 匹配！返回 true
// ============================================================
class Solution1 {
public:
    bool repeatedSubstringPattern(string s) {
        int n = s.size();
        for (int len = 1; len <= n / 2; len++) {
            // 只检查 n 的因子，非因子不可能构成完整重复
            if (n % len != 0) continue;
            
            bool match = true;
            // 从 len 开始比较（前 len 个字符是候选子串本身）
            for (int i = len; i < n; i++) {
                if (s[i] != s[i % len]) {
                    match = false;
                    break;
                }
            }
            if (match) return true;
        }
        return false;
    }
};

// ============================================================
// 解法2: 拼接法 — 数学巧妙解
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 核心观察：如果 s 有重复子串结构，将 s+s 拼接后去掉首尾各一个字符，
// 在剩余部分中一定还能找到完整的 s。
//
// 为什么？直觉如下：
// 假设 s = "abcabc" (= "abc" × 2)
// s+s = "abcabc|abcabc"
// 去首尾: "bcabc abcab"
//          在其中找 "abcabc":
//          "bcabc[abcabc]b"? 不对，让我们仔细看：
//          "bcabcabcab" 中，从位置 3 开始 "abcabc" ← 找到了！
//
// 若 s 无重复结构，如 s = "abc"
// s+s = "abcabc"
// 去首尾: "bcab" — 长度4，找长度3的 "abc"，没有。
//
// 实现时不需要真的去首尾，只需 find 从位置 1 开始搜索，
// 若找到位置 < n，说明是"中间"冒出来的匹配 → 有重复结构。
// ============================================================
class Solution2 {
public:
    bool repeatedSubstringPattern(string s) {
        string t = s + s;
        // 从位置 1 开始搜索，跳过 t[0] 开头的那个 s
        // 找到的位置若 < s.size()，说明不是第二个完整 s，而是中间的匹配
        return t.find(s, 1) != s.size();
        
        // 注意：也可以写 t.find(s, 1) < s.size()
        // 若无重复结构，find 会在位置 s.size() 找到第二个完整的 s
    }
};

// ============================================================
// 解法3: KMP next 数组 — 利用前缀函数的周期性质
// 时间: O(n)  空间: O(n)
//
// 【思路】
// KMP 的 next 数组（前缀函数）：next[i] = s[0..i] 的最长相等真前后缀长度。
//
// 关键定理：字符串 s 的最小周期 = n - next[n-1]
// 如果 n 能被最小周期整除，则 s 由该周期重复构成。
//
// 可视化 next 数组构建过程:
//
// s = "a b c a b c a b c"
//      0 1 2 3 4 5 6 7 8
//
// i=0: next[0] = 0 (单个字符无真前后缀)
// i=1: s[1]='b' vs s[0]='a' → 不匹配, next[1] = 0
// i=2: s[2]='c' vs s[0]='a' → 不匹配, next[2] = 0
// i=3: s[3]='a' vs s[0]='a' → 匹配!  next[3] = 1
//      "abca" 的最长相等前后缀: "a"
// i=4: s[4]='b' vs s[1]='b' → 匹配!  next[4] = 2
//      "abcab" 的最长相等前后缀: "ab"
// i=5: s[5]='c' vs s[2]='c' → 匹配!  next[5] = 3
//      "abcabc" 的最长相等前后缀: "abc"
// i=6: s[6]='a' vs s[3]='a' → 匹配!  next[6] = 4
// i=7: s[7]='b' vs s[4]='b' → 匹配!  next[7] = 5
// i=8: s[8]='c' vs s[5]='c' → 匹配!  next[8] = 6
//
// next[8] = 6, 周期 = 9 - 6 = 3, 9 % 3 == 0 → true
//
// 对比 s = "a b a":
// next = [0, 0, 1]
// next[2] = 1, 周期 = 3 - 1 = 2, 3 % 2 == 1 ≠ 0 → false
// ============================================================
class Solution3 {
public:
    bool repeatedSubstringPattern(string s) {
        int n = s.size();
        
        // 构建前缀函数 (KMP next 数组)
        // next[i]: s[0..i] 的最长相等真前缀和真后缀的长度
        vector<int> next(n, 0);
        for (int i = 1; i < n; i++) {
            int j = next[i - 1]; // j 指向上一个匹配位置的下一个字符
            
            // 核心：不匹配时回退，利用已有的前缀信息
            // 为什么回退到 next[j-1]？因为 s[0..j-1] 的最长相等前后缀
            // 就是下一个可能匹配的位置
            while (j > 0 && s[i] != s[j]) {
                j = next[j - 1];
            }
            
            if (s[i] == s[j]) {
                j++;
            }
            next[i] = j;
        }
        
        int lps = next[n - 1]; // 整个字符串的最长相等前后缀长度
        int period = n - lps;  // 最小周期长度
        
        // 两个条件缺一不可：
        // 1. lps > 0：存在非空的相等前后缀（否则无重复结构）
        // 2. n % period == 0：周期能整除 n（否则最后一段不完整）
        return lps > 0 && n % period == 0;
    }
};

// ============================================================
// 【解法对比】
//
// 枚举因子法:
//   - 优点：直觉清晰，空间 O(1)，面试中最容易写对
//   - 缺点：最坏 O(n√n)，但对于 n ≤ 10^4 完全够用
//   - 适合：作为面试第一反应方案
//
// 拼接法:
//   - 优点：代码极简（一行核心逻辑），O(n) 时间
//   - 缺点：需要额外解释正确性，且依赖 find 的实现效率
//   - 适合：展示数学直觉和创造性思维
//
// KMP 法:
//   - 优点：纯 O(n)，不依赖库函数，展示算法功底
//   - 缺点：需要掌握 KMP，代码较长
//   - 适合：面试追问"不用库函数怎么做"时
//
// 【易错点】
//
// 1. 枚举法中 len 范围：
//    ✗ len < n → 会检查 len=n（整个字符串不算"重复"）
//    ✓ len <= n/2 → 至少重复 2 次
//
// 2. 拼接法 find 起始位置：
//    ✗ t.find(s) → 在位置 0 找到，永远 true
//    ✓ t.find(s, 1) → 跳过开头
//
// 3. KMP 法漏检查 lps > 0：
//    ✗ return n % period == 0; → 当 lps=0 时 period=n，n%n==0 为 true
//    ✓ return lps > 0 && n % period == 0;
//
// 4. KMP next 数组中 while 循环的回退条件：
//    ✗ while (s[i] != s[j]) j = next[j-1]; → 当 j=0 时访问 next[-1]
//    ✓ while (j > 0 && s[i] != s[j]) j = next[j-1]; → 先检查 j>0
//
// 【面试追问】
//
// Q1（基础理解）: 子串长度为什么只需要枚举 n 的因子？
//     → n = len × k，所以 len 必须整除 n。非因子长度最后一段一定不完整。
//
// Q2（优化）: 枚举法能否从大到小枚举以提前终止？
//     → 可以从 n/2 到 1 枚举。找到第一个就返回 true。但注意题目只要求
//       判断是否存在，不要求找最短/最长子串，所以方向不影响正确性。
//       但如果想找最短重复单元，应该从小到大。
//
// Q3（进阶）: 不用库函数的 find，拼接法如何实现？
//     → 可以在 s+s 上手写 KMP 匹配，或者直接用 KMP next 数组性质
//       （解法3），完全不需要做字符串搜索。
//
// Q4（变体）: 如何找出最短重复单元？
//     → 用 KMP：最短重复单元长度 = n - next[n-1]。如果它整除 n，
//       则 s[0..period-1] 就是最短重复单元；否则最短重复单元是 s 本身。
// ============================================================
