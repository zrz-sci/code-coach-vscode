/*
 * LeetCode 402: 移掉 K 位数字 (Remove K Digits)
 *
 * 【题目本质】
 * 从数字字符串中删除 k 位，使剩余数字最小。
 * 贪心策略：高位越小越好。用单调递增栈维护保留的数字序列。
 *
 * 【解法总览】
 * 解法1: 单调栈（贪心）    — O(n) / O(n) — 唯一正解
 * 解法2: 变体（入栈时跳零） — O(n) / O(n) — 另一种前导零处理方式
 */

// ============================================================
// 解法1: 单调栈（贪心）— O(n) / O(n) ⭐
//
// 【思路】
// 贪心直觉：高位的数字影响最大。如果发现前一位比当前位大，
// 删掉前一位一定更优（让更小的数字占据高位）。
//
// 用 string 模拟单调递增栈：
// - 遍历每个字符 c
// - 只要栈顶 > c 且还有删除额度(k>0)，弹出栈顶（删掉它）
// - 将 c 入栈
// - 遍历结束后若 k>0，从末尾删除剩余的 k 个
// - 最后去掉前导零
//
// 【栈状态变化 — num="1432219", k=3】
//
//   处理'1': stk="1"                (空栈，入)
//   处理'4': stk="14"               (4>1，入)
//   处理'3': 3<4 → 弹4(k=2)         stk="1"
//            3>1 → 入               stk="13"
//   处理'2': 2<3 → 弹3(k=1)         stk="1"
//            2>1 → 入               stk="12"
//   处理'2': 2==2 → 入              stk="122"
//   处理'1': 1<2 → 弹2(k=0)         stk="12"
//            k=0 → 入               stk="121"
//   处理'9': 9>1 → 入               stk="1219"
//
//   k=0，无需末尾删。去前导零 → "1219" ✓
//
// 【栈状态变化 — num="10200", k=1】
//
//   处理'1': stk="1"
//   处理'0': 0<1 → 弹1(k=0)         stk=""
//            入                      stk="0"
//   处理'2': stk="02"
//   处理'0': k=0, 不弹, 入           stk="020"
//   处理'0': stk="0200"
//
//   去前导零: "0200" → "200" ✓
// ============================================================
class Solution1 {
public:
    string removeKdigits(string num, int k) {
        // 用 string 模拟栈：push_back 入栈，pop_back 出栈
        string stk;

        for (char c : num) {
            // 栈顶比当前大就弹出（删掉高位大数字）
            // 三个条件缺一不可：非空 && 有额度 && 栈顶更大
            while (!stk.empty() && k > 0 && stk.back() > c) {
                stk.pop_back();
                k--;
            }
            stk.push_back(c);
        }

        // 遍历完 k 还有剩余 → 栈内是递增的，从末尾删
        while (k > 0) {
            stk.pop_back();
            k--;
        }

        // 去掉前导零
        size_t pos = stk.find_first_not_of('0');
        if (pos == string::npos) return "0";  // 全是零或空
        return stk.substr(pos);
    }
};

// ============================================================
// 解法2: 变体 — 入栈时跳过前导零
//
// 【思路】
// 在入栈阶段就跳过前导零（栈为空时不入零），
// 最后不需要再处理前导零。逻辑稍复杂但避免了后处理。
//
// 【注意】
// 跳过的零不消耗 k（不算"删除"），只是不放入结果。
// 但 k 的消耗逻辑（while 弹出栈顶时 k--）是一样的。
// ============================================================
class Solution2 {
public:
    string removeKdigits(string num, int k) {
        string stk;

        for (char c : num) {
            while (!stk.empty() && k > 0 && stk.back() > c) {
                stk.pop_back();
                k--;
            }
            // 栈为空时不入零 → 自动跳过前导零
            if (!stk.empty() || c != '0') {
                stk.push_back(c);
            }
        }

        // k 还有剩余，从末尾删
        while (k > 0 && !stk.empty()) {
            stk.pop_back();
            k--;
        }

        return stk.empty() ? "0" : stk;
    }
};

// ============================================================
// 【解法对比】
//
// | 写法           | 前导零处理          | 代码简洁度 | 推荐    |
// |----------------|---------------------|-----------|---------|
// | 后处理去零     | find_first_not_of   | 更简洁    | ⭐ 首选 |
// | 入栈时跳零     | 入栈时判断          | 略复杂    | 变体    |
//
// 两种写法时间/空间复杂度完全一样：O(n) / O(n)。
// 每个字符最多入栈一次、出栈一次，总操作 O(n)。
//
// 【易错点】
// 1. 忘记遍历后处理剩余 k:
//    ✗ 遍历完就返回 → "12345" k=2 应输出 "123" 但输出 "12345"
//    ✓ while (k > 0) stk.pop_back(), k--;
//
// 2. 忘记去前导零:
//    ✗ 直接返回 stk → "10200" k=1 返回 "0200"
//    ✓ find_first_not_of('0') 或入栈时跳零
//
// 3. 空结果返回 "" 而非 "0":
//    ✗ return stk → 可能是空串
//    ✓ return stk.empty() ? "0" : stk
//
// 4. while 条件漏 k>0:
//    ✗ while (!stk.empty() && stk.back() > c) → k 用完了还在弹
//    ✓ while (!stk.empty() && k > 0 && stk.back() > c)
//
// 5. 用 stack<char> 而非 string:
//    不是 bug 但不推荐 — stack 最后需逐个 pop + reverse 拼字符串
//
// 【面试追问】
// Q1: 为什么贪心正确？
//     → 高位数字影响最大。d_i > d_{i+1} 时删 d_i 让更小的数占高位，
//       数值一定更小。单调栈保证每次删除都是当前最优。
//
// Q2: 时间 O(n) 怎么证明？
//     → 每个字符最多入栈1次出栈1次，总操作 <= 2n = O(n)。
//
// Q3: 如果要"移掉 k 位后最大"？
//     → 维护单调递减栈。遇到比栈顶大的就弹出（删高位小数字）。
//
// Q4: 与 316/1081（去除重复字母）的关系？
//     → 同为"单调栈+贪心"。316/1081 额外要求每字符恰好出现一次
//       (需计数器)，但核心"遇到更小就弹出"逻辑一样。
// ============================================================
