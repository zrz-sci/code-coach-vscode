/*
 * LeetCode 367: Valid Perfect Square (有效的完全平方数)
 *
 * 【题目本质】
 * 在 [1, num] 中找是否存在整数 x 使得 x*x == num。
 * 搜索空间有序(x² 单调递增)，可以二分。
 *
 * 【解法总览】
 * 解法1: 线性枚举     — O(√n) / O(1) — 最直觉
 * 解法2: 二分查找     — O(log n) / O(1) — 面试首选 ⭐
 * 解法3: 奇数求和     — O(√n) / O(1) — 数学技巧
 * 解法4: 牛顿迭代法   — O(log n) / O(1) — 进阶加分
 */

// ============================================================
// 解法1: 线性枚举 — 从1开始逐个试 x²
// 时间: O(√n)  空间: O(1)
//
// 【思路】
// 最朴素的想法：x 从 1 开始递增，
// 如果 x*x < num 就继续，x*x == num 就找到了，x*x > num 就不存在。
// 循环最多执行 √n 次就会停下。
// ============================================================
class Solution1 {
public:
    bool isPerfectSquare(int num) {
        long long x = 1;
        // 只要 x² 还没达到 num，就继续往上试
        while (x * x < num) {
            x++;
        }
        // 退出时 x*x >= num，检查是否恰好相等
        return x * x == num;
    }
};

// ============================================================
// 解法2: 二分查找 — 在 [1, num] 上二分 ⭐ 面试首选
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 解法1 的搜索空间 [1, num] 上，f(x)=x² 是单调递增函数。
// 既然有序，就能二分，每次排除一半，从 O(√n) 优化到 O(log n)。
//
// 搜索空间收缩过程 (num = 16):
// Round1: [1, 16]  mid=8  → 64 > 16  → right=7
// Round2: [1, 7]   mid=4  → 16 == 16 → 找到!
//
// 搜索空间收缩过程 (num = 14):
// Round1: [1, 14]  mid=7  → 49 > 14  → right=6
// Round2: [1, 6]   mid=3  → 9  < 14  → left=4
// Round3: [4, 6]   mid=5  → 25 > 14  → right=4
// Round4: [4, 4]   mid=4  → 16 > 14  → right=3
// Round5: left=4 > right=3 → 退出，return false
// ============================================================
class Solution2 {
public:
    bool isPerfectSquare(int num) {
        long long left = 1, right = num;
        while (left <= right) {
            long long mid = left + (right - left) / 2;
            long long square = mid * mid;
            if (square == num) {
                return true;       // 精确命中
            } else if (square < num) {
                left = mid + 1;    // mid 太小，答案在右半边
            } else {
                right = mid - 1;   // mid 太大，答案在左半边
            }
        }
        // 搜索空间耗尽，不存在整数 x 使得 x² == num
        return false;
    }
};

// ============================================================
// 解法3: 奇数求和（数学性质）— 利用 1+3+5+...+(2n-1) = n²
// 时间: O(√n)  空间: O(1)
//
// 【思路】
// 数学事实: 前 n 个奇数之和 = n²
//   1           = 1  = 1²
//   1+3         = 4  = 2²
//   1+3+5       = 9  = 3²
//   1+3+5+7     = 16 = 4²
//
// 所以从 num 中依次减去 1, 3, 5, 7, ...
// 如果恰好减到 0 → 完全平方数
// 如果减成负数 → 不是
//
// 这个方法不需要乘法，纯加减法就能判断！
// ============================================================
class Solution3 {
public:
    bool isPerfectSquare(int num) {
        int odd = 1;
        while (num > 0) {
            num -= odd;       // 依次减去第 k 个奇数
            odd += 2;         // 下一个奇数
        }
        // 恰好减到 0 说明 num 是某个 n² (减了 n 次奇数)
        return num == 0;
    }
};

// ============================================================
// 解法4: 牛顿迭代法 — 数值逼近 √num
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 求 f(x) = x² - num = 0 的根。
// 牛顿法迭代公式: x_{n+1} = (x_n + num / x_n) / 2
// 从 x = num 开始迭代，x 会快速收敛到 floor(√num)。
//
// 为什么 while 条件是 x*x > num？
// 因为整数除法向下取整，迭代最终会稳定在 floor(√num)，
// 此时 x*x <= num。退出循环后检查 x*x == num 即可。
//
// 收敛过程 (num = 16):
//   x=16 → (16 + 16/16)/2 = (16+1)/2 = 8
//   x=8  → (8 + 16/8)/2  = (8+2)/2 = 5
//   x=5  → (5 + 16/5)/2  = (5+3)/2 = 4
//   x=4  → 4*4 = 16 == 16 → 退出, return true
// ============================================================
class Solution4 {
public:
    bool isPerfectSquare(int num) {
        long long x = num;
        // 不断逼近 √num，直到 x*x <= num
        while (x * x > num) {
            x = (x + num / x) / 2;
        }
        return x * x == num;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间      | 空间 | 特点                           |
// |-----------|----------|------|-------------------------------|
// | 线性枚举   | O(√n)    | O(1) | 最直觉，面试起手              |
// | 二分查找   | O(log n) | O(1) | 面试首选，展示搜索空间思维    |
// | 奇数求和   | O(√n)    | O(1) | 纯数学，不用乘法              |
// | 牛顿迭代   | O(log n) | O(1) | 进阶数值方法，收敛极快        |
//
// 面试推荐: 先说解法1表示理解题意 → 立刻给出解法2(二分) → 
//           如果面试官追问数学方法，给出解法3或4。
//
// 和 LeetCode 69 (Sqrt(x)) 的关系:
// - 69 题: 求 floor(√x)，二分找最大的 mid 使得 mid² <= x → 返回 right
// - 本题:  判断 √x 是否为整数，二分找 mid 使得 mid² == x → 返回 bool
// - 核心框架完全一样，只是返回值的语义不同
//
// 【易错点】
// 1. mid*mid 溢出: num 最大 2^31-1 ≈ 2.1×10⁹，mid 可能到 46340，
//    mid*mid ≈ 2.1×10⁹ 刚好在 int 边界。必须用 long long。
//    ✗ int mid = ...; if (mid * mid == num)  // 可能溢出
//    ✓ long long mid = ...; long long square = mid * mid;
//
// 2. 二分右边界: 如果右边界写 num/2，当 num=1 时 right=0，
//    搜索空间为空，返回 false（1 是完全平方数！）。
//    ✗ right = num / 2;   // num=1 时 right=0，漏掉答案
//    ✓ right = num;        // 安全
//
// 3. 牛顿法初始值: 如果选 num/2，当 num=1 时初始值为0，除零错误。
//    ✗ long long x = num / 2;  // num=1 时 x=0
//    ✓ long long x = num;       // 安全
//
// 【面试追问】
// Q1: "暴力法时间复杂度多少？能接受吗？"
//   → O(√n)，n≤2^31，√n≈46340，当然能过。但面试官想看更优的。
//
// Q2: "为什么能二分？二分的前提条件是什么？"
//   → f(x)=x² 在正整数上单调递增，搜索空间有序，所以能二分。
//      每次通过 mid² 与 num 的大小关系，确定性地排除一半空间。
//
// Q3: "如果不允许用乘法呢？"
//   → 用奇数求和法(解法3)，只需加减法。或者用位运算模拟乘法。
//
// Q4: "和 Sqrt(x) 这题有什么区别？代码改哪里？"
//   → Sqrt(x) 求 floor(√x)，用 left < right 模板找上界，返回 right。
//      本题判断精确匹配，用 left <= right 模板，找到 == 就返回 true。
// ============================================================
