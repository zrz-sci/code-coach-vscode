/*
 * LeetCode 1249: 移除无效的括号 (Minimum Remove to Make Valid Parentheses)
 *
 * 【题目本质】
 * 找出所有无法配对的括号的位置，删除它们。
 * 无法配对 = 多余的 ')' (没有左括号匹配) + 多余的 '(' (没有右括号匹配)。
 *
 * 【解法总览】
 * 解法1: 栈记录索引 + Set   — O(n) / O(n) — 最直觉，面试首选
 * 解法2: 两遍扫描计数       — O(n) / O(n) — 不依赖栈，思路对称优美
 * 解法3: 栈 + 原地标记      — O(n) / O(n) — 代码最简洁
 */

// ============================================================
// 解法1: 栈记录索引 + Set — 最直觉的思路
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 括号匹配是栈的经典应用：遇到'('入栈，遇到')'弹栈匹配。
// 普通匹配只判断"是否有效"，但我们需要"定位无效括号"。
// 关键突破：栈里存索引而不是字符。
//
// 未匹配的括号有两类：
// 1. 遍历过程中：遇到')'但栈空 → 这个')'多余
// 2. 遍历结束后：栈中残留的'(' → 这些'('多余
//
// 示例: s = "a)b(c)d"
// 
// i=0 'a' → 跳过                栈: []
// i=1 ')' → 栈空, 标记删除!     栈: []      toRemove: {1}
// i=2 'b' → 跳过                栈: []
// i=3 '(' → push(3)             栈: [3]
// i=4 'c' → 跳过                栈: [3]
// i=5 ')' → pop(3), 匹配!      栈: []
// i=6 'd' → 跳过                栈: []
// 
// 栈空，无残余。toRemove = {1}
// 跳过索引1，结果: "ab(c)d"
// ============================================================
class Solution1 {
public:
    string minRemoveToMakeValid(string s) {
        stack<int> stk;  // 存未匹配的左括号索引
        unordered_set<int> toRemove;  // 需要删除的索引集合
        
        for (int i = 0; i < (int)s.size(); i++) {
            if (s[i] == '(') {
                stk.push(i);  // 左括号先入栈等待匹配
            } else if (s[i] == ')') {
                if (!stk.empty()) {
                    stk.pop();  // 找到了配对的左括号
                } else {
                    toRemove.insert(i);  // 没有左括号能配对，标记删除
                }
            }
            // 小写字母不影响括号匹配，直接跳过
        }
        
        // 关键：遍历结束后栈中剩余的(都是多余的，也要删除
        while (!stk.empty()) {
            toRemove.insert(stk.top());
            stk.pop();
        }
        
        // 构建结果：跳过所有标记删除的位置
        string result;
        for (int i = 0; i < (int)s.size(); i++) {
            if (toRemove.find(i) == toRemove.end()) {
                result += s[i];
            }
        }
        return result;
    }
};

// ============================================================
// 解法2: 两遍扫描计数 — 正反各扫一遍，不用栈
// 时间: O(n)  空间: O(n) (中间字符串)
//
// 【思路】
// 核心观察：多余的')'和多余的'('是"对称"的问题。
// - 正向扫描：维护openCount(未匹配的'('个数)，
//   遇到')'时如果openCount==0说明多余，不加入结果。
//   → 这一遍保证结果中没有多余的')'
// - 反向扫描：维护closeCount(未匹配的')'个数)，
//   遇到'('时如果closeCount==0说明多余，不加入结果。
//   → 这一遍保证结果中没有多余的'('
//
// 为什么正向扫描不能同时处理多余的'('？
// 因为只有走到字符串末尾才能确定哪些'('是多余的，
// 而此时已经把它们加入了结果。反向扫描恰好弥补这一点。
//
// 示例: s = "(a(b)"
// 正向扫描: openCount跟踪
//   '(' openCount=1, 加入 → "(..."
//   'a' 加入 → "(a..."
//   '(' openCount=2, 加入 → "(a(..."
//   'b' 加入 → "(a(b..."
//   ')' openCount=1, 加入 → "(a(b)"
//   结束后 temp = "(a(b)", 没有多余的')', 但有多余的'('
//
// 反向扫描 temp = "(a(b)":
//   ')' closeCount=1, 加入
//   'b' 加入
//   '(' closeCount=0, 匹配, 加入
//   'a' 加入
//   '(' closeCount=0, 多余! 不加入
//   反向结果 = ")b(a", reverse → "a(b)"
// ============================================================
class Solution2 {
public:
    string minRemoveToMakeValid(string s) {
        // 第一遍：正向扫描，去除多余的 )
        string temp;
        int openCount = 0;
        for (char c : s) {
            if (c == '(') {
                openCount++;
                temp += c;
            } else if (c == ')') {
                if (openCount > 0) {
                    openCount--;
                    temp += c;
                }
                // openCount==0时这个)没有(配对，跳过（即删除）
            } else {
                temp += c;
            }
        }
        
        // 第二遍：反向扫描，去除多余的 (
        string result;
        int closeCount = 0;
        for (int i = (int)temp.size() - 1; i >= 0; i--) {
            if (temp[i] == ')') {
                closeCount++;
                result += temp[i];
            } else if (temp[i] == '(') {
                if (closeCount > 0) {
                    closeCount--;
                    result += temp[i];
                }
                // closeCount==0时这个(没有)配对，跳过
            } else {
                result += temp[i];
            }
        }
        
        // 反向构建的需要翻转回来
        reverse(result.begin(), result.end());
        return result;
    }
};

// ============================================================
// 解法3: 栈 + 原地标记 — 代码最简洁
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 与解法1思路完全相同，但优化了实现：
// 不用 set 存要删除的索引，而是直接在原字符串上把无效括号
// 标记为特殊字符'*'，最后一次过滤即可。
//
// 为什么'*'不会和原字符冲突？
// 因为题目明确说 s[i] 只可能是 '(', ')' 或小写字母。
//
// 示例: s = "))(("
//
// i=0 ')' → 栈空, s[0]='*'     栈: []      s: "*)(("
// i=1 ')' → 栈空, s[1]='*'     栈: []      s: "**(("
// i=2 '(' → push(2)            栈: [2]     s: "**(("
// i=3 '(' → push(3)            栈: [2,3]   s: "**(("
//
// 清理栈: s[3]='*', s[2]='*'   s: "****"
// 过滤'*': 结果 = ""
// ============================================================
class Solution3 {
public:
    string minRemoveToMakeValid(string s) {
        stack<int> stk;
        
        for (int i = 0; i < (int)s.size(); i++) {
            if (s[i] == '(') {
                stk.push(i);
            } else if (s[i] == ')') {
                if (!stk.empty()) {
                    stk.pop();  // 匹配成功
                } else {
                    s[i] = '*';  // 多余的)，原地标记
                }
            }
        }
        
        // 栈中残余的(也标记为*
        while (!stk.empty()) {
            s[stk.top()] = '*';
            stk.pop();
        }
        
        // 过滤掉所有*字符
        string result;
        for (char c : s) {
            if (c != '*') result += c;
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 解法1: 栈+Set | 解法2: 两遍扫描 | 解法3: 原地标记 |
// |-----------|--------------|----------------|---------------|
// | 时间       | O(n)         | O(n)           | O(n)          |
// | 空间       | O(n) 栈+set  | O(n) 中间串     | O(n) 栈       |
// | 代码复杂度 | 中等          | 稍长            | 最简洁         |
// | 面试推荐   | ✓ 思路最清晰  | ✓ 展示对称思维   | ✓ 代码最短     |
//
// 面试建议：优先写解法3（最短最清晰），用解法2作为follow-up
// "不用栈怎么做"的回答。
//
// 【易错点】
//
// 1. 忘记处理栈中残余的'('
//    ✗ 只在遍历中标记了多余的')', 遍历后直接返回
//    ✓ 遍历结束后必须把栈中所有残留索引也标记为删除
//    这是最高频的bug！
//
// 2. 两遍扫描法第二遍方向搞反
//    ✗ 两遍都正向扫描, 第二遍用openCount来决定删'('
//      → 会贪心地删前面能匹配的'(', 导致结果不对
//      例如 "(a(b)" 会错误删除第一个'('变成"a(b)"
//      而不是删第二个'('变成"(ab)"（虽然都合法但删的不是多余的那个）
//    ✓ 第二遍必须反向扫描
//
// 3. s[i] = '' 试图"删除"字符
//    ✗ C++中 char 不能设为空字符串来"删除"
//    ✓ 用'*'标记后再过滤, 或用erase(但erase是O(n)每次调用)
//
// 4. 用 string.erase() 在循环中逐个删除
//    ✗ for(int i=0; i<s.size(); i++) if(需删除) s.erase(i);
//      → 删除后索引移位, 且每次erase是O(n), 整体O(n²)
//    ✓ 先标记, 最后统一构建新字符串
//
// 【面试追问】
//
// Q1: 你怎么证明删除数量是最少的？
// → 栈匹配贪心地把所有能配对的都配对了，只有真正无法配对的才被
//   标记删除。每个被删的括号都是因为找不到配对方，不删就必然无效。
//
// Q2: 如果要返回所有可能的合法字符串怎么办？（→ LeetCode 301）
// → 变成 BFS/回溯问题。先用本题方法确定最少删除数量k，
//   然后 BFS 逐层搜索：每层尝试删一个括号，第一层出现有效结果
//   的就是所有答案。需要用 set 去重避免重复字符串。
//
// Q3: 字符串非常长且内存敏感，能否避免创建中间字符串？
// → 用解法3原地标记，再用 erase-remove 惯用法一步完成：
//   s.erase(remove(s.begin(), s.end(), '*'), s.end());
//   这样全程在原字符串上操作，不创建额外的中间结果。
// ============================================================
