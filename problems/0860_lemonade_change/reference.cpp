/*
 * LeetCode 860: 柠檬水找零 (Lemonade Change)
 *
 * 【题目本质】
 * 模拟找零过程：只需跟踪 5 元和 10 元钞票的数量，
 * 对 20 元找零时贪心地优先使用 10+5 而非 5+5+5。
 *
 * 【解法总览】
 * 解法1: 贪心模拟 — O(n) / O(1) — 唯一正解，面试必须写出
 *
 * 本题是 Easy 级贪心题，只有一种核心思路，
 * 重点在于理解贪心策略的正确性。
 */

// ============================================================
// 解法1: 贪心模拟 — 维护 5 元和 10 元计数器
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 每杯柠檬水 5 元。顾客付款只有三种情况:
//   付5元  → 不用找零，five++
//   付10元 → 找5元，必须 five > 0
//   付20元 → 找15元，两种方案:
//            方案A: 10 + 5 (优先选！因为 10 元只能在这个场景使用)
//            方案B: 5 + 5 + 5 (方案A不行时的备选)
//
// 贪心正确性: 5 元是"万能零钱"(找10和找20都要用)，
//            10 元是"专用零钱"(只能在找20时用)。
//            优先消耗专用的、保留万能的，不会更差。
//
// 模拟过程:
// bills = [5, 5, 5, 10, 20]
//
// 顾客1: 付5   → five=1, ten=0  (收下)
// 顾客2: 付5   → five=2, ten=0  (收下)
// 顾客3: 付5   → five=3, ten=0  (收下)
// 顾客4: 付10  → 找5元  → five=2, ten=1
// 顾客5: 付20  → 找15元 → 用10+5 → five=1, ten=0  ✓
//
// bills = [5, 5, 10, 10, 20]
//
// 顾客1: 付5   → five=1, ten=0
// 顾客2: 付5   → five=2, ten=0
// 顾客3: 付10  → 找5元  → five=1, ten=1
// 顾客4: 付10  → 找5元  → five=0, ten=2
// 顾客5: 付20  → 找15元 → 想用10+5但five=0 → 想用5+5+5但five=0 → false ✗
// ============================================================
class Solution1 {
public:
    bool lemonadeChange(vector<int>& bills) {
        int five = 0, ten = 0;
        // 不需要跟踪 twenty，因为 20 元永远不会被用来找零
        // (最多只需要找 15 元，而 20 > 15)
        
        for (int bill : bills) {
            if (bill == 5) {
                // 付5元：正好，直接收下
                five++;
            } 
            else if (bill == 10) {
                // 付10元：必须找一张5元
                if (five == 0) return false;
                five--;
                ten++;  // 别忘了收下这张10元！
            } 
            else {
                // bill == 20：找15元
                // 贪心：优先用 10+5（保留更灵活的 5 元）
                if (ten > 0 && five > 0) {
                    // 方案A：10 + 5 = 15 ✓
                    ten--;
                    five--;
                } else if (five >= 3) {
                    // 方案B：5 + 5 + 5 = 15 ✓
                    five -= 3;
                } else {
                    // 无法找零
                    return false;
                }
                // 收到的 20 元不用记录
            }
        }
        
        return true;
    }
};

