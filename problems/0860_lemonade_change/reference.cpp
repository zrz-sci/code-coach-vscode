// 【解法对比】
// 本题只有一种核心思路（贪心模拟），没有暴力 vs 优化的递进。
// 但贪心策略的正确性论证是面试的考察重点:
//   - 10 元钞票只能在 20 元找零时使用（专用）
//   - 5 元钞票在 10 元和 20 元找零时都需要（通用）
//   - 优先消耗专用资源、保留通用资源 → 交换论证可证最优
//
// 【易错点】
// 1. 付10元时忘了 ten++ — 只写了 five-- 导致 10 元钞票丢失
//    ✗ if (bill == 10) { five--; }
//    ✓ if (bill == 10) { five--; ten++; }
//
// 2. 20元找零的条件漏检 five:
//    ✗ if (ten > 0) { ten--; five--; }  // five 可能是 0！
//    ✓ if (ten > 0 && five > 0) { ten--; five--; }
//
// 3. 贪心顺序搞反:
//    ✗ 先尝试 5+5+5，再尝试 10+5 → 过度消耗 5 元钞票
//    ✓ 先尝试 10+5，再尝试 5+5+5
//
// 4. 多余跟踪 20 元:
//    ✗ 用 twenty 变量计数 → 浪费空间且没用
//    ✓ 20 元找零永远用不到，无需记录
//
// 【面试追问】
