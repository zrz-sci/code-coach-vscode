/*
 * LeetCode 150: 逆波兰表达式求值 (Evaluate Reverse Polish Notation)
 *
 * 【题目本质】
 * 给定后缀表达式的 token 序列，用栈模拟求值。
 * 核心操作：遇数字入栈，遇运算符弹两个操作数计算后压回。
 *
 * 【解法总览】
 * 解法1: 栈模拟(经典)     — O(n) / O(n)  — 面试首选 ⭐
 * 解法2: 递归(逆向解析)    — O(n) / O(n)  — 表达式树视角，加分项
 * 解法3: 原地数组模拟栈    — O(n) / O(1)  — 空间优化，Follow-up
 */

// ============================================================
// 解法1: 栈模拟 — 逆波兰表达式的标准求值方式
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 逆波兰表达式的定义本身就在告诉你怎么用栈求值：
//   - 遇到数字 → 入栈
//   - 遇到运算符 → 弹出栈顶两个数，计算，结果压回栈
// 遍历完后栈中唯一的元素就是答案。
//
// 为什么栈能正确求值？因为后缀表达式中，运算符紧跟在它的
// 两个操作数后面，而栈的后进先出特性恰好保证了"最近的两个
// 操作数"就是栈顶的两个元素。
//
// 示例 ["4","13","5","/","+"] 栈变化过程:
//
//  Token:  "4"    "13"    "5"     "/"         "+"
//                  ┌──┐
//                  │ 5│
//          ┌──┐    ├──┤    弹5,13            弹2,4
//  ┌──┐    │13│    │13│    13/5=2    ┌──┐    4+2=6    ┌──┐
//  │ 4│    ├──┤    ├──┤    压入2     │ 2│    压入6     │ 6│
//  └──┘    │ 4│    │ 4│              ├──┤              └──┘
//          └──┘    └──┘              │ 4│
//                                    └──┘
//  栈:     [4]   [4,13]  [4,13,5]  [4,2]              [6] ← 答案
// ============================================================
class Solution1 {
public:
    int evalRPN(vector<string>& tokens) {
        stack<int> stk;
        
        for (const string& token : tokens) {
            if (token == "+" || token == "-" || token == "*" || token == "/") {
                // 先弹出的是右操作数，后弹出的是左操作数
                // 为什么？因为左操作数先入栈，右操作数后入栈，后进先出
                int right = stk.top(); stk.pop();
                int left  = stk.top(); stk.pop();
                
                if      (token == "+") stk.push(left + right);
                else if (token == "-") stk.push(left - right);
                else if (token == "*") stk.push(left * right);
                else                   stk.push(left / right);
                // C++ 整数除法默认向零截断，符合题意
            } else {
                // stoi 自动处理负数字符串如 "-11"
                stk.push(stoi(token));
            }
        }
        
        // 合法的逆波兰表达式保证最终栈里恰好剩一个元素
        return stk.top();
    }
};

// ============================================================
// 解法2: 递归（逆向解析表达式树）
// 时间: O(n)  空间: O(n)（递归调用栈深度）
//
// 【思路】
// 换一个视角：后缀表达式可以看作一棵表达式树的后序遍历结果。
// 最后一个 token 是树的根（一定是运算符，除非只有一个数字）。
//
// 从右往左扫描 tokens：
//   - 遇到运算符 → 它是某棵子树的根，递归解析右子树、再解析左子树
//   - 遇到数字 → 叶子节点，直接返回
//
// 表达式树示例 ["4","13","5","/","+"]:
//
//         +
//        / \
//       4   /
//          / \
//         13  5
//
// 从右往左: "+" → 根
//   右子树: "/" → 根
//     右子树: "5" → 叶子 = 5
//     左子树: "13" → 叶子 = 13
//     计算: 13 / 5 = 2
//   左子树: "4" → 叶子 = 4
//   计算: 4 + 2 = 6
// ============================================================
class Solution2 {
public:
    int evalRPN(vector<string>& tokens) {
        // 从最后一个 token 开始逆向解析
        int idx = tokens.size() - 1;
        return helper(tokens, idx);
    }
    
private:
    int helper(vector<string>& tokens, int& idx) {
        // idx 必须是引用：递归过程中各层共享同一个索引
        const string& token = tokens[idx--];
        
        // 基准情况：数字（叶子节点）
        if (token != "+" && token != "-" && token != "*" && token != "/") {
            return stoi(token);
        }
        
        // 递归情况：运算符（内部节点）
        // 为什么先求 right 再求 left？
        // 因为从右往左扫描，紧挨运算符的是右子表达式的最后一个 token
        int right = helper(tokens, idx);
        int left  = helper(tokens, idx);
        
        if      (token == "+") return left + right;
        else if (token == "-") return left - right;
        else if (token == "*") return left * right;
        else                   return left / right;
    }
};

// ============================================================
// 解法3: 原地数组模拟栈 — O(n) / O(1) 额外空间
// 时间: O(n)  空间: O(1)（复用 tokens 数组，不开额外栈）
//
// 【思路】
// 面试 Follow-up: 能否不用额外 O(n) 空间？
//
// 观察：我们可以用 tokens 数组本身来充当栈。
// 维护一个 top 指针表示栈顶位置：
//   - 遇到数字 → tokens[top++] = 该数字（实际用整数数组更方便）
//   - 遇到运算符 → 从 top-2 和 top-1 取操作数，结果存到 top-2，top--
//
// 为什么可行？因为运算符消耗两个元素、产生一个结果，
// 栈的使用空间一定 <= 已遍历过的 tokens 位置。
//
// 注意：这里用一个 int 数组来复用空间（而非直接修改 string 数组），
// 因为存储效率更好。实际上我们用 tokens 的索引空间就够了。
// ============================================================
class Solution3 {
public:
    int evalRPN(vector<string>& tokens) {
        // 用一个数组模拟栈，大小不超过 (n+1)/2（操作数最多这么多）
        // 但如果题目允许修改输入，可以直接复用 tokens
        vector<int> stk(tokens.size());
        int top = 0; // 栈顶指针
        
        for (const string& token : tokens) {
            if (token == "+" || token == "-" || token == "*" || token == "/") {
                int right = stk[--top];
                int left  = stk[--top];
                if      (token == "+") stk[top++] = left + right;
                else if (token == "-") stk[top++] = left - right;
                else if (token == "*") stk[top++] = left * right;
                else                   stk[top++] = left / right;
            } else {
                stk[top++] = stoi(token);
            }
        }
        
        return stk[0];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间 | 空间 | 特点                           |
// |-----------|------|------|-------------------------------|
// | 栈模拟     | O(n) | O(n) | 最直观，和RPN定义完全一致 ⭐    |
// | 递归解析   | O(n) | O(n) | 表达式树视角，展示深度理解       |
// | 数组模拟栈 | O(n) | O(1) | 空间优化，Follow-up 追问        |
//
// 面试中写解法1即可。解法2展示对表达式树的理解。
// 解法3是 Follow-up "能否减少空间开销"的回答。
//
// 【易错点】
//
// 1. 操作数弹出顺序搞反
//    ✗ int left = stk.top(); stk.pop();
//      int right = stk.top(); stk.pop();
//    ✓ int right = stk.top(); stk.pop();  // 先弹出的是右操作数
//      int left  = stk.top(); stk.pop();  // 后弹出的是左操作数
//    对 "+" 和 "*" 无影响（交换律），但对 "-" 和 "/" 致命！
//    例如 ["6","2","-"] 应该是 6-2=4，搞反就变成 2-6=-4
//
// 2. 负数被误判为运算符
//    ✗ if (token[0] == '-') → 认为是减号运算符
//       但 "-11" 也以 '-' 开头！
//    ✓ 用 token == "-" 判断（运算符一定是长度为1的字符串）
//       或者用 token.size() == 1 && !isdigit(token[0]) 判断
//
// 3. 递归解法中 idx 忘记传引用
//    ✗ int helper(vector<string>& tokens, int idx) → 各层独立的 idx
//    ✓ int helper(vector<string>& tokens, int& idx) → 共享同一个索引
//    不传引用会导致每次递归回来 idx 没变化，重复解析相同 token
//
// 【面试追问】
//
// Q1(基础理解): 为什么逆波兰表达式不需要括号？
//    → 运算符的位置已经隐含了优先级和结合性。在后缀表达式中，
//      运算符出现的顺序就是执行顺序，不会有歧义。
//
// Q2(扩展): 如何把中缀表达式转成逆波兰表达式？
//    → 调度场算法(Shunting Yard)：用输出队列+运算符栈。
//      数字直接输出，运算符根据优先级决定是否弹出栈内运算符。
//      左括号入栈，遇右括号弹出到左括号。
//      这是 LeetCode 224/227 基本计算器系列的核心。
//
// Q3(变体): 如果要支持一元运算符(如取负)怎么办？
//    → 可以在预处理阶段把一元负号替换为特殊 token（如 "~"），
//      遇到 "~" 时只弹一个操作数取负。或者用 "0" 和 "-" 两个
//      token 代替一元负号。
// ============================================================
