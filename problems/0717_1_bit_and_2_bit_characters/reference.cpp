// 717. 1-bit and 2-bit Characters
// 难度: Easy
// 标签: Array
//
// 思路: 贪心线性扫描 -- 从左到右解码
// 遇到1跳2步(2比特字符)，遇到0跳1步(1比特字符)
// 如果指针最终恰好停在最后一位(n-1)，说明最后字符是1比特
//
// 时间复杂度: O(n)
// 空间复杂度: O(1)

// ============================================================
// 解法一: 贪心线性扫描（推荐面试解法）
// ============================================================
class Solution {
public:
    bool isOneBitCharacter(vector<int>& bits) {
        int n = bits.size();
        int i = 0;

        // 模拟解码过程，但不处理最后一位
        while (i < n - 1) {
            if (bits[i] == 1) {
                // 2比特字符 (10 或 11)，跳过2位
                i += 2;
            } else {
                // 1比特字符 (0)，跳过1位
                i += 1;
            }
        }

        // 如果 i 恰好停在最后一位，说明最后的 0 是独立的 1 比特字符
        // 如果 i == n，说明最后的 0 被前面的 1 "吃掉"了（成为 10 的一部分）
        return i == n - 1;
    }
};

// ============================================================
// 解法二: 更简洁的写法（利用 bits[i] 直接作为步长偏移）
// ============================================================
class Solution_V2 {
public:
    bool isOneBitCharacter(vector<int>& bits) {
        int n = bits.size();
        int i = 0;

        while (i < n - 1) {
            // bits[i] == 0 => i += 1 (0 + 1)
            // bits[i] == 1 => i += 2 (1 + 1)
            i += bits[i] + 1;
        }

        return i == n - 1;
    }
};

// ============================================================
// 解法三: 末尾连续 1 计数（从右向左）
// ============================================================
// 只关注末尾 0 前面有多少个连续的 1
// 偶数个 1 => 两两配对，末尾 0 独立 => true
// 奇数个 1 => 最后一个 1 和末尾 0 组成 10 => false
class Solution_V3 {
public:
    bool isOneBitCharacter(vector<int>& bits) {
        int n = bits.size();
        int consecutiveOnes = 0;

        // 从倒数第二位向左数连续的 1
        for (int i = n - 2; i >= 0 && bits[i] == 1; i--) {
            consecutiveOnes++;
        }

        // 偶数个连续 1 => true, 奇数个 => false
        return consecutiveOnes % 2 == 0;
    }
};

// ============================================================
// 解法四: 递归解法（正确但效率不是最优）
// ============================================================
// 展示递归思路: 从位置0开始解码到末尾
class Solution_V4 {
public:
    bool isOneBitCharacter(vector<int>& bits) {
        return decode(bits, 0);
    }

private:
    bool decode(vector<int>& bits, int i) {
        int n = bits.size();

        // 恰好到达最后一位，且最后一位是 0
        if (i == n - 1) return true;

        // 越过末尾，说明最后的 0 是 2 比特字符的一部分
        if (i >= n) return false;

        if (bits[i] == 0) {
            // 1比特字符，跳1步
            return decode(bits, i + 1);
        } else {
            // 2比特字符，跳2步
            return decode(bits, i + 2);
        }
    }
};

// ============================================================
// 解法五: 动态规划视角（展示DP思路，实际过度设计）
// ============================================================
// 等价于从右侧数连续1的个数，判断奇偶性
// 由于编码是前缀码（解码唯一），DP退化为线性扫描
class Solution_V5 {
public:
    bool isOneBitCharacter(vector<int>& bits) {
        int n = bits.size();

        // 从最后一位往前看，数连续的 1
        int i = n - 2;
        int count = 0;
        while (i >= 0 && bits[i] == 1) {
            count++;
            i--;
        }
        return count % 2 == 0;
    }
};

// ============================================================
// 关键点总结:
// 1. 编码系统是前缀码，解码唯一确定：1开头=2比特, 0=1比特
// 2. 解法一: 最直观，从左到右模拟解码，看指针最终位置
// 3. 解法二: 利用 bits[i]+1 作为步长，代码最简洁
// 4. 解法三: 数学洞察——末尾连续1的奇偶性决定答案
// 5. 循环条件必须是 i < n-1，不处理最后一位
// 6. 面试中推荐解法一/二（直观），解法三（聪明）作为追问
// ============================================================
