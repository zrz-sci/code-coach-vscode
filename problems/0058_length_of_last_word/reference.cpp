// 【解法对比】
//
// | 解法         | 时间          | 空间  | 优势                   | 劣势                     |
// |-------------|--------------|-------|----------------------|-------------------------|
// | 反向扫描     | O(n),最优O(k) | O(1) | 最快，可提前终止          | 无                       |
// | 正向遍历记录  | O(n)         | O(1) | 不依赖方向              | 必须扫全，逻辑稍复杂        |
// | stringstream | O(n)         | O(n) | 代码简洁               | 额外空间，面试通常不接受     |
//
// 面试选择: 直接写反向扫描（解法1），简洁且展示了"从目标出发"的思维。
//
// ============================================================
// 【易错点】
//
// 1. 忘记跳过尾部空格:
//    ✗ 直接从末尾数非空格字符 → "Hello World  " 返回 0
//    ✓ Phase 1 先跳过尾部空格
//
// 2. 循环越界:
//    ✗ while (s[i] == ' ') i--;  → "hello" Phase 2 数完 i=-1，
//      如果还有代码访问 s[i] 就越界
//    ✓ while (i >= 0 && s[i] == ' ') i--;
//
// 3. 正向遍历法尾部空格:
//    ✗ 遇到空格直接 count=0，最终返回 count → 尾部有空格时返回 0
//    ✓ 用 lastLen 在空格前保存上一个完整单词长度
//
// 4. off-by-one (下标差算长度):
//    如果用 end 和 start 标记单词位置:
//    ✗ end - start + 1 (如果 start 指向空格位置) → 多算了一个
//    ✓ 画图确认 start 到底指向空格还是单词首字母
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 字符串非常长但最后一个单词很短，怎么优化？
//     反向扫描天然 O(k)，k = 尾部空格 + 最后一个单词长度。
//     正向遍历必须 O(n)，劣势明显。
//
// Q2: 如果要返回最后一个单词本身？
//     反向扫描记录 end（跳过空格后的位置）和 start（遇到空格时 i+1）。
//     然后 s.substr(start, end - start + 1)。
//
// Q3: 如果可能有制表符、换行符等多种空白字符？
//     把 s[i] == ' ' 改为 isspace(s[i])，核心算法不变。
//
// Q4: 如果要返回所有单词的长度数组？
//     正向遍历：维护 count，遇到空格时 count>0 就 push 到数组并重置。
//     遍历结束后 count>0 再 push 一次。
