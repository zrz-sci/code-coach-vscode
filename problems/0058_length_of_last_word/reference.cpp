/*
 * LeetCode 58: Length of Last Word (最后一个单词的长度)
 *
 * 【题目本质】
 * 给定一个包含单词和空格的字符串，返回最后一个单词的长度。
 * 核心难点：尾部可能有空格，需要先跳过再计数。
 *
 * 【解法总览】
 * 解法1: 反向扫描（双阶段）   — O(n) / O(1)  — 面试首选，最简洁
 * 解法2: 正向遍历记录         — O(n) / O(1)  — 备选，逻辑稍复杂
 * 解法3: 库函数(stringstream)  — O(n) / O(n)  — 了解即可
 */

// ============================================================
// 解法1: 反向扫描（双阶段） — 面试首选 ⭐
// 时间: O(n) 最优 O(k)   空间: O(1)
//
// 【思路】
// 既然只关心最后一个单词，就从字符串末尾开始扫描。
// 分两步：
//   Phase 1: 跳过尾部空格
//   Phase 2: 计数最后一个单词的字符数
//
// 为什么这样分？
//   字符串可能以空格结尾，如 "Hello World  "。
//   如果不先跳过尾部空格，Phase 2 一开始就遇到空格，直接返回 0。
//
// 示例: s = "   fly me   to   the moon  "
//
//   Phase 1: i 从 26 开始
//   s[26]=' ', s[25]=' ' → 跳过
//   i 停在 24 (字母 'n')
//
//   Phase 2: 从 i=24 开始计数
//   s[24]='n' count=1
//   s[23]='o' count=2
//   s[22]='o' count=3
//   s[21]='m' count=4
//   s[20]=' ' → 停止
//
//   返回 count = 4 ✓ (最后一个单词 "moon")
//
// 为什么最优可以 O(k)？
//   k = 尾部空格数 + 最后一个单词长度。
//   如果字符串很长但最后一个单词很短，我们只需要看末尾几个字符。
//   正向遍历必须看完整个字符串，反向扫描可以提前结束。
// ============================================================
class Solution1 {
public:
    int lengthOfLastWord(string s) {
        int i = s.size() - 1;

        // Phase 1: 跳过尾部空格
        // 条件 i >= 0 防止字符串全是一个单词（无空格）时越界
        while (i >= 0 && s[i] == ' ') {
            i--;
        }

        // Phase 2: 计数最后一个单词的字母
        // 到这里 s[i] 一定是字母（题目保证至少一个单词）
        int count = 0;
        while (i >= 0 && s[i] != ' ') {
            count++;
            i--;
        }

        return count;
    }
};

// ============================================================
// 解法2: 正向遍历记录
// 时间: O(n)   空间: O(1)
//
// 【思路】
// 从头到尾扫描，维护"当前单词长度" count。
// 遇到字母 → count++
// 遇到空格 → 如果 count > 0，保存到 lastLen，然后 count = 0
//
// 最终：
//   如果字符串不以空格结尾 → count 就是最后一个单词长度
//   如果以空格结尾 → count 被重置为 0，但 lastLen 记住了最后一个单词
//
// 示例: s = "Hello World  "
//   H→1, e→2, l→3, l→4, o→5,
//   ' '→ lastLen=5, count=0,
//   W→1, o→2, r→3, l→4, d→5,
//   ' '→ lastLen=5, count=0,
//   ' '→ lastLen=5, count=0
//   返回 count>0 ? count : lastLen → 0>0? 否 → 返回 5 ✓
//
// 陷阱：
//   如果只维护一个 count，遇到空格直接 count=0，
//   那 "Hello World  " 最终 count=0，返回 0 是错的！
//   所以需要 lastLen 在遇到空格前保存上一个完整单词的长度。
// ============================================================
class Solution2 {
public:
    int lengthOfLastWord(string s) {
        int count = 0;
        int lastLen = 0;

        for (char c : s) {
            if (c != ' ') {
                count++;
            } else {
                // 只有当 count > 0 时才更新 lastLen
                // 连续空格时 count==0，不应该覆盖 lastLen
                if (count > 0) {
                    lastLen = count;
                }
                count = 0;
            }
        }

        // 字符串不以空格结尾 → count 是答案
        // 字符串以空格结尾 → lastLen 是答案
        return count > 0 ? count : lastLen;
    }
};

// ============================================================
// 解法3: 库函数法（stringstream 自动分词）
// 时间: O(n)   空间: O(n)
//
// 【思路】
// 利用 istringstream 的 >> 运算符自动按空格分词。
// 不断读取单词，最后一次读到的 word 就是最后一个单词。
//
// 示例: s = "   fly me   to   the moon  "
//   iss >> word: "fly" → "me" → "to" → "the" → "moon"
//   循环结束，word = "moon"，返回 word.size() = 4 ✓
//
// 优点：代码极简洁。
// 缺点：
//   1. 需要 O(n) 额外空间（创建流和存储字符串）
//   2. 必须遍历整个字符串（无法提前终止）
//   3. 面试中面试官通常会要求手写，不接受纯库函数解
// ============================================================
class Solution3 {
public:
    int lengthOfLastWord(string s) {
        istringstream iss(s);
        string word;
        // >> 自动跳过空格，逐个读取单词
        while (iss >> word) {
            // 不断读取，最终 word 就是最后一个单词
        }
        return word.size();
    }
};

