// ============================================================
// LeetCode 845: Longest Mountain in Array (数组中的最长山脉)
//
// 【解法1】枚举山峰 + 双向扩展 — O(n) / O(1)
//
// 找每个山峰 (比左右邻居都严格大), 向两侧扩展
// 山脉长度 = right - left + 1
// ============================================================

/*
 * 枚举山峰示意 (arr = [2, 1, 4, 7, 3, 2, 5]):
 *
 * 下标:  0  1  2  3  4  5  6
 * 值:    2  1  4  7  3  2  5
 *                 ★
 *        i=3 是山峰 (4<7 且 7>3)
 *        左扩展: 1 < 4 < 7 → left=1
 *        右扩展: 7 > 3 > 2 → right=5
 *        山脉长度 = 5-1+1 = 5
 *        山脉: [1, 4, 7, 3, 2]
 */

class Solution {
public:
    int longestMountain(vector<int>& arr) {
        int n = arr.size(), ans = 0;

        for (int i = 1; i < n - 1; i++) {
            // 检查 i 是否是山峰: 比左右邻居都严格大
            if (arr[i] > arr[i - 1] && arr[i] > arr[i + 1]) {
                int left = i - 1, right = i + 1;

                // 向左扩展上坡 (严格递增)
                while (left > 0 && arr[left - 1] < arr[left])
                    left--;

                // 向右扩展下坡 (严格递减)
                while (right < n - 1 && arr[right + 1] < arr[right])
                    right++;

                ans = max(ans, right - left + 1);
            }
        }
        return ans;
    }
};


// ============================================================
// 【解法2】一次遍历状态机 — O(n) / O(1)  [Follow-up 最优]
//
// 用 up/down 计数器追踪上升和下降阶段
// 状态转换:
//   上升 (arr[i]>arr[i-1]): 如果之前在下降则重置; 否则 up++
//   下降 (arr[i]<arr[i-1]): 如果有上坡则 down++
//   平地 (arr[i]==arr[i-1]): 全部重置
// 当 up>0 && down>0 时更新答案 = up+down+1
// ============================================================

/*
 * 状态机遍历过程 (arr = [2, 1, 4, 7, 3, 2, 5]):
 *
 * i=1: arr[1]=1 < arr[0]=2 → down? 但 up==0, 无效山脉
 *      up=0, down=0 (纯下坡无法形成山脉)
 *
 * i=2: arr[2]=4 > arr[1]=1 → up=1, down=0
 * i=3: arr[3]=7 > arr[2]=4 → up=2, down=0
 * i=4: arr[4]=3 < arr[3]=7 → down=1, up=2
 *      up>0 && down>0 → 山脉长度 = 2+1+1 = 4
 * i=5: arr[5]=2 < arr[4]=3 → down=2, up=2
 *      up>0 && down>0 → 山脉长度 = 2+2+1 = 5 ← 最优!
 * i=6: arr[6]=5 > arr[5]=2 → down>0所以重置, up=1, down=0
 *
 * 答案: 5
 */

class Solution_StateMachine {
public:
    int longestMountain(vector<int>& arr) {
        int n = arr.size(), ans = 0;
        int up = 0, down = 0;

        for (int i = 1; i < n; i++) {
            // 需要重置的情况:
            // 1. 下降后又上升 → 新山脉开始
            // 2. 平地 → 打断一切
            if ((down > 0 && arr[i] > arr[i - 1]) || arr[i] == arr[i - 1]) {
                up = 0;
                down = 0;
            }

            if (arr[i] > arr[i - 1]) up++;      // 上坡
            if (arr[i] < arr[i - 1]) down++;     // 下坡

            // 有上坡且有下坡 → 有效山脉
            if (up > 0 && down > 0) {
                ans = max(ans, up + down + 1);
            }
        }
        return ans;
    }
};


// ============================================================
// 【解法3】DP 预处理 — O(n) / O(n)
//
// inc[i] = 以 i 结尾的连续严格上升长度
// dec[i] = 以 i 开头的连续严格下降长度
// i 是山峰 → inc[i]>=2 && dec[i]>=2
// 山脉长度 = inc[i] + dec[i] - 1 (山峰被计算了两次)
// ============================================================

/*
 * DP 数组计算 (arr = [2, 1, 4, 7, 3, 2, 5]):
 *
 * 下标: 0  1  2  3  4  5  6
 * arr:  2  1  4  7  3  2  5
 * inc:  1  1  2  3  1  1  2  (从左到右, arr[i]>arr[i-1] 时 +1)
 * dec:  1  1  1  3  2  1  1  (从右到左, arr[i]>arr[i+1] 时 +1)
 *
 * i=3: inc[3]=3>=2, dec[3]=3>=2 → 山脉长度 = 3+3-1 = 5
 */

class Solution_DP {
public:
    int longestMountain(vector<int>& arr) {
        int n = arr.size();
        if (n < 3) return 0;

        vector<int> inc(n, 1), dec(n, 1);

        // inc[i]: 以 i 结尾的连续严格上升长度
        for (int i = 1; i < n; i++) {
            if (arr[i] > arr[i - 1])
                inc[i] = inc[i - 1] + 1;
        }

        // dec[i]: 以 i 开头的连续严格下降长度
        for (int i = n - 2; i >= 0; i--) {
            if (arr[i] > arr[i + 1])
                dec[i] = dec[i + 1] + 1;
        }

        // 合并: 找山峰 (inc[i]>=2 表示左侧有上坡, dec[i]>=2 表示右侧有下坡)
        int ans = 0;
        for (int i = 1; i < n - 1; i++) {
            if (inc[i] >= 2 && dec[i] >= 2) {
                ans = max(ans, inc[i] + dec[i] - 1);
            }
        }
        return ans;
    }
};


