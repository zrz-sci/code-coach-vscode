// ============================================================
//
// 解法1 枚举山峰:
//   时间: O(n) — 每个元素最多被左/右扩展各访问一次
//   空间: O(1) — 只用常数变量
//
// 解法2 状态机:
//   时间: O(n) — 严格一次遍历
//   空间: O(1) — 两个计数器
//
// 解法3 DP:
//   时间: O(n) — 三次遍历
//   空间: O(n) — inc[] 和 dec[] 数组


// ============================================================
// 总结
// ============================================================
//
// 【解法对比】
// ┌──────────────┬────────┬────────┬──────────────────────────┐
// │ 解法          │ 时间   │ 空间   │ 适用场景                 │
// ├──────────────┼────────┼────────┼──────────────────────────┤
// │ 1. 枚举山峰   │ O(n)   │ O(1)   │ 面试首选, 直觉清晰       │
// │ 2. 状态机     │ O(n)   │ O(1)   │ 严格单次遍历, follow-up  │
// │ 3. DP 预处理  │ O(n)   │ O(n)   │ 代码最短, 适合竞赛       │
// └──────────────┴────────┴────────┴──────────────────────────┘
//
// 【易错点】
// 1. 山脉最少 3 个元素 → 边界: i 从 1 到 n-2 才能做山峰
// 2. "严格"递增/递减 → arr[i]==arr[i-1] 不算上坡也不算下坡
// 3. 枚举山峰时 left/right 扩展可能越界 → while 中先检查边界
// 4. 状态机中: 下降后又上升必须重置 up/down, 否则把两座山连起来
// 5. DP 解法中 inc[i]+dec[i]-1 要减 1, 山峰被两端各算了一次
//
// 【面试追问】
// Q1: 如果要求返回最长山脉的起止下标, 怎么改?
//     → 枚举山峰时记录 bestLeft/bestRight; 状态机时记录山脉起点.
//
// Q2: 如果数组可以是环形的 (首尾相连), 怎么处理?
//     → 将数组复制一份拼接 arr+arr, 跑同样的算法,
//       但山脉长度上限为 n (不能绕一整圈), 且需去重同一座山.
//
// Q3: 如果要求在线 (streaming) 处理, 数据一个一个到来?
//     → 状态机解法天然支持: 维护 up/down 状态,
//       每来一个新元素做一次状态转换即可, O(1) per element.
