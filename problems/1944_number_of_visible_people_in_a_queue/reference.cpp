/*
 * LeetCode 1944: 队列中可以看到的人数 (Number of Visible People in a Queue)
 *
 * 【题目本质】
 * 对每个人，向右数"中间没有更高障碍"的可见人数。
 * 本质是单调栈的经典应用——从右往左维护递减栈，
 * 弹出的元素 = 能看到的矮个子，栈顶残留 = 能看到的第一个高个子。
 *
 * 【解法总览】
 * 解法1: 暴力枚举     — O(n²) / O(1)  — 最直觉，面试暖场
 * 解法2: 单调栈(从右往左) — O(n) / O(n) — 最优解，面试必须写出
 */

// ============================================================
// 解法1: 暴力枚举
// 时间: O(n²)  空间: O(1) (不算输出)
//
// 【思路】
// 对每个人 i，向右逐个检查 j。
// 维护 i+1..j-1 之间的最大高度 maxBetween。
// 可见条件: min(h[i], h[j]) > maxBetween
// 优化: 当 h[j] >= h[i] 时，后面的人全被 j 挡住，提前 break。
//
// 这是最自然的思路，瓶颈在于对每个 i 都要扫描右边所有人，
// 最坏情况（递减数组）每个人扫到末尾 → O(n²)。
// ============================================================
class Solution1 {
public:
    vector<int> canSeePersonsCount(vector<int>& heights) {
        int n = heights.size();
        vector<int> answer(n, 0);
        
        for (int i = 0; i < n; i++) {
            int maxBetween = 0;
            for (int j = i + 1; j < n; j++) {
                // 可见条件: 中间所有人都比 min(h[i], h[j]) 矮
                if (min(heights[i], heights[j]) > maxBetween) {
                    answer[i]++;
                }
                // 更新中间最大值
                maxBetween = max(maxBetween, heights[j]);
                // 遇到比 i 高的人 → 后面全被挡住，提前退出
                if (heights[j] >= heights[i]) break;
            }
        }
        
        return answer;
    }
};

// ============================================================
// 解法2: 单调栈（从右往左遍历）⭐ 面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法1的瓶颈: 每个人独立向右扫描，大量重复工作。
// 
// 关键观察: 从右往左处理时，栈维护"还有资格被左边的人看到"的高度。
// 栈是从底到顶严格递减的（单调递减栈）。
//
// 对于当前人 i (高度 h[i]):
//   1. 弹出栈中所有 < h[i] 的元素 → 这些人是 i 能看到的"矮个子"
//      为什么可见? 因为栈是递减的，弹出顺序从矮到高，它们之间没有更高的人遮挡
//      为什么要弹出? 因为 i 比它们高，i 会挡住它们，左边更远的人看不到它们了
//   2. 弹完后如果栈非空 → 栈顶是第一个 >= h[i] 的人，i 也能看到
//   3. 把 h[i] 压入栈
//
// 每个元素最多入栈1次、出栈1次 → 总操作 O(2n) = O(n)
//
// 【可视化: heights = [10, 6, 8, 5, 11, 9]】
//
//   索引:  0   1   2   3   4   5
//   高度: 10   6   8   5  11   9
//
//   i=5, h=9:  栈: [] → 弹出0个, 栈空           → ans[5]=0, push 9  → 栈:[9]
//   i=4, h=11: 栈: [9] → 弹出9(9<11)=1个, 栈空  → ans[4]=1, push 11 → 栈:[11]
//   i=3, h=5:  栈: [11] → 弹出0个, 栈非空(+1)   → ans[3]=1, push 5  → 栈:[11,5]
//   i=2, h=8:  栈: [11,5] → 弹出5(5<8)=1个, 栈非空(+1) → ans[2]=2, push 8 → 栈:[11,8]
//   i=1, h=6:  栈: [11,8] → 弹出0个, 栈非空(+1) → ans[1]=1, push 6  → 栈:[11,8,6]
//   i=0, h=10: 栈: [11,8,6] → 弹出6,8(2个), 栈非空(+1) → ans[0]=3, push 10 → 栈:[11,10]
//
//   结果: [3, 1, 2, 1, 1, 0] ✓
// ============================================================
class Solution2 {
public:
    vector<int> canSeePersonsCount(vector<int>& heights) {
        int n = heights.size();
        vector<int> answer(n, 0);
        stack<int> stk; // 存高度值，从底到顶严格递减
        
        for (int i = n - 1; i >= 0; i--) {
            int count = 0;
            
            // 弹出所有比当前人矮的 → 它们都是 i 能看到的
            // 为什么是可见的: 栈是递减的，弹出顺序从矮到高，构成递增序列
            // 它们之间没有更高的人遮挡（因为更高的人在栈的更底部还没弹出）
            while (!stk.empty() && stk.top() < heights[i]) {
                stk.pop();
                count++;
            }
            
            // 栈顶是第一个 >= h[i] 的人，i 也能看到这个人
            // 为什么? 刚才弹出的都比 h[i] 矮，不会挡住栈顶
            if (!stk.empty()) {
                count++;
            }
            
            answer[i] = count;
            
            // 把当前人压入栈，它会挡住刚才弹出的那些人
            stk.push(heights[i]);
        }
        
        return answer;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度     | 解法1 暴力     | 解法2 单调栈      |
// |----------|---------------|------------------|
// | 时间     | O(n²) 最坏    | O(n) 摊还        |
// | 空间     | O(1)          | O(n) 栈空间       |
// | 适用场景 | n ≤ 1000      | n ≤ 10^5         |
// | 面试     | 暖场展示理解   | 面试官期望的答案  |
//
// 单调栈的关键洞察:
// - 暴力解中，每个人向右扫描时做的"判断谁可见"的工作是重复的
// - 单调栈把右边的信息压缩成一个递减序列
// - 弹出操作同时完成了"计数可见"和"淘汰被遮挡者"两件事
//
// ============================================================
// 【易错点】
//
// 1. 忘记栈顶的更高者也是可见的:
//    ✗ answer[i] = count;  // 只算了弹出的矮个子
//    ✓ if (!stk.empty()) count++;  // 第一个更高的人也能看到!
//    原因: 弹出的是比 i 矮的人，但 i 还能望到右边第一个比自己高的"墙"
//
// 2. 遍历方向搞反:
//    ✗ for (int i = 0; i < n; i++)  // 从左往右
//    ✓ for (int i = n-1; i >= 0; i--)  // 从右往左
//    原因: 需要栈中已经存储了右边的信息才能计算当前人的答案
//
// 3. 弹出条件用 <= 还是 <:
//    本题高度互不相同，所以 < 和 <= 等价。
//    但如果扩展到高度可重复的变体:
//    ✗ stk.top() < heights[i]   // 相等的人没被弹出，多算了
//    ✓ stk.top() <= heights[i]  // 相等的人互相遮挡，应该弹出
//    （需根据题意中"严格矮"的定义决定）
//
// 4. 空栈时忘记 guard:
//    ✗ while (stk.top() < heights[i])  // stk为空时 UB!
//    ✓ while (!stk.empty() && stk.top() < heights[i])
//
// ============================================================
// 【面试追问】
//
// Q1: 暴力怎么做? 能剪枝吗?
// A1: 对每个i向右扫描，维护maxBetween判断可见性。
//     剪枝: 遇到h[j]>=h[i]就break。但最坏仍O(n²)(递减数组)。
//
// Q2: 单调栈为什么是O(n)? 不是有while循环嵌套在for里吗?
// A2: 摊还分析。每个元素最多push 1次、pop 1次。
//     所有while循环的pop操作总共≤n次。总操作2n = O(n)。
//
// Q3: 如果改成"每个人向左能看到几个人"，怎么改?
// A3: 从左往右遍历，维护同样的递减栈。逻辑完全对称:
//     弹出比自己矮的(能看到)，栈顶如果非空也能看到(+1)。
//
// Q4: 如果高度可以重复怎么办?
// A4: 需要根据"可见"定义处理相等情况。通常相同高度互相遮挡，
//     while条件改为 stk.top() <= heights[i]。
//     但要注意: 这会改变"栈顶+1"的语义——弹出的最后一个
//     可能和当前人等高，它是否可见需要单独判断。
//
// Q5: 能否同时算出每个人"向右看到的人"和"向左看到的人"?
// A5: 两次遍历，分别用从右往左和从左往右的单调栈。
//     总时间仍O(n)，空间O(n)。
// ============================================================
