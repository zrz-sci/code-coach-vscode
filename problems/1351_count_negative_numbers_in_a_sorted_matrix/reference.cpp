/*
 * LeetCode 1351: Count Negative Numbers in a Sorted Matrix
 * (统计有序矩阵中的负数)
 *
 * 【题目本质】
 * m x n 矩阵，每行每列都按非递增排列。统计负数个数。
 * 核心：利用行列双有序性，避免检查每个元素。
 *
 * 【解法总览】
 * 解法1: 暴力遍历        — O(m*n)     / O(1) — 最直觉，不利用排序
 * 解法2: 每行二分查找     — O(m*log n) / O(1) — 利用行有序
 * 解法3: 阶梯形(右上角)   — O(m+n)     / O(1) — 利用行+列双有序，最优
 */

// ============================================================
// 解法1: 暴力遍历 — 检查每个元素
// 时间: O(m*n)  空间: O(1)
//
// 【思路】
// 最朴素的想法：遍历矩阵中每个元素，如果 < 0 就 count++。
// 完全没利用排序信息，但代码极简，n<=100 时足够快。
//
// 示例: grid = [[4,3,2,-1],[3,2,1,-1],[1,1,-1,-2],[-1,-1,-2,-3]]
//   逐个检查: 4✓ 3✓ 2✓ -1✗ 3✓ 2✓ 1✓ -1✗ 1✓ 1✓ -1✗ -2✗ -1✗ -1✗ -2✗ -3✗
//   负数个数 = 8
//
// 瓶颈分析：
//   每一行的负数一定在右边连续的一段（因为非递增），
//   所以找到分界点就不需要逐个检查了 → 引出二分查找
// ============================================================
class Solution1 {
public:
    int countNegatives(vector<vector<int>>& grid) {
        int count = 0;
        for (auto& row : grid) {
            for (int val : row) {
                if (val < 0) count++;
            }
        }
        return count;
    }
};

// ============================================================
// 解法2: 每行二分查找 — 每行找第一个负数的位置
// 时间: O(m * log n)  空间: O(1)
//
// 【思路】
// 每行是非递增的（降序），负数一定在右边连续的一段。
// 对每行做二分查找，找到"第一个 < 0 的位置" pos，
// 那么该行的负数个数 = n - pos。
//
// 注意：这是降序数组的二分，不能直接用 lower_bound（它假设升序）。
// 需要自己写二分逻辑：
//   - row[mid] >= 0 → 非负，第一个负数在右边 → lo = mid + 1
//   - row[mid] <  0 → 负数，可能是第一个，也可能不是 → hi = mid
//   循环结束时 lo == hi == 第一个负数的位置（如果没有负数则 lo == n）
//
// 二分查找收缩过程图解:
//
// 行: [4, 3, 2, -1]     n = 4
//
// 轮次1: lo=0, hi=4
//         mid = 2, row[2]=2 >= 0 → lo = 3
//         [4, 3, 2, -1]
//                   ^mid
//          lo───────────→lo'
//
// 轮次2: lo=3, hi=4
//         mid = 3, row[3]=-1 < 0 → hi = 3
//
// 结束: lo=3, hi=3 → 第一个负数在 index 3
//       负数个数 = 4 - 3 = 1  ✓
//
// ---
//
// 行: [1, 1, -1, -2]    n = 4
//
// 轮次1: lo=0, hi=4
//         mid = 2, row[2]=-1 < 0 → hi = 2
//
// 轮次2: lo=0, hi=2
//         mid = 1, row[1]=1 >= 0 → lo = 2
//
// 结束: lo=2, hi=2 → 第一个负数在 index 2
//       负数个数 = 4 - 2 = 2  ✓
//
// ---
//
// 行: [-1, -1, -2, -3]  n = 4
//
// 轮次1: mid=2, -2 < 0 → hi = 2
// 轮次2: mid=1, -1 < 0 → hi = 1
// 轮次3: mid=0, -1 < 0 → hi = 0
//
// 结束: lo=0 → 负数个数 = 4 - 0 = 4  ✓
// ============================================================
class Solution2 {
public:
    int countNegatives(vector<vector<int>>& grid) {
        int count = 0;
        int n = grid[0].size();

        for (auto& row : grid) {
            // 二分找第一个 < 0 的位置
            // 搜索区间 [lo, hi)，lo 是答案候选
            int lo = 0, hi = n;
            while (lo < hi) {
                int mid = lo + (hi - lo) / 2;
                if (row[mid] >= 0) {
                    lo = mid + 1;  // 非负，跳过，去右半边找
                } else {
                    hi = mid;      // 负数，可能是第一个，收缩右边界
                }
            }
            // lo == 第一个负数的位置（如果没有负数则 lo == n）
            // 从 lo 到 n-1 都是负数
            count += n - lo;
        }
        return count;
    }
};

// ============================================================
// 解法3: 阶梯形遍历（从右上角出发） — 最优解 ⭐
// 时间: O(m + n)  空间: O(1)
//
// 【思路】
// 同时利用行和列的非递增性质。
//
// 核心观察：从右上角 (row=0, col=n-1) 出发：
//   - 如果 grid[row][col] < 0:
//     该列从 row 到 m-1 都 <= grid[row][col]（列非递增），
//     全是负数 → count += m - row，然后向左移 col--
//   - 如果 grid[row][col] >= 0:
//     该位置不是负数 → 向下移 row++
//
// 为什么是 O(m+n)？
//   每步要么 row+1（最多 m 次），要么 col-1（最多 n 次），
//   所以总步数 <= m + n。
//
// 矩阵示意:
//       col →  0    1    2    3
//   row↓   +----+----+----+----+
//     0    |  4 |  3 |  2 | -1 |  ← 从(0,3)开始
//          +----+----+----+----+
//     1    |  3 |  2 |  1 | -1 |
//          +----+----+----+----+
//     2    |  1 |  1 | -1 | -2 |
//          +----+----+----+----+
//     3    | -1 | -1 | -2 | -3 |
//          +----+----+----+----+
//
// 阶梯分界线：
//   >=0 区域和 <0 区域之间的分界线是阶梯形（单调不增）：
//     行0: 分界在 col=3  → 1个负数
//     行1: 分界在 col=3  → 1个负数
//     行2: 分界在 col=2  → 2个负数
//     行3: 分界在 col=0  → 4个负数
//
// 行走路线:
//   (0,3)=-1 < 0 → count += 4-0 = 4, col-- → (0,2)
//   (0,2)= 2 >=0 → row++ → (1,2)
//   (1,2)= 1 >=0 → row++ → (2,2)
//   (2,2)=-1 < 0 → count += 4-2 = 2, col-- → (2,1)
//   (2,1)= 1 >=0 → row++ → (3,1)
//   (3,1)=-1 < 0 → count += 4-3 = 1, col-- → (3,0)
//   (3,0)=-1 < 0 → count += 4-3 = 1, col-- → col=-1, 结束
//   总计: 4 + 2 + 1 + 1 = 8  ✓
// ============================================================
class Solution3 {
public:
    int countNegatives(vector<vector<int>>& grid) {
        int m = grid.size(), n = grid[0].size();
        int count = 0;
        int row = 0, col = n - 1;  // 从右上角出发

        while (row < m && col >= 0) {
            if (grid[row][col] < 0) {
                // 当前值是负数
                // 列非递增 → 从 row 到 m-1 这一列都是负数
                count += m - row;
                col--;  // 向左移，处理更多列
            } else {
                // 当前值 >= 0
                // 这一行中，col 右边的负数已被上面的列处理过
                row++;  // 向下移，在这一列找负数
            }
        }
        return count;
    }
};

// ============================================================
// 解法3 变体: 逐行扫描（col 不重置）
// 时间: O(m + n)  空间: O(1)
//
// 【思路】
// 等价于解法3，但用不同的循环结构：
// 逐行遍历，对每行找到分界点 col。关键：col 不在每行重置。
//
// 因为列也是非递增的，下一行的负数起始位置只会 <= 当前行的。
// 所以 col 全程只会从 n-1 减到 0，总减少次数 <= n。
// 外层 for 走 m 行 + col 减少 n 次 = O(m + n)。
//
// 直觉理解：
//   如果行2的分界在 col=2（即 col=2 开始负数），
//   那行3的分界只可能在 col<=2（因为列非递增，行3对应位置只会更小）。
//   所以 col 从 n-1 单调减小，不需要回退。
// ============================================================
class Solution3_v2 {
public:
    int countNegatives(vector<vector<int>>& grid) {
        int m = grid.size(), n = grid[0].size();
        int count = 0;
        int col = n - 1;  // 从最右列开始，全程不重置

        for (int row = 0; row < m; row++) {
            // 向左找到第一个 >= 0 的位置
            while (col >= 0 && grid[row][col] < 0) {
                col--;
            }
            // col+1 到 n-1 都是负数
            count += n - 1 - col;
        }
        return count;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法             | 时间         | 空间  | 利用有序性     |
// |-----------------|-------------|-------|--------------|
// | 暴力遍历         | O(m*n)      | O(1)  | 不利用         |
// | 每行二分查找      | O(m*log n)  | O(1)  | 行有序         |
// | 阶梯形(右上角)    | O(m+n)      | O(1)  | 行+列双有序    |
//
// 面试选择：先说暴力 → 二分展现搜索能力 → 阶梯形展现矩阵搜索能力。
//
// ============================================================
// 【易错点】
//
// 1. 二分的方向搞反:
//    ✗ if (row[mid] < 0) lo = mid + 1;  → 这是升序模板
//    ✓ if (row[mid] >= 0) lo = mid + 1; → 降序数组跳过非负部分
//
// 2. 阶梯形加错数量:
//    ✗ count += m;       → 不是整列都负
//    ✓ count += m - row; → 从当前行到底部
//
// 3. 阶梯形起点选错:
//    ✗ 从(0,0)或(m-1,n-1)出发 → 两方向同向，无法决策
//    ✓ 从(0,n-1)或(m-1,0)出发 → 两方向一增一减
//
// 4. 逐行扫描版本每行重置 col:
//    ✗ for (int row...) { int col = n-1; ... } → O(m*n)
//    ✓ int col = n-1; for (int row...) { ... } → O(m+n)
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么阶梯形是 O(m+n)？
//     每步 row+1 或 col-1，row 最多加 m 次，col 最多减 n 次，总 m+n。
//
// Q2: 如果矩阵是升序（非递减）排列呢？
//     负数在左上角区域。从左下角出发，调整比较和移动方向即可。
//
// Q3: 如果要统计零的个数？
//     两次二分：找"第一个<=0"和"第一个<0"的位置，差就是零的个数。
//     阶梯形不直接适用（零不在矩阵某一角）。
//
