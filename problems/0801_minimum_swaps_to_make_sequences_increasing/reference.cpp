/*
 * LeetCode 801: Minimum Swaps To Make Sequences Increasing (使序列递增的最小交换次数)
 *
 * 【题目本质】
 * 给定两个等长数组 nums1 和 nums2，每个位置可以选择交换 nums1[i] 和 nums2[i]，
 * 求使两个数组都严格递增所需的最小交换次数。
 * 核心：每个位置只有"换/不换"两种选择，合法性只和前一个位置的选择有关 → 状态机DP。
 *
 * 【解法总览】
 * 解法1: 状态DP（滚动变量） — O(n) / O(1) — 面试首选，空间最优
 * 解法2: 状态DP（数组版）   — O(n) / O(n) — 更直观，便于理解
 */

// ============================================================
// 解法1: 状态机DP（滚动变量） — 面试首选 ⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 定义两个状态：
//   noSwap: 当前位置不交换时，使 0..i 都合法的最小交换次数
//   swap:   当前位置交换时，使 0..i 都合法的最小交换次数
//
// 对于相邻位置 (i-1, i)，有两种可能使其合法：
//
// 条件1 (原始合法): nums1[i] > nums1[i-1] && nums2[i] > nums2[i-1]
//   含义：不需要交叉，原始顺序就满足递增。
//   转移：
//     - 都不换: noSwap[i] = noSwap[i-1]
//     - 都换(交换后等价于原始顺序): swap[i] = swap[i-1] + 1
//
// 条件2 (交叉合法): nums1[i] > nums2[i-1] && nums2[i] > nums1[i-1]
//   含义：如果一个位置换了另一个没换（或反之），交叉后也合法。
//   转移：
//     - 前面换了,当前不换: noSwap[i] = swap[i-1]
//     - 前面不换,当前换:   swap[i] = noSwap[i-1] + 1
//
// 注意：两个条件可能同时成立！此时两种转移都要考虑，取 min。
//
// 示例: nums1 = [1,3,5,4], nums2 = [1,2,3,7]
//
// i=0: noSwap=0, swap=1
//
// i=1: nums1[1]=3 > nums1[0]=1 ✓, nums2[1]=2 > nums2[0]=1 ✓ (条件1成立)
//      nums1[1]=3 > nums2[0]=1 ✓, nums2[1]=2 > nums1[0]=1 ✓ (条件2也成立)
//      noSwap = min(noSwap[0], swap[0]) = min(0, 1) = 0
//      swap   = min(swap[0]+1, noSwap[0]+1) = min(2, 1) = 1
//
// i=2: 类似分析... noSwap=0, swap=1
//
// i=3: nums1[3]=4 > nums1[2]=5 ✗ (条件1不成立)
//      nums1[3]=4 > nums2[2]=3 ✓, nums2[3]=7 > nums1[2]=5 ✓ (条件2成立)
//      noSwap = swap[2] = 1
//      swap   = noSwap[2]+1 = 1
//      答案: min(1, 1) = 1 ✓
// ============================================================
class Solution1 {
public:
    int minSwap(vector<int>& nums1, vector<int>& nums2) {
        int n = nums1.size();

        // 初始状态：位置0不换花费0次，换花费1次
        int prevNoSwap = 0, prevSwap = 1;

        for (int i = 1; i < n; i++) {
            // 初始化为不可达状态
            int curNoSwap = INT_MAX, curSwap = INT_MAX;

            // 条件1: 原始顺序合法
            // nums1[i] > nums1[i-1] && nums2[i] > nums2[i-1]
            if (nums1[i] > nums1[i-1] && nums2[i] > nums2[i-1]) {
                // 都不换: 继承前面不换的状态
                curNoSwap = min(curNoSwap, prevNoSwap);
                // 都换: 交换后仍保持原始顺序关系，继承前面换的状态+1
                curSwap = min(curSwap, prevSwap + 1);
            }

            // 条件2: 交叉后合法
            // nums1[i] > nums2[i-1] && nums2[i] > nums1[i-1]
            if (nums1[i] > nums2[i-1] && nums2[i] > nums1[i-1]) {
                // 前面换了当前不换: 交叉关系合法
                curNoSwap = min(curNoSwap, prevSwap);
                // 前面不换当前换: 交叉关系合法
                curSwap = min(curSwap, prevNoSwap + 1);
            }

            prevNoSwap = curNoSwap;
            prevSwap = curSwap;
        }

        return min(prevNoSwap, prevSwap);
    }
};

// ============================================================
// 解法2: 状态机DP（数组版） — 更直观
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 和解法1完全相同的逻辑，只是用数组存储所有位置的状态。
// 优点是更容易理解和调试，缺点是多了 O(n) 空间。
//
// 适合在面试中先用数组版讲清楚思路，再说"可以优化到 O(1) 空间
// 因为每个状态只依赖前一个位置"。
// ============================================================
class Solution2 {
public:
    int minSwap(vector<int>& nums1, vector<int>& nums2) {
        int n = nums1.size();

        // noSwap[i]: 位置 i 不交换时，0..i 都合法的最小交换次数
        // sw[i]:     位置 i 交换时，0..i 都合法的最小交换次数
        vector<int> noSwap(n, INT_MAX);
        vector<int> sw(n, INT_MAX);

        noSwap[0] = 0;  // 位置0不换: 0次
        sw[0] = 1;       // 位置0换: 1次

        for (int i = 1; i < n; i++) {
            // 条件1: 原始顺序合法
            if (nums1[i] > nums1[i-1] && nums2[i] > nums2[i-1]) {
                noSwap[i] = min(noSwap[i], noSwap[i-1]);
                sw[i] = min(sw[i], sw[i-1] + 1);
            }

            // 条件2: 交叉后合法（注意：两个条件可能同时成立）
            if (nums1[i] > nums2[i-1] && nums2[i] > nums1[i-1]) {
                noSwap[i] = min(noSwap[i], sw[i-1]);
                sw[i] = min(sw[i], noSwap[i-1] + 1);
            }
        }

        return min(noSwap[n-1], sw[n-1]);
    }
};

// ============================================================
// 【解法对比】
//
// | 解法          | 时间  | 空间  | 优势                       | 劣势           |
// |--------------|-------|-------|---------------------------|----------------|
// | 滚动变量DP    | O(n)  | O(1)  | 空间最优，代码简洁          | 不易调试中间状态 |
// | 数组版DP      | O(n)  | O(n)  | 直观，可以回溯所有中间状态   | 多 O(n) 空间    |
//
// 面试策略：先用数组版讲清楚状态定义和转移，然后指出空间可以优化到 O(1)。
//
// ============================================================
// 【易错点】
//
// 1. 两个条件用 else if 而非独立 if:
//    ✗ if (条件1) {...} else if (条件2) {...}
//      → 当两个条件同时成立时，漏掉了一半转移，可能得到错误的最小值
//    ✓ if (条件1) {...} if (条件2) {...}
//      → 独立判断，所有合法转移都考虑到
//
// 2. 交叉条件写反:
//    ✗ nums1[i] > nums1[i-1] && nums2[i] > nums1[i-1]
//      → 第二个比较对象应该是 nums1[i-1] 对 nums2[i]，不是 nums2[i] 对 nums1[i-1]
//    ✓ nums1[i] > nums2[i-1] && nums2[i] > nums1[i-1]
//      → 交叉比较：nums1[i] 对 nums2[i-1]，nums2[i] 对 nums1[i-1]
//
// 3. 滚动变量更新顺序问题:
//    ✗ prevNoSwap = curNoSwap; 在使用 prevNoSwap 之前就更新了
//      → 如果条件2中用到 prevNoSwap 但它已经被覆盖为 curNoSwap
//    ✓ 先算完 curNoSwap 和 curSwap，再一起更新 prev 值
//      → 由于 cur 是独立的新变量，不会有覆盖问题
//
// 4. 初始化 cur 值为 0 而非 INT_MAX:
//    ✗ int curNoSwap = 0, curSwap = 0;
//      → 不合法的转移（条件不成立时）也会被选中，因为 0 < 合法转移的值
//    ✓ int curNoSwap = INT_MAX, curSwap = INT_MAX;
//      → 只有通过满足条件的转移才能更新，保证结果正确
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 为什么状态只和前一个位置有关？
//     严格递增只要求 arr[i] > arr[i-1]。每对相邻元素独立满足
//     递增关系，就保证整个数组递增。所以决策只看 (i-1, i)。
//
// Q2: 如何证明题目保证有解？
//     题目说"测试用例保证有解"。条件是对于每个位置 i，
//     至少有一种合法的 (不换/换) 选择使得和前一个位置一致。
//     换句话说，至少条件1或条件2成立。
//
// Q3: 如果允许交换不同位置（如 nums1[i] 和 nums2[j]），会怎样？
//     问题会变成一个全局优化问题，不再具有子问题独立性。
//     可能需要回溯或更复杂的DP建模，甚至是 NP-hard。
//
