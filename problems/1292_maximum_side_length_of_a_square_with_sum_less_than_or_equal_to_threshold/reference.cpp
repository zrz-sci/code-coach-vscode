/*
 * LeetCode 1292: Maximum Side Length of a Square with Sum <= Threshold
 * (元素和小于等于阈值的正方形的最大边长)
 *
 * 【题目本质】
 * 在 m*n 矩阵中找元素和 <= threshold 的最大正方形，返回其边长。
 * 核心技巧：二维前缀和 O(1) 查询子矩阵和 + 枚举优化。
 *
 * 【解法总览】
 * 解法1: 前缀和 + 逐步增长 — O(m*n) / O(m*n)          — 最优
 * 解法2: 前缀和 + 二分搜索 — O(m*n*log min(m,n)) / O(m*n) — 经典
 * 解法3: 前缀和 + 暴力枚举 — O(m*n*min(m,n)) / O(m*n)   — 基础
 */

// ============================================================
// 解法1: 前缀和 + 逐步增长 — 最优解 ⭐
// 时间: O(m*n)  空间: O(m*n)
//
// 【二维前缀和原理】
//
// 建表公式:
//   pre[i+1][j+1] = mat[i][j] + pre[i][j+1] + pre[i+1][j] - pre[i][j]
//                   ^当前格       ^上方         ^左方         ^左上角(重叠)
//
// 含义: pre[i][j] = mat 中前 i 行、前 j 列的元素总和
//
// 查询公式 (左上角(r1,c1)到右下角(r2,c2)的子矩阵和):
//   sum = pre[r2+1][c2+1] - pre[r1][c2+1] - pre[r2+1][c1] + pre[r1][c1]
//         ^整个矩形          ^减上方          ^减左方          ^左上角被减两次加回
//
// 容斥示意:
//   ┌───────────┐
//   │ A  │  B   │      sum(目标) = (A+B+C+目标) - (A+B) - (A+C) + A
//   ├────┼──────┤                 = 目标
//   │ C  │ 目标 │
//   └────┴──────┘
//
// 【逐步增长优化】
//
// 关键观察: 全局最优 ans 单调不减。
// 对每个位置(i,j), 只需要检查 k = ans+1:
//   - 如果 k*k 正方形的和 <= threshold → ans = k
//   - 否则跳过 (更大的 k 只会让和更大)
//
// 为什么是 O(m*n)?
//   遍历所有 m*n 个位置，每个位置做 O(1) 工作(一次前缀和查询)。
//   ans 最多增长 min(m,n) 次，总额外工作 O(min(m,n))。
//   总计 O(m*n)。
//
// 示例: mat = [[1,1,3,2,4,3,2],
//              [1,1,3,2,4,3,2],
//              [1,1,3,2,4,3,2]], threshold = 4
//
//   (0,0): ans=0, k=1, sum=1 ≤ 4 → ans=1
//   (0,1): ans=1, k=2, 2x2 sum=4 ≤ 4 → ans=2
//   (0,2): ans=2, k=3, 3x3 sum=15 > 4 → 不变
//   ...后续都无法找到 3x3 满足条件
//   最终 ans = 2
// ============================================================
class Solution {
public:
    int maxSideLength(vector<vector<int>>& mat, int threshold) {
        int m = mat.size(), n = mat[0].size();

        // ---- Step 1: 建立二维前缀和 ----
        // pre 大小 (m+1) x (n+1)，第 0 行/列全为 0，处理边界
        vector<vector<int>> pre(m + 1, vector<int>(n + 1, 0));
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                // 容斥建表: 当前 = 本格 + 上 + 左 - 左上
                pre[i+1][j+1] = mat[i][j]
                              + pre[i][j+1]   // 上方
                              + pre[i+1][j]   // 左方
                              - pre[i][j];    // 左上角(被加了两次，减掉)
            }
        }

        // ---- Step 2: 逐步增长找最大边长 ----
        int ans = 0;
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                // 只尝试 ans+1——如果能成功，ans 就增大
                int k = ans + 1;

                // 边界检查: 以 (i,j) 为左上角的 k*k 正方形不越界
                if (i + k <= m && j + k <= n) {
                    // 容斥查询: (i,j) 到 (i+k-1, j+k-1) 的子矩阵和
                    int sum = pre[i+k][j+k]   // 整个矩形
                            - pre[i][j+k]     // 减上方
                            - pre[i+k][j]     // 减左方
                            + pre[i][j];      // 加回左上角
                    if (sum <= threshold) {
                        ans = k;
                    }
                }
            }
        }
        return ans;
    }
};

// ============================================================
// 解法2: 前缀和 + 二分搜索
// 时间: O(m*n*log(min(m,n)))  空间: O(m*n)
//
// 【思路】
// 对边长进行二分搜索: lo=0, hi=min(m,n)。
// 给定边长 mid，检查是否存在某个位置使得正方形和 <= threshold。
//   - 存在 → lo = mid (更大的边长可能也行)
//   - 不存在 → hi = mid - 1
//
// 二分的正确性: 如果边长 k 可行，那 k-1 也可行(取 k*k 正方形的左上角子正方形)。
//   但反过来不一定: k-1 可行不代表 k 可行。
//   所以"可行边长"形成 [0, ans] 的连续区间，适合二分。
//
// 注意: mid = lo + (hi-lo+1)/2 上取整，因为 lo=mid 时下取整会死循环。
// ============================================================
class Solution2 {
public:
    int maxSideLength(vector<vector<int>>& mat, int threshold) {
        int m = mat.size(), n = mat[0].size();
        vector<vector<int>> pre(m + 1, vector<int>(n + 1, 0));
        for (int i = 0; i < m; i++)
            for (int j = 0; j < n; j++)
                pre[i+1][j+1] = mat[i][j] + pre[i][j+1] + pre[i+1][j] - pre[i][j];

        int lo = 0, hi = min(m, n);
        while (lo < hi) {
            // 上取整，避免 lo = mid 时的死循环
            int mid = lo + (hi - lo + 1) / 2;

            // 检查是否存在边长为 mid 的正方形满足条件
            bool found = false;
            for (int i = 0; i + mid <= m && !found; i++) {
                for (int j = 0; j + mid <= n && !found; j++) {
                    int sum = pre[i+mid][j+mid] - pre[i][j+mid]
                            - pre[i+mid][j] + pre[i][j];
                    if (sum <= threshold) found = true;
                }
            }

            if (found) lo = mid;   // 可行，尝试更大
            else hi = mid - 1;     // 不可行，缩小
        }
        return lo;
    }
};

// ============================================================
// 解法3: 前缀和 + 暴力枚举边长 (基础版)
// 时间: O(m*n*min(m,n))  空间: O(m*n)
//
// 【思路】
// 枚举每个左上角 (i,j)，对每个边长 k 从 1 到 min(m-i, n-j) 检查。
// 一旦和 > threshold，更大的 k 和更大，可以 break。
// 最坏仍是 O(m*n*min(m,n))。
// ============================================================
class Solution3 {
public:
    int maxSideLength(vector<vector<int>>& mat, int threshold) {
        int m = mat.size(), n = mat[0].size();
        vector<vector<int>> pre(m + 1, vector<int>(n + 1, 0));
        for (int i = 0; i < m; i++)
            for (int j = 0; j < n; j++)
                pre[i+1][j+1] = mat[i][j] + pre[i][j+1] + pre[i+1][j] - pre[i][j];

        int ans = 0;
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                int maxK = min(m - i, n - j);
                for (int k = 1; k <= maxK; k++) {
                    int sum = pre[i+k][j+k] - pre[i][j+k] - pre[i+k][j] + pre[i][j];
                    if (sum <= threshold) {
                        ans = max(ans, k);
                    }
                    // 元素非负, 边长更大和只会更大, 但不一定因为别的位置可能更好
                    // 所以不能 break (除非 sum > threshold)
                    // 其实如果 sum > threshold 可以 break: 更大的正方形包含当前
                    // 但因为元素可以是 0, 这个剪枝不一定有效, 保守不 break
                }
            }
        }
        return ans;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法          | 时间                    | 空间    | 说明                    |
// |--------------|------------------------|---------|------------------------|
// | 逐步增长      | O(m*n)                 | O(m*n) | 最优，利用 ans 单调性     |
// | 二分搜索      | O(m*n*log min(m,n))    | O(m*n) | 经典，适合边长范围很大时   |
// | 暴力枚举      | O(m*n*min(m,n))        | O(m*n) | 基础，面试中用于对拍验证   |
//
// m,n ≤ 300 → 所有解法都能 AC, 但面试中展示逐步增长最加分
//
// ============================================================
// 【易错点】
//
// 1. 前缀和数组大小:
//    ✗ pre[m][n] → 访问 pre[m][n] 越界
//    ✓ pre[m+1][n+1], 多一行一列初始化为 0
//
// 2. 容斥公式符号:
//    ✗ pre[i+k][j+k] + pre[i][j+k] + pre[i+k][j] - pre[i][j]
//    ✓ pre[i+k][j+k] - pre[i][j+k] - pre[i+k][j] + pre[i][j]
//    助记: "大减两边加角"
//
// 3. 边界条件:
//    ✗ i + k < m → 丢失 mat 最后一行
//    ✓ i + k <= m (因为 pre 下标到 m)
//
// 4. 二分死循环:
//    ✗ mid = (lo+hi)/2 配合 lo = mid → hi=lo+1 时 mid=lo 永远不变
//    ✓ mid = lo + (hi-lo+1)/2 上取整
//
// ============================================================
// 【面试追问】
//
// Q1: 逐步增长为什么是 O(m*n)?
//     遍历 m*n 个位置各 O(1); ans 最多增 min(m,n) 次;
//     总 O(m*n + min(m,n)) = O(m*n)
//
// Q2: 如果矩阵元素可以为负数呢?
//     逐步增长失效(大正方形的和可能小于小正方形)。
//     需要枚举所有(i,j,k), O(m*n*min(m,n))。
//
// Q3: 如果不限正方形，找最大面积矩形呢?
//     更难。固定两行，用一维前缀和做列方向的区间和查询。
//     O(m²*n) 或用更高级算法。
//
