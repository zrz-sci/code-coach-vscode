/*
 * LeetCode 2235: 两整数相加 (Add Two Integers)
 *
 * 题目本质：两数求和。虽然一行代码即可，但面试价值在于位运算模拟加法，
 *          考察对计算机底层加法器原理的理解。
 *
 * 解法总览：
 *   Solution1 - 直接相加        O(1)/O(1)       面试首选，快速给出正确答案
 *   Solution2 - 位运算迭代      O(1)/O(1)       不用+号，展示底层理解
 *   Solution3 - 递归位运算      O(1)/O(1)       递归写法，更简洁
 */

// ============================================================
// 解法1: 直接相加 — O(1)/O(1) ⭐面试首选
// ============================================================
// 思考过程：
//   题目要求两数之和，直接用加法运算符即可。
//   数据范围 -100 <= num <= 100，和在 [-200, 200]，int 无溢出风险。
//   面试中应首先给出此解法，展示"快速解题"能力。
class Solution1 {
public:
    int sum(int num1, int num2) {
        return num1 + num2;
    }
};

// ============================================================
// 解法2: 位运算迭代 — O(1)/O(1)
// ============================================================
// 思考过程：
//   如果面试官追问"不用 + 运算符怎么做"，需要从 CPU 加法器原理出发。
//   核心公式: a + b = (a ^ b) + ((a & b) << 1)
//     - a ^ b   : 无进位和（XOR 在不考虑进位时与加法一致）
//     - (a&b)<<1: 进位（两位都为1才产生进位，且进位影响高一位）
//   重复此过程直到进位为 0。
//
//   以 5 + 3 为例:
//     轮1: 0101 ^ 0011 = 0110(6), (0101 & 0011)<<1 = 0010(2)
//     轮2: 0110 ^ 0010 = 0100(4), (0110 & 0010)<<1 = 0100(4)
//     轮3: 0100 ^ 0100 = 0000(0), (0100 & 0100)<<1 = 1000(8)
//     轮4: 0000 ^ 1000 = 1000(8), (0000 & 1000)<<1 = 0000(0) -> 终止
//     结果 = 8 = 5 + 3 ✓
class Solution2 {
public:
    int sum(int num1, int num2) {
        while (num2 != 0) {
            // 必须先算 carry，再更新 num1（否则 num1 被修改影响 carry 计算）
            int carry = (num1 & num2) << 1;  // 进位
            num1 = num1 ^ num2;              // 无进位和
            num2 = carry;                    // 将进位赋给 num2，继续迭代
        }
        return num1;
    }
};

// ============================================================
// 解法3: 递归位运算 — O(1)/O(1)
// ============================================================
// 思考过程：
//   解法2的递归版本。递归终止条件：进位 num2 == 0 时，num1 即为结果。
//   递归调用栈深度最多 32（int 位数），属于 O(1) 常数空间。
class Solution3 {
public:
    int sum(int num1, int num2) {
        if (num2 == 0) return num1;
        // sum(无进位和, 进位) -> 继续处理直到进位为 0
        return sum(num1 ^ num2, (num1 & num2) << 1);
    }
};

/*
 * ============================================================
 * 解法对比
 * ============================================================
 * | 解法      | 时间 | 空间 | 特点                      |
 * |-----------|------|------|---------------------------|
 * | Solution1 | O(1) | O(1) | 直接相加，最简洁          |
 * | Solution2 | O(1) | O(1) | 位运算迭代，展示底层理解  |
 * | Solution3 | O(1) | O(1) | 递归位运算，代码更优雅    |
 *
 * 面试建议：先给 Solution1，再主动提出 Solution2 展示深度。
 *
 * ============================================================
 * 易错点
 * ============================================================
 * 1. 位运算顺序错误:
 *    ✗ num1 = num1 ^ num2; carry = (num1 & num2) << 1;
 *      -> num1 已被修改，carry 计算错误
 *    ✓ carry = (num1 & num2) << 1; num1 = num1 ^ num2;
 *      -> 先算 carry，再更新 num1
 *
 * 2. Python 负数位运算陷阱（C++ 无此问题）:
 *    Python 整数无限精度，负数补码有无限前导 1，
 *    需要手动 mask 为 32 位: carry = ((a & b) << 1) & 0xFFFFFFFF
 *
 * 3. 有符号左移溢出 (C++20前是 UB):
 *    本题数据范围小不会触发，通用场景应用 unsigned 转换。
 *
 * ============================================================
 * 面试追问
 * ============================================================
 * Q1: 不用四则运算实现加法?
 *   -> 位运算: XOR 算无进位和, AND+左移 算进位, 迭代直到进位为 0
 *
 * Q2: 循环一定终止吗?
 *   -> C++ 中一定终止。carry 最低位始终为 0（左移），1 的位置不断左移，
 *      32 位 int 中最多移 31 次就溢出为 0。Python 负数需 mask。
 *
 * Q3: 如何实现减法 a - b?
 *   -> a - b = a + (-b), 补码中 -b = ~b + 1, 所以 subtract(a,b) = add(a, add(~b, 1))
 *
 * Q4: CPU 全加器原理?
 *   -> Full Adder: Sum = A^B^Cin, Cout = (A&B)|(Cin&(A^B))
 *      串联成行波进位加法器 (Ripple Carry Adder), 进位延迟 O(n)
 *      改进: 超前进位加法器 (Carry Lookahead), 延迟 O(log n)
 */
