/*
 * LeetCode 917: 仅仅反转字母 (Reverse Only Letters)
 *
 * 【题目本质】
 * 给定字符串 s，只反转其中的英文字母，非字母字符保持原位。
 * 经典双指针问题——左右指针跳过非字母，遇到两个字母就交换。
 *
 * 【解法总览】
 * 解法1: 提取-反转-填回   — O(n) / O(n) — 直觉方法
 * 解法2: 栈辅助           — O(n) / O(n) — 利用 LIFO 自动反转
 * 解法3: 双指针 ⭐        — O(n) / O(1) — 面试首选
 */

// ============================================================
// 解法1: 提取-反转-填回 — 分三步完成
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 1. 遍历字符串，把所有字母提取到一个数组中
// 2. 反转这个字母数组
// 3. 再次遍历字符串，遇到字母位置就从反转后的数组中取值填回
//
// 示意 (s = "ab-cd"):
//   提取字母: [a, b, c, d]
//   反转:     [d, c, b, a]
//   填回:     d, c, -, b, a → "dc-ba" ✓
// ============================================================
class Solution1 {
public:
    string reverseOnlyLetters(string s) {
        // 第一步：提取所有字母
        string letters;
        for (char c : s) {
            if (isalpha(c)) letters += c;
        }

        // 第二步：反转字母序列
        reverse(letters.begin(), letters.end());

        // 第三步：填回原字符串的字母位置
        int idx = 0;
        for (int i = 0; i < (int)s.size(); i++) {
            if (isalpha(s[i])) {
                s[i] = letters[idx++];
            }
            // 非字母字符保持不变
        }

        return s;
    }
};

// ============================================================
// 解法2: 栈辅助 — 利用 LIFO 特性自动反转
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 栈的后进先出特性天然实现"反转"：
// 1. 遍历字符串，把所有字母入栈
// 2. 再次遍历字符串，遇到字母位置就弹出栈顶
//    （最后入栈的最先弹出，实现了字母的反转顺序）
//
// 示意 (s = "ab-cd"):
//   入栈: 栈底 → a, b, c, d ← 栈顶
//   弹出: d, c, b, a
//   结果: d, c, -, b, a → "dc-ba" ✓
// ============================================================
class Solution2 {
public:
    string reverseOnlyLetters(string s) {
        // 所有字母入栈
        stack<char> stk;
        for (char c : s) {
            if (isalpha(c)) stk.push(c);
        }

        // 遍历字符串，字母位置用栈顶替换
        string result;
        for (char c : s) {
            if (isalpha(c)) {
                result += stk.top();
                stk.pop();
            } else {
                result += c;  // 非字母保持原位
            }
        }

        return result;
    }
};

// ============================================================
// 解法3: 双指针 — 原地交换 ⭐ 面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 前两种方法都需要 O(n) 额外空间。能否原地完成？
//
// 经典双指针：left 从头、right 从尾，两者都跳过非字母，
// 遇到两个字母就交换。和反转字符串(344题)一样，
// 只是多了"跳过非字母"的判断。
//
// 过程示意 (s = "Test1ng-Leet=code-Q!"):
//
// 初始:  T  e  s  t  1  n  g  -  L  e  e  t  =  c  o  d  e  -  Q  !
//        ^left                                                   ^right
//
// s[0]='T' 字母, s[19]='!' 非字母 → right-- → s[18]='Q' 字母
// 交换: Q  e  s  t  1  n  g  -  L  e  e  t  =  c  o  d  e  -  T  !
//          ^left                                            ^right
//
// s[1]='e' 字母, s[17]='-' 非字母 → right-- → s[16]='e' 字母
// 交换: Q  e  s  t  1  n  g  -  L  e  e  t  =  c  o  d  e  -  T  !
// (e 和 e 交换不变)
//             ^left                                     ^right
//
// ... 继续直到 left >= right
//
// 结果: "Qedo1ct-eeLg=ntse-T!" ✓
// ============================================================
class Solution3 {
public:
    string reverseOnlyLetters(string s) {
        int left = 0, right = (int)s.size() - 1;

        while (left < right) {
            // 左指针跳过非字母字符
            // 注意内层循环也要检查 left < right，防止越界
            while (left < right && !isalpha(s[left])) {
                left++;
            }
            // 右指针跳过非字母字符
            while (left < right && !isalpha(s[right])) {
                right--;
            }

            // 此时 left 和 right 都指向字母（或 left >= right）
            if (left < right) {
                swap(s[left], s[right]);
                left++;     // 交换完毕，两个指针都前进
                right--;
            }
        }

        return s;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法             | 时间  | 空间  | 核心思想                  | 适用场景      |
// |------------------|-------|-------|--------------------------|--------------|
// | 提取-反转-填回    | O(n) | O(n) | 分离字母，反转后回填       | 直觉方法      |
// | 栈辅助           | O(n) | O(n) | 利用栈的 LIFO 自动反转    | 代码简洁      |
// | 双指针 ⭐         | O(n) | O(1) | 左右指针跳过非字母并交换   | 面试首选      |
//
// 面试中直接写双指针解法。如果时间紧可以先写提取-反转-填回。
//
// ============================================================
// 【易错点】
//
// 1. 内层 while 忘记检查 left < right
//    ✗ while (!isalpha(s[left])) left++;  // 全是非字母时 left 越界
//    ✓ while (left < right && !isalpha(s[left])) left++;
//
// 2. swap 后忘记移动指针
//    ✗ swap(s[left], s[right]);  // 然后直接回到外层 while
//    → 会在同一对字母上无限交换
//    ✓ swap(s[left], s[right]); left++; right--;
//
// 3. isalpha 判断遗漏大写或小写
//    isalpha(c) 同时包含大写和小写字母。
//    如果手动写判断，确保两种都覆盖：
//    (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
//
// 4. 空字符串或全非字母字符串
//    双指针 left < right 条件自然处理：直接退出，返回原字符串。
//
// ============================================================
// 【面试追问】
//
// Q1: 双指针和经典反转字符串的关系？
// → 完全一样的模板，只是加了"跳过非字母"的判断。
//
// Q2: 如果要反转的是元音字母而不是所有字母？
// → LeetCode 345。同样的双指针模板，把 isalpha 换成 isVowel 判断。
//
// Q3: 如果字符串中只有一个字母？
// → left 和 right 最终指向同一个字母，不交换，返回原字符串。正确。
//
// Q4: 时间复杂度为什么是 O(n) 而不是 O(n^2)？
// → 虽然有嵌套 while 循环，但 left 只增不减、right 只减不增，
//   两个指针总共最多移动 n 步，所以是 O(n)。
//
