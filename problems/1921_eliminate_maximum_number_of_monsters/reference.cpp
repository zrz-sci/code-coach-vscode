/*
 * LeetCode 1921: 消灭怪物的最大数量 (Eliminate Maximum Number of Monsters)
 * 
 * 【题目本质】
 * 每分钟只能消灭一个怪物，给定每个怪物的距离和速度，
 * 问按最优顺序消灭，最多能消灭几个怪物？
 * → 本质是贪心调度问题：计算每个怪物的到达时间，优先消灭最紧迫的。
 *
 * 【解法总览】
 * 解法1: 暴力模拟 — O(n²) / O(n) — 逐分钟模拟，每分钟找最紧迫的怪物
 * 解法2: 贪心排序 — O(n log n) / O(n) — 算到达时间排序后线性扫描 ⭐ 面试首选
 */

// ============================================================
// 解法1: 暴力模拟
// 时间: O(n²)  空间: O(n)
// 
// 【思路】
// 最直觉的方法：模拟每一分钟的过程。
// 每分钟：
//   1) 所有存活怪物前进一步（第0分钟除外）
//   2) 检查是否有怪物到达城市
//   3) 选择到达时间最早的怪物消灭
//
// 瓶颈：每分钟都要遍历所有怪物找最紧迫的 → O(n) × O(n) = O(n²)
//
// 示例演示 dist=[1,1,2,3], speed=[1,1,1,1]:
//   第0分钟: 距离=[1,1,2,3], 消灭到达时间最近的(index 0 或 1)
//   第1分钟: 距离=[X,0,1,2], 怪物1已到达! → 返回1
// ============================================================
class Solution1 {
public:
    int eliminateMaximum(vector<int>& dist, vector<int>& speed) {
        int n = dist.size();
        vector<bool> alive(n, true);
        // 用浮点数追踪当前距离，避免整数精度问题
        vector<double> curDist(dist.begin(), dist.end());
        int killed = 0;
        
        for (int minute = 0; minute < n; minute++) {
            // 怪物移动（第0分钟不移动）
            if (minute > 0) {
                for (int i = 0; i < n; i++) {
                    if (alive[i]) {
                        curDist[i] -= speed[i];
                        // 有怪物到达城市 → 游戏结束
                        if (curDist[i] <= 0) return killed;
                    }
                }
            }
            
            // 选择最紧迫的怪物消灭（距离/速度 最小的）
            int target = -1;
            double minArrival = 1e18;
            for (int i = 0; i < n; i++) {
                if (alive[i]) {
                    double t = curDist[i] / speed[i];
                    if (t < minArrival) {
                        minArrival = t;
                        target = i;
                    }
                }
            }
            
            if (target != -1) {
                alive[target] = false;
                killed++;
            }
        }
        return killed;
    }
};

// ============================================================
// 解法2: 贪心 + 排序 ⭐ 面试首选
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 解法1的瓶颈是每分钟都要O(n)找最紧迫的怪物。
// 
// 关键洞察：我们根本不需要模拟！
// 1) 每个怪物的"到达时间" = ceil(dist[i] / speed[i])
//    这个值是固定的，不受消灭其他怪物的影响
// 2) 排序后，第 i 个怪物在第 i 分钟被消灭
// 3) 只要 arrival[i] > i，就来得及
//
// 为什么贪心正确？（交换论证）
// 假设最优策略中，在某分钟消灭了"不紧迫"的怪物B，
// 而更紧迫的A被推迟消灭。
// 交换AB的消灭顺序后，A更安全了，B因为到达时间更晚，
// 推迟一分钟也不会有问题。所以交换后不会变差。
//
// 示例演示:
//   dist  = [3, 2, 4],  speed = [5, 3, 2]
//   arrival = ceil(3/5)=1, ceil(2/3)=1, ceil(4/2)=2
//   排序后: [1, 1, 2]
//
//   i=0: arrival[0]=1 > 0 ✓ (第0分钟消灭)
//   i=1: arrival[1]=1 > 1 ✗ (第1分钟时，怪物已到达!)
//   返回 1
// ============================================================
class Solution2 {
public:
    int eliminateMaximum(vector<int>& dist, vector<int>& speed) {
        int n = dist.size();
        
        // 步骤1: 计算到达时间
        // 为什么用 (dist+speed-1)/speed 而不是 dist/speed？
        // 因为整数除法向下取整，但怪物 dist=5 speed=3 实际要 1.67 分钟
        // 到达，在第 1 分钟开始时还没到(距离还剩 2)，第 2 分钟开始时
        // 才到达。所以向上取整才正确。
        vector<int> arrival(n);
        for (int i = 0; i < n; i++) {
            arrival[i] = (dist[i] + speed[i] - 1) / speed[i];
        }
        
        // 步骤2: 排序 — 最紧迫的怪物排在前面
        sort(arrival.begin(), arrival.end());
        
        // 步骤3: 线性扫描
        // 第 i 分钟消灭第 i 个怪物（0-indexed）
        // 武器在第 i 分钟开始时充好电，但如果怪物也恰好在这时到达，
        // 游戏在使用武器前就结束了 → 所以必须 arrival[i] > i (严格大于)
        for (int i = 0; i < n; i++) {
            if (arrival[i] <= i) {
                // 第 i 个怪物来不及消灭
                // 已经成功消灭了 0,1,...,i-1 共 i 个
                return i;
            }
        }
        
        // 所有怪物都被消灭
        return n;
    }
};

// ============================================================
// 解法2变体: 使用浮点数（避免向上取整的困惑）
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 有些人对整数向上取整技巧不熟悉，可以直接用浮点除法。
// 到达时间 = (double)dist[i] / speed[i]
// 判定: arrival[i] <= i (浮点比较)
// 注意: 浮点精度在本题范围内 (dist, speed <= 10^5) 不会有问题
// ============================================================
class Solution2b {
public:
    int eliminateMaximum(vector<int>& dist, vector<int>& speed) {
        int n = dist.size();
        
        vector<double> arrival(n);
        for (int i = 0; i < n; i++) {
            arrival[i] = (double)dist[i] / speed[i];
        }
        
        sort(arrival.begin(), arrival.end());
        
        for (int i = 0; i < n; i++) {
            // 浮点数比较: 如果到达时间 <= 当前分钟数，来不及
            if (arrival[i] <= i) {
                return i;
            }
        }
        return n;
    }
};

// ============================================================
// 【解法对比】
// 
// | 维度       | 暴力模拟(Solution1)  | 贪心排序(Solution2)   |
// |-----------|---------------------|----------------------|
// | 时间       | O(n²)              | O(n log n)           |
// | 空间       | O(n)               | O(n)                 |
// | 思维难度   | 低（直接模拟）       | 中（需要贪心洞察）     |
// | 代码复杂度 | 高（模拟细节多）     | 低（三步走）          |
// | 面试推荐   | 仅用于说明理解       | ⭐ 首选              |
//
// 核心区别：暴力是"走一步看一步"，贪心是"提前算好到达时间，
// 一次排序解决所有调度决策"。
//
// 【易错点】
//
// 1. 向上取整写错:
//    ✗ arrival[i] = dist[i] / speed[i];  
//      → dist=5, speed=3 得到 1（应该是 2）
//    ✓ arrival[i] = (dist[i] + speed[i] - 1) / speed[i];
//      → (5+3-1)/3 = 7/3 = 2 ✓
//
// 2. 判定条件方向搞反:
//    ✗ if (arrival[i] > i) return i;  → 这是"来得及"的条件
//    ✓ if (arrival[i] <= i) return i; → 到达时间<=当前分钟 = 来不及
//
// 3. 对"恰好到达"的处理:
//    ✗ if (arrival[i] < i)  → 漏掉 arrival[i] == i 的情况
//    ✓ if (arrival[i] <= i) → 题目说"恰好到达也算输"
//    用整数向上取整版本时: arrival=1 表示在第1分钟开始时到达
//    如果 i=1, arrival[1]=1, 则 1<=1 为 true, 正确返回失败
//
// 4. 返回值搞混:
//    ✗ return i - 1;  → 第 i 个失败，但之前成功了 i 个(0到i-1)
//    ✓ return i;      → 0-indexed，第 i 个失败 = 成功消灭了 i 个
//
// 【面试追问】
//
// Q1(基础理解): "为什么优先消灭最早到达的怪物？"
//    → 交换论证: 如果交换两个怪物的消灭顺序，把更紧迫的提前，
//      更不紧迫的推迟，结果不会变差。因此按到达时间排序是最优的。
//
// Q2(变体): "如果武器每次充电需要 k 分钟，怎么改？"
//    → 第 i 次开火时间从 i 变成 i*k（第0次仍在第0分钟）
//      判定条件: arrival[i] <= i * k → 来不及
//
// Q3(变体): "如果有 m 把武器同时可用，怎么改？"
//    → 第 i 个怪物可以在第 i/m 分钟被消灭
//      判定条件: arrival[i] <= i / m → 来不及
//
// Q4(优化): "能否做到 O(n) 时间？"
//    → 如果到达时间范围有限(设最大值为 M)，可以用计数排序 O(n+M)
//      本题 dist,speed ∈ [1,10^5]，M 最大 10^5，可以实现
//      一般情况下 O(n log n) 已经足够
// ============================================================
