/*
 * LeetCode 338: Counting Bits
 * 难度: Easy | 标签: Bit Manipulation, Dynamic Programming
 *
 * 三种O(n)递推的核心对比:
 *
 *   i    bin    i>>1  i&1  i&(i-1)  highBit  dp值
 *   0    0000    0     0     -        -       0
 *   1    0001    0     1     0        1       1
 *   2    0010    1     0     0        2       1
 *   3    0011    1     1     2        2       2
 *   4    0100    2     0     0        4       1
 *   5    0101    2     1     4        4       2
 *   6    0110    3     0     4        4       2
 *   7    0111    3     1     6        4       3
 *   8    1000    4     0     0        8       1
 *   9    1001    4     1     8        8       2
 *  10    1010    5     0     8        8       2
 *  11    1011    5     1    10        8       3
 *  12    1100    6     0     8        8       2
 *  13    1101    6     1    12        8       3
 *  14    1110    7     0    12        8       3
 *  15    1111    7     1    14        8       4
 */


// ================================================================
// 解法1: 右移递推 -- O(n) 时间, O(1) 额外空间 [面试首选]
// ================================================================
// 思路: i 的二进制 = (i>>1 的二进制) 后面追加最低位
//       popcount(i) = popcount(i >> 1) + (i & 1)
//
// 例: 13 = 1101
//     13 >> 1 = 6 = 0110   (砍掉最低位)
//     最低位 = 13 & 1 = 1
//     popcount(13) = popcount(6) + 1 = 2 + 1 = 3
//
// 依赖安全: i >> 1 < i 对所有 i >= 1 成立
class Solution {
public:
    vector<int> countBits(int n) {
        vector<int> dp(n + 1, 0);  // dp[0] = 0 是基础
        for (int i = 1; i <= n; i++) {
            dp[i] = dp[i >> 1] + (i & 1);
        }
        return dp;
    }
};


// ================================================================
// 解法2: 去最低1递推 -- O(n) 时间, O(1) 额外空间
// ================================================================
// 思路: i & (i-1) 恰好将 i 的最低位的 1 翻转为 0
//       popcount(i) = popcount(i & (i-1)) + 1
//
// 位运算原理:
//   i   = ...1 0...0   (最低位的1，后面全是0)
//   i-1 = ...0 1...1   (该位变0，更低位全变1)
//   i & (i-1) = ...0 0...0  (最低位的1被清除)
//
// 例: 12 = 1100, 11 = 1011
//     12 & 11 = 1000 = 8
//     popcount(12) = popcount(8) + 1 = 1 + 1 = 2
class Solution2 {
public:
    vector<int> countBits(int n) {
        vector<int> dp(n + 1, 0);
        for (int i = 1; i <= n; i++) {
            dp[i] = dp[i & (i - 1)] + 1;
        }
        return dp;
    }
};


// ================================================================
// 解法3: 最高位偏移 -- O(n) 时间, O(1) 额外空间
// ================================================================
// 思路: 观察popcount的分组规律
//   [0]:      0
//   [1]:      1                  = [0] 每个+1
//   [2,3]:    1,2                = [0,1] 每个+1
//   [4,7]:    1,2,2,3            = [0,3] 每个+1
//   [8,15]:   1,2,2,3,2,3,3,4   = [0,7] 每个+1
//
// 当 i 达到 2 的幂次时，开始新一轮"复制+1"
// dp[i] = dp[i - highBit] + 1
// 检测 2 的幂: (i & (i-1)) == 0
class Solution3 {
public:
    vector<int> countBits(int n) {
        vector<int> dp(n + 1, 0);
        int highBit = 0;
        for (int i = 1; i <= n; i++) {
            if ((i & (i - 1)) == 0) {
                highBit = i;  // i 是 2 的幂，更新最高位
            }
            dp[i] = dp[i - highBit] + 1;
        }
        return dp;
    }
};


// ================================================================
// 解法4: 暴力逐位统计 -- O(n log n) 时间
// ================================================================
// 对每个数 i，循环检查每一位是否为 1
// 每个数最多 log(n) 位
class Solution4 {
public:
    vector<int> countBits(int n) {
        vector<int> ans(n + 1);
        for (int i = 0; i <= n; i++) {
            int count = 0, x = i;
            while (x) {
                count += (x & 1);  // 取最低位
                x >>= 1;           // 右移一位
            }
            ans[i] = count;
        }
        return ans;
    }
};


// ================================================================
// 解法5: Brian Kernighan -- O(n * k) 时间, k=平均1的个数
// ================================================================
// 对每个数，用 x & (x-1) 循环去掉最低位的 1
// 循环次数 = 1 的个数，比逐位统计更高效
class Solution5 {
public:
    vector<int> countBits(int n) {
        vector<int> ans(n + 1);
        for (int i = 0; i <= n; i++) {
            int count = 0, x = i;
            while (x) {
                x = x & (x - 1);  // 去掉最低位的 1
                count++;
            }
            ans[i] = count;
        }
        return ans;
    }
};


/*
 * ================================================================
 * 复杂度对比:
 *
 * | 解法          | 时间       | 额外空间 | 核心操作            |
 * |--------------|-----------|--------|-------------------|
 * | 右移递推       | O(n)      | O(1)*  | dp[i>>1] + (i&1)  |
 * | 去最低1递推    | O(n)      | O(1)*  | dp[i&(i-1)] + 1   |
 * | 最高位偏移     | O(n)      | O(1)*  | dp[i-highBit] + 1 |
 * | 暴力逐位统计   | O(n logn) | O(1)   | 每个数 O(logn) 位  |
 * | Brian Kernig  | O(n * k)  | O(1)   | 每个数 O(k) 个1    |
 *
 * (*) 输出数组不算额外空间
 *
 * ================================================================
 * 核心位运算总结:
 *
 *   i >> 1       右移一位 = i/2 (去掉最低位)
 *   i & 1        取最低位 (判断奇偶)
 *   i & (i-1)    去掉最低位的 1
 *   i & (-i)     取最低位的 1 (lowbit)
 *   (i & (i-1)) == 0  判断是否为 2 的幂
 *
 * ================================================================
 * 易错点:
 *
 * 1. 数组大小: n+1 个元素 (0 到 n), 不是 n 个
 * 2. dp[0] = 0: 0 没有任何 1 位, 是所有递推的基础
 * 3. 右移递推依赖: i>>1 < i 对 i>=1 成立, 顺序遍历安全
 * 4. 最高位偏移: 每当 i 是 2 的幂时必须更新 highBit
 * ================================================================
 */
