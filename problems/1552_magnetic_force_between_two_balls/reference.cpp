/*
 * LeetCode 1552: 两球之间的磁力 (Magnetic Force Between Two Balls)
 *
 * 【题目本质】
 * "最大化最小值"问题：在 n 个位置中选 m 个，使得相邻选中位置的最小间距尽可能大。
 * 这是二分答案的经典应用场景。
 *
 * 【解法总览】
 * 解法1: 暴力枚举 — O(C(n,m)·m) / O(m) — 枚举所有选法，仅用于理解问题
 * 解法2: 二分答案 + 贪心验证 — O(n log n + n log D) / O(1) — 面试首选
 */

// ============================================================
// 解法1: 暴力回溯枚举 — 枚举所有 C(n,m) 种选法
// 时间: O(C(n,m) · m)  空间: O(m) 递归栈
//
// 【思路】
// 最直觉的做法：从 n 个篮子中选 m 个放球，对每种方案计算
// 任意相邻球的最小距离，取所有方案中的最大值。
// 排序后只需看相邻选中位置的差值即可（最小距离一定出现在相邻位置之间）。
//
// 瓶颈：C(n,m) 是组合数，n=10^5 时完全不可行。
// 但这个思路帮我们理解了问题的本质。
// ============================================================
class Solution1 {
public:
    int maxDistance(vector<int>& position, int m) {
        sort(position.begin(), position.end());
        int n = position.size();
        int ans = 0;
        vector<int> chosen;  // 存储选中的篮子下标
        
        function<void(int)> dfs = [&](int start) {
            if ((int)chosen.size() == m) {
                // 计算相邻球的最小间距
                int minDist = INT_MAX;
                for (int i = 1; i < m; i++) {
                    minDist = min(minDist, 
                        position[chosen[i]] - position[chosen[i-1]]);
                }
                ans = max(ans, minDist);
                return;
            }
            // 剪枝：剩余篮子不够选满 m 个
            if (n - start < m - (int)chosen.size()) return;
            
            for (int i = start; i < n; i++) {
                chosen.push_back(i);
                dfs(i + 1);
                chosen.pop_back();  // 回溯：撤销选择
            }
        };
        
        dfs(0);
        return ans;
    }
};

// ============================================================
// 解法2: 二分答案 + 贪心验证 — 面试首选 ⭐
// 时间: O(n log n + n log D)  空间: O(1)
// 其中 D = max(position) - min(position)
//
// 【思路】
// "最大化最小值"是二分答案的经典信号词。
// 
// 反转问题：不枚举"怎么放球"，而是猜一个答案 d（最小间距），
// 然后问"能否放下 m 个球使得任意两球间距 ≥ d？"
// 
// 关键观察：
// - d 越小 → 限制越松 → 能放的球越多
// - d 越大 → 限制越严 → 能放的球越少
// 这是单调关系！所以可以二分 d。
//
// 验证用贪心：排序后从最左开始放，每次找到距离 ≥ d 的下一个篮子就放。
// 贪心正确性：尽量往左放，给右边留出更多空间，如果这样都放不下，
// 其他策略也不行。
//
// 二分搜索空间收缩过程 (示例1: position=[1,2,3,4,7], m=3):
// 排序后: [1, 2, 3, 4, 7]
// 搜索空间: [1, 6]
//
// Round1: lo=1, hi=6, mid=4 (上取整: (1+6+1)/2=4)
//   贪心: 放pos[0]=1, 跳过2,3,4(距离<4), 放pos[4]=7(距离6≥4)
//   count=2 < 3 → 不可行! hi=3
//
// Round2: lo=1, hi=3, mid=2 (上取整: (1+3+1)/2=2 → 实际=(1+4)/2=2)
//   → 实际: mid = 1+(3-1+1)/2 = 1+1=2? 
//   让我重新算: lo=1,hi=3, mid=1+(3-1+1)/2=1+1=2... 
//   不对，用公式: mid = lo + (hi-lo+1)/2 = 1+(3-1+1)/2 = 1+1 = 2
//   贪心: 放1, 放3(距离2≥2), 放7(距离4≥2) → count=3 ≥ 3 → 可行! lo=2
//
// Round3: lo=2, hi=3, mid=2+(3-2+1)/2=2+1=3
//   贪心: 放1, 放4(距离3≥3), 放7(距离3≥3) → count=3 ≥ 3 → 可行! lo=3
//
// lo=hi=3 → 答案=3 ✓
// ============================================================
class Solution2 {
public:
    int maxDistance(vector<int>& position, int m) {
        // 第一步：排序，这是贪心和二分的基础
        sort(position.begin(), position.end());
        int n = position.size();
        
        // 贪心验证：最小间距 ≥ d 时，能否放下 m 个球？
        // 策略：第一个球放最左边，然后从左到右扫描，
        // 每次找到距离上一个球 ≥ d 的篮子就放一个球
        auto canPlace = [&](int d) -> bool {
            int count = 1;              // 第一个球放在 position[0]
            int lastPos = position[0];  // 上一个球的位置
            for (int i = 1; i < n; i++) {
                if (position[i] - lastPos >= d) {
                    count++;
                    lastPos = position[i];
                    // 提前退出：已经能放够了
                    if (count >= m) return true;
                }
            }
            return count >= m;
        };
        
        // 二分答案：在 [1, max_gap] 中找最大的 d 使得 canPlace(d)==true
        int lo = 1;
        int hi = position[n - 1] - position[0];
        
        while (lo < hi) {
            // 找最大可行值，必须上取整，否则 lo=mid 可能死循环
            // 例如 lo=3,hi=4 → 下取整 mid=3 → lo=mid=3 不变 → 死循环
            // 上取整 mid=4 → 要么 lo=4 要么 hi=3 → 一定收缩
            int mid = lo + (hi - lo + 1) / 2;
            
            if (canPlace(mid)) {
                lo = mid;       // mid 可行，答案可能更大，收缩左边界
            } else {
                hi = mid - 1;   // mid 不可行，答案一定 < mid
            }
        }
        
        return lo;  // lo == hi 时就是答案
    }
};

// ============================================================
// 【解法对比】
// 
// 解法1 (暴力):
// - 优点：思路直接，帮助理解问题
// - 缺点：C(n,m) 指数级，n>20 就超时
// - 用途：面试中口头说明"暴力怎么做"
//
// 解法2 (二分+贪心):
// - 优点：O(n log n + n log D)，完全可以处理 n=10^5
// - 核心：把"优化问题"转化为"判定问题" —— 二分答案的精髓
// - 面试首选
//
// 【二分答案模板总结 —— "最大化最小值"】
// 1. 确定搜索空间 [lo, hi]（答案的可能范围）
// 2. 写 canPlace(mid) 验证函数（通常是贪心 O(n)）
// 3. 二分找最大可行的 mid：
//    - canPlace(mid)==true → lo = mid（上取整避免死循环）
//    - canPlace(mid)==false → hi = mid - 1
// 4. 返回 lo
//
// 对偶模板 —— "最小化最大值"：
//    - check(mid)==true → hi = mid（下取整）
//    - check(mid)==false → lo = mid + 1
//    - while (lo < hi), 返回 lo
//
// 【易错点】
// 1. 忘记排序：position 原始无序，不排序贪心结果完全错误
//    ✗ 直接在原数组上跑 canPlace
//    ✓ 先 sort(position.begin(), position.end())
//
// 2. 二分 mid 计算导致死循环：
//    找最大可行值时 lo=mid，必须上取整
//    ✗ int mid = lo + (hi - lo) / 2;     // lo=3,hi=4 → mid=3 → lo=3 死循环
//    ✓ int mid = lo + (hi - lo + 1) / 2; // lo=3,hi=4 → mid=4 → 正常收缩
//
// 3. 贪心 count 初始值：
//    ✗ int count = 0; for (int i=0; ...) — 第一个位置的处理容易出错
//    ✓ int count = 1; lastPos = position[0]; for (int i=1; ...)
//    因为第一个球一定放在最左边的篮子
//
// 4. 搜索空间上界：
//    ✗ hi = position[n-1]              — 值太大，虽然不影响正确性但浪费二分轮数
//    ✓ hi = position[n-1] - position[0] — 最小间距不可能超过总跨度
//
// 【面试追问】
// Q1: 为什么贪心从左到右放球是最优的？
//   → 排序后从左到右贪心，相当于把每一步的间距都"刚好够用"，
//     把多余的空间留给后面。如果连贪心都放不下 m 个球，
//     那任何策略都放不下（可以用交换论证严格证明）。
//
// Q2: 二分找"最大可行值" vs "最小可行值"有什么区别？
//   → 最大可行值：lo=mid（上取整），hi=mid-1
//     最小可行值：hi=mid（下取整），lo=mid+1
//     区别在于 lo=mid 时需要上取整防死循环，hi=mid 时下取整即可。
//     本题求"最大化最小值"，所以是找最大可行值。
//
// Q3: 如果球必须放在连续的篮子中（不能跳过篮子），怎么改？
//   → 问题变成"从 n 个篮子中选连续 m 个"，滑动窗口即可：
//     窗口大小 m，最小间距 = 窗口内相邻位置差的最小值，
//     遍历所有窗口取最大值。复杂度 O(n log n + n)。
//
// Q4: 这个二分答案框架还能解决哪些问题？
//   → 875.爱吃香蕉的珂珂（二分速度，验证时间够不够）
//     1011.在D天内送达包裹（二分载重，验证天数够不够）
//     410.分割数组的最大值（最小化最大值，二分方向相反）
//     2517.礼盒的最大甜蜜度（本题的翻版，代码几乎一样）
// ============================================================
