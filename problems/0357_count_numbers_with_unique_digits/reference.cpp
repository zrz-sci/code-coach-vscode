/*
 * 【题目本质】
 * 计数 [0, 10^n) 范围内各位数字互不相同的数的个数
 * 本质是排列组合计数：k 位数中首位 9 选择 × 后续位递减选择
 *
 * 【解法总览】
 * 解法1: 数学排列公式 — O(1) 直接计算，最优
 * 解法2: DP 递推 — O(N)，思路清晰
 */

// ===================== Solution 1: 数学排列（推荐）=====================
// 思路：
//   0 位数：只有 0 → 1 个
//   1 位数：0-9 → 10 个
//   k 位数 (k>=2)：首位 9 种(1-9) × 第2位 9 种(0-9除首位) × 第3位 8 种 × ...
//   k 位唯一数字数 = 9 × 9 × 8 × 7 × ... × (11-k)
//   总答案 = 1 + Σ(k位唯一数字数), k=1..min(n,10)
//
// 详细推导：
//   f(1) = 9    （1-9）
//   f(2) = 9 × 9 = 81    （首位9种 × 第二位9种）
//   f(3) = 9 × 9 × 8 = 648
//   f(k) = f(k-1) × (11-k)
//   答案 = 1 + f(1) + f(2) + ... + f(n)
//        = 1 + 9 + 81 + 648 + ...
//
// 时间：O(min(N,10))   空间：O(1)
class Solution {
public:
    int countNumbersWithUniqueDigits(int n) {
        if (n == 0) return 1;

        int total = 10;   // 初始包含 0-9（1位数部分）
        int uniqueK = 9;  // f(1) = 9, 即1位数中不含0的唯一数字数

        for (int k = 2; k <= min(n, 10); k++) {
            uniqueK *= (11 - k);  // f(k) = f(k-1) * (11-k)
            total += uniqueK;     // 累加 k 位数的贡献
        }
        return total;
    }
};

// ===================== Solution 2: DP 递推 =====================
// 思路：dp[i] = i 位数中各位不重复的数的个数（不含前导零，即 i 位数范围）
// dp[1] = 9 (1-9)
// dp[i] = dp[i-1] * (11-i)
// 答案 = 1 + dp[1] + dp[2] + ... + dp[min(n,10)]
//
// 等价于解法1的显式 DP 写法，更便于理解递推关系
// 时间：O(N)   空间：O(N)
class Solution2 {
public:
    int countNumbersWithUniqueDigits(int n) {
        if (n == 0) return 1;

        int bound = min(n, 10);
        vector<int> dp(bound + 1, 0);
        dp[1] = 9;

        for (int i = 2; i <= bound; i++) {
            dp[i] = dp[i - 1] * (11 - i);
            // i=2: 9*9=81, i=3: 81*8=648, i=4: 648*7=4536 ...
        }

        int total = 1;  // 数字 0
        for (int i = 1; i <= bound; i++) {
            total += dp[i];
        }
        return total;
    }
};

/*
 * 【解法对比】
 * | 解法 | 时间 | 空间 | 优势 |
 * |------|------|------|------|
 * | 数学公式 | O(1) | O(1) | 最简洁高效 |
 * | DP | O(N) | O(N) | 递推关系清晰 |
 *
 * 【数值参考表】
 * n=0: 1
 * n=1: 10
 * n=2: 91
 * n=3: 739
 * n=4: 5275
 * n=5: 32491
 * n=6: 168571
 * n=7: 712891
 * n=8: 2345851
 *
 * 【易错点】
 * 1. n=0 特判：返回 1（只有数字 0）
 * 2. 首位不能为 0：k 位数首位只有 9 种选择，不是 10 种
 * 3. n > 10 时等价于 n=10：只有 10 个数字(0-9)，超过 10 位必重复
 * 4. 累加 vs 替换：答案是 Σf(k)，不是只算 f(n)
 *    题目要求 0 <= x < 10^n 范围内的所有数，包括位数 < n 的
 *
 * 【面试追问】
 * Q1: 如何从 f(k) 推导到 f(k+1)？
 *     → f(k+1) = f(k) × (10-k)，第 k+1 位有 (10-k) 种可选数字
 * Q2: 如果范围是 [L, R] 而非 [0, 10^n)？
 *     → 数位 DP：按位枚举，维护 tight bound 和已选数字 bitmask
 * Q3: 如果允许前导零（视为 k 位数）？
 *     → 首位也有 10 种选择，f(k) = 10 × 9 × 8 × ... × (11-k) = P(10,k)
 */
