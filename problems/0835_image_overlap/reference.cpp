/*
 * 835. 图像重叠 (Image Overlap)
 * 难度: Medium
 * 标签: Array, Matrix
 *
 * 题目:
 *   两个 n x n 二进制矩阵 img1, img2。可以平移 img1（上下左右，不旋转），
 *   求平移后与 img2 重叠（都为1）的最大位置数。
 *   1 <= n <= 30
 *
 * 核心思路:
 *   对 img1 每个 1 和 img2 每个 1，计算偏移向量 (dr, dc)。
 *   共享同一偏移向量的 1-1 对在该平移下同时重叠。
 *   用哈希表统计出现最多的偏移向量。
 *
 * 解法概览:
 *   解法1 - 偏移向量哈希 ⭐: O(A*B), 稀疏时快
 *   解法2 - 枚举所有偏移: O(n^4), 直观稳定
 */

// ============================================================
// 解法 1: 偏移向量哈希（推荐）⭐
// ============================================================
// 思路: 收集两图的 1 坐标，枚举所有 1-1 对的偏移向量，哈希表计数
// 时间: O(A*B)  空间: O(A*B)  (A,B 为两图中 1 的个数)
//
// 核心原理:
//   如果 img1 的 (r1,c1) 平移后对齐 img2 的 (r2,c2)
//   -> 偏移向量 delta = (r2-r1, c2-c1)
//   -> 所有共享此 delta 的 1-1 对在该平移下同时重叠
//   -> 最大频次的 delta 就是答案
//
// 模拟 (示例):
//   img1 的 1: (0,0),(0,1),(1,1),(2,1)
//   img2 的 1: (1,1),(1,2),(2,2)
//
//   (0,0)-(1,1)=(1,1)  (0,0)-(1,2)=(1,2)  (0,0)-(2,2)=(2,2)
//   (0,1)-(1,1)=(1,0)  (0,1)-(1,2)=(1,1)  (0,1)-(2,2)=(2,1)
//   (1,1)-(1,1)=(0,0)  (1,1)-(1,2)=(0,1)  (1,1)-(2,2)=(1,1)
//   (2,1)-(1,1)=(-1,0) (2,1)-(1,2)=(-1,1) (2,1)-(2,2)=(0,1)
//
//   delta (1,1) 出现 3 次 -> 答案 = 3
class Solution1 {
public:
    int largestOverlap(vector<vector<int>>& img1, vector<vector<int>>& img2) {
        int n = img1.size();
        vector<pair<int, int>> pts1, pts2;

        // 1. 收集两图中所有 1 的坐标
        for (int i = 0; i < n; i++)
            for (int j = 0; j < n; j++) {
                if (img1[i][j]) pts1.push_back({i, j});
                if (img2[i][j]) pts2.push_back({i, j});
            }

        // 2. 枚举所有 1-1 对，统计偏移向量频次
        unordered_map<int, int> count;
        int ans = 0;

        for (auto& [r1, c1] : pts1) {
            for (auto& [r2, c2] : pts2) {
                // 编码: dx*100+dy, |dx|<=29, |dy|<=29, 100>58 无冲突
                int key = (r2 - r1) * 100 + (c2 - c1);
                count[key]++;
                ans = max(ans, count[key]);
            }
        }
        return ans;
    }
    // 关键点:
    //   - 编码基数 100 > 2*29+1=59, 保证 (dx,dy) 唯一映射到 int
    //   - 稀疏矩阵时 A*B 远小于 n^4
    //   - 如果全是 0，pts 为空，自然返回 0
};

// ============================================================
// 解法 2: 枚举所有偏移量
// ============================================================
// 思路: 枚举 (2n-1)^2 种偏移量，每种偏移下遍历矩阵计算重叠数
// 时间: O(n^4)  空间: O(1)
//
// 思考过程:
//   1. 偏移量 (dx,dy) 范围: [-(n-1), n-1]
//   2. 对每个偏移量, img1 的 (i,j) 对应 img2 的 (i+dx, j+dy)
//   3. 检查边界 + 两者都为 1 -> 重叠 +1
//   4. 取所有偏移量中的最大重叠数
class Solution2 {
public:
    int largestOverlap(vector<vector<int>>& img1, vector<vector<int>>& img2) {
        int n = img1.size();
        int ans = 0;

        for (int dx = -(n - 1); dx <= n - 1; dx++) {       // 行偏移
            for (int dy = -(n - 1); dy <= n - 1; dy++) {   // 列偏移
                int overlap = 0;
                for (int i = 0; i < n; i++) {
                    for (int j = 0; j < n; j++) {
                        int ni = i + dx, nj = j + dy;
                        if (ni >= 0 && ni < n && nj >= 0 && nj < n)
                            overlap += img1[i][j] & img2[ni][nj];
                    }
                }
                ans = max(ans, overlap);
            }
        }
        return ans;
    }
    // 关键点:
    //   - dx/dy 覆盖正负方向, 已包含 img1 移向 img2 和反方向
    //   - 边界检查: ni,nj 必须在 [0,n) 内
    //   - n=30 时约 59^2 * 30^2 = 3.13M 次操作, 可接受
};

/*
 * ============================================================
 * 解法对比
 * ============================================================
 * | 维度       | 解法1 偏移哈希 ⭐ | 解法2 枚举偏移   |
 * |-----------|-------------------|-----------------|
 * | 时间       | O(A*B), worst n^4 | O(n^4)          |
 * | 空间       | O(A*B)            | O(1)            |
 * | 稀疏矩阵   | 快                | 不变            |
 * | 密集矩阵   | 同                | 同              |
 * | 代码简洁   | 更简洁            | 较长            |
 *
 * ============================================================
 * 易错点
 * ============================================================
 * 1. 偏移量编码冲突
 *    错: key = dx*50 + dy  // 28*50+21 = 29*50+(-29)? 不会, 但接近边界
 *    对: key = dx*100 + dy  // 基数 100 >> 59, 完全安全
 *
 * 2. 枚举偏移时边界检查遗漏
 *    错: overlap += img1[i][j] & img2[i+dx][j+dy]  // 越界!
 *    对: 先 if (ni>=0 && ni<n && nj>=0 && nj<n)
 *
 * 3. 只枚举正偏移, 漏掉左移/上移
 *    错: for(dx=0; dx<n; ...)  // 只有右下方向
 *    对: for(dx=-(n-1); dx<=n-1; ...)
 *
 * 4. 收集坐标时只收集一个图
 *    必须同时收集 img1 和 img2 的 1 坐标
 *
 * ============================================================
 * 面试追问
 * ============================================================
 * Q1: 稀疏矩阵(1很少)时哪种方法好?
 * A1: 偏移哈希法。k 个 1 时只需 O(k^2), 远优于 O(n^4)。
 *
 * Q2: 允许旋转 90/180/270 度怎么办?
 * A2: 对 img1 生成 4 种旋转版本, 各自求最大重叠, 取最大值。
 *     90度旋转: (i,j) -> (j, n-1-i)。
 *
 * Q3: 和信号处理中的互相关(cross-correlation)有什么关系?
 * A3: 完全等价。可用 FFT 加速到 O(n^2 log n), 但 n<=30 不需要。
 */
