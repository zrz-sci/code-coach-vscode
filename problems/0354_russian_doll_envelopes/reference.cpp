/*
 * LeetCode 354: 俄罗斯套娃信封问题 (Russian Doll Envelopes)
 *
 * 【题目本质】
 * 二维最长递增子序列(LIS)：在宽度和高度都严格递增的约束下，找最长嵌套链。
 * 通过排序降维，将二维 LIS 转化为一维 LIS。
 *
 * 【解法总览】
 * 解法1: 排序 + O(n²) DP — O(n²) / O(n) — 最直觉，展示 LIS DP 思路
 * 解法2: 排序 + 二分 LIS (patience sorting) — O(n log n) / O(n) — 最优，面试必须掌握
 */

// ============================================================
// 解法1: 排序 + O(n²) DP — 经典 LIS DP 的二维扩展
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 最朴素的想法：先排序让宽度有序，然后对每个信封 i，
// 检查所有 j < i 是否能装进 i（两个维度都严格小于）。
// 这就是标准的 LIS DP：dp[i] = max(dp[j] + 1) for all valid j < i。
//
// 排序只需要按宽度升序即可，因为 DP 中会显式检查两个维度。
// 但 n = 10^5 时 O(n²) 会超时，所以这是理解用的解法。
//
// DP 填表过程 (示例 [2,3] [5,4] [6,4] [6,7]):
// 排序后: [2,3] [5,4] [6,4] [6,7]
//
// i=0: dp[0] = 1  (只有自己)
// i=1: j=0, [2,3] < [5,4]? 2<5 且 3<4 ✓ → dp[1] = dp[0]+1 = 2
// i=2: j=0, [2,3] < [6,4]? 2<6 且 3<4 ✓ → dp[2] = dp[0]+1 = 2
//      j=1, [5,4] < [6,4]? 5<6 但 4<4 ✗ → 跳过
//      dp[2] = 2
// i=3: j=0, [2,3] < [6,7]? 2<6 且 3<7 ✓ → dp[3] = 2
//      j=1, [5,4] < [6,7]? 5<6 且 4<7 ✓ → dp[3] = 3
//      j=2, [6,4] < [6,7]? 6<6 ✗ → 跳过
//      dp[3] = 3
//
// 答案 = max(dp) = 3
// ============================================================
class Solution1 {
public:
    int maxEnvelopes(vector<vector<int>>& envelopes) {
        int n = envelopes.size();
        
        // 按宽度升序排序（宽度相同时顺序无所谓，因为 DP 会检查两个维度）
        sort(envelopes.begin(), envelopes.end());
        
        // dp[i] = 以第 i 个信封结尾的最长嵌套链长度
        vector<int> dp(n, 1);
        int ans = 1;
        
        for (int i = 1; i < n; i++) {
            for (int j = 0; j < i; j++) {
                // 必须两个维度都严格小于才能嵌套
                if (envelopes[j][0] < envelopes[i][0] &&
                    envelopes[j][1] < envelopes[i][1]) {
                    dp[i] = max(dp[i], dp[j] + 1);
                }
            }
            ans = max(ans, dp[i]);
        }
        
        return ans;
    }
};

// ============================================================
// 解法2: 排序 + 二分 LIS (Patience Sorting) — 最优解
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 解法1的瓶颈: O(n²) 的 LIS DP。一维 LIS 有 O(n log n) 的经典解法，
// 能否把二维问题降为一维？
//
// 关键排序策略:
// - 宽度升序: 保证遍历顺序中宽度非递减
// - 同宽度时高度降序: 阻止同宽度的信封同时被选入 LIS
//
// 为什么高度降序能解决同宽度问题？
// 例如 [6,4] 和 [6,7]:
//   高度升序 → [4,7] → LIS 会选 4,7 → 错! 宽度相同不能嵌套
//   高度降序 → [7,4] → 7 后面是 4, 不可能同时在递增子序列中 → 正确!
//
// 排序后只需要对高度数组求严格递增的 LIS。
//
// Patience Sorting 过程:
// 维护 tails 数组: tails[i] = 长度为 i+1 的递增子序列的最小末尾元素
// 遍历每个高度 h:
//   - 如果 h > tails 的最后一个元素 → 追加, LIS 长度+1
//   - 否则 → 用二分找到第一个 >= h 的位置, 替换它 (让末尾尽可能小)
//
// 示例: envelopes = [5,4] [6,4] [6,7] [2,3]
//
// Step1 排序 (宽度升序, 同宽高度降序):
//   [2,3] [5,4] [6,7] [6,4]
//
// Step2 提取高度: [3, 4, 7, 4]
//
// Step3 Patience Sorting:
//   h=3: tails=[]       → 追加         → tails=[3]
//   h=4: tails=[3]      → 4>3, 追加    → tails=[3,4]
//   h=7: tails=[3,4]    → 7>4, 追加    → tails=[3,4,7]
//   h=4: tails=[3,4,7]  → lower_bound找到索引1(值4)
//                          替换tails[1]=4 → tails=[3,4,7]
//                          (4替换4, 没变化)
//
//   最终 tails 长度 = 3 → 答案 3 ✓
//
// tails 数组中 lower_bound 二分搜索详解:
//
// 当 h=4, tails=[3,4,7] 时, lower_bound 找第一个 >= 4 的位置:
//   lo=0          hi=2
//   [3,   4,   7]
//   Round1: mid=1, tails[1]=4 >= 4 → hi=mid=1
//   lo=0  hi=1
//   Round2: mid=0, tails[0]=3 < 4 → lo=mid+1=1
//   lo==hi=1 → 位置 1, 替换 tails[1]=4 (不变)
//
// 更复杂的例子: envelopes = [1,2] [2,6] [3,4] [4,5] [5,7] [6,3]
// 排序 (宽度升序, 同宽高度降序, 这里无同宽):
//   [1,2] [2,6] [3,4] [4,5] [5,7] [6,3]
// 提取高度: [2, 6, 4, 5, 7, 3]
//
// Patience Sorting 过程 (tails 变化):
//   h=2: tails=[]        → 追加          → tails=[2]
//   h=6: tails=[2]       → 6>2, 追加     → tails=[2,6]
//   h=4: tails=[2,6]     → lower_bound:
//        lo=0      hi=1
//        [2,  6]
//        Round1: mid=0, tails[0]=2 < 4 → lo=1
//        lo==hi=1 → 位置 1, 替换 tails[1]=4 → tails=[2,4]
//   h=5: tails=[2,4]     → 5>4, 追加     → tails=[2,4,5]
//   h=7: tails=[2,4,5]   → 7>5, 追加     → tails=[2,4,5,7]
//   h=3: tails=[2,4,5,7] → lower_bound:
//        lo=0              hi=3
//        [2,   4,   5,   7]
//        Round1: mid=1, tails[1]=4 >= 3 → hi=1
//        lo=0  hi=1
//        Round2: mid=0, tails[0]=2 < 3 → lo=1
//        lo==hi=1 → 位置 1, 替换 tails[1]=3 → tails=[2,3,5,7]
//
//   最终 tails 长度 = 4 → LIS 长度 = 4 ✓
//   (实际 LIS: 高度 2→4→5→7, 对应信封 [1,2]→[3,4]→[4,5]→[5,7])
//
// 注意: 如果没有高度降序, 排序后是 [2,3] [5,4] [6,4] [6,7]
//   高度: [3, 4, 4, 7]
//   h=3: tails=[3]
//   h=4: tails=[3,4]
//   h=4: lower_bound → 索引1, 替换 → tails=[3,4]
//   h=7: tails=[3,4,7]
//   长度=3, 这个例子碰巧对了。但试试 [3,3] [3,5]:
//     升序: [3,3] [3,5] → 高度 [3,5] → LIS=2 → 错! 宽度都是3
//     降序: [3,5] [3,3] → 高度 [5,3] → LIS=1 → 正确!
// ============================================================
class Solution2 {
public:
    int maxEnvelopes(vector<vector<int>>& envelopes) {
        // 排序: 宽度升序, 同宽度时高度降序
        // 为什么同宽高度降序: 阻止同宽度的信封同时出现在 LIS 中
        sort(envelopes.begin(), envelopes.end(), [](const vector<int>& a, const vector<int>& b) {
            if (a[0] != b[0]) return a[0] < b[0];  // 宽度升序
            return a[1] > b[1];                      // 同宽高度降序
        });
        
        // 对高度求一维严格递增 LIS
        // tails[i] = 长度为 i+1 的严格递增子序列的最小末尾
        vector<int> tails;
        
        for (const auto& env : envelopes) {
            int h = env[1];
            
            // lower_bound: 找第一个 >= h 的位置 (保证严格递增)
            // 不能用 upper_bound, 否则允许相等元素出现, 变成非严格递增
            auto it = lower_bound(tails.begin(), tails.end(), h);
            
            if (it == tails.end()) {
                // h 比所有末尾都大, LIS 可以延伸
                tails.push_back(h);
            } else {
                // 替换: 让这个长度的子序列末尾尽可能小, 为后续元素留更多空间
                *it = h;
            }
        }
        
        // tails 的长度 = LIS 的长度 = 最多能嵌套的信封数
        return tails.size();
    }
};

// ============================================================
// 【解法对比】
// 
// 解法1 vs 解法2:
// - 解法1 是经典 O(n²) LIS DP，直接比较两个维度，无需特殊排序策略
//   适合 n ≤ 5000 的情况，代码简单直观
// - 解法2 通过排序降维 + O(n log n) patience sorting 实现最优
//   n = 10^5 时必须用这个解法
// - 核心区别在排序: 解法1 只需宽度升序; 解法2 必须同宽高度降序
//
// 【易错点】
// 1. 排序时宽度相同的高度方向:
//    ✗ sort(env.begin(), env.end());  // 默认两个维度都升序
//    ✓ 宽度升序 + 同宽高度降序
//    不降序会导致 [3,3][3,5] 这类同宽度信封被错误选入 LIS
//
// 2. 二分查找函数的选择:
//    ✗ upper_bound → 允许相等, 得到的是非严格递增 (≤ 不是 <)
//    ✓ lower_bound → 替换掉 >=h 的第一个, 保证严格递增
//    例如 tails=[3,5], h=5:
//      lower_bound 找到索引1, 替换为5(不变) → tails=[3,5], 长度不增 ✓
//      upper_bound 找到索引2(end), 追加5    → tails=[3,5,5], 长度+1 ✗
//
// 3. tails 数组的含义:
//    ✗ 误以为 tails 就是最终的 LIS 序列
//    ✓ tails 的长度等于 LIS 长度, 但内容可能不是实际的 LIS
//    替换操作可能让 tails 中的元素来自不同的子序列
//
// 4. 排序的 lambda 写法:
//    ✗ return a[0] < b[0] || a[1] > b[1];  // 逻辑错误, 宽度不同时也比较了高度
//    ✓ return a[0] < b[0] || (a[0] == b[0] && a[1] > b[1]);  // 先比宽度, 同宽再比高度
//
// 【面试追问】
// Q1: 为什么排序后只对高度求 LIS 就够了？宽度怎么保证严格递增？
//     → 排序保证宽度非递减。同宽高度降序意味着同宽最多选一个（高度递减不可能
//       同时在递增子序列中）。不同宽度之间，前者宽度 < 后者宽度，自然满足。
//
// Q2: 如果改成非严格嵌套(宽高可以相等)，代码怎么改？
//     → 两处改动: (1) 排序时同宽高度不需降序 (2) 用 upper_bound 代替 lower_bound
//
// Q3: 三维套娃(宽、高、深)能用同样的方法吗？
//     → 不能直接降维。可以按两个维度排序后用 BIT/CDQ分治 优化，
//       或退回 O(n²) DP。这是经典的三维偏序问题。
//
// Q4: 本题和 LeetCode 300 (最长递增子序列) 的关系？
//     → 300 是一维 LIS，本题通过排序降维后复用 300 的 O(n log n) 解法。
//       掌握 300 是解本题的前提。
// ============================================================
