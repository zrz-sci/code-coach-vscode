/*
 * LCR 074: 合并区间 (同主站第 56 题)
 *
 * 【题目本质】
 * 给定若干区间，合并所有重叠的区间。
 * 核心问题：如何高效判断哪些区间重叠并合并它们？
 *
 * 【解法总览】
 * 解法1: 排序+线性扫描  — O(nlogn) / O(1)  — 面试首选
 * 解法2: 排序+双指针    — O(nlogn) / O(1)  — 不同写法
 * 解法3: 连通分量(图)   — O(n^2)  / O(n^2) — 理论了解
 */

// ============================================================
// 解法1: 排序 + 线性扫描 — 面试首选 ⭐
// 时间: O(n log n)  空间: O(1) (不计输出)
//
// 【思路】
// 按起点排序后，重叠区间必定连续。
// 维护结果数组 res:
//   - 如果当前区间起点 <= res最后一个区间终点 → 重叠, 合并
//   - 否则 → 不重叠, 加入 res
//
// 关键: 合并时取 max(end), 处理包含关系。
//
// 示例: intervals = [[1,3],[2,6],[8,10],[15,18]]
//
// 排序后: [[1,3],[2,6],[8,10],[15,18]]
//   [1,3] → res = [[1,3]]
//   [2,6] → 2<=3, merge: res = [[1,6]]
//   [8,10] → 8>6, 加入: res = [[1,6],[8,10]]
//   [15,18] → 15>10, 加入: res = [[1,6],[8,10],[15,18]]
//
// 包含关系示例: [[1,10],[2,3],[4,5]]
//   [1,10] → res = [[1,10]]
//   [2,3] → 2<=10, max(10,3)=10 → res = [[1,10]] (不变)
//   [4,5] → 4<=10, max(10,5)=10 → res = [[1,10]] (不变)
//
// 端点相等示例: [[1,4],[4,5]]
//   [1,4] → res = [[1,4]]
//   [4,5] → 4<=4, max(4,5)=5 → res = [[1,5]]
// ============================================================
class Solution1 {
public:
    vector<vector<int>> merge(vector<vector<int>>& intervals) {
        // 按起点排序 (sort 默认: 先按[0]升序, [0]相同按[1]升序)
        sort(intervals.begin(), intervals.end());

        vector<vector<int>> res;
        for (auto& iv : intervals) {
            if (res.empty() || iv[0] > res.back()[1]) {
                // 不重叠: 直接加入
                res.push_back(iv);
            } else {
                // 重叠: 合并 (取更大的终点)
                res.back()[1] = max(res.back()[1], iv[1]);
            }
        }
        return res;
    }
};

// ============================================================
// 解法2: 排序 + 双指针写法
// 时间: O(n log n)  空间: O(1) (不计输出)
//
// 【思路】
// 同解法1, 但用 start/end 变量追踪当前合并区间。
// 注意: 循环结束后需要手动 push 最后一个合并区间。
//
// 相比解法1:
//   - 优点: 对某些人来说逻辑更直观
//   - 缺点: 需要收尾操作, 容易漏
// ============================================================
class Solution2 {
public:
    vector<vector<int>> merge(vector<vector<int>>& intervals) {
        sort(intervals.begin(), intervals.end());

        vector<vector<int>> res;
        int start = intervals[0][0];
        int end = intervals[0][1];

        for (int i = 1; i < (int)intervals.size(); i++) {
            if (intervals[i][0] <= end) {
                // 重叠: 扩展终点
                end = max(end, intervals[i][1]);
            } else {
                // 不重叠: 保存当前区间, 开始新的
                res.push_back({start, end});
                start = intervals[i][0];
                end = intervals[i][1];
            }
        }
        // 别忘了最后一个合并区间!
        res.push_back({start, end});
        return res;
    }
};

// ============================================================
// 解法3: 连通分量 (图论方法)
// 时间: O(n^2)  空间: O(n^2)
//
// 【思路】
// 把区间看作图的节点, 重叠的区间连边。
// 合并后的每个区间 = 图中的一个连通分量。
// 用 BFS 找连通分量, 取每个分量中的 min(start), max(end)。
//
// 价值: 展示"区间问题 → 图论"的思维转换。
// 面试中不推荐(O(n^2)太慢), 但被问"还有别的方法吗?"可以提。
// ============================================================
class Solution3 {
public:
    vector<vector<int>> merge(vector<vector<int>>& intervals) {
        int n = intervals.size();
        // 建图: O(n^2)
        vector<vector<int>> graph(n);
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                // 判断重叠: a.start <= b.end && b.start <= a.end
                if (intervals[i][0] <= intervals[j][1] &&
                    intervals[j][0] <= intervals[i][1]) {
                    graph[i].push_back(j);
                    graph[j].push_back(i);
                }
            }
        }

        // BFS 求连通分量
        vector<bool> visited(n, false);
        vector<vector<int>> res;
        for (int i = 0; i < n; i++) {
            if (visited[i]) continue;
            queue<int> q;
            q.push(i);
            visited[i] = true;
            int lo = intervals[i][0], hi = intervals[i][1];
            while (!q.empty()) {
                int cur = q.front(); q.pop();
                lo = min(lo, intervals[cur][0]);
                hi = max(hi, intervals[cur][1]);
                for (int nb : graph[cur]) {
                    if (!visited[nb]) {
                        visited[nb] = true;
                        q.push(nb);
                    }
                }
            }
            res.push_back({lo, hi});
        }
        return res;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法          | 时间      | 空间    | 代码量 | 推荐   |
// |---------------|----------|---------|--------|--------|
// | 排序+线性扫描 | O(nlogn) | O(1)*  | 最短   | ⭐首选 |
// | 排序+双指针   | O(nlogn) | O(1)*  | 中等   | 可以   |
// | 连通分量      | O(n^2)   | O(n^2) | 长     | 了解   |
//
// *不计输出数组
//
// ============================================================
// 【易错点】
//
// 1. 合并时直接赋值而非取 max:
//    ✗ res.back()[1] = iv[1]
//      → [1,10] 和 [2,3] 合并后变成 [1,3], 范围缩小了!
//    ✓ res.back()[1] = max(res.back()[1], iv[1])
//
// 2. 合并条件用 < 而非 <=:
//    ✗ iv[0] < res.back()[1]  → [1,4] 和 [4,5] 不合并
//    ✓ iv[0] <= res.back()[1] → 端点相等也合并
//
// 3. 忘记排序:
//    ✗ 不排序直接扫描 → [[1,3],[8,10],[2,6]] 中 [1,3] 和 [2,6] 不相邻
//    ✓ 必须先排序, 保证重叠区间连续
//
// 4. 双指针写法忘记收尾:
//    ✗ 循环后没有 push_back({start, end})
//    ✓ 循环后追加最后一个合并区间
//
// 5. 空输入未处理:
//    ✗ intervals为空时 intervals[0] 崩溃 (双指针写法)
//    ✓ 加 if (intervals.empty()) return {};
//       (解法1不需要, for循环天然处理空数组)
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 时间复杂度能否更优？
//     排序下界 O(nlogn), 无法更快。
//     除非值域有限用桶排序 O(n+k)。
//
// Q2: 如果区间是流式输入(一个个来), 怎么维护？
//     用有序集合(如 std::set)维护已合并区间。
//     每次新区间来, lower_bound 找重叠区间,
//     合并后删旧插新。每次 O(k logn), k为被合并数。
//
// Q3: 如果要求区间交集而非合并呢？(LC986)
//     双指针扫描两组有序区间,
//     交集 = [max(start1,start2), min(end1,end2)]。
