// 【解法对比】
// 
// | 维度         | DP O(n²)           | 贪心+二分 O(n log n)    |
// |-------------|--------------------|-----------------------|
// | 思维难度     | 低                 | 高（贪心正确性需理解）    |
// | 编码难度     | 低                 | 中                      |
// | 面试推荐     | 先写这个            | Follow-up 追问时写       |
// | 还原 LIS     | 容易（加 prev 数组）| 不能直接还原              |
// | n=2500      | ~6M 次操作，能过    | 更快但没必要              |
//
// 面试策略：先 O(n²) DP 展示思路清晰 → 面试官追问时给 O(n log n)
//
// ============================================================
// 【易错点】
//
// 1. 答案位置：
//    ✗ return dp[n-1];
//    ✓ return *max_element(dp.begin(), dp.end());
//    原因：LIS 不一定以最后一个元素结尾
//
// 2. dp 初始化：
//    ✗ vector<int> dp(n, 0);
//    ✓ vector<int> dp(n, 1);
//    原因：每个元素自身就是长度 1 的递增子序列
//
// 3. 严格递增 vs 非递减：
//    ✗ if (nums[j] <= nums[i])  — 这是非递减
//    ✓ if (nums[j] < nums[i])   — 严格递增
//    对应到二分解法：严格递增用 lower_bound，非递减用 upper_bound
//
// 4. tails 数组误当 LIS：
//    tails 的内容不是一个有效的 LIS，只有 tails.size() 是正确的
//    如果需要输出实际 LIS，需要额外记录每个元素在 tails 中的位置
//
// 5. 手写二分的边界：
//    ✗ while (lo <= hi) 配合 hi = tails.size() — 会越界
//    ✓ while (lo < hi) 配合 hi = tails.size() — 标准 lower_bound 模板
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1 (基础理解): 为什么 dp[i] 定义为"以 nums[i] 结尾"？
//    → 因为转移需要知道子序列末尾值才能判断新元素能否接上。
//      定义为"前 i 个的 LIS"转移时信息不够。
//
// Q2 (Follow-up 优化): 能否 O(n log n)?
//    → 贪心 + 二分。维护各长度子序列的最小末尾，利用有序性二分。
//
// Q3 (变体 — 还原序列): 如何输出实际的 LIS？
//    → DP 解法加 prev[i] 记录前驱，从最大 dp 处回溯。
//      二分解法需额外记录每个元素在 tails 中的索引。
//
// Q4 (拓展 — 二维): 信封嵌套问题 (354)?
//    → 按宽度升序排序，宽度相同时按高度降序，
//      然后对高度序列求一维 LIS。
//      降序是为了防止同宽度的信封互相嵌套。
//
