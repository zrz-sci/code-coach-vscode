/*
 * LeetCode 300: 最长递增子序列 (Longest Increasing Subsequence)
 * 
 * 【题目本质】
 * 在序列中选出尽可能多的元素，保持原始相对顺序且严格递增。
 * 经典的"子序列选取"问题，兼具 DP 和贪心+二分两种经典解法。
 *
 * 【解法总览】
 * 解法1: 动态规划          — O(n²) / O(n)      — 最直觉，面试首选
 * 解法2: 贪心 + 二分查找   — O(n log n) / O(n)  — Follow-up 最优解
 */

// ============================================================
// 解法1: 动态规划 — 以每个元素结尾的 LIS
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 子序列 = "选/不选"决策 → 天然适合 DP。
// 关键：状态定义为"以 nums[i] 结尾的 LIS 长度"。
// 为什么要"结尾"？因为转移时需要知道子序列末尾的值，
// 才能判断新元素能否接上去。"结尾"的定义携带了这个信息。
//
// dp[i] = max(dp[j] + 1)，对所有 j < i 且 nums[j] < nums[i]
// 答案 = max(dp[0], dp[1], ..., dp[n-1])
//
// 【DP 填表过程】 以 nums = [10, 9, 2, 5, 3, 7, 101, 18]:
//
//  索引:  0   1   2   3   4   5    6    7
//  nums: 10   9   2   5   3   7  101   18
//  dp:    1   1   1   2   2   3    4    4
//         ↑   ↑   ↑   ↑   ↑   ↑    ↑    ↑
//         无  无  无  2>2? 3>2  7>5  101>7 18>7
//         前  前  前  是!  是!  是!   是!   是!
//         驱  驱  驱  dp=2 dp=2 dp=3  dp=4  dp=4
//
// 答案 = max(1,1,1,2,2,3,4,4) = 4
// ============================================================
class Solution1 {
public:
    int lengthOfLIS(vector<int>& nums) {
        int n = nums.size();
        // dp[i]: 以 nums[i] 结尾的最长递增子序列长度
        // 初始化为 1 —— 每个元素自身是长度为 1 的子序列
        vector<int> dp(n, 1);
        
        int ans = 1;
        for (int i = 1; i < n; i++) {
            // 遍历所有可能的前驱 j
            for (int j = 0; j < i; j++) {
                // 严格递增：nums[j] < nums[i]（不是 <=）
                if (nums[j] < nums[i]) {
                    dp[i] = max(dp[i], dp[j] + 1);
                }
            }
            // 答案是所有 dp[i] 中的最大值，不是 dp[n-1]！
            // 因为 LIS 不一定以最后一个元素结尾
            ans = max(ans, dp[i]);
        }
        return ans;
    }
};

// ============================================================
// 解法2: 贪心 + 二分查找 — 维护最小末尾数组 (Follow-up)
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 解法1的瓶颈：对每个 i，要遍历所有 j < i 找最优前驱 → O(n)。
// 
// 贪心直觉：如果两个递增子序列长度相同，末尾越小越好。
// 因为末尾越小，后面能接上的元素越多，给未来留更多空间。
//
// 维护 tails 数组：tails[k] = 长度为 k+1 的递增子序列的最小末尾。
// 
// 关键性质：tails 一定是严格递增的！
// 证明（反证）：若 tails[a] >= tails[b] 且 a < b，
//   则长度 b+1 的子序列的前 a+1 个元素构成一个更短的子序列，
//   其末尾 <= tails[b] <= tails[a]，与 tails[a] 是最小矛盾。
//
// 因为 tails 有序，可以用二分查找！
//
// 对每个 nums[i]:
// - 若 nums[i] > tails 末尾：追加，LIS 长度 +1
// - 否则：二分找第一个 >= nums[i] 的位置，替换之
//
// 【tails 变化过程】 以 nums = [10, 9, 2, 5, 3, 7, 101, 18]:
//
//  num=10:  tails = [10]               ← 初始
//  num=9:   tails = [9]                ← 9 < 10, 替换 tails[0]
//  num=2:   tails = [2]                ← 2 < 9, 替换 tails[0]
//  num=5:   tails = [2, 5]             ← 5 > 2, 追加
//  num=3:   tails = [2, 3]             ← 3 替换 5 (lower_bound 找到 5)
//  num=7:   tails = [2, 3, 7]          ← 7 > 3, 追加
//  num=101: tails = [2, 3, 7, 101]     ← 101 > 7, 追加
//  num=18:  tails = [2, 3, 7, 18]      ← 18 替换 101
//
//  答案 = tails.size() = 4
//
// 注意：tails 最终内容 [2,3,7,18] 不是实际的 LIS！
//       实际 LIS 可以是 [2,3,7,101] 或 [2,5,7,101] 等。
//       tails 只能用于求长度。
// ============================================================
class Solution2 {
public:
    int lengthOfLIS(vector<int>& nums) {
        // tails[k]: 长度为 k+1 的递增子序列的最小末尾
        vector<int> tails;
        
        for (int num : nums) {
            // 在 tails 中二分查找第一个 >= num 的位置
            // 为什么用 lower_bound (>=) 而不是 upper_bound (>)?
            // 因为是"严格递增"，相等的元素不能算递增，需要替换
            auto it = lower_bound(tails.begin(), tails.end(), num);
            
            if (it == tails.end()) {
                // num 比所有现有末尾都大 → 可以延伸最长子序列
                tails.push_back(num);
            } else {
                // 用 num 替换第一个 >= num 的位置
                // 这维护了"最小末尾"的贪心性质
                *it = num;
            }
        }
        
        // tails 的长度就是 LIS 的长度
        return tails.size();
    }
};

// ============================================================
// 解法2 变体: 手写二分（不用 STL lower_bound）
// 适合面试中展示二分查找基本功
//
// 【二分搜索空间收缩过程】
// tails = [2, 3, 7, 101], 查找 num = 18:
//
// Round1: lo=0, hi=3, mid=1, tails[1]=3 < 18 → lo=2
// Round2: lo=2, hi=3, mid=2, tails[2]=7 < 18 → lo=3
// Round3: lo=3, hi=3, mid=3, tails[3]=101 >= 18 → hi=3
// 退出: lo=3=hi → 替换 tails[3]=18
//       tails = [2, 3, 7, 18]
// ============================================================
class Solution2_ManualBinarySearch {
public:
    int lengthOfLIS(vector<int>& nums) {
        vector<int> tails;
        
        for (int num : nums) {
            // 手写二分：找 tails 中第一个 >= num 的位置
            int lo = 0, hi = tails.size();
            while (lo < hi) {
                int mid = lo + (hi - lo) / 2;
                if (tails[mid] < num) {
                    lo = mid + 1;  // tails[mid] 太小，排除左半
                } else {
                    hi = mid;      // tails[mid] >= num，可能是答案，收缩右界
                }
            }
            // lo 就是第一个 >= num 的位置
            
            if (lo == (int)tails.size()) {
                tails.push_back(num);
            } else {
                tails[lo] = num;
            }
        }
        
        return tails.size();
    }
};

