/*
 * LeetCode 344: 反转字符串 (Reverse String)
 *
 * 【题目本质】
 * 原地反转字符数组 —— 把对称位置的元素两两交换。
 * 这是对撞双指针（Two Pointers）最基础的应用。
 *
 * 【解法总览】
 * 解法1: 双指针（对撞指针）— O(n) / O(1) — ⭐ 面试首选
 * 解法2: 递归             — O(n) / O(n) — 展示递归思维
 * 解法3: STL reverse      — O(n) / O(1) — 了解即可
 */

// ============================================================
// 解法1: 双指针（对撞指针） — 首尾交换，向中间收拢
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 反转 = 第i个元素和第(n-1-i)个元素交换。
// 用 left 和 right 两个指针从两端出发，
// 每次交换后各向中间走一步，直到相遇。
//
// 交换过程可视化 (s = "hello"):
//
//   Step0: [h, e, l, l, o]
//           ↑           ↑
//          left        right
//
//   Step1: [o, e, l, l, h]    ← swap(h, o)
//              ↑     ↑
//             left  right
//
//   Step2: [o, l, l, e, h]    ← swap(e, l)
//                 ↑
//             left=right       ← left >= right, 停止
//
//   结果: [o, l, l, e, h]  ✓
//
// 偶数长度 (s = "Hannah"):
//
//   Step0: [H, a, n, n, a, h]
//           ↑              ↑
//          left           right
//
//   Step1: [h, a, n, n, a, H]   ← swap(H, h)
//              ↑        ↑
//             left     right
//
//   Step2: [h, a, n, n, a, H]   ← swap(a, a) (相同也交换，无影响)
//                 ↑  ↑
//                left right
//
//   Step3: [h, a, n, n, a, H]   ← swap(n, n)
//                    left > right → 停止
//
//   结果: [h, a, n, n, a, H]  ✓
// ============================================================
class Solution1 {
public:
    void reverseString(vector<char>& s) {
        int left = 0, right = (int)s.size() - 1;
        while (left < right) {
            // 交换对称位置的字符，然后指针向中间靠拢
            swap(s[left], s[right]);
            left++;
            right--;
        }
        // 为什么 left < right 而不是 left <= right?
        // 当 left == right 时指向同一个元素，无需交换
    }
};

// ============================================================
// 解法2: 递归 — 递归交换首尾，缩小问题规模
// 时间: O(n)  空间: O(n) — 递归栈深度 n/2
//
// 【思路】
// 和双指针本质相同，只是用递归调用栈代替 while 循环：
//   1. 交换 s[left] 和 s[right]
//   2. 递归处理子问题 [left+1, right-1]
//   3. 终止条件: left >= right
//
// 注意：递归深度为 n/2，栈空间 O(n)，
// 严格来说不满足题目 O(1) 空间的要求。
// 但面试中可以用来展示递归思维，同时主动指出空间劣势。
// ============================================================
class Solution2 {
public:
    void reverseString(vector<char>& s) {
        helper(s, 0, (int)s.size() - 1);
    }

private:
    void helper(vector<char>& s, int left, int right) {
        // 终止条件：指针相遇或交叉
        if (left >= right) return;

        // 交换当前首尾
        swap(s[left], s[right]);

        // 递归缩小范围 —— 等价于双指针的 left++, right--
        helper(s, left + 1, right - 1);
    }
};

// ============================================================
// 解法3: STL reverse — 一行搞定
// 时间: O(n)  空间: O(1)
//
// 【思路】
// C++ STL 的 std::reverse 内部实现就是双指针交换。
// 了解即可，面试中不建议只写这一行。
// ============================================================
class Solution3 {
public:
    void reverseString(vector<char>& s) {
        reverse(s.begin(), s.end());
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间  | 空间  | 满足 O(1) | 面试推荐 |
// |------------|-------|-------|-----------|----------|
// | 双指针     | O(n)  | O(1)  | ✓         | ⭐ 首选  |
// | 递归       | O(n)  | O(n)  | ✗         | 能说即可 |
// | STL        | O(n)  | O(1)  | ✓         | 了解即可 |
//
// 三种解法本质都是首尾交换，区别只在实现方式。
// 面试写解法1（双指针），简洁高效，空间 O(1)。
//
// 【易错点】
//
// 1. 循环条件写成 left <= right
//    ✗ while (left <= right) { swap... }
//      → left==right 时自己和自己交换，不出 bug 但多余
//    ✓ while (left < right)
//
// 2. right 初始化错误
//    ✗ int right = s.size();      → 越界！s[s.size()] 不存在
//    ✓ int right = s.size() - 1;  → 最后一个有效下标
//
// 3. 递归忘记终止条件
//    ✗ 没有 if (left >= right) return;  → 无限递归，栈溢出
//    ✓ 递归函数第一行必须写终止条件
//
// 4. s.size() 返回 unsigned，size()-1 在空数组上溢出
//    ✗ int right = s.size() - 1;  当 s 为空时，size()=0，
//      0u - 1 = 4294967295 (unsigned 溢出)
//    ✓ 先判断空数组，或强转 int right = (int)s.size() - 1;
//      本题约束 s.length >= 1，但养成习惯更安全
//
// 【面试追问 — 递进链】
//
// Q1: 时间复杂度是多少？
//   → O(n)，精确是 n/2 次交换，每次 O(1)。
//
// Q2: 如果不用 swap，怎么交换两个变量？
//   → 临时变量法: char t = a; a = b; b = t;
//   → 异或法: a ^= b; b ^= a; a ^= b;
//     (注意：如果 a 和 b 是同一个内存地址，异或法会把值清零)
//
// Q3: 如果要反转的不是整个数组，而是 [i, j] 区间呢？
//   → 把 left=0, right=n-1 改成 left=i, right=j 即可。
//     这个"区间反转"是很多题的子操作（如 151 反转单词）。
//
// Q4: 如果输入是 UTF-8 编码的多字节字符呢？
//   → 每个"字符"可能占多个字节，不能简单按字节反转。
//     需要先解析出字符边界，再以字符为单位反转。
//
// 【相关题型】
//
// - 541. 反转字符串 II
//   复用本题的区间反转，区别：每 2k 个字符只反转前 k 个
//
// - 151. 反转字符串中的单词
//   调用两次本题的反转：先整体反转，再逐词反转
//
// - 125. 验证回文串
//   同样对撞双指针，区别：比较而非交换
//
// - 917. 仅仅反转字母
//   对撞双指针，区别：遇到非字母跳过
// ============================================================
