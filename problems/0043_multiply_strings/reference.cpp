/*
 * LeetCode 43: 字符串相乘 (Multiply Strings)
 *
 * 【题目本质】
 * 模拟手算竖式乘法：两个大整数逐位相乘，用数组存储每一位的累加值，
 * 最后统一处理进位。核心是位置映射：num1[i] × num2[j] 落在 result[i+j] 和 result[i+j+1]。
 *
 * 【解法总览】
 * 解法1: 逐行累加（竖式模拟 + 大数加法）— O(m·n·(m+n)) / O(m+n) — 最直觉
 * 解法2: 乘积数组（位置映射）          — O(m·n) / O(m+n) — 面试首选 ⭐
 */

// ============================================================
// 解法1: 逐行累加 — 完全模拟竖式乘法过程
// 时间: O(m·n·(m+n))  空间: O(m+n)
//
// 【思路】
// 和小学手算竖式完全一致：
// 1. 用 num2 的每一位分别乘以整个 num1，得到一个中间结果字符串
// 2. 中间结果根据位数补零（等价于左移）
// 3. 所有中间结果用大数加法累加起来
//
// 这个方法最直觉，但缺点是需要反复做字符串加法，
// 每次加法是 O(m+n)，做 n 次，再加上每次乘法 O(m)，
// 总体约 O(m·n + n·(m+n))。
//
// 竖式示意 (123 × 456):
//         1  2  3
//      ×  4  5  6
//      ---------
//         7  3  8      ← 123 × 6
//      6  1  5         ← 123 × 5, 左移1位
//   4  9  2            ← 123 × 4, 左移2位
//   ----------------
//   5  6  0  8  8
// ============================================================
class Solution1 {
public:
    string multiply(string num1, string num2) {
        if (num1 == "0" || num2 == "0") return "0";
        
        int m = num1.size(), n = num2.size();
        string result = "0";
        
        for (int j = n - 1; j >= 0; j--) {
            string cur;
            int carry = 0;
            
            // 补零：num2 的第 j 位（从左数）对应左移 (n-1-j) 位
            for (int k = 0; k < n - 1 - j; k++) {
                cur += '0';
            }
            
            int d2 = num2[j] - '0';
            // num1 从低位到高位，逐位与 d2 相乘
            for (int i = m - 1; i >= 0; i--) {
                int prod = (num1[i] - '0') * d2 + carry;
                cur += (char)('0' + prod % 10);
                carry = prod / 10;
            }
            if (carry) cur += (char)('0' + carry);
            
            // cur 是低位在前，需要反转
            reverse(cur.begin(), cur.end());
            
            // 大数加法累加
            result = addStrings(result, cur);
        }
        
        return result;
    }
    
private:
    // 大数加法：从末尾对齐，逐位加 + 进位
    string addStrings(const string& a, const string& b) {
        string res;
        int i = a.size() - 1, j = b.size() - 1, carry = 0;
        while (i >= 0 || j >= 0 || carry) {
            int sum = carry;
            if (i >= 0) sum += a[i--] - '0';
            if (j >= 0) sum += b[j--] - '0';
            res += (char)('0' + sum % 10);
            carry = sum / 10;
        }
        reverse(res.begin(), res.end());
        return res;
    }
};

// ============================================================
// 解法2: 乘积数组（位置映射）— 面试首选 ⭐
// 时间: O(m·n)  空间: O(m+n)
//
// 【思路】
// 解法1 的瓶颈在于反复做字符串加法。如果我们能直接把每一对
// num1[i] × num2[j] 的乘积放到正确的位置上，就不需要中间字符串了。
//
// 关键观察 — 位置映射规律:
//   num1[i] × num2[j] 的乘积是一个 ≤81 的两位数
//   高位（十位）放到 result[i+j]
//   低位（个位）放到 result[i+j+1]
//
// 为什么？因为 num1[i] 代表 10^(m-1-i)，num2[j] 代表 10^(n-1-j)，
// 它们的乘积贡献到 10^(m+n-2-i-j) 这个量级，
// 对应 result 数组从左数第 (i+j) 位（高位）和第 (i+j+1) 位（低位）。
//
// 详细填表过程 (123 × 456):
//
//  result 数组有 m+n = 6 个位置: [0] [1] [2] [3] [4] [5]
//
//  i=2,j=2: 3×6=18 → result[5]+=8, result[4]+=1
//  i=2,j=1: 3×5=15 → 15+result[4]=16 → result[4]=6, result[3]+=1
//  i=2,j=0: 3×4=12 → 12+result[3]=13 → result[3]=3, result[2]+=1
//  i=1,j=2: 2×6=12 → 12+result[4]=18 → result[4]=8, result[3]+=1
//  i=1,j=1: 2×5=10 → 10+result[3]=14 → result[3]=4, result[2]+=1
//  i=1,j=0: 2×4= 8 →  8+result[2]=10 → result[2]=0, result[1]+=1
//  i=0,j=2: 1×6= 6 →  6+result[3]=10 → result[3]=0, result[2]+=1
//  i=0,j=1: 1×5= 5 →  5+result[2]= 6 → result[2]=6, result[1]+=0
//  i=0,j=0: 1×4= 4 →  4+result[1]= 5 → result[1]=5, result[0]+=0
//
//  最终: [0] [5] [6] [0] [8] [8] → 跳过前导零 → "56088" ✓
// ============================================================
class Solution2 {
public:
    string multiply(string num1, string num2) {
        int m = num1.size(), n = num2.size();
        
        // m位 × n位 的乘积最多 m+n 位
        // 例: 99×99 = 9801 (2位×2位 = 4位)
        vector<int> result(m + n, 0);
        
        // 从最低位开始逐对相乘
        // 为什么从低位开始？因为进位是从低位向高位传递的
        for (int i = m - 1; i >= 0; i--) {
            for (int j = n - 1; j >= 0; j--) {
                int mul = (num1[i] - '0') * (num2[j] - '0');
                
                // 位置映射：i+j 是高位，i+j+1 是低位
                int p1 = i + j;      // 进位目标位置
                int p2 = i + j + 1;  // 当前位位置
                
                // 关键：要加上 result[p2] 已有的累加值！
                // 这里同时处理了"累加"和"进位"两件事
                int sum = mul + result[p2];
                
                result[p2] = sum % 10;   // 当前位只保留个位
                result[p1] += sum / 10;  // 十位进位到高位
            }
        }
        
        // 拼接结果字符串，跳过前导零
        string str;
        for (int digit : result) {
            if (str.empty() && digit == 0) continue;  // 跳过前导零
            str += (char)('0' + digit);
        }
        
        // 全部为零的情况（如 "0" × "0"）
        return str.empty() ? "0" : str;
    }
};

// ============================================================
// 【解法对比】
//
// 解法1 vs 解法2:
// - 解法1 完全模拟竖式，需要额外实现大数加法，代码量大，常数大
// - 解法2 用数组直接累加，避免了字符串操作，是最简洁高效的做法
// - 面试中直接写解法2，但要能解释清楚位置映射的原理
//
// 【易错点】
//
// 1. 位置映射搞反:
//    ✗ p1 = i + j + 1, p2 = i + j  (高低位反了)
//    ✓ p1 = i + j (高位), p2 = i + j + 1 (低位)
//    记忆: i=0,j=0 时乘积应在最高位 → p1 = 0+0 = 0
//
// 2. 累加时漏掉已有值:
//    ✗ int sum = mul;
//    ✓ int sum = mul + result[p2];
//    因为 result[p2] 可能已经被之前的 (i',j') 对累加过了
//
// 3. 前导零处理:
//    ✗ 直接把整个 result 数组转字符串 → 可能输出 "056088"
//    ✓ 跳过前导零: if (str.empty() && digit == 0) continue;
//    ✗ 但如果结果本身就是 0 呢？→ 最后兜底: return str.empty() ? "0" : str;
//
// 4. 没处理 "0" 输入:
//    ✗ "0" × "123" 可能输出 "000" 或空串
//    ✓ 解法2 的前导零跳过 + 兜底已经自然处理了这种情况
//       但也可以在开头加 if (num1 == "0" || num2 == "0") return "0"; 提前返回
//
// 【面试追问】
//
// Q1(基础理解): 为什么 m 位数 × n 位数最多 m+n 位？
//    → (10^m - 1) × (10^n - 1) < 10^(m+n)，所以不超过 m+n 位。
//
// Q2(细节): result[p1] += sum/10 会不会导致某个位置超过 9？
//    → 会！但没关系。比如 result[p1] 可能暂时变成 10+，
//      但当后续处理到 (i', j') 使得 p2' == p1 时，sum = mul + result[p1]
//      会继续往更高位进位。最终遍历完所有 (i,j) 对后，
//      只有 result[0] 可能 >9（实际不会，因为已经充分进位了）。
//      实际上逐对处理时每次都在进位，所以最终每位都在 0-9 范围内。
//
// Q3(变体): 如果要实现大数加法（LeetCode 415），代码怎么写？
//    → 双指针从末尾对齐，逐位加 + 进位，参见解法1的 addStrings。
//
// Q4(进阶): 有没有比 O(m·n) 更快的大数乘法？
//    → Karatsuba 算法 O(n^1.585)，基于分治：
//      将 n 位数拆成两半，3 次递归乘法代替 4 次。
//      FFT/NTT 可达 O(n log n)，面试中了解即可。
// ============================================================
