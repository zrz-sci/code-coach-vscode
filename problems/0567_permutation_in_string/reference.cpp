/*
 * LeetCode 567: 字符串的排列 (Permutation in String)
 *
 * 【题目本质】
 * 判断 s2 中是否存在一个长度等于 len(s1) 的连续子串，
 * 使得该子串与 s1 的字符频次完全相同（即互为排列/异位词）。
 * 核心洞察：排列 ⟺ 频次相同 → 固定大小滑动窗口 + 频次比较。
 *
 * 【解法总览】
 * 解法1: 滑窗 + 频次数组比较   — O(26×m) / O(1) — 最直觉，代码最简
 * 解法2: 滑窗 + diff 计数器    — O(m) / O(1)    — 面试首选，真正 O(m)
 * 解法3: 滑窗 + match 计数器   — O(m) / O(1)    — 解法2的对偶写法
 *
 * 其中 n = len(s1), m = len(s2)
 */

// ============================================================
// 解法1: 滑动窗口 + 频次数组比较 — O(26×m) / O(1)
//
// 【思路】
// 排列 = 频次相同。用固定大小为 n 的窗口在 s2 上滑动。
// 每次窗口移动：加入右端新字符，移除左端旧字符，然后比较
// 两个长度为 26 的频次数组是否完全相等。
//
// 为什么 O(26m)？每次滑动后 vector == 比较需要遍历 26 个元素。
// 实际上 26 是常数，所以也算 O(m)，但可以做得更纯粹。
//
// 滑窗过程 (s1="ab", s2="eidbaooo", 窗口大小=2):
//   e i d b a o o o
//   [e i]             cnt2={e:1,i:1} ≠ cnt1={a:1,b:1}
//     [i d]           cnt2={i:1,d:1} ≠
//       [d b]         cnt2={d:1,b:1} ≠
//         [b a]       cnt2={b:1,a:1} == cnt1  → true!
// ============================================================
class Solution1 {
public:
    bool checkInclusion(string s1, string s2) {
        int n = s1.size(), m = s2.size();
        if (n > m) return false;  // s1 比 s2 长，不可能包含

        vector<int> cnt1(26, 0), cnt2(26, 0);
        // 初始化：统计 s1 频次 和 s2 前 n 个字符的频次
        for (int i = 0; i < n; i++) {
            cnt1[s1[i] - 'a']++;
            cnt2[s2[i] - 'a']++;
        }
        if (cnt1 == cnt2) return true;

        // 窗口从位置 n 开始向右滑动
        for (int i = n; i < m; i++) {
            cnt2[s2[i] - 'a']++;       // 新字符进入窗口右端
            cnt2[s2[i - n] - 'a']--;   // 旧字符离开窗口左端
            // 此时窗口为 [i-n+1, i]，大小恒为 n
            if (cnt1 == cnt2) return true;
        }
        return false;
    }
};

// ============================================================
// 解法2: 滑动窗口 + diff 计数器 — O(m) / O(1) ⭐ 面试首选
//
// 【思路】
// 解法1 每次滑动后需要比较 26 个位置，虽然是常数但不够优雅。
// 优化：用一个 diff 变量记录"有多少种字符的频次还不匹配"。
//
// 维护 cnt[c] = s1中c的频次 - 窗口中c的频次
//   - cnt[c] == 0 → 字符 c 完全匹配
//   - cnt[c] != 0 → 字符 c 不匹配
//   - diff = 所有 cnt[c] != 0 的 c 的种数
//   - diff == 0 → 所有字符都匹配 → 找到排列!
//
// 每次窗口滑动，只有 2 个字符变化（一进一出），
// 每个字符最多影响 diff ±1，所以更新是 O(1)。
//
// diff 更新逻辑（以进入字符 c 为例，cnt[c]--）：
//   更新前 cnt[c]==0 → 原本匹配的，这一改就不匹配了 → diff++
//   cnt[c]--
//   更新后 cnt[c]==0 → 改完之后恰好匹配了 → diff--
//
// 注意顺序：先判断旧值 → 修改 → 再判断新值
// ============================================================
class Solution2 {
public:
    bool checkInclusion(string s1, string s2) {
        int n = s1.size(), m = s2.size();
        if (n > m) return false;

        // cnt[c] = s1中c的频次 - 窗口中c的频次
        vector<int> cnt(26, 0);
        for (int i = 0; i < n; i++) {
            cnt[s1[i] - 'a']++;   // s1 贡献 +1
            cnt[s2[i] - 'a']--;   // 初始窗口贡献 -1
        }

        // 统计初始有多少种字符不匹配
        int diff = 0;
        for (int i = 0; i < 26; i++) {
            if (cnt[i] != 0) diff++;
        }
        if (diff == 0) return true;

        for (int i = n; i < m; i++) {
            // --- 新字符 s2[i] 进入窗口，cnt 对应位 -1 ---
            int in_c = s2[i] - 'a';
            if (cnt[in_c] == 0) diff++;    // 修改前匹配 → 修改后一定不匹配
            cnt[in_c]--;
            if (cnt[in_c] == 0) diff--;    // 修改后恰好匹配

            // --- 旧字符 s2[i-n] 离开窗口，cnt 对应位 +1 ---
            int out_c = s2[i - n] - 'a';
            if (cnt[out_c] == 0) diff++;   // 修改前匹配 → 修改后一定不匹配
            cnt[out_c]++;
            if (cnt[out_c] == 0) diff--;   // 修改后恰好匹配

            if (diff == 0) return true;
        }
        return false;
    }
};

// ============================================================
// 解法3: 滑动窗口 + match 计数器 — O(m) / O(1)
//
// 【思路】
// 与解法2 是"对偶"关系：
//   解法2 记录"不匹配的种数 diff"，diff==0 时匹配
//   解法3 记录"已匹配的种数 match"，match==26 时匹配
//
// 需要两个频次数组 cnt1 和 cnt2，match 记录有多少个位置
// cnt1[i] == cnt2[i]。
//
// 进入字符 c:
//   cnt2[c]++
//   如果 cnt2[c] == cnt1[c]  → 刚好匹配了 → match++
//   如果 cnt2[c] == cnt1[c]+1 → 刚超过，从匹配变不匹配 → match--
//
// 离开字符 c:
//   cnt2[c]--
//   如果 cnt2[c] == cnt1[c]  → 刚好匹配了 → match++
//   如果 cnt2[c] == cnt1[c]-1 → 刚不够，从匹配变不匹配 → match--
// ============================================================
class Solution3 {
public:
    bool checkInclusion(string s1, string s2) {
        int n = s1.size(), m = s2.size();
        if (n > m) return false;

        vector<int> cnt1(26, 0), cnt2(26, 0);
        for (int i = 0; i < n; i++) {
            cnt1[s1[i] - 'a']++;
            cnt2[s2[i] - 'a']++;
        }

        // 初始匹配种数（包括两边都是0的字符）
        int match = 0;
        for (int i = 0; i < 26; i++) {
            if (cnt1[i] == cnt2[i]) match++;
        }
        if (match == 26) return true;

        for (int i = n; i < m; i++) {
            int in_c = s2[i] - 'a';
            int out_c = s2[i - n] - 'a';

            // 新字符进入
            cnt2[in_c]++;
            if (cnt2[in_c] == cnt1[in_c]) match++;         // 变匹配
            else if (cnt2[in_c] == cnt1[in_c] + 1) match--; // 刚超过

            // 旧字符离开
            cnt2[out_c]--;
            if (cnt2[out_c] == cnt1[out_c]) match++;
            else if (cnt2[out_c] == cnt1[out_c] - 1) match--;

            if (match == 26) return true;
        }
        return false;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间     | 空间 | 核心区别               |
// |------|----------|------|------------------------|
// | 1    | O(26×m)  | O(1) | 每次比较 26 个位置       |
// | 2    | O(m)     | O(1) | diff 计数器，O(1)判断    |
// | 3    | O(m)     | O(1) | match 计数器，解法2对偶  |
//
// 面试建议：先写解法1确保正确性，再口述/改写解法2。
// 解法2 和 解法3 本质相同，选自己更不容易写错的。
//
// 【易错点】
//
// 1. 忘记 n > m 的判断：
//    ✗ 直接滑窗 → 初始化循环 for(i=0;i<n;i++) 访问 s2[i] 越界
//    ✓ 开头 if (n > m) return false;
//
// 2. diff/match 更新顺序错误：
//    ✗ cnt[in_c]--; if (cnt[in_c] == 0) diff--; if (cnt[in_c] == -1) diff++;
//       → 这样是"先改后判"，要用 -1 和 0 来判断，容易搞混
//    ✓ 先判断修改前 → 修改 → 再判断修改后（解法2的写法更清晰）
//
// 3. 窗口左端移除的索引算错：
//    ✗ s2[i - n + 1] → 窗口实际变成 n+1 大小
//    ✓ s2[i - n]     → 窗口是 [i-n+1, i]，移除的是上一个窗口的左端 i-n
//
// 4. match 初始化漏掉"两边都是0"的字符：
//    ✗ 只在 cnt1[i] > 0 时比较 → 漏掉了那些 s1 中没出现、窗口中也没出现的字符
//    ✓ 遍历全部 26 个字符，cnt1[i]==0 && cnt2[i]==0 也算 match++
//
// 【面试追问】
//
// Q1(基础): "为什么不用真的生成排列?"
//   → 排列数是 n!，而我们只需要比较频次。两个字符串互为排列 ⟺ 频次完全相同。
//
// Q2(优化): "每次比较 26 个位置，能不能做到真正 O(1) 判断?"
//   → 用 diff 计数器。记录有多少种字符不匹配，每次滑动只更新进出两个字符，
//     O(1) 更新 diff，当 diff==0 时就是匹配。
//
// Q3(变体): "如果要返回所有匹配的起始位置呢?"
//   → 就是 LeetCode 438。框架完全一样，把 return true 改成
//     result.push_back(i - n + 1) 并继续滑动即可。
//
// Q4(扩展): "如果字符集是整个 Unicode 而不是 26 个字母呢?"
//   → 用 unordered_map 替代 int[26]。diff 计数器的逻辑完全不变，
//     此时 diff 的优势更大——不用遍历整个 map。
// ============================================================
