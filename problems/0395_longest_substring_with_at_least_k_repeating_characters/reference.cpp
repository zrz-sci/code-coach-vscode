/*
 * LeetCode 395: Longest Substring with At Least K Repeating Characters
 * (至少有 K 个重复字符的最长子串)
 *
 * 【题目本质】
 * 找最长子串，使得子串内每个字符的出现次数都 >= k。
 * 关键洞察：频率 < k 的字符是天然的分割点 —— 它们不可能出现在任何合法子串中。
 *
 * 【解法总览】
 * 解法1: 分治递归   — O(26n) / O(26)  — 面试首选，直觉清晰
 * 解法2: 滑动窗口   — O(26n) / O(1)   — 加分项，需要理解枚举技巧
 */


// ============================================================
// 解法1: 分治递归 — 面试首选 ⭐
// 时间: O(26n)  空间: O(26) 递归栈
//
// 【思路】
// 1. 统计整个字符串的字符频率
// 2. 找到频率 < k 的"坏"字符
// 3. 以坏字符为分割点，把字符串切成几段
// 4. 对每段递归求解，取最大值
// 5. 如果没有坏字符 → 整个字符串都合法
//
// 为什么坏字符是天然分割点？
//   如果字符 c 在整个字符串中出现 < k 次，
//   那么即便把整个字符串算上，c 也不够 k 次。
//   所以 c 不可能出现在任何合法子串中。
//   合法子串只能在 c 的间隔中。
//
// 递归一定终止吗？
//   是的。每层递归至少淘汰一种坏字符。
//   最多 26 种字母 → 最多递归 26 层。
//   每层所有分支的总长度 <= n。
//   总复杂度: 26 * n = O(n)。
//
// 示例: s = "ababbc", k = 2
//   第1层: 频率 a:2, b:3, c:1
//          c 是坏字符 (1 < 2)，在位置 5
//          分割: [0,5) = "ababb" 和 [6,6) = ""
//
//   第2层 "ababb": 频率 a:2, b:3
//          所有频率 >= 2 → 返回长度 5 ✓
//
//   第2层 "": 长度 0 < 2 → 返回 0
//
//   结果: max(5, 0) = 5
// ============================================================
class Solution1 {
public:
    int longestSubstring(string s, int k) {
        return helper(s, 0, s.size(), k);
    }

    // 处理 s[start..end) 子串（左闭右开）
    int helper(const string& s, int start, int end, int k) {
        // 基础情况：子串长度 < k，不可能满足条件
        if (end - start < k) return 0;

        // Step 1: 统计当前子串内的字符频率
        int freq[26] = {};
        for (int i = start; i < end; i++) {
            freq[s[i] - 'a']++;
        }

        // Step 2: 找第一个频率 < k 的字符作为分割点
        for (int i = start; i < end; i++) {
            if (freq[s[i] - 'a'] < k) {
                // 找到坏字符！跳过连续的坏字符
                // (连续多个坏字符中间的空段没必要递归)
                int j = i + 1;
                while (j < end && freq[s[j] - 'a'] < k) j++;

                // 递归处理左段 [start, i) 和右段 [j, end)
                // 只需找第一个坏字符分割即可——
                // 左段如果还有坏字符，下一层递归会继续分割
                int leftResult  = helper(s, start, i, k);
                int rightResult = helper(s, j, end, k);
                return max(leftResult, rightResult);
            }
        }

        // Step 3: 没有坏字符 → 所有字符频率都 >= k
        // 当前子串就是一个合法子串
        return end - start;
    }
};


// ============================================================
// 解法2: 滑动窗口变体 — 加分项
// 时间: O(26n)  空间: O(1)
//
// 【思路】
// 直接对"所有字符频率 >= k"做滑窗不行，因为没有单调性。
// 关键技巧：枚举"窗口内恰好有 t 种不同字符"(t = 1..26)。
// 对于固定的 t，滑窗有明确的收缩条件：
//   不同字符数 > t → 收缩左边界
//
// 维护两个计数器：
//   unique:    窗口内不同字符总数
//   atLeastK:  窗口内频率 >= k 的字符数
//
// 合法窗口条件：unique == t && atLeastK == t
// 含义：恰好 t 种不同字符，且每种频率都 >= k
//
// 为什么枚举 t 就能用滑窗了？
//   固定 t 后，"不同字符数 > t" 是收缩的明确条件。
//   而不同字符数关于右指针的移动是单调不减的（加入新字符只会增加）。
//   这满足滑动窗口的基本条件。
//
// 示例: s = "ababbc", k = 2
//
// t=2 的滑窗过程:
// [a]babbc      unique=1, atLeastK=0
// [ab]abbc      unique=2, atLeastK=0
// [aba]bbc      unique=2, atLeastK=1 (a:2>=2)
// [abab]bc      unique=2, atLeastK=2 → 合法! 长度=4
// [ababb]c      unique=2, atLeastK=2 → 合法! 长度=5
// [ababbc]      unique=3 > t=2 → 收缩
//   → a[babbc]  unique=3, 继续收缩
//   → ab[abbc]  unique=2 → 停止. atLeastK=1 → 不合法
//
// t=2 最大长度 = 5 → 最终答案
// ============================================================
class Solution2 {
public:
    int longestSubstring(string s, int k) {
        int n = s.size();
        int result = 0;

        // 外层：枚举窗口内不同字符数 t
        // 最多 26 种小写字母
        for (int t = 1; t <= 26; t++) {
            int freq[26] = {};
            int left = 0;
            int unique = 0;     // 窗口内不同字符数
            int atLeastK = 0;   // 窗口内频率 >= k 的字符数

            for (int right = 0; right < n; right++) {
                // 扩展右边界
                int ridx = s[right] - 'a';
                if (freq[ridx] == 0) unique++;   // 新字符出现
                freq[ridx]++;
                if (freq[ridx] == k) atLeastK++; // 刚好达到 k

                // 收缩左边界：当不同字符数 > t
                while (unique > t) {
                    int lidx = s[left] - 'a';
                    if (freq[lidx] == k) atLeastK--; // 即将低于 k
                    freq[lidx]--;
                    if (freq[lidx] == 0) unique--;   // 字符消失
                    left++;
                }

                // 检查当前窗口是否合法：
                // 恰好 t 种不同字符，且每种频率都 >= k
                if (unique == t && atLeastK == t) {
                    result = max(result, right - left + 1);
                }
            }
        }

        return result;
    }
};


// ============================================================
// 【解法对比】
//
// | 解法      | 时间    | 空间   | 优势                   | 劣势               |
// |-----------|--------|--------|----------------------|-------------------|
// | 分治递归  | O(26n) | O(26)  | 直觉清晰，代码简洁     | 递归开销           |
// | 滑动窗口  | O(26n) | O(1)   | 无递归，迭代更高效     | 需要理解枚举t的技巧 |
//
// 面试选择：先讲分治（更容易理解和解释），
// 面试官追问优化时讲滑窗变体。
//
// ============================================================
// 【易错点】
//
// 1. 分治时不跳过连续坏字符:
//    ✗ 对每个坏字符位置单独递归 → 产生大量空段，效率低
//    ✓ while (j < end && freq[s[j]-'a'] < k) j++; 跳过连续坏字符
//
// 2. 递归区间用闭区间容易出错:
//    ✗ helper(s, start, i-1, k) → 边界处理复杂
//    ✓ 统一用左闭右开 [start, end) → helper(s, start, i, k)
//
// 3. 滑窗中 atLeastK 的更新时机:
//    扩展: freq[ridx]++; if (freq[ridx] == k) atLeastK++;
//    收缩: if (freq[lidx] == k) atLeastK--; freq[lidx]--;
//    注意：扩展先++再判断，收缩先判断再--
//
// 4. 忘记处理 k=1 的特殊情况:
//    k=1 时任何非空子串都合法 → 答案就是字符串全长
//    分治法自动处理（没有坏字符直接返回全长）
//
// 5. 滑窗 unique 更新顺序:
//    扩展: 先检查 freq==0 (新字符), 再 freq++
//    收缩: 先 freq--, 再检查 freq==0 (字符消失)
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么不能直接用标准滑窗？
//     "所有字符频率>=k" 没有单调性——加入新字符可能让某些字符
//     达标但让窗口内出现不够频繁的新字符。
//     固定不同字符数 t 后才有单调性。
//
// Q2: 分治的递归深度严格证明？
//     每层至少淘汰一种频率<k的字符。字母表26个→最多26层。
//     每层所有分支总扫描长度 <= n → 总时间 O(26n)。
//
// Q3: 字符集从26扩展到任意大小怎么办？
//     分治: 递归深度 = min(|charset|, 字符串中不同字符数)
//     滑窗: 外层枚举变成 O(|charset|)
//     实际中分治更优，因为递归深度取决于实际出现的字符数。
//
// ============================================================
