/*
 * LeetCode 2141: 同时运行 N 台电脑的最长时间
 * 
 * 【题目本质】
 * 电池可以随时切换 → 电量可以在电脑间"流动"。
 * 问题转化为：找最大的 T，使得所有电池对 T 的"有效贡献"总和 >= n*T。
 * 每块电池对 T 的有效贡献 = min(电量, T)（因为同一时刻只能给一台电脑用）。
 *
 * 【解法总览】
 * 解法1: 二分答案 + 贪心验证 — O(m·log(sum/n)) / O(1) — 面试首选⭐
 * 解法2: 排序 + 贪心       — O(m·log m) / O(1)         — 更优雅的数学解法
 */

// ============================================================
// 解法1: 二分答案 + 贪心验证
// 时间: O(m · log(sum/n))  空间: O(1)
//
// 【思路】
// "最大化运行时间"→ 答案有单调性 → 二分答案。
//
// 二分的关键是 check(T) 函数：
// - n 台电脑运行 T 分钟，总需求 = n * T
// - 每块电池 b 的有效贡献 = min(b, T)
//   （为什么？同一时刻一块电池只能给一台电脑，所以 T 分钟内最多用 T）
// - 总贡献 >= 总需求 → 可行
//
// 为什么总贡献 >= n*T 就一定能构造出合法方案？
// 把 n*T 想象成一个 n×T 的网格（n台电脑×T分钟）：
//   电脑1: [___________] T分钟
//   电脑2: [___________] T分钟
//   ...
//   电脑n: [___________] T分钟
// 大电池(>=T)独占一整行，小电池(<T)像水一样流动填充剩余空位。
// 小电池每块 < T，所以可以在不同行之间切换而不冲突。
//
// 二分搜索空间收缩示例:
// n=2, batteries=[3,3,3], sum=9, 搜索范围 [1, 4]
//
// Round1: lo=1, hi=4, mid=2
//   贡献 = min(3,2)+min(3,2)+min(3,2) = 6 >= 2*2=4 ✓ → lo=3
// Round2: lo=3, hi=4, mid=3
//   贡献 = 3+3+3 = 9 >= 2*3=6 ✓ → lo=4
// Round3: lo=4, hi=4, mid=4
//   贡献 = min(3,4)+min(3,4)+min(3,4) = 9 >= 2*4=8 ✓ → lo=5
// lo > hi → 退出, 返回 hi=4
// ============================================================
class Solution1 {
public:
    long long maxRunTime(int n, vector<int>& batteries) {
        // 先算总电量，作为二分上界的依据
        long long sum = 0;
        for (int b : batteries) sum += b;
        
        // 二分搜索：在 [1, sum/n] 中找最大的可行时间
        // 上界是 sum/n：所有电量均匀分配的理论极限
        // （不能用 max(batteries) 做上界——多块电池轮换可能超过单块最大值）
        long long lo = 1, hi = sum / n;
        
        while (lo <= hi) {
            long long mid = lo + (hi - lo) / 2;
            
            // check(mid): 每块电池最多贡献 mid 分钟，总贡献够不够？
            long long total = 0;
            for (int b : batteries) {
                // min(b, mid): 电池 b 对目标时间 mid 的有效贡献
                // 必须转 long long，否则 min 比较时可能出问题
                total += min((long long)b, mid);
            }
            
            if (total >= (long long)n * mid) {
                lo = mid + 1;  // mid 可行，尝试更大的时间
            } else {
                hi = mid - 1;  // mid 不可行，缩小
            }
        }
        
        // lo <= hi 模板：循环结束时 hi 是最后一个满足条件的值
        return hi;
    }
};

// ============================================================
// 解法2: 排序 + 贪心
// 时间: O(m · log m)  空间: O(1)（原地排序）
//
// 【思路】
// 换一个角度：不二分时间，而是直接推导。
//
// 核心观察：
// 排序后从大到小看每块电池：
// - 如果最大的电池 > 剩余总电量的平均值(sum/n)，
//   说明它"太大了"，多余电量浪费，让它独占一台电脑。
//   然后 n 减 1，sum 减去这块电池，继续看下一个最大的。
// - 一旦最大电池 <= 平均值，说明所有剩余电池都 <= 平均值，
//   它们可以完美地"流动"填满所有电脑，答案就是 sum/n。
//
// 为什么"所有电池 <= 平均值"就能完美分配？
// 因为每块电池 <= T = sum/n < T+1，所以可以在不同电脑之间
// 分时复用而不冲突（每块电池在 T 分钟内用不完，可以切换）。
//
// 示例: n=2, batteries=[3,3,3]
// 排序: [3,3,3], sum=9
// i=2(最大): batteries[2]=3, sum/n=9/2=4, 3 <= 4 → 停止
// 答案 = 9/2 = 4 ✓
//
// 示例: n=2, batteries=[1,1,1,1]
// 排序: [1,1,1,1], sum=4
// i=3(最大): batteries[3]=1, sum/n=4/2=2, 1 <= 2 → 停止
// 答案 = 4/2 = 2 ✓
//
// 示例: n=2, batteries=[1,2,100]
// 排序: [1,2,100], sum=103
// i=2: batteries[2]=100, sum/n=103/2=51, 100 > 51 → 独占! sum=3, n=1
// i=1: batteries[1]=2, sum/n=3/1=3, 2 <= 3 → 停止
// 答案 = 3/1 = 3
// ============================================================
class Solution2 {
public:
    long long maxRunTime(int n, vector<int>& batteries) {
        // 升序排序
        sort(batteries.begin(), batteries.end());
        
        long long sum = 0;
        for (int b : batteries) sum += b;
        
        int m = batteries.size();
        
        // 从最大电池开始，检查是否"太大"需要独占一台电脑
        for (int i = m - 1; i >= 0; i--) {
            // 当前平均值 = sum / n
            // 如果最大电池 > 平均值，它独占一台电脑
            if (batteries[i] > sum / n) {
                sum -= batteries[i]; // 去掉这块电池的电量
                n--;                  // 少一台电脑需要分配
                // 继续检查下一个最大的电池
            } else {
                // 从这里开始，所有电池 <= 平均值
                // 它们可以完美分配给 n 台电脑
                break;
            }
        }
        
        // 剩余电量均匀分给剩余电脑
        // 整数除法向下取整是正确的（时间是整数分钟）
        return sum / n;
    }
};

// ============================================================
// 【解法对比】
// 
// 解法1（二分答案）:
//   - 思路通用："猜答案+验证" 是一大类问题的模板
//   - 不需要排序，check 函数简单直观
//   - 时间 O(m·log(sum/n))，当 sum 很大时 log 因子可能较大
//
// 解法2（排序+贪心）:
//   - 更数学化，直接推导答案
//   - 时间 O(m·log m)，排序主导
//   - 需要更强的直觉来理解"大电池独占，小电池流动"
//
// 面试建议: 优先写解法1（二分答案），容易解释且不容易出错。
// 如果面试官追问"能不能不用二分？"，再给出解法2。
//
// ============================================================
// 【易错点】
//
// 1. 整数溢出:
//    ✗ int sum = 0; → batteries 总和可达 10^14
//    ✓ long long sum = 0;
//    ✗ total += min(b, (int)mid); → mid 是 long long，b 是 int，
//      min 会取 int 类型导致截断
//    ✓ total += min((long long)b, mid);
//
// 2. 二分上界设错:
//    ✗ hi = *max_element(batteries.begin(), batteries.end());
//      → 多块电池轮换使用，总时间可能远超单块最大值
//      例: n=1, batteries=[3,3,3] → 答案是9，不是3
//    ✓ hi = sum / n;
//
// 3. 二分返回值:
//    ✗ return lo; → lo 是第一个 **不满足** 条件的值
//    ✓ return hi; → hi 是最后一个满足条件的值
//    （使用 lo <= hi 模板时的规律）
//
// 4. 贪心解法中 n 可能减到 0:
//    不会发生，因为题目保证 batteries.length >= n，
//    且至少有 n 块电池，最坏情况每块独占一台。
//
// ============================================================
// 【面试追问】
//
// Q1: "check 函数为什么是充分的？总贡献 >= n*T 就真的能构造出方案吗？"
// A1: 把 n*T 看成网格。大电池(>=T)各占一行。小电池(<T)的总电量
//     够填满剩余格子。因为每块小电池 < T，可以在不同行之间分时
//     使用而不冲突（每个时间片只给一台电脑），构造方法是轮转分配。
//
// Q2: "二分的复杂度中 log(sum/n) 最大是多少？能不能更快？"
// A2: sum 最大 10^14, n 最小 1，所以 log(10^14) ≈ 47。
//     每次 check 遍历整个数组 O(m)，总计 O(47m) ≈ O(m)。
//     解法2 排序+贪心是 O(m·log m)，当 m 较大时差不多。
//
// Q3: "如果电池有使用次数限制（最多切换 k 次），怎么办？"
// A3: 这就不能简单地认为电量可以自由流动了。需要考虑切换次数
//     约束，可能需要 DP 或更复杂的贪心。问题变得更像调度问题。
// ============================================================
