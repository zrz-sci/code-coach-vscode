/*
 * LeetCode 50: Pow(x, n)
 *
 * 【题目本质】
 * 高效计算 x 的 n 次方。核心是快速幂：利用 x^n = (x^(n/2))^2
 * 将乘法次数从 O(n) 降到 O(log n)。
 *
 * 【解法总览】
 * 解法1: 暴力循环        — O(n)     / O(1)      — 最直觉，但会 TLE
 * 解法2: 递归快速幂       — O(log n) / O(log n)  — 面试首选，逻辑清晰
 * 解法3: 迭代快速幂(位运算) — O(log n) / O(1)     — 最优，面试加分
 */

// ============================================================
// 解法1: 暴力循环 — 逐个相乘 n 次
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 最直觉的做法：x 乘 n 次。负指数先取倒数。
// 当 n 达到 2^31 量级时必然超时，但帮我们理清了负指数处理。
//
// 计算过程 (x=2, n=5):
// result = 1 → 1*2=2 → 2*2=4 → 4*2=8 → 8*2=16 → 16*2=32
// 共 5 次乘法
// ============================================================
class Solution1 {
public:
    double myPow(double x, int n) {
        // 先转 long long，防止 n = INT_MIN 时取反溢出
        long long N = n;
        if (N < 0) {
            x = 1.0 / x;  // x^(-n) = (1/x)^n
            N = -N;
        }
        double result = 1.0;
        for (long long i = 0; i < N; i++) {
            result *= x;
        }
        return result;
    }
};

// ============================================================
// 解法2: 递归快速幂 — 指数折半，每次问题规模减半
// 时间: O(log n)  空间: O(log n) — 递归栈深度
//
// 【思路】
// 暴力的瓶颈：乘法次数 = n，太多了。
// 关键观察：x^10 = (x^5)^2，x^5 = x * (x^2)^2
// 每次把指数减半，递归深度只有 log n 层。
//
// 递归分解过程 (x=2, n=10):
//
//   pow(2, 10)
//     half = pow(2, 5) → 32
//       half = pow(2, 2) → 4
//         half = pow(2, 1) → 2
//           half = pow(2, 0) → 1     ← base case
//           return 1*1*2 = 2         ← 奇数: half*half*x
//         return 2*2 = 4             ← 偶数: half*half
//       return 4*4*2 = 32            ← 奇数: half*half*x
//     return 32*32 = 1024            ← 偶数: half*half
//
// 只做了 4 次递归 + 4 次乘法，远少于 10 次！
// ============================================================
class Solution2 {
public:
    double myPow(double x, int n) {
        long long N = n;
        if (N < 0) {
            x = 1.0 / x;
            N = -N;
        }
        return fastPow(x, N);
    }

private:
    double fastPow(double x, long long n) {
        if (n == 0) return 1.0;  // base case: x^0 = 1

        // 只递归一次！不能写两次 fastPow(x, n/2)，否则退化为 O(n)
        double half = fastPow(x, n / 2);

        if (n % 2 == 0) {
            return half * half;       // 偶数: x^n = (x^(n/2))^2
        } else {
            return half * half * x;   // 奇数: x^n = (x^(n/2))^2 * x
        }
    }
};

// ============================================================
// 解法3: 迭代快速幂（位运算） — O(1) 空间的最优解
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 把指数 n 看作二进制表示，利用二进制分解来避免递归。
//
// 核心想法：n = b_k * 2^k + ... + b_1 * 2 + b_0
// 所以 x^n = x^(b_k * 2^k) * ... * x^(b_1 * 2) * x^(b_0)
//          = (x^(2^k))^b_k * ... * (x^2)^b_1 * x^b_0
//
// 算法：维护 current_product，每轮自乘（x → x² → x⁴ → x⁸ ...）
//       同时从低位到高位扫描 n 的每一个 bit，
//       bit 为 1 时把 current_product 乘入 result。
//
// 迭代过程 (x=2, n=13, 二进制 1101):
//
//   初始: result=1, cur=2, N=1101₂
//
//   bit0=1: result = 1*2 = 2,     cur = 2*2 = 4,      N = 110₂
//   bit1=0: result 不变 = 2,       cur = 4*4 = 16,     N = 11₂
//   bit2=1: result = 2*16 = 32,   cur = 16*16 = 256,  N = 1₂
//   bit3=1: result = 32*256 = 8192, cur = 256*256,     N = 0
//
//   结果: 8192 = 2^13 ✓
//   只用了 4 次迭代 = ⌈log₂13⌉ 次
// ============================================================
class Solution3 {
public:
    double myPow(double x, int n) {
        long long N = n;
        if (N < 0) {
            x = 1.0 / x;
            N = -N;
        }

        double result = 1.0;
        double current_product = x;  // 依次为 x^1, x^2, x^4, x^8, ...

        while (N > 0) {
            // 当前最低位为 1，说明 x 的这个 2^k 次方要乘入结果
            if (N & 1) {
                result *= current_product;
            }
            // current_product 每轮自平方：x → x² → x⁴ → x⁸ ...
            current_product *= current_product;
            // 右移一位，处理下一个 bit
            N >>= 1;
        }

        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间      | 空间       | 适用场景          |
// |------|-----------|-----------|-------------------|
// | 暴力 | O(n)      | O(1)      | n 很小时可用，面试开场 |
// | 递归 | O(log n)  | O(log n)  | 面试首选，最容易讲清 |
// | 迭代 | O(log n)  | O(1)      | 追问空间优化时给出   |
//
// 递归版代码最清晰，逻辑"指数折半"一目了然。
// 迭代版用位运算，代码稍复杂但空间 O(1)。
// 面试中建议先写递归版，被追问空间优化再给迭代版。
//
// ============================================================
// 【易错点】
//
// 1. INT_MIN 取反溢出:
//    ✗ long long N = -n;    // n 在 int 内已经溢出了
//    ✓ long long N = n; N = -N;  // 先扩展类型再取反
//
// 2. 递归中重复计算:
//    ✗ return fastPow(x, n/2) * fastPow(x, n/2);
//      → 两次递归调用，时间退化为 O(n)
//    ✓ double half = fastPow(x, n/2); return half * half;
//      → 只算一次，时间 O(log n)
//
// 3. 迭代版忘记处理负指数:
//    ✗ 直接 while (N > 0) 但 N 还是负的
//    ✓ 入口处统一把 x 取倒数、N 取绝对值
//
// 4. base case 遗漏:
//    ✗ 递归没有 n==0 的终止条件 → 无限递归
//    ✓ if (n == 0) return 1.0;
//
// ============================================================
// 【面试追问】
//
// Q1: "暴力法的瓶颈在哪？"
//     → n 最大 2^31，循环次数线性于 n，超时。
//
// Q2: "递归快速幂的空间能优化吗？"
//     → 用迭代+位运算，把递归栈 O(log n) 降到 O(1)。
//
// Q3: "n = INT_MIN 时为什么特殊？怎么处理？"
//     → INT_MIN = -2147483648，取反后 2147483648 超出 int 范围。
//       必须先转 long long 再取反。
//
// Q4: "如果是 x^n mod p (大数快速幂取模)，怎么改？"
//     → 框架完全一样，每次乘法后加 % p。
//       这是 RSA 加密等算法的基础操作。
//
// Q5: "迭代版的位运算为什么正确？"
//     → n 的二进制分解保证 x^n = ∏ x^(2^k) 对所有 bit_k=1 的项。
//       current_product 每轮自乘实现了 x^(2^k) 的递推。
// ============================================================
