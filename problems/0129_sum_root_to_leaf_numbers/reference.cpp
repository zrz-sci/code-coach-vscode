/*
 * LeetCode 129: Sum Root to Leaf Numbers (求根节点到叶节点数字之和)
 *
 * 【题目本质】
 * 二叉树中每条从根到叶子的路径构成一个十进制数字。
 * 返回所有这些数字的总和。
 * 核心操作：DFS 传递 num = num * 10 + node->val，叶子处收割。
 *
 * 【ASCII 图】
 *
 *     示例1:          示例2:
 *         1               4
 *        / \             / \
 *       2   3           9   0
 *                      / \
 *                     5   1
 *
 *     路径:            路径:
 *     1->2 = 12        4->9->5 = 495
 *     1->3 = 13        4->9->1 = 491
 *                      4->0    = 40
 *     总和: 25          总和: 1026
 *
 * 【解法总览】
 * 解法1: DFS递归(传参)  — O(n) / O(h) — 面试首选，最简洁
 * 解法2: DFS迭代(栈)    — O(n) / O(h) — 追问迭代时写
 * 解法3: BFS(队列)      — O(n) / O(n) — 追问BFS时写
 */

// ============================================================
// 解法1: DFS 递归（传参） — 面试首选 ⭐
// 时间: O(n)   空间: O(h)  h=树高，最坏O(n)链状，最优O(logn)平衡
//
// 【思路】
// DFS 时携带参数 num = "从根到当前节点所构成的数字"。
// 每进入一个节点：num = num * 10 + node->val
//
// 关键洞察：
//   num * 10 是"十进制左移一位"，相当于给前面的数字腾出一个个位，
//   然后 + node->val 把当前节点的值填到个位上。
//
// 递归返回值的语义：
//   "以 node 为根的子树中，所有根-到-叶路径的数字之和"
//
// 执行过程 (示例2: root = [4,9,0,5,1]):
//
//                  dfs(4, num=0)
//                  num = 0*10+4 = 4
//                 /              \
//        dfs(9, num=4)       dfs(0, num=4)
//        num = 4*10+9=49     num = 4*10+0=40
//       /            \       叶子! return 40
//  dfs(5, num=49) dfs(1, num=49)
//  num=49*10+5=495 num=49*10+1=491
//  叶子! return 495 叶子! return 491
//
//  dfs(9,4) = 495 + 491 = 986
//  dfs(4,0) = 986 + 40 = 1026 ✓
// ============================================================
class Solution1 {
public:
    int sumNumbers(TreeNode* root) {
        return dfs(root, 0);
    }

    int dfs(TreeNode* node, int num) {
        // base case: 空节点不贡献任何数字
        if (!node) return 0;

        // 构建当前数字：十进制左移 + 当前节点值
        num = num * 10 + node->val;

        // 叶子节点：路径完整，返回这条路径的数字
        if (!node->left && !node->right) {
            return num;
        }

        // 非叶子节点：左右子树路径数字之和
        // 注意 num 对左右子树是"只读"的——
        // 左子树的递归不会修改 num，右子树拿到的是同一个 num
        return dfs(node->left, num) + dfs(node->right, num);
    }
};

// ============================================================
// 解法2: DFS 迭代（显式栈）
// 时间: O(n)   空间: O(h)
//
// 【思路】
// 把递归改成显式栈。栈中每个元素是 (节点, 到达该节点时的数字)。
// 弹出时如果是叶子就累加 sum，否则子节点入栈。
//
// 栈模拟过程 (示例1: root = [1,2,3]):
//
//   初始: stack = [(1, 1)], sum = 0
//
//   弹出 (1, 1): 非叶子
//     压右子 (3, 1*10+3=13)
//     压左子 (2, 1*10+2=12)
//     stack = [(3,13), (2,12)]
//
//   弹出 (2, 12): 叶子! sum += 12 → sum = 12
//     stack = [(3,13)]
//
//   弹出 (3, 13): 叶子! sum += 13 → sum = 25
//     stack = []
//
//   返回 25 ✓
//
// 为什么子节点入栈时就算好数字？
//   因为弹出时直接用，不需要再去查"它的父节点是谁、数字是多少"。
//   这就是"提前计算"的技巧——避免栈中还要维护父子关系。
// ============================================================
class Solution2 {
public:
    int sumNumbers(TreeNode* root) {
        if (!root) return 0;

        int sum = 0;
        // 栈存 (节点指针, 到达该节点时的累积数字)
        stack<pair<TreeNode*, int>> stk;
        stk.push({root, root->val});

        while (!stk.empty()) {
            auto [node, num] = stk.top();
            stk.pop();

            // 叶子节点：收割
            if (!node->left && !node->right) {
                sum += num;
                continue;
            }

            // 先压右后压左，保证左子树先被处理（前序遍历顺序）
            // 对本题来说顺序无所谓，只是习惯
            if (node->right) {
                stk.push({node->right, num * 10 + node->right->val});
            }
            if (node->left) {
                stk.push({node->left, num * 10 + node->left->val});
            }
        }

        return sum;
    }
};

// ============================================================
// 解法3: BFS（队列）
// 时间: O(n)   空间: O(n)  最坏情况最后一层 n/2 个节点
//
// 【思路】
// 和解法2几乎一样，只是把栈换成队列（层序遍历）。
// 队列中存 (节点, 当前数字) 对。
//
// 空间为什么可能更大？
//   BFS 的队列在最宽的一层时最大。完全二叉树最后一层有 n/2 个节点，
//   所以空间是 O(n)。DFS 的栈深度是 O(h)，对平衡树来说更优。
//   但对链状树来说两者都是 O(n)。
// ============================================================
class Solution3 {
public:
    int sumNumbers(TreeNode* root) {
        if (!root) return 0;

        int sum = 0;
        queue<pair<TreeNode*, int>> q;
        q.push({root, root->val});

        while (!q.empty()) {
            auto [node, num] = q.front();
            q.pop();

            if (!node->left && !node->right) {
                sum += num;
                continue;
            }

            if (node->left) {
                q.push({node->left, num * 10 + node->left->val});
            }
            if (node->right) {
                q.push({node->right, num * 10 + node->right->val});
            }
        }

        return sum;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间  | 空间      | 优势              | 劣势          |
// |-----------|------|----------|------------------|--------------|
// | DFS 递归   | O(n) | O(h)     | 代码最简洁          | 深度大时栈溢出  |
// | DFS 迭代   | O(n) | O(h)     | 无栈溢出风险        | 代码略长       |
// | BFS       | O(n) | O(n)     | 直观               | 空间可能更大   |
//
// 面试选择: DFS 递归（解法1），5 行核心代码，最能展示递归思维。
//
// ============================================================
// 【易错点】
//
// 1. 空节点 vs 叶子节点:
//    ✗ if (!node) return num;  → 空节点会贡献虚假数字
//    ✓ if (!node) return 0; if (!left && !right) return num;
//
// 2. num 计算时机:
//    ✗ 先递归左右子树，再 num = num*10 + val → 数字少一位
//    ✓ 进入节点时立即 num = num*10 + val
//
// 3. 迭代版初始值:
//    ✗ stk.push({root, 0}) 然后弹出时 num = num*10+val
//      → 也能工作，但容易和递归版搞混
//    ✓ stk.push({root, root->val})，入栈时提前算好
//
// 4. 只有一个子节点的情况:
//    节点只有右子节点时，它不是叶子！
//    ✗ 只检查 !node->left 就当叶子处理 → 遗漏右子树
//    ✓ 必须 !left && !right 才是叶子
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 能不能迭代？
//     用栈或队列存 (node, num) 对。解法2/3。
//
// Q2: 如果是二进制路径 (0/1)？
//     num * 10 改成 num * 2，其余不变。即 LC 1022。
//
// Q3: 数字很大超 int 怎么办？
//     用 long long，或字符串模拟大数。
//     本题约束：深度 <= 10，保证不溢出。
//
// Q4: 如果要求所有节点（不仅叶子）的路径数字之和？
//     去掉叶子判断，改为:
//     return num + dfs(left, num) + dfs(right, num);
//
// Q5: 如果要输出最大/最小路径数字和对应路径？
//     DFS 时维护 vector<int> path，进入 push，回溯 pop。
//     叶子处比较并记录最优路径。
//
