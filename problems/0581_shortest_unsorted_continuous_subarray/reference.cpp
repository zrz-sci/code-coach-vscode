/*
 * LeetCode 581: 最短无序连续子数组 (Shortest Unsorted Continuous Subarray)
 *
 * 【题目本质】
 * 找出数组中最左和最右的"不在正确位置"的元素，它们之间的距离就是答案。
 * 等价于：将数组分成 [有序左段 | 需排序中段 | 有序右段]，求中段长度。
 *
 * 【解法总览】
 * 解法1: 排序对比       — O(n log n) / O(n)  — 最直觉
 * 解法2: 双向扫描(贪心) — O(n) / O(1)       — 面试首选 ⭐
 * 解法3: 单调栈         — O(n) / O(n)       — 加分项
 */

// ============================================================
// 解法1: 排序对比 — 排序得到"正确答案"，逐位对比找边界
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 最自然的想法：如果我知道数组排好序长什么样，
// 那第一个和最后一个"不一样"的位置就是需要排序的范围。
//
// 示例:
//   原数组:  [2, 6, 4, 8, 10, 9, 15]
//   排序后:  [2, 4, 6, 8,  9, 10, 15]
//               ↑              ↑
//            left=1         right=5
//   答案 = 5 - 1 + 1 = 5
// ============================================================
class Solution1 {
public:
    int findUnsortedSubarray(vector<int>& nums) {
        vector<int> sorted_nums = nums;
        sort(sorted_nums.begin(), sorted_nums.end());
        
        int left = nums.size(), right = -1;
        for (int i = 0; i < (int)nums.size(); i++) {
            if (nums[i] != sorted_nums[i]) {
                left = min(left, i);    // 第一个不同的位置
                right = max(right, i);  // 最后一个不同的位置
            }
        }
        
        // right == -1 表示数组本身就有序
        return right == -1 ? 0 : right - left + 1;
    }
};

// ============================================================
// 解法2: 双向扫描（贪心/双指针思想） — O(n) / O(1) ⭐ 面试首选
//
// 【思路】
// 解法1的瓶颈在排序 O(n log n)。我们能否不排序直接找边界？
//
// 核心观察：在一个正确排序的数组中——
//   · 从左往右，每个元素都应该 >= 之前所有元素（即是前缀最大值）
//   · 从右往左，每个元素都应该 <= 之后所有元素（即是后缀最小值）
//
// 所以：
//   · 从左→右维护 max_seen：如果 nums[i] < max_seen，说明 i 处"有错"
//     最后一个"有错"的位置就是右边界 right
//   · 从右→左维护 min_seen：如果 nums[i] > min_seen，说明 i 处"有错"
//     最后一个"有错"的位置就是左边界 left
//
// 可视化:
//   nums:      [2, 6, 4, 8, 10, 9, 15]
//
//   从左→右找 right:
//   max_seen:   2  6  6  8  10  10  15
//   比较:       =  =  4<6 =   =  9<10  =
//                     ↑          ↑
//                   错!        错!  → right = 5
//
//   从右→左找 left:
//   min_seen:  15  9  9  8   4   4   2     (从右往左看)
//   实际:      15  9  9  8   4   4   2
//   重新看:     2  6  4  8  10   9  15
//   min_seen:   2  4  4  8   9   9  15     (反向累积最小值)
//   比较:       =  6>4 =  =  10>9  =   =
//                 ↑         ↑
//               错!       错!  → left = 1
//
//   答案 = right - left + 1 = 5 - 1 + 1 = 5
// ============================================================
class Solution2 {
public:
    int findUnsortedSubarray(vector<int>& nums) {
        int n = nums.size();
        int max_seen = INT_MIN, min_seen = INT_MAX;
        int left = -1, right = -1;
        
        for (int i = 0; i < n; i++) {
            // --- 从左往右：找右边界 ---
            // 如果当前值 < 之前最大值，说明这个位置"不对"
            if (nums[i] < max_seen) {
                right = i;
            } else {
                max_seen = nums[i];
            }
            
            // --- 从右往左：找左边界 ---
            // 用 n-1-i 镜像索引，合并到同一个循环
            int j = n - 1 - i;
            if (nums[j] > min_seen) {
                left = j;
            } else {
                min_seen = nums[j];
            }
        }
        
        // left == -1 说明没有任何位置"不对"，数组已有序
        return left == -1 ? 0 : right - left + 1;
    }
};

// ============================================================
// 解法3: 单调栈 — 用递增栈找"逆序的边界"
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 另一种视角：我们用单调栈来找"哪些元素被打乱了"。
//
// 找左边界：从左到右维护递增栈（栈里存索引）。
//   遇到比栈顶小的元素时，说明栈顶元素不该在那个位置，弹栈。
//   弹出的最小索引就是左边界。
//
// 找右边界：对称地，从右到左维护递增栈。
//   遇到比栈顶大的元素时弹栈，弹出的最大索引就是右边界。
//
// 可视化（从左→右递增栈找左边界）:
//   nums:  [2, 6, 4, 8, 10, 9, 15]
//
//   i=0: 栈空, push 0          栈(值): [2]
//   i=1: 6>2, push 1           栈(值): [2, 6]
//   i=2: 4<6, pop 1→left=1     栈(值): [2]       ← 6不该在4前面
//        4>2, push 2           栈(值): [2, 4]
//   i=3: 8>4, push 3           栈(值): [2, 4, 8]
//   i=4: 10>8, push 4          栈(值): [2, 4, 8, 10]
//   i=5: 9<10, pop 4→left=min(1,4)=1  栈(值): [2, 4, 8]
//        9>8, push 5           栈(值): [2, 4, 8, 9]
//   i=6: 15>9, push 6          栈(值): [2, 4, 8, 9, 15]
//   结果: left = 1
//
// 对称地从右→左找 right = 5
// ============================================================
class Solution3 {
public:
    int findUnsortedSubarray(vector<int>& nums) {
        int n = nums.size();
        stack<int> stk;
        int left = n, right = -1;
        
        // 从左→右，递增栈找左边界
        for (int i = 0; i < n; i++) {
            // 当前值比栈顶小 → 栈顶位置的元素"不该在那里"
            while (!stk.empty() && nums[stk.top()] > nums[i]) {
                left = min(left, stk.top());  // 记录被弹出的最小索引
                stk.pop();
            }
            stk.push(i);
        }
        
        // 清空栈，复用做右边界
        while (!stk.empty()) stk.pop();
        
        // 从右→左，递增栈（从右看）找右边界
        for (int i = n - 1; i >= 0; i--) {
            // 当前值比栈顶大 → 栈顶位置的元素"不该在那里"
            while (!stk.empty() && nums[stk.top()] < nums[i]) {
                right = max(right, stk.top());  // 记录被弹出的最大索引
                stk.pop();
            }
            stk.push(i);
        }
        
        // left == n 说明栈从未弹过，数组已有序
        return right == -1 ? 0 : right - left + 1;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间         | 空间  | 核心操作           |
// |-----------|-------------|------|-------------------|
// | 排序对比    | O(n log n)  | O(n) | 排序+线性扫描      |
// | 双向扫描    | O(n)        | O(1) | 维护前缀max/后缀min |
// | 单调栈     | O(n)        | O(n) | 递增栈找逆序边界    |
//
// · 排序对比：最容易想到，面试起手先说，展示理解
// · 双向扫描：时间空间最优，面试重点写这个
// · 单调栈：换一种思路，面试追问"还有别的方法吗"时拿出来
//
// 【易错点】
//
// 1. left/right 初始值选错:
//    ✗ left=0, right=n-1 → 数组已有序时返回 n 而不是 0
//    ✓ left=-1, right=-1（或 left=n, right=-1），未更新时返回 0
//
// 2. 比较方向搞反:
//    ✗ 从左往右时写 if(nums[i] > max_seen) right=i
//      → 这找的是"前缀最大值出现的位置"，不是"错误位置"
//    ✓ if(nums[i] < max_seen) right=i
//      → 当前值比已见最大值小，说明此位置不对
//
// 3. max_seen 初始化为 nums[0] 而不是 INT_MIN:
//    都可以，但用 INT_MIN 更安全，避免空数组边界问题
//    （本题保证 n>=1，所以 nums[0] 也行）
//
// 4. 单调栈里存值而不是存索引:
//    ✗ 存值 → 弹栈时无法得知位置，无法确定边界
//    ✓ 存索引 → 通过 nums[stk.top()] 取值比较
//
// 【面试追问】
//
// Q1: (基础理解) 暴力怎么做？
// A1: 排序后逐位对比，O(n log n) 时间 O(n) 空间。
//
// Q2: (优化) 能否 O(n) 时间 O(1) 空间？
// A2: 双向扫描。从左→右维护 max_seen 找右边界，
//     从右→左维护 min_seen 找左边界。
//     核心直觉：排好序的数组每个位置都是前缀最大值。
//
// Q3: (变体) 如果要返回需要排序的那个子数组本身呢？
// A3: 找到 left 和 right 后，返回 nums[left..right] 即可。
//     算法不变，只是最后返回子数组而不是长度。
//
// Q4: (深入) 为什么双向扫描一定能找到最小的范围？
// A4: 右边界 right 是"最后一个比前面某个元素小"的位置，
//     意味着 right 之后的元素都 >= 前面所有元素，已有序。
//     对称地 left 之前的元素都 <= 后面所有元素，已有序。
//     所以 [left, right] 恰好是最小需要排序的范围。
// ============================================================
