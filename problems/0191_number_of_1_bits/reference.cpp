/*
 * LeetCode 191: Number of 1 Bits (位1的个数)
 *
 * 【题目本质】
 * 计算32位整数二进制表示中1的个数（Hamming Weight / popcount）。
 * 核心技巧：n & (n-1) 消除最低位的1。
 *
 * 【解法总览】
 * 解法1: 逐位检查    — O(1) / O(1)   — 最直觉，循环32次
 * 解法2: n & (n-1)   — O(1) / O(1)   — 面试首选，循环次数=1的个数
 * 解法3: 分治法      — O(1) / O(1)   — 进阶，5步并行计数
 */

// ============================================================
// 解法1: 逐位检查
// 时间: O(1)  空间: O(1)  (固定32次迭代)
//
// 【思路】
// 最直接的方法：逐一检查32位中每一位是否为1。
// 可以用两种方式：
//   方式A: 固定mask左移 → 用 (1 << i) 检查第i位
//   方式B: n右移 → 用 (n & 1) 检查末位
//
// 示例: n = 11 (1011)
//   检查bit0: 1011 & 1 = 1 → count=1
//   检查bit1: 0101 & 1 = 1 → count=2  (n右移后)
//   检查bit2: 0010 & 1 = 0 → count=2
//   检查bit3: 0001 & 1 = 1 → count=3
//   ...后续28位都是0...
//   结果: 3 ✓
// ============================================================
class Solution1 {
public:
    int hammingWeight(int n) {
        int count = 0;
        for (int i = 0; i < 32; i++) {
            // 检查最低位是否为1
            if (n & 1) count++;
            // n右移，准备检查下一位
            n >>= 1;
        }
        return count;
    }
};

// ============================================================
// 解法2: n & (n-1) 消除最低位的1 — 面试首选 ⭐
// 时间: O(1)  空间: O(1)  (循环次数 = 1的个数，最多32)
//
// 【思路】
// 核心技巧: n & (n-1) 会把 n 最低位的1变成0。
//
// 为什么？
//   n     = xxxx1000 (最低位的1，右边全是0)
//   n-1   = xxxx0111 (减1后，最低位的1变0，右边的0变1，更高位不变)
//   n&n-1 = xxxx0000 (最低位的1被清除)
//
// 有几个1就循环几次，比固定32次平均更快。
//
// 示例: n = 11 (1011)
//   第1次: 1011 & 1010 = 1010, count=1  (消掉bit0的1)
//   第2次: 1010 & 1001 = 1000, count=2  (消掉bit1的1)
//   第3次: 1000 & 0111 = 0000, count=3  (消掉bit3的1)
//   n=0, 结束. 答案: 3 ✓
//
// 对比: n = 128 (10000000)
//   只需1次: 10000000 & 01111111 = 0, count=1 ✓
//   逐位检查需要32次，这里只需1次！
// ============================================================
class Solution2 {
public:
    int hammingWeight(int n) {
        int count = 0;
        while (n) {
            // 每次消除最低位的1
            n &= (n - 1);
            count++;
        }
        return count;
    }
};

// ============================================================
// 解法3: 分治法（并行计数）
// 时间: O(1)  空间: O(1)  (5步常数操作)
//
// 【思路】
// 类似"人口普查分区统计"的思想：
//   第1步：把32位分成16组，每组2位，统计每组内1的个数
//   第2步：合并相邻2位组 → 每组4位
//   第3步：合并相邻4位组 → 每组8位
//   第4步：合并相邻8位组 → 每组16位
//   第5步：合并高低16位 → 得到32位中1的总个数
//
// 第1步的细节:
//   每2位 "ab" 中1的个数 = a + b
//   a = (n >> 1) & 0x55555555  (取偶数位)
//   b = n & 0x55555555          (取奇数位)
//   result = a + b
//
// 8位简化示例: n = 10110100
//   第1步: (01)(10)(01)(00)       → 每2位中的1的个数: 1,1,1,0
//   第2步: (0011)(0001)           → 每4位中的1的个数: 3,1
//   第3步: (00000100)             → 8位中共4个1
//   结果: 4 ✓
//
// 这个方法的mask与 190.Reverse Bits 的分治法完全相同，
// 区别是190用移位+OR做交换，这里用移位+ADD做计数。
// ============================================================
class Solution3 {
public:
    int hammingWeight(int n) {
        // 第1步：每2位中1的个数
        n = (n & 0x55555555) + ((n >> 1) & 0x55555555);
        // 第2步：每4位中1的个数（合并相邻2位组）
        n = (n & 0x33333333) + ((n >> 2) & 0x33333333);
        // 第3步：每8位中1的个数（合并相邻nibble）
        n = (n & 0x0f0f0f0f) + ((n >> 4) & 0x0f0f0f0f);
        // 第4步：每16位中1的个数（合并相邻byte）
        n = (n & 0x00ff00ff) + ((n >> 8) & 0x00ff00ff);
        // 第5步：32位中1的总个数（合并高低16位）
        n = (n & 0x0000ffff) + ((n >> 16) & 0x0000ffff);
        return n;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间  | 空间  | 循环次数        | 优势                        |
// |------------|-------|-------|----------------|----------------------------|
// | 逐位检查    | O(1)  | O(1)  | 固定32次       | 最直觉，容易理解             |
// | n & (n-1)  | O(1)  | O(1)  | = 1的个数      | 最优雅，平均更快             |
// | 分治法      | O(1)  | O(1)  | 固定5步        | 无循环，可并行，硬件友好       |
//
// 面试选择：先说逐位检查表明理解题意，然后写 n&(n-1)。
// 分治法如果面试官追问"还有没有其他方法"时讲。
//
// ============================================================
// 【易错点】
//
// 1. 有符号右移死循环:
//    ✗ while (n) { count += n & 1; n >>= 1; }
//      → 如果 n 是负数（int最高位为1），有符号右移补1，永远不为0
//    ✓ 用 for 固定32次，或用 n &= (n-1) 方法
//
// 2. n & (n-1) 理解错误:
//    ✗ 以为去掉最高位的1 → 实际去掉的是最低位的1
//    ✓ 画二进制：n = 1010100, n-1 = 1010011, n&(n-1) = 1010000
//
// 3. 循环后忘记计数:
//    ✗ while (n) { n &= (n-1); } return n;
//      → 循环结束时 n=0，应该返回 count
//    ✓ while (n) { n &= (n-1); count++; } return count;
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: n & (n-1) 还能解什么题？
//     判断2的幂: n > 0 && (n & (n-1)) == 0
//     只有一个1时 n&(n-1)=0，即2的幂。
//
// Q2: Follow-up: 多次调用怎么优化？
//     查找表: 预计算0~255的popcount，拆4字节查表求和。
//     或直接用 __builtin_popcount(n)，通常对应CPU的POPCNT指令。
//
// Q3: 分治法和190题的关系？
//     mask完全一样。190用移位+OR做"交换位置"，
//     191用移位+ADD做"累加计数"。分治的层次结构相同。
//
// ============================================================
// 【相关题型】
//
// - 190. 颠倒二进制位 (Reverse Bits):
//   分治法mask相同，操作从ADD换成OR+SHIFT。
//
// - 231. 2的幂 (Power of Two):
//   n & (n-1) == 0 即2的幂（只有一个1位）。
//
// - 338. 比特位计数 (Counting Bits):
//   对 0~n 每个数求 popcount，DP: dp[i] = dp[i&(i-1)] + 1。
//
// - 461. 汉明距离 (Hamming Distance):
//   先异或得到不同的位，再对结果求 popcount。
// ============================================================
