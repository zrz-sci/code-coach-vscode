/*
 * LeetCode 316: Remove Duplicate Letters (去除重复字母)
 *
 * 【题目本质】
 * 在字符串的所有"每个字母恰好出现一次"的子序列中，找字典序最小的。
 * 等价于：用贪心策略从左到右构建结果，每一步都让当前位置尽量小。
 *
 * 【解法总览】
 * 解法1: 暴力枚举 — O(2^n · n) / O(n) — 理解题意，不可行
 * 解法2: 贪心+单调栈 — O(n) / O(1) — 面试最优解 ⭐
 * 解法2b: 贪心+单调栈(用count代替lastIndex) — O(n) / O(1) — 变体写法
 */

// ============================================================
// 解法1: 暴力枚举 — 枚举所有子序列取字典序最小
// 时间: O(2^n · n)  空间: O(n)
//
// 【思路】
// 最直觉的做法：枚举所有 2^n 个子序列，检查哪些恰好包含
// 每种字母一次，在这些合法子序列中取字典序最小的。
// 
// 这个解法只适用于 n 很小（≤20）的情况，n=10^4 完全不可行。
// 但它帮助我们准确理解题意：我们在做"选择子序列"的决策。
// ============================================================
class Solution1 {
public:
    string removeDuplicateLetters(string s) {
        int n = s.size();
        // 统计不同字母数 = 结果的目标长度
        set<char> chars(s.begin(), s.end());
        int target = chars.size();
        
        string best = "";
        // 枚举所有子序列（仅演示思路，大输入会超时）
        for (int mask = 0; mask < (1 << n); mask++) {
            string sub = "";
            for (int i = 0; i < n; i++) {
                if (mask & (1 << i)) sub += s[i];
            }
            // 检查：长度 == target 且 无重复字母
            set<char> used(sub.begin(), sub.end());
            if ((int)used.size() == target && (int)sub.size() == target) {
                if (best.empty() || sub < best) best = sub;
            }
        }
        return best;
    }
};

// ============================================================
// 解法2: 贪心 + 单调栈 — 面试首选 ⭐
// 时间: O(n)  空间: O(1)（栈最大26，inStack最大26）
//
// 【思路】
// 暴力解的瓶颈：指数级枚举。
// 贪心优化：逐字符扫描，维护一个"结果栈"。
//
// 核心贪心策略：
// - 如果当前字符 c 比栈顶小，说明 c 放在前面更优。
// - 但栈顶能弹出的前提是：栈顶字母后面还会出现（不会丢失）。
// - 如果 c 已在栈中，跳过（已经在最优位置了）。
//
// 为什么正确？
// - 弹出的字母后面还会出现，不会丢。
// - 换来更小的字母在前面，字典序一定更小。
// - 不能弹（后面没有了）就保留，保证不丢字母。
//
// 手动模拟 "cbacdcbc":
// lastIndex: a→2, b→6, c→7, d→4
//
// i=0 'c': 栈空 → push               栈: [c]
// i=1 'b': b<c, last[c]=7>1 → pop c  栈: [b]
// i=2 'a': a<b, last[b]=6>2 → pop b  栈: [a]
// i=3 'c': c>a → push                栈: [a,c]
// i=4 'd': d>c → push                栈: [a,c,d]
// i=5 'c': c 已在栈中 → skip         栈: [a,c,d]
// i=6 'b': b<d, 但 last[d]=4<6 → 不弹d!
//          push b                     栈: [a,c,d,b]
// i=7 'c': c 已在栈中 → skip         栈: [a,c,d,b]
//
// 结果: "acdb" ✓
// ============================================================
class Solution2 {
public:
    string removeDuplicateLetters(string s) {
        // 预处理：每个字母最后出现的位置
        // 这是贪心决策的依据——决定能否安全弹出栈顶
        int lastIndex[26] = {};
        for (int i = 0; i < (int)s.size(); i++) {
            lastIndex[s[i] - 'a'] = i;
        }
        
        bool inStack[26] = {};  // 标记字母是否已在当前结果中
        string stk;             // 用 string 模拟栈，最后直接返回
        
        for (int i = 0; i < (int)s.size(); i++) {
            char c = s[i];
            
            // 已经在结果栈中了 → 跳过
            // 为什么跳过是安全的？因为它在栈中的位置已经是贪心最优的
            if (inStack[c - 'a']) continue;
            
            // 贪心弹出：三个条件必须同时满足
            // ① 栈非空
            // ② 栈顶 > 当前字符（弹出后字典序更小）
            // ③ 栈顶字母在 i 之后还会出现（弹了不会丢）
            while (!stk.empty() 
                   && stk.back() > c 
                   && lastIndex[stk.back() - 'a'] > i) {
                inStack[stk.back() - 'a'] = false;  // 弹出时清除标记
                stk.pop_back();
            }
            
            stk.push_back(c);
            inStack[c - 'a'] = true;  // 入栈时设置标记
        }
        
        return stk;
    }
};

// ============================================================
// 解法2b: 贪心 + 单调栈（用剩余次数代替 lastIndex）
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 和解法2完全相同的贪心策略，只是判断"后面还有没有"
// 用 count[c] > 0 代替 lastIndex[c] > i。
//
// 区别：
// - 预处理变成统计每个字母的总出现次数
// - 每次处理字符时（不论是否入栈），都要 count[c]--
// - 弹栈条件中 lastIndex[top] > i 改为 count[top] > 0
//
// 注意：count[c]-- 必须在 inStack 检查之前做！
// 否则被跳过的字符不会递减计数，导致后面判断"还有几个"出错。
// ============================================================
class Solution2b {
public:
    string removeDuplicateLetters(string s) {
        int count[26] = {};
        for (char c : s) {
            count[c - 'a']++;
        }
        
        bool inStack[26] = {};
        string stk;
        
        for (int i = 0; i < (int)s.size(); i++) {
            char c = s[i];
            
            // 不论是否入栈，当前字符的剩余次数都要减 1
            // 因为我们已经"经过"了这个位置
            count[c - 'a']--;
            
            if (inStack[c - 'a']) continue;
            
            // count[stk.back()-'a'] > 0 表示栈顶字母后面还有剩余
            while (!stk.empty() 
                   && stk.back() > c 
                   && count[stk.back() - 'a'] > 0) {
                inStack[stk.back() - 'a'] = false;
                stk.pop_back();
            }
            
            stk.push_back(c);
            inStack[c - 'a'] = true;
        }
        
        return stk;
    }
};

// ============================================================
// 【解法对比】
// 
// 解法1 (暴力) vs 解法2 (贪心+单调栈):
//   暴力枚举所有子序列是 O(2^n)，贪心每个字符最多入栈出栈各一次是 O(n)。
//   贪心的正确性：弹出的字母后面一定还会出现，所以不会丢失。
//
// 解法2 vs 解法2b:
//   逻辑完全等价。lastIndex 版本更直观（直接比位置），
//   count 版本更容易推广（如果需要知道剩余多少个）。
//   面试时任选其一即可。
//
// 【易错点】
// 1. ✗ 弹栈条件只写 stk.back() > c，漏掉"后面还有"的检查
//    → 会把最后一次出现的字母弹掉，导致结果缺少字母
//    ✓ 必须同时满足 lastIndex[top] > i（或 count[top] > 0）
//
// 2. ✗ inStack 检查放在 count[c]-- 之前（解法2b中）
//    → 被跳过的字符没有递减 count，后面误以为还剩很多
//    ✓ count[c]-- 必须在 inStack 跳过判断之前
//
// 3. ✗ 弹栈时忘记 inStack[top] = false
//    → 该字母被弹出后，后面再遇到会被误跳过，结果缺字母
//    ✓ pop 之前先清除 inStack 标记
//
// 4. ✗ 用 stack<char> 而不是 string，最后拼接结果时忘记反转
//    → stack 弹出顺序是反的，得到反序结果
//    ✓ 直接用 string 的 push_back/pop_back 模拟栈，最后直接返回
//
// 【面试追问 — 递进链】
//
// Q1（基础理解）: "inStack 跳过"为什么是安全的？
// A1: 如果字母 c 已在栈中，说明它的位置是之前贪心决策选好的。
//     再加一个 c 会导致重复。不加也不会更差——如果后面有更好
//     的位置，那应该在之前就把旧的弹出了。
//
// Q2（正确性证明）: 如何证明贪心策略得到的一定是字典序最小的？
// A2: 可以用交换论证(exchange argument)：假设存在更优解 OPT，
//     在第一个和贪心解不同的位置，OPT 选了更大的字母 x，贪心选了
//     更小的 y。由于 y < x 且 y 在 x 前面出现，我们可以把 OPT
//     中的 x 换成 y 得到字典序更小的合法解，与 OPT 最优矛盾。
//
// Q3（变体）: 如果要求字典序最大呢？
// A3: 把弹栈条件从 stk.back() > c 改为 stk.back() < c 即可，
//     维护单调递减栈而非递增栈。
//
// Q4（关联题）: 和 402. 移掉K位数字 有什么关系？
// A4: 框架完全相同的单调栈贪心。402 的弹出条件是"剩余删除次数 k>0"，
//     本题是"栈顶后面还有"。掌握本题后 402 只需改弹出条件那一行。
// ============================================================
