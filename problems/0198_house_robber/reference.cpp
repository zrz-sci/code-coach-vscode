/*
 * LeetCode 198: 打家劫舍 (House Robber)
 * 
 * 【题目本质】
 * 在一个数组中选取若干不相邻的元素，使其和最大。
 * 经典的线性 DP 入门题，也是打家劫舍系列的基础。
 *
 * 【解法总览】
 * 解法1: 暴力递归        — O(2^n) / O(n)  — 穷举所有选/不选的组合
 * 解法2: 记忆化搜索      — O(n)   / O(n)  — 递归 + memo 消除重复子问题
 * 解法3: 递推 DP         — O(n)   / O(n)  — 自底向上填表 ⭐面试首选
 * 解法4: 递推 DP 空间优化 — O(n)   / O(1)  — 滚动变量，面试加分项
 */

// ============================================================
// 解法1: 暴力递归 — 穷举每间房偷/不偷的所有组合
// 时间: O(2^n)  空间: O(n) 递归栈
//
// 【思路】
// 站在第 i 间房前面，做一个选择：
//   偷 → 获得 nums[i]，下一步只能从 i+2 开始（不能偷相邻的）
//   不偷 → 从 i+1 继续考虑
// 取两种选择的较大值。
//
// 决策树 (nums = [2, 7, 9, 3]):
//
//                    rob(0)
//                  /        \
//           rob(2)+2       rob(1)
//           /     \        /     \
//      rob(4)+9  rob(3)  rob(3)+7  rob(2)   ← rob(3)、rob(2) 重复计算!
//      =0+9=9   =3      =3+7=10   =9+2=11
//
// rob(2)+2 = max(9+2, 3+2) = 11+2... 不对，让我们更仔细地看：
// rob(0) = max(rob(2)+2, rob(1))
//        = max(max(rob(4)+9, rob(3))+2, max(rob(3)+7, rob(2)))
//
// 瓶颈：指数级时间，因为同一个 rob(i) 被多次计算。
// ============================================================
class Solution1 {
public:
    int rob(vector<int>& nums) {
        return helper(nums, 0);
    }

private:
    int helper(vector<int>& nums, int i) {
        // 越界 = 没有房子可偷 = 收益 0
        if (i >= (int)nums.size()) return 0;
        
        // 偷第 i 间: nums[i] + 从 i+2 开始的最优
        // 不偷第 i 间: 从 i+1 开始的最优
        return max(helper(nums, i + 2) + nums[i],
                   helper(nums, i + 1));
    }
};

// ============================================================
// 解法2: 记忆化搜索 — 消除暴力递归中的重复子问题
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法1 的瓶颈是同一个 rob(i) 被重复计算。
// 加一个 memo 数组，首次计算时存入结果，后续直接查表返回。
// 每个状态 i 只计算一次 → 总共 n 个状态 → O(n)。
// ============================================================
class Solution2 {
public:
    int rob(vector<int>& nums) {
        int n = nums.size();
        // -1 表示"未计算"（金额 >= 0，不会和合法结果冲突）
        vector<int> memo(n, -1);
        return helper(nums, 0, memo);
    }

private:
    int helper(vector<int>& nums, int i, vector<int>& memo) {
        if (i >= (int)nums.size()) return 0;
        if (memo[i] != -1) return memo[i]; // 已计算，直接返回
        
        memo[i] = max(helper(nums, i + 2, memo) + nums[i],
                      helper(nums, i + 1, memo));
        return memo[i];
    }
};

// ============================================================
// 解法3: 递推 DP — 自底向上填表 ⭐面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 把记忆化搜索"翻译"成 for 循环。
//
// 状态定义: dp[i] = 考虑前 i+1 间房屋(下标 0 到 i)能偷到的最大金额
//
// 状态转移: dp[i] = max(dp[i-1],          ← 不偷第 i 间
//                       dp[i-2] + nums[i]) ← 偷第 i 间
//
// 初始化:
//   dp[0] = nums[0]              （只有一间，偷它）
//   dp[1] = max(nums[0], nums[1])（两间取较大的）
//
// dp 填表方向 (从左到右):
//
//   dp[i-2]  dp[i-1]   dp[i]
//     \                  ↑
//      ————————————————→ |   dp[i] = max(dp[i-1], dp[i-2] + nums[i])
//               \        ↑
//                ——————→ |
//
// 填表示例 (nums = [2, 7, 9, 3, 1]):
//
//   i:      0    1    2    3    4
//   nums:   2    7    9    3    1
//   dp:     2    7   11   11   12
//
//   dp[0] = 2
//   dp[1] = max(2, 7) = 7
//   dp[2] = max(7, 2+9) = 11     ← 偷第0间和第2间
//   dp[3] = max(11, 7+3) = 11    ← 不偷第3间更优
//   dp[4] = max(11, 11+1) = 12   ← 偷第2间和第4间
//   答案 = dp[4] = 12
// ============================================================
class Solution3 {
public:
    int rob(vector<int>& nums) {
        int n = nums.size();
        if (n == 1) return nums[0]; // 边界：只有一间房
        
        vector<int> dp(n);
        dp[0] = nums[0];
        dp[1] = max(nums[0], nums[1]); // 注意：不是 nums[1]!
        
        for (int i = 2; i < n; i++) {
            // 不偷第 i 间 vs 偷第 i 间（必须跳过第 i-1 间）
            dp[i] = max(dp[i - 1], dp[i - 2] + nums[i]);
        }
        
        return dp[n - 1];
    }
};

// ============================================================
// 解法4: 递推 DP + 空间优化 — 滚动变量
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法3 中 dp[i] 只依赖 dp[i-1] 和 dp[i-2]，不需要整个数组。
// 用两个变量 prev2(对应 dp[i-2]) 和 prev1(对应 dp[i-1]) 滚动即可。
//
// 滚动过程 (nums = [2, 7, 9, 3, 1]):
//
//   初始: prev2=2, prev1=7
//   i=2:  curr=max(7, 2+9)=11   → prev2=7,  prev1=11
//   i=3:  curr=max(11, 7+3)=11  → prev2=11, prev1=11
//   i=4:  curr=max(11, 11+1)=12 → prev2=11, prev1=12
//   答案 = prev1 = 12
//
// 关键：必须先用旧的 prev2 算 curr，再更新 prev2 和 prev1!
// ============================================================
class Solution4 {
public:
    int rob(vector<int>& nums) {
        int n = nums.size();
        if (n == 1) return nums[0];
        
        int prev2 = nums[0];               // dp[i-2]
        int prev1 = max(nums[0], nums[1]);  // dp[i-1]
        
        for (int i = 2; i < n; i++) {
            int curr = max(prev1, prev2 + nums[i]);
            // 滚动：窗口向右移一位
            prev2 = prev1;
            prev1 = curr;
        }
        
        return prev1;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间   | 空间  | 核心区别                        |
// |-------------|--------|------|---------------------------------|
// | 暴力递归     | O(2^n) | O(n) | 指数级，大量重复计算              |
// | 记忆化搜索   | O(n)   | O(n) | 用 memo 消除重复，自顶向下       |
// | 递推 DP      | O(n)   | O(n) | 翻译成循环，自底向上填表          |
// | 递推+空间优化 | O(n)   | O(1) | dp[i] 只看前两个，用滚动变量     |
//
// 面试策略：先写解法3（递推DP），被追问时给出解法4（空间优化）。
//
// 【易错点】
//
// 1. dp[1] 初始化错误
//    ✗ dp[1] = nums[1]
//    ✓ dp[1] = max(nums[0], nums[1])
//    原因: dp[1] 是"考虑前两间"的最优，可能只偷第0间
//
// 2. 忘记处理 n==1 的边界
//    ✗ 直接 dp[1] = max(nums[0], nums[1]) → 数组越界
//    ✓ 先 if (n == 1) return nums[0]
//
// 3. 空间优化时更新顺序错误
//    ✗ prev2 = prev1; prev1 = max(prev1, prev2 + nums[i]);
//      → prev2 已经被覆盖，算 curr 时用了新的 prev2（就是旧的 prev1）
//    ✓ int curr = max(prev1, prev2 + nums[i]); prev2 = prev1; prev1 = curr;
//
// 4. 误用贪心（只偷奇数位或偶数位）
//    反例: [2,1,1,2] → 最优是偷 index 0 和 3（=4），
//    而奇数位是 index 1+3=3，偶数位是 index 0+2=3，都不是最优
//    → 必须用 DP 考虑所有合法组合
//
// 【面试追问 — 递进链】
//
// Q1(基础): "暴力解为什么是 O(2^n)？瓶颈在哪？"
//   → 每间房 2 种选择，递归树是指数级的。瓶颈是子问题被重复计算，
//     如 rob(3) 会在 rob(0)→rob(2) 和 rob(1) 两条路径上各算一次。
//
// Q2(优化): "能否将空间从 O(n) 降到 O(1)？"
//   → dp[i] 只依赖 dp[i-1] 和 dp[i-2]，用两个滚动变量即可。见解法4。
//
// Q3(变体): "如果房屋排成环形（首尾相邻），怎么办？"
//   → LeetCode 213。首尾不能同时偷，拆成两个子问题:
//     (1) 考虑 nums[0..n-2]（排除最后一间）
//     (2) 考虑 nums[1..n-1]（排除第一间）
//     取两者最大值。代码只需调用两次本题的函数。
//
// Q4(进阶): "如果房屋排成二叉树呢？"
//   → LeetCode 337。在树上做 DP，每个节点返回 pair<偷, 不偷>:
//     偷当前节点 = nums[node] + 不偷左孩子 + 不偷右孩子
//     不偷当前节点 = max(偷/不偷左孩子) + max(偷/不偷右孩子)
//
// 【系列题串联】
// 198 打家劫舍 (本题): 线性 DP，dp[i] = max(dp[i-1], dp[i-2]+nums[i])
// 213 打家劫舍 II:     环形，拆成两次线性 DP 调用（代码改动: 加一层循环调用）
// 337 打家劫舍 III:    二叉树，树形 DP（代码改动: 从 for 循环变成树的后序遍历）
// 740 删除并获得点数:   先统计频率数组，然后在频率数组上跑本题的 DP（本质相同）
// ============================================================
