/*
 * LeetCode 1190: Reverse Substrings Between Each Pair of Parentheses
 * (反转每对括号间的子串)
 *
 * 【题目本质】
 * 给定含小写字母和括号的字符串，从最内层开始逐层反转括号内容。
 * 核心问题：如何高效处理嵌套反转？
 *
 * 【解法总览】
 * 解法1: 栈模拟      — O(n^2) / O(n) — 面试首选，简洁直观
 * 解法2: 虫洞穿越    — O(n)   / O(n) — 进阶加分，预处理配对+方向切换
 */

// ============================================================
// 解法1: 栈模拟 — 面试首选 ⭐
// 时间: O(n^2)  空间: O(n)
//
// 【思路】
// 维护 stack<string>，初始push一个空串作为最外层容器:
//   '(' → push("") 开启新层
//   ')' → pop栈顶, reverse, 拼接到新栈顶
//   字母 → 追加到栈顶
//
// 示例: s = "(u(love)i)"
//
//   '(' → push("")           栈: ["", ""]
//   'u' → top += 'u'         栈: ["", "u"]
//   '(' → push("")           栈: ["", "u", ""]
//   'l','o','v','e'          栈: ["", "u", "love"]
//   ')' → pop "love" → reverse → "evol" → top += "evol"
//                              栈: ["", "uevol"]
//   'i' → top += 'i'         栈: ["", "uevoli"]
//   ')' → pop "uevoli" → reverse → "iloveu" → top += "iloveu"
//                              栈: ["iloveu"]
//   结果: "iloveu" ✓
//
// 复杂度: 每次 ')' 反转 O(k) 个字符, 最坏嵌套 n/2 层,
//   每层 O(n) → 总 O(n^2)。n<=2000 完全够用。
// ============================================================
class Solution1 {
public:
    string reverseParentheses(string s) {
        stack<string> stk;
        stk.push(""); // 最外层容器

        for (char c : s) {
            if (c == '(') {
                stk.push(""); // 开启新的括号层
            } else if (c == ')') {
                string cur = stk.top(); stk.pop();
                reverse(cur.begin(), cur.end()); // 反转当前层
                stk.top() += cur; // 合并到上一层
            } else {
                stk.top() += c; // 字母追加到当前层
            }
        }
        return stk.top();
    }
};

// ============================================================
// 解法2: 虫洞穿越 (Wormhole Teleportation)
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 每对括号的效果 = "遍历方向反转"。
// 1. 预处理: 用栈建立括号配对映射 pair[i] = j, pair[j] = i
// 2. 遍历: 从 i=0, dir=+1(向右) 开始
//    - 遇到括号: 跳到 pair[i], 反转方向, i += dir
//    - 遇到字母: 收集, i += dir
//    - 越界时停止
//
// 正确性: 一对括号代表一次反转。向右遇到'(', 跳到')'并
// 改为向左 = 把括号内容倒着读。多层嵌套时方向反复切换,
// 效果等同于逐层反转。
//
// 示例: s = "(ed(et(oc))el)"
// 配对: pair[0]=13, pair[3]=10, pair[6]=9
//
// 遍历轨迹:
//   i=0 '('  → i=13, dir=-1, i=12
//   i=12 'l' → 收集'l', i=11
//   i=11 'e' → 收集'e', i=10
//   i=10 ')' → i=3, dir=1, i=4
//   i=4  'e' → 收集'e', i=5
//   i=5  't' → 收集't', i=6
//   i=6  '(' → i=9, dir=-1, i=8
//   i=8  'c' → 收集'c', i=7
//   i=7  'o' → 收集'o', i=6
//   i=6  '(' → i=9, dir=1, i=10
//   i=10 ')' → i=3, dir=-1, i=2
//   i=2  'd' → 收集'd', i=1
//   i=1  'e' → 收集'e', i=0
//   i=0  '(' → i=13, dir=1, i=14 → 越界停止
//
//   收集: "leetcode" ✓
//
// 为什么是 O(n)?
//   每个字母字符只被收集一次。括号字符可能被经过两次(正/反向),
//   但总步数 <= 2n。
// ============================================================
class Solution2 {
public:
    string reverseParentheses(string s) {
        int n = s.size();
        vector<int> pair_idx(n);
        stack<int> stk;

        // 预处理: 建立括号配对映射（双向）
        for (int i = 0; i < n; i++) {
            if (s[i] == '(') {
                stk.push(i);
            } else if (s[i] == ')') {
                int j = stk.top(); stk.pop();
                pair_idx[i] = j; // ')' → '('
                pair_idx[j] = i; // '(' → ')'
            }
        }

        // 虫洞遍历
        string result;
        int i = 0, dir = 1; // dir=1向右, dir=-1向左
        while (i >= 0 && i < n) {
            if (s[i] == '(' || s[i] == ')') {
                // 跳到配对括号, 反转方向
                i = pair_idx[i];
                dir = -dir;
            } else {
                // 收集字母
                result += s[i];
            }
            i += dir; // 按当前方向前进一步
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法      | 时间    | 空间  | 代码量 | 直觉 |
// |-----------|--------|-------|--------|------|
// | 栈模拟    | O(n^2) | O(n)  | 最短   | 简单 |
// | 虫洞穿越  | O(n)   | O(n)  | 中等   | 中等 |
//
// 面试策略: 先写栈模拟(简洁快速), 追问O(n)时讲虫洞法。
//
// ============================================================
// 【易错点】
//
// 1. 栈初始状态忘记push空串:
//    ✗ 栈为空, 第一个字母无处放 → crash
//    ✓ stk.push("") 作为最外层容器
//
// 2. 虫洞法方向切换顺序:
//    ✗ 先 i+=dir 再跳 → 位置错位
//    ✓ 先跳到配对位置, 再反转方向, 最后 i+=dir
//
// 3. 虫洞法终止条件:
//    ✗ while(i < n) → 方向向左时i可能变负
//    ✓ while(i >= 0 && i < n)
//
// 4. 括号配对忘记双向建立:
//    ✗ 只建 pair[j]=i (从'('指向')')
//    ✓ 双向: pair[i]=j 且 pair[j]=i
//
// 5. 字符串拼接性能:
//    ✗ cur = cur + stk.top()  → 多次拷贝
//    ✓ stk.top() += cur       → 直接追加
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 栈模拟最坏 O(n^2)，具体什么情况?
//     s = "(((...)))", n/2 层嵌套, 每层反转约 n/2 字符。
//     但 n<=2000, O(n^2)=4*10^6 可以接受。
//
// Q2: 虫洞法为什么是 O(n)？看起来指针在跳来跳去。
//     每个字母只被收集一次, 每个括号最多经过2次(正/反向),
//     总步数 <= 2n, 所以是 O(n)。
//
// Q3: 如果括号不平衡怎么办？
//     题目保证平衡。若需处理: 先用栈验证平衡性,
//     不平衡时返回原串或报错。
