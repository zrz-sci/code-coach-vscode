/*
 * LeetCode 670: Maximum Swap (最大交换)
 * 
 * 【题目本质】
 * 给定一个非负整数，至多交换一次任意两位数字，使得结果最大。
 * 贪心：让尽可能高的位放尽可能大的数字。
 *
 * 【解法总览】
 * 解法1: 暴力枚举所有交换对     — O(n²) / O(n) — 最直觉
 * 解法2: 贪心（后缀最大值数组） — O(n)  / O(n) — 面试首选
 * 解法3: 贪心（记录每个数字最后出现位置）— O(n) / O(1) — 代码最简洁
 *
 * 其中 n 是数字的位数，本题 n ≤ 9
 */

// ============================================================
// 解法1: 暴力枚举 — 枚举所有可能的交换对，取最大值
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 数字最多 9 位，所有交换对数量最多 C(9,2) = 36。
// 直接枚举每一对 (i, j)，交换后比较，保留最大值。
// 这是最直觉的思路，n 小所以完全可行。
// ============================================================
class Solution1 {
public:
    int maximumSwap(int num) {
        string s = to_string(num);
        int n = s.size();
        int best = num;
        
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                swap(s[i], s[j]);
                best = max(best, stoi(s));
                // 撤销交换，恢复原始状态
                swap(s[i], s[j]);
            }
        }
        return best;
    }
};

// ============================================================
// 解法2: 贪心（后缀最大值）— 面试首选 ⭐
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 贪心策略：从最高位开始扫描，如果当前位不是其右侧（含自身）
// 的最大数字，就把右侧最大数字的最右出现位置换到当前位。
//
// 为什么"最右出现位置"？
//   例如 1993: 右侧最大值是 9，出现在下标 1 和 2
//   交换 s[0] 和 s[1] → 9193
//   交换 s[0] 和 s[2] → 9913  ← 这个更大！
//   选最右的 9 来换，被换走的 1 落在更低的位上，损失更小。
//
// 算法步骤：
//   1. 从右到左构建 suffixMaxIdx 数组
//   2. 从左到右扫描，找第一个 s[i] < s[suffixMaxIdx[i]] 的位置
//   3. 交换并返回
//
// 示例: num = 2736
//   字符串:      ['2', '7', '3', '6']
//   下标:          0    1    2    3
//
//   suffixMaxIdx: [1,   1,   3,   3]
//   含义: 位置0右侧最大是'7'在下标1, 位置2右侧最大是'6'在下标3
//
//   从左扫描:
//     i=0: s[0]='2' < s[1]='7' → 交换 s[0] 和 s[1]
//     结果: "7236" → 返回 7236
// ============================================================
class Solution2 {
public:
    int maximumSwap(int num) {
        string s = to_string(num);
        int n = s.size();
        
        // suffixMaxIdx[i] = 从下标 i 到末尾，最大字符的最右出现下标
        vector<int> suffixMaxIdx(n);
        suffixMaxIdx[n - 1] = n - 1;
        for (int i = n - 2; i >= 0; i--) {
            // 关键：用 > 而不是 >=
            // 当 s[i] == s[右侧最大] 时，保留右侧更靠右的下标
            // 这样交换时低位损失最小
            if (s[i] > s[suffixMaxIdx[i + 1]]) {
                suffixMaxIdx[i] = i;
            } else {
                suffixMaxIdx[i] = suffixMaxIdx[i + 1];
            }
        }
        
        // 从高位到低位，找第一个"不够大"的位
        for (int i = 0; i < n; i++) {
            int j = suffixMaxIdx[i];
            if (s[j] > s[i]) {
                // 当前位可以变大，执行交换
                swap(s[i], s[j]);
                return stoi(s);
            }
        }
        
        // 所有位都已经是最优排列，无需交换
        return num;
    }
};

// ============================================================
// 解法3: 贪心（记录每个数字最后出现位置）— 代码最简洁
// 时间: O(n)  空间: O(1) — 只用长度 10 的数组
//
// 【思路】
// 换一个角度：不预处理后缀，而是直接记录 0-9 每个数字最后出现的下标。
// 然后从高位到低位遍历，对于每一位，从 9 开始往下试：
//   "有没有比当前位更大的数字，且它的最后出现位置在当前位的右边？"
// 如果有，交换并返回。
//
// 为什么从 9 往下试？因为我们要让高位尽可能大。
// 为什么用"最后出现位置"？同一个数字取最右的那个，低位损失最小。
//
// 示例: num = 98368
//   字符串:   ['9', '8', '3', '6', '8']
//   下标:       0    1    2    3    4
//   last[8] = 4, last[9] = 0, last[3] = 2, last[6] = 3
//
//   i=0, s[0]='9': d=9..9, 没有比9更大的 → 跳过
//   i=1, s[1]='8': d=9: last[9]=0 < 1 → 不行; 没有更大的 → 跳过  
//   i=2, s[2]='3': d=9: last[9]=0 < 2 → 不行
//                  d=8: last[8]=4 > 2 → 交换 s[2] 和 s[4]
//   结果: "98863" → 返回 98863
// ============================================================
class Solution3 {
public:
    int maximumSwap(int num) {
        string s = to_string(num);
        int n = s.size();
        
        // last[d] = 数字 d 在字符串中最后一次出现的下标
        int last[10] = {};
        for (int i = 0; i < n; i++) {
            last[s[i] - '0'] = i;
        }
        
        for (int i = 0; i < n; i++) {
            // 从 9 开始尝试，看能否找到比 s[i] 更大的数字在右边
            for (int d = 9; d > s[i] - '0'; d--) {
                if (last[d] > i) {
                    // 数字 d 最后出现在 i 的右边，交换后高位变大
                    swap(s[i], s[last[d]]);
                    return stoi(s);
                }
            }
        }
        
        return num;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间   | 空间  | 核心思想                     |
// |------|--------|-------|------------------------------|
// | 暴力 | O(n²)  | O(n)  | 枚举所有交换对               |
// | 后缀 | O(n)   | O(n)  | 预处理右侧最大值的最右位置   |
// | 最后 | O(n)   | O(1)  | 记录每个数字的最后出现位置   |
//
// 本题 n ≤ 9，三种解法实际运行时间几乎无差异。
// 面试推荐解法2（后缀最大值），逻辑最清晰易讲；
// 解法3 代码最短，适合快速手写。
//
// 【易错点】
// 1. 后缀最大值比较用 > 还是 >=：
//    ✗ if (s[i] >= s[suffixMaxIdx[i+1]]) suffixMaxIdx[i] = i;
//      → 相等时取了左边的下标，导致 1993 → 9193 而非 9913
//    ✓ if (s[i] > s[suffixMaxIdx[i+1]]) suffixMaxIdx[i] = i;
//      → 相等时保留右侧下标
//
// 2. 解法3内层循环的终止条件：
//    ✗ for (int d = 9; d >= s[i]-'0'; d--)  → d == s[i]-'0' 时
//      last[d] 可能等于 i 本身，交换自己没意义但不会报错，
//      可能和更右边同值数字交换导致数字不变，浪费交换机会
//    ✓ for (int d = 9; d > s[i]-'0'; d--)   → 只看严格更大的数字
//
// 3. 忘记处理不需要交换的情况：
//    如果数字已经是非递增排列如 9973，遍历完不会进入交换分支，
//    必须在循环外 return num。不能假设一定会交换。
//
// 【面试追问】
// Q1: 暴力解的复杂度是多少？这道题暴力能过吗？
//     A: O(n²)，n≤9 所以完全可以。但面试官期望看到贪心思路。
//
// Q2: 贪心策略的正确性怎么证明？
//     A: 高位的权重严格大于所有低位权重之和（如千位 1000 > 999）。
//     所以让最高位尽可能大一定是全局最优。从左到右第一个可以变大
//     的位交换后，增量在最高可能的位上，不可能有更好的选择。
//
// Q3: 如果允许交换 K 次呢？
//     A: 贪心策略不变：每次找最高位可以提升的位交换，重复 K 次。
//     但需要注意重复交换可能把之前换走的数字换回来，需要更细致
//     的分析。一种思路是每次贪心选增益最大的交换执行。
// ============================================================
