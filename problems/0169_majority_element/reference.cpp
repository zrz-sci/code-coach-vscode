/*
 * LeetCode 169: 多数元素 (Majority Element)
 *
 * 【题目本质】
 * 找出数组中出现次数超过 ⌊n/2⌋ 的元素。
 * 核心性质：多数元素的数量比其他所有元素加起来还多。
 *
 * 【解法总览】
 * 解法1: 哈希表计数      — O(n) / O(n)      — 最直觉
 * 解法2: 排序取中位数    — O(n log n) / O(1) — 简单直接
 * 解法3: Boyer-Moore 投票 — O(n) / O(1)      — 最优 (Follow-up)
 * 解法4: 分治            — O(n log n) / O(log n) — 展示分治思维
 */

// ============================================================
// 解法1: 哈希表计数 — 统计每个元素出现次数
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 最自然的想法：遍历一遍，用哈希表记录每个数出现几次，
// 谁的计数超过 n/2 就是答案。
// 一旦某个数的计数超过阈值就可以提前返回，不用遍历完。
// 
// 瓶颈：需要 O(n) 的额外空间来存储计数。
// ============================================================
class Solution1 {
public:
    int majorityElement(vector<int>& nums) {
        unordered_map<int, int> count;
        int n = nums.size();
        for (int num : nums) {
            count[num]++;
            // 提前返回：一旦某数计数过半，直接返回
            if (count[num] > n / 2) return num;
        }
        return -1; // 题目保证一定存在多数元素
    }
};

// ============================================================
// 解法2: 排序取中位数 — 排序后中间位置一定是多数元素
// 时间: O(n log n)  空间: O(1)（原地排序）
//
// 【思路】
// 多数元素出现超过 n/2 次。排序后，这些相同的元素会聚在一起，
// 形成一段长度 > n/2 的连续区间。
// 无论这段区间在最左、最右还是中间，它一定覆盖 index n/2。
//
// 示意图:
//   假设多数元素是 x，出现 k 次 (k > n/2)
//   最极端情况1: x 全在左边       最极端情况2: x 全在右边
//   [x x x x x _ _ _ _]           [_ _ _ _ x x x x x]
//            ↑ n/2 被 x 覆盖                ↑ n/2 被 x 覆盖
// ============================================================
class Solution2 {
public:
    int majorityElement(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        return nums[nums.size() / 2];
    }
};

// ============================================================
// 解法3: Boyer-Moore 投票算法 — 抵消思想 ⭐ 面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 这是 Follow-up 要求的 O(n) 时间 O(1) 空间解法。
//
// 核心洞察：多数元素的数量 > 所有其他元素数量之和。
// 想象"投票对战"：
//   - 维护一个候选人 candidate 和计数 count
//   - 遇到相同元素，count+1（得到一票支持）
//   - 遇到不同元素，count-1（被抵消一票）
//   - count 归零时，换新的候选人
//   - 因为多数元素"人多势众"，最后一定是它存活
//
// 过程演示 — nums = [2, 2, 1, 1, 1, 2, 2]:
//
//   索引:    0    1    2    3    4    5    6
//   元素:    2    2    1    1    1    2    2
//   操作:   新选  +1   -1   归零  新选  -1   归零→新选
//   候选:    2    2    2    2→1   1    1    1→2
//   计数:    1    2    1    0→1   1→2  1    0→1
//                                              ↑ 最终候选=2 ✓
//
// 为什么正确？
// 将过程看作"配对抵消"：每次 count-1 都消耗了一个多数和一个非多数。
// 多数元素总数 > n/2，即使被全部非多数元素抵消，还会剩余。
// ============================================================
class Solution3 {
public:
    int majorityElement(vector<int>& nums) {
        int candidate = 0;
        int count = 0;
        
        for (int num : nums) {
            // 关键：count == 0 时更换候选人，必须在判断相等之前
            if (count == 0) {
                candidate = num;
            }
            // 相同则支持(+1)，不同则抵消(-1)
            count += (num == candidate) ? 1 : -1;
        }
        
        // 题目保证多数元素一定存在，直接返回
        // 若不保证存在，需要第二遍验证 candidate 出现次数是否 > n/2
        return candidate;
    }
};

// ============================================================
// 解法4: 分治 — 全局多数一定是左半或右半的多数
// 时间: O(n log n)  空间: O(log n) 递归栈
//
// 【思路】
// 分治三步：
//   1. 分：数组分成左右两半
//   2. 治：递归找左半多数 leftMaj 和右半多数 rightMaj
//   3. 合：全局多数一定是 leftMaj 或 rightMaj 之一
//          线性扫描计数验证哪个在整个区间出现更多
//
// 为什么全局多数一定是左或右的多数之一？
//   反证：如果全局多数 x 既不是左半多数也不是右半多数，
//   则 x 在左半出现 ≤ 左半长度/2 次，在右半出现 ≤ 右半长度/2 次，
//   总计 ≤ n/2 次，矛盾。
//
// 复杂度分析：T(n) = 2T(n/2) + O(n)，由主定理 T(n) = O(n log n)
// ============================================================
class Solution4 {
public:
    int majorityElement(vector<int>& nums) {
        return majority(nums, 0, nums.size() - 1);
    }
    
private:
    int majority(vector<int>& nums, int lo, int hi) {
        // base case: 单个元素就是自己的多数
        if (lo == hi) return nums[lo];
        
        int mid = lo + (hi - lo) / 2;
        int leftMaj = majority(nums, lo, mid);
        int rightMaj = majority(nums, mid + 1, hi);
        
        // 左右多数相同，无需验证
        if (leftMaj == rightMaj) return leftMaj;
        
        // 不同则分别计数，返回出现次数更多的那个
        int leftCount = count(nums.begin() + lo, nums.begin() + hi + 1, leftMaj);
        int rightCount = count(nums.begin() + lo, nums.begin() + hi + 1, rightMaj);
        
        return leftCount > rightCount ? leftMaj : rightMaj;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间       | 空间     | 改原数组 | 适用场景         |
// |-------------|-----------|---------|---------|-----------------|
// | 哈希表       | O(n)      | O(n)    | 否      | 通用，最直觉      |
// | 排序         | O(nlogn)  | O(1)*   | 是      | 代码最短          |
// | Boyer-Moore | O(n)      | O(1)    | 否      | 面试首选          |
// | 分治         | O(nlogn)  | O(logn) | 否      | 展示递归分治思维   |
//
// *排序 O(1) 指堆排序等原地排序，std::sort 实际用 O(log n) 栈空间
//
// 面试策略：先说哈希表展示理解 → 主动优化到 Boyer-Moore 展示功力
//
// 【易错点】
// 1. Boyer-Moore 中 count==0 更换候选人的逻辑必须在判断相等之前：
//    ✗ if (num == candidate) count++; else { count--; if (count < 0) { candidate = num; count = 0; } }
//      → 这样在 count 刚好为0时遇到新元素不会正确更换候选人
//    ✓ if (count == 0) candidate = num; count += (num == candidate) ? 1 : -1;
//
// 2. 若题目不保证多数元素存在，Boyer-Moore 需要第二遍验证：
//    ✗ 直接返回 candidate
//    ✓ 再遍历一遍确认 candidate 出现次数 > n/2，否则返回 -1
//
// 3. 排序解法取 nums[n/2] 而不是 nums[(n-1)/2]：
//    n=3 时 n/2=1，(n-1)/2=1 一样；但 n=4 时 n/2=2，(n-1)/2=1
//    多数元素占 >2 个位置，index 2 一定被覆盖，index 1 不一定
//    例: [1,2,2,2] 排序后 nums[2]=2 ✓ 但 nums[1]=2 只是巧合
//
// 4. 分治合并时不能比较值的大小来决定多数：
//    ✗ return max(leftMaj, rightMaj);  // 多数元素不一定是最大值
//    ✓ 分别计数 leftMaj 和 rightMaj 在区间内的出现次数
//
// 【面试追问 — 递进链】
//
// Q1: "暴力怎么做？复杂度多少？瓶颈在哪？"
// → 哈希表 O(n)/O(n)，瓶颈在 O(n) 空间。
//    或者暴力双循环对每个元素计数 O(n²)/O(1)，瓶颈在时间。
//
// Q2: "能否同时做到 O(n) 时间和 O(1) 空间？" (Follow-up)
// → Boyer-Moore 投票算法。利用多数元素数量 > 其他元素总和的性质，
//    一次遍历通过抵消找到候选人。
//
// Q3: "如果不保证多数元素存在呢？"
// → Boyer-Moore 第一遍找候选人，第二遍验证计数是否真的 > n/2。
//    不存在则返回 -1。
//
// Q4: "如果要找出现次数超过 ⌊n/3⌋ 的所有元素？" (LeetCode 229)
// → 扩展 Boyer-Moore：维护两个候选人和两个计数器。
//    出现超过 n/3 的元素最多两个。遍历完后需要第二遍验证。
//    代码改动：candidate 从 1 个变 2 个，count 从 1 个变 2 个，
//    抵消逻辑变为"两个候选人都不匹配时两个计数器同时 -1"。
// ============================================================
