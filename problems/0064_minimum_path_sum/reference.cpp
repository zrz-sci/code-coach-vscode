// ============================================================
// LeetCode 64. Minimum Path Sum
// 难度: Medium | 标签: Array, Dynamic Programming, Matrix
// ============================================================

// ------------------------------------------------------------
// 解法1: 二维 DP（标准解法）
// 时间 O(mn), 空间 O(mn)
//
// 思考过程:
//   1. 定义 dp[i][j] = 从(0,0)到(i,j)的最小路径和
//   2. 只能从上方(i-1,j)或左方(i,j-1)到达
//      -> dp[i][j] = grid[i][j] + min(dp[i-1][j], dp[i][j-1])
//   3. 边界: 第一行只能从左来(前缀和), 第一列只能从上来(前缀和)
//
// DP表示例 (grid = [[1,3,1],[1,5,1],[4,2,1]]):
//   grid:        dp:
//   1  3  1      1  4  5
//   1  5  1  ->  2  7  6
//   4  2  1      6  8  7  <- 答案=7
// ------------------------------------------------------------
class Solution1 {
public:
    int minPathSum(vector<vector<int>>& grid) {
        int m = grid.size(), n = grid[0].size();
        vector<vector<int>> dp(m, vector<int>(n));

        // 起点
        dp[0][0] = grid[0][0];

        // 第一列: 只能从上方来
        for (int i = 1; i < m; i++)
            dp[i][0] = dp[i-1][0] + grid[i][0];

        // 第一行: 只能从左方来
        for (int j = 1; j < n; j++)
            dp[0][j] = dp[0][j-1] + grid[0][j];

        // 填表: 从上到下, 从左到右
        for (int i = 1; i < m; i++)
            for (int j = 1; j < n; j++)
                dp[i][j] = grid[i][j] + min(dp[i-1][j], dp[i][j-1]);

        return dp[m-1][n-1];
    }
};

// ------------------------------------------------------------
// 解法2: 一维 DP 空间优化 (面试首选)
// 时间 O(mn), 空间 O(n)
//
// 思考过程:
//   1. dp[i][j] 只依赖 dp[i-1][j](正上方) 和 dp[i][j-1](正左方)
//   2. 逐行处理时, 用一维数组:
//      - dp[j] 更新前 = 上一行的值 (即 dp[i-1][j])
//      - dp[j-1] = 当前行已更新的值 (即 dp[i][j-1])
//   3. 关键: 每行开头, dp[0] 需要单独累加 grid[i][0]
//
// 滚动过程 (grid = [[1,3,1],[1,5,1],[4,2,1]]):
//   初始(第0行): dp = [1, 4, 5]
//   处理第1行:   dp = [2, 7, 6]
//     dp[0]=1+1=2, dp[1]=5+min(4,2)=7, dp[2]=1+min(5,7)=6
//   处理第2行:   dp = [6, 8, 7]
//     dp[0]=2+4=6, dp[1]=2+min(7,6)=8, dp[2]=1+min(6,8)=7
//   答案 = dp[2] = 7
// ------------------------------------------------------------
class Solution2 {
public:
    int minPathSum(vector<vector<int>>& grid) {
        int m = grid.size(), n = grid[0].size();
        vector<int> dp(n);

        // 初始化第一行
        dp[0] = grid[0][0];
        for (int j = 1; j < n; j++)
            dp[j] = dp[j-1] + grid[0][j];

        // 逐行更新
        for (int i = 1; i < m; i++) {
            dp[0] += grid[i][0];           // 第一列单独处理
            for (int j = 1; j < n; j++)
                dp[j] = grid[i][j] + min(dp[j], dp[j-1]);
                //                       ^上方     ^左方(当前行已更新)
        }
        return dp[n-1];
    }
};

// ------------------------------------------------------------
// 解法3: 原地修改输入
// 时间 O(mn), 空间 O(1)
//
// 思考过程:
//   1. 如果允许修改 grid, 直接在上面累加
//   2. grid[i][j] += min(grid[i-1][j], grid[i][j-1])
//   3. 优势: O(1)空间; 劣势: 破坏原始数据
//   4. 面试时要主动说明: "这种方法修改了输入, 需要确认是否可以"
// ------------------------------------------------------------
class Solution3 {
public:
    int minPathSum(vector<vector<int>>& grid) {
        int m = grid.size(), n = grid[0].size();

        // 第一列: 从上到下累加
        for (int i = 1; i < m; i++)
            grid[i][0] += grid[i-1][0];

        // 第一行: 从左到右累加
        for (int j = 1; j < n; j++)
            grid[0][j] += grid[0][j-1];

        // 填表
        for (int i = 1; i < m; i++)
            for (int j = 1; j < n; j++)
                grid[i][j] += min(grid[i-1][j], grid[i][j-1]);

        return grid[m-1][n-1];
    }
};

/*
 * ============================================================
 * 解法对比:
 * ============================================================
 * | 解法     | 时间   | 空间   | 修改输入 | 面试推荐 |
 * |----------|--------|--------|---------|---------|
 * | 二维DP   | O(mn)  | O(mn)  | 否      | 起步讲解 |
 * | 一维DP   | O(mn)  | O(n)   | 否      | 首选     |
 * | 原地修改 | O(mn)  | O(1)   | 是      | 加分项   |
 *
 * 面试策略: 先写二维DP讲清思路 -> 优化到一维DP展示能力
 *           -> 提及原地修改作为加分
 *
 * ============================================================
 * 易错点:
 * ============================================================
 * 1. 忘记初始化第一行和第一列 (它们只有一条路径)
 *    错误: 直接从(1,1)填表, dp[0][1]=0 而不是 grid[0][0]+grid[0][1]
 *
 * 2. 一维DP中 dp[0] 每行需单独累加 grid[i][0]
 *    错误: 跳过 dp[0] 的更新, 导致第一列的值始终是第一行的
 *
 * 3. 空间优化更新顺序搞混
 *    本题从左到右是正确的 (需要当前行的 dp[j-1])
 *    对比: 0-1背包需要从右到左 (防止重复使用)
 *
 * 4. 原地修改后忘了输入已被改变
 *    如果之后还需要原始 grid 就会出 bug
 *
 * ============================================================
 * 面试追问:
 * ============================================================
 * Q1: 输出具体路径?
 *     -> 额外记录方向数组 dir[i][j], 从终点反向追踪
 *
 * Q2: 可以上下左右四方向?
 *     -> 不再是DAG, 用 Dijkstra (非负权重), O(mn*log(mn))
 *
 * Q3: 有障碍物?
 *     -> 障碍格 dp[i][j] = INF, 其余正常转移
 *
 * Q4: 浮点数权重?
 *     -> 同样DP, 注意浮点比较精度
 */
