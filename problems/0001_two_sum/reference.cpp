/*
 * LeetCode 1: Two Sum (两数之和)
 *
 * 【题目本质】
 * 在数组中找两个数使得它们的和等于 target，返回它们的原始索引。
 * 核心问题：对每个 nums[i]，能否快速找到 target - nums[i]？
 *
 * 【解法总览】
 * 解法1: 暴力双循环      — O(n²) / O(1)   — 最直觉，枚举所有配对
 * 解法2: 哈希表(一次遍历) — O(n)  / O(n)   — 面试首选，空间换时间
 * 解法3: 排序+双指针      — O(nlogn) / O(n) — 进阶，适合已排序数组或扩展到3Sum
 */

// ============================================================
// 解法1: 暴力双循环 — 枚举所有 (i, j) 配对
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 最朴素的想法：尝试数组中每一对 (i, j)，检查和是否等于 target。
// 这是理解题意的基础，面试中可以先说这个，表明你理解了问题。
//
// 示例: nums = [2, 7, 11, 15], target = 9
//   i=0, j=1: 2+7=9 ✓ → 返回 [0,1]
//   (如果不是，继续 i=0,j=2; i=0,j=3; i=1,j=2; ...)
//
// 瓶颈分析：
//   外层固定 nums[i]，内层在做的事是"查找 target-nums[i]"
//   这个查找操作是 O(n)，如果能降到 O(1)，总体就从 O(n²) 降到 O(n)
// ============================================================
class Solution1 {
public:
    vector<int> twoSum(vector<int>& nums, int target) {
        int n = nums.size();
        for (int i = 0; i < n; i++) {
            // 从 i+1 开始，避免重复配对和自身配对
            for (int j = i + 1; j < n; j++) {
                if (nums[i] + nums[j] == target) {
                    return {i, j};
                }
            }
        }
        // 题目保证有且仅有一个答案，不会走到这里
        return {};
    }
};

// ============================================================
// 解法2: 哈希表（一次遍历） — 面试首选 ⭐
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法1的瓶颈在于"查找配对"需要 O(n)。
// 核心优化：用哈希表把"查找"从 O(n) 降到 O(1)。
//
// 做法：遍历数组，对于每个 nums[i]：
//   1. 计算 complement = target - nums[i]
//   2. 在哈希表中查找 complement（O(1)）
//   3. 如果找到 → 返回两个索引
//   4. 如果没找到 → 把 nums[i] 存入哈希表，供后续元素配对
//
// 为什么"边遍历边建表"就够了？
//   假设答案是 (i, j)，i < j。当遍历到 j 时，nums[i] 已经在
//   前面被存进了哈希表，所以一定能找到。
//
// 为什么"先查后存"？
//   如果先存后查，遍历到 nums[i] 时把它存入表，再去查 complement，
//   当 complement == nums[i] 时（如 [3,3] target=6），会找到自己。
//   先查后存：查的时候表里还没有当前元素，不会自我匹配。
//
// 示例: nums = [2, 7, 11, 15], target = 9
//   i=0: complement=7, 表{} 无7   → 存入 {2:0}
//   i=1: complement=2, 表{2:0} 有2 → 返回 [0, 1] ✓
//
// 示例: nums = [3, 3], target = 6
//   i=0: complement=3, 表{} 无3   → 存入 {3:0}
//   i=1: complement=3, 表{3:0} 有3 → 返回 [0, 1] ✓
//   （先查后存，i=1 查到的是 i=0 的那个3，不是自己）
// ============================================================
class Solution2 {
public:
    vector<int> twoSum(vector<int>& nums, int target) {
        // key: 元素值, value: 该元素在原数组中的索引
        // 用 unordered_map 保证平均 O(1) 查找
        unordered_map<int, int> seen;
        
        for (int i = 0; i < (int)nums.size(); i++) {
            int complement = target - nums[i];
            
            // 先查：配对元素是否已在表中
            auto it = seen.find(complement);
            if (it != seen.end()) {
                // 找到了！it->second 是配对元素的索引
                return {it->second, i};
            }
            
            // 后存：当前元素存入表中，供后续元素来配对
            seen[nums[i]] = i;
        }
        
        return {}; // 题目保证有解
    }
};

// ============================================================
// 解法3: 排序 + 双指针
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 如果数组有序，可以用左右双指针从两端向中间夹逼：
//   - sum < target → left++ (让和变大)
//   - sum > target → right-- (让和变小)
//   - sum == target → 找到
//
// 但排序会打乱原始索引，所以需要用 pair<值, 原始索引> 来排序。
//
// 为什么双指针不会漏解？
//   反证法：假设答案是 (a, b)，a < b。
//   如果 left 指向 a 时 right 已经越过了 b，说明之前 left 指向某个
//   值 ≤ a 时 right 从 b 移到了更左边，即 left+right 的和 > target，
//   但 left ≤ a 且 right = b，和 ≤ a+b = target，矛盾。
//
// 示例: nums = [3, 2, 4], target = 6
//   带索引: [(2,1), (3,0), (4,2)]  ← 按值排序
//   left=0, right=2: 2+4=6 == target → 返回原始索引 [1, 2] ✓
//
// 这个解法的价值：
//   - 时间 O(n log n) 不如哈希表的 O(n)
//   - 但双指针思路在 3Sum/4Sum 中更实用（哈希表去重很麻烦）
//   - 如果数组本身已排序，就是 O(n) 时间 O(1) 空间，比哈希表更优
// ============================================================
class Solution3 {
public:
    vector<int> twoSum(vector<int>& nums, int target) {
        int n = nums.size();
        
        // 保存 (值, 原始索引)，排序后仍能追溯原始位置
        vector<pair<int, int>> sorted_nums(n);
        for (int i = 0; i < n; i++) {
            sorted_nums[i] = {nums[i], i};
        }
        sort(sorted_nums.begin(), sorted_nums.end());
        
        // 双指针夹逼
        int left = 0, right = n - 1;
        while (left < right) {
            int sum = sorted_nums[left].first + sorted_nums[right].first;
            if (sum == target) {
                return {sorted_nums[left].second, sorted_nums[right].second};
            } else if (sum < target) {
                left++;   // 和太小，左指针右移让和变大
            } else {
                right--;  // 和太大，右指针左移让和变小
            }
        }
        
        return {};
    }
};

// ============================================================
// 【解法对比】
//
// | 解法      | 时间       | 空间  | 优势                      | 劣势                      |
// |-----------|-----------|-------|--------------------------|--------------------------|
// | 暴力      | O(n²)     | O(1)  | 无额外空间，代码最简单       | 慢                        |
// | 哈希表    | O(n)      | O(n)  | 最快，代码简洁              | 额外空间 O(n)             |
// | 排序+双指针| O(nlogn)  | O(n)  | 适合扩展到3Sum/4Sum        | 需额外存原始索引，不如哈希快 |
//
// 面试选择：先说暴力思路表明理解题意，然后写哈希表解法。
// 如果面试官追问"数组有序怎么办"，再讲双指针。
//
// ============================================================
// 【易错点】
//
// 1. 先存后查导致自身配对:
//    ✗ seen[nums[i]] = i; if (seen.count(complement)) ...
//      → [3,3] target=6, i=0时存入{3:0}再查complement=3, 找到自己
//    ✓ if (seen.count(complement)) ...; seen[nums[i]] = i;
//      → 先查再存，i=0时表为空查不到，存入后 i=1查到的是i=0的3
//
// 2. 暴力解法内层起点错误:
//    ✗ for (int j = 0; j < n; j++)  → j==i 时自己和自己配对
//    ✓ for (int j = i + 1; j < n; j++)
//
// 3. 排序后忘记保存原始索引:
//    ✗ sort(nums.begin(), nums.end()); return {left, right};
//      → 返回的是排序后的位置，不是原始索引
//    ✓ 用 vector<pair<int,int>> 保存 (值, 原始索引) 再排序
//
// 4. 用 [] 访问不存在的 key:
//    ✗ if (seen[complement] >= 0)  → [] 会自动插入默认值0，污染哈希表
//    ✓ if (seen.count(complement)) 或 seen.find(complement) != seen.end()
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 暴力能过吗？瓶颈在哪？
//     n ≤ 10⁴, O(n²) ≈ 10⁸ 勉强能过。瓶颈在对每个元素做 O(n) 的线性查找。
//
// Q2: 如果数组已经排好序呢？
//     双指针 O(n) 时间 O(1) 空间，比哈希表省空间。
//     这就是 LeetCode 167 的场景。
//
// Q3: 如果有多个有效答案，要全部返回呢？
//     哈希表改为 unordered_map<int, vector<int>>，一个值对应多个索引。
//     找到配对时从两个索引列表中组合出所有 (i,j) 对。
//
// Q4: 如果这个函数用同一个数组被大量调用（不同 target），怎么优化？
//     预处理阶段：排序一次 O(nlogn) 或建一次哈希表 O(n)。
//     每次查询：双指针 O(n) 或哈希表遍历 O(n)。
//     核心：把一次性工作放到预处理阶段。
//
