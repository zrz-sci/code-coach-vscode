/*
 * LeetCode 674: 最长连续递增序列
 * 
 * 【题目本质】
 * 在数组中找最长的一段连续子数组，使得元素严格递增。
 * 关键词是"连续"——和 LIS(300) 不同，这里不能跳着选。
 *
 * 【解法总览】
 * 解法1: 暴力枚举      — O(n²) / O(1) — 每个起点向右扫到断点
 * 解法2: 一次遍历(贪心) — O(n)  / O(1) — 计数器 + 断点重置 ⭐面试首选
 * 解法3: 线性 DP        — O(n)  / O(n) — dp[i]=以i结尾的最长连续递增长度
 * 解法3b: DP空间优化    — O(n)  / O(1) — 滚动变量，和解法2等价
 */

// ============================================================
// 解法1: 暴力枚举 — 每个起点向右扫到断点
// 时间: O(n²) 最坏  空间: O(1)
//
// 【思路】
// 最朴素的想法：对每个位置 l 作为起点，向右扩展直到不再递增。
// 记录所有段中最长的。
//
// 瓶颈：如果 [l, r] 是递增段，那么以 l+1,...,r-1 为起点的段
// 一定不会比 [l,r] 更长，但我们还是会重复扫描它们。
//
// 示例 nums = [1, 3, 5, 4, 7]:
//   l=0: 扫到 r=2 (1<3<5, 但5≥4断) → 长度3
//   l=1: 扫到 r=2 (3<5, 但5≥4断)   → 长度2 ← 重复工作
//   l=2: 扫到 r=2 (5≥4断)           → 长度1 ← 重复工作
//   l=3: 扫到 r=4 (4<7)             → 长度2
//   l=4: 只有自己                    → 长度1
//   答案: 3
// ============================================================
class Solution1 {
public:
    int findLengthOfLCIS(vector<int>& nums) {
        int n = nums.size();
        int ans = 1;
        for (int l = 0; l < n; l++) {
            int r = l;
            while (r + 1 < n && nums[r + 1] > nums[r]) {
                r++;
            }
            ans = max(ans, r - l + 1);
        }
        return ans;
    }
};

// ============================================================
// 解法2: 一次遍历（贪心）— 计数器 + 断点重置 ⭐面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 从解法1的瓶颈出发：不需要对每个起点重新扫描。
// 维护一个计数器 cur 表示"当前连续递增段的长度"：
//   - nums[i] > nums[i-1]：递增，cur++
//   - 否则：断裂，cur 重置为 1（当前元素是新段起点）
// 全程用 ans 记录 cur 的最大值。
//
// 一次遍历过程 (nums = [1, 3, 5, 4, 7]):
//
//   i=0: cur=1, ans=1  (初始化)
//   i=1: 3>1 → cur=2, ans=2
//   i=2: 5>3 → cur=3, ans=3
//   i=3: 4≤5 → cur=1, ans=3  ← 断裂！重置
//   i=4: 7>4 → cur=2, ans=3
//   最终 ans=3
//
// 为什么正确？每段连续递增区间只被扫描一次，
// 断裂点自然把不同段分开。不会漏掉任何段。
// ============================================================
class Solution2 {
public:
    int findLengthOfLCIS(vector<int>& nums) {
        int ans = 1;  // 至少一个元素，答案至少为1
        int cur = 1;  // 当前连续递增段的长度
        for (int i = 1; i < (int)nums.size(); i++) {
            if (nums[i] > nums[i - 1]) {
                cur++;           // 严格递增，延长当前段
            } else {
                cur = 1;         // 断裂，当前元素自成新段（长度1）
            }
            ans = max(ans, cur); // 随时更新全局最大值
        }
        return ans;
    }
};

// ============================================================
// 解法3: 线性 DP — dp[i] = 以 nums[i] 结尾的最长连续递增长度
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 定义状态：dp[i] = 以 nums[i] 结尾的最长连续递增序列的长度
// 
// 转移方程：
//   if nums[i] > nums[i-1]:  dp[i] = dp[i-1] + 1
//   else:                     dp[i] = 1
//
// 初始化：dp[0] = 1（单个元素长度为1）
// 答案：max(dp[0..n-1])
//
// DP 填表示意 (nums = [1, 3, 5, 4, 7]):
//   i:     0   1   2   3   4
//   nums:  1   3   5   4   7
//   dp:    1   2   3   1   2
//              ↑   ↑   ↑   ↑
//            3>1  5>3  4≤5  7>4
//   
//   dp[i] 只依赖 dp[i-1] → 可以空间优化为一个变量
// ============================================================
class Solution3 {
public:
    int findLengthOfLCIS(vector<int>& nums) {
        int n = nums.size();
        vector<int> dp(n, 1);  // 初始化全部为1
        int ans = 1;
        for (int i = 1; i < n; i++) {
            if (nums[i] > nums[i - 1]) {
                dp[i] = dp[i - 1] + 1;  // 延续前一段
            }
            // else dp[i] 保持 1（已初始化）
            ans = max(ans, dp[i]);
        }
        return ans;
    }
};

// ============================================================
// 解法3b: DP 空间优化 — 滚动变量
// 时间: O(n)  空间: O(1)
//
// 【思路】
// dp[i] 只依赖 dp[i-1]，所以用一个变量 prev 替代整个数组。
// 优化后和解法2（贪心）的代码完全等价！
// 这说明：贪心的一次遍历 = 空间优化后的线性 DP。
// ============================================================
class Solution3b {
public:
    int findLengthOfLCIS(vector<int>& nums) {
        int ans = 1;
        int prev = 1;  // prev 代替 dp[i-1]
        for (int i = 1; i < (int)nums.size(); i++) {
            prev = (nums[i] > nums[i - 1]) ? prev + 1 : 1;
            ans = max(ans, prev);
        }
        return ans;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间   | 空间  | 核心区别                         |
// |------------|--------|-------|----------------------------------|
// | 暴力枚举   | O(n²)  | O(1)  | 每个起点重新向右扫               |
// | 一次遍历   | O(n)   | O(1)  | 计数器 + 断点重置，一趟搞定      |
// | DP         | O(n)   | O(n)  | 显式建 dp 数组                   |
// | DP空间优化 | O(n)   | O(1)  | 滚动变量，和贪心等价             |
//
// 面试推荐解法2（一次遍历），代码最简洁。
// 如果面试官追问 DP，能说出解法3 + 3b 的推导过程。
//
// 【易错点】
// 1. cur 重置为 0 而不是 1
//    ✗ cur = 0;  → 断裂后当前元素被忽略，少计了一个
//    ✓ cur = 1;  → 当前元素本身是新段的第一个元素
//
// 2. 用 >= 判断递增
//    ✗ if (nums[i] >= nums[i-1])  → 相等也算递增了，但题目要求严格递增
//    ✓ if (nums[i] > nums[i-1])
//
// 3. ans 初始化为 0 且数组只有一个元素
//    ✗ int ans = 0; for (int i = 1; ...) → 循环不执行，返回 0
//    ✓ int ans = 1;  → 至少一个元素，答案至少为 1
//
// 4. nums.size() 为 unsigned，i < nums.size()-1 可能溢出
//    当 nums 为空时 size()-1 = UINT_MAX，循环会执行 4 billion 次
//    ✓ 转成 (int)nums.size() 或提前判空
//
// 【面试追问】
// Q1: 和 LeetCode 300 LIS 有什么区别？
//   → 300 不要求连续，需要 O(n²) DP 或 O(n log n) 贪心+二分。
//     本题要求连续，一次遍历 O(n) 即可。"连续"约束大大简化了问题。
//
// Q2: 如果改成"最长连续非递减序列"（允许相等）？
//   → 判断条件从 > 改成 >=，其他不变。
//
// Q3: 如果要返回最长段本身（不只是长度）？
//   → 额外记录最优段起始位置 start。当 cur > ans 时更新 start = i - cur + 1。
//     最后用 vector<int>(nums.begin()+start, nums.begin()+start+ans) 截取。
//
// Q4: 数组极大需要分布式处理？
//   → 分块计算，每块独立求最长连续递增段。相邻块边界处检查能否合并。
//
// 【相关题型】
// - 300 最长递增子序列: 去掉"连续"约束，从 O(n) 升级到 O(n log n)
// - 128 最长连续序列: "值连续"而非"位置连续"，需要哈希表 O(n)
// - 53 最大子数组和: 同样的"当前段/重置"框架(Kadane算法)，
//   把本题的"递增计数"换成"求和比较"
// - 673 最长递增子序列个数: 300的进阶，不仅要长度还要计数
// ============================================================
