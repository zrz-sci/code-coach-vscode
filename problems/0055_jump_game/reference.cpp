/*
 * LeetCode 55: 跳跃游戏 (Jump Game)
 *
 * 【题目本质】
 * 给定非负整数数组，nums[i] 表示从位置 i 最远能跳 nums[i] 步。
 * 问从位置 0 能否到达最后一个位置。
 * 本质：判断从 0 出发的"最远可达范围"能否覆盖终点。
 *
 * 【解法总览】
 * 解法1: 动态规划(自底向上) — O(n²) / O(n) — 最直觉的分解方式
 * 解法2: 贪心(正向，最远可达) — O(n) / O(1) — 面试首选 ⭐
 * 解法3: 贪心(反向，最近好位置) — O(n) / O(1) — 另一种贪心视角
 */

// ============================================================
// 解法1: 动态规划 — 从终点反向推导可达性
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 定义 dp[i] = 从位置 i 能否到达终点(位置 n-1)。
// 从右往左填表:
//   dp[n-1] = true (已在终点)
//   dp[i] = 存在 j ∈ [i+1, min(i+nums[i], n-1)] 使得 dp[j] = true
//
// 这是最自然的"分治"思维：大问题(从0能否到终点)拆成子问题(从i能否到终点)。
// 瓶颈：对每个 i 需要遍历 nums[i] 个位置检查 dp 值，最坏 O(n²)。
//
// dp 填表示例:
// nums:  [2, 3, 1, 1, 4]
// 索引:   0  1  2  3  4
// dp:     ?  ?  ?  ?  T     ← dp[4] = true
// i=3:   nums[3]=1, 检查 j=4: dp[4]=T → dp[3]=T
// i=2:   nums[2]=1, 检查 j=3: dp[3]=T → dp[2]=T
// i=1:   nums[1]=3, 检查 j=2: dp[2]=T → dp[1]=T  (break, 不用查j=3,4)
// i=0:   nums[0]=2, 检查 j=1: dp[1]=T → dp[0]=T
// 结果:   T  T  T  T  T → return dp[0] = true
// ============================================================
class Solution1 {
public:
    bool canJump(vector<int>& nums) {
        int n = nums.size();
        vector<bool> dp(n, false);
        dp[n - 1] = true;

        for (int i = n - 2; i >= 0; i--) {
            // 从位置 i 最远能跳到的位置，注意不能越界
            int farthest = min(i + nums[i], n - 1);
            for (int j = i + 1; j <= farthest; j++) {
                if (dp[j]) {
                    dp[i] = true;
                    break; // 找到一个可达位置就够了，提前退出内层循环
                }
            }
        }
        return dp[0];
    }
};

// ============================================================
// 解法2: 贪心(正向) — 维护最远可达位置 ⭐ 面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1的瓶颈：每个位置都要向右扫描检查可达性，O(n²)。
// 关键观察：如果位置 0~k 都可达，那最远可达位置 = max(i + nums[i]) for i in [0,k]。
// 可达性具有"连续性"——从 0 到 maxReach 之间不会出现断层。
//
// 所以只需要一个变量 maxReach:
//   - 从左到右遍历每个位置 i
//   - 如果 i > maxReach，说明存在断层，不可达
//   - 否则更新 maxReach = max(maxReach, i + nums[i])
//   - 如果 maxReach >= n-1，提前返回 true
//
// 可视化:
// nums = [2, 3, 1, 1, 4]
// 索引:   0  1  2  3  4
//
// i=0: i(0) <= maxReach(0) ✓  maxReach = max(0, 0+2) = 2
//      可达范围: [0 ====== 2]
//
// i=1: i(1) <= maxReach(2) ✓  maxReach = max(2, 1+3) = 4
//      可达范围: [0 ============== 4]  4 >= 4 → return true!
//
// nums = [3, 2, 1, 0, 4]
// 索引:   0  1  2  3  4
//
// i=0: maxReach = max(0, 3) = 3    [0 ========= 3]
// i=1: maxReach = max(3, 3) = 3    [0 ========= 3]  不变
// i=2: maxReach = max(3, 3) = 3    [0 ========= 3]  不变
// i=3: maxReach = max(3, 3) = 3    [0 ========= 3]  还是3
// i=4: i(4) > maxReach(3) → return false!  位置4不可达
// ============================================================
class Solution2 {
public:
    bool canJump(vector<int>& nums) {
        int maxReach = 0;
        for (int i = 0; i < (int)nums.size(); i++) {
            // 核心判断：如果当前位置超出了最远可达范围，存在断层
            if (i > maxReach) return false;

            // 用当前位置能到达的最远距离更新 maxReach
            maxReach = max(maxReach, i + nums[i]);

            // 提前终止：已经能覆盖终点，无需继续
            if (maxReach >= (int)nums.size() - 1) return true;
        }
        return true; // 遍历完所有位置都没有断层，说明可达
    }
};

// ============================================================
// 解法3: 贪心(反向) — 维护最近"好位置"
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 换个方向：从终点往起点看。
// 定义 "好位置"(good position)：能到达终点的位置。
// 显然终点自身是好位置。
//
// 从右往左扫描，维护 lastGood = 最靠左的好位置。
// 对于位置 i，如果 i + nums[i] >= lastGood，
// 说明从 i 可以跳到(或跳过) lastGood，那 i 也是好位置。
//
// 最终检查 lastGood 是否被推到了位置 0。
//
// 与解法2的关系:
// - 解法2: 正向扫描，维护"能到达的最远位置"(向右扩展)
// - 解法3: 反向扫描，维护"最近的好位置"(向左收缩)
// - 两者本质都是贪心，利用可达性的连续性/单调性
//
// 示例:
// nums = [2, 3, 1, 1, 4]
// 索引:   0  1  2  3  4
//                      ^ lastGood = 4
// i=3: 3+1=4 >= 4 → lastGood = 3
// i=2: 2+1=3 >= 3 → lastGood = 2
// i=1: 1+3=4 >= 2 → lastGood = 1
// i=0: 0+2=2 >= 1 → lastGood = 0
// lastGood == 0 → return true
// ============================================================
class Solution3 {
public:
    bool canJump(vector<int>& nums) {
        int lastGood = nums.size() - 1;
        for (int i = nums.size() - 2; i >= 0; i--) {
            // 如果从位置 i 能够跳到或超过 lastGood
            if (i + nums[i] >= lastGood) {
                lastGood = i; // i 成为新的最近好位置
            }
        }
        // 如果 lastGood 被一路推到了起点，说明起点可以到达终点
        return lastGood == 0;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 解法1 (DP)      | 解法2 (正向贪心)    | 解法3 (反向贪心)    |
// |-----------|----------------|-------------------|-------------------|
// | 时间       | O(n²)          | O(n)              | O(n)              |
// | 空间       | O(n)           | O(1)              | O(1)              |
// | 方向       | 右→左填表       | 左→右扫描          | 右→左扫描          |
// | 核心变量   | dp[i] 数组      | maxReach 一个变量   | lastGood 一个变量   |
// | 适用场景   | 理解DP思维      | 面试首选 ⭐        | 换个角度展示思维     |
//
// 解法1 → 解法3 的优化路径:
//   dp[i] 为 true 的位置形成一个连续后缀 [lastGood, n-1]
//   → 整个 dp 数组可以压缩为一个变量 lastGood
//   → 这就是解法3
//
// 解法2 和解法3 的关系:
//   解法2 从左往右问 "最远能到哪？"
//   解法3 从右往左问 "最近的安全点在哪？"
//   → 同一问题的正反两面
//
// 【易错点】
//
// 1. 解法2中漏掉 i > maxReach 的判断:
//    ✗ maxReach = max(maxReach, i + nums[i]); // 不管 i 是否可达都更新
//    ✓ if (i > maxReach) return false;        // 必须先检查可达性
//       maxReach = max(maxReach, i + nums[i]);
//    原因: 如果位置 i 不可达，i + nums[i] 是一个无效信息，不能用它更新 maxReach。
//
// 2. 解法1中内层循环上界越界:
//    ✗ for (int j = i+1; j <= i + nums[i]; j++) // j 可能超过 n-1
//    ✓ int farthest = min(i + nums[i], n - 1);
//       for (int j = i+1; j <= farthest; j++)
//
// 3. nums.size() 返回 size_t (无符号), 与 int 比较时:
//    ✗ if (maxReach >= nums.size() - 1)  // 当 nums.size()=0 时, size()-1 下溢为巨大值
//    ✓ if (maxReach >= (int)nums.size() - 1) // 显式转 int
//    本题约束 n >= 1 所以不会出事，但好习惯应该转换。
//
// 4. 数组只有一个元素时:
//    nums = [0], 应返回 true (已在终点)。
//    解法2: maxReach=0 >= n-1=0 → true ✓ (for循环条件 i<1 直接跳过)
//    解法3: lastGood=0 == 0 → true ✓
//
// 【面试追问】
//
// Q1: "暴力 DFS 有什么问题？"
//   → 指数级时间复杂度 O(2^n)。比如 nums=[5,4,3,2,1,0,0]，
//     从位置0可以跳1~5步，每个到达的位置又有多种选择，路径数爆炸。
//     加上记忆化能降到 O(n²)，进一步观察单调性才能 O(n)。
//
// Q2: "为什么贪心是对的？有没有反例？"
//   → 可达性具有连续性：如果能到达位置 k，那 0~k 所有位置都可达
//     (因为到达 k 的任何路径必经中间位置)。所以 maxReach 描述的是
//     一个连续区间 [0, maxReach]，不会出现"跳过某段后面又能回来"的情况。
//
// Q3: "如果要求最少跳跃次数呢？(LeetCode 45)"
//   → 在本题贪心基础上增加两个变量:
//     - curEnd: 当前这一"步"能到的最远位置
//     - steps: 跳跃次数
//     当 i 走到 curEnd 时，必须再跳一步，steps++，curEnd = maxReach。
//     核心改动：从"能不能到"变成"什么时候必须跳"。
//
// Q4: "如果要输出具体跳跃路径？"
//   → 贪心无法回溯路径。需要用 DP + parent 数组记录每个位置从哪里跳来，
//     最后从终点沿 parent 链反向回溯出路径。时间 O(n²)，空间 O(n)。
// ============================================================
