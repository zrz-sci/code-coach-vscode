// 775. Global and Local Inversions
// 难度: Medium
// 解法: 偏移量检查 / 前缀最大值 (两种 O(n) 解法)
// 时间复杂度: O(n)
// 空间复杂度: O(1)

// ============================================================
// 核心洞察:
// - 局部倒置(local) 一定是 全局倒置(global) 的子集
// - global == local 等价于 "不存在非局部的全局倒置"
// - 即不存在 j >= i+2 且 nums[i] > nums[j]
// ============================================================

// ============================================================
// 解法一: 偏移量检查 (最简洁, 面试首选)
// ============================================================
// 对于 [0,n-1] 的排列, global == local 当且仅当
// 每个元素最多偏离其"正确位置" 1 格: |nums[i] - i| <= 1

class Solution {
public:
    bool isIdealPermutation(vector<int>& nums) {
        int n = nums.size();
        for (int i = 0; i < n; i++) {
            // 如果任何元素偏离其标准位置超过1, 必有非局部倒置
            if (abs(nums[i] - i) > 1) {
                return false;
            }
        }
        return true;
    }
};

// ============================================================
// 解法二: 前缀最大值 (更通用, 不依赖排列性质)
// ============================================================
// 维护 nums[0..i-2] 的最大值
// 如果 prefixMax > nums[i], 存在距离>=2的倒置

class Solution2 {
public:
    bool isIdealPermutation(vector<int>& nums) {
        int n = nums.size();
        if (n <= 2) return true;

        // prefixMax 追踪 nums[0..i-2] 的最大值
        int prefixMax = nums[0];

        for (int i = 2; i < n; i++) {
            // 如果 nums[0..i-2] 中有元素大于 nums[i]
            // 说明存在距离 >= 2 的全局倒置 (非局部倒置)
            if (prefixMax > nums[i]) {
                return false;
            }
            // 更新前缀最大值: 加入 nums[i-1]
            // 注意是 i-1 不是 i, 因为下一轮比较的是 nums[0..i-1] vs nums[i+1]
            prefixMax = max(prefixMax, nums[i - 1]);
        }

        return true;
    }
};

// ============================================================
// 解法三: 后缀最小值 (等价变体)
// ============================================================
// 从右往左维护后缀最小值
// 如果 nums[i] > suffixMin (从 i+2 开始的最小值), 存在非局部倒置

class Solution3 {
public:
    bool isIdealPermutation(vector<int>& nums) {
        int n = nums.size();
        if (n <= 2) return true;

        // suffixMin 追踪 nums[i+2..n-1] 的最小值
        int suffixMin = nums[n - 1];

        // 从右往左遍历, 检查 nums[i] 与 suffixMin 的关系
        for (int i = n - 3; i >= 0; i--) {
            if (nums[i] > suffixMin) {
                return false;
            }
            // 更新后缀最小值: 加入 nums[i+1]
            // 下一轮需要的是 nums[(i-1)+2..n-1] = nums[i+1..n-1] 的最小值
            suffixMin = min(suffixMin, nums[i + 1]);
        }

        return true;
    }
};

// ============================================================
// 解法分析与对比:
//
// 解法一 (偏移量):
//   - 最简洁, 一行判断: abs(nums[i]-i) > 1
//   - 依赖于输入是 [0,n-1] 排列的性质
//   - 面试中优先展示, 再解释为什么成立
//
// 解法二 (前缀最大值):
//   - 更通用, 不需要排列性质
//   - 直接检测 "是否存在距离>=2的倒置"
//   - 逻辑稍复杂但更直观 (检查远距离倒置)
//
// 解法三 (后缀最小值):
//   - 解法二的镜像版本
//   - 从右往左扫描
//   - 与解法二等价, 选择哪个看个人偏好
//
// 三种解法复杂度完全相同: O(n) 时间, O(1) 空间
// ============================================================

// ============================================================
// 直觉验证:
// [0,1,2,3] -> 每个 |nums[i]-i|=0 <= 1, 返回 true  (恒等排列)
// [1,0,2,3] -> |1-0|=1, |0-1|=1, 其余=0, 返回 true  (相邻交换)
// [1,0,3,2] -> 所有 |nums[i]-i| <= 1, 返回 true
// [2,0,1,3] -> |nums[0]-0|=2 > 1, 返回 false (2在位置0, 偏移2)
// [1,2,0,3] -> |nums[2]-2|=2 > 1, 返回 false
// ============================================================
