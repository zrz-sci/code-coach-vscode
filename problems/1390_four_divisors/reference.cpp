/*
 * LeetCode 1390: 四因数 (Four Divisors)
 *
 * 【题目本质】
 * 对数组中每个数，判断它是否恰好有4个因数，如果是则累加其因数之和。
 * 核心在于高效枚举因数（利用因数成对出现的性质，只枚举到 √n）。
 *
 * 【解法总览】
 * 解法1: 暴力枚举 — O(N×V) / O(1) — 最直觉，会超时
 * 解法2: √n 优化  — O(N×√V) / O(1) — 面试首选
 * 解法3: 去重优化 — O(U×√V + N) / O(U) — 大数组场景进一步优化
 *
 * 其中 N=数组长度, V=max(nums[i]), U=不同值的个数
 */

// ============================================================
// 解法1: 暴力枚举 — 对每个数从 1 到 n 逐个试除
// 时间: O(N × V), V = max(nums[i]) = 10^5
// 空间: O(1)
//
// 【思路】
// 最直觉的做法：对每个数 n，遍历 1 到 n 检查所有因数。
// 如果因数恰好 4 个，累加因数之和。
// 瓶颈：内层循环 O(V)，总共 O(10^4 × 10^5) = O(10^9)，超时。
// ============================================================
class Solution1 {
public:
    int sumFourDivisors(vector<int>& nums) {
        int ans = 0;
        for (int n : nums) {
            int cnt = 0, sum = 0;
            for (int d = 1; d <= n; d++) {
                if (n % d == 0) {
                    cnt++;
                    sum += d;
                }
            }
            if (cnt == 4) ans += sum;
        }
        return ans;
    }
};

// ============================================================
// 解法2: √n 优化枚举 — 因数成对出现，只枚举到 √n
// 时间: O(N × √V), √(10^5) ≈ 316
// 空间: O(1)
//
// 【思路】
// 解法1的瓶颈：对每个数枚举到 n 太慢。
// 关键观察：若 d 是 n 的因数，则 n/d 也是。因数总是成对出现。
// 所以只需枚举 d 从 1 到 √n：
//   - 找到因数 d 时，同时获得配对因数 n/d
//   - 特殊情况：d == n/d（完全平方）时只算一次
//   - 提前终止：cnt > 4 就不可能恰好为4了
//
// 枚举示例 (n = 21, √21 ≈ 4):
//   d=1: 21%1==0 → 因数 1 和 21   cnt=2, sum=22
//   d=2: 21%2!=0 → 跳过
//   d=3: 21%3==0 → 因数 3 和 7    cnt=4, sum=32
//   d=4: 21%4!=0 → 跳过
//   结束: cnt==4 → ans += 32
//
// 枚举示例 (n = 4, √4 = 2):
//   d=1: 4%1==0 → 因数 1 和 4     cnt=2, sum=5
//   d=2: 4%2==0, 但 2*2==4 → 只加一个因数 2  cnt=3, sum=7
//   结束: cnt==3 ≠ 4 → 不累加
// ============================================================
class Solution2 {
public:
    int sumFourDivisors(vector<int>& nums) {
        int ans = 0;
        for (int n : nums) {
            int cnt = 0, sum = 0;
            for (int d = 1; (long long)d * d <= n; d++) {
                if (n % d == 0) {
                    // d 是因数，累加
                    cnt++;
                    sum += d;
                    // 配对因数 n/d（完全平方时 d == n/d，不重复计）
                    if (d != n / d) {
                        cnt++;
                        sum += n / d;
                    }
                }
                // 因数已超过4个，不可能满足条件，提前退出
                if (cnt > 4) break;
            }
            if (cnt == 4) ans += sum;
        }
        return ans;
    }
};

// ============================================================
// 解法3: 去重优化 — 先统计值的频次，每个值只算一次因数
// 时间: O(U × √V + N), U = 不同值的个数 ≤ min(N, V)
// 空间: O(U) 用于哈希表
//
// 【思路】
// 如果数组中有大量重复值（如 nums = [21, 21, 21, ..., 21]），
// 解法2会对同一个值重复计算因数。
// 优化：先用哈希表统计每个值的出现频次，
// 对每个不同的值只做一次因数判断，然后乘以频次。
//
// 当 N 很大但值域 V 较小时，这个优化非常显著。
// ============================================================
class Solution3 {
public:
    int sumFourDivisors(vector<int>& nums) {
        // 统计每个值的出现次数
        unordered_map<int, int> freq;
        for (int n : nums) freq[n]++;

        int ans = 0;
        for (auto& [n, count] : freq) {
            int cnt = 0, sum = 0;
            for (int d = 1; (long long)d * d <= n; d++) {
                if (n % d == 0) {
                    cnt++;
                    sum += d;
                    if (d != n / d) {
                        cnt++;
                        sum += n / d;
                    }
                }
                if (cnt > 4) break;
            }
            // 每个满足条件的值，乘以它在数组中出现的次数
            if (cnt == 4) ans += sum * count;
        }
        return ans;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间       | 空间  | 适用场景                |
// |------|-----------|-------|------------------------|
// | 解法1 | O(N×V)    | O(1)  | 理解题意，不能通过       |
// | 解法2 | O(N×√V)   | O(1)  | 面试首选，简洁高效       |
// | 解法3 | O(U×√V+N) | O(U)  | 大数组且有大量重复值时    |
//
// 面试写解法2即可。解法3在追问"数组非常大怎么办"时展示。
//
// 【数论补充】
// 恰好有 4 个因数的正整数只有两种形式:
//   1) p³ (质数的立方): 因数 = {1, p, p², p³}
//      例: 8 = 2³, 因数之和 = 1+2+4+8 = 15
//   2) p × q (两个不同质数之积): 因数 = {1, p, q, pq}
//      例: 21 = 3×7, 因数之和 = 1+3+7+21 = 32
//
// 【易错点】
// 1. 完全平方数 d == n/d 时只能计一个因数:
//    ✗ 无条件 cnt += 2, sum += d + n/d
//    ✓ if (d != n/d) { cnt++; sum += n/d; }
//    反例: n=4, d=2, 如果不判断会多算一个因数变成 cnt=4（错误）
//
// 2. 循环条件用乘法避免浮点:
//    ✗ d <= sqrt(n) — sqrt 返回 double，存在精度问题
//    ✓ (long long)d * d <= n — 整数运算，精确无误
//
// 3. 提前终止用 > 4 不是 >= 4:
//    ✗ if (cnt >= 4) break; — 可能恰好 cnt==4 但后面还有因数
//    ✓ if (cnt > 4) break;  — cnt 已经超过 4，不可能恰好为 4
//    注意: cnt==4 时循环自然会结束（因为之后 d*d > n），
//    但 > 4 的提前退出能跳过因数很多的合数
//
// 【面试追问】
// Q1(基础): 暴力法为什么超时? 瓶颈在哪?
//   → 对每个数枚举 1~n 找因数, O(N×V)=10^9, 内层循环太长
//
// Q2(优化): 怎么利用因数的数学性质优化?
//   → 因数成对出现, 只枚举到√n, 每找到d同时得到n/d
//   → 完全平方数 d==n/d 特判, 提前终止 cnt>4
//
// Q3(数论): 什么样的数恰好有4个因数?
//   → 因数个数公式 (a1+1)(a2+1)...=4, 两种: p³ 或 p×q
//
// Q4(大规模): 如果数组有10^8个元素但值域不变, 怎么优化?
//   → 去重: 哈希表统计频次, 每个不同值只算一次因数, 再乘频次
//   → 最多 10^5 个不同值, 每个 O(√V), 总计 O(10^5 × 316) ≈ 3×10^7
// ============================================================
