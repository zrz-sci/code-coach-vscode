/*
 * LeetCode 313: 超级丑数 (Super Ugly Number)
 *
 * 【题目本质】
 * 超级丑数: 质因子都在给定数组 primes 中的正整数。
 * 给定 n 和 primes, 求第 n 个超级丑数。
 * 本题是 264 (Ugly Number II, primes=[2,3,5]) 的通用化版本。
 *
 * 【核心思路】
 * 多指针 DP = 合并 k 个有序链表:
 * 每个质数 p 生成有序序列 p*ugly[0], p*ugly[1], p*ugly[2], ...
 * 用 k 个指针追踪各序列当前位置, 每轮取最小候选值。
 *
 * 【解法总览】
 * 解法1: 多指针 DP      — O(n*k) / O(n+k)     — 面试首选 ⭐
 * 解法2: 最小堆         — O(n*log k) / O(n+k)  — k 大时更优
 * 解法3: set 简洁版     — O(n*k*log(nk)) / O(nk) — 理解等价性
 */

/*
 * 多指针过程可视化: n=12, primes=[2,7,13,19]
 *
 * 初始: dp=[1], idx=[0,0,0,0]
 *
 *  步骤  2*dp[idx0]  7*dp[idx1]  13*dp[idx2]  19*dp[idx3]  min  谁推进
 *  ─────────────────────────────────────────────────────────────────
 *  1     2*1=2       7*1=7       13*1=13      19*1=19      2    idx0→1
 *  2     2*2=4       7*1=7       13*1=13      19*1=19      4    idx0→2
 *  3     2*4=8       7*1=7       13*1=13      19*1=19      7    idx1→1
 *  4     2*4=8       7*2=14      13*1=13      19*1=19      8    idx0→3
 *  5     2*7=14      7*2=14      13*1=13      19*1=19      13   idx2→1
 *  6     2*7=14      7*2=14      13*2=26      19*1=19      14   idx0→4,idx1→2  ← 去重!
 *  7     2*8=16      7*4=28      13*2=26      19*1=19      16   idx0→5
 *  8     2*13=26     7*4=28      13*2=26      19*1=19      19   idx3→1
 *  9     2*13=26     7*4=28      13*2=26      19*2=38      26   idx0→6,idx2→2  ← 去重!
 *  10    2*14=28     7*4=28      13*4=52      19*2=38      28   idx0→7,idx1→3  ← 去重!
 *  11    2*16=32     7*7=49      13*4=52      19*2=38      32   idx0→8
 *
 *  dp = [1, 2, 4, 7, 8, 13, 14, 16, 19, 26, 28, 32]
 *  答案: dp[11] = 32
 *
 *  注意第6步: 2*7=14 和 7*2=14 相同, 两个指针都要推进!
 */

// ============================================================
// 解法1: 多指针 DP ⭐ 面试首选
// 时间: O(n * k)  空间: O(n + k)
// 其中 k = primes.size()
//
// 【思路】
// dp[i] = 第 (i+1) 个超级丑数, dp[0] = 1
// idx[j] = 质数 primes[j] 下一个要乘的丑数在 dp 中的下标
// 每轮:
//   1. 候选值 = primes[j] * dp[idx[j]], 取所有 j 中的最小值
//   2. dp[i] = 最小值
//   3. 所有产生最小值的 j, 其 idx[j]++ (去重)
//
// 【等价视角: 合并 k 个有序链表】
// 链表 j: primes[j]*dp[0], primes[j]*dp[1], primes[j]*dp[2], ...
// idx[j] 就是链表 j 的当前指针位置
// 每轮取 k 个链表当前值的最小 = 合并操作
// ============================================================
class Solution1 {
public:
    int nthSuperUglyNumber(int n, vector<int>& primes) {
        int k = primes.size();
        vector<int> idx(k, 0);  // 每个质数的指针, 初始都指向 dp[0]=1
        vector<long> dp(n);
        dp[0] = 1;

        for (int i = 1; i < n; i++) {
            // Step 1: 从 k 个候选值中取最小
            long minVal = LONG_MAX;
            for (int j = 0; j < k; j++) {
                long candidate = (long)primes[j] * dp[idx[j]];
                minVal = min(minVal, candidate);
            }

            dp[i] = minVal;

            // Step 2: 所有产生最小值的指针前进 (去重!)
            // 例如 2*7 = 7*2 = 14, 两个指针都要推进
            // 如果只推一个, 下轮另一个还会产生14 → 重复
            for (int j = 0; j < k; j++) {
                if ((long)primes[j] * dp[idx[j]] == minVal) {
                    idx[j]++;
                }
            }
        }

        return (int)dp[n - 1];
    }
};

// ============================================================
// 解法2: 最小堆
// 时间: O(n * log k)  空间: O(n + k)
//
// 【思路】
// 多指针法每轮线性扫描 k 个候选值取最小 → O(k)。
// 用最小堆维护 k 个候选值, 每轮 O(log k) 弹出最小。
// 当 k 很大时 (>>100) 比多指针法更优。
//
// 堆中元素: {候选值, 质数下标 j, 丑数指针下标 idx}
// 弹出最小后, 将该质数的下一个候选值入堆。
// 去重: 如果堆顶值等于刚弹出的值, 继续弹出并推进。
// ============================================================
class Solution2 {
public:
    int nthSuperUglyNumber(int n, vector<int>& primes) {
        int k = primes.size();
        vector<long> dp(n);
        dp[0] = 1;

        // 最小堆: {候选值, 质数下标, 丑数指针下标}
        using T = tuple<long, int, int>;
        priority_queue<T, vector<T>, greater<T>> pq;

        // 初始: 每个质数的第一个候选值 = primes[j] * dp[0]
        for (int j = 0; j < k; j++) {
            pq.push({(long)primes[j], j, 0});
        }

        for (int i = 1; i < n; i++) {
            // 弹出最小候选值
            auto [val, j, idx] = pq.top();
            pq.pop();
            dp[i] = val;

            // 推入该质数的下一个候选值
            pq.push({(long)primes[j] * dp[idx + 1], j, idx + 1});

            // 去重: 堆顶如果等于当前值, 继续弹出并推进
            while (!pq.empty() && get<0>(pq.top()) == val) {
                auto [v2, j2, idx2] = pq.top();
                pq.pop();
                pq.push({(long)primes[j2] * dp[idx2 + 1], j2, idx2 + 1});
            }
        }

        return (int)dp[n - 1];
    }
};

// ============================================================
// 解法3: set 简洁版 — 理解等价性
// 时间: O(n * k * log(nk))  空间: O(n * k) 最差
//
// 【思路】
// 用 set 存所有候选丑数, 每次取最小, 然后将其乘以所有质数入 set。
// set 自动排序 + 去重, 但候选集可能膨胀到 O(n*k), 空间不如多指针。
//
// 优点: 代码最简洁, 容易理解
// 缺点: 空间大, 常数大, 不适合 n 和 k 都大的情况
// ============================================================
class Solution3 {
public:
    int nthSuperUglyNumber(int n, vector<int>& primes) {
        set<long> candidates;
        candidates.insert(1);
        long cur = 1;

        for (int i = 0; i < n; i++) {
            // 取最小候选值
            cur = *candidates.begin();
            candidates.erase(candidates.begin());

            // 将 cur * 每个质数 加入候选集
            for (int p : primes) {
                candidates.insert(cur * (long)p);
            }
        }

        return (int)cur;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 每轮取最小 | 总时间 | 空间 | k小推荐 | k大推荐 |
// |------|-----------|--------|------|--------|--------|
// | 1.多指针 ⭐ | O(k) | O(nk) | O(n+k) | 首选 | 尚可 |
// | 2.最小堆 | O(log k) | O(n log k) | O(n+k) | 常数大 | 首选 |
// | 3.set | O(log size) | O(nk log nk) | O(nk) | 不推荐 | 不推荐 |
//
// 本题 k <= 100, n <= 10^5, 多指针法完全够用。
//
// 【和 264 题 (Ugly Number II) 的关系】
// 264 题: primes = [2, 3, 5], k=3 固定
//   int p2=0, p3=0, p5=0;
//   dp[i] = min(2*dp[p2], 3*dp[p3], 5*dp[p5]);
//   if (dp[i] == 2*dp[p2]) p2++;
//   if (dp[i] == 3*dp[p3]) p3++;  // 注意: 用 if 不是 else if!
//   if (dp[i] == 5*dp[p5]) p5++;
//
// 本题: 把 3 个变量推广成 k 个数组元素, 逻辑完全一样。
//
// 【易错点】
// 1. 不去重:
//    ✗ 只推进产生最小值的第一个指针 → 14 出现两次 (2*7 和 7*2)
//    ✓ 所有产生最小值的指针都推进
//    264 题中也是同理: 用多个独立的 if (不是 else if) 来去重。
//
// 2. int 溢出:
//    ✗ primes[j] * dp[idx[j]]  // 两个 int 相乘可能溢出
//    ✓ (long)primes[j] * dp[idx[j]]  // 先转 long
//    或者 dp 数组直接用 vector<long>。
//
// 3. dp[0] 设错:
//    ✗ dp[0] = primes[0]  // 错! 第一个丑数是 1 不是最小质数
//    ✓ dp[0] = 1          // 1 是所有丑数序列的起点
//
// 4. 指针忘记初始化:
//    所有 idx[j] 初始为 0 (指向 dp[0]=1)。
//    未初始化 → 未定义行为。
//
// 【面试追问】
// Q1: 和 264 的关系?
//    → 264 是 primes=[2,3,5] 的特例, 3 指针; 本题推广到 k 指针。
//
// Q2: k 很大时怎么优化?
//    → 用最小堆, 每轮 O(log k) 取最小, 替代 O(k) 线性扫描。
//
// Q3: 为什么等价于合并 k 个有序链表?
//    → 每个质数 p 生成序列 p*ugly[0], p*ugly[1], ...
//      k 个递增序列合并 = 合并 k 个有序链表。
//
// Q4: dp 能空间优化吗?
//    → 不能。idx[j] 可能指向 dp 中很早的位置, 必须保留全部历史值。
//
// Q5: 去重的原理?
//    → 当 primes[a]*dp[idx[a]] == primes[b]*dp[idx[b]] 时,
//      两个序列同时产生了同一个丑数。两个指针都推进 = 两个序列都跳过这个值。
// ============================================================
