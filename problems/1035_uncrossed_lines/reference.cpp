/*
 * LeetCode 1035: 不相交的线 (Uncrossed Lines)
 *
 * 【题目本质】
 * 两个数组间画不交叉的连线 = 求两个数组的最长公共子序列(LCS)。
 * "不交叉"意味着选出的匹配对下标在两个数组中都递增 → 公共子序列的定义。
 * 和 LeetCode 1143 (Longest Common Subsequence) 代码完全一样。
 *
 * 【解法总览】
 * 解法1: 暴力递归          — O(2^(m+n)) / O(m+n)  — 理解递归结构
 * 解法2: 记忆化搜索        — O(mn) / O(mn)        — 消除重叠子问题
 * 解法3: 二维 DP (经典LCS) — O(mn) / O(mn)        — 面试首选 ⭐
 * 解法4: 一维 DP (空间优化) — O(mn) / O(n)         — 追问加分项
 */

// ============================================================
// 解法1: 暴力递归 — 穷举所有匹配可能
// 时间: O(2^(m+n))  空间: O(m+n) 递归栈
//
// 【思路】
// 最朴素的想法：从两个数组开头出发，
// - 如果当前元素相同，连线，两边同时前进
// - 如果不同，尝试跳过 nums1 当前元素 或 跳过 nums2 当前元素
// 取最大值。
//
// 为什么相同时直接连线不会亏？
// 反证：假设跳过这条线能得到更优解 k，那把这条线加上得 k+1，
// 且不会和之前的线交叉（因为下标更大），矛盾。
// ============================================================
class Solution1 {
public:
    int maxUncrossedLines(vector<int>& nums1, vector<int>& nums2) {
        return dfs(nums1, nums2, 0, 0);
    }

private:
    int dfs(vector<int>& a, vector<int>& b, int i, int j) {
        // 任一数组走完，无法再连线
        if (i == (int)a.size() || j == (int)b.size()) return 0;

        if (a[i] == b[j]) {
            // 值相同 → 连线，两边前进
            return 1 + dfs(a, b, i + 1, j + 1);
        }
        // 值不同 → 跳过 a[i] 或跳过 b[j]，取较大
        return max(dfs(a, b, i + 1, j), dfs(a, b, i, j + 1));
    }
};

// ============================================================
// 解法2: 记忆化搜索 — 在暴力递归基础上加 memo
// 时间: O(mn)  空间: O(mn)
//
// 【思路】
// 暴力递归中，(i, j) 相同的状态会被反复计算。
// 比如 dfs(2,3) 可能从 dfs(1,3) 和 dfs(2,2) 都进入，
// 这就是"重叠子问题"。加一个二维数组缓存即可。
//
// 重叠子问题示意（部分）:
//   dfs(0,0)
//   ├── dfs(1,0)
//   │   ├── dfs(2,0)
//   │   └── dfs(1,1)     ← 重复
//   └── dfs(0,1)
//       ├── dfs(1,1)     ← 重复
//       └── dfs(0,2)
// ============================================================
class Solution2 {
public:
    int maxUncrossedLines(vector<int>& nums1, vector<int>& nums2) {
        int m = nums1.size(), n = nums2.size();
        vector<vector<int>> memo(m, vector<int>(n, -1));
        return dfs(nums1, nums2, 0, 0, memo);
    }

private:
    int dfs(vector<int>& a, vector<int>& b, int i, int j,
            vector<vector<int>>& memo) {
        if (i == (int)a.size() || j == (int)b.size()) return 0;
        if (memo[i][j] != -1) return memo[i][j]; // 已计算过，直接返回

        if (a[i] == b[j]) {
            memo[i][j] = 1 + dfs(a, b, i + 1, j + 1, memo);
        } else {
            memo[i][j] = max(dfs(a, b, i + 1, j, memo),
                             dfs(a, b, i, j + 1, memo));
        }
        return memo[i][j];
    }
};

// ============================================================
// 解法3: 二维 DP — 经典 LCS 递推 ⭐ 面试首选
// 时间: O(mn)  空间: O(mn)
//
// 【思路】
// 把记忆化搜索翻译成自底向上的递推。
//
// 状态定义:
//   dp[i][j] = nums1 前 i 个元素 与 nums2 前 j 个元素 的最大连线数
//
// 转移方程:
//   nums1[i-1] == nums2[j-1] → dp[i][j] = dp[i-1][j-1] + 1
//   nums1[i-1] != nums2[j-1] → dp[i][j] = max(dp[i-1][j], dp[i][j-1])
//
// 初始化:
//   dp[0][*] = dp[*][0] = 0  (空数组，连线数为0)
//
// DP 填表过程 (nums1=[1,4,2], nums2=[1,2,4]):
//
//   dp[i][j]  ""  1   2   4
//        ""    0  0   0   0
//         1    0  1   1   1    ← nums1[0]=1 == nums2[0]=1, dp=0+1=1
//         4    0  1   1   2    ← nums1[1]=4 == nums2[2]=4, dp=1+1=2
//         2    0  1   2   2    ← nums1[2]=2 == nums2[1]=2, dp=1+1=2
//
// 填表方向: 从左到右, 从上到下
// 依赖关系: dp[i][j] 依赖 ↖(左上) ↑(上) ←(左)
//
//   ┌──────┬──────┐
//   │i-1,j-1│ i-1,j│
//   ├──────┼──────┤
//   │ i,j-1│ i,j  │ ← 当前要填的格子
//   └──────┴──────┘
// ============================================================
class Solution3 {
public:
    int maxUncrossedLines(vector<int>& nums1, vector<int>& nums2) {
        int m = nums1.size(), n = nums2.size();
        // dp[i][j]: nums1前i个 与 nums2前j个 的最大连线数
        vector<vector<int>> dp(m + 1, vector<int>(n + 1, 0));

        for (int i = 1; i <= m; i++) {
            for (int j = 1; j <= n; j++) {
                if (nums1[i - 1] == nums2[j - 1]) {
                    // 值相同 → 连线！在去掉这两个元素的 LCS 基础上 +1
                    dp[i][j] = dp[i - 1][j - 1] + 1;
                } else {
                    // 值不同 → 跳过 nums1[i-1] 或跳过 nums2[j-1]
                    dp[i][j] = max(dp[i - 1][j], dp[i][j - 1]);
                }
            }
        }
        return dp[m][n];
    }
};

// ============================================================
// 解法4: 一维 DP — 空间优化 (滚动数组)
// 时间: O(mn)  空间: O(n)
//
// 【思路】
// 解法3中 dp[i][j] 只依赖 dp[i-1][j-1]、dp[i-1][j]、dp[i][j-1]，
// 即只依赖"上一行"和"当前行左边"。所以可以用一维数组滚动。
//
// 关键难点: 压缩到一维后，dp[j] 更新前存的是 dp[i-1][j]（上一行），
// 更新后变成 dp[i][j]（当前行）。但 dp[i-1][j-1]（左上角）在
// 更新 dp[j-1] 时已经被覆盖了！
//
// 解决: 用 prev 变量在覆盖前保存旧值。
//
// 滚动过程示意 (nums1=[1,4,2], nums2=[1,2,4]):
//
// 初始:   dp = [0, 0, 0, 0]    (对应 i=0 行)
//
// i=1 (nums1[0]=1):
//   j=1: nums1[0]=1 == nums2[0]=1 → dp[1] = prev(0) + 1 = 1
//   j=2: 1 != 2 → dp[2] = max(dp[2]=0, dp[1]=1) = 1
//   j=3: 1 != 4 → dp[3] = max(dp[3]=0, dp[2]=1) = 1
//   dp = [0, 1, 1, 1]
//
// i=2 (nums1[1]=4):
//   j=1: 4 != 1 → dp[1] = max(dp[1]=1, dp[0]=0) = 1
//   j=2: 4 != 2 → dp[2] = max(dp[2]=1, dp[1]=1) = 1
//   j=3: 4 == 4 → dp[3] = prev(1) + 1 = 2
//   dp = [0, 1, 1, 2]
//
// i=3 (nums1[2]=2):
//   j=1: 2 != 1 → dp[1] = max(1, 0) = 1
//   j=2: 2 == 2 → dp[2] = prev(1) + 1 = 2
//   j=3: 2 != 4 → dp[3] = max(2, 2) = 2
//   dp = [0, 1, 2, 2]  → 答案 dp[3] = 2 ✓
// ============================================================
class Solution4 {
public:
    int maxUncrossedLines(vector<int>& nums1, vector<int>& nums2) {
        int m = nums1.size(), n = nums2.size();
        vector<int> dp(n + 1, 0);

        for (int i = 1; i <= m; i++) {
            int prev = 0; // prev 保存 dp[i-1][j-1]，即"左上角"
            for (int j = 1; j <= n; j++) {
                int temp = dp[j]; // dp[j] 此刻还是上一行的值 dp[i-1][j]
                if (nums1[i - 1] == nums2[j - 1]) {
                    // 相等: 用左上角 prev (= dp[i-1][j-1]) + 1
                    dp[j] = prev + 1;
                } else {
                    // 不相等: max(上一行同列 dp[j], 当前行左边 dp[j-1])
                    dp[j] = max(dp[j], dp[j - 1]);
                }
                // temp 是本轮 dp[i-1][j]，下一轮 j+1 时就变成 dp[i-1][j-1]
                prev = temp;
            }
        }
        return dp[n];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 时间       | 空间    | 适用场景              |
// |-------------|-----------|---------|----------------------|
// | 暴力递归     | O(2^(m+n))| O(m+n) | 仅用于理解问题结构      |
// | 记忆化搜索   | O(mn)     | O(mn)  | 自顶向下思考时自然写出   |
// | 二维DP ⭐   | O(mn)     | O(mn)  | 面试默认写法，清晰不易错 |
// | 一维DP      | O(mn)     | O(n)   | 面试追问空间优化时写出   |
//
// 推荐: 面试直接写解法3(二维DP)，追问空间再优化到解法4。
//
// 【和系列题的关系】
// - LeetCode 1143 (Longest Common Subsequence): 完全相同的代码，
//   本题只是把字符串换成了整数数组。
// - LeetCode 718 (Maximum Length of Repeated Subarray): 要求连续子数组，
//   区别在于不匹配时 dp[i][j]=0 而不是取 max。
//   代码差异: 718 的 else 分支是 dp[i][j]=0，本题是 max(dp[i-1][j], dp[i][j-1])
//
// 【易错点】
// 1. 下标偏移:
//    ✗ dp[i][j] 对应 nums1[i], nums2[j] → i=m 或 j=n 时越界
//    ✓ dp[i][j] 对应 nums1[i-1], nums2[j-1]，dp 大小 (m+1)×(n+1)
//
// 2. 空间优化时左上角被覆盖:
//    ✗ dp[j] = dp[j-1] + 1 — dp[j-1] 已经是当前行更新后的值
//    ✓ 用 prev 变量保存覆盖前的 dp[j]，下一轮用 prev 作为左上角
//
// 3. 相等时多余的 max:
//    ✗ dp[i][j] = max({dp[i-1][j-1]+1, dp[i-1][j], dp[i][j-1]})
//    ✓ dp[i][j] = dp[i-1][j-1] + 1 就够了
//    原因: dp[i-1][j] >= dp[i-1][j-1] 且 dp[i][j-1] >= dp[i-1][j-1]，
//    但 dp[i-1][j-1]+1 一定 >= 两者（可以数学证明），所以不需要取 max。
//
// 【面试追问】
// Q1: 为什么这道题等价于 LCS？
// → "不交叉"要求选出的匹配对下标在两数组中都递增，
//   即 i1<i2 且 j1<j2，这恰好是公共子序列的定义。
//
// Q2: 空间能否进一步优化？
// → 可以用 O(min(m,n))：先比较两数组长度，让较短的做 dp 的维度。
//   代码只需在开头加: if (m < n) swap(nums1, nums2), swap(m, n);
//
// Q3: 如果要输出具体连了哪些线怎么办？
// → 保留二维 dp 表，从 dp[m][n] 回溯:
//   - 若 nums1[i-1]==nums2[j-1]，记录 (i-1, j-1)，走到 (i-1, j-1)
//   - 否则走 dp 较大的方向 (i-1,j) 或 (i,j-1)
//
// Q4: 数组很长(n=10^5)时 O(n²) 太慢，有更优方法吗？
// → 可以将 LCS 转化为 LIS:
//   1. 建立 nums2 中每个值到所有下标的映射
//   2. 遍历 nums1，将每个元素替换为它在 nums2 中的下标（倒序排列）
//   3. 对替换后的序列求 LIS，用 patience sorting O(n log n)
//   适用条件: 匹配对数量远小于 n² 时效果好
// ============================================================
