/*
 * LeetCode 88: 合并两个有序数组 (Merge Sorted Array)
 *
 * 【题目本质】
 * 归并排序中的 merge 步骤：把两个有序数组合并成一个有序数组，
 * 且必须原地合并到 nums1 中（nums1 尾部预留了足够空间）。
 *
 * 【解法总览】
 * 解法1: 合并后排序        — O((m+n)log(m+n)) / O(1) — 最直觉，没利用有序性
 * 解法2: 正向双指针+额外数组 — O(m+n) / O(m)         — 经典归并，需要额外空间
 * 解法3: 逆向双指针(最优)   — O(m+n) / O(1)          — 利用尾部空间，从后往前填充
 */

// ============================================================
// 解法1: 合并后排序
// 时间: O((m+n) log(m+n))  空间: O(1)（忽略排序内部空间）
//
// 【思路】
// 最直觉的做法：先把 nums2 全部拷贝到 nums1 后半段，
// 然后对整个 nums1 排序。
// 简单粗暴，但完全没利用"两个数组各自已排序"的信息。
// 作为面试起点，展示理解题意即可。
// ============================================================
class Solution1 {
public:
    void merge(vector<int>& nums1, int m, vector<int>& nums2, int n) {
        for (int i = 0; i < n; i++) {
            nums1[m + i] = nums2[i];
        }
        sort(nums1.begin(), nums1.end());
    }
};

// ============================================================
// 解法2: 正向双指针 + 额外数组
// 时间: O(m+n)  空间: O(m)
//
// 【思路】
// 这就是归并排序的标准 merge 操作：
// 两个指针分别指向两个数组头部，每次取较小的放入结果。
//
// 但如果直接往 nums1 里从前往后写，会覆盖 nums1 还没比较的元素。
// 解决方案：先把 nums1 的前 m 个元素拷贝一份。
//
// 过程示意:
// nums1_copy = [1, 2, 3]
// nums2      = [2, 5, 6]
//               i          j          k → nums1
// Step1: 1 < 2  → nums1[0]=1, i++     → [1, _, _, _, _, _]
// Step2: 2 ≤ 2  → nums1[1]=2, i++     → [1, 2, _, _, _, _]
// Step3: 3 > 2  → nums1[2]=2, j++     → [1, 2, 2, _, _, _]
// Step4: 3 < 5  → nums1[3]=3, i++     → [1, 2, 2, 3, _, _]
// Step5: i 耗尽 → nums1[4]=5, j++     → [1, 2, 2, 3, 5, _]
// Step6:        → nums1[5]=6, j++     → [1, 2, 2, 3, 5, 6] ✓
// ============================================================
class Solution2 {
public:
    void merge(vector<int>& nums1, int m, vector<int>& nums2, int n) {
        // 拷贝 nums1 有效部分，避免从前往后写时被覆盖
        vector<int> nums1_copy(nums1.begin(), nums1.begin() + m);

        int i = 0, j = 0, k = 0;
        while (i < m && j < n) {
            // 取较小者放入 nums1[k]
            if (nums1_copy[i] <= nums2[j]) {
                nums1[k++] = nums1_copy[i++];
            } else {
                nums1[k++] = nums2[j++];
            }
        }
        // 处理剩余：nums1_copy 或 nums2 可能还有未放入的元素
        while (i < m) nums1[k++] = nums1_copy[i++];
        while (j < n) nums1[k++] = nums2[j++];
    }
};

// ============================================================
// 解法3: 逆向双指针 — 从后往前填充 ⭐ 面试首选
// 时间: O(m+n)  空间: O(1)
//
// 【思路】
// 解法2的瓶颈是需要 O(m) 额外空间，原因是"从前往后写会覆盖"。
// 
// 关键观察：nums1 的**尾部** n 个位置是空的（0 占位）！
// 如果从后往前填充，每次取两个数组中**较大的**放到 nums1 末尾，
// 写指针永远不会追上 nums1 的读指针，因此不需要额外空间。
//
// 【为什么不会覆盖？】
// 设 k 为写位置，i 为 nums1 读位置。
// 初始: k = m+n-1, i = m-1, 差值 k-i = n（nums2 的元素个数）
// 每次循环:
//   - 若取 nums1[i]: k--, i-- → 差值不变（= 剩余的 nums2 元素数）
//   - 若取 nums2[j]: k--, j-- → 差值减 1 但仍 ≥ 0
// 所以 k ≥ i 始终成立，永远不会覆盖。
//
// 过程演示 (nums1=[1,2,3,0,0,0] m=3, nums2=[2,5,6] n=3):
//
// i=2 j=2 k=5: nums1[2]=3 < nums2[2]=6  → nums1[5]=6, j--
//   [1, 2, 3, 0, 0, 6]
//
// i=2 j=1 k=4: nums1[2]=3 < nums2[1]=5  → nums1[4]=5, j--
//   [1, 2, 3, 0, 5, 6]
//
// i=2 j=0 k=3: nums1[2]=3 > nums2[0]=2  → nums1[3]=3, i--
//   [1, 2, 3, 3, 5, 6]
//         ↑     ↑
//         i     k  (k > i, 安全!)
//
// i=1 j=0 k=2: nums1[1]=2 >= nums2[0]=2 → nums1[2]=2, j--
//   [1, 2, 2, 3, 5, 6]
//
// j<0 退出。nums1 剩余的 [1,2] 已在正确位置 ✓
// ============================================================
class Solution3 {
public:
    void merge(vector<int>& nums1, int m, vector<int>& nums2, int n) {
        int i = m - 1;      // nums1 有效部分的尾指针
        int j = n - 1;      // nums2 的尾指针
        int k = m + n - 1;  // 写入位置，从 nums1 最末尾开始

        // 从后往前，每次取较大的放到位置 k
        while (i >= 0 && j >= 0) {
            if (nums1[i] > nums2[j]) {
                nums1[k--] = nums1[i--];
            } else {
                // 相等时取 nums2（保持稳定性：nums2 的相等元素排在 nums1 后面）
                nums1[k--] = nums2[j--];
            }
        }

        // 如果 nums2 还有剩余元素，拷贝到 nums1 前面
        // （nums1 剩余元素已经在正确位置，无需移动）
        while (j >= 0) {
            nums1[k--] = nums2[j--];
        }
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间             | 空间  | 利用有序性 | 适用场景          |
// |------|------------------|-------|-----------|-------------------|
// | 解法1 | O((m+n)log(m+n)) | O(1)  | ✗         | 快速实现，不求最优 |
// | 解法2 | O(m+n)           | O(m)  | ✓ 归并    | 允许额外空间时     |
// | 解法3 | O(m+n)           | O(1)  | ✓ 逆向归并 | ⭐ 面试最优解     |
//
// 解法1 → 解法2: 利用有序性，从排序升级为归并
// 解法2 → 解法3: 消除额外空间，关键洞察是"尾部有空位，从后往前填"
//
// ============================================================
// 【易错点】
//
// 1. 忘记处理 nums2 剩余元素:
//    ✗ 只写主循环 while(i>=0 && j>=0) 就结束
//    ✓ 需要额外 while(j>=0) nums1[k--]=nums2[j--]
//    场景: nums2=[1,2], nums1=[3,4,_,_], 主循环因 j<0 退出时
//          实际是 i<0 退出，nums2 还有元素没放
//
// 2. 误以为 nums1 剩余也需要拷贝:
//    ✗ 多写 while(i>=0) nums1[k--]=nums1[i--]
//    ✓ 不需要! nums1 的剩余元素本来就在 nums1 前部，位置正确
//    虽然多写不会出错（自己拷贝到自己），但说明理解不到位
//
// 3. m=0 时 i=-1 导致越界:
//    ✗ 主循环中先访问 nums1[i] 再判断 i>=0
//    ✓ while 条件 i>=0 && j>=0 已经保护了，i=-1 时不进入循环
//       然后 while(j>=0) 把 nums2 全部拷贝，逻辑自洽
//
// ============================================================
// 【面试追问】
//
// Q1: "暴力解时间复杂度是多少？瓶颈在哪？"
//     O((m+n)log(m+n))，瓶颈是排序。没利用已排序的性质。
//
// Q2: "经典归并为什么需要额外空间？能否消除？"
//     从前往后写会覆盖 nums1 未读元素。
//     消除方法：nums1 尾部有空位，从后往前写就不会覆盖。
//
// Q3: "能否严格证明逆向填充不会覆盖？"
//     差值 k-i = 剩余 nums2 元素个数 ≥ 0，所以写位置 k ≥ 读位置 i。
//
// Q4: "如果是 K 个有序数组合并呢？"
//     → LeetCode 23: 用最小堆，每次取 K 个数组头部最小的，O(N log K)。
//
// Q5: "如果数组极大，不能全放内存呢？"
//     → 外部排序 / K 路归并：每次从磁盘读一块到内存，用堆归并。
// ============================================================
