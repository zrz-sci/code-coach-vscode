/*
 * LeetCode 790: Domino and Tromino Tiling (多米诺和托米诺平铺)
 *
 * 【题目本质】
 * 用 2x1 domino 和 L 形 tromino 铺满 2xN 棋盘的方案数。
 * 核心是建立状态机模型，推导出简洁的三项递推公式。
 *
 * 【解法总览】
 * 解法1: 递推 DP (数组)     — O(n) / O(n)   — f[n] = 2*f[n-1] + f[n-3]
 * 解法2: 递推 DP (滚动变量)  — O(n) / O(1)   — 空间优化版 ⭐推荐
 * 解法3: 状态机 DP          — O(n) / O(1)   — 显式维护 f 和 g 两个状态
 */

// ============================================================
// 解法1: 递推 DP (数组) — f[n] = 2*f[n-1] + f[n-3]
// 时间: O(n)  空间: O(n)
//
// 【递推公式推导】
//
// 定义:
//   f[n] = 铺满 2 x n 棋盘的方案数
//   g[n] = 铺满 2 x n 但缺一个角的方案数
//
// 状态转移:
//   f[n] = f[n-1] + f[n-2] + 2*g[n-1]
//          ↑竖domino  ↑两个横domino  ↑tromino(上L+下L)
//
//   g[n] = g[n-1] + f[n-2]
//          ↑补一个横domino  ↑放一个tromino
//
// 消去 g[n]:
//   f[n] - f[n-1] = f[n-1] + f[n-3]
//   ⟹ f[n] = 2*f[n-1] + f[n-3]
//
// 基础值:
//   f[0] = 1  (空棋盘 = 1种方案，什么都不放)
//   f[1] = 1  (一个竖domino)
//   f[2] = 2  (两个竖domino 或 两个横domino)
//
// 验证:
//   f[3] = 2*2 + 1 = 5 ✓ (题目示例)
//   f[4] = 2*5 + 1 = 11
//   f[5] = 2*11 + 2 = 24
//
// n=3 的 5 种铺法:
//   1. |||  2. ==|  3. |==  4. L型+补  5. L型+补
//   三竖   两横一竖  一竖两横  tromino    tromino
// ============================================================
class Solution1 {
public:
    int numTilings(int n) {
        const int MOD = 1e9 + 7;
        if (n <= 2) return n;

        // f[i] = 铺满 2 x i 的方案数
        vector<long long> f(n + 1);
        f[0] = 1;
        f[1] = 1;
        f[2] = 2;

        for (int i = 3; i <= n; i++) {
            // 注意取模: 2*f[i-1] 可能接近 2e9，超出 int 范围
            // 用 long long 计算中间结果
            f[i] = (2 * f[i - 1] % MOD + f[i - 3]) % MOD;
        }

        return f[n];
    }
};

// ============================================================
// 解法2: 递推 DP (滚动变量) — 空间优化版 ⭐推荐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// f[n] 只依赖 f[n-1] 和 f[n-3]，间隔最多 3 项。
// 用 3 个变量 a, b, c 滚动存储 f[i-3], f[i-2], f[i-1]。
//
// 滚动过程:
//   初始: a=f[0]=1, b=f[1]=1, c=f[2]=2
//
//   i=3: cur = 2*c + a = 2*2+1 = 5
//        a=b=1, b=c=2, c=cur=5
//        → (a,b,c) = (1,2,5) = (f[1],f[2],f[3])
//
//   i=4: cur = 2*5 + 1 = 11
//        a=2, b=5, c=11
//        → (a,b,c) = (2,5,11) = (f[2],f[3],f[4])
//
//   i=5: cur = 2*11 + 2 = 24
//        a=5, b=11, c=24
//        → (a,b,c) = (5,11,24) = (f[3],f[4],f[5])
// ============================================================
class Solution2 {
public:
    int numTilings(int n) {
        const int MOD = 1e9 + 7;
        if (n <= 2) return n;

        long long a = 1, b = 1, c = 2;  // f[i-3], f[i-2], f[i-1]

        for (int i = 3; i <= n; i++) {
            long long cur = (2 * c % MOD + a) % MOD;
            a = b;      // f[i-3] ← f[i-2]
            b = c;      // f[i-2] ← f[i-1]
            c = cur;    // f[i-1] ← f[i]
        }

        return (int)c;
    }
};

// ============================================================
// 解法3: 状态机 DP — 显式维护 f 和 g 两个状态
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 不做消元，直接维护两个状态:
//   f[i] = 铺满 2 x i 的方案数
//   g[i] = 铺满 2 x i 缺一角的方案数
//
// 转移:
//   f[i] = f[i-1] + f[i-2] + 2*g[i-1]
//   g[i] = f[i-2] + g[i-1]
//
// 这种写法更容易理解（不需要推导消元），
// 缺点是需要同时维护两个状态。
//
// 基础值: f[0]=1, f[1]=1, g[0]=0, g[1]=0
// (g[0]和g[1]没有实际意义，设为0使递推正确)
//
// 严格来说:
//   f[2] = f[1] + f[0] + 2*g[1] = 1 + 1 + 0 = 2 ✓
//   g[2] = f[0] + g[1] = 1 + 0 = 1
//   f[3] = f[2] + f[1] + 2*g[2] = 2 + 1 + 2 = 5 ✓
//   g[3] = f[1] + g[2] = 1 + 1 = 2
//   f[4] = f[3] + f[2] + 2*g[3] = 5 + 2 + 4 = 11 ✓
// ============================================================
class Solution3 {
public:
    int numTilings(int n) {
        const int MOD = 1e9 + 7;
        if (n <= 2) return n;

        // 使用滚动变量存储 f 和 g 的最近几个值
        long long f_prev2 = 1;  // f[i-2]
        long long f_prev1 = 1;  // f[i-1]
        long long g_prev1 = 0;  // g[i-1]

        for (int i = 2; i <= n; i++) {
            long long f_cur = (f_prev1 + f_prev2 + 2 * g_prev1 % MOD) % MOD;
            long long g_cur = (f_prev2 + g_prev1) % MOD;

            // 如果还需要更早的 f 值，要在覆盖前保存
            // f[i-2] for next iteration = current f[i-1]
            f_prev2 = f_prev1;
            f_prev1 = f_cur;
            g_prev1 = g_cur;
        }

        return (int)f_prev1;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法            | 时间    | 空间  | 代码复杂度 | 面试推荐 |
// |----------------|---------|-------|-----------|---------|
// | 递推数组        | O(n)   | O(n)  | 简单       | ✓       |
// | 滚动变量        | O(n)   | O(1)  | 简单       | ⭐⭐⭐  |
// | 状态机(f+g)    | O(n)   | O(1)  | 中等       | ✓ 更直观 |
// | 矩阵快速幂     | O(logn) | O(1)  | 复杂       | 加分项   |
//
// 面试策略:
//   1. 先画状态转移图，解释 f 和 g 两个状态
//   2. 消元得到 f[n] = 2*f[n-1] + f[n-3]
//   3. 写滚动变量版本（最简洁）
//   4. 面试官追问 O(logn) → 描述矩阵快速幂思路
//
// ============================================================
// 【易错点】
//
// 1. f[0] 必须是 1 不是 0:
//    ✗ f[0]=0 → f[3]=2*2+0=4 (错误)
//    ✓ f[0]=1 → f[3]=2*2+1=5 (正确)
//    空棋盘有 1 种铺法（什么都不放）
//
// 2. 取模溢出:
//    ✗ f[i] = 2*f[i-1] + f[i-3]  (int 乘法可能溢出)
//    ✓ f[i] = (2LL * f[i-1] % MOD + f[i-3]) % MOD
//    2 * 10^9 > INT_MAX (2.1 * 10^9)
//
// 3. 滚动变量更新顺序:
//    ✗ 先更新 a 再计算 cur (覆盖了旧值)
//    ✓ 先计算 cur，再按顺序滚动 a←b, b←c, c←cur
//
// 4. 递推公式记错:
//    ✗ f[n] = 2*f[n-1] + f[n-2]  (多了，这不对)
//    ✓ f[n] = 2*f[n-1] + f[n-3]  (注意是 n-3 不是 n-2)
// ============================================================

// ============================================================
// 【总结】
//
// ——— 解法对比 ———
// | 解法            | 时间    | 空间  | 适用场景                |
// |----------------|---------|------|------------------------|
// | 递推数组        | O(n)   | O(n)  | 入门理解，可打表验证     |
// | 滚动变量        | O(n)   | O(1)  | 面试首选 ⭐             |
// | 状态机(f+g)    | O(n)   | O(1)  | 推导更直观，不需消元     |
// | 矩阵快速幂     | O(logn) | O(1)  | 面试加分项              |
//
// 核心难点在于建模：把棋盘铺砖抽象成 f（满列）和 g（缺角列）
// 两个状态，再推导递推关系。消元后得到简洁公式 f[n]=2f[n-1]+f[n-3]。
//
// ——— 易错点 ———
// 1. f[0]=1 不是 0: 空棋盘有 1 种铺法（什么都不放）
// 2. 取模溢出: 2*f[i-1] 可达 2e9 超 int，必须用 long long
// 3. 公式是 f[n-3] 不是 f[n-2]: 背错公式直接全错
// 4. 滚动变量更新顺序: 先算 cur，再按 a←b, b←c, c←cur 滚动
//
// ——— 面试追问 ———
// Q1: 能否做到 O(log n)？
//     → 矩阵快速幂。把递推 [f[n], f[n-1], f[n-2]] 写成矩阵乘法:
//       | f[n]   |   | 2 0 1 |   | f[n-1] |
//       | f[n-1] | = | 1 0 0 | * | f[n-2] |
//       | f[n-2] |   | 0 1 0 |   | f[n-3] |
//       对转移矩阵做快速幂即可。
//
// Q2: 如果棋盘是 3xN 呢？
//     → 状态更复杂。3xN 只有 domino（无 tromino）时，N 为奇数无解，
//       N 为偶数有经典递推 f[n] = 4*f[n-2] - f[n-4]。
//       加 tromino 后需要 bitmask DP，状态数 = 2^3 = 8。
//
// Q3: 如果要输出所有铺法（而不只是计数）？
//     → 回溯法。逐列填充，每列维护当前状态（满/缺角），
//       尝试所有合法的砖块放置方式。n 较大时方案数指数级增长，
//       只适合 n 较小的情况。
// ============================================================
