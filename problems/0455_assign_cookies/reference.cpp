/*
 * LeetCode 455: 分发饼干 (Assign Cookies)
 *
 * 【题目本质】
 * 两个集合（孩子胃口 g、饼干尺寸 s）之间做最大数量的一对一匹配，
 * 匹配条件：s[j] >= g[i]。
 * 贪心策略：排序后，用尽量小的饼干去满足胃口最小的孩子。
 *
 * 【解法总览】
 * 解法1: 排序 + 正向贪心双指针 — O(n log n + m log m) / O(1) — 面试首选
 * 解法2: 排序 + 反向贪心双指针 — O(n log n + m log m) / O(1) — 换个方向
 *
 * 【贪心正确性证明 — 交换论证】
 * 假设最优方案中，大饼干 S 给了小胃口孩子 A(胃口 g_A)，
 * 小饼干 s 给了大胃口孩子 B(胃口 g_B)，其中 g_A <= g_B <= s <= S。
 * 交换：S 给 B，s 给 A。因为 s >= g_B >= g_A，所以 s >= g_A 成立，
 * 交换后两人依然满足，总数不变。
 * 因此"小饼干优先给小胃口"不劣于任何方案 → 贪心正确。
 */

// ============================================================
// 解法1: 排序 + 正向贪心双指针（从小到大）
// 时间: O(n log n + m log m)  空间: O(1)（忽略排序栈空间）
//
// 【思路】
// 直觉：一块小饼干如果能满足小胃口的孩子，就不要浪费给大胃口的。
// 排序后，从最小的孩子和最小的饼干开始配对：
//   - 饼干够大 → 匹配成功，双方前进
//   - 饼干太小 → 这块饼干对谁都没用（后面孩子胃口更大），丢弃
//
// 示例: g = [1,2,3], s = [1,1]
// 排序后: g = [1,2,3], s = [1,1]
//
//   i=0, j=0: s[0]=1 >= g[0]=1 ✓ → count=1, i=1, j=1
//   i=1, j=1: s[1]=1 <  g[1]=2 ✗ → j=2 (饼干太小，跳过)
//   j=2 越界 → 结束, 返回 count=1
// ============================================================
class Solution1 {
public:
    int findContentChildren(vector<int>& g, vector<int>& s) {
        // 排序是贪心的前提：让我们能从小到大有序匹配
        sort(g.begin(), g.end());
        sort(s.begin(), s.end());

        int i = 0; // 指向当前待满足的孩子（胃口从小到大）
        int j = 0; // 指向当前可用的饼干（尺寸从小到大）
        int count = 0;

        while (i < (int)g.size() && j < (int)s.size()) {
            if (s[j] >= g[i]) {
                // 当前饼干能满足当前孩子
                // 为什么选这块饼干？因为它是能满足这个孩子的最小饼干
                // 用更大的饼干给这个孩子是浪费（大饼干留给后面的大胃口）
                count++;
                i++; // 这个孩子满足了，看下一个
                j++; // 这块饼干用掉了，看下一块
            } else {
                // 当前饼干太小，连胃口最小的未满足孩子都喂不了
                // 后面的孩子胃口更大，这块饼干更没用 → 丢弃
                j++;
            }
        }
        // 任一数组扫完就结束：要么所有孩子都看过了，要么饼干用完了

        return count;
    }
};

// ============================================================
// 解法2: 排序 + 反向贪心双指针（从大到小）
// 时间: O(n log n + m log m)  空间: O(1)
//
// 【思路】
// 换个方向：从胃口最大的孩子开始，用最大的饼干尝试满足他。
//   - 最大的饼干能满足 → 匹配成功，双方后退
//   - 最大的饼干都不能满足 → 这个孩子谁也满足不了，放弃他
//
// 与解法1的对称关系：
//   解法1: 失败时跳过饼干（饼干太小没用）
//   解法2: 失败时跳过孩子（孩子太贪心没人能满足）
//
// 示例: g = [1,2,3], s = [1,1]
// 排序后: g = [1,2,3], s = [1,1]
//
//   i=2, j=1: s[1]=1 <  g[2]=3 ✗ → i=1 (放弃这个孩子)
//   i=1, j=1: s[1]=1 <  g[1]=2 ✗ → i=0 (放弃这个孩子)
//   i=0, j=1: s[1]=1 >= g[0]=1 ✓ → count=1, i=-1, j=0
//   i<0 → 结束, 返回 count=1
// ============================================================
class Solution2 {
public:
    int findContentChildren(vector<int>& g, vector<int>& s) {
        sort(g.begin(), g.end());
        sort(s.begin(), s.end());

        // 易错点：s 为空时 s.size()-1 是 unsigned 溢出！
        // 必须转 int 或提前判断
        if (s.empty()) return 0;

        int i = (int)g.size() - 1; // 从胃口最大的孩子开始
        int j = (int)s.size() - 1; // 从最大的饼干开始
        int count = 0;

        while (i >= 0 && j >= 0) {
            if (s[j] >= g[i]) {
                // 最大的饼干能满足当前最贪心的孩子 → 匹配
                count++;
                i--;
                j--;
            } else {
                // 最大的饼干都满足不了这个孩子
                // 更小的饼干更不可能 → 放弃这个孩子
                i--;
            }
        }

        return count;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度         | 解法1 正向贪心      | 解法2 反向贪心      |
// |-------------|--------------------|--------------------|
// | 方向         | 从小到大           | 从大到小            |
// | 失败时跳过   | 跳过饼干(太小没用)  | 跳过孩子(太贪满足不了)|
// | 时间复杂度   | O(n log n + m log m)| O(n log n + m log m)|
// | 空间复杂度   | O(1)              | O(1)               |
// | 面试推荐     | ⭐ 更直觉          | 也可以              |
//
// 两种方向结果相同，面试写哪个都行。正向的"小饼干给小胃口"
// 更容易向面试官解释为什么是对的。
//
// ============================================================
// 【易错点】
//
// 1. 忘记排序：不排序就无法保证贪心正确性。
//    ✗ 直接双指针扫描未排序数组
//    ✓ 两个数组都要 sort
//
// 2. 匹配失败时移错指针（正向贪心中）：
//    ✗ s[j] < g[i] 时写 i++（跳过孩子）
//      → 错误：这个孩子可能被后面更大的饼干满足
//    ✓ s[j] < g[i] 时应该 j++（跳过饼干）
//      → 正确：这块饼干对所有剩余孩子都太小了
//
// 3. unsigned 溢出（反向遍历时）：
//    ✗ int j = s.size() - 1;  // 当 s 为空，s.size()=0，0u-1 = 4294967295
//    ✓ 先判断 if (s.empty()) return 0; 或用 (int)s.size() - 1
//
// 4. 匹配成功只移一个指针：
//    ✗ count++; j++;   // 忘了 i++，同一个孩子被重复匹配
//    ✓ count++; i++; j++;  // 孩子满足了，饼干用掉了，都要移
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么贪心是正确的？暴力解是什么？
//     暴力是枚举所有配对方案，指数级复杂度。
//     贪心正确性用交换论证：任何方案中如果存在"大饼干给了小胃口"，
//     交换后不会变差 → 小饼干优先给小胃口的策略是最优的。
//
// Q2: 如果每个孩子可以接收多块饼干（尺寸累加），怎么做？
//     变成了分组/背包问题。贪心思路：排序后从胃口最小的孩子开始，
//     贪心地用小饼干累加直到满足。需要更细致的分析。
//
// Q3: 如果饼干有保质期（只能在特定时间段使用），怎么做？
//     变成了带时间约束的匹配/调度问题，可以用区间贪心
//     （按截止时间排序）或匈牙利算法。
//
