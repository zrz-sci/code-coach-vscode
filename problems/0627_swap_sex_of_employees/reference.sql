-- ============================================================
-- 627. Swap Sex of Employees
-- ============================================================
-- 题目：用单条 UPDATE 语句交换 Salary 表中的 sex 列
--       'm' -> 'f', 'f' -> 'm'
--
-- 表结构:
--   Salary(id INT PK, name VARCHAR, sex ENUM('m','f'), salary INT)
--
-- 关键知识点：
--   1. SQL UPDATE 的求值语义：SET 中的表达式使用旧值计算
--   2. CASE WHEN 条件表达式
--   3. IF() 函数 (MySQL 专用)
--   4. ASCII/CHAR 字符运算技巧
-- ============================================================


-- ============================================================
-- 解法一：CASE WHEN（推荐，SQL 标准语法，所有数据库通用）
-- ============================================================
-- 思路：
--   对每一行判断 sex 的当前值，返回相反值
--   CASE WHEN 是 SQL:1992 标准，MySQL/PostgreSQL/SQL Server/Oracle 均支持
--
-- 执行过程：
--   1. 数据库扫描 Salary 表的每一行
--   2. 对每行的 sex 列求值：若为 'm' 返回 'f'，若为 'f' 返回 'm'
--   3. 将求值结果写入 sex 列
--   4. 所有行的求值在赋值之前完成，不会出现"先改了 m，导致后续判断错误"
--
-- 时间：O(n)  空间：O(1)

UPDATE Salary
SET sex = CASE
    WHEN sex = 'm' THEN 'f'
    WHEN sex = 'f' THEN 'm'
END;

-- 简化版（因为只有两个值，可以用 ELSE）：
-- UPDATE Salary
-- SET sex = CASE WHEN sex = 'm' THEN 'f' ELSE 'm' END;


-- ============================================================
-- 解法二：IF 函数（MySQL 专用，最简洁）
-- ============================================================
-- 思路：
--   IF(condition, true_value, false_value) 是 MySQL 内建的三元表达式
--   等价于 CASE WHEN condition THEN true_value ELSE false_value END
--
-- 注意：
--   - PostgreSQL 使用 CASE WHEN 或自定义函数，不支持 IF()
--   - SQL Server 使用 IIF()
--   - Oracle 使用 DECODE() 或 CASE WHEN
--
-- 时间：O(n)  空间：O(1)

-- UPDATE Salary
-- SET sex = IF(sex = 'm', 'f', 'm');


-- ============================================================
-- 解法三：ASCII 运算技巧
-- ============================================================
-- 思路：
--   利用两个字符 ASCII 码之和减去当前字符的 ASCII 码，得到另一个字符
--   ASCII('m') = 109, ASCII('f') = 102, 和 = 211
--   当 sex = 'm': CHAR(211 - 109) = CHAR(102) = 'f'
--   当 sex = 'f': CHAR(211 - 102) = CHAR(109) = 'm'
--
-- 这是经典的"不用临时变量交换两个值"思路：a = total - a
-- 在 SQL 面试中展示这个技巧能体现对字符编码的理解
--
-- 时间：O(n)  空间：O(1)

-- UPDATE Salary
-- SET sex = CHAR(ASCII('m') + ASCII('f') - ASCII(sex));


-- ============================================================
-- 解法四：XOR 位运算技巧
-- ============================================================
-- 思路：
--   利用 XOR 的自反性质：a ^ b ^ a = b
--   ASCII('m') ^ ASCII('f') = 109 ^ 102 = 11
--   当 sex = 'm': ASCII('m') ^ 11 = 109 ^ 11 = 102 = 'f'
--   当 sex = 'f': ASCII('f') ^ 11 = 102 ^ 11 = 109 = 'm'
--
-- 时间：O(n)  空间：O(1)

-- UPDATE Salary
-- SET sex = CHAR(ASCII(sex) ^ 11);
-- 或等价写法：
-- UPDATE Salary
-- SET sex = CHAR(ASCII(sex) ^ ASCII('m') ^ ASCII('f'));


