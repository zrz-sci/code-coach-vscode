/*
 * LeetCode 45: 跳跃游戏 II (Jump Game II)
 *
 * 【题目本质】
 * 从位置0出发，每个位置可以跳到若干后续位置，求到达终点的最少跳跃次数。
 * 本质是无权图上的最短路径问题 → BFS / 贪心。
 *
 * 【解法总览】
 * 解法1: 动态规划        — O(n²) / O(n)  — 最直觉的暴力思路
 * 解法2: 贪心(隐式BFS)   — O(n)  / O(1)  — 面试首选 ⭐
 * 解法3: 显式BFS层序      — O(n)  / O(1)  — 帮助理解解法2的本质
 *
 * 【和 LeetCode 55 的关系】
 * 55题只需判断能否到达终点：只维护 farthest
 * 45题需要最少跳次：多维护 curEnd 来标记每一跳的边界
 * 核心区别：加了 curEnd + jumps
 */

// ============================================================
// 解法1: 动态规划 — 对每个位置，看前面谁能跳到它
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// dp[i] = 从位置0到位置i的最少跳跃次数。
// 对于每个位置 i，枚举所有 j < i，如果 j + nums[j] >= i，
// 则 dp[i] = min(dp[i], dp[j] + 1)。
//
// 为什么想到这个？—— 这是最自然的"最短路径"思维：
// 要到达位置 i，一定是从某个能跳到 i 的位置 j 再跳一步过来。
//
// 瓶颈：对每个 i 都扫描所有 j，O(n²)。
//
// DP 填表过程 (nums = [2,3,1,1,4]):
//   位置:  0   1   2   3   4
//   dp:   [0]  ∞   ∞   ∞   ∞   初始
//         [0]  1   ∞   ∞   ∞   i=1: j=0, 0+2>=1 ✓ → dp[1]=1
//         [0]  1   1   ∞   ∞   i=2: j=0, 0+2>=2 ✓ → dp[2]=1
//         [0]  1   1   2   ∞   i=3: j=1, 1+3>=3 ✓ → dp[3]=2
//         [0]  1   1   2   2   i=4: j=1, 1+3>=4 ✓ → dp[4]=2
// ============================================================
class Solution1 {
public:
    int jump(vector<int>& nums) {
        int n = nums.size();
        vector<int> dp(n, INT_MAX);
        dp[0] = 0;

        for (int i = 1; i < n; i++) {
            for (int j = 0; j < i; j++) {
                // j 本身可达 且 j 能跳到 i
                if (dp[j] != INT_MAX && j + nums[j] >= i) {
                    dp[i] = min(dp[i], dp[j] + 1);
                    // dp 是非递减的，第一个能到 i 的 j 就是最优
                    // 所以可以 break（小优化，但不改变最坏复杂度）
                    break;
                }
            }
        }
        return dp[n - 1];
    }
};

// ============================================================
// 解法2: 贪心（隐式 BFS）— 面试首选 ⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 把问题看成 BFS 层序遍历：
//   - 第 0 跳：只有位置 0
//   - 第 1 跳：从位置 0 能跳到的所有位置 [1, nums[0]]
//   - 第 2 跳：从第 1 跳覆盖的位置能跳到的更远的位置
//   - ...以此类推
//
// BFS 在无权图上天然找最短路径，所以这个方法一定是最优的。
//
// 关键：因为每一层覆盖的是一段连续区间，不需要真的用队列，
// 只需要两个变量：
//   curEnd   — 当前这一跳能到的最远边界（当前层的右端点）
//   farthest — 遍历过程中记录的下一跳能到的最远位置
//
// 遍历到 curEnd 时，说明当前层遍历完了，必须跳一次进入下一层。
//
// 执行过程 (nums = [2, 3, 1, 1, 4]):
//
// i=0: farthest = max(0, 0+2) = 2
//      i == curEnd(0) → jumps=1, curEnd=2
//      [当前层: {0}] → 下一层覆盖到位置2
//
// i=1: farthest = max(2, 1+3) = 4
//      i != curEnd(2) → 继续
//
// i=2: farthest = max(4, 2+1) = 4
//      i == curEnd(2) → jumps=2, curEnd=4
//      [当前层: {1,2}] → 下一层覆盖到位置4
//      curEnd=4 >= n-1=4 → break!
//
// 返回 jumps = 2
// ============================================================
class Solution2 {
public:
    int jump(vector<int>& nums) {
        int n = nums.size();
        int jumps = 0;
        int curEnd = 0;     // 当前跳跃的右边界
        int farthest = 0;   // 遍历中记录的下一跳最远可达

        // 为什么只遍历到 n-2？
        // 如果遍历到 n-1，当 curEnd 恰好等于 n-1 时会多跳一次。
        // 到达 n-1 就是终点，不需要再"跳出去"。
        for (int i = 0; i < n - 1; i++) {
            // 更新从当前层所有位置出发能到的最远处
            farthest = max(farthest, i + nums[i]);

            // 到达当前层边界 → 必须跳一次
            if (i == curEnd) {
                jumps++;
                curEnd = farthest;

                // 提前退出：已经能覆盖到终点
                if (curEnd >= n - 1) break;
            }
        }
        return jumps;
    }
};

// ============================================================
// 解法3: 显式 BFS 层序遍历 — 帮助理解解法2的本质
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 和解法2完全等价，但用 curStart/curEnd 显式维护每一层的区间。
// 每一层遍历 [curStart, curEnd]，找到下一层的 farthest，
// 然后 curStart = curEnd + 1, curEnd = farthest，层数+1。
//
// 这种写法更直观地体现 BFS 的"逐层扩展"。
//
// BFS 层序过程 (nums = [2, 3, 1, 1, 4]):
//
//   第0层: [0, 0]  扫描→ farthest=2  → jumps=1
//   第1层: [1, 2]  扫描→ farthest=4  → jumps=2
//   curEnd=4 >= n-1=4 → 结束
// ============================================================
class Solution3 {
public:
    int jump(vector<int>& nums) {
        int n = nums.size();
        if (n == 1) return 0;  // 已经在终点

        int jumps = 0;
        int curStart = 0, curEnd = 0;

        while (curEnd < n - 1) {
            int farthest = 0;
            // 遍历当前层的所有位置
            for (int i = curStart; i <= curEnd; i++) {
                farthest = max(farthest, i + nums[i]);
            }
            // 进入下一层
            curStart = curEnd + 1;
            curEnd = farthest;
            jumps++;
        }
        return jumps;
    }
};

// ============================================================
// 【解法对比】
//
// 解法1 (DP):
//   - 优点: 思路直觉，标准 DP 套路
//   - 缺点: O(n²)，数据量大会超时
//   - 适用: 作为面试起点展示理解
//
// 解法2 (贪心/隐式BFS):
//   - 优点: O(n) 时间 O(1) 空间，代码最简洁
//   - 缺点: 第一次看不太直观（为什么这就是 BFS？）
//   - 适用: ⭐ 面试首选写法
//
// 解法3 (显式BFS):
//   - 优点: 逻辑更清晰，显式体现 BFS 层序
//   - 缺点: 代码稍长
//   - 适用: 用来解释思路，然后简化成解法2的代码
//
// 解法2和解法3本质完全等价：
//   解法3的 for(curStart→curEnd) 对应解法2中 i 从 curEnd+1 到下一个 curEnd
//   解法2把这个过程融入了一个 for 循环，用 if(i==curEnd) 触发层切换
//
// ============================================================
// 【易错点】
//
// 1. 遍历范围必须是 i < n-1 而非 i < n
//    ✗ for (int i = 0; i < n; i++)
//      → 当 i=n-1 且 i==curEnd 时，会多跳一次
//    ✓ for (int i = 0; i < n - 1; i++)
//      → 到达 n-1 就是终点，不需要再跳
//
// 2. DP 解法中 dp[j]+1 溢出
//    ✗ dp[i] = min(dp[i], dp[j] + 1)  // 没检查 dp[j] 是否为 INT_MAX
//    ✓ if (dp[j] != INT_MAX && ...) dp[i] = min(dp[i], dp[j] + 1)
//
// 3. 贪心解法中 farthest 初始化为 nums[0] 而不是 0
//    ✗ int farthest = nums[0]  // 跳过了 i=0 时的统一更新逻辑
//    ✓ int farthest = 0        // 在循环中统一处理
//
// ============================================================
// 【面试追问】
//
// Q1: 和 LeetCode 55 的区别？代码怎么改？
// → 55只需 farthest 判断可达性。45多了 curEnd 和 jumps 来计数。
//   具体：55的代码只需 "if (farthest >= n-1) return true"，
//   45在此基础上加 "if (i == curEnd) { jumps++; curEnd = farthest; }"
//
// Q2: 为什么贪心正确？
// → 本质是 BFS。BFS 在无权图上保证最短路径。
//   每一跳 = BFS 一层，每层尽可能扩展覆盖范围 = 标准 BFS 行为。
//
// Q3: 如果允许双向跳跃怎么办？
// → 贪心失效（覆盖范围不再是连续区间）。
//   需要真正的 BFS + visited 数组：
//   从位置 i 可以跳到 [i-nums[i], i+nums[i]]，
//   用队列逐层扩展，visited 避免重复。
//   时间 O(n * max(nums[i]))，空间 O(n)。
//
// Q4: 如果不保证能到达终点？
// → 在贪心中检测"无法前进"：
//   if (i == curEnd && farthest == curEnd) return -1;
//   即当前层遍历完后，最远可达没有任何进展，说明被卡住了。
// ============================================================
