/*
 * LeetCode 945: 使数组唯一的最小增量 (Minimum Increment to Make Array Unique)
 *
 * 【题目本质】
 * 给定数组，每个元素只能增加（+1操作），使所有元素互不相同，求最小总操作次数。
 * 关键：只能增加不能减少 → 排序后贪心保证每个元素至少比前一个大1。
 *
 * 【解法总览】
 * 解法1: 暴力试探    — O(n²) / O(n)         — 展示理解
 * 解法2: 排序+贪心   — O(n log n) / O(1)    — 面试首选 ⭐
 * 解法3: 计数+顺延   — O(n + max_val) / O(max_val+n) — 加分项
 */

// ============================================================
// 解法1: 暴力试探 — 用集合判重，重复元素逐步+1
// 时间: O(n²) 最坏  空间: O(n)
//
// 【思路】
// 最直觉的想法：遍历每个元素，如果它已经被用了，就+1直到找到空位。
// 用集合记录已分配的值。
//
// 瓶颈：极端情况（全部相同）每个元素都要"爬"很远，总操作 O(n²)。
// 这个解法帮助理解题意，但 n=10⁵ 会超时。
// ============================================================
class Solution1 {
public:
    int minIncrementForUnique(vector<int>& nums) {
        unordered_set<int> seen;
        int moves = 0;
        for (int num : nums) {
            while (seen.count(num)) {
                num++;
                moves++;
            }
            seen.insert(num);
        }
        return moves;
    }
};

// ============================================================
// 解法2: 排序 + 贪心 — 面试首选 ⭐
// 时间: O(n log n)  空间: O(1) (原地排序)
//
// 【思路】
// 解法1的瓶颈是"寻找空位"太慢。排序后问题变得简单：
// 从左到右扫描，维护 need（当前元素至少应该是多少）。
// - 如果 nums[i] >= need：不用动，need 更新为 nums[i]+1
// - 如果 nums[i] < need：必须增加到 need，代价 = need - nums[i]
//
// 为什么贪心是最优的？
// 排序后每个元素只能增加不能减少，让它增加到"刚好不冲突的最小值"
// 一定不比增加到更大的值差。交换论证即可证明。
//
// 示例: nums = [3, 2, 1, 2, 1, 7]
// 排序后: [1, 1, 2, 2, 3, 7]
//
//   i=0: num=1, need=0 → max(0,1)=1, moves+=0, need=2
//   i=1: num=1, need=2 → max(2,1)=2, moves+=1, need=3
//   i=2: num=2, need=3 → max(3,2)=3, moves+=1, need=4
//   i=3: num=2, need=4 → max(4,2)=4, moves+=2, need=5
//   i=4: num=3, need=5 → max(5,3)=5, moves+=2, need=6
//   i=5: num=7, need=6 → max(6,7)=7, moves+=0, need=8
//   总 moves = 0+1+1+2+2+0 = 6 ✓
// ============================================================
class Solution2 {
public:
    int minIncrementForUnique(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        int moves = 0;
        int need = 0;  // 当前元素至少应该是的值
        
        for (int num : nums) {
            // need 和 num 取较大者：
            // 如果 num 本身就够大（没冲突），直接用 num
            // 如果 num 太小（会冲突），必须提升到 need
            need = max(need, num);
            moves += need - num;  // 增量（可能为0）
            need++;               // 下一个至少要 +1
        }
        return moves;
    }
};

// ============================================================
// 解法3: 计数 + 顺延 — 利用桶排序思想
// 时间: O(n + max_val)  空间: O(max_val + n)
//
// 【思路】
// 不排序，换用计数数组。统计每个值的出现次数，然后从小到大扫描：
// - 如果某个值出现了 k 次（k > 1），留1个，多出的 k-1 个顺延到下一个值
// - 每个顺延操作相当于 +1，moves 累加多余数量
//
// 本质上这是桶排序 + 贪心的组合，避免了 O(n log n) 的排序。
//
// 示例: nums = [3, 2, 1, 2, 1, 7]
//
// 计数数组:
//   val:   0  1  2  3  4  5  6  7
//   count: 0  2  2  1  0  0  0  1
//
// 扫描过程:
//   val=0: count=0 → 跳过
//   val=1: count=2 → 多1个→count[2]+=1, moves+=1
//   val=2: count=2+1=3 → 多2个→count[3]+=2, moves+=2
//   val=3: count=1+2=3 → 多2个→count[4]+=2, moves+=2
//   val=4: count=0+2=2 → 多1个→count[5]+=1, moves+=1
//   val=5: count=0+1=1 → 刚好
//   val=6: count=0 → 跳过
//   val=7: count=1 → 刚好
//   总 moves = 1+2+2+1 = 6 ✓
//
// 注意：值域上限不是 max(nums)，因为顺延可能超过原始最大值。
// 最坏情况：n 个相同元素，顺延到 max_val + n - 1。
// ============================================================
class Solution3 {
public:
    int minIncrementForUnique(vector<int>& nums) {
        int n = nums.size();
        int maxVal = *max_element(nums.begin(), nums.end());
        // 顺延的上限：所有元素相同时，最后一个会被推到 maxVal + n - 1
        int limit = maxVal + n;
        
        vector<int> count(limit + 1, 0);
        for (int num : nums) {
            count[num]++;
        }
        
        int moves = 0;
        for (int val = 0; val < limit; val++) {
            if (count[val] > 1) {
                int overflow = count[val] - 1;  // 多余元素个数
                count[val + 1] += overflow;      // 全部顺延到下一个位置
                // 每个多余元素都 +1 了一次
                // 如果它们到了下一个位置还是多余的，下一轮会继续+1
                // 所以总增量是正确累加的
                moves += overflow;
            }
        }
        return moves;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间 | 空间 | 核心思想 |
// |------|------|------|----------|
// | 暴力试探 | O(n²) | O(n) | 逐个找空位 |
// | 排序+贪心 | O(n log n) | O(1) | 排序后保证递增 |
// | 计数+顺延 | O(n+max_val) | O(max_val+n) | 桶排序+多余顺延 |
//
// 面试推荐：排序+贪心（代码最短、思路最清晰、无额外空间）
// 追问优化时：给出计数+顺延法（时间更优但需要额外空间）
//
// 【易错点】
// 1. 排序贪心中 need 的更新：
//    ✗ need = num + 1;  
//      → 当 num < need 时丢失了 need 的信息，后续元素可能冲突
//    ✓ need = max(need, num); moves += need - num; need++;
//
// 2. 计数数组大小：
//    ✗ vector<int> count(100001, 0);
//      → 10^5 个元素都是 10^5 时，最终值到 2*10^5，数组越界
//    ✓ vector<int> count(maxVal + n + 1, 0);
//
// 3. 排序贪心中 moves 的计算：
//    ✗ if (nums[i] <= nums[i-1]) moves += nums[i-1] - nums[i] + 1;
//       然后修改 nums[i] = nums[i-1] + 1;
//      → 这种写法虽然也对，但修改了原数组，且和前一个元素比较
//         更容易出错（比如忘记修改 nums[i]）
//    ✓ 用 need 变量更简洁安全
//
// 4. 计数法中 moves += overflow 只加了1步的量：
//    ✗ 以为每个元素被推了若干格但只计了一次
//    ✓ 实际上每一轮只推一格，如果需要推多格会在后续轮次继续累加
//       所以最终的 moves 是所有"推一格"操作的总和，恰好等于总增量
//
// 【面试追问】
// Q1: 暴力能过吗？→ O(n²)，n=10^5 约 10^10 次操作，超时。
//     但可以作为起点，说明你理解问题，再优化。
//
// Q2: 排序贪心的正确性怎么证？
//     → 排序后每个元素只能增加。对于第 i 个元素，它的目标值至少是
//       max(nums[i], target[i-1]+1)。让它恰好等于这个最小值，
//       不会影响后面元素的最优性（后面元素的 need 只会更大或不变）。
//       交换论证：如果某方案让第 i 个增加更多，把它换成增加更少
//       不会使结果更差（后面的 need 只会 ≤ 原方案）。
//
// Q3: 如果操作改为"可以+1或-1"，最小操作次数？
//     → 变成了一个更复杂的问题。排序后，需要选择 n 个不同的目标值
//       使得总距离 |nums[i] - target[i]| 最小。
//       可以证明最优的 target 序列是某个等差序列的平移，
//       转化为中位数问题的变体。
// ============================================================
