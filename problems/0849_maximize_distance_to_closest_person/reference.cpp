/*
 * LeetCode 849: Maximize Distance to Closest Person (到最近的人的最大距离)
 *
 * 【题目本质】
 * 在一排座位中找一个空位坐下，使得到最近有人座位的距离最大化。
 * 核心问题：分析有人位置之间的间隔，找到最优的落座点。
 *
 * 【解法总览】
 * 解法1: 两次遍历        — O(n) / O(n)   — 预处理左右最近人距离
 * 解法2: 一次遍历(间隔法) — O(n) / O(1)   — 面试首选，维护 prev 指针
 * 解法3: 收集有人位置     — O(n) / O(k)   — 显式收集再分析间隔
 */

// ============================================================
// 解法1: 两次遍历 — 预处理每个位置到最近人的距离
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 正向遍历：对每个位置记录到左侧最近人的距离 left[i]。
// 反向遍历：对每个位置记录到右侧最近人的距离 right[i]。
// 每个空位到最近人的距离 = min(left[i], right[i])。
// 答案 = max{ min(left[i], right[i]) | seats[i] == 0 }。
//
// 示例: seats = [1, 0, 0, 0, 1, 0, 1]
//   left:  [0, 1, 2, 3, 0, 1, 0]
//   right: [0, 3, 2, 1, 0, 1, 0]
//   min:   [0, 1, 2, 1, 0, 1, 0]
//   空位处 min: [1, 2, 1, 1]  → max = 2 ✓
// ============================================================
class Solution1 {
public:
    int maxDistToClosest(vector<int>& seats) {
        int n = seats.size();
        // left[i]: 位置 i 到左侧最近有人座位的距离
        // right[i]: 位置 i 到右侧最近有人座位的距离
        // 初始化为 n (足够大，表示该方向暂无人)
        vector<int> left(n, n), right(n, n);

        // 正向遍历：计算到左边最近人的距离
        for (int i = 0; i < n; i++) {
            if (seats[i] == 1) {
                left[i] = 0;      // 有人的位置距离为 0
            } else if (i > 0) {
                left[i] = left[i - 1] + 1; // 从左邻居 +1
            }
            // i == 0 且 seats[0] == 0 时，left[0] 保持 n (左边无人)
        }

        // 反向遍历：计算到右边最近人的距离
        for (int i = n - 1; i >= 0; i--) {
            if (seats[i] == 1) {
                right[i] = 0;
            } else if (i < n - 1) {
                right[i] = right[i + 1] + 1;
            }
        }

        // 取每个空位到最近人的距离的最大值
        int ans = 0;
        for (int i = 0; i < n; i++) {
            if (seats[i] == 0) {
                ans = max(ans, min(left[i], right[i]));
            }
        }
        return ans;
    }
};

// ============================================================
// 解法2: 一次遍历 — 维护上一个有人位置 prev ⭐ 面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 遍历数组，用 prev 记录上一个有人的座位位置。
// 遇到 seats[i] == 1 时：
//   - 如果 prev == -1: 这是第一个人，左端空位段距离 = i
//   - 否则: 中间段，最优位置在两人中点，距离 = (i - prev) / 2
// 遍历完后处理右端空位段：距离 = n - 1 - prev
//
// 三种间隔类型示意:
//   [0,0,0,1,...,1,0,0]
//    ^^^^^           ^^^
//    左端段           右端段
//    距离=i           距离=n-1-prev
//
//   [...,1,0,0,0,0,1,...]
//         ^^^^^^^^^
//         中间段
//         距离=(right-left)/2
//
// 示例: seats = [0, 0, 1, 0, 0, 0, 0, 1, 0]
//   i=2: prev==-1, 左端段距离=2
//   i=7: prev==2, 中间段距离=(7-2)/2=2
//   结束: 右端段距离=8-7=1
//   ans = max(2, 2, 1) = 2 ✓
// ============================================================
class Solution2 {
public:
    int maxDistToClosest(vector<int>& seats) {
        int n = seats.size();
        int prev = -1;  // 上一个有人的位置，-1 表示还没遇到
        int ans = 0;

        for (int i = 0; i < n; i++) {
            if (seats[i] == 1) {
                if (prev == -1) {
                    // 左端空位段：从位置0到位置i的距离
                    // 坐在位置0，离最近人(位置i)的距离就是 i
                    ans = i;
                } else {
                    // 中间段：两个有人位置 prev 和 i 之间
                    // 最优坐在中点，距离 = (i - prev) / 2
                    ans = max(ans, (i - prev) / 2);
                }
                prev = i;  // 更新上一个有人的位置
            }
        }

        // 右端空位段：从 prev 到末尾的距离
        // 坐在位置 n-1，离最近人(位置 prev)的距离是 n-1-prev
        ans = max(ans, n - 1 - prev);

        return ans;
    }
};

// ============================================================
// 解法3: 收集有人位置 — 显式分析间隔
// 时间: O(n)  空间: O(k)，k 为有人位置数
//
// 【思路】
// 先把所有有人的位置收集到数组 occupied 中。
// 然后分析相邻有人位置之间的间隔：
//   - 左端间隔: occupied[0]（首个有人位到左墙的距离）
//   - 中间间隔: (occupied[i+1] - occupied[i]) / 2
//   - 右端间隔: n - 1 - occupied.back()
//
// 这个解法思路最清晰，适合面试中先讲解思路。
//
// 示例: seats = [1, 0, 0, 0, 1, 0, 1]
//   occupied = [0, 4, 6]
//   左端: occupied[0] = 0 (第一个有人位在0，左墙无空位)
//   中间: (4-0)/2=2, (6-4)/2=1
//   右端: 7-1-6 = 0 (最后一个有人位在6，右墙无空位)
//   ans = max(0, 2, 1, 0) = 2 ✓
// ============================================================
class Solution3 {
public:
    int maxDistToClosest(vector<int>& seats) {
        int n = seats.size();

        // 收集所有有人的位置
        vector<int> occupied;
        for (int i = 0; i < n; i++) {
            if (seats[i] == 1) {
                occupied.push_back(i);
            }
        }

        int ans = 0;

        // 左端间隔：坐在位置0，离第一个有人位的距离
        ans = max(ans, occupied[0]);

        // 中间间隔：相邻两个有人位之间
        for (int i = 0; i + 1 < (int)occupied.size(); i++) {
            int gap = occupied[i + 1] - occupied[i];
            ans = max(ans, gap / 2);
        }

        // 右端间隔：坐在位置 n-1，离最后有人位的距离
        ans = max(ans, n - 1 - occupied.back());

        return ans;
    }
};

