//
// | 解法        | 时间  | 空间  | 优势               | 劣势              |
// |------------|-------|-------|-------------------|------------------|
// | 两次遍历    | O(n)  | O(n)  | 思路直观，通用性强    | 额外数组           |
// | 一次遍历    | O(n)  | O(1)  | 最优空间            | 需处理三种间隔类型   |
// | 收集位置    | O(n)  | O(k)  | 代码最清晰           | 额外存储有人位置    |
//
// 面试建议：先说思路用"收集位置"讲解，写代码用"一次遍历"。
// ============================================================
// 【易错点】
//
// 1. 左端/右端间隔忘记特殊处理:
//    ✗ 所有间隔都 gap/2 → [0,0,0,1] 返回 1 而非 3
//    ✓ 端部间隔不除以2
//
// 2. prev 初始化为 0 而非 -1:
//    ✗ prev=0 → seats=[0,1,...] 时左端间隔被算成 (1-0)/2=0
//    ✓ prev=-1 作哨兵
//
// 3. 遍历结束后忘记处理右端:
//    ✗ [1,0,0,0] 循环只处理中间段，漏掉右端 → 返回0
//    ✓ 循环后加 ans = max(ans, n-1-prev)
