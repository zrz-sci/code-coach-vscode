/*
 * LeetCode 1963: Minimum Number of Swaps to Make the String Balanced
 * (使字符串平衡的最小交换次数)
 *
 * 【题目本质】
 * 字符串由等数量的 '[' 和 ']' 组成，可以交换任意两个位置。
 * 求使字符串变为平衡括号串所需的最少交换次数。
 *
 * 【核心洞察】
 * 先消掉已匹配的括号对，剩余形如 "]]]...[[[..." (close个]和close个[)。
 * 每次交换修掉2个未匹配 → 答案 = ceil(close/2) = (close+1)/2
 *
 * 【解法总览】
 * 解法1: 贪心计数      — O(n) / O(1)   — 面试首选
 * 解法1b: 更简洁写法   — O(n) / O(1)   — 只用一个变量
 * 解法2: 栈模拟        — O(n) / O(n)   — 空间浪费
 *
 * 【交换过程可视化】
 *
 *   s = "][]["
 *   扫描: ]→close=1, [→open=1, ]→消掉open, [→open=1
 *   close = 1 → (1+1)/2 = 1 次交换
 *
 *   具体: ] [ ] [  →  交换s[0]和s[3]  →  [ [ ] ]  → 平衡! ✓
 *         0 1 2 3
 *
 *   s = "]]][[["
 *   close = 3 → (3+1)/2 = 2 次交换
 *
 *   ] ] ] [ [ [  →  交换s[0]和s[4]  →  [ ] ] [ ] [
 *                →  消掉已匹配后剩 ][
 *                →  交换  →  [] → 平衡!
 *   共2次 ✓
 *
 * 【公式推导】
 *   n/2个'[' + n/2个']', 消掉m对已匹配
 *   剩余: k = n/2 - m 对未匹配 (k个']' + k个'[')
 *   每次交换最多修2个未匹配 → 下界 = ceil(k/2)
 *   贪心恰好达到下界 → 答案 = (k+1)/2
 */


// ============================================================
// 解法1: 贪心计数 — 面试首选
// 时间: O(n)  单次遍历
// 空间: O(1)  两个变量
//
// 【思路】
// open: 当前未匹配的 '[' 数量
// close: 遇到 ']' 时无法匹配的次数
//
// 遍历字符串:
//   遇到 '[': open++ (记录一个待匹配的左括号)
//   遇到 ']':
//     如果 open > 0: open-- (和最近的'['配对消掉)
//     否则: close++ (无法配对，是多余的']')
//
// 遍历完后 close = 未匹配的 ']' 数
// 答案 = (close + 1) / 2
//
// 【为什么 遍历完后 open == close?】
// 总 '[' 数 = n/2, 总 ']' 数 = n/2
// 已匹配的对数 = m
// 剩余 '[' = n/2 - m = open
// 剩余 ']' = n/2 - m = close
// 所以 open == close
//
// 【扫描过程详解: s = "]]][[[" 】
//
//   字符  open  close  说明
//   ]     0     1      open=0, 无法匹配 → close++
//   ]     0     2      open=0, 无法匹配 → close++
//   ]     0     3      open=0, 无法匹配 → close++
//   [     1     3      open++
//   [     2     3      open++
//   [     3     3      open++
//
//   close = 3, 答案 = (3+1)/2 = 2 ✓
//
// 【扫描过程详解: s = "][][" 】
//
//   字符  open  close  说明
//   ]     0     1      无法匹配 → close++
//   [     1     1      open++
//   ]     0     1      open>0, 匹配! open--
//   [     1     1      open++
//
//   close = 1, 答案 = (1+1)/2 = 1 ✓
// ============================================================
class Solution1 {
public:
    int minSwaps(string s) {
        int open = 0;   // 未匹配的 '[' 数量
        int close = 0;  // 无法匹配的 ']' 数量

        for (char c : s) {
            if (c == '[') {
                open++;
            } else {  // c == ']'
                if (open > 0) {
                    open--;   // 消掉一对已匹配的
                } else {
                    close++;  // 无法配对
                }
            }
        }

        // 每次交换修掉 2 个未匹配
        return (close + 1) / 2;
    }
};


// ============================================================
// 解法1b: 更简洁的写法 — 只用一个变量
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 遍历完后 open == close (证明见上)。
// 所以不需要 close 变量, 直接用最终的 open 值。
//
// 遍历过程:
//   遇到 '[': open++
//   遇到 ']': 如果 open > 0 则 open-- (配对消掉),
//            否则什么都不做 (跳过这个多余的']')
//
// 遍历完后 open = 未匹配的'['数 = 未匹配的']'数
// 答案 = (open + 1) / 2
// ============================================================
class Solution1b {
public:
    int minSwaps(string s) {
        int open = 0;
        for (char c : s) {
            if (c == '[') {
                open++;
            } else if (open > 0) {
                open--;  // 配对消掉
            }
            // 遇到']'且 open==0: 跳过 (这是多余的']')
        }
        // open = 未匹配的'['数 = 未匹配的']'数
        return (open + 1) / 2;
    }
};


// ============================================================
// 解法2: 栈模拟 — 教学用，空间 O(n)
// 时间: O(n)  空间: O(n) 栈
//
// 【思路】
// 用栈消掉所有匹配的括号对。
// 栈中剩余的就是未匹配的 ']]]...[[[...'。
// 栈的大小 = 2 * close, 所以 close = st.size() / 2。
//
// 【为什么不推荐】
// 和解法1 本质一样，但用了 O(n) 额外空间。
// 面试中可以提到但不必实现。
// ============================================================
class Solution2 {
public:
    int minSwaps(string s) {
        stack<char> st;
        for (char c : s) {
            if (c == '[') {
                st.push(c);
            } else {
                // 栈顶是 '[' → 配对消掉
                if (!st.empty() && st.top() == '[') {
                    st.pop();
                } else {
                    st.push(c);  // 无法配对，压入栈
                }
            }
        }

        // 栈中: close个']' + close个'['
        // 总大小 = 2 * close
        int close = st.size() / 2;
        return (close + 1) / 2;
    }
};


// ============================================================
// 【解法对比】
//
// | 维度       | 贪心计数      | 简洁写法       | 栈模拟         |
// |-----------|-------------|---------------|---------------|
// | 时间       | O(n)        | O(n)          | O(n)          |
// | 空间       | O(1)        | O(1)          | O(n) 栈       |
// | 代码量     | 10行        | 8行           | 12行          |
// | 面试推荐   | 首选        | 最简洁         | 教学用        |
//
// 推荐: 解法1 或 1b。面试时解释"消掉已匹配对后剩余形状"很关键。
//
// ============================================================
// 【贪心正确性的严格证明】
//
// 命题: 对于 close 对未匹配的括号, 最少需要 ceil(close/2) 次交换。
//
// 下界: 每次交换最多修复 2 个未匹配的括号 (将一个']'和一个'['互换)。
//       因此至少需要 ceil(close/2) 次。
//
// 上界: 贪心策略能达到这个下界:
//       每次取最左未匹配的']'和最右未匹配的'['交换。
//       交换后这两个位置都变成了已匹配的。
//       close 为偶数: 恰好 close/2 次
//       close 为奇数: 最后一次交换 "][" → "[]", 修复2个。
//                     共 (close+1)/2 次 = ceil(close/2) 次。
//
// 上界 == 下界 → 最优。
//
// ============================================================
// 【易错点】
//
// 1. 答案公式写错
//    ✗ close / 2         → 奇数 close 时少算了 1
//    ✗ (close + 2) / 2   → 偶数 close 时多算了 1
//    ✓ (close + 1) / 2   → 等价于 ceil(close / 2)
//
// 2. 混淆 open 和 close 的含义
//    open = 当前未匹配的 '[' 数 (遍历过程中动态变化)
//    close = 遍历完后无法匹配的 ']' 数 (只增不减)
//    遍历完后 open == close (未匹配的'['和']'一样多)
//
// 3. 栈解法中 size() 返回值
//    st.size() 返回 size_t (无符号), 整除时注意:
//    如果 size=0, size/2=0, (0+1)/2=0 → 正确
//    如果 size=2, close=1, (1+1)/2=1 → 正确
//
// 4. 忘记处理空字符串
//    s = "[]" → close=0, 答案=0 ✓ (公式自动处理)
//    s = "" → 不会出现 (n >= 2)
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么消掉已匹配后剩余一定是 "]]]...[[[..." ?
//     → 从左往右扫描, 每个']'要么和左边的'['配对(被消掉),
//       要么左边没有'['(无法配对, 留下)。
//       所有无法配对的']'一定在所有未匹配的'['左边。
//
// Q2: 为什么每次交换最多修2个?
//     → 交换把一个']'移到右边, 一个'['移到左边。
//       最好情况: 这个']'和这个'['都从"未匹配"变成"已匹配"。
//       所以修2个。不可能修3个或更多。
//
// Q3: 如果不是交换任意位置, 而是只能相邻交换呢?
//     → 完全不同的问题! 需要计算把每个未匹配']'移到右边
//       所需的相邻交换次数之和, 通常更大。
//       (类似于冒泡排序的交换次数 = 逆序对数)
//
// Q4: 这个贪心和 LC921 有什么区别?
//     → LC921 是"最少添加次数使括号有效", 答案 = open + close。
//       本题是"最少交换次数", 答案 = ceil(close/2)。
//       两题都需要统计 open 和 close, 但最终公式不同。
//
// Q5: n 最大 10^6, O(n) 足够吗?
//     → 足够。10^6 次循环 + 每次 O(1) 操作, 远在时限内。
//       O(1) 空间也很完美。
// ============================================================
