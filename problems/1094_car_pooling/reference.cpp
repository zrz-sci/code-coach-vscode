/*
 * LeetCode 1094: 拼车 (Car Pooling)
 *
 * 【题目本质】
 * 区间叠加问题：多段行程在各自区间 [from, to) 内增加乘客，
 * 问任意位置的乘客总数是否超过 capacity。
 *
 * 【解法总览】
 * 解法1: 暴力模拟       — O(n·L) / O(L)     — 最直觉，逐点累加
 * 解法2: 差分数组       — O(n+L) / O(L)     — 面试首选，端点操作+前缀和
 * 解法3: 事件排序(map)  — O(n log n) / O(n) — 位置范围大时的通用方案
 */

// ============================================================
// 解法1: 暴力模拟 — 对每段行程逐位置累加乘客数
// 时间: O(n·L)  空间: O(L)
// 其中 n = trips.size(), L = 位置上界(≤1000)
//
// 【思路】
// 最直觉：开一个数组代表每个位置车上有多少人。
// 对每段行程，把 [from, to) 区间内每个位置都加上乘客数。
// 如果任何位置超过 capacity，返回 false。
//
// 瓶颈：每段行程要遍历 (to - from) 个位置，如果行程很长就慢。
//
// 示例: trips=[[2,1,5],[3,3,7]], capacity=4
//
// 位置:    0    1    2    3    4    5    6    7
// 行程1:        +2   +2   +2   +2              
// 行程2:                  +3   +3   +3   +3    
// 总人数:  0    2    2    5    5    3    3    0
//                        ↑ 5 > 4, 超载！返回 false
// ============================================================
class Solution1 {
public:
    bool carPooling(vector<vector<int>>& trips, int capacity) {
        vector<int> passengers(1001, 0);

        for (auto& trip : trips) {
            int num = trip[0], from = trip[1], to = trip[2];
            // 区间 [from, to) 内每个位置都加乘客
            // 注意是 < to，因为乘客在 to 处已下车
            for (int i = from; i < to; i++) {
                passengers[i] += num;
                if (passengers[i] > capacity) return false;
            }
        }
        return true;
    }
};

// ============================================================
// 解法2: 差分数组 — 区间加操作压缩为两个端点操作
// 时间: O(n + L)  空间: O(L)
//
// 【思路】
// 解法1的瓶颈：每段行程需要 O(to - from) 的区间逐点累加。
// 差分数组的核心洞察：对区间 [a, b) 加 val，
// 等价于 diff[a] += val, diff[b] -= val，只需 O(1)。
// 最后对 diff 做前缀和就还原了每个位置的实际值。
//
// 为什么这能 work？
// diff[i] 记录的是"位置 i 相对于 i-1 的变化量"。
// 在 from 处 +num = "从这里开始多 num 人"
// 在 to 处 -num = "到这里这些人下车了"
// 前缀和 = 累加所有变化量 = 每个位置的实际乘客数
//
// 示例: trips=[[2,1,5],[3,3,7]], capacity=5
//
// 差分构建:
//   行程1: diff[1]+=2, diff[5]-=2
//   行程2: diff[3]+=3, diff[7]-=3
//
// diff:    [0, +2,  0, +3,  0, -2,  0, -3, ...]
// 前缀和:  [0,  2,  2,  5,  5,  3,  3,  0, ...]
//                       ↑ 5 <= 5, OK
// ============================================================
class Solution2 {
public:
    bool carPooling(vector<vector<int>>& trips, int capacity) {
        // diff[i] = 位置 i 的乘客变化量
        vector<int> diff(1001, 0);

        for (auto& trip : trips) {
            int num = trip[0], from = trip[1], to = trip[2];
            diff[from] += num;  // from 处上车：+num
            diff[to] -= num;    // to 处下车：-num（左闭右开，to处已不在车上）
        }

        // 前缀和还原实际乘客数
        int current = 0;
        for (int i = 0; i <= 1000; i++) {
            current += diff[i];
            // current 就是位置 i 处车上的实际乘客数
            if (current > capacity) return false;
        }
        return true;
    }
};

// ============================================================
// 解法3: 事件排序（扫描线）— 用 map 天然排序
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 换一个角度：把每段行程拆成两个"事件"：
//   - 位置 from: +num（上车事件）
//   - 位置 to:   -num（下车事件）
//
// 把所有事件按位置排序，从左到右扫描，
// 维护当前车上人数 current，检查是否超载。
//
// 与差分数组本质相同，但优势在于：
// 当位置范围极大（如 10^9）时，差分数组开不了那么大，
// 而事件排序只需要 O(n) 空间存储实际出现的位置。
//
// 这里用 map<int,int> 自动按 key 排序，简洁优雅：
// map 的 key = 位置，value = 该位置的变化量总和
//
// 示例: trips=[[2,1,5],[3,3,7]]
// events: {1:+2, 3:+3, 5:-2, 7:-3}
// 扫描: pos=1, cur=2 → pos=3, cur=5 → pos=5, cur=3 → pos=7, cur=0
// ============================================================
class Solution3 {
public:
    bool carPooling(vector<vector<int>>& trips, int capacity) {
        // map 按位置自动排序，同一位置的变化量直接累加
        map<int, int> events;

        for (auto& trip : trips) {
            int num = trip[0], from = trip[1], to = trip[2];
            events[from] += num;   // 上车事件
            events[to] -= num;     // 下车事件
        }

        int current = 0;
        for (auto& [pos, change] : events) {
            current += change;
            if (current > capacity) return false;
        }
        return true;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间     | 空间 | 适用场景                     |
// |------|----------|------|------------------------------|
// | 暴力 | O(n·L)   | O(L) | 理解题意，不推荐             |
// | 差分 | O(n+L)   | O(L) | 位置范围小时最优 ⭐          |
// | 事件 | O(nlogn) | O(n) | 位置范围大或需要通用方案     |
//
// 差分数组 vs 事件排序：
// - 本质相同，都是在端点记录变化量，前缀和还原
// - 差分用数组直接寻址 O(1)，但需要位置范围小
// - 事件用排序/map，空间与行程数 n 相关而非位置范围 L
//
// 【易错点】
// 1. 左闭右开：diff[to] -= num 而不是 diff[to+1] -= num
//    乘客在 to 处已经下车，to 位置不应计入。
//    ✗ diff[to + 1] -= num  → 多算了一个位置
//    ✓ diff[to] -= num
//
// 2. 差分数组大小：位置最大为1000，需要 diff[1001]
//    ✗ vector<int> diff(1000, 0)  → diff[1000] 越界
//    ✓ vector<int> diff(1001, 0)
//
// 3. 不能在构建差分时判断超载：
//    ✗ 构建差分时看 diff[from] > capacity → 差分值不是实际乘客数
//    ✓ 必须做完前缀和后才能判断
//
// 4. 事件排序用 unordered_map 会出错：
//    ✗ unordered_map 无序，无法按位置从左到右扫描
//    ✓ 用 map（有序）或 vector<pair> 排序后扫描
//
// 【面试追问】
// Q1: 暴力的瓶颈是什么？差分数组怎么优化的？
//     → 瓶颈是区间逐点加 O(L)。差分将其压缩为两个端点操作 O(1)，
//       最后一次前缀和 O(L) 还原。总体从 O(n·L) 降到 O(n+L)。
//
// Q2: 如果位置范围是 10^9 怎么办？
//     → 差分数组开不了那么大，改用事件排序法（解法3）。
//       只存实际出现的位置，空间 O(n)，时间 O(n log n)。
//
// Q3: 如果需要在线动态添加行程并实时查询是否超载？
//     → 用线段树：支持区间加 O(log L) 和区间最值查询 O(log L)。
//       位置范围大时用动态开点线段树或离散化。
//
