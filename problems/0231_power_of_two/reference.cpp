/*
 * 【题目本质】
 * 判断一个整数是否是 2 的幂次方
 * 2 的幂的二进制特征：恰好只有一个 1 位 (1, 10, 100, 1000...)
 *
 * 【解法总览】
 * 解法1: n & (n-1) 消除最低位1   - O(1) ⭐推荐
 * 解法2: n & (-n) lowbit 提取     - O(1)
 * 解法3: 循环除 2                 - O(log n)
 */

// ==================== 解法1: n & (n-1) ====================
// 思路: n & (n-1) 消除最低位的1，2的幂只有一个1，消除后为0
// 注意: 必须先判 n > 0（0 和负数不是 2 的幂）
class Solution1 {
public:
    bool isPowerOfTwo(int n) {
        // n > 0: 排除 0 和负数
        // (n & (n-1)) == 0: 只有一个1位
        return n > 0 && (n & (n - 1)) == 0;
    }
};

// ==================== 解法2: n & (-n) lowbit ====================
// 思路: n & (-n) 提取最低位的1，若等于 n 本身则只有一个1位
// -n 是 n 的补码 = ~n + 1
class Solution2 {
public:
    bool isPowerOfTwo(int n) {
        // n > 0: 排除 0 和负数
        // (n & (-n)) == n: 最低位的1就是唯一的1
        return n > 0 && (n & (-n)) == n;
    }
};

// ==================== 解法3: 循环除 2 ====================
// 思路: 不断除以2，若最终为1则是2的幂
// 适合不熟悉位运算时使用
class Solution3 {
public:
    bool isPowerOfTwo(int n) {
        if (n <= 0) return false;
        while (n % 2 == 0) {
            n /= 2;
        }
        return n == 1;
    }
};

/*
 * 【解法对比】
 * ┌──────────────┬──────────┬──────────┬──────────────────────────┐
 * │ 解法         │ 时间     │ 空间     │ 特点                     │
 * ├──────────────┼──────────┼──────────┼──────────────────────────┤
 * │ n & (n-1)    │ O(1)     │ O(1)    │ 经典位运算，面试首选      │
 * │ n & (-n)     │ O(1)     │ O(1)    │ lowbit 思想，BIT 树基础   │
 * │ 循环除 2     │ O(log n) │ O(1)    │ 最直觉，但非最优          │
 * └──────────────┴──────────┴──────────┴──────────────────────────┘
 *
 * 【易错点】
 * 1. 忘记 n > 0 判断 -> n=0 时 0 & (-1) = 0 也满足条件但不是2的幂
 * 2. 运算符优先级: n & (n-1) == 0 实际是 n & ((n-1) == 0)
 *    必须写成 (n & (n-1)) == 0，加括号！
 * 3. INT_MIN 是负数，-INT_MIN 溢出 -> n > 0 判断必须在前（短路求值）
 *
 * 【面试追问】
 * Q: n & (n-1) 还能做什么？
 * A: 统计二进制1的个数 (LC 191)：循环 n = n & (n-1)，计数直到 n=0
 *
 * Q: 判断 4 的幂？
 * A: 先判断是2的幂，再确认1在奇数位: n > 0 && (n&(n-1))==0 && (n&0x55555555)
 *    0x55555555 = 01010101...01 (奇数位为1)
 *
 * Q: 判断 3 的幂？(LC 326)
 * A: 不能用位运算。用 int 范围最大的3的幂 3^19=1162261467 取模:
 *    return n > 0 && 1162261467 % n == 0; (仅对质数底数有效)
 */
