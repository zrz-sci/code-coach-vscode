/*
 * LeetCode 739: 每日温度 (Daily Temperatures)
 *
 * 【题目本质】
 * 对数组中每个元素，找右边第一个比它大的元素的距离。
 * 经典的 "Next Greater Element" 问题。
 *
 * 【解法总览】
 * 解法1: 暴力双循环       — O(n²) / O(1)   — 最直觉
 * 解法2: 单调递减栈       — O(n) / O(n)    — 面试首选 ⭐
 * 解法3: 反向遍历+跳跃    — O(n) / O(1)    — 空间优化加分项
 */

// ============================================================
// 解法1: 暴力双循环 — 对每天向右扫描第一个更高温度
// 时间: O(n²)  空间: O(1)（不计输出数组）
//
// 【思路】
// 最直觉的做法：对每一天 i，从 i+1 开始逐个检查，
// 找到第一个温度严格大于 temperatures[i] 的天 j，
// 记录 answer[i] = j - i。
//
// 瓶颈：每个元素独立扫描，没有利用之前的比较结果。
// 递减数组（如 [100,99,98,...]）最坏 O(n²)，n=10^5 会超时。
// ============================================================
class Solution1 {
public:
    vector<int> dailyTemperatures(vector<int>& temperatures) {
        int n = temperatures.size();
        vector<int> answer(n, 0);
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                if (temperatures[j] > temperatures[i]) {
                    answer[i] = j - i;
                    break;  // 只要第一个更高的
                }
            }
            // 如果内层循环走完没 break，answer[i] 保持 0
        }
        return answer;
    }
};

// ============================================================
// 解法2: 单调递减栈 — 遇到更高温度时批量结算等待者 ⭐
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 暴力法的瓶颈：每个元素重复向右扫描。
// 关键观察：维护一个"还没找到答案的天"的栈。
// 当遇到一个较高温度时，它能一次性结算所有栈中比它小的天。
//
// 为什么栈是递减的？
// 如果栈中有 A < B（B 在 A 上面），那 B 入栈时应该已经结算了 A，
// 所以栈中不会出现下面小上面大的情况 → 栈底到栈顶温度递减。
//
// 每个元素最多入栈一次、出栈一次 → 总操作 ≤ 2n → O(n)。
//
// 【单调栈处理过程】
// temperatures: [73, 74, 75, 71, 69, 72, 76, 73]
// 索引:          0   1   2   3   4   5   6   7
//
// i=0: 栈空，0入栈              栈=[0(73)]
// i=1: 74>73，弹0 ans[0]=1     栈=[] → 1入栈 → 栈=[1(74)]
// i=2: 75>74，弹1 ans[1]=1     栈=[] → 2入栈 → 栈=[2(75)]
// i=3: 71<75，3入栈            栈=[2(75), 3(71)]
// i=4: 69<71，4入栈            栈=[2(75), 3(71), 4(69)]
// i=5: 72>69，弹4 ans[4]=1
//      72>71，弹3 ans[3]=2
//      72<75，停。5入栈         栈=[2(75), 5(72)]
// i=6: 76>72，弹5 ans[5]=1
//      76>75，弹2 ans[2]=4
//      栈空。6入栈              栈=[6(76)]
// i=7: 73<76，7入栈            栈=[6(76), 7(73)]
//
// 遍历结束，栈中 [6,7] 保持 ans=0
// 结果: [1, 1, 4, 2, 1, 1, 0, 0] ✓
// ============================================================
class Solution2 {
public:
    vector<int> dailyTemperatures(vector<int>& temperatures) {
        int n = temperatures.size();
        vector<int> answer(n, 0);
        stack<int> stk;  // 存索引（不是温度值！需要索引来算距离）

        for (int i = 0; i < n; i++) {
            // 当前温度比栈顶高 → 栈顶那天找到了"下一个更高温度"
            // 注意：是严格大于(>)，不是 >=，因为相等不算"更高"
            while (!stk.empty() && temperatures[i] > temperatures[stk.top()]) {
                int prevDay = stk.top();
                stk.pop();
                answer[prevDay] = i - prevDay;
            }
            // 当前天入栈，等待未来某个更高温度来结算它
            stk.push(i);
        }
        // 栈中剩余的天右边没有更高温度，answer 初始化就是 0，无需额外处理
        return answer;
    }
};

// ============================================================
// 解法3: 反向遍历 + 跳跃 — 利用已计算的 answer 跳过无效区间
// 时间: O(n) 均摊  空间: O(1)（不计输出数组）
//
// 【思路】
// 从右往左遍历。对于第 i 天，先看 i+1：
// - 如果 temperatures[i+1] > temperatures[i]，直接 answer[i] = 1
// - 否则，i+1 的答案 answer[i+1] 告诉我们：
//   从 i+1 到 i+1+answer[i+1]-1 这段区间内，没有比 temperatures[i+1] 更高的
//   既然 temperatures[i+1] <= temperatures[i]，这段也不可能比 i 高
//   所以直接跳到 j = i+1+answer[i+1] 继续检查
// - 如果 answer[j] == 0，说明 j 右边没有更高的了，i 也找不到，answer[i] = 0
//
// 【跳跃过程示例】
// temperatures: [73, 74, 75, 71, 69, 72, 76, 73]
// 从右往左:
// i=7: 最后一天，answer[7]=0
// i=6: 73<76? 不是，answer[7]=0 → 右边没更高的 → answer[6]=0
// i=5: j=6, 76>72 ✓ → answer[5]=6-5=1
// i=4: j=5, 72>69 ✓ → answer[4]=5-4=1
// i=3: j=4, 69>71? 不是 → j+=answer[4]=1 → j=5, 72>71 ✓ → answer[3]=5-3=2
// i=2: j=3, 71>75? 不是 → j+=answer[3]=2 → j=5, 72>75? 不是 → j+=answer[5]=1 → j=6, 76>75 ✓ → answer[2]=6-2=4
// i=1: j=2, 75>74 ✓ → answer[1]=2-1=1
// i=0: j=1, 74>73 ✓ → answer[0]=1-0=1
// ============================================================
class Solution3 {
public:
    vector<int> dailyTemperatures(vector<int>& temperatures) {
        int n = temperatures.size();
        vector<int> answer(n, 0);

        for (int i = n - 2; i >= 0; i--) {
            int j = i + 1;
            while (j < n) {
                if (temperatures[j] > temperatures[i]) {
                    // 找到了右边第一个更高温度
                    answer[i] = j - i;
                    break;
                } else if (answer[j] == 0) {
                    // j 右边没有更高温度了，那 i 也找不到
                    // （因为 temperatures[j] <= temperatures[i]，
                    //  j 右边连比 j 高的都没有，更不可能比 i 高）
                    answer[i] = 0;
                    break;
                } else {
                    // 跳跃：j 到 j+answer[j]-1 这段没有比 j 高的
                    // 既然 temperatures[j] <= temperatures[i]，
                    // 这段也不可能比 i 高，直接跳到 j+answer[j]
                    j += answer[j];
                }
            }
        }
        return answer;
    }
};

// ============================================================
// 【解法对比】
//
// |          | 暴力双循环 | 单调栈 ⭐    | 反向跳跃    |
// |----------|-----------|-------------|------------|
// | 时间      | O(n²)     | O(n)        | O(n) 均摊  |
// | 空间      | O(1)      | O(n)        | O(1)       |
// | 直觉性    | ★★★       | ★★☆         | ★☆☆        |
// | 面试推荐  | 说明理解   | 首选写出     | 追问时提及  |
//
// 暴力 → 单调栈：从"独立扫描"到"批量结算"，核心是用栈维护等待者。
// 单调栈 vs 反向跳跃：正向思维 vs 反向思维，单调栈更通用更直观。
//
// ============================================================
// 【易错点】
//
// 1. 栈里存值而不是存索引：
//    ✗ stk.push(temperatures[i])  → 无法计算距离 i - prevDay
//    ✓ stk.push(i)  → 温度通过 temperatures[stk.top()] 获取
//
// 2. 比较条件用 >= 而不是 >：
//    ✗ temperatures[i] >= temperatures[stk.top()]
//      → 相等温度会被错误结算（"更高"要求严格大于）
//    ✓ temperatures[i] > temperatures[stk.top()]
//
// 3. answer 初始化不是 0：
//    ✗ vector<int> answer(n)  (未指定初值，不同编译器行为不同)
//    ✓ vector<int> answer(n, 0)  → 栈中剩余元素天然得到 0
//
// 4. 反向跳跃法漏判 answer[j]==0：
//    ✗ 没有 answer[j]==0 的分支 → j += 0 导致死循环
//    ✓ answer[j]==0 时直接 break，因为 j 右边没有更高温度
//
// ============================================================
// 【面试追问】
//
// Q1（基础理解）: 暴力法的瓶颈在哪？单调栈凭什么 O(n)？
// → 暴力法每个元素独立扫描 O(n²)。单调栈中每个元素最多入栈/出栈
//   各一次，总操作 ≤ 2n，这是均摊分析，不看嵌套层数。
//
// Q2（变体）: 如果要找右边第一个"更低"温度呢？
// → 改成单调递增栈（栈底到栈顶递增）。
//   while 条件改为 temperatures[i] < temperatures[stk.top()]。
//   模板完全相同，只是比较方向反了。
//
// Q3（空间优化）: 能否 O(1) 额外空间？
// → 可以，用反向遍历+跳跃法（解法3），利用 answer 数组本身
//   做跳跃，不需要栈。代价是思路不如单调栈直观。
//
// Q4（扩展）: 如果温度数组是循环的（首尾相连），怎么处理？
// → 参考 LC 503 "下一个更大元素 II"，遍历两遍（i 从 0 到 2n-1，
//   取 i%n 做索引），单调栈模板不变。
// ============================================================
