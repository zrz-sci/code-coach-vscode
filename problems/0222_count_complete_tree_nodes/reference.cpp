/*
 * LeetCode 222: 完全二叉树的节点个数 (Count Complete Tree Nodes)
 *
 * 【题目本质】
 * 利用"完全二叉树"的结构特性，把节点计数从 O(n) 优化到 O(log²n)。
 * 核心：完全二叉树的子树中必有满二叉树，满二叉树可以公式直接算。
 *
 * 【解法总览】
 * 解法1: 暴力递归 — O(n) / O(log n) — 最直觉，不利用完全二叉树性质
 * 解法2: 暴力迭代(BFS) — O(n) / O(n) — 迭代版本
 * 解法3: 满子树判断递归 — O(log²n) / O(log n) — 面试首选 ⭐
 * 解法4: 二分查找+位运算 — O(log²n) / O(1) — 进阶，空间最优
 */


// ============================================================
// 解法1: 暴力递归 — 遍历所有节点
// 时间: O(n)  空间: O(log n) 递归栈深度
//
// 【思路】
// 最简单的想法：把每个节点都访问一遍，每访问一个就 +1。
// 递归公式：count(root) = 1 + count(left) + count(right)
// 这个方法对任何二叉树都适用，完全没利用"完全二叉树"的性质。
//
//         1           count(1) = 1 + count(2) + count(3)
//        / \                    = 1 + 3 + 2 = 6
//       2   3         count(2) = 1 + count(4) + count(5) = 1 + 1 + 1 = 3
//      / \ /          count(3) = 1 + count(6) + count(null) = 1 + 1 + 0 = 2
//     4  5 6          count(4) = 1, count(5) = 1, count(6) = 1
// ============================================================
class Solution1 {
public:
    int countNodes(TreeNode* root) {
        if (!root) return 0;
        return 1 + countNodes(root->left) + countNodes(root->right);
    }
};

// ============================================================
// 解法2: 暴力迭代(BFS) — 层序遍历计数
// 时间: O(n)  空间: O(n) 队列最大存一层的宽度
//
// 【思路】
// 用队列做 BFS，每弹出一个节点就 +1。
// 同样没利用完全二叉树性质，但展示了迭代思路。
//
//  BFS 遍历过程:
//  Queue: [1]          count=0
//  弹出1, 入2,3        count=1, Queue: [2,3]
//  弹出2, 入4,5        count=2, Queue: [3,4,5]
//  弹出3, 入6          count=3, Queue: [4,5,6]
//  弹出4               count=4, Queue: [5,6]
//  弹出5               count=5, Queue: [6]
//  弹出6               count=6, Queue: []  → 返回 6
// ============================================================
class Solution2 {
public:
    int countNodes(TreeNode* root) {
        if (!root) return 0;
        int count = 0;
        // 需要 #include <queue>
        // 这里为了教学目的写出完整逻辑
        // 实际提交时确保包含头文件
        queue<TreeNode*> q;
        q.push(root);
        while (!q.empty()) {
            TreeNode* node = q.front();
            q.pop();
            count++;
            if (node->left) q.push(node->left);
            if (node->right) q.push(node->right);
        }
        return count;
    }
};

// ============================================================
// 解法3: 满子树判断 — 利用完全二叉树性质 ⭐ 面试首选
// 时间: O(log²n)  空间: O(log n) 递归栈
//
// 【思路】
// 暴力解的瓶颈：每个节点都要访问一遍。
// 突破口：完全二叉树的子树中，必有至少一个是满二叉树。
// 满二叉树节点数 = 2^h - 1，直接公式计算，不用遍历。
//
// 怎么判断满二叉树？
// - 从根沿最左路径到底 = leftDepth
// - 从根沿最右路径到底 = rightDepth
// - leftDepth == rightDepth → 满二叉树!
//
// 为什么 O(log²n)？
// - 每次递归，左右子树至少一个是满的（直接返回公式），只递归另一侧
// - 递归深度 = O(log n)，每次算高度 = O(log n)
//
//  递归过程:
//         1            leftD=3, rightD=2 → 不等，递归两侧
//        / \
//       2   3
//      / \ /
//     4  5 6
//
//  左子树根=2:          右子树根=3:
//       2                  3
//      / \                /
//     4   5              6
//  leftD=2, rightD=2    leftD=2, rightD=1
//  相等! 满二叉树!       不等，继续递归
//  返回 2^2 - 1 = 3
//                       左子树根=6:    右子树=null:
//                          6            返回 0
//                       leftD=1, rightD=1
//                       相等! 返回 2^1 - 1 = 1
//
//                       节点3 = 1 + 1 + 0 = 2
//
//  总计: 1 + 3 + 2 = 6  ✓
// ============================================================
class Solution3 {
public:
    int countNodes(TreeNode* root) {
        if (!root) return 0;
        
        // 沿最左路径计算深度（节点数）
        int leftDepth = 0;
        TreeNode* left = root;
        while (left) {
            leftDepth++;
            left = left->left;
        }
        
        // 沿最右路径计算深度（节点数）
        int rightDepth = 0;
        TreeNode* right = root;
        while (right) {
            rightDepth++;
            right = right->right;
        }
        
        // 左右深度相同 → 满二叉树，直接用公式
        // 注意括号！(1 << leftDepth) 必须括起来，否则运算优先级出错
        if (leftDepth == rightDepth) {
            return (1 << leftDepth) - 1;
        }
        
        // 不是满二叉树，递归左右子树
        // 由完全二叉树性质保证：左右子树中至少一个会命中上面的满二叉树分支
        return 1 + countNodes(root->left) + countNodes(root->right);
    }
};

// ============================================================
// 解法4: 二分查找 + 位运算 — 进阶解法
// 时间: O(log²n)  空间: O(1)
//
// 【思路】
// 换个角度：先算高度 h（沿最左走到底），前 h-1 层是满的(2^h - 1 个节点)。
// 问题变成：最后一层有几个节点？
// 最后一层位置编号 0 ~ 2^h-1，从左到右连续填充。
// 用二分查找找到最后一个存在的节点位置。
//
// 关键技巧：怎么判断编号 idx 的节点是否存在？
// 用 idx 的二进制表示从高位到低位导航：0=左，1=右
//
//         1           h=2 (根是第0层，最后一层是第2层)
//        / \          最后一层位置: 0(=00₂), 1(=01₂), 2(=10₂), 3(=11₂)
//       2   3
//      / \ /
//     4  5 6          实际: 位置0,1,2存在; 位置3不存在
//
//  判断位置2(二进制10)是否存在:
//  第1位=1 → 往右(到节点3)
//  第0位=0 → 往左(到节点6) → 存在! ✓
//
//  判断位置3(二进制11)是否存在:
//  第1位=1 → 往右(到节点3)
//  第0位=1 → 往右(null) → 不存在! ✗
//
//  二分过程: lo=0, hi=3
//  Round1: mid=1, exists(1=01₂)? 根→左→右=节点5 ✓ → lo=2
//  Round2: mid=2, exists(2=10₂)? 根→右→左=节点6 ✓ → lo=3
//  Round3: mid=3, exists(3=11₂)? 根→右→右=null ✗ → hi=2
//  lo=3 > hi=2, 退出. 最后一层有 lo=3 个节点
//  总计 = (2^2 - 1) + 3 = 3 + 3 = 6  ✓
// ============================================================
class Solution4 {
public:
    int countNodes(TreeNode* root) {
        if (!root) return 0;
        
        // 计算高度 h（从0开始，根是第0层）
        int h = 0;
        TreeNode* node = root;
        while (node->left) {
            h++;
            node = node->left;
        }
        
        // 只有根节点
        if (h == 0) return 1;
        
        // 最后一层编号范围 [0, 2^h - 1]
        int lo = 0, hi = (1 << h) - 1;
        
        while (lo <= hi) {
            int mid = lo + (hi - lo) / 2;
            if (exists(root, h, mid)) {
                lo = mid + 1;   // mid 存在，最后节点可能更靠右
            } else {
                hi = mid - 1;   // mid 不存在，最后节点在左边
            }
        }
        
        // 前 h 层满的节点数 + 最后一层节点数 lo
        return (1 << h) - 1 + lo;
    }
    
private:
    // 判断最后一层编号 idx 的节点是否存在
    // idx 用 h 位二进制表示，从高到低每一位决定走左(0)还是走右(1)
    bool exists(TreeNode* root, int h, int idx) {
        TreeNode* node = root;
        for (int i = h - 1; i >= 0; i--) {
            if ((idx >> i) & 1) {
                node = node->right;  // 该位为1，走右
            } else {
                node = node->left;   // 该位为0，走左
            }
            if (!node) return false; // 中途遇到 null，不存在
        }
        return true;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法           | 时间       | 空间      | 利用完全二叉树 | 推荐场景   |
// |----------------|-----------|-----------|---------------|-----------|
// | 暴力递归       | O(n)      | O(log n)  | ❌            | 起点/热身  |
// | 暴力BFS        | O(n)      | O(n)      | ❌            | 迭代版     |
// | 满子树判断     | O(log²n)  | O(log n)  | ✅            | 面试首选⭐ |
// | 二分+位运算    | O(log²n)  | O(1)      | ✅            | 进阶追问   |
//
// 解法3 vs 解法4:
// - 解法3 更直觉，递归判断子树是否为满二叉树，代码简洁
// - 解法4 是完全不同的思路（把问题转化为在最后一层二分查找），
//   空间 O(1) 但代码更复杂，适合面试追问"能否不用递归"时展示
//
// 【易错点】
// 1. 位运算优先级：
//    ✗ return 1 << leftDepth - 1;    // 实际是 1 << (leftDepth-1)
//    ✓ return (1 << leftDepth) - 1;  // 必须加括号
//
// 2. 深度定义不统一：
//    如果 leftDepth 数的是"节点数"(根到叶经过几个节点)，公式是 2^d - 1
//    如果数的是"边数"(根到叶经过几条边)，公式是 2^(d+1) - 1
//    ✗ 混用两种定义导致答案差 1 或差一倍
//
// 3. 解法4中遗漏 h==0 的特判：
//    ✗ 直接进入二分，h=0 时 (1<<0)-1=0，lo=0,hi=-1 循环不执行
//       返回 0+0=0，但正确答案是 1
//    ✓ if (h == 0) return 1; 单独处理
//
// 4. 解法4中位运算位数错误：
//    ✗ for (int i = h; i >= 0; i--)  → 多走一步，从"根的上面"开始
//    ✓ for (int i = h - 1; i >= 0; i--)  → 从根的下一层开始导航
//
// 【面试追问】
// Q1(基础): 暴力解是 O(n)，完全二叉树有什么特殊的可以利用？
//    → 子树中必有满二叉树，满二叉树节点数可以公式算，不用遍历。
//
// Q2(分析): 解法3 为什么是 O(log²n)？为什么不是 O(n)？
//    → 每次递归只递归一侧(另一侧是满的直接返回)，递归深度 O(log n)，
//      每次算高度 O(log n)，总计 O(log n × log n) = O(log²n)。
//
// Q3(优化): 能否做到 O(1) 空间？
//    → 用二分查找+位运算(解法4)。先算高度，在最后一层二分查找，
//      用位运算解码路径判断节点是否存在。迭代实现，O(1)空间。
//
// Q4(变体): 如果不是完全二叉树，能否优于 O(n)？
//    → 不能。任意二叉树没有结构保证，每个位置都可能有或没有节点，
//      必须全部访问一遍。O(log²n) 的优化完全依赖完全二叉树的结构。
// ============================================================
