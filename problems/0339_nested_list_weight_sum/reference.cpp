/*
 * LeetCode 339: Nested List Weight Sum (嵌套列表加权和)
 *
 * 【题目本质】
 * 嵌套列表是一棵多叉树，求所有叶子节点(整数)的 值×深度 之和。
 *
 * 【解法总览】
 * 解法1: DFS 递归 — O(N) / O(D) — 最自然，面试首选
 * 解法2: BFS 层序 — O(N) / O(N) — 迭代方式，作为 follow-up
 *
 * 其中 N = 所有元素总数，D = 最大嵌套深度
 */

// ============================================================
// NestedInteger 接口说明（题目已提供，此处仅作参考）:
//   bool isInteger() const;            // 是否为整数
//   int getInteger() const;            // 获取整数值（当 isInteger() 为 true）
//   const vector<NestedInteger> &getList() const; // 获取列表（当 isInteger() 为 false）
// ============================================================

// ============================================================
// 解法1: DFS 递归 — 递归遍历嵌套结构，传递深度参数
// 时间: O(N)  空间: O(D)
//
// 【思路】
// 嵌套列表天然是递归定义的，用递归处理最直觉。
// 对于每个元素:
//   - 如果是整数 → 贡献 = 值 × 当前深度
//   - 如果是列表 → 递归处理子列表，深度 + 1
//
// 把嵌套列表看成一棵多叉树:
//
//   示例: [[1,1], 2, [1,1]]
//
//          root (depth=1)
//         /   |   \
//       [ ]   2   [ ]         ← 2 在 depth=1, 贡献 2×1=2
//       / \       / \
//      1   1     1   1        ← 每个 1 在 depth=2, 贡献 1×2=2
//
//   总和 = 2 + 2 + 2 + 2 + 2 = 10
//
//   示例: [1, [4, [6]]]
//
//          root (depth=1)
//          / \
//         1  [ ]              ← 1 在 depth=1, 贡献 1×1=1
//            / \
//           4  [ ]            ← 4 在 depth=2, 贡献 4×2=8
//              |
//              6              ← 6 在 depth=3, 贡献 6×3=18
//
//   总和 = 1 + 8 + 18 = 27
// ============================================================
class Solution1 {
public:
    int depthSum(vector<NestedInteger>& nestedList) {
        // 最外层元素的深度是 1（不是 0！）
        return dfs(nestedList, 1);
    }
    
private:
    int dfs(const vector<NestedInteger>& list, int depth) {
        int sum = 0;
        for (const auto& ni : list) {
            if (ni.isInteger()) {
                // 整数：值 × 当前深度，累加到结果
                sum += ni.getInteger() * depth;
            } else {
                // 列表：递归进入子列表，深度 + 1
                // 注意必须用 sum += 接收返回值，否则子树结果丢失
                sum += dfs(ni.getList(), depth + 1);
            }
        }
        return sum;
    }
};

// ============================================================
// 解法2: BFS 层序遍历 — 用队列逐层处理，每层 depth+1
// 时间: O(N)  空间: O(N)
//
// 【思路】
// DFS 用递归栈隐式追踪深度，BFS 用队列显式逐层处理。
// 队列中存 NestedInteger 对象：
//   - 如果是整数 → 值 × 当前层深度，累加
//   - 如果是列表 → 把子元素全部入队（属于下一层）
// 每处理完一层，depth++。
//
// BFS 过程 (示例: [[1,1], 2, [1,1]]):
//
//   初始队列: [ [1,1], 2, [1,1] ]    depth=1
//     → 2 是整数: sum += 2×1 = 2
//     → [1,1] 是列表: 展开 → 1, 1 入队
//     → [1,1] 是列表: 展开 → 1, 1 入队
//
//   队列: [ 1, 1, 1, 1 ]             depth=2
//     → sum += 1×2 + 1×2 + 1×2 + 1×2 = 8
//
//   总和 = 2 + 8 = 10 ✓
// ============================================================
class Solution2 {
public:
    int depthSum(vector<NestedInteger>& nestedList) {
        int sum = 0;
        int depth = 1;
        queue<NestedInteger> q;
        
        // 最外层所有元素入队
        for (auto& ni : nestedList) {
            q.push(ni);
        }
        
        while (!q.empty()) {
            // 用 size 锁定当前层的元素数量
            // 这样在循环中入队的新元素属于下一层，不会混淆
            int size = q.size();
            for (int i = 0; i < size; i++) {
                NestedInteger curr = q.front();
                q.pop();
                
                if (curr.isInteger()) {
                    // 整数：值 × 当前层深度
                    sum += curr.getInteger() * depth;
                } else {
                    // 列表：把子元素全部入队到下一层
                    for (auto& child : curr.getList()) {
                        q.push(child);
                    }
                }
            }
            // 当前层处理完毕，深度 +1
            depth++;
        }
        return sum;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度     | DFS 递归       | BFS 层序       |
// |----------|---------------|----------------|
// | 时间     | O(N)          | O(N)           |
// | 空间     | O(D) 递归栈    | O(N) 队列      |
// | 代码量   | 更短更简洁      | 稍长            |
// | 思维方式 | 深度优先，递归   | 广度优先，逐层   |
// | 面试推荐 | ⭐ 首选        | follow-up      |
//
// D = 最大嵌套深度 (≤50)，通常 D << N
// 默认写 DFS；面试官追问"不用递归"时切换 BFS
//
// ============================================================
// 【易错点】
//
// 1. 初始深度写成 0:
//    ✗ dfs(nestedList, 0)  → 最外层整数贡献为 0，答案偏小
//    ✓ dfs(nestedList, 1)  → 题目定义最外层深度为 1
//
// 2. BFS 忘记用 size 锁定当前层:
//    ✗ 直接 while (!q.empty()) 逐个处理，每次 pop 后就 depth++
//      → 同一层的元素被分配了不同的 depth
//    ✓ int size = q.size(); for (int i = 0; i < size; i++) 处理完一层后 depth++
//
// 3. 对列表元素调用 getInteger():
//    ✗ 不判断 isInteger() 就调用 getInteger() → 行为未定义
//    ✓ 先 if (ni.isInteger()) 再调用
//
// 4. DFS 中忘记累加返回值:
//    ✗ dfs(ni.getList(), depth + 1);         // 返回值被丢弃！
//    ✓ sum += dfs(ni.getList(), depth + 1);  // 必须累加
//
// ============================================================
// 【面试追问】
//
// Q1 (基础): "时间和空间复杂度是多少？DFS 和 BFS 各自的空间消耗区别？"
//    → 时间都 O(N)。DFS 空间 O(D) 取决于嵌套深度（递归栈），
//      BFS 空间 O(N) 取决于队列中最大元素数（某层很宽时）。
//      一般嵌套结构"深窄"时 DFS 优，"浅宽"时两者差不多。
//
// Q2 (变体): "如果改成反向加权——最深层权重为 1，最浅层权重最大——怎么做？"
//    → LeetCode 364。两种方法:
//      (1) 先遍历一次求 maxDepth，再遍历用 (maxDepth - depth + 1) 作为权重
//      (2) BFS 逐层，维护一个 unweightedSum，每层把之前累积的 unweightedSum
//          再加一次到 weightedSum（深层的值被"重复加"了更多次）
//
// Q3 (拓展): "如果输入是字符串形式 '[1,[4,[6]]]'，怎么解析并计算？"
//    → 用栈模拟：遇到 '[' 压入新列表，遇到数字解析整数，
//      遇到 ']' 弹出栈顶列表合并到上一层。解析完后用同样的 DFS 求解。
//      这考察字符串解析 + 栈的综合能力。
// ============================================================
