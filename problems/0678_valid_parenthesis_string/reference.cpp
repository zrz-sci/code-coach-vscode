/*
 * LeetCode 678: Valid Parenthesis String (有效的括号字符串)
 *
 * 【题目本质】
 * 在 * 可以变成 (、) 或空字符串的情况下，判断是否存在一种分配方案
 * 使得括号序列合法。核心是处理 * 带来的"不确定性"。
 *
 * 【解法总览】
 * 解法1: 动态规划       — O(n²) / O(n)  — 最通用，标准状态转移
 * 解法2: 贪心(区间追踪) — O(n)  / O(1)  — 最优，面试首选
 * 解法3: 双栈法         — O(n)  / O(n)  — 直觉好理解的栈方案
 */

// ============================================================
// 解法1: 动态规划 — dp[j] 表示当前未匹配左括号数为 j 是否可达
// 时间: O(n²)  空间: O(n)  (滚动数组优化后)
//
// 【思路】
// 没有 * 时，遍历过程中"未匹配左括号数量"是确定值。
// 有 * 后，每个 * 使数量分叉成3种可能。
// 用布尔数组 dp[j] 追踪所有可达的左括号余量。
//
// 为什么想到 DP？因为暴力枚举 3^k 种 * 的组合太多，
// 但很多组合导致相同的"左括号余量"，DP 去重后状态数只有 O(n)。
//
// DP 填表过程示例 (s = "(*)"):
//   字符     dp (true的位置)     含义
//   初始     [T F F F]          余量=0可达
//   '('      [F T F F]          余量=1可达 (必须+1)
//   '*'      [T T T F]          余量=0,1,2可达 (*当), 空, ()
//   ')'      [T T F F]          余量=0,1可达 (各-1)
//   最终 dp[0]=true → 合法 ✓
// ============================================================
class Solution1 {
public:
    bool checkValidString(string s) {
        int n = s.size();
        // dp[j] = 处理到当前字符后，未匹配左括号数为 j 是否可能
        vector<bool> dp(n + 1, false);
        dp[0] = true; // 初始只有余量=0可达

        for (char c : s) {
            vector<bool> ndp(n + 1, false);
            for (int j = 0; j <= n; j++) {
                if (!dp[j]) continue;
                if (c == '(') {
                    // ( 必然使余量 +1
                    if (j + 1 <= n) ndp[j + 1] = true;
                } else if (c == ')') {
                    // ) 必然使余量 -1，但 j 需要 >= 1
                    if (j >= 1) ndp[j - 1] = true;
                } else {
                    // * 有三种选择
                    ndp[j] = true;                       // 当空串
                    if (j + 1 <= n) ndp[j + 1] = true;  // 当 (
                    if (j >= 1) ndp[j - 1] = true;       // 当 )
                }
            }
            dp = ndp;
        }

        return dp[0];
    }
};

// ============================================================
// 解法2: 贪心(区间追踪) — 维护未匹配左括号数的可能范围 [lo, hi]
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1 的瓶颈：每个字符都要遍历整个 dp 数组 → O(n²)。
//
// 关键观察：dp[j] 为 true 的 j 值总是构成一个连续区间 [lo, hi]。
// 证明：若 j 和 j+2 都可达，把某个 * 的选择"降一级"即可得到 j+1。
//
// 所以不需要布尔数组，两个变量足够追踪整个区间！
//
// 模拟 s = "(*))" 的过程:
//
//  字符    lo    hi    操作说明
//  ────────────────────────────────────
//  初始     0     0
//   '('     1     1    都+1
//   '*'     0     2    lo-1(当)), hi+1(当()
//   ')'     0     1    lo: max(-1,0)=0, hi: 2-1=1
//   ')'     0     0    lo: max(-1,0)=0, hi: 1-1=0
//  ────────────────────────────────────
//  最终 lo == 0 → true ✓
//  对应方案: ( 当(, * 当(, 两个 ) 分别匹配 → "(())"
// ============================================================
class Solution2 {
public:
    bool checkValidString(string s) {
        int lo = 0, hi = 0;
        // lo: 未匹配左括号数的最小可能值（尽量让 * 当 ) 来消耗）
        // hi: 未匹配左括号数的最大可能值（尽量让 * 当 ( 来积攒）

        for (char c : s) {
            if (c == '(') {
                lo++;
                hi++;
            } else if (c == ')') {
                lo--;
                hi--;
            } else { // '*'
                lo--;  // * 当 ): 消耗一个左括号
                hi++;  // * 当 (: 增加一个未匹配左括号
            }

            // hi < 0: 即使所有 * 都当 (，右括号仍然多了 → 无解
            if (hi < 0) return false;

            // lo 不能为负: 未匹配左括号数不可能为负数
            // 负了意味着我们"过度消耗"，但实际上那些 * 可以当空串
            lo = max(lo, 0);
        }

        // 0 在 [lo, hi] 中 ⟺ lo <= 0
        // 而 lo 始终 >= 0（因为有修正），所以等价于 lo == 0
        return lo == 0;
    }
};

// ============================================================
// 解法3: 双栈法 — 分别记录 ( 和 * 的索引
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 从栈匹配括号的经典思路出发。
// 遇到 ) 时，优先弹 ( 栈匹配；没有 ( 就弹 * 栈（让 * 当 (）。
// 遍历完后，剩余的 ( 需要被其右边的 * 匹配（让 * 当 )）。
//
// 关键：位置关系！( 必须在 * 左边，* 才能当 ) 来匹配它。
//
// 示例 s = "*(":
//   i=0, '*': starStack = [0]
//   i=1, '(': leftStack = [1]
//   遍历完: leftStack=[1], starStack=[0]
//   leftStack.top()=1 > starStack.top()=0
//   → ( 在 * 右边，* 无法当 ) 匹配它 → false ✓
// ============================================================
class Solution3 {
public:
    bool checkValidString(string s) {
        stack<int> leftStack;  // 存 '(' 的索引
        stack<int> starStack;  // 存 '*' 的索引

        for (int i = 0; i < (int)s.size(); i++) {
            if (s[i] == '(') {
                leftStack.push(i);
            } else if (s[i] == '*') {
                starStack.push(i);
            } else { // ')'
                // 优先匹配 ( — 因为 * 更灵活，留给后面用
                if (!leftStack.empty()) {
                    leftStack.pop();
                } else if (!starStack.empty()) {
                    starStack.pop(); // 用 * 当 (
                } else {
                    return false; // 没有任何东西能匹配这个 )
                }
            }
        }

        // 剩余的 ( 需要被右边的 * 匹配
        while (!leftStack.empty() && !starStack.empty()) {
            // ( 的索引必须 < * 的索引，* 才能出现在 ( 右边当 )
            if (leftStack.top() > starStack.top()) {
                return false;
            }
            leftStack.pop();
            starStack.pop();
        }

        // 如果还有剩余 (，说明无法全部匹配
        return leftStack.empty();
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间   | 空间  | 核心思想                           |
// |-------------|--------|-------|-----------------------------------|
// | DP          | O(n²)  | O(n)  | 追踪所有可达的左括号余量            |
// | 贪心        | O(n)   | O(1)  | 可达余量是连续区间，只追踪边界      |
// | 双栈        | O(n)   | O(n)  | 索引栈 + 位置约束                  |
//
// 面试推荐：解法2（贪心）。代码最短，复杂度最优。
// 如果面试官追问证明，用 DP 的"连续区间"性质解释。
// 双栈法作为不同视角的补充。
//
// ============================================================
// 【易错点】
//
// 1. 贪心解法忘记 lo = max(lo, 0)
//    ✗ lo--; 直接不管 → lo 可能变成 -5，最后 lo != 0 返回 false
//      但实际上 "(***)" 是合法的
//    ✓ lo = max(lo - 1, 0); 或 lo--; lo = max(lo, 0);
//
// 2. 贪心只检查 hi >= 0 忘记检查 lo == 0
//    ✗ return hi >= 0;  → 对 "(" 返回 true（hi=1>=0），但 "(" 不合法
//    ✓ return lo == 0;
//
// 3. 双栈法忘记比较索引
//    ✗ return leftStack.size() <= starStack.size();
//      → 对 "*(" 返回 true（有1个*和1个(），但 * 在 ( 左边无法匹配
//    ✓ 必须逐个比较 leftStack.top() < starStack.top()
//
// 4. DP 中 j-1 越界
//    ✗ 直接 ndp[j-1] = true 不检查 j >= 1
//    ✓ if (j >= 1) ndp[j - 1] = true;
//
// ============================================================
// 【面试追问】
//
// Q1: 没有 * 怎么判断括号合法？
//    → 计数器 count: 遇( +1, 遇) -1，任何时刻 <0 则 false，
//      最终 ==0 则 true。O(n)/O(1)。
//
// Q2: 有 * 后暴力 3^k 太慢，怎么优化？
//    → 关键观察：只关心"未匹配左括号数量"，不关心具体哪些 * 选了什么。
//      DP 将状态压缩为 O(n)；进一步观察可达值是连续区间，贪心压缩为 O(1)。
//
// Q3: 怎么证明"可达值是连续区间"？
//    → 若余量 j 和 j+2 都可达，在达到 j+2 的方案中必有某个 * 贡献了 +1
//      （被当作 ( 或空串）。将它"降一级"（( → 空串，或 空串 → )）
//      就得到余量 j+1 的方案。归纳可得整个区间连续。
//
// Q4: 如果 * 只能当 ( 或 )，不能当空串呢？
//    → 区间仍然连续，但每遇到 * 时 lo 和 hi 的变化都是 ±1（没有不变选项）。
//      需要额外注意奇偶性：如果字符串长度是奇数，直接返回 false。
// ============================================================
