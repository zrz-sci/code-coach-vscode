/*
 * LeetCode 680: 验证回文串 II (Valid Palindrome II)
 *
 * 【题目本质】
 * 一个字符串最多删除一个字符后能否成为回文串。
 * 核心洞察：双指针从两端收缩，遇到不匹配时只需尝试"删左"或"删右"两种情况。
 *
 * 【解法总览】
 * 解法1: 暴力枚举     — O(n²) / O(n) — 枚举删除每个位置，逐一判断
 * 解法2: 双指针贪心   — O(n) / O(1)  — 两端收缩，不匹配时分支尝试 ⭐ 面试首选
 */

// ============================================================
// 解法1: 暴力枚举 — 枚举删除每个位置，判断是否回文
// 时间: O(n²)  空间: O(n) (substr 创建新字符串)
//
// 【思路】
// 最直觉的方法：既然可以删一个字符，那就枚举删除每个位置（包括不删），
// 对每种情况判断是否回文。
//
// 为什么这样想？因为"最多删一个"意味着最多 n+1 种情况（不删 + 删每个位置），
// 每种判断 O(n)，总共 O(n²)。
//
// 瓶颈：对 n=10⁵ 可能超时，且大部分位置根本不需要尝试删除。
// ============================================================
class Solution1 {
public:
    bool validPalindrome(string s) {
        int n = s.size();
        // 先检查不删的情况
        if (isPalin(s, 0, n - 1)) return true;
        // 枚举删除第 i 个字符
        for (int i = 0; i < n; i++) {
            string t = s.substr(0, i) + s.substr(i + 1);
            if (isPalin(t, 0, (int)t.size() - 1)) return true;
        }
        return false;
    }

private:
    bool isPalin(const string& s, int left, int right) {
        while (left < right) {
            if (s[left] != s[right]) return false;
            left++;
            right--;
        }
        return true;
    }
};

// ============================================================
// 解法2: 双指针贪心 — 两端收缩，不匹配时尝试删左/删右
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1的瓶颈是"盲目枚举删除位置"。
// 
// 关键观察：双指针从两端向中间走——
//   - s[left] == s[right] 时，这对字符满足回文要求，一定不需要删它们
//   - s[left] != s[right] 时，必须删除其中一个来"修复"不匹配
//     → 删左边: 检查 s[left+1 .. right] 是否回文
//     → 删右边: 检查 s[left .. right-1] 是否回文
//     → 任一成功即可
//
// 为什么只需要在第一个不匹配处分支？
// 因为题目限制"最多删一个"，第一次不匹配用掉了唯一的删除机会，
// 之后的子串必须严格回文。
//
// 图解 (s = "abca"):
//   a b c a
//   ↑     ↑   s[0]='a' == s[3]='a' ✓ → left++, right--
//     b c
//     ↑ ↑     s[1]='b' != s[2]='c' ✗
//             → 尝试删左: s[2..2] = "c" → 单字符，回文 ✓ → return true
//             → (短路，不需要尝试删右)
//
// 图解 (s = "abc"):
//   a b c
//   ↑   ↑     s[0]='a' != s[2]='c' ✗
//             → 尝试删左: s[1..2] = "bc" → b≠c → false
//             → 尝试删右: s[0..1] = "ab" → a≠b → false
//             → return false
// ============================================================
class Solution2 {
public:
    bool validPalindrome(string s) {
        int left = 0, right = (int)s.size() - 1;
        while (left < right) {
            if (s[left] != s[right]) {
                // 不匹配！尝试删左边 或 删右边
                // 这是唯一一次使用删除机会
                return isPalindrome(s, left + 1, right)
                    || isPalindrome(s, left, right - 1);
            }
            left++;
            right--;
        }
        // 全程配对成功，原串本身就是回文，不需要删除
        return true;
    }

private:
    // 严格回文判断：s[left..right] 是否是回文
    // 传引用+索引，不创建新字符串 → O(1) 空间
    bool isPalindrome(const string& s, int left, int right) {
        while (left < right) {
            if (s[left] != s[right]) return false;
            left++;
            right--;
        }
        return true;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法           | 时间   | 空间  | 核心思想                     |
// |----------------|--------|-------|------------------------------|
// | 暴力枚举       | O(n²)  | O(n)  | 枚举所有删除位置             |
// | 双指针贪心     | O(n)   | O(1)  | 只在不匹配处分支尝试         |
//
// 双指针的优势：两端相等的字符一定不需要删除（它们已满足回文对称要求），
// 只有不匹配时才需要动手，把搜索空间从 n 个位置缩小到 1 个位置。
//
// ============================================================
// 【易错点】
//
// 1. 只尝试删一边:
//    ✗ return isPalindrome(s, left+1, right);
//    ✓ return isPalindrome(s, left+1, right) || isPalindrome(s, left, right-1);
//    反例: "deeee" → left=0,right=4 → 'd'≠'e'
//          删左: "eeee" ✓  但某些情况只有删右才行
//
// 2. isPalindrome 范围写错，没跳过不匹配字符:
//    ✗ isPalindrome(s, left, right)  // 没删除任何字符
//    ✓ isPalindrome(s, left+1, right)  // 跳过 left 位置
//
// 3. 忘记处理"原串就是回文"的情况:
//    while 循环正常结束（没遇到不匹配）时应返回 true
//    如果漏了最后的 return true，会返回未定义值
//
// 4. int 转换问题:
//    s.size() 返回 size_t(unsigned)，如果 s 为空，s.size()-1 会溢出
//    用 (int)s.size() - 1 或提前判空
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1(基础): "如果不允许删除任何字符，怎么判断回文？"
// → 双指针从两端向中间走，所有对应位置相等即可。这正是本题的子函数 isPalindrome。
//
// Q2(进阶): "如果允许删除最多 k 个字符呢？"
// → 贪心不再适用（每次不匹配有两种选择，k 次不匹配会导致 2^k 分支）。
//   方法1: 递归+记忆化 solve(l, r, k)，O(n² * k)
//   方法2: 转化为最长回文子序列 LPS 问题：如果 len(s) - LPS(s) <= k 则可以，O(n²)
//
// Q3(变体): "能否返回应该删除的字符索引？"
// → 不匹配时，如果 isPalindrome(s, left+1, right) 成功则索引为 left，
//   如果 isPalindrome(s, left, right-1) 成功则索引为 right。
//   如果原串就是回文，可以返回 -1 表示不需要删除。
//
// ============================================================
