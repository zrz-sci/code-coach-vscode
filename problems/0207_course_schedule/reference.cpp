/*
 * LeetCode 207: 课程表 (Course Schedule)
 *
 * 【题目本质】
 * 有向图判环：课程是节点，先修关系是有向边。
 * 能完成所有课程 ⟺ 有向图无环 ⟺ 存在拓扑排序。
 *
 * 【解法总览】
 * 解法1: BFS 拓扑排序 (Kahn 算法) — O(V+E) / O(V+E) — 面试首选
 * 解法2: DFS 三色标记法             — O(V+E) / O(V+E) — 也要掌握
 *
 * 图示:
 *   numCourses=4, prerequisites=[[1,0],[2,0],[3,1],[3,2]]
 *
 *       0 ──→ 1
 *       |      \
 *       ↓       ↓
 *       2 ──→ 3
 *
 *   入度: 0:0  1:1  2:1  3:2
 *   拓扑排序: 0 → 1 → 2 → 3 (或 0 → 2 → 1 → 3)
 *   无环 → 返回 true
 *
 *   有环的例子: prerequisites=[[1,0],[0,1]]
 *       0 ⇄ 1   (互相依赖)
 *   入度: 0:1  1:1  → 没有入度为0的节点 → 无法开始 → 返回 false
 */

// ============================================================
// 解法1: BFS 拓扑排序 (Kahn 算法)
// 时间: O(V+E)  空间: O(V+E)
//
// 【思路】
// 核心直觉："入度为 0 = 没有前置依赖 = 可以直接学"
//
// 1. 建图 + 统计每个节点的入度
// 2. 所有入度为 0 的节点入队（可以直接学）
// 3. BFS：弹出一个节点 = "学完这门课"
//    → 它指向的所有节点入度 -1
//    → 入度变为 0 的节点入队
// 4. 如果最终学完的课程数 == 总课程数 → 无环
//
// 为什么能 work？
// 如果存在环，环上的节点入度永远无法降为 0（鸡生蛋蛋生鸡），
// 所以最终学完的课程数 < 总课程数。
//
// 过程示例:
// prerequisites=[[1,0],[2,0],[3,1],[3,2]]
//
//  初始入度: [0:0, 1:1, 2:1, 3:2]   队列: [0]
//
//  弹出 0 → 邻居 1(入度1→0,入队), 2(入度1→0,入队)
//  已学: 1,  队列: [1, 2]
//
//  弹出 1 → 邻居 3(入度2→1)
//  已学: 2,  队列: [2]
//
//  弹出 2 → 邻居 3(入度1→0,入队)
//  已学: 3,  队列: [3]
//
//  弹出 3 → 无邻居
//  已学: 4 == numCourses=4 → true
// ============================================================
class Solution1 {
public:
    bool canFinish(int numCourses, vector<vector<int>>& prerequisites) {
        vector<vector<int>> graph(numCourses);
        vector<int> indegree(numCourses, 0);

        // 建图: pre[1] → pre[0]，即"先修 pre[1] 才能学 pre[0]"
        for (auto& pre : prerequisites) {
            graph[pre[1]].push_back(pre[0]);
            indegree[pre[0]]++;  // pre[0] 多了一个前置依赖
        }

        // 入度为 0 的节点入队
        queue<int> q;
        for (int i = 0; i < numCourses; i++) {
            if (indegree[i] == 0) {
                q.push(i);
            }
        }

        int learnedCount = 0;
        while (!q.empty()) {
            int course = q.front();
            q.pop();
            learnedCount++;  // "学完"这门课

            for (int next : graph[course]) {
                indegree[next]--;
                // 前置课程全部学完，这门课可以学了
                if (indegree[next] == 0) {
                    q.push(next);
                }
            }
        }

        // 所有课程都学完 → 无环 → 可以完成
        return learnedCount == numCourses;
    }
};

// ============================================================
// 解法2: DFS 三色标记法
// 时间: O(V+E)  空间: O(V+E)
//
// 【思路】
// 换一个角度：直接检测有向图是否有环。
//
// DFS 时给每个节点标记三种颜色（状态）：
//   0（白色）= 未访问
//   1（灰色）= 正在当前 DFS 路径上（递归还没返回）
//   2（黑色）= 已处理完毕，确认从此节点出发无环
//
// 核心判断：
//   DFS 过程中遇到灰色节点 → 说明当前路径形成了环 → return true (有环)
//   遇到黑色节点 → 已确认安全，跳过
//   遇到白色节点 → 继续 DFS
//
// 为什么不能只用 visited 布尔值？
//   0 → 1 → 2
//   0 → 2
//   从 0 出发：DFS 0→1→2，标记 2 为 visited
//   回到 0，走 0→2，发现 2 已 visited → 误判为环！
//   实际上这只是两条不同路径到达同一节点，不是环。
//   三色标记中，2 在第一次 DFS 后变黑色（已完成），
//   第二次到达时看到黑色就跳过，不会误判。
//
// 过程示例 (有环):
//   0 → 1 → 2 → 0
//
//   DFS(0): 标灰 → DFS(1): 标灰 → DFS(2): 标灰
//   → 邻居 0 是灰色 → 发现环！返回 true
// ============================================================
class Solution2 {
public:
    bool canFinish(int numCourses, vector<vector<int>>& prerequisites) {
        vector<vector<int>> graph(numCourses);
        for (auto& pre : prerequisites) {
            graph[pre[1]].push_back(pre[0]);
        }

        // 0=白色(未访问), 1=灰色(访问中), 2=黑色(已完成)
        vector<int> color(numCourses, 0);

        // 可能有多个连通分量，每个未访问节点都要尝试
        for (int i = 0; i < numCourses; i++) {
            if (color[i] == 0) {
                if (hasCycle(graph, color, i)) {
                    return false;
                }
            }
        }
        return true;
    }

private:
    bool hasCycle(vector<vector<int>>& graph, vector<int>& color, int node) {
        color[node] = 1;  // 进入当前路径，标记为灰色

        for (int next : graph[node]) {
            if (color[next] == 1) {
                // 遇到灰色 = 遇到当前路径上的祖先 = 有环
                return true;
            }
            if (color[next] == 0) {
                // 白色节点，继续深入探索
                if (hasCycle(graph, color, next)) {
                    return true;  // 子树中发现环，向上传递
                }
            }
            // color[next] == 2: 黑色，已确认安全，直接跳过
        }

        // 所有邻居都探索完毕且无环 → 标记为黑色（已完成）
        // 这一行不能漏！否则同一节点被多次作为灰色处理，时间退化
        color[node] = 2;
        return false;
    }
};

// ============================================================
// 【解法对比】
//
// |          | BFS 拓扑排序 (Kahn)      | DFS 三色标记         |
// |----------|--------------------------|---------------------|
// | 核心思想 | 逐层剥离入度为0的节点    | 检测回边(灰→灰)     |
// | 数据结构 | 入度数组 + 队列          | 颜色数组 + 递归栈   |
// | 判断标准 | 学完课程数 == 总数       | 没有遇到灰色节点    |
// | 扩展210  | 记录出队顺序即可         | 黑色时入栈，最后反转|
// | 实现难度 | 较低                     | 中等（三色易忘）    |
// | 面试推荐 | 首选                     | 追问时补充          |
//
// 【易错点】
//
// 1. 建图方向搞反:
//    ✗ graph[pre[0]].push_back(pre[1])  // a→b，方向反了
//    ✓ graph[pre[1]].push_back(pre[0])  // b→a，先修b才能学a
//    两种写法都能编译运行，但结果完全不同，debug很痛苦
//
// 2. DFS 只用 bool visited 而非三色标记:
//    ✗ if (visited[next]) return true;
//    ✓ if (color[next] == 1) return true;  // 只有灰色才是环
//       if (color[next] == 2) continue;    // 黑色是安全的
//    有向图中从不同路径到达同一节点是合法的，不是环
//
// 3. DFS 结束时忘记标黑:
//    ✗ 函数末尾缺少 color[node] = 2;
//    ✓ 必须在所有邻居处理完后 color[node] = 2;
//    否则已确认安全的节点仍是灰色，下次被误判为环
//    同时每次都重新 DFS 该子树，时间复杂度退化
//
// 4. BFS 中忘记处理孤立节点:
//    入度为 0 的孤立节点会正常入队，不会遗漏
//    但如果 numCourses 很大而边很少，确保初始化时遍历了所有节点
//
// 【面试追问】(递进链)
//
// Q1: 这道题本质上是什么图论问题？
// → 有向图判环。存在环 = 循环依赖 = 无法完成。
//    等价于判断图是否是 DAG（有向无环图）。
//
// Q2: 你能同时写出 BFS 和 DFS 两种方法吗？
// → BFS = Kahn 算法（入度+队列），DFS = 三色标记。
//    BFS 从"能学什么"正向推，DFS 从"是否有环"直接检测。
//
// Q3: 如果要输出一个合法的学习顺序呢？（LeetCode 210）
// → BFS: 出队顺序就是拓扑排序，多加一行 order.push_back()。
//    DFS: 节点标黑时加入结果，最后反转。
//    核心改动只有 1-2 行代码。
//
// Q4: 如果有 10 万门课但只有 100 条先修关系呢？
// → 当前邻接表实现已经是 O(V+E)，在稀疏图上表现良好。
//    邻接矩阵 O(V²) 会浪费大量空间，不可取。
// ============================================================
