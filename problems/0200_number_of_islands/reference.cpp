/*
 * LeetCode 200: 岛屿数量 (Number of Islands)
 *
 * 【题目本质】
 * 在一个二维网格中，求由相邻 '1' 构成的连通分量的个数。
 * 这是图论中"求连通分量数"的经典问题，放在了矩阵场景下。
 *
 * 【解法总览】
 * 解法1: DFS 递归沉岛    — O(m*n) / O(m*n)       — 面试首选，代码最简
 * 解法2: BFS 队列沉岛    — O(m*n) / O(min(m,n))   — 无栈溢出风险
 * 解法3: Union Find 并查集 — O(m*n*α) / O(m*n)    — 加分项，可扩展到动态场景
 *
 * 网格示例可视化 (示例2):
 *
 *   1 1 0 0 0        ✓ ✓ · · ·       岛屿 #1: (0,0)(0,1)(1,0)(1,1)
 *   1 1 0 0 0   →    ✓ ✓ · · ·       岛屿 #2: (2,2)
 *   0 0 1 0 0        · · ✓ · ·       岛屿 #3: (3,3)(3,4)
 *   0 0 0 1 1        · · · ✓ ✓
 *
 *   遍历到 (0,0) 时发现 '1'，DFS 把整个左上角的 1 全部沉掉
 *   继续遍历到 (2,2) 时发现 '1'，DFS 沉掉这一个
 *   继续遍历到 (3,3) 时发现 '1'，DFS 把 (3,3) 和 (3,4) 沉掉
 *   共触发 3 次 DFS → 答案 = 3
 */


// ============================================================
// 解法1: DFS 递归沉岛 — 面试首选
// 时间: O(m * n)  每个格子最多访问一次
// 空间: O(m * n)  最坏情况递归栈深度（全是'1'的蛇形路径）
//
// 【思路】
// 遍历每个格子，发现 '1' 就说明找到了一个新岛屿（count++），
// 然后用 DFS 把与它相连的所有 '1' 都变成 '0'（"沉岛"），
// 这样后续遍历就不会重复计数。
//
// 为什么直接修改 grid 而不用 visited？
// → 省空间。把 '1' 改成 '0' 等价于 visited 标记。
//   如果题目不允许修改输入，再用 visited 数组。
//
// DFS 扩展过程 (示例2，从(0,0)出发):
//   (0,0)='1' → 沉为'0'
//     → (1,0)='1' → 沉为'0'
//       → (1,1)='1' → 沉为'0'
//         → (0,1)='1' → 沉为'0'
//           → 四周全是 '0' 或越界，回溯
//         → 其余方向全是 '0' 或越界，回溯
//       → 其余方向全是 '0' 或越界，回溯
//     → (0,1) 已经是 '0'（上面沉过了），跳过
//   整个岛沉完，count = 1
// ============================================================
class Solution1 {
public:
    int numIslands(vector<vector<char>>& grid) {
        int m = grid.size(), n = grid[0].size();
        int count = 0;
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (grid[i][j] == '1') {
                    count++;          // 发现新岛屿
                    dfs(grid, i, j);  // 沉掉整个岛
                }
            }
        }
        return count;
    }

private:
    void dfs(vector<vector<char>>& grid, int i, int j) {
        int m = grid.size(), n = grid[0].size();
        // 越界 或 是水 → 终止递归
        if (i < 0 || i >= m || j < 0 || j >= n || grid[i][j] == '0')
            return;

        // 为什么先标记再递归？防止相邻格子绕回来无限递归
        grid[i][j] = '0';

        // 向四个方向扩展
        dfs(grid, i + 1, j);
        dfs(grid, i - 1, j);
        dfs(grid, i, j + 1);
        dfs(grid, i, j - 1);
    }
};


// ============================================================
// 解法2: BFS 队列沉岛 — 无栈溢出风险
// 时间: O(m * n)  每个格子最多入队一次
// 空间: O(min(m, n))  BFS 队列最大长度
//
// 【思路】
// 和 DFS 思路完全一样，区别只是用队列替代递归栈。
// 好处：不会栈溢出。在 300×300 的网格上更安全。
//
// 为什么空间是 O(min(m,n))？
// → BFS 的"波前"在矩阵中呈对角线扩展，最宽处约 min(m,n)。
//
// BFS 扩展过程 (示例2，从(0,0)出发):
//
//   初始队列: [(0,0)]         grid[0][0] = '0'
//   弹出(0,0):
//     邻居(1,0)='1' → 入队，沉   队列: [(1,0)]
//     邻居(0,1)='1' → 入队，沉   队列: [(1,0),(0,1)]
//   弹出(1,0):
//     邻居(1,1)='1' → 入队，沉   队列: [(0,1),(1,1)]
//   弹出(0,1):
//     四周已是'0'或越界，无新入队  队列: [(1,1)]
//   弹出(1,1):
//     四周已是'0'或越界，无新入队  队列: []
//   结束，这个岛处理完毕
//
// 【关键易错点】
// 必须在 **入队时** 就把格子沉为 '0'，不能等出队时再沉。
// 否则同一个格子会被多个邻居重复入队，在大网格上严重超时。
// ============================================================
class Solution2 {
public:
    int numIslands(vector<vector<char>>& grid) {
        int m = grid.size(), n = grid[0].size();
        int count = 0;
        // 方向数组：右、左、下、上
        int dx[] = {0, 0, 1, -1};
        int dy[] = {1, -1, 0, 0};

        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (grid[i][j] == '1') {
                    count++;
                    // 入队时就沉岛（不是出队时！）
                    grid[i][j] = '0';
                    queue<pair<int, int>> q;
                    q.push({i, j});

                    while (!q.empty()) {
                        auto [x, y] = q.front();
                        q.pop();
                        for (int d = 0; d < 4; d++) {
                            int nx = x + dx[d];
                            int ny = y + dy[d];
                            if (nx >= 0 && nx < m && ny >= 0 && ny < n
                                && grid[nx][ny] == '1') {
                                // 入队时就沉，防止重复入队
                                grid[nx][ny] = '0';
                                q.push({nx, ny});
                            }
                        }
                    }
                }
            }
        }
        return count;
    }
};


// ============================================================
// 解法3: Union Find (并查集) — 可扩展到动态场景
// 时间: O(m * n * α(m*n)) ≈ O(m * n)  α是反阿克曼函数，近似常数
// 空间: O(m * n)  parent 和 rank 数组
//
// 【思路】
// 换一个角度：不是"搜索标记"，而是"集合合并"。
// - 初始时，每个 '1' 格子自成一个集合，count = 所有 '1' 的数量
// - 遍历每个 '1'，如果它的右方或下方也是 '1'，就 union 它们
// - 每次 union 成功（两个根不同），count--
// - 最后 count 就是岛屿数
//
// 为什么只看右方和下方？
// → 因为遍历是从左上到右下，(i,j)的左方和上方已经在之前处理过了。
//   只看右和下就能覆盖所有相邻对，避免重复 union。
//
// 二维坐标 → 一维编号：(i, j) → i * n + j
//
// 【并查集的优势场景】
// LeetCode 305 "岛屿数量 II"：陆地动态加入，每次加入后求岛屿数。
// DFS/BFS 每次要重扫整个网格，O(k*m*n) 太慢。
// 并查集只需 O(α) 处理每次加入，总共 O(k*α)。
// ============================================================
class Solution3 {
public:
    int numIslands(vector<vector<char>>& grid) {
        int m = grid.size(), n = grid[0].size();
        parent.resize(m * n);
        rank_.resize(m * n, 0);
        count = 0;

        // 初始化：每个 '1' 自成一个集合
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (grid[i][j] == '1') {
                    parent[i * n + j] = i * n + j;  // 自己是自己的根
                    count++;                          // 初始每个 '1' 算一个岛
                } else {
                    parent[i * n + j] = -1;           // '0' 不参与
                }
            }
        }

        // 只向右和向下合并，避免重复
        int dx[] = {1, 0};
        int dy[] = {0, 1};
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (grid[i][j] == '1') {
                    for (int d = 0; d < 2; d++) {
                        int ni = i + dx[d], nj = j + dy[d];
                        if (ni < m && nj < n && grid[ni][nj] == '1') {
                            unite(i * n + j, ni * n + nj);
                        }
                    }
                }
            }
        }

        return count;
    }

private:
    vector<int> parent;
    vector<int> rank_;
    int count;

    // 路径压缩：让每个节点直接指向根
    int find(int x) {
        if (parent[x] != x)
            parent[x] = find(parent[x]);
        return parent[x];
    }

    // 按秩合并：矮树挂到高树下，保持平衡
    void unite(int x, int y) {
        int px = find(x), py = find(y);
        if (px == py) return;  // 已经属于同一个岛，不需要合并

        // 按秩合并
        if (rank_[px] < rank_[py]) swap(px, py);
        parent[py] = px;
        if (rank_[px] == rank_[py]) rank_[px]++;

        count--;  // 两个岛合并成一个，岛屿数减 1
    }
};


// ============================================================
// 【解法对比】
//
// | 维度         | DFS(递归)      | BFS(队列)       | Union Find     |
// |-------------|---------------|----------------|----------------|
// | 时间         | O(m*n)        | O(m*n)         | O(m*n*α)≈O(m*n)|
// | 空间         | O(m*n) 栈     | O(min(m,n)) 队列| O(m*n) 数组    |
// | 代码量       | 最短           | 中等            | 最长           |
// | 栈溢出风险   | ⚠️ 有          | 无              | 无             |
// | 动态场景(305)| 不适用         | 不适用          | ✅ 唯一选择     |
//
// 面试建议: 先写 DFS（最快写完），然后主动提 BFS 的优势（无栈溢出）。
// 如果被追问 305 动态版，给出 Union Find。
//
// ============================================================
// 【易错点】
//
// 1. grid 存的是 char '1' 不是 int 1
//    ✗ if (grid[i][j] == 1)    → 永远为 false，整数 1 != 字符 '1'
//    ✓ if (grid[i][j] == '1')
//
// 2. BFS 出队时才标记导致重复入队
//    ✗ auto [x,y] = q.front(); q.pop(); grid[x][y] = '0';
//      → 同一格子可能被多个邻居入队
//    ✓ grid[nx][ny] = '0'; q.push({nx, ny});
//      → 入队那一刻就标记
//
// 3. DFS 先递归后标记导致无限递归
//    ✗ dfs(grid, i+1, j); grid[i][j] = '0';
//      → (i+1,j) 的递归可能绕回 (i,j)
//    ✓ grid[i][j] = '0'; dfs(grid, i+1, j);
//      → 进入函数第一步就沉岛
//
// 4. Union Find 中 '0' 格子的 parent 初始化
//    如果 parent 全初始化为 0 而不是 -1，那 '0' 格子的 parent
//    恰好指向 (0,0) 格子，可能导致错误合并。
//    ✓ 对 '0' 格子设 parent = -1，且 union 前检查 grid 值
//
// ============================================================
// 【面试追问】
//
// Q1(基础): DFS 递归深度最坏多少？会栈溢出吗？
//    → O(m*n)，300×300=90000层，可能栈溢出。
//      改用 BFS 或手动栈 DFS 可避免。
//
// Q2(优化): 不允许修改输入 grid 怎么办？
//    → 额外用 bool visited[m][n] 数组，空间 O(m*n)。
//      或者 DFS/BFS 结束后把 '0' 恢复成 '1'（更复杂不推荐）。
//
// Q3(变体): 陆地动态加入，每次加入后求岛屿数？(LeetCode 305)
//    → 并查集。每次 addLand: count++, 检查四周是否有'1',
//      有就 union，union 成功则 count--。单次 O(α)。
//
// Q4(变体): 求最大岛屿面积？(LeetCode 695)
//    → 同样的 DFS/BFS 框架，dfs 函数返回 int (面积)，取 max。
//
// Q5(变体): 求岛屿周长？(LeetCode 463)
//    → 遍历每个 '1'，检查四个方向，遇到水或边界就周长+1。
// ============================================================
