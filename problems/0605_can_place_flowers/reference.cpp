/*
 * LeetCode 605: Can Place Flowers (种花问题)
 *
 * 【题目本质】
 * 花坛数组中，0 表示空，1 表示已种花。相邻位置不能同时种花。
 * 判断能否再种入 n 朵花。
 *
 * 核心：贪心 — 从左到右扫描，能种就种。尽早种花不会影响全局最优。
 *
 * 【解法总览】
 * 解法1:  贪心扫描           — O(m) / O(1) — 面试首选 ⭐
 * 解法1b: 贪心+跳步优化      — O(m) / O(1) — 常数更小
 * 解法2:  连续零计数          — O(m) / O(1) — 不修改原数组
 * 解法3:  补零法              — O(m) / O(m) — 代码最简洁
 */


// ============================================================
// 解法1: 贪心扫描
// 时间: O(m)  空间: O(1) (原地修改)
//
// 【思路】
// 从左到右遍历花坛，对每个位置检查：
//   1. 当前位置为空 (flowerbed[i] == 0)
//   2. 左邻居为空 (i==0 或 flowerbed[i-1] == 0)
//   3. 右邻居为空 (i==m-1 或 flowerbed[i+1] == 0)
// 三个条件都满足时，种花并计数。
//
// 贪心正确性（交换论证）：
//   如果最优解跳过了 i 但在 i+2 种了花，
//   把花从 i+2 移到 i 不会违反规则，也不会减少总数。
//   所以"尽早种花"的策略一定能达到最优。
//
// 示例1: flowerbed = [1,0,0,0,1], n = 1
//   i=0: 值=1, 跳过
//   i=1: 值=0, 左=1, 不满足
//   i=2: 值=0, 左=0, 右=0 → 种花! count=1, 数组=[1,0,1,0,1]
//   i=3: 值=0, 左=1, 不满足
//   i=4: 值=1, 跳过
//   count=1 >= n=1 → true ✓
//
// 示例2: flowerbed = [1,0,0,0,1], n = 2
//   只有 i=2 能种 → count=1 < n=2 → false ✓
//
// 示例3: flowerbed = [0,0,0,0,0], n = 3
//   i=0: 左边界OK, 右=0 → 种花! [1,0,0,0,0], count=1
//   i=1: 左=1 → 不满足
//   i=2: 左=0, 右=0 → 种花! [1,0,1,0,0], count=2
//   i=3: 左=1 → 不满足
//   i=4: 左=0, 右边界OK → 种花! [1,0,1,0,1], count=3
//   count=3 >= n=3 → true ✓
// ============================================================
class Solution1 {
public:
    bool canPlaceFlowers(vector<int>& flowerbed, int n) {
        int count = 0;
        int m = flowerbed.size();

        for (int i = 0; i < m; i++) {
            // 三个条件都满足：当前空、左邻空、右邻空
            if (flowerbed[i] == 0
                && (i == 0 || flowerbed[i - 1] == 0)
                && (i == m - 1 || flowerbed[i + 1] == 0)) {
                flowerbed[i] = 1;  // 种花并标记
                count++;
                if (count >= n) return true; // 提前返回
            }
        }

        return count >= n;
    }
};

// ============================================================
// 解法1b: 贪心 + 跳步优化
// 时间: O(m)  空间: O(1)
//
// 【思路】
// 在解法1的基础上，利用以下观察减少检查次数：
//   - 当前位置是1 → 下一个位置一定不能种 → 跳2格
//   - 当前位置是0且种花了 → 下一个位置一定不能种 → 跳2格
//   - 当前位置是0但右边是1 → 当前不能种，且右边的下一个也不能 → 跳到右边那个1后面
//
// 这种写法减少了条件判断的次数，对长数组常数更小。
// ============================================================
class Solution1b {
public:
    bool canPlaceFlowers(vector<int>& flowerbed, int n) {
        int count = 0;
        int m = flowerbed.size();

        for (int i = 0; i < m; ) {
            if (flowerbed[i] == 1) {
                // 当前已种花，下一个一定不能种
                i += 2;
            } else if (i == m - 1 || flowerbed[i + 1] == 0) {
                // 当前为空，右邻为空或到边界 → 可以种花
                // 注意：左邻一定为空（要么i==0，要么前一个是1跳了2格过来，
                //        要么前一个是0但没种花）
                count++;
                if (count >= n) return true;
                i += 2; // 种完跳2格
            } else {
                // 当前为空但右邻是1 → 不能种
                i++; // 只前进1格
            }
        }

        return count >= n;
    }
};

// ============================================================
// 解法2: 连续零计数
// 时间: O(m)  空间: O(1)
//
// 【思路】
// 不修改原数组。统计连续 0 的段长度，用公式计算每段能种多少花。
//
// 对于连续 len 个零的段：
//   - 两端都是花: 能种 (len-1)/2 朵
//     例: 1,0,0,0,1 → len=3 → (3-1)/2 = 1
//   - 一端是边界: 能种 len/2 朵
//     例: 0,0,0,1 → len=3 → 3/2 = 1
//   - 两端都是边界: 能种 (len+1)/2 朵
//     例: 0,0,0 → len=3 → (3+1)/2 = 2
//
// 统一处理：假想在数组两端各有一个 0，
// 则所有段都变成"两端是花"的情况，统一用 (len-1)/2。
// 实现方法：初始 zeros=1（虚拟左0），结束后 zeros++（虚拟右0）。
//
// 示例: flowerbed = [1,0,0,0,0,1]
//   初始 zeros=1
//   遇到1: count += (1-1)/2 = 0, zeros=0
//   遇到0: zeros=1
//   遇到0: zeros=2
//   遇到0: zeros=3
//   遇到0: zeros=4
//   遇到1: count += (4-1)/2 = 1, zeros=0
//   结束: zeros=0+1=1, count += (1-1)/2 = 0
//   count = 1 ✓
// ============================================================
class Solution2 {
public:
    bool canPlaceFlowers(vector<int>& flowerbed, int n) {
        int count = 0;
        int zeros = 1; // 虚拟左边界的 0

        for (int bed : flowerbed) {
            if (bed == 0) {
                zeros++;
            } else {
                // 遇到花，结算前面的连续零段
                count += (zeros - 1) / 2;
                zeros = 0; // 重置（注意不是1，因为这里是花不是边界）
            }
        }
        // 结算最后一段连续零（加上虚拟右边界的0）
        zeros++;
        count += (zeros - 1) / 2;

        return count >= n;
    }
};

// ============================================================
// 解法3: 补零法 — 代码最简洁
// 时间: O(m)  空间: O(m)
//
// 【思路】
// 在数组两端各添加一个 0，所有位置的检查逻辑统一。
// 不需要 i==0 和 i==m-1 的特殊判断。
//
// 缺点：需要 O(m) 额外空间复制数组。
// 面试中通常用解法1（O(1) 空间）。
// ============================================================
class Solution3 {
public:
    bool canPlaceFlowers(vector<int>& flowerbed, int n) {
        // 两端各加一个 0
        vector<int> f = {0};
        f.insert(f.end(), flowerbed.begin(), flowerbed.end());
        f.push_back(0);

        int count = 0;
        int m = f.size();
        for (int i = 1; i < m - 1; i++) {
            // 不需要边界判断，因为两端有哨兵0
            if (f[i] == 0 && f[i - 1] == 0 && f[i + 1] == 0) {
                f[i] = 1;
                count++;
                if (count >= n) return true;
            }
        }
        return count >= n;
    }
};

// ============================================================
// 解法1c: 不修改原数组的贪心（用变量记录上次种花位置）
// 时间: O(m)  空间: O(1)
//
// 【思路】
// 如果不允许修改 flowerbed，可以用 lastPlanted 变量
// 记录上次种花的位置，检查距离 >= 2 即可。
// ============================================================
class Solution1c {
public:
    bool canPlaceFlowers(vector<int>& flowerbed, int n) {
        int count = 0;
        int m = flowerbed.size();
        int lastPlanted = -2; // 虚拟位置，距离够远

        for (int i = 0; i < m; i++) {
            if (flowerbed[i] == 1) {
                lastPlanted = i; // 更新最近种花位置
            } else if (i - lastPlanted >= 2
                       && (i == m - 1 || flowerbed[i + 1] == 0)) {
                // 距离上次种花 >= 2，且右邻为空
                count++;
                lastPlanted = i; // 标记为种花位置
                if (count >= n) return true;
            }
        }
        return count >= n;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法          | 时间  | 空间  | 修改原数组 | 代码简洁 |
// |--------------|-------|-------|----------|---------|
// | 贪心扫描      | O(m)  | O(1)  | 是       | 高      |
// | 贪心+跳步     | O(m)  | O(1)  | 是       | 中      |
// | 连续零计数    | O(m)  | O(1)  | 否       | 中      |
// | 补零法        | O(m)  | O(m)  | 否(副本) | 最高    |
// | 变量记录      | O(m)  | O(1)  | 否       | 中      |
//
// 面试推荐: 解法1（贪心扫描），简洁直观，O(1) 空间。
//
// ============================================================
// 【易错点】
//
// 1. 忘记标记种花位置:
//    ✗ 不设 flowerbed[i]=1 → 后续位置误以为左邻为空
//    ✓ 种花后 flowerbed[i] = 1
//
// 2. 边界越界:
//    ✗ 不检查 i==0 就访问 flowerbed[i-1]
//    ✓ (i == 0 || flowerbed[i-1] == 0) 利用短路求值
//
// 3. n=0 忘记处理:
//    大多数实现天然处理 (count=0 >= n=0 为 true)
//    但写 "return count >= n" 而不是 "return count == n"
//
// 4. 连续零计数的初始化:
//    ✗ zeros=0 → 开头的连续零少算一朵
//    ✓ zeros=1（虚拟左边界0）
//
// 5. 跳步优化中左邻居隐含条件:
//    在 Solution1b 中，当 flowerbed[i]==0 进入 else if 分支时，
//    左邻居一定为空。这是因为：
//    - i==0（左边界）
//    - 或上一个位置是1，跳了2格过来（中间一定是空的）
//    - 或上一个位置是0但不满足种花条件
//    如果不理解这个隐含条件，代码看起来像漏了检查。
//
// ============================================================
