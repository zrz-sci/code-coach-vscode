/*
 * LeetCode 91: 解码方法 (Decode Ways)
 * 难度: Medium | 标签: String, Dynamic Programming
 *
 * 题意: A-Z 映射到 "1"-"26"。给定数字字符串 s，返回解码方法总数。
 *
 * 核心思路:
 *   类似爬楼梯，dp[i] = 解码 s[0..i-1] 的方法数。
 *   每步可取 1 位或 2 位，但必须满足合法条件:
 *   - 1 位: s[i-1] != '0'
 *   - 2 位: 10 <= s[i-2..i-1] <= 26
 *
 * DP 状态表 (s = "226"):
 *   i:    0  1  2  3
 *   dp:   1  1  2  3
 *   答案: dp[3]=3 ("2,2,6"→BBF, "22,6"→VF, "2,26"→BZ)
 *
 * DP 状态表 (s = "1206"):
 *   i:    0  1  2  3  4
 *   dp:   1  1  2  1  1
 *   dp[3]: '0'不能单独解码, "20"合法 → dp[3]=dp[1]=1
 *   dp[4]: '6'合法, "06"不合法 → dp[4]=dp[3]=1
 *
 * DP 状态表 (s = "06"):
 *   i:    0  1  2
 *   dp:   1  0  0
 *   dp[1]: '0'不能单独解码 → dp[1]=0
 *   dp[2]: "06"不合法 → dp[2]=0 (无法解码)
 */


// ============================================================
// 解法1: 一维 DP ⭐ 推荐
// 时间: O(n)  空间: O(n)
//
// dp[i]: 解码 s[0..i-1] 的方法数
// 转移:
//   if s[i-1] != '0': dp[i] += dp[i-1]  (单字符解码)
//   if 10 <= two <= 26: dp[i] += dp[i-2]  (双字符解码)
// 初始: dp[0] = 1 (空串基准, 使 dp[2] 能正确累加)
//
// 注意: 两位数范围是 10-26, 不是 1-26!
//       "06" 的 two=6 < 10 → 不合法
//       "30" 的 two=30 > 26 → 不合法
// ============================================================
class Solution1 {
public:
    int numDecodings(string s) {
        int n = s.size();
        vector<int> dp(n + 1, 0);
        dp[0] = 1;  // 空串基准 (数学上的base case)

        for (int i = 1; i <= n; i++) {
            // 单字符解码: s[i-1] 必须不是 '0'
            if (s[i-1] != '0') {
                dp[i] += dp[i-1];
            }
            // 双字符解码: 两位数必须在 10-26 范围
            if (i >= 2) {
                int two = (s[i-2] - '0') * 10 + (s[i-1] - '0');
                if (two >= 10 && two <= 26) {
                    dp[i] += dp[i-2];
                }
            }
        }
        return dp[n];
    }
};

// ============================================================
// 解法2: O(1) 空间优化 — 滚动变量
// 时间: O(n)  空间: O(1)
//
// dp[i] 只依赖 dp[i-1] 和 dp[i-2], 用两个变量滚动:
//   prev2 = dp[i-2], prev1 = dp[i-1]
//
// 和爬楼梯/斐波那契的空间优化完全相同。
//
// 注意: 先检查 s[0]=='0' 的 early return!
//       否则 prev1 的初始化不正确。
// ============================================================
class Solution2 {
public:
    int numDecodings(string s) {
        if (s[0] == '0') return 0;  // 首字符 '0' → 无法解码

        int prev2 = 1;  // dp[0] = 1 (空串基准)
        int prev1 = 1;  // dp[1] = 1 (s[0] != '0' 已由上面保证)

        for (int i = 2; i <= (int)s.size(); i++) {
            int curr = 0;
            // 单字符解码
            if (s[i-1] != '0') {
                curr += prev1;
            }
            // 双字符解码
            int two = (s[i-2] - '0') * 10 + (s[i-1] - '0');
            if (two >= 10 && two <= 26) {
                curr += prev2;
            }
            // 滚动更新
            prev2 = prev1;
            prev1 = curr;
        }
        return prev1;
    }
};

// ============================================================
// 解法3: 递归 + 记忆化 (自顶向下)
// 时间: O(n)  空间: O(n)
//
// dfs(idx): 从位置 idx 开始解码的方法数
// 终止: idx == n → 1 (成功解码完)
//       s[idx] == '0' → 0 (当前位是 '0' 无法继续)
// 转移: 取 1 位 + 取 2 位 (合法时)
// ============================================================
class Solution3 {
public:
    int numDecodings(string s) {
        int n = s.size();
        vector<int> memo(n, -1);
        return dfs(s, 0, memo);
    }

private:
    int dfs(const string& s, int idx, vector<int>& memo) {
        int n = s.size();
        if (idx == n) return 1;          // 成功解码到末尾
        if (s[idx] == '0') return 0;     // '0' 开头无法解码
        if (memo[idx] != -1) return memo[idx];

        // 取 1 位
        int ways = dfs(s, idx + 1, memo);

        // 取 2 位 (检查合法性)
        if (idx + 1 < n) {
            int two = (s[idx] - '0') * 10 + (s[idx+1] - '0');
            if (two <= 26) {
                // s[idx] != '0' 已保证 two >= 10
                ways += dfs(s, idx + 2, memo);
            }
        }

        return memo[idx] = ways;
    }
};

/*
 * ============================================================
 * 解法对比
 * ============================================================
 * | 解法         | 时间 | 空间 | 思维方向  | 面试推荐 |
 * |-------------|------|------|----------|---------|
 * | 一维 DP     | O(n) | O(n) | 自底向上 | ⭐首选   |
 * | 空间优化 DP  | O(n) | O(1) | 自底向上 | follow-up|
 * | 记忆化递归   | O(n) | O(n) | 自顶向下 | 理解用   |
 *
 * ============================================================
 * 易错点
 * ============================================================
 * 1. '0' 不能单独解码:
 *    错误: dp[i] += dp[i-1] (不检查 s[i-1])
 *    正确: if (s[i-1] != '0') dp[i] += dp[i-1]
 *    反例: s="10" → '0' 不能单独解码
 *
 * 2. 两位数范围 1-26 而非 10-26:
 *    错误: if (two >= 1 && two <= 26)
 *    反例: s="06", two=6, 被错误认为合法
 *    正确: if (two >= 10 && two <= 26)
 *
 * 3. dp[0] 初始化为 0:
 *    错误: dp[0] = 0 (认为空串 0 种解码)
 *    正确: dp[0] = 1 (DP 数学基准)
 *    影响: dp[2] = dp[0] + dp[1] 中的 dp[0] 必须是 1
 *
 * 4. 空间优化漏检 s[0]:
 *    错误: int prev1 = 1; (s[0]=='0' 时应为 0)
 *    正确: if (s[0]=='0') return 0; 先检查
 *
 * 5. "30" 被当合法:
 *    two=30 > 26 → 不合法 ✓
 *    '0' 不能单独解码 → dp[i] 从 dp[i-1] 不转移
 *    结果 dp=0, s="30" 无法解码
 *
 * 6. 混淆下标:
 *    dp[i] 对应 s[0..i-1]
 *    单字符: s[i-1] (不是 s[i])
 *    双字符: s[i-2], s[i-1] (不是 s[i-1], s[i])
 *
 * ============================================================
 * 面试追问
 * ============================================================
 * Q1: 带 '*' 通配符 (代表 1-9)?
 *     A: LC 639。'*' 单独解码 9 种, 双字符分类讨论, 取模 10^9+7。
 *
 * Q2: 输出所有解码方案?
 *     A: 回溯: 每步尝试取 1 位或 2 位, 到末尾记录方案。
 *
 * Q3: 空间优化?
 *     A: dp[i] 只依赖 dp[i-1] 和 dp[i-2], 用两个变量滚动。
 *        和斐波那契/爬楼梯的空间优化完全相同。
 *
 * Q4: 和爬楼梯的关系?
 *     A: 爬楼梯: dp[i] = dp[i-1] + dp[i-2] (无约束)
 *        解码方法: 相同转移 + 合法性约束 ('0' 和 10-26)
 *        本质是"有约束的爬楼梯"。
 *
 * Q5: 字符串很长 (10^6)?
 *     A: 解法2 O(1) 空间, 无问题。int 不会溢出(题目保证)。
 *
 * Q6: 矩阵快速幂优化?
 *     A: 转移系数取决于当前字符(非常数), 不适合矩阵快速幂。
 */
