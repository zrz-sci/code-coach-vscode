// - 437. 路径总和 III — 路径不必从根到叶，需前缀和+哈希表，难度大增
// - 124. 二叉树中的最大路径和 — 路径可跨根，自底向上 DP，Hard
// - 257. 二叉树的所有路径 — 简化版，不判断和，只收集路径字符串
// ============================================================
