/*
 * LeetCode 112: 路径总和 (Path Sum)
 *
 * 【题目本质】
 * 判断二叉树中是否存在一条从根到叶子的路径，使得路径上所有节点值之和等于 targetSum。
 * 核心思想：逐步扣减——每经过一个节点就减去其值，到叶子节点时检查剩余值是否为 0。
 *
 * 【解法总览】
 * 解法1: 递归 DFS (自顶向下扣减)   — O(n) / O(h) — 最简洁，面试首选
 * 解法2: 迭代 DFS (栈模拟递归)     — O(n) / O(h) — 面试追问"不用递归"
 * 解法3: BFS (队列逐层扩展)        — O(n) / O(w) — 展示多种遍历方式
 *
 * n = 节点数, h = 树高(最坏 n), w = 最大层宽(最坏 n/2)
 */

// ============================================================
// 解法1: 递归 DFS — 自顶向下逐步扣减 targetSum
// 时间: O(n)  空间: O(h) 递归栈深度
//
// 【思路】
// 树的路径问题天然适合递归。从根出发，每到一个节点就把 targetSum
// 减去该节点的值，传递给左右子树。
// 
// 当到达叶子节点时（左右孩子都为空），检查当前节点值是否恰好等于
// 剩余的 targetSum。如果相等，说明找到了一条满足条件的路径。
//
// 递归三要素:
//   返回值: bool — 该子树中是否存在满足条件的路径
//   终止条件: 空节点 → false; 叶子节点 → 判断值是否匹配
//   单层逻辑: 递归检查左/右子树，target 减去当前值
//
// 示例树: targetSum = 22
//       5
//      / \
//     4   8
//    /   / \
//   11  13  4
//  / \       \
// 7   2       1
//
// 递归扣减过程:
// hasPathSum(5, 22)
//   → hasPathSum(4, 17)        // 22-5=17
//     → hasPathSum(11, 13)     // 17-4=13
//       → hasPathSum(7, 2)     // 13-11=2, 叶子, 7≠2 → false
//       → hasPathSum(2, 2)     // 13-11=2, 叶子, 2==2 → true ✓
// ============================================================
class Solution1 {
public:
    bool hasPathSum(TreeNode* root, int targetSum) {
        // 空节点：不存在路径（注意：空树返回 false，即使 targetSum==0）
        if (!root) return false;
        
        // 叶子节点：左右孩子都为空，检查当前值是否等于剩余目标
        if (!root->left && !root->right) {
            return root->val == targetSum;
        }
        
        // 非叶子节点：将"剩余目标"传递给左右子树
        // 只要左/右任一子树满足条件即可
        int remaining = targetSum - root->val;
        return hasPathSum(root->left, remaining) 
            || hasPathSum(root->right, remaining);
    }
};

// ============================================================
// 解法2: 迭代 DFS — 用栈模拟递归
// 时间: O(n)  空间: O(h) 显式栈
//
// 【思路】
// 递归的本质是利用函数调用栈，我们可以用显式栈来模拟同样的过程。
// 关键：栈中每个元素必须同时存储"节点指针"和"到达该节点时的剩余目标和"，
// 因为不同路径的剩余值不同，不能用一个全局变量记录。
//
// 栈模拟过程 (targetSum=22):
//
// 初始:          push(5, 22)
// pop(5, 22)     → 非叶子 → push(8, 17), push(4, 17)
// pop(4, 17)     → 非叶子 → push(11, 13)
// pop(11, 13)    → 非叶子 → push(2, 2), push(7, 2)
// pop(7, 2)      → 叶子, 7≠2 → 继续
// pop(2, 2)      → 叶子, 2==2 → return true!
// ============================================================
class Solution2 {
public:
    bool hasPathSum(TreeNode* root, int targetSum) {
        if (!root) return false;
        
        // 栈中存 {节点, 到达该节点时的剩余目标和}
        stack<pair<TreeNode*, int>> stk;
        stk.push({root, targetSum});
        
        while (!stk.empty()) {
            auto [node, remaining] = stk.top();
            stk.pop();
            
            // 叶子节点：检查当前节点值是否等于剩余目标
            if (!node->left && !node->right) {
                if (node->val == remaining) return true;
                continue;
            }
            
            // 非叶子：将子节点和更新后的剩余值压栈
            // 先压右后压左，这样左孩子先出栈（模拟递归中先处理左子树）
            int newRemaining = remaining - node->val;
            if (node->right) stk.push({node->right, newRemaining});
            if (node->left)  stk.push({node->left,  newRemaining});
        }
        
        return false;
    }
};

// ============================================================
// 解法3: BFS — 队列逐层扩展
// 时间: O(n)  空间: O(w) 队列最大宽度
//
// 【思路】
// BFS 逐层扩展所有节点，每个队列元素存储 {节点, 从根到该节点的路径累加和}。
// 当弹出一个叶子节点时，检查其路径和是否等于 targetSum。
//
// 这里用的是"累加"方式（和解法1的"扣减"方式对称），两种风格等价。
//
// BFS 过程 (targetSum=22):
// Level 0: {(5, 5)}
// Level 1: {(4, 9), (8, 13)}
// Level 2: {(11, 20), (13, 26), (4, 17)}
// Level 3: {(7, 27), (2, 22), (1, 18)}
//           叶子7: 27≠22 ✗   叶子2: 22==22 ✓
// ============================================================
class Solution3 {
public:
    bool hasPathSum(TreeNode* root, int targetSum) {
        if (!root) return false;
        
        // 队列存 {节点, 从根到该节点的路径累加和}
        queue<pair<TreeNode*, int>> q;
        q.push({root, root->val});
        
        while (!q.empty()) {
            auto [node, pathSum] = q.front();
            q.pop();
            
            // 叶子节点：检查路径累加和是否等于目标
            if (!node->left && !node->right) {
                if (pathSum == targetSum) return true;
                continue;
            }
            
            // 非叶子：扩展子节点，累加子节点的值到路径和
            if (node->left)  q.push({node->left,  pathSum + node->left->val});
            if (node->right) q.push({node->right, pathSum + node->right->val});
        }
        
        return false;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法      | 时间  | 空间  | 代码量 | 适用场景                |
// |-----------|-------|-------|--------|------------------------|
// | 递归 DFS  | O(n)  | O(h)  | 最少   | 面试首选，简洁易理解    |
// | 迭代 DFS  | O(n)  | O(h)  | 中等   | 面试追问"不用递归"      |
// | BFS       | O(n)  | O(w)  | 中等   | 展示多种遍历方式        |
//
// 三种解法时间复杂度相同（都要遍历所有节点），空间复杂度取决于树的形状。
// 递归版本最简洁（核心只有3行），面试优先写这个。
//
// ============================================================
// 【易错点】
//
// 1. 空树误判:
//    ✗ if (!root) return targetSum == 0;
//    ✓ if (!root) return false;
//    原因：空树没有叶子节点，不存在任何"根到叶"路径，即使 targetSum==0
//
// 2. 叶子节点判断条件用错:
//    ✗ if (!root->left || !root->right)   // 只有一个孩子的节点会被误判为叶子
//    ✓ if (!root->left && !root->right)   // 必须两个孩子都为空才是叶子
//    反例：树 [1,2]，节点1有左孩子2，不是叶子。按错误写法会在节点1处判断
//
// 3. 单孩子节点上的空孩子误匹配:
//    树 [1,2], targetSum=1
//    递归到根节点1的右孩子(null): 若用 return remaining==0，会返回 true
//    但实际上节点1不是叶子，唯一的叶子是节点2(路径和=3≠1)
//    正确做法：空节点一律返回 false，叶子判断放在非空节点上
//
// 4. 迭代版只存节点不存路径信息:
//    ✗ stack<TreeNode*> stk; 然后用全局变量记和 — 回溯时和会出错
//    ✓ stack<pair<TreeNode*, int>> stk; 每个节点带上自己的剩余值
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么空节点返回 false 而不是 targetSum==0？
// → 空节点不是叶子。"根到叶路径"要求终点是叶子节点（有实际存在的节点）。
//   空树连根都没有，不存在任何路径。
//
// Q2: 不用递归怎么写？
// → 用栈模拟 DFS（解法2）。关键是栈中每个元素同时存节点和剩余目标值，
//   不能用全局变量，因为不同分支的剩余值不同。
//
// Q3: 如果要返回所有满足条件的路径（LeetCode 113），怎么改？
// → 在递归基础上增加一个 path 数组：
//   - 进入节点: path.push_back(node->val)
//   - 叶子且满足条件: result.push_back(path)
//   - 退出节点: path.pop_back() (回溯)
//   核心递归框架不变，从返回 bool 变成收集路径。
//
// Q4: 节点值可以为负，会影响算法吗？
// → 不会。算法遍历所有根到叶路径，没有基于"和递增"的剪枝假设。
//   负数不影响正确性，只是不能提前终止（因为后面的负数可能让和变小）。
//
