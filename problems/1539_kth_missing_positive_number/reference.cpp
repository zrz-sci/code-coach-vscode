/*
 * LeetCode 1539: Kth Missing Positive Number
 * 
 * 【题目本质】
 * 正整数序列 1,2,3,... 中去掉 arr 出现的数，求剩余序列的第 k 个。
 * 关键洞察：arr[i] 之前缺失的正整数个数 = arr[i] - (i+1)，单调不减，可二分。
 *
 * 【解法总览】
 * 解法1: 暴力遍历       — O(n+k) / O(1)  — 最直觉
 * 解法2: 二分查找       — O(log n) / O(1) — 最优 (Follow-up 要求)
 */

// ============================================================
// 解法1: 暴力遍历 — 逐个正整数检查是否缺失
// 时间: O(n + k)  空间: O(1)
//
// 【思路】
// 最朴素的想法：从 1 开始逐个检查每个正整数。
// 用一个指针 idx 跟踪 arr，如果当前数等于 arr[idx]，
// 说明它没有缺失，跳过；否则它是缺失的，计数 k--。
// 当 k 减到 0 时，当前数就是答案。
//
// 利用 arr 有序的特性，idx 只会往前走，所以总体 O(n+k)。
//
// 示例: arr = [2,3,4,7,11], k = 5
//   current=1: 不在arr → k=4
//   current=2: ==arr[0] → skip, idx=1
//   current=3: ==arr[1] → skip, idx=2
//   current=4: ==arr[2] → skip, idx=3
//   current=5: 不在arr → k=3
//   current=6: 不在arr → k=2
//   current=7: ==arr[3] → skip, idx=4
//   current=8: 不在arr → k=1
//   current=9: 不在arr → k=0 → 返回 9
// ============================================================
class Solution1 {
public:
    int findKthPositive(vector<int>& arr, int k) {
        int idx = 0;
        int current = 0;
        
        while (k > 0) {
            current++;
            // idx 没越界且当前数在 arr 中 → 不是缺失数
            if (idx < (int)arr.size() && arr[idx] == current) {
                idx++;
            } else {
                // 当前数是缺失的，消耗一次 k
                k--;
            }
        }
        return current;
    }
};

// ============================================================
// 解法2: 二分查找 — 利用缺失数量的单调性 ⭐ 面试首选
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 解法1 的瓶颈：逐个遍历，无法跳跃。
// 
// 关键公式：arr[i] 之前缺失的正整数个数 = arr[i] - (i + 1)
//   原因：如果 0~i 这些位置全不缺，arr[i] 应恰好等于 i+1。
//   实际 arr[i] 比 i+1 大多少，就说明前面缺了多少个。
//
// 缺失数 missing(i) = arr[i] - (i+1) 是单调不减的：
//   arr 严格递增 → arr[i+1] >= arr[i]+1
//   → missing(i+1) = arr[i+1]-(i+2) >= arr[i]+1-(i+2) = missing(i)
//
// 有了单调性，就可以二分：
//   找最后一个 missing(mid) < k 的位置
//   → left 停在第一个 missing >= k 的索引
//   → 答案 = k + left
//
// 为什么答案 = k + left？
//   left 表示 arr 中有 left 个元素出现在答案之前。
//   正整数序列中，答案前面有 left 个"存在的" + (k-1) 个"缺失的"。
//   答案 = left + (k-1) + 1 = left + k。
//
// 示例: arr = [2,3,4,7,11], k = 5
//
// 索引i:     0    1    2    3    4
// arr[i]:    2    3    4    7    11
// i+1:       1    2    3    4    5
// missing:   1    1    1    3    6
//
// 二分搜索空间收缩:
//   Round1: left=0, right=4, mid=2
//           missing(2) = 4-3 = 1 < 5 → left = 3
//
//   Round2: left=3, right=4, mid=3
//           missing(3) = 7-4 = 3 < 5 → left = 4
//
//   Round3: left=4, right=4, mid=4
//           missing(4) = 11-5 = 6 >= 5 → right = 3
//
//   结束: left=4 > right=3
//   答案 = k + left = 5 + 4 = 9 ✓
//
// 边界情况: arr = [1,2,3,4], k = 2
//   missing: 0  0  0  0  (全为0，都 < 2)
//   二分结束 left = 4 = n
//   答案 = 2 + 4 = 6 ✓ (缺失的是 5, 6, 7, ...)
// ============================================================
class Solution2 {
public:
    int findKthPositive(vector<int>& arr, int k) {
        int left = 0, right = (int)arr.size() - 1;
        
        while (left <= right) {
            int mid = left + (right - left) / 2;
            // arr[mid] 之前缺失了多少个正整数
            int missing = arr[mid] - (mid + 1);
            
            if (missing < k) {
                // 缺失数不够 k 个，答案在更右边
                left = mid + 1;
            } else {
                // 缺失数已 >= k，尝试往左收缩
                right = mid - 1;
            }
        }
        
        // left = arr 中 <= 答案的元素个数
        // 答案 = k(缺失的) + left(存在的)
        return k + left;
    }
};

// ============================================================
// 【解法对比】
// 
// | 维度       | 解法1 暴力遍历 | 解法2 二分查找 |
// |-----------|---------------|---------------|
// | 时间       | O(n + k)      | O(log n)      |
// | 空间       | O(1)          | O(1)          |
// | 思维难度   | 低            | 中             |
// | 核心       | 逐个检查      | 缺失数公式+单调性 |
// 
// 解法1 在 n 和 k 都小时足够用（本题约束 <= 1000）。
// 解法2 是 Follow-up 要求的 O(log n) 解法，面试推荐。
//
// 【易错点】
// 1. 缺失数公式写成 arr[mid]-mid 而不是 arr[mid]-(mid+1)
//    → 索引从0开始，正整数从1开始，差了1
//
// 2. 二分条件用 missing <= k 而不是 missing < k
//    → 当 missing == k 时，arr[mid] 恰好是第 k 个缺失数之后的
//      存在数，答案在它左边，应该让 right 收缩，不是 left
//
// 3. 答案写成 arr[left] - (缺失差值) 这种复杂形式
//    → 容易在 left == n (越界) 时出错
//    → 直接用 k + left 最简洁，涵盖所有边界
//
// 4. 暴力法中 idx 越界：忘了 idx < arr.size() 的检查
//
// 【面试追问】
// Q1: 暴力解时间复杂度是多少？瓶颈在哪？
//     → O(n+k)，逐个遍历正整数。当 k 远大于 n 时由 k 主导。
//
// Q2: 能否 O(log n)？关键观察是什么？
//     → arr[i]-(i+1) 单调不减，表示 arr[i] 之前缺了多少个正整数。
//       二分找最后一个 < k 的位置，答案 = k + left。
//
// Q3: 如果 arr 有重复元素怎么办？
//     → arr[i]-(i+1) 不再正确（重复使得实际"占位"比索引暗示的少）。
//       需要先去重，或改用 set 辅助的线性方法。
//
// Q4: 如果多次查询不同的 k，如何优化？
//     → 预计算 missing 数组（O(n)），之后每次查询二分 O(log n)。
