/*
 * LeetCode 643: 子数组最大平均数 I (Maximum Average Subarray I)
 *
 * 【题目本质】
 * 在所有长度恰好为 k 的连续子数组中，找到元素之和最大的那个。
 * 因为 k 固定，和最大 ⟺ 平均数最大，所以只需最后除一次 k。
 *
 * 【解法总览】
 * 解法1: 暴力枚举     — O(n·k) / O(1) — 最直觉，理解题意
 * 解法2: 前缀和       — O(n)   / O(n) — 通用区间和查询技巧
 * 解法3: 固定滑动窗口 — O(n)   / O(1) — 最优，面试首选
 */

// ============================================================
// 解法1: 暴力枚举 — 每个起点重新计算 k 项之和
// 时间: O(n·k)  空间: O(1)
//
// 【思路】
// 最直接的想法：枚举所有起点 i ∈ [0, n-k]，对每个起点
// 用内层循环累加 nums[i..i+k-1]，记录最大和。
//
// 瓶颈：相邻窗口 [i, i+k-1] 和 [i+1, i+k] 重叠了 k-1 个元素，
// 却每次都重新计算，这就是 O(n·k) 的根源。
//
// 滑动窗口示意（nums = [1,12,-5,-6,50,3], k = 4）:
//
// i=0: [1, 12, -5, -6] 50  3   sum=2    ← 全部重新加
// i=1:  1 [12, -5, -6, 50]  3   sum=51   ← 又全部重新加（12,-5,-6 被重复计算）
// i=2:  1  12 [-5, -6, 50,  3]  sum=42   ← 又全部重新加（-5,-6,50 被重复计算）
// ============================================================
class Solution1 {
public:
    double findMaxAverage(vector<int>& nums, int k) {
        int n = nums.size();
        int maxSum = INT_MIN;

        for (int i = 0; i <= n - k; i++) {
            int sum = 0;
            for (int j = i; j < i + k; j++) {
                sum += nums[j];
            }
            maxSum = max(maxSum, sum);
        }

        return (double)maxSum / k;
    }
};

// ============================================================
// 解法2: 前缀和 — 预处理后 O(1) 查询任意区间和
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法1 的瓶颈是"每次重新求区间和"。前缀和把这个操作从 O(k) 优化到 O(1)：
//   prefix[i] = nums[0] + nums[1] + ... + nums[i-1]
//   区间 [i, i+k-1] 的和 = prefix[i+k] - prefix[i]
//
// 前缀和数组构建过程:
//   nums:    1   12   -5   -6   50    3
//   prefix: [0,   1,  13,   8,   2,  52,  55]
//             ↑                            ↑
//           prefix[0]=0                  prefix[6]=55
//
//   [1,4] 的和 = prefix[5] - prefix[1] = 52 - 1 = 51 ✓ (12-5-6+50=51)
//
// 注意：前缀和更适合"需要查询多种不同长度区间和"的场景。
// 本题窗口大小固定，滑动窗口更优（不需要额外空间）。
// ============================================================
class Solution2 {
public:
    double findMaxAverage(vector<int>& nums, int k) {
        int n = nums.size();
        // prefix[i] 存 nums[0..i-1] 的和，prefix[0] = 0
        vector<int> prefix(n + 1, 0);
        for (int i = 0; i < n; i++) {
            prefix[i + 1] = prefix[i] + nums[i];
        }

        int maxSum = INT_MIN;
        for (int i = 0; i <= n - k; i++) {
            // 区间 [i, i+k-1] 的和 = prefix[i+k] - prefix[i]
            int sum = prefix[i + k] - prefix[i];
            maxSum = max(maxSum, sum);
        }

        return (double)maxSum / k;
    }
};

// ============================================================
// 解法3: 固定大小滑动窗口 — O(1) 增量更新窗口和 ⭐ 面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 核心观察：窗口从 [i, i+k-1] 滑到 [i+1, i+k] 时，
//   新窗口和 = 旧窗口和 - nums[i] + nums[i+k]
// 只做了一次减法和一次加法，O(1)！
//
// 这就是"固定大小滑动窗口"的标准模板：
//   Step1: 计算第一个窗口 [0, k-1] 的和
//   Step2: 窗口右移，加入右边新元素，去掉左边旧元素
//   Step3: 每次更新最大和
//
// 滑动过程（nums = [1,12,-5,-6,50,3], k = 4）:
//
//  初始窗口: [1, 12, -5, -6] 50  3    sum = 1+12-5-6 = 2, maxSum = 2
//
//  i=4:  出去 nums[0]=1, 进来 nums[4]=50
//         1 [12, -5, -6, 50]  3        sum = 2 - 1 + 50 = 51, maxSum = 51
//
//  i=5:  出去 nums[1]=12, 进来 nums[5]=3
//         1  12 [-5, -6, 50,  3]       sum = 51 - 12 + 3 = 42, maxSum = 51
//
//  结果: maxSum = 51, 答案 = 51 / 4 = 12.75
// ============================================================
class Solution3 {
public:
    double findMaxAverage(vector<int>& nums, int k) {
        // Step1: 初始化第一个窗口的和
        int windowSum = 0;
        for (int i = 0; i < k; i++) {
            windowSum += nums[i];
        }

        int maxSum = windowSum;

        // Step2: 窗口逐步右移
        for (int i = k; i < (int)nums.size(); i++) {
            // nums[i] 是新进来的元素，nums[i-k] 是出去的元素
            // 为什么是 i-k 而不是 i-k+1？因为当前窗口右端是 i，
            // 窗口大小为 k，所以左端是 i-k+1，而出去的是上一个窗口的左端 i-k
            windowSum += nums[i] - nums[i - k];
            maxSum = max(maxSum, windowSum);
        }

        // 全程用 int 比较避免浮点精度问题，只在最后转 double
        return (double)maxSum / k;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间   | 空间 | 核心思想           | 适用场景           |
// |-----------|--------|------|--------------------|--------------------|
// | 暴力枚举   | O(n·k) | O(1) | 每次重新计算       | 理解题意           |
// | 前缀和     | O(n)   | O(n) | 预处理 → O(1)查询  | 多种区间长度查询   |
// | 滑动窗口   | O(n)   | O(1) | 增量更新           | 固定/可变窗口问题  |
//
// 暴力 → 前缀和：把"每次 O(k) 求和"变成"O(1) 区间查询"，代价是 O(n) 空间
// 暴力 → 滑动窗口：利用相邻窗口重叠的性质，O(1) 增量更新，无额外空间
// 前缀和 vs 滑动窗口：前缀和更通用（支持任意区间），滑动窗口更省空间（仅适合固定大小窗口）
//
// 【易错点】
//
// 1. maxSum 初始化错误
//    ✗ int maxSum = 0;
//    → 全负数数组如 [-1,-2,-3], k=2 时，maxSum 不会更新，返回 0/(double)k = 0，错！
//    ✓ int maxSum = windowSum; → 用第一个窗口的真实和初始化
//
// 2. 返回值整数除法
//    ✗ return maxSum / k; → 整数除法截断小数（如 51/4=12 而非 12.75）
//    ✓ return (double)maxSum / k; → 强制浮点除法
//
// 3. 滑动时出去元素的下标
//    ✗ windowSum += nums[i] - nums[i - k + 1];
//    → i - k + 1 是当前窗口的左端点，但出去的应该是上一个窗口的左端点 i - k
//    ✓ windowSum += nums[i] - nums[i - k];
//
// 4. 循环边界
//    ✗ for (int i = k; i < nums.size(); i++) 当 nums.size() 返回 unsigned 且 k > size 时
//    → 不会发生因为题目保证 k ≤ n，但好习惯是 (int)nums.size()
//    ✓ for (int i = k; i < (int)nums.size(); i++)
//
// 【面试追问】
//
// Q1(基础): "暴力解为什么会超时？相邻两个窗口之间有什么关系？"
//    → 暴力 O(n·k) 最坏 10^10。相邻窗口重叠 k-1 个元素，
//      新窗口和 = 旧和 - 出去的 + 进来的，只需 O(1)。
//
// Q2(变体): "如果不是固定长度 k，而是找 ≥ k 的最大平均子数组呢？"
//    → LeetCode 644，Hard。固定窗口不再适用，需要二分答案 + 前缀和。
//      二分猜平均值 mid，将每个元素减去 mid，问题变成"是否存在长度 ≥ k 的
//      非负和子数组"，可用前缀和 + 维护最小前缀在 O(n) 内判定。
//
// Q3(扩展): "如果数据是流式的（不断有新元素到来），如何维护最近 k 个的平均值？"
//    → 用一个大小为 k 的循环队列（或直接维护 sum 和计数器），
//      每来一个新元素 O(1) 更新 sum。本质上就是滑动窗口的在线版本。
// ============================================================
