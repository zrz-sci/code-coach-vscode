// 【Python 简洁写法参考】
//
// # 方法1: 列表推导
// def transpose(matrix):
//     return [[matrix[i][j] for i in range(len(matrix))]
//             for j in range(len(matrix[0]))]
//
// # 方法2: zip 解包 (最 Pythonic)
// def transpose(matrix):
//     return [list(row) for row in zip(*matrix)]
//
// zip(*matrix) 将矩阵的每一行作为参数传给 zip，
// zip 按列打包 → 自动完成转置。
//
// ============================================================
// 【解法对比】
//
// | 解法          | 时间    | 空间    | 适用场景       |
// |--------------|--------|--------|---------------|
// | 创建新矩阵   | O(mn)  | O(mn)  | 通用（方阵/非方阵） |
// | 原地转置     | O(n²)  | O(1)   | 仅方阵         |
//
// 本题通用解法只有"创建新矩阵"，原地转置是面试追问的知识点。
//
// ============================================================
// 【易错点】
//
// 1. 结果矩阵行列搞反:
//    ✗ res(m, vector<int>(n))  → 大小和原矩阵一样，赋值越界
//    ✓ res(n, vector<int>(m))  → 行列互换: n行m列
//
// 2. 赋值方向搞反:
//    ✗ res[i][j] = matrix[j][i]  → 没有转置
//    ✓ res[j][i] = matrix[i][j]  → 正确：行列互换
//
// 3. 方阵原地转置遍历全部:
//    ✗ for j=0..n: swap(m[i][j], m[j][i])  → 每对交换两次=没转
//    ✓ for j=i+1..n: swap(m[i][j], m[j][i])  → 上三角每对交换一次
//
// 4. 非方阵尝试原地转置:
//    ✗ 在 2x3 矩阵上原地操作 → 下标越界
//    ✓ 非方阵必须创建新矩阵
//
// ============================================================
// 【面试追问】
//
// Q1: 非方阵能原地转置吗？
//     理论上可以用"置换环"算法，但极其复杂，面试中直接说
//     创建新矩阵即可。
//
// Q2: 转置 + 翻转 = 旋转？
//     转置 + 每行翻转 = 顺时针90度 (LC 48)
//     转置 + 每列翻转 = 逆时针90度
//     这是矩阵旋转的标准分解。
//
// Q3: 大矩阵在磁盘上怎么转置？
//     分块转置 (block transpose):
//     把矩阵分成小块 → 块级别转置 → 块内部转置
//     利用空间局部性减少磁盘 I/O。
//
// Q4: 稀疏矩阵怎么转置？
//     三元组存储 (row, col, val) → 交换 row 和 col → 按新 row 排序
//     时间 O(nnz * log nnz)，nnz = 非零元素数。
//
// Q5: 时间能低于 O(mn) 吗？
//     不能。每个元素至少读取一次，O(mn) 是下界。
//
// ============================================================
// 【相关题型】
//
