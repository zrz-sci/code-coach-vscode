/*
 * LeetCode 867: Transpose Matrix (转置矩阵)
 *
 * 【题目本质】
 * 将矩阵沿主对角线翻转：行变列、列变行。
 * 原矩阵 m x n → 转置后 n x m。
 * result[j][i] = matrix[i][j]
 *
 * 【核心考点】
 * 1. 正确处理非方阵（m != n）
 * 2. 新矩阵的维度初始化
 * 3. 方阵原地转置的技巧（追问）
 *
 * 【解法总览】
 * 解法1: 创建新矩阵         — O(m*n) / O(m*n) — 通用做法
 * 解法1b: cache友好遍历      — O(m*n) / O(m*n) — 按结果矩阵行序遍历
 * 解法2: 方阵原地转置        — O(n^2) / O(1)   — 仅方阵可用（知识点）
 */


// ============================================================
// 解法1: 创建新矩阵 — 通用做法 ⭐
// 时间: O(m*n)  空间: O(m*n)
//
// 【思路】
// 非方阵不能原地转置（2x3 无法变成 3x2），必须创建新矩阵。
// 核心赋值: res[j][i] = matrix[i][j]
//
// 【图解】
//
// 原矩阵 (2x3):           转置后 (3x2):
// ┌─────────────┐          ┌─────────┐
// │  1   2   3  │          │  1   4  │
// │  4   5   6  │    →     │  2   5  │
// └─────────────┘          │  3   6  │
//                          └─────────┘
//
// 映射过程:
//   matrix[0][0]=1 → res[0][0]=1    (i=0,j=0)
//   matrix[0][1]=2 → res[1][0]=2    (i=0,j=1: 行列互换)
//   matrix[0][2]=3 → res[2][0]=3    (i=0,j=2)
//   matrix[1][0]=4 → res[0][1]=4    (i=1,j=0)
//   matrix[1][1]=5 → res[1][1]=5    (i=1,j=1)
//   matrix[1][2]=6 → res[2][1]=6    (i=1,j=2)
//
// 【方阵示例 (3x3)】
//
// 原始:              转置后:
// ┌───────────┐     ┌───────────┐
// │ 1  2  3   │     │ 1  4  7   │
// │ 4  5  6   │  →  │ 2  5  8   │
// │ 7  8  9   │     │ 3  6  9   │
// └───────────┘     └───────────┘
//
// 观察: 主对角线 (1,5,9) 不变
//       上三角和下三角对称交换: 2↔4, 3↔7, 6↔8
// ============================================================
class Solution1 {
public:
    vector<vector<int>> transpose(vector<vector<int>>& matrix) {
        int m = matrix.size();       // 原矩阵行数
        int n = matrix[0].size();    // 原矩阵列数

        // 转置后: n 行 m 列
        // 注意: 不是 (m, n)! 行列要反过来
        vector<vector<int>> res(n, vector<int>(m));

        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                res[j][i] = matrix[i][j];
                //  ↑  ↑          ↑  ↑
                //  行列互换    原始位置
            }
        }

        return res;
    }
};


// ============================================================
// 解法1b: 按结果矩阵行序遍历（cache友好版本）
// 时间: O(m*n)  空间: O(m*n)
//
// 【思路】
// 与解法1逻辑完全相同，但改为遍历结果矩阵。
// 对 res 的写入是按行顺序 (res[j][0], res[j][1], ...)，
// 在行主序存储中这是连续内存访问，更 cache 友好。
//
// 对于大矩阵(本题 m*n <= 10^5 不算大)，这个优化有实际意义。
// ============================================================
class Solution1b {
public:
    vector<vector<int>> transpose(vector<vector<int>>& matrix) {
        int m = matrix.size();
        int n = matrix[0].size();

        vector<vector<int>> res(n, vector<int>(m));

        // 外层遍历结果矩阵的行 (j)
        // 内层遍历结果矩阵的列 (i)
        for (int j = 0; j < n; j++) {
            for (int i = 0; i < m; i++) {
                res[j][i] = matrix[i][j];
            }
        }

        return res;
    }
};


// ============================================================
// 解法2: 方阵原地转置 — 知识点展示（仅方阵可用）
// 时间: O(n^2)  空间: O(1)
//
// 【思路】
// 方阵可以原地转置：遍历上三角(i < j)，交换对称位置。
// 注意: 本题矩阵可能不是方阵，此解法仅作为追问知识点。
//
// 【图解 — 只遍历上三角】
//
// ┌───────────┐     操作:
// │[1] 2  3   │     swap(m[0][1], m[1][0]): 2 ↔ 4
// │ 4 [5] 6   │     swap(m[0][2], m[2][0]): 3 ↔ 7
// │ 7  8 [9]  │     swap(m[1][2], m[2][1]): 6 ↔ 8
// └───────────┘     [对角线] 不动
//
// 为什么 j 从 i+1 开始？
//   j=0: 每对 (i,j) 和 (j,i) 会被交换两次 → 相当于没转置
//   j=i+1: 每对只交换一次 → 正确转置
//   j=i: 对角线元素自己和自己交换 → 不需要
//
// 【应用：矩阵旋转90度 (LC 48)】
// 顺时针旋转90度 = 转置 + 每行翻转
// 逆时针旋转90度 = 转置 + 每列翻转(或每行翻转后转置)
// ============================================================
class Solution2_SquareOnly {
public:
    void transposeInPlace(vector<vector<int>>& matrix) {
        int n = matrix.size();
        // 前提: matrix 是 n x n 方阵

        // 只遍历严格上三角 (i < j)
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                swap(matrix[i][j], matrix[j][i]);
            }
        }
    }
};


