/*
 * LeetCode 228: 汇总区间 (Summary Ranges)
 *
 * 【题目本质】
 * 在有序无重复数组中找出所有"公差为1的连续段"，格式化为字符串输出。
 *
 * 【解法总览】
 * 解法1: 双指针(start + i) — O(n) / O(1) — 最直觉，面试首选
 * 解法2: 单遍历 + 判断区间尾部 — O(n) / O(1) — 代码更整洁
 */

// ============================================================
// 解法1: 双指针 — 用 start 记录区间起点，i 向后探索连续段
// 时间: O(n)  空间: O(1)（不算输出）
//
// 【思路】
// 最自然的思路：每次固定一个区间的起点 start，
// 然后让 i 往后走，只要下一个数 = 当前数 + 1 就继续。
// 走不动了，说明 [start..i] 是一个完整的连续段。
// 格式化后加入结果，然后 i++ 跳到下一段。
//
// 示意图: nums = [0, 1, 2, 4, 5, 7]
//
// 第1轮: start=0, i从0走到2 (0→1→2连续)
//        输出 "0->2", i跳到3
// 第2轮: start=3, i从3走到4 (4→5连续)
//        输出 "4->5", i跳到5
// 第3轮: start=5, i=5 (7后面没了)
//        输出 "7", i跳到6, 结束
// ============================================================
class Solution1 {
public:
    vector<string> summaryRanges(vector<int>& nums) {
        vector<string> result;
        int n = nums.size();
        int i = 0;
        
        while (i < n) {
            int start = i;
            
            // 向后扩展: 只要下一个数恰好比当前大1，就继续
            // 为什么用 nums[i+1] == nums[i] + 1 而不是差值:
            // 避免减法可能的溢出（虽然本题数据量小不会出问题）
            while (i + 1 < n && nums[i + 1] == nums[i] + 1) {
                i++;
            }
            
            // 此时 nums[start..i] 构成一个连续区间
            if (start == i) {
                // 单元素区间: 只输出这一个数
                result.push_back(to_string(nums[start]));
            } else {
                // 多元素区间: "起点->终点"
                result.push_back(to_string(nums[start]) + "->" + to_string(nums[i]));
            }
            
            // 关键: i++ 跳过当前区间的最后一个元素，到下一段起点
            // 忘记这一步会导致死循环!
            i++;
        }
        
        return result;
    }
};

// ============================================================
// 解法2: 单遍历 + 判断区间尾部
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 换个角度: 不在内层循环"跳过"整段，而是每次只走一步。
// 每到一个位置，检查它是不是某段的"结尾":
//   - 它是数组最后一个元素（后面没数了），或者
//   - 下一个数不连续（nums[i+1] != nums[i] + 1）
// 如果是区间尾部，就把 [start..i] 输出，并更新 start。
//
// 好处: 只有一层循环，不需要手动控制 i 的跳跃，不容易写错。
// ============================================================
class Solution2 {
public:
    vector<string> summaryRanges(vector<int>& nums) {
        vector<string> result;
        int n = nums.size();
        
        int start = 0; // 当前区间起始索引
        for (int i = 0; i < n; i++) {
            // 判断 i 是否是当前区间的末尾
            // 两种情况: 到达数组末尾 || 下一个数不连续
            if (i == n - 1 || nums[i + 1] != nums[i] + 1) {
                if (start == i) {
                    result.push_back(to_string(nums[start]));
                } else {
                    result.push_back(to_string(nums[start]) + "->" + to_string(nums[i]));
                }
                // 下一段从 i+1 开始
                start = i + 1;
            }
        }
        
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// 解法1 vs 解法2:
// - 本质完全一样，都是 O(n) 扫一遍
// - 解法1 用 while 嵌套 while，内层直接跳过整个连续段
//   → 思路更直觉（"找到一段的起点，然后扩展到尾"）
//   → 风险: 外层忘记 i++ 导致死循环
// - 解法2 单层 for，每次只走一步，在"断裂点"输出区间
//   → 代码更整洁，不容易出 bug
//   → 但需要额外维护 start 变量
//
// 面试时选哪个都行，能清楚解释即可。
//
// ============================================================
// 【易错点】
//
// 1. 双指针写法忘记外层 i++:
//    ✗ while(i<n){ start=i; while(连续) i++; 输出; }  ← 死循环!
//    ✓ while(i<n){ start=i; while(连续) i++; 输出; i++; }
//
// 2. 越界访问 nums[i+1]:
//    ✗ while(nums[i+1]==nums[i]+1) i++;  ← 当 i==n-1 时越界
//    ✓ while(i+1<n && nums[i+1]==nums[i]+1) i++;  ← 先检查边界
//
// 3. 空数组:
//    ✗ 直接开始处理，访问 nums[0] 越界
//    ✓ 解法1 的 while(i<n) 自然跳过; 解法2 的 for 也自然跳过
//
// 4. 整数溢出(理论上):
//    ✗ nums[i] + 1 当 nums[i] == INT_MAX 时溢出
//    ✓ 本题约束数组长度 ≤ 20 且元素不重复，INT_MAX 附近最多一个元素
//       不会出现 nums[i]==INT_MAX 且 nums[i+1] 存在的情况
//       如果要严谨: (long)nums[i+1] == (long)nums[i] + 1
//
// ============================================================
// 【面试追问】
//
// Q1(基础理解): "时间复杂度是多少？能更快吗？"
//   → O(n)，不能更快，每个元素至少看一次。
//
// Q2(变体): "如果数组有重复元素怎么办？"
//   → 在连续性判断中加上 nums[i+1]==nums[i] 也算连续（或先去重）。
//
// Q3(在线版): "如果是数据流，元素一个个到来呢？"
//   → 维护当前区间的 start/end。
//     新数字 == end+1 则扩展 end；否则输出 [start,end] 并重置。
//     空间 O(1)。
//
// Q4(逆操作): "给定 ["0->2","4->5","7"]，展开成 [0,1,2,4,5,7]？"
//   → 解析每个字符串: 找 "->" 分隔，
//     有则 for(a to b) push_back，无则直接 push_back(stoi(s))。
//
