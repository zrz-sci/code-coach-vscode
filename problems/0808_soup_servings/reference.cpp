/*
 * LeetCode 808: 分汤 (Soup Servings)
 *
 * 【题目本质】
 * 概率 DP：两碗汤同时按四种等概率操作消耗，求 A 先空的概率 + 0.5 * 同时空的概率。
 * 核心技巧：除以 25 缩小状态空间 + 大 n 时概率趋近 1 直接返回。
 *
 * 【解法总览】
 * 解法1: 记忆化搜索 + 大 n 剪枝 — O(k^2) / O(k^2) — 面试首选
 * 解法2: 自底向上 DP — O(k^2) / O(k^2) — 迭代写法
 *
 * 其中 k = ceil(n/25)，最大约 192（因为 n>=4800 时直接返回 1.0）
 */

// ============================================================
// 解法1: 记忆化搜索 + 大 n 剪枝
// 时间: O(k^2)  空间: O(k^2)  其中 k = ceil(n/25) <= 192
//
// 【思路】
// 1. 四种操作消耗 (A, B):
//    (100,0), (75,25), (50,50), (25,75) → 除以25 → (4,0),(3,1),(2,2),(1,3)
//
// 2. A 平均每轮消耗 (4+3+2+1)/4 = 2.5 份
//    B 平均每轮消耗 (0+1+2+3)/4 = 1.5 份
//    → A 消耗更快，A 先空的概率 > 0.5
//    → n 越大，这个统计优势越明显，概率趋近 1.0
//
// 3. 经计算 n >= 4800 时概率 > 1 - 1e-5，可直接返回 1.0
//
// 4. dfs(a, b) 含义: A 剩 a 份、B 剩 b 份时的目标概率
//    边界:
//      a<=0 && b<=0 → 0.5 (同时用完)
//      a<=0 && b>0  → 1.0 (A 先用完)
//      a>0 && b<=0  → 0.0 (B 先用完)
//    递推:
//      dfs(a,b) = 0.25 * [dfs(a-4,b) + dfs(a-3,b-1) + dfs(a-2,b-2) + dfs(a-1,b-3)]
//
// 验证:
// n=50 → k=2
// dfs(2,2) = 0.25 * [dfs(-2,2) + dfs(-1,1) + dfs(0,0) + dfs(1,-1)]
//          = 0.25 * [1.0 + 1.0 + 0.5 + 0.0]
//          = 0.625 ✓
// ============================================================
class Solution1 {
public:
    unordered_map<int, double> memo;

    double soupServings(int n) {
        // 大 n 剪枝: A 先空的概率已超过 1 - 1e-5
        if (n >= 4800) return 1.0;

        // 除以 25 向上取整，简化状态空间
        n = (n + 24) / 25;
        return dfs(n, n);
    }

    double dfs(int a, int b) {
        // 边界: 注意先判断同时用完
        if (a <= 0 && b <= 0) return 0.5;
        if (a <= 0) return 1.0;
        if (b <= 0) return 0.0;

        // 状态编码: a, b 均 < 200，用 a*200+b 作为唯一 key
        int key = a * 200 + b;
        if (memo.count(key)) return memo[key];

        // 四种操作等概率 (各 0.25)
        double prob = 0.25 * (
            dfs(a - 4, b    ) +   // A倒4份, B倒0份
            dfs(a - 3, b - 1) +   // A倒3份, B倒1份
            dfs(a - 2, b - 2) +   // A倒2份, B倒2份
            dfs(a - 1, b - 3)     // A倒1份, B倒3份
        );

        return memo[key] = prob;
    }
};

// ============================================================
// 解法2: 自底向上 DP
// 时间: O(k^2)  空间: O(k^2)
//
// 【思路】
// 和解法1 完全相同的状态定义和转移方程，
// 用二维数组迭代填表代替递归。
// dp[i][j] = A 剩 i 份、B 剩 j 份时的目标概率。
//
// 注意: 转移时 i-4 等可能为负，用 max(0, i-4) 处理
// (因为 a<=0 时等价于已经用完，由边界条件处理)
// ============================================================
class Solution2 {
public:
    double soupServings(int n) {
        if (n >= 4800) return 1.0;
        n = (n + 24) / 25;

        // dp[i][j]: A 剩 i 份、B 剩 j 份时的目标概率
        vector<vector<double>> dp(n + 1, vector<double>(n + 1, 0.0));

        // 边界: dp[0][j] = 1.0 (A 先用完, j > 0)
        // dp[0][0] = 0.5 (同时用完)
        dp[0][0] = 0.5;
        for (int j = 1; j <= n; j++) {
            dp[0][j] = 1.0;
        }
        // dp[i][0] = 0.0 (B 先用完, i > 0) — 已初始化为 0

        // 填表: 从小到大遍历
        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= n; j++) {
                // 四种操作，注意下标不能为负
                // 当 a-k <= 0 时对应 dp[0][...] 已经设好边界
                auto get = [&](int a, int b) -> double {
                    if (a <= 0 && b <= 0) return 0.5;
                    if (a <= 0) return 1.0;
                    if (b <= 0) return 0.0;
                    return dp[a][b];
                };

                dp[i][j] = 0.25 * (
                    get(i - 4, j    ) +
                    get(i - 3, j - 1) +
                    get(i - 2, j - 2) +
                    get(i - 1, j - 3)
                );
            }
        }

        return dp[n][n];
    }
};

// ============================================================
// 【解法对比】
// | 解法 | 优点 | 缺点 |
// |------|------|------|
// | 记忆化搜索 | 代码直观，自然处理负下标 | 递归栈开销 |
// | 自底向上 DP | 无递归开销 | 需要额外处理负下标边界 |
//
// 两种解法时间空间复杂度相同，面试中推荐记忆化搜索（更好写）。
//
// 【易错点】
// 1. 忘记大 n 剪枝:
//    ✗ 直接 DP n=1e9 → MLE/TLE
//    ✓ n >= 4800 返回 1.0
//
// 2. 向上取整写错:
//    ✗ n = n / 25 (50mL → 2份 ok，但 51mL 应该是 3 份而非 2 份)
//    ✓ n = (n + 24) / 25
//
// 3. 边界条件顺序:
//    ✗ 先判断 a<=0 再判断 a<=0&&b<=0 → 同时用完的 0.5 被 1.0 覆盖
//    ✓ 先判断同时用完 (a<=0 && b<=0 → 0.5)
//
// 4. 状态编码冲突:
//    ✗ key = a * 100 + b (当 a=1,b=100 和 a=2,b=0 冲突)
//    ✓ key = a * 200 + b (因为 k <= 192 < 200)
//
// 【面试追问】
// Q1: 为什么 4800 是安全阈值？(A 平均消耗 2.5/轮 vs B 1.5/轮，
//     CLT 保证大样本下 A 几乎一定先用完)
// Q2: 操作概率不均等怎么改？(加权求和，阈值需重算)
// Q3: 迭代 DP 怎么处理负下标？(用 max(0,x) 或 lambda 封装边界判断)
// ============================================================
