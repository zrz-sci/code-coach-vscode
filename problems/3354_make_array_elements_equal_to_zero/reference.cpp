// =====================================================
// 3354. Make Array Elements Equal to Zero
// 标签: Array, Prefix Sum, Simulation
// 难度: Easy
// =====================================================

// 解法1: 暴力模拟 — O(n * totalSum) / O(n)
//
// 思考过程:
//   对每个 nums[i] == 0 的位置，分别模拟向左和向右出发:
//   - 当 pos 在范围内时:
//     - 如果 arr[pos] == 0，沿当前方向继续走
//     - 如果 arr[pos] > 0，减 1，反转方向，沿新方向走一步
//   - 走出边界后检查数组是否全零
//
//   数据范围 n<=100, 元素<=100，暴力完全可行。
class Solution1 {
public:
    int countValidSelections(vector<int>& nums) {
        int n = nums.size(), ans = 0;

        for (int i = 0; i < n; i++) {
            if (nums[i] != 0) continue;

            // 尝试两个方向: -1=向左, 1=向右
            for (int dir : {-1, 1}) {
                // 拷贝数组 (每次模拟会修改)
                vector<int> arr(nums.begin(), nums.end());
                int pos = i, d = dir;

                // 模拟弹球过程
                while (pos >= 0 && pos < n) {
                    if (arr[pos] == 0) {
                        // 当前位置为 0, 沿当前方向继续
                        pos += d;
                    } else {
                        // 当前位置 > 0, 消耗并反弹
                        arr[pos]--;  // 消耗 1
                        d = -d;      // 反转方向
                        pos += d;    // 沿新方向走一步
                    }
                }

                // 检查是否所有元素归零
                bool allZero = true;
                for (int x : arr) {
                    if (x != 0) { allZero = false; break; }
                }
                if (allZero) ans++;
            }
        }
        return ans;
    }
};


// =====================================================
// 解法2: 前缀和 + 数学推导（最优解）⭐ — O(n) / O(1)
//
// 核心洞察:
//   弹球从位置 i 出发，向左走消耗左侧元素和 L，向右走消耗右侧元素和 R。
//   交替反弹的过程，最终能否全部清零，取决于 L 和 R 的关系:
//
//   - L == R      → 两个方向都有效 → +2
//     (完全平衡，无论先走哪边都能清完)
//
//   - |L - R| == 1 → 恰好一个方向有效 → +1
//     (先向"重的"那边走才能清完)
//
//   - |L - R| >= 2 → 两个方向都无效 → +0
//     (差太大，无论怎么走都有剩余)
//
// 推导:
//   先向左走: 弹球交替清扫左右，左边被清扫的轮次 = ceil((清扫总轮次)/2)
//   有效条件: L == R (偶数轮完美清零) 或 L == R-1 (奇数轮多清右边一个)
//   先向右走: 对称，R == L 或 R == L-1
//   合并: L==R → +2; |L-R|==1 → +1; 否则 → +0
//
// 实现:
//   totalSum 预算。遍历时 leftSum 递增，rightSum = totalSum - leftSum。
class Solution2 {
public:
    int countValidSelections(vector<int>& nums) {
        // 预计算总和
        int totalSum = 0;
        for (int x : nums) totalSum += x;

        int leftSum = 0, ans = 0;
        for (int i = 0; i < (int)nums.size(); i++) {
            if (nums[i] == 0) {
                int rightSum = totalSum - leftSum;

                if (leftSum == rightSum) {
                    // 完全平衡: 两个方向都有效
                    ans += 2;
                } else if (abs(leftSum - rightSum) == 1) {
                    // 差1: 恰好一个方向有效
                    ans += 1;
                }
                // 差 >= 2: 无效, 不加
            }
            // 注意: 在判断之后再更新 leftSum
            leftSum += nums[i];
        }
        return ans;
    }
};


// =====================================================
// 验证示例
//
// 示例1: nums = [1,0,2,0,3], totalSum = 6
//   i=0: nums[0]=1, skip. leftSum=1
//   i=1: nums[1]=0, L=1, R=6-1=5, |diff|=4 → +0. leftSum=1
//   i=2: nums[2]=2, skip. leftSum=3
//   i=3: nums[3]=0, L=3, R=6-3=3, diff=0 → +2. leftSum=3
//   i=4: nums[4]=3, skip. leftSum=6
//   结果: 2 ✓
//
// 示例2: nums = [2,3,4,0,4,1,0], totalSum = 14
//   i=3: nums[3]=0, L=2+3+4=9, R=14-9=5, |diff|=4 → +0
//   i=6: nums[6]=0, L=2+3+4+0+4+1=14, R=14-14=0, |diff|=14 → +0
//   结果: 0 ✓


/*
 * =====================================================
 * 解法对比
 * =====================================================
 *
 * | 解法       | 时间              | 空间   | 适用场景           |
 * |------------|------------------|--------|-------------------|
 * | Solution1  | O(n * totalSum)  | O(n)   | 保底方案, 直接模拟  |
 * | Solution2  | O(n)             | O(1)   | 最优解, 前缀和      |
 *
 * =====================================================
 * 易错点 (具体 bug)
 * =====================================================
 *
 * 1. leftSum 更新时机错误:
 *    应该在判断 nums[i]==0 之后再 leftSum += nums[i]
 *    如果先更新, 当 nums[i]==0 时 leftSum 不受影响但逻辑混乱
 *
 * 2. 忘记 abs():
 *    条件是 |L-R| == 1, 不是 L-R == 1
 *    漏掉 R > L 的情况会少算方案
 *
 * 3. 暴力模拟忘记拷贝数组:
 *    每次模拟修改数组, 不拷贝的话第二个方向基于已修改的数组
 *
 * 4. 暴力模拟反转方向后忘移动:
 *    反转 d=-d 后还需 pos+=d, 题目要求"反转并走一步"
 *
 * 5. 差值 >= 2 时误加:
 *    只有 diff==0 或 diff==1 才有效, 其他情况不加
 *
 * =====================================================
 * 面试追问
 * =====================================================
 *
 * Q1: 如何发现前缀和规律?
 * A:  手动模拟 [1,0,1], [2,0,1], [1,0,2] 等小例子,
 *     观察有效条件与左右和的关系。
 *
 * Q2: 如果数组中没有 0?
 * A:  题目保证至少一个 0。但如果没有, 答案就是 0。
 *
 * Q3: 暴力模拟的时间复杂度?
 * A:  每次最多走 totalSum + n 步, 共 O(n) 个起点 * 2 方向,
 *     总共 O(n * totalSum), n<=100 时约 2*10^6。
 *
 * Q4: 能否进一步优化?
 * A:  O(n) 已是下界(需读完数组), O(1) 空间已最优。
 */
