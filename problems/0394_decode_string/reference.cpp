/*
 * LeetCode 394: 字符串解码 (Decode String)
 *
 * 【题目本质】
 * 解析嵌套的 k[encoded_string] 格式，展开重复。
 * 本质是嵌套结构的解析，天然适合栈或递归。
 *
 * 【解法总览】
 * 解法1: 栈模拟      — O(N) / O(N) — 面试首选，显式栈处理嵌套
 * 解法2: 递归解析    — O(N) / O(N) — 代码更简洁，隐式调用栈
 *
 * 其中 N 是解码后字符串的总长度。
 */

// ============================================================
// 解法1: 栈模拟 — 遇 '[' 存档压栈，遇 ']' 读档弹栈
// 时间: O(N)  空间: O(N)  （N = 解码后字符串长度）
//
// 【思路】
// 嵌套括号 → 先进后出 → 栈。
// 
// 核心想法：维护"当前层"的两个状态：
//   - currStr: 当前层正在拼接的字符串
//   - currNum: 当前正在解析的数字
//
// 遇到四种字符的处理：
//   数字 → 累积到 currNum（注意多位数）
//   '['  → 把 (currStr, currNum) 压栈存档，然后重置开始新层
//   ']'  → 弹栈读档，把当前层结果重复后拼到上一层
//   字母 → 直接追加到 currStr
//
// 以 "3[a2[c]]" 为例:
//
//   字符  | 动作                | 栈                  | currStr | currNum
//   '3'   | 累积数字            | []                  | ""      | 3
//   '['   | 压栈("",3), 重置    | [("",3)]            | ""      | 0
//   'a'   | 追加字母            | [("",3)]            | "a"     | 0
//   '2'   | 累积数字            | [("",3)]            | "a"     | 2
//   '['   | 压栈("a",2), 重置   | [("",3),("a",2)]    | ""      | 0
//   'c'   | 追加字母            | [("",3),("a",2)]    | "c"     | 0
//   ']'   | 弹出("a",2)         | [("",3)]            | "acc"   | 0
//         | currStr = "a"+"c"*2                        |         |
//   ']'   | 弹出("",3)          | []                  |"accaccacc"| 0
//         | currStr = ""+"acc"*3                        |         |
//
// ============================================================
class Solution1 {
public:
    string decodeString(string s) {
        stack<pair<string, int>> stk; // <之前拼好的串, 重复次数>
        string currStr = "";
        int currNum = 0;
        
        for (char c : s) {
            if (isdigit(c)) {
                // 数字可能是多位的（如 100[a]），逐位累积
                currNum = currNum * 10 + (c - '0');
            } else if (c == '[') {
                // 存档：保存当前层的上下文
                stk.push({currStr, currNum});
                // 重置：进入新的一层
                currStr = "";
                currNum = 0;
            } else if (c == ']') {
                // 读档：恢复上一层的上下文
                auto [prevStr, repeatCount] = stk.top();
                stk.pop();
                // 当前层重复 repeatCount 次，拼到上一层后面
                string repeated = "";
                for (int i = 0; i < repeatCount; i++) {
                    repeated += currStr;
                }
                currStr = prevStr + repeated;
            } else {
                // 普通字母，直接追加到当前层
                currStr += c;
            }
        }
        
        return currStr;
    }
};

// ============================================================
// 解法2: 递归解析 — 把嵌套结构看成递归定义
// 时间: O(N)  空间: O(N)
//
// 【思路】
// k[encoded_string] 的结构天然是递归的：
//   encoded_string 内部可能还有 k[...]
//
// 用一个共享索引 i 驱动扫描：
//   - 遇到数字：解析完整数字，然后跳过 '['，递归处理内部
//   - 遇到字母：直接追加
//   - 遇到 ']' ：返回当前层的结果（让调用者跳过 ']'）
//
// 递归调用关系（以 "3[a2[c]]" 为例）:
//
//   decode(s, i=0):
//     解析数字 3, 跳过 '['
//     ├── decode(s, i=2):  // 处理 "a2[c]"
//     │     追加 'a'
//     │     解析数字 2, 跳过 '['
//     │     ├── decode(s, i=5):  // 处理 "c"
//     │     │     追加 'c'
//     │     │     遇到 ']' → 返回 "c"
//     │     跳过 ']', inner="c", 重复2次 → result="acc"
//     │     遇到 ']' → 返回 "acc"
//     跳过 ']', inner="acc", 重复3次 → result="accaccacc"
//
// 关键：i 必须是引用传递 (int& i)，
//       这样所有递归层共享同一个扫描位置。
// ============================================================
class Solution2 {
public:
    string decodeString(string s) {
        int i = 0;
        return decode(s, i);
    }
    
private:
    // i 是引用！所有递归层共享扫描位置
    string decode(const string& s, int& i) {
        string result = "";
        
        // 扫描直到遇到 ']' 或字符串结尾
        while (i < (int)s.size() && s[i] != ']') {
            if (isdigit(s[i])) {
                // 解析完整的多位数字
                int num = 0;
                while (i < (int)s.size() && isdigit(s[i])) {
                    num = num * 10 + (s[i] - '0');
                    i++;
                }
                
                // 此时 s[i] == '['，跳过它
                i++;
                
                // 递归解析括号内的内容
                string inner = decode(s, i);
                
                // 此时 s[i] == ']'，跳过它
                // （约定：decode 返回时 i 指向 ']'，由调用者跳过）
                i++;
                
                // 重复 num 次拼接
                for (int j = 0; j < num; j++) {
                    result += inner;
                }
            } else {
                // 普通字母，直接追加
                result += s[i];
                i++;
            }
        }
        
        // 返回时 i 指向 ']' 或已到末尾
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 特性         | 解法1: 栈模拟           | 解法2: 递归解析          |
// |-------------|------------------------|------------------------|
// | 核心思想     | 显式栈存档/读档         | 隐式调用栈处理嵌套       |
// | 代码风格     | 迭代，一个 for 循环     | 递归，层次更清晰          |
// | 扩展性       | 容易改成处理其他格式     | 天然适合语法解析类题       |
// | 面试推荐     | ⭐ 更通用              | 代码更简洁优雅            |
//
// 时间和空间复杂度相同，面试中写哪个都行，
// 但建议能说出两种思路。
//
// ============================================================
// 【易错点】
//
// 1. 多位数字没处理:
//    ✗ int num = s[i] - '0';    // 只读一位，"100[a]" 会当成 1
//    ✓ while循环累积: num = num * 10 + (s[i] - '0');
//
// 2. 栈解法遇到 '[' 时忘记重置:
//    ✗ 压栈后没有 currStr = ""; currNum = 0;
//      → 新层会把上一层的内容混进来
//    ✓ 压栈后立即重置这两个变量
//
// 3. 递归解法中 i 不用引用:
//    ✗ string decode(const string& s, int i)
//      → 每层递归有自己的 i，返回后扫描位置没更新，死循环
//    ✓ string decode(const string& s, int& i)
//
// 4. 递归解法中 ']' 跳过时机:
//    ✗ decode 内部遇到 ']' 时 i++ 后再返回
//      → 调用者也 i++ 导致多跳一个字符
//    ✓ 约定: decode 返回时 i 指向 ']'，由调用者负责 i++
//
// 5. 栈中 pair 的顺序搞反:
//    ✗ 压栈 {currNum, currStr} 弹栈时按 {prevStr, repeatCount} 解构
//    ✓ 压栈和弹栈的顺序要一致
//
// ============================================================
// 【面试追问】
//
// Q1: 能不能不用额外空间？
// → 不行。嵌套结构天然需要 O(嵌套深度) 的空间记录上下文。
//   嵌套深度最多约 n/4（每层至少 "k[" 和 "]"），所以空间 O(n)。
//
// Q2: 如果输入可能不合法（括号不匹配、格式错误），怎么处理？
// → 解析前先用栈验证括号匹配 + 检查 '[' 前必须有数字。
//   或在解析过程中遇到异常格式抛出异常/返回 error string。
//
// Q3: 如果结果字符串极长，不能放内存，只能流式逐字符输出？
// → 改成惰性求值：用栈记录嵌套结构和重复次数，
//   用迭代器逐字符输出，记录"当前在第几层、第几次重复、第几个字符"。
//   本质是把递归展开成状态机。
//
