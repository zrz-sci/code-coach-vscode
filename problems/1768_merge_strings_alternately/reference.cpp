/*
 * LeetCode 1768: 交替合并字符串 (Merge Strings Alternately)
 *
 * 【题目本质】
 * 拉链合并：两个字符串交替取字符，短的用完后追加长的剩余部分。
 *
 * 【解法总览】
 * 解法1: 分段拼接    — O(n+m) / O(1) — 最直觉，分两阶段处理
 * 解法2: 双指针      — O(n+m) / O(1) — 一趟循环统一处理（面试首选）
 * 解法3: 单指针变体  — O(n+m) / O(1) — 利用对称消费的特点简化
 */

// ============================================================
// 解法1: 分段拼接
// 时间: O(n+m)  空间: O(1)（除输出外）
//
// 【思路】
// 最朴素的想法：先处理两个字符串都有字符的部分（交替取），
// 再把较长那个的剩余部分整段追加。
// 这样逻辑分明，但代码分成了两段。
//
// 交替合并可视化 (word1="abcd", word2="pq"):
//   阶段1 (i < minLen=2): 取 a,p,b,q → "apbq"
//   阶段2 (追加剩余):     word1 剩 "cd" → "apbqcd"
//                          word2 剩 "" → 不变
// ============================================================
class Solution1 {
public:
    string mergeAlternately(string word1, string word2) {
        string result;
        int n = word1.size(), m = word2.size();
        int minLen = min(n, m);

        // 阶段1：交替拼接公共长度部分
        for (int i = 0; i < minLen; i++) {
            result += word1[i];
            result += word2[i];
        }

        // 阶段2：追加剩余部分
        // 两行都写，因为只有较长的那个会真正追加内容
        // substr(minLen) 在 minLen == size() 时返回空串，安全
        result += word1.substr(minLen);
        result += word2.substr(minLen);

        return result;
    }
};

// ============================================================
// 解法2: 双指针一趟遍历 ⭐ 面试首选
// 时间: O(n+m)  空间: O(1)（除输出外）
//
// 【思路】
// 解法1 把逻辑分成了"交替"和"追加"两段，不够优雅。
// 观察：无论是交替阶段还是追加阶段，本质都是——
//   "word1 有字符就取一个，word2 有字符就取一个"。
// 用双指针 i,j，循环条件 i<n || j<m，每轮按条件取字符即可。
// 一个循环搞定所有情况。
//
// 指针移动过程 (word1="ab", word2="pqrs"):
//   i=0,j=0: 取 word1[0]='a', word2[0]='p' → "ap"
//   i=1,j=1: 取 word1[1]='b', word2[1]='q' → "apbq"
//   i=2,j=2: i>=n 跳过, 取 word2[2]='r'   → "apbqr"
//   i=2,j=3: i>=n 跳过, 取 word2[3]='s'   → "apbqrs"
//   i=2,j=4: 都越界，结束
//
// 为什么循环条件是 || 而不是 &&？
//   && 会在短的用完时就停止，丢掉长的剩余字符。
//   || 确保两边都用完才停止。
// ============================================================
class Solution2 {
public:
    string mergeAlternately(string word1, string word2) {
        string result;
        int i = 0, j = 0;
        int n = word1.size(), m = word2.size();

        // 只要任意一个字符串还有字符，就继续
        while (i < n || j < m) {
            // 先取 word1 的（保证 word1 在前）
            if (i < n) result += word1[i++];
            // 再取 word2 的
            if (j < m) result += word2[j++];
        }

        return result;
    }
};

// ============================================================
// 解法3: 单指针变体
// 时间: O(n+m)  空间: O(1)（除输出外）
//
// 【思路】
// 观察解法2：i 和 j 每轮都各自 +1，始终保持 i == j。
// 既然两个指针同步递增，那用一个指针 i 就够了。
// 循环范围：i 从 0 到 max(n,m)-1。
// 每轮：如果 i < n 就取 word1[i]，如果 i < m 就取 word2[i]。
//
// 注意：这个简化只在"对称消费"时成立。
// 如果题目改成 word1 每次取2个、word2 每次取1个，就不能这样简化了。
// ============================================================
class Solution3 {
public:
    string mergeAlternately(string word1, string word2) {
        string result;
        int n = word1.size(), m = word2.size();

        for (int i = 0; i < max(n, m); i++) {
            if (i < n) result += word1[i];
            if (i < m) result += word2[i];
        }

        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法   | 循环结构     | 代码量 | 扩展性                   |
// |--------|-------------|--------|--------------------------|
// | 分段拼接| 两段(for+追加)| 稍多  | 逻辑分明但不够统一        |
// | 双指针  | 一个while    | 简洁  | 通用，不对称场景也适用     |
// | 单指针  | 一个for      | 最简  | 仅对称消费场景            |
//
// 面试推荐：解法2 双指针。
// 理由：它是"合并两个序列"的通用模板（归并排序 merge、
// 合并有序链表等都用同样的框架），展示出你理解双指针的套路。
//
// 【易错点】
// 1. 循环条件写成 && 而不是 ||：
//    ✗ while (i < n && j < m) — 短的用完就停了，长的剩余丢失
//    ✓ while (i < n || j < m) — 两边都用完才停
//
// 2. 取字符前忘记边界检查：
//    ✗ result += word1[i++];  // i 可能已经 >= n，越界访问！
//    ✓ if (i < n) result += word1[i++];
//
// 3. size() 返回 size_t (unsigned)，和 int 比较可能有警告：
//    ✗ for (int i = 0; i < word1.size(); ...)  // signed vs unsigned
//    ✓ int n = word1.size(); for (int i = 0; i < n; ...)
//
// 【面试追问】
// Q1（基础）：时间复杂度能比 O(n+m) 更低吗？
//    → 不能。结果长度就是 n+m，构建它至少 O(n+m)。
//
// Q2（优化）：大字符串场景下有什么常数优化？
//    → result.reserve(n + m) 提前分配空间，避免 string 多次扩容拷贝。
//
// Q3（变体）：如果是 K 个字符串交替合并呢？
//    → K 个指针数组，外层按轮次循环，内层遍历 K 个字符串各取一个。
//       时间 O(所有字符串长度之和)。
//
// Q4（变体）：如果 word1 每次取 2 个、word2 每次取 1 个呢？
//    → 必须用双指针(i,j)，每轮 i+=2, j+=1，取字符时逐个检查边界。
// ============================================================
