/*
 * LeetCode 927: Three Equal Parts (三等分)
 *
 * 【题目本质】
 * 将只含0和1的数组分成三个非空部分，使三部分代表的二进制值相等。
 * 核心问题：如何在 O(n) 时间内确定分割点，使三段的二进制表示完全一致。
 *
 * 【解法总览】
 * 解法1: 计数1 + 三指针同步比较 — O(n) / O(1) — 唯一最优解
 */

// ============================================================
// 解法1: 计数1 + 三指针同步比较
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 三段二进制值相等 → 去掉前导零后的位模式完全一样。
// 因此三段中1的个数必须相等 → totalOnes % 3 == 0。
//
// 核心观察：
//   1. 第三段延伸到数组末尾，其末尾0的个数固定不变。
//   2. 第一段和第二段的末尾0可以从段间间隔"借用"。
//   3. 三段从各自第一个1开始的位模式必须完全相同。
//
// 算法：
//   1. 统计 totalOnes，若不能被3整除则无解
//   2. 若 totalOnes == 0，全0数组任意分均可
//   3. 找到每段第一个1的位置 p1, p2, p3
//   4. 三指针同步前进比较，直到 p3 到达末尾
//   5. 比较成功后 i = p1-1, j = p2 就是分割点
//
// 为什么同步比较就能处理末尾0？
//   第三段从 p3 开始一直到数组末尾，包含了有效位和末尾0。
//   p1 和 p2 同步推进，自然也会走过同样多的位（包括末尾0）。
//   如果第一段或第二段在1的模式匹配完后空间不够放末尾0，
//   p1 或 p2 会越过下一段的第一个1，导致比较失败。
//
// 示例: arr = [1,0,1,0,1]
//   totalOnes = 3, k = 1
//   p1=0(第1个1), p2=2(第2个1), p3=4(第3个1)
//   比较 arr[0]=1 == arr[2]=1 == arr[4]=1 ✓
//   p1=1, p2=3, p3=5 → p3==n, 停止
//   返回 [p1-1, p2] = [0, 3]
//   验证: [1] | [0,1,0] | [1] → 二进制值都是1 ✓
//
// 示例: arr = [1,1,0,1,1]
//   totalOnes = 4, 4%3 != 0 → 返回 [-1,-1]
//
// 示例: arr = [1,1,0,0,1]
//   totalOnes = 3, k = 1
//   p1=0(第1个1), p2=1(第2个1), p3=4(第3个1)
//   比较 arr[0]=1 == arr[1]=1 == arr[4]=1 ✓
//   p1=1, p2=2, p3=5 → p3==n, 停止
//   返回 [0, 2]
//   验证: [1] | [1,0,0] | [1] → 值都是1 ✓
// ============================================================
class Solution1 {
public:
    vector<int> threeEqualParts(vector<int>& arr) {
        int n = arr.size();

        // 第一步：统计1的个数
        int totalOnes = 0;
        for (int x : arr) totalOnes += x;

        // 1的个数不是3的倍数 → 无解
        if (totalOnes % 3 != 0) return {-1, -1};

        // 特殊情况：没有任何1，全0数组任意分割都行
        if (totalOnes == 0) return {0, 2};

        int k = totalOnes / 3;

        // 第二步：找到每段第一个1的位置
        // p1: 第1个1 (第一段的有效起点)
        // p2: 第k+1个1 (第二段的有效起点)
        // p3: 第2k+1个1 (第三段的有效起点)
        int p1 = -1, p2 = -1, p3 = -1;
        int cnt = 0;
        for (int i = 0; i < n; i++) {
            if (arr[i] == 1) {
                cnt++;
                if (cnt == 1)         p1 = i;
                if (cnt == k + 1)     p2 = i;
                if (cnt == 2 * k + 1) p3 = i;
            }
        }

        // 第三步：三指针同步比较
        // 以第三段为基准（因为第三段末尾由数组末尾决定，不可调）
        // p3 从第三段第一个1开始，一路走到 arr 末尾
        // p1, p2 同步走，逐位比较
        while (p3 < n) {
            if (arr[p1] != arr[p2] || arr[p1] != arr[p3]) {
                return {-1, -1};
            }
            p1++;
            p2++;
            p3++;
        }

        // 比较全部通过：
        // p1 现在是第一段结束后的下一个位置 → i = p1 - 1
        // p2 现在是第二段结束后的下一个位置 → j = p2
        // (因为第三段从 j 开始，即 arr[j..n-1])
        return {p1 - 1, p2};
    }
};

// ============================================================
// 【解法对比】
//
// 本题本质上只有一种最优解法：计数 + 三指针同步比较。
// 其他变体（先提取位模式再比较字符串等）时间空间都不更优，
// 且代码更复杂。
//
// | 方法               | 时间  | 空间  | 说明                       |
// |--------------------|-------|-------|---------------------------|
// | 三指针同步比较     | O(n)  | O(1)  | 最优解，代码简洁            |
// | 提取位模式字符串   | O(n)  | O(n)  | 用字符串存每段的位模式再比较 |
//
// ============================================================
// 【易错点】
//
// 1. 全0特判遗漏:
//    ✗ 跳过全0检查 → totalOnes=0 时 k=0，找"第1个1"会失败
//    ✓ totalOnes==0 时直接返回 {0, 2}
//
// 2. 分割索引含义搞混:
//    第一段: arr[0..i]
//    第二段: arr[i+1..j-1]
//    第三段: arr[j..n-1]
//    ✗ 返回 {p1, p2} → 需要 -1 和不需要 -1 的位置搞反
//    ✓ 返回 {p1-1, p2}
//
// 3. 末尾0的处理理解错误:
//    ✗ 只比较1的模式，忘记末尾0也是二进制值的一部分
//       [1,0] 表示2, [1] 表示1，它们不相等!
//    ✓ 同步比较自动包含了末尾0的匹配
//
// 4. 1的个数分段计算错误:
//    ✗ 第二段从第 k 个1开始 → 实际应该从第 k+1 个1开始
//    ✓ 每段 k 个1: 第一段1~k, 第二段k+1~2k, 第三段2k+1~3k
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 为什么用第三段作为基准？
//     第三段延伸到数组末尾，其内容（包括末尾0）完全固定。
//     而第一段和第二段可以通过调整分割点来"借用"段间的0作为末尾0。
//
// Q2: 如果 totalOnes 很大会不会性能有问题？
//     不会。无论 totalOnes 多大，我们只遍历数组两次（统计 + 比较），
//     每次 O(n)，总时间 O(n)。
//
// Q3: 分成 K 等分怎么办？
//     完全相同的思路：totalOnes 必须是 K 的倍数，找到 K 段各自的
//     第一个1位置，以最后一段为基准 K 指针同步比较。O(n) 时间。
//
