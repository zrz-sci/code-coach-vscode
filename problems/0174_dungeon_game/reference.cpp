/*
 * LeetCode 174: Dungeon Game (地下城游戏)
 *
 * 【题目本质】
 * 骑士从左上角到右下角（只能向右/向下），每个房间有正/负值影响血量。
 * 求进入第一个房间前的最低血量，使得全程血量始终 > 0。
 * 核心问题：正向 DP 无法处理"过程约束"，必须反向 DP。
 *
 * 【解法总览】
 * 解法1: 反向二维DP     — O(mn) / O(mn) — 标准写法
 * 解法2: 反向一维DP     — O(mn) / O(n)  — 空间优化，面试首选
 * 解法3: 二分+正向验证  — O(mn logK)/O(mn) — 不同思路，了解即可
 */

// ============================================================
// 解法1: 反向二维 DP
// 时间: O(mn)  空间: O(mn)
//
// 【思路】
// dp[i][j] = 进入(i,j)前，骑士至少需要多少血量才能活着到达终点。
//
// 状态转移:
//   dp[i][j] = max(min(dp[i+1][j], dp[i][j+1]) - dungeon[i][j], 1)
//
// 解读:
//   - min(下, 右): 选择需要血量更少的方向
//   - 减去 dungeon[i][j]: 如果房间补血则需求减少，损血则需求增加
//   - max(..., 1): 进入任何房间前至少需要 1 HP
//
// 边界:
//   dp[m][n-1] = dp[m-1][n] = 1 (公主房的虚拟出口)
//   其余虚拟边界 = INT_MAX (不可达)
//
// DP 表可视化 (dungeon = [[-2,-3,3],[-5,-10,1],[10,30,-5]]):
//
//   dp:    7   5   2
//          6  11   5
//          1   1   6
//
//   答案 dp[0][0] = 7
//   验证: 7→(7-2=5)→(5-3=2)→(2+3=5)→(5+1=6)→(6-5=1) >= 1 ✓
// ============================================================
class Solution1 {
public:
    int calculateMinimumHP(vector<vector<int>>& dungeon) {
        int m = dungeon.size(), n = dungeon[0].size();

        // dp 多一行一列作为虚拟边界
        vector<vector<int>> dp(m + 1, vector<int>(n + 1, INT_MAX));
        // 公主房间的右边/下边出去后至少需要 1 HP
        dp[m][n - 1] = dp[m - 1][n] = 1;

        // 从右下角往左上角填表
        for (int i = m - 1; i >= 0; i--) {
            for (int j = n - 1; j >= 0; j--) {
                // 选需要血量更少的方向，减去当前房间值，至少为1
                int need = min(dp[i + 1][j], dp[i][j + 1]) - dungeon[i][j];
                dp[i][j] = max(need, 1);
            }
        }
        return dp[0][0];
    }
};

// ============================================================
// 解法2: 反向一维 DP（空间优化） — 面试首选 ⭐
// 时间: O(mn)  空间: O(n)
//
// 【空间优化原理】
// 从下往上、从右往左填表，dp[j] 在更新前存的是"下一行"的值
// (即 dp[i+1][j])，dp[j+1] 在本轮中已更新为当前行的值
// (即 dp[i][j+1])。因此一维数组足够。
//
// 一维 dp 覆盖过程:
//
// 初始:    dp = [INF, INF, 1, INF]   (n=3, dp[n-1]=1, 哨兵dp[3]=INF)
//
// i=2 行 [10, 30, -5]:
//   j=2: max(min(1, INF)-(-5), 1) = 6   dp = [INF, INF, 6, INF]
//   j=1: max(min(INF, 6)-30, 1) = 1     dp = [INF, 1, 6, INF]
//   j=0: max(min(INF, 1)-10, 1) = 1     dp = [1, 1, 6, INF]
//   重置 dp[3]=INF
//
// i=1 行 [-5, -10, 1]:
//   j=2: max(min(6, INF)-1, 1) = 5      dp = [1, 1, 5, INF]
//   j=1: max(min(1, 5)-(-10), 1) = 11   dp = [1, 11, 5, INF]
//   j=0: max(min(1, 11)-(-5), 1) = 6    dp = [6, 11, 5, INF]
//   重置 dp[3]=INF
//
// i=0 行 [-2, -3, 3]:
//   j=2: max(min(5, INF)-3, 1) = 2      dp = [6, 11, 2, INF]
//   j=1: max(min(11, 2)-(-3), 1) = 5    dp = [6, 5, 2, INF]
//   j=0: max(min(6, 5)-(-2), 1) = 7     dp = [7, 5, 2, INF]
//
// 答案: dp[0] = 7 ✓
// ============================================================
class Solution2 {
public:
    int calculateMinimumHP(vector<vector<int>>& dungeon) {
        int m = dungeon.size(), n = dungeon[0].size();
        // dp[j] = 进入当前行第j列前需要的最低血量
        vector<int> dp(n + 1, INT_MAX);
        dp[n - 1] = 1; // 公主房间下方的虚拟出口

        for (int i = m - 1; i >= 0; i--) {
            for (int j = n - 1; j >= 0; j--) {
                // dp[j] = 下方(上一轮值); dp[j+1] = 右方(本轮刚更新)
                dp[j] = max(min(dp[j], dp[j + 1]) - dungeon[i][j], 1);
            }
            // 非最后一行时, 重置哨兵防止干扰
            if (i > 0) dp[n] = INT_MAX;
        }
        return dp[0];
    }
};

// ============================================================
// 解法3: 二分搜索 + 正向验证
// 时间: O(mn log K)  空间: O(mn)
//
// 【思路】
// 二分答案：猜测初始血量 mid，正向 DP 检验能否活着到达终点。
// 如果能存活则尝试更小的血量(hi=mid)，否则增加(lo=mid+1)。
//
// canSurvive 的正向 DP:
//   dp[i][j] = 以初始血量 hp 出发，到达(i,j)后的最大可能血量
//   选上/左中最大血量的路径到达，如果 <= 0 则标记不可达(0)
// ============================================================
class Solution3 {
public:
    int calculateMinimumHP(vector<vector<int>>& dungeon) {
        int m = dungeon.size(), n = dungeon[0].size();
        int lo = 1, hi = 1;
        // 估算上界: 最坏情况全部损血
        for (auto& row : dungeon)
            for (int v : row)
                if (v < 0) hi -= v;
        hi = max(hi, 1);

        while (lo < hi) {
            int mid = lo + (hi - lo) / 2;
            if (canSurvive(dungeon, mid, m, n))
                hi = mid;
            else
                lo = mid + 1;
        }
        return lo;
    }

private:
    bool canSurvive(vector<vector<int>>& d, int hp, int m, int n) {
        vector<vector<int>> dp(m, vector<int>(n, 0));
        dp[0][0] = hp + d[0][0];
        if (dp[0][0] <= 0) return false;

        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (i == 0 && j == 0) continue;
                int best = 0;
                if (i > 0 && dp[i-1][j] > 0) best = max(best, dp[i-1][j]);
                if (j > 0 && dp[i][j-1] > 0) best = max(best, dp[i][j-1]);
                if (best == 0) { dp[i][j] = 0; continue; }
                dp[i][j] = best + d[i][j];
                if (dp[i][j] <= 0) dp[i][j] = 0;
            }
        }
        return dp[m-1][n-1] > 0;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法          | 时间         | 空间   | 代码量 | 推荐  |
// |---------------|-------------|--------|--------|-------|
// | 反向二维 DP   | O(mn)       | O(mn)  | 短     | ⭐    |
// | 反向一维 DP   | O(mn)       | O(n)   | 最短   | ⭐首选|
// | 二分+正向验证 | O(mn logK)  | O(mn)  | 长     | 了解  |
//
// 面试策略: 先解释为什么不能正向 DP, 然后写反向一维 DP。
//
// ============================================================
// 【易错点】
//
// 1. 尝试正向 DP:
//    ✗ dp[i][j] = 从起点到(i,j)需要的最低血量 → 最优子结构不成立
//    ✓ 反向: dp[i][j] = 从(i,j)到终点需要的最低入口血量
//
// 2. 忘记 max(..., 1):
//    ✗ dp[i][j] = min(下,右) - dungeon[i][j]  → 补血房可能算出0或负数
//    ✓ dp[i][j] = max(min(下,右) - dungeon[i][j], 1)
//
// 3. 边界初始化错误:
//    ✗ dp[m-1][n-1] 特殊处理, 最后一行/列单独处理 → 容易写错
//    ✓ 用(m+1)x(n+1)的dp, 虚拟边界统一处理
//
// 4. 一维DP哨兵未重置:
//    ✗ dp[n]在第一轮后可能变为有限值
//    ✓ 每行处理完后(非最后一行时)重置 dp[n]=INT_MAX
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 为什么不能正向 DP？
//     正向 dp[i][j] 的"最优路径"取决于后面遇到什么。
//     两条到达(i,j)的路径，一条总和大但有极低点，另一条总和小但
//     没极低点。无法在(i,j)处判断哪条更优，因为取决于后续路径。
//
// Q2: 如何输出最优路径？
//     在反向 DP 中记录每个格子的选择方向(右 or 下)到 choice 数组。
//     然后从(0,0)沿 choice 还原路径。
//
// Q3: 这题和 LC64 有什么区别？
//     LC64 无过程约束，只需路径总和最小 → 正向 DP。
//     本题有过程约束(每步血量>0) → 必须反向 DP。
//
// ============================================================
// 【相关题型】
//
// - 64. 最小路径和:
//   正向 DP 对比。同样网格路径，但无过程约束，正向就行。
//
// - 62. 不同路径:
//   最基础的网格路径 DP，可用反向填表思路。
//
// - 741. 摘樱桃:
//   更复杂的路径 DP，两人同时走。类似的"路径过程约束"。
// ============================================================
