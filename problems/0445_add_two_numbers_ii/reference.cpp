/*
 * LeetCode 445: Add Two Numbers II (两数相加 II)
 *
 * 【题目本质】
 * 链表版大数相加，但链表高位在前。
 * 加法必须从低位开始，所以需要"反转访问顺序"。
 * 核心选择：反转链表 OR 用栈 模拟反转。
 *
 * 【解法总览】
 * 解法1: 反转链表法   — O(n+m) / O(1)   — 修改原链表
 * 解法2: 双栈 + 头插法 — O(n+m) / O(n+m) — 不修改原链表 ⭐ 推荐
 */

// ============================================================
// 解法1: 反转链表法 — 反转两个链表，按 LC 2 方式相加，再反转结果
// 时间: O(n+m)  空间: O(1)（不计输出链表）
//
// 【思路】
// 链表高位在前 → 反转后低位在前 → 和 LC 2 完全一样。
// 加完后结果也是低位在前 → 再反转一次变回高位在前。
//
// 指针图 (l1 = [7,2,4,3], l2 = [5,6,4]):
//
//   原始:  l1: 7 -> 2 -> 4 -> 3     (表示 7243)
//          l2: 5 -> 6 -> 4           (表示  564)
//
//   反转:  l1: 3 -> 4 -> 2 -> 7
//          l2: 4 -> 6 -> 5
//
//   逐位相加:
//     3+4     = 7,  carry=0  → [7]
//     4+6     = 10, carry=1  → [7] -> [0]
//     2+5+1   = 8,  carry=0  → [7] -> [0] -> [8]
//     7+0     = 7,  carry=0  → [7] -> [0] -> [8] -> [7]
//
//   反转结果: [7] -> [8] -> [0] -> [7]  = 7807
//
// 【优缺点】
// + 空间 O(1)（只用指针操作）
// - 修改了原始链表（破坏性操作）
// - 如果要保留原链表，需要加完后再反转回去，代码更复杂
// ============================================================
class Solution1 {
public:
    // 辅助函数：反转单链表（迭代法）
    //
    //  反转过程:
    //    prev   curr   next
    //    null    7 -> 2 -> 4 -> 3 -> null
    //    7       2 -> 4 -> 3 -> null          (7->null)
    //    7<-2    4 -> 3 -> null
    //    7<-2<-4 3 -> null
    //    7<-2<-4<-3  null
    //    返回 prev = 3
    ListNode* reverseList(ListNode* head) {
        ListNode* prev = nullptr;
        while (head) {
            ListNode* next = head->next;
            head->next = prev;  // 当前节点指向前一个
            prev = head;        // prev 前进
            head = next;        // head 前进
        }
        return prev;
    }

    ListNode* addTwoNumbers(ListNode* l1, ListNode* l2) {
        // Step 1: 反转两个链表
        l1 = reverseList(l1);
        l2 = reverseList(l2);

        // Step 2: 从低位到高位逐位相加（和 LC 2 完全一样）
        ListNode dummy(0);       // 哨兵节点，简化头节点处理
        ListNode* cur = &dummy;
        int carry = 0;

        while (l1 || l2 || carry) {
            int sum = carry;
            if (l1) { sum += l1->val; l1 = l1->next; }
            if (l2) { sum += l2->val; l2 = l2->next; }
            carry = sum / 10;
            cur->next = new ListNode(sum % 10);
            cur = cur->next;
        }

        // Step 3: 反转结果链表（当前结果是低位在前）
        return reverseList(dummy.next);
    }
};

// ============================================================
// 解法2: 双栈 + 头插法 — 用栈模拟反转访问，不修改原链表
// 时间: O(n+m)  空间: O(n+m)
//
// 【思路】
// 栈 = "先进后出"。把链表值依次入栈，弹出时自然从低位开始。
// 用头插法构建结果：每次新节点插在链表最前面，
// 低位先算出但放在后面，高位后算出但放在前面 → 结果自然高位在前。
//
// 指针图 (l1 = [7,2,4,3], l2 = [5,6,4]):
//
//   Step 1: 遍历链表，值入栈
//     l1: 7 -> 2 -> 4 -> 3
//     s1:  ┌───┐
//          │ 3 │ ← top
//          │ 4 │
//          │ 2 │
//          │ 7 │
//          └───┘
//
//     l2: 5 -> 6 -> 4
//     s2:  ┌───┐
//          │ 4 │ ← top
//          │ 6 │
//          │ 5 │
//          └───┘
//
//   Step 2: 弹栈相加 + 头插法
//
//     pop s1=3, s2=4: sum=7,  carry=0, digit=7
//     head: [7] -> null
//                ↑ head 指向这里
//
//     pop s1=4, s2=6: sum=10, carry=1, digit=0
//     head: [0] -> [7] -> null
//            ↑ 新节点插在头部
//
//     pop s1=2, s2=5: sum=7+1=8, carry=0, digit=8
//     head: [8] -> [0] -> [7] -> null
//
//     pop s1=7, s2空: sum=7, carry=0, digit=7
//     head: [7] -> [8] -> [0] -> [7] -> null
//
//   结果: 7807 ✓
//
// 【为什么推荐这个解法】
// 1. 不修改原链表（满足 Follow-up）
// 2. 代码简洁（核心只有一个 while 循环）
// 3. 头插法免去了最终反转结果的步骤
// ============================================================
class Solution2 {
public:
    ListNode* addTwoNumbers(ListNode* l1, ListNode* l2) {
        stack<int> s1, s2;

        // 将两个链表的值分别压入栈
        // 遍历后，栈顶是链表尾部（最低位）
        for (ListNode* p = l1; p; p = p->next) s1.push(p->val);
        for (ListNode* p = l2; p; p = p->next) s2.push(p->val);

        int carry = 0;
        ListNode* head = nullptr;

        // 从低位到高位逐位相加
        // 循环条件包含 carry：确保最高位进位不丢失
        // 例: 999 + 1 = 1000，最后 carry=1 需要额外创建节点
        while (!s1.empty() || !s2.empty() || carry) {
            int sum = carry;
            if (!s1.empty()) { sum += s1.top(); s1.pop(); }
            if (!s2.empty()) { sum += s2.top(); s2.pop(); }

            carry = sum / 10;
            // 头插法：新节点的 next 指向当前 head
            // 效果：后创建的高位节点在前，先创建的低位节点在后
            head = new ListNode(sum % 10, head);
        }

        return head;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 数据结构 | 修改原链表 | 时间    | 空间    |
// |----------|----------|-----------|---------|---------|
// | 反转链表 | 指针操作 | 是        | O(n+m)  | O(1)    |
// | 双栈法   | 两个栈   | 否        | O(n+m)  | O(n+m)  |
//
// 面试推荐：双栈法。不修改输入，代码更简洁，满足 Follow-up。
// 如果面试官追问"能否 O(1) 空间"，再说反转法。
//
// ============================================================
// 【易错点】
//
// 1. 忘记处理最终进位：
//    ✗ while (!s1.empty() || !s2.empty()) — 漏掉了 carry
//    ✓ while (!s1.empty() || !s2.empty() || carry)
//    反例: 999 + 1 → 应该输出 1000，但漏掉 carry 会输出 000
//
// 2. 头插法方向搞反：
//    ✗ 用尾插法 → 结果低位在前，需要额外反转
//    ✓ 头插法 → 结果自然高位在前，无需反转
//    new ListNode(digit, head) 中第二个参数是 next 指针
//
// 3. 栈弹出前忘记判空：
//    ✗ sum += s1.top(); s1.pop(); // 如果 s1 已空，UB!
//    ✓ if (!s1.empty()) { sum += s1.top(); s1.pop(); }
//
// 4. 反转法忘记最后反转结果：
//    反转 l1、反转 l2、相加、反转结果 — 总共涉及 3 次反转
//    漏掉最后一次反转，结果就是低位在前（7087 而非 7807）
//
// ============================================================
// 【面试追问】
//
// Q1: "双栈法和反转法的本质区别？"
//     反转法修改了原链表结构（破坏性操作）。
//     双栈法用 O(n+m) 额外空间，保持原链表不变。
//     如果后续还需要使用原链表，只能用双栈法。
//
// Q2: "能否不用栈也不反转？"
//     可以。先遍历得到两个链表长度，对齐后从高位开始相加
//     （不处理进位），再从低位到高位处理进位（递归或再次遍历）。
//     实现更复杂，面试中不推荐。
//
// Q3: "头插法和尾插法+反转，哪个更好？"
//     头插法只需一次遍历就能构建正确顺序的结果。
//     尾插法需要额外的反转步骤。
//     头插法代码更简洁，但两者时间复杂度相同。
//
// ============================================================
