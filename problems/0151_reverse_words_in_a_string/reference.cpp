/*
 * LeetCode 151: 反转字符串中的单词 (Reverse Words in a String)
 *
 * 【题目本质】
 * 把字符串中的单词顺序反转，同时清除多余空格。
 * 核心挑战在于：能否做到 O(1) 额外空间（Follow-up）。
 *
 * 【解法总览】
 * 解法1: 分割+反转+拼接  — O(n) / O(n)  — 最直觉
 * 解法2: 从后往前遍历     — O(n) / O(n)  — 面试首选，代码简洁
 * 解法3: 原地三步法       — O(n) / O(1)  — Follow-up 最优
 *
 * 示例演示:
 *   输入: "  hello   world  "
 *
 *   解法2 (从后往前):
 *          ←───────── 扫描方向
 *     "  hello   world  "
 *                  ↑   ↑
 *                  i+1 j     → 提取 "world"
 *       ↑    ↑
 *       i+1  j               → 提取 "hello"
 *     结果: "world hello"
 *
 *   解法3 (原地三步):
 *     原始:   "  hello   world  "
 *     Step1:  "hello world"          ← 双指针去多余空格
 *     Step2:  "dlrow olleh"          ← 整体反转
 *     Step3:  "world hello"          ← 逐词反转 ✓
 */

// ============================================================
// 解法1: 分割 + 反转 + 拼接 — 最直觉的思路
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 最自然的想法：把字符串按空格拆成单词数组，反转数组，再拼回去。
// 拆分时用 while 跳过空格，自然就过滤掉了多余空格。
// 这是"理解题意"的基础解法。
// ============================================================
class Solution1 {
public:
    string reverseWords(string s) {
        // 1. 手动分割出所有单词
        vector<string> words;
        int n = s.size(), i = 0;
        while (i < n) {
            while (i < n && s[i] == ' ') i++;       // 跳过空格
            if (i >= n) break;
            int j = i;
            while (j < n && s[j] != ' ') j++;       // 找到单词尾
            words.push_back(s.substr(i, j - i));     // 提取单词
            i = j;
        }
        
        // 2. 反转单词数组
        reverse(words.begin(), words.end());
        
        // 3. 用单个空格拼接
        string result;
        for (int k = 0; k < (int)words.size(); k++) {
            if (k > 0) result += ' ';  // 单词之间加一个空格
            result += words[k];
        }
        return result;
    }
};

// ============================================================
// 解法2: 从后往前遍历 — 面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法1先分割再反转，两步可以合成一步：
// 从字符串尾部开始扫描，每遇到一个单词就直接追加到结果。
// 因为是从后往前扫，追加顺序自然就是反转的。
//
// 双指针 j 和 i:
//   j: 从后往前，先跳过尾部空格，停在单词最后一个字符
//   i: 从 j 往前，跳过非空格字符，停在单词左边的空格 (或 -1)
//   单词 = s[i+1 .. j]
// ============================================================
class Solution2 {
public:
    string reverseWords(string s) {
        string result;
        int j = (int)s.size() - 1;
        
        while (j >= 0) {
            // 跳过尾部空格
            while (j >= 0 && s[j] == ' ') j--;
            if (j < 0) break;
            
            // 找到单词起点: i 停在单词左边的空格 (或 -1)
            int i = j;
            while (i >= 0 && s[i] != ' ') i--;
            
            // 追加到结果 (不是第一个单词就加空格分隔)
            if (!result.empty()) result += ' ';
            // 为什么是 i+1: i 指向空格或 -1，单词从 i+1 开始
            // 为什么长度是 j-i: 单词长度 = j - (i+1) + 1 = j - i
            result += s.substr(i + 1, j - i);
            
            j = i;  // 继续往前扫下一个单词
        }
        return result;
    }
};

// ============================================================
// 解法3: 原地三步法 — Follow-up: O(1) 额外空间
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 前两种解法都需要 O(n) 额外空间。如果字符串可变 (C++ string 可变)，
// 能否在原地完成？
//
// 关键洞察：「两次反转」
//   - 反转整个字符串：单词顺序对了，但每个单词内部的字母是倒的
//   - 再逐个单词反转：每个单词恢复正确
//
// 但在反转前，需要先去除多余空格（否则空格会出现在错误位置）。
//
// 三步走：
//   Step 1: 双指针去除多余空格 (类似 LC 27 移除元素)
//   Step 2: 反转整个字符串
//   Step 3: 逐词反转
//
// 详细过程:
//   "  hello   world  "
//     ↓ Step1: 去空格 (write指针压缩)
//   "hello world"
//     ↓ Step2: 整体反转
//   "dlrow olleh"
//     ↓ Step3: 逐词反转
//     "dlrow" → "world"
//     "olleh" → "hello"
//   "world hello" ✓
// ============================================================
class Solution3 {
public:
    string reverseWords(string s) {
        int n = s.size();
        
        // ======= Step 1: 去除多余空格 =======
        // 双指针: read 读取, write 写入
        // 规则: 单词间只保留一个空格, 首尾无空格
        int write = 0;
        for (int read = 0; read < n; read++) {
            if (s[read] != ' ') {
                // 不是第一个单词时，先写一个空格做分隔
                // 为什么用 write > 0 判断: write=0 说明还没写过任何字符
                if (write > 0) s[write++] = ' ';
                // 拷贝整个单词 (连续的非空格字符)
                while (read < n && s[read] != ' ') {
                    s[write++] = s[read++];
                }
                // 注意: 内层 while 结束时 read 指向空格或末尾
                // 外层 for 的 read++ 会再跳一位，但没关系，那一位也是空格
            }
        }
        s.resize(write);  // 截断! 不做这步会残留垃圾字符
        
        // ======= Step 2: 反转整个字符串 =======
        reverse(s.begin(), s.end());
        
        // ======= Step 3: 逐词反转 =======
        int start = 0;
        for (int i = 0; i <= (int)s.size(); i++) {
            // 遇到空格或字符串末尾 → 一个单词结束
            // 为什么 i <= s.size(): 最后一个单词后面没有空格,
            // 需要 i==s.size() 来触发最后一次反转
            if (i == (int)s.size() || s[i] == ' ') {
                reverse(s.begin() + start, s.begin() + i);
                start = i + 1;  // 下一个单词的起点
            }
        }
        
        return s;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间 | 空间 | 核心技巧 | 代码复杂度 |
// |------|------|------|----------|-----------|
// | 分割+反转 | O(n) | O(n) | split+reverse | 简单 |
// | 从后往前  | O(n) | O(n) | 双指针从尾扫  | 简单 |
// | 原地三步  | O(n) | O(1) | 两次反转     | 中等 |
//
// 面试策略:
//   - 先写解法2（简洁清晰，15行搞定）
//   - 面试官追问 O(1) 空间时，切换到解法3
//   - 解法1 用于口述"最直觉的思路"
//
// 【易错点】
//
// 1. 原地去空格时漏加单词间的空格
//    ✗ 只拷贝非空格字符 → "helloworld"
//    ✓ 每个单词前 (write>0时) 先写一个空格
//
// 2. 忘记 s.resize(write)
//    ✗ 去空格后尾部残留原字符 → "hello worldrld  "
//    ✓ s.resize(write) 截断字符串
//
// 3. Step3 逐词反转时漏掉最后一个单词
//    ✗ for (i = 0; i < s.size(); i++) 只在 s[i]==' ' 时反转
//      → 最后一个单词后面没有空格，不会触发反转
//    ✓ for (i = 0; i <= s.size(); i++) 让 i==s.size() 也触发反转
//
// 4. 从后往前遍历的 substr 参数算错
//    ✗ s.substr(i, j - i) → i 是空格位置，起点错了
//    ✓ s.substr(i + 1, j - i) → 起点是 i+1
//
// 5. Step1 外层 for 和内层 while 的 read 冲突
//    内层 while 把 read 推进到空格位置，外层 for 再 read++
//    看似跳过了一个字符，但那个字符一定是空格，跳过无妨
//    如果不放心，可以在内层 while 后加 read-- 抵消
//
// 【面试追问】
//
// Q1: 暴力解的思路和复杂度？
// → 分割成单词数组，反转，拼接。O(n) 时间，O(n) 空间。
//    时间已经是线性最优，优化空间是 Follow-up 的方向。
//
// Q2: 能否 O(1) 额外空间完成？
// → 三步法：去空格 → 整体反转 → 逐词反转。
//    核心洞察：两次反转 = 只反转顺序不反转内容。
//    去空格用双指针原地压缩，类似 LC 27 移除元素。
//
// Q3: 如果输入是 char[] (C风格字符串) 而不是 string？
// → 思路完全相同，但不能用 resize，需要在 write 位置放 '\0'。
//    这就是 LC 186 的场景。
//
// Q4: "两次反转"技巧还能用在哪？
// → 数组旋转 (LC 189)：将数组右旋 k 步 = 整体反转 + 前k个反转 + 后面反转。
//    本质相同：用两次反转实现"分段平移"。
//
