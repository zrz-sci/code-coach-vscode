/*
 * LeetCode 921: 使括号有效的最少添加 (Minimum Add to Make Parentheses Valid)
 *
 * 【题目本质】
 * 遍历括号字符串，统计有多少个左括号和右括号无法被匹配。
 * 每个未匹配的括号需要添加一个对应括号来补，总添加数 = 未匹配左括号数 + 未匹配右括号数。
 *
 * 【解法总览】
 * 解法1: 栈模拟      — O(n) / O(n) — 经典括号匹配，直觉最自然
 * 解法2: 贪心计数    — O(n) / O(1) — 栈退化为计数器，空间最优
 */

// ============================================================
// 解法1: 栈模拟 — 经典括号匹配思路
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 括号匹配最自然的工具就是栈：
// - 遇到 '(' → 入栈，等待后续的 ')' 来配对
// - 遇到 ')' → 检查栈顶是否有 '(' 可以配对
//   - 有 → 弹出栈顶，配对成功
//   - 没有 → 这个 ')' 多余，需要额外添加一个 '('
// 遍历结束后，栈里剩余的 '(' 都是未匹配的，各需添加一个 ')'
//
// 示例 "())" 的过程:
//   字符   栈        unmatchedClose   说明
//   '('   ['(']         0            入栈
//   ')'   []            0            配对成功，弹出
//   ')'   []            1            栈空，无法配对
//   结果: 栈剩余 0 + unmatchedClose 1 = 1
//
// 示例 "(((" 的过程:
//   字符   栈             unmatchedClose   说明
//   '('   ['(']              0            入栈
//   '('   ['(','(']          0            入栈
//   '('   ['(','(','(']      0            入栈
//   结果: 栈剩余 3 + unmatchedClose 0 = 3
// ============================================================
class Solution1 {
public:
    int minAddToMakeValid(string s) {
        stack<char> stk;
        int unmatchedClose = 0; // 无法配对的 ')' 数量

        for (char c : s) {
            if (c == '(') {
                stk.push(c);
            } else {
                // c == ')'
                if (!stk.empty()) {
                    stk.pop(); // 和栈顶的 '(' 成功配对
                } else {
                    unmatchedClose++; // 没有 '(' 可配，这个 ')' 是多余的
                }
            }
        }

        // 栈中剩余的 '(' 全是未匹配的
        // 每个需要添加一个 ')' → 共 stk.size() 次
        // 每个多余的 ')' 需要添加一个 '(' → 共 unmatchedClose 次
        return (int)stk.size() + unmatchedClose;
    }
};

// ============================================================
// 解法2: 贪心计数 — 栈退化为计数器 ⭐ 面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1的栈里只会存 '('，我们不关心具体是哪些 '('，只关心"有几个"。
// 所以用整数 open 替代栈：
// - open: 当前未匹配的 '(' 数量（等价于栈的大小）
// - close: 过程中无法配对的 ')' 数量
//
// 贪心策略：每个 ')' 优先和前面最近的未匹配 '(' 配对。
// 为什么贪心是对的？
//   如果 ')' 不和前面的 '(' 配，而是靠添加来补，那前面的 '(' 也要靠添加来补，
//   添加次数 >= 2，而直接配对只需 0 次。所以贪心配对一定最优。
//
// 遍历 "())":
//   字符  open  close  说明
//   '('    1     0     左括号，open++
//   ')'    0     0     open>0, 配对! open--
//   ')'    0     1     open==0, 无法配对, close++
//   答案 = 0 + 1 = 1
//
// 遍历 "(((":
//   字符  open  close  说明
//   '('    1     0     open++
//   '('    2     0     open++
//   '('    3     0     open++
//   答案 = 3 + 0 = 3
//
// 遍历 "()))(":
//   字符  open  close  说明
//   '('    1     0     open++
//   ')'    0     0     配对, open--
//   ')'    0     1     无法配对, close++
//   ')'    0     2     无法配对, close++
//   '('    1     2     open++
//   答案 = 1 + 2 = 3
// ============================================================
class Solution2 {
public:
    int minAddToMakeValid(string s) {
        int open = 0;   // 未匹配的 '(' 数量（替代栈）
        int close = 0;  // 未匹配的 ')' 数量

        for (char c : s) {
            if (c == '(') {
                open++;
            } else {
                // c == ')'
                if (open > 0) {
                    open--;  // 贪心：和前面最近的未匹配 '(' 配对
                } else {
                    close++; // 没有 '(' 可配，需要额外添加一个 '('
                }
            }
        }

        // open: 剩余未匹配的 '('，每个需添加一个 ')' 来补
        // close: 过程中多余的 ')'，每个需添加一个 '(' 来补
        return open + close;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度     | 解法1 栈模拟   | 解法2 贪心计数  |
// |----------|---------------|----------------|
// | 时间     | O(n)          | O(n)           |
// | 空间     | O(n) 栈       | O(1) 两个变量   |
// | 代码量   | 略多          | 精简            |
// | 面试推荐 | 口述思路起点   | ⭐ 最终代码      |
//
// 核心区别：解法2 发现栈中只存 '(' → 用计数器替代栈。
// 面试建议：先说"栈可以做"，再优化为"计数器更好"，展示思维过程。
//
// ============================================================
// 【易错点】
//
// 1. 忘记统计未匹配的左括号:
//    ✗ return close;  // 只数了多余的 ')'，忘了最后栈中/open 里的 '('
//    ✓ return open + close;
//
// 2. open 减到负数:
//    ✗ if (c == ')') open--;  // open 可能变成 -1, -2...
//    ✓ if (c == ')') {
//        if (open > 0) open--;
//        else close++;
//      }
//    反例: s = "))" → 错误写法得到 open=-2, close=0, 答案=-2 (荒谬)
//                       正确写法得到 open=0, close=2, 答案=2 (正确)
//
// 3. 误以为答案 = max(open, close):
//    ✗ return max(open, close);
//    ✓ return open + close;
//    反例: s = "())(" → open=1, close=1, 正确答案=2, max=1 (错误)
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么贪心策略（每个 ')' 优先配对最近的 '('）是最优的？
//     答: 如果 ')' 选择不配对，它自己需要添加1次 '(' 来补，
//     而前面那个 '(' 也需要添加1次 ')' 来补，共2次。
//     直接配对则0次。所以贪心配对一定 <= 不配对。
//
// Q2: 如果括号扩展为 ()[]{}，怎么改？
//     答: 计数器不够用了，因为不同类型的左括号顺序很重要。
//     必须用栈方案：入栈左括号，遇到右括号检查栈顶类型是否匹配。
//     不匹配则 close++（或需要更复杂的处理逻辑）。
//
// Q3: 如果不是"添加"而是"删除"使括号有效，最少删几个？
//     答: 答案相同! 每个未匹配的括号，添加一个配对 或 删除它自身，
//     都是一次操作。所以最少添加数 = 最少删除数。
//
// Q4: 能否在 O(n) 时间内同时输出一个有效的结果字符串？
//     答: 可以。第一遍从左到右标记多余的 ')'，第二遍从右到左标记多余的 '('，
//     删除所有被标记的字符即可。或者用栈记录索引来标记。
// ============================================================
