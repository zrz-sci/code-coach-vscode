/*
 * LeetCode 986: 区间列表的交集 (Interval List Intersections)
 *
 * 【题目本质】
 * 两个已排序、不重叠的闭区间列表，求所有交集区间。
 * 本质是"两个有序序列的归并"——利用有序性，双指针同步扫描即可。
 *
 * 【解法总览】
 * 解法1: 暴力双循环      — O(m×n) / O(1)   — 最直觉，不利用排序性
 * 解法2: 双指针归并 ⭐    — O(m+n) / O(1)   — 面试首选，最优
 * 解法3: 扫描线          — O((m+n)log(m+n)) / O(m+n) — 通用性强，可扩展到K路
 */

// ============================================================
// 解法1: 暴力双循环 — 遍历所有 (i,j) 对
// 时间: O(m×n)  空间: O(1)（不算输出）
//
// 【思路】
// 最朴素的想法：每一对区间都检查一下有没有交集。
// 交集 = [max(两个起点), min(两个终点)]，如果起点 ≤ 终点就有交集。
// 完全没有利用"已排序"这个条件，所以效率不高。
// ============================================================
class Solution1 {
public:
    vector<vector<int>> intervalIntersection(vector<vector<int>>& firstList, 
                                              vector<vector<int>>& secondList) {
        vector<vector<int>> result;
        for (int i = 0; i < (int)firstList.size(); i++) {
            for (int j = 0; j < (int)secondList.size(); j++) {
                int lo = max(firstList[i][0], secondList[j][0]);
                int hi = min(firstList[i][1], secondList[j][1]);
                if (lo <= hi) {
                    result.push_back({lo, hi});
                }
            }
        }
        return result;
    }
};

// ============================================================
// 解法2: 双指针归并 ⭐ — 利用有序性同步扫描
// 时间: O(m+n)  空间: O(1)（不算输出）
//
// 【思路】
// 解法1的瓶颈: 大量不可能相交的组合被白白检查了。
// 关键观察: 两个列表都已排序，可以像归并排序一样双指针扫描。
//
// 两个指针 i, j 分别指向当前正在考虑的区间:
//   - 计算交集: lo = max(A[i].start, B[j].start)
//                hi = min(A[i].end,   B[j].end)
//   - 若 lo <= hi，记录交集 [lo, hi]
//   - 谁的终点小谁前进（终点小的区间"用完了"）
//
// 可视化示例:
// A: [0,2]  [5,10]  [13,23]  [24,25]
//     i→
// B: [1,5]  [8,12]  [15,24]  [25,26]
//     j→
//
// Step1: i=0,j=0: [0,2]∩[1,5] → lo=1,hi=2 → [1,2]  A.end=2<B.end=5 → i++
// Step2: i=1,j=0: [5,10]∩[1,5] → lo=5,hi=5 → [5,5]  B.end=5<A.end=10 → j++
// Step3: i=1,j=1: [5,10]∩[8,12] → lo=8,hi=10 → [8,10] A.end=10<B.end=12 → i++
// Step4: i=2,j=1: [13,23]∩[8,12] → lo=13,hi=12 → 无交集  B.end=12<A.end=23 → j++
// Step5: i=2,j=2: [13,23]∩[15,24] → lo=15,hi=23 → [15,23] A.end=23<B.end=24 → i++
// Step6: i=3,j=2: [24,25]∩[15,24] → lo=24,hi=24 → [24,24] B.end=24<A.end=25 → j++
// Step7: i=3,j=3: [24,25]∩[25,26] → lo=25,hi=25 → [25,25] A.end=25<B.end=26 → i++
// i=4 越界 → 结束
// 结果: [[1,2],[5,5],[8,10],[15,23],[24,24],[25,25]] ✓
// ============================================================
class Solution2 {
public:
    vector<vector<int>> intervalIntersection(vector<vector<int>>& firstList, 
                                              vector<vector<int>>& secondList) {
        vector<vector<int>> result;
        int i = 0, j = 0;
        
        while (i < (int)firstList.size() && j < (int)secondList.size()) {
            // 两个区间的交集 = [max(起点), min(终点)]
            int lo = max(firstList[i][0], secondList[j][0]);
            int hi = min(firstList[i][1], secondList[j][1]);
            
            // lo <= hi 表示有交集（包含单点交集如 [5,5]）
            if (lo <= hi) {
                result.push_back({lo, hi});
            }
            
            // 终点小的区间已经"用完"——它不可能再和对方的后续区间有交集
            // 因为对方后续区间的起点只会更大
            if (firstList[i][1] < secondList[j][1]) {
                i++;  // A 的当前区间先结束，淘汰它
            } else {
                j++;  // B 的当前区间先结束（或同时结束），淘汰它
            }
        }
        
        return result;
    }
};

// ============================================================
// 解法3: 扫描线 — 端点事件排序
// 时间: O((m+n)log(m+n))  空间: O(m+n)
//
// 【思路】
// 换一个视角：把所有区间端点拆成"事件"。
// 起点 = 进入事件(+1)，终点 = 离开事件(-1)。
// 按坐标排序后扫描，维护当前活跃区间计数 count。
// 当 count 变为 2 时，两个区间开始重叠，记下起点。
// 当 count 从 2 降为 1 时，重叠结束，记下终点。
//
// 这个方法的优势: 天然支持 K 个区间列表的交集（count == K）。
// 对于本题 K=2 的场景，不如双指针简洁，但通用性更强。
//
// 排序规则: 坐标相同时，起点事件排在终点事件前面。
// 这保证了 [1,5] 和 [5,10] 的交集 [5,5] 不被遗漏。
// 如果先处理终点，count 会变为 0 再变为 1，永远到不了 2。
// ============================================================
class Solution3 {
public:
    vector<vector<int>> intervalIntersection(vector<vector<int>>& firstList, 
                                              vector<vector<int>>& secondList) {
        // events: (坐标, 类型)  类型: 0=起点(进入), 1=终点(离开)
        // 排序: 坐标升序；坐标相同时起点(0)在终点(1)前（保证相切也算交集）
        vector<pair<int,int>> events;
        for (auto& a : firstList) {
            events.push_back({a[0], 0});  // 进入
            events.push_back({a[1], 1});  // 离开
        }
        for (auto& b : secondList) {
            events.push_back({b[0], 0});
            events.push_back({b[1], 1});
        }
        
        sort(events.begin(), events.end());
        
        vector<vector<int>> result;
        int count = 0;   // 当前活跃区间数
        int start = -1;  // 重叠开始的坐标
        
        for (auto& [pos, type] : events) {
            if (type == 0) {  // 进入事件
                count++;
                if (count == 2) {
                    start = pos;  // 两个区间开始重叠
                }
            } else {  // 离开事件
                if (count == 2) {
                    result.push_back({start, pos});  // 重叠结束，记录交集
                }
                count--;
            }
        }
        
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 指标           | 暴力双循环    | 双指针归并 ⭐  | 扫描线             |
// |----------------|--------------|---------------|--------------------|
// | 时间           | O(m×n)       | O(m+n)        | O((m+n)log(m+n))   |
// | 空间           | O(1)         | O(1)          | O(m+n)             |
// | 利用排序性     | 否           | 是            | 否（自己排序）      |
// | 可扩展到K路    | 困难         | 需用最小堆    | 天然支持            |
// | 面试推荐       | 展示理解     | 首选          | 追问时提及          |
//
// 面试场景:
// - 首先写出解法2（双指针），时间空间都最优
// - 如果面试官追问"K个列表怎么办"，提出扫描线或K路归并
//
// ============================================================
// 【易错点】
//
// 1. 按起点而非终点移动指针:
//    ✗ if (firstList[i][0] < secondList[j][0]) i++;
//    ✓ if (firstList[i][1] < secondList[j][1]) i++;
//    原因: A=[1,10], B=[2,3] 时 A 起点更小，但 A 还要和 B 的下一个区间比较。
//    "谁先结束谁走"才是正确的贪心策略。
//
// 2. 交集判断用 < 而非 <=:
//    ✗ if (lo < hi) — 漏掉单点交集 [5,5]
//    ✓ if (lo <= hi) — 闭区间 [5,5] 包含一个实数点，是有效交集
//
// 3. 终点相等时忘记移动导致死循环:
//    ✗ if (A[i][1] < B[j][1]) i++; 
//       else if (A[i][1] > B[j][1]) j++;
//       // 相等时什么也没做 → 死循环!
//    ✓ 用 else（不区分 > 和 ==），两个都用完了移哪个都行
//
// 4. 扫描线中坐标相同时排序顺序错误:
//    ✗ 终点排在起点前面 → [1,5] 和 [5,10] 的交集 [5,5] 丢失
//    ✓ 起点(type=0)排在终点(type=1)前面，pair 默认比较即满足
//
// ============================================================
// 【面试追问】
//
// Q1: 双指针的正确性怎么保证？为什么不会漏解？
// A1: 每次淘汰终点更小的区间。该区间的终点 < 对方下一个区间的起点
//     （因为对方列表有序且不重叠），所以该区间不可能和对方的后续
//     区间有交集。而终点更大的区间被保留，继续和对方的下一个比较。
//
// Q2: 如果有 K 个已排序区间列表，怎么求公共交集？
// A2: 方法1: K路归并——用大小为K的最小堆维护每个列表的当前指针，
//     每次取终点最小的，同时检查K个区间是否全部重叠。O(N·logK)。
//     方法2: 扫描线——所有端点排序，count==K 时有交集。O(N·logN)。
//
// Q3: 如果区间列表没有排序呢？
// A3: 先排序 O(n·logn)，然后用同样的双指针。总复杂度被排序主导。
//     或者直接用扫描线（它本身就包含排序步骤）。
//
// Q4: 如果不是求交集而是求并集（合并两个区间列表）？
// A4: 归并两个有序列表后，使用 LeetCode 56 合并区间的逻辑：
//     如果当前区间和上一个重叠就合并，否则新开一个。
// ============================================================
