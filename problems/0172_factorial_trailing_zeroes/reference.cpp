/*
 * 【题目本质】
 * 计算 n! 末尾零的个数 = 计算 n! 中因子 5 的总个数。
 * 因为 10 = 2 * 5，而因子 2 的数量永远 >= 因子 5，所以只需数 5。
 *
 * 【解法总览】
 * 解法1: 除5累加法 — O(log5(n))，最优解
 * 解法2: 逐个分解法 — O(n)，直观但慢
 */

// ===================== 解法1: 除5累加 =====================
// 思路：count = n/5 + n/25 + n/125 + ...
// 为什么这样做？n/5 统计含至少一个因子5的数，n/25 统计含至少两个因子5的数...
// 等价于不断 n /= 5 并累加，因为 n/25 == (n/5)/5
class Solution1 {
public:
    int trailingZeroes(int n) {
        int count = 0;
        // 每次除以5，累加商
        // 第1轮: 统计 5,10,15,20,25... 每个贡献1个5
        // 第2轮: 统计 25,50,75,100... 每个额外贡献1个5
        // 第3轮: 统计 125,250... 每个再额外贡献1个5
        while (n >= 5) {
            n /= 5;
            count += n;
        }
        return count;
    }
};

// ===================== 解法2: 逐个因子分解 =====================
// 思路：对每个 5 的倍数，分解出它包含几个因子 5
// 直观但效率低，仅用于理解问题本质
class Solution2 {
public:
    int trailingZeroes(int n) {
        int count = 0;
        // 只遍历 5 的倍数，跳过非 5 的倍数
        for (int i = 5; i <= n; i += 5) {
            int num = i;
            // 25 包含 2 个因子 5, 125 包含 3 个, ...
            while (num % 5 == 0) {
                count++;
                num /= 5;
            }
        }
        return count;
    }
};

/*
 * 【解法对比】
 * | 解法 | 时间 | 空间 | 特点 |
 * |------|------|------|------|
 * | 除5累加 | O(log5(n)) | O(1) | 最优，面试首选 |
 * | 逐个分解 | O(n/5 * log5(n)) | O(1) | 直观但慢 |
 *
 * 【易错点】
 * 1. 只算 n/5 忘记 n/25, n/125... → 25! 应该是 6 个零不是 5 个
 * 2. 想要直接算 n! 的值再数零 → 溢出
 * 3. 用 while(n > 0) 而非 while(n >= 5) → 功能相同但语义更清晰
 *
 * 【面试追问】
 * Q1: 为什么只数5不数2？→ 因子2的个数 = n/2+n/4+n/8+... 远大于因子5的个数
 * Q2: n=25 时答案？→ 25/5=5, 5/5=1, 总共 6 个零 (5,10,15,20贡献1个，25贡献2个)
 * Q3: 扩展到 k 进制末尾零？→ 对 k 质因数分解，分别统计取最小值
 */
