/*
 * LeetCode 1703: 得到连续 K 个 1 的最少相邻交换次数
 * 
 * 【题目本质】
 * 从所有 1 的位置中选 k 个，用最少的相邻交换使它们连续。
 * 等价于：选 k 个坐标点，移到以中位数为中心的连续位置上，求最小总距离。
 * 坐标变换 pos[i] -= i 后，化归为"k 个点聚到同一值"的经典中位数问题。
 *
 * 【解法总览】
 * 解法1: 暴力枚举窗口 — O(m*k) / O(m) — 直觉理解用
 * 解法2: 前缀和 + 滑动窗口 — O(n) / O(m) — 面试最优解
 */

// ============================================================
// 解法1: 暴力枚举窗口
// 时间: O(m*k)  空间: O(m)    (m = 1 的个数)
//
// 【思路】
// 1) 提取所有 1 的位置到 pos[]
// 2) 坐标变换: pos[i] -= i，把"聚到连续位置"变成"聚到同一点"
//    为什么？如果 k 个 1 最终在 [t, t+1, ..., t+k-1]，
//    第 j 个 1 目标是 t+j，变换后 g[j] = pos[j]-j，目标变成 t，
//    所有人聚到同一个值 t。
// 3) 对每个长度为 k 的窗口，中位数是最优集合点，O(k) 算代价
// 4) 取所有窗口的最小值
//
// 示例: nums = [1,0,0,0,0,0,1,1], k = 3
//   pos = [0, 6, 7]
//   变换: g = [0-0, 6-1, 7-2] = [0, 5, 5]
//   窗口 [0,5,5], mid=5, cost = |0-5|+|5-5|+|5-5| = 5  ✓
// ============================================================
class Solution1 {
public:
    int minMoves(vector<int>& nums, int k) {
        vector<long long> g;
        for (int i = 0; i < (int)nums.size(); i++) {
            if (nums[i] == 1) g.push_back(i);
        }
        int m = g.size();

        // 坐标变换: 消除"连续"约束
        for (int i = 0; i < m; i++) g[i] -= i;

        long long ans = LLONG_MAX;
        for (int i = 0; i + k <= m; i++) {
            int mid = i + k / 2;
            long long M = g[mid];
            long long cost = 0;
            for (int j = i; j < i + k; j++) {
                cost += abs(g[j] - M);
            }
            ans = min(ans, cost);
        }
        return (int)ans;
    }
};

// ============================================================
// 解法2: 前缀和 + 滑动窗口 — 面试最优解 ⭐
// 时间: O(n)  空间: O(m)
//
// 【思路】
// 解法1的瓶颈: 每个窗口内 O(k) 求距离和。
// 优化: 用前缀和 O(1) 求任意子数组之和。
//
// 窗口 [i, i+k-1] 中, mid = i + k/2, M = g[mid]:
//
//   g[i], g[i+1], ..., g[mid-1], g[mid], g[mid+1], ..., g[i+k-1]
//   |-------- 左半 --------|    中位数   |-------- 右半 --------|
//   这些 <= M                              这些 >= M
//
// cost = (左半个数 * M - 左半之和) + (右半之和 - 右半个数 * M)
//
// 其中:
//   左半 = [i, mid-1], 个数 = mid - i = k/2
//   右半 = [mid, i+k-1], 个数 = i+k - mid = k - k/2
//   (右半包含中位数自身，贡献为0，不影响结果)
//
// 用 pre[j] = g[0] + g[1] + ... + g[j-1] (前缀和, pre[0]=0):
//   左半之和 = pre[mid] - pre[i]
//   右半之和 = pre[i+k] - pre[mid]
//
// 复杂度: 前缀和 O(m) 预处理，每个窗口 O(1) 计算，共 O(m) 个窗口。
// ============================================================
class Solution2 {
public:
    int minMoves(vector<int>& nums, int k) {
        // Step 1: 提取所有 1 的位置
        vector<long long> g;
        for (int i = 0; i < (int)nums.size(); i++) {
            if (nums[i] == 1) g.push_back(i);
        }
        int m = g.size();

        // Step 2: 坐标变换
        // 变换后 g[] 非递减 (因为原 pos 严格递增, pos[i+1]-pos[i] >= 1)
        // 所以窗口内天然有序, 中间位置就是中位数
        for (int i = 0; i < m; i++) g[i] -= i;

        // Step 3: 构建前缀和
        vector<long long> pre(m + 1, 0);
        for (int i = 0; i < m; i++) {
            pre[i + 1] = pre[i] + g[i];
        }

        // Step 4: 滑动窗口, 对每个窗口 O(1) 计算代价
        long long ans = LLONG_MAX;
        for (int i = 0; i + k <= m; i++) {
            int mid = i + k / 2;
            long long M = g[mid];

            // 右半 [mid, i+k-1]: 这些值 >= M
            long long rightSum = pre[i + k] - pre[mid];
            long long rightCnt = i + k - mid;  // = k - k/2

            // 左半 [i, mid-1]: 这些值 <= M
            long long leftSum = pre[mid] - pre[i];
            long long leftCnt = mid - i;        // = k/2

            long long cost = (rightSum - rightCnt * M)
                           + (leftCnt * M - leftSum);
            ans = min(ans, cost);
        }
        return (int)ans;
    }
};

// ============================================================
// 【解法对比】
// 
// 解法1 vs 解法2:
//   - 核心框架完全相同: 坐标变换 + 中位数最优 + 滑动窗口
//   - 唯一区别: 窗口内求和方式
//     * 解法1: 暴力 O(k) 遍历 → 总 O(m*k)
//     * 解法2: 前缀和 O(1) 查询 → 总 O(m) ≈ O(n)
//   - 面试中解法2是必须写出的目标解
//
// 【易错点】
//
// 1. 忘记坐标变换 pos[i] -= i:
//    ✗ 直接对原始位置求中位数距离 → 这是"聚到一点"的代价
//    ✓ 变换后求中位数距离 → 这才是"聚到连续位置"的代价
//
// 2. 前缀和区间写错:
//    ✗ rightSum = pre[i+k-1] - pre[mid]  (漏掉最后一个元素)
//    ✓ rightSum = pre[i+k] - pre[mid]     (pre 数组长度 m+1)
//
// 3. 用 int 导致溢出:
//    ✗ int cost = ...  → n=10^5 时前缀和 ~10^9, 乘法后溢出
//    ✓ long long cost = ...
//
// 4. 中位数下标不一致:
//    ✗ mid = i + (k-1)/2 但左右半区间按 mid = i + k/2 划分
//    ✓ 统一使用 mid = i + k/2, 左半 [i, mid-1], 右半 [mid, i+k-1]
//
// 5. g[] 为什么一定非递减?
//    pos[] 严格递增 → pos[i+1] >= pos[i]+1
//    → g[i+1] = pos[i+1]-(i+1) >= pos[i]-i = g[i]
//    所以 g[] 非递减, 不需要排序, 中间位置直接是中位数
//
// 【面试追问】
//
// Q1: 为什么相邻交换的代价 = 每个1到目标位置的距离之和?
//     因为只有0和1, 交换相邻的0和1等于把1移一格。
//     多个1的移动可以看作独立的（它们不会互相阻碍，
//     等价于每个1独立走到目标位置）。
//
// Q2: 坐标变换 pos[i]-=i 的几何直觉?
//     如果k个1已经连续在 [t,t+1,...,t+k-1]，第j个1在t+j，
//     变换后 g[j]=t+j-j=t，全相等。
//     所以变换后"连续排列"=>"同一值"，是标准的中位数聚合问题。
//
// Q3: 如果不是相邻交换，而是任意位置交换，怎么做?
//     完全不同的问题。任意交换的最小次数由置换环决定:
//     分解成若干不相交的环，每个长L的环需要L-1次交换。
//     需要用另一套方法（如贪心匹配目标排列）。
//
// Q4: 如果数组里不只是0和1，而是任意正整数，怎么推广?
//     此时相邻交换的代价不能简单化归为距离之和，
//     需要考虑逆序对等更复杂的分析。
// ============================================================
