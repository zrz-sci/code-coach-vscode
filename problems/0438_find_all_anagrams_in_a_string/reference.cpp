/*
 * LeetCode 438: 找到字符串中所有字母异位词 (Find All Anagrams in a String)
 *
 * 【题目本质】
 * 在字符串 s 中找出所有长度等于 len(p) 的子串，使得子串的字符频率和 p 完全相同。
 * 核心：固定长度滑动窗口 + 频率匹配。
 *
 * 【解法总览】
 * 解法1: 暴力排序比较      — O(n·m log m) / O(m) — 最直觉但最慢
 * 解法2: 滑窗 + 频率数组比较 — O(26n) / O(1)     — 面试首选 ⭐
 * 解法3: 滑窗 + diff 计数   — O(n) / O(1)        — 极致优化
 *
 * 滑窗可视化 (s = "cbaebabacd", p = "abc"):
 *
 *   s:  c  b  a  e  b  a  b  a  c  d
 *       [c  b  a]                        → freq 匹配! index=0
 *          [b  a  e]                     → 'e' 多余, 不匹配
 *             [a  e  b]                  → 不匹配
 *                [e  b  a]               → 不匹配
 *                   [b  a  b]            → 'b' 多余, 不匹配
 *                      [a  b  a]         → 'a' 多余, 不匹配
 *                         [b  a  c]      → freq 匹配! index=6
 *                            [a  c  d]   → 不匹配
 */

// ============================================================
// 解法1: 暴力排序比较
// 时间: O(n · m log m)  空间: O(m)
//
// 【思路】
// 异位词 = 排序后相同的字符串。
// 对 s 中每一个长度为 m 的子串，截取、排序、和排好序的 p 比较。
// 正确但慢：相邻子串共享 m-1 个字符，排序无法利用这个重叠。
// ============================================================
class Solution1 {
public:
    vector<int> findAnagrams(string s, string p) {
        vector<int> result;
        int n = s.size(), m = p.size();
        if (n < m) return result;

        string sorted_p = p;
        sort(sorted_p.begin(), sorted_p.end());

        for (int i = 0; i <= n - m; i++) {
            string sub = s.substr(i, m);
            sort(sub.begin(), sub.end());
            if (sub == sorted_p) {
                result.push_back(i);
            }
        }
        return result;
    }
};

// ============================================================
// 解法2: 固定窗口 + 频率数组比较 — 面试首选 ⭐
// 时间: O(26 · n)  空间: O(1) (两个长度26的数组是常数空间)
//
// 【思路】
// 解法1的瓶颈：排序无法利用相邻子串的重叠。
// 观察：异位词的本质不是"排序后相同"，而是"字符频率相同"。
// 用长度26的数组统计频率，比较代价 O(26)。
// 再用滑动窗口：窗口右移一步，加入右端新字符，去掉左端旧字符，
// 频率数组只做 +1 和 -1，增量更新 O(1)。
// 总计：n 步滑动 × 每步 O(1) 更新 + O(26) 比较 = O(26n)。
//
// 窗口维护过程:
//   初始窗口 [0, m-1]: 统计 s[0..m-1] 的频率
//   滑动到 [1, m]:     w_cnt[s[m]]++, w_cnt[s[0]]--
//   滑动到 [2, m+1]:   w_cnt[s[m+1]]++, w_cnt[s[1]]--
//   ...以此类推
// ============================================================
class Solution2 {
public:
    vector<int> findAnagrams(string s, string p) {
        vector<int> result;
        int n = s.size(), m = p.size();
        if (n < m) return result;  // s 比 p 短，不可能有异位词

        vector<int> p_cnt(26, 0), w_cnt(26, 0);

        // 统计 p 的频率 + 初始化第一个窗口 [0, m-1]
        for (int i = 0; i < m; i++) {
            p_cnt[p[i] - 'a']++;
            w_cnt[s[i] - 'a']++;
        }
        // 第一个窗口就可能匹配
        if (p_cnt == w_cnt) result.push_back(0);

        // 窗口从 [1, m] 滑到 [n-m, n-1]
        for (int i = m; i < n; i++) {
            w_cnt[s[i] - 'a']++;           // 右端新字符 s[i] 进入窗口
            w_cnt[s[i - m] - 'a']--;       // 左端旧字符 s[i-m] 离开窗口

            // 比较两个频率数组 (26个元素逐一比较)
            if (p_cnt == w_cnt) {
                result.push_back(i - m + 1); // 窗口起始索引
            }
        }
        return result;
    }
};

// ============================================================
// 解法3: 固定窗口 + diff 计数 — 极致优化
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法2每步要 O(26) 比较两个数组。能否做到 O(1) 判断？
// 
// 核心想法：用一个数组 cnt[c] = p中c的频率 - 窗口中c的频率。
// 当所有 cnt[c] == 0 时，窗口就是异位词。
// 维护 diff = "cnt 中非零项的个数"。
// 
// 每次滑窗只改变2个字符的 cnt 值，diff 的变化是 O(1) 可追踪的：
//   - 改变前 cnt[x]==0 → 即将变成非零 → diff++
//   - 改变后 cnt[x]==0 → 刚好变成零   → diff--
// 
// diff 更新逻辑（以右端字符 r 进入窗口为例）：
//   修改前: cnt[r] 若为 0，说明 r 本来是匹配的，现在要变不匹配了 → diff++
//   执行:   cnt[r]--  (窗口多了一个 r)
//   修改后: cnt[r] 若为 0，说明减完后刚好匹配了 → diff--
// ============================================================
class Solution3 {
public:
    vector<int> findAnagrams(string s, string p) {
        vector<int> result;
        int n = s.size(), m = p.size();
        if (n < m) return result;

        // cnt[c] = p中字符c需要的数量 - 窗口中字符c已有的数量
        // cnt[c] > 0: 窗口还缺 c
        // cnt[c] < 0: 窗口中 c 多了
        // cnt[c] == 0: 字符 c 完全匹配
        vector<int> cnt(26, 0);
        for (char c : p) cnt[c - 'a']++;

        // diff = cnt 中非零项的个数 = 还没匹配好的字符种类数
        int diff = 0;
        for (int i = 0; i < 26; i++) {
            if (cnt[i] != 0) diff++;
        }

        // 初始化第一个窗口 [0, m-1]
        for (int i = 0; i < m; i++) {
            int idx = s[i] - 'a';
            if (cnt[idx] == 0) diff++;   // 从匹配→即将不匹配
            cnt[idx]--;                  // 窗口消耗了一个 idx
            if (cnt[idx] == 0) diff--;   // 减完后刚好匹配
        }
        if (diff == 0) result.push_back(0);

        // 滑动窗口
        for (int i = m; i < n; i++) {
            // --- 右端字符 s[i] 进入窗口 ---
            int r = s[i] - 'a';
            if (cnt[r] == 0) diff++;     // 原本匹配，即将打破
            cnt[r]--;                    // 窗口多了一个 r
            if (cnt[r] == 0) diff--;     // 减完后恰好匹配

            // --- 左端字符 s[i-m] 离开窗口 ---
            int l = s[i - m] - 'a';
            if (cnt[l] == 0) diff++;     // 原本匹配，即将打破
            cnt[l]++;                    // 窗口少了一个 l（归还）
            if (cnt[l] == 0) diff--;     // 加完后恰好匹配

            if (diff == 0) {
                result.push_back(i - m + 1);
            }
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 核心操作 | 每步开销 | 总时间 | 代码复杂度 |
// |------|----------|----------|--------|------------|
// | 1. 排序 | substr+sort | O(m log m) | O(n·m log m) | 简单 |
// | 2. 频率比较 | 滑窗+数组== | O(26) | O(26n) | 简单 |
// | 3. diff计数 | 滑窗+diff | O(1) | O(n) | 中等 |
//
// 面试首选解法2：思路清晰，代码简洁，26n 实际就是线性。
// 解法3用于面试官追问"能否真正O(1)每步"时展示。
//
// 【易错点】
// 1. 漏掉 n < m 的边界检查 → 当 s 比 p 短时，循环越界或返回错误结果。
//
// 2. 左端索引算错:
//    ✗ w_cnt[s[i - m + 1] - 'a']--   ← 这是新窗口的左端，不是要移除的字符
//    ✓ w_cnt[s[i - m] - 'a']--       ← 这才是滑出窗口的那个字符
//
// 3. diff 更新顺序搞反 (解法3):
//    ✗ cnt[r]--; if (cnt[r] == 1) diff++; if (cnt[r] == 0) diff--;
//      → 逻辑混乱，1 不代表什么
//    ✓ 必须是：先检查修改前是否为0 → 修改 → 再检查修改后是否为0
//      因为 diff 追踪的是"非零项的个数"，只关心跨越0这个边界。
//
// 4. 结果索引计算:
//    ✗ result.push_back(i)           ← i 是窗口右端
//    ✓ result.push_back(i - m + 1)   ← 窗口起始位置
//
// 【面试追问】
// Q1: 暴力解瓶颈在哪？怎么优化？
// → 瓶颈在每个子串排序 O(m log m)。用频率数组代替排序 → O(m)。
//   再用滑动窗口增量更新 → O(1)。
//
// Q2: 解法2的 O(26) 比较能否优化到 O(1)？
// → 用 diff 变量追踪不匹配的字符种类数。每次只影响2个字符，
//   diff 的更新是 O(1)。diff==0 时即匹配。
//
// Q3: 如果字符集是 Unicode 全集而不是 26 个字母怎么办？
// → 频率数组换成 unordered_map。diff 思路不变，
//   当 key 的值变为 0 时从 map 中 erase。diff = map.size()。
//
// Q4: 这题和 567(字符串的排列) 有什么关系？
// → 567 只需判断是否存在至少一个异位词子串(返回bool)。
//   代码完全相同，只是找到第一个匹配就 return true。
//
// Q5: 和 76(最小覆盖子串) 有什么关系？
// → 76 是可变长度窗口：右端扩展到满足条件，左端收缩找最小。
//   本题是固定长度窗口，更简单。但 freq+diff 的技巧完全复用。
// ============================================================
