/*
 * LeetCode 1320: Minimum Distance to Type a Word Using Two Fingers
 *
 * 【题目本质】
 * 序列决策问题：对字符串中每个字符，决定用哪根手指按，使两根手指的总移动距离最小。
 * 核心在于状态定义 — 如何用最少的信息描述"当前局面"。
 *
 * 【键盘布局】
 *   col: 0 1 2 3 4 5
 * row0:  A B C D E F
 * row1:  G H I J K L
 * row2:  M N O P Q R
 * row3:  S T U V W X
 * row4:  Y Z
 * 字母 ch 的坐标: ((ch-'A')/6, (ch-'A')%6)
 *
 * 【解法总览】
 * 解法1: 三维记忆化搜索 — O(n×27²) / O(n×27²) — 最直觉
 * 解法2: 二维DP(降维)   — O(n×27)  / O(n×27)  — 面试首选
 * 解法3: 空间优化DP     — O(n×27)  / O(27)    — 最优
 */

// ============================================================
// 解法1: 三维记忆化搜索 — 直接记录两根手指的位置
// 时间: O(n × 27 × 27)  空间: O(n × 27 × 27)
//
// 【思路】
// 最自然的想法：状态 = (当前字符索引i, 手指1位置f1, 手指2位置f2)
// 每步两种选择：用手指1按 或 用手指2按。
// 用26表示"未使用"，从26到任何字母距离为0（起始免费）。
//
// 为什么能work：完整枚举了所有可能的决策，通过记忆化避免重复计算。
// 瓶颈：状态空间 27² = 729 per step，总共 ~218K 状态，可以通过但不够优雅。
// ============================================================
class Solution1 {
public:
    int minimumDistance(string word) {
        int n = word.size();
        memo.assign(n, vector<vector<int>>(27, vector<int>(27, -1)));
        return dfs(0, 26, 26, word);
    }

private:
    vector<vector<vector<int>>> memo;
    
    // 曼哈顿距离，26表示"未使用"→距离为0
    int cost(int a, int b) {
        if (a == 26 || b == 26) return 0;
        return abs(a / 6 - b / 6) + abs(a % 6 - b % 6);
    }
    
    // dfs(i, f1, f2): 从第i个字符起，手指1在f1、手指2在f2的最小代价
    int dfs(int i, int f1, int f2, const string& word) {
        if (i == (int)word.size()) return 0;
        if (memo[i][f1][f2] != -1) return memo[i][f1][f2];
        
        int c = word[i] - 'A';
        
        // 选择1: 用手指1按c，手指1从f1移动到c
        int opt1 = cost(f1, c) + dfs(i + 1, c, f2, word);
        // 选择2: 用手指2按c，手指2从f2移动到c
        int opt2 = cost(f2, c) + dfs(i + 1, f1, c, word);
        
        return memo[i][f1][f2] = min(opt1, opt2);
    }
};

// ============================================================
// 解法2: 二维DP (降维) — 利用"必有一指在word[i-1]上"
// 时间: O(n × 27)  空间: O(n × 27)
//
// 【思路】
// 解法1的瓶颈：状态空间有 27² 的因子。
// 关键洞察：处理完word[i-1]后，两根手指中**必有一根**在word[i-1]上！
// 因为word[i-1]一定是被某根手指按的，那根手指按完就停在那里。
// 
// 所以我们只需记录"另一根手指"的位置j，状态降为 dp[i][j]。
// dp[i][j] = 处理完前i个字符，另一根手指在位置j时的最小代价。
// （"这一根手指"在 word[i-1] 上是隐含的）
//
// 转移（处理word[i]，设 c=word[i], p=word[i-1]）：
//   情况1: 用"在p上的手指"按c → 另一根手指不动
//          dp[i+1][j] ← dp[i][j] + dist(p, c)
//   情况2: 用"在j上的另一根手指"按c → 按完后c被这根手指按了，
//          而之前在p上的手指现在变成"另一根"
//          dp[i+1][p] ← dp[i][j] + dist(j, c)
//
// 【DP表填充示意】(word = "CAKE", C=2, A=0, K=10, E=4)
//
//   i=1(处理A): p=C=2, c=A=0
//     dp[1][26]=0 →  情况1: dp[2][26] = 0+dist(C,A) = 0+2 = 2
//                    情况2: dp[2][2]  = 0+dist(26,A) = 0+0 = 0
//
//   i=2(处理K): p=A=0, c=K=10
//     dp[2][26]=2 →  情况1: dp[3][26] = 2+dist(A,K) = 2+4 = 6
//                    情况2: dp[3][0]  = 2+dist(26,K) = 2+0 = 2
//     dp[2][2]=0  →  情况1: dp[3][2]  = 0+dist(A,K) = 0+4 = 4
//                    情况2: dp[3][0]  = min(2, 0+dist(C,K)) = min(2,3) = 2
//
//   i=3(处理E): p=K=10, c=E=4
//     dp[3][0]=2  →  情况1: dp[4][0]  = 2+dist(K,E) = 2+1 = 3 ← 最优!
//                    情况2: dp[4][10] = 2+dist(A,E) = 2+2 = 4
//     (其他路径代价更大，省略)
//
//   答案: min(dp[4][all j]) = 3 ✓
// ============================================================
class Solution2 {
public:
    int minimumDistance(string word) {
        int n = word.size();
        const int INF = 1e9;
        vector<vector<int>> dp(n + 1, vector<int>(27, INF));
        
        // 初始：第一个字符放下，另一根手指在26(未使用)，代价0
        dp[1][26] = 0;
        
        for (int i = 1; i < n; i++) {
            int c = word[i] - 'A';       // 当前要按的字符
            int p = word[i - 1] - 'A';   // 上一个字符（必有一指在此）
            
            for (int j = 0; j < 27; j++) {
                if (dp[i][j] == INF) continue;
                
                // 情况1: 用"在p上的手指"继续按c，另一根手指位置j不变
                dp[i + 1][j] = min(dp[i + 1][j], dp[i][j] + cost(p, c));
                
                // 情况2: 用"在j上的另一根手指"按c，p变成了"另一根手指"
                dp[i + 1][p] = min(dp[i + 1][p], dp[i][j] + cost(j, c));
            }
        }
        
        int ans = INF;
        for (int j = 0; j < 27; j++) {
            ans = min(ans, dp[n][j]);
        }
        return ans;
    }

private:
    int cost(int a, int b) {
        if (a == 26 || b == 26) return 0; // 未使用的手指，首次放下免费
        return abs(a / 6 - b / 6) + abs(a % 6 - b % 6);
    }
};

// ============================================================
// 解法3: 空间优化DP — 滚动数组
// 时间: O(n × 27)  空间: O(27) = O(1)
//
// 【思路】
// dp[i+1] 只依赖 dp[i]，所以用两个长度27的数组交替即可。
// 这是线性DP空间优化的标准手法。
// ============================================================
class Solution3 {
public:
    int minimumDistance(string word) {
        int n = word.size();
        const int INF = 1e9;
        vector<int> dp(27, INF), ndp(27, INF);
        
        // 初始：处理完第一个字符后，另一根手指在26(未使用)
        dp[26] = 0;
        
        for (int i = 1; i < n; i++) {
            int c = word[i] - 'A';
            int p = word[i - 1] - 'A';
            fill(ndp.begin(), ndp.end(), INF);
            
            for (int j = 0; j < 27; j++) {
                if (dp[j] == INF) continue;
                
                // 情况1: 用在p上的手指按c
                ndp[j] = min(ndp[j], dp[j] + cost(p, c));
                // 情况2: 用在j上的另一根手指按c
                ndp[p] = min(ndp[p], dp[j] + cost(j, c));
            }
            swap(dp, ndp);
        }
        
        return *min_element(dp.begin(), dp.end());
    }

private:
    int cost(int a, int b) {
        if (a == 26 || b == 26) return 0;
        return abs(a / 6 - b / 6) + abs(a % 6 - b % 6);
    }
};

// ============================================================
// 【解法对比】
//
// 解法1 (三维记忆化):
//   - 最直觉，直接记录(i, f1, f2)
//   - 状态空间 O(n×27²)，对本题n≤300可以通过
//   - 适合快速验证思路正确性
//
// 解法2 (二维DP):
//   - 利用"必有一指在word[i-1]"降维
//   - 状态空间 O(n×27)，更高效
//   - 面试中这是期望的最优解法
//
// 解法3 (空间优化):
//   - 在解法2基础上用滚动数组
//   - 空间从 O(n×27) 降到 O(27)
//   - 面试追问"能否优化空间"时给出
//
// 【易错点】
// 1. cost函数忘记处理26(未使用)的情况
//    ✗ 直接用 26/6 和 26%6 算坐标 → 得到 (4,2) 即字母W的位置
//    ✓ if(a==26||b==26) return 0; 未使用的手指首次放下不计代价
//
// 2. 键盘是6列不是5列
//    ✗ a/5, a%5 → A=0,0 B=0,1 C=0,2 D=0,3 E=0,4 F=1,0 ← 错！F应在第0行
//    ✓ a/6, a%6 → A=0,0 B=0,1 ... F=0,5 G=1,0 ← 正确
//
// 3. 情况2的转移目标写错
//    ✗ dp[i+1][j] = dp[i][j] + cost(j, c) — 另一根手指位置应该变成p，不是仍然是j
//    ✓ dp[i+1][p] = dp[i][j] + cost(j, c) — 用j手指按了c，p变成了"另一根"
//
// 4. 初始化错误
//    ✗ dp[0][26] = 0 或 dp[1][word[0]-'A'] = 0
//    ✓ dp[1][26] = 0 — 处理完第1个字符后，按了word[0]的手指在word[0]上(隐含)，
//      另一根手指在26(未使用)
//
// 【面试追问】
// Q1(基础): 暴力枚举所有方案是什么复杂度？怎么用DP优化？
//    → 2^n指数级。DP记录(i,f1,f2)状态，O(n×27²)。
//
// Q2(优化): 能否从O(n×27²)降到O(n×27)？关键观察是什么？
//    → 处理完word[i-1]后必有一指在word[i-1]上，只需记录另一根手指位置。
//
// Q3(变体): 如果键盘布局可以自定义（给一个pos数组），怎么改？
//    → 只改cost函数，用pos[ch]获取坐标，DP框架不变。
//
// Q4(扩展): 如果是k根手指呢？
//    → 需要记录k-1根"另外手指"的位置，状态空间指数增长于k。
//      k较小可做，k大需要近似。
// ============================================================
