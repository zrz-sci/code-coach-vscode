/*
 * LeetCode 268: 丢失的数字 (Missing Number)
 *
 * 【题目本质】
 * [0, n] 共 n+1 个数，数组里有 n 个不重复的数，找出缺失的那一个。
 * 本质：找出"完整集合"与"当前集合"的差异。
 *
 * 【解法总览】
 * 解法1: 排序       — O(n log n) / O(1) — 最直觉
 * 解法2: 哈希表     — O(n) / O(n)       — 查找优化
 * 解法3: 数学求和   — O(n) / O(1)       — 面试首选 ⭐
 * 解法4: 异或位运算 — O(n) / O(1)       — 加分项，无溢出
 */

// ============================================================
// 解法1: 排序 — 排序后 nums[i] 应该等于 i
// 时间: O(n log n)  空间: O(1) (原地排序)
//
// 【思路】
// 排序后，完整序列应该是 [0, 1, 2, ..., n]。
// 扫描一遍找第一个 nums[i] != i 的位置，那个 i 就是缺失的数。
// 如果所有位置都对（0~n-1 都在），说明缺的是 n。
//
// 示例: nums = [3, 0, 1]
//   排序后: [0, 1, 3]
//   i=0: nums[0]=0 ✓
//   i=1: nums[1]=1 ✓
//   i=2: nums[2]=3 ≠ 2 → 返回 2
// ============================================================
class Solution1 {
public:
    int missingNumber(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        int n = nums.size();
        for (int i = 0; i < n; i++) {
            if (nums[i] != i) return i;
        }
        // 0 到 n-1 都在，缺的是 n
        // 例: nums = [0, 1] → 排序后 [0, 1]，缺 2
        return n;
    }
};

// ============================================================
// 解法2: 哈希表 — 用 set 把查找从 O(n) 降到 O(1)
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法1 排序是为了快速判断"某个数是否存在"。
// 哈希表能直接 O(1) 判断存在性，不需要排序。
// 把数组所有元素放入 set，然后遍历 0~n，
// 第一个不在 set 中的就是答案。
// ============================================================
class Solution2 {
public:
    int missingNumber(vector<int>& nums) {
        unordered_set<int> s(nums.begin(), nums.end());
        int n = nums.size();
        // 注意遍历范围是 [0, n]，不是 [0, n-1]
        // 因为缺失的数可能是 n 本身
        for (int i = 0; i <= n; i++) {
            if (s.find(i) == s.end()) return i;
        }
        return -1; // 逻辑上不会到达
    }
};

// ============================================================
// 解法3: 数学求和 — 期望总和减去实际总和 ⭐ 面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法2 用了 O(n) 额外空间。能否 O(1) 空间？
// 
// 关键观察：[0, n] 的完整总和 = n*(n+1)/2（等差数列公式）
// 数组的实际总和比完整总和少了恰好一个数的值。
// 差值 = 缺失的数。
//
// 示例: nums = [3, 0, 1], n = 3
//   期望: 0+1+2+3 = 3*4/2 = 6
//   实际: 3+0+1 = 4
//   缺失: 6 - 4 = 2 ✓
// ============================================================
class Solution3 {
public:
    int missingNumber(vector<int>& nums) {
        int n = nums.size();
        // 等差数列求和：0 + 1 + ... + n
        int expectedSum = n * (n + 1) / 2;
        int actualSum = 0;
        for (int x : nums) {
            actualSum += x;
        }
        // 差值就是缺失的数
        return expectedSum - actualSum;
    }
};

// ============================================================
// 解法4: 异或位运算 — 成对抵消，无溢出
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 同样是 O(1) 空间，但相比求和法没有溢出风险。
//
// 核心性质：a ^ a = 0，a ^ 0 = a
// 如果把 0~n 全部异或，再异或上数组所有元素：
//   - 存在的数出现了两次（一次在 0~n 中，一次在数组中），异或后抵消为 0
//   - 缺失的数只出现一次（只在 0~n 中），留下来就是答案
//
// 示例: nums = [3, 0, 1], n = 3
//   索引异或: 0 ^ 1 ^ 2 ^ 3 = ?
//   数组异或: 3 ^ 0 ^ 1 = ?
//   全部异或: (0^1^2^3) ^ (3^0^1)
//           = (0^0) ^ (1^1) ^ (3^3) ^ 2
//           =   0   ^   0   ^   0   ^ 2
//           = 2 ✓
// ============================================================
class Solution4 {
public:
    int missingNumber(vector<int>& nums) {
        int n = nums.size();
        int xorAll = n; // 先把 n 异或进去（因为循环 i 只到 n-1）
        for (int i = 0; i < n; i++) {
            // 同时异或索引 i 和数组值 nums[i]
            xorAll ^= i ^ nums[i];
        }
        // 成对的数互相抵消，剩下的就是缺失的数
        return xorAll;
    }
};

// ============================================================
// 解法4 拆开写的版本（更容易理解）
// ============================================================
class Solution4_Verbose {
public:
    int missingNumber(vector<int>& nums) {
        int n = nums.size();
        int xorAll = 0;
        // 第一步：异或上 0 ~ n 的所有数
        for (int i = 0; i <= n; i++) {
            xorAll ^= i;
        }
        // 第二步：异或上数组中的所有数
        for (int x : nums) {
            xorAll ^= x;
        }
        // 存在的数出现两次被抵消，缺失的数只出现一次
        return xorAll;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 时间        | 空间  | 溢出风险 | 面试推荐 |
// |----------|-------------|-------|----------|----------|
// | 排序     | O(n log n)  | O(1)  | 无       | 低       |
// | 哈希表   | O(n)        | O(n)  | 无       | 中       |
// | 求和     | O(n)        | O(1)  | n大时有  | 高 ⭐    |
// | 异或     | O(n)        | O(1)  | 无       | 高       |
//
// 面试策略：
// - 先说暴力（排序或哈希表），展示理解题意
// - 然后给出求和法，简洁高效
// - 如果面试官追问溢出，切换到异或法
//
// 【易错点】
// 1. 遍历候选数范围写成 [0, n) 而非 [0, n]
//    ✗ for(int i=0; i<n; i++) — 漏掉了 n 本身可能是缺失的
//    ✓ for(int i=0; i<=n; i++) — 候选范围是 [0, n]
//
// 2. 排序法循环结束后忘记 return n
//    ✗ 循环完就结束 — nums=[0,1,2] 时缺 3(=n) 没有返回
//    ✓ 循环后加 return n;
//
// 3. 异或法合并循环时初始值错误
//    ✗ xorAll = 0, 循环 i 从 0 到 n-1 — 漏掉了索引 n
//    ✓ xorAll = n, 循环 i 从 0 到 n-1 — 等价于异或 0~n 全部
//
// 4. 求和溢出意识（面试加分）
//    本题 n ≤ 10⁴ 不会溢出，但面试中要主动说：
//    "如果 n 很大比如 10⁹，n*(n+1)/2 可能超过 int 范围，
//     可以用 long long 或者改用异或法避免溢出"
//
// 【面试追问】
//
// Q1: "暴力怎么做？"
// → 对每个候选 0~n，线性扫描数组看是否存在。O(n²) 时间。
//
// Q2: "能否 O(n) 时间？"
// → 哈希表 O(n)/O(n)，或求和法 O(n)/O(1)。
//
// Q3: "Follow-up: O(n) 时间 + O(1) 空间？"
// → 求和法或异或法。推荐异或法因为无溢出风险。
//
// Q4: "如果数组很大，求和可能溢出怎么办？"
// → 用 long long，或者改用异或法（完全不涉及加法，不会溢出）。
//    也可以用"边加边减"的写法：
//    int diff = n; for(int i=0; i<n; i++) diff += i - nums[i];
//    这样中间值不会太大。
//
// Q5: "如果缺了两个数怎么办？"
// → 纯异或只能得到两个缺失数的异或值 a^b，不够。
//    需要找到 a^b 中任意一个为 1 的位，按该位分成两组，
//    分别异或得到 a 和 b。参见 LeetCode 260。
//
// 【相关题型】
// - 136. Single Number — 直接复用"异或成对抵消"技巧
// - 260. Single Number III — 两个落单数，在异或基础上按位分组
// - 287. Find the Duplicate Number — "多了一个"而非"少了一个"，对偶问题
// - 41. First Missing Positive — 范围不固定，Hard，需要原地哈希
//
// 【关于二分查找】
// 本题最优解是数学(求和)或位运算(异或)，不需要二分查找。
//
// 排序后可以用二分找到"断裂点"(nums[i] != i 的第一个位置)，
// 但排序本身 O(n log n) 已经劣于数学/位运算的 O(n)，没有实际意义。
//
// 二分在排序数组上的过程（仅供参考，非推荐解法）:
//   排序后 nums = [0, 1, 3], n = 3, 缺失的数 = 2
//
//   目标: 找第一个 nums[i] != i 的位置
//   lo=0, hi=2
//   Round1: mid=1, nums[1]=1 == 1 → 左半正常, lo=mid+1=2
//   Round2: mid=2, nums[2]=3 != 2 → 右半有断裂, hi=mid=2
//   lo==hi=2 → 返回 2 (缺失的数)
//
//   如果数组完全匹配 [0,1,2], 循环结束 lo=3=n → 返回 n
// ============================================================
