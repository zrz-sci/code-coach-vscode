/*
 * LeetCode 940: 不同的子序列 II (Distinct Subsequences II)
 *
 * 【题目本质】
 * 计算字符串 s 中不同非空子序列的个数，结果取模 10^9+7。
 * 核心难点是去重：相同的子序列只计一次。
 *
 * 【解法总览】
 * 解法1: endWith 数组    — O(26n) / O(26) — 覆盖即去重 ⭐面试首选
 * 解法2: 经典 DP + 减法  — O(n) / O(n)   — 显式减去重复量
 * 解法3: endWith + 维护 total — O(n) / O(26) — 严格 O(n) 优化
 */

// ============================================================
// 解法1: endWith 数组 — 覆盖即去重 ⭐面试首选
// 时间: O(26n) ≈ O(n)  空间: O(26) = O(1)
//
// 【核心思想】
// endWith[c] = 以字符 c 结尾的不同子序列个数
//
// 遍历到字符 c 时:
//   endWith[c] = sum(所有 endWith) + 1
//   含义: c 追加到所有已有子序列后面 (sum) + c 单独作为子序列 (+1)
//
// 关键: 是覆盖赋值, 不是累加! 覆盖自动消除了旧的以 c 结尾的子序列。
//
// 答案 = sum(endWith[0..25])
//
// DP 表模拟:
//
// ┌──────────────────────────────────────────────────────┐
// │ s = "aba"                                            │
// │                                                      │
// │ 初始: endWith = [a:0, b:0, ...] (全0)               │
// │                                                      │
// │ Step 1: c='a'                                       │
// │   total = 0                                          │
// │   endWith['a'] = 0 + 1 = 1                          │
// │   endWith: [a:1, b:0]                               │
// │   子序列集合: {"a"}                                  │
// │   总数 = 1                                           │
// │                                                      │
// │ Step 2: c='b'                                       │
// │   total = 1  (只有 endWith['a']=1)                  │
// │   endWith['b'] = 1 + 1 = 2                          │
// │   endWith: [a:1, b:2]                               │
// │   以b结尾: {"b", "ab"} ← "b"自身 + "a"后加"b"      │
// │   总数 = 1 + 2 = 3                                  │
// │                                                      │
// │ Step 3: c='a'                                       │
// │   total = 1 + 2 = 3                                 │
// │   endWith['a'] = 3 + 1 = 4   ← 覆盖旧的1!         │
// │   endWith: [a:4, b:2]                               │
// │   以a结尾: {"a","ba","aa","aba"}                     │
// │     ← "a"自身 + "b"后加"a" + "a"后加"a" + "ab"后加"a" │
// │   总数 = 4 + 2 = 6 ✓                               │
// └──────────────────────────────────────────────────────┘
//
// ┌──────────────────────────────────────────────────────┐
// │ s = "aaa"                                            │
// │                                                      │
// │ Step 1: c='a' → total=0 → endWith['a']=1           │
// │   以a结尾: {"a"}                                    │
// │                                                      │
// │ Step 2: c='a' → total=1 → endWith['a']=2 (覆盖!)  │
// │   以a结尾: {"a","aa"}                               │
// │   注意: 不是 1+2=3! 是覆盖为2!                     │
// │   如果用累加: endWith['a']=3 → 会多数一个"a"       │
// │                                                      │
// │ Step 3: c='a' → total=2 → endWith['a']=3 (覆盖!)  │
// │   以a结尾: {"a","aa","aaa"}                         │
// │   总数 = 3 ✓                                        │
// └──────────────────────────────────────────────────────┘
//
// ┌──────────────────────────────────────────────────────┐
// │ s = "abc" (所有字符不同，无需去重)                   │
// │                                                      │
// │ Step 1: c='a' → endWith=[1,0,0] → total=1          │
// │ Step 2: c='b' → endWith=[1,2,0] → total=3          │
// │ Step 3: c='c' → endWith=[1,2,4] → total=7          │
// │                                                      │
// │ 验证: 2^3-1=7 (无重复字符时等于全子集数-空集)       │
// └──────────────────────────────────────────────────────┘
//
// ============================================================
class Solution1 {
public:
    int distinctSubseqII(string s) {
        const int MOD = 1e9 + 7;
        // endWith[c] = 以字符 c 结尾的不同子序列数
        vector<long> endWith(26, 0);

        for (char c : s) {
            // 计算所有已有子序列的总数
            long total = 0;
            for (int i = 0; i < 26; i++) {
                total = (total + endWith[i]) % MOD;
            }
            // 核心: 覆盖赋值 (不是累加!)
            // c 追加到所有已有子序列后面 (total) + c 自身 (+1)
            endWith[c - 'a'] = (total + 1) % MOD;
        }

        // 答案 = 所有 endWith 之和
        long ans = 0;
        for (int i = 0; i < 26; i++) {
            ans = (ans + endWith[i]) % MOD;
        }
        return ans;
    }
};

// ============================================================
// 解法2: 经典 DP 公式 + 减法去重
// 时间: O(n)  空间: O(n)
//
// 【思路】
// dp[i] = 前 i+1 个字符的不同非空子序列数
//
// 基础转移: dp[i] = 2 * dp[i-1] + 1
//   含义: 旧子序列(dp[i-1]) + 旧子序列追加s[i](dp[i-1]) + s[i]自身(1)
//
// 去重: 如果 s[i] 上次在位置 j 出现过:
//   dp[i] -= dp[j-1] + 1
//   含义: 处理 s[j] 时产生的新子序列 = dp[j-1]个(追加) + 1个(自身)
//         这些在 s[i] 时又被完全重复产生了
//
// 模拟 (s = "aba"):
//
//   i=0, c='a': dp[0] = 2*0+1 = 1     子序列: {"a"}
//   i=1, c='b': dp[1] = 2*1+1 = 3     子序列: {"a","b","ab"}
//   i=2, c='a': dp[2] = 2*3+1 = 7
//     'a' 上次在 j=0 出现
//     重复量 = dp[-1]+1 = 0+1 = 1     (就是 "a" 自身)
//     dp[2] = 7 - 1 = 6               子序列: {"a","b","ab","ba","aa","aba"}
//
// ============================================================
class Solution2 {
public:
    int distinctSubseqII(string s) {
        const int MOD = 1e9 + 7;
        int n = s.size();
        vector<long> dp(n, 0);
        vector<int> last(26, -1);  // 每个字符上次出现的位置

        for (int i = 0; i < n; i++) {
            int c = s[i] - 'a';

            // 基础转移
            if (i == 0) {
                dp[i] = 1;
            } else {
                dp[i] = (2 * dp[i - 1] % MOD + 1) % MOD;
            }

            // 去重: 减去上次出现时的重复量
            if (last[c] != -1) {
                int j = last[c];
                // 重复量 = j==0 时为 1, 否则为 dp[j-1]+1
                long dup = (j == 0) ? 1 : (dp[j - 1] + 1) % MOD;
                // 注意: 减法可能产生负数, 加 MOD 后再取模
                dp[i] = (dp[i] - dup + MOD) % MOD;
            }

            // 更新 last (必须在减法之后!)
            last[c] = i;
        }

        return dp[n - 1];
    }
};

// ============================================================
// 解法3: endWith + 维护 total 变量 — 严格 O(n)
//
// 解法1 每次需要 O(26) 求 total，总时间 O(26n)。
// 优化: 用一个变量 total 维护 sum(endWith)，每次更新时:
//   new_endWith[c] = total + 1
//   total = total - old_endWith[c] + new_endWith[c]
// 这样每步 O(1), 总时间严格 O(n)。
// ============================================================
class Solution3 {
public:
    int distinctSubseqII(string s) {
        const int MOD = 1e9 + 7;
        vector<long> endWith(26, 0);
        long total = 0;  // 维护 sum(endWith)

        for (char c : s) {
            int idx = c - 'a';
            long oldVal = endWith[idx];
            long newVal = (total + 1) % MOD;

            endWith[idx] = newVal;

            // 更新 total: 减去旧值, 加上新值
            total = ((total - oldVal + newVal) % MOD + MOD) % MOD;
        }

        return total;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法             | 时间     | 空间  | 面试推荐 |
// |-----------------|----------|-------|---------|
// | endWith 数组     | O(26n)  | O(26) | ⭐⭐⭐    |
// | 经典 DP + 减法   | O(n)    | O(n)  | ⭐⭐     |
// | endWith + total | O(n)    | O(26) | 追问优化  |
//
// 推荐 endWith 方法: 代码最短, 去重逻辑最自然 (覆盖即去重),
// 不会出现取模负数问题 (没有减法)。
//
// ============================================================
// 【易错点】
//
// 1. endWith 覆盖 vs 累加 (最核心的错误):
//    ✗ endWith[c] += total + 1  — 旧的以c结尾的子序列被重复计数
//    ✓ endWith[c] = total + 1   — 覆盖旧值, 自动去重
//
// 2. 减法取模产生负数:
//    ✗ dp[i] = (dp[i] - dup) % MOD — 可能得到负数
//    ✓ dp[i] = (dp[i] - dup + MOD) % MOD
//    C++ 中 (-1) % MOD = -1, 不是 MOD-1!
//
// 3. 忘记 +1 (c 自身作为子序列):
//    ✗ endWith[c] = total — 漏掉了 c 自身
//    ✓ endWith[c] = total + 1
//    +1 代表 c 单独作为一个长度为 1 的子序列
//
// 4. lastOccurrence 更新时机:
//    在经典 DP 中, 必须先用 last[c] 做减法, 再更新 last[c] = i
//    如果先更新, j 就是当前位置, 找不到"上次出现的位置"
//
// 5. 解法3中 total 更新的负数问题:
//    total = total - oldVal + newVal 可能中间产生负数
//    需要 (total - oldVal + newVal % MOD + MOD) % MOD
//
// ============================================================
// 【面试追问 Interview Follow-ups】
//
// Q1: 为什么 endWith 覆盖能去重? 请证明。
// A1: 新的 endWith[c] = total+1 枚举了所有"在当前位置的c之前的子序列后追加c"
//     的可能性。这完全覆盖了之前任何位置的c所产生的以c结尾的子序列。
//     因为: 如果旧的以c结尾的子序列是 "...c"(c在位置j), 那么 "..." 一定是
//     前j-1个字符的某个子序列, 它肯定也是前i-1个字符的子序列(子集关系),
//     所以新的 total 已经包含了它, "..."+c 一定在新的枚举中。
//
// Q2: 时间复杂度能否优化到 O(n)?
// A2: 可以! 用一个 total 变量维护 sum(endWith) (解法3):
//     每次 total = total - oldEndWith[c] + newEndWith[c]
//     每步 O(1), 总时间 O(n)。
//
// Q3: 这道题和 LC 115 Distinct Subsequences 有什么区别?
// A3: 完全不同的问题。LC 115 是"s中有多少子序列等于t"(双串匹配, 二维DP)。
//     本题是"s有多少不同的子序列"(单串计数, 一维DP+去重)。
//
// Q4: 如果字符集不限于26个字母?
// A4: endWith 改为 HashMap<char, long>。空间 O(K), K为不同字符数。
//     时间 O(Kn) 或用 total 变量做到 O(n)。
// ============================================================
