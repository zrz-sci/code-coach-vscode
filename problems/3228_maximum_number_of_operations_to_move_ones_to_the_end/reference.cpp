/*
 * LeetCode 3228: 将 1 移动到末尾的最大操作次数
 * (Maximum Number of Operations to Move Ones to the End)
 * 难度: Medium
 * 标签: Greedy, String, Counting
 *
 * 题目: 给定二进制字符串 s，每次操作选一个 "10" 位置，将 '1' 滑到右边
 *       最近的 '1' 前或字符串末尾。返回最大操作次数。
 *
 * 约束: 1 <= s.length <= 10^5, s[i] 是 '0' 或 '1'
 *
 * 核心洞察: 每段连续 0 被它左边所有 1 穿越，每次穿越 = 一次操作。
 *           在 "10" 边界处累加左侧已见到的 1 的个数。
 */


/* ============================================================
 * 解法 1: 贪心一次遍历 — O(n) / O(1) [推荐]
 * ============================================================
 *
 * 算法:
 *   1. 从左到右扫描，维护已见到的 '1' 的个数 ones
 *   2. 遇到 '1': ones++
 *   3. 遇到 '0' 且前一个是 '1' (即 "10" 边界):
 *      → 所有左侧的 ones 个 '1' 都要穿越这段 '0'
 *      → ans += ones
 *
 * 为什么 "10" 边界只计一次?
 *   一段连续的 "000..." 对每个左边的 '1' 来说只需穿越一次
 *   不管这段 '0' 有多长，穿越它就是一次操作
 *
 * 详细推演 (s = "1001101"):
 * ┌────┬──────┬─────────────────────┬──────┬──────┐
 * │ i  │ s[i] │ 动作                │ ones │ ans  │
 * ├────┼──────┼─────────────────────┼──────┼──────┤
 * │ 0  │ '1'  │ ones++              │  1   │  0   │
 * │ 1  │ '0'  │ "10"边界 → ans += 1│  1   │  1   │
 * │ 2  │ '0'  │ 连续 0, 跳过       │  1   │  1   │
 * │ 3  │ '1'  │ ones++              │  2   │  1   │
 * │ 4  │ '1'  │ ones++              │  3   │  1   │
 * │ 5  │ '0'  │ "10"边界 → ans += 3│  3   │  4   │
 * │ 6  │ '1'  │ ones++              │  4   │  4   │
 * └────┴──────┴─────────────────────┴──────┴──────┘
 * 答案: 4 ✓
 */
class Solution {
public:
    int maxOperations(string s) {
        int ones = 0;   // 左侧已见到的 '1' 的个数
        int ans = 0;    // 总操作次数
        int n = s.size();

        for (int i = 0; i < n; i++) {
            if (s[i] == '1') {
                // 遇到 '1'，计数器加 1
                ones++;
            } else {
                // s[i] == '0'
                // 检查是否是 "10" 边界（一段新 0 的起点）
                if (i > 0 && s[i - 1] == '1') {
                    // 所有左边的 ones 个 '1' 都要穿越这段 '0'
                    ans += ones;
                }
                // 如果 s[i-1] 也是 '0'，说明在同一段连续 0 中，不重复计数
            }
        }

        return ans;
    }
};


