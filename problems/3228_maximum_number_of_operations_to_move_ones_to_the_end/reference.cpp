/* ============================================================
 * 知识点总结
 * ============================================================
 *
 * 1. 贪心计数的核心:
 *    每段连续 '0' 的操作贡献 = 它左边 '1' 的个数
 *    因为每个 '1' 穿越这段 '0' 恰好需要一次操作
 *
 * 2. "10" 边界检测:
 *    s[i]=='0' && s[i-1]=='1' 标志着进入新的 '0' 段
 *    在这个入口点计数，避免对同一段 '0' 重复计数
 *
 * 3. 操作顺序无关性:
 *    无论先移动哪个 '1'，每个 '1' 最终都要穿越它右边
 *    的每段 '0' 恰好一次，所以总操作次数唯一确定
 *
 * 4. 时间 O(n) 空间 O(1)，最优
 *
 * 5. 类似问题:
 *    - 冒泡排序的交换次数 = 逆序对数
 *    - 本题的"穿越"操作比冒泡更粗粒度 (跳过整段0)
 */

/*
 * ============================================================
 * 总结
 * ============================================================
 *
 * 【解法对比】
 * ┌──────────────────────────────┬────────┬────────┬──────────────────────────┐
 * │ 解法                         │ 时间   │ 空间   │ 特点                     │
 * ├──────────────────────────────┼────────┼────────┼──────────────────────────┤
 * │ 1. "10"边界检测 ⭐            │ O(n)   │ O(1)   │ 面试首选，一次遍历       │
 * │ 2. 按0段分割 + flag           │ O(n)   │ O(1)   │ 用 bool 标记0段，更直观  │
 * │ 3. 简洁写法 (等价变体)        │ O(n)   │ O(1)   │ 代码最短                 │
 * └──────────────────────────────┴────────┴────────┴──────────────────────────┘
 *   三种解法本质完全相同，只是检测"进入新0段"的写法不同。
 *
 * 【易错点】
 * 1. "10"边界只在段入口计一次: s[i]=='0' && s[i-1]=='1' 才累加 ones，
 *    连续的 "000..." 中只有第一个 '0' 触发计数，否则会多算。
 * 2. 边界 i=0: 检查 s[i-1] 前要确保 i>0，否则越界访问。
 * 3. 末尾全是 '1' 时不产生操作: "111" 答案是 0，因为没有 '0' 可穿越。
 *    容易误以为 '1' 之间需要操作。
 * 4. 容易和冒泡排序类比混淆: 冒泡是每交换一对相邻元素算一次，本题是
 *    '1' 跳过整段 '0' 算一次。"1001" 中第一个 '1' 穿越两个 '0' 只算 1 次操作。
 * 5. ones 只增不减: 每个 '1' 一旦被计入 ones，它对后续所有 '0' 段都有贡献，
 *    不需要重置。
 *
 * 【面试追问】
 * Q1: 这道题和逆序对有什么关系?
 *     → 如果把每个 '1' 穿越每个 '0' 都算一次 (冒泡模型)，答案就是 (1,0) 逆序对数。
 *       本题的操作定义更粗: '1' 一次滑过整段连续 '0'，所以比逆序对数小。
 *
 * Q2: 如果操作改为"每次只能将 '1' 和相邻的 '0' 交换一次"，答案怎么变?
 *     → 变成求 (1,0) 逆序对数。遍历时每遇到 '0' 就累加左侧 ones (不是只在
 *       "10"边界)。s="1001" 从 1 次变成 2 次。
 *
 * Q3: 如果字符串不是二进制而是多种字符 (如 "abc")，要把所有 'a' 移到末尾，
 *     最大操作次数怎么算?
 *     → 类似地，遍历时维护 'a' 的计数，遇到非 'a' 段的入口时累加。
 *       本质不变，只是判断条件从 '1'/'0' 泛化为目标字符/非目标字符。
 */
