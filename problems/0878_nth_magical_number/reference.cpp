/*
 * LeetCode 878: Nth Magical Number (第 N 个神奇数字)
 *
 * 【题目本质】
 * 求第 n 个能被 a 或 b 整除的正整数（mod 10^9+7）。
 * n 最大 10^9，不可能枚举 → 二分答案 + 容斥原理。
 *
 * 【解法总览】
 * 解法1: 二分+容斥    — O(log(n*min(a,b))) / O(1) — 唯一正解
 * 解法2: 周期法(参考)  — O(a+b) / O(1)            — 数学方法
 */

// ============================================================
// 解法1: 二分查找 + 容斥原理
// 时间: O(log(n*min(a,b)))  空间: O(1)
//
// 【核心思想】
// 定义 f(x) = [1, x] 中能被 a 或 b 整除的正整数个数。
// 由容斥原理: f(x) = x/a + x/b - x/lcm(a,b)
//   - x/a: 被 a 整除的数的个数
//   - x/b: 被 b 整除的数的个数
//   - x/lcm(a,b): 同时被 a 和 b 整除的数的个数（即被 lcm 整除）
//   - 减去 lcm 部分避免重复计数
//
// f(x) 是非递减函数 → 二分查找最小的 x 使得 f(x) >= n。
//
// 【为什么 f(x) = n 一定有解？】
// 对于 a 或 b 的倍数 x，f(x) = f(x-1) + 1（恰好多一个神奇数字）。
// 而对于非倍数 x，f(x) = f(x-1)（不变）。
// 所以 f 的值域覆盖所有正整数，n 一定在值域中。
//
// 【二分范围】
// lo = 1（最小正整数）
// hi = n * min(a, b)（最坏情况：所有神奇数字都是 min(a,b) 的倍数）
//
// 示例: n=4, a=2, b=3
//   lcm(2,3) = 6
//   f(x) = x/2 + x/3 - x/6
//
//   x: 1  2  3  4  5  6  7  8
// f(x): 0  1  2  3  3  4  4  5
//        ↑     ↑     ↑     ↑
//       非    #2    #3    #4=6
//
//   二分找 f(x) >= 4 的最小 x = 6
//   答案: 6
// ============================================================
class Solution1 {
public:
    int nthMagicalNumber(int n, int a, int b) {
        const long long MOD = 1e9 + 7;

        // 计算最小公倍数 lcm(a, b)
        // 注意: 先除 gcd 再乘，防止 a*b 溢出
        long long g = __gcd(a, b);
        long long lcm = (long long)a / g * b;

        // 二分查找: 找最小的 x 使得 f(x) >= n
        long long lo = 1;
        long long hi = (long long)n * min(a, b); // 上界

        while (lo < hi) {
            long long mid = lo + (hi - lo) / 2;

            // 容斥计数: [1, mid] 中能被 a 或 b 整除的数的个数
            long long cnt = mid / a + mid / b - mid / lcm;

            if (cnt < n) {
                lo = mid + 1; // 不够 n 个，答案在右半边
            } else {
                hi = mid;     // 够了，答案可能是 mid 或更小
            }
        }

        // 二分过程不能取模！只在最终结果取模
        return lo % MOD;
    }
};

// ============================================================
// 解法2: 数学周期法 (参考)
// 时间: O(lcm/a + lcm/b) ≈ O(a+b)  空间: O(1)
//
// 【思路】
// 在一个 LCM 周期 [1, lcm(a,b)] 内，神奇数字个数是固定的:
//   m = lcm/a + lcm/b - 1
//
// 第 n 个神奇数字:
//   完整周期数 q = (n-1) / m
//   周期内偏移 r = n - q * m  (r >= 1)
//   答案 = q * lcm + 在 [1, lcm] 中的第 r 个神奇数字
//
// 在 [1, lcm] 内找第 r 个神奇数字:
//   用双指针合并 a 的倍数和 b 的倍数的有序序列
//   a: a, 2a, 3a, ..., lcm
//   b: b, 2b, 3b, ..., lcm
//   每次取较小的那个，直到取了 r 个
//
// 这个方法对 a, b 较小时很快，但当 a, b 都很大时
// 周期内元素数可能也很大，不如二分通用。
// ============================================================
class Solution2 {
public:
    int nthMagicalNumber(int n, int a, int b) {
        const long long MOD = 1e9 + 7;
        long long g = __gcd(a, b);
        long long lcm = (long long)a / g * b;

        // 一个 lcm 周期内的神奇数字个数
        long long m = lcm / a + lcm / b - 1;

        // 完整周期数和周期内偏移
        long long q = (n - 1) / m;     // 有多少个完整周期
        long long r = n - q * m;        // 周期内第几个 (1-indexed)

        // 基础值: q 个完整周期的贡献
        long long base = (q % MOD) * (lcm % MOD) % MOD;

        // 在 [1, lcm] 内用双指针找第 r 个神奇数字
        long long pa = a, pb = b; // 当前 a 的倍数和 b 的倍数
        long long val = 0;
        for (long long i = 0; i < r; i++) {
            if (pa <= pb) {
                val = pa;
                pa += a;
            } else {
                val = pb;
                pb += b;
            }
            // 如果 pa 和 pb 相等（都是 lcm 的倍数），跳过重复
            if (pa == pb) {
                // 不需要特殊处理，下次循环自然处理
                // 但如果 val == lcm，pa 和 pb 都会超过 lcm
            }
        }

        return (base + val % MOD) % MOD;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法      | 时间                  | 空间  | 适用场景            |
// |-----------|----------------------|-------|-------------------|
// | 二分+容斥  | O(log(n*min(a,b)))   | O(1)  | 通用，推荐          |
// | 周期法     | O(a+b)               | O(1)  | a,b 较小时很快      |
//
// 面试选择：二分+容斥。代码简洁，思路清晰，容易讲解。
// 周期法作为补充说明，展示数学直觉。
//
// ============================================================
// 【易错点总结】
//
// 1. 整数溢出:
//    ✗ long long hi = n * min(a, b); → n 是 int，乘法溢出
//    ✓ long long hi = (long long)n * min(a, b);
//
// 2. 二分过程中取模:
//    ✗ mid = (lo + hi) / 2 % MOD; → 取模后值变小，cnt 计算错误
//    ✓ 二分全程用真实值，只在 return lo % MOD 时取模
//
// 3. lcm 计算溢出:
//    ✗ long long lcm = a * b / __gcd(a, b); → a*b 可能溢出
//    ✓ long long lcm = (long long)a / __gcd(a, b) * b; → 先除后乘
//
// 4. 容斥公式漏减 lcm 部分:
//    ✗ cnt = mid/a + mid/b; → 重复计算了同时被 a 和 b 整除的数
//    ✓ cnt = mid/a + mid/b - mid/lcm;
//
// 5. 二分上界不够大:
//    ✗ hi = n; → 当 a=b=2 时，第 n 个神奇数字是 2n，大于 n
//    ✓ hi = (long long)n * min(a, b); → 保证上界足够
//
// ============================================================
// 【面试追问与回答】
//
// Q: 如果是三个数 a, b, c 呢？
// A: 容斥扩展:
//    f(x) = x/a + x/b + x/c
//         - x/lcm(a,b) - x/lcm(a,c) - x/lcm(b,c)
//         + x/lcm(a,b,c)
//    二分框架不变。这就是 LeetCode 1201 (丑数 III)。
//
// Q: 容斥原理的时间复杂度与参与个数的关系？
// A: k 个数的容斥需要 2^k - 1 项。对于 k 很大时不实用，
//    但 k 通常很小（2或3），O(2^k) 可以忽略。
