// | 2.DP | O(n) | O(1)滚动 | 超时 | 理解转移 |
// | 3.Minimax | O(n) | O(n) | 超时超空间 | 理解博弈 |
//
// 面试策略:
// 1. 先从小例子推导规律: n=1→W, n=2→W, n=3→W, n=4→L, n=5→W, ...
// 2. 发现 n%4 的周期性
// 3. 给出"凑4策略"的直觉解释
// 4. 如果面试官要求严格证明, 用数学归纳法
// 5. 写出一行代码
//
// 【博弈论扩展知识】
//
// Bash Game 一般化:
//   每次可取 1~m 个, n 块石头, n%(m+1)!=0 时先手赢。
//   本题 m=3, 所以 n%4!=0。
//
// 多堆 Nim (标准 Nim Game):
//   多堆石头, 每次从一堆取任意个, 取完最后一块的赢。
//   结论: 所有堆 XOR != 0 时先手赢。(Sprague-Grundy 定理)
//
// Misere Nim (反向 Nim):
//   取走最后一块的人"输"。
//   结论: 略有不同, 但本题是标准 Nim, 不涉及。
//
// 【易错点】
// 1. 用 O(n) DP 导致超时:
//    n 可达 2^31-1, O(n) 完全不可行。必须用 O(1) 数学方法。
//
// 2. 只给结论不给推导:
//    面试官期望看到从小例子 → 发现规律 → 解释/证明的完整过程。
//
// 3. 混淆"拿到最后赢"和"拿到最后输":
//    本题是标准 Nim (拿到最后赢)。如果是 Misere Nim, 结论不同。
//
// 【面试追问】
// Q1: 为什么是4? → 每轮两人合拿4(你拿k对手拿4-k), 凑4策略。
// Q2: 一般化? → 每次取1~m个, 答案 n%(m+1)!=0。
// Q3: 多堆? → 各堆XOR!=0先手赢 (Sprague-Grundy)。
// Q4: 反向Nim(取最后输)? → Misere Nim, 结论略有不同。
// ============================================================
