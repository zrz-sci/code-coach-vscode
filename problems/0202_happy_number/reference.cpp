/*
 * LeetCode 202: 快乐数 (Happy Number)
 *
 * 【题目本质】
 * 反复对数字做"各位平方和"运算，判断序列是否能到达 1。
 * 本质是隐式链表的判环问题：序列要么到 1（自环），要么进入不含 1 的环。
 *
 * 【解法总览】
 * 解法1: 哈希集合     — O(log n) / O(log n) — 最直觉，用 set 检测重复
 * 解法2: 快慢指针     — O(log n) / O(1)     — 面试首选，Floyd 判环
 * 解法3: 数学(硬编码) — O(log n) / O(1)     — 利用"非快乐数必经过4"的结论
 *
 * 【为什么时间是 O(log n)？】
 * n 有 O(log n) 位数字，getNext 一次是 O(log n)。
 * 第一次 getNext 后数字 ≤ 810（因为最多10位，9²×10=810）。
 * 之后在有限范围内运算，总步数是常数。
 * 所以整体 O(log n)。
 */

// ============================================================
// 公共辅助函数: 计算各位数字的平方和
// ============================================================
// 单独提取出来，三种解法共用
// 例如: getNext(19) = 1² + 9² = 1 + 81 = 82
//       getNext(82) = 8² + 2² = 64 + 4  = 68

// ============================================================
// 解法1: 哈希集合 — 记录所有出现过的数字，检测循环
// 时间: O(log n)  空间: O(log n)
//
// 【思路】
// 最直觉的想法：怎么知道序列进入了循环？
// → 如果一个数字之前出现过，就说明有环。
// 用 HashSet 存储见过的数字，每次检查是否重复。
//
// 数字序列示意:
// n=19: 19 → 82 → 68 → 100 → 1 (到达1, 快乐数!)
// n=2:  2 → 4 → 16 → 37 → 58 → 89 → 145 → 42 → 20 → 4 (循环!)
//                                                      ↑______|
// ============================================================
class Solution1 {
public:
    bool isHappy(int n) {
        unordered_set<int> seen;
        while (n != 1) {
            // 如果 n 已经见过，说明进入循环，永远到不了 1
            if (seen.count(n)) return false;
            seen.insert(n);
            n = getNext(n);
        }
        return true; // n == 1
    }

private:
    int getNext(int n) {
        int sum = 0;
        while (n > 0) {
            int d = n % 10;   // 取最低位数字
            sum += d * d;     // 平方后累加
            n /= 10;          // 去掉最低位
        }
        return sum;
    }
};

// ============================================================
// 解法2: 快慢指针 (Floyd 判环) — 面试首选
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 解法1的瓶颈：需要 O(log n) 空间存储 set。
// 
// 关键洞察：把 "n → getNext(n)" 看成链表的 "node → node.next"
// 那么这道题就变成了经典的"链表判环"问题！
//
// 类比:
//   链表判环:  node → node.next → node.next.next → ...
//   本题:      n    → getNext(n) → getNext(getNext(n)) → ...
//
// Floyd 快慢指针:
//   - 慢指针: 每次走一步 slow = getNext(slow)
//   - 快指针: 每次走两步 fast = getNext(getNext(fast))
//   - 如果有环，fast 和 slow 一定相遇
//   - 如果序列能到达 1，由于 getNext(1)=1，1 是自环
//     快指针会先到 1 然后停在 1，循环终止
//
// 快慢指针过程 (n=19):
//   Step  slow  fast
//   init   19    82    (fast 先走一步: getNext(19)=82)
//   1      82    100   (slow: getNext(19)=82, fast: getNext(getNext(82))=getNext(68)=100)
//   2      68    1     (slow: getNext(82)=68, fast: getNext(getNext(100))=getNext(1)=1)
//   → fast==1, 返回 true!
//
// 快慢指针过程 (n=2):
//   Step  slow  fast
//   init   2     4     (fast: getNext(2)=4)
//   1      4     37    (slow: 4, fast: getNext(getNext(4))=getNext(16)=37)
//   2      16    145   ...
//   ...    ...   ...
//   最终 slow == fast (在环上相遇, 且不为1) → 返回 false
// ============================================================
class Solution2 {
public:
    bool isHappy(int n) {
        int slow = n;
        int fast = getNext(n);  // fast 先走一步，避免初始 slow==fast

        // 循环直到 fast 到达 1 或者 slow 追上 fast（有环）
        while (fast != 1 && slow != fast) {
            slow = getNext(slow);            // 慢指针走一步
            fast = getNext(getNext(fast));    // 快指针走两步
        }

        // fast == 1 说明序列能到达 1 → 快乐数
        // slow == fast 且 fast != 1 说明在非 1 的环上相遇 → 非快乐数
        return fast == 1;
    }

private:
    int getNext(int n) {
        int sum = 0;
        while (n > 0) {
            int d = n % 10;
            sum += d * d;
            n /= 10;
        }
        return sum;
    }
};

// ============================================================
// 解法3: 数学方法 — 非快乐数必经过 4
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 数学事实：所有非快乐数在迭代过程中一定会经过 4。
// 更具体地说，不含 1 的环只有一个:
//   4 → 16 → 37 → 58 → 89 → 145 → 42 → 20 → 4
//
// 证明思路：
//   - getNext 的值域很小（≤810）
//   - 穷举 1~810 所有数字的序列，发现只有上述一个环
//   - 所以只要检测到 4 就可以提前终止
//
// 注意：这个解法依赖数学结论，面试中如果能推导出来是加分项，
// 但大多数面试官更认可解法2（快慢指针），因为它展示的是通用算法能力。
// ============================================================
class Solution3 {
public:
    bool isHappy(int n) {
        // 只有两种终态：到达 1（快乐）或到达 4（进入非快乐环）
        while (n != 1 && n != 4) {
            n = getNext(n);
        }
        return n == 1;
    }

private:
    int getNext(int n) {
        int sum = 0;
        while (n > 0) {
            int d = n % 10;
            sum += d * d;
            n /= 10;
        }
        return sum;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间     | 空间     | 核心思想           | 面试推荐   |
// |------------|----------|----------|--------------------|-----------|
// | 哈希集合   | O(log n) | O(log n) | 记录历史检测重复   | 先说出来   |
// | 快慢指针   | O(log n) | O(1)     | Floyd 判环         | ⭐ 首选    |
// | 数学方法   | O(log n) | O(1)     | 非快乐数必经过 4   | 加分项     |
//
// 哈希集合 vs 快慢指针:
//   - 哈希集合直觉简单，但需要额外空间
//   - 快慢指针 O(1) 空间，体现算法功底
//   - 面试时建议：先说哈希集合，再优化为快慢指针
//
// 【易错点】
// 1. 快慢指针初始化:
//    ✗ int slow = n, fast = n; → while 条件 slow != fast 一开始就 false
//    ✓ int slow = n, fast = getNext(n); → fast 先走一步
//
// 2. getNext 中 n % 10 的理解:
//    ✗ 误以为 n % 10 可能返回负数 → 题目保证 n ≥ 1，且平方和始终为正
//    ✓ 对正整数，n % 10 ∈ [0, 9]，完全安全
//
// 3. while 循环条件遗漏:
//    ✗ while (slow != fast) → 如果 fast 先到 1，slow 还在路上，
//       可能 slow 永远追不上 fast=1...等等，其实能追上，
//       因为 getNext(1)=1，fast 停在 1，slow 最终也到 1。
//       但更清晰的写法是 while (fast != 1 && slow != fast)，
//       一旦 fast==1 就直接返回 true，不需要等 slow 追上。
//
// 4. 以为平方和会溢出 int:
//    ✗ 担心 d*d 溢出 → d ∈ [0,9], d*d ≤ 81, 最多10位数
//       sum ≤ 810，远小于 INT_MAX，不会溢出
//
// 【面试追问】
// Q1: "为什么序列一定会进入循环？不会无限增长吗？"
//     → 32位int最大约2×10⁹(10位), 各位平方和 ≤ 9²×10 = 810
//     → 第一步后就收敛到 ≤ 810, 有限范围内由鸽巢原理必产生循环
//
// Q2: "哈希表需要额外空间, 能否优化到 O(1)?"
//     → Floyd 快慢指针: 把数字序列看成隐式链表, 判环只需两个变量
//
// Q3: "如果要输出非快乐数的循环包含哪些数字, 怎么做?"
//     → 先用快慢指针找到环上相遇点, 然后从相遇点出发
//       反复 getNext 直到回到相遇点, 沿途所有数字就是环上元素
//       (和 142.环形链表II 找环上所有节点思路相同)
//
// 【相关题型】
// - 141. 环形链表 — 直接复用 Floyd 快慢指针框架
//   区别: 141 是显式链表, 本题是隐式链表(数字序列)
//
// - 142. 环形链表 II — 找环的入口点
//   本题如果追问"环从哪里开始", 就用同样的两阶段法
//
// - 258. 各位相加 — 同样是反复对各位做运算直到收敛
//   区别: 258 是求和(不是平方和), 且有 O(1) 数学公式 (digital root)
//
// - 457. 环形数组是否存在循环 — 另一个隐式图上的判环问题
//   复用快慢指针, 但需要额外处理方向一致性约束
// ============================================================
