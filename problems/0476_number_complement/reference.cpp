/*
 * LeetCode 476: Number Complement
 * 难度: Easy | 标签: Bit Manipulation
 *
 * 核心思路: 构造全1掩码 + XOR
 *
 * 原理:
 *   num  = 101  (5)
 *   mask = 111  (7, 与num位数相同的全1)
 *   XOR  = 010  (2, 补数)
 *
 *   0 XOR 1 = 1  (0翻转为1)
 *   1 XOR 1 = 0  (1翻转为0)
 *
 * mask构造:
 *   循环法: mask = 0 -> 1 -> 11 -> 111  (每次左移加1)
 *   位长法: mask = (1 << bitLength) - 1
 *
 * 注意 ~num 是32位全翻转(包括前导零), 不等于补数!
 *   ~5 = ~(00...0101) = 11...1010 = -6  (不是2!)
 */


// ================================================================
// 解法1: 循环构造mask -- O(log n) 时间, O(1) 空间 [最推荐]
// ================================================================
// mask 从 0 开始, 不断 (mask << 1) | 1 直到 mask >= num
// 最终 mask 是与 num 位数相同的全 1 数
//
// 过程:
//   num = 5 (101)
//   mask = 0
//   mask = (0 << 1) | 1 = 1      (1)     < 5
//   mask = (1 << 1) | 1 = 3      (11)    < 5
//   mask = (3 << 1) | 1 = 7      (111)   >= 5, 停止
//   结果 = 5 ^ 7 = 101 ^ 111 = 010 = 2
class Solution {
public:
    int findComplement(int num) {
        unsigned mask = 0;
        unsigned n = num;
        while (mask < n) {
            mask = (mask << 1) | 1;
        }
        return num ^ mask;
    }
};


// ================================================================
// 解法2: 位长计算mask -- O(log n) 时间, O(1) 空间
// ================================================================
// 先数出 num 的二进制位长度 bitLen
// mask = 2^bitLen - 1 (全1)
//
// 例: num = 5 (101), bitLen = 3
//     mask = (1 << 3) - 1 = 8 - 1 = 7 (111)
//     5 ^ 7 = 2
//
// 注意: 1 << 31 溢出 int, 必须用 unsigned
class Solution2 {
public:
    int findComplement(int num) {
        int bitLen = 0;
        int temp = num;
        while (temp > 0) {
            bitLen++;
            temp >>= 1;
        }
        unsigned mask = (1u << bitLen) - 1;
        return num ^ mask;
    }
};


// ================================================================
// 解法3: 逐位翻转 -- O(log n) 时间, O(1) 空间
// ================================================================
// 不用 XOR, 直接逐位构造补数
// 如果当前位是 0, 在结果中设为 1
// 如果当前位是 1, 结果中保持 0 (初始值)
class Solution3 {
public:
    int findComplement(int num) {
        int result = 0;
        int bit = 1;  // 当前处理的位掩码
        int temp = num;
        while (temp > 0) {
            if ((temp & 1) == 0) {
                result |= bit;  // 原来是0的位, 补数中设为1
            }
            bit <<= 1;
            temp >>= 1;
        }
        return result;
    }
};


// ================================================================
// 解法4: 减法法 -- O(log n) 时间, O(1) 空间
// ================================================================
// 观察: num + complement = mask (全1)
// 所以: complement = mask - num
//
// 例: 5 + 2 = 7 (111)
//     complement = 7 - 5 = 2
class Solution4 {
public:
    int findComplement(int num) {
        unsigned mask = 0;
        unsigned n = num;
        while (mask < n) {
            mask = (mask << 1) | 1;
        }
        return mask - num;  // 等价于 num ^ mask
    }
};


// ================================================================
// 解法5: 一行解法 (利用内置函数)
// ================================================================
// __builtin_clz: count leading zeros (前导零个数)
// 32 - clz(num) = 有效位数
// mask = (1u << 有效位数) - 1
class Solution5 {
public:
    int findComplement(int num) {
        return num ^ ((1u << (32 - __builtin_clz(num))) - 1);
    }
};


/*
 * ================================================================
 * 复杂度对比:
 *
 * | 解法         | 时间      | 空间 | 核心操作              |
 * |-------------|----------|------|---------------------|
 * | 循环构造mask  | O(log n) | O(1) | mask = (mask<<1)|1  |
 * | 位长计算mask  | O(log n) | O(1) | (1u << bitLen) - 1  |
 * | 逐位翻转     | O(log n) | O(1) | 每位独立处理         |
 * | 减法法       | O(log n) | O(1) | mask - num          |
 * | 一行内置     | O(1)*    | O(1) | __builtin_clz       |
 *
 * (*) 内置函数通常有硬件支持, 视为O(1)
 *
 * ================================================================
 * 位运算备忘:
 *
 *   num ^ mask    XOR: 相同位变0, 不同位变1 -> 翻转
 *   ~num          NOT: 所有32位翻转 (包括前导零)
 *   (x << 1) | 1  左移后最低位设1 -> 构造全1
 *   (1 << k) - 1  k位全1: 111...1 (k个1)
 *
 * ================================================================
 * ~num vs findComplement(num):
 *
 *   ~5 = ~(00000000...00000101)
 *      =  (11111111...11111010)
 *      = -6  (补码表示)
 *
 *   findComplement(5) = 5 ^ 7
 *      = 101 ^ 111
 *      = 010
 *      = 2
 *
 *   区别: ~num 翻转所有32位, complement 只翻转有效位
 *
 * ================================================================
 * 易错点:
 *
 * 1. 使用 ~num 代替 complement -> 结果完全错误
 * 2. 1 << 31 溢出 int -> 使用 1u << bitLen
 * 3. mask 循环条件 while(mask!=num) -> 应该是 while(mask<num)
 * 4. 忘记处理 num=0 的边界 (题目约束num>=1, 但要注意)
 * ================================================================
 */
