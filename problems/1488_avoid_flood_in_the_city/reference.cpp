/*
 * LeetCode 1488: 避免洪水泛滥 (Avoid Flood in The City)
 *
 * 【题目本质】
 * 贪心调度问题：晴天是有限的"抽干资源"，当某湖泊即将第二次下雨（洪水）时，
 * 必须在两次下雨之间找到一个晴天去抽干它。选择最早的可用晴天（贪心）。
 *
 * 【解法总览】
 * 解法1: 暴力回扫     — O(n²) / O(n) — 直觉做法，面试能说出思路
 * 解法2: 贪心+set     — O(n log n) / O(n) — ⭐ 面试必写
 */

// ============================================================
// 解法1: 暴力回扫 — 遇到洪水风险时线性查找可用晴天
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 从左到右遍历。遇到下雨日：如果这个湖已经满了，就回头在
// [上次下雨日+1, 当前日-1] 区间内线性扫描一个未使用的晴天。
// 瓶颈：每次回头扫描最坏 O(n)。
// ============================================================
class Solution1 {
public:
    vector<int> avoidFlood(vector<int>& rains) {
        int n = rains.size();
        vector<int> ans(n, 1);            // 晴天默认填1（抽空湖无事发生）
        unordered_map<int, int> lastRain; // 湖编号 → 上次下雨日期
        vector<bool> used(n, false);      // 标记晴天是否已被分配

        for (int i = 0; i < n; i++) {
            if (rains[i] > 0) {
                ans[i] = -1; // 下雨日固定输出-1
                int lake = rains[i];
                if (lastRain.count(lake)) {
                    // 湖已满，必须找一个晴天来抽干
                    bool found = false;
                    for (int j = lastRain[lake] + 1; j < i; j++) {
                        if (rains[j] == 0 && !used[j]) {
                            ans[j] = lake;  // 分配这个晴天抽干 lake
                            used[j] = true;
                            found = true;
                            break; // 找最早的一个就行
                        }
                    }
                    if (!found) return {}; // 无解
                }
                lastRain[lake] = i; // 更新（无论是否第一次下雨都要更新）
            }
        }
        return ans;
    }
};

// ============================================================
// 解法2: 贪心 + 有序集合 (set + lower_bound) ⭐ 面试首选
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 解法1的瓶颈：线性查找区间内的可用晴天 → O(n)。
// 优化：把所有未使用的晴天索引放入 set<int>（有序集合），
// 当湖 x 第二次下雨时，用 lower_bound(上次下雨日+1) 在 O(log n) 
// 内找到最早的可用晴天。
//
// 贪心正确性：选最早的晴天 → 把更晚的晴天留给后续可能的需求。
// 如果选了更晚的晴天，可能导致某个中间的需求无晴天可用。
//
// 【模拟过程】 rains = [1, 2, 0, 0, 2, 1]
//
//  Day | rains[i] | 操作                          | lastRain       | sunny   | ans
//  ----+----------+-------------------------------+----------------+---------+------------------
//   0  |    1     | 湖1满, lastRain[1]=0          | {1:0}          | {}      | [-1,_,_,_,_,_]
//   1  |    2     | 湖2满, lastRain[2]=1          | {1:0, 2:1}     | {}      | [-1,-1,_,_,_,_]
//   2  |    0     | 存入sunny                     | {1:0, 2:1}     | {2}     | [-1,-1,1,_,_,_]
//   3  |    0     | 存入sunny                     | {1:0, 2:1}     | {2,3}   | [-1,-1,1,1,_,_]
//   4  |    2     | 湖2已满! lb(1+1=2)→day2       | {1:0, 2:4}     | {3}     | [-1,-1,2,1,_,_]
//      |          | ans[2]=2, erase(2)            |                |         |
//   5  |    1     | 湖1已满! lb(0+1=1)→day3       | {1:5, 2:4}     | {}      | [-1,-1,2,1,-1,-1]
//      |          | ans[3]=1, erase(3)            |                |         |
//
// 最终结果: [-1, -1, 2, 1, -1, -1] ✓
// ============================================================
class Solution2 {
public:
    vector<int> avoidFlood(vector<int>& rains) {
        int n = rains.size();
        vector<int> ans(n, 1);            // 晴天默认填1（抽空湖无影响）
        unordered_map<int, int> lastRain; // 湖编号 → 上次下雨日期
        set<int> sunny;                   // 可用晴天索引的有序集合

        for (int i = 0; i < n; i++) {
            if (rains[i] == 0) {
                // 晴天：先存起来，推迟决策
                // 不在这里决定抽哪个湖，因为不知道未来哪个湖需要
                sunny.insert(i);
            } else {
                ans[i] = -1; // 下雨日固定输出-1
                int lake = rains[i];

                if (lastRain.count(lake)) {
                    // 湖已满，需要在 (lastRain[lake], i) 之间找一个晴天
                    // lower_bound: 找第一个 >= lastRain[lake]+1 的晴天索引
                    auto it = sunny.lower_bound(lastRain[lake] + 1);

                    if (it == sunny.end()) {
                        // 两次下雨之间没有可用晴天 → 必定洪水
                        return {};
                    }
                    // it 指向最早的可用晴天，且一定 < i（因为只insert了已遍历的日子）

                    ans[*it] = lake; // 把这个晴天分配给抽干 lake
                    sunny.erase(it); // 该晴天已使用，从集合中移除
                }

                // 无论是第一次还是第N次下雨，都更新为当前日期
                // 这样下次查找时，区间起点是正确的
                lastRain[lake] = i;
            }
        }
        return ans;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 解法1 暴力回扫  | 解法2 贪心+set    |
// |------------|----------------|-------------------|
// | 时间       | O(n²)          | O(n log n)        |
// | 空间       | O(n)           | O(n)              |
// | 查找晴天   | 线性扫描 O(n)  | lower_bound O(logn)|
// | 面试       | 说明理解       | ⭐ 必须写出        |
//
// 核心优化点：将"在区间内找可用晴天"从线性扫描变成有序集合的二分查找。
//
// ============================================================
// 【易错点】
//
// 1. 晴天默认值填错：
//    ✗ vector<int> ans(n, 0);  — 题目要求晴天输出正整数（湖泊编号）
//    ✓ vector<int> ans(n, 1);  — 填1表示抽空湖（题目说空湖无事发生）
//
// 2. lower_bound 参数错误：
//    ✗ sunny.lower_bound(lastRain[lake]);     — 上次下雨那天不可能是晴天
//    ✓ sunny.lower_bound(lastRain[lake] + 1); — 要找严格在上次下雨之后的晴天
//
// 3. 忘记更新 lastRain[lake]：
//    ✗ 只在第一次下雨时设置 lastRain，第二次下雨后不更新
//    ✓ 每次下雨都 lastRain[lake] = i，否则第三次下雨时查找区间起点错误
//
// 4. 忘记 erase 已使用的晴天：
//    ✗ 只写 ans[*it] = lake，没有 sunny.erase(it)
//    ✓ 必须 erase，否则同一个晴天会被分配给多个湖泊
//
// 5. 想在晴天立刻决定抽谁（前瞻贪心）：
//    ✗ 遇到晴天就去看哪个湖最"危险"然后抽它 — 你不知道未来信息
//    ✓ 推迟决策：晴天先存入set，等到湖泊真正需要时再分配
//
// ============================================================
// 【面试追问】
//
// Q1: "为什么要用 set 而不是 priority_queue？"
// → 堆只能取最值，但我们需要"第一个 >= 某个值的元素"，
//   这是 lower_bound 的语义，堆不支持这种查询。
//   set 底层红黑树天然支持 O(log n) 的 lower_bound。
//
// Q2: "贪心选最早的晴天，能严格证明正确性吗？"
// → 交换论证：假设最优解选了一个更晚的晴天 d2 给湖 x，
//   而 d1 < d2 也在合法区间内。把 d1 分配给湖 x、d2 留着，
//   d2 能覆盖的需求一定包含 d1 不能覆盖的（更晚的需求），
//   所以选 d1 不会更差，交换后仍然合法。
//
// Q3: "如果一天可以抽干多个湖（比如 k 个），怎么改？"
// → 每个晴天在 multiset 中插入 k 次索引，或者用 map<int,int>
//   记录每个晴天剩余可用次数。每次分配时减 1，减到 0 时删除。
//
// Q4: "如果要求输出字典序最小的方案呢？"
// → 当前贪心（选最早晴天）已经倾向于把较早的晴天优先用掉，
//   但字典序最小需要更精细的处理：可能需要优先给编号小的湖
//   分配更早的晴天，需要额外的优先级逻辑。
// ============================================================
