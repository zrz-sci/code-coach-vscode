/*
 * LeetCode 560: 和为 K 的子数组 (Subarray Sum Equals K)
 *
 * 【题目本质】
 * 统计数组中有多少个连续子数组的元素和恰好等于 k。
 * 核心转化：子数组和 = 两个前缀和之差，问题变成"找有多少对前缀和之差等于 k"。
 *
 * 【为什么不能用滑动窗口】
 * 元素可以为负数 → 窗口扩大时和不一定增大 → 单调性被破坏 → 无法判断该扩还是该缩。
 *
 * 【解法总览】
 * 解法1: 暴力枚举        — O(n²) / O(1)  — 枚举所有子数组，递推求和
 * 解法2: 前缀和 + 哈希表  — O(n)  / O(n)  — Two Sum 模式，一次遍历 ⭐ 面试首选
 */

// ============================================================
// 解法1: 暴力枚举 — 枚举所有子数组，利用递推求和
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 最直觉的想法：固定起点 i，从 i 向右逐个累加元素。
// 每累加一个元素，检查当前和是否等于 k。
// 利用 sum(i,j) = sum(i,j-1) + nums[j] 避免重复求和，
// 从 O(n³) 优化到 O(n²)。
//
// 【瓶颈】
// 对每个终点 j，需要遍历所有可能的起点 i → O(n²)。
// 能否对固定的 j，快速知道有多少个 i 满足条件？
//
// 前缀和可视化 (nums = [1, 2, 3], k = 3):
//
//   nums:     1     2     3
//   index:    0     1     2
//
//   i=0: sum = 1 → 1+2=3 ✓ → 3+3=6
//   i=1: sum = 2 → 2+3=5
//   i=2: sum = 3 ✓
//   count = 2
// ============================================================
class Solution1 {
public:
    int subarraySum(vector<int>& nums, int k) {
        int n = nums.size();
        int count = 0;
        
        for (int i = 0; i < n; i++) {
            int sum = 0;
            for (int j = i; j < n; j++) {
                sum += nums[j];
                if (sum == k) {
                    count++;
                    // 不能 break！因为有负数，后面可能再次凑到 k
                    // 例如 nums = [1, -1, 1], k = 1
                    // i=0: sum=1✓ → sum=0 → sum=1✓  (两次!)
                }
            }
        }
        
        return count;
    }
};

// ============================================================
// 解法2: 前缀和 + 哈希表 — Two Sum 思路的推广 ⭐ 面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 从解法1的瓶颈出发：对每个终点 j，我们想快速知道有多少个
// 起点 i 使得 sum(i+1, j) == k。
//
// 定义前缀和: prefix[j] = nums[0] + nums[1] + ... + nums[j-1]
// 则 sum(i+1, j) = prefix[j+1] - prefix[i]
// 要 prefix[j+1] - prefix[i] == k  ⟹  prefix[i] == prefix[j+1] - k
//
// 问题转化为：对每个当前前缀和 currSum，之前出现过多少次 (currSum - k)？
// 这和 Two Sum "找 target - nums[i]" 的模式完全一样！
//
// 工作过程 (nums = [1, 1, 1], k = 2):
//
//   初始 map = {0: 1}  (空前缀和为0，出现1次)
//
//   i=0: currSum = 1
//        查 map[1-2] = map[-1] = 0     → count += 0 → count = 0
//        更新 map = {0:1, 1:1}
//
//   i=1: currSum = 2
//        查 map[2-2] = map[0] = 1      → count += 1 → count = 1
//        更新 map = {0:1, 1:1, 2:1}
//        (对应子数组 [0,1] 即 [1,1]，和为2)
//
//   i=2: currSum = 3
//        查 map[3-2] = map[1] = 1      → count += 1 → count = 2
//        更新 map = {0:1, 1:1, 2:1, 3:1}
//        (对应子数组 [1,2] 即 [1,1]，和为2)
//
//   最终 count = 2 ✓
// ============================================================
class Solution2 {
public:
    int subarraySum(vector<int>& nums, int k) {
        // key: 某个前缀和的值, value: 这个前缀和在之前出现了几次
        unordered_map<int, int> prefixCount;
        
        // 空前缀和为0，出现1次
        // 为什么必须初始化？
        // 例: nums=[3], k=3 → currSum=3, 查 map[3-3]=map[0]
        // 如果 map 中没有 0，就漏掉了 [3] 这个子数组
        prefixCount[0] = 1;
        
        int currSum = 0;
        int count = 0;
        
        for (int num : nums) {
            currSum += num;
            
            // 核心：查找之前有多少个前缀和等于 currSum - k
            // 每找到一个这样的前缀和，就对应一个和为 k 的子数组
            auto it = prefixCount.find(currSum - k);
            if (it != prefixCount.end()) {
                count += it->second;
            }
            
            // 把当前前缀和记入哈希表
            // 为什么必须"先查后加"？
            // 如果先加后查，当 k=0 时 currSum-k = currSum，
            // 会把刚加入的自己也算进去，导致多计数
            prefixCount[currSum]++;
        }
        
        return count;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度     | 解法1 暴力枚举      | 解法2 前缀和+哈希表    |
// |---------|--------------------|-----------------------|
// | 时间     | O(n²)             | O(n)                  |
// | 空间     | O(1)              | O(n) 哈希表            |
// | 核心技巧 | 递推求区间和        | Two Sum 模式查配对     |
// | 难度     | 容易想到           | 需要前缀和转化的洞察    |
// | 面试     | 展示理解           | ⭐ 必须写出            |
//
// 本质区别：暴力是"对每个 j 遍历所有 i"，哈希表是
// "对每个 j 用 O(1) 查到有多少个 i 满足条件"。
//
// ============================================================
// 【易错点】
//
// 1. 忘记 prefixCount[0] = 1
//    ✗ 不初始化 → nums=[5], k=5 时，currSum=5, 查 map[0] 得到 0，返回 0
//    ✓ prefixCount[0] = 1 → 查 map[0] 得到 1，返回 1
//
// 2. 先加后查的顺序错误
//    ✗ prefixCount[currSum]++;  // 先加
//      count += prefixCount[currSum - k];  // 后查
//      当 k=0 时，currSum-k = currSum，刚刚自己加进去的又被查到了
//    ✓ count += prefixCount[currSum - k];  // 先查
//      prefixCount[currSum]++;  // 后加
//
// 3. 误用滑动窗口
//    ✗ 看到"连续子数组"+"和等于 k"就用滑动窗口
//    ✓ 元素有负数时不满足单调性，滑动窗口不适用
//      只有全部非负时才能用滑动窗口
//
// 4. 找到 sum==k 后 break 内层循环 (解法1)
//    ✗ if (sum == k) { count++; break; }
//    ✓ if (sum == k) { count++; }  // 继续循环，后面可能再次等于 k
//      例: nums = [1, -1, 1], k = 1, i=0 → sum 依次为 1✓, 0, 1✓
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 这道题为什么不能用滑动窗口？什么条件下可以？
//     → 元素有负数时窗口单调性被破坏。如果所有元素 >= 0，
//       扩窗口和一定增大，缩窗口和一定减小，此时可以用滑动窗口。
//
// Q2: prefixCount[0] = 1 去掉后，哪些测试用例会错？
//     → 任何"从数组第一个元素开始的子数组和恰好为 k"的用例都会出错。
//       例如 nums=[k], k=k; 或 nums=[1,2], k=3。
//       这些子数组对应 prefix[j] - prefix[0] = prefix[j] - 0 = k。
//
// Q3: 如果要求返回所有和为 k 的子数组的 [起始, 结束] 索引对，怎么改？
//     → 把 map 改成 unordered_map<int, vector<int>>，value 存下标列表。
//       找到配对时，遍历列表中每个起始下标，和当前下标配成区间。
//       时间复杂度退化为 O(n × 平均匹配数)。
//
// Q4: 相关题 974 "和可被 K 整除的子数组" 和本题有什么区别？
//     → 974 的条件是 (prefix[j] - prefix[i]) % k == 0，
//       等价于 prefix[j] % k == prefix[i] % k。
//       所以哈希表的 key 从"前缀和"变成"前缀和 % k"。
//       注意负数取模要修正：key = ((currSum % k) + k) % k。
//
// ============================================================
// 【相关题型】
//
// - 1. Two Sum
//   复用: 完全相同的"边遍历边用哈希表查配对"模式
//   区别: Two Sum 直接对数组元素配对，本题对前缀和配对
//
// - 523. 连续的子数组和 (Continuous Subarray Sum)
//   复用: 前缀和 + 哈希表框架
//   区别: 条件变成"子数组和是 k 的倍数"，map 存 prefix % k
//        另外要求子数组长度 >= 2，所以 map 存的是第一次出现的下标
//
// - 974. 和可被 K 整除的子数组
//   复用: 和 523 一样存 prefix % k，但是要计数而非判断存在
//   区别: 要处理负数取模 ((sum % k) + k) % k
//
// - 325. 和等于 K 的最长子数组长度
//   复用: 前缀和 + 哈希表
//   区别: 不是计数而是求最长 → map 只存每个前缀和第一次出现的下标
// ============================================================
