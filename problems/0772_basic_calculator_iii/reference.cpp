// 【解法对比】
//
// | 特性         | 解法1(递归+栈) | 解法2(双栈)    | 解法3(转后缀)  |
// |-------------|---------------|---------------|---------------|
// | 核心思想     | 递归处理嵌套   | 显式栈管理所有 | 两步分离      |
// | 代码量       | 最少          | 中等          | 最多          |
// | 可读性       | 最好          | 中等          | 逻辑清晰但长  |
// | 面试推荐     | ⭐首选        | ⭐备选        | 加分项        |
//
// 面试建议：先写解法1（最快最清晰），如果面试官追问非递归写法，切换到解法2。
//
// 【易错点】
// 1. op 初始化必须是 '+'：
//    ✗ char op = 0;  → 第一个数字不知道怎么入栈
//    ✓ char op = '+'; → 第一个数字作为 +num 入栈
//
// 2. 双栈法 apply() 操作数顺序：
//    ✗ int a = nums.top(); pop; int b = nums.top(); pop;  // a是右操作数!
//    ✓ int b = nums.top(); pop; int a = nums.top(); pop;  // b是右，a是左
//    对 6-4: 搞反得 4-6=-2，正确应该是 2
//
// 3. 递归法遇到 '(' 时不能用 else if：
//    遇到 '(' → 递归设置 num → 下一个运算符需要处理这个 num
//    如果 '(' 分支和运算符处理分支互斥，num 来不及被处理
//
// 4. 多位数解析和 i 的管理：
//    ✗ for(i=0;i<n;i++) 内部又 while(isdigit) i++ → 多加一次
//    ✓ 要么外层 while 手动控制 i，要么 for 循环内部不再额外 i++
//
// 5. 同优先级运算符必须用 >= 弹出（左结合）：
//    ✗ prec(top) > prec(cur)  → "6-4-2" 变成 6-(4-2)=4，应该是 0
//    ✓ prec(top) >= prec(cur) → 先算 6-4=2，再算 2-2=0
//
// 【面试追问】
// Q1: 这道题和 224、227 的关系是什么？
//     → 224 = +-和括号，227 = +-*/无括号，772 = 两者的合并
//     → 代码层面：772 = 227的栈逻辑 + 224的括号递归
//
// Q2: 如果表达式有一元负号（如 "-2+3" 或 "1+(-2)"），怎么处理？
//     → 在字符串开头或 '(' 后面遇到 '-'，插入一个隐含的 0
//     → 即 "-2+3" 变成 "0-2+3"，"(-2)" 变成 "(0-2)"
//
// Q3: 如果要支持幂运算 ^ （右结合，优先级最高），怎么改？
//     → 双栈法：给 ^ 设最高优先级(如3)，弹出条件改为 > 而非 >=（右结合）
//     → 递归法：在栈处理逻辑中把 ^ 和 */ 类似处理，但要注意右结合性
//
// Q4: 如何验证表达式是否合法？
//     → 括号匹配检查（计数器）、相邻两个运算符检测、空括号 "()" 检测、
//       运算符在开头/结尾的合法性检测
// ============================================================
