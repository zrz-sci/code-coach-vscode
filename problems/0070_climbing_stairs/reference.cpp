/*
 * LeetCode 70: 爬楼梯 (Climbing Stairs)
 * 
 * 【题目本质】
 * 求到达第 n 阶楼梯的不同走法数，每次走 1 或 2 步。
 * 本质就是斐波那契数列：f(n) = f(n-1) + f(n-2)。
 *
 * 【解法总览】
 * 解法1: 暴力递归        — O(2^n) / O(n)    — 最直觉，理解递推关系
 * 解法2: 记忆化搜索      — O(n)   / O(n)    — 消除重复计算
 * 解法3: 递推 DP         — O(n)   / O(n)    — 自底向上填表
 * 解法4: 滚动变量(空间优化) — O(n)  / O(1)    — 面试首选
 * 解法5: 矩阵快速幂       — O(log n) / O(1) — 数学加分项
 */

// ============================================================
// 解法1: 暴力递归 — 决策树穷举
// 时间: O(2^n)  空间: O(n) 递归栈深度
// 
// 【思路】
// 站在第 n 阶往回看：你要么从第 n-1 阶走了 1 步到这里，
// 要么从第 n-2 阶走了 2 步到这里。
// 所以 ways(n) = ways(n-1) + ways(n-2)。
// 
// 递归树 (n=5):
//                      f(5)
//                    /      \
//                f(4)        f(3)     ← f(3) 被重复计算
//               /    \       /    \
//           f(3)    f(2)   f(2)  f(1)
//          /   \   /  \   /  \
//        f(2) f(1) f(1) f(0) f(1) f(0)
//       / \
//    f(1) f(0)
//
// 瓶颈：同一个子问题被指数级地重复计算。
// ============================================================
class Solution1 {
public:
    int climbStairs(int n) {
        if (n <= 1) return 1;
        // 从 n-1 走1步的方案数 + 从 n-2 走2步的方案数
        return climbStairs(n - 1) + climbStairs(n - 2);
    }
};

// ============================================================
// 解法2: 记忆化搜索 — 递归 + memo 数组
// 时间: O(n)  空间: O(n)
// 
// 【思路】
// 解法1的瓶颈是重复计算。加一个 memo 数组记录已计算的结果，
// 每个子问题只算一次，总共 n 个子问题，所以 O(n)。
// 
// 这是"自顶向下"的 DP：从大问题出发，递归拆分，遇到算过的直接返回。
// ============================================================
class Solution2 {
public:
    int climbStairs(int n) {
        vector<int> memo(n + 1, -1);  // -1 表示未计算
        return dfs(n, memo);
    }
    
    int dfs(int n, vector<int>& memo) {
        if (n <= 1) return 1;
        if (memo[n] != -1) return memo[n];  // 查表，避免重复计算
        memo[n] = dfs(n - 1, memo) + dfs(n - 2, memo);
        return memo[n];
    }
};

// ============================================================
// 解法3: 递推 DP — 自底向上填表
// 时间: O(n)  空间: O(n)
// 
// 【思路】
// 把记忆化搜索"翻译"成 for 循环：从 dp[0]、dp[1] 出发，
// 依次算到 dp[n]。省去递归调用栈的开销。
// 
// dp[i] 的含义：到达第 i 阶的方法数
// 转移方程：dp[i] = dp[i-1] + dp[i-2]
// base case：dp[0] = 1, dp[1] = 1
//
// 填表过程 (n=5):
// i:     0  1  2  3  4  5
// dp[i]: 1  1  2  3  5  8
//                 ↑
//                 dp[2] = dp[0] + dp[1] = 1 + 1 = 2
//                    dp[3] = dp[1] + dp[2] = 1 + 2 = 3
//                       dp[4] = dp[2] + dp[3] = 2 + 3 = 5
//                          dp[5] = dp[3] + dp[4] = 3 + 5 = 8
// 填表方向: → 从左到右（因为 dp[i] 依赖 dp[i-1] 和 dp[i-2]）
// ============================================================
class Solution3 {
public:
    int climbStairs(int n) {
        if (n <= 1) return 1;
        vector<int> dp(n + 1);
        dp[0] = 1;  // base case: "空走法"算一种，保证 dp[2] = 2
        dp[1] = 1;  // base case: 到第1阶只有1种走法
        for (int i = 2; i <= n; i++) {
            dp[i] = dp[i - 1] + dp[i - 2];
        }
        return dp[n];
    }
};

// ============================================================
// 解法4: 滚动变量 — DP 空间优化（面试首选）
// 时间: O(n)  空间: O(1)
// 
// 【思路】
// 解法3 中 dp[i] 只依赖 dp[i-1] 和 dp[i-2]，
// 不需要记住整个数组，两个变量交替滚动即可。
// 
// 这是线性 DP 空间优化的标准技巧：
//   当 dp[i] 只依赖固定数量的前驱项时，用滚动变量替代数组。
//
// 滚动过程 (n=5):
//   初始:  prev=1 (dp[0]), curr=1 (dp[1])
//   i=2:   next = 1+1 = 2   → prev=1, curr=2
//   i=3:   next = 1+2 = 3   → prev=2, curr=3
//   i=4:   next = 2+3 = 5   → prev=3, curr=5
//   i=5:   next = 3+5 = 8   → prev=5, curr=8  → 返回 8 ✓
// ============================================================
class Solution4 {
public:
    int climbStairs(int n) {
        if (n <= 1) return 1;
        int prev = 1;  // dp[i-2]
        int curr = 1;  // dp[i-1]
        for (int i = 2; i <= n; i++) {
            int next = prev + curr;  // 先算出 dp[i]
            prev = curr;             // 再移动窗口
            curr = next;
        }
        return curr;
    }
};

// ============================================================
// 解法5: 矩阵快速幂 — O(log n) / O(1)
// 
// 【思路】
// 斐波那契递推可以表示为矩阵乘法：
//
//   | f(n+1) |   | 1  1 |^n   | 1 |
//   | f(n)   | = | 1  0 |   × | 0 |
//
// 等价地，M^n 的 [0][0] 位置就是 f(n+1)，[1][0] 位置就是 f(n)。
// 
// 矩阵快速幂和整数快速幂原理一样：
//   M^10 = M^(1010₂) = M^8 × M^2
// 每次把指数右移一位，基底自乘，总共 O(log n) 次矩阵乘法。
// 每次矩阵乘法是 O(1)（因为是固定的 2×2 矩阵）。
//
// 适用场景：n 极大时（本题 n≤45 没有实际优势，但展示数学功底）
// ============================================================
class Solution5 {
public:
    // 2×2 矩阵类型别名
    using Matrix = vector<vector<long long>>;
    
    Matrix multiply(Matrix& A, Matrix& B) {
        Matrix C(2, vector<long long>(2, 0));
        for (int i = 0; i < 2; i++)
            for (int j = 0; j < 2; j++)
                for (int k = 0; k < 2; k++)
                    C[i][j] += A[i][k] * B[k][j];
        return C;
    }
    
    Matrix matpow(Matrix M, int n) {
        // 单位矩阵（矩阵乘法的"1"）
        Matrix result = {{1, 0}, {0, 1}};
        while (n > 0) {
            if (n & 1) result = multiply(result, M);  // 当前位是1，累乘
            M = multiply(M, M);  // 基底平方
            n >>= 1;
        }
        return result;
    }
    
    int climbStairs(int n) {
        if (n <= 1) return 1;
        // [[1,1],[1,0]]^n 的 [0][0] 就是 f(n+1)
        // 由于我们的 f(1)=1, f(2)=2，对应 fib(2)=1, fib(3)=2
        // 直接算 M^n，取 [0][0] 即为所求
        Matrix M = {{1, 1}, {1, 0}};
        Matrix result = matpow(M, n);
        return (int)result[0][0];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间     | 空间   | 核心思想         |
// |-------------|---------|--------|-----------------|
// | 暴力递归     | O(2^n)  | O(n)   | 决策树穷举       |
// | 记忆化搜索   | O(n)    | O(n)   | 消除重复子问题   |
// | 递推 DP      | O(n)    | O(n)   | 自底向上填表     |
// | 滚动变量     | O(n)    | O(1)   | DP 空间优化      |
// | 矩阵快速幂   | O(logn) | O(1)   | 数学递推矩阵化   |
//
// 面试建议：先口述暴力思路，然后直接写"滚动变量"版本（解法4），
// 代码最短、空间最优、思路清晰。如果面试官追问更快，提矩阵快速幂。
//
// 从暴力到最优的演进关系：
//   暴力递归 → (加 memo) → 记忆化 → (翻译成循环) → 递推 DP → (压缩空间) → 滚动变量
//   这条演进路线适用于所有线性 DP 题目。
//
// ============================================================
// 【易错点】
//
// 1. dp[0] 初始化为 0 而不是 1:
//    ✗ dp[0] = 0 → dp[2] = dp[1]+dp[0] = 1+0 = 1 (正确答案是2)
//    ✓ dp[0] = 1 → dp[2] = dp[1]+dp[0] = 1+1 = 2 ✓
//
// 2. 滚动变量更新顺序搞反:
//    ✗ curr = prev + curr; prev = curr;  
//      (prev 被赋了新的 curr，丢失了旧的 curr 信息)
//    ✓ int next = prev + curr; prev = curr; curr = next;
//      (先用临时变量保存，再移动)
//
// 3. 边界条件 n=1 时循环不执行:
//    如果没有 if (n <= 1) return 1; 的提前返回，
//    要确保 curr 的初始值就是正确答案。
//
// 4. 暴力递归忘记加 memo 导致 TLE:
//    n=45 时 O(2^45) ≈ 3.5万亿次，一定会超时。
//
// ============================================================
// 【面试追问（递进链）】
//
// Q1: 为什么 dp[i] = dp[i-1] + dp[i-2]？
//   → 到第 i 阶只能从第 i-1 阶(走1步)或第 i-2 阶(走2步)到达，
//     两种来源互斥且完备，所以方案数相加。
//
// Q2: 能否用 O(1) 空间？
//   → 可以，dp[i] 只依赖前两项，用 prev 和 curr 两个变量滚动即可。
//
// Q3: 能否比 O(n) 更快？
//   → 矩阵快速幂 O(log n)。将递推关系写成矩阵形式 [[1,1],[1,0]]^n。
//
// Q4: 如果每次可以爬 1、2 或 3 步呢？
//   → dp[i] = dp[i-1] + dp[i-2] + dp[i-3]，滚动变量从 2 个变 3 个。
//
// Q5: 如果步数从任意数组 steps[] 中选？
//   → 变成完全背包：for i in 0..n: for s in steps: dp[i] += dp[i-s]。
//     本题是 steps = {1, 2} 的特例。
// ============================================================
