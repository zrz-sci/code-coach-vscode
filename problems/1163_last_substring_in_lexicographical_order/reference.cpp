/*
 * LeetCode 1163: Last Substring in Lexicographical Order
 * 
 * 【题目本质】
 * 在所有子串中找字典序最大的那个。
 * 关键洞察：答案一定是某个后缀（从位置 i 到字符串末尾），
 * 因为任何子串扩展到末尾字典序只会不减。
 * 问题转化为：在 n 个后缀中找字典序最大的，要求 O(n) 时间。
 *
 * 【解法总览】
 * 解法1: 暴力比较     — O(n²) / O(1) — 最直觉，TLE
 * 解法2: 双指针跳跃   — O(n)  / O(1) — 面试首选 ⭐
 * 解法3: 后缀数组     — O(n log n)~O(n) / O(n) — 加分了解
 */

// ============================================================
// 解法1: 暴力比较 — 枚举所有后缀起始位置，逐字符比较
// 时间: O(n²)  空间: O(1)  (不含输出)
// 
// 【思路】
// 答案是某个后缀 s[i..]，枚举 i=0..n-1，维护当前最优 best。
// 每次将 s[i..] 与 s[best..] 逐字符比较，更优则更新。
// 
// 瓶颈：对于 "aaaa...ab" 这类输入，每次比较走 O(n) 步
// 才能分出胜负，总计 O(n²)。n=4×10⁵ 会 TLE。
// ============================================================
class Solution1 {
public:
    string lastSubstring(string s) {
        int n = s.size();
        int best = 0;
        for (int i = 1; i < n; i++) {
            // 逐字符比较 s[i..] 和 s[best..]
            int j = 0;
            while (i + j < n && s[i + j] == s[best + j]) {
                j++;
            }
            if (i + j < n && s[i + j] > s[best + j]) {
                best = i;
            }
        }
        return s.substr(best);
    }
};

// ============================================================
// 解法2: 双指针跳跃 — O(n) / O(1) ⭐ 面试首选
//
// 【思路】
// 解法1每次只淘汰1个候选。能否利用"已经比了k个字符都相等"
// 这个信息，一次性淘汰多个候选？
//
// 维护两个候选 i, j 和已匹配长度 k:
//   - s[i+k] == s[j+k]: 还没分胜负, k++
//   - s[i+k] <  s[j+k]: i 输了, i 跳到 i+k+1
//   - s[i+k] >  s[j+k]: j 输了, j 跳到 j+k+1
//
// 【为什么跳 k+1 步安全？】
// 若 s[i..i+k-1] == s[j..j+k-1] 且 s[i+k] < s[j+k]:
//   对任意 0 ≤ t ≤ k, suffix(i+t) < suffix(j+t)
//   因为它们前 k-t 个字符相同，第 k-t+1 个字符处 i 方小
//   所以 i, i+1, ..., i+k 全部被淘汰
//
// 【复杂度证明】
// 每次循环 j+k 至少增1 (要么k++, 要么j跳到j+k+1)
// j+k 从1增到n-1, 所以总循环次数 O(n)
//
// 示例: s = "abab"
//
//   i=0, j=1, k=0: s[0]='a' < s[1]='b' → i=1, i==j → i=2, k=0
//   i=2, j=1, k=0: s[2]='a' < s[1]='b' → i=3, k=0
//   i=3, j=1, k=0: s[3]='b' == s[1]='b' → k=1
//   i=3, j=1, k=1: j+k=2 < n=4, s[4]越界? 不,i+k=4>=n
//     实际循环条件 j+k<n → 1+1=2<4 ✓, 但还要看 i+k: 3+1=4>=n
//     此时 suffix(j) 更长(有更多字符), 但我们还需检查...
//     实际上 j+k=2<4: s[i+k]=s[4]越界
//     → 循环条件为 j+k<n, 我们需要 i+k<n 也成立
//     由于 i<j 不一定成立(此时i=3>j=1), 需要额外判断
//     → 但此时 i+k >= n, 意味着 j 方后缀有剩余字符, j 更长
//     → 但 i=3 < j+k=2 不对... 让我们重新 trace:
//
//   更准确的trace:
//   初始 i=0, j=1, k=0
//   Round1: s[0]='a' < s[1]='b' → i=0+0+1=1, i==j → i=2, k=0
//   Round2: s[2]='a' < s[1]='b' → i=2+0+1=3, k=0  
//   Round3: s[3]='b' == s[1]='b' → k=1
//   Round4: j+k=1+1=2<4: s[3+1]=s[4] 越界... 但 i+k=4 不 <n
//     代码中循环条件只检查 j+k<n, 如果 i+k>=n 呢?
//     → 此时 suffix(i) 比较短, suffix(j) 到 i+k-1 处相同但更长
//     → suffix(j) > suffix(i), 但... j=1 对应 "bab", i=3 对应 "b"
//     → "bab" > "b" ✓, 所以 j 赢
//     → 但代码返回的是 s.substr(i)... 
//     → 实际上当 i+k >= n 时, suffix(i) 是 suffix(j) 的前缀, 
//       suffix(j) 更长所以 suffix(j) 更大
//     → 我们需要让 j 赢: s[i+k] 视为 -∞ (越界=更小)
//     → 所以应该 i = i+k+1 (淘汰 i)
//     → i = 3+1+1 = 5 >= n, 循环结束
//     → 但答案应该是 min(i,j)?  不, 应该是 j=1
//     
//  重新分析终止条件:
//  当 j+k < n 但 i+k >= n 时, suffix(i) 是 suffix(j) 的前缀
//  且 suffix(j) 更长, 所以 suffix(j) 更大
//  此时应该淘汰 i, 即 i = i+k+1 (已>=n)
//  循环结束, 答案是 min(i, j) 中仍在有效范围内的那个 = j
//
//  → 修正: 答案应该是 min(i, j), 因为更小的起始位置
//    对应更长的后缀
//  → 不对, 我们要的是字典序最大的后缀, 不是最长的
//  
//  标准做法: 循环条件 j+k<n, 结束后返回 s.substr(min(i,j))
//  因为循环保证 i 和 j 中至少有一个是全局最优的候选
//  当一方越界时, 另一方就是答案; 取 min(i,j) 更安全
//
// ============================================================
class Solution2 {
public:
    string lastSubstring(string s) {
        int n = s.size();
        int i = 0, j = 1, k = 0;
        while (j + k < n) {
            if (i + k >= n) {
                // suffix(i) 是 suffix(j) 的前缀, suffix(j) 更大
                // 淘汰 i
                i = j;
                j = i + 1;
                k = 0;
            } else if (s[i + k] == s[j + k]) {
                k++;
            } else if (s[i + k] < s[j + k]) {
                // i 方输了, 跳过 i..i+k 这些位置
                i = i + k + 1;
                if (i == j) i++;  // 两个候选不能重合
                k = 0;
            } else {
                // j 方输了, 跳过 j..j+k 这些位置
                j = j + k + 1;
                if (i == j) j++;  // 两个候选不能重合
                k = 0;
            }
        }
        // 答案是位置较小的那个候选 (它对应更长/更大的后缀)
        return s.substr(min(i, j));
    }
};

// ============================================================
// 解法2 (精简版): 利用 i < j 的不变量简化代码
// 
// 【思路】
// 通过保持 i < j 的不变量, 简化终止条件的处理。
// 当 i+k >= n 时, 因为 i < j, j+k 必然也 >= n, 循环自然结束。
// 但实际上 i < j 不一定成立... 需要确保:
// 
// 更标准的写法: 始终保证 i < j 不变量
// 如果跳跃后 i >= j, 调整之
// ============================================================
class Solution {
public:
    string lastSubstring(string s) {
        int n = s.size();
        int i = 0, j = 1, k = 0;
        // 不变量: i != j, 且 i 和 j 都是候选
        while (j + k < n) {
            if (s[i + k] == s[j + k]) {
                // 前 k+1 个字符都相同, 继续匹配
                k++;
            } else if (s[i + k] < s[j + k]) {
                // suffix(i) < suffix(j), 淘汰 i 方 k+1 个位置
                // i+1..i+k 也都不如 j+1..j+k
                i = i + k + 1;
                if (i == j) i++; // 不能和 j 重合
                k = 0;
            } else {
                // suffix(j) < suffix(i), 淘汰 j 方 k+1 个位置
                j = j + k + 1;
                if (i == j) j++; // 不能和 i 重合
                k = 0;
            }
        }
        // 当 j+k >= n 时:
        //   如果是因为 k 一直增长到 j+k>=n: 说明 suffix(j) 是 suffix(i) 的子串
        //   (因为 s[i..i+k-1] == s[j..j+k-1] 且 j 方到头了)
        //   suffix(i) 更长或相同前缀 → suffix(i) >= suffix(j)
        //   但如果 i > j, 那 suffix(j) 包含 suffix(i), suffix(j) 更大
        //   所以答案是 min(i, j) — 更小的起始位置对应更长后缀
        return s.substr(min(i, j));
    }
};

// ============================================================
// 【解法对比】
// 
// 暴力法: 思路简单, 但最坏 O(n²), 不能通过本题
// 双指针: O(n) 时间 O(1) 空间, 利用已比较信息批量淘汰候选
//         核心: 两个后缀前k个字符相同时, 输的一方连同前k个位移都淘汰
// 后缀数组: 更通用(能处理第K大后缀等问题), 但实现复杂
//
// 面试推荐: 解法2 双指针, 代码简洁且复杂度最优
//
// ============================================================
// 【易错点】
//
// 1. ✗ 跳跃后忘记检查 i==j:
//      i = i + k + 1;   // 如果恰好等于 j, 两个候选重合
//      k = 0;            // 后续 s[i+k] == s[j+k] 永远成立, k无限增长
//    ✓ 必须加 if (i == j) i++; 保证不重合
//
// 2. ✗ 循环条件写 while (j < n) 而不是 while (j + k < n):
//      当 k > 0 时访问 s[j+k] 会越界
//    ✓ 必须用 j + k < n 保护访问
//
// 3. ✗ 返回 s.substr(i) 而不是 s.substr(min(i, j)):
//      当循环因 j+k>=n 终止时, 如果 i > j, 则 j 才是答案
//      (j对应的后缀更长, 两者前缀相同, 更长的字典序更大)
//    ✓ 返回 s.substr(min(i, j))
//
// 4. ✗ 跳跃步长写成 i + k 而不是 i + k + 1:
//      位置 i+k 本身也需要被淘汰(它对应的是 j+k, j+k 更优)
//    ✓ i = i + k + 1
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么答案一定是后缀?
// → 子串 s[i..j] 扩展到 s[i..n-1], 字典序不减。
//   如果多出的字符 s[j+1] 存在, 那就更大; 即使没有(j==n-1), 也不变。
//   所以最大子串一定是后缀。
//
// Q2: 跳跃为什么正确? 被跳过的位置真的不可能是答案?
// → s[i..i+k-1]==s[j..j+k-1], s[i+k]<s[j+k]
//   对任意 0≤t≤k: suffix(i+t) 和 suffix(j+t) 前 k-t 个字符相同,
//   第 k-t+1 个字符处 i方<j方, 所以 suffix(i+t)<suffix(j+t)。
//   每个被跳过的位置都有严格更优的对手。
//
// Q3: 这个技巧还能用在哪?
// → 最小表示法: 找循环字符串的字典序最小旋转。
//   几乎完全相同的双指针框架, 区别是:
//   (1) 比较时取模 n; (2) 找最小而非最大(不等时判断方向相反)
//
// Q4: 如果要找第K大的后缀呢?
// → 需要后缀数组。双指针只能找最大, 无法扩展到第K大。
//   后缀数组 O(n log n) 构建, 然后直接取 sa[n-K]。
// ============================================================
