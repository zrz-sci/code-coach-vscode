/*
 * LeetCode 696: Count Binary Substrings (计数二进制子串)
 *
 * 【题目本质】
 * 在二进制字符串中，找出满足以下条件的子串数量：
 * (1) 0 和 1 的数量相等
 * (2) 所有 0 连续且所有 1 连续
 * 核心洞察：按连续字符分组后，相邻两组贡献 min(prev, curr) 个合法子串。
 *
 * 【解法总览】
 * 解法1: 分组计数(滚动变量) — O(n) / O(1) — 面试首选
 * 解法2: 分组计数(显式数组) — O(n) / O(n) — 辅助理解
 */

// ============================================================
// 解法1: 分组计数（滚动变量） — 面试首选 ⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 按连续相同字符分组，相邻两组能构成的合法子串数 = min(前一组长度, 当前组长度)。
// 用 prev 和 curr 两个变量滚动，不需要存分组数组。
//
// 为什么 min(prev, curr)?
//   从交界处向两边扩展：prev 组提供一种字符，curr 组提供另一种。
//   合法子串要求两边等长，最多取到较短组的长度。
//   例: prev=3("000"), curr=2("11") → 合法子串: "01", "0011" → 2个 = min(3,2)
//
// 分组可视化:
//   s = "00110011"
//   "00" | "11" | "00" | "11"
//    2      2      2      2
//   贡献: min(2,2) + min(2,2) + min(2,2) = 6 ✓
//
// 滚动过程:
//   s = "00110011", prev=0, curr=1, ans=0
//   i=1: '0'=='0' → curr=2
//   i=2: '1'!='0' → ans+=min(0,2)=0, prev=2, curr=1
//   i=3: '1'=='1' → curr=2
//   i=4: '0'!='1' → ans+=min(2,2)=2, prev=2, curr=1
//   i=5: '0'=='0' → curr=2
//   i=6: '1'!='0' → ans+=min(2,2)=2, prev=2, curr=1
//   i=7: '1'=='1' → curr=2
//   结束: ans+=min(2,2)=2 → 总计 0+2+2+2=6 ✓
// ============================================================
class Solution1 {
public:
    int countBinarySubstrings(string s) {
        int ans = 0;
        int prev = 0;  // 上一组的长度（初始为0：第一组之前没有"上一组"）
        int curr = 1;  // 当前组的长度（s[0]已经是当前组的第一个字符）

        for (int i = 1; i < (int)s.size(); i++) {
            if (s[i] == s[i - 1]) {
                // 同一组，当前组长度+1
                curr++;
            } else {
                // 字符切换！相邻两组贡献 min(prev, curr) 个合法子串
                ans += min(prev, curr);
                prev = curr;  // 当前组变成"上一组"
                curr = 1;     // 新的一组从长度1开始
            }
        }

        // ⚠️ 关键：循环结束后，最后两组还没被计入！
        // 此时 prev = 倒数第二组长度，curr = 最后一组长度
        ans += min(prev, curr);

        return ans;
    }
};

// ============================================================
// 解法2: 分组计数（显式数组） — 辅助理解
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 两步走：
//   Step 1: 遍历字符串，建立分组长度数组
//   Step 2: 遍历分组数组，相邻两组取 min 求和
//
// 理解这个解法后，解法1就是它的空间优化版:
//   用 prev/curr 代替了整个 groups 数组
//
// 示例: s = "00110011"
//   Step 1: groups = [2, 2, 2, 2]
//   Step 2: min(2,2) + min(2,2) + min(2,2) = 6 ✓
//
// 面试策略：先讲解法2的思路让面试官理解，再优化到解法1。
// ============================================================
class Solution2 {
public:
    int countBinarySubstrings(string s) {
        // Step 1: 建分组长度数组
        vector<int> groups;
        int count = 1;
        for (int i = 1; i < (int)s.size(); i++) {
            if (s[i] == s[i - 1]) {
                count++;
            } else {
                groups.push_back(count);
                count = 1;
            }
        }
        groups.push_back(count);  // 别忘了最后一组

        // Step 2: 相邻两组取 min 累加
        int ans = 0;
        for (int i = 1; i < (int)groups.size(); i++) {
            ans += min(groups[i - 1], groups[i]);
        }
        return ans;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 时间 | 空间 | 适用场景                     |
// |------------|------|------|----------------------------|
// | 滚动变量    | O(n) | O(1) | 最终答案，空间最优            |
// | 显式数组    | O(n) | O(n) | 理解思路用，更直观            |
//
// ============================================================
// 【为什么 min(prev, curr) 是对的？— 数学证明】
//
// 设相邻两组分别有 a 个字符x 和 b 个字符y (x≠y)。
// 合法子串形如: x...xy...y 或 y...yx...x
// 长度必须是偶数 2k，其中 k 个x + k 个y。
// k 的范围: 1 ≤ k ≤ min(a, b)
// 所以合法子串数 = min(a, b)
//
// ============================================================
// 【易错点】
//
// 1. 循环结束后忘记最后一次累加:
//    ✗ 只在 s[i]!=s[i-1] 时加 min(prev,curr) → 最后两组漏掉
//    ✓ 循环外补 ans += min(prev, curr)
//
// 2. prev 初始值设错:
//    ✗ prev=1 → 第一次切换时多加了 min(1, curr) 而不是 0
//    ✓ prev=0 → 第一组之前没有上一组，min(0, x) = 0，不影响
//
// 3. 分组数组忘记最后一组:
//    ✗ 循环结束后没有 groups.push_back(count)
//    ✓ 循环外补上最后一组
//
// 4. 误以为需要枚举子串:
//    ✗ 双重循环 O(n^2) 枚举
//    ✓ 分组后一次遍历 O(n)
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么 min(prev, curr) 就是贡献的子串数？
//     合法子串要求等量的0和1，从交界处向两边扩展，
//     最多取到较短组的长度。长度1到min的各一个。
//
// Q2: 这个思路能推广到非二进制字符串吗？
//     可以。只要定义"合法子串"为相邻两种不同字符各自连续且等量，
//     同样按连续字符分组，相邻组取min累加。
