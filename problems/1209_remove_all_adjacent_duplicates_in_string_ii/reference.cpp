/*
 * LeetCode 1209: 删除字符串中的所有相邻重复项 II
 * 
 * 【题目本质】
 * 持续消除连续 k 个相同字符，消除后两侧拼接可能产生新的可消除段。
 * 核心问题：如何高效追踪"每个字符的连续计数"并处理消除后的拼接。
 *
 * 【解法总览】
 * 解法1: 暴力模拟    — O(n²/k) / O(n) — 最直觉，反复扫描删除
 * 解法2: 栈+计数     — O(n)   / O(n) — 面试首选，一次遍历
 * 解法3: 双指针模拟栈 — O(n)   / O(n) — 进阶技巧，原地操作
 */

// ============================================================
// 解法1: 暴力模拟 — 反复扫描，每轮删除所有 k 连续段
// 时间: O(n²/k)  空间: O(n)
// 
// 【思路】
// 最直觉的想法：一轮一轮扫描字符串，每轮找出所有连续 k 个相同字符
// 并删除它们。删除后字符串变短，两侧拼接可能产生新的连续段，
// 所以需要下一轮继续扫描，直到某一轮没有任何删除。
//
// 模拟示例 s = "deeedbbcccbdaa", k = 3:
//   轮1: "deeedbbcccbdaa" → 删 "eee" 和 "ccc" → "ddbbbdaa"
//   轮2: "ddbbbdaa" → 删 "bbb" → "dddaa"
//   轮3: "dddaa" → 删 "ddd" → "aa"
//   轮4: "aa" → 无可删 → 结束
//
// 瓶颈：最坏 O(n/k) 轮，每轮 O(n)，总 O(n²/k)
// ============================================================
class Solution1 {
public:
    string removeDuplicates(string s, int k) {
        bool changed = true;
        while (changed) {
            changed = false;
            string next;
            int i = 0;
            while (i < (int)s.size()) {
                int j = i;
                while (j < (int)s.size() && s[j] == s[i]) j++;
                int count = j - i;
                if (count >= k) {
                    // 删掉 k 的整数倍，保留 count % k 个
                    int remain = count % k;
                    next.append(remain, s[i]);
                    changed = true; // 本轮有删除，需要下一轮
                } else {
                    next.append(count, s[i]);
                }
                i = j;
            }
            s = next;
        }
        return s;
    }
};

// ============================================================
// 解法2: 栈 + 计数 — 一次遍历，面试首选 ⭐
// 时间: O(n)  空间: O(n)
// 
// 【思路】
// 暴力解的瓶颈：删除后拼接产生新的可删段，需要重新扫描。
// 
// 观察：删除操作很像"括号匹配" —— 新字符需要和"之前留下的字符"
// 配对。栈天然支持这种"最近匹配"模式。
// 
// 关键设计：栈里存 (字符, 连续计数) 对，而不是每个字符单独入栈。
// - 新字符和栈顶相同 → 计数+1
// - 新字符和栈顶不同 → 压入新元素(字符, 1)
// - 计数达到 k → 弹出（等价于删除 k 个连续相同字符）
// - 弹出后栈顶自动变成之前的字符段 → 完美处理拼接！
//
// 模拟 s = "deeedbbcccbdaa", k = 3:
//
//   字符 | 栈状态 (底→顶)
//   -----+-----------------------------------
//    d   | [(d,1)]
//    e   | [(d,1), (e,1)]
//    e   | [(d,1), (e,2)]
//    e   | [(d,1), (e,3)] → 弹出! → [(d,1)]
//    d   | [(d,2)]              ← 拼接后计数自然延续
//    b   | [(d,2), (b,1)]
//    b   | [(d,2), (b,2)]
//    c   | [(d,2), (b,2), (c,1)]
//    c   | [(d,2), (b,2), (c,2)]
//    c   | [(d,2), (b,2), (c,3)] → 弹出! → [(d,2), (b,2)]
//    b   | [(d,2), (b,3)] → 弹出! → [(d,2)]
//    d   | [(d,3)] → 弹出! → []
//    a   | [(a,1)]
//    a   | [(a,2)]
//
//   结果: "aa" ✓
// ============================================================
class Solution2 {
public:
    string removeDuplicates(string s, int k) {
        // 栈存 (字符, 连续出现次数)
        // 用 vector 而非 stack，方便最后遍历构建结果
        vector<pair<char, int>> stk;
        
        for (char c : s) {
            if (!stk.empty() && stk.back().first == c) {
                // 和栈顶字符相同 → 计数累加
                stk.back().second++;
                if (stk.back().second == k) {
                    // 达到 k 个 → 弹出，等价于删除这 k 个字符
                    // 弹出后栈顶变成之前的字符，自动处理拼接
                    stk.pop_back();
                }
            } else {
                // 和栈顶字符不同（或栈为空）→ 压入新元素
                stk.push_back({c, 1});
            }
        }
        
        // 从栈内容构建结果字符串
        // 注意：每个栈元素可能代表多个字符，要按计数展开
        string result;
        for (auto& [ch, cnt] : stk) {
            result.append(cnt, ch); // 追加 cnt 个 ch
        }
        return result;
    }
};

// ============================================================
// 解法3: 双指针（原地模拟栈）— 用字符串本身当栈
// 时间: O(n)  空间: O(n)（count 数组）
// 
// 【思路】
// 解法2用了额外的 vector<pair> 作为栈，最后还需要从栈构建结果。
// 
// 优化思路：直接在原字符串上操作，用慢指针 j 表示"栈顶"，
// 配合一个 count 数组记录每个位置的连续计数。
// 
// s[0..j-1] 就是当前的"栈内容"：
// - 每次把 s[i] 写到 s[j]（相当于压栈）
// - 如果 s[j] == s[j-1]，count[j] = count[j-1] + 1（延续计数）
// - 否则 count[j] = 1（新字符段开始）
// - 如果 count[j] == k，j -= k（弹出 k 个字符）
// 
// 最后 s[0..j-1] 就是结果，无需额外构建。
// ============================================================
class Solution3 {
public:
    string removeDuplicates(string s, int k) {
        int n = s.size();
        vector<int> count(n, 0); // count[j]: 位置 j 处字符的连续计数
        
        int j = 0; // 慢指针 = "栈顶"，指向下一个要写入的位置
        for (int i = 0; i < n; i++) {
            s[j] = s[i]; // 把当前字符写到"栈顶"
            
            // 计算当前位置的连续计数
            if (j > 0 && s[j] == s[j - 1]) {
                count[j] = count[j - 1] + 1; // 和前一个相同 → 延续计数
            } else {
                count[j] = 1; // 新字符段 → 计数重置
            }
            
            // 达到 k 个 → 弹出（栈顶后退 k 步）
            if (count[j] == k) {
                j -= k;
            }
            j++; // 移动到下一个写入位置
        }
        
        return s.substr(0, j); // s[0..j-1] 就是最终结果
    }
};

// ============================================================
// 【解法对比】
// 
// | 解法 | 核心思想 | 时间 | 空间 | 特点 |
// |------|---------|------|------|------|
// | 暴力 | 多轮扫描删除 | O(n²/k) | O(n) | 直觉但慢 |
// | 栈+计数 | 一次遍历，栈自动处理拼接 | O(n) | O(n) | 清晰直观 ⭐ |
// | 双指针 | 原地模拟栈 | O(n) | O(n) | 技巧性强 |
//
// 面试首选解法2：思路清晰、代码简洁、不容易出错。
// 解法3作为面试官追问"能否减少额外结构"时的展示。
//
// 【和 1047 题（k=2）的关系】
// 1047 题栈里只存 char，栈顶相同就 pop（隐含 k=2）。
// 本题改动：栈元素从 char 变成 pair<char,int>，pop 条件从
// "栈顶相同" 变成 "计数==k"。仅此两处区别。
//
// 【易错点】
// 1. 栈里只存字符不存计数：
//    ✗ stack<char> stk; 然后想办法数连续个数 → 每次要 pop 再 push 回去，极易出错
//    ✓ vector<pair<char,int>> stk; 字符和计数绑定
//
// 2. 构建结果时只取一个字符：
//    ✗ for (auto& p : stk) result += p.first;
//       → 如果栈里 (a,2) 只输出一个 'a'，丢失了字符
//    ✓ for (auto& [ch, cnt] : stk) result.append(cnt, ch);
//       → 按计数展开，(a,2) 输出 "aa"
//
// 3. 解法3中 j>0 的边界检查：
//    ✗ if (s[j] == s[j-1]) → 当 j==0 时 s[-1] 越界
//    ✓ if (j > 0 && s[j] == s[j-1]) → 先检查 j>0
//
// 4. 解法3中弹出后忘记 j++：
//    count[j]==k 时执行 j-=k，但循环末尾的 j++ 仍然要执行。
//    j-=k 后 j 指向的是被弹出区域的起始位置，j++ 让它指向
//    下一个可写入位置。这两步不能合并也不能跳过。
//
// 【面试追问】
// Q1(基础理解): "为什么栈能一次遍历就处理完？暴力法不是需要多轮吗？"
//   → 栈弹出后栈顶自动变成之前的元素，新字符继续和它比较，
//     等价于"删除后拼接"的效果，不需要重新扫描。
//
// Q2(优化): "栈解法能否优化空间？比如不用 pair？"
//   → 可以用两个栈分别存字符和计数，但没有本质区别。
//     也可以用解法3的双指针+count数组方式，避免 pair 的开销，
//     但空间复杂度仍是 O(n)。
//
// Q3(变体): "如果要求在线处理（字符一个个到来，每次返回当前结果）怎么办？"
//   → 栈解法天然支持在线处理！每来一个字符就执行一次入栈/弹出逻辑，
//     然后从栈内容构建当前结果。这也是栈解法优于暴力法的另一个优势。
//
// Q4(扩展): "如果不同位置可以有不同的 k 值（即每种字符有自己的消除阈值）？"
//   → 栈的框架不变，只是弹出条件从 count==k 变成
//     count==threshold[ch]，其中 threshold 是每种字符的阈值映射。
// ============================================================
