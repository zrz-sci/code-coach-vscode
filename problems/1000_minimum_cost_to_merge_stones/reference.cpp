/*
 * LeetCode 1000: 合并石头的最低成本 (Minimum Cost to Merge Stones)
 *
 * 【题目本质】
 * n 堆石头排成一行，每次合并连续 k 堆为一堆，代价为这 k 堆总数。
 * 求合并为一堆的最小总代价。区间 DP 经典题。
 *
 * 【解法总览】
 * 解法1: 二维区间 DP  — O(n^3/k) / O(n^2)    — 面试首选 ⭐
 * 解法2: 三维区间 DP  — O(n^3*k) / O(n^2*k)  — 更直观
 */

// ============================================================
// 解法1: 二维区间 DP — 面试首选 ⭐
// 时间: O(n^3 / (k-1))  空间: O(n^2)
//
// 【思路】
// 为什么是区间 DP？
// 1. 每次合并连续 k 堆 → 区间操作
// 2. 最终合并整个 [0, n-1] → 大区间由小区间构成
// 3. 经典区间 DP 结构: 枚举分割点
//
// 可行性条件: (n-1) % (k-1) == 0
//   每次合并减少 k-1 堆，从 n 堆到 1 堆需减少 n-1 堆
//   (n-1) 必须是 (k-1) 的倍数
//
// DP 定义:
//   dp[i][j] = 将 stones[i..j] 尽可能合并的最小代价
//   当 (j-i) % (k-1) == 0 时，[i..j] 恰好能合并为 1 堆
//
// 转移:
//   dp[i][j] = min { dp[i][m] + dp[m+1][j] }  (m 以 k-1 为步长)
//   如果 (j-i) % (k-1) == 0:
//     dp[i][j] += sum(i, j)   // 最后一步合并的代价
//
// 为什么 m 以 k-1 为步长？
//   左半 [i..m] 要能合并为 1 堆 → (m-i) % (k-1) == 0
//   m = i, i+(k-1), i+2(k-1), ...
//
// 示例: stones = [3,5,1,2,6], k = 3
//   n=5, (5-1)%(3-1) = 4%2 = 0 ✓ 可行
//   前缀和: [0, 3, 8, 9, 11, 17]
//
//   len=3 (最小可合并长度):
//     dp[0][2] = dp[0][0]+dp[1][2] = 0+0，再加 sum(0,2)=9 → 9
//                (m只能=0, 步长k-1=2, 下一个m=2≥j)
//     dp[1][3] = dp[1][1]+dp[2][3] = 0+0 + sum(1,3)=8 → 8
//     dp[2][4] = dp[2][2]+dp[3][4] = 0+0 + sum(2,4)=9 → 9
//
//   len=4 ((3)%2=1 ≠ 0, 不加sum):
//     dp[0][3]: m=0 → dp[0][0]+dp[1][3] = 0+8 = 8
//               m=2 → dp[0][2]+dp[3][3] = 9+0 = 9
//               → dp[0][3] = 8
//     dp[1][4]: m=1 → dp[1][1]+dp[2][4] = 0+9 = 9
//               m=3 → dp[1][3]+dp[4][4] = 8+0 = 8
//               → dp[1][4] = 8
//
//   len=5 ((4)%2=0, 加sum):
//     dp[0][4]: m=0 → dp[0][0]+dp[1][4] = 0+8 = 8
//               m=2 → dp[0][2]+dp[3][4] = 9+0 = 9
//               → min = 8, 再加 sum(0,4)=17 → dp[0][4] = 25
//
//   答案: dp[0][4] = 25 ✓
// ============================================================
class Solution1 {
public:
    int mergeStones(vector<int>& stones, int k) {
        int n = stones.size();

        // 可行性判断
        if ((n - 1) % (k - 1) != 0) return -1;

        // 前缀和，用于 O(1) 查询区间和
        vector<int> prefix(n + 1, 0);
        for (int i = 0; i < n; i++) {
            prefix[i + 1] = prefix[i] + stones[i];
        }

        // dp[i][j] = 将 stones[i..j] 尽可能合并的最小代价
        // 初始化为 0（单堆不需要合并，也是后续累加的基础）
        vector<vector<int>> dp(n, vector<int>(n, 0));

        // 从长度 k 开始（长度 < k 的区间无法执行合并操作）
        for (int len = k; len <= n; len++) {
            for (int i = 0; i + len - 1 < n; i++) {
                int j = i + len - 1;
                dp[i][j] = INT_MAX;

                // 枚举分割点 m
                // m 以 k-1 为步长，保证 [i..m] 能合并为 1 堆
                for (int m = i; m < j; m += k - 1) {
                    dp[i][j] = min(dp[i][j],
                                   dp[i][m] + dp[m + 1][j]);
                }

                // 如果 [i..j] 恰好能合并为 1 堆
                // 加上最后一次合并的代价 = 区间总和
                if ((j - i) % (k - 1) == 0) {
                    dp[i][j] += prefix[j + 1] - prefix[i];
                }
            }
        }

        return dp[0][n - 1];
    }
};

// ============================================================
// 解法2: 三维区间 DP — 更直观的定义
// 时间: O(n^3 * k)  空间: O(n^2 * k)
//
// 【思路】
// dp[i][j][p] = 将 stones[i..j] 合并为恰好 p 堆的最小代价
//
// 转移:
//   dp[i][j][p] = min { dp[i][m][1] + dp[m+1][j][p-1] }
//   即把 [i..m] 合并为 1 堆，[m+1..j] 合并为 p-1 堆
//
//   dp[i][j][1] = dp[i][j][k] + sum(i, j)
//   即先合并成 k 堆，再把 k 堆合并成 1 堆
//
// 基础情况: dp[i][i][1] = 0 (单堆本身就是 1 堆)
//
// 优点: 状态含义非常清晰
// 缺点: 空间 O(n^2 * k)，时间常数大
// ============================================================
class Solution2 {
public:
    int mergeStones(vector<int>& stones, int k) {
        int n = stones.size();
        if ((n - 1) % (k - 1) != 0) return -1;

        vector<int> prefix(n + 1, 0);
        for (int i = 0; i < n; i++) {
            prefix[i + 1] = prefix[i] + stones[i];
        }

        // dp[i][j][p] = 把 [i..j] 合并成 p 堆的最小代价
        // INT_MAX 表示不可达状态
        const int INF = INT_MAX;
        vector<vector<vector<int>>> dp(n, vector<vector<int>>(n, vector<int>(k + 1, INF)));

        // 基础情况
        for (int i = 0; i < n; i++) {
            dp[i][i][1] = 0;
        }

        for (int len = 2; len <= n; len++) {
            for (int i = 0; i + len - 1 < n; i++) {
                int j = i + len - 1;

                // 合并成 p 堆 (2 <= p <= k)
                for (int p = 2; p <= min(len, k); p++) {
                    for (int m = i; m < j; m++) {
                        // 左半 [i..m] 合并成 1 堆
                        // 右半 [m+1..j] 合并成 p-1 堆
                        if (dp[i][m][1] != INF && dp[m + 1][j][p - 1] != INF) {
                            long long cost = (long long)dp[i][m][1] + dp[m + 1][j][p - 1];
                            dp[i][j][p] = min(dp[i][j][p], (int)cost);
                        }
                    }
                }

                // 合并成 1 堆 = 先合并成 k 堆 + 最后一步
                if (dp[i][j][k] != INF) {
                    dp[i][j][1] = dp[i][j][k] + prefix[j + 1] - prefix[i];
                }
            }
        }

        return dp[0][n - 1][1];
    }
};

// ============================================================
// 解法1 的带详细注释版本（帮助理解步长的含义）
// ============================================================
class Solution3 {
public:
    int mergeStones(vector<int>& stones, int k) {
        int n = stones.size();
        if ((n - 1) % (k - 1) != 0) return -1;

        // 前缀和
        vector<int> pre(n + 1, 0);
        for (int i = 0; i < n; i++) pre[i + 1] = pre[i] + stones[i];
        auto rangeSum = [&](int i, int j) { return pre[j + 1] - pre[i]; };

        vector<vector<int>> dp(n, vector<int>(n, 0));

        for (int len = k; len <= n; len++) {
            for (int i = 0; i + len - 1 < n; i++) {
                int j = i + len - 1;
                dp[i][j] = INT_MAX;

                // m 的意义: 把 [i..j] 分成 [i..m] 和 [m+1..j]
                // [i..m] 能合并成 1 堆 → m-i 是 k-1 的倍数
                // 最小的 m 是 i (m-i=0, 是 k-1 的倍数)
                // 下一个 m 是 i+k-1 (m-i=k-1)
                // 再下一个 m 是 i+2(k-1) ...
                for (int m = i; m < j; m += k - 1) {
                    dp[i][j] = min(dp[i][j], dp[i][m] + dp[m + 1][j]);
                }

                // (j-i) % (k-1) == 0 意味着 [i..j] 的长度满足
                // 能被完全合并为 1 堆的条件
                // 此时需要加上"最终合并为1堆"的代价 = 区间总和
                if ((j - i) % (k - 1) == 0) {
                    dp[i][j] += rangeSum(i, j);
                }
            }
        }

        return dp[0][n - 1];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间 | 空间 | 代码量 | 推荐场景 |
// |------|------|------|--------|----------|
// | 二维DP | O(n^3/k) | O(n^2) | 中等 | ⭐面试首选 |
// | 三维DP | O(n^3*k) | O(n^2*k) | 多 | 理解用 |
// | 注释版 | O(n^3/k) | O(n^2) | 多 | 学习用 |
//
// 【易错点】
//
// 1. 忘记可行性判断
//    ✗ 直接开始 DP → 对不可行输入返回错误结果
//    ✓ 先检查 (n-1) % (k-1) != 0 → return -1
//
// 2. 分割点步长写成 1
//    ✗ for (int m = i; m < j; m++) → 枚举了无效的分割点
//    ✓ for (int m = i; m < j; m += k-1) → 只枚举能合并为1堆的分割点
//    注意: 步长为1也能得到正确答案(因为dp值已含不可行信息)，但浪费时间
//
// 3. 最后合并代价加在循环内
//    ✗ dp[i][j] = min(...) + sum(i,j); → 每个分割点都加了sum
//    ✓ 先完成所有分割点的 min，再判断是否加 sum
//
// 4. 前缀和下标错误
//    ✗ sum(i,j) = prefix[j] - prefix[i] → 少了 stones[j]
//    ✓ sum(i,j) = prefix[j+1] - prefix[i]
//
// 5. 初始化 dp 为 INT_MAX 导致溢出
//    ✗ dp[i][j] = INT_MAX; 然后 dp[i][j] += sum → 溢出
//    ✓ 初始化为 0（因为小区间不需要合并），INT_MAX 只在转移时用
//
// 【面试追问】
//
// Q1: 为什么 (n-1)%(k-1)!=0 就无解？
// → 每次操作把 k 堆变 1 堆，净减 k-1 堆。
//    从 n 堆到 1 堆需净减 n-1 堆。
//    n-1 必须是 k-1 的倍数。
//
// Q2: k=2 时退化成什么问题？
// → 经典石子合并。(n-1)%(2-1)=n-1≥0 总是可行。
//    分割点步长=1，就是标准区间 DP。
//
// Q3: 能用贪心吗？
// → 不能。即使 k=2，贪心（每次选最小的两堆）也不是最优的，
//    因为必须是连续的堆。必须用 DP 保证全局最优。
//
// Q4: 二维DP为什么不需要第三维？
// → 因为 m 以 k-1 为步长，隐含保证了左半能合并为 1 堆。
//    加上 (j-i)%(k-1)==0 的判断，二维就能正确表达状态。
//    实质是把第三维的信息编码进了步长和 mod 条件里。
// ============================================================
