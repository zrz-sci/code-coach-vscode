/*
 * LeetCode 868: 二进制间距 (Binary Gap)
 *
 * 【题目本质】
 * 找正整数 n 的二进制表示中，两个相邻 1 之间的最长距离。
 * 只有一个 1 时返回 0。
 *
 * 【解法总览】
 * 解法1: 位运算逐位扫描   — O(log n) / O(1)   — 面试首选，简洁直观
 * 解法2: 转字符串扫描     — O(log n) / O(log n) — 备选，不够优雅
 * 解法3: lowbit 技巧      — O(k) / O(1)        — 进阶，只遍历1的个数次
 */


// ============================================================
// 解法1: 位运算逐位扫描 — 面试首选 ⭐
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 从低位到高位遍历 n 的每一位。每遇到一个 1，就计算它和上一个 1
// 之间的距离，更新最大值。
//
// 核心变量：
//   pos  — 当前正在检查的位的位置（0, 1, 2, ...）
//   last — 上一个 1 的位置（-1 表示还没遇到过 1）
//   ans  — 目前为止最大的间距
//
// 示例: n = 22 → 二进制 10110
//
//   pos=0: 10110 & 1 = 0 → 跳过
//   pos=1: 1011  & 1 = 1 → last=-1 (第一个1), 设 last=1
//   pos=2: 101   & 1 = 1 → last=1, gap=2-1=1, ans=1, 设 last=2
//   pos=3: 10    & 1 = 0 → 跳过
//   pos=4: 1     & 1 = 1 → last=2, gap=4-2=2, ans=2, 设 last=4
//   n 变成 0，退出循环
//
//   返回 ans = 2 ✓
//
// 示例: n = 8 → 二进制 1000
//   pos=0,1,2: 都是0 → 跳过
//   pos=3: 1 → last=-1, 第一个1, 设 last=3
//   只有一个 1, ans 保持 0 ✓
//
// 为什么 n > 0 做循环条件而不是固定32次？
//   n 右移到 0 就没有更多的位了，提前退出节省时间。
//   比如 n=5=101 只需检查3位，而不是32位。
// ============================================================
class Solution1 {
public:
    int binaryGap(int n) {
        int ans = 0;
        int last = -1;  // 上一个 1 的位置，-1 表示还没遇到

        for (int pos = 0; n > 0; pos++, n >>= 1) {
            if (n & 1) {  // 当前位是 1
                if (last != -1) {
                    ans = max(ans, pos - last);
                }
                last = pos;
            }
        }
        return ans;
    }
};

// ============================================================
// 解法2: 转字符串扫描
// 时间: O(log n)  空间: O(log n)
//
// 【思路】
// 先把 n 转成二进制字符串（低位在前），然后扫描 '1' 的位置。
// 间距只看"位置差"，所以低位在前不影响结果。
//
// 这个解法的意义：
//   对位运算不熟的人，用字符串处理更直观。
//   但额外 O(log n) 空间，且构建字符串有开销，不推荐面试用。
//
// 示例: n = 22 = 0b10110
//   binary = "01101" (低位在前: 位0=0, 位1=1, 位2=1, 位3=0, 位4=1)
//   1 的位置: 1, 2, 4
//   间距: 2-1=1, 4-2=2
//   最大间距: 2 ✓
// ============================================================
class Solution2 {
public:
    int binaryGap(int n) {
        // 转成二进制字符串（低位在前）
        string binary;
        while (n > 0) {
            binary += (char)('0' + (n & 1));
            n >>= 1;
        }

        int ans = 0, last = -1;
        for (int i = 0; i < (int)binary.size(); i++) {
            if (binary[i] == '1') {
                if (last != -1) {
                    ans = max(ans, i - last);
                }
                last = i;
            }
        }
        return ans;
    }
};

// ============================================================
// 解法3: lowbit 技巧 (Brian Kernighan)
// 时间: O(k)  空间: O(1)，k 为 n 的二进制中 1 的个数
//
// 【思路】
// 不需要逐位扫描所有 log n 位，只需要跳到每一个 1 的位置。
//
// 关键位运算：
//   __builtin_ctz(n): 返回末尾 0 的个数 = 最低位 1 的位置
//   n &= (n - 1):    去掉最低位的 1
//
// n &= (n-1) 的原理：
//   n   = ...10...0  (最低位的1后面全是0)
//   n-1 = ...01...1  (借位：最低位的1变0，后面的0变1)
//   n & (n-1) = ...00...0  (最低位的1被消除)
//
// 示例: n = 22 = 10110
//   轮1: ctz(10110)=1 → pos=1, last=-1 → 设 last=1
//         n &= (n-1): 10110 & 10100 = 10100
//   轮2: ctz(10100)=2 → pos=2, gap=2-1=1, ans=1, last=2
//         n &= (n-1): 10100 & 10000 = 10000
//   轮3: ctz(10000)=4 → pos=4, gap=4-2=2, ans=2, last=4
//         n &= (n-1): 10000 & 01111 = 00000
//   n = 0, 退出
//   返回 2 ✓
//
// 优势：当 n 的 1 很稀疏时（如 2^30 + 2^0 = 1000...001），
//       只需 2 次迭代而不是 31 次。
// ============================================================
class Solution3 {
public:
    int binaryGap(int n) {
        int ans = 0;
        int last = -1;

        while (n > 0) {
            // __builtin_ctz: count trailing zeros
            // 返回最低位的 1 的位置
            int pos = __builtin_ctz(n);

            if (last != -1) {
                ans = max(ans, pos - last);
            }
            last = pos;

            // 去掉最低位的 1 (Brian Kernighan trick)
            n &= (n - 1);
        }
        return ans;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间      | 空间     | 迭代次数          | 推荐 |
// |-------------|-----------|---------|------------------|------|
// | 逐位扫描    | O(log n)  | O(1)    | log n 次（所有位）  | ⭐   |
// | 转字符串    | O(log n)  | O(log n)| log n 次          | 备选 |
// | lowbit 技巧 | O(k)      | O(1)    | k 次（只看1的位）  | 加分 |
//
// 面试策略：写解法1（简洁稳妥），然后讲解法3的优化思路。
//
// ============================================================
// 【易错点】
//
// 1. 初始化 last:
//    ✗ last = 0 → 第一个1恰好在位置0时会误认为"已有前一个1"
//    ✓ last = -1 → 显式标记"还没遇到1"
//
// 2. 循环条件:
//    ✗ for (pos = 0; pos < 32; pos++) 但忘了右移n
//      → 每次 n&1 都检查同一位
//    ✓ n >>= 1 要放在循环体或循环更新表达式中
//
// 3. 距离 vs 中间0的个数:
//    10010001: 位0到位4，距离=4（不是3）
//    距离 = pos差，不是中间0的数量
//
// 4. 只有一个1 (如 n=8=1000):
//    last 只被设置一次，ans 保持 0 → 正确返回 0
//
// 5. 负数右移陷阱:
//    有符号 int 的 >> 是算术右移（高位补1），可能死循环
//    题目 n >= 1，用 n > 0 循环条件即可避免
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 如果 n = 0 呢？
//     n=0 没有1，while(n>0) 不进循环，返回0。正确。
//
// Q2: 如果要找最小间距呢？
//     max 改成 min，初始 ans=INT_MAX，最后检查 last 是否被设置过两次。
//     若不到两个1，返回0。
//
// Q3: 如果 n 是 64 位呢？
//     int → long long / uint64_t, __builtin_ctz → __builtin_ctzll。
//     循环最多64次，逻辑不变。
//
// Q4: __builtin_ctz 不能用怎么办？
//     手写：while(!(n & 1)) { n >>= 1; pos++; }
//     或者直接用解法1的逐位扫描。
//
