// 总结
// ============================================================
/*
 * -------- 解法对比一览 --------
 *
 * | 解法         | 时间    | 空间 | 适用场景           | 面试推荐 |
 * |-------------|---------|------|--------------------|---------|
 * | 暴力三重循环 | O(n^3)  | O(1) | n<=100 直接AC      | 起手     |
 * | 剪枝优化     | O(n^3)w | O(1) | 实测快数倍          | ⭐首选  |
 * | 值域范围分析 | O(n^2*n)| O(1) | 面试口述优化思路     | 讨论用  |
 *
 * -------- 易错点 --------
 *
 * 1. 三条件用 AND 而非 OR -- 必须同时满足
 * 2. abs() 别漏 -- |arr[i]-arr[j]| 不是 arr[i]-arr[j]
 * 3. 剪枝只能提前判第一个条件(i,j相关)，第三条件关联 i 和 k
 *    无法在 j 循环中提前排除
 * 4. 不要过度工程化 -- n<=100 时暴力就是最优策略
 *
 * -------- 面试追问链 --------
 *
 * Q1: n 增大到 10^5 怎么优化?
 *     -> 枚举中间元素 j，左右用 BIT/线段树维护值域计数
 *        但第三条件关联 i 和 k，仍需巧妙处理
 *
 * Q2: 如果只有两个条件 |arr[i]-arr[j]| <= a，如何 O(n log n)?
 *     -> 排序后双指针，或 BIT 在值域上做区间计数
 *
 * Q3: 推广到四元组 (i<j<k<l) 怎么做?
 *     -> 类似 LC 1995，枚举中间两个元素，左右分别用数据结构计数
 *        从 O(n^4) 优化到 O(n^2 log n)
 */
