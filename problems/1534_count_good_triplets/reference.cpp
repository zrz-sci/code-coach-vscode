/*
 * LeetCode 1534: 统计好三元组 (Count Good Triplets)
 *
 * 难度: Easy
 * 标签: Array, Enumeration
 *
 * 核心思想: 数据量小(n<=100)，暴力三重循环+剪枝即可
 *           面试关注: 剪枝技巧 + 大数据量优化方向讨论
 */



// ============================================================
// 解法1: 暴力三重循环（无剪枝）
// 时间: O(n^3)  空间: O(1)
//
// 最直接的做法: 枚举所有满足 i < j < k 的三元组，
// 检查三个条件是否同时成立。
//
// n <= 100 时，C(100,3) = 161700 次，毫秒级完成。
// ============================================================
class Solution_BruteForce {
public:
    int countGoodTriplets(vector<int>& arr, int a, int b, int c) {
        int n = arr.size();
        int count = 0;

        // 枚举所有 i < j < k 的组合
        for (int i = 0; i < n - 2; i++) {
            for (int j = i + 1; j < n - 1; j++) {
                for (int k = j + 1; k < n; k++) {
                    // 三个条件必须同时满足（AND）
                    // && 短路求值: 前面不满足就不检查后面
                    if (abs(arr[i] - arr[j]) <= a &&
                        abs(arr[j] - arr[k]) <= b &&
                        abs(arr[i] - arr[k]) <= c) {
                        count++;
                    }
                }
            }
        }

        return count;
    }
};

// ============================================================
// 解法2: 剪枝优化  ⭐ 推荐写法
// 时间: O(n^3) 最坏  空间: O(1)
//
// 关键优化: 在 j 循环中先检查 |arr[i]-arr[j]| <= a
//           不满足就 continue，跳过整个 k 循环
//
// 为什么有效:
// - 当 a 较小时，大部分 (i,j) 对不满足第一个条件
// - 跳过的 k 循环节省 O(n) 的无效比较
// - 例如 a=0 时，只有 arr[i]==arr[j] 的对才进入 k 循环
//
// 图示:
//   arr = [3, 0, 1, 1, 9, 7], a=7, b=2, c=3
//
//   i=0, j=1: |3-0|=3 <= 7  -> 进入 k 循环
//     k=2: |0-1|=1<=2, |3-1|=2<=3 -> count++ (3,0,1)
//     k=3: |0-1|=1<=2, |3-1|=2<=3 -> count++ (3,0,1)
//     k=4: |0-9|=9>2              -> skip
//     k=5: |0-7|=7>2              -> skip
//
//   i=0, j=2: |3-1|=2 <= 7  -> 进入 k 循环
//     k=3: |1-1|=0<=2, |3-1|=2<=3 -> count++ (3,1,1)
//     k=4: |1-9|=8>2              -> skip
//     k=5: |1-7|=6>2              -> skip
//
//   i=0, j=4: |3-9|=6 <= 7  -> 进入 k 循环
//     k=5: |9-7|=2<=2, |3-7|=4>3  -> skip (第三条件不满足)
//
//   i=1, j=2: |0-1|=1 <= 7  -> 进入 k 循环
//     k=3: |1-1|=0<=2, |0-1|=1<=3 -> count++ (0,1,1)
//     ...
//
//   最终: count = 4
// ============================================================
class Solution_Pruned {
public:
    int countGoodTriplets(vector<int>& arr, int a, int b, int c) {
        int n = arr.size();
        int count = 0;

        for (int i = 0; i < n - 2; i++) {
            for (int j = i + 1; j < n - 1; j++) {
                // 剪枝: 第一个条件不满足 -> 跳过所有 k
                if (abs(arr[i] - arr[j]) > a) continue;

                for (int k = j + 1; k < n; k++) {
                    // 只需检查剩余两个条件
                    if (abs(arr[j] - arr[k]) <= b &&
                        abs(arr[i] - arr[k]) <= c) {
                        count++;
                    }
                }
            }
        }

        return count;
    }
};

// ============================================================
// 解法3: 枚举中间元素 + 值域范围分析
// 时间: O(n^2 * V) 或 O(n^2)  空间: O(V)
//
// 思路（面试讨论用，n<=100 不需要实现）:
//
// 绝对值不等式展开:
//   |arr[i] - arr[j]| <= a  等价于  arr[j]-a <= arr[i] <= arr[j]+a
//   |arr[j] - arr[k]| <= b  等价于  arr[j]-b <= arr[k] <= arr[j]+b
//   |arr[i] - arr[k]| <= c  等价于  arr[i]-c <= arr[k] <= arr[i]+c
//
// 固定 j 后:
//   arr[k] 的有效范围 = [arr[j]-b, arr[j]+b] ∩ [arr[i]-c, arr[i]+c]
//   = [max(arr[j]-b, arr[i]-c), min(arr[j]+b, arr[i]+c)]
//
// 用前缀和数组在值域上快速求范围内的计数
// ============================================================
class Solution_ValueRange {
public:
    int countGoodTriplets(vector<int>& arr, int a, int b, int c) {
        int n = arr.size();
        int count = 0;

        // 前缀和优化: 维护 j 右边的值域计数
        // sum[v] = 在 j 右边，值为 v 的元素个数
        // 但由于第三条件关联 i 和 k，仍需枚举 i
        // 所以这个优化对本题帮助有限

        // 仍然枚举 i 和 j，对 k 用范围查询加速
        for (int j = 1; j < n - 1; j++) {
            for (int i = 0; i < j; i++) {
                if (abs(arr[i] - arr[j]) > a) continue;

                // arr[k] 的有效范围
                int lo_k = max(arr[j] - b, arr[i] - c);
                int hi_k = min(arr[j] + b, arr[i] + c);

                if (lo_k > hi_k) continue; // 无有效范围

                // 在 j 右边计数值在 [lo_k, hi_k] 内的元素
                for (int k = j + 1; k < n; k++) {
                    if (arr[k] >= lo_k && arr[k] <= hi_k) {
                        count++;
                    }
                }
            }
        }

        return count;
    }
};

// ============================================================
// 解法对比分析
// ============================================================
/*
 * | 解法              | 时间       | 空间  | 优点              | 缺点              |
 * |-------------------|-----------|-------|-------------------|--------------------|
 * | 暴力三重循环       | O(n^3)    | O(1)  | 最直观，不易出错  | 无优化             |
 * | 剪枝优化           | O(n^3)max | O(1)  | 实际快很多        | 最坏仍 O(n^3)      |
 * | 值域范围分析       | O(n^2*n)  | O(1)  | 范围收窄          | 第三条件难以去除n  |
 *
 * n <= 100 的关键认知:
 * - 暴力就是最佳策略，不要过度工程化
 * - 面试中写出解法2，然后口述解法3的思路即可
 * - "先写出正确解，再讨论优化" 比 "直接写复杂优化解" 更好
 *
 * 三角不等式观察:
 * |arr[i]-arr[k]| <= |arr[i]-arr[j]| + |arr[j]-arr[k]| <= a + b
 * 所以如果 c >= a + b，第三个条件自动满足
 * 但如果 c < a + b，第三条件仍然有约束力
 */

// ============================================================
// 面试 Follow-up
// ============================================================
/*
 * Q1: 如果 n 增大到 10^4 或 10^5？
 * A1: O(n^3) 不可行。考虑:
 *     - 枚举中间 j，左右分别用 BIT/线段树维护值域计数
 *     - 但第三条件关联 i 和 k，需要巧妙处理
 *     - 可能需要 O(n^2) 或 O(n * V) 的做法
 *
 * Q2: 如果只有两个条件 (i,j)，不涉及 k？
 * A2: 两层循环 O(n^2)。如果 n 很大，排序后双指针或
 *     BIT 可以做到 O(n log n)。
 *
 * Q3: 如果要找四元组？
 * A3: 类似 LC 1995，暴力 O(n^4)；优化可以枚举中间两个，
 *     左右分别计数。
 *
 * Q4: 如果数组元素可以重复使用（允许 i=j 或 j=k）？
 * A4: 去掉 i<j<k 的约束，三层循环都从 0 开始，
 *     但需要注意是否允许自身配对。
 */

// ============================================================
// 使用 Solution_Pruned 作为默认解法提交
// ============================================================
class Solution {
public:
    int countGoodTriplets(vector<int>& arr, int a, int b, int c) {
        int n = arr.size();
        int count = 0;
        for (int i = 0; i < n - 2; i++) {
            for (int j = i + 1; j < n - 1; j++) {
                if (abs(arr[i] - arr[j]) > a) continue;
                for (int k = j + 1; k < n; k++) {
                    if (abs(arr[j] - arr[k]) <= b &&
                        abs(arr[i] - arr[k]) <= c) {
                        count++;
                    }
                }
            }
        }
        return count;
    }
};

