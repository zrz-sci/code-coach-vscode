/*
 * LeetCode 538: 把二叉搜索树转换为累加树 (Convert BST to Greater Tree)
 *
 * 【题目本质】
 * BST 的每个节点的新值 = 原值 + 所有大于它的节点值之和。
 * 本质：BST 中序有序数组的"后缀和"。
 * 反向中序遍历（右→根→左）= 从大到小访问，维护累加和即可一次搞定。
 *
 * 【解法总览】
 * 解法1: 暴力两次遍历    — O(n) / O(n)   — 最直觉，先理解问题
 * 解法2: 反向中序递归     — O(n) / O(h)   — 面试首选 ⭐
 * 解法3: 反向中序迭代(栈) — O(n) / O(h)   — 追问时给出
 * 解法4: Morris 反向中序  — O(n) / O(1)   — 加分项
 *
 * 原始 BST 示例:
 *          4
 *         / \
 *        1   6
 *       / \ / \
 *      0  2 5  7
 *          \    \
 *           3    8
 *
 * 中序遍历(升序): 0, 1, 2, 3, 4, 5, 6, 7, 8
 * 反向中序(降序): 8, 7, 6, 5, 4, 3, 2, 1, 0
 * 累加和:         8,15,21,26,30,33,35,36,36
 *
 * 转换后的树:
 *          30
 *         /  \
 *       36    21
 *       / \  / \
 *     36 35 26  15
 *          \     \
 *          33     8
 */


// ============================================================
// 解法1: 暴力两次遍历 — 先收集有序数组，算后缀和，再写回
// 时间: O(n)  空间: O(n) — 额外数组存所有节点值
//
// 【思路】
// 最朴素的理解：BST 中序遍历得到升序数组。
// "大于等于当前值的和" = 升序数组中从当前位置到末尾的后缀和。
// 所以：中序收集 → 算后缀和 → 再中序遍历把新值写回。
// 虽然三步略繁琐，但思路清晰，帮助理解问题本质。
// ============================================================
class Solution1 {
public:
    TreeNode* convertBST(TreeNode* root) {
        vector<int> vals;
        // 第一步：中序遍历收集升序值
        inorder(root, vals);
        
        // 第二步：从右往左求后缀和
        // [0,1,2,3,4,5,6,7,8] → [36,36,35,33,30,26,21,15,8]
        for (int i = (int)vals.size() - 2; i >= 0; i--) {
            vals[i] += vals[i + 1];
        }
        
        // 第三步：再次中序遍历，按顺序写回后缀和
        int idx = 0;
        assign(root, vals, idx);
        return root;
    }
    
private:
    void inorder(TreeNode* node, vector<int>& vals) {
        if (!node) return;
        inorder(node->left, vals);
        vals.push_back(node->val);
        inorder(node->right, vals);
    }
    
    void assign(TreeNode* node, vector<int>& vals, int& idx) {
        if (!node) return;
        assign(node->left, vals, idx);
        node->val = vals[idx++]; // 中序顺序一一对应
        assign(node->right, vals, idx);
    }
};

// ============================================================
// 解法2: 反向中序递归 — 右→根→左，维护累加变量 ⭐ 面试首选
// 时间: O(n)  空间: O(h) — h为树高，递归栈空间
//
// 【思路】
// 解法1分三步，能不能一步搞定？
// 关键洞察：反向中序遍历（右→根→左）按降序访问节点。
// 维护一个累加变量 sum，每访问一个节点：
//   sum += node->val;   // 累加当前值
//   node->val = sum;    // 当前节点的新值 = 所有 ≥ 它的值的和
// 一次遍历同时完成"计算"和"赋值"！
//
// 遍历过程 (以示例为例):
//   访问节点: 8 → 7 → 6 → 5 → 4 → 3 → 2 → 1 → 0
//   sum 变化: 8   15  21  26  30  33  35  36  36
//   新值:     8   15  21  26  30  33  35  36  36
//
// 递归三要素:
//   返回值: TreeNode* (返回根节点，方便调用)
//   终止条件: node == nullptr
//   单层逻辑: 递归右 → 累加&赋值 → 递归左
// ============================================================
class Solution2 {
public:
    int sum = 0; // 成员变量，在所有递归调用间共享

    TreeNode* convertBST(TreeNode* root) {
        if (!root) return nullptr;
        
        // 先递归右子树 — 处理所有比 root 大的节点
        convertBST(root->right);
        
        // 处理当前节点 — 此时 sum 已经是所有 > root 的值的和
        sum += root->val;    // 加上自身
        root->val = sum;     // 新值 = 自身 + 所有比它大的
        
        // 再递归左子树 — 处理所有比 root 小的节点
        convertBST(root->left);
        
        return root;
    }
};

// ============================================================
// 解法3: 反向中序迭代（栈模拟） — 用栈替代递归
// 时间: O(n)  空间: O(h) — 显式栈
//
// 【思路】
// 和标准中序迭代几乎一样，区别只有方向：
//   标准中序: 一路向左入栈 → 弹出处理 → 转右子树
//   反向中序: 一路向右入栈 → 弹出处理 → 转左子树
//
// 用栈模拟递归调用栈的过程:
//
//   以示例树为例:
//   初始: curr=4
//
//   Round1: 一路向右入栈 → 栈: [4, 6, 7, 8]
//           弹出8, sum=8, val=8, 转左(null)
//   Round2: 弹出7, sum=15, val=15, 转左(null)
//   Round3: 弹出6, sum=21, val=21, 转左 → curr=5
//   Round4: 一路向右(5无右子) → 栈: [4, 5]
//           弹出5, sum=26, val=26, 转左(null)
//   Round5: 弹出4, sum=30, val=30, 转左 → curr=1
//   ... 继续处理左子树 ...
// ============================================================
class Solution3 {
public:
    TreeNode* convertBST(TreeNode* root) {
        stack<TreeNode*> stk;
        TreeNode* curr = root;
        int sum = 0;
        
        while (curr || !stk.empty()) {
            // 一路向右，把右链全部入栈（对应递归中的"先进入右子树"）
            while (curr) {
                stk.push(curr);
                curr = curr->right;
            }
            
            // 弹出栈顶 = 当前最大的未处理节点
            curr = stk.top();
            stk.pop();
            
            // 累加并更新（对应递归中的"处理当前节点"）
            sum += curr->val;
            curr->val = sum;
            
            // 转向左子树（对应递归中的"进入左子树"）
            curr = curr->left;
        }
        
        return root;
    }
};

// ============================================================
// 解法4: Morris 反向中序遍历 — O(1) 空间，无栈无递归
// 时间: O(n)  空间: O(1)
//
// 【思路】
// Morris 遍历的核心思想：利用叶子节点的空指针建立临时线索，
// 从而在不用栈的情况下完成遍历后能"回到"父节点。
//
// 标准 Morris 中序: 找左子树最右节点作为线索
// 反向 Morris 中序: 找右子树最左节点作为线索
//
// 对于当前节点 curr:
//   情况1: 没有右子树 → 直接处理 curr，转左子树
//   情况2: 有右子树 → 找右子树的最左节点 succ
//     2a: succ->left == null → 建立线索 succ->left = curr，进入右子树
//     2b: succ->left == curr → 线索已存在，说明右子树已处理完
//                               断开线索，处理 curr，转左子树
//
// 示意（以节点4为例）：
//   找到右子树(6)的最左节点(5)
//   建立线索: 5->left = 4 (临时)
//   先去处理 6, 7, 8, 然后回到 5, 处理 5
//   5->left 指向 4，回到 4，此时断开线索恢复 5->left = null
//   处理 4，然后转向左子树
// ============================================================
class Solution4 {
public:
    TreeNode* convertBST(TreeNode* root) {
        TreeNode* curr = root;
        int sum = 0;
        
        while (curr) {
            if (!curr->right) {
                // 情况1: 没有右子树，当前就是最大的未处理节点
                sum += curr->val;
                curr->val = sum;
                curr = curr->left; // 转向左子树
            } else {
                // 情况2: 有右子树，找右子树的最左节点
                TreeNode* succ = curr->right;
                while (succ->left && succ->left != curr) {
                    succ = succ->left;
                }
                
                if (!succ->left) {
                    // 情况2a: 首次到达，建立线索让 succ 的左指针指回 curr
                    succ->left = curr;
                    curr = curr->right; // 先去处理右子树
                } else {
                    // 情况2b: 线索已存在，右子树已处理完毕
                    succ->left = nullptr; // 恢复树结构！
                    sum += curr->val;
                    curr->val = sum;
                    curr = curr->left; // 转向左子树
                }
            }
        }
        
        return root;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法    | 时间 | 空间 | 代码量 | 适用场景              |
// |---------|------|------|--------|-----------------------|
// | 暴力    | O(n) | O(n) | 多     | 理解问题本质          |
// | 递归 ⭐ | O(n) | O(h) | 极少   | 面试首选              |
// | 迭代    | O(n) | O(h) | 中等   | 追问"不用递归怎么做" |
// | Morris  | O(n) | O(1) | 较多   | 追问"O(1)空间"       |
//
// 核心区别:
//   解法1 分三步理解问题，解法2 合三为一。
//   解法2 和 3 本质相同（反向中序+累加），区别是递归 vs 迭代。
//   解法4 通过线索化避免栈空间，但会临时修改树结构。
//
// 【易错点】
// 1. 累加变量用值传递导致修改丢失:
//    ✗ void dfs(TreeNode* node, int sum) — sum 是局部变量拷贝
//    ✓ void dfs(TreeNode* node, int& sum) 或用成员变量
//
// 2. 遍历方向写反:
//    ✗ 左→根→右 (标准中序) — 累加的是"比当前小的值"
//    ✓ 右→根→左 (反向中序) — 累加的是"比当前大的值"
//
// 3. 迭代版内层循环方向:
//    ✗ while(curr) { stk.push(curr); curr = curr->left; }
//    ✓ while(curr) { stk.push(curr); curr = curr->right; }
//
// 4. Morris 遍历忘记恢复树结构:
//    ✗ 只建立线索不断开 → 树变成有环图，后续操作死循环
//    ✓ 第二次到达时 succ->left = nullptr; 必须恢复
//
// 5. 空树边界:
//    ✗ 没检查 root == nullptr 直接访问
//    ✓ 递归第一行就 if (!root) return nullptr;
//
// 【面试追问】
// Q1: 为什么反向中序+累加就是正确答案？
//     → BST 中序是升序，反向中序是降序。按降序访问时，已访问的
//       节点全部 ≥ 当前节点，累加和 = 所有 ≥ 当前值的和。
//
// Q2: 树极度不平衡（退化成链表）时递归有什么风险？
//     → 递归深度 = 树高 = n，可能栈溢出。
//       用迭代(解法3)或 Morris(解法4)避免。
//
// Q3: 如果不是 BST 而是普通二叉树怎么办？
//     → 不能利用中序有序性。方案：先遍历求总和 S，
//       再中序遍历维护前缀和 prefix，每个节点新值 = S - prefix + 原值。
//       或者收集所有值排序后用哈希表映射。
//
// Q4: 这道题和 1038 题的关系？
//     → 完全相同的题目，代码一字不改。
// ============================================================
