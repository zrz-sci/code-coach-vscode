//
// - LC 224 基本计算器 I — 只有 +- 和括号，无乘除。
//   复用：栈处理嵌套的框架，但不需要乘除优先级逻辑。
//
// - LC 772 基本计算器 III — 有 +-*/ 和括号。
//   复用：本题的优先级处理 + LC 224 的括号递归，合并即可。
//
// - LC 150 逆波兰表达式求值 — 后缀表达式，无优先级问题。
//   对比：本题的栈操作本质上是在线地将中缀转后缀并求值。
//
