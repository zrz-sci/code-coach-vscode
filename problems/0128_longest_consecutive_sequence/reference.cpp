/*
 * LeetCode 128: 最长连续序列 (Longest Consecutive Sequence)
 *
 * 【题目本质】
 * 在无序数组中找到最长的"值连续递增1"的子集长度，要求 O(n) 时间。
 * 核心挑战：不排序的前提下，如何高效判断一个数的邻居是否存在。
 *
 * 【解法总览】
 * 解法1: 排序 + 线性扫描   — O(n log n) / O(1)    — 最直觉，但不满足 O(n) 要求
 * 解法2: 哈希集合 + 起点判断 — O(n) / O(n)         — 面试首选 ⭐
 * 解法3: 并查集            — O(n·α(n)) / O(n)     — 图论视角，动态场景更灵活
 */

// ============================================================
// 解法1: 排序 + 线性扫描
// 时间: O(n log n)  空间: O(1)（原地排序）或 O(n)（取决于排序实现）
//
// 【思路】
// 最自然的想法：排序后相邻数字挨在一起，线性扫描即可。
// 排序后数组: [1, 2, 3, 4, 100, 200]
//              \_________/
//              连续段长度=4
//
// 需要特别处理重复元素：[1, 1, 2] 排序后遇到重复要跳过，
// 否则 1→1 不连续会错误地重置当前长度。
// ============================================================
class Solution1 {
public:
    int longestConsecutive(vector<int>& nums) {
        if (nums.empty()) return 0;
        
        sort(nums.begin(), nums.end());
        
        int maxLen = 1, curLen = 1;
        for (int i = 1; i < (int)nums.size(); i++) {
            // 重复元素：跳过，不算断开也不算延伸
            if (nums[i] == nums[i - 1]) continue;
            
            if (nums[i] == nums[i - 1] + 1) {
                // 与前一个连续，延伸当前段
                curLen++;
            } else {
                // 断开，重新开始
                curLen = 1;
            }
            maxLen = max(maxLen, curLen);
        }
        return maxLen;
    }
};

// ============================================================
// 解法2: 哈希集合 + 起点判断 — 面试首选 ⭐
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法1 的瓶颈是排序 O(n log n)。我们其实不需要全局有序，
// 只需要快速回答"某个数存不存在"——哈希集合 O(1)。
//
// 关键洞察：一条连续序列只需要从"起点"延伸一次。
// 怎么判断起点？如果 num-1 不在集合中，num 就是起点。
//
// 可视化示例: nums = [100, 4, 200, 1, 3, 2]
// 哈希集合: {1, 2, 3, 4, 100, 200}
//
// 遍历每个数:
//   num=1:   0不在集合 → 是起点! 延伸: 1→2→3→4→(5不在) 长度=4 ★
//   num=2:   1在集合   → 跳过（会被从1开始的链覆盖）
//   num=3:   2在集合   → 跳过
//   num=4:   3在集合   → 跳过
//   num=100: 99不在    → 是起点! 延伸: 100→(101不在) 长度=1
//   num=200: 199不在   → 是起点! 延伸: 200→(201不在) 长度=1
//
// 【为什么是 O(n)？均摊分析】
// 外层 for 循环 n 次。只有"起点"才进入 while。
// 每个元素最多作为一条链的成员被 while 访问一次。
// 所有 while 的总迭代次数 ≤ n，所以总复杂度 O(n) + O(n) = O(n)。
// ============================================================
class Solution2 {
public:
    int longestConsecutive(vector<int>& nums) {
        // 所有数字放入哈希集合，天然去重
        unordered_set<int> numSet(nums.begin(), nums.end());
        
        int maxLen = 0;
        
        // 遍历集合（不是原数组，避免重复元素多次处理）
        for (int num : numSet) {
            // 核心：只有 num-1 不存在时，num 才是起点
            // 这保证了每条连续链只被从起点延伸一次
            if (numSet.count(num - 1)) continue;
            
            // num 是起点，向后延伸
            int curNum = num;
            int curLen = 1;
            while (numSet.count(curNum + 1)) {
                curNum++;
                curLen++;
            }
            
            maxLen = max(maxLen, curLen);
        }
        
        return maxLen;
    }
};

// ============================================================
// 解法3: 并查集 (Union-Find)
// 时间: O(n·α(n)) ≈ O(n)  空间: O(n)
//
// 【思路】
// 换一个视角：把每个数看作图的节点。
// 如果 x 和 x+1 都存在，就在它们之间连一条边。
// 问题变成：找最大连通分量的大小 → 并查集的经典应用。
//
// 步骤：
// 1. 初始化：每个数字是一个独立的集合，大小为1
// 2. 合并：对每个数 x，如果 x+1 也在数组中，把它们合并
// 3. 查询：遍历所有根节点，找最大的 size
//
// 可视化: nums = [100, 4, 200, 1, 3, 2]
// 初始: {1} {2} {3} {4} {100} {200}
// 合并1和2: {1,2} {3} {4} {100} {200}
// 合并2和3: {1,2,3} {4} {100} {200}
// 合并3和4: {1,2,3,4} {100} {200}
// 最大连通分量大小 = 4
//
// 【适用场景】
// 本题用哈希集合更简洁。但如果是动态场景（数字流式到达，
// 需要不断维护最长连续序列），并查集更灵活——每来一个新数，
// 与左邻右舍合并即可，均摊 O(1) 更新。
// ============================================================
class Solution3 {
public:
    unordered_map<int, int> parent; // 父节点
    unordered_map<int, int> rank_;  // 秩（树高的上界）
    unordered_map<int, int> size_;  // 以该节点为根的集合大小
    
    // 查找根节点，带路径压缩
    int find(int x) {
        if (parent[x] != x) {
            parent[x] = find(parent[x]);
        }
        return parent[x];
    }
    
    // 合并两个集合，按秩合并
    void unite(int x, int y) {
        int px = find(x), py = find(y);
        if (px == py) return; // 已在同一集合
        
        // 小树接到大树下面
        if (rank_[px] < rank_[py]) swap(px, py);
        parent[py] = px;
        size_[px] += size_[py]; // 合并后更新大小
        if (rank_[px] == rank_[py]) rank_[px]++;
    }
    
    int longestConsecutive(vector<int>& nums) {
        if (nums.empty()) return 0;
        
        // 初始化每个数为独立集合
        for (int num : nums) {
            if (parent.count(num)) continue; // 去重
            parent[num] = num;
            rank_[num] = 0;
            size_[num] = 1;
        }
        
        // 对每个数 x，如果 x+1 存在就合并
        for (int num : nums) {
            if (parent.count(num + 1)) {
                unite(num, num + 1);
            }
        }
        
        // 找最大连通分量
        int maxLen = 0;
        for (auto& [num, _] : parent) {
            if (find(num) == num) { // 只看根节点的 size
                maxLen = max(maxLen, size_[num]);
            }
        }
        return maxLen;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间         | 空间  | 代码量 | 面试推荐 |
// |-------------|-------------|-------|--------|---------|
// | 排序+扫描    | O(n log n)  | O(1)  | 最少   | 起手式   |
// | 哈希集合 ⭐  | O(n)        | O(n)  | 适中   | 首选     |
// | 并查集       | O(n·α(n))   | O(n)  | 较多   | 追问时说 |
//
// 选择建议：
// - 面试先说排序思路表示理解题意，然后主推哈希集合方案
// - 被追问"动态场景"时提并查集
// - 排序方案在不要求 O(n) 时是最简洁的
//
// 【易错点】
// 1. 重复元素处理（排序解法）：
//    ✗ 遇到 nums[i]==nums[i-1] 时重置 curLen=1
//    ✓ 遇到重复要 continue 跳过，不能断开也不能延伸
//
// 2. 遍历对象选错（哈希解法）：
//    ✗ for (int num : nums) — 重复元素多次作为起点，虽然结果正确但浪费时间
//    ✓ for (int num : numSet) — 去重后遍历更高效
//
// 3. 起点判断条件写反：
//    ✗ if (numSet.count(num + 1)) continue; — 这跳过的是"有后继的"，恰好反了
//    ✓ if (numSet.count(num - 1)) continue; — 跳过"有前驱的"，保留真正的起点
//
// 4. 空数组未处理：
//    ✗ 排序解法中直接 maxLen=1 但数组为空时应返回 0
//    ✓ 开头加 if (nums.empty()) return 0;
//
// 5. 并查集中重复数字初始化覆盖：
//    ✗ 每次都 size_[num]=1，如果 num 已经被合并过，size 被重置
//    ✓ 初始化时加 if (parent.count(num)) continue;
//
// 【面试追问（递进链）】
//
// Q1: 暴力怎么做？复杂度多少？
// A1: 对每个数 x 向后查找 x+1, x+2...，线性查找存在性。
//     最坏 O(n²)。瓶颈：查找 O(n) + 每个数都延伸有重复。
//
// Q2: 为什么哈希解法的嵌套循环是 O(n) 而不是 O(n²)？
// A2: 均摊分析。只有起点进入 while，每个元素最多被 while
//     访问一次。所有 while 迭代总数 ≤ n。
//
// Q3: 如果数据流式到达，不断有新数字加入，怎么维护？
// A3: 用并查集。新数字 x 到来时，创建节点，尝试与 x-1、x+1
//     合并。维护全局 maxLen，每次合并后更新。均摊 O(α(n)) 更新。
//
// Q4: 能否同时 O(n) 时间和 O(1) 空间？
// A4: 不能。要判断某个值是否存在，必须记录信息，至少 O(n) 空间。
//     除非允许修改原数组且用排序（但排序是 O(n log n)）。
// ============================================================
