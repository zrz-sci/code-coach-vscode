/*
 * LeetCode 1047: 删除字符串中的所有相邻重复项
 *
 * 【题目本质】
 * "对对碰消除"——相邻相同字符配对消除，消除后可能产生新的相邻对，继续消除。
 * 本质是栈匹配问题，和括号匹配（LC 20）同一模式。
 *
 * 【解法总览】
 * 解法1: 暴力模拟 — O(n²) / O(n) — 反复扫描删除，最直觉
 * 解法2: 栈       — O(n) / O(n) — 一次遍历，栈顶匹配则弹出
 * 解法3: string当栈— O(n) / O(n) — 用string模拟栈，最简洁
 * 解法4: 双指针   — O(n) / O(1) — 原地操作，Follow-up 最优空间
 */

// ============================================================
// 解法1: 暴力模拟 — 完全按题意反复扫描删除
// 时间: O(n²) 最坏  空间: O(n)
//
// 【思路】
// 最朴素的想法：一轮一轮扫描，每轮找到相邻重复对就删掉，
// 直到某一轮没有任何删除发生为止。
//
// 为什么是 O(n²)？考虑 "aabbccdd"：
//   轮1: 删除 aa,bb,cc,dd → ""
//   但如果是 "abbacddc"：
//   轮1: 删除 bb,dd → "aacc"
//   轮2: 删除 aa,cc → ""
//   最坏需要 O(n/2) 轮，每轮 O(n)。
// ============================================================

// 处理 "abbaca" 的过程:
//   轮1: a|bb|aca → 删除 bb → "aaca"
//   轮2: |aa|ca   → 删除 aa → "ca"
//   轮3: "ca" 无相邻重复 → 结束
//   结果: "ca"

class Solution1 {
public:
    string removeDuplicates(string s) {
        bool found = true;
        while (found) {
            found = false;
            string next;
            for (int i = 0; i < (int)s.size(); i++) {
                if (i + 1 < (int)s.size() && s[i] == s[i + 1]) {
                    found = true;
                    i++;  // 跳过配对的第二个字符
                } else {
                    next += s[i];
                }
            }
            s = next;
        }
        return s;
    }
};

// ============================================================
// 解法2: 栈 — 一次遍历，栈顶相同则消除
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 暴力解的瓶颈：删除一对后，前后字符变成新邻居，需要"回头看"。
// 反复扫描来回头看太低效。
//
// 栈天然支持"回头看上一个"：
//   - 当前字符 == 栈顶 → 弹出（消除这一对）
//   - 当前字符 != 栈顶 → 压入
// 消除后栈顶自动变成前一个未被消除的字符，连锁反应自然处理。
//
// 这和括号匹配的逻辑完全一致：
//   括号匹配：遇到匹配的右括号 → 弹出左括号
//   本题：    遇到和栈顶相同的字符 → 弹出栈顶
// ============================================================

// 处理 "abbaca" 的栈过程:
//
// 字符   操作              栈状态（左=底，右=顶）
//  'a'   栈空,压入          [a]
//  'b'   a≠b, 压入          [a, b]
//  'b'   b==b, 弹出!        [a]         ← bb 消除
//  'a'   a==a, 弹出!        []          ← aa 消除（连锁！）
//  'c'   栈空, 压入          [c]
//  'a'   c≠a, 压入          [c, a]
//
// 栈内: [c, a] → 翻转后 → "ca" ✓

class Solution2 {
public:
    string removeDuplicates(string s) {
        stack<char> stk;
        for (char c : s) {
            if (!stk.empty() && stk.top() == c) {
                stk.pop();   // 配对消除
            } else {
                stk.push(c); // 压入等待匹配
            }
        }
        // 栈底→栈顶是正序，但弹出是逆序，需要翻转
        string result;
        while (!stk.empty()) {
            result += stk.top();
            stk.pop();
        }
        reverse(result.begin(), result.end());
        return result;
    }
};

// ============================================================
// 解法3: 字符串当栈 — 最简洁写法（面试推荐）
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法2需要从栈弹出再翻转，不够优雅。
// 观察：C++ 的 string 有 back()/pop_back()/push_back()，
// 和栈的 top()/pop()/push() 功能完全一样！
//
// 用 string 模拟栈：
//   - string 末尾 = 栈顶
//   - push_back = push
//   - pop_back = pop
//   - back() = top()
//
// 好处：遍历完后 string 本身就是答案，无需翻转。
// ============================================================

class Solution3 {
public:
    string removeDuplicates(string s) {
        string result;  // 既当栈，又是最终答案
        for (char c : s) {
            // result.back() 就是"栈顶"
            if (!result.empty() && result.back() == c) {
                result.pop_back();  // 消除
            } else {
                result.push_back(c); // 压栈
            }
        }
        return result;  // 直接返回，不需要翻转！
    }
};

// ============================================================
// 解法4: 双指针原地操作 — Follow-up: O(1) 额外空间
// 时间: O(n)  空间: O(1) 额外空间（在原字符串上操作）
//
// 【思路】
// 如果面试官追问"能否不用额外空间？"，可以在原字符串上模拟栈。
//
// 用 i 作为"栈顶指针"：
//   - s[0..i] 就是栈中的内容
//   - j 遍历原字符串
//   - s[i] == s[j] → 弹栈（i--）
//   - 否则 → 压栈（s[++i] = s[j]）
//
// 最后 s[0..i] 就是结果。
// ============================================================

// 处理 "abbaca" 的双指针过程:
//
//  j=0: s="abbaca", i=-1(栈空), 压入 → s[0]='a',  i=0
//       栈: [a]
//  j=1: s[0]='a' != 'b', 压入 → s[1]='b', i=1
//       栈: [a,b]
//  j=2: s[1]='b' == 'b', 弹出 → i=0
//       栈: [a]
//  j=3: s[0]='a' == 'a', 弹出 → i=-1
//       栈: []
//  j=4: 栈空, 压入 → s[0]='c', i=0
//       栈: [c]
//  j=5: s[0]='c' != 'a', 压入 → s[1]='a', i=1
//       栈: [c,a]
//
// 结果: s.substr(0, 2) = "ca" ✓

class Solution4 {
public:
    string removeDuplicates(string s) {
        int i = -1;  // i 指向"栈顶"，-1 表示栈空
        for (int j = 0; j < (int)s.size(); j++) {
            // i >= 0 表示栈非空，且栈顶 s[i] 和当前 s[j] 相同
            if (i >= 0 && s[i] == s[j]) {
                i--;  // 弹栈（消除）
            } else {
                i++;       // 栈顶前进
                s[i] = s[j]; // 压栈
            }
        }
        return s.substr(0, i + 1);  // s[0..i] 就是结果
    }
};

// ============================================================
// 【解法对比】
//
// | 解法           | 时间   | 空间   | 需要翻转 | 代码复杂度 |
// |----------------|--------|--------|----------|------------|
// | 暴力模拟       | O(n²)  | O(n)   | 否       | 简单       |
// | stack<char>    | O(n)   | O(n)   | 是       | 中等       |
// | string当栈     | O(n)   | O(n)   | 否       | 最简       |
// | 双指针原地     | O(n)   | O(1)*  | 否       | 中等       |
//
// * 双指针修改了原字符串，如果不允许修改则需要 O(n) 拷贝
//
// 面试推荐：直接写解法3（string当栈），简洁高效易懂。
// 如果追问空间优化，补充解法4（双指针）。
//
// 【易错点】
// 1. 忘记判空：
//    ✗ if (result.back() == c)  → result为空时调用back()是UB
//    ✓ if (!result.empty() && result.back() == c)
//
// 2. 用 stack 时忘记翻转：
//    ✗ 直接弹栈拼字符串，得到 "ac" 而不是 "ca"
//    ✓ 弹栈后 reverse，或直接用 string 当栈避免
//
// 3. 双指针解法中 i 的初始值：
//    ✗ i = 0 → 第一个字符被跳过或多算
//    ✓ i = -1 → 表示栈空，第一次压栈时 i 变成 0
//
// 4. 暴力解法中跳过配对的第二个字符：
//    ✗ 发现 s[i]==s[i+1] 后只 continue，下次循环 i++ 指向 s[i+1]
//      又会把 s[i+1] 加入 next
//    ✓ 必须额外 i++ 跳过第二个字符
//
// 【面试追问】
// Q1: 这道题和括号匹配（LC 20）有什么共同点？
//     → 都是"栈匹配消除"模式。遍历序列，当前元素和栈顶满足
//       某种匹配条件就弹出，否则压入。括号匹配的条件是左右配对，
//       本题的条件是字符相同。
//
// Q2: 如果改成删除 k 个相邻相同字符呢？（LC 1209）
//     → 栈元素从 char 变成 pair<char, int>，记录字符和连续次数。
//       和栈顶字符相同时 count++，count 达到 k 时弹出。
//       核心框架不变，只是消除条件从 count==2 变成 count==k。
//
// Q3: 能否用 O(1) 额外空间完成？
//     → 可以，用双指针（解法4）。i 充当栈顶指针，在原字符串上
//       原地操作。每个字符最多被写入和覆盖一次，时间仍是 O(n)。
// ============================================================
