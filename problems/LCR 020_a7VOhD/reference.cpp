/*
 * LCR 020: 回文子串 (同主站 LeetCode 647: Palindromic Substrings)
 *
 * 【题目本质】
 * 统计字符串 s 中回文子串的总数量。
 * 不同位置的相同内容算不同子串（如 "aaa" 中 "a" 出现在 3 个位置算 3 个）。
 *
 * 【解法总览】
 * 解法1: 中心扩展 (统一编码)  — O(n^2) / O(1) — 一个循环处理所有中心 ⭐推荐
 * 解法2: 中心扩展 (分奇偶)    — O(n^2) / O(1) — 两次调用 expand 函数
 * 解法3: 动态规划             — O(n^2) / O(n^2) — dp[i][j] 记录回文状态
 */

// ============================================================
// 解法1: 中心扩展 (统一编码) — 一个循环处理 2n-1 个中心 ⭐推荐
// 时间: O(n^2)  空间: O(1)
//
// 【思路】
// 回文关于中心对称。枚举每个可能的中心，向两边扩展。
// 每次扩展成功（s[left]==s[right]）就多发现一个回文子串。
//
// 中心统一编码技巧:
//   center: 0, 1, 2, ..., 2n-2
//   left  = center / 2
//   right = left + center % 2
//
//   center=0: left=0, right=0  → expand(0,0) 奇数长度 (以 s[0] 为中心)
//   center=1: left=0, right=1  → expand(0,1) 偶数长度 (以 s[0..1] 为中心)
//   center=2: left=1, right=1  → expand(1,1) 奇数长度
//   center=3: left=1, right=2  → expand(1,2) 偶数长度
//   ...
//
// 执行过程 (s = "aaa"):
//
//   center=0: expand(0,0)
//     s[0]=='a'==s[0] ✓ → ans++ (回文"a")
//     s[-1]? 越界 → 停 → 贡献 1 个
//
//   center=1: expand(0,1)
//     s[0]=='a'==s[1]=='a' ✓ → ans++ (回文"aa")
//     s[-1]? 越界 → 停 → 贡献 1 个
//
//   center=2: expand(1,1)
//     s[1]=='a'==s[1] ✓ → ans++ (回文"a")
//     s[0]=='a'==s[2]=='a' ✓ → ans++ (回文"aaa")
//     s[-1]? 越界 → 停 → 贡献 2 个
//
//   center=3: expand(1,2)
//     s[1]=='a'==s[2]=='a' ✓ → ans++ (回文"aa")
//     s[0]? left=0 → s[0]=='a' vs s[3]? 越界 → 停 → 贡献 1 个
//
//   center=4: expand(2,2)
//     s[2]=='a'==s[2] ✓ → ans++ (回文"a")
//     s[1]? right=3 越界 → 停 → 贡献 1 个
//
//   总计: 1+1+2+1+1 = 6 ✓
// ============================================================
class Solution1 {
public:
    int countSubstrings(string s) {
        int n = s.size(), ans = 0;

        // 遍历 2n-1 个中心
        for (int center = 0; center < 2 * n - 1; center++) {
            int left = center / 2;
            int right = left + center % 2;

            // 从中心向外扩展
            while (left >= 0 && right < n && s[left] == s[right]) {
                ans++;      // 每次扩展成功 = 发现一个新的回文子串
                left--;     // 向左扩
                right++;    // 向右扩
            }
        }

        return ans;
    }
};

// ============================================================
// 解法2: 中心扩展 (分奇偶调用) — 更直观的写法
// 时间: O(n^2)  空间: O(1)
//
// 【思路】
// 和解法1逻辑完全一样，但用两次调用 expand 分别处理奇偶长度。
// 写法更容易理解，但多一次函数调用。
// ============================================================
class Solution2 {
public:
    int countSubstrings(string s) {
        int n = s.size(), ans = 0;

        for (int i = 0; i < n; i++) {
            // 以 s[i] 为中心扩展（奇数长度回文）
            ans += expand(s, i, i);
            // 以 s[i] 和 s[i+1] 之间为中心扩展（偶数长度回文）
            ans += expand(s, i, i + 1);
        }

        return ans;
    }

private:
    // 从 (left, right) 向外扩展，返回找到的回文子串数量
    int expand(const string& s, int left, int right) {
        int count = 0;
        while (left >= 0 && right < (int)s.size() && s[left] == s[right]) {
            count++;
            left--;
            right++;
        }
        return count;
    }
};

// ============================================================
// 解法3: 动态规划 — dp[i][j] 记录 s[i..j] 是否为回文
// 时间: O(n^2)  空间: O(n^2)
//
// 【思路】
// 定义 dp[i][j] = true 表示 s[i..j] 是回文。
//
// 状态转移:
//   dp[i][j] = (s[i] == s[j]) && (j - i < 2 || dp[i+1][j-1])
//
//   三种情况:
//     len=1 (j==i): 单字符一定是回文
//     len=2 (j==i+1): s[i]==s[j] 即为回文
//     len>=3: s[i]==s[j] 且 s[i+1..j-1] 也是回文
//
// 遍历顺序: 按子串长度从小到大（保证 dp[i+1][j-1] 先于 dp[i][j] 计算）
//
// DP 表 (s = "aaa"):
//
//      j→  0(a)  1(a)  2(a)
//  i↓
//  0(a)     T     T     T     ← dp[0][0]="a"✓, dp[0][1]="aa"✓, dp[0][2]="aaa"✓
//  1(a)           T     T     ← dp[1][1]="a"✓, dp[1][2]="aa"✓
//  2(a)                 T     ← dp[2][2]="a"✓
//
//  T 的个数 = 6 ✓
// ============================================================
class Solution3 {
public:
    int countSubstrings(string s) {
        int n = s.size(), ans = 0;
        // dp[i][j] = true 表示 s[i..j] 是回文
        vector<vector<bool>> dp(n, vector<bool>(n, false));

        // 按子串长度从小到大遍历
        // 保证计算 dp[i][j] 时 dp[i+1][j-1] 已经算过
        for (int len = 1; len <= n; len++) {
            for (int i = 0; i <= n - len; i++) {
                int j = i + len - 1;

                if (s[i] == s[j]) {
                    // len<=2: "a" 或 "aa"，s[i]==s[j] 就够
                    // len>=3: 还需要中间 s[i+1..j-1] 也是回文
                    if (len <= 2 || dp[i + 1][j - 1]) {
                        dp[i][j] = true;
                        ans++;
                    }
                }
            }
        }

        return ans;
    }
};

