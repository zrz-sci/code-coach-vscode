// 【解法对比】
//
// | 解法          | 时间    | 空间    | 代码复杂度 | 面试推荐 |
// |--------------|---------|---------|-----------|---------|
// | 中心扩展统一  | O(n^2) | O(1)    | 简洁       | ⭐⭐⭐  |
// | 中心扩展分奇偶| O(n^2) | O(1)    | 直观       | ⭐⭐⭐  |
// | 动态规划      | O(n^2) | O(n^2)  | 中等       | ✓ 备选  |
// | Manacher     | O(n)   | O(n)    | 复杂       | 加分项   |
//
// 面试策略:
//   1. 直接写中心扩展（简洁、O(1) 空间）
//   2. 和 LC5 对比：框架一样，只是把"记录最长"改成"累加计数"
//   3. 面试官追问 DP → 描述状态定义和转移方程
//   4. 面试官问 O(n) → 描述 Manacher 思路
//
// ============================================================
// 【易错点】
//
// 1. 忘记偶数长度回文:
//    ✗ 只调用 expand(i, i) → 漏掉 "aa" 类回文
//    ✓ 必须同时 expand(i, i) 和 expand(i, i+1)
//
// 2. 统一编码时 right 计算错误:
//    ✗ right = center / 2 + 1 → 偶数center时跳过了自身
//    ✓ right = left + center % 2
//
// 3. DP 遍历顺序错误:
//    ✗ for(i=0→n) for(j=i→n) → dp[i+1][j-1] 可能还没算
//    ✓ 按子串长度从 1 到 n 遍历
//
// 4. while 循环中忘记 count:
//    ✗ 只在 while 结束后 count 一次 → 只算了最长的
//    ✓ 每次 s[left]==s[right] 就 count++ → 算了所有中间长度
// ============================================================

// ============================================================
// 【面试追问】
//
// Q1: 本题改成「求最长回文子串」（LC5）该怎么改？
// A1: 框架完全一样（中心扩展），只需把 count++ 改成：
//     每次扩展成功时记录 (left, right)，取最长的 right-left+1。
//     最终用 s.substr(bestLeft, bestLen) 返回子串。
//     本题是「计数」，LC5 是「求最值」，核心扩展逻辑不变。
//
// Q2: 如果字符串很长（n=10^5），O(n^2) 不够快怎么办？
// A2: Manacher 算法可以 O(n) 解决：
//     1. 插入分隔符 "#" 将奇偶统一：abc → #a#b#c#
//     2. 维护 p[i] = 以 i 为中心的最长回文半径
//     3. 利用已知回文的对称性跳过重复计算
//     回文子串总数 = sum(ceil(p[i]/2))。
//     面试中能描述思路即可，一般不要求手写。
//
// Q3: 如果要求「回文子序列」的数量（LC730）呢？
// A3: 子串要求连续，子序列不要求连续，必须用 DP：
//     dp[i][j] = s[i..j] 中回文子序列的数量
//     转移: if s[i]==s[j]: dp[i][j] = dp[i+1][j] + dp[i][j-1] + 1
//           else:          dp[i][j] = dp[i+1][j] + dp[i][j-1] - dp[i+1][j-1]
//     时间 O(n^2)，空间 O(n^2)，中心扩展法不再适用。
// ============================================================
