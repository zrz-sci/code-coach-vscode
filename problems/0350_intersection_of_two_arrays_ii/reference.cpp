/*
 * LeetCode 350: Intersection of Two Arrays II (两个数组的交集 II)
 *
 * 【题目本质】
 * 给两个整数数组，返回它们的交集。结果中每个元素的出现次数
 * 等于该元素在两个数组中各出现次数的较小值。
 * 核心问题：如何高效地做"带计数的匹配"？
 *
 * 【解法总览】
 * 解法1: 哈希表计数   — O(m+n) / O(min(m,n)) — 面试首选
 * 解法2: 排序+双指针  — O(mlogm+nlogn) / O(1) — Follow-up已排序场景
 */

// ============================================================
// 解法1: 哈希表计数 — 面试首选 ⭐
// 时间: O(m+n)  空间: O(min(m,n))
//
// 【思路】
// 对较小的数组建频率哈希表，然后遍历另一个数组：
//   如果当前元素在哈希表中且计数 > 0，加入结果，计数减 1。
//
// 为什么要在较小数组上建哈希表？
//   哈希表的大小 = 数组中不同元素的个数，最大不超过数组长度。
//   选较小数组建表，保证空间 O(min(m, n))。
//
// 示例: nums1 = [4,9,5], nums2 = [9,4,9,8,4]
//   Step1: freq = {4:1, 9:1, 5:1}  (对较小的 nums1 建表)
//   Step2: 遍历 nums2:
//     9 → freq[9]=1>0 → 收集, freq[9]=0
//     4 → freq[4]=1>0 → 收集, freq[4]=0
//     9 → freq[9]=0   → 跳过
//     8 → freq无8     → 跳过
//     4 → freq[4]=0   → 跳过
//   结果: [9, 4] ✓
// ============================================================
class Solution1 {
public:
    vector<int> intersect(vector<int>& nums1, vector<int>& nums2) {
        // 确保 nums1 是较小的数组，优化哈希表空间
        if (nums1.size() > nums2.size()) {
            return intersect(nums2, nums1);
        }

        // Step 1: 对较小数组建频率表
        unordered_map<int, int> freq;
        for (int x : nums1) {
            freq[x]++;
        }

        // Step 2: 遍历较大数组，匹配并消耗计数
        vector<int> result;
        for (int x : nums2) {
            // 必须检查 > 0，不能只检查 count(x)
            // 因为计数可能已经被消耗到 0
            if (freq[x] > 0) {
                result.push_back(x);
                freq[x]--;  // 消耗一个匹配名额
            }
        }

        return result;
    }
};

// ============================================================
// 解法2: 排序 + 双指针
// 时间: O(m log m + n log n)  空间: O(1) (如果允许修改原数组)
//
// 【思路】
// 两个数组排序后，用双指针同步扫描，类似归并排序的合并步骤。
// - 值相等 → 收集，双指针同时右移
// - 值不等 → 较小值的指针右移（追赶较大值）
//
// 为什么不会漏掉匹配？
//   当 nums1[i] < nums2[j] 时，nums1[i] 不可能匹配
//   nums2[j] 或之后的元素（有序递增），安全跳过。
//
// 示例: nums1 = [1,2,2,1], nums2 = [2,2]
//   排序后: [1,1,2,2] 和 [2,2]
//   i=0,j=0: 1 < 2 → i++
//   i=1,j=0: 1 < 2 → i++
//   i=2,j=0: 2 == 2 → 收集2, i++, j++
//   i=3,j=1: 2 == 2 → 收集2, i++, j++
//   结束 → [2,2] ✓
//
// 【Follow-up 1 场景】
// 如果数组已排序，直接跳过排序步骤，
// 双指针部分就是 O(m+n) 时间 O(1) 空间，比哈希表更优。
// ============================================================
class Solution2 {
public:
    vector<int> intersect(vector<int>& nums1, vector<int>& nums2) {
        // 排序两个数组
        sort(nums1.begin(), nums1.end());
        sort(nums2.begin(), nums2.end());

        vector<int> result;
        int i = 0, j = 0;
        int m = nums1.size(), n = nums2.size();

        while (i < m && j < n) {
            if (nums1[i] < nums2[j]) {
                // nums1 当前值太小，右移追赶
                i++;
            } else if (nums1[i] > nums2[j]) {
                // nums2 当前值太小，右移追赶
                j++;
            } else {
                // 相等 → 收集到结果中
                result.push_back(nums1[i]);
                // 两个指针同时右移！不能只移一个
                i++;
                j++;
            }
        }

        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间            | 空间          | 适用场景                    |
// |-------------|----------------|--------------|---------------------------|
// | 哈希表计数   | O(m+n)         | O(min(m,n))  | 通用首选，特别是m<<n时       |
// | 排序+双指针  | O(mlogm+nlogn) | O(1)*        | 数组已排序时最优             |
//
// * O(1) 空间前提：允许修改原数组
//
// ============================================================
// 【Follow-up 详解】
//
// Q1: 如果给定的数组已经排好序呢？
//     直接用解法2的双指针部分，跳过排序。
//     时间 O(m+n)，空间 O(1)。比哈希表省了 O(min(m,n)) 空间。
//
// Q2: 如果 nums1 的大小比 nums2 小很多，哪种方法更优？
//     哈希表法：在 nums1(小数组) 上建表，空间 O(m) 很小。
//     遍历 nums2 时间 O(n)，总时间 O(m+n)。
//     排序法：排序 nums2 代价 O(n log n) 更大。
//     进一步优化：对小数组排序 O(m log m)，
//     对大数组每个元素二分查找 O(n log m)，总 O((m+n) log m)。
//
// Q3: 如果 nums2 在磁盘上，内存有限怎么办？
//     方法1: nums1 建哈希表（假设能装下），分块读 nums2 匹配。
//     方法2: 外排序两个数组后，双指针分块读取比较。
//     方法3: MapReduce 按哈希值分桶，逐桶处理。
//
// ============================================================
// 【易错点】
//
// 1. 用 set 代替 map (丢失重复计数):
//    ✗ unordered_set → [2,2]∩[2,2] 只返回 [2]
//    ✓ unordered_map<int,int> 记录频率
//
// 2. 只检查 count 不检查值>0:
//    ✗ if (freq.count(x))  → 计数减到0后仍然匹配
//    ✓ if (freq[x] > 0)
//
// 3. 双指针相等时只移一个指针:
//    ✗ nums1[i]==nums2[j] 后只 i++ → j 下次还匹配同一个元素
//    ✓ 相等时 i++ 且 j++ 同时移动
//
