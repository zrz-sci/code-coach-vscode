/*
 * LeetCode 108: 将有序数组转换为二叉搜索树
 * (Convert Sorted Array to Binary Search Tree)
 *
 * 【题目本质】
 * 升序数组 = BST 的中序遍历。要从中序遍历还原一棵高度平衡的 BST。
 * 核心：每次选中间元素作为根（分治），使左右子树节点数尽量相等。
 *
 * 【解法总览】
 * 解法1: 递归分治      — O(n) / O(log n) — 最自然直观 ⭐面试首选
 * 解法2: 迭代(栈模拟)  — O(n) / O(log n) — 展示不用递归的能力
 */

// ============================================================
// 解法1: 递归分治 — 选中间元素为根，递归构建左右子树
// 时间: O(n)     — 每个元素恰好被访问一次
// 空间: O(log n) — 递归深度 = 树的高度 = log n
//
// 【思路】
// 升序数组天然就是 BST 中序遍历的结果。
// 要平衡 → 让左右子树节点数尽量相等 → 选中间元素当根。
// 左半部分递归构建左子树，右半部分递归构建右子树。
// 这就是分治：分解(选中点) → 递归(处理左右) → 合并(连接到根)。
//
// 以 nums = [-10, -3, 0, 5, 9] 为例:
//
//  数组索引: [0   1   2   3   4]
//  数组值:  [-10, -3, 0,  5,  9]
//
//  第1层: left=0, right=4, mid=2 → 根=0
//         左区间[0,1]          右区间[3,4]
//
//  第2层: left=0,right=1,mid=0  left=3,right=4,mid=3
//         根=-10                根=5
//         左[空] 右[1,1]       左[空] 右[4,4]
//
//  第3层: left=1,right=1,mid=1  left=4,right=4,mid=4
//         根=-3                 根=9
//
//  构建结果:
//            0
//           / \
//        -10    5
//          \     \
//          -3     9
//
// ============================================================
class Solution1 {
public:
    TreeNode* sortedArrayToBST(vector<int>& nums) {
        return build(nums, 0, (int)nums.size() - 1);
    }

private:
    // 用 nums[left..right] 闭区间构建平衡 BST，返回根节点
    TreeNode* build(vector<int>& nums, int left, int right) {
        // 终止条件：区间为空，对应空子树
        if (left > right) return nullptr;

        // 选中间位置作为根 —— 保证左右子树节点数差 ≤ 1
        // 用 left + (right - left) / 2 而不是 (left + right) / 2 防溢出
        int mid = left + (right - left) / 2;
        TreeNode* root = new TreeNode(nums[mid]);

        // 左半 [left, mid-1] 递归构建左子树
        // 注意是 mid-1，因为 mid 已经被选为根了
        root->left = build(nums, left, mid - 1);

        // 右半 [mid+1, right] 递归构建右子树
        root->right = build(nums, mid + 1, right);

        return root;
    }
};

// ============================================================
// 解法2: 迭代 (栈模拟分治) — 手动管理栈替代递归
// 时间: O(n)     — 每个元素恰好被处理一次
// 空间: O(log n) — 显式栈最大深度 = 树高
//
// 【思路】
// 递归的本质是系统调用栈保存了每层的 (left, right) 区间。
// 迭代版本用自己的栈来模拟：
//   - 栈中存 (当前节点指针, 区间左端, 区间右端)
//   - 每次弹出一个元素，计算该区间的 mid，创建左右子节点
//   - 如果子区间非空，把子节点和对应子区间压入栈
//
// 这样每个节点在创建时就被正确地挂到了父节点上。
//
// 处理过程 (以 [-10,-3,0,5,9] 为例):
//
//  初始: 创建根 root=0, 栈: {(root, 0, 4)}
//
//  弹出 (root=0, 0, 4):  mid=2
//    左区间[0,1]: lmid=0, root->left = -10, 入栈(-10, 0, 1)
//    右区间[3,4]: rmid=3, root->right = 5,  入栈(5, 3, 4)
//
//  弹出 (5, 3, 4):  mid=3
//    左区间[空]
//    右区间[4,4]: rmid=4, 5->right = 9, 入栈(9, 4, 4)
//
//  弹出 (9, 4, 4):  mid=4, 左右都空 → 不入栈
//
//  弹出 (-10, 0, 1):  mid=0
//    左区间[空]
//    右区间[1,1]: rmid=1, -10->right = -3, 入栈(-3, 1, 1)
//
//  弹出 (-3, 1, 1):  mid=1, 左右都空 → 不入栈
//
//  栈空, 结束。
// ============================================================
class Solution2 {
public:
    TreeNode* sortedArrayToBST(vector<int>& nums) {
        if (nums.empty()) return nullptr;

        int n = (int)nums.size();
        int mid = n / 2;
        TreeNode* root = new TreeNode(nums[mid]);

        // 栈中存: (当前节点, 该节点对应的区间左端, 区间右端)
        stack<tuple<TreeNode*, int, int>> stk;
        stk.push({root, 0, n - 1});

        while (!stk.empty()) {
            auto [node, left, right] = stk.top();
            stk.pop();

            int m = left + (right - left) / 2;

            // 处理左子区间 [left, m-1]
            if (left <= m - 1) {
                int lmid = left + (m - 1 - left) / 2;
                node->left = new TreeNode(nums[lmid]);
                stk.push({node->left, left, m - 1});
            }
            // 否则 node->left 保持 nullptr

            // 处理右子区间 [m+1, right]
            if (m + 1 <= right) {
                int rmid = (m + 1) + (right - m - 1) / 2;
                node->right = new TreeNode(nums[rmid]);
                stk.push({node->right, m + 1, right});
            }
            // 否则 node->right 保持 nullptr
        }

        return root;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度         | 解法1 递归分治    | 解法2 迭代栈模拟  |
// |-------------|------------------|-------------------|
// | 时间         | O(n)             | O(n)              |
// | 空间         | O(log n) 递归栈  | O(log n) 显式栈   |
// | 代码量       | ~10行            | ~25行             |
// | 可读性       | ⭐⭐⭐ 极好      | ⭐⭐ 一般          |
// | 面试推荐     | ✅ 首选          | 追问时展示         |
//
// 结论: 递归版代码简洁、逻辑清晰，面试首选。
//       迭代版作为"如果面试官追问能否不用递归"的储备。
//
// ============================================================
// 【易错点】
//
// 1. mid 计算溢出:
//    ✗ int mid = (left + right) / 2;         // left+right 可能溢出
//    ✓ int mid = left + (right - left) / 2;  // 安全
//
// 2. 右边界传错:
//    ✗ build(nums, 0, nums.size());           // 开区间，且 size() 是 unsigned
//    ✓ build(nums, 0, (int)nums.size() - 1);  // 闭区间 [0, n-1]
//    注意: 如果 nums 为空, size()-1 对 unsigned 会下溢!
//          所以要么先判空，要么强转 int。
//
// 3. 递归区间包含 mid:
//    ✗ root->left = build(nums, left, mid);      // mid 已经是根了，不应再放入左子树
//    ✓ root->left = build(nums, left, mid - 1);   // 排除 mid
//
// 4. 空数组没有特殊处理:
//    递归版没问题 (left=0, right=-1 直接返回 nullptr)
//    迭代版需要开头判空，否则 n-1 会下溢
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 时间复杂度是多少？为什么？
// A1: O(n)。每个元素恰好被访问一次用来创建节点。
//     递归深度 O(log n)，每层合计访问的元素数 = n，所以总共 O(n)。
//
// Q2: 如果输入不是数组而是有序链表怎么办？(LeetCode 109)
// A2: 链表无法 O(1) 访问中间元素。三种方案:
//     - 链表转数组，复用本题解法。O(n) 时间 + O(n) 额外空间。
//     - 快慢指针找中点。O(n log n) 时间 + O(log n) 空间。
//     - 模拟中序遍历：先递归建左子树(同时链表指针前进)，
//       然后取当前链表节点建根，再递归建右子树。O(n) + O(log n)。
//
// Q3: 答案唯一吗？如果要求返回所有可能的平衡 BST 呢？
// A3: 不唯一。当数组长度为偶数时，中间位置可选偏左或偏右。
//     要枚举所有可能，在 mid 选择处做分支 → 变成回溯题。
//     类似 LeetCode 95 (不同的二叉搜索树 II)。
//
// 【相关题型】
// - 109. 有序链表转换二叉搜索树: 输入从数组变链表，
//        复用同样的分治框架，区别在找中点方式(快慢指针)。
// - 95.  不同的二叉搜索树 II: 复用分治框架，
//        区别: 本题只选一个 mid，95 循环枚举每个可能的根。
// - 1382. 将二叉搜索树变平衡: 先中序遍历得到有序数组，
//         然后直接调用本题解法。两步组合。
// ============================================================
