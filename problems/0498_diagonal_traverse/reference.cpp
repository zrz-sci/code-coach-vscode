/*
 * LeetCode 498: 对角线遍历 (Diagonal Traverse)
 *
 * 【题目本质】
 * 按锯齿形对角线顺序遍历矩阵。核心观察：同一对角线上 r+c 相等，
 * 偶数对角线向右上走，奇数对角线向左下走。
 *
 * 【解法总览】
 * 解法1: 收集对角线+翻转 — O(m·n) / O(min(m,n)) — 直觉清晰
 * 解法2: 直接模拟       — O(m·n) / O(1)          — 面试首选(空间最优)
 */

// ============================================================
// 解法1: 收集对角线 + 翻转
// 时间: O(m·n)  空间: O(min(m,n)) 临时对角线数组
//
// 【思路】
// 矩阵中同一条对角线上的元素满足 r + c = 常数。
// 我们按 d = 0, 1, ..., m+n-2 枚举每条对角线，
// 收集该对角线上所有元素，偶数对角线翻转后追加到结果。
//
//  矩阵 3x3 的对角线分组:
//     c=0  c=1  c=2
// r=0  1    2    3      d=0: {1}           → 偶数, 翻转 → [1]
// r=1  4    5    6      d=1: {2, 4}        → 奇数, 不翻 → [2, 4]
// r=2  7    8    9      d=2: {3, 5, 7}     → 偶数, 翻转 → [7, 5, 3]
//                       d=3: {6, 8}        → 奇数, 不翻 → [6, 8]
//                       d=4: {9}           → 偶数, 翻转 → [9]
//
//  拼接结果: [1, 2, 4, 7, 5, 3, 6, 8, 9] ✓
// ============================================================
class Solution1 {
public:
    vector<int> findDiagonalOrder(vector<vector<int>>& mat) {
        int m = mat.size(), n = mat[0].size();
        vector<int> result;
        result.reserve(m * n);
        
        for (int d = 0; d <= m + n - 2; d++) {
            // 每条对角线上 r+c=d
            // r 的有效范围: max(0, d-n+1) <= r <= min(d, m-1)
            // 因为 c = d-r 需要满足 0 <= c <= n-1 → r <= d 且 r >= d-n+1
            int r_min = max(0, d - n + 1);
            int r_max = min(d, m - 1);
            
            if (d % 2 == 0) {
                // 偶数对角线: 右上方向 → r 从大到小
                for (int r = r_max; r >= r_min; r--) {
                    result.push_back(mat[r][d - r]);
                }
            } else {
                // 奇数对角线: 左下方向 → r 从小到大
                for (int r = r_min; r <= r_max; r++) {
                    result.push_back(mat[r][d - r]);
                }
            }
        }
        
        return result;
    }
};

// ============================================================
// 解法2: 直接模拟 — 面试首选
// 时间: O(m·n)  空间: O(1) 额外空间
//
// 【思路】
// 维护当前位置 (r, c) 和方向 (向右上 or 向左下)。
// 每步先记录当前元素，然后尝试按当前方向移动。
// 如果越界，就转向并调整位置。
//
// 边界转向规则（这是本题的核心难点）:
//
// 向右上走 (r-1, c+1) 越界:
//   Case A: c == n-1 → 不能再右了，只能下移 r++ → 转向左下
//   Case B: r == 0   → 不能再上了，只能右移 c++ → 转向左下
//   ⚠️ 先检查A再检查B！因为角落 (0,n-1) 两个都触发，优先下移
//
// 向左下走 (r+1, c-1) 越界:
//   Case C: r == m-1 → 不能再下了，只能右移 c++ → 转向右上
//   Case D: c == 0   → 不能再左了，只能下移 r++ → 转向右上
//   ⚠️ 先检查C再检查D！因为角落 (m-1,0) 两个都触发，优先右移
//
// 3x3 矩阵完整模拟:
//  Step  pos    val  方向   边界情况
//  0    (0,0)   1    ↗     r==0 → c++, 转↙
//  1    (0,1)   2    ↙     正常移动
//  2    (1,0)   4    ↙     c==0 → r++, 转↗
//  3    (2,0)   7    ↗     正常移动
//  4    (1,1)   5    ↗     正常移动
//  5    (0,2)   3    ↗     c==n-1 → r++, 转↙
//  6    (1,2)   6    ↙     正常移动
//  7    (2,1)   8    ↙     r==m-1 → c++, 转↗
//  8    (2,2)   9    ↗     结束
//
//  结果: [1, 2, 4, 7, 5, 3, 6, 8, 9] ✓
// ============================================================
class Solution2 {
public:
    vector<int> findDiagonalOrder(vector<vector<int>>& mat) {
        int m = mat.size(), n = mat[0].size();
        vector<int> result(m * n);
        
        int r = 0, c = 0;
        bool goingUp = true; // true = 向右上 (r--, c++)
        
        for (int i = 0; i < m * n; i++) {
            result[i] = mat[r][c];
            
            if (goingUp) {
                // 向右上走 (r-1, c+1)
                if (c == n - 1) {
                    // Case A: 碰右边界 → 下移, 转向
                    // 为什么先检查这个？角落(0, n-1)处 r==0 和 c==n-1 同时成立，
                    // 如果先执行 c++ 会越界，所以必须先处理 c==n-1 的情况
                    r++;
                    goingUp = false;
                } else if (r == 0) {
                    // Case B: 碰上边界 → 右移, 转向
                    c++;
                    goingUp = false;
                } else {
                    // 未越界，正常右上移动
                    r--;
                    c++;
                }
            } else {
                // 向左下走 (r+1, c-1)
                if (r == m - 1) {
                    // Case C: 碰下边界 → 右移, 转向
                    // 同理，角落(m-1, 0)处需要优先处理 r==m-1
                    c++;
                    goingUp = true;
                } else if (c == 0) {
                    // Case D: 碰左边界 → 下移, 转向
                    r++;
                    goingUp = true;
                } else {
                    // 未越界，正常左下移动
                    r++;
                    c--;
                }
            }
        }
        
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 特性         | 解法1 收集+翻转      | 解法2 直接模拟     |
// |-------------|---------------------|-------------------|
// | 时间         | O(m·n)              | O(m·n)            |
// | 额外空间     | O(min(m,n))         | O(1)              |
// | 代码复杂度   | 低                   | 中（边界多）       |
// | 出错概率     | 低                   | 中                 |
// | 面试推荐     | 作为思路展示         | 作为最终解法 ⭐     |
//
// 面试建议：先讲解法1的思路（r+c 分组），再写解法2的代码。
//
// 【易错点】
//
// 1. 边界检查顺序：
//    ✗ 向右上时先 if (r == 0) { c++; } else if (c == n-1) { r++; }
//      → 在 (0, n-1) 处执行 c++，c 变成 n，后续 mat[r][c] 越界！
//    ✓ 必须先检查 c == n-1，再检查 r == 0
//
// 2. 收集法的 r 范围推导：
//    ✗ r_min = max(0, d - n)  → 当 d = n 时，r_min = 0，
//      但 c = d - 0 = n 越界！应该是 d - (n-1) = d - n + 1
//    ✓ r_min = max(0, d - n + 1)
//
// 3. 偶奇翻转方向搞反：
//    ✗ d=0 时不翻转 → 结果: [1, 4, 2, ...]（先向左下走了）
//    ✓ d=0（偶数）应该向右上走。可以通过 d=0 只有元素 [1] 来验证正确性。
//
// 4. 1×1 矩阵的边界：
//    ✗ 模拟法中没处理 m*n==1 的情况（实际上循环只执行一次就结束，不会出错）
//    ✓ 不需要特判，但要确认循环逻辑在只有一个元素时不会越界
//
// 【面试追问】
//
// Q1（基础理解）: 同一对角线上的元素有什么数学特征？
// → r + c 相等。第 d 条对角线上所有元素满足 r + c = d。
//
// Q2（优化）: 收集法需要 O(min(m,n)) 额外空间，能否优化到 O(1)？
// → 可以，就是解法2的直接模拟法。不需要存储中间对角线，
//   直接在矩阵上走并记录到结果数组。
//
// Q3（变体）: 如果矩阵是稀疏的（大部分是0），且只要非零元素的对角线遍历结果？
// → 用哈希表 map<int, vector<pair<int,int>>> 按 r+c 分组存非零元素坐标，
//   然后按 key 从小到大遍历，偶数 key 翻转。时间复杂度 O(k log k)，k 为非零元素数。
//
// Q4（扩展）: LeetCode 1424 对角线遍历 II 中矩阵行不等长，怎么处理？
// → 思路一样：按 r+c 分组。但由于行不等长，遍历时需要注意
//   每行的长度不同，用 map<int, vector<int>> 收集即可。
// ============================================================
