/*
 * LeetCode 114: Flatten Binary Tree to Linked List
 * (二叉树展开为链表)
 *
 * 【题目本质】
 * 将二叉树原地展开为前序遍历顺序的单链表（用 right 指针连接）。
 *
 * 原始:              展开后:
 *       1              1
 *      / \              \
 *     2   5              2
 *    / \   \              \
 *   3   4   6              3
 *                           \
 *                            4
 *                             \
 *                              5
 *                               \
 *                                6
 *
 * 【解法总览】
 * 解法1: 前序遍历 + 重新连接  — O(n) / O(n) — 最直觉
 * 解法2: 反向后序递归          — O(n) / O(n) — 代码最短 ⭐
 * 解法3: 前序迭代 + 栈         — O(n) / O(n) — 最直观
 * 解法4: Morris 式 O(1) 空间  — O(n) / O(1) — 最优 ⭐⭐
 */



// ============================================================
// 解法1: 前序遍历 + 重新连接
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 最直接的两步走：
// 1. 前序遍历二叉树，把所有节点按顺序存入数组
// 2. 按数组顺序重新连接：每个节点的 right 指向下一个，left 置空
//
// 优点：逻辑清晰，不容易出错。
// 缺点：需要 O(n) 额外空间存储节点列表。
// ============================================================
class Solution1 {
public:
    void flatten(TreeNode* root) {
        vector<TreeNode*> nodes;
        preorder(root, nodes);
        // 按前序顺序重新连接
        for (int i = 0; i < (int)nodes.size() - 1; i++) {
            nodes[i]->left = nullptr;
            nodes[i]->right = nodes[i + 1];
        }
    }

private:
    void preorder(TreeNode* node, vector<TreeNode*>& nodes) {
        if (!node) return;
        nodes.push_back(node);
        preorder(node->left, nodes);
        preorder(node->right, nodes);
    }
};

// ============================================================
// 解法2: 反向后序递归（右 → 左 → 根）
// 时间: O(n)  空间: O(n) 递归栈
//
// 【思路】
// 前序遍历是 "根→左→右"，其逆序是 "右→左→根"。
// 按这个逆序处理每个节点：处理到节点 X 时，
// 前序中排在 X 后面的所有节点已经被串成链表（存在 prev 中）。
// 所以直接 X.right = prev 即可。
//
// 处理顺序（以示例为例）:
//   6 → 5 → 4 → 3 → 2 → 1
//
//   处理6: prev=null  → 6.right=null,    prev=6
//   处理5: prev=6     → 5.right=6,       prev=5
//   处理4: prev=5→6   → 4.right=5,       prev=4
//   处理3: prev=4→5→6 → 3.right=4,       prev=3
//   处理2: prev=3→..  → 2.right=3,       prev=2
//   处理1: prev=2→..  → 1.right=2,       prev=1
//
// 最终: 1→2→3→4→5→6 ✓
//
// 为什么是"右→左→根"而不是"左→右→根"（标准后序）？
//   前序: 根→左→右   反转: 右→左→根
//   标准后序: 左→右→根  反转: 根→右→左
//   我们需要前序的逆序，所以用"右→左→根"。
// ============================================================
class Solution2 {
public:
    TreeNode* prev = nullptr;

    void flatten(TreeNode* root) {
        if (!root) return;
        flatten(root->right);  // 先递归处理右子树
        flatten(root->left);   // 再递归处理左子树
        root->right = prev;    // 当前节点的 right 指向之前处理好的链表
        root->left = nullptr;  // left 必须置空
        prev = root;           // 更新 prev 为当前节点
    }
};

// ============================================================
// 解法3: 前序迭代 + 栈
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 用栈模拟前序遍历。弹出节点时：
//   1. 先压右子节点再压左子节点（保证左先弹出 = 前序顺序）
//   2. 当前节点的 right 指向栈顶（即前序中的下一个节点）
//   3. 当前节点的 left 置空
//
// 栈模拟过程:
//   初始: 栈=[1]
//   弹出1: 压5,压2 → 栈=[5,2], 1.right=2
//   弹出2: 压4,压3 → 栈=[5,4,3], 2.right=3
//   弹出3: 无子节点 → 栈=[5,4], 3.right=4
//   弹出4: 无子节点 → 栈=[5], 4.right=5
//   弹出5: 压6 → 栈=[6], 5.right=6
//   弹出6: 栈空, 6.right=null
// ============================================================
class Solution3 {
public:
    void flatten(TreeNode* root) {
        if (!root) return;
        stack<TreeNode*> stk;
        stk.push(root);

        while (!stk.empty()) {
            TreeNode* node = stk.top();
            stk.pop();

            // 先右后左入栈，保证左先弹出（前序：根→左→右）
            if (node->right) stk.push(node->right);
            if (node->left) stk.push(node->left);

            // 当前节点连到下一个前序节点
            if (!stk.empty()) {
                node->right = stk.top();
            }
            node->left = nullptr;
        }
    }
};

// ============================================================
// 解法4: Morris 式 O(1) 空间 — 最优解 ⭐⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 对于每个有左子树的节点 curr：
//   1. 找到 curr 左子树的最右节点 rightmost
//      （即前序遍历中左子树的最后一个节点）
//   2. 把 curr 的右子树挂到 rightmost 的右边
//      （因为前序中 rightmost 的下一个就是 curr 的右子树根）
//   3. 把 curr 的左子树移到 curr 的右边，左边置空
//   4. curr 移到 curr->right 继续处理
//
// 图解过程:
//
// 初始:                Step1(处理1):      Step2(处理2):
//       1                  1                  1
//      / \                  \                  \
//     2   5                  2                  2
//    / \   \                / \                  \
//   3   4   6              3   4                  3
//                               \                  \
//                                5                  4
//                                 \                  \
//                                  6                  5
//                                                      \
//                                                       6
//
// Step3(处理3): 3没有左子树，跳过
// Step4(处理4): 4没有左子树，跳过
// Step5(处理5): 5没有左子树，跳过
// 完成! 1→2→3→4→5→6
//
// 时间 O(n) 的证明:
//   看起来 while (rightmost->right) 是嵌套循环，但：
//   二叉树共 n-1 条边，每条边在"找最右节点"时最多被走一次，
//   再加上主循环走 n 步，总操作 <= 2(n-1) + n = O(n)。
// ============================================================
class Solution4 {
public:
    void flatten(TreeNode* root) {
        TreeNode* curr = root;
        while (curr) {
            if (curr->left) {
                // 1. 找到左子树的最右节点
                TreeNode* rightmost = curr->left;
                while (rightmost->right) {
                    rightmost = rightmost->right;
                }
                // 2. 把当前节点的右子树挂到左子树的最右节点后面
                rightmost->right = curr->right;
                // 3. 左子树移到右边，左边置空
                curr->right = curr->left;
                curr->left = nullptr;
            }
            // 4. 移到下一个节点
            curr = curr->right;
        }
    }
};

// ============================================================
// 【解法对比】
//
// | 解法          | 时间  | 空间  | 代码量 | 直观度 |
// |--------------|-------|-------|--------|--------|
// | 前序+重连     | O(n)  | O(n)  | 中     | 高     |
// | 反向后序递归  | O(n)  | O(n)  | 最少   | 需理解 |
// | 前序迭代+栈   | O(n)  | O(n)  | 中     | 高     |
// | Morris式     | O(n)  | O(1)  | 少     | 需理解 |
//
// ============================================================
// 【易错点】
//
// 1. 反向后序递归顺序:
//    ✗ flatten(left); flatten(right); → 标准后序，顺序错
//    ✓ flatten(right); flatten(left); → 前序的逆序
//
// 2. 忘记 left 置空:
//    ✗ 只设 right，不管 left → 展开后 left 不是 null
//    ✓ 每个节点都要 node->left = nullptr
//
// 3. 栈压入顺序:
//    ✗ 先压左再压右 → 右先弹出，变成"根右左"
//    ✓ 先压右再压左 → 左先弹出，正确前序"根左右"
//
// 4. Morris 式找最右节点:
//    ✗ 从 curr 开始找 → 可能死循环
//    ✓ 从 curr->left 开始，沿 right 走到底
//
// 5. 递归中 prev 的作用域:
//    ✗ prev 定义为局部变量 → 递归间不共享
//    ✓ prev 定义为类成员变量
//
// ============================================================
// 【面试追问】
//
// Q1: 三种解法怎么选？
//     O(1)空间 → Morris式; 代码最短 → 反向后序递归;
//     最直观 → 前序迭代+栈
//
// Q2: Morris式时间复杂度为什么是 O(n)？
//     二叉树 n-1 条边，找最右节点时每条边最多被走一次。
//     主循环走 n 步。总计 <= 2(n-1) + n = O(n)。
//
// Q3: 如果按中序展开？
//     改遍历顺序即可。递归法改为中序逆序处理，
//     Morris法改用标准 Morris 中序遍历思路。
