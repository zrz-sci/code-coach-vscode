/*
 * 521. Longest Uncommon Subsequence I
 * 难度: Easy | 标签: String
 *
 * 【题目本质】
 * 脑筋急转弯题。两个字符串相等则无特殊序列(-1)，
 * 不等则较长者本身就是答案。
 *
 * 【解法总览】
 * Solution1: 直接比较 — O(n) 时间, O(1) 空间 ⭐⭐⭐
 */

// ===================== Solution1: 直接比较 =====================
// 如果 a == b，任何子序列都是共同的 → -1
// 如果 a != b，较长者不可能是较短者的子序列 → max(len_a, len_b)
class Solution1 {
public:
    int findLUSlength(string a, string b) {
        if (a == b) return -1;
        return max(a.size(), b.size());
    }
};

