/*
 * LeetCode 898: Bitwise ORs of Subarrays (子数组按位或操作)
 *
 * 【题目本质】
 * 求所有非空子数组的 OR 值有多少个不同的。
 * 核心观察：OR 只加 bit 不减 bit，所以以每个位置结尾的不同 OR 值
 * 最多只有 O(log(max_val)) ≈ 30 个。用滚动 set 维护。
 *
 * 【解法总览】
 * 解法1: 暴力枚举           — O(n²) / O(n²)   — TLE，但要能说出来
 * 解法2: 滚动 set + OR 单调性 — O(30n) / O(30n) — 面试首选
 * 解法3: 用 bitset 优化常数   — O(30n) / O(30n) — 竞赛优化
 */

// ============================================================
// 解法1: 暴力枚举所有子数组 (TLE)
// 时间: O(n²)  空间: O(n²)
//
// 【思路】
// 最朴素的想法：枚举所有子数组 [i..j]，增量计算 OR 值。
// 对于每个起点 i，维护 orVal 表示 arr[i..j] 的 OR，
// j 每右移一位就 orVal |= arr[j]。
//
// 示例: arr = [1, 1, 2]
//   i=0: orVal = 1       → {1}
//         orVal = 1|1 = 1
//         orVal = 1|2 = 3 → {1, 3}
//   i=1: orVal = 1       → {1}
//         orVal = 1|2 = 3 → {1, 3}
//   i=2: orVal = 2       → {2}
//   全局: {1, 2, 3} → 答案 3 ✓
//
// 瓶颈: n = 5×10⁴, O(n²) ≈ 2.5×10⁹ 超时。
//   但增量 OR 的技巧是优化解法的基础。
// ============================================================
class Solution1 {
public:
    int subarrayBitwiseORs(vector<int>& arr) {
        unordered_set<int> result;  // 全局去重
        int n = arr.size();

        for (int i = 0; i < n; i++) {
            int orVal = 0;
            for (int j = i; j < n; j++) {
                orVal |= arr[j];     // 增量 OR
                result.insert(orVal);
            }
        }

        return result.size();
    }
};

// ============================================================
// 解法2: 滚动 set + OR 单调性 — 面试首选 ⭐
// 时间: O(30n)  空间: O(30n)
//
// 【思路】
// 核心观察：OR 运算的单调性。
//   a | b >= a，因为 OR 只会把 0 变成 1，不会把 1 变成 0。
//
// 推论：以位置 i 结尾的所有子数组的 OR 值，随着子数组变长
//       只增不减。而且每次增加至少多一个 bit。
//       32 位整数最多 30 个有效 bit → 最多 30 个不同 OR 值。
//
// 算法：
//   prev = 以前一位置结尾的所有不同 OR 值 (set)
//   对于 arr[i]:
//     curr = {v | arr[i] : v ∈ prev} ∪ {arr[i]}
//     全局 result ∪= curr
//     prev = curr
//
// 为什么 curr 最多 30 个元素？
//   curr 中的值可以写成：
//     arr[i]                        ← 1个bit pattern
//     arr[i-1] | arr[i]             ← 要么不变，要么多至少1个bit
//     arr[i-2] | arr[i-1] | arr[i]  ← 同上
//     ...
//   每增加一步，要么 OR 值不变（合并到上一个），要么多一个 bit。
//   最多 30 个 bit → 最多 30+1 个不同值。
//
// 示例详解: arr = [1, 2, 4]  (二进制: 001, 010, 100)
//
//   i=0: x=1, prev={}
//     curr = {1}
//     result = {1}
//     prev = {1}
//
//   i=1: x=2, prev={1}
//     对 prev 中每个 v: v|2 → 1|2=3 → {3}
//     加上 x=2 → curr = {3, 2}
//     result = {1, 2, 3}
//     prev = {3, 2}
//
//   i=2: x=4, prev={3, 2}
//     对 prev 中每个 v: 3|4=7, 2|4=6 → {7, 6}
//     加上 x=4 → curr = {7, 6, 4}
//     result = {1, 2, 3, 4, 6, 7}
//     prev = {7, 6, 4}
//
//   答案: 6 ✓
// ============================================================
class Solution2 {
public:
    int subarrayBitwiseORs(vector<int>& arr) {
        unordered_set<int> result;  // 全局去重：存所有不同的 OR 值
        unordered_set<int> prev;    // 以前一个位置结尾的不同 OR 值

        for (int x : arr) {
            // curr = 以当前位置结尾的所有不同 OR 值
            unordered_set<int> curr;

            // 长度为 1 的子数组：就是 x 本身
            curr.insert(x);

            // 在 prev 中每个值的基础上 OR 上 x
            // 相当于把以前一位置结尾的每个子数组右扩一位
            for (int v : prev) {
                curr.insert(v | x);
            }

            // 把 curr 中所有值加入全局结果
            for (int v : curr) {
                result.insert(v);
            }

            // 滚动：当前变成"前一个"
            prev = move(curr);
        }

        return result.size();
    }
};

// ============================================================
// 解法3: 用 set 替代 unordered_set（哈希更稳定的版本）
// 时间: O(30n · log(30n))  空间: O(30n)
//
// 【思路】
// 和解法2 完全一样，只是用 set (红黑树) 替代 unordered_set。
// 优势：不会因为哈希冲突退化到 O(n²)。
// 劣势：每次插入 O(log n)，常数稍大。
//
// 实际提交中两者差距不大，因为 curr 只有最多 30 个元素，
// 无论用什么容器操作都很快。
// ============================================================
class Solution3 {
public:
    int subarrayBitwiseORs(vector<int>& arr) {
        set<int> result;
        set<int> prev;

        for (int x : arr) {
            set<int> curr;
            curr.insert(x);

            for (int v : prev) {
                curr.insert(v | x);
            }

            // 批量插入到结果集
            result.insert(curr.begin(), curr.end());

            prev = move(curr);
        }

        return (int)result.size();
    }
};

