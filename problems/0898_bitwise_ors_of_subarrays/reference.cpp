// ============================================================
// 【易错点】
//
// 1. 忘记加 x 本身:
//    ✗ curr 只有 {v|x : v ∈ prev}，漏掉了长度为1的子数组
//    ✓ curr.insert(x) 必须在循环之前
//
// 2. prev 和 curr 混用:
//    ✗ 直接修改 prev → 遍历 prev 时修改它是 UB
//    ✓ 创建新 curr，遍历完后 prev = curr
//
// 3. 没有推导出 O(30) 上界:
//    面试中如果只写暴力 O(n²) 而说不出优化方向，很难拿好评。
//    核心论点：OR 只加 bit → 不同值 ≤ bit 数 → O(30)
//
// 4. 全局 result 没去重:
//    ✗ 用 vector 存结果，最后 size() → 包含重复
//    ✓ 用 set/unordered_set 自动去重
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 为什么 OR 没有逆运算？
//     OR 把 bit 从 0 变成 1。一旦变成 1，无法仅凭 OR 结果
//     判断这个 1 是来自 a 还是 b，所以无法"减去"一个元素的贡献。
//     对比：XOR 是自己的逆运算 (a^b^b = a)，SUM 的逆是减法。
//
// Q2: 把 OR 换成 AND，复杂度一样吗？
//     完全一样。AND 只去 bit: a&b <= a。以 i 结尾的 AND 值
//     也最多 30 个不同值。同样的滚动 set 框架。
//
// Q3: 如果是 XOR 呢？
//     XOR 没有单调性(a^b 可能变大也可能变小)，不同 XOR 值
//     可能有 O(n) 个 → 滚动 set 退化为 O(n²)。
//     XOR 相关问题通常需要前缀 XOR + 字典树等其他技巧。
//
// Q4: 实际 result set 的大小上界更紧吗？
//     理论上 O(30n)，但由于不同位置的 OR 值大量重叠，
//     实际通常远小于此。最坏情况 arr = [1, 2, 4, 8, ...]
//     （每个元素只有一个 bit），此时组合最多。
//
