/*
 * LeetCode 124: 二叉树中的最大路径和 (Binary Tree Maximum Path Sum)
 * 
 * 【题目本质】
 * 在二叉树上找一条"可以拐弯"的路径（左子树→某节点→右子树），
 * 使路径上所有节点的值之和最大。路径不一定经过根，至少包含一个节点。
 *
 * 【核心难点】
 * 递归函数需要同时完成两件事：
 *   1. 计算"以当前节点为拐点的完整路径和"→ 更新全局答案
 *   2. 返回"从当前节点出发的单边最大贡献"→ 给父节点使用
 * 这两个值不同！前者可以左右都走，后者只能选一边。
 *
 * 【解法总览】
 * 解法1: 后序DFS + 全局变量 — O(n) / O(h) — 面试首选 ⭐
 * 解法2: 后序DFS + 返回pair  — O(n) / O(h) — 无全局变量，函数式风格
 */


// ============================================================
// 解法1: 后序DFS + 全局变量 — 面试首选 ⭐
// 时间: O(n)  空间: O(h)，h为树高，最坏O(n)
//
// 【思路】
// 树上的路径一定有一个"最高点"（拐弯处/顶点），我们枚举每个节点
// 作为这个最高点。对于节点 X：
//   - 左子树能向下贡献的最大和 = leftGain（负数则取0，表示不走）
//   - 右子树能向下贡献的最大和 = rightGain（负数则取0）
//   - 以X为拐点的路径和 = leftGain + X.val + rightGain → 更新全局答案
//   - X向上返回给父节点 = X.val + max(leftGain, rightGain) → 只能选一边
//
// 为什么只能返回一边？因为如果X把左右都走了，再往上走到父节点，
// 路径就分叉了，不再是一条"链"。
//
// 【示例推演】
//
//         -10
//         / \
//        9   20
//           / \
//          15   7
//
// 后序遍历顺序: 9 → 15 → 7 → 20 → -10
//
// 节点  9: leftGain=0, rightGain=0
//         拐弯路径和 = 0 + 9 + 0 = 9    → 更新答案 maxSum=9
//         返回给父   = 9 + max(0,0) = 9
//
// 节点 15: leftGain=0, rightGain=0
//         拐弯路径和 = 0 + 15 + 0 = 15  → 更新答案 maxSum=15
//         返回给父   = 15
//
// 节点  7: leftGain=0, rightGain=0
//         拐弯路径和 = 0 + 7 + 0 = 7    → maxSum不变=15
//         返回给父   = 7
//
// 节点 20: leftGain=15, rightGain=7
//         拐弯路径和 = 15 + 20 + 7 = 42 → 更新答案 maxSum=42 ✓
//         返回给父   = 20 + max(15,7) = 35
//
// 节点-10: leftGain=9, rightGain=35
//         拐弯路径和 = 9 + (-10) + 35 = 34 → maxSum不变=42
//         返回给父   = -10 + max(9,35) = 25
//
// 最终答案: 42
// ============================================================
class Solution1 {
    int maxSum;

    // 返回：从 node 出发往下走（单边）的最大贡献值
    // 副作用：更新 maxSum
    int maxGain(TreeNode* node) {
        if (!node) return 0;

        // 后序：先处理左右子树
        // 贡献为负 → 不走那边（取0），这就是"剪枝"
        int leftGain = max(0, maxGain(node->left));
        int rightGain = max(0, maxGain(node->right));

        // ① 以当前节点为拐点的完整路径和（左+根+右）
        //    这个值用来更新全局答案
        int pathThroughMe = node->val + leftGain + rightGain;
        maxSum = max(maxSum, pathThroughMe);

        // ② 返回给父节点：只能选一边（路径不能分叉）
        //    注意这里没有 max(0, ...)，因为负数的处理
        //    是由父节点在调用时用 max(0, maxGain(child)) 完成的
        return node->val + max(leftGain, rightGain);
    }

public:
    int maxPathSum(TreeNode* root) {
        maxSum = INT_MIN; // 不能初始化为0！所有节点可能为负
        maxGain(root);
        return maxSum;
    }
};

// ============================================================
// 解法2: 后序DFS + 返回pair — 无全局变量，纯函数式
// 时间: O(n)  空间: O(h)
//
// 【思路】
// 与解法1完全相同的逻辑，但不用全局变量。
// 递归函数返回一个pair:
//   first  = 以该子树内任意节点为拐点的最大路径和（全局答案候选）
//   second = 从当前节点出发往下走的单边最大贡献（传给父节点用）
//
// 这样信息完全通过返回值传递，无副作用。
//
// 【何时用这个方案】
// - 面试官追问"能否不用全局变量/成员变量"
// - 需要线程安全或纯函数式风格时
// ============================================================
class Solution2 {
    // 返回 {子树内最大路径和, 从root出发的单边最大贡献}
    pair<int, int> dfs(TreeNode* node) {
        if (!node) return {INT_MIN, 0};
        // INT_MIN 表示空子树没有合法路径
        // 0 表示空子树的贡献为0（不走）

        auto [leftMax, leftGain] = dfs(node->left);
        auto [rightMax, rightGain] = dfs(node->right);

        // 负贡献不如不走
        leftGain = max(0, leftGain);
        rightGain = max(0, rightGain);

        // 以当前节点为拐点的路径和
        int throughMe = node->val + leftGain + rightGain;

        // 子树内全局最大 = max(左子树最大, 右子树最大, 经过当前节点)
        int bestInSubtree = max({leftMax, rightMax, throughMe});

        // 返回给父节点的单边贡献
        int gain = node->val + max(leftGain, rightGain);

        return {bestInSubtree, gain};
    }

public:
    int maxPathSum(TreeNode* root) {
        return dfs(root).first;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度         | 解法1 (全局变量)    | 解法2 (返回pair)     |
// |-------------|--------------------|--------------------|
// | 代码行数     | 更少，更简洁        | 稍长                |
// | 副作用       | 有（修改maxSum）    | 无，纯函数式         |
// | 面试推荐     | ⭐ 首选             | 追问时展示           |
// | 时间/空间    | O(n) / O(h)       | O(n) / O(h)        |
//
// 两种解法本质相同：一次后序DFS，每个节点O(1)工作。
// 区别仅在于全局最大值是通过成员变量还是返回值传递。
//
// ============================================================
// 【易错点】
//
// 1. maxSum 初始化为 0 而非 INT_MIN
//    ✗ maxSum = 0;
//    ✓ maxSum = INT_MIN;
//    当所有节点为负时（如 [-3]），答案应为 -3，不是 0。
//
// 2. 返回值也做了 max(0, ...) 截断
//    ✗ return max(0, node->val + max(leftGain, rightGain));
//    ✓ return node->val + max(leftGain, rightGain);
//    负贡献的"不走"决策应该由父节点来做（在 leftGain/rightGain
//    取值时用 max(0, ...)），而不是在返回时截断。如果在返回时截断，
//    会导致空节点和负值节点返回相同的0，父节点无法区分。
//
// 3. 拐弯路径和漏掉当前节点值
//    ✗ pathSum = leftGain + rightGain;
//    ✓ pathSum = leftGain + node->val + rightGain;
//    路径必须经过当前节点（它是拐弯的最高点）。
//
// 4. 只在根节点处更新答案
//    ✗ 只返回根的拐弯路径和
//    ✓ 在每个节点处都更新 maxSum
//    最大路径可能完全在某个子树内部（如示例2中的15→20→7），
//    完全不经过根节点。
//
// ============================================================
// 【面试追问】
//
// Q1: maxGain 返回的值和更新答案用的值有什么区别？为什么不同？
// A1: 返回值是"单边贡献"（只能选左或右），因为向上走时路径不能分叉。
//     更新答案的值是"拐弯路径和"（左+根+右），因为路径的最高点可以
//     同时连接左右两个方向。
//
// Q2: 如果还需要输出具体的最大路径（节点列表），怎么改？
// A2: 在 maxGain 中额外维护"最优单边路径"信息。
//     每个节点返回 {贡献值, 路径节点列表}。
//     更新全局最大时，拼接 reverse(leftPath) + [node] + rightPath。
//     空间从 O(h) 增加到 O(n)。
//
// Q3: 如果是 N 叉树（每个节点有多个子节点），怎么做？
// A3: 对所有子节点的贡献排序（或直接扫描找最大和次大），
//     取最大的两个子贡献来"拐弯"更新答案:
//       throughMe = node->val + top1Gain + top2Gain
//     返回给父节点的单边贡献 = node->val + top1Gain。
//     时间仍为 O(n)。
//
// Q4: 路径必须经过根节点，怎么简化？
// A4: 只需一个简单 DFS 求每棵子树的最大深度和：
//       ans = root->val + max(0, leftMaxDepthSum) + max(0, rightMaxDepthSum)
//     不需要全局变量，因为路径固定经过根。
//
// ============================================================
// 【相关题型】
//
// 543. 二叉树的直径
//   — 框架完全相同！区别：543求的是边数（路径长度），不是值之和。
//     把 `node->val + leftGain + rightGain` 改成 `leftDepth + rightDepth`，
//     返回值从"贡献"改成"深度"即可。
//
// 687. 最长同值路径
//   — 同样的"后序DFS + 拐弯更新 + 单边返回"框架，
//     增加约束：只有值相同的边才能计入路径长度。
//
// 1372. 二叉树中的最长交错路径
//   — 类似的后序DFS思路，但状态是"当前方向"（左/右交替）。
//
// 112/113. 路径总和 I/II
//   — 简化版：路径只从根到叶，不涉及"拐弯"和"选择子树"。
//
// 【关于迭代版本】
// 迭代版需要后序遍历 + 哈希表记录每个节点的单边最大贡献值。
// 后序保证处理当前节点时左右子的贡献已计算完毕。
// 实现思路：
//   1. 用双栈或 prev 指针实现后序遍历迭代
//   2. unordered_map<TreeNode*, int> gain 记录每个节点的单边贡献
//   3. 处理节点时: leftGain = max(0, gain[node->left])
//                  rightGain = max(0, gain[node->right])
//                  maxSum = max(maxSum, node->val + leftGain + rightGain)
//                  gain[node] = node->val + max(leftGain, rightGain)
//
// 但面试中递归是标准做法，代码量少且思路清晰。
// 迭代版代码量大幅增加且可读性下降，实际面试中不推荐。
// ============================================================
