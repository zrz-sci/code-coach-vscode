/*
 * LeetCode 1470: Shuffle the Array (重新排列数组)
 *
 * 【题目本质】
 * 给定 [x1,x2,...,xn,y1,y2,...,yn]，返回 [x1,y1,x2,y2,...,xn,yn]。
 * 核心就是一个索引映射：result[2*i] = nums[i], result[2*i+1] = nums[n+i]。
 *
 * 【解法总览】
 * 解法1: 新数组直接映射   — O(n) / O(n)  — 面试首选，极简
 * 解法2: 位编码原地操作   — O(n) / O(1)  — 进阶，利用值域 <= 1000
 * 解法3: 乘法编码变体     — O(n) / O(1)  — 等价于解法2，更直观
 */

// ============================================================
// 解法1: 新数组直接映射 — 面试首选 ⭐
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 开一个新数组，遍历 i = 0 到 n-1，
// 把 nums[i]（前半段第i个）和 nums[n+i]（后半段第i个）交替放入。
//
// 索引映射:
//   result[2*i]   = nums[i]     (前半段 → 偶数位)
//   result[2*i+1] = nums[n+i]   (后半段 → 奇数位)
//
// 示例: nums = [2,5,1,3,4,7], n = 3
//   前半段 x: [2, 5, 1]  后半段 y: [3, 4, 7]
//   i=0: result[0]=2, result[1]=3
//   i=1: result[2]=5, result[3]=4
//   i=2: result[4]=1, result[5]=7
//   → [2, 3, 5, 4, 1, 7] ✓
// ============================================================
class Solution1 {
public:
    vector<int> shuffle(vector<int>& nums, int n) {
        vector<int> result(2 * n);
        for (int i = 0; i < n; i++) {
            result[2 * i] = nums[i];         // x_i 放偶数位
            result[2 * i + 1] = nums[n + i]; // y_i 放奇数位
        }
        return result;
    }
};

// 等价的 push_back 写法，更直观
class Solution1b {
public:
    vector<int> shuffle(vector<int>& nums, int n) {
        vector<int> result;
        result.reserve(2 * n); // 预分配，避免动态扩容
        for (int i = 0; i < n; i++) {
            result.push_back(nums[i]);     // x_i
            result.push_back(nums[n + i]); // y_i
        }
        return result;
    }
};

// ============================================================
// 解法2: 位编码原地操作 — 进阶
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 关键观察: nums[i] <= 1000 < 1024 = 2^10
// 每个 int 只用了低 10 位，高位空闲。
//
// 我们可以把"新值"编码到高位:
//   nums[pos] |= (newVal << 10)  → 高位存新值
//   nums[pos] & 1023             → 低位取旧值
//   nums[pos] >> 10              → 高位取新值
//
// 为什么从后往前处理？
//   对于第 i 对:
//   源位置: nums[i] 和 nums[n+i]
//   目标位置: nums[2*i] 和 nums[2*i+1]
//
//   当 i >= 1 时, 2*i >= i 且 2*i+1 >= i
//   所以目标位置总是 >= 源位置中较小的那个(即 i)
//   但目标位置可能 < 源位置中较大的那个(即 n+i)
//
//   从后往前处理时:
//   - i 最大时 (i=n-1): 2*(n-1) = 2n-2, n+i = 2n-1
//     目标位置 [2n-2, 2n-1] 和源位置 [n-1, 2n-1] 重叠的只是 nums[2n-1]
//     但 nums[2n-1] 的源就是 nums[n+i] = nums[2n-1]，自己写自己，OK
//   - 逐渐往前时，所有需要读取的源值要么还没被覆盖，
//     要么可以通过 & 1023 取出旧值
//
// 示例: nums = [2,5,1,3,4,7], n = 3
//   MASK = 1023 (0x3FF)
//
//   i=2: xi = nums[2] & 1023 = 1
//        yi = nums[5] & 1023 = 7
//        nums[4] |= (1 << 10) → nums[4] = 4 + 1024 = 1028
//        nums[5] |= (7 << 10) → nums[5] = 7 + 7168 = 7175
//
//   i=1: xi = nums[1] & 1023 = 5
//        yi = nums[4] & 1023 = 4  (低10位还是旧值!)
//        nums[2] |= (5 << 10) → nums[2] = 1 + 5120 = 5121
//        nums[3] |= (4 << 10) → nums[3] = 3 + 4096 = 4099
//
//   i=0: xi = nums[0] & 1023 = 2
//        yi = nums[3] & 1023 = 3  (低10位还是旧值!)
//        nums[0] |= (2 << 10) → nums[0] = 2 + 2048 = 2050
//        nums[1] |= (3 << 10) → nums[1] = 5 + 3072 = 3077
//
//   解码: 每个位置 >>10
//   nums = [2, 3, 5, 4, 1, 7] ✓
// ============================================================
class Solution2 {
public:
    vector<int> shuffle(vector<int>& nums, int n) {
        const int MASK = 1023; // 2^10 - 1

        // 从后往前，把新值编码到高位
        for (int i = n - 1; i >= 0; i--) {
            int xi = nums[i] & MASK;         // 旧的 x 值 (低10位)
            int yi = nums[n + i] & MASK;     // 旧的 y 值 (低10位)
            nums[2 * i] |= (xi << 10);       // 编码 x 到高位
            nums[2 * i + 1] |= (yi << 10);   // 编码 y 到高位
        }

        // 提取高位作为新值
        for (int i = 0; i < 2 * n; i++) {
            nums[i] >>= 10;
        }

        return nums;
    }
};

// ============================================================
// 解法3: 乘法编码变体 — 对不熟悉位运算的人更直观
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 用乘法代替位移，逻辑完全等价:
//   编码: nums[pos] += newVal * 1024
//   取旧值: nums[pos] % 1024
//   取新值: nums[pos] / 1024
//
// BASE = 1024 必须大于 max(nums[i]) = 1000
// ============================================================
class Solution3 {
public:
    vector<int> shuffle(vector<int>& nums, int n) {
        const int BASE = 1024;

        // 编码: nums[pos] = old + new * BASE
        for (int i = n - 1; i >= 0; i--) {
            int xi = nums[i] % BASE;       // 旧的 x 值
            int yi = nums[n + i] % BASE;   // 旧的 y 值
            nums[2 * i] += xi * BASE;      // 编码 x 到高位
            nums[2 * i + 1] += yi * BASE;  // 编码 y 到高位
        }

        // 解码: 取高位
        for (auto& x : nums) {
            x /= BASE;
        }

        return nums;
    }
};

