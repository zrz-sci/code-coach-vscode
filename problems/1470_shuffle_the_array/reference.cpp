// 【解法对比】
//
// | 解法        | 时间  | 空间  | 优势                    | 劣势                      |
// |-------------|-------|-------|------------------------|--------------------------|
// | 新数组映射   | O(n)  | O(n)  | 极简，30秒写完          | 额外空间 O(n)             |
// | 位编码原地   | O(n)  | O(1)  | 真正O(1)空间            | 需理解位编码，受值域限制    |
// | 乘法编码     | O(n)  | O(1)  | O(1)空间 + 更易理解     | 本质同位编码              |
//
// 面试选择: 先写解法1（极简），再主动提出解法2展示深度。
//
// ============================================================
// 【易错点】
//
// 1. 后半段索引写错:
//    ✗ nums[i + 1] 或 nums[n - i]
//    ✓ nums[n + i] (后半段第i个, i从0开始)
//
// 2. 结果数组大小:
//    ✗ vector<int> result(n)  → 少了一半
//    ✓ vector<int> result(2 * n)
//
// 3. 位编码取旧值:
//    ✗ 直接用 nums[i]  → 可能高位已经被编码过了
//    ✓ nums[i] & 1023 或 nums[i] % 1024
//
// 4. 位编码方向:
//    ✗ 从前往后  → i=0 写入 nums[0] 后，后续读 nums[0] 旧值出错
//    ✓ 从后往前  → 目标位置 >= 源位置，不覆盖未处理数据
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 时间空间复杂度？能优化空间吗？
//     O(n)/O(n)。用位编码可以 O(1) 空间（前提是值域 <= 10^3）。
//
// Q2: 如果数组极大，内存装不下额外数组？
//     必须原地。位编码或循环置换。
//
// Q3: 值域很大（<= 10^9），位编码还能用吗？
//     不行，int 32位不够。改用 long long 编码，或循环置换。
//
// Q4: 逆操作 [x1,y1,...] → [x1,x2,...,y1,y2,...] 怎么做？
//     映射反转: result[i] = nums[2*i], result[n+i] = nums[2*i+1]
//
// Q5: 分成 k 组怎么交错？
//     result 第 i 位 = 原数组第 (i%k)*n + (i/k) 位
