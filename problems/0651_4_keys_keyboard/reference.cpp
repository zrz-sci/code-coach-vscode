// LeetCode 651: 4 Keys Keyboard
// 解法一：DP
// 时间复杂度: O(n^2)  空间复杂度: O(n)

// ============================================================
// 核心思想：
// dp[i] = 用 i 次按键最多能产生多少个 'A'
// 转移：要么直接打 A (dp[i-1]+1)，要么在之前某步 j 做
// Ctrl-A + Ctrl-C + 若干次 Ctrl-V，将字符数乘以 (i-j-1)
// ============================================================

class Solution {
public:
    int maxA(int n) {
        // dp[i] = 用 i 步能得到的最大 A 数量
        vector<int> dp(n + 1, 0);

        for (int i = 1; i <= n; ++i) {
            // 选项 1：直接打一个 A
            dp[i] = dp[i - 1] + 1;

            // 选项 2：在之前第 j 步后，做 Ctrl-A + Ctrl-C + 若干 Ctrl-V
            // j+1: Ctrl-A
            // j+2: Ctrl-C
            // j+3 到 i: 共 i-j-2 次 Ctrl-V
            // 倍增因子 = i-j-2+1 = i-j-1 (原来的内容 + 粘贴的内容)
            for (int j = i - 3; j >= 1; --j) {
                int multiplier = i - j - 1;  // 包括原本的1份 + (i-j-2)份粘贴
                dp[i] = max(dp[i], dp[j] * multiplier);
            }
        }

        return dp[n];
    }
};

// ============================================================
// 解法二：优化 DP（只检查最近几个分割点）
// 时间复杂度: O(n)  空间复杂度: O(n)
//
// 数学分析表明最优乘法因子不超过 5，
// 因此 j 只需要检查 i-3 到 i-5 即可。
// ============================================================

class Solution_Optimized {
public:
    int maxA(int n) {
        vector<int> dp(n + 1, 0);

        for (int i = 1; i <= n; ++i) {
            dp[i] = dp[i - 1] + 1;  // 直接打 A

            // 只检查乘以 2, 3, 4 的情况（对应 j = i-3, i-4, i-5）
            // 因为数学上乘以 3 或 4 效率最高
            for (int j = max(1, i - 5); j <= i - 3; ++j) {
                int multiplier = i - j - 1;
                dp[i] = max(dp[i], dp[j] * multiplier);
            }
        }

        return dp[n];
    }
};

// ============================================================
// 解法三：递归 + 记忆化
// 时间复杂度: O(n^2)  空间复杂度: O(n)
// ============================================================

class Solution_Memo {
public:
    int maxA(int n) {
        vector<int> memo(n + 1, -1);
        return solve(n, memo);
    }

private:
    int solve(int n, vector<int>& memo) {
        // base case: n 步直接打 A
        if (n <= 6) {
            // n <= 6 时，直接打 A 是最优的
            // 手动验证：
            // n=1: 1, n=2: 2, n=3: 3, n=4: 4, n=5: 5, n=6: 6
            // 实际上 n=7 才开始有乘法的优势 (3*3=9 > 7)
            return n;
        }

        if (memo[n] != -1) return memo[n];

        int result = n;  // 全部打 A

        // 在第 j 步做最后一次 Ctrl-A + Ctrl-C，然后 Ctrl-V 直到第 n 步
        for (int j = n - 3; j >= 1; --j) {
            int multiplier = n - j - 1;
            result = max(result, solve(j, memo) * multiplier);
        }

        return memo[n] = result;
    }
};

// ============================================================
// 手动模拟：n = 7
//
// dp[1] = 1  (A)
// dp[2] = 2  (A, A)
// dp[3] = 3  (A, A, A)
// dp[4] = 4  (A, A, A, A)
//   j=1: dp[1] * (4-1-1) = 1*2 = 2 < 4
//
// dp[5] = 5  (A, A, A, A, A)
//   j=2: dp[2] * (5-2-1) = 2*2 = 4 < 5
//   j=1: dp[1] * (5-1-1) = 1*3 = 3 < 5
//
// dp[6] = 6  (A, A, A, A, A, A)
//   j=3: dp[3] * (6-3-1) = 3*2 = 6 = 6 (相同)
//   j=2: dp[2] * (6-2-1) = 2*3 = 6 = 6 (相同)
//   j=1: dp[1] * (6-1-1) = 1*4 = 4 < 6
//
// dp[7] = dp[6] + 1 = 7  先设为全打 A
//   j=4: dp[4] * (7-4-1) = 4*2 = 8 > 7 => dp[7]=8
//   j=3: dp[3] * (7-3-1) = 3*3 = 9 > 8 => dp[7]=9
//   j=2: dp[2] * (7-2-1) = 2*4 = 8 < 9
//   j=1: dp[1] * (7-1-1) = 1*5 = 5 < 9
//
// dp[7] = 9
// 对应操作：A, A, A, Ctrl-A, Ctrl-C, Ctrl-V, Ctrl-V
// 即打 3 个 A，然后全选复制，粘贴 2 次 => 3 * 3 = 9
// ============================================================

// ============================================================
// 倍增因子分析（为什么 3 和 4 最优）：
//
// 乘以 k 需要 k+1 步（1 步 Ctrl-A + 1 步 Ctrl-C + (k-1) 步 Ctrl-V）
//
// 每步的"效率" = k^(1/(k+1))：
//   k=2: 2^(1/3) = 1.260
//   k=3: 3^(1/4) = 1.316  <-- 最优之一
//   k=4: 4^(1/5) = 1.320  <-- 最优之一
//   k=5: 5^(1/6) = 1.308
//   k=6: 6^(1/7) = 1.292
//
// 结论：最优的乘法因子是 3 或 4。
// 大的 n 应该反复用 3 或 4 来分段乘。
// ============================================================
