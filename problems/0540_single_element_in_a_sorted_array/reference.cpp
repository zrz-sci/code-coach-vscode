/*
 * LeetCode 540: Single Element in a Sorted Array
 * 
 * 【题目本质】
 * 有序数组中每个元素出现两次，只有一个出现一次。
 * 单一元素打破了"偶数下标=对头、奇数下标=对尾"的配对规律。
 * 利用这个规律，二分查找定位配对断裂点。
 *
 * 【解法总览】
 * 解法1: 异或法           — O(n)     / O(1) — 最直觉，不满足题目要求
 * 解法2: 二分(奇偶配对)   — O(log n) / O(1) — 面试首选，用 ^1 技巧
 * 解法3: 二分(偶数下标)   — O(log n) / O(1) — 逻辑更直观的二分写法
 */

// ============================================================
// 解法1: 异或法 — 不利用有序性，O(n) 遍历
// 时间: O(n)  空间: O(1)
// 
// 【思路】
// a ^ a = 0, a ^ 0 = a
// 所有成对元素异或后抵消为0，剩下的就是单一元素。
// 这是"找唯一出现一次元素"的经典做法，但完全没用到"有序"。
// 作为面试的起手式，展示你理解问题，然后再优化。
// ============================================================
class Solution1 {
public:
    int singleNonDuplicate(vector<int>& nums) {
        int result = 0;
        for (int num : nums) {
            result ^= num;
        }
        return result;
    }
};

// ============================================================
// 解法2: 二分查找（奇偶配对） — 面试首选
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 关键观察：在单一元素出现之前，配对是"正常"的：
//   偶数下标的元素 == 下一个元素（奇数下标）
// 在单一元素出现之后，配对被"错位"了：
//   偶数下标的元素 == 前一个元素（奇数下标）
//
// 示例:
//   下标:  0  1  2  3  4  5  6  7  8
//   值:    1  1  2  3  3  4  4  8  8
//               ↑
//           单一元素(下标2)
//   之前: (0,1) → 1,1 配对正常
//   之后: (3,4) → 3,3 配对错位（偶数下标3!=4的值）
//
// 技巧: mid ^ 1 可以统一获取配对下标
//   mid=4(偶) → 4^1=5  检查 nums[4]==nums[5]?
//   mid=5(奇) → 5^1=4  检查 nums[5]==nums[4]?
//
// 搜索空间收缩过程（示例1）:
//   Round1: left=0, right=8, mid=4
//     mid^1=5, nums[4]=3 != nums[5]=4 → right=4
//   Round2: left=0, right=4, mid=2
//     mid^1=3, nums[2]=2 != nums[3]=3 → right=2
//   Round3: left=0, right=2, mid=1
//     mid^1=0, nums[1]=1 == nums[0]=1 → left=2
//   left==right==2 → 答案 nums[2]=2 ✓
// ============================================================
class Solution2 {
public:
    int singleNonDuplicate(vector<int>& nums) {
        int left = 0, right = nums.size() - 1;
        // 使用 left < right 模板，最终 left==right 为答案
        while (left < right) {
            int mid = left + (right - left) / 2;
            // mid ^ 1: 偶数→+1, 奇数→-1，统一找配对下标
            if (nums[mid] == nums[mid ^ 1]) {
                // 配对完好 → 单一元素在 mid 右侧
                left = mid + 1;
            } else {
                // 配对断裂 → 单一元素在 mid 或其左侧
                right = mid;
            }
        }
        return nums[left];
    }
};

// ============================================================
// 解法3: 二分查找（仅偶数下标） — 逻辑更直观
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 核心观察同解法2，但换一个角度：
// 单一元素一定在偶数下标上（它前面有偶数个配对元素）。
// 只在偶数下标上做二分：
//   - 若 nums[mid] == nums[mid+1]，这对完好，答案在右边
//   - 否则，答案在 mid 或左边
//
// 图解:
//   下标:  0  1  2  3  4  5  6  7  8
//   值:    1  1  2  3  3  4  4  8  8
//          ↑     ↑     ↑     ↑     ↑   ← 偶数下标
//
//   mid=0: nums[0]=1==nums[1]=1 → 完好 → left=2
//   mid=4: nums[4]=3!=nums[5]=4 → 断裂 → right=4
//   mid=2: nums[2]=2!=nums[3]=3 → 断裂 → right=2
//   left==right==2 → 答案 nums[2]=2 ✓
// ============================================================
class Solution3 {
public:
    int singleNonDuplicate(vector<int>& nums) {
        int left = 0, right = nums.size() - 1;
        while (left < right) {
            int mid = left + (right - left) / 2;
            // 强制 mid 为偶数：如果是奇数就减1
            if (mid % 2 == 1) mid--;
            
            if (nums[mid] == nums[mid + 1]) {
                // 这一对配对完好，单一元素在后面
                // 跳过整对，所以 +2
                left = mid + 2;
            } else {
                // 配对断裂，单一元素在 mid 或更左边
                right = mid;
            }
        }
        return nums[left];
    }
};

// ============================================================
// 【解法对比】
//
// 解法1 (异或):     O(n)      简单直接，但没用有序性，不满足O(log n)
// 解法2 (^1二分):   O(log n)  代码最简洁，^1 技巧统一处理奇偶
// 解法3 (偶数二分): O(log n)  逻辑最直观，强制 mid 为偶数后判断
//
// 解法2 和 解法3 本质相同，都是利用配对规律做二分。
// 解法2 更适合"一行判断"的简洁风格。
// 解法3 更适合面试时边讲边写，逻辑清晰好解释。
//
// 【易错点】
// 1. ✗ while (left <= right) 导致死循环
//    ✓ while (left < right)，这是"找边界"模板，不是"找确切值"
//    因为 right=mid（不是 mid-1），用 <= 时 left 和 right
//    可能永远不交错
//
// 2. ✗ 解法3中 left = mid + 1
//    ✓ left = mid + 2
//    因为 mid 和 mid+1 是完好配对，必须跳过整对；
//    如果只跳到 mid+1（奇数下标），下一轮 mid 可能也是奇数，
//    逻辑就全乱了
//
// 3. ✗ 解法3忘了将 mid 调整为偶数
//    ✓ if (mid % 2 == 1) mid--;
//    不调整的话 nums[mid]==nums[mid+1] 的判断含义完全不同
//
// 4. ✗ 担心 nums[mid+1] 越界
//    ✓ 当 left < right 时，mid < right <= n-1，所以 mid+1 <= n-1
//    解法3 中 mid 被调整为偶数后 mid <= right-1，mid+1 <= right，安全
//
// 【面试追问】
// Q1: "不要求 O(log n) 你怎么做？" 
//     → 异或 O(n)，或者逐对检查 nums[i]!=nums[i+1]
//
// Q2: "有序+O(log n) 暗示什么？判断条件怎么设计？"
//     → 二分查找。单一元素打破配对规律，检查 mid 处配对是否正常
//       来决定搜索方向。这是"非标准二分"：搜索空间的单调性不是
//       值的大小，而是配对规律的正常/异常
//
// Q3: "如果数组无序但每个元素出现两次只有一个一次？两个呢？"
//     → 一个: 异或所有元素（LC 136）
//     → 两个: 异或得 a^b，取最低有效位分组异或（LC 260）
//
// Q4: "mid ^ 1 这个技巧的原理是什么？"
//     → 最低位取反: 偶数(末位0)变奇数(末位1)，奇数变偶数
//       相当于 mid%2==0 ? mid+1 : mid-1，但一条位运算搞定
// ============================================================
