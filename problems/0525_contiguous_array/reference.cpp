/*
 * LeetCode 525: 连续数组 (Contiguous Array)
 *
 * 【题目本质】
 * 找含有相同数量 0 和 1 的最长连续子数组。
 * 关键转化：把 0 替换成 -1 后，问题等价于"找和为 0 的最长子数组"，
 * 即找两个位置 i < j 使得 prefix[j] == prefix[i] 且 j - i 最大。
 *
 * 【解法总览】
 * 解法1: 暴力枚举      — O(n²) / O(1) — 展示理解
 * 解法2: 前缀和+哈希表 — O(n)  / O(n) — 面试必写 ⭐
 */

// ============================================================
// 解法1: 暴力枚举 — 枚举所有子数组，用 count 变量跟踪 0/1 差值
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 最直觉的做法：固定起点 i，向右扩展终点 j。
// 遇到 1 则 count++，遇到 0 则 count--。
// count == 0 说明 [i, j] 内 0 和 1 个数相等。
//
// 瓶颈：O(n²) 对 n=10⁵ 会超时，但它展示了"0→-1"这个核心思想。
// ============================================================
class Solution1 {
public:
    int findMaxLength(vector<int>& nums) {
        int n = nums.size(), maxLen = 0;
        for (int i = 0; i < n; i++) {
            int count = 0;
            for (int j = i; j < n; j++) {
                // 1 贡献 +1，0 贡献 -1
                count += (nums[j] == 1) ? 1 : -1;
                // count == 0 意味着 [i..j] 内 0 和 1 个数相等
                if (count == 0) {
                    maxLen = max(maxLen, j - i + 1);
                }
            }
        }
        return maxLen;
    }
};

// ============================================================
// 解法2: 前缀和 + 哈希表 — O(n) / O(n)  ⭐ 面试首选
//
// 【思路】
// 解法1的瓶颈：对每个起点都要线性扫描。
// 优化关键：如果 prefix[j] == prefix[i]，则 [i+1..j] 的和为 0。
// 所以只需记录每个前缀和第一次出现的位置，再次出现时计算距离。
//
// 为什么记录"第一次"？因为要最长子数组，起点越早越好。
//
// 初始化 map[0] = -1：处理从数组开头就满足条件的情况。
//
// 【可视化示例】
// nums:    [0,  1,  1,  1,  1,  1,  0,  0,  0]
// 替换→:  [-1,  1,  1,  1,  1,  1, -1, -1, -1]
//
// idx:    -1   0   1   2   3   4   5   6   7   8
// prefix:  0  -1   0   1   2   3   4   3   2   1
//          ↑       ↑
//          └───────┘ prefix[1]==prefix[-1]==0 → len=1-(-1)=2
//
//                  ↑                           ↑
//                  └───────────────────────────┘
//                  prefix[8]==prefix[2]==1 → len=8-2=6 (最大!)
//
// 哈希表变化过程:
// i=-1(初始): {0: -1}
// i=0, sum=-1: {0:-1, -1:0}
// i=1, sum=0:  已存在 → maxLen = 1-(-1) = 2
// i=2, sum=1:  {0:-1, -1:0, 1:2}
// i=3, sum=2:  {0:-1, -1:0, 1:2, 2:3}
// i=4, sum=3:  {0:-1, -1:0, 1:2, 2:3, 3:4}
// i=5, sum=4:  {0:-1, -1:0, 1:2, 2:3, 3:4, 4:5}
// i=6, sum=3:  已存在(first=4) → maxLen = max(2, 6-4) = 2
// i=7, sum=2:  已存在(first=3) → maxLen = max(2, 7-3) = 4
// i=8, sum=1:  已存在(first=2) → maxLen = max(4, 8-2) = 6
// 答案: 6
// ============================================================
class Solution2 {
public:
    int findMaxLength(vector<int>& nums) {
        // key: 前缀和, value: 该前缀和第一次出现的索引
        unordered_map<int, int> firstOccurrence;
        
        // 前缀和为0意味着从开头到当前整段满足条件
        // 设虚拟位置-1处前缀和为0
        firstOccurrence[0] = -1;
        
        int prefixSum = 0, maxLen = 0;
        
        for (int i = 0; i < (int)nums.size(); i++) {
            // 0 当作 -1，累加前缀和
            prefixSum += (nums[i] == 1) ? 1 : -1;
            
            if (firstOccurrence.count(prefixSum)) {
                // 同一个前缀和之前出现过 → 中间这段区间和为 0
                // 只和第一次出现的位置做差，保证最长
                maxLen = max(maxLen, i - firstOccurrence[prefixSum]);
            } else {
                // 第一次出现这个前缀和，记录位置
                // 注意：后续再遇到相同值时不更新，因为要最长子数组
                firstOccurrence[prefixSum] = i;
            }
        }
        
        return maxLen;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 解法1 暴力枚举    | 解法2 前缀和+哈希表 |
// |------------|-------------------|---------------------|
// | 时间       | O(n²)             | O(n)                |
// | 空间       | O(1)              | O(n)                |
// | 核心思想   | 枚举所有子数组     | prefix相等⟹区间和=0 |
// | 面试       | 说思路即可         | 必须写出 ⭐          |
//
// 两种解法都用了"0→-1"的转化。解法2的突破在于：
// 不再枚举起点，而是用哈希表在 O(1) 内找到"同一前缀和最早出现的位置"。
//
// ============================================================
// 【易错点】
//
// 1. 忘记 firstOccurrence[0] = -1
//    ✗ 不初始化 → nums=[0,1] 时 prefix 变化为 -1,0，
//      到 i=1 时 prefix=0 但 map 中没有 0，漏掉答案 2。
//    ✓ firstOccurrence[0] = -1 → 0 出现过(位置-1)，len = 1-(-1) = 2。
//
// 2. 哈希表覆盖了已有值
//    ✗ firstOccurrence[prefixSum] = i; (每次都更新)
//      → 得到最短子数组而非最长。
//    ✓ 只在 count()==0 时才存入，保证存的是第一次出现的位置。
//
// 3. 长度计算多加了 1
//    ✗ i - firstOccurrence[prefixSum] + 1
//    ✓ i - firstOccurrence[prefixSum]
//    因为 firstOccurrence 存的是子数组开始之前的位置（类似前缀和的
//    下标含义），子数组是 (firstOccurrence[sum], i]，长度就是差值。
//
// 4. 没有把 0 替换成 -1
//    ✗ prefixSum += nums[i]; → 前缀和单调不减，无法用"相等即和为0"
//    ✓ prefixSum += (nums[i] == 1) ? 1 : -1;
//
// ============================================================
// 【面试追问】
//
// Q1(基础): 暴力解的复杂度？瓶颈在哪？
//    A: O(n²)，瓶颈在对每个起点线性扫描所有终点。
//
// Q2(核心): 为什么把 0 替换成 -1？
//    A: 替换后"0和1个数相等"⟺"子数组和=0"⟺"两个位置前缀和相等"，
//       就能用哈希表在 O(1) 内匹配。
//
// Q3(变体): 如果要求 0 的个数比 1 多 k 个的最长子数组？
//    A: 0→+1, 1→-1（或反过来），找子数组和=k 的最长子数组。
//       哈希表中查 prefixSum - k 是否出现过。
//
// Q4(变体): 如果要返回满足条件的子数组个数而非最长长度？
//    A: 哈希表 value 改为"出现次数"。每次遇到相同前缀和，
//       答案加上之前出现的次数。参考 LeetCode 560。
//
// 【相关题型】
// - 560. 和为K的子数组 — 同样的前缀和+哈希表框架，区别：
//   525 存第一次出现位置(求最长)，560 存出现次数(求个数)。
// - 930. 和相同的二元子数组 — 二进制数组+前缀和，不需 0→-1 转换。
// - 325. 和等于k的最长子数组长度 — 完全相同模板，525 是其 k=0 特例。
// - 1. 两数之和 — 复用"边遍历边查哈希表"的模式。
// ============================================================
