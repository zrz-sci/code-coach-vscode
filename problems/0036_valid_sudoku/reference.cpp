/*
 * LeetCode 36: 有效的数独 (Valid Sudoku)
 *
 * 【题目本质】
 * 遍历 9×9 棋盘，检查每个已填入的数字在其所在行、列、3×3 宫格中是否有重复。
 * 本质是一个重复检测问题，核心难点在于快速确定格子 (i,j) 属于哪个宫格。
 *
 * 【解法总览】
 * 解法1: 三次遍历       — O(81×3) / O(9)     — 最直觉，分别检查行、列、宫格
 * 解法2: 一次遍历+数组  — O(81) / O(27×9)    — 面试首选，27个数组同时检查
 * 解法3: 一次遍历+位运算 — O(81) / O(27)      — 空间更紧凑，面试加分项
 *
 * 【棋盘与宫格编号示意图】
 *
 *  col:  0 1 2   3 4 5   6 7 8
 * row 0 [5 3 .] [. 7 .] [. . .]     宫格编号:
 * row 1 [6 . .] [1 9 5] [. . .]      0 | 1 | 2
 * row 2 [. 9 8] [. . .] [. 6 .]     ---+---+---
 *        ------  ------  ------       3 | 4 | 5
 * row 3 [8 . .] [. 6 .] [. . 3]     ---+---+---
 * row 4 [4 . .] [8 . 3] [. . 1]      6 | 7 | 8
 * row 5 [7 . .] [. 2 .] [. . 6]
 *        ------  ------  ------      公式: boxIndex = (i/3)*3 + (j/3)
 * row 6 [. 6 .] [. . .] [2 8 .]     例: (4,7) → (4/3)*3 + 7/3 = 3+2 = 5
 * row 7 [. . .] [4 1 9] [. . 5]
 * row 8 [. . .] [. 8 .] [. 7 9]
 */

// ============================================================
// 解法1: 三次遍历 — 分别检查行、列、宫格
// 时间: O(81×3)  空间: O(9) (每轮一个临时集合)
//
// 【思路】
// 最直觉的做法：题目有三种约束，就分三轮分别检查。
// 每轮遍历 9 个"组"（9行 / 9列 / 9宫格），每个组内用集合检测重复。
// 优点：逻辑清晰不容易写错；缺点：三次遍历稍显冗余。
// ============================================================
class Solution1 {
public:
    bool isValidSudoku(vector<vector<char>>& board) {
        // --- 第一轮: 检查每一行 ---
        for (int i = 0; i < 9; i++) {
            unordered_set<char> seen;
            for (int j = 0; j < 9; j++) {
                if (board[i][j] == '.') continue;
                // 如果已出现过，说明行内重复
                if (seen.count(board[i][j])) return false;
                seen.insert(board[i][j]);
            }
        }
        
        // --- 第二轮: 检查每一列 ---
        for (int j = 0; j < 9; j++) {
            unordered_set<char> seen;
            for (int i = 0; i < 9; i++) {
                if (board[i][j] == '.') continue;
                if (seen.count(board[i][j])) return false;
                seen.insert(board[i][j]);
            }
        }
        
        // --- 第三轮: 检查每个 3×3 宫格 ---
        // 第 box 个宫格的起始坐标: (startRow, startCol)
        //   box=0 → (0,0), box=1 → (0,3), box=2 → (0,6)
        //   box=3 → (3,0), box=4 → (3,3), ...
        for (int box = 0; box < 9; box++) {
            unordered_set<char> seen;
            int startRow = (box / 3) * 3;  // box 的行号(0/1/2) × 3
            int startCol = (box % 3) * 3;  // box 的列号(0/1/2) × 3
            for (int i = startRow; i < startRow + 3; i++) {
                for (int j = startCol; j < startCol + 3; j++) {
                    if (board[i][j] == '.') continue;
                    if (seen.count(board[i][j])) return false;
                    seen.insert(board[i][j]);
                }
            }
        }
        
        return true;
    }
};

// ============================================================
// 解法2: 一次遍历 + bool 数组 — 面试首选 ⭐
// 时间: O(81)  空间: O(27×9) = O(243) ≈ O(1)
//
// 【思路】
// 解法1 分三轮，但遍历到 (i,j) 时，我们已经同时知道:
//   - 它在第 i 行
//   - 它在第 j 列
//   - 它在第 (i/3)*3 + (j/3) 个宫格
// 所以预先创建 27 个标记数组 (9行+9列+9宫格)，一次遍历同时检查三个约束。
//
// 为什么用 bool[9][9] 而不是 HashSet?
// 因为数字只有 1-9，固定大小的数组比哈希表更快且无碰撞开销。
// ============================================================
class Solution2 {
public:
    bool isValidSudoku(vector<vector<char>>& board) {
        // rows[i][d]: 第 i 行是否已出现数字 (d+1)
        // cols[j][d]: 第 j 列是否已出现数字 (d+1)
        // boxes[b][d]: 第 b 个宫格是否已出现数字 (d+1)
        bool rows[9][9] = {};
        bool cols[9][9] = {};
        bool boxes[9][9] = {};
        
        for (int i = 0; i < 9; i++) {
            for (int j = 0; j < 9; j++) {
                if (board[i][j] == '.') continue;  // 跳过空格，不参与检查
                
                // '1'→0, '2'→1, ..., '9'→8 —— 映射到0-based索引
                int d = board[i][j] - '1';
                int boxIndex = (i / 3) * 3 + (j / 3);
                
                // 核心: 同时检查行、列、宫格三个约束
                if (rows[i][d] || cols[j][d] || boxes[boxIndex][d]) {
                    return false;  // 任何一个已出现过 → 无效
                }
                
                // 标记为已出现
                rows[i][d] = true;
                cols[j][d] = true;
                boxes[boxIndex][d] = true;
            }
        }
        return true;
    }
};

// ============================================================
// 解法3: 一次遍历 + 位运算 — 空间更紧凑
// 时间: O(81)  空间: O(27) = O(1)
//
// 【思路】
// 解法2 用 bool[9] 记录哪些数字出现过，但一个 int 有 32 位，
// 用低 9 位分别代表数字 1-9 是否出现过，就能用一个 int 代替一个 bool[9]。
//
// 检查重复: rows[i] & bit → 如果该位已为1，说明重复
// 标记出现: rows[i] |= bit → 将该位置为1
//
// 位掩码示例:
//   数字 3 → bit = 1 << 2 = 0b000000100
//   数字 7 → bit = 1 << 6 = 0b001000000
//   已出现 3 和 7: mask = 0b001000100
//   再来一个 3: mask & (1<<2) = 0b000000100 ≠ 0 → 重复!
// ============================================================
class Solution3 {
public:
    bool isValidSudoku(vector<vector<char>>& board) {
        // 每个 int 用低 9 位表示数字 1-9 的出现情况
        int rows[9] = {0};
        int cols[9] = {0};
        int boxes[9] = {0};
        
        for (int i = 0; i < 9; i++) {
            for (int j = 0; j < 9; j++) {
                if (board[i][j] == '.') continue;
                
                // 数字 d 对应第 (d-1) 位
                int bit = 1 << (board[i][j] - '1');
                int boxIndex = (i / 3) * 3 + (j / 3);
                
                // 位与检测: 如果该位已被置位，说明重复
                if ((rows[i] & bit) || (cols[j] & bit) || (boxes[boxIndex] & bit)) {
                    return false;
                }
                
                // 位或置位: 标记该数字已出现
                rows[i] |= bit;
                cols[j] |= bit;
                boxes[boxIndex] |= bit;
            }
        }
        return true;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 解法1 三次遍历 | 解法2 数组 ⭐ | 解法3 位运算 |
// |------------|---------------|-------------|-------------|
// | 遍历次数    | 3次           | 1次          | 1次          |
// | 空间表示    | HashSet(临时)  | bool[9][9]×3 | int[9]×3     |
// | 代码简洁度  | 长            | 简洁          | 简洁         |
// | 面试推荐    | 说思路         | ⭐首选        | 追问加分      |
//
// 三者逻辑完全一致，区别只在遍历次数和"已出现"的存储方式。
// 面试中推荐解法2: 容易写、容易讲、不容易出错。
//
// ============================================================
// 【易错点】
//
// 1. 字符转索引偏移:
//    ✗ int d = board[i][j] - '0';  // d∈[1,9]，作为下标需要数组开到10
//    ✓ int d = board[i][j] - '1';  // d∈[0,8]，正好匹配 [9] 数组
//    两种都行但必须和数组大小匹配，推荐 -'1' 更自然。
//
// 2. 宫格编号公式:
//    ✗ boxIndex = i / 3 + j / 3;   // 最多只到 2+2=4，无法区分 9 个宫格
//    ✓ boxIndex = (i/3)*3 + (j/3); // 结果∈[0,8]，正确映射 9 个宫格
//    验证: (0,0)→0, (2,8)→2, (8,8)→8 ✓
//
// 3. 忘记跳过'.':
//    ✗ 直接计算 '.' - '1' = -3，用作数组下标导致越界
//    ✓ if (board[i][j] == '.') continue; 必须在最前面
//
// 4. 位运算版用 == 而不是 &:
//    ✗ if (rows[i] == bit)  // 只有恰好只出现这一个数字时才为true
//    ✓ if (rows[i] & bit)   // 检查特定位是否被置位
//
// ============================================================
// 【面试追问】(递进链)
//
// Q1: "这题的时间复杂度是多少? 如果推广到 N×N 数独呢?"
// → 固定 9×9 严格来说 O(1)。推广到 N×N (N = k²)，
//   一次遍历 O(N²)，这已经是下界（每个格子至少看一次）。
//
// Q2: "如果要进一步求解数独（填满空格），怎么做?"
// → 在本题数据结构基础上加回溯: 找到一个空格，尝试 1-9，
//   用 rows[i][d]/cols[j][d]/boxes[b][d] 快速判断能否放置，
//   放置后递归填下一个空格，失败则回退。即 LeetCode 37。
//
// Q3: "能用位运算加速求解器吗?"
// → 可以。用解法3的位掩码，对于空格 (i,j)，
//   可选数字 = ~(rows[i] | cols[j] | boxes[b]) & 0x1FF，
//   直接得到所有合法数字的位集合，用 lowbit 逐个提取尝试。
//   这比逐一尝试 1-9 再逐个检查要快。
//
