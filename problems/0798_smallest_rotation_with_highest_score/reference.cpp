/*
 * LeetCode 798: 得分最高的最小轮调 (Smallest Rotation with Highest Score)
 * 难度: Hard
 * 标签: Array, Prefix Sum, Difference Array
 *
 * 【题目本质】
 * 给定数组 nums，轮调 k 次后若 nums[i] <= i 则得 1 分。
 * 求使总分最高的最小 k 值。
 *
 * 核心思想: 对每个元素独立分析它在哪些 k 值下得分，
 * 用差分数组标记得分区间，前缀和还原每个 k 的总得分。
 *
 * 【解法总览】
 * 解法一: 差分数组 + 前缀和   O(n) / O(n)  唯一最优解
 * 解法二: 暴力枚举 (验证用)    O(n^2) / O(1)  TLE for n=10^5
 */


/*
 * ============================================================
 * 解法一: 差分数组 + 前缀和（唯一最优解）
 * ============================================================
 *
 * 核心推导:
 *   对于原位置 i 上的元素 v = nums[i]:
 *   - 轮调 k 后，它到达新位置 j = (i - k + n) % n
 *   - 得分条件: v <= j
 *
 *   得分的 k 区间:
 *   - lo = (i + 1) % n : 此时 j = n-1 (最大下标)，开始得分
 *   - hi = (i - v + n) % n : 此时 j = v (恰好等于值)，最后得分
 *   - k = (i - v + 1 + n) % n 时 j = v-1 < v，不再得分
 *
 *   所以每个元素的得分 k 区间是 [(i+1)%n, (i-v+n)%n]
 *   如果 lo <= hi: 正常区间
 *   如果 lo > hi: 回绕区间, 拆成 [lo, n-1] + [0, hi]
 *
 * 差分数组标记区间:
 *   正常: diff[lo]++, diff[hi+1]--
 *   回绕: diff[lo]++, diff[n]--, diff[0]++, diff[hi+1]--
 *
 * 前缀和还原: 累加 diff[k] 得到 k 的总得分
 *
 * 举例: nums = [2, 3, 1, 4, 0], n = 5
 *
 *   i=0, v=2: lo=1, hi=3 -> [1,3] 正常
 *     diff[1]++, diff[4]--
 *
 *   i=1, v=3: lo=2, hi=3 -> [2,3] 正常
 *     diff[2]++, diff[4]--
 *
 *   i=2, v=1: lo=3, hi=1 -> [3,4]+[0,1] 回绕
 *     diff[3]++, diff[5]--, diff[0]++, diff[2]--
 *
 *   i=3, v=4: lo=4, hi=4 -> [4,4] 正常
 *     diff[4]++, diff[5]--
 *
 *   i=4, v=0: lo=0, hi=4 -> [0,4] 正常
 *     diff[0]++, diff[5]--
 *
 *   diff = [2, 1, 0, 1, 0, -4]  (索引 0~5)
 *   前缀和: k=0: 2, k=1: 3, k=2: 3, k=3: 4, k=4: 4
 *   最大得分 = 4, 最小 k = 3 -> 返回 3
 *
 * 时间: O(n), 空间: O(n)
 */
class Solution1 {
public:
    int bestRotation(vector<int>& nums) {
        int n = nums.size();
        vector<int> diff(n + 1, 0);  // 差分数组, 大小 n+1 防越界

        for (int i = 0; i < n; i++) {
            int v = nums[i];
            // 得分 k 区间: lo = (i+1)%n, hi = (i-v+n)%n
            int lo = (i + 1) % n;
            int hi = (i - v + n) % n;

            if (lo <= hi) {
                // 正常区间 [lo, hi]
                diff[lo]++;
                diff[hi + 1]--;
            } else {
                // 回绕区间: [lo, n-1] + [0, hi]
                diff[lo]++;
                diff[n]--;       // 关闭 [lo, n-1]
                diff[0]++;       // 打开 [0, hi]
                diff[hi + 1]--;  // 关闭 [0, hi]
            }
        }

        // 前缀和求每个 k 的得分，取最大值对应的最小 k
        int bestK = 0, maxScore = 0, score = 0;
        for (int k = 0; k < n; k++) {
            score += diff[k];
            if (score > maxScore) {
                maxScore = score;
                bestK = k;
            }
        }

        return bestK;
    }
};


/*
 * ============================================================
 * 解法二: 暴力枚举 (用于验证，面试不推荐)
 * ============================================================
 *
 * 思路:
 *   枚举每个 k (0 到 n-1)，计算轮调 k 后的得分。
 *   对每个 k，检查所有位置 i 是否满足 nums[(i+k)%n] <= i。
 *
 * 这里 nums[(i+k)%n] 表示轮调 k 后位置 i 上的元素:
 *   原来在位置 (i+k)%n 的元素，轮调 k 后移到位置 i
 *
 * 举例: nums = [2, 3, 1, 4, 0], k = 3
 *   轮调后: [4, 0, 2, 3, 1]
 *   得分: 4<=0? N, 0<=1? Y, 2<=2? Y, 3<=3? Y, 1<=4? Y -> 4分
 *
 * 时间: O(n^2), 空间: O(1)
 * n = 10^5 时约 10^10 次操作，TLE
 */
class Solution2 {
public:
    int bestRotation(vector<int>& nums) {
        int n = nums.size();
        int bestK = 0, maxScore = 0;

        for (int k = 0; k < n; k++) {
            int score = 0;
            for (int i = 0; i < n; i++) {
                // 轮调 k 后，位置 i 上的元素是 nums[(i+k)%n]
                if (nums[(i + k) % n] <= i) {
                    score++;
                }
            }
            if (score > maxScore) {
                maxScore = score;
                bestK = k;
            }
        }

        return bestK;
    }
};


/*
 * ============================================================
 * 【解法对比】
 *
 * | 解法              | 时间    | 空间  | 特点                          |
 * |-------------------|---------|-------|------------------------------|
 * | 差分数组 (解法一)   | O(n)    | O(n)  | 唯一最优，面试必会             |
 * | 暴力枚举 (解法二)   | O(n^2)  | O(1)  | 逻辑简单，仅用于验证           |
 *
 * 面试推荐: 解法一是唯一能过大数据的方案。
 * 先讲暴力思路，再推导差分优化。
 *
 * ============================================================
 * 【易错点】
 *
 * 1. 区间边界推导错误:
 *    错: lo = i, hi = (i - nums[i] - 1 + n) % n
 *    对: lo = (i+1)%n, hi = (i-nums[i]+n)%n
 *    推导: k = (i+1)%n 时 j = (i-(i+1)+n)%n = (n-1)%n = n-1
 *          k = (i-v+n)%n 时 j = (i-(i-v+n)+n)%n = v%n = v
 *
 * 2. 回绕区间不拆分:
 *    错: diff[lo]++, diff[hi+1]-- (lo > hi 时 diff[hi+1] 在 lo 之前)
 *    对: 必须拆成两段分别标记
 *
 * 3. diff 数组大小不够:
 *    错: vector<int> diff(n, 0); -> diff[n] 越界
 *    对: vector<int> diff(n+1, 0); 保证 diff[hi+1] 和 diff[n] 合法
 *
 * 4. 忽略 nums[i] == 0 的特殊情况:
 *    v=0 时 hi = i, lo = (i+1)%n, 如果 i < n-1 则 lo > 0 = lo? 不对...
 *    实际: lo = (i+1)%n, hi = i, lo > hi (除非 i = n-1)
 *    回绕区间 [(i+1)%n, n-1] + [0, i] 即 [0, n-1] 覆盖全部 k
 *    这是正确的: 值为 0 的元素在任何位置都得分
 *
 * 5. 最大得分取最小 k:
 *    错: 用 >= 比较 (会取到更大的 k)
 *    对: 用 > 比较 (只在严格更大时更新, 保证 k 最小)
 *
 * ============================================================
 * 【面试追问】
 *
 * Q1: 差分数组和前缀和的关系？
 * -> 差分是前缀和的逆运算。对差分数组求前缀和得到原数组。
 *    区间 [l,r] 加 c: diff[l]+=c, diff[r+1]-=c
 *    前缀和还原: a[i] = sum(diff[0..i])
 *
 * Q2: 为什么不直接用 BIT 或线段树？
 * -> 本题只需 "所有区间更新 + 一次性查询所有位置"，
 *    差分数组足够且最简单。BIT/线段树适合在线查询场景。
 *
 * Q3: 时间复杂度为什么是 O(n)？
 * -> n 个元素各做一次 O(1) 差分标记 = O(n)
 *    一次前缀和遍历 = O(n)
 *    总计 O(n)
 *
 * Q4: 这题和 LeetCode 1109 的本质区别？
 * -> 1109 是线性区间加；本题的区间可能回绕（环形），
 *    需要额外处理回绕拆分。
 * ============================================================
 */
