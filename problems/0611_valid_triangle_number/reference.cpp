/*
 * LeetCode 611: 有效三角形的个数 (Valid Triangle Number)
 *
 * 【题目本质】
 * 统计数组中能构成三角形的三元组个数。
 * 三角形条件：任意两边之和 > 第三边。
 * 排序后只需检查最小两边之和 > 最大边。
 *
 * 【解法总览】
 * 解法1: 暴力枚举       — O(n^3) / O(1)      — 最直觉
 * 解法2: 排序+二分查找   — O(n^2 log n) / O(1) — 中间优化
 * 解法3: 排序+双指针     — O(n^2) / O(1)      — 面试首选
 */

// ============================================================
// 解法1: 暴力枚举 — O(n^3) / O(1)
//
// 【思路】
// 枚举所有三元组，检查三角形条件。
// n=1000 时约 10^9 次操作，太慢。作为面试起点展示理解。
// ============================================================
class Solution1 {
public:
    int triangleNumber(vector<int>& nums) {
        int n = nums.size(), count = 0;
        for (int i = 0; i < n; i++)
            for (int j = i + 1; j < n; j++)
                for (int k = j + 1; k < n; k++)
                    if (nums[i] + nums[j] > nums[k] &&
                        nums[i] + nums[k] > nums[j] &&
                        nums[j] + nums[k] > nums[i])
                        count++;
        return count;
    }
};

// ============================================================
// 解法2: 排序 + 二分查找 — O(n^2 log n) / O(1)
//
// 【思路】
// 排序后 a <= b <= c:
// - a+c > b 自动成立 (c >= b, 加上 a >= 0)
// - b+c > a 自动成立 (b >= a, 加上 c >= 0)
// - 只需检查 a+b > c
//
// 固定 a=nums[i], b=nums[j]，二分找最大的 c 使得 a+b > c。
// 有效 c 的范围是 [j+1, k-1]，其中 k 是第一个 >= a+b 的位置。
// ============================================================
class Solution2 {
public:
    int triangleNumber(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        int n = nums.size(), count = 0;

        for (int i = 0; i < n - 2; i++) {
            for (int j = i + 1; j < n - 1; j++) {
                int sum = nums[i] + nums[j];
                // lower_bound 找第一个 >= sum 的位置
                int k = lower_bound(nums.begin() + j + 1,
                                    nums.end(), sum) - nums.begin();
                // [j+1, k-1] 范围内的 c 都满足 a+b > c
                count += k - j - 1;
            }
        }

        return count;
    }
};

// ============================================================
// 解法3: 排序 + 双指针 — O(n^2) / O(1) ⭐ 面试首选
//
// 【思路】
// 固定最大边 c = nums[k]（从右到左枚举），
// 用双指针 i=0, j=k-1 在 [0, k-1] 中找 a+b > c 的对数。
//
// - nums[i]+nums[j] > nums[k]:
//   i 到 j-1 的所有左端点都满足，贡献 j-i 个，j--
// - nums[i]+nums[j] <= nums[k]:
//   两边之和不够大，i++ 增大较小边
//
// 示例 (nums = [2,2,3,4], 已排序):
//   k=3 (c=4): i=0, j=2
//     2+3=5 > 4 ✓ → count += 2 (j-i=2), j=1
//     2+2=4 > 4? ✗ → i=1, i >= j → 停
//   k=2 (c=3): i=0, j=1
//     2+2=4 > 3 ✓ → count += 1 (j-i=1), j=0
//     i >= j → 停
//   总计: 2+1 = 3 ✓
// ============================================================
class Solution3 {
public:
    int triangleNumber(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        int n = nums.size();
        int count = 0;

        // 固定最大边 nums[k]
        for (int k = n - 1; k >= 2; k--) {
            int i = 0, j = k - 1;
            while (i < j) {
                if (nums[i] + nums[j] > nums[k]) {
                    // 因为数组已排序，nums[i] 是最小的
                    // 如果最小的 i 都满足，那 i+1, i+2, ..., j-1 当然也满足
                    // 所以一次性计入 j-i 个有效组合
                    count += j - i;
                    j--;  // 缩小较大边，继续找
                } else {
                    i++;  // 两边之和不够大，增大较小边
                }
            }
        }

        return count;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间         | 空间  | 面试推荐 |
// |------------|-------------|-------|----------|
// | 暴力       | O(n^3)      | O(1)  | 起步     |
// | 排序+二分  | O(n^2 logn) | O(1)  | 中等     |
// | 排序+双指针 | O(n^2)     | O(1)  | ⭐ 首选  |
//
// 面试建议：
// - 先说暴力 O(n^3)（展示理解）
// - 排序后只需检查一个条件 → O(n^2 log n) 二分
// - 双指针替代二分 → O(n^2)
// - 每步优化都说清"为什么更好"
//
// 【易错点】
// 1. 忘记排序:
//    ✗ 不排序就双指针 → 单调性不成立，逻辑错误
//    ✓ 必须先 sort
//
// 2. 计数错误:
//    ✗ count++ → 只计了一个组合
//    ✓ count += j - i → 一次计入所有有效组合
//
// 3. 固定最小边而非最大边:
//    ✗ 固定 nums[i] → 双指针不好统计
//    ✓ 固定 nums[k] (最大边) → 满足条件时 count += j-i
//
// 4. 三角形条件检查不完整:
//    ✗ 未排序时只检查 a+b>c → 漏条件
//    ✓ 排序后只检查 a+b>c 是完备的
//
// 【面试追问】
// Q1: 为什么固定最大边？
//     → a+b > c 是对 a+b 的下界约束，双指针从两端收缩最自然。
//
// Q2: 能否优于 O(n^2)？
//     → 不太可能。有效三元组本身可能有 O(n^2) 个需要统计。
//
// Q3: 与 3Sum 的对比？
//     → 结构相似(排序+双指针)。3Sum 找和为0需去重，本题计数不去重。
//
// Q4: 如果要输出所有三元组？
//     → 在 count += j-i 处改为循环输出 (nums[i'], nums[j], nums[k])。
// ============================================================
