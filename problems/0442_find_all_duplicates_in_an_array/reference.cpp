/*
 * LeetCode 442: Find All Duplicates in an Array (数组中重复的数据)
 * 难度: Medium | 标签: Array, Hash Table, Sorting
 *
 * 题目: 找出数组中所有出现两次的整数
 * 约束: O(n) 时间, O(1) 额外空间 (不含输出)
 * 关键条件: 值域 [1, n], 每个整数最多出现两次
 *
 * 核心技巧: 值 v 映射到索引 v-1
 *           利用符号位做原地标记
 */


// =====================================================
// 解法一: 原地取反标记法 (最优解, 面试首选)
// =====================================================
// 思路: 值 v → 索引 v-1, 第一次访问取反标记, 第二次发现已为负则为重复
// 时间: O(n) — 一次遍历
// 空间: O(1) — 利用符号位, 无额外数据结构
//
// 详细 trace: nums = [4, 3, 2, 7, 8, 2, 3, 1]
//
// i=0: val=4,     idx=3, nums[3]= 7>0  → 取反 → [4,  3,  2, -7,  8,  2,  3,  1]
// i=1: val=3,     idx=2, nums[2]= 2>0  → 取反 → [4,  3, -2, -7,  8,  2,  3,  1]
// i=2: val=|-2|=2,idx=1, nums[1]= 3>0  → 取反 → [4, -3, -2, -7,  8,  2,  3,  1]
// i=3: val=|-7|=7,idx=6, nums[6]= 3>0  → 取反 → [4, -3, -2, -7,  8,  2, -3,  1]
// i=4: val=8,     idx=7, nums[7]= 1>0  → 取反 → [4, -3, -2, -7,  8,  2, -3, -1]
// i=5: val=2,     idx=1, nums[1]=-3<0  → 重复! push 2
// i=6: val=|-3|=3,idx=2, nums[2]=-2<0  → 重复! push 3
// i=7: val=|-1|=1,idx=0, nums[0]= 4>0  → 取反 → [-4, -3, -2, -7, 8, 2, -3, -1]
//
// 结果: [2, 3]
//
class Solution {
public:
    vector<int> findDuplicates(vector<int>& nums) {
        vector<int> result;

        for (int i = 0; i < (int)nums.size(); i++) {
            // 取绝对值获得原始值 (可能已被前面的操作取反)
            int val = abs(nums[i]);
            // 值 v 映射到索引 v-1
            int idx = val - 1;

            if (nums[idx] < 0) {
                // 该位置已经被标记过 → val 出现了第二次
                result.push_back(val);
            } else {
                // 第一次遇到 val, 将对应位置取反作标记
                nums[idx] = -nums[idx];
            }
        }

        // 如需恢复原数组: for (auto& x : nums) x = abs(x);

        return result;
    }
};


// =====================================================
// 解法二: 交换归位法 (Cyclic Sort)
// =====================================================
// 思路: 把每个值 v 放到索引 v-1 上, 归位后不在正确位置的就是重复的
// 时间: O(n) — 每个元素最多被交换一次到正确位置
// 空间: O(1) — 原地操作
//
// 归位规则:
//   while nums[i] != i+1 && nums[nums[i]-1] != nums[i]:
//       swap(nums[i], nums[nums[i]-1])
//   停止: (1) 已归位 或 (2) 目标位有相同值 → 重复
//
class Solution2 {
public:
    vector<int> findDuplicates(vector<int>& nums) {
        int n = nums.size();

        // 第一步: 交换归位
        for (int i = 0; i < n; i++) {
            while (nums[i] != i + 1 && nums[nums[i] - 1] != nums[i]) {
                swap(nums[i], nums[nums[i] - 1]);
            }
        }

        // 第二步: 收集不在正确位置的值
        vector<int> result;
        for (int i = 0; i < n; i++) {
            if (nums[i] != i + 1) {
                result.push_back(nums[i]);
            }
        }

        return result;
    }
};


// =====================================================
// 解法三: 加 n 标记法 (另一种原地标记思路)
// =====================================================
// 思路: 不用取反, 给 nums[v-1] 加上 n
//       如果某位置的值 > 2n → 被加了两次 → 对应索引+1 是重复数
// 时间: O(n) — 两次遍历
// 空间: O(1) — 原地操作
//
// trace (n=8):
//   i=0: val=(4-1)%8=3, nums[3]+=8 → 15
//   i=1: val=(3-1)%8=2, nums[2]+=8 → 10
//   i=2: val=(10-1)%8=1, nums[1]+=8 → 11
//   i=3: val=(15-1)%8=6, nums[6]+=8 → 11
//   i=4: val=(8-1)%8=7, nums[7]+=8 → 9
//   i=5: val=(2-1)%8=1, nums[1]+=8 → 19 > 16 → 重复!
//   i=6: val=(11-1)%8=2, nums[2]+=8 → 18 > 16 → 重复!
//   i=7: val=(9-1)%8=0, nums[0]+=8 → 12
//   扫描: nums[1]=19>16→push 2, nums[2]=18>16→push 3
//
class Solution3 {
public:
    vector<int> findDuplicates(vector<int>& nums) {
        int n = nums.size();
        vector<int> result;

        // 第一遍: 标记
        for (int i = 0; i < n; i++) {
            int val = (nums[i] - 1) % n;
            nums[val] += n;
        }

        // 第二遍: 收集 > 2n 的位置
        for (int i = 0; i < n; i++) {
            if (nums[i] > 2 * n) {
                result.push_back(i + 1);
            }
        }

        return result;
    }
};


/*
 * =====================================================
 * 解法总结
 * =====================================================
 *
 * ┌──────────────┬────────┬────────┬──────────┬────────────────┐
 * │ 解法         │ 时间   │ 空间   │ 遍历次数 │ 说明           │
 * ├──────────────┼────────┼────────┼──────────┼────────────────┤
 * │ 取反标记     │ O(n)   │ O(1)   │ 1 次     │ 最简洁, 首选   │
 * │ 交换归位     │ O(n)   │ O(1)   │ 2 次     │ Cyclic Sort    │
 * │ 加 n 标记    │ O(n)   │ O(1)   │ 2 次     │ 不用取反       │
 * └──────────────┴────────┴────────┴──────────┴────────────────┘
 *
 * "值在 [1,n] 范围" 题目家族:
 *   41.  First Missing Positive — 交换归位 (Hard)
 *   268. Missing Number — 异或/数学
 *   287. Find the Duplicate Number — Floyd 快慢指针 (不修改数组)
 *   442. Find All Duplicates — 取反标记 (本题)
 *   448. Find All Numbers Disappeared — 取反标记 (找未标记位置)
 *
 * 442 与 448 是"镜像题":
 *   442: 标记后, 第二次遇到负数 → 重复
 *   448: 标记后, 仍为正数的位置 → 消失
 *
 * 易错点:
 *   1. 忘记 abs() → nums[i] 可能已被取反, 用负值做索引越界
 *   2. 直接用 v 做索引 → 越界 (v 范围 [1,n] 不是 [0,n-1]); 应 idx = v - 1
 *   3. 交换归位时死循环 → nums[i]==nums[nums[i]-1] 时无限交换; 加退出条件
 *   4. 混淆 442 和 448 → 442 找重复, 448 找消失, 判断逻辑不同
 *
 * 面试追问:
 * Q1: 如果不允许修改原数组?
 *     → 只有一个重复数(LC287) 用 Floyd 快慢指针 O(n)/O(1);
 *       多个重复数 O(1) 空间几乎不可能, 需 O(n) 哈希集合.
 *
 * Q2: 如果每个元素可以出现任意次?
 *     → 取反标记仍有效, 但第三次遇到 nums[idx] 又变正, 需修改逻辑.
 *       更保险用 HashSet 去重结果或改用加 n 标记法.
 *
 * Q3: 如何恢复被修改的数组?
 *     → 遍历一次取绝对值: for (auto& x : nums) x = abs(x);
 *
 * 面试策略:
 *   1. 先说约束排除了哈希和排序
 *   2. 指出值域 [1,n] → 索引映射 (核心观察)
 *   3. 用 [3,1,3,2] 小例子演示取反标记
 *   4. 追问时介绍交换归位作为替代方案
 *   5. 被问 Follow-up 时: 不可修改 → 287 的 Floyd 指针
 */
