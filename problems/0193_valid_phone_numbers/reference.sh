#!/bin/bash
# LeetCode 193: Valid Phone Numbers (有效电话号码)
#
# 【题目本质】
# 从文件中筛选出符合两种格式之一的电话号码行：
#   格式A: xxx-xxx-xxxx
#   格式B: (xxx) xxx-xxxx
# 核心：正则表达式 + 整行匹配（^ 和 $）。
#
# 【解法总览】
# 解法1: grep -E 扩展正则    — 最简洁，面试首选
# 解法2: awk 正则匹配        — awk 内置正则
# 解法3: sed 正则过滤        — sed 删除不匹配行
# 解法4: grep 基本正则(BRE)  — 不用 -E 的写法

# ============================================================
# 解法1: grep -E 扩展正则 — 面试首选 ⭐
#
# 【正则解析】
# ^                     → 行首锚点
# (                     → 分组开始（ERE中(是分组符号）
#   [0-9]{3}-           → 格式A的前缀: 3个数字+横杠
#   |                   → 或
#   \([0-9]{3}\)空格     → 格式B的前缀: 字面括号+3数字+字面括号+空格
# )                     → 分组结束
# [0-9]{3}-[0-9]{4}     → 共同后缀: 3数字+横杠+4数字
# $                     → 行尾锚点
#
# 关键细节:
#   - \( 和 \) 在ERE中匹配字面括号（不是分组）
#   - (xxx) 后面有一个空格，正则中必须包含
#   - ^ 和 $ 确保整行匹配，防止子串误匹配
#
# 示例:
#   987-123-4567   → 匹配格式A ✓
#   123 456 7890   → 不匹配 ✗ (空格分隔而非横杠)
#   (123) 456-7890 → 匹配格式B ✓
# ============================================================
grep -E '^([0-9]{3}-|\([0-9]{3}\) )[0-9]{3}-[0-9]{4}$' file.txt

# ============================================================
# 解法2: awk 正则匹配
#
# 【思路】
# awk 的模式匹配：/正则/ { 动作 }
# 省略动作时默认打印整行。
# awk 的正则与 ERE 语法相同。
#
# 优势: awk 可以在匹配基础上做更多操作（如提取区号）。
# ============================================================
# awk '/^([0-9]{3}-|\([0-9]{3}\) )[0-9]{3}-[0-9]{4}$/' file.txt

# ============================================================
# 解法3: sed 正则过滤
#
# 【思路】
# sed -n '/pattern/p' — 只打印匹配的行。
# -n 抑制默认输出，/p 打印匹配行。
# -E 启用扩展正则（与 grep -E 语法一致）。
# ============================================================
# sed -n -E '/^([0-9]{3}-|\([0-9]{3}\) )[0-9]{3}-[0-9]{4}$/p' file.txt

# ============================================================
# 解法4: grep 基本正则 (BRE, 不加 -E)
#
# 【思路】
# 基本正则(BRE)中:
#   {} → 需要 \{\} 表示量词
#   () → 需要 \(\) 表示分组
#   |  → 需要 \| 表示或（GNU扩展）
#   但字面括号 ( ) → 不需要转义
#
# 对比 ERE:
#   {} () | → 直接使用（元字符）
#   字面括号 → 需要 \( \) 转义
#
# 注意: BRE 写法更繁琐，面试中推荐用 grep -E。
# ============================================================
# grep '^\([0-9]\{3\}-\|([0-9]\{3\}) \)[0-9]\{3\}-[0-9]\{4\}$' file.txt

# ============================================================
# 【解法对比】
#
# | 解法        | 语法复杂度 | 可读性 | 兼容性             | 面试推荐 |
# |-------------|-----------|--------|-------------------|---------|
# | grep -E     | 低        | 高     | POSIX, 通用        | ⭐ 首选  |
# | awk         | 低        | 高     | POSIX, 通用        | 可选     |
# | sed -n -E   | 中        | 中     | POSIX, 通用        | 可选     |
# | grep (BRE)  | 高        | 低     | 最通用(无需-E支持)  | 避免     |
#
# ============================================================
# 【易错点】
#
# 1. 忘记 ^ 和 $:
#    ✗ grep -E '([0-9]{3}-|\([0-9]{3}\) )[0-9]{3}-[0-9]{4}'
#      → 子串匹配: "abc123-456-7890xyz" 也会被匹配
#    ✓ 加上 ^ 和 $ 锚定整行
#
# 2. ERE 中括号转义方向搞反:
#    ✗ grep -E '(xxx)' → 这是正则分组，不匹配字面括号
#    ✓ grep -E '\(xxx\)' → 匹配字面括号字符
#
# 3. 漏掉 (xxx) 后的空格:
#    ✗ \([0-9]{3}\)[0-9]{3}  → (123)456 无空格
#    ✓ \([0-9]{3}\) [0-9]{3} → (123) 456 有空格
#
# 4. 最后一段数字位数:
#    ✗ [0-9]{3}-[0-9]{3}  → 最后应该4位
#    ✓ [0-9]{3}-[0-9]{4}  → 最后4位
#
# ============================================================
# 【面试追问】
#
# Q1: grep -E 和 grep -P 的区别？
#     -E 是 POSIX ERE，不支持 \d \b 等简写。
#     -P 是 Perl PCRE，功能更强但非所有系统都支持。
#
# Q2: 如何提取电话号码的子串（非整行匹配）？
#     去掉 ^$ 锚点，加 -o 参数:
#     grep -oE '([0-9]{3}-|\([0-9]{3}\) )[0-9]{3}-[0-9]{4}'
#
# Q3: 如何支持更多格式（如 +1 前缀、点分隔）？
#     正则前加 (\+1[- ]?)? 匹配可选国际前缀，
#     分隔符改为 [.-] 匹配多种分隔符。
