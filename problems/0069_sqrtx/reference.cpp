/*
 * LeetCode 69: x 的平方根 (Sqrt(x))
 *
 * 【题目本质】
 * 在 [0, x] 的有序搜索空间中，找最大的整数 k 使得 k² ≤ x。
 *
 * 【解法总览】
 * 解法1: 线性扫描        — O(√x)    / O(1) — 最直觉
 * 解法2: 二分查找        — O(log x) / O(1) — 面试首选 ⭐
 * 解法3: 牛顿迭代法      — O(log x) / O(1) — 数学加分项
 */

// ============================================================
// 解法1: 线性扫描 — 从小到大逐个试
// 时间: O(√x)  空间: O(1)
//
// 【思路】
// 最朴素的想法：从 k=0 开始逐个检查 k² 和 x 的关系。
// 当 k² 刚好超过 x 时，答案就是 k-1。
// 
// 瓶颈：搜索空间是有序的，线性扫描没有利用这个性质。
// ============================================================
class Solution1 {
public:
    int mySqrt(int x) {
        if (x == 0) return 0;
        
        long long k = 1;
        // 逐个检查，直到 k² 超过 x
        while (k * k <= x) {
            k++;
        }
        // 循环退出时 k*k > x，答案是 k-1
        return (int)(k - 1);
    }
};

// ============================================================
// 解法2: 二分查找 — 在 [0, x] 上二分找右边界 ⭐
// 时间: O(log x)  空间: O(1)
//
// 【思路】
// 搜索空间 [0, x] 中，k² 随 k 单调递增。
// 我们要找满足 k² ≤ x 的最大 k（右边界）。
//
// 二分策略：
//   - mid² ≤ x → mid 可能是答案，但更大的也可能，往右找
//   - mid² > x → mid 太大，往左找
//
// 搜索空间收缩过程 (x = 8):
// Round1: [0 ......... 8]  mid=4, 16 > 8  → right=3
// Round2: [0 .. 3]         mid=1, 1  ≤ 8  → left=2
// Round3: [2, 3]           mid=2, 4  ≤ 8  → left=3
// Round4: [3, 3]           mid=3, 9  > 8  → right=2
// left=3 > right=2 → 退出，返回 right=2 ✓
// ============================================================
class Solution2 {
public:
    int mySqrt(int x) {
        int left = 0, right = x;
        
        while (left <= right) {
            int mid = left + (right - left) / 2;
            
            // 用 long long 防止 mid*mid 溢出 int 范围
            // 当 mid ≈ 46340 时，mid*mid ≈ 2.1×10⁹，接近 INT_MAX
            long long square = (long long)mid * mid;
            
            if (square <= x) {
                // mid² ≤ x：mid 是候选答案，但可能存在更大的 k
                // 所以继续在 [mid+1, right] 中找
                left = mid + 1;
            } else {
                // mid² > x：mid 太大了
                // 答案一定在 [left, mid-1] 中
                right = mid - 1;
            }
        }
        
        // 循环结束时 left = right + 1
        // right 是最后一个满足 k² ≤ x 的值，即我们要的答案
        // 为什么是 right？因为每次 square <= x 时 left 右移跳过了 mid，
        // 而 right 最后一次被赋值是从某个 mid² > x 的 mid-1，
        // 此时 right 恰好是分界点
        return right;
    }
};

// ============================================================
// 解法2b: 二分查找（避免 long long 的写法）
// 时间: O(log x)  空间: O(1)
//
// 【思路】
// 如果面试官追问"不用 long long 能写吗？"
// 可以用 mid <= x / mid 代替 mid * mid <= x，
// 但要特判 mid == 0 避免除零。
// ============================================================
class Solution2b {
public:
    int mySqrt(int x) {
        if (x == 0) return 0; // 特判避免后面 x/mid 除零
        
        int left = 1, right = x; // left从1开始，因为x=0已处理
        
        while (left <= right) {
            int mid = left + (right - left) / 2;
            
            // mid <= x/mid 等价于 mid*mid <= x，但不会溢出
            // 注意：这里用 <= 是因为我们找的是最大的满足条件的 k
            if (mid <= x / mid) {
                left = mid + 1;
            } else {
                right = mid - 1;
            }
        }
        
        return right;
    }
};

// ============================================================
// 解法3: 牛顿迭代法 — 数学逼近
// 时间: O(log x)  空间: O(1)
//
// 【思路】
// 求 √x 等价于求 f(k) = k² - x = 0 的正根。
// 牛顿法：从初始猜测 k₀ 出发，不断用切线逼近根：
//   k_{n+1} = k_n - f(k_n)/f'(k_n)
//           = k_n - (k_n² - x) / (2·k_n)
//           = (k_n + x/k_n) / 2
//
// 收敛过程 (x = 8):
//   k₀ = 8
//   k₁ = (8 + 8/8) / 2 = (8 + 1) / 2 = 4   (整数运算)
//   k₂ = (4 + 8/4) / 2 = (4 + 2) / 2 = 3
//   k₃ = (3 + 8/3) / 2 = (3 + 2) / 2 = 2
//   k₃² = 4 ≤ 8 → 收敛，返回 2 ✓
//
// 为什么从 x 开始？
// 对于 x ≥ 1，f(x) = x²-x ≥ 0，说明 x 在根的右侧。
// 牛顿法从右侧出发，每步单调递减，直到收敛到 ⌊√x⌋。
// ============================================================
class Solution3 {
public:
    int mySqrt(int x) {
        if (x == 0) return 0;
        
        long long k = x; // 初始猜测：从 x 开始
        
        // 当 k² > x 时继续迭代
        // 一旦 k² ≤ x，说明 k 已经是 ⌊√x⌋
        while (k * k > x) {
            // 牛顿迭代公式（整数版本）
            k = (k + x / k) / 2;
        }
        
        return (int)k;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 时间      | 空间 | 适用场景                 |
// |----------|-----------|------|--------------------------|
// | 线性扫描 | O(√x)    | O(1) | 展示理解，暖场           |
// | 二分查找 | O(log x) | O(1) | 面试首选，模板通用       |
// | 牛顿迭代 | O(log x) | O(1) | 数学加分项，实际更快     |
//
// 二分 vs 牛顿：
// - 二分是通用技巧（几乎所有"有序空间上找值"的题都能用）
// - 牛顿法是数学方法，二阶收敛更快，但需要推公式
// - 面试先写二分，追问时提牛顿法展示深度
//
// 【易错点】
// 1. 溢出：mid * mid 在 mid ≈ 46340 时溢出 int
//    ✗ int square = mid * mid;
//    ✓ long long square = (long long)mid * mid;
//
// 2. 二分返回值搞反：
//    ✗ return left;   // left 在退出时 = right + 1，已越过答案
//    ✓ return right;  // right 是最后一个满足 k² ≤ x 的位置
//
// 3. 牛顿法终止条件写成相邻两次迭代相等：
//    ✗ while (k != prev_k) — 整数除法可能在两个值间震荡(如3和2之间)
//    ✓ while (k * k > x)  — 直接判断是否已收敛到答案
//
// 4. x=0 特判遗漏：
//    牛顿法初始 k=0，第一轮 x/k 除零崩溃
//    二分法 left=0, right=0, mid=0, 0*0=0 ≤ 0 → left=1 → 退出返回 right=0，恰好正确
//    但最好显式处理，避免依赖巧合
//
// 【面试追问】
// Q1(基础): 暴力解是什么？时间复杂度？
//    → 线性扫描 O(√x)，搜索空间有序 → 二分优化到 O(log x)
//
// Q2(溢出): mid*mid 会溢出吗？怎么处理？
//    → 转 long long，或用 mid <= x/mid 代替（注意 mid=0 除零保护）
//
// Q3(数学): 还有更快的方法吗？
//    → 牛顿迭代法，k = (k + x/k) / 2，二阶收敛
//
// Q4(变体): 如果要精确到小数点后6位呢？
//    → 二分改为浮点区间 [0.0, x]，终止条件 right - left < 1e-7
//    → 或牛顿法在浮点数上迭代到 |k_{n+1} - k_n| < 1e-7
//
