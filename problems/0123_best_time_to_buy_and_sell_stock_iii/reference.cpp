/*
 * LeetCode 123: 买卖股票的最佳时机 III (Best Time to Buy and Sell Stock III)
 * 
 * 【题目本质】
 * 在价格序列上最多完成两笔不重叠的买卖交易，使总利润最大化。
 * 
 * 【系列题定位】
 * Stock I (k=1) → Stock III (k=2) → Stock IV (k=任意)
 * 本题是 Stock I 的扩展，也是 Stock IV 的特例。
 *
 * 【解法总览】
 * 解法1: 前后缀分解   — O(n) / O(n) — 最直观，面试首选讲解
 * 解法2: 状态机 DP    — O(n) / O(n) — 通用框架，可扩展到 k 次
 * 解法3: 状态机空间优化 — O(n) / O(1) — 最优，面试写代码首选
 */

// ============================================================
// 解法1: 前后缀分解 — "两笔交易一定被某天分隔"
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 两笔不重叠的交易必然存在一个分割日 d:
//   第1笔在 [0..d] 完成，第2笔在 [d..n-1] 完成
// 预处理:
//   left[i]  = [0..i] 区间内做一次交易的最大利润 (从左到右, 维护最小买入价)
//   right[i] = [i..n-1] 区间内做一次交易的最大利润 (从右到左, 维护最大卖出价)
// 答案 = max(left[i] + right[i]) for all i
//
// 为什么想到这个？因为"最多2次"且"不重叠"自然引导我们切分数组。
// 每一半就是 Stock I 问题，我们已经知道怎么 O(n) 解决。
//
// 【示例过程】
// prices = [3, 3, 5, 0, 0, 3, 1, 4]
//
// left[i] (从左到右, min_price 跟踪历史最低):
//   i:     0  1  2  3  4  5  6  7
//   min:   3  3  3  0  0  0  0  0
//   left:  0  0  2  2  2  3  3  4
//
// right[i] (从右到左, max_price 跟踪未来最高):
//   i:     0  1  2  3  4  5  6  7
//   max:   5  5  5  4  4  4  4  4
//   right: 4  4  4  4  4  3  3  0
//
// left[i]+right[i]: 4 4 6 6 6 6 6 4 → 最大=6
// ============================================================
class Solution1 {
public:
    int maxProfit(vector<int>& prices) {
        int n = prices.size();
        if (n <= 1) return 0;
        
        // left[i]: 在 [0..i] 范围内做最多一次交易的最大利润
        // 本质就是 Stock I，从左到右一遍扫描
        vector<int> left(n, 0);
        int minPrice = prices[0];
        for (int i = 1; i < n; i++) {
            minPrice = min(minPrice, prices[i]);
            // 要么延续之前的最大利润，要么今天卖出（买入价是历史最低）
            left[i] = max(left[i - 1], prices[i] - minPrice);
        }
        
        // right[i]: 在 [i..n-1] 范围内做最多一次交易的最大利润
        // "反向 Stock I"：从右往左扫描，维护未来最高卖出价
        vector<int> right(n, 0);
        int maxPrice = prices[n - 1];
        for (int i = n - 2; i >= 0; i--) {
            maxPrice = max(maxPrice, prices[i]);
            // 要么延续右边的最大利润，要么今天买入（卖出价是未来最高）
            right[i] = max(right[i + 1], maxPrice - prices[i]);
        }
        
        // 枚举分割点：第1笔在左半完成，第2笔在右半完成
        // left[i] 和 right[i] 都包含"不交易=0"的情况
        // 所以枚举每个 i，left[i]+right[i] 覆盖了0次、1次、2次交易
        int result = 0;
        for (int i = 0; i < n; i++) {
            result = max(result, left[i] + right[i]);
        }
        return result;
    }
};


// ============================================================
// 解法2: 状态机 DP（二维表）— 股票系列通用框架
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 前后缀分解虽然直观，但只适用于 k=2。要扩展到 k 次，需要状态机。
// 
// 定义5种状态（每天结束时所处的阶段）:
//   s0: 未操作（利润恒为0，可以省略）
//   s1: 完成第1次买入（持有股票）
//   s2: 完成第1次卖出（不持有）
//   s3: 完成第2次买入（持有股票）
//   s4: 完成第2次卖出（不持有）
//
// 状态转移（每个状态要么保持，要么从前一个状态转来）:
//   s1[i] = max(s1[i-1],        -prices[i])        // 保持 or 首次买入
//   s2[i] = max(s2[i-1], s1[i-1]+prices[i])        // 保持 or 第1次卖出
//   s3[i] = max(s3[i-1], s2[i-1]-prices[i])        // 保持 or 第2次买入
//   s4[i] = max(s4[i-1], s3[i-1]+prices[i])        // 保持 or 第2次卖出
//
// 【DP 填表方向】从左到右，每行依赖上一行的同列或自身
//
//  day  price   s1    s2    s3    s4
//  ──────────────────────────────────
//   0    3      -3     0    -3     0
//   1    3      -3     0    -3     0
//   2    5      -3     2    -3     2
//   3    0       0     2     2     2
//   4    0       0     2     2     2
//   5    3       0     3     2     5
//   6    1       0     3     2     5
//   7    4       0     4     2     6  ← ans = 6
//
// 与 Stock I 的关系: Stock I 只有 s1, s2 两个状态
// 与 Stock IV 的关系: k次交易就是 s1..s_{2k} 共 2k 个状态
// ============================================================
class Solution2 {
public:
    int maxProfit(vector<int>& prices) {
        int n = prices.size();
        if (n <= 1) return 0;
        
        vector<int> s1(n), s2(n), s3(n), s4(n);
        
        // 初始化：第0天只能选择买入或不操作
        s1[0] = -prices[0];   // 第1次买入：花了 prices[0]
        s2[0] = 0;            // 第1次卖出：当天买当天卖，利润0
        s3[0] = -prices[0];   // 第2次买入：当天完成第1次(利润0)后立即第2次买入
        s4[0] = 0;            // 第2次卖出：同理，当天全部完成，利润0
        
        for (int i = 1; i < n; i++) {
            // 第1次买入：保持昨天的持有 or 今天新买入（从"未操作"状态，利润0出发）
            s1[i] = max(s1[i - 1], -prices[i]);
            // 第1次卖出：保持昨天的空仓 or 昨天持有+今天卖出
            s2[i] = max(s2[i - 1], s1[i - 1] + prices[i]);
            // 第2次买入：保持昨天的持有 or 昨天完成第1次+今天买入
            s3[i] = max(s3[i - 1], s2[i - 1] - prices[i]);
            // 第2次卖出：保持昨天的空仓 or 昨天持有+今天卖出
            s4[i] = max(s4[i - 1], s3[i - 1] + prices[i]);
        }
        
        // s4[n-1] 已经包含了 0次(=0)、1次(通过初始化传递)、2次交易的最大值
        return s4[n - 1];
    }
};


// ============================================================
// 解法3: 状态机 DP 空间优化 — 4个变量滚动
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法2中 s1[i]..s4[i] 只依赖 i-1 的值，无需数组。
// 用 buy1, sell1, buy2, sell2 四个变量代替。
//
// 初始化:
//   buy1 = INT_MIN: 还没买入过（不可能的状态用极小值表示）
//   sell1 = 0:      还没交易过，利润0
//   buy2 = INT_MIN: 同理
//   sell2 = 0:      同理
//
// 为什么更新顺序可以"就地"而不需要暂存？
// 假设 buy1 被当天的 -price 更新了（今天买入），
// 然后 sell1 = max(sell1, buy1 + price) = max(sell1, -price + price) = max(sell1, 0)
// 这相当于"今天买今天卖"利润0，不会破坏 sell1 的最优性。
//
// 与 Stock IV (k次) 的代码差异:
//   本题: buy1/sell1/buy2/sell2 四个变量
//   IV题: buy[k]/sell[k] 数组，for j in 1..k 循环更新
// ============================================================
class Solution3 {
public:
    int maxProfit(vector<int>& prices) {
        // buy1/sell1: 第1笔交易的买入余额/卖出利润
        // buy2/sell2: 第2笔交易的买入余额/卖出利润
        int buy1 = INT_MIN, sell1 = 0;
        int buy2 = INT_MIN, sell2 = 0;
        
        for (int price : prices) {
            // 第1次买入：要么保持之前的买入，要么今天新买入（从0出发花 price）
            buy1  = max(buy1, -price);
            // 第1次卖出：要么保持之前的利润，要么今天把持有的卖了
            sell1 = max(sell1, buy1 + price);
            // 第2次买入：要么保持之前的持有，要么用第1次的利润减去今天的买入价
            buy2  = max(buy2, sell1 - price);
            // 第2次卖出：要么保持之前的利润，要么今天把第2次持有的卖了
            sell2 = max(sell2, buy2 + price);
        }
        
        // sell2 >= sell1 >= 0，所以直接返回 sell2
        return sell2;
    }
};


// ============================================================
// 【解法对比】
//
// | 解法 | 时间 | 空间 | 直觉性 | 可扩展到k次 |
// |------|------|------|--------|------------|
// | 前后缀分解 | O(n) | O(n) | ★★★★★ | ✗ 仅k=2 |
// | 状态机数组 | O(n) | O(n) | ★★★☆☆ | ✓ |
// | 状态机变量 | O(n) | O(1) | ★★★☆☆ | ✓ |
//
// 面试建议:
// - 先讲前后缀分解（展示问题分解能力）
// - 再讲状态机（展示通用化思维）
// - 最后优化到 O(1) 空间（展示代码优化能力）
//
// ============================================================
// 【易错点】
//
// 1. right 数组扫描方向:
//    ✗ 从左到右维护 minPrice，算的还是"到第i天"的利润
//    ✓ 从右到左维护 maxPrice（未来最高卖出价），right[i] = maxPrice - prices[i]
//
// 2. 状态机初始化 buy 为 0:
//    ✗ buy1 = 0 → 意味着不花钱就持有了股票
//    ✓ buy1 = INT_MIN → 表示"还没发生过买入"的不可能状态
//       或 buy1 = -prices[0] → 表示"第0天买入"
//
// 3. 前后缀法分割点范围:
//    ✗ left[i] + right[i+1] 然后 i 从 0 到 n-2
//      → 漏掉了"只做1次交易"（不分割）的情况
//    ✓ left[i] + right[i] 然后 i 从 0 到 n-1
//      → right[i] 包含"不交易=0"，自然覆盖只做1次的情况
//
// 4. 状态机更新用了当天更新后的值会不会出错?
//    不会! 如果 buy1 被更新为 -price（今天买入），
//    sell1 = max(sell1, buy1+price) = max(sell1, 0)
//    相当于当天买当天卖利润0，不影响 sell1 的最优性。
//
// ============================================================
// 【面试追问】
//
// Q1: 基础 — 只允许1次交易怎么做？
// → Stock I: 维护 min_price, 每天更新 max_profit = max(profit, price - min_price)
//   O(n) 时间 O(1) 空间。
//
// Q2: 递进 — 从2次推广到最多 k 次交易怎么办？
// → Stock IV: 把 buy1/sell1/buy2/sell2 泛化为 buy[1..k]/sell[1..k]
//   for each price: for j = 1..k: buy[j] = max(buy[j], sell[j-1]-price)
//                                 sell[j] = max(sell[j], buy[j]+price)
//   注意: 当 k >= n/2 时退化为无限次交易（Stock II），直接贪心。
//
// Q3: 变体 — 如果有冷冻期（卖出后下一天不能买入）？
// → Stock with Cooldown (309): 状态机加一个 cooldown 状态
//   buy[i] = max(buy[i-1], cooldown[i-1] - price)
//   sell[i] = max(sell[i-1], buy[i-1] + price)
//   cooldown[i] = max(cooldown[i-1], sell[i-1])
//
// Q4: 前后缀分解能否优化到 O(1) 空间？
// → 不能，因为需要预处理整个 right[] 数组后才能和 left[] 配对。
//   要 O(1) 空间必须用状态机方法。
// ============================================================
