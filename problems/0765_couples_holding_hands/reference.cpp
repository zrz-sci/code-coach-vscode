/*
 * LeetCode 765: Couples Holding Hands (情侣牵手)
 *
 * 【题目本质】
 * n 对情侣坐在 2n 个座位上，情侣编号为 (0,1),(2,3),...,(2n-2,2n-1)。
 * 每次可以交换任意两人的座位，求让每对情侣相邻的最少交换次数。
 * 核心洞察：编号 x 的伴侣是 x^1（异或 1），贪心逐对修复即可。
 *
 * 【解法总览】
 * 解法1: 贪心交换（位置数组） — O(n) / O(n) — 面试首选，直觉简单
 * 解法2: 并查集（连通分量）  — O(n*alpha) / O(n) — 进阶，图论建模
 * 解法3: 贪心变体（无位置数组）— O(n²) / O(1) — 空间更优，但时间稍差
 */

// ============================================================
// 解法1: 贪心交换 + 位置数组 — 面试首选 ⭐
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 从左到右扫描每对座位 (0,1), (2,3), (4,5), ...
// 如果当前一对座位上的两个人不是情侣，就把正确的伴侣交换过来。
// 用 pos[person] = seat_index 实现 O(1) 找人。
//
// 示例: row = [0, 2, 1, 3]
//   pos = [0, 2, 1, 3]  // 人0在座位0, 人1在座位2, 人2在座位1, 人3在座位3
//
//   i=0: row[0]=0, 伴侣=0^1=1, row[1]=2≠1
//     找到人1的位置: pos[1]=2
//     交换 row[1] 和 row[2]: row = [0, 1, 2, 3]
//     更新 pos[2]=2, pos[1]=1
//     swaps = 1
//
//   i=2: row[2]=2, 伴侣=2^1=3, row[3]=3 ✓
//     不需要交换
//
//   结果: 1
//
// 为什么贪心是最优的？
//   1. 每对不匹配的座位至少需要 1 次交换
//   2. 我们的贪心每次交换恰好修复 1 对
//   3. 交换不会破坏已修复的对（被换走的人来自右边未处理区域）
//   4. 所以交换次数 = 不匹配的对数 = 最小可能
// ============================================================
class Solution1 {
public:
    int minSwapsCouples(vector<int>& row) {
        int n = row.size();
        // pos[person] = 这个人坐在哪个座位
        vector<int> pos(n);
        for (int i = 0; i < n; i++) {
            pos[row[i]] = i;
        }

        int swaps = 0;
        for (int i = 0; i < n; i += 2) {
            // row[i] 的伴侣编号: 异或 1
            // 0^1=1, 1^1=0, 2^1=3, 3^1=2, ...
            int partner = row[i] ^ 1;

            if (row[i + 1] != partner) {
                // 伴侣不在旁边，需要交换
                int j = pos[partner]; // 伴侣实际坐在座位 j

                // 交换前更新 pos:
                // row[i+1] 这个人要被换到座位 j
                pos[row[i + 1]] = j;
                // partner 要被换到座位 i+1
                pos[partner] = i + 1;

                // 执行交换
                swap(row[i + 1], row[j]);
                swaps++;
            }
        }
        return swaps;
    }
};

// ============================================================
// 解法2: 并查集 — 进阶解法
// 时间: O(n * alpha(n))  空间: O(n)
//
// 【思路】
// 将问题建模为图论中的置换环问题。
// 把每对座位看成一个"位置节点"（共 n 个节点，0 到 n-1）。
// 对于座位 2i 和 2i+1 上的两个人 a 和 b：
//   - a 属于"情侣组" a/2
//   - b 属于"情侣组" b/2
//   - 执行 union(a/2, b/2)
//
// 如果一个连通分量包含 k 个情侣组，说明这 k 对情侣互相"纠缠"，
// 需要 k-1 次交换来理清（类似长度为 k 的置换环需要 k-1 次交换）。
//
// 总交换次数 = n - 连通分量数
//
// 示例: row = [0, 2, 1, 3]
//   座位 0-1: 人0(组0) 和 人2(组1) → union(0, 1)
//   座位 2-3: 人1(组0) 和 人3(组1) → union(0, 1) // 已在一组
//   连通分量数 = 1
//   答案 = 2 - 1 = 1 ✓
//
// 示例: row = [3, 2, 0, 1]
//   座位 0-1: 人3(组1) 和 人2(组1) → union(1, 1) // 同组，已是情侣
//   座位 2-3: 人0(组0) 和 人1(组0) → union(0, 0) // 同组，已是情侣
//   连通分量数 = 2
//   答案 = 2 - 2 = 0 ✓
// ============================================================
class Solution2 {
    vector<int> parent, rank_;

    int find(int x) {
        if (parent[x] != x) {
            parent[x] = find(parent[x]); // 路径压缩
        }
        return parent[x];
    }

    bool unite(int x, int y) {
        int px = find(x), py = find(y);
        if (px == py) return false; // 已在同一组
        // 按秩合并
        if (rank_[px] < rank_[py]) swap(px, py);
        parent[py] = px;
        if (rank_[px] == rank_[py]) rank_[px]++;
        return true; // 成功合并
    }

public:
    int minSwapsCouples(vector<int>& row) {
        int n = row.size() / 2; // 情侣对数
        parent.resize(n);
        rank_.resize(n, 0);
        iota(parent.begin(), parent.end(), 0); // parent[i] = i

        int swaps = 0;
        for (int i = 0; i < 2 * n; i += 2) {
            int groupA = row[i] / 2;     // 座位 i 上的人属于哪个情侣组
            int groupB = row[i + 1] / 2; // 座位 i+1 上的人属于哪个情侣组
            if (unite(groupA, groupB)) {
                swaps++; // 合并成功说明这两个组之前不在一起，需要一次交换
            }
        }
        return swaps;
    }
};

// ============================================================
// 解法3: 贪心（无位置数组，线性扫描找人）
// 时间: O(n²) 最坏  空间: O(1) 额外空间
//
// 【思路】
// 和解法1相同的贪心策略，但不用 pos 数组。
// 找伴侣时线性扫描右边的座位。
// 空间更优，但时间退化为 O(n²)。
// 仅在 n 极小时可考虑（本题 n ≤ 30，实际差别不大）。
//
// 示例: row = [0, 2, 1, 3]
//   i=0: row[0]=0, 伴侣=1, row[1]=2≠1
//     线性扫描 j=2,3,... 找到 row[2]=1
//     交换 row[1] 和 row[2]
//     swaps = 1
// ============================================================
class Solution3 {
public:
    int minSwapsCouples(vector<int>& row) {
        int n = row.size();
        int swaps = 0;
        for (int i = 0; i < n; i += 2) {
            int partner = row[i] ^ 1;
            if (row[i + 1] == partner) continue;

            // 线性扫描找到伴侣
            for (int j = i + 2; j < n; j++) {
                if (row[j] == partner) {
                    swap(row[i + 1], row[j]);
                    swaps++;
                    break;
                }
            }
        }
        return swaps;
    }
};

/*
 * 易错点总结:
 * 1. 伴侣公式是 x^1 不是 x+1 或 x-1
 *    - 人0的伴侣是1, 人1的伴侣是0, 人2的伴侣是3, 人3的伴侣是2
 * 2. 解法1中交换后必须同步更新 pos 数组
 *    - 先更新 pos[row[i+1]] = j（被换走的人去了位置 j）
 *    - 再更新 pos[partner] = i+1（伴侣来到了位置 i+1）
 *    - 注意顺序：必须在 swap(row[i+1], row[j]) 之前更新 pos
 * 3. 并查集建模对象是"情侣组"（person/2），不是人或座位
 * 4. 并查集中 unite 返回 true 的次数就是交换次数
 *
 * 面试追问:
 * Q: 证明贪心最优性？
 *    → 每次交换修复恰好一对，不破坏已修复的对，所以是最少交换。
 * Q: 并查集的理论基础？
 *    → 置换环理论：k 元素的环需要 k-1 次交换归位。
 * Q: 如果要输出交换方案？
 *    → 贪心法中记录每次 swap 的两个位置即可。
 * Q: 时间复杂度能否低于 O(n)？
 *    → 不能，至少要读一遍输入，O(n) 已是最优。
 *
 * ============================================================
 * 总结：解法对比 & 面试要点
 * ============================================================
 *
 * 【解法选择决策树】
 *
 *   需要最优时间？
 *    ├─ YES → 贪心+位置数组 O(n), O(n)  ← 面试首选
 *    │         直觉清晰: 逐对扫描，不匹配就把伴侣换过来
 *    ├─ 想展示图论功底 → 并查集 O(n*alpha), O(n)  ← 进阶加分
 *    │         建模: 置换环理论，连通分量数推出交换次数
 *    └─ 空间优先 → 贪心无pos数组 O(n²), O(1)
 *              n<=30时实际可接受
 *
 * | 解法           | 时间         | 空间   | 面试推荐 |
 * |---------------|-------------|--------|---------|
 * | 贪心+位置数组  | O(n)        | O(n)   | ⭐⭐⭐  |
 * | 并查集        | O(n*alpha)  | O(n)   | ⭐⭐    |
 * | 贪心(无pos)   | O(n²)       | O(1)   | ⭐     |
 *
 * 【核心易错点】
 * 1. 伴侣公式是 x^1（异或）不是 x+1 或 x-1
 *    0^1=1, 1^1=0, 2^1=3, 3^1=2 — 偶数+1、奇数-1 的效果
 * 2. 交换时必须先更新 pos 再执行 swap — 否则 pos 数组会不一致
 *    顺序: pos[row[i+1]]=j → pos[partner]=i+1 → swap(row[i+1], row[j])
 * 3. 并查集建模对象是"情侣组"(person/2) — 不是人也不是座位
 * 4. 并查集中 unite 返回 true 的次数 = 交换次数
 *    等价公式: 交换次数 = n(对数) - 连通分量数
 *
 * 【面试追问链 Q1 → Q2 → Q3】
 *
 * Q1: 如何证明贪心是最优的？
 *   → 每对不匹配的座位至少需要1次交换来修复。贪心每次交换恰好修复1对，
 *     且不会破坏已修复的对（被换走的人来自右边未处理区域）。
 *     因此交换次数 = 不匹配对数 = 下界。
 *
 * Q2: 并查集方案的数学本质是什么？
 *   → 置换环理论: 将"当前状态"到"目标状态"的映射看成置换。
 *     一个长度为 k 的环需要 k-1 次交换来归位。
 *     总交换 = sum(环长-1) = n - 环数 = n - 连通分量数。
 *
 * Q3: 如果情侣不是 (0,1),(2,3),... 而是任意配对关系，怎么改？
 *   → 用 HashMap 存配对关系 partner[a]=b, partner[b]=a。
 *     贪心和并查集的框架不变，只需把 x^1 替换为 partner[x]。
 */
