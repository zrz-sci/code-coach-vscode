/*
 * LCR 152: 验证二叉搜索树的后序遍历序列
 *
 * 难度: Medium
 * 标签: Stack, Tree, Binary Search Tree, Recursion, Array, Binary Tree, Monotonic Stack
 *
 * 题意:
 *   判断整数数组 postorder 是否可能是某棵 BST 的后序遍历结果
 *   后序遍历: 左-右-根  (最后一个是根)
 *   BST性质:  左子树 < 根 < 右子树
 *
 * 递归分治的核心逻辑:
 *
 *   postorder = [4, 6, 5, 9, 8]
 *
 *   对应BST:       8
 *                /   \
 *               5     9
 *              / \
 *             4   6
 *
 *   后序结构: [左子树, 右子树, 根]
 *             [4,6,5,  9,      8]
 *              全<8    全>8    根
 *
 *   第一个 >= root 的位置就是右子树起点
 *   验证右子树部分全 > root, 然后递归验证左右子树
 *
 * 递归分解树:
 *
 *            verify([4,6,5,9,8])       root=8, m=3
 *              ┌──────┴───────┐
 *    verify([4,6,5])       verify([9])   root=5
 *      ┌────┴────┐            │
 *   verify([4]) verify([6]) return true
 *      │            │
 *   return true  return true
 */

// =====================================================
// 解法1: 递归分治 (推荐, 直观易懂)
// 时间: O(n^2) 最坏, O(n log n) 平衡
// 空间: O(n) 递归栈
// =====================================================
class Solution {
public:
    bool verifyTreeOrder(vector<int>& postorder) {
        return verify(postorder, 0, (int)postorder.size() - 1);
    }

private:
    bool verify(vector<int>& post, int l, int r) {
        // 基准情况: 空区间或单元素, 一定合法
        if (l >= r) return true;

        // 后序遍历的最后一个元素是根
        int root = post[r];

        // --- 步骤1: 找右子树的起始位置 ---
        // 从左到右扫描, 找到第一个 >= root 的位置
        // [l, m-1] 是左子树(全 < root)
        // [m, r-1] 是右子树(应全 > root)
        int m = l;
        while (m < r && post[m] < root) {
            m++;
        }

        // --- 步骤2: 验证右子树部分全 > root ---
        // 左子树部分在扫描时已经确认了全 < root
        // 只需检查右子树部分是否有违反
        for (int i = m; i < r; i++) {
            if (post[i] < root) {
                return false; // 右子树中存在 < root 的值, 违反BST
            }
        }

        // --- 步骤3: 递归验证左子树和右子树 ---
        return verify(post, l, m - 1)     // 左子树: [l, m-1]
            && verify(post, m, r - 1);    // 右子树: [m, r-1] (不含根r)
    }
};

/*
 * 执行过程 — 示例1 (合法):
 *
 *   postorder = [4, 6, 5, 9, 8]
 *
 *   verify(l=0, r=4):
 *     root = 8
 *     扫描: post[0]=4<8, post[1]=6<8, post[2]=5<8, post[3]=9>=8  → m=3
 *     左子树 [4,6,5], 右子树 [9]
 *     验证右子树: post[3]=9>8 ✓
 *     递归左: verify(0,2)  递归右: verify(3,3)
 *
 *   verify(l=0, r=2):  [4,6,5]
 *     root = 5
 *     扫描: post[0]=4<5, post[1]=6>=5  → m=1
 *     验证右子树: post[1]=6>5 ✓
 *     递归: verify(0,0) → true, verify(1,1) → true
 *
 *   verify(l=3, r=3):  单元素 → true
 *
 *   全部 true → 返回 true ✓
 *
 *
 * 执行过程 — 示例2 (非法):
 *
 *   postorder = [4, 9, 6, 5, 8]
 *
 *   verify(l=0, r=4):
 *     root = 8
 *     扫描: post[0]=4<8, post[1]=9>=8  → m=1
 *     左子树 [4], 右子树 [9,6,5]
 *     验证右子树: post[1]=9>8 ✓, post[2]=6<8 ✗!
 *     返回 false ✓
 */


// =====================================================
// 解法2: 单调栈 (最优, O(n))
// 时间: O(n)   空间: O(n)
// =====================================================
/*
 * 核心思想:
 *   逆序遍历后序数组 = "根-右-左" 的顺序
 *   (类似于前序遍历的镜像)
 *
 *   维护一个单调递减栈:
 *   - 如果当前值比栈顶大: 是栈顶的右子树, 直接入栈
 *   - 如果当前值比栈顶小: 进入了某个祖先的左子树
 *     → 不断弹栈, 更新上界(upper)
 *     → 当前值必须 < upper, 否则违反BST
 *
 *   逆序遍历: 8, 9, 5, 6, 4
 *
 *     处理8: stack=[], push 8       stack=[8], upper=INF
 *     处理9: 9>8, push 9            stack=[8,9], upper=INF
 *     处理5: 5<9, 弹栈
 *       pop 9 → upper=9
 *       pop 8 → upper=8
 *       5<8(upper) ✓, push 5        stack=[5], upper=8
 *     处理6: 6>5, push 6            stack=[5,6], upper=8
 *       6<8(upper) ✓
 *     处理4: 4<6, 弹栈
 *       pop 6 → upper=6
 *       pop 5 → upper=5
 *       4<5(upper) ✓, push 4        stack=[4], upper=5
 *
 *   全部通过 → true ✓
 */
class Solution2 {
public:
    bool verifyTreeOrder(vector<int>& postorder) {
        stack<int> stk;
        int upper = INT_MAX; // 当前节点值的上界

        // 逆序遍历后序数组: 按"根-右-左"顺序访问
        for (int i = (int)postorder.size() - 1; i >= 0; i--) {
            int cur = postorder[i];

            // 检查: 当前值必须小于上界
            // 如果 cur > upper, 说明左子树中出现了大于祖先的值, 违反BST
            if (cur > upper) {
                return false;
            }

            // 弹栈: 找到当前节点应属于的祖先的左子树
            // 每个比 cur 大的栈内元素都是 cur 的祖先
            // 最后一个被弹出的就是 cur 直接所在的左子树对应的根
            while (!stk.empty() && cur < stk.top()) {
                upper = stk.top(); // 更新上界为弹出的祖先值
                stk.pop();
            }

            // 将当前值入栈
            stk.push(cur);
        }

        return true;
    }
};

/*
 * 单调栈方法的直觉解释:
 *
 * 逆序遍历后序 = "根→右→左" 的DFS访问顺序
 *
 * 在DFS中:
 * - 从根到右子树: 值递增(栈保持递减, 直接入栈)
 * - 从右子树回到左子树: 值突然变小(需要弹栈找到正确的祖先)
 * - 在左子树中: 所有值必须小于最近的祖先(upper)
 *
 * 栈中维护的是"从根到当前节点"路径上的右侧祖先链
 * upper 记录的是"当前必须在其左子树中"的那个祖先的值
 */


// =====================================================
// 时间复杂度对比
// =====================================================
/*
 * | 解法       | 最好时间     | 最坏时间 | 空间  | 适用场景       |
 * |------------|-------------|----------|-------|----------------|
 * | 递归分治   | O(n log n)  | O(n^2)   | O(n)  | 面试首选, 直观 |
 * | 单调栈     | O(n)        | O(n)     | O(n)  | 最优解, 加分项 |
 *
 * 递归分治最坏 O(n^2) 的情况:
 *   后序 [1, 2, 3, 4, 5] — 完全偏斜的BST(链)
 *   每层递归只能划分出一个元素, 总共 n 层, 每层扫描 O(n)
 *
 * 单调栈的 O(n) 保证:
 *   每个元素最多入栈一次、出栈一次, 总操作 2n
 *
 * 易错点:
 * 1. 空数组 → 应返回 true
 * 2. 递归中 r-1 是右子树的范围终点(不包含根)
 * 3. 单调栈中 upper 初始为 INT_MAX(无上界限制)
 * 4. 题目保证无重复, 否则需修改 < 和 >= 的判断
 */


// =====================================================
// 总结
// =====================================================
/*
 * ── 解法对比 ──
 *
 * | 解法       | 时间(最坏)  | 时间(均摊)   | 空间  | 代码量 | 推荐度 |
 * |------------|------------ |-------------|-------|--------|--------|
 * | 递归分治   | O(n^2)      | O(n log n)  | O(n)  | 少     | ★★★ 面试首选 |
 * | 单调栈     | O(n)        | O(n)        | O(n)  | 中     | ★★★ 最优解   |
 *
 * 递归分治: 思路直接对应BST+后序的定义, 面试讲解最清晰;
 *           缺点是退化链 O(n^2), 但面试中通常可接受。
 * 单调栈:   O(n) 严格最优, 但"逆序=根右左"的直觉需要额外解释,
 *           适合作为 follow-up 优化方案展示。
 *
 * ── 易错点 (具体bug) ──
 *
 * 1. 递归基准漏判: l >= r 时直接返回 true。
 *    BUG: 写成 l > r 会漏掉单元素情况, 导致对 l==r 再取 root 后
 *    递归 verify(l, l-1) 出现越界。
 *
 * 2. 右子树验证遗漏: 找到分界点 m 后, 必须检查 [m, r-1] 全 > root。
 *    BUG: 只分治不验证 → [4,9,6,5,8] 这种非法序列也会返回 true,
 *    因为左右子树各自内部合法, 但右子树含 6<8 违反 BST 却没被捕获。
 *
 * 3. 单调栈的 upper 方向反了: 当 cur > upper 才返回 false。
 *    BUG: 写成 cur >= upper 在有重复元素时会误判合法序列。
 *    (本题保证无重复, 但万一面试官改条件要注意。)
 *
 * 4. 递归右子树范围写成 (m, r) 而非 (m, r-1):
 *    BUG: 会把根 post[r] 包含进右子树递归, 导致死循环或误判。
 *
 * ── 面试追问链 ──
 *
 * Q1: 递归分治最坏 O(n^2), 能否优化到 O(n)?
 * A1: 用单调栈。逆序遍历后序数组相当于"根-右-左"访问顺序,
 *     维护递减栈 + upper 上界, 每个元素至多入栈出栈一次。
 *
 * Q2: 如果 BST 允许重复值 (left <= root < right), 怎么改?
 * A2: 递归分治中分界条件改为 post[m] <= root (找第一个 > root 的位置),
 *     右子树验证改为检查 post[i] <= root 时 return false。
 *     单调栈中 cur > upper 改为 cur >= upper (等于祖先也违法)。
 *
 * Q3: 给定合法的后序序列, 能否在 O(n) 时间内重建这棵 BST?
 * A3: 可以。利用单调栈的思路: 逆序遍历后序 = "根-右-左",
 *     用栈追踪当前路径, 栈顶是当前子树的根。
 *     遇到更大的值 → 右子节点; 遇到更小的值 → 弹栈找到正确的祖先,
 *     作为该祖先的左子节点。O(n) 时间 O(n) 空间。
 */
