/*
 * 120. 三角形最小路径和 (Triangle)
 * 难度: Medium
 * 标签: Array, Dynamic Programming
 *
 * 题目:
 *   给定三角形数组 triangle，找出自顶向下的最小路径和。
 *   每一步只能移到下一行相邻位置（下标 i 或 i+1）。
 *   1 <= triangle.length <= 200, -10^4 <= triangle[i][j] <= 10^4
 *   Follow-up: O(n) 额外空间
 *
 * 核心思路:
 *   自底向上 DP 是最优雅的方向：
 *   dp[j] = triangle[i][j] + min(dp[j], dp[j+1])
 *   无需处理边界，答案直接是 dp[0]。
 *
 * 解法概览:
 *   解法1 - 自底向上一维DP ⭐: O(n^2) 时间, O(n) 空间
 *   解法2 - 自顶向下一维DP: O(n^2) 时间, O(n) 空间
 *   解法3 - 原地修改: O(n^2) 时间, O(1) 空间
 */

// ============================================================
// 解法 1: 自底向上一维 DP（推荐）⭐
// ============================================================
// 思路: dp[j] = 从第 i 行第 j 列到底部的最小路径和
//       从最后一行开始向上滚动
// 时间: O(n^2)  空间: O(n)
//
// DP 表模拟 (triangle = [[2],[3,4],[6,5,7],[4,1,8,3]]):
//
//   三角形:            dp 滚动过程:
//      2               初始 dp = [4, 1, 8, 3]  (最后一行)
//     3 4
//    6 5 7             i=2: dp = [7, 6, 10, 3]
//   4 1 8 3              6+min(4,1)=7, 5+min(1,8)=6, 7+min(8,3)=10
//
//                      i=1: dp = [9, 10, 10, 3]
//                        3+min(7,6)=9, 4+min(6,10)=10
//
//                      i=0: dp = [11, 10, 10, 3]
//                        2+min(9,10)=11
//
//                      答案: dp[0] = 11
//
// 空间优化原理:
//   二维: dp[i][j] = triangle[i][j] + min(dp[i+1][j], dp[i+1][j+1])
//   dp[i] 只依赖 dp[i+1] -> 压缩为一维
//   从左到右遍历 j: dp[j] 用旧 dp[j] 和旧 dp[j+1]
//     dp[j] 被覆盖后不再需要; dp[j+1] 还是旧值(尚未更新)
class Solution1 {
public:
    int minimumTotal(vector<vector<int>>& triangle) {
        int n = triangle.size();
        vector<int> dp(triangle.back());             // 初始化为最后一行
        for (int i = n - 2; i >= 0; i--)             // 从倒数第二行向上
            for (int j = 0; j <= i; j++)             // 从左到右（安全方向）
                dp[j] = triangle[i][j] + min(dp[j], dp[j + 1]);
        return dp[0];                                 // 答案直接在 dp[0]
    }
    // 关键点:
    //   - 自底向上: 每个位置都有两个子节点, 不需要边界判断
    //   - vector<int> dp(triangle.back()) 是拷贝构造
    //   - j 从左到右遍历是安全的: dp[j+1] 在本轮还未被更新
    //   - 答案直接 dp[0], 不需要额外扫描
};

// ============================================================
// 解法 2: 自顶向下一维 DP
// ============================================================
// 思路: dp[j] = 从顶部到当前行第 j 列的最小路径和
//       到达 (i,j) 可从 (i-1,j-1) 或 (i-1,j) 转移
// 时间: O(n^2)  空间: O(n)
//
// 思考过程:
//   1. dp[j] = triangle[i][j] + min(dp[j-1], dp[j])
//   2. 边界问题: j=0 时没有 dp[j-1], j=i 时没有 dp[j]
//   3. 必须从右到左遍历(否则 dp[j-1] 被覆盖)
//   4. 最终答案需要扫描最后一行的最小值
class Solution2 {
public:
    int minimumTotal(vector<vector<int>>& triangle) {
        int n = triangle.size();
        vector<int> dp(n, INT_MAX);
        dp[0] = triangle[0][0];                      // base case: 顶部

        for (int i = 1; i < n; i++) {
            for (int j = i; j >= 0; j--) {           // 从右到左，保护 dp[j-1]
                int fromLeft  = (j > 0) ? dp[j - 1] : INT_MAX;  // 左上方
                int fromAbove = (j < i) ? dp[j]     : INT_MAX;  // 正上方
                dp[j] = triangle[i][j] + min(fromLeft, fromAbove);
            }
        }
        return *min_element(dp.begin(), dp.begin() + n);  // 扫描最后一行
    }
    // 关键点:
    //   - 必须从右到左遍历，否则 dp[j-1] 被新值覆盖
    //   - j=0 和 j=i 的边界需要特判
    //   - 答案不是 dp[0]，而是 min(dp[0..n-1])
    //   - 相比自底向上，代码更复杂，更容易出错
};

// ============================================================
// 解法 3: 原地修改（O(1) 额外空间）
// ============================================================
// 思路: 直接在 triangle 数组上做自底向上 DP
// 时间: O(n^2)  空间: O(1)
//
// 注意: 修改了输入数据，面试中应先说明
class Solution3 {
public:
    int minimumTotal(vector<vector<int>>& triangle) {
        for (int i = (int)triangle.size() - 2; i >= 0; i--)
            for (int j = 0; j <= i; j++)
                triangle[i][j] += min(triangle[i + 1][j], triangle[i + 1][j + 1]);
        return triangle[0][0];
    }
    // 关键点:
    //   - 代码最精简, 但修改了输入
    //   - (int) 强转避免 size_t - 2 在空数组时下溢
    //   - 面试中先问 "可以修改输入吗？"
};

/*
 * ============================================================
 * 解法对比
 * ============================================================
 * | 维度       | 解法1 自底向上 ⭐ | 解法2 自顶向下 | 解法3 原地修改 |
 * |-----------|------------------|---------------|---------------|
 * | 时间       | O(n^2)           | O(n^2)        | O(n^2)        |
 * | 空间       | O(n)             | O(n)          | O(1)          |
 * | 边界处理   | 无需             | j=0和j=i特判   | 无需          |
 * | 答案获取   | dp[0] 直接       | 需扫描min      | triangle[0][0]|
 * | 修改输入   | 否               | 否             | 是            |
 *
 * ============================================================
 * 易错点
 * ============================================================
 * 1. 自顶向下遍历方向错误
 *    错: for(j=0..i) dp[j] = tri[i][j] + min(dp[j-1], dp[j])
 *        // dp[j-1] 已被覆盖!
 *    对: for(j=i..0) 从右到左
 *
 * 2. 自顶向下忘记边界判断
 *    错: dp[j] = tri[i][j] + min(dp[j-1], dp[j])
 *        // j=0 时 dp[-1] 越界!
 *    对: 用 (j>0)?dp[j-1]:INT_MAX 保护
 *
 * 3. dp 初始化错误
 *    错: vector<int> dp(n, 0)  // 0 不是正确初始值
 *    对: vector<int> dp(triangle.back())  // 用最后一行
 *
 * 4. 自顶向下忘记取最后一行最小值
 *    错: return dp[0]  // 这是自底向上的返回!
 *    对: return *min_element(dp.begin(), dp.begin()+n)
 *
 * ============================================================
 * 面试追问
 * ============================================================
 * Q1: 为什么自底向上更好?
 * A1: (1)无需边界判断 (2)答案直接 dp[0]，代码更简洁不易出错。
 *
 * Q2: 如果要输出最小路径本身?
 * A2: 额外维护 choice[i][j] 记录每步选择方向，DP 后回溯。
 *     需要 O(n^2) 额外空间。
 *
 * Q3: 推广到任意 DAG 上的最短路径?
 * A3: 三角形本质是 DAG（有向无环图）。一般 DAG 最短路可以
 *     用拓扑排序 + DP。三角形因结构规整可以省去拓扑排序。
 */
