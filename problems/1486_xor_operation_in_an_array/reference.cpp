/*
 * LeetCode 1486: XOR Operation in an Array (数组异或操作)
 *
 * 【题目本质】
 * 给定 n 和 start，数组 nums[i] = start + 2*i (i = 0..n-1)。
 * 返回 nums[0] ^ nums[1] ^ ... ^ nums[n-1]。
 *
 * 【解法总览】
 * 解法1: 直接模拟        — O(n) / O(1)   — 面试首选
 * 解法2: 数学 O(1)       — O(1) / O(1)   — 利用 XOR 前缀和规律
 *
 * 【手动推演】
 *
 *   n=5, start=0 → nums = [0, 2, 4, 6, 8]
 *   0 ^ 2 = 2 → 2 ^ 4 = 6 → 6 ^ 6 = 0 → 0 ^ 8 = 8
 *   答案: 8
 *
 *   n=4, start=3 → nums = [3, 5, 7, 9]
 *   二进制:  011 ^ 101 = 110   (3^5=6)
 *           110 ^ 111 = 001   (6^7=1)
 *           001 ^ 1001 = 1000 (1^9=8)
 *   答案: 8
 *
 * 【XOR 基本性质速查】
 *   a ^ a = 0          (自反性/消除)
 *   a ^ 0 = a          (恒等性)
 *   a ^ b = b ^ a      (交换律)
 *   (a^b)^c = a^(b^c)  (结合律)
 */


// ============================================================
// 解法1: 直接模拟 — 面试首选
// 时间: O(n)  最多循环 1000 次
// 空间: O(1)  只用一个变量
//
// 【思路】
// 不需要真的创建数组。直接在循环中计算 start + 2*i，
// 累积 XOR 到 result 中。
//
// 【为什么不创建数组？】
// nums[i] 可以在循环中 O(1) 计算出来，
// 创建 vector 会额外消耗 O(n) 空间且有 push_back 开销。
// ============================================================
class Solution1 {
public:
    int xorOperation(int n, int start) {
        int result = 0;
        for (int i = 0; i < n; i++) {
            result ^= start + 2 * i;
        }
        return result;
    }
};


// ============================================================
// 解法2: 数学 O(1) — 利用 XOR 前缀和规律
// 时间: O(1)  只做常数次运算
// 空间: O(1)
//
// 【核心数学】
// f(n) = 0 ^ 1 ^ 2 ^ ... ^ n 有四周期规律:
//   n % 4 == 0 → f(n) = n
//   n % 4 == 1 → f(n) = 1
//   n % 4 == 2 → f(n) = n + 1
//   n % 4 == 3 → f(n) = 0
//
// 验证:
//   f(0) = 0           (0%4=0, ans=0 ✓)
//   f(1) = 0^1 = 1     (1%4=1, ans=1 ✓)
//   f(2) = 1^2 = 3     (2%4=2, ans=2+1=3 ✓)
//   f(3) = 3^3 = 0     (3%4=3, ans=0 ✓)
//   f(4) = 0^4 = 4     (4%4=0, ans=4 ✓)
//   f(5) = 4^5 = 1     (5%4=1, ans=1 ✓)
//
// 【推导: 从 f(n) 到本题】
//
// 原问题: XOR(start, start+2, start+4, ..., start+2*(n-1))
//
// Step 1: 每个数右移 1 位（除以 2），变成连续整数
//   s = start / 2
//   e = start / 2 + n - 1
//   右移后: s, s+1, s+2, ..., e
//
// Step 2: 用 f() 计算 XOR(s..e) = f(e) ^ f(s-1)
//
// Step 3: 左移回来（乘 2）
//   result = xor_shifted << 1
//
// Step 4: 处理被右移丢掉的最低位
//   每个 nums[i] 的最低位 = start 的最低位
//   （因为 2*i 的最低位总是 0）
//   n 个相同位的 XOR: 奇数个1→1, 偶数个1→0
//   所以: start为奇 && n为奇 → 最低位=1, 否则=0
// ============================================================
class Solution2 {
public:
    // f(n) = 0 ^ 1 ^ 2 ^ ... ^ n 的 O(1) 计算
    int xorUpTo(int n) {
        switch (n % 4) {
            case 0: return n;
            case 1: return 1;
            case 2: return n + 1;
            case 3: return 0;
        }
        return 0; // unreachable, suppress warning
    }

    int xorOperation(int n, int start) {
        // nums[i] = start + 2*i, i = 0, 1, ..., n-1
        // 右移1位后变成连续整数: s, s+1, ..., e
        int s = start / 2;
        int e = s + n - 1;

        // XOR(s..e) = f(e) ^ f(s-1), 特判 s=0
        int xorShifted = xorUpTo(e);
        if (s > 0) xorShifted ^= xorUpTo(s - 1);

        // 左移回来（恢复 ×2）
        int result = xorShifted << 1;

        // 处理最低位:
        // 每个 nums[i] 最低位 = start 最低位
        // n 个相同位 XOR = (n为奇 && 位为1) ? 1 : 0
        if (n % 2 == 1 && start % 2 == 1) {
            result |= 1;
        }

        return result;
    }
};


// ============================================================
// 【解法对比】
//
// | 维度       | 直接模拟     | 数学 O(1)        |
// |-----------|-------------|-----------------|
// | 时间       | O(n)        | O(1)            |
// | 空间       | O(1)        | O(1)            |
// | 代码量     | 3行         | 15+行           |
// | 出错概率   | 极低         | 中等（位运算易错）|
// | 面试推荐   | 首选         | 加分项/被追问时给 |
//
// 本题 n ≤ 1000，O(n) 完全足够。
// 面试中先给解法1，被追问"能否做到 O(1)" 再给解法2。
//
// ============================================================
// 【XOR 前缀和规律的直觉理解】
//
// 为什么 f(n) = 0^1^...^n 有4周期？
//
// 观察: 连续两个整数 2k 和 2k+1
//   2k   = ...xxx0
//   2k+1 = ...xxx1
//   XOR  = 000...001 = 1
//
// 所以每两个连续整数的 XOR = 1
// 四个一组: (2k)^(2k+1)^(2k+2)^(2k+3)
//         = 1 ^ something = 0 (完全消掉)
//
// 因此 f(n) 只取决于 n%4 的余数
//
// ============================================================
// 【易错点】
//
// 1. 数学解中忘记处理最低位
//    ✗ return xorShifted << 1;   → 丢失了最低位信息
//    ✓ result = xorShifted << 1; if (n%2 && start%2) result |= 1;
//
// 2. 数学解中 s=0 时 f(s-1) = f(-1) 未定义
//    ✗ xorUpTo(e) ^ xorUpTo(s-1)  → s=0 时调用 xorUpTo(-1)
//    ✓ 特判: if (s > 0) xorShifted ^= xorUpTo(s-1);
//
// 3. 混淆 ^ (XOR) 和 | (OR) 或 & (AND)
//    面试紧张时容易写错运算符，记住: ^ 是异或（不同为1）
//
// 4. 不必要地创建数组
//    ✗ vector<int> nums; for (...) nums.push_back(start+2*i);
//    ✓ 直接在循环里 result ^= start + 2*i;
//
// ============================================================
// 【面试追问】
//
// Q1: XOR 有哪些关键性质？
//     → 自反 a^a=0, 恒等 a^0=a, 交换律, 结合律
//
// Q2: 能否 O(1) 完成？
//     → 可以，利用 f(n)=0^1^...^n 的4周期规律
//       把等差数列右移1位变连续整数，XOR后左移回来
//
// Q3: 为什么 0^1^...^n 有4周期？
//     → 相邻两整数 XOR=1, 每4个一组 XOR=0
//       所以只剩 n%4 的余数决定结果
//
// Q4: 如果 n 很大（如 10^9），哪种解法必须用？
//     → O(1) 数学解。O(n) 循环会超时。
//       （本题 n ≤ 1000 所以无所谓）
