/*
 * LeetCode 800: 相似 RGB 颜色 (Similar RGB Color)
 * 难度: Easy
 * 标签: Math, String, Enumeration
 *
 * 【题目本质】
 * 给定 RGB 颜色 "#ABCDEF"，找到与它最相似的可简写颜色 "#XXYYZZ"。
 * 可简写颜色每个通道两位相同，即 "XX" 形式 = X * 17 (X: 0~15)。
 * 相似度 = -(r差^2 + g差^2 + b差^2)，最大化相似度等价于最小化距离。
 * 三通道独立，各找最近的 x*17 即可。
 *
 * 【解法总览】
 * 解法一: 数学四舍五入   O(1) / O(1)  最简洁
 * 解法二: 枚举16个候选   O(1) / O(1)  更直观
 */


/*
 * ============================================================
 * 解法一: 数学四舍五入（面试首选）
 * ============================================================
 *
 * 思路:
 *   可简写值 = x * 17 (x: 0~15)，共 16 个候选，等间距分布
 *   对每个通道值 v，最近的候选 = round(v / 17.0) * 17
 *   整数等价: (v + 8) / 17 * 17
 *
 * 为什么 +8?
 *   候选间距 17。四舍五入的分界点在间距的一半 = 8.5 处。
 *   整数除法 (v + 8) / 17 在 v%17 <= 8 时选下方候选,
 *   v%17 >= 9 时选上方候选, 恰好实现四舍五入。
 *
 *   数学证明:
 *   设 v = 17q + r (0 <= r < 17)
 *   (v + 8) / 17 = (17q + r + 8) / 17
 *   当 r <= 8: (17q + r + 8) / 17 = q (因为 r+8 <= 16 < 17)
 *   当 r >= 9: (17q + r + 8) / 17 = q+1 (因为 r+8 >= 17)
 *   所以 nearest = q*17 (r<=8) 或 (q+1)*17 (r>=9)
 *   正是到 17q 和 17(q+1) 中较近的那个
 *
 * 示例: color = "#09f166"
 *   R = 0x09 = 9  -> x = (9+8)/17 = 1  -> 1*17 = 17 = 0x11 -> "11"
 *   G = 0xf1 = 241 -> x = (241+8)/17 = 14 (整除 249/17=14.6, 取14)
 *     等等 249/17 = 14.647... 取14? 不对
 *     整数除法: 249/17 = 14 (余 11)
 *     14*17 = 238, 15*17 = 255
 *     |241-238| = 3, |241-255| = 14 -> 选 238 = 0xEE -> "ee"
 *   B = 0x66 = 102 -> x = (102+8)/17 = 110/17 = 6
 *     6*17 = 102 恰好等于原值 -> "66"
 *   输出: "#11ee66"
 *
 * 时间: O(1), 空间: O(1)
 */
class Solution1 {
public:
    string similarRGB(string color) {
        // 分别处理三个通道: color[1..2], color[3..4], color[5..6]
        return "#" + closest(color.substr(1, 2))
                   + closest(color.substr(3, 2))
                   + closest(color.substr(5, 2));
    }

private:
    string closest(string hex) {
        // 两位十六进制 -> 十进制整数 (0~255)
        int val = stoi(hex, nullptr, 16);

        // 四舍五入到最近的 x*17
        int x = (val + 8) / 17;
        int nearest = x * 17;

        // 十进制 -> 两位小写十六进制字符串
        char buf[3];
        sprintf(buf, "%02x", nearest);
        return string(buf);
    }
};


/*
 * ============================================================
 * 解法二: 枚举 16 个候选值
 * ============================================================
 *
 * 思路:
 *   对每个通道值 v，遍历 x = 0 到 15，计算候选 c = x * 17，
 *   找 |v - c| 最小的 c。
 *
 * 优点: 不需要推导数学公式，逻辑简单直观
 * 缺点: 代码稍长
 *
 * 举例: v = 128
 *   x=7: c=119, diff=9
 *   x=8: c=136, diff=8  <- 最近
 *   选 136 = 0x88 -> "88"
 *
 * 举例: v = 0
 *   x=0: c=0, diff=0  <- 完美匹配
 *   选 0 = 0x00 -> "00"
 *
 * 举例: v = 255
 *   x=15: c=255, diff=0  <- 完美匹配
 *   选 255 = 0xFF -> "ff"
 *
 * 时间: O(16 * 3) = O(1), 空间: O(1)
 */
class Solution2 {
public:
    string similarRGB(string color) {
        return "#" + closest(color.substr(1, 2))
                   + closest(color.substr(3, 2))
                   + closest(color.substr(5, 2));
    }

private:
    string closest(string hex) {
        int val = stoi(hex, nullptr, 16);

        // 枚举所有 16 个可简写值
        int bestVal = 0;
        int bestDiff = 256;   // 最大可能差值为 255

        for (int x = 0; x <= 15; x++) {
            int candidate = x * 17;
            int diff = abs(val - candidate);
            if (diff < bestDiff) {
                bestDiff = diff;
                bestVal = candidate;
            }
        }

        char buf[3];
        sprintf(buf, "%02x", bestVal);
        return string(buf);
    }
};


/*
 * ============================================================
 * 解法三: 查表法 (预计算)
 * ============================================================
 *
 * 思路:
 *   预先计算 256 个值各自最近的可简写值，存入查找表。
 *   运行时直接查表。
 *
 * 优点: 运行时零计算
 * 缺点: 需要 256 字节查找表（对此题无必要）
 *
 * 实际上对于面试场景，解法一的 (v+8)/17*17 已经足够高效。
 *
 * 时间: O(1) 查表, 空间: O(256) = O(1)
 */
class Solution3 {
public:
    string similarRGB(string color) {
        return "#" + closest(color.substr(1, 2))
                   + closest(color.substr(3, 2))
                   + closest(color.substr(5, 2));
    }

private:
    // 查找表: lut[v] = 最近的可简写值
    // 在实际使用中可以用 constexpr 或静态初始化
    int roundTo17(int v) {
        // 等价于查表, 但这里用公式代替
        return ((v + 8) / 17) * 17;
    }

    string closest(string hex) {
        int val = stoi(hex, nullptr, 16);
        int nearest = roundTo17(val);

        char buf[3];
        sprintf(buf, "%02x", nearest);
        return string(buf);
    }
};


/*
 * ============================================================
 * 【解法对比】
 *
 * | 解法            | 时间 | 空间 | 特点                     |
 * |-----------------|------|------|-------------------------|
 * | 数学四舍五入(一)  | O(1) | O(1) | 最简洁，一行公式搞定      |
 * | 枚举候选(二)     | O(1) | O(1) | 最直观，不需要数学推导     |
 * | 查表法(三)       | O(1) | O(1) | 预计算，运行零开销        |
 *
 * 面试推荐: 解法一。代码最短，展示数学能力。
 * 如果面试官问"如何验证正确性"，给出解法二作为对照。
 *
 * ============================================================
 * 【易错点】
 *
 * 1. 十六进制大小写:
 *    错: sprintf(buf, "%02X", nearest) -> 输出 "FF" 大写
 *    对: sprintf(buf, "%02x", nearest) -> 输出 "ff" 小写
 *    题目要求小写输出
 *
 * 2. 四舍五入错误:
 *    错: (val / 17) * 17  (总是向下取整)
 *        val=9 -> 0*17=0, 但最近是 17 (距离 8 vs 9, 选 17 更近? 不对, 9 到 0 距离 9, 到 17 距离 8, 选 17)
 *        用向下取整得到 0, 但正确答案是 17
 *    对: (val + 8) / 17 * 17  (四舍五入)
 *        (9+8)/17 = 17/17 = 1, 1*17 = 17 正确
 *
 * 3. 子串偏移量错误:
 *    错: color.substr(0, 2) 包含 '#'
 *    对: color.substr(1, 2) 从第 2 个字符开始 (跳过 '#')
 *
 * 4. 输出格式不足两位:
 *    错: 值为 0 时输出 "0" (1位)
 *    对: "%02x" 保证 "00" (2位，前补零)
 *
 * 5. stoi 基数参数:
 *    错: stoi(hex) (按十进制解析 "AB" -> 异常)
 *    对: stoi(hex, nullptr, 16) (按十六进制解析)
 *
 * ============================================================
 * 【面试追问】
 *
 * Q1: 为什么三通道可以独立处理？
 * -> 相似度公式是三项独立平方差的和 (取负)。
 *    最大化整体 = 分别最小化各项。通道间无交叉项。
 *
 * Q2: 17 这个数怎么来的？
 * -> 十六进制 "XX" = X*16 + X = X*17。
 *    17 = 16 + 1, 是十六进制中 "两位相同" 数值的间距。
 *
 * Q3: 如果候选值不是等间距的呢？
 * -> 不能直接用 round(v/间距)。
 *    需要排序后二分查找最近的候选值。
 *    或者暴力枚举所有候选值（如果候选数量不大）。
 *
 * Q4: 如果颜色空间是 HSL 而非 RGB，能类似处理吗？
 * -> HSL 各通道也是独立的，但 H 是角度 (0-360)，
 *    需要处理环形距离 (min(|h1-h2|, 360-|h1-h2|))。
 *    S 和 L 可以直接用类似方法。
 *
 * Q5: (v+8)/17 和 round(v/17.0) 有区别吗？
 * -> 在 v 为 0 到 255 的范围内完全等价。
 *    整数方式避免浮点精度问题，更可靠。
 *    但 round 返回 double, 需要转 int, 可能有微小误差。
 * ============================================================
 */
