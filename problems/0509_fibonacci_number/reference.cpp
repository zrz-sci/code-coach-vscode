/*
 * LeetCode 509: 斐波那契数 (Fibonacci Number)
 *
 * 【题目本质】
 * 计算斐波那契数列第 n 项。这是动态规划的最基础入门题，
 * 用来学习"暴力递归 → 记忆化 → 递推 → 空间优化"的完整演进路线。
 *
 * 【解法总览】
 * 解法1: 暴力递归      — O(2^n) / O(n)   — 最直觉，但有大量重复计算
 * 解法2: 记忆化搜索    — O(n)   / O(n)   — 给递归加缓存，消除重复
 * 解法3: 递推 DP       — O(n)   / O(n)   — 自底向上填表
 * 解法4: 滚动变量      — O(n)   / O(1)   — ⭐ 面试首选，空间最优
 * 解法5: 矩阵快速幂    — O(logn)/ O(1)   — 加分项，适合超大 n
 */

// ============================================================
// 解法1: 暴力递归 — 直接按定义递归
// 时间: O(2^n)  空间: O(n) 递归栈深度
//
// 【思路】
// 题目直接给了 F(n) = F(n-1) + F(n-2)，翻译成代码就是递归。
// 但递归树中存在大量重复计算：
//
//                     fib(5)
//                    /      \
//               fib(4)       fib(3)      ← fib(3) 重复!
//              /     \       /    \
//          fib(3)  fib(2)  fib(2) fib(1)  ← fib(2) 重复!
//         /    \
//     fib(2) fib(1)
//
// fib(3) 被算了 2 次，fib(2) 被算了 3 次...
// 这就是为什么暴力递归是指数级复杂度。
// ============================================================
class Solution1 {
public:
    int fib(int n) {
        if (n <= 1) return n;  // F(0)=0, F(1)=1
        return fib(n - 1) + fib(n - 2);
    }
};

// ============================================================
// 解法2: 记忆化搜索（自顶向下 DP）
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 暴力递归的瓶颈：同一个 fib(k) 被重复计算多次。
// 解决方法：用 memo 数组缓存已算过的结果。
// 第一次算 fib(k) 时存入 memo[k]，之后直接查表返回。
// 每个子问题只算一次 → n 个子问题 × O(1) = O(n)
// ============================================================
class Solution2 {
public:
    int fib(int n) {
        vector<int> memo(n + 1, -1);  // -1 表示尚未计算
        return helper(n, memo);
    }

private:
    int helper(int n, vector<int>& memo) {
        if (n <= 1) return n;
        // 如果已经算过，直接返回缓存，不再递归展开
        if (memo[n] != -1) return memo[n];
        // 计算并缓存结果——这一步容易忘记存入 memo
        memo[n] = helper(n - 1, memo) + helper(n - 2, memo);
        return memo[n];
    }
};

// ============================================================
// 解法3: 递推 DP（自底向上）
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 把记忆化搜索的"自顶向下"翻转成"自底向上"：
// 从已知的 F(0)=0, F(1)=1 开始，用循环一步步推到 F(n)。
// 好处：没有递归栈开销，代码更简洁。
//
// DP 填表过程 (n=6):
// 索引:  0  1  2  3  4  5  6
// dp[]:  0  1  1  2  3  5  8
//                 ↑
//                 dp[2] = dp[1] + dp[0] = 1 + 0 = 1
//
// 填表方向: → (从左到右)
// 依赖关系: dp[i] 只依赖 dp[i-1] 和 dp[i-2]
// ============================================================
class Solution3 {
public:
    int fib(int n) {
        if (n <= 1) return n;
        vector<int> dp(n + 1);  // 注意是 n+1，不是 n
        dp[0] = 0;
        dp[1] = 1;
        for (int i = 2; i <= n; i++) {
            dp[i] = dp[i - 1] + dp[i - 2];
        }
        return dp[n];
    }
};

// ============================================================
// 解法4: 滚动变量（空间优化 DP） ⭐ 面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法3 中 dp[i] 只依赖 dp[i-1] 和 dp[i-2]，
// 所以不需要保留整个数组，两个变量就够了。
// 这是线性 DP 空间优化的经典模式，适用于所有
// "当前状态只依赖前 k 个状态"的情况。
//
// 滚动过程 (n=6):
//   初始: prev=0 (F0), curr=1 (F1)
//   i=2:  next=0+1=1  → prev=1, curr=1   (F1, F2)
//   i=3:  next=1+1=2  → prev=1, curr=2   (F2, F3)
//   i=4:  next=1+2=3  → prev=2, curr=3   (F3, F4)
//   i=5:  next=2+3=5  → prev=3, curr=5   (F4, F5)
//   i=6:  next=3+5=8  → prev=5, curr=8   (F5, F6)
//   返回 curr = 8 ✓
// ============================================================
class Solution4 {
public:
    int fib(int n) {
        if (n <= 1) return n;
        int prev = 0;  // F(i-2)
        int curr = 1;  // F(i-1)
        for (int i = 2; i <= n; i++) {
            // 必须用临时变量，否则 prev 被覆盖后 curr 计算出错
            int next = prev + curr;
            prev = curr;
            curr = next;
        }
        return curr;
    }
};

// ============================================================
// 解法5: 矩阵快速幂
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 斐波那契递推可以用矩阵表示：
//
//   | F(n)   |   | 1 1 |^(n-1)   | 1 |
//   |        | = |     |       × |   |
//   | F(n-1) |   | 1 0 |         | 0 |
//
// 计算矩阵的 (n-1) 次幂，用快速幂（反复平方法）：
//   M^10 = (M^5)^2
//   M^5  = M × (M^2)^2
// 这样只需 O(log n) 次矩阵乘法。
//
// 当 n 可以到 10^18 时，只有这种方法能在合理时间内计算。
// ============================================================
class Solution5 {
public:
    using Matrix = vector<vector<int>>;

    // 2×2 矩阵乘法
    Matrix multiply(const Matrix& A, const Matrix& B) {
        return {
            {A[0][0]*B[0][0] + A[0][1]*B[1][0],
             A[0][0]*B[0][1] + A[0][1]*B[1][1]},
            {A[1][0]*B[0][0] + A[1][1]*B[1][0],
             A[1][0]*B[0][1] + A[1][1]*B[1][1]}
        };
    }

    // 矩阵快速幂：反复平方法计算 M^p
    Matrix matPow(Matrix M, int p) {
        // 单位矩阵（相当于数字的 1）
        Matrix result = {{1, 0}, {0, 1}};
        while (p > 0) {
            if (p & 1) {
                // p 是奇数，先乘一次 M
                result = multiply(result, M);
            }
            M = multiply(M, M);  // M 自身平方
            p >>= 1;             // p 除以 2
        }
        return result;
    }

    int fib(int n) {
        if (n <= 1) return n;
        Matrix M = {{1, 1}, {1, 0}};
        Matrix res = matPow(M, n - 1);
        // 结果矩阵的 [0][0] 位置就是 F(n)
        return res[0][0];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间    | 空间  | 适用场景                    |
// |-------------|---------|-------|-----------------------------|
// | 暴力递归     | O(2^n)  | O(n)  | 理解递归思路，面试中说明即可  |
// | 记忆化搜索   | O(n)    | O(n)  | 自顶向下思考更自然时          |
// | 递推 DP      | O(n)    | O(n)  | 需要回溯查看所有 dp 值时      |
// | 滚动变量     | O(n)    | O(1)  | ⭐ 面试首选，最简洁高效       |
// | 矩阵快速幂   | O(logn) | O(1)  | n 极大时（10^18 级别）        |
//
// 核心演进: 暴力 → 发现重叠子问题 → 记忆化 → 翻成递推 → 空间优化
// 这条路线适用于所有线性 DP 题！
//
// ============================================================
// 【易错点】
//
// 1. 忘记处理 n=0 或 n=1 的边界
//    ✗ 直接进入 for 循环，n=0 时返回 curr=1（应该是 0）
//    ✓ 开头 if (n <= 1) return n;
//
// 2. 滚动变量更新顺序写反
//    ✗ prev = curr; curr = prev + curr;
//       此时 prev 已经被 curr 覆盖，curr 的计算结果错误
//    ✓ int next = prev + curr; prev = curr; curr = next;
//
// 3. 记忆化搜索忘记存结果
//    ✗ return helper(n-1,memo) + helper(n-2,memo); // 没存 memo[n]
//    ✓ memo[n] = helper(n-1,memo) + helper(n-2,memo); return memo[n];
//
// 4. dp 数组大小开成 n 而不是 n+1
//    ✗ vector<int> dp(n); dp[n] = ... // 越界!
//    ✓ vector<int> dp(n + 1);
//
// ============================================================
// 【面试追问（递进链）】
//
// Q1: 暴力递归为什么是 O(2^n)？
// A1: 递归树每层分裂成两个子问题，高度为 n，节点数接近 2^n。
//     严格说是 O(φ^n)，φ ≈ 1.618（黄金比例）。
//
// Q2: 记忆化搜索为什么能把 O(2^n) 降到 O(n)？
// A2: 只有 n 个不同的子问题 fib(0)~fib(n)。记忆化保证每个只算一次，
//     每次 O(1) 工作量，总计 O(n)。
//
// Q3: 能否 O(1) 空间？
// A3: 可以。dp[i] 只依赖 dp[i-1] 和 dp[i-2]，用两个滚动变量即可。
//
// Q4: 如果 n 可以到 10^18，怎么办？
// A4: 矩阵快速幂。将递推写成矩阵乘法 [[1,1],[1,0]]^n，
//     用快速幂在 O(log n) 时间内计算。结果需要取模。
//
// Q5: 还有没有 O(1) 时间的方法？
// A5: 有。Binet 公式 F(n) = (φ^n - ψ^n) / √5，
//     但浮点精度有限，n 较大时结果不准确，面试中了解即可。
//
