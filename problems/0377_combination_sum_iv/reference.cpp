/*
 * LeetCode 377: 组合总和 IV (Combination Sum IV)
 *
 * 【题目本质】
 * 从一个无重复整数数组中可重复选取元素，组成总和为 target 的序列，
 * 不同顺序算不同方案，求方案数。
 * 本质：完全背包的"排列"变体（外容量内物品）。
 *
 * 【解法总览】
 * 解法1: 回溯暴力       — O(指数级) / O(target)  — 理解问题结构
 * 解法2: 记忆化搜索     — O(target×n) / O(target) — 自顶向下 DP
 * 解法3: 递推 DP        — O(target×n) / O(target) — 面试首选 ⭐
 */

// ============================================================
// 解法1: 回溯暴力 — 枚举所有排列序列
// 时间: O(指数级，最坏 O(n^target))  空间: O(target) 递归栈
//
// 【思路】
// 最直觉的做法：从 target 出发，每次尝试选 nums 中任意一个数，
// 递归地凑剩余部分。remaining=0 时说明找到一个合法序列。
//
// 决策树 (nums=[1,2,3], target=4):
//                    4
//              /     |     \
//           3(选1)  2(选2)  1(选3)
//          /|\      /|      |
//        2  1  0  1  0      0
//       /|  |    |
//      1  0 0    0
//      |
//      0
//
// remaining=1 出现了多次 → 重叠子问题！这就是优化的切入点。
// ============================================================
class Solution1 {
public:
    int combinationSum4(vector<int>& nums, int target) {
        // base case：凑出 0，什么都不选，算 1 种
        if (target == 0) return 1;
        
        int count = 0;
        for (int num : nums) {
            if (target >= num) {
                // 选 num，递归凑 target - num
                count += combinationSum4(nums, target - num);
            }
        }
        return count;
    }
};

// ============================================================
// 解法2: 记忆化搜索（自顶向下 DP）
// 时间: O(target × n)  空间: O(target)
//
// 【思路】
// 解法1 的瓶颈：同一个 remaining 值被反复计算。
// 加一个 memo 数组，memo[r] 记录"凑出 r 的排列数"。
// 算过的直接查表返回，避免重复计算。
//
// 为什么 memo 初始化为 -1 而不是 0？
// 因为某些 remaining 确实凑不出（结果为 0），如果用 0 标记"未计算"，
// 就无法区分"还没算"和"算了但结果是 0"。
// ============================================================
class Solution2 {
public:
    int combinationSum4(vector<int>& nums, int target) {
        vector<int> memo(target + 1, -1);
        return dfs(nums, target, memo);
    }

private:
    int dfs(vector<int>& nums, int remaining, vector<int>& memo) {
        if (remaining == 0) return 1;
        if (memo[remaining] != -1) return memo[remaining];
        
        int count = 0;
        for (int num : nums) {
            if (remaining >= num) {
                count += dfs(nums, remaining - num, memo);
            }
        }
        // 存入缓存再返回
        memo[remaining] = count;
        return count;
    }
};

// ============================================================
// 解法3: 递推 DP（自底向上）⭐ 面试首选
// 时间: O(target × n)  空间: O(target)
//
// 【思路】
// 把记忆化搜索翻译成循环填表：
//   dp[i] = 凑出总和 i 的排列数
//   dp[i] = Σ dp[i - num]，对所有 num ∈ nums 且 num <= i
//   dp[0] = 1（空序列凑出 0，算 1 种方案）
//
// 【核心：为什么外层遍历容量、内层遍历物品 = 排列？】
// 对于每个容量 i，我们考虑"序列的最后一个元素是什么"。
// 如果最后选了 num，则前面的序列凑出 i-num，方案数为 dp[i-num]。
// 由于每个 i 都重新遍历所有 num，不同的选取顺序会被分别计入。
//
// 对比：如果外层遍历物品、内层遍历容量（LeetCode 518），
// 每个物品按顺序处理，避免了同一组物品的不同排列被重复计数。
//
// 【DP 填表过程】 (nums=[1,2,3], target=4)
//
//  i:    0   1   2   3   4
//  dp:   1   ?   ?   ?   ?
//
//  i=1: num=1→dp[0]=1, num=2→skip, num=3→skip  → dp[1]=1
//  i=2: num=1→dp[1]=1, num=2→dp[0]=1, num=3→skip → dp[2]=2
//  i=3: num=1→dp[2]=2, num=2→dp[1]=1, num=3→dp[0]=1 → dp[3]=4
//  i=4: num=1→dp[3]=4, num=2→dp[2]=2, num=3→dp[1]=1 → dp[4]=7
//
//  dp:   1   1   2   4   7
//        ↑               ↑
//     base case        答案
//
// 填表方向: → → → → （从左到右，因为 dp[i] 依赖 dp[i-num] 且 i-num < i）
// ============================================================
class Solution3 {
public:
    int combinationSum4(vector<int>& nums, int target) {
        vector<int> dp(target + 1, 0);
        dp[0] = 1;  // 凑出 0 的方式：空序列，1 种
        
        // 外层遍历容量（排列的关键！）
        for (int i = 1; i <= target; i++) {
            // 内层遍历每个可选物品，作为"序列最后一个元素"
            for (int num : nums) {
                if (i >= num) {
                    dp[i] += dp[i - num];
                }
            }
        }
        
        return dp[target];
    }
};

// ============================================================
// 【排列 vs 组合的循环顺序对比】
//
// 排列（本题 377）:               组合（LeetCode 518）:
//   for (i = 1..target)             for (num : nums)
//     for (num : nums)                for (i = num..target)
//       dp[i] += dp[i-num]              dp[i] += dp[i-num]
//
// 转移方程完全相同！区别仅在循环嵌套顺序。
// 这是完全背包计数问题中最核心的区分点。
//
// 【和爬楼梯的关系】
// 如果 nums = [1, 2]，本题变成：
//   dp[i] = dp[i-1] + dp[i-2]  (i >= 2)
// 这就是 LeetCode 70 爬楼梯！斐波那契数列。
// ============================================================

// ============================================================
// 【解法对比】
//
// 解法1 (回溯) vs 解法2 (记忆化):
//   唯一区别是加了 memo 数组，把指数级降到 O(target×n)。
//
// 解法2 (记忆化) vs 解法3 (递推):
//   计算结果相同。记忆化是"按需计算"（只算递归访问到的子问题），
//   递推是"全部计算"（dp[1]~dp[target] 全填）。
//   本题 target 不大，递推更简洁、无递归开销。
//
// 面试中推荐解法3，代码最短、最清晰。
// ============================================================

// ============================================================
// 【易错点】
//
// 1. dp[0] 初始化错误
//    ✗ dp[0] = 0  → 所有 dp 值都是 0，因为没有"种子"
//    ✓ dp[0] = 1  → 空序列凑出 0 是 1 种方案（数学约定）
//
// 2. 循环顺序搞反（最高频错误！）
//    ✗ for (num : nums) { for (i = num..target) { dp[i]+=dp[i-num]; } }
//      → 这是组合数（LeetCode 518），不是排列数
//    ✓ for (i = 1..target) { for (num : nums) { dp[i]+=dp[i-num]; } }
//      → 外层遍历容量 = 排列数
//
// 3. 忘记判断 i >= num
//    ✗ dp[i] += dp[i - num];  // 当 i < num 时，dp[负数] 越界
//    ✓ if (i >= num) dp[i] += dp[i - num];
//
// 4. 记忆化搜索中 memo 初始化为 0
//    ✗ vector<int> memo(target+1, 0);  → 无法区分"未算"和"结果是0"
//    ✓ vector<int> memo(target+1, -1); → -1 表示未计算
//
// 5. 潜在溢出问题
//    虽然题目保证最终答案在 32 位内，但某些恶意测试用例的中间
//    累加值可能溢出。可以用 unsigned int 或在累加前检查：
//    if (dp[i] < INT_MAX - dp[i - num]) dp[i] += dp[i - num];
// ============================================================

// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 这道题和 LeetCode 518（零钱兑换 II）有什么区别？
// → 518 求组合数（不考虑顺序），377 求排列数（考虑顺序）。
//   转移方程一模一样，唯一区别是循环嵌套顺序。
//   518: 外物品内容量 → 每种硬币按顺序处理，避免重复排列
//   377: 外容量内物品 → 每个容量都重新选所有物品，不同顺序分别计入
//
// Q2: 能直觉解释一下为什么外层遍历容量就是排列吗？
// → 考虑 dp[i] 的含义："凑出 i 的所有排列数"。
//   我们枚举"序列的最后一个元素 num"，前面的部分是 dp[i-num]。
//   因为 dp[i-num] 已经包含了所有排列，所以 num 放在最后一个位置
//   的所有排列都被计入了。不同的 num 作为最后一个元素，自然产生
//   不同的排列。
//
// Q3 (Follow-up): 如果 nums 中有负数会怎样？
// → 如果存在正数 a 和负数 b 使得 a + b = 0，则可以在序列中
//   无限插入 (a, b) 对，产生无穷多个合法序列。
//   解决方案：限制序列最大长度为 k。
//   此时需要二维 DP：dp[i][j] = 用恰好 j 个数凑出总和 i 的方案数。
//   dp[i][j] = Σ dp[i-num][j-1]，最终答案 = Σ dp[target][j] for j in [1..k]。
//   时间复杂度 O(target × k × n)，空间 O(target × k)。
//
// ============================================================
// 【空间优化说明】
//
// 解法3 的 dp[i] 已经是一维 O(target) 空间，无法进一步压缩。
//
// dp[i] 的转移：dp[i] = Σ dp[i - num]，对所有 num ∈ nums。
// 当 nums 包含多个不同大小的数时，dp[i] 同时依赖 dp[i-1]、dp[i-2]、
// dp[i-nums[k]] 等多个位置，跨度取决于 nums 中的最大值。
// 例如 nums=[1,2,3] 时，dp[10] 依赖 dp[9]、dp[8]、dp[7]，
// 无法只用 2~3 个变量滚动替代。
//
// 特殊情况：如果 nums=[1,2]，dp[i] = dp[i-1] + dp[i-2]（斐波那契），
// 此时可以用两个变量滚动。但一般情况下 nums 大小不固定，无法压缩。
//
// 结论：O(target) 一维 DP 已是最优空间，无法进一步压缩。
// ============================================================
