/*
 * LeetCode 968: 监控二叉树 (Binary Tree Cameras)
 *
 * 【题目本质】
 * 树上最小支配集问题：在树节点上放最少的摄像头，使每个节点被自身或相邻节点的摄像头覆盖。
 * 核心洞察：叶子不放摄像头，自底向上贪心决策。
 *
 * 【解法总览】
 * 解法1: 贪心 + 后序遍历(三状态)  — O(n) / O(h) — 面试首选，简洁高效
 * 解法2: 树形 DP(精确三状态)      — O(n) / O(h) — 更严谨，状态转移更清晰
 */


// ============================================================
// 解法1: 贪心 + 后序遍历(三状态) — 面试首选
// 时间: O(n)  空间: O(h)  h为树高，递归栈深度
//
// 【思路】
// 为什么自底向上贪心？因为叶子放摄像头"浪费"——叶子没有子节点，
// 覆盖范围小。把摄像头放在叶子的父节点，一个摄像头能覆盖更多节点。
//
// 定义三种状态:
//   0 = 未被覆盖 (需要父节点来救)
//   1 = 已被覆盖 (被子节点的摄像头覆盖，自己没装)
//   2 = 有摄像头 (自己装了摄像头)
//
// 后序遍历，拿到左右子状态后:
//   - 任一子=0 → 当前必须放摄像头(2)
//   - 任一子=2 → 当前已被覆盖(1)
//   - 否则(两子都=1) → 当前未覆盖(0)
//
// 示例演示:
//
//       0              0(状态?)         0(状态1=已覆盖)
//      / \            / \              / \
//     0   null  →    0   (1)    →    📷   (1)
//    / \            / \              / \
//   0   0         (0)  (0)         (1)  (1)
//                叶子=未覆盖      父放摄像头,覆盖叶子
//
//   根节点: 左子=2(有摄像头), 右子=1(null=已覆盖)
//           → 根节点状态=1(已被覆盖)  cameras=1 ✓
//
// 根节点特判:
//   如果根最终=0(未覆盖), 根没有父, 必须自己补一个摄像头
// ============================================================
class Solution1 {
public:
    int cameras = 0;

    // 返回值: 0=未覆盖, 1=已覆盖, 2=有摄像头
    int dfs(TreeNode* node) {
        // null 视为"已覆盖"——这是贪心的基石
        // 为什么？因为这让叶子节点的子状态都是1，
        // 叶子自身返回0(未覆盖)，推动叶子的父放摄像头
        if (!node) return 1;

        int left = dfs(node->left);
        int right = dfs(node->right);

        // 规则1: 子节点有未覆盖的 → 当前必须放摄像头
        // (最高优先级，即使另一个子有摄像头，未覆盖的子仍需救助)
        if (left == 0 || right == 0) {
            cameras++;
            return 2;
        }

        // 规则2: 子节点有摄像头 → 当前已被覆盖
        if (left == 2 || right == 2) {
            return 1;
        }

        // 规则3: 两个子都是已覆盖(1) → 没人帮当前节点，等父节点
        return 0;
    }

    int minCameraCover(TreeNode* root) {
        // 根节点没有父，如果未覆盖必须自己放
        if (dfs(root) == 0) {
            cameras++;
        }
        return cameras;
    }
};


// ============================================================
// 解法2: 树形 DP(精确三状态) — 更严谨的方法
// 时间: O(n)  空间: O(h)
//
// 【思路】
// 贪心解法虽然正确但需要证明。树形 DP 通过穷举每个节点的所有合法状态，
// 用 min 操作精确选择最优方案，天然保证最优性。
//
// 对每个节点返回三个值:
//   cam:       该节点放摄像头时，子树最少摄像头数
//   covered:   该节点不放但被子节点覆盖时的最少数
//   uncovered: 该节点不放且未被覆盖时的最少数(期望父来覆盖)
//
// 状态转移:
//   cam = 1 + min(l.cam, l.covered, l.uncovered) 
//           + min(r.cam, r.covered, r.uncovered)
//     → 自己放了摄像头，子节点什么状态都行（都会被覆盖）
//
//   covered = min(l.cam + min(r.cam, r.covered),
//                 r.cam + min(l.cam, l.covered))
//     → 自己不放，至少一个子放了摄像头来覆盖自己
//     → 注意：uncovered 的子不能出现在这里（子必须自身合法）
//
//   uncovered = l.covered + r.covered
//     → 自己不放且没被覆盖，子节点各自"不放但被覆盖"即可
//     → 为什么不能用 l.uncovered？因为子节点的 uncovered 状态
//       是指望当前节点来覆盖的，但当前节点没放摄像头，矛盾
//
// DP 依赖关系:
//   当前节点的三个值 ← 左子的三个值 + 右子的三个值
//   (后序遍历，自底向上填表)
//
//   null 节点: cam=INF(不能放), covered=0, uncovered=0
//
// 根节点答案: min(cam, covered)
//   uncovered 不可选，因为根没有父来覆盖
// ============================================================
class Solution2 {
public:
    static constexpr int INF = 1e9;

    struct State {
        int cam;       // 自己放摄像头
        int covered;   // 不放但被子覆盖
        int uncovered; // 不放且未被覆盖
    };

    State dfs(TreeNode* node) {
        if (!node) {
            // null: 不能放摄像头(INF), 视为已覆盖(0), 未覆盖也是0(不消耗)
            return {INF, 0, 0};
        }

        auto [la, lb, lc] = dfs(node->left);
        auto [ra, rb, rc] = dfs(node->right);

        // 自己放摄像头: 子节点任意状态都行(都被自己覆盖)
        int cam = 1 + std::min({la, lb, lc}) + std::min({ra, rb, rc});

        // 自己不放但被覆盖: 至少一个子放了摄像头
        // 情况A: 左子放摄像头, 右子放或被覆盖(不能uncovered, 否则右子没人管)
        // 情况B: 右子放摄像头, 左子放或被覆盖
        int covered = std::min(la + std::min(ra, rb),
                               ra + std::min(la, lb));

        // 自己不放且未被覆盖: 两个子各自"不放但被覆盖"
        // 为什么不能用 lc 或 rc？因为 uncovered 的子指望当前节点覆盖它，
        // 但当前节点没放摄像头，形成循环依赖
        int uncovered = lb + rb;

        return {cam, covered, uncovered};
    }

    int minCameraCover(TreeNode* root) {
        auto [cam, covered, uncovered] = dfs(root);
        // 根节点没有父，不能处于 uncovered 状态
        return std::min(cam, covered);
    }
};


// ============================================================
// 【解法对比】
//
// 解法1(贪心) vs 解法2(树形DP):
// - 贪心: 代码量少(~20行核心), 思路直觉, 但贪心正确性需要论证
// - 树形DP: 代码量多, 状态转移更复杂, 但天然保证最优性
// - 面试首选解法1, 如果面试官追问正确性证明可以切换到解法2的思路
// - 两者时间空间复杂度相同，都是 O(n) 时间, O(h) 空间
//
// 【易错点】
//
// 1. null 返回值搞错:
//    ✗ if (!node) return 0;  // null=未覆盖 → 叶子的父和祖父都会被迫放摄像头
//    ✓ if (!node) return 1;  // null=已覆盖 → 叶子返回0, 正确触发父放摄像头
//
// 2. 忘记根节点特判:
//    ✗ return cameras;       // 如果根是状态0(未覆盖), 漏掉了
//    ✓ if (dfs(root)==0) cameras++;  // 根没有父, 必须自救
//
// 3. 判断优先级写反(解法1):
//    ✗ 先判断 left==2||right==2 再判断 left==0||right==0
//       → 当左子=0(未覆盖)且右子=2(有摄像头)时, 会错误返回1(已覆盖)
//       → 但左子0没人救!
//    ✓ 先判断0(未覆盖最紧急), 再判断2, 最后1
//
// 4. 树形DP中covered转移遗漏(解法2):
//    ✗ covered = la + ra;    // 两个子都放 → 不是最小的
//    ✓ covered = min(la+min(ra,rb), ra+min(la,lb));  // 至少一个放即可
//
// 5. 树形DP中uncovered错误使用子节点的uncovered:
//    ✗ uncovered = lc + rc;  // 子的uncovered指望当前节点覆盖, 但当前没放摄像头
//    ✓ uncovered = lb + rb;  // 子各自被覆盖, 不依赖当前节点
//
// 【面试追问 — 递进链】
//
// Q1(基础): "为什么叶子不放摄像头？"
//   → 叶子放摄像头只覆盖2个节点(自己+父), 父放能覆盖最多4个(父+所有子+祖父)
//     效率更高。交换论证: 任何在叶子放摄像头的方案, 移到父不会更差。
//
// Q2(深入): "三状态的转移顺序为什么不能变？"
//   → 因为状态0(未覆盖)是最紧急的。当一个孩子=0, 另一个=2时,
//     如果先判断2, 会返回1(已覆盖), 但状态0的孩子没人管了。
//     先判断0保证不遗漏任何未覆盖节点。
//
// Q3(变体): "如果摄像头覆盖范围是距离k(不只是1)?"
//   → 需要树形DP, 状态变为 dp[node][距离最近摄像头的距离]
//     每个节点维护 O(k) 个状态, 总复杂度 O(nk)。
//
// Q4(扩展): "如果是一般图而不是树?"
//   → 最小支配集在一般图上是NP-hard。树上可多项式解决的关键:
//     无环 → 子问题独立 → 贪心/DP 有效。
// ============================================================
