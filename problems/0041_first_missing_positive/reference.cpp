/*
 * LeetCode 41: First Missing Positive (缺失的第一个正数)
 *
 * 【题目本质】
 * 在未排序数组中找"没出现的最小正整数"。核心约束: O(n)时间 + O(1)空间。
 * 关键洞察: 长度为n的数组, 答案一定在[1, n+1]范围内, 
 * 因此可以把数组本身当成哈希表 —— 索引i存值i+1。
 *
 * 【解法总览】
 * 解法1: 暴力枚举           — O(n²) / O(1)    — 最直觉, 面试用来展示理解
 * 解法2: 哈希表              — O(n)  / O(n)    — 时间够了但空间超标
 * 解法3: 原地哈希(置换法)    — O(n)  / O(1)    — ⭐ 面试首选
 * 解法4: 原地标记(正负号法)  — O(n)  / O(1)    — 备选方案, 思路更巧妙
 */

// ============================================================
// 解法1: 暴力枚举
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 最朴素: 依次检查 1, 2, 3, ... 是否在数组中。
// 对每个候选值k, 遍历整个数组看k是否存在。
// 第一个不存在的k就是答案。
// 瓶颈: "检查k是否存在"需要O(n), 共检查最多n+1个候选, 总O(n²)。
// ============================================================
class Solution1 {
public:
    int firstMissingPositive(vector<int>& nums) {
        int n = nums.size();
        for (int k = 1; k <= n + 1; k++) {
            bool found = false;
            for (int i = 0; i < n; i++) {
                if (nums[i] == k) {
                    found = true;
                    break;
                }
            }
            if (!found) return k;
        }
        return n + 1;
    }
};

// ============================================================
// 解法2: 哈希表
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 暴力的瓶颈在"查找k是否存在"需要O(n)。
// 把所有元素存入 HashSet, 查找降到O(1)。
// 然后从1开始查, 第一个不在Set中的就是答案。
//
// 满足了O(n)时间, 但空间也是O(n), 不满足O(1)空间要求。
// 但这个解法自然引出下一步思考: 能不能不用额外空间做标记?
// ============================================================
class Solution2 {
public:
    int firstMissingPositive(vector<int>& nums) {
        unordered_set<int> s(nums.begin(), nums.end());
        int n = nums.size();
        for (int k = 1; k <= n + 1; k++) {
            if (s.find(k) == s.end()) return k;
        }
        return n + 1;
    }
};

// ============================================================
// 解法3: 原地哈希 — 置换法 ⭐ 面试首选
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法2的瓶颈是O(n)额外空间。
// 核心洞察: 数组有n个格子, 答案在[1,n+1]范围内。
// 如果把值k放到索引k-1的位置(即 nums[k-1]=k), 
// 数组本身就成了一个"完美哈希表"。
//
// 遍历数组, 对每个位置:
//   - 如果 nums[i] 在[1,n]范围内且不在正确位置, 就swap到正确位置
//   - swap后当前位置来了新值, 可能也需要归位, 所以用while
//   - 如果目标位置已经有正确的值了(重复元素), 停止
//
// 第二遍扫描, 第一个 nums[i] != i+1 的位置, i+1就是答案。
//
// 为什么是O(n): 每次swap至少把一个元素放到最终位置, 
// 归位的元素不会再被移走, 所以总swap次数 ≤ n。(均摊分析)
//
// 示例: nums = [3, 4, -1, 1], n=4
//
// 索引:    0  1  2  3     目标: nums[i] = i+1
// 初始:   [3, 4, -1, 1]
//
// i=0: nums[0]=3, 应在索引2 → swap → [-1, 4, 3, 1]
//      nums[0]=-1, 不在[1,4], 停止while
//
// i=1: nums[1]=4, 应在索引3 → swap → [-1, 1, 3, 4]
//      nums[1]=1, 应在索引0 → swap → [1, -1, 3, 4]
//      nums[1]=-1, 不在[1,4], 停止while
//
// i=2: nums[2]=3, 应在索引2, 已就位, 停止while
// i=3: nums[3]=4, 应在索引3, 已就位, 停止while
//
// 最终: [1, -1, 3, 4]
//        ✓   ✗  ✓  ✓
// 索引1处 nums[1]≠2 → 答案=2
// ============================================================
class Solution3 {
public:
    int firstMissingPositive(vector<int>& nums) {
        int n = nums.size();

        for (int i = 0; i < n; i++) {
            // while 而非 if: swap来的新值可能也需要归位
            // 三个条件缺一不可:
            //   1) nums[i] >= 1          — 忽略非正数
            //   2) nums[i] <= n          — 忽略超出范围的数
            //   3) nums[nums[i]-1] != nums[i] — 目标位置还没有正确值(防重复元素死循环)
            while (nums[i] >= 1 && nums[i] <= n
                   && nums[nums[i] - 1] != nums[i]) {
                // 把 nums[i] 放到它该去的位置 nums[i]-1
                swap(nums[i], nums[nums[i] - 1]);
            }
        }

        // 扫描: 第一个 nums[i] != i+1 的位置
        for (int i = 0; i < n; i++) {
            if (nums[i] != i + 1) return i + 1;
        }

        // 数组恰好是 [1,2,...,n], 答案是 n+1
        return n + 1;
    }
};

// ============================================================
// 解法4: 原地标记 — 正负号法
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 另一种原地哈希的思路: 不移动元素, 而是用"正负号"做标记。
// 如果值k存在, 就把索引k-1处的值变成负数。
// 最后第一个正数的索引i, 说明i+1不存在。
//
// 问题: 原数组可能有负数和零, 会干扰正负标记。
// 解决: 先把所有 ≤0 的数替换成 n+1 (一个不在[1,n]范围内的安全值)。
//
// 三遍扫描:
// 1) 把 ≤0 的数替换成 n+1
// 2) 对于每个值 val∈[1,n], 把 nums[val-1] 标记为负
// 3) 第一个正数的索引 → 答案
//
// 示例: nums = [3, 4, -1, 1], n=4
//
// Step1 - 清除非正数: [3, 4, 5, 1]    (-1 → 5)
//
// Step2 - 标记:
//   i=0: val=|3|=3 ≤ 4, 标记索引2 → [3, 4, -5, 1]
//   i=1: val=|4|=4 ≤ 4, 标记索引3 → [3, 4, -5, -1]
//   i=2: val=|-5|=5 > 4, 跳过
//   i=3: val=|-1|=1 ≤ 4, 标记索引0 → [-3, 4, -5, -1]
//
// Step3 - 扫描:
//   索引0: -3 < 0 ✓ (1存在)
//   索引1:  4 > 0 ✗ → 答案 = 2
// ============================================================
class Solution4 {
public:
    int firstMissingPositive(vector<int>& nums) {
        int n = nums.size();

        // 第一步: 把 ≤0 的数变成 n+1
        // 为什么是 n+1: 它不在[1,n]范围内, 第二步会被跳过, 不会错误标记
        for (int i = 0; i < n; i++) {
            if (nums[i] <= 0) nums[i] = n + 1;
        }

        // 第二步: 用正负号标记
        for (int i = 0; i < n; i++) {
            int val = abs(nums[i]);  // 取绝对值: 该位置可能已经被标记为负
            if (val <= n) {
                // 用 -abs 而非取反: 防止同一位置被标记两次后翻回正数
                nums[val - 1] = -abs(nums[val - 1]);
            }
        }

        // 第三步: 第一个正数的索引+1 就是缺失的最小正整数
        for (int i = 0; i < n; i++) {
            if (nums[i] > 0) return i + 1;
        }

        return n + 1;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间  | 空间  | 修改原数组 | 理解难度 |
// |-----------|-------|-------|-----------|---------|
// | 暴力枚举   | O(n²) | O(1)  | 否        | 低      |
// | 哈希表     | O(n)  | O(n)  | 否        | 低      |
// | 置换法 ⭐  | O(n)  | O(1)  | 是        | 中      |
// | 正负号法   | O(n)  | O(1)  | 是        | 中高    |
//
// 面试首选置换法: "把k放到位置k-1"一句话就能讲清核心思想,
// 代码也最简洁。正负号法作为追问"还有别的方法吗"的备选。
//
// ============================================================
// 【易错点】
//
// 1. 置换法用 if 而不是 while:
//    ✗ if (nums[i]>=1 && ...) swap(...);
//      只swap一次, 换来的新数没继续归位
//    ✓ while (nums[i]>=1 && ...) swap(...);
//
// 2. 置换法缺少防重复判断:
//    ✗ while (nums[i]>=1 && nums[i]<=n) swap(...);
//      对 [1,1] 这种重复数组会死循环
//    ✓ while (... && nums[nums[i]-1] != nums[i]) swap(...);
//
// 3. 正负号法标记时直接取反:
//    ✗ nums[val-1] = -nums[val-1];
//      同一位置标记两次: 正→负→正, 等于没标记
//    ✓ nums[val-1] = -abs(nums[val-1]);
//      多次标记都保持为负
//
// 4. 忘记返回 n+1:
//    当数组恰好是[1,2,...,n]的排列时, 循环结束无异常位置,
//    必须在最后 return n+1;
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么答案一定在[1, n+1]?
//     → 数组n个位置最多放n个不同正整数(1到n), 
//       任何不是{1,...,n}全集的情况都有缺失, 答案≤n;
//       如果恰好是{1,...,n}, 答案就是n+1。
//
// Q2: 置换法的 while 嵌套在 for 里, 总时间真的是O(n)吗?
//     → 均摊分析: 每次swap让一个元素归位, 归位后不再移动,
//       所以总swap次数≤n。虽然某个i可能触发多次swap,
//       但分摊到所有迭代, 总工作量O(n)。
//
// Q3: 如果数组不允许修改, 怎么做?
//     → 不修改数组 + O(1)空间是不可能的(需要O(n)空间记录信息)。
//       最优是O(n)时间O(n)空间的哈希表解法。
//       或者复制数组再原地操作, 但这也是O(n)空间。
//
// Q4(变体): 如果要找前k个缺失的正整数呢?
//     → 原地归位后, 扫描时不是遇到第一个就返回,
//       而是收集所有 nums[i]!=i+1 的位置, 直到凑够k个。
//       如果不够, 从n+1继续往后数。
// ============================================================
