/*
 * LeetCode 1732: 找到最高海拔 (Find the Highest Altitude)
 *
 * 【题目本质】
 * gain 是差分数组，海拔是前缀和。求前缀和序列（包含起点 0）的最大值。
 *
 * 【解法总览】
 * 解法1: 构建海拔数组（前缀和）   — O(n) / O(n)  — 最直觉
 * 解法2: 滚动变量（空间优化前缀和）— O(n) / O(1)  — 面试首选
 */

// ============================================================
// 解法1: 构建海拔数组 — 先算出所有点的海拔，再取最大值
// 时间: O(n)  空间: O(n)
//
// 【思路】
// gain[i] 是第 i 点到第 i+1 点的海拔差，起点海拔为 0。
// 那么每个点的海拔就是 gain 的前缀和：
//   altitude[0] = 0
//   altitude[i] = gain[0] + gain[1] + ... + gain[i-1]
// 
// 示例: gain = [-5, 1, 5, 0, -7]
//
//   点:       0    1    2    3    4    5
//   海拔:     0   -5   -4    1    1   -6
//             ↑         ↑    ↑
//           起点    -5+1=−4  −4+5=1
//
//   最高海拔 = 1
// ============================================================
class Solution1 {
public:
    int largestAltitude(vector<int>& gain) {
        int n = gain.size();
        // n+1 个点（n 条边连接 n+1 个节点）
        vector<int> altitude(n + 1, 0);
        for (int i = 0; i < n; i++) {
            altitude[i + 1] = altitude[i] + gain[i];  // 前缀和
        }
        // 在所有海拔中找最大值（包含起点 altitude[0] = 0）
        return *max_element(altitude.begin(), altitude.end());
    }
};

// ============================================================
// 解法2: 滚动变量 — 不存数组，一边累加一边取 max
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1 开了 O(n) 的数组，但我们只关心最大值，不需要保存所有海拔。
// 用一个变量 cur 表示"当前海拔"，每次累加 gain[i]，
// 同时维护 maxAlt 记录出现过的最大海拔。
//
// 关键：maxAlt 初始化为 0，因为起点海拔 0 也是候选答案。
//       如果所有 gain 都是负数，答案就是起点的 0。
//
// 过程演示 (gain = [-5, 1, 5, 0, -7]):
//   初始: cur=0, maxAlt=0
//   i=0: cur=0+(-5)=-5, maxAlt=max(0,-5)=0
//   i=1: cur=-5+1=-4,   maxAlt=max(0,-4)=0
//   i=2: cur=-4+5=1,    maxAlt=max(0,1)=1   ← 更新
//   i=3: cur=1+0=1,     maxAlt=max(1,1)=1
//   i=4: cur=1+(-7)=-6, maxAlt=max(1,-6)=1
//   结果: 1
// ============================================================
class Solution2 {
public:
    int largestAltitude(vector<int>& gain) {
        int cur = 0;      // 当前海拔，起点为 0
        int maxAlt = 0;   // 最高海拔，起点 0 也参与比较，所以初始化为 0
        for (int g : gain) {
            cur += g;
            maxAlt = max(maxAlt, cur);
        }
        return maxAlt;
    }
};

// ============================================================
// 【解法对比】
// 
// 解法1 vs 解法2:
//   - 时间复杂度相同 O(n)
//   - 解法1 额外 O(n) 空间存完整海拔数组，解法2 仅 O(1)
//   - 解法2 是解法1 的空间优化版：因为 altitude[i+1] 只依赖
//     altitude[i]，所以可以用滚动变量替代数组（经典前缀和优化）
//   - 如果后续需要多次查询某个点的海拔，用解法1；只求最值用解法2
//
// 【易错点】
// 1. maxAlt 初始化为 INT_MIN 而非 0:
//    ✗ int maxAlt = INT_MIN;
//      → 看似"安全"，实际遗漏了起点海拔 0
//      → 但其实 INT_MIN < 0，如果所有前缀和都 < 0，
//        INT_MIN 仍然 < 0，最终 maxAlt 会是某个负的前缀和，
//        但正确答案是起点的 0。
//    ✓ int maxAlt = 0;
//      → 起点海拔 0 本身就是候选答案，直接作为初始值
//
// 2. 数组大小搞错:
//    ✗ vector<int> altitude(n, 0);     // n 个元素，少了起点
//    ✓ vector<int> altitude(n + 1, 0); // n+1 个点
//
// 【面试追问】
// Q1: 这道题的数学本质？
//   → gain 是差分数组，海拔是前缀和。求最高海拔 = 求前缀和最大值。
//
// Q2: 如果起点海拔不是 0 而是 startAlt？
//   → cur 和 maxAlt 都初始化为 startAlt，其余不变。
//
// Q3: 如果需要多次查询 [l, r] 范围内最高海拔？
//   → 先建前缀和数组得到所有海拔，再用 Sparse Table 或线段树
//     支持 O(1) / O(log n) 区间最值查询。
// ============================================================
