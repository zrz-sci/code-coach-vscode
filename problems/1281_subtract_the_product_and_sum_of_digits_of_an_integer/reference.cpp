/*
 * LeetCode 1281: 整数的各位积和之差
 * Subtract the Product and Sum of Digits of an Integer
 *
 * 【题目本质】
 * 给定正整数 n，把它的每一位数字拆出来，分别算乘积和求和，返回 乘积 - 求和。
 * 核心技能：数位分离（% 10 取末位，/ 10 去末位）。
 *
 * 【解法总览】
 * 解法1: 循环取模（标准）  — O(d) / O(1)  — 面试首选，最能体现数学功底
 * 解法2: 字符串转换        — O(d) / O(d)  — 直观但不如取模写法精炼
 * 解法3: 递归拆位          — O(d) / O(d)  — 递归思维练习
 *
 * d 是数字的位数，n <= 10^5 所以 d <= 6
 */

// ============================================================
// 解法1: 循环取模 — 面试首选
// 时间: O(d)  空间: O(1)
//
// 【思路】
// 用 % 10 取末位，/ 10 去掉末位，循环直到 n 变成 0。
// 两个累加器分别记录乘积和求和。
//
// 【初始化为什么这样设？】
// product = 1 → 乘法的单位元（任何数 * 1 = 任何数）
// sum = 0     → 加法的单位元（任何数 + 0 = 任何数）
// 如果 product = 0，那乘积永远是 0（常见错误！）
//
// 示例: n = 234
//   第1轮: digit = 234 % 10 = 4
//          product = 1 * 4 = 4,   sum = 0 + 4 = 4
//          n = 234 / 10 = 23
//   第2轮: digit = 23 % 10 = 3
//          product = 4 * 3 = 12,  sum = 4 + 3 = 7
//          n = 23 / 10 = 2
//   第3轮: digit = 2 % 10 = 2
//          product = 12 * 2 = 24, sum = 7 + 2 = 9
//          n = 2 / 10 = 0
//   结束: product - sum = 24 - 9 = 15 ✓
//
// 示例: n = 4421
//   digit 序列: 1, 2, 4, 4（从低位到高位）
//   product = 1*1*2*4*4 = 32 （乘法满足交换律，顺序无所谓）
//   sum = 0+1+2+4+4 = 11
//   结果 = 32 - 11 = 21 ✓
//
// 示例（含0）: n = 105
//   digit 序列: 5, 0, 1
//   product = 1*5*0*1 = 0  （任何数乘0都是0）
//   sum = 0+5+0+1 = 6
//   结果 = 0 - 6 = -6（结果可以是负数，没问题）
// ============================================================
class Solution1 {
public:
    int subtractProductAndSum(int n) {
        int product = 1;  // 乘法单位元，不能初始化为0！
        int sum = 0;      // 加法单位元

        while (n > 0) {
            int digit = n % 10;  // 取最低位（个位）
            product *= digit;    // 累乘
            sum += digit;        // 累加
            n /= 10;             // 去掉最低位（整数除法自动截断）
        }

        return product - sum;
    }
};

// ============================================================
// 解法2: 字符串转换
// 时间: O(d)  空间: O(d)
//
// 【思路】
// 把整数转成字符串，遍历每个字符。
// 字符 '0'~'9' 的 ASCII 值连续，所以 c - '0' 就得到对应的数字。
//
// 这种写法更直观，适合快速实现。但面试中取模写法
// 更能展示对数字运算的理解。
//
// 示例: n = 234 → str = "234"
//   '2'-'0'=2, '3'-'0'=3, '4'-'0'=4
//   product = 2*3*4 = 24, sum = 2+3+4 = 9
//   结果 = 24 - 9 = 15 ✓
//
// 【和取模方法的区别】
// - 取模：从低位到高位处理（先拿到 4, 再 3, 再 2）
// - 字符串：从高位到低位处理（先拿到 2, 再 3, 再 4）
// - 因为加法和乘法都满足交换律，顺序不影响结果
// ============================================================
class Solution2 {
public:
    int subtractProductAndSum(int n) {
        string s = to_string(n);  // 整数 → 字符串
        int product = 1, sum = 0;

        for (char c : s) {
            int digit = c - '0';  // 字符 → 数字
            product *= digit;
            sum += digit;
        }

        return product - sum;
    }
};

// ============================================================
// 解法3: 递归拆位
// 时间: O(d)  空间: O(d) — 递归栈深度为 d
//
// 【思路】
// 把"处理 n 的所有位"分解为：
//   - 处理 n 的末位（n % 10）
//   - 递归处理剩余部分（n / 10）
// 用引用参数传递 product 和 sum。
//
// 递归终止条件：n == 0 时所有位都已处理完毕。
//
// 这只是循环的等价递归写法。递归深度最多 6 层（n <= 10^5），
// 不会栈溢出。实际面试不建议用这种方式，但有助于理解递归思维。
//
// 示例: n = 234
//   helper(234, 1, 0)
//     digit=4, product=4, sum=4
//     helper(23, 4, 4)
//       digit=3, product=12, sum=7
//       helper(2, 12, 7)
//         digit=2, product=24, sum=9
//         helper(0, 24, 9) → return
//   最终: product=24, sum=9, 返回 24-9=15 ✓
// ============================================================
class Solution3 {
public:
    int subtractProductAndSum(int n) {
        int product = 1, sum = 0;
        helper(n, product, sum);
        return product - sum;
    }

private:
    void helper(int n, int& product, int& sum) {
        if (n == 0) return;       // 递归终止：所有位都处理完了
        int digit = n % 10;       // 取末位
        product *= digit;         // 累乘
        sum += digit;             // 累加
        helper(n / 10, product, sum);  // 递归处理剩余位
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 时间  | 空间  | 代码量 | 推荐度 |
// |------------|-------|-------|--------|--------|
// | 循环取模    | O(d)  | O(1)  | 最少   | ⭐⭐⭐  |
// | 字符串转换  | O(d)  | O(d)  | 中等   | ⭐⭐    |
// | 递归拆位    | O(d)  | O(d)  | 最多   | ⭐      |
//
// 面试建议：直接写解法1。如果面试官问"还有别的方式吗？"，
// 可以提解法2（字符串）。解法3（递归）一般不需要提。
//
// ============================================================
// 【易错点】
//
// 1. product 初始化为 0:
//    ✗ int product = 0; → 乘积永远是 0，因为 0 * 任何数 = 0
//    ✓ int product = 1; → 乘法单位元
//
// 2. 循环条件 n >= 0:
//    ✗ while (n >= 0) → n=0 时还会执行，digit=0, product 变成 0
//    ✓ while (n > 0)  → n 减到 0 就停
//
// 3. 忘记 n /= 10:
//    ✗ 只取了 n%10 没有 n/=10 → 死循环，digit 永远是同一个数
//    ✓ 取完末位后必须去掉末位
//
// 4. 字符串中 c - 0 而非 c - '0':
//    ✗ int digit = c - 0; → 得到 ASCII 值（'4' 是 52，不是 4）
//    ✓ int digit = c - '0'; → 得到数字值
//
// ============================================================
// 【数位拆分模板总结】
//
// 这道题的 % 10 / / 10 模板是很多题目的基础：
//
//   while (n > 0) {
//       int digit = n % 10;  // 取末位
//       // ... 对 digit 做操作 ...
//       n /= 10;             // 去掉末位
//   }
//
// 应用场景：
// - LeetCode 7:   整数反转 → rev = rev*10 + digit
// - LeetCode 9:   回文数   → 反转后半段比较
// - LeetCode 202: 快乐数   → digit*digit 求和
// - LeetCode 258: 各位相加 → 反复求数位和
// - LeetCode 1281:本题     → 同时求积和和
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 如果 n 可以是 0？
//     while 循环不进入，product=1, sum=0, 返回 1。
//     但题意保证 n >= 1，不需要特殊处理。
//
// Q2: 如果 n 可以是负数？
//     先取绝对值。注意 C++ 中负数取模的符号：
//     -234 % 10 = -4（不是 6），所以 n = abs(n) 再处理。
//
// Q3: 如果 n 超出 int 范围（比如 10^18）？
//     用 long long，或者直接用字符串输入按字符处理。
//     乘积可能溢出：最坏情况 9^18 约 1.5*10^17，在 long long 范围内。
//
// Q4: 这个数位拆分思想还能用在哪？
//     整数反转、回文数判断、快乐数、数位 DP 等。
//     是处理整数问题的最基本工具。
// ============================================================
