/*
 * LeetCode 6: Z 字形变换 (Zigzag Conversion)
 *
 * 【题目本质】
 * 索引映射问题：字符在行间以"弹球"模式上下移动，按行收集后拼接。
 * 核心是发现周期性：周期 cycle = 2 * numRows - 2。
 *
 * 【解法总览】
 * 解法1: 模拟行桶收集 — O(n) / O(n) — 直觉模拟，面试首选
 * 解法2: 数学周期索引 — O(n) / O(1) — 利用周期公式直接按行收集，加分项
 */

// ============================================================
// 解法1: 模拟行桶收集 — 弹球模式逐字符分配
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 想象手写 Z 字形：笔从第 0 行开始往下，到底反弹往上，到顶再反弹。
// 不需要真正的二维网格，只需要 numRows 个字符串"桶"。
// 遍历原字符串，根据当前行号把字符追加到对应桶，遇到边界就反转方向。
//
// 以 "PAYPALISHIRING", numRows=4 为例:
//
//   字符: P  A  Y  P  A  L  I  S  H  I  R  I  N  G
//   行号: 0  1  2  3  2  1  0  1  2  3  2  1  0  1
//         ↓  ↓  ↓  ↓  ↑  ↑  ↓  ↓  ↓  ↓  ↑  ↑  ↓  ↓
//
//   行0: P     I     N       → "PIN"
//   行1: A   L S   I G       → "ALSIG"
//   行2: Y A   H R           → "YAHR"
//   行3: P     I             → "PI"
//
//   拼接: "PIN" + "ALSIG" + "YAHR" + "PI" = "PINALSIGYAHRPI"
// ============================================================
class Solution1 {
public:
    string convert(string s, int numRows) {
        // numRows==1 时没有 Z 字形；numRows>=len 时每个字符独占一行，结果就是原串
        if (numRows == 1 || numRows >= (int)s.size()) return s;

        vector<string> rows(numRows);

        int curRow = 0;
        int direction = -1;  // 初始-1，因为curRow==0时会立刻反转为+1（向下）

        for (char c : s) {
            rows[curRow] += c;

            // 到达顶部(0)或底部(numRows-1)时反转移动方向
            if (curRow == 0 || curRow == numRows - 1) {
                direction = -direction;
            }
            curRow += direction;
        }

        // 逐行拼接
        string result;
        for (const string& row : rows) {
            result += row;
        }
        return result;
    }
};

// ============================================================
// 解法2: 数学周期索引 — 直接按行计算包含哪些字符
// 时间: O(n)  空间: O(1)（不计输出字符串）
//
// 【思路】
// 解法1需要模拟方向切换过程。但 Z 字形排列有严格的周期性：
//   cycle = 2 * numRows - 2
//
// 对于第 row 行，在每个周期起点 j 处：
//   - 下行字符索引: j + row
//   - 上行字符索引: j + cycle - row（仅中间行有，首尾行没有）
//
// 为什么 j + cycle - row？
//   从周期起点 j，下行走到底需要 numRows-1 步到达第 numRows-1 行，
//   再上行走 numRows-1-row 步回到第 row 行，
//   总步数 = (numRows-1) + (numRows-1-row) = 2*numRows - 2 - row = cycle - row
//
// 以 numRows=4, cycle=6 为例:
//
//   周期起点 j:    0           6          12
//   行0: 0,             6,          12        (j+0)
//   行1: 1,    5,       7,   11,    13        (j+1, j+5)
//   行2: 2,  4,         8, 10                 (j+2, j+4)
//   行3: 3,             9                     (j+3)
//
//   注意行1和行2每个周期有两个字符，行0和行3只有一个
// ============================================================
class Solution2 {
public:
    string convert(string s, int numRows) {
        if (numRows == 1 || numRows >= (int)s.size()) return s;

        int n = s.size();
        int cycle = 2 * numRows - 2;
        string result;
        result.reserve(n);  // 预分配，避免反复扩容

        for (int row = 0; row < numRows; row++) {
            for (int j = 0; j + row < n; j += cycle) {
                // 下行字符：每行每个周期都有
                result += s[j + row];

                // 上行字符：仅中间行有（首行和末行每周期只有1个字符）
                // 索引 j + cycle - row 必须在合法范围内
                if (row != 0 && row != numRows - 1 && j + cycle - row < n) {
                    result += s[j + cycle - row];
                }
            }
        }

        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 解法1: 模拟行桶  | 解法2: 数学周期    |
// |-----------|----------------|------------------|
// | 核心思想   | 弹球模拟，逐字符分配 | 周期公式直接按行索引 |
// | 时间       | O(n)            | O(n)              |
// | 空间       | O(n) 行桶       | O(1) 除输出外      |
// | 代码难度   | 简单直观         | 需推导公式          |
// | 面试推荐   | ⭐ 首选          | 追问时展示数学能力   |
//
// 两种解法时间都是 O(n)，解法1更好写、不容易出错，面试优先写解法1。
// 解法2的价值在于展示你能发现周期规律并直接计算。
//
// ============================================================
// 【易错点】
//
// 1. 忘记特判 numRows == 1:
//    ✗ cycle = 2*1-2 = 0，内层循环 j += 0 死循环
//    ✓ 开头特判 if (numRows == 1) return s;
//
// 2. direction 初始值搞反（解法1）:
//    ✗ direction = 1，第一个字符放到行0后直接移到行1，
//      但没在行0触发反转 → 行为正确但逻辑不一致
//    ✓ direction = -1，利用 curRow==0 时的反转自动变成+1
//    （也可以 direction=1 但把反转判断放到 curRow += 之后，
//     此时判断条件是 curRow<0 || curRow>=numRows，然后回退+反转）
//
// 3. 数学解法越界（解法2）:
//    ✗ result += s[j + cycle - row]; 没检查索引 < n
//    ✓ 必须加 j + cycle - row < n 的判断
//
// 4. 整型溢出不是问题：
//    s.length <= 1000，不会溢出 int。但如果 s.size() 返回 size_t
//    和 numRows 比较时要注意无符号 vs 有符号（这里我们用了 (int)s.size()）。
//
// ============================================================
// 【面试追问】
//
// Q1（基础理解）: Z字形排列的移动模式是什么？
// → 弹球模式，在第0行和第numRows-1行之间反复上下移动，
//   周期长度 = 2*numRows-2。
//
// Q2（优化）: 能否不用额外的行数组？
// → 利用周期公式直接按行收集，就是解法2。
//   每行的索引可以直接计算：下行 j+row，上行 j+cycle-row。
//
// Q3（变体）: 给定Z字形变换后的字符串和numRows，还原原串？
// → 先用周期公式算出每行有多少字符，确定变换后字符串中每行的起止位置。
//   然后按弹球顺序（0,1,2,...,numRows-1,...,1,0,...）
//   依次从对应行取下一个字符，即可还原。
//
// Q4（并行）: 超长字符串如何并行化？
// → 数学解法天然可并行：每行的索引计算独立，分配给不同线程。
//   模拟法必须顺序执行（方向依赖上一步状态）。
//
