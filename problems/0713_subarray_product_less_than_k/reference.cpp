/*
 * LeetCode 713: 乘积小于 K 的子数组 (Subarray Product Less Than K)
 *
 * 【题目本质】
 * 在正整数数组中，统计乘积严格小于 k 的连续子数组个数。
 * 因为所有元素 ≥ 1，乘积随窗口扩大单调不减，天然适合滑动窗口。
 *
 * 【解法总览】
 * 解法1: 暴力枚举          — O(n²) / O(1)   — 最直觉，枚举所有子数组
 * 解法2: 滑动窗口(双指针)   — O(n)  / O(1)   — 利用乘积单调性 ⭐ 面试首选
 * 解法3: 对数前缀和+二分    — O(n log n) / O(n) — 乘法变加法，展示知识面
 */

// ============================================================
// 解法1: 暴力枚举 — 固定左端点，右端点扩展累乘
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 最朴素的做法：枚举每个起点 i，从 i 开始向右累乘。
// 因为所有元素 ≥ 1，乘积单调不减，一旦 ≥ k 就 break。
// 虽然有 break 加速，但最坏仍是 O(n²)（如全1且k很大）。
//
// 【过程示意】 nums = [10,5,2,6], k = 100
// i=0: 10 → 50 → 100(≥k,break)         → count += 2 ([10],[10,5])
// i=1: 5  → 10 → 60                     → count += 3 ([5],[5,2],[5,2,6])
// i=2: 2  → 12                           → count += 2 ([2],[2,6])
// i=3: 6                                 → count += 1 ([6])
//                                          总计 = 8 ✓
// ============================================================
class Solution1 {
public:
    int numSubarrayProductLessThanK(vector<int>& nums, int k) {
        if (k <= 1) return 0; // 所有元素≥1，乘积≥1，不可能<1
        int n = nums.size(), count = 0;
        for (int i = 0; i < n; i++) {
            int prod = 1;
            for (int j = i; j < n; j++) {
                prod *= nums[j];
                if (prod < k) {
                    count++;
                } else {
                    break; // 乘积单调不减，后面更大，不用继续
                }
            }
        }
        return count;
    }
};

// ============================================================
// 解法2: 滑动窗口(双指针) — 利用乘积单调不减的性质 ⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1的瓶颈：每个起点都要从头开始累乘。
// 观察：当左端点从 i 移到 i+1 时，只需要除掉 nums[i]。
// 这就是滑动窗口：right 右移乘入，left 右移除去。
//
// 核心问题：怎么数子数组个数？
// 当右指针在 right 时，[left..right] 是以 right 结尾的最长合法窗口。
// 以 right 结尾的合法子数组恰好有 right - left + 1 个：
//   [left..right], [left+1..right], ..., [right..right]
// 每个子数组在其右端点处恰好被计数一次，不重不漏。
//
// 【滑动窗口过程】 nums = [10,5,2,6], k = 100
//
// right=0: prod=10            [10]          10<100 → count += 0-0+1 = 1
//          窗口: |10| 5  2  6
//
// right=1: prod=50            [10,5]        50<100 → count += 1-0+1 = 2
//          窗口: |10  5| 2  6
//
// right=2: prod=100           [10,5,2]      100≥100 → 收缩!
//          prod=100/10=10     [5,2]         10<100  → count += 2-1+1 = 2
//          窗口:  10 |5  2| 6
//
// right=3: prod=60            [5,2,6]       60<100  → count += 3-1+1 = 3
//          窗口:  10 |5  2  6|
//
// 总计: 1 + 2 + 2 + 3 = 8 ✓
// ============================================================
class Solution2 {
public:
    int numSubarrayProductLessThanK(vector<int>& nums, int k) {
        // 特判：所有元素≥1，乘积≥1，k≤1时不可能有合法子数组
        if (k <= 1) return 0;

        int left = 0, count = 0;
        int prod = 1; // 维护窗口 [left, right] 内的乘积

        for (int right = 0; right < (int)nums.size(); right++) {
            prod *= nums[right]; // 右指针扩展，乘入新元素

            // 如果乘积 ≥ k，收缩左边界（除掉最左元素）
            // 为什么是 >= 不是 >？因为题目要求"严格小于"k
            while (prod >= k) {
                prod /= nums[left];
                left++;
            }

            // 以 right 结尾的合法子数组个数 = right - left + 1
            // 分别是 [left..right], [left+1..right], ..., [right..right]
            count += right - left + 1;
        }

        return count;
    }
};

// ============================================================
// 解法3: 对数前缀和 + 二分查找 — 乘法变加法
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 不同角度思考：log(a*b*c) = log(a) + log(b) + log(c)
// 取对数后乘积问题变成求和问题！
//
// 令 prefix[i] = sum of log(nums[0..i-1])
// 子数组 [i..j] 的乘积 < k
//   等价于 prefix[j+1] - prefix[i] < log(k)
//   等价于 prefix[i] > prefix[j+1] - log(k)
//
// 因为 nums[i] ≥ 1，所以 log(nums[i]) ≥ 0，prefix 是单调不减的。
// 对每个 j，用二分找最小的 i 使得 prefix[i] > prefix[j+1] - log(k)。
//
// 【二分搜索过程示意】 nums = [10,5,2,6], k = 100
// prefix = [0, 2.30, 3.91, 4.61, 6.40]   (取 log)
// logK = 4.605
//
// j=0: target = prefix[1] - logK = 2.30 - 4.61 = -2.31
//      在 prefix[0..1] 中找 > -2.31 的最小 i → i=0
//      count += 0 - 0 + 1 = 1
//
// j=3: target = prefix[4] - logK = 6.40 - 4.61 = 1.79
//      在 prefix[0..4] 中找 > 1.79 的最小 i → i=1 (prefix[1]=2.30)
//      count += 3 - 1 + 1 = 3
//
// 注意：浮点精度是这种方法的固有弱点。
// ============================================================
class Solution3 {
public:
    int numSubarrayProductLessThanK(vector<int>& nums, int k) {
        if (k <= 1) return 0;
        int n = nums.size();

        // 构建对数前缀和
        vector<double> prefix(n + 1, 0.0);
        for (int i = 0; i < n; i++) {
            prefix[i + 1] = prefix[i] + log(nums[i]);
        }

        double logK = log(k);
        int count = 0;

        for (int j = 0; j < n; j++) {
            // 需要 prefix[j+1] - prefix[i] < logK
            // 即 prefix[i] > prefix[j+1] - logK
            // 加 1e-9 是为了处理"严格小于"在浮点下的边界
            double target = prefix[j + 1] - logK + 1e-9;

            // 在 prefix[0..j+1] 中二分找第一个 >= target 的位置
            int lo = 0, hi = j + 1;
            while (lo < hi) {
                int mid = lo + (hi - lo) / 2;
                if (prefix[mid] >= target) {
                    hi = mid;
                } else {
                    lo = mid + 1;
                }
            }
            // lo 是最小的合法起点，以 j 结尾的合法子数组有 j - lo + 1 个
            count += j - lo + 1;
        }

        return count;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 时间       | 空间  | 核心思想         | 适用场景       |
// |----------|-----------|-------|------------------|---------------|
// | 暴力枚举  | O(n²)     | O(1)  | 枚举+提前break   | 展示理解       |
// | 滑动窗口  | O(n)      | O(1)  | 双指针+单调性    | ⭐ 面试首选    |
// | 对数+二分 | O(n logn) | O(n)  | 乘法变加法       | 展示知识面     |
//
// 解法2 是最优解：O(n) 时间 O(1) 空间，代码简洁，没有浮点精度问题。
// 解法3 的价值在于展示"通过数学变换把一种问题转化为另一种"的思维。
//
// ============================================================
// 【易错点】
//
// 1. 漏掉 k ≤ 1 的特判：
//    ✗ 不特判直接进入循环 → 当 k=0 时 while(prod>=0) 永远为真，left 越界
//    ✓ 开头 if (k <= 1) return 0;
//    原因: 所有 nums[i] ≥ 1，任何子数组乘积 ≥ 1，不可能 < 1
//
// 2. while 条件用 > 而不是 >=：
//    ✗ while (prod > k) → prod == k 时不收缩，但 k 不是"小于等于"而是"严格小于"
//    ✓ while (prod >= k) → 严格小于 k，等于 k 也要收缩
//
// 3. 计数写成赋值而不是累加：
//    ✗ count = right - left + 1;  → 每次覆盖前面的计数
//    ✓ count += right - left + 1; → 累加每个右端点的贡献
//
// 4. 整数溢出分析（面试加分项）：
//    prod 在收缩前最大 = (k-1) * max(nums[i]) ≤ (10⁶-1) * 1000 ≈ 10⁹
//    在 int 范围内 (2^31 ≈ 2.1×10⁹)，不会溢出。
//    但如果 k 或 nums[i] 更大，就需要用 long long。
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1（基础）：为什么滑动窗口能保证不漏数？
// A: 每个合法子数组恰好在其右端点处被计数一次。当 right 固定时，
//    以 right 结尾的所有合法子数组就是 [left..right] 到 [right..right]，
//    共 right-left+1 个。right 从 0 遍历到 n-1，覆盖了所有可能的右端点。
//
// Q2（优化）：如果数组中有 0 怎么办？
// A: 0 会导致 prod=0，之后除法失效（不能 prod/=0 来"去掉"0）。
//    需要特殊处理：遇到 0 时将 left 跳到 right+1，prod 重置为 1。
//    如果 k>0，包含 0 的子数组乘积为 0<k，需要额外计数。
//
// Q3（变体）：如果改成"乘积等于 k"的子数组个数？
// A: 等于没有单调性，滑动窗口不适用。可以参考 560 题的思路：
//    用哈希表存前缀积，检查 prefixProd / k 是否在哈希表中。
//    但要注意乘积溢出和 0 的情况。
//
// Q4（拓展）：如果元素可以是负数呢？
// A: 负数使乘积不再单调。窗口扩大乘积可能变小也可能变大。
//    需要像 152 题那样同时维护最大积和最小积，且滑动窗口不再适用，
//    需要考虑其他方法（如 DP 或分治）。
// ============================================================
