// 【解法对比】
//
// | 解法             | 时间      | 空间  | 难度  | 推荐  |
// |-----------------|----------|-------|-------|------|
// | HashSet+起点枚举 | O(n)     | O(n)  | 低    | ⭐⭐⭐ |
// | 排序+扫描        | O(nlogn) | O(1)  | 低    | ⭐⭐   |
// | 并查集           | O(n)     | O(n)  | 高    | ⭐    |
//
// 面试策略:
// 1. 先说排序思路: "排序后线性扫描，O(nlogn)，但题目要求O(n)..."
// 2. 引出 HashSet: "用 set 做 O(1) 查找，只从起点开始延伸"
// 3. 写出解法1，解释时间复杂度
// 4. 如果面试官追问，可提并查集
//
// ============================================================
// 【易错点】
//
// 1. 遍历原数组而非 set:
//    ✗ for (int num : nums) → 重复元素会多次触发起点判断
//    ✓ for (int num : s)    → 每个值只处理一次
//
// 2. 忘记起点判断:
//    ✗ 对每个数都 while(s.count(cur+1)) → O(n^2)
//    ✓ if (!s.count(num-1)) 才进入 while → O(n)
//
// 3. 排序解法忘记跳过重复:
//    ✗ nums[i] == nums[i-1] 时重置 curLen → [1,1,2,3] 得到 2 而非 3
//    ✓ continue 跳过重复，不重置
//
// 4. 空数组:
//    ✗ 排序后访问 nums[0] → 越界
//    ✓ 开头判 empty() 返回 0
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 为什么是 O(n)？那个 while 循环不是嵌套在 for 里吗？
//     不能简单看嵌套层数。while 循环只在"起点"时触发，
//     所有 while 循环的总迭代次数 = 所有连续链总长 = n。
//     所以总时间 = 外层 for O(n) + 所有 while 总计 O(n) = O(n)。
//
// Q2: unordered_set 最坏不是 O(n) 查找吗？
//     是的，哈希冲突严重时单次查找退化为 O(n)。
//     但实际中（随机数据 + 好的哈希函数）是 O(1)。
//     如果面试官纠结，可以用排序解法作为保底（确定性 O(nlogn)）。
//
// Q3: 如果数字动态加入，每次要回答最长连续序列？
//     并查集更适合。每次加入 num 时检查 num-1 和 num+1
//     是否已存在，存在就合并。用 size 数组维护连通分量大小。
//
// Q4: 如果要返回最长连续序列本身？
//     在找到最长链时记录 start = num, end = cur。
//     最终用 [start, end] 构造 vector。
