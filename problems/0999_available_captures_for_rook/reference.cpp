/*
 * LeetCode 999: 可以被一步捕获的棋子数 (Available Captures for Rook)
 *
 * 【题目本质】
 * 8x8 棋盘上一个白车 'R'，若干白象 'B'，若干黑卒 'p'。
 * 车沿行列直线移动，遇到棋子或边界停止。统计车能捕获的卒数。
 * 简单模拟题，重点在代码清晰性。
 *
 * 【解法总览】
 * 解法1: 方向数组 + 四方向扫描 — O(1) / O(1) — 面试首选 ⭐
 * 解法2: 四个独立循环           — O(1) / O(1) — 直白版
 */

// ============================================================
// 解法1: 方向数组 + 四方向扫描 — 面试首选 ⭐
// 时间: O(1)  空间: O(1)  (棋盘固定 8x8)
//
// 【思路】
// 1. 遍历棋盘找 'R' 的位置 (rr, rc)
// 2. 用方向数组 dx/dy 统一处理上下左右四个方向
// 3. 每个方向从 'R' 旁边开始逐格前进:
//    - 遇 'B': 该方向被阻挡，break
//    - 遇 'p': 可捕获，count++，break
//    - 遇 '.': 继续前进
//    - 越界: break
//
// 示例1:
//   . . . . . . . .
//   . . . p . . . .
//   . . . R . . . p
//   . . . . . . . .
//   . . . . . . . .
//   . . . p . . . .
//   . . . . . . . .
//   . . . . . . . .
//
//   R在(2,3):
//   上: (1,3)='p' → count=1
//   下: (3,3)→(4,3)→(5,3)='p' → count=2
//   左: (2,2)→(2,1)→(2,0)→越界 → 停
//   右: (2,4)→...→(2,7)='p' → count=3
//   答案: 3 ✓
//
// 示例2 (全被象阻挡):
//   R在(3,3), 上下左右紧挨 B
//   四个方向都 break at 'B' → count=0 ✓
// ============================================================
class Solution1 {
public:
    int numRookCaptures(vector<vector<char>>& board) {
        // 找到 'R' 的位置
        int rr = 0, rc = 0;
        for (int i = 0; i < 8; i++) {
            for (int j = 0; j < 8; j++) {
                if (board[i][j] == 'R') {
                    rr = i;
                    rc = j;
                    // 可以 break，但 8x8 无所谓效率
                }
            }
        }

        int count = 0;
        // 方向数组: 上(-1,0), 下(1,0), 左(0,-1), 右(0,1)
        int dx[] = {-1, 1, 0, 0};
        int dy[] = {0, 0, -1, 1};

        for (int d = 0; d < 4; d++) {
            int x = rr + dx[d];
            int y = rc + dy[d];

            // 沿当前方向逐格前进
            while (x >= 0 && x < 8 && y >= 0 && y < 8) {
                if (board[x][y] == 'B') {
                    // 白象阻挡，该方向无法继续
                    break;
                }
                if (board[x][y] == 'p') {
                    // 遇到黑卒，可以捕获
                    count++;
                    break;
                }
                // '.' 空格，继续前进
                x += dx[d];
                y += dy[d];
            }
        }

        return count;
    }
};

// ============================================================
// 解法2: 四个独立循环
// 时间: O(1)  空间: O(1)
//
// 【思路】
// 不用方向数组，四个方向分别写一个 for 循环。
// 代码稍长但意图更明确，特别适合面试白板时口述逻辑。
//
// 每个方向逻辑相同:
//   从 R 的位置出发（不包含 R 自身），沿一个方向走
//   遇到 'B' break，遇到 'p' count++ 然后 break
// ============================================================
class Solution2 {
public:
    int numRookCaptures(vector<vector<char>>& board) {
        // 找 R
        int rr = 0, rc = 0;
        for (int i = 0; i < 8; i++)
            for (int j = 0; j < 8; j++)
                if (board[i][j] == 'R') { rr = i; rc = j; }

        int count = 0;

        // 向上: row 递减
        for (int i = rr - 1; i >= 0; i--) {
            if (board[i][rc] == 'B') break;
            if (board[i][rc] == 'p') { count++; break; }
        }

        // 向下: row 递增
        for (int i = rr + 1; i < 8; i++) {
            if (board[i][rc] == 'B') break;
            if (board[i][rc] == 'p') { count++; break; }
        }

        // 向左: col 递减
        for (int j = rc - 1; j >= 0; j--) {
            if (board[rr][j] == 'B') break;
            if (board[rr][j] == 'p') { count++; break; }
        }

        // 向右: col 递增
        for (int j = rc + 1; j < 8; j++) {
            if (board[rr][j] == 'B') break;
            if (board[rr][j] == 'p') { count++; break; }
        }

        return count;
    }
};

// ============================================================
// 解法1 的提前退出版（找到 R 后立即开始扫描）
// ============================================================
class Solution3 {
public:
    int numRookCaptures(vector<vector<char>>& board) {
        // 找 R 并在找到时立即处理
        for (int i = 0; i < 8; i++) {
            for (int j = 0; j < 8; j++) {
                if (board[i][j] == 'R') {
                    return countCaptures(board, i, j);
                }
            }
        }
        return 0; // 不会到达这里（题目保证有 R）
    }

private:
    int countCaptures(vector<vector<char>>& board, int rr, int rc) {
        int count = 0;
        int dx[] = {-1, 1, 0, 0};
        int dy[] = {0, 0, -1, 1};

        for (int d = 0; d < 4; d++) {
            for (int x = rr + dx[d], y = rc + dy[d];
                 x >= 0 && x < 8 && y >= 0 && y < 8;
                 x += dx[d], y += dy[d]) {
                if (board[x][y] == 'B') break;
                if (board[x][y] == 'p') { count++; break; }
            }
        }
        return count;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间 | 空间 | 代码量 | 推荐场景 |
// |------|------|------|--------|----------|
// | 方向数组 | O(1) | O(1) | 中等 | ⭐面试首选 |
// | 四循环 | O(1) | O(1) | 稍多 | 白板简单 |
// | 提前退出 | O(1) | O(1) | 中等 | 展示编码习惯 |
//
// 【易错点】
//
// 1. 扫描起点包含了 R 自身
//    ✗ int x = rr, y = rc; → 第一格是 R 本身
//    ✓ int x = rr + dx[d], y = rc + dy[d]; → 从 R 旁边开始
//
// 2. 遇到 'B' 时没有 break
//    ✗ if (board[x][y] == 'p') count++; → 穿过了象去吃卒
//    ✓ 遇到 B 必须 break，象阻挡了车的路径
//
// 3. 只检查了第一格
//    ✗ 只看 R 上下左右紧邻的四格
//    ✓ 车可以移动任意格数（直到遇到棋子或边界）
//
// 4. 方向写错
//    ✗ 上: dx=1 → 这是向下
//    ✓ 上: dx=-1, dy=0 (row 减小)
//
// 【面试追问】
//
// Q1: 这题的时间复杂度？
// → O(1)。棋盘固定 8x8 = 64 格。找 R 最多 64 步，
//    四个方向各最多 7 步。总共 < 100 步操作。
//
// Q2: 如果棋盘 n x n?
// → O(n^2) 找 R + O(n) 四方向扫描 = O(n^2)。
//
// Q3: 如果车可以沿对角线移动（像皇后）？
// → 增加四个对角方向: (-1,-1), (-1,1), (1,-1), (1,1)。
//    方向数组从 4 个扩展到 8 个，逻辑完全相同。
//
// Q4: 如果要计算所有黑卒被任意白棋子攻击的情况？
// → 这就变成了更复杂的棋盘分析问题。需要分别处理每种白棋子
//    的攻击规则（车: 行列, 象: 对角线, 马: L形跳跃）。
// ============================================================
