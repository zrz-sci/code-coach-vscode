/*
 * LeetCode 647: 回文子串 (Palindromic Substrings)
 *
 * 【题目本质】
 * 统计字符串 s 中有多少个子串是回文的。
 * 核心洞察: 每个回文都有一个中心，从中心向两边扩展是最自然的检测方式。
 *
 * 【解法总览】
 * 解法1: 暴力枚举      — O(n³) / O(1) — 枚举所有子串逐一检查
 * 解法2: 动态规划       — O(n²) / O(n²) — dp[i][j] 表示 s[i..j] 是否回文
 * 解法3: 中心扩展       — O(n²) / O(1) — ⭐ 面试首选，枚举中心向两边扩展
 * 解法4: Manacher算法   — O(n) / O(n) — 利用对称性加速扩展
 */

// ============================================================
// 解法1: 暴力枚举 — 枚举所有子串，逐一判断是否回文
// 时间: O(n³)  空间: O(1)
//
// 【思路】
// 最直觉的方法: 两层循环枚举子串的起点 i 和终点 j，
// 然后对每个 s[i..j] 用双指针从两端向中间比较来判断回文。
// 
// 瓶颈: 每个子串独立检查，没有利用 s[i..j] 和 s[i+1..j-1] 之间的递推关系。
// ============================================================
class Solution1 {
public:
    int countSubstrings(string s) {
        int n = s.size(), count = 0;
        for (int i = 0; i < n; i++) {
            for (int j = i; j < n; j++) {
                if (isPalindrome(s, i, j)) {
                    count++;
                }
            }
        }
        return count;
    }
    
private:
    bool isPalindrome(const string& s, int left, int right) {
        while (left < right) {
            if (s[left] != s[right]) return false;
            left++;
            right--;
        }
        return true;
    }
};

// ============================================================
// 解法2: 动态规划 — 利用子问题的递推关系
// 时间: O(n²)  空间: O(n²)
//
// 【思路】
// 从暴力法的瓶颈出发: s[i..j] 是否回文 = s[i]==s[j] 且 s[i+1..j-1] 是回文。
// 定义 dp[i][j] = true 表示子串 s[i..j] 是回文。
//
// 状态转移:
//   if s[i] == s[j]:
//     if j - i <= 2:  dp[i][j] = true   (长度1/2/3的特殊情况)
//     else:           dp[i][j] = dp[i+1][j-1]
//
// dp 填表依赖关系:
//   dp[i][j] 依赖 dp[i+1][j-1]（左下方），
//   所以 i 必须从大到小遍历（或按子串长度从小到大）。
//
//   以 s = "aaa" 为例:
//         j=0  j=1  j=2
//   i=0    T    T    T     "a"✓  "aa"✓  "aaa"✓
//   i=1         T    T           "a"✓   "aa"✓
//   i=2              T                  "a"✓
//   统计 T 的个数 = 6
// ============================================================
class Solution2 {
public:
    int countSubstrings(string s) {
        int n = s.size(), count = 0;
        vector<vector<bool>> dp(n, vector<bool>(n, false));
        
        // i 从大到小: 保证 dp[i+1][j-1] 在 dp[i][j] 之前已计算
        for (int i = n - 1; i >= 0; i--) {
            for (int j = i; j < n; j++) {
                if (s[i] == s[j]) {
                    // j-i<=2 涵盖: 单字符(j==i), 双字符(j==i+1), 三字符(j==i+2)
                    // 这些情况下只要两端相等就一定是回文，不需要查 dp[i+1][j-1]
                    if (j - i <= 2 || dp[i + 1][j - 1]) {
                        dp[i][j] = true;
                        count++;
                    }
                }
            }
        }
        return count;
    }
};

// ============================================================
// 解法3: 中心扩展 — ⭐ 面试首选
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 换个角度: 不枚举子串再判断，而是枚举回文的"中心"，向两边扩展。
// 
// 回文中心有两种:
//   - 奇数长度: 中心是单个字符，如 "aba" 的中心是 'b'
//   - 偶数长度: 中心是两个相邻字符之间，如 "abba" 的中心在两个 'b' 之间
//
// 中心总数: n 个单字符中心 + (n-1) 个双字符中心 = 2n-1
// 每个中心最多扩展 O(n) 次，总计 O(n²)。
//
// 为什么比 DP 更好? 空间只要 O(1)，而且代码更简洁直觉。
//
// 以 s = "aab" 为例:
//
//   奇数中心:
//     i=0: 'a' → 扩展 s[-1]?  越界 → 贡献 1 ("a")
//     i=1: 'a' → 扩展 s[0]='a' vs s[2]='b' 不等 → 贡献 1 ("a")
//     i=2: 'b' → 扩展 s[1]?='a' vs s[3]? 越界 → 贡献 1 ("b")
//
//   偶数中心:
//     (0,1): s[0]='a'==s[1]='a' → "aa"✓ → 扩展越界 → 贡献 1
//     (1,2): s[1]='a'≠s[2]='b' → 贡献 0
//
//   总计: 1+1+1+1+0 = 4 ✓
// ============================================================
class Solution3 {
public:
    int countSubstrings(string s) {
        int n = s.size(), count = 0;
        
        for (int i = 0; i < n; i++) {
            // 奇数长度回文: 中心是 s[i] 一个字符
            count += expandFromCenter(s, i, i);
            // 偶数长度回文: 中心是 s[i] 和 s[i+1] 之间
            count += expandFromCenter(s, i, i + 1);
        }
        
        return count;
    }
    
private:
    // 从 (left, right) 向两边扩展，每次匹配就找到一个新回文
    int expandFromCenter(const string& s, int left, int right) {
        int count = 0;
        while (left >= 0 && right < (int)s.size() && s[left] == s[right]) {
            count++;   // 当前 s[left..right] 是回文，计数 +1
            left--;    // 继续向左扩展
            right++;   // 继续向右扩展
        }
        return count;
    }
};

// ============================================================
// 解法4: Manacher 算法 — O(n) 时间
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 中心扩展的加速版。核心观察:
// 当我们从左到右计算每个中心的回文半径时，如果当前位置 i 落在
// 某个已知回文的范围内（由 center 和 maxRight 标记），
// 那么 i 关于 center 的镜像位置 mirror 的回文半径信息可以直接复用，
// 从而跳过部分扩展。
//
// 预处理: 插入 '#' 统一奇偶
//   "abc" → "^#a#b#c#$"
//   '^' 和 '$' 是哨兵，避免边界检查。
//
// p[i]: 以 t[i] 为中心的最长回文半径（不含中心本身）
// 
// 利用对称性:
//   如果 i < maxRight（i 在当前最远回文内部），
//   那么 p[i] >= min(p[mirror], maxRight - i)
//   然后再尝试继续扩展。
//
// 统计回文子串数:
//   变换后的半径 p[i] 对应原字符串中 ceil(p[i]/2) 个回文子串。
//   即 (p[i] + 1) / 2。
// ============================================================
class Solution4 {
public:
    int countSubstrings(string s) {
        // 预处理: 插入分隔符，统一奇偶长度
        string t = "^#";
        for (char c : s) {
            t += c;
            t += '#';
        }
        t += '$';
        
        int n = t.size();
        vector<int> p(n, 0);
        int center = 0, maxRight = 0;
        
        for (int i = 1; i < n - 1; i++) {
            int mirror = 2 * center - i;  // i 关于 center 的对称位置
            
            // 利用对称性给 p[i] 一个初始值，避免从 0 开始扩展
            if (i < maxRight) {
                p[i] = min(maxRight - i, p[mirror]);
            }
            
            // 尝试继续扩展（超出已知范围的部分仍需逐一检查）
            while (t[i + p[i] + 1] == t[i - p[i] - 1]) {
                p[i]++;
            }
            
            // 如果当前回文的右边界超过了 maxRight，更新
            if (i + p[i] > maxRight) {
                center = i;
                maxRight = i + p[i];
            }
        }
        
        // 统计原字符串中的回文子串数
        // 变换后半径 p[i] → 原字符串中 (p[i]+1)/2 个回文子串
        int count = 0;
        for (int i = 1; i < n - 1; i++) {
            count += (p[i] + 1) / 2;
        }
        return count;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间   | 空间   | 优势               | 劣势             |
// |-------------|--------|--------|--------------------|-----------------| 
// | 暴力枚举     | O(n³)  | O(1)   | 最直觉             | 太慢             |
// | 动态规划     | O(n²)  | O(n²)  | dp表可复用(如131题) | 需要额外空间      |
// | 中心扩展     | O(n²)  | O(1)   | 简洁高效，面试首选   | 无               |
// | Manacher    | O(n)   | O(n)   | 理论最优            | 代码复杂，面试少考 |
//
// 选择建议:
// - 面试默认写中心扩展(解法3): O(n²)时间 O(1)空间，代码最简洁
// - 如果后续需要查询子串是否回文(如131/132题): 用DP(解法2)预处理
// - 如果面试官追问O(n): 说出Manacher思路即可，一般不要求手写
//
// ============================================================
// 【易错点】
//
// 1. DP 遍历方向:
//    ✗ for(i=0→n) for(j=i→n)  → dp[i+1][j-1] 还没算就被引用
//    ✓ for(i=n-1→0) for(j=i→n) → 保证 dp[i+1][...] 已经填好
//
// 2. DP base case 漏洞:
//    ✗ dp[i][j] = (s[i]==s[j]) && dp[i+1][j-1]
//      当 j-i==1 时, dp[i+1][j-1] = dp[i+1][i] 其中 i+1>i 越界!
//    ✓ 先检查 j-i<=2, 短子串直接判定为 true
//
// 3. 中心扩展漏掉偶数中心:
//    ✗ 只调用 expandFromCenter(s, i, i)
//    ✓ 必须同时调用 expandFromCenter(s, i, i) 和 expandFromCenter(s, i, i+1)
//
// 4. 中心扩展计数位置:
//    ✗ 扩展结束后才 count++（只计了最长的那个）
//    ✓ 每次扩展成功都 count++（每个半径都是一个不同的回文子串）
//
// 5. Manacher 统计公式:
//    ✗ 直接用 p[i] 作为回文数 → 这是变换后字符串的半径，包含了 '#'
//    ✓ 原字符串中的回文子串数 = (p[i] + 1) / 2
//
// ============================================================
// 【面试追问】
//
// Q1: 暴力法为什么是 O(n³)? 瓶颈在哪?
// → O(n²) 枚举子串 × O(n) 检查回文 = O(n³)。
//   瓶颈: 每个子串独立检查，没有利用相邻子串之间的递推关系。
//
// Q2: DP 和中心扩展都是 O(n²)，面试选哪个?
// → 选中心扩展。O(1) 空间，代码更短，思路更直觉。
//   DP 的优势是 dp 表可以被其他题复用（如 131 回文分割需要快速查询子串是否回文）。
//
// Q3: 能否 O(n) 解?
// → Manacher 算法。维护当前最远回文右边界 maxRight 和对应中心 center，
//   利用回文的对称性，对新位置 i 的回文半径给出初始下界，
//   总扩展次数均摊 O(n)。
//
// Q4: 这道题和 LeetCode 5 (最长回文子串) 的关系?
// → 框架完全相同。647 在每次扩展时 count++（统计个数），
//   5 在每次扩展时更新 maxLen 和 start（记录最长回文的位置和长度）。
//   中心扩展函数可以一字不改地复用。
// ============================================================
