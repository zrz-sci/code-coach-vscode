/*
 * LeetCode 541: 反转字符串 II (Reverse String II)
 * 
 * 【题目本质】
 * 按固定步长 2k 遍历字符串，每一步反转前 k 个字符，统一处理末尾不足 k 的边界。
 *
 * 【解法总览】
 * 解法1: 模拟 + 手写双指针反转 — O(n) / O(1) — 面试首选，展示基本功
 * 解法2: 模拟 + std::reverse     — O(n) / O(1) — 代码最简洁
 */

// ============================================================
// 解法1: 模拟 + 手写双指针反转
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 这是一道纯模拟题，关键是理清规则：
//   - 以 2k 为步长遍历
//   - 每步反转 [i, min(i+k-1, n-1)] 这个区间
// 边界处理的精髓：用 min 统一"剩余 >= k"和"剩余 < k"两种情况。
//
// 【可视化过程】
// s = "a b c d e f g",  k = 2,  2k = 4
//
// i=0: 窗口 [a b c d], 反转前2个 [a b] → [b a]
//      s = "b a c d e f g"
//       ↑ ↑
//      left right
//
// i=4: 窗口 [e f g], 反转前2个 [e f] → [f e]
//      s = "b a c d f e g"
//               ↑ ↑
//              left right
//
// i=8: 超过 n=7, 循环结束
// 结果: "bacdfeg"
// ============================================================
class Solution1 {
public:
    string reverseStr(string s, int k) {
        int n = s.size();
        for (int i = 0; i < n; i += 2 * k) {
            // 反转区间 [left, right]
            // right 用 min 处理末尾不足 k 的情况
            int left = i;
            int right = min(i + k - 1, n - 1);
            
            // 经典双指针反转：两端向中间靠拢，逐对交换
            while (left < right) {
                swap(s[left], s[right]);
                left++;
                right--;
            }
        }
        return s;
    }
};

// ============================================================
// 解法2: 模拟 + std::reverse
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 和解法1完全相同的循环逻辑，只是用 STL 的 reverse 代替手写反转。
// 注意 std::reverse 用左闭右开区间 [begin, end)，
// 所以右端点是 min(i + k, n) 而不是 min(i + k - 1, n - 1)。
// ============================================================
class Solution2 {
public:
    string reverseStr(string s, int k) {
        int n = s.size();
        for (int i = 0; i < n; i += 2 * k) {
            // reverse 用 [begin, end) 左闭右开
            // min(i + k, n) 保证不越界，同时处理"剩余 < k"的情况
            reverse(s.begin() + i, s.begin() + min(i + k, n));
        }
        return s;
    }
};

// ============================================================
// 【解法对比】
// 解法1 vs 解法2:
//   - 逻辑完全相同，区别仅在反转操作的实现方式
//   - 解法1 用闭区间 [left, right]，解法2 用左闭右开 [begin, end)
//   - 面试中建议先用解法2快速通过，被追问再切换到解法1
//
// 【易错点】
// 1. 步长写成 k 而不是 2k：
//    ✗ for (int i = 0; i < n; i += k)        → 每段都反转了
//    ✓ for (int i = 0; i < n; i += 2 * k)    → 每 2k 步才反转前 k 个
//
// 2. 闭区间 vs 左闭右开搞混：
//    手写反转用闭区间: right = min(i + k - 1, n - 1)
//    std::reverse 用左闭右开: end = min(i + k, n)
//    混用会导致多反转或少反转一个字符
//
// 3. 不用 min 导致越界：
//    ✗ int right = i + k - 1;    → 最后一段不足 k 时 right 越界
//    ✓ int right = min(i + k - 1, n - 1);
//
// 【面试追问】
// Q1(基础): 时间复杂度为什么是 O(n)?
//    → 虽然有嵌套(外层 n/2k 次 × 内层最多 k 次)，但每个字符最多被
//      访问一次，总工作量 = n。
//
// Q2(变体): 如果改成"反转每 2k 段的后 k 个"呢?
//    → 反转区间改为 [i+k, min(i+2k-1, n-1)]，循环结构不变。
//
// Q3(边界): 如果 k=0 怎么办?
//    → 题目保证 k>=1，但若需处理：特判 k==0 直接返回，
//      否则 i += 0 死循环。
// ============================================================
