-- ============================================================
-- 620. Not Boring Movies (有趣的电影)
-- 难度: Easy | 标签: Database
-- ============================================================
-- 题意: 筛选 id 为奇数且 description 不是 "boring" 的电影
--       按 rating 降序排列
-- ============================================================

-- ============================================================
-- 解法一: MOD 函数 (推荐 - SQL 标准写法)
-- ============================================================
-- 思路: 使用 MOD(id, 2) = 1 判断奇数, 标准 SQL 兼容性最好
-- 时间: O(n) | 空间: O(1)
-- ============================================================

SELECT *
FROM cinema
WHERE MOD(id, 2) = 1
  AND description != 'boring'
ORDER BY rating DESC;

