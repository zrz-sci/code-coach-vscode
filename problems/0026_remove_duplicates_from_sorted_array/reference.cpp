/*
 * LeetCode 26: 删除有序数组中的重复项 (Remove Duplicates from Sorted Array)
 *
 * 【题目本质】
 * 有序数组原地去重：用覆盖代替删除，快慢双指针一次遍历搞定。
 *
 * 【解法总览】
 * 解法1: 暴力搬移    — O(n²) / O(1) — 最直觉，理解题意
 * 解法2: 快慢双指针  — O(n)  / O(1) — 面试首选，一次遍历
 */

// ============================================================
// 解法1: 暴力搬移 — 遇到重复就把后面的元素全部前移
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 最直觉的想法：真正地"删除"重复元素。
// 从前往后扫描，发现 nums[i] == nums[i-1] 时，
// 把 i 位置后面的所有元素前移一位，相当于把重复元素挤出去。
//
// 瓶颈：每次删除都要搬 O(n) 个元素。
// 如果数组全是相同值（如 [1,1,1,...,1]），要删 n-1 次，
// 每次搬移约 O(n)，总共 O(n²)。
//
// 【运行示意】
// nums = [1, 1, 2]
// i=1: nums[1]=1 == nums[0]=1 → 前移: [1, 2, _], n=2
// i=1: nums[1]=2 != nums[0]=1 → i++
// 返回 n=2, nums前2个 = [1, 2] ✓
// ============================================================
class Solution1 {
public:
    int removeDuplicates(vector<int>& nums) {
        int n = nums.size();
        for (int i = 1; i < n; ) {
            if (nums[i] == nums[i - 1]) {
                // 把 i 后面的元素全部前移一位，模拟"删除"
                for (int j = i; j < n - 1; j++) {
                    nums[j] = nums[j + 1];
                }
                n--;  // 有效长度减1
                // i 不动：前移后新的 nums[i] 可能还是重复的
            } else {
                i++;
            }
        }
        return n;
    }
};

// ============================================================
// 解法2: 快慢双指针 — 用覆盖代替删除，一次遍历
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1的瓶颈在于"真的删除"需要大量搬移。
// 核心转变：不去删除重复元素，而是只保留不重复的元素。
//
// 用两个指针：
// - slow: 指向去重后数组的"最后一个有效元素"
// - fast: 从左到右扫描原数组
//
// 当 nums[fast] != nums[slow] 时，说明遇到了一个新值：
//   1. slow 后移一位（腾出写入位置）
//   2. 把新值覆盖到 slow 位置
// 当 nums[fast] == nums[slow] 时，fast 继续前进（跳过重复）。
//
// 为什么和 slow 比较就够了（不需要哈希表）？
// 因为数组有序，相同元素一定连续。slow 位置就是"当前最后一个被保留的值"，
// fast 遇到的重复元素一定和 slow 位置的值相同。
//
// 【运行示意】
// nums = [0, 0, 1, 1, 1, 2, 2, 3, 3, 4]
//         s
//         f
//
// f=1: 0==0 → 跳过         s=0
// f=2: 1!=0 → s=1, 写入1   [0,1,1,1,1,2,2,3,3,4]
// f=3: 1==1 → 跳过         s=1
// f=4: 1==1 → 跳过         s=1
// f=5: 2!=1 → s=2, 写入2   [0,1,2,1,1,2,2,3,3,4]
// f=6: 2==2 → 跳过         s=2
// f=7: 3!=2 → s=3, 写入3   [0,1,2,3,1,2,2,3,3,4]
// f=8: 3==3 → 跳过         s=3
// f=9: 4!=3 → s=4, 写入4   [0,1,2,3,4,2,2,3,3,4]
//
// 返回 slow+1 = 5
// 前5个元素: [0,1,2,3,4] ✓
// ============================================================
class Solution2 {
public:
    int removeDuplicates(vector<int>& nums) {
        if (nums.empty()) return 0;
        
        // slow 指向去重后数组的最后一个有效位置
        int slow = 0;
        
        for (int fast = 1; fast < (int)nums.size(); fast++) {
            // 遇到新值：和 slow 位置不同 → 保留它
            if (nums[fast] != nums[slow]) {
                slow++;                    // 先移动写入位置
                nums[slow] = nums[fast];   // 再覆盖
            }
            // 如果相同，什么都不做，fast 继续往前扫
        }
        
        // slow 是最后一个有效元素的下标，长度 = 下标 + 1
        return slow + 1;
    }
};

// ============================================================
// 解法2-变体: "下一个写入位置"风格
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 和解法2 完全等价，只是 slow 的含义不同：
// - 解法2: slow = "最后一个有效元素的下标"，初始0，返回 slow+1
// - 变体:  slow = "下一个要写入的位置"，初始1，返回 slow
//
// 两种风格在面试中都常见，选一个用熟即可。
// ============================================================
class Solution2b {
public:
    int removeDuplicates(vector<int>& nums) {
        if (nums.empty()) return 0;
        
        // slow 代表"下一个要写入的位置"，第一个元素天然保留
        int slow = 1;
        
        for (int fast = 1; fast < (int)nums.size(); fast++) {
            if (nums[fast] != nums[fast - 1]) {
                // 这里也可以写 nums[fast] != nums[slow - 1]
                // 因为 slow-1 就是上一个被写入的有效值
                nums[slow] = nums[fast];
                slow++;
            }
        }
        
        return slow;  // slow 本身就是长度
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 时间  | 空间  | 核心思想           | 面试 |
// |----------|-------|-------|--------------------|------|
// | 暴力搬移 | O(n²) | O(1) | 真的删除，逐个搬移 | 展示理解 |
// | 快慢双指针| O(n) | O(1) | 覆盖代替删除       | ⭐ 必写 |
//
// 本质区别：暴力在"删除坏数据"，双指针在"收集好数据"。
// 思维模式的转变：不是把不要的踢出去，而是把要的搬到前面。
//
// 解法2 和 2b 的区别只是 slow 指针的语义：
// - 解法2: slow = 最后有效下标 → 返回 slow + 1
// - 2b:    slow = 下一个写入位置 → 返回 slow
// 两种都对，选一种记住即可。推荐解法2b（"写入位置"更直觉）。
//
// ============================================================
// 【易错点】
//
// 1. 返回值 off-by-one:
//    ✗ return slow;     // slow 是下标0开始的最后有效位置
//    ✓ return slow + 1; // 长度 = 下标 + 1
//    （如果用 2b 的"写入位置"风格就不会有这个问题）
//
// 2. 赋值顺序搞反:
//    ✗ nums[slow] = nums[fast]; slow++;
//       当 slow==0 时会覆盖第一个有效值（虽然本题恰好没问题，
//       因为 slow==0 且 nums[fast]!=nums[0] 时 fast>slow，
//       但逻辑上先移再写更清晰安全）
//    ✓ slow++; nums[slow] = nums[fast];
//
// 3. 空数组边界:
//    ✗ 不做判断直接 int slow = 0; → 返回1（错）
//    ✓ if (nums.empty()) return 0;
//    （题目约束 nums.length >= 1，但好习惯应该有）
//
// 4. fast 起始位置:
//    ✗ for (int fast = 0; ...) → 第一轮 nums[0] != nums[0]
//       永远为 false，不影响正确性但浪费一轮
//    ✓ for (int fast = 1; ...) → 第一个元素天然保留，从第二个开始比较
//
// ============================================================
// 【面试追问】
//
// Q1: "如果数组无序呢？还能 O(n) 时间 O(1) 空间吗？"
// → 不能同时满足 O(n) + O(1) + 保持顺序。
//   方案A: 排序 O(n log n) 后用本题双指针，但会打乱原始顺序。
//   方案B: 哈希集合 O(n) 时间但 O(n) 空间。
//   方案C: 如果不要求保持顺序，排序+双指针是最优。
//
// Q2: "如果允许每个元素最多出现两次呢？"（→ LeetCode 80）
// → 框架完全一样！核心改动一行：
//   本题:  nums[fast] != nums[slow]
//   80题:  nums[fast] != nums[slow - 1]
//   (允许和前一个相同，但不允许和前两个相同)
//   更通用地，允许最多出现 k 次：nums[fast] != nums[slow - (k-1)]
//
// Q3: "能否不移动任何元素，只返回去重后的长度？"
// → 更简单：只需计数。遍历数组，遇到 nums[i] != nums[i-1] 就计数+1。
//   但题目要求修改原数组前 k 个元素，所以必须有写入操作。
//   这个追问是检验你是否真正读题。
//
