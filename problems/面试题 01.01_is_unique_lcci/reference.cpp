/*
 * 面试题 01.01: 判定字符是否唯一 (Is Unique LCCI)
 *
 * 【题目】判断字符串 s 的所有字符是否全都不同。
 *        进阶：不使用额外的数据结构。
 *        约束：0 <= len(s) <= 100, 仅包含小写字母。
 *
 * 【解法1】位运算 — O(n) / O(1) ⭐ 首选
 * 【解法2】哈希集合 — O(n) / O(n)
 * 【解法3】bool数组标记 — O(n) / O(1)
 * 【解法4】排序 + 相邻检查 — O(n log n) / O(1)
 * 【解法5】暴力双循环 — O(n^2) / O(1)
 */

// ============================================================
// 解法1: 位运算 ⭐ 面试首选
// ============================================================
/*
 * 核心思想: 用 int 的低 26 位分别标记 a-z 是否出现。
 *
 *   bit位:  ...   2  1  0
 *   字母:   ...   c  b  a
 *
 * 位操作:
 *   1 << val        → 生成第 val 位为 1 的掩码
 *   checker & mask  → 检查第 val 位是否已为 1
 *   checker |= mask → 将第 val 位设为 1
 *
 * 示例 "abc":
 *   'a': val=0, checker=000...001 (标记 a)
 *   'b': val=1, checker=000...011 (标记 b)
 *   'c': val=2, checker=000...111 (标记 c) → 全部唯一
 *
 * 示例 "leetcode":
 *   'l': val=11, checker=...1000_0000_0000
 *   'e': val=4,  checker=...1000_0001_0000
 *   'e': val=4,  checker & (1<<4) ≠ 0 → 重复! return false
 */
class Solution {
public:
    bool isUnique(string astr) {
        // 鸽巢原理: 26个小写字母, 长度>26必有重复
        if (astr.size() > 26) return false;

        int checker = 0; // 26个bit位标记 a-z

        for (char c : astr) {
            int val = c - 'a';           // 'a'→0, 'b'→1, ..., 'z'→25
            if (checker & (1 << val)) {  // 第val位已为1? → 重复
                return false;
            }
            checker |= (1 << val);       // 标记第val位为1
        }

        return true; // 全部唯一
    }
};

// ============================================================
// 解法2: 哈希集合
// ============================================================
/*
 * 最直觉的解法: 用 set 记录出现过的字符。
 * 缺点: 使用了额外数据结构, 不满足进阶要求。
 *
 * 示例 "leetcode":
 *   seen = {'l'} → {'l','e'} → 'e'已存在! return false
 */
class Solution2 {
public:
    bool isUnique(string astr) {
        if (astr.size() > 26) return false;

        unordered_set<char> seen;
        for (char c : astr) {
            if (seen.count(c)) return false; // 已存在
            seen.insert(c);                   // 记录
        }
        return true;
    }
};

// ============================================================
// 解法3: bool 数组标记
// ============================================================
/*
 * 用固定大小 bool[26] 标记每个字母是否出现。
 * 介于 set 和位运算之间的方案。
 * 严格来说 O(1) 空间 (固定26个bool)。
 * 面试中可能被质疑"这算不算额外数据结构"。
 */
class Solution3 {
public:
    bool isUnique(string astr) {
        if (astr.size() > 26) return false;

        bool seen[26] = {false}; // 初始化全 false
        for (char c : astr) {
            int idx = c - 'a';
            if (seen[idx]) return false;
            seen[idx] = true;
        }
        return true;
    }
};

// ============================================================
// 解法4: 排序 + 相邻检查
// ============================================================
/*
 * 排序后, 相同字符必然相邻。
 * 扫描一遍检查相邻字符是否相同。
 *
 * 满足"不用额外数据结构"(原地排序), 但:
 * 1. 时间 O(n log n) 比位运算慢
 * 2. 修改了输入字符串
 *
 * 示例 "leetcode":
 *   排序后 → "cdeeelot"
 *   检查: c-d OK, d-e OK, e-e 重复! return false
 */
class Solution4 {
public:
    bool isUnique(string astr) {
        if (astr.size() > 26) return false;

        sort(astr.begin(), astr.end()); // 原地排序
        for (int i = 1; i < (int)astr.size(); i++) {
            if (astr[i] == astr[i - 1]) return false; // 相邻重复
        }
        return true;
    }
};

// ============================================================
// 解法5: 暴力双循环
// ============================================================
/*
 * 对每一对 (i, j), 检查 s[i] == s[j]。
 * O(n^2) 时间, O(1) 空间。最朴素, 仅作分析用。
 */
class Solution5 {
public:
    bool isUnique(string astr) {
        if (astr.size() > 26) return false;

        for (int i = 0; i < (int)astr.size(); i++) {
            for (int j = i + 1; j < (int)astr.size(); j++) {
                if (astr[i] == astr[j]) return false;
            }
        }
        return true;
    }
};


// ============================================================
// 总结
// ============================================================
//
// 【解法对比】
// ┌──────────────────┬────────────┬────────┬──────────────────────────────────┐
// │ 解法              │ 时间       │ 空间   │ 适用场景                         │
// ├──────────────────┼────────────┼────────┼──────────────────────────────────┤
// │ 1. 位运算         │ O(n)       │ O(1)   │ ⭐ 面试首选, 满足进阶要求         │
// │ 2. 哈希集合       │ O(n)       │ O(n)   │ 最直觉, 不满足进阶               │
// │ 3. bool数组       │ O(n)       │ O(1)   │ 折中方案, 可能被质疑"额外结构"   │
// │ 4. 排序+相邻检查  │ O(nlogn)   │ O(1)   │ 满足进阶但修改了输入             │
// │ 5. 暴力双循环     │ O(n^2)     │ O(1)   │ 最朴素, 仅作分析基准             │
// └──────────────────┴────────────┴────────┴──────────────────────────────────┘
//
// 【易错点】
// 1. 鸽巢原理: 26个小写字母, 字符串长度>26必有重复 → 提前返回 false
// 2. 位运算中 1 << val 的 1 默认是 int (32位), 足够覆盖 26 个字母;
//    但如果字符集扩大到 >31, 需要用 1LL << val 或 bitset
// 3. checker & (1 << val) 结果不是 0/1 而是 0 或 2^val → 用 if 判断非零即可
// 4. 排序解法会修改原字符串 → 面试时要和面试官确认是否允许
// 5. 题目说"仅小写字母"→ 如果改为 ASCII 全集 (128/256), 位运算需要更大容器
//
// 【面试追问】
// Q1: 如果字符集是全部 ASCII (128个字符), 位运算怎么改?
//     → 128 位超出 long long (64位). 可以用两个 long long,
//       或用 bitset<128>, 或用 bool[128] 数组 (固定大小仍是 O(1) 空间).
//
// Q2: 如果字符集是 Unicode (百万级), 还能 O(1) 空间吗?
//     → 不能用位掩码了. 但鸽巢原理仍适用: 如果字符串长度超过字符集大小,
//       直接返回 false. 否则用哈希集合 O(n) 空间.
//       排序解法始终是 O(1) 额外空间的备选 (但 O(nlogn) 时间).
//
// Q3: 如果要求不修改输入且 O(1) 空间, 但字符集未知?
//     → 只剩暴力双循环 O(n^2). 这是时间-空间 trade-off 的经典案例.
//       面试中应明确约束后选择最优方案, 展示对 trade-off 的理解.
