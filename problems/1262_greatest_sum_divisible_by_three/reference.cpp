// ============================================================
// LeetCode 1262: Greatest Sum Divisible by Three
// (可被三整除的最大和)
// 难度: Medium | 标签: Greedy, Array, Dynamic Programming, Sorting
//
// 题意: 从数组中选出若干元素, 使得和最大且能被 3 整除。
// ============================================================


// ============================================================
// 解法1: DP（余数状态） ⭐ 推荐
//
// 思路:
//   dp[r] = 当前所选子集和 mod 3 == r 时的最大和
//   初始: dp[0]=0, dp[1]=dp[2]=-INF (不可达)
//   转移: 对每个 num, 旧 dp[j] + num 的余数为 (j + num%3) % 3
//
// DP 表推演 (nums = [3, 6, 5, 1, 8]):
//
//   初始:     dp = [  0, -INF, -INF]
//   num=3(r=0): dp = [  3, -INF, -INF]
//   num=6(r=0): dp = [  9, -INF, -INF]
//   num=5(r=2): dp = [  9, -INF,   14]
//   num=1(r=1): dp = [ 15,   10,   14]
//   num=8(r=2): dp = [ 18,   22,   23]
//
//   答案: dp[0] = 18 (选 3+6+1+8)
//
// 时间: O(n) | 空间: O(1)
// ============================================================
class Solution {
public:
    int maxSumDivThree(vector<int>& nums) {
        // dp[r] = 余数为 r 时的最大子集和
        // 初始: 空集的和为 0 (余数 0), 余数 1 和 2 不可达
        vector<int> dp = {0, INT_MIN, INT_MIN};

        for (int num : nums) {
            // 必须用旧值更新, 所以先拷贝
            vector<int> temp = dp;
            for (int j = 0; j < 3; j++) {
                int newR = (j + num % 3) % 3;
                dp[newR] = max(dp[newR], temp[j] + num);
            }
        }

        return dp[0]; // 余数为 0 的最大和
    }
};


// ============================================================
// 解法2: 贪心（总和 - 最小代价）
//
// 思路:
//   先求总和 S, 根据 S % 3 分类:
//   - S%3 == 0: 直接返回 S
//   - S%3 == 1: 减去 min(最小余1的1个数, 最小余2的2个数)
//   - S%3 == 2: 减去 min(最小余2的1个数, 最小余1的2个数)
//
// 原理: 要让 (S - removed) % 3 == 0
//   S%3==1 → removed%3==1 → 要么1个余1, 要么2个余2 (2+2≡1 mod3)
//   S%3==2 → removed%3==2 → 要么1个余2, 要么2个余1 (1+1≡2 mod3)
//   选代价最小的方案, 使剩余和最大
//
// 时间: O(n log n) | 空间: O(n)
// ============================================================
class Solution2 {
public:
    int maxSumDivThree(vector<int>& nums) {
        int S = 0;
        vector<int> mod1, mod2;

        for (int num : nums) {
            S += num;
            if (num % 3 == 1) mod1.push_back(num);
            if (num % 3 == 2) mod2.push_back(num);
        }

        // 排序以便取最小值
        sort(mod1.begin(), mod1.end());
        sort(mod2.begin(), mod2.end());

        if (S % 3 == 0) return S;

        if (S % 3 == 1) {
            int optA = (mod1.size() >= 1) ? S - mod1[0] : 0;
            int optB = (mod2.size() >= 2) ? S - mod2[0] - mod2[1] : 0;
            return max(optA, optB);
        }

        // S % 3 == 2
        int optA = (mod2.size() >= 1) ? S - mod2[0] : 0;
        int optB = (mod1.size() >= 2) ? S - mod1[0] - mod1[1] : 0;
        return max(optA, optB);
    }
};


// ============================================================
// 解法3: 贪心优化版（O(n) 时间 O(1) 空间）
//
// 思路:
//   不排序, 而是手动维护余数为 1 和 2 的最小两个值
//   这样遍历一次即可
//
// 时间: O(n) | 空间: O(1)
// ============================================================
class Solution3 {
public:
    int maxSumDivThree(vector<int>& nums) {
        int S = 0;
        // 余数为1的最小和次小
        int m1a = INT_MAX, m1b = INT_MAX;
        // 余数为2的最小和次小
        int m2a = INT_MAX, m2b = INT_MAX;

        for (int num : nums) {
            S += num;
            int r = num % 3;
            if (r == 1) {
                if (num <= m1a) {
                    m1b = m1a;
                    m1a = num;
                } else if (num < m1b) {
                    m1b = num;
                }
            } else if (r == 2) {
                if (num <= m2a) {
                    m2b = m2a;
                    m2a = num;
                } else if (num < m2b) {
                    m2b = num;
                }
            }
        }

        if (S % 3 == 0) return S;

        if (S % 3 == 1) {
            int optA = (m1a != INT_MAX) ? S - m1a : 0;
            int optB = (m2b != INT_MAX) ? S - m2a - m2b : 0;
            return max(optA, optB);
        }

        // S % 3 == 2
        int optA = (m2a != INT_MAX) ? S - m2a : 0;
        int optB = (m1b != INT_MAX) ? S - m1a - m1b : 0;
        return max(optA, optB);
    }
};


// ============================================================
// 解法4: DP 推广版 — 可被 k 整除的最大和
//
// 思路:
//   dp 从 3 个状态扩展到 k 个
//   dp[r] = 子集和 mod k == r 时的最大和
//
// 时间: O(n * k) | 空间: O(k)
// ============================================================
class Solution4 {
public:
    int maxSumDivThree(vector<int>& nums) {
        return maxSumDivK(nums, 3);
    }

    int maxSumDivK(vector<int>& nums, int k) {
        vector<int> dp(k, INT_MIN);
        dp[0] = 0;

        for (int num : nums) {
            vector<int> temp = dp;
            for (int j = 0; j < k; j++) {
                int newR = (j + num % k) % k;
                dp[newR] = max(dp[newR], temp[j] + num);
            }
        }

        return max(dp[0], 0);
    }
};


/*
 * ============================================================
 * 易错点总结:
 *
 * 1. dp 初始化: dp[1]=dp[2]=-INF, 不是 0
 *    若为 0, 会错误认为余数 1/2 可达且和为 0
 *
 * 2. 更新时必须用旧值:
 *    不拷贝 temp = dp 会导致一个 num 被多次"使用"
 *    例如 num=1(r=1): dp[0]→dp[1], 如果 dp[1] 被更新,
 *    接下来 dp[1]→dp[2] 就用了新值, 相当于加了两次
 *
 * 3. INT_MIN + num 溢出:
 *    INT_MIN + 正数 = 大负数(未定义行为)
 *    安全做法: 用 -1e9 替代 INT_MIN, 或转移前检查
 *
 * 4. 贪心中不检查数组大小:
 *    mod1/mod2 可能不足 2 个元素, 直接取 [0],[1] 会越界
 *
 * 5. 返回 dp[0] 而非 max(dp[0], 0):
 *    本题 nums 全为正数, dp[0] >= 0 一定成立
 *    但如果有负数, 需要返回 max(dp[0], 0) 确保非负
 *
 * 面试追问:
 * Q: 只有 3 个状态? → 余数只有 0,1,2
 * Q: 推广到 mod k? → dp 数组扩展到 k 个
 * Q: 加维度 "恰好选 m 个"? → dp[j][r]
 * Q: 贪心 vs DP? → DP 更通用, 贪心只适用 mod 3
 * ============================================================
 */


/* ============================================================
 * 📋 总结区块
 * ============================================================
 *
 * 一、解法对比
 * ┌──────────────────────┬──────────┬──────────┬─────────────────────────┐
 * │ 解法                 │ 时间     │ 空间     │ 说明                    │
 * ├──────────────────────┼──────────┼──────────┼─────────────────────────┤
 * │ 1.DP(余数状态)       │ O(n)     │ O(1)     │ 面试首选，最通用        │
 * │ 2.贪心(总和-最小代价)│ O(nlogn) │ O(n)     │ 直觉友好，但需排序      │
 * │ 3.贪心优化(维护最小) │ O(n)     │ O(1)     │ 手动维护min避免排序     │
 * │ 4.DP推广(mod k)      │ O(n*k)   │ O(k)     │ 面试加分，通用模板      │
 * └──────────────────────┴──────────┴──────────┴─────────────────────────┘
 * DP解法是"余数状态机"的经典应用：只有3个状态，转移关系固定。
 * 贪心解法更直觉但推广性差；DP可直接扩展到 mod k。
 *
 * 二、易错点
 * 1. dp 初始化用 0 而非 -INF：
 *    dp[1]=dp[2]=0 会让算法错误地认为余数1/2一开始就可达，
 *    导致答案偏大。必须用 INT_MIN（或 -1e9 避免溢出）。
 *
 * 2. 更新时不拷贝旧值（同一个num被"使用"多次）：
 *    dp[0]→dp[1] 更新后，紧接着 dp[1]→dp[2] 用了新dp[1]，
 *    相当于同一个num加了两次。必须 temp = dp 再用 temp 转移。
 *
 * 3. INT_MIN + num 溢出：
 *    C++中 INT_MIN + 正数 是未定义行为。
 *    安全做法：用 -1e9 代替，或在转移前检查 temp[j] > INT_MIN。
 *
 * 4. 贪心中数组越界：
 *    mod1/mod2 元素可能不足2个，直接访问 [0]/[1] 会段错误。
 *    必须先检查 size() >= 1 / size() >= 2。
 *
 * 三、面试追问
 * Q1: 为什么 DP 只需要 3 个状态？
 *     → 我们只关心子集和对3的余数（0/1/2），
 *       不关心具体选了哪些元素。这是"状态压缩"的思想——
 *       把无穷多种子集和映射到3个等价类。
 *
 * Q2: 如果改成"可被 k 整除的最大和"？
 *     → dp 数组从 3 扩展到 k，转移逻辑完全一样：
 *       newR = (j + num%k) % k。时间 O(nk)，空间 O(k)。
 *       见解法4的 maxSumDivK 实现。
 *
 * Q3: 如果加约束"恰好选 m 个元素"？
 *     → 增加一个维度: dp[count][remainder]，
 *       dp[c][r] = 恰好选c个元素、和对3余r时的最大和。
 *       转移: dp[c+1][(r+num%3)%3] = max(..., dp[c][r]+num)。
 *       时间 O(n*m*k)，空间 O(m*k)。
 *
 * ============================================================ */
