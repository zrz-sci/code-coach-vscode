/*
 * LeetCode 844: 比较含退格的字符串 (Backspace String Compare)
 *
 * 【题目本质】
 * 模拟文本编辑器：普通字符追加，'#' 退格删除前一个字符。
 * 对两个字符串各自模拟后，比较最终结果是否相同。
 *
 * 【解法总览】
 * 解法1: 栈模拟       — O(n+m) / O(n+m) — 最直觉，面试首选
 * 解法2: 双指针逆序   — O(n+m) / O(1)   — Follow-up，O(1) 空间
 */

// ============================================================
// 解法1: 栈模拟 — 直接模拟编辑器行为
// 时间: O(n+m)  空间: O(n+m)
//
// 【思路】
// 编辑器怎么工作就怎么写：
// - 遇到普通字符 → 追加到末尾（入栈）
// - 遇到 '#' → 删除末尾字符（出栈）
// - 对空文本退格 → 什么都不做
// 用 string 当栈（push_back / pop_back），处理完直接比较。
//
// 模拟过程 s = "ab#c":
//   'a' → [a]
//   'b' → [a, b]
//   '#' → [a]       ← 退格删掉 'b'
//   'c' → [a, c]
//   结果: "ac"
// ============================================================
class Solution1 {
public:
    bool backspaceCompare(string s, string t) {
        return build(s) == build(t);
    }

private:
    string build(const string& str) {
        string result;
        for (char c : str) {
            if (c != '#') {
                result.push_back(c);           // 普通字符，追加
            } else if (!result.empty()) {
                result.pop_back();              // 退格：删除最后一个（必须先判非空！）
            }
            // c=='#' 且 result 为空 → 跳过，对空文本退格无效果
        }
        return result;
    }
};

// ============================================================
// 解法2: 双指针逆序比较 — Follow-up: O(1) 空间
// 时间: O(n+m)  空间: O(1)
//
// 【思路】
// 解法1需要 O(n+m) 额外空间存结果字符串。
// 关键洞察：'#' 消除的是它左边的字符。如果从右往左遍历，
// 遇到 '#' 就知道要跳过接下来几个字符（用 skip 计数器），
// 这样不需要存储中间结果。
//
// 为什么从后往前？
// '#' 影响前面（左边）的字符。从右往左扫描时，先遇到 '#'，
// 再跳过应该被删除的字符——这是"先知道规则，再应用"的自然顺序。
//
// 双指针比较 s="ab#c", t="ad#c" 的过程:
//
// s: a  b  #  c       t: a  d  #  c
//    0  1  2  3          0  1  2  3
//
// Round1: i=3 → 'c'(有效), j=3 → 'c'(有效) → 'c'=='c' ✓, i=2,j=2
// Round2: i=2 → '#' skip=1 → i=1 → 'b' skip跳过 → i=0 → 'a'(有效)
//         j=2 → '#' skip=1 → j=1 → 'd' skip跳过 → j=0 → 'a'(有效)
//         'a'=='a' ✓, i=-1,j=-1
// Round3: i<0, j<0, 都走完 → return true
// ============================================================
class Solution2 {
public:
    bool backspaceCompare(string s, string t) {
        int i = s.size() - 1;
        int j = t.size() - 1;
        int skipS = 0, skipT = 0;

        // 用 || 不是 &&：一边走完另一边可能还有有效字符
        while (i >= 0 || j >= 0) {

            // 在 s 中找到下一个有效字符（向左扫描）
            while (i >= 0) {
                if (s[i] == '#') {
                    skipS++;    // 遇到退格，累积跳过计数
                    i--;
                } else if (skipS > 0) {
                    skipS--;    // 当前字符被退格消除，跳过
                    i--;
                } else {
                    break;      // s[i] 是有效字符，停下来等比较
                }
            }

            // 在 t 中找到下一个有效字符（向左扫描）
            while (j >= 0) {
                if (t[j] == '#') {
                    skipT++;
                    j--;
                } else if (skipT > 0) {
                    skipT--;
                    j--;
                } else {
                    break;
                }
            }

            // 比较两个有效字符
            if (i >= 0 && j >= 0) {
                // 两边都有有效字符，必须相同
                if (s[i] != t[j]) return false;
            } else if (i >= 0 || j >= 0) {
                // 一边有有效字符，另一边已经没有了 → 长度不同
                return false;
            }
            // 两边都没有（i<0 && j<0）→ 本轮相等，继续

            i--;
            j--;
        }

        return true;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 解法1 栈模拟   | 解法2 双指针逆序 |
// |------------|---------------|-----------------|
// | 时间       | O(n+m)        | O(n+m)          |
// | 空间       | O(n+m)        | O(1)            |
// | 代码难度   | 简单          | 中等             |
// | 适用场景   | 面试第一版    | Follow-up 追问   |
//
// 面试策略：先写栈模拟（简洁正确），被追问 O(1) 空间时再优化为双指针。
//
// 【易错点】
// 1. 栈模拟：对空栈 pop_back 是未定义行为
//    ✗ if (c == '#') result.pop_back();
//    ✓ if (c == '#' && !result.empty()) result.pop_back();
//
// 2. 双指针外层循环用 && 导致漏比较
//    ✗ while (i >= 0 && j >= 0)  — s="a", t="a#" 时 j 先走完但 i 还剩 'a'
//    ✓ while (i >= 0 || j >= 0)  — 确保两边都走完才停
//
// 3. 双指针比较时直接访问 s[i]/t[j] 没检查越界
//    ✗ if (s[i] != t[j]) return false;  — i 或 j 可能已经 < 0
//    ✓ 先判 if (i>=0 && j>=0) 再比较字符
//
// 4. 连续 '#' 处理：skip 必须累加，不能只跳过一个
//    s = "ab##" → skip 应该累加到 2，跳过 'b' 和 'a'
//
// 【面试追问】
// Q1: 直觉解法？→ 栈模拟，O(n+m) 时间和空间
// Q2: 能否 O(1) 空间？→ 从后往前双指针 + skip 计数器
// Q3: 如果是流式输入（字符逐个到达），哪种解法更合适？
//     → 栈模拟天然支持流式，双指针需要完整字符串
// Q4: 如果 '#' 变成 "删除前面所有字符"？
//     → 栈改成 clear()，双指针改成 skip = i+1（跳到开头）
// ============================================================
