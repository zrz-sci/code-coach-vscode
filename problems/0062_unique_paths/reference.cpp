/*
 * LeetCode 62: 不同路径 (Unique Paths)
 *
 * 【题目本质】
 * 在 m×n 网格中从左上走到右下，每步只能向右或向下，求路径总数。
 * 本质：路径计数 DP / 组合数学 C(m+n-2, m-1)。
 *
 * 【解法总览】
 * 解法1: 暴力递归            — O(2^(m+n)) / O(m+n)  — 最直觉，理解问题
 * 解法2: 记忆化搜索          — O(m*n) / O(m*n)      — 消除重叠子问题
 * 解法3: 二维 DP (自底向上)  — O(m*n) / O(m*n)      — 面试标准写法
 * 解法4: 一维 DP (空间优化)  — O(m*n) / O(n)        — 面试进阶必备
 * 解法5: 组合数学            — O(min(m,n)) / O(1)   — 数学加分项
 */

// ============================================================
// 解法1: 暴力递归 — DFS 穷举所有路径
// 时间: O(2^(m+n))  空间: O(m+n) 递归栈深度
//
// 【思路】
// 最直觉的想法：站在 (i,j)，可以选择向下走到 (i+1,j) 或向右走到 (i,j+1)。
// 到达终点 (m-1, n-1) 返回 1（找到一条路径），越界返回 0。
// 递归把两个方向的路径数加起来。
//
// 递归树 (m=3, n=3):
//                      (0,0)
//                     /     \
//                 (1,0)      (0,1)
//                /    \      /    \
//            (2,0)  (1,1) (1,1)  (0,2)    ← (1,1) 重复!
//              |    / \    / \      |
//           (2,1) ... ...  ...   (1,2)
//              |                    |
//           (2,2)               (2,2)     ← (2,2) 也重复!
//
// 瓶颈：大量重叠子问题导致指数级时间复杂度。
// ============================================================
class Solution1 {
public:
    int uniquePaths(int m, int n) {
        return dfs(0, 0, m, n);
    }

private:
    int dfs(int i, int j, int m, int n) {
        if (i == m - 1 && j == n - 1) return 1;  // 到达终点
        if (i >= m || j >= n) return 0;            // 越界
        // 向下走的路径数 + 向右走的路径数
        return dfs(i + 1, j, m, n) + dfs(i, j + 1, m, n);
    }
};

// ============================================================
// 解法2: 记忆化搜索 — 给暴力递归加缓存
// 时间: O(m*n)  空间: O(m*n)
//
// 【思路】
// 解法1的瓶颈是重叠子问题：同一个 (i,j) 被多次计算。
// 加一个 memo 数组，第一次计算后存下来，后续直接返回。
// 每个 (i,j) 只计算一次，总共 m*n 个格子 → O(m*n)。
// ============================================================
class Solution2 {
public:
    int uniquePaths(int m, int n) {
        // memo[i][j] = -1 表示尚未计算
        vector<vector<int>> memo(m, vector<int>(n, -1));
        return dfs(0, 0, m, n, memo);
    }

private:
    int dfs(int i, int j, int m, int n, vector<vector<int>>& memo) {
        if (i == m - 1 && j == n - 1) return 1;
        if (i >= m || j >= n) return 0;
        if (memo[i][j] != -1) return memo[i][j];  // 已缓存，直接返回

        // 计算并缓存
        memo[i][j] = dfs(i + 1, j, m, n, memo) + dfs(i, j + 1, m, n, memo);
        return memo[i][j];
    }
};

// ============================================================
// 解法3: 二维 DP (自底向上) — 面试标准写法
// 时间: O(m*n)  空间: O(m*n)
//
// 【思路】
// 把记忆化搜索翻译成 for 循环递推。
// 定义 dp[i][j] = 从 (0,0) 到 (i,j) 的路径数。
// 
// 状态转移：dp[i][j] = dp[i-1][j] + dp[i][j-1]
//           （从上方来）  （从左方来）
// 
// 初始化：第一行 dp[0][j] = 1（只能一直向右）
//         第一列 dp[i][0] = 1（只能一直向下）
//
// dp 填表过程 (m=3, n=7):
//
//   j→  0  1  2  3  4   5   6
// i↓
//  0   [1  1  1  1  1   1   1]    ← 第一行全1
//  1   [1  2  3  4  5   6   7]    ← dp[1][j] = dp[0][j] + dp[1][j-1]
//  2   [1  3  6 10 15  21  28]    ← dp[2][6] = 21 + 7 = 28
//
// 填表方向：从左到右，从上到下（保证依赖的格子已经算过）
//
//  dp[i][j] 依赖关系:
//    dp[i-1][j]  (上方 ↑)
//         |
//         v
//    dp[i][j-1] → dp[i][j]
//    (左方 ←)
// ============================================================
class Solution3 {
public:
    int uniquePaths(int m, int n) {
        // 全部初始化为 1，第一行和第一列自动正确
        vector<vector<int>> dp(m, vector<int>(n, 1));

        for (int i = 1; i < m; i++) {
            for (int j = 1; j < n; j++) {
                // 从上方来的路径数 + 从左方来的路径数
                dp[i][j] = dp[i - 1][j] + dp[i][j - 1];
            }
        }
        return dp[m - 1][n - 1];
    }
};

// ============================================================
// 解法4: 一维 DP (空间优化) — 滚动数组
// 时间: O(m*n)  空间: O(n)
//
// 【思路】
// 解法3中 dp[i][j] 只依赖：
//   - dp[i-1][j]：上一行同列 = 更新前的 dp[j]（旧值）
//   - dp[i][j-1]：本行前一列 = 刚更新的 dp[j-1]（新值）
// 
// 所以只需要一维数组，从左到右更新：
//   dp[j] += dp[j-1]
//   (旧dp[j]=上方) + (新dp[j-1]=左方)
//
// 滚动过程 (m=3, n=4):
//
//   初始 (第0行): [1, 1, 1, 1]
//
//   i=1: j=1: dp[1] = 1 + dp[0] = 1+1 = 2
//         j=2: dp[2] = 1 + dp[1] = 1+2 = 3
//         j=3: dp[3] = 1 + dp[2] = 1+3 = 4
//         → [1, 2, 3, 4]
//
//   i=2: j=1: dp[1] = 2 + dp[0] = 2+1 = 3
//         j=2: dp[2] = 3 + dp[1] = 3+3 = 6
//         j=3: dp[3] = 4 + dp[2] = 4+6 = 10
//         → [1, 3, 6, 10]  答案 = dp[3] = 10
// ============================================================
class Solution4 {
public:
    int uniquePaths(int m, int n) {
        vector<int> dp(n, 1);  // 第一行全1

        for (int i = 1; i < m; i++) {
            // dp[0] 始终是 1（最左列只有一条路），不需要更新
            for (int j = 1; j < n; j++) {
                // dp[j](旧) = 来自上方的路径数
                // dp[j-1](新) = 来自左方的路径数
                dp[j] += dp[j - 1];
            }
        }
        return dp[n - 1];
    }
};

// ============================================================
// 解法5: 组合数学 — C(m+n-2, m-1)
// 时间: O(min(m,n))  空间: O(1)
//
// 【思路】
// 换一个角度思考：从 (0,0) 到 (m-1, n-1) 必须走：
//   - (m-1) 步向下 (D)
//   - (n-1) 步向右 (R)
//   总共 (m+n-2) 步
//
// 每条路径就是一个由 D 和 R 组成的排列，例如 m=3, n=3:
//   DDRR, DRDR, DRRD, RDDR, RDRD, RRDD → 共6种
//
// 这等价于：从 (m+n-2) 个位置中选 (m-1) 个放 D（剩下的放 R）
// 答案 = C(m+n-2, m-1) = (m+n-2)! / ((m-1)! * (n-1)!)
//
// 计算技巧：
//   C(N, k) = N*(N-1)*...*(N-k+1) / (1*2*...*k)
//   边乘边除，保证中间结果是整数（因为连续 i 个整数的乘积一定能被 i! 整除）
//
// 选 k = min(m-1, n-1) 以减少乘除次数。
// 用 long long 防止中间结果溢出。
// ============================================================
class Solution5 {
public:
    int uniquePaths(int m, int n) {
        int N = m + n - 2;                // 总步数
        int k = min(m - 1, n - 1);        // 选较小值减少计算

        long long result = 1;
        for (int i = 0; i < k; i++) {
            result *= (N - i);             // 分子：N, N-1, ..., N-k+1
            result /= (i + 1);            // 分母：1, 2, ..., k
            // 数学保证：C(N, i+1) 是整数，所以这里整除一定没有余数
        }
        return (int)result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法           | 时间         | 空间     | 特点                     |
// |---------------|-------------|---------|--------------------------|
// | 暴力递归       | O(2^(m+n))  | O(m+n)  | 理解问题，必然 TLE        |
// | 记忆化搜索     | O(m*n)      | O(m*n)  | 消除重叠子问题            |
// | 二维 DP        | O(m*n)      | O(m*n)  | 递推标准写法              |
// | 一维 DP        | O(m*n)      | O(n)    | 空间优化，面试必备         |
// | 组合数学       | O(min(m,n)) | O(1)    | 最优，但需要数学直觉       |
//
// 面试建议：
//   - 先说暴力递归思路，展示理解
//   - 写二维 DP，说清楚状态定义和转移
//   - 主动优化到一维 DP，展示空间优化能力
//   - 如果面试官感兴趣，提组合数学解法
//
// 【易错点】
// 1. 一维 DP 内层循环起点：
//    ✗ for (int j = 0; j < n; j++) dp[j] += dp[j-1]; → j=0时dp[-1]越界
//    ✓ for (int j = 1; j < n; j++) dp[j] += dp[j-1]; → dp[0]永远是1不用更新
//
// 2. 组合数用 int 存中间结果：
//    ✗ int result = 1; result *= (N - i); → m=100,n=100时中间结果溢出
//    ✓ long long result = 1; → 用 long long 存中间乘积
//
// 3. 组合数先全部乘完再除：
//    ✗ for(...) result *= (N-i); for(...) result /= (i+1);
//      → 先乘完分子可能爆 long long (100! 级别)
//    ✓ for(...) { result *= (N-i); result /= (i+1); }
//      → 边乘边除，中间结果始终是组合数，不会溢出
//
// 4. 二维 DP 忘记初始化边界：
//    ✗ vector<vector<int>> dp(m, vector<int>(n, 0)); 然后直接转移
//      → dp 全是 0，答案也是 0
//    ✓ 初始化为 1，或者显式设 dp[i][0]=1, dp[0][j]=1
//
// 【面试追问】
//
// Q1(基础): 为什么 dp[i][j] = dp[i-1][j] + dp[i][j-1]？
//   → 因为到达 (i,j) 只有两种方式：从 (i-1,j) 向下一步，或从 (i,j-1) 向右一步。
//     两种方式互斥且穷尽所有可能，所以路径数相加。
//
// Q2(优化): 空间能否进一步优化到 O(min(m,n))？
//   → 一维 DP 中数组长度取 min(m,n)。如果 m < n，交换 m 和 n，
//     让滚动数组的长度取较小的那个维度。
//
// Q3(变体): 如果有障碍物怎么办？(LeetCode 63)
//   → 在转移时加判断：if (obstacleGrid[i][j] == 1) dp[i][j] = 0;
//     一维 DP 版：遇到障碍直接 dp[j] = 0。
//     注意：起点或终点有障碍则答案直接是 0。
//
// Q4(变体): 如果要求路径本身而非路径数？
//   → 用回溯 DFS 收集所有路径，时间复杂度等于路径数(可能指数级)。
//     或者在 DP 基础上从终点回溯重建一条路径。
// ============================================================
