#!/bin/bash
# LeetCode 192: Word Frequency (统计词频)
#
# 【题目本质】
# 统计文本文件中每个单词的出现频率，按降序输出。
# 核心：文本拆词 → 计数 → 排序 → 格式化输出。
#
# 【解法总览】
# 解法1: tr + sort + uniq + awk   — 经典管道组合，面试首选
# 解法2: awk 关联数组             — 一次遍历统计，大文件友好
# 解法3: xargs + sort + uniq      — xargs 拆词替代 tr
# 解法4: sed + sort + uniq        — sed 替代 tr 做分词

# ============================================================
# 解法1: tr + sort + uniq + awk — 经典管道 ⭐
#
# 【管道数据流】
# cat words.txt             → 读取文件内容
# | tr -s ' ' '\n'          → 把空格替换为换行，-s压缩连续空格
# | sort                    → 排序（uniq要求输入已排序）
# | uniq -c                 → 统计每个单词的出现次数
# | sort -rn                → 按数值降序排序
# | awk '{print $2, $1}'    → 调换列顺序（word count → count word）
#
# 为什么 uniq 前必须 sort？
#   uniq 只能去除相邻的重复行。如果不排序，
#   "the" 出现在不同位置会被当成不同的组。
#
# 为什么 tr 要加 -s？
#   -s (squeeze) 把多个连续空格当一个处理。
#   不加 -s，多空格会产生空行，空行也会被计数。
# ============================================================
cat words.txt | tr -s ' ' '\n' | sort | uniq -c | sort -rn | awk '{print $2, $1}'

# ============================================================
# 解法2: awk 关联数组 — 一次遍历
#
# 【思路】
# awk 内置关联数组（类似 Python dict），遍历文件中每个单词，
# 用 count[$i]++ 直接统计频率。END 块中输出结果。
#
# NF 是 awk 内置变量，表示当前行的字段数。
# $i 是第 i 个字段（单词）。
# awk 自动按空白分割字段，无需 tr。
#
# 优势：只遍历一次文件，不需要 sort（awk 数组就是哈希表）。
# 劣势：最终排序仍需管道接 sort。
# ============================================================
# awk '{for(i=1;i<=NF;i++) count[$i]++} END {for(w in count) print w, count[w]}' words.txt | sort -k2 -rn

# ============================================================
# 解法3: xargs 拆词
#
# 【思路】
# xargs -n1 把输入按空白拆成每行一个单词。
# 效果与 tr -s ' ' '\n' 相同，但 xargs 更通用。
#
# -n1 表示每次输出1个参数（一个单词一行）。
# ============================================================
# cat words.txt | xargs -n1 | sort | uniq -c | sort -rn | awk '{print $2, $1}'

# ============================================================
# 解法4: sed 拆词
#
# 【思路】
# sed 's/ /\n/g' 把空格替换为换行符。
# 与 tr 类似，但 sed 支持更复杂的正则替换。
# ============================================================
# sed 's/[[:space:]]\+/\n/g' words.txt | sort | uniq -c | sort -rn | awk '{print $2, $1}'

# ============================================================
# 【解法对比】
#
# | 解法              | 工具数 | 内存   | 优势                    | 劣势                  |
# |-------------------|--------|--------|------------------------|----------------------|
# | tr+sort+uniq+awk  | 5      | O(n)   | 经典Unix管道，面试标答   | sort是O(nlogn)       |
# | awk关联数组        | 2      | O(词表) | 一次遍历，大文件友好     | 仍需sort排序          |
# | xargs             | 5      | O(n)   | xargs更通用             | 与tr方案等价          |
# | sed               | 5      | O(n)   | sed正则更强             | 可读性略差            |
#
# ============================================================
# 【易错点】
#
# 1. uniq前忘排序:
#    ✗ tr -s ' ' '\n' < words.txt | uniq -c
#      → 不相邻的相同单词被分别计数
#    ✓ tr -s ' ' '\n' < words.txt | sort | uniq -c
#
# 2. tr不加-s:
#    ✗ tr ' ' '\n' → 多个连续空格产生空行
#    ✓ tr -s ' ' '\n' → -s压缩连续分隔符
#
# 3. sort不加-n:
#    ✗ sort -r → 字典序排序，"9"排在"10"后面
#    ✓ sort -rn → 数值降序排序
#
# 4. 输出格式:
#    ✗ uniq -c 输出 "  4 the" → 前导空格+count在前
#    ✓ awk '{print $2, $1}' → 调换为 "the 4"
#
# ============================================================
# 【面试追问】
#
# Q1: 能一行命令完成吗？
#     是的，解法1就是一行管道命令。
#
# Q2: 超大文件怎么优化？
#     用awk关联数组一次遍历统计（避免sort的O(nlogn)），
#     或用 sort --parallel=N 利用多核。
#
# Q3: 大小写不敏感怎么处理？
#     管道开头加 tr 'A-Z' 'a-z' 统一转小写。
