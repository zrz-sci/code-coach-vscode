/*
 * LeetCode 283: 移动零 (Move Zeroes)
 * 
 * 【题目本质】
 * 数组原地分区：非零元素保持相对顺序放前面，零放后面。
 * 本质和快排的 partition 操作同类，也和 27.移除元素 几乎相同。
 *
 * 【解法总览】
 * 解法1: 暴力冒泡       — O(n²) / O(1) — 最直觉，每遇到0就后移
 * 解法2: 覆盖+补零      — O(n)  / O(1) — 面试首选，清晰好写
 * 解法3: 交换法(最少操作) — O(n)  / O(1) — Follow-up 最优，最少写操作
 */

// ============================================================
// 解法1: 暴力冒泡 — 遇到0就和后面第一个非零元素交换
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 最直觉的想法：从左到右扫描，遇到一个0就往后找第一个非零元素，
// 交换它们。像冒泡排序一样把零一个个"沉到底部"。
//
// 瓶颈：对于 [0,0,0,...,0,1] 这种情况，每次内层 while 几乎
// 扫完整个数组，总计 O(n²)。
//
// 过程演示: nums = [0, 1, 0, 3, 12]
// i=0: nums[0]==0, 找到j=1(非零), swap → [1, 0, 0, 3, 12]
// i=1: nums[1]==0, 找到j=3(非零), swap → [1, 3, 0, 0, 12]
// i=2: nums[2]==0, 找到j=4(非零), swap → [1, 3, 12, 0, 0]
// i=3: nums[3]==0, j扫到末尾无非零, 跳过
// i=4: nums[4]==0, 跳过
// 结果: [1, 3, 12, 0, 0] ✓
// ============================================================
class Solution1 {
public:
    void moveZeroes(vector<int>& nums) {
        int n = nums.size();
        for (int i = 0; i < n; i++) {
            if (nums[i] == 0) {
                // 往后找第一个非零元素来交换
                int j = i + 1;
                while (j < n && nums[j] == 0) j++;
                if (j < n) {
                    swap(nums[i], nums[j]);
                }
            }
        }
    }
};

// ============================================================
// 解法2: 覆盖 + 补零 — 非零元素前移，末尾补零
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1的瓶颈：每遇到零都要线性查找下一个非零元素，重复扫描。
// 换个角度：不去"移动零"，而是"把非零元素往前放"。
//
// 用快慢双指针：
//   - fast: 扫描整个数组，找非零元素
//   - slow: 标记"下一个非零元素该放的位置"
//
// 不变量: nums[0..slow-1] 始终是已归位的非零元素。
//
// 两趟操作：
//   第一趟: 把所有非零元素依次写到 nums[0], nums[1], ...
//   第二趟: nums[slow..n-1] 全部填零
//
// 过程演示: nums = [0, 1, 0, 3, 12]
//
// 第一趟(覆盖):
//   fast=0: nums[0]==0, 跳过.          slow=0
//   fast=1: nums[1]==1, nums[0]=1.     slow=1  → [1, 1, 0, 3, 12]
//   fast=2: nums[2]==0, 跳过.          slow=1
//   fast=3: nums[3]==3, nums[1]=3.     slow=2  → [1, 3, 0, 3, 12]
//   fast=4: nums[4]==12, nums[2]=12.   slow=3  → [1, 3, 12, 3, 12]
//
// 第二趟(补零):
//   nums[3]=0, nums[4]=0               → [1, 3, 12, 0, 0] ✓
// ============================================================
class Solution2 {
public:
    void moveZeroes(vector<int>& nums) {
        int slow = 0;
        
        // 第一趟：非零元素依次前移
        for (int fast = 0; fast < (int)nums.size(); fast++) {
            if (nums[fast] != 0) {
                nums[slow] = nums[fast];
                slow++;
            }
        }
        
        // 第二趟：slow 之后的位置全部填零
        // 【易错】不能漏掉这一步，否则末尾残留旧值
        while (slow < (int)nums.size()) {
            nums[slow] = 0;
            slow++;
        }
    }
};

// ============================================================
// 解法3: 交换法 — Follow-up: 最小化操作次数
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法2 的问题：即使非零元素本来就在正确位置（如 [1,2,3,0,0]），
// 前3个元素也会被"覆盖"成自己（多余操作），而且还需要第二趟补零。
//
// 优化：用 swap 代替覆盖。
//   - 当 nums[fast] 非零时，swap(nums[slow], nums[fast])
//   - 零被自然交换到后面，不需要第二趟补零
//   - 加上 fast != slow 判断，避免无意义的自我交换
//
// 操作次数分析：
//   - 数组无零 [1,2,3]: fast==slow 始终成立，0 次交换
//   - 数组全零 [0,0,0]: 没有非零触发交换，0 次交换
//   - 一般情况: 交换次数 = 非零元素个数（最坏）
//
// 过程演示: nums = [0, 1, 0, 3, 12]
//
//   初始: [0, 1, 0, 3, 12]    slow=0, fast=0
//          s
//          f
//
//   f=0: nums[0]==0, 跳过
//         [0, 1, 0, 3, 12]    slow=0, fast=1
//          s  f
//
//   f=1: nums[1]==1≠0, f≠s → swap(nums[0],nums[1]), slow++
//         [1, 0, 0, 3, 12]    slow=1, fast=2
//             s  f
//
//   f=2: nums[2]==0, 跳过
//         [1, 0, 0, 3, 12]    slow=1, fast=3
//             s     f
//
//   f=3: nums[3]==3≠0, f≠s → swap(nums[1],nums[3]), slow++
//         [1, 3, 0, 0, 12]    slow=2, fast=4
//                s      f
//
//   f=4: nums[4]==12≠0, f≠s → swap(nums[2],nums[4]), slow++
//         [1, 3, 12, 0, 0]    slow=3, fast=5→结束
//                    s
//
//   结果: [1, 3, 12, 0, 0] ✓ (总共 3 次交换，恰好等于非零元素数)
// ============================================================
class Solution3 {
public:
    void moveZeroes(vector<int>& nums) {
        int slow = 0;
        for (int fast = 0; fast < (int)nums.size(); fast++) {
            if (nums[fast] != 0) {
                // 只在 slow 和 fast 不同位置时才交换
                // 这是 Follow-up 要求"最少操作"的关键
                if (fast != slow) {
                    swap(nums[slow], nums[fast]);
                }
                slow++;
            }
        }
        // 不需要补零 — 零已经被交换到后面了
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 时间   | 空间  | 写操作次数      | 需要补零？ |
// |------------|--------|------|----------------|-----------|
// | 暴力冒泡    | O(n²)  | O(1) | 最多            | 否        |
// | 覆盖+补零   | O(n)   | O(1) | 恰好 n 次       | 是        |
// | 交换法      | O(n)   | O(1) | ≤ 非零元素个数   | 否        |
//
// 面试建议：先写解法2，被追问 Follow-up 时优化到解法3。
//
// 【易错点】
// 1. 覆盖法忘记补零：
//    ✗ 只做第一趟覆盖，漏掉 while(slow<n) nums[slow++]=0;
//    → [0,1,0,3,12] 变成 [1,3,12,3,12]（末尾残留旧值）
//    ✓ 必须第二趟把 [slow, n) 全部置零
//
// 2. 交换法漏掉 fast != slow 判断：
//    ✗ if (nums[fast] != 0) swap(nums[slow++], nums[fast]);
//    正确性没问题，但多了无意义的自我交换，不满足 Follow-up
//    ✓ 加上 if (fast != slow) 条件
//
// 3. slow 初始化为 1：
//    ✗ int slow = 1; — 跳过了 nums[0] 的处理
//    ✓ int slow = 0; — 从头开始
//
// 【面试追问】
// Q1(基础): 你的解法能保持非零元素相对顺序吗？为什么？
//    → fast 从左到右顺序扫描，非零元素按遇到顺序放到 slow 位置，
//      相对顺序不变。
//
// Q2(Follow-up): 能否最小化操作次数？数组本身无零的情况呢？
//    → 交换法 + fast!=slow 判断。无零时 fast==slow 始终成立，
//      0 次交换操作。
//
// Q3(变体): 移动零到数组开头怎么做？
//    → 从右往左扫描，slow 从末尾向前移动，逻辑完全对称。
//
// Q4(泛化): 移动任意值 val 到末尾？
//    → 即 LeetCode 27. 移除元素。只需把 != 0 改成 != val，
//      283 额外需要补零（或用交换法自动处理）。
//
// 【相关题型】
// - 27. 移除元素: 完全相同的快慢指针框架，不需要补零
// - 26. 删除有序数组重复项: 同样快慢指针，判断改为 nums[fast]!=nums[slow-1]
// - 75. 颜色分类(荷兰国旗): 三指针分区，283 是两分区简化版
// - 88. 合并两个有序数组: 双指针原地操作数组的经典题
// ============================================================
