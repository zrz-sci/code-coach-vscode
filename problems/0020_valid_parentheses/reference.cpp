/*
 * LeetCode 20: 有效的括号 (Valid Parentheses)
 *
 * 【题目本质】
 * 判断括号序列是否合法 = 每个右括号都能和"最近的未配对左括号"匹配。
 * "最近"→ 后进先出 → 栈。
 *
 * 【解法总览】
 * 解法1: 暴力替换 — O(n²) / O(n) — 反复删除相邻配对，直到不变
 * 解法2: 栈匹配   — O(n) / O(n) — 左括号入栈，右括号检查栈顶 ⭐ 面试首选
 * 解法3: 栈匹配(压入期望值) — O(n) / O(n) — 入栈时压右括号，比较更优雅
 */

// ============================================================
// 解法1: 暴力替换 — 反复消除相邻配对
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 最直觉的想法：配对的括号可以"消掉"。
// 反复在字符串中查找 "()", "[]", "{}" 并删除，
// 如果最终字符串为空就合法。
//
// 为什么是 O(n²)？每次 erase 是 O(n)，最多 n/2 轮。
// 瓶颈：每次删除后要重新扫描，大量重复工作。
//
// 演示: s = "{[()]}"
// Round1: 找到"()" → "{[()]}" → "{[]}"
// Round2: 找到"[]" → "{[]}" → "{}"
// Round3: 找到"{}" → "{}" → ""
// 空字符串 → true
// ============================================================
class Solution1 {
public:
    bool isValid(string s) {
        string prev;
        do {
            prev = s;
            size_t pos;
            while ((pos = s.find("()")) != string::npos) s.erase(pos, 2);
            while ((pos = s.find("[]")) != string::npos) s.erase(pos, 2);
            while ((pos = s.find("{}")) != string::npos) s.erase(pos, 2);
        } while (s != prev); // 直到没有变化
        
        return s.empty();
    }
};

// ============================================================
// 解法2: 栈匹配 — 左括号入栈，右括号检查栈顶 ⭐ 面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 从暴力法我们知道，括号配对的核心是"最近的左括号先配对"。
// "最近" = "后进先出" = 栈！
//
// 规则：
//   - 遇到左括号 → 压入栈
//   - 遇到右括号 → 检查栈顶的左括号是否匹配
//     - 匹配 → 弹出栈顶（配对成功）
//     - 不匹配或栈空 → 不合法
//   - 遍历结束 → 栈必须为空（没有多余左括号）
//
// 演示: s = "({[]})"
//
// 字符  操作              栈状态(底→顶)
//  (    左括号, push      [ ( ]
//  {    左括号, push      [ (, { ]
//  [    左括号, push      [ (, {, [ ]
//  ]    栈顶=[, 匹配, pop [ (, { ]
//  }    栈顶={, 匹配, pop [ ( ]
//  )    栈顶=(, 匹配, pop [ ]  ← 空
// 遍历结束, 栈空 → true
//
// 失败演示: s = "([)]"
//
// 字符  操作              栈状态(底→顶)
//  (    左括号, push      [ ( ]
//  [    左括号, push      [ (, [ ]
//  )    栈顶=[ ≠ ( → false!
// ============================================================
class Solution2 {
public:
    bool isValid(string s) {
        stack<char> stk;
        
        for (char c : s) {
            if (c == '(' || c == '[' || c == '{') {
                stk.push(c);
            } else {
                // 右括号：栈空意味着没有左括号可配对
                if (stk.empty()) return false;
                
                char top = stk.top();
                // 类型必须匹配
                if ((c == ')' && top != '(') ||
                    (c == ']' && top != '[') ||
                    (c == '}' && top != '{')) {
                    return false;
                }
                stk.pop(); // 配对成功
            }
        }
        
        // 栈非空 = 左括号多余，如 "(("
        return stk.empty();
    }
};

// ============================================================
// 解法3: 栈匹配(压入期望值) — 入栈时压对应右括号
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法2中，遇到右括号要判断"栈顶的左括号是否和当前右括号配对"，
// 需要写三个条件。
//
// 技巧：遇到左括号时，不压左括号本身，而是压入"期望的右括号"。
// 这样遇到右括号时，只需 stk.top() == c 一个判断。
// 把匹配逻辑"前移"到入栈时，出栈时只需简单比较。
//
// 演示: s = "({[]})"
//
// 字符  操作                 栈状态(底→顶) — 存的是"期望值"
//  (    push ')'             [ ) ]
//  {    push '}'             [ ), } ]
//  [    push ']'             [ ), }, ] ]
//  ]    top=']'==']', pop    [ ), } ]
//  }    top='}'=='}', pop    [ ) ]
//  )    top=')'==')', pop    [ ]
// 遍历结束, 栈空 → true
// ============================================================
class Solution3 {
public:
    bool isValid(string s) {
        stack<char> stk;
        
        for (char c : s) {
            // 遇到左括号，压入"期望的右括号"
            if (c == '(')      stk.push(')');
            else if (c == '[') stk.push(']');
            else if (c == '{') stk.push('}');
            else {
                // 遇到右括号，直接和栈顶的"期望值"比较
                if (stk.empty() || stk.top() != c) return false;
                stk.pop();
            }
        }
        
        return stk.empty();
    }
};

// ============================================================
// 【解法对比】
//
// 解法1 暴力替换: 
//   - O(n²) 时间，理解最直觉，面试中口述即可
//   - 瓶颈：每次删除后重新扫描
//
// 解法2 栈匹配:
//   - O(n) 时间，一次遍历，面试标准答案
//   - 核心洞察：括号配对是后进先出(LIFO)
//
// 解法3 压入期望值:
//   - 本质和解法2相同，只是编码技巧不同
//   - 优点：判断逻辑更简洁（一个 != 替代三个 ||）
//   - 面试中展示体现代码能力
//
// 面试推荐顺序: 先说思路(为什么用栈) → 写解法2 → 提一嘴解法3的技巧
//
// 【易错点】
// 1. 遇到右括号时忘记检查 stk.empty():
//    ✗ char top = stk.top();          // s=")" 时栈空，崩溃!
//    ✓ if (stk.empty()) return false;  // 先检查
//
// 2. 遍历结束后直接 return true:
//    ✗ return true;       // s="((" 时栈还有元素，应该返回 false
//    ✓ return stk.empty(); // 栈空才说明完全匹配
//
// 3. 匹配条件写反:
//    ✗ c == '(' && top != ')'  // c 是右括号，不是左括号!
//    ✓ c == ')' && top != '('  // 当前是右括号，栈顶应是对应左括号
//
// 4. 提前优化: 奇数长度的字符串一定不合法，可以在开头加:
//    if (s.size() % 2 != 0) return false;
//    虽然不加也能过，但面试中加上展示细心。
//
// 【面试追问】
// Q1(基础): 为什么不能用三个计数器分别统计三种括号的数量？
//    → 计数器只能保证数量匹配，无法保证顺序。
//      "([)]" 数量都对但顺序错。栈记录了"打开顺序"。
//
// Q2(优化): 能否 O(1) 空间？
//    → 如果允许修改输入字符串，可以把字符串本身当栈使用
//      (用一个 top 指针标记栈顶位置，原地覆盖)。
//      但严格来说字符串本身占 O(n)。
//      不修改输入则无法做到 O(1)，因为需要记录历史。
//
// Q3(变体): 如果括号类型不固定(如自定义 <> 或更多)，怎么扩展？
//    → 用 unordered_map<char,char> 存右括号→左括号映射。
//      判断逻辑不变：在 map 中的是右括号，不在的是左括号。
//      代码几乎不用改，只改映射表。
// ============================================================
