/*
 * LeetCode 899: Orderly Queue (有序队列)
 *
 * 【题目本质】
 * 从字符串前 k 个字符中选一个移到末尾，重复任意次，求字典序最小结果。
 * 关键洞察：k=1 只能循环旋转；k>=2 能实现任意排列（冒泡排序）。
 *
 * 【解法总览】
 * 解法1: 分类讨论(k=1旋转 / k>=2排序) — O(n²) or O(nlogn) — 唯一正解
 * 解法2: k=1 用拼接优化              — O(n²) / O(n)        — 写法变体
 */

// ============================================================
// 解法1: 分类讨论 — 核心正解 ⭐
// 时间: k=1时O(n²), k>=2时O(n log n)  空间: O(n)
//
// 【思路 — 分两种情况】
//
// 情况A: k == 1
//   只能把第1个字符移到末尾 = 循环旋转。
//   字符串 "abc" 的所有旋转: "abc", "bca", "cab"
//   枚举所有 n 种旋转，取字典序最小。
//
//   示例: s = "cba", k = 1
//     旋转0: "cba"
//     旋转1: "bac"  (c 移到末尾)
//     旋转2: "acb"  (b 移到末尾)
//     最小: "acb" ✓
//
// 情况B: k >= 2
//   可以选前 k 个中任意一个移到末尾。
//   关键定理：k>=2 时能交换任意相邻字符 → 等价于冒泡排序 → 任意排列。
//   所以答案就是字符串排序后的结果。
//
//   示例: s = "baaca", k = 3
//     k >= 2 → 排序 → "aaabc" ✓
//
// 【为什么 k>=2 能交换相邻字符？证明】
//
// 设字符串为 "a b R"（a,b 是前两个字符，R 是剩余部分）
//
// 目标：把 "a b R" 变成 "b a R"（交换 a 和 b）
//
// 步骤:
//   "a b R"     原始
//   → "a R b"   选第2个字符 b，移到末尾
//   → "R b a"   选第1个字符 a，移到末尾
//   → "b a R"   连续选第1个字符 len(R) 次，把 R 中每个字符移到末尾
//               等价于 R 整体旋转到末尾
//               最终 R 回到原位，但 a 和 b 交换了
//
// 能交换相邻字符 = 冒泡排序 = 能生成任意排列 (对称群 S_n)
// 所以 k>=2 时，最小排列 = 排序后的字符串
// ============================================================
class Solution1 {
public:
    string orderlyQueue(string s, int k) {
        if (k == 1) {
            // 只能循环旋转：枚举所有 n 种旋转，取字典序最小
            string minStr = s;
            int n = s.size();

            for (int i = 1; i < n; i++) {
                // s[i:] + s[:i] = 以位置 i 开头的旋转
                string rotated = s.substr(i) + s.substr(0, i);
                if (rotated < minStr) {
                    minStr = rotated;
                }
            }

            return minStr;
        } else {
            // k >= 2: 能实现任意排列，直接排序
            string sorted_s = s;
            sort(sorted_s.begin(), sorted_s.end());
            return sorted_s;
        }
    }
};

// ============================================================
// 解法2: k=1 用 s+s 拼接技巧
// 时间: k=1时O(n²), k>=2时O(n log n)  空间: O(n)
//
// 【思路】
// 处理循环字符串的经典技巧：把字符串复制一份拼接。
// s + s 包含了 s 的所有 n 种旋转作为长度 n 的子串。
// doubled[i..i+n-1] = 以 s[i] 开头的旋转。
//
// 示例: s = "abc"
//   doubled = "abcabc"
//   doubled[0..2] = "abc"  ← 旋转0
//   doubled[1..3] = "bca"  ← 旋转1
//   doubled[2..4] = "cab"  ← 旋转2
//
// 这个技巧在很多循环字符串/数组问题中都很有用：
//   - 796. 旋转字符串：判断 t 是否是 s 的旋转 → (s+s).find(t)
//   - 本题：枚举所有旋转取最小
//   - 环形数组问题：把数组复制一份处理
// ============================================================
class Solution2 {
public:
    string orderlyQueue(string s, int k) {
        if (k == 1) {
            // s+s 包含所有旋转
            string doubled = s + s;
            string minStr = s;
            int n = s.size();

            for (int i = 1; i < n; i++) {
                string rotated = doubled.substr(i, n);
                if (rotated < minStr) {
                    minStr = rotated;
                }
            }

            return minStr;
        } else {
            sort(s.begin(), s.end());
            return s;
        }
    }
};

// ============================================================
// 解法3: k=1 用逐字符比较避免 substr（常数优化）
// 时间: O(n²)  空间: O(1) 额外空间
//
// 【思路】
// substr 每次创建新字符串有额外开销。
// 可以直接用取模索引逐字符比较两个旋转，避免创建子串。
//
// 比较旋转 i 和当前最小旋转 best:
//   对于位置 j (0 到 n-1):
//     s[(i+j) % n] 和 s[(best+j) % n]
//
// 这种写法更底层，但效率更高（尤其 n 很大时）。
// ============================================================
class Solution3 {
public:
    string orderlyQueue(string s, int k) {
        int n = s.size();

        if (k == 1) {
            int best = 0;  // 最小旋转的起始位置

            for (int i = 1; i < n; i++) {
                // 比较旋转 i 和旋转 best
                bool smaller = false;
                for (int j = 0; j < n; j++) {
                    char ci = s[(i + j) % n];
                    char cb = s[(best + j) % n];
                    if (ci < cb) {
                        smaller = true;
                        break;
                    } else if (ci > cb) {
                        break;
                    }
                    // ci == cb: 继续比较下一位
                }
                if (smaller) {
                    best = i;
                }
            }

            // 构造最小旋转
            return s.substr(best) + s.substr(0, best);
        } else {
            sort(s.begin(), s.end());
            return s;
        }
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间(k=1)  | 时间(k>=2)  | 空间  | 优势                    |
// |-------------|-----------|------------|-------|------------------------|
// | substr枚举   | O(n²)     | O(nlogn)   | O(n)  | 代码最简洁               |
// | s+s 拼接     | O(n²)     | O(nlogn)   | O(n)  | 体现循环字符串技巧         |
// | 取模比较      | O(n²)     | O(nlogn)   | O(1)  | 常数最优，不创建子串       |
//
// n ≤ 1000，三种写法都能过。面试选择解法1，代码最清晰。
//
// ============================================================
// 【易错点】
//
// 1. k>=2 时还在模拟操作:
//    ✗ BFS/DFS 搜索所有操作序列 → 状态空间 O(n!) 爆炸
//    ✓ 直接 sort()，因为 k>=2 等价于任意排列
//
// 2. k=1 时只试了几种旋转:
//    ✗ 只旋转了一两次就返回
//    ✓ 必须枚举所有 n 种旋转（0 到 n-1）
//
// 3. 分水岭搞错:
//    ✗ 认为 k=2 和 k=3 不同
//    ✓ 只有 k=1 和 k>=2 两种情况。k>=2 全部等价于能做任意排列。
//
// 4. 旋转索引计算错误:
//    ✗ s.substr(i) 但忘了后面还要接 s.substr(0, i)
//    ✓ 旋转 i = s[i..n-1] + s[0..i-1]
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 如何严格证明 k>=2 能实现任意排列？
//     1. 展示 k>=2 能交换相邻字符（见上面的步骤证明）
//     2. 相邻对换生成对称群 S_n（群论基本定理）
//     3. 因此 k>=2 能实现任意排列
//
// Q2: k=1 有没有 O(n) 的算法？
//     Booth's algorithm: 用类似 KMP 的失败函数在 s+s 上
//     找最小旋转。O(n) 时间 O(n) 空间。竞赛内容，面试不要求。
//
// Q3: 如果操作有次数限制呢？
//     完全不同的问题。k=1: 旋转 i 步需要 i 次操作。
//     k>=2: 需要分析最少交换次数（= 逆序对数量）。
//
