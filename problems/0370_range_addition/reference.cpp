// ============================================================
// 370. Range Addition
// ============================================================
// 标签: Array, Prefix Sum
// 难度: Medium
//
// 【题目本质】
//   长度为n的全零数组，执行k次区间加法 [start, end, inc]，
//   返回最终数组。核心: 差分数组将每次O(n)操作降为O(1)。
//
// 【解法总览】
//   解法1: 差分数组 -- diff[start]+=inc, diff[end+1]-=inc, 前缀和还原
//   解法2: 暴力模拟 -- 每次操作遍历区间(O(nk), 不推荐)
// ============================================================


// ============================================================
// 解法1: 差分数组 (推荐)
//
// 原理:
//   差分数组 diff[i] = arr[i] - arr[i-1]
//   区间 [start, end] 加 inc:
//     diff[start] += inc   // 从 start 开始增加
//     diff[end+1] -= inc   // 从 end+1 开始取消增加
//   前缀和 prefix_sum(diff) = 最终的 arr
//
// 过程可视化 (length=5, updates=[[1,3,2],[2,4,3],[0,2,-2]]):
//
//   初始 diff = [0, 0, 0, 0, 0]
//
//   操作 [1,3,2]:
//     diff[1]+=2, diff[4]-=2
//     diff = [0, 2, 0, 0, -2]
//
//   操作 [2,4,3]:
//     diff[2]+=3, end+1=5 越界省略
//     diff = [0, 2, 3, 0, -2]
//
//   操作 [0,2,-2]:
//     diff[0]+=-2, diff[3]-=(-2)=+2
//     diff = [-2, 2, 3, 2, -2]
//
//   前缀和还原:
//     [-2, 0, 3, 5, 3] ✓
//
// 时间: O(n + k)  -- k次标记 + 1次前缀和
// 空间: O(n)      -- 差分数组(也是结果数组)
// ============================================================
class Solution {
public:
    vector<int> getModifiedArray(int length, vector<vector<int>>& updates) {
        vector<int> diff(length, 0);

        // 差分标记: 每个操作 O(1)
        for (auto& update : updates) {
            int start = update[0];
            int end = update[1];
            int inc = update[2];

            diff[start] += inc;         // 起点: 开始增加
            if (end + 1 < length) {
                diff[end + 1] -= inc;   // 终点后一位: 取消增加
            }
        }

        // 前缀和还原: O(n)
        for (int i = 1; i < length; i++) {
            diff[i] += diff[i - 1];
        }

        return diff;  // diff 现在就是最终数组
    }
};


// ============================================================
// 解法2: 暴力模拟 (对照用, 不推荐)
//
// 直接按操作遍历区间修改。
//
// 时间: O(n * k) -- 最坏 10^5 * 10^4 = 10^9, 超时
// 空间: O(n)
// ============================================================
class Solution2 {
public:
    vector<int> getModifiedArray(int length, vector<vector<int>>& updates) {
        vector<int> arr(length, 0);

        for (auto& update : updates) {
            int start = update[0];
            int end = update[1];
            int inc = update[2];

            // 逐个元素修改
            for (int i = start; i <= end; i++) {
                arr[i] += inc;
            }
        }

        return arr;
    }
};


// ============================================================
// 【解法对比】
//   解法1 (差分数组): O(n + k) 时间, O(n) 空间 -- 唯一推荐
//   解法2 (暴力):     O(n * k) 时间, O(n) 空间 -- 超时
//
// 【易错点】
//   1. diff[end] -= inc 而非 diff[end+1] -= inc:
//      差分取消点是 end+1 而非 end，因为 end 本身也在区间内。
//   2. 忘记边界检查 end+1 < length:
//      当 end == length-1 时，end+1 越界，不需要减操作。
//   3. 前缀和起始索引错:
//      从 i=1 开始做 diff[i] += diff[i-1]，diff[0] 本身已正确。
//   4. 返回 diff 前忘记做前缀和:
//      diff 只是标记，必须做前缀和才是最终数组。
//   5. inc 可以是负数:
//      题目允许 -1000 <= inc <= 1000，差分法天然支持负数。
//
// 【面试追问】
//   Q1: 差分数组的适用场景是什么?
//       → 多次区间修改 + 最终一次全量查询。
//         如果需要边修改边查询，需要树状数组或线段树。
//
//   Q2: 如何推广到二维?
//       → 对矩形 (r1,c1)-(r2,c2) 加 inc:
//         diff[r1][c1] += inc
//         diff[r1][c2+1] -= inc
//         diff[r2+1][c1] -= inc
//         diff[r2+1][c2+1] += inc
//         然后做二维前缀和还原。
//
//   Q3: 差分和前缀和是什么关系?
//       → 互逆操作。差分: diff[i] = arr[i] - arr[i-1]
//         前缀和: arr[i] = diff[0] + diff[1] + ... + diff[i]
//         差分数组上做前缀和恢复原数组，原数组做差分得差分数组。
// ============================================================
