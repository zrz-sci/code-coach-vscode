/*
 * LeetCode 723: 粉碎糖果 (Candy Crush)
 *
 * 【题目本质】
 * 模拟消消乐：反复执行"标记三连→粉碎→重力下落"直到棋盘稳定。
 * 核心难点：(1)同时标记所有待粉碎糖果 (2)正确模拟重力下落
 *
 * 【解法总览】
 * 解法1: 额外标记矩阵 — O((m·n)²) / O(m·n) — 最直觉
 * 解法2: 取负值原地标记 — O((m·n)²) / O(1) — 面试首选，省空间
 */

// ============================================================
// 解法1: 额外标记矩阵
// 时间: O((m·n)²)  空间: O(m·n)
//
// 【思路】
// 每轮用一个 bool 矩阵记录哪些位置需要粉碎。
// 分两步扫描（水平+垂直），标记所有连续3+个相同糖果。
// 统一粉碎后，每列用双指针模拟重力下落。
// 循环直到某轮没有任何标记。
//
// 模拟过程 (示例2):
//   原始:            标记crush:       粉碎后:         下落后:
//   1 3 5 5 2       . . . . .       1 3 5 5 2       1 3 0 0 0
//   3 4 3 3 1       . x . . .       3 0 3 3 1       3 4 0 5 2
//   3 2 4 5 2       . . x . .  →    3 2 0 5 2  →    3 2 0 3 1
//   2 4 4 5 5       . x x . .       2 0 0 5 5       2 4 0 5 2
//   1 4 4 1 1       . x x . .       1 0 0 1 1       1 4 3 1 1
//   (x = 列方向 4,4,4 三连)
//
//   下落原理（以第1列为例）:
//   粉碎后: [3, 0, 2, 0, 0]  (从上到下)
//   双指针: write=4, read=4→3→2→1→0
//     read=4: 0, 跳过
//     read=3: 0, 跳过
//     read=2: 2, 写到[4], write=3
//     read=1: 0, 跳过
//     read=0: 3, 写到[3], write=2
//     填零: [2]=0, [1]=0, [0]=0
//   结果: [0, 0, 0, 3, 2]  → 非零元素沉到底部
// ============================================================
class Solution1 {
public:
    vector<vector<int>> candyCrush(vector<vector<int>>& board) {
        int m = board.size(), n = board[0].size();
        
        while (true) {
            vector<vector<bool>> crush(m, vector<bool>(n, false));
            bool found = false;
            
            // 水平扫描：每行找连续>=3个相同的
            for (int i = 0; i < m; i++) {
                for (int j = 0; j + 2 < n; j++) {
                    int v = board[i][j];
                    if (v != 0 && v == board[i][j+1] && v == board[i][j+2]) {
                        // 窗口滑动天然覆盖4连、5连等情况
                        crush[i][j] = crush[i][j+1] = crush[i][j+2] = true;
                        found = true;
                    }
                }
            }
            
            // 垂直扫描：每列找连续>=3个相同的
            for (int j = 0; j < n; j++) {
                for (int i = 0; i + 2 < m; i++) {
                    int v = board[i][j];
                    if (v != 0 && v == board[i+1][j] && v == board[i+2][j]) {
                        crush[i][j] = crush[i+1][j] = crush[i+2][j] = true;
                        found = true;
                    }
                }
            }
            
            // 没有可粉碎的，棋盘已稳定
            if (!found) break;
            
            // 粉碎
            for (int i = 0; i < m; i++)
                for (int j = 0; j < n; j++)
                    if (crush[i][j]) board[i][j] = 0;
            
            // 下落：每列独立，双指针将非零元素沉到底部
            for (int j = 0; j < n; j++) {
                int write = m - 1;
                for (int read = m - 1; read >= 0; read--) {
                    if (board[read][j] != 0) {
                        board[write][j] = board[read][j];
                        write--;
                    }
                }
                // 上方填零（没有新糖果从顶部落下）
                while (write >= 0) {
                    board[write][j] = 0;
                    write--;
                }
            }
        }
        
        return board;
    }
};

// ============================================================
// 解法2: 取负值原地标记 — 面试首选
// 时间: O((m·n)²)  空间: O(1) 额外空间
//
// 【思路】
// 解法1的空间开销来自 bool crush[][] 矩阵。
// 优化：利用"糖果值都是正整数"这一条件，用负值表示"待粉碎"。
//   - 标记时：board[i][j] = -abs(board[i][j])
//   - 比较时：用 abs(board[i][j]) 获取原始值
//   - 下落时：board[i][j] > 0 才是存活糖果
//
// 为什么取负值后比较不会出错？
//   同一轮中，格子A先被水平标记为负，之后垂直扫描到A时：
//   abs(board[A]) 仍然得到原始值，不影响垂直方向的比较。
//   这就是"取绝对值比较"的关键作用。
//
// 取负值标记过程示意:
//   board[i][j] = 5 (正值，未标记)
//   ↓ 水平检测到三连
//   board[i][j] = -5 (负值，已标记)
//   ↓ 垂直检测时
//   abs(board[i][j]) = 5 (正确获取原始值进行比较)
// ============================================================
class Solution2 {
public:
    vector<vector<int>> candyCrush(vector<vector<int>>& board) {
        int m = board.size(), n = board[0].size();
        
        while (true) {
            bool found = false;
            
            // === 标记阶段 ===
            
            // 水平方向：滑动窗口大小3
            for (int i = 0; i < m; i++) {
                for (int j = 0; j + 2 < n; j++) {
                    // 取绝对值比较 —— 已标记为负的格子仍能正确参与比较
                    int v = abs(board[i][j]);
                    if (v != 0 
                        && v == abs(board[i][j+1]) 
                        && v == abs(board[i][j+2])) {
                        // 取负标记（幂等操作，重复取负无害）
                        board[i][j]   = -v;
                        board[i][j+1] = -v;
                        board[i][j+2] = -v;
                        found = true;
                    }
                }
            }
            
            // 垂直方向：滑动窗口大小3
            for (int j = 0; j < n; j++) {
                for (int i = 0; i + 2 < m; i++) {
                    int v = abs(board[i][j]);
                    if (v != 0 
                        && v == abs(board[i+1][j]) 
                        && v == abs(board[i+2][j])) {
                        board[i][j]   = -v;
                        board[i+1][j] = -v;
                        board[i+2][j] = -v;
                        found = true;
                    }
                }
            }
            
            // 没有任何标记 → 稳定状态
            if (!found) break;
            
            // === 粉碎 + 下落阶段（合并处理）===
            // 每列独立：把正值（存活糖果）沉到底部，上方填零
            // 本质是 LC 27 "移除元素" 的列方向版本
            for (int j = 0; j < n; j++) {
                int write = m - 1; // 写指针从底部开始
                for (int read = m - 1; read >= 0; read--) {
                    // 只保留正值（存活的糖果）
                    // 负值 = 待粉碎，零 = 已空
                    if (board[read][j] > 0) {
                        board[write][j] = board[read][j];
                        write--;
                    }
                }
                // 上方全部置零
                while (write >= 0) {
                    board[write][j] = 0;
                    write--;
                }
            }
        }
        
        return board;
    }
};

// ============================================================
// 【解法对比】
//
//  | 解法1 (bool矩阵)     | 解法2 (取负值)
// -|-----------------------|-------------------
// 空间 | O(m·n) 额外        | O(1) 额外
// 代码 | 标记和比较完全分离   | 需要到处写 abs()
// 适用 | 值域包含负数时也可用 | 值域必须是正整数
//
// 面试建议：先说解法1思路（清晰），代码直接写解法2（展示优化意识）
//
// ============================================================
// 【易错点】
//
// 1. 忘记取绝对值比较
//    ✗ if (v != 0 && v == board[i][j+1] && ...)
//    ✓ if (v != 0 && v == abs(board[i][j+1]) && ...)
//    → 同一轮中，已被水平标记为负的格子，垂直扫描时比较会失败
//
// 2. 下落方向写反
//    ✗ for (int read = 0; read < m; read++) // 从上往下
//    ✓ for (int read = m-1; read >= 0; read--) // 从下往上
//    → 重力向下，必须从底部开始，否则糖果会"浮"上去
//
// 3. 下落时判断条件用 != 0 而非 > 0
//    ✗ if (board[read][j] != 0) // 负值也会被保留！
//    ✓ if (board[read][j] > 0)  // 只保留正值（存活糖果）
//    → 解法2中负值表示待粉碎，下落时必须用 > 0 过滤
//
// 4. 边粉碎边检测
//    ✗ 发现三连立刻清零 → 后续扫描漏掉交叉消除
//    ✓ 先标记所有，再统一粉碎/下落
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么必须"同时标记"而不能边找边消？
// A1: 一个糖果可能同时参与水平和垂直消除（T形/L形交叉）。
//     如果先消掉水平的，交叉点被清零，垂直的就检测不到了。
//
// Q2: 取负值标记的前提是什么？如果值可以是0或负数怎么办？
// A2: 前提是值都是正整数（题目保证1~2000）。
//     如果值域含负数，只能用额外标记矩阵（解法1）。
//     如果值可以是0但不能是负数，需要区分"原始0"和"空位0"。
//
// Q3: 下落操作本质上是什么？和哪道经典题一样？
// A3: 本质是 LC 27 "移除元素" — 每列上移除所有零/负值元素，
//     非零正值保持相对顺序沉到底部。读写双指针，O(m)一次扫描。
//
// Q4: 最坏时间复杂度怎么分析？
// A4: 每轮至少消除3个糖果，总共m·n个，所以最多 O(m·n/3) 轮。
//     每轮扫描 O(m·n)，总时间 O((m·n)²)。
//     实际中轮数远小于理论上界。
// ============================================================
