/*
 * LeetCode 876: 链表的中间结点 (Middle of the Linked List)
 * 
 * 【题目本质】
 * 在单链表中找中点。链表无法随机访问，如何高效定位到 n/2 的位置？
 *
 * 【解法总览】
 * 解法1: 两次遍历        — O(n) / O(1) — 最直觉
 * 解法2: 数组存储        — O(n) / O(n) — 以空间换随机访问
 * 解法3: 快慢指针        — O(n) / O(1) — 最优，面试首选
 */

/**
 * Definition for singly-linked list.
 * struct ListNode {
 *     int val;
 *     ListNode *next;
 *     ListNode() : val(0), next(nullptr) {}
 *     ListNode(int x) : val(x), next(nullptr) {}
 *     ListNode(int x, ListNode *next) : val(x), next(next) {}
 * };
 */

// ============================================================
// 解法1: 两次遍历 — 先数长度，再走到中点
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 链表不知道长度？那就先数一遍。
// 知道长度 n 后，中间节点在第 n/2 步（0-indexed）。
// 整数除法 n/2 恰好满足偶数时取第二个中间节点：
//   n=5 → n/2=2 → 走2步到第3个节点(val=3) ✓
//   n=6 → n/2=3 → 走3步到第4个节点(val=4) ✓
//
// 过程示意 (n=5):
//   第一遍数长度: 1→2→3→4→5→NULL, n=5
//   第二遍走 n/2=2 步:
//     head(1) → step1 → 2 → step2 → 3  ← 返回这里
// ============================================================
class Solution1 {
public:
    ListNode* middleNode(ListNode* head) {
        // 第一遍：数链表长度
        int n = 0;
        ListNode* curr = head;
        while (curr) {
            n++;
            curr = curr->next;
        }
        
        // 第二遍：从 head 走 n/2 步
        curr = head;
        for (int i = 0; i < n / 2; i++) {
            curr = curr->next;
        }
        return curr;
    }
};

// ============================================================
// 解法2: 数组存储 — 遍历时存入数组，直接随机访问
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 链表不能随机访问是瓶颈，那就转化成数组。
// 遍历一遍把所有节点指针存到 vector 中，
// 然后直接返回 arr[size/2]。
// 
// 这个解法展示了"用空间换能力"的思想，
// 但面试中一般不推荐，因为 O(n) 空间可以避免。
// ============================================================
class Solution2 {
public:
    ListNode* middleNode(ListNode* head) {
        vector<ListNode*> nodes;
        ListNode* curr = head;
        while (curr) {
            nodes.push_back(curr);
            curr = curr->next;
        }
        // size/2 整数除法恰好满足"偶数返回第二个中间节点"
        return nodes[nodes.size() / 2];
    }
};

// ============================================================
// 解法3: 快慢指针 — O(n) / O(1) ⭐ 面试首选
//
// 【思路】
// 解法1 需要两次遍历，瓶颈是"不知道什么时候走到一半"。
// 快慢指针的核心洞察：
//   如果快指针速度是慢指针的 2 倍，
//   那么快指针走完全程时，慢指针恰好走了一半。
//
// 这就像操场跑步：你跑 2 圈的时间里，朋友跑了 1 圈，
// 你回到起点时朋友在半圈的位置。
//
// 指针移动过程（奇数长度 5 个节点）:
//
//   1 → 2 → 3 → 4 → 5 → NULL
//   s                              初始: slow=1, fast=1
//   f
//
//   1 → 2 → 3 → 4 → 5 → NULL
//        s                         Step1: slow=2, fast=3
//             f
//
//   1 → 2 → 3 → 4 → 5 → NULL
//             s                    Step2: slow=3, fast=5
//                        f        fast->next==NULL → 停！返回 slow(3) ✓
//
// 指针移动过程（偶数长度 6 个节点）:
//
//   1 → 2 → 3 → 4 → 5 → 6 → NULL
//   s                              初始
//   f
//
//   1 → 2 → 3 → 4 → 5 → 6 → NULL
//        s                         Step1
//             f
//
//   1 → 2 → 3 → 4 → 5 → 6 → NULL
//             s                    Step2
//                        f
//
//   1 → 2 → 3 → 4 → 5 → 6 → NULL
//                  s               Step3
//                             f→NULL
//                                  fast==NULL → 停！返回 slow(4) ✓
// ============================================================
class Solution3 {
public:
    ListNode* middleNode(ListNode* head) {
        ListNode* slow = head;
        ListNode* fast = head;
        
        // 循环条件：fast 和 fast->next 都非空才能继续走两步
        // 为什么先检查 fast？ —— 偶数长度时 fast 会走到 NULL，
        // 此时不能再访问 fast->next，短路求值保证安全
        while (fast != nullptr && fast->next != nullptr) {
            slow = slow->next;          // 慢指针走 1 步
            fast = fast->next->next;    // 快指针走 2 步
        }
        
        // fast 到头了，slow 在中间
        return slow;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 遍历次数 | 空间  | 适用场景                    |
// |-----------|---------|-------|---------------------------|
// | 两次遍历   | 2       | O(1)  | 理解问题的起点              |
// | 数组存储   | 1       | O(n)  | 快速实现，不在乎空间         |
// | 快慢指针   | 1       | O(1)  | 面试首选，链表找中点的标准技巧 |
//
// 快慢指针是链表题的核心技巧之一，必须熟练掌握。
//
// 【易错点】
//
// 1. 循环条件顺序错误：
//    ✗ while (fast->next && fast)
//      → 当 fast==NULL 时先访问 fast->next，空指针解引用崩溃！
//    ✓ while (fast && fast->next)
//      → 短路求值：fast==NULL 时不再判断 fast->next
//
// 2. 混淆"第一个中间"和"第二个中间"：
//    ✗ while (fast->next && fast->next->next) → 这是找第一个中间节点
//      （链表归并排序断链时用这个）
//    ✓ while (fast && fast->next) → 这是找第二个中间节点（本题要求）
//
// 3. 单节点链表不需要特判：
//    fast=head, fast->next=NULL → 循环不执行 → 直接返回 head ✓
//
// 【面试追问】
//
// Q1: 暴力怎么做？瓶颈在哪？
//     → 先遍历数长度再走到中间，两次遍历。瓶颈是链表不支持随机访问。
//
// Q2: 能否一次遍历且 O(1) 空间？
//     → 快慢指针。快 2 倍速度，快到头时慢在中间。
//
// Q3: 如果要返回第一个中间节点呢？（归并排序常见需求）
//     → 改循环条件为 while (fast->next && fast->next->next)。
//       偶数时 fast 停在倒数第二个，slow 停在第一个中间节点。
//
// Q4: 快慢指针还能解决什么问题？
//     → 141 检测环（快慢是否相遇）
//     → 142 找环入口（相遇后一个回起点同步走）
//     → 19 删除倒数第k个（快先走k步）
//     → 234 回文链表（找中点+反转后半段）
//
// 【相关题型】
// - 141. 环形链表 — 复用快慢指针，区别：不是到头停止而是判断相遇
// - 142. 环形链表 II — 在 141 相遇基础上，数学推导找环入口
// - 234. 回文链表 — 先用本题找中点，再反转后半段逐一比较
// - 148. 排序链表 — 归并排序需要找中点断开，注意要找第一个中间节点
// ============================================================
