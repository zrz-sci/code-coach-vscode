/*
 * LeetCode 100: 相同的树 (Same Tree)
 * 
 * 【题目本质】
 * 同步遍历两棵树的每一个位置，判断结构和值是否完全一致。
 * 这是"双参数递归"的入门模板题。
 *
 * 【解法总览】
 * 解法1: 递归 DFS          — O(n) / O(h) — 最直觉，面试首选
 * 解法2: 迭代 DFS（栈）    — O(n) / O(h) — 不用递归的 DFS 版本
 * 解法3: 迭代 BFS（队列）  — O(n) / O(w) — 层序同步比较
 *
 * 其中 n = min(两棵树节点数), h = 树高, w = 树最大宽度
 */

/*
 * 【树结构示意图 — 以示例1为例】
 *
 *     p:          q:
 *      1           1          ← 根节点值相同? 1==1 ✓
 *     / \         / \
 *    2   3       2   3        ← 左子树 2==2 ✓, 右子树 3==3 ✓
 *
 * 递归调用过程:
 *   isSame(1,1) → val相同 → 递归左右
 *     isSame(2,2) → val相同 → 递归左右
 *       isSame(null,null) → 都为空 → true
 *       isSame(null,null) → 都为空 → true
 *     → true
 *     isSame(3,3) → val相同 → 递归左右
 *       isSame(null,null) → true
 *       isSame(null,null) → true
 *     → true
 *   → true && true = true
 *
 * 【示例2: p=[1,2], q=[1,null,2] — 结构不同】
 *
 *     p:          q:
 *      1           1         ← 1==1 ✓
 *     /              \
 *    2                2      ← 比较左子树: isSame(2, null)
 *                                p=2 非空, q=null → false!
 */

// ============================================================
// 解法1: 递归 DFS — 双参数同步递归（面试首选）
// 时间: O(n)  空间: O(h)  h为树高，最坏O(n)
//
// 【思路】
// 树是递归定义的结构，所以判断两棵树是否相同自然可以递归：
// - 两个节点都为 null → 这条路走到底了，匹配成功
// - 一个为 null 另一个不是 → 结构不同
// - 都不为 null → 比较值，再递归比较左子树和右子树
//
// 为什么先检查 "都为null" 再检查 "一个为null":
//   如果反过来，(!p || !q) 在两个都为null时也为true，
//   会错误返回false。
// ============================================================
class Solution1 {
public:
    bool isSameTree(TreeNode* p, TreeNode* q) {
        // 两个都到达空节点 — 这条路径完全匹配
        if (!p && !q) return true;
        
        // 只有一个为空 — 结构不同，立即返回
        if (!p || !q) return false;
        
        // 值不同 — 不是相同的树
        if (p->val != q->val) return false;
        
        // 同侧配对递归：左配左，右配右
        // （对比 101 对称二叉树：左配右，右配左）
        return isSameTree(p->left, q->left) 
            && isSameTree(p->right, q->right);
    }
};

// ============================================================
// 解法2: 迭代 DFS（栈） — 手动模拟递归调用栈
// 时间: O(n)  空间: O(h)
//
// 【思路】
// 递归的本质是系统帮你维护了一个调用栈，栈里存的是"待处理的参数"。
// 我们可以自己建一个栈，每次压入一对节点 (p_node, q_node)。
// 弹出时做和递归完全一样的判断逻辑。
//
// 关键：null 也要入栈！因为我们需要检测"一个有子节点一个没有"的情况。
// 如果跳过 null 不入栈，就无法发现结构差异。
//
// 迭代遍历过程 (示例1: 两棵 [1,2,3]):
//   栈初始: [(1,1)]
//   弹出(1,1): 值相同 → 压入 (2,2) 和 (3,3) → 栈: [(2,2),(3,3)]
//   弹出(3,3): 值相同 → 压入 (null,null) x2 → 栈: [(2,2),(null,null),(null,null)]
//   弹出(null,null): 都空 → continue
//   弹出(null,null): 都空 → continue
//   弹出(2,2): 值相同 → 压入 (null,null) x2
//   ... 全部 continue → 栈空 → return true
// ============================================================
class Solution2 {
public:
    bool isSameTree(TreeNode* p, TreeNode* q) {
        stack<pair<TreeNode*, TreeNode*>> stk;
        stk.push({p, q});
        
        while (!stk.empty()) {
            auto [n1, n2] = stk.top();
            stk.pop();
            
            // 都为空 — 这对匹配，看下一对
            if (!n1 && !n2) continue;
            
            // 结构不同 或 值不同
            if (!n1 || !n2) return false;
            if (n1->val != n2->val) return false;
            
            // 把子节点对压栈（null 也要压进去！）
            stk.push({n1->left, n2->left});
            stk.push({n1->right, n2->right});
        }
        
        // 所有节点对都检查通过
        return true;
    }
};

// ============================================================
// 解法3: 迭代 BFS（队列） — 层序同步遍历
// 时间: O(n)  空间: O(w)  w为树最大宽度
//
// 【思路】
// 和解法2逻辑完全相同，只是把栈换成队列。
// 遍历顺序从 DFS 变为 BFS（层序），但判断逻辑一模一样。
//
// 空间区别：
//   - DFS（栈）空间取决于树高 h，链状树最坏 O(n)
//   - BFS（队列）空间取决于最大宽度 w，完全二叉树最坏 O(n/2)
//   - 对于平衡树：h = O(log n), w = O(n/2)，BFS 空间更大
//   - 对于链状树：h = O(n), w = O(1)，BFS 空间更小
// ============================================================
class Solution3 {
public:
    bool isSameTree(TreeNode* p, TreeNode* q) {
        queue<pair<TreeNode*, TreeNode*>> que;
        que.push({p, q});
        
        while (!que.empty()) {
            auto [n1, n2] = que.front();
            que.pop();
            
            if (!n1 && !n2) continue;
            if (!n1 || !n2) return false;
            if (n1->val != n2->val) return false;
            
            que.push({n1->left, n2->left});
            que.push({n1->right, n2->right});
        }
        
        return true;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间  | 空间   | 代码量 | 适用场景            |
// |-----------|-------|--------|-------|-------------------|
// | 递归 DFS   | O(n)  | O(h)  | 5行   | 面试首选，最直观      |
// | 迭代 DFS栈 | O(n)  | O(h)  | 15行  | 追问"不用递归"时      |
// | 迭代 BFS   | O(n)  | O(w)  | 15行  | 需要层序信息/链状树时  |
//
// 三种解法的核心判断逻辑完全相同，区别仅在遍历方式（递归/栈/队列）。
//
// ============================================================
// 【易错点】
//
// 1. 终止条件顺序错误:
//    ✗ if (!p || !q) return false;  // 两个都为null时也会返回false!
//      if (!p && !q) return true;   // 这行永远执行不到
//    ✓ if (!p && !q) return true;   // 先判断都为空
//      if (!p || !q) return false;  // 再判断一个为空
//
// 2. 迭代版跳过null不入栈:
//    ✗ if (n1->left) stk.push({n1->left, n2->left}); // 如果n1有左孩子但n2没有呢？
//    ✓ stk.push({n1->left, n2->left}); // null也入栈，在弹出时统一判断
//
// 3. 和101题混淆:
//    ✗ isSameTree(p->left, q->right) // 这是对称树的交叉配对
//    ✓ isSameTree(p->left, q->left)  // 相同树是同侧配对
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: "这个递归的时间空间复杂度？最坏情况是什么？"
//   → 时间 O(n)，每个位置最多访问一次。
//   → 空间 O(h)，h 为树高。最坏情况是链状树 h=n。
//   → 最好情况是完全平衡树 h=log(n)。
//
// Q2: "能不能不用递归实现？"
//   → 用显式栈（解法2）或队列（解法3）。
//   → 核心：把隐式调用栈变成显式数据结构，存储"待比较的节点对"。
//
// Q3: "如果改成判断对称二叉树（101），代码怎么改？"
//   → 只改递归调用的参数配对方式：
//     100: isSame(p->left, q->left) && isSame(p->right, q->right)  [同侧]
//     101: isMirror(p->left, q->right) && isMirror(p->right, q->left) [交叉]
//   → 其余终止条件和判断逻辑完全不变。
//
// Q4: "如果树很大，分布式存储，怎么判断相同？"
//   → 方案1: 各自序列化（前序遍历+null标记），比较字符串。
//   → 方案2: 流式同步遍历，边遍历边比较，不需要完整序列化。
//   → 方案3: 各自计算 Merkle Hash（每个节点hash = hash(val, hash(left), hash(right))），
//     只需比较根节点的hash。
//
// ============================================================
// 【相关题型】
//
// - 101. 对称二叉树 — 复用同样的双参数递归框架。
//   区别：100 同侧配对 (left,left)+(right,right)，
//         101 交叉配对 (left,right)+(right,left)。
//   代码只改一行递归调用。
//
// - 572. 另一棵树的子树 — 对 s 的每个节点调用 isSameTree(s_node, t)。
//   本题是 572 的核心子过程。
//
// - 951. 翻转等价二叉树 — 双参数递归，但递归时有两种选择：
//   不翻转 (left,left)+(right,right) 或 翻转 (left,right)+(right,left)，
//   任一成立即可。
// ============================================================
