/*
 * LeetCode 485: Max Consecutive Ones (最大连续 1 的个数)
 * 难度：Easy | 标签：Array
 *
 * ============================================================
 * 题目描述：
 * 给定一个二进制数组 nums，计算其中最大连续 1 的个数。
 *
 * 约束：
 * - 1 <= nums.length <= 10^5
 * - nums[i] 只能是 0 或 1
 *
 * 示例：
 * 输入：[1,1,0,1,1,1] → 输出：3
 * 输入：[1,0,1,1,0,1] → 输出：2
 * ============================================================
 *
 * 状态变化可视化：
 *
 *  数组:     [1,  1,  0,  1,  1,  1]
 *  count:     1   2   0   1   2   3
 *  maxCount:  1   2   2   2   2   3
 *                                 ↑ 答案
 *
 * ============================================================
 */


/*
 * ============================================================
 * 解法一：计数法（最优解，面试首选）
 * ============================================================
 *
 * 核心思路：
 * - 维护 count（当前连续1的长度）和 maxCount（历史最大）
 * - 遇到 1：count++，更新 maxCount
 * - 遇到 0：count 重置为 0
 *
 * 执行过程：
 *
 *  nums:     [1,  1,  0,  1,  1,  1]
 *             │   │   │   │   │   │
 *  count:     1   2   0   1   2   3
 *  maxCount:  1   2   2   2   2   3
 *
 * 时间复杂度：O(n) — 一次遍历
 * 空间复杂度：O(1) — 只用两个变量
 */
class Solution {
public:
    int findMaxConsecutiveOnes(vector<int>& nums) {
        int maxCount = 0;  // 全局最大连续 1 的长度
        int count = 0;     // 当前连续 1 的长度

        for (int num : nums) {
            if (num == 1) {
                count++;
                maxCount = max(maxCount, count);
            } else {
                count = 0;  // 遇到 0，连续段断裂
            }
        }

        return maxCount;
    }
};


/*
 * ============================================================
 * 解法二：简化写法（三元运算符）
 * ============================================================
 *
 * 逻辑完全等价，代码更紧凑。
 * maxCount 在每步都更新（包括 count=0 时），不影响正确性。
 */
class Solution_Compact {
public:
    int findMaxConsecutiveOnes(vector<int>& nums) {
        int maxCount = 0, count = 0;
        for (int num : nums) {
            count = (num == 1) ? count + 1 : 0;
            maxCount = max(maxCount, count);
        }
        return maxCount;
    }
};


/*
 * ============================================================
 * 解法三：滑动窗口（为 follow-up 铺垫）
 * ============================================================
 *
 * 维护窗口 [left, right]，窗口内全部是 1。
 * 当 nums[right] == 0 时，left 跳到 right + 1。
 *
 * 本题中等价于计数法，但思路可以直接扩展到：
 * - LC 487: 最多翻转一个 0（窗口内最多一个 0）
 * - LC 1004: 最多翻转 k 个 0（窗口内最多 k 个 0）
 *
 * 窗口滑动过程：
 *
 *  nums: [1, 1, 0, 1, 1, 1]
 *         L  R              window=[0,1], len=2
 *            LR             nums[2]=0, L跳到3
 *               L     R     window=[3,5], len=3 → maxLen=3
 *
 * 时间复杂度：O(n)
 * 空间复杂度：O(1)
 */
class Solution_SlidingWindow {
public:
    int findMaxConsecutiveOnes(vector<int>& nums) {
        int maxLen = 0;
        int left = 0;

        for (int right = 0; right < (int)nums.size(); right++) {
            if (nums[right] == 0) {
                left = right + 1;  // 窗口收缩到 right + 1
            }
            maxLen = max(maxLen, right - left + 1);
        }

        return maxLen;
    }
};


/*
 * ============================================================
 * 解法四：分组统计
 * ============================================================
 *
 * 把数组按 0 分割成若干段连续的 1，求最长段的长度。
 *
 * [1,1,0,1,1,1,0,1]
 *  ├──┤  ├──────┤  ├┤
 *   2       3       1    → max = 3
 *
 * 时间复杂度：O(n)
 * 空间复杂度：O(1)
 */
class Solution_Group {
public:
    int findMaxConsecutiveOnes(vector<int>& nums) {
        int maxLen = 0;
        int i = 0, n = nums.size();

        while (i < n) {
            if (nums[i] == 1) {
                int start = i;
                while (i < n && nums[i] == 1) {
                    i++;
                }
                maxLen = max(maxLen, i - start);
            } else {
                i++;
            }
        }

        return maxLen;
    }
};


/*
 * ============================================================
 * 解法五：位运算技巧（趣味解法）
 * ============================================================
 *
 * 思路：将数组看作二进制数，连续 1 的长度可以通过
 *       反复做 n & (n << 1) 来"侵蚀"。
 *
 * 但这要求数组能表示为一个整数，只适用于小数组。
 * 实际不适用本题（数组长度可达 10^5），仅作思维拓展。
 *
 * 例：n = 0b110111
 *   n & (n<<1) = 0b110111 & 0b101110 = 0b100110 (侵蚀1次)
 *   n & (n<<1) = 0b100110 & 0b001100 = 0b000100 (侵蚀2次)
 *   n & (n<<1) = 0b000100 & 0b001000 = 0b000000 (侵蚀3次，变0)
 *   总共侵蚀了 3 次 → 最大连续 1 长度 = 3
 */


/*
 * ============================================================
 * Follow-up 扩展：最多翻转 k 个 0（LC 1004 模板）
 * ============================================================
 *
 * 滑动窗口，窗口内最多 k 个 0。
 * 当 zeros > k 时收缩左边界。
 *
 * k=0 时退化为本题（不翻转任何 0）。
 * k=1 时等价于 LC 487。
 */
class Solution_FollowUp {
public:
    int longestOnes(vector<int>& nums, int k) {
        int maxLen = 0, zeros = 0, left = 0;

        for (int right = 0; right < (int)nums.size(); right++) {
            if (nums[right] == 0) zeros++;

            // 窗口内 0 的个数超过 k，收缩左边界
            while (zeros > k) {
                if (nums[left] == 0) zeros--;
                left++;
            }

            maxLen = max(maxLen, right - left + 1);
        }

        return maxLen;
    }
};


/*
 * ============================================================
 * 常见错误示范
 * ============================================================
 */

/* 错误1: maxCount 只在遇到 0 时更新
 *
 * for (int num : nums) {
 *     if (num == 1) { count++; }
 *     else { maxCount = max(maxCount, count); count = 0; }
 * }
 * return maxCount;
 *
 * 问题：如果数组以 1 结尾 [0,1,1,1]，最后一段 count=3 没有被记录
 * 修正：在循环内 num==1 时就更新 maxCount
 *       或在循环后加 maxCount = max(maxCount, count)
 */

/* 错误2: count 初始化为 1
 *
 * int count = 1;  // 如果第一个元素是 0，count 就不对了
 * 正确: int count = 0;
 */

/* 错误3: 混淆 == 和 = 运算符
 *
 * if (num = 1) { ... }  // 赋值，不是比较！永远为 true
 * 正确: if (num == 1) { ... }
 */


/*
 * ============================================================
 * 复杂度对比
 * ============================================================
 *
 * | 解法        | 时间  | 空间  | 面试推荐 |
 * |------------|-------|-------|---------|
 * | 计数法      | O(n) | O(1) | ⭐⭐⭐  |
 * | 简化写法    | O(n) | O(1) | ⭐⭐⭐  |
 * | 滑动窗口    | O(n) | O(1) | ⭐⭐   |
 * | 分组统计    | O(n) | O(1) | ⭐     |
 *
 * ============================================================
 * 面试追问链
 * ============================================================
 *
 * Q1: 如果可以翻转最多1个0？ → LC 487，滑动窗口(zeros<=1)
 * Q2: 如果可以翻转最多k个0？ → LC 1004，滑动窗口(zeros<=k)
 * Q3: 如果是流式数据？ → 计数法天然支持，O(1)空间
 * Q4: 返回位置而非长度？ → 记录 start 和 bestStart/bestEnd
 * Q5: 与 Kadane's Algorithm 关系？ → 本题是简化版
 * Q6: 如果数组有 0/1/2 三种值？ → 对每种值分别计数
 *
 * ============================================================
 * 相关题目
 * ============================================================
 *
 * 487. Max Consecutive Ones II    —— 翻转一个0
 * 1004. Max Consecutive Ones III  —— 翻转k个0
 *   53. Maximum Subarray          —— Kadane's Algorithm
 *  674. Longest Continuous Increasing Subsequence —— 计数模式
 * 1446. Consecutive Characters    —— 连续相同字符
 *  121. Best Time to Buy and Sell Stock —— 遍历+状态维护
 *
 * ============================================================
 * 总结：解法对比 & 面试要点
 * ============================================================
 *
 * 【解法选择决策树】
 *
 *   不翻转0？
 *    └─ YES → 计数法 O(n), O(1)  ← 面试首选，最简洁
 *
 *   最多翻转1个0？ → LC487 滑动窗口 zeros<=1
 *   最多翻转k个0？ → LC1004 滑动窗口 zeros<=k
 *   流式数据？     → 计数法天然支持，无需修改
 *
 * 【核心易错点】
 * 1. maxCount 必须在遇到 1 时就更新，不能只在遇到 0 时更新
 *    错误场景: [0,1,1,1] — 数组以1结尾时最后一段未被记录
 *    修正: 在 count++ 之后立刻 maxCount = max(maxCount, count)
 * 2. count 初始化为 0 不是 1 — 第一个元素是 0 时 count=1 就错了
 * 3. 滑动窗口解法中 left = right+1 是"硬重置"
 *    区别于 LC1004 的 while(zeros>k) left++ 是"渐进收缩"
 *
 * 【面试追问链 Q1 → Q2 → Q3】
 *
 * Q1: 如果允许翻转最多 1 个 0，最长连续1是多少？(LC 487)
 *   → 滑动窗口，窗口内最多1个0。遇到第二个0时收缩左边界到上一个0之后。
 *     可以用 prevZero 记录上一个0的位置做到 O(1) 更新。
 *
 * Q2: 推广到翻转最多 k 个 0 呢？(LC 1004)
 *   → 滑动窗口经典模板: 维护窗口内0的个数 zeros，
 *     当 zeros > k 时收缩左边界。本题是 k=0 的特例。
 *
 * Q3: 如果输入是流式数据（一次只能看到一个元素），怎么处理？
 *   → 计数法天然支持流式: 每来一个元素更新 count 和 maxCount。
 *     滑动窗口也可以，但需要维护窗口内0的位置（deque存最近k个0的下标）。
 *     k=0 时计数法只需 O(1) 空间，k>0 时需要 O(k) 空间。
 */
