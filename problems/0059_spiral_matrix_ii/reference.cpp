/*
 * LeetCode 59: 螺旋矩阵 II (Spiral Matrix II)
 *
 * 【题目本质】
 * 按顺时针螺旋顺序，把 1~n² 填入 n×n 矩阵。
 * 本质是模拟螺旋行走路径，核心在于如何控制转弯时机。
 *
 * 【解法总览】
 * 解法1: 边界层剥离 — O(n²) / O(n²) — 维护四个边界一圈圈填，面试首选
 * 解法2: 方向模拟   — O(n²) / O(n²) — 方向数组+碰壁转向，更通用
 */

// ============================================================
// 解法1: 边界层剥离 (Layer-by-Layer)
// 时间: O(n²)  空间: O(n²)（结果矩阵本身，额外空间 O(1)）
//
// 【思路】
// 螺旋 = 一圈一圈从外往内填。每一圈由4条边组成：
//   上边(左→右)、右边(上→下)、下边(右→左)、左边(下→上)
// 用 top/bottom/left/right 四个变量维护当前待填区域。
// 每填完一条边，收缩对应边界。循环直到所有格子填满。
//
// n=4 的完整填充过程:
//
//  第1圈 (top=0, bottom=3, left=0, right=3):
//   上边→:  1  2  3  4   → top=1
//   右边↓:           5   → right=2
//                    6
//                    7
//   下边←: 10  9  8      → bottom=2
//   左边↑: 12            → left=1
//          11
//
//  第2圈 (top=1, bottom=2, left=1, right=2):
//   上边→: 13 14         → top=2
//   右边↓:       15      → right=1
//   下边←: 16            → bottom=1
//   左边↑: (top>bottom, 无元素)
//
//  最终矩阵:
//    1  2  3  4
//   12 13 14  5
//   11 16 15  6
//   10  9  8  7
// ============================================================
class Solution1 {
public:
    vector<vector<int>> generateMatrix(int n) {
        vector<vector<int>> matrix(n, vector<int>(n, 0));
        int top = 0, bottom = n - 1;
        int left = 0, right = n - 1;
        int num = 1;

        while (top <= bottom && left <= right) {
            // 上边：从左往右填
            for (int j = left; j <= right; j++)
                matrix[top][j] = num++;
            top++;  // 上边已填完，上边界下移

            // 右边：从上往下填
            for (int i = top; i <= bottom; i++)
                matrix[i][right] = num++;
            right--;  // 右边已填完，右边界左移

            // 下边：从右往左填
            // 对于 n×n 正方形，此时 top <= bottom 一定成立（可不判断）
            // 但加上判断是更安全的写法，也兼容 m×n 的情况
            for (int j = right; j >= left; j--)
                matrix[bottom][j] = num++;
            bottom--;  // 下边已填完，下边界上移

            // 左边：从下往上填
            for (int i = bottom; i >= top; i--)
                matrix[i][left] = num++;
            left++;  // 左边已填完，左边界右移
        }

        return matrix;
    }
};

// ============================================================
// 解法2: 方向模拟 (Direction Simulation)
// 时间: O(n²)  空间: O(n²)（结果矩阵本身，额外空间 O(1)）
//
// 【思路】
// 模拟一个人在矩阵中行走：
//   - 初始位置 (0,0)，初始方向"向右"
//   - 每一步：填入当前数字，计算下一步位置
//   - 如果下一步越界或已填过 → 顺时针右转
//   - 方向顺序: 右(0,1) → 下(1,0) → 左(0,-1) → 上(-1,0)
//
// 这种方法更通用：不需要矩阵是正方形，起点和方向也容易修改。
//
// n=3 模拟过程:
//   (0,0)→填1  (0,1)→填2  (0,2)→填3
//   碰壁!转向↓
//   (1,2)→填4  (2,2)→填5
//   碰壁!转向←
//   (2,1)→填6  (2,0)→填7
//   碰壁!转向↑
//   (1,0)→填8
//   碰壁!转向→
//   (1,1)→填9
//   done!
// ============================================================
class Solution2 {
public:
    vector<vector<int>> generateMatrix(int n) {
        vector<vector<int>> matrix(n, vector<int>(n, 0));

        // 方向数组：右、下、左、上（顺时针顺序）
        int dx[] = {0, 1, 0, -1};
        int dy[] = {1, 0, -1, 0};
        int dir = 0;  // 初始方向：向右

        int x = 0, y = 0;

        for (int num = 1; num <= n * n; num++) {
            // 先填当前位置（不是先移动！）
            matrix[x][y] = num;

            // 计算沿当前方向的下一步
            int nx = x + dx[dir];
            int ny = y + dy[dir];

            // 碰壁判断：越界 or 已填过 → 右转
            if (nx < 0 || nx >= n || ny < 0 || ny >= n || matrix[nx][ny] != 0) {
                dir = (dir + 1) % 4;  // 顺时针右转
                nx = x + dx[dir];
                ny = y + dy[dir];
            }

            // 移动到下一个位置（最后一次循环后 x,y 可能越界，但不会再访问）
            x = nx;
            y = ny;
        }

        return matrix;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 解法1 边界层剥离        | 解法2 方向模拟           |
// |-----------|------------------------|-------------------------|
// | 思维模型   | 一圈一圈，结构化思考     | 模拟走路，直觉化思考      |
// | 代码结构   | 4个for循环，稍长         | 1个for循环，更简洁        |
// | 扩展性     | 适合规则矩形             | 任意形状/起点/方向皆可    |
// | 面试推荐   | ⭐ 首选（逻辑清晰好讲）  | 备选（代码短好写）        |
// | 出错概率   | 边界收缩顺序易错         | 转向判断条件易遗漏        |
//
// ============================================================
// 【易错点】
//
// 1. 边界层剥离法中，遍历和收缩的顺序搞反：
//    ✗ top++; for(j=left; j<=right; j++) matrix[top][j]=num++;
//      → 跳过了第0行！
//    ✓ for(j=left; j<=right; j++) matrix[top][j]=num++; top++;
//      → 先填再收缩
//
// 2. 方向模拟法中，先移动再填数：
//    ✗ x=nx; y=ny; matrix[x][y]=num++;
//      → (0,0) 永远没填，第一步就移到了 (0,1)
//    ✓ matrix[x][y]=num++; ... x=nx; y=ny;
//      → 先填当前位置，再移动到下一个
//
// 3. 方向数组的顺序写错导致不是顺时针：
//    ✗ dx={0,-1,0,1}, dy={1,0,-1,0} → 右、上、左、下（逆时针！）
//    ✓ dx={0,1,0,-1}, dy={1,0,-1,0} → 右、下、左、上（顺时针）
//
// 4. 下边遍历方向写反：
//    ✗ for(j=left; j<=right; j++) matrix[bottom][j]=num++;
//      → 下边应该从右往左！
//    ✓ for(j=right; j>=left; j--) matrix[bottom][j]=num++;
//
// ============================================================
// 【面试追问】
//
// Q1: 这道题和 54 题（螺旋矩阵 I）有什么关系？代码能复用吗？
// A1: 遍历框架完全相同。54 是读（m×n矩阵，需在下边和左边加
//     top<=bottom / left<=right 的判断防止重复读）；
//     59 是写（n×n正方形，天然不会重复）。把读操作换成写操作即可。
//
// Q2: 如果要求逆时针螺旋怎么改？
// A2: 边界层剥离法：四条边的遍历顺序改为 左列↓→下行→→右列↑→上行←。
//     方向模拟法：方向数组改为 下(1,0)→右(0,1)→上(-1,0)→左(0,-1)。
//
// Q3: 如果矩阵是 m×n 的长方形怎么办？
// A3: 边界层剥离法需要在下边遍历前检查 top<=bottom，
//     在左边遍历前检查 left<=right，防止只剩一行/一列时重复遍历。
//     方向模拟法不需要改动，碰壁判断天然适配。
//
// Q4: 能否 O(1) 空间（不算输出）直接计算 matrix[i][j] 的值？
// A4: 可以。对于给定的 (i,j)，先算出它在第几圈 k=min(i, j, n-1-i, n-1-j)，
//     再根据它在该圈的哪条边上计算偏移量。但公式推导复杂，面试中不推荐。
// ============================================================
