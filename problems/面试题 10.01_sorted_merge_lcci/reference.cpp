/*
 * 面试题 10.01: 合并排序的数组 (Sorted Merge LCCI)
 * 同 LeetCode 88: Merge Sorted Array
 *
 * 【题目本质】
 * 两个有序数组 A(有效m个元素, 末尾有n个空位) 和 B(n个元素)，
 * 将 B 合并到 A 中并保持有序。要求原地操作。
 * 核心技巧: 从后往前填充，利用 A 末尾的空位避免覆盖有效数据。
 *
 * 【解法总览】
 * 解法1: 额外数组合并        — O(m+n) / O(m+n) — 新建数组正向归并
 * 解法2: 逆向双指针          — O(m+n) / O(1)   — 从后往前填充 ⭐面试首选
 * 解法3: 直接拼接排序        — O((m+n)log(m+n)) / O(1) — 暴力排序
 */


// ============================================================
// 解法1: 额外数组合并 — 新建数组，正向归并
// 时间: O(m+n)  空间: O(m+n)
//
// 【思路】
// 最直觉的做法: 新建 temp 数组，两个指针从前往后比较，
// 小的先放入 temp，最后拷贝回 A。
//
// 缺点: 需要 O(m+n) 额外空间。
// 面试中能说出这个思路作为起点，然后引出逆向优化。
//
// 示例: A = [1,2,3,0,0,0], m=3, B = [2,5,6], n=3
//   i=0,j=0: 1<2 → temp=[1]
//   i=1,j=0: 2==2 → temp=[1,2]
//   i=2,j=0: 3>2 → temp=[1,2,2]
//   i=2,j=1: 3<5 → temp=[1,2,2,3]
//   i用完, j=1,2: → temp=[1,2,2,3,5,6]
// ============================================================
class Solution1 {
public:
    void merge(vector<int>& A, int m, vector<int>& B, int n) {
        vector<int> temp(m + n);
        int i = 0, j = 0, k = 0;

        // 标准归并: 比较两个指针指向的元素，较小的先放入 temp
        while (i < m && j < n) {
            if (A[i] <= B[j]) {
                temp[k++] = A[i++];
            } else {
                temp[k++] = B[j++];
            }
        }
        // 处理剩余
        while (i < m) temp[k++] = A[i++];
        while (j < n) temp[k++] = B[j++];

        // 拷贝回 A
        for (int p = 0; p < m + n; p++) {
            A[p] = temp[p];
        }
    }
};

// ============================================================
// 解法2: 逆向双指针 — 从后往前填充
// 时间: O(m+n)  空间: O(1)
//
// 【思路】
// 核心洞察: A 末尾有 n 个空位 [m..m+n-1]。
// 如果从后往前填充，先放最大的元素到 A[m+n-1]，
// 就不会覆盖 A 中还没处理的有效元素。
//
// 三指针设计:
//   i = m-1   → A 有效部分的末尾
//   j = n-1   → B 的末尾
//   k = m+n-1 → A 总空间的末尾（写入位置）
//
// 每次比较 A[i] 和 B[j]，较大的放到 A[k]，
// 然后对应指针和 k 都左移。
//
// 为什么 k 永远不会追上 i (不会覆盖)?
//   k 每轮减 1，而 i 最多减 1（也可能不减，当放的是 B[j] 时）。
//   数学上: k - i = (m+n-1) - (m-1) - 已处理A个数 + 已处理B个数 的差 >= 0
//   直觉: k 的移动速度 = i 的移动速度 + j 的移动速度，
//         所以 k 总是领先于 i。
//
// 收尾:
//   B 先用完 (j<0): A 剩余在 A[0..i]，已在正确位置，不需要移动
//   A 先用完 (i<0): B 剩余在 B[0..j]，需要填入 A[0..j]
//
// 手动模拟: A = [1,2,3,0,0,0], m=3, B = [2,5,6], n=3
//   初始: i=2, j=2, k=5
//   step1: A[2]=3 < B[2]=6 → A[5]=6, j=1, k=4  → [1,2,3,0,0,6]
//   step2: A[2]=3 < B[1]=5 → A[4]=5, j=0, k=3  → [1,2,3,0,5,6]
//   step3: A[2]=3 > B[0]=2 → A[3]=3, i=1, k=2  → [1,2,3,3,5,6]
//   step4: A[1]=2 == B[0]=2 → A[2]=2, j=-1, k=1 → [1,2,2,3,5,6]
//   j<0, 结束。A剩余[1,2]位置正确。结果: [1,2,2,3,5,6] ✓
// ============================================================
class Solution2 {
public:
    void merge(vector<int>& A, int m, vector<int>& B, int n) {
        int i = m - 1;      // A 有效部分的末尾
        int j = n - 1;      // B 的末尾
        int k = m + n - 1;  // A 总空间的末尾（写入位置）

        // 从后往前，每次选较大的放入 A[k]
        while (i >= 0 && j >= 0) {
            if (A[i] > B[j]) {
                A[k--] = A[i--];
            } else {
                // A[i] <= B[j] 时放 B[j]
                // 等于时放B保持稳定性（B中的相等元素排在A中的后面）
                A[k--] = B[j--];
            }
        }

        // 收尾: B 中剩余元素填入 A
        // 为什么不需要处理 A 剩余？
        // 因为 A 剩余的元素 A[0..i] 本来就在 A 的前面，位置正确！
        while (j >= 0) {
            A[k--] = B[j--];
        }
    }
};

// ============================================================
// 解法3: 直接拼接排序 — 把B拷贝到A末尾，整体排序
// 时间: O((m+n)log(m+n))  空间: O(log(m+n)) (排序栈空间)
//
// 【思路】
// "偷懒"做法: 无视两个数组已有序的条件，直接拼接后排序。
// 面试中写这个基本等于没有理解题意。
// 唯一价值: 作为 baseline 对比，展示优化的意义。
// ============================================================
class Solution3 {
public:
    void merge(vector<int>& A, int m, vector<int>& B, int n) {
        // 把 B 拷贝到 A 的空位处
        for (int i = 0; i < n; i++) {
            A[m + i] = B[i];
        }
        // 整体排序
        sort(A.begin(), A.end());
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间          | 空间     | 利用有序 | 面试推荐 |
// |-------------|---------------|---------|---------|---------|
// | 额外数组     | O(m+n)       | O(m+n)  | 是      | 说出思路 |
// | 逆向双指针   | O(m+n)       | O(1)    | 是      | ⭐⭐⭐   |
// | 直接排序     | O((m+n)log)  | O(log)  | 否      | ❌       |
//
// 演进关系:
//   解法1: 正向归并需要额外空间（覆盖问题）
//   → 解法2: 逆向归并利用末尾空位，O(1) 空间（核心创新）
//   解法3: 完全不利用有序条件，退化解
//
// 面试策略:
//   1. 先提正向归并思路和覆盖问题（30秒）
//   2. 引出"从后往前"的关键洞察
//   3. 写出解法2，解释三指针的含义
//   4. 提一下"为什么A剩余不需要处理"
//
// ============================================================
// 【易错点】
//
// 1. 忘记处理 B 剩余:
//    ✗ 只有 while(i>=0 && j>=0) 循环，B 可能还有更小的元素
//    ✓ 加 while(j>=0) A[k--] = B[j--]; 收尾
//
// 2. 多此一举处理 A 剩余:
//    while(i>=0) A[k--] = A[i--];
//    这不会出错但浪费时间。A 的剩余已在正确位置。
//
// 3. k 的初始值写错:
//    ✗ int k = m + n;     // 越界! A[m+n] 不存在
//    ✓ int k = m + n - 1; // A 的最后一个位置
//
// 4. 正向合并覆盖数据:
//    ✗ 从前往后填 A → A[0] 被新值覆盖，原值丢失
//    ✓ 从后往前填 A → 利用末尾空位，安全
//
// 5. 比较运算符写反:
//    ✗ if (A[i] < B[j]) A[k--] = A[i--]; // 应该放大的!
//    ✓ if (A[i] > B[j]) A[k--] = A[i--]; // 大的先放到后面
//
// ============================================================
// 【面试追问 Interview Follow-ups】
//
// Q1: 为什么从后往前不会覆盖数据？
// A1: 写指针 k 的移动速度等于 i 和 j 移动速度之和。
//     k 始终 >= i（因为 k-i = j的已处理数 >= 0），
//     所以当 k 写入时，A[k] 要么是空位，要么是已经处理过的元素。
//
// Q2: 如果没有预留空间怎么办？
// A2: 必须使用额外空间，或就地归并（gap merge，时间退化到 O(n log n)）。
//     在面试中说明"预留空间是这个 O(1) 解法的前提"。
//
// Q3: 推广到 K 个有序数组合并？
// A3: 用最小堆 K 路归并: 堆中维护 K 个指针，每次取最小值。
//     时间 O(N log K), N 是总元素数。参考 LC 23。
//
// Q4: 如果是链表呢？
// A4: 链表合并更简单，不存在覆盖问题，正向遍历调整指针即可。
//     参考 LC 21 Merge Two Sorted Lists。
//
// Q5: 这题在归并排序中对应哪个步骤？
// A5: 对应 merge 步骤。归并排序先递归拆分，再 merge 合并。
//     标准归并需要 O(n) 辅助空间。本题利用预留空间实现了 O(1) merge。
//
// 相关题: 88 Merge Sorted Array, 21 Merge Two Sorted Lists,
//         23 Merge k Sorted Lists, 977 Squares of a Sorted Array
// ============================================================
