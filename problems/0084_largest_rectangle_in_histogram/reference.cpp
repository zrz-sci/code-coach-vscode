/*
 * LeetCode 84: 柱状图中最大的矩形 (Largest Rectangle in Histogram)
 *
 * 【题目本质】
 * 对于每根柱子，以它的高度作为矩形高度，向左右尽可能延伸，
 * 求所有柱子中能撑起的最大矩形面积。
 * 核心子问题：快速找到每根柱子左/右第一个比它矮的柱子位置。
 *
 * 【解法总览】
 * 解法1: 暴力枚举         — O(n²) / O(1)   — 对每根柱子线性扫描左右边界
 * 解法2: 单调栈(两次遍历)  — O(n)  / O(n)   — 预处理 left[] 和 right[]
 * 解法3: 单调栈(一次遍历)  — O(n)  / O(n)   — 出栈时直接算面积 + 哨兵技巧 ⭐
 */

// ============================================================
// 解法1: 暴力枚举 — 以每根柱子为高度中心，向左右扩展
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 最直觉的想法：对于每根柱子 i，以 heights[i] 为高度，
// 向左找到第一个比它矮的位置 left，向右找到第一个比它矮的位置 right，
// 面积 = heights[i] * (right - left + 1)。
//
// 瓶颈：每根柱子都要线性扫描，全等高数组退化到 O(n²)。
//
// 示例 [2,1,5,6,2,3]:
//   柱子 i=0, h=2: 左右都不能扩展, 面积 = 2×1 = 2
//   柱子 i=1, h=1: 可以扩展到全部, 面积 = 1×6 = 6
//   柱子 i=2, h=5: 左到2,右到3,    面积 = 5×2 = 10 ★
//   柱子 i=3, h=6: 左右都不能扩展, 面积 = 6×1 = 6
//   柱子 i=4, h=2: 左到2,右到5,    面积 = 2×4 = 8
//   柱子 i=5, h=3: 左右都不能扩展, 面积 = 3×1 = 3
// ============================================================
class Solution1 {
public:
    int largestRectangleArea(vector<int>& heights) {
        int n = heights.size(), maxArea = 0;
        for (int i = 0; i < n; i++) {
            int left = i, right = i;
            // 向左扩展：只要左边柱子 >= 当前高度就继续
            while (left > 0 && heights[left - 1] >= heights[i]) left--;
            // 向右扩展：只要右边柱子 >= 当前高度就继续
            while (right < n - 1 && heights[right + 1] >= heights[i]) right++;
            maxArea = max(maxArea, heights[i] * (right - left + 1));
        }
        return maxArea;
    }
};

// ============================================================
// 解法2: 单调栈（两次遍历预处理 left[] 和 right[]）
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法1的瓶颈：对每根柱子线性扫描找左右第一个更小元素。
// "找左/右第一个更小元素" 是单调递增栈的经典应用。
//
// 维护一个栈底到栈顶严格递增的栈（存下标）：
// - 正向遍历求 left[i]：遇到 i 时弹出所有 >= heights[i] 的，
//   栈顶就是左边第一个 < heights[i] 的位置
// - 反向遍历求 right[i]：同理
//
// 最后 面积[i] = heights[i] * (right[i] - left[i] - 1)
//
// 单调栈求 left[] 过程（以 [2,1,5,6,2,3] 为例）:
//   i=0: 栈空,          left[0]=-1, push 0.  栈:[0]
//   i=1: h[0]=2>=h[1]=1, pop. 栈空, left[1]=-1, push 1.  栈:[1]
//   i=2: h[1]=1<h[2]=5,  left[2]=1,  push 2.  栈:[1,2]
//   i=3: h[2]=5<h[3]=6,  left[3]=2,  push 3.  栈:[1,2,3]
//   i=4: h[3]=6>=2, pop. h[2]=5>=2, pop. h[1]=1<2, left[4]=1, push 4. 栈:[1,4]
//   i=5: h[4]=2<h[5]=3,  left[5]=4,  push 5.  栈:[1,4,5]
//   left[] = [-1, -1, 1, 2, 1, 4]
// ============================================================
class Solution2 {
public:
    int largestRectangleArea(vector<int>& heights) {
        int n = heights.size();
        vector<int> left(n), right(n);
        stack<int> stk;

        // 第一遍：正向遍历，求每根柱子左边第一个比它矮的位置
        for (int i = 0; i < n; i++) {
            while (!stk.empty() && heights[stk.top()] >= heights[i])
                stk.pop();
            // 栈空说明左边没有比它矮的，设为 -1（虚拟左边界）
            left[i] = stk.empty() ? -1 : stk.top();
            stk.push(i);
        }

        // 清栈
        while (!stk.empty()) stk.pop();

        // 第二遍：反向遍历，求每根柱子右边第一个比它矮的位置
        for (int i = n - 1; i >= 0; i--) {
            while (!stk.empty() && heights[stk.top()] >= heights[i])
                stk.pop();
            // 栈空说明右边没有比它矮的，设为 n（虚拟右边界）
            right[i] = stk.empty() ? n : stk.top();
            stk.push(i);
        }

        // 汇总：以每根柱子为高度的最大矩形
        int maxArea = 0;
        for (int i = 0; i < n; i++) {
            // 宽度 = 右边界 - 左边界 - 1（开区间内的柱子数）
            maxArea = max(maxArea, heights[i] * (right[i] - left[i] - 1));
        }
        return maxArea;
    }
};

// ============================================================
// 解法3: 单调栈（一次遍历 + 哨兵技巧）⭐ 面试首选
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 解法2用了两次遍历分别求 left[] 和 right[]。
// 其实在出栈的那一刻，左右边界都已经确定了：
//   - 右边界 = 当前遍历到的下标 i（就是它导致了出栈）
//   - 左边界 = 弹出后的新栈顶（栈中它下面的元素）
// 所以可以在出栈时直接计算面积，不需要额外数组。
//
// 哨兵技巧：
//   - 在数组头部加一个 0：保证栈永远不为空（计算宽度时栈顶有值）
//   - 在数组尾部加一个 0：保证所有柱子最终都会被弹出处理
//
// 完整过程（[2,1,5,6,2,3] → 加哨兵后 [0,2,1,5,6,2,3,0]）:
//
//   i=0, h=0: push 0                        栈: [0]
//   i=1, h=2: 2>0, push 1                   栈: [0,1]
//   i=2, h=1: 1<2 → pop 1
//       弹出高度=2, 宽度=2-0-1=1, 面积=2
//       1≤0? No → push 2                    栈: [0,2]
//   i=3, h=5: 5>1, push 3                   栈: [0,2,3]
//   i=4, h=6: 6>5, push 4                   栈: [0,2,3,4]
//   i=5, h=2: 
//       2<6 → pop 4: h=6, w=5-3-1=1, area=6
//       2<5 → pop 3: h=5, w=5-2-1=2, area=10  ★ 最大
//       2>1? No → push 5                    栈: [0,2,5]
//   i=6, h=3: 3>2, push 6                   栈: [0,2,5,6]
//   i=7, h=0:
//       0<3 → pop 6: h=3, w=7-5-1=1, area=3
//       0<2 → pop 5: h=2, w=7-2-1=4, area=8
//       0<1 → pop 2: h=1, w=7-0-1=6, area=6
//       0≤0? No → push 7                    栈: [0,7]
//
//   答案 = 10 ✓
// ============================================================
class Solution3 {
public:
    int largestRectangleArea(vector<int>& heights) {
        // 加首尾哨兵（高度为0），简化边界处理
        heights.insert(heights.begin(), 0);  // 头部哨兵
        heights.push_back(0);                // 尾部哨兵
        int n = heights.size(), maxArea = 0;
        stack<int> stk;

        for (int i = 0; i < n; i++) {
            // 维护单调递增栈：当前柱子比栈顶矮时，栈顶柱子的右边界确定
            while (!stk.empty() && heights[stk.top()] > heights[i]) {
                int h = heights[stk.top()];  // 被弹出柱子的高度
                stk.pop();
                // 弹出后新栈顶 = 左边界，i = 右边界
                // 宽度是开区间 (stk.top(), i) 内的柱子数
                int w = i - stk.top() - 1;
                maxArea = max(maxArea, h * w);
            }
            stk.push(i);
        }

        // 恢复原数组（移除哨兵）
        heights.erase(heights.begin());
        heights.pop_back();

        return maxArea;
    }
};

// ============================================================
// 解法3 变体: 不修改原数组的写法
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 有些面试官不希望修改输入数组。
// 我们可以不真正 insert 哨兵，而是在逻辑上处理：
//   - 遍历范围 [0, n]，当 i == n 时视为高度 0（尾部哨兵）
//   - 栈空时视为左边界 -1（等效于头部哨兵）
// ============================================================
class Solution3b {
public:
    int largestRectangleArea(vector<int>& heights) {
        int n = heights.size(), maxArea = 0;
        stack<int> stk;

        for (int i = 0; i <= n; i++) {
            // i==n 时当前高度为 0，充当尾部哨兵
            int curH = (i == n) ? 0 : heights[i];
            while (!stk.empty() && heights[stk.top()] > curH) {
                int h = heights[stk.top()];
                stk.pop();
                // 栈空时左边界为 -1，充当头部哨兵
                int w = i - (stk.empty() ? -1 : stk.top()) - 1;
                maxArea = max(maxArea, h * w);
            }
            stk.push(i);
        }
        return maxArea;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 时间   | 空间 | 特点                          |
// |----------|--------|------|-------------------------------|
// | 暴力     | O(n²)  | O(1) | 好理解，大数据 TLE            |
// | 两次遍历 | O(n)   | O(n) | 思路清晰，分步好理解          |
// | 一次遍历 | O(n)   | O(n) | 代码最简洁，面试首选           |
// | 不修改版 | O(n)   | O(n) | 不修改输入，逻辑哨兵           |
//
// 面试推荐路线：
// 1. 先说暴力思路 O(n²)，展示你理解题意
// 2. 说出瓶颈："每根柱子都要线性找边界"
// 3. 引出单调栈，写解法3（一次遍历 + 哨兵）
//
// ============================================================
// 【易错点】
//
// 1. 宽度计算错误：
//    ✗ int w = i - mid;  
//       只算了右半部分，漏了左边能延伸的部分
//    ✓ int w = i - stk.top() - 1;
//       弹出 mid 后，新栈顶才是真正的左边界
//
// 2. 忘记尾部哨兵导致栈中残留：
//    ✗ 只遍历到 n-1，全递增数组 [1,2,3] 时栈中元素没被处理
//    ✓ 尾部加 0（或遍历到 n），确保所有柱子被弹出
//
// 3. while 条件用 >= 还是 >：
//    ✗ 用 >= 时相等高度的柱子也被弹出，某些计算的宽度偏小
//       但因为后面弹出的柱子宽度会更大，取 max 后结果仍正确
//    ✓ 用 > 更直观：相等的柱子留在栈中，最终计算时宽度自动正确
//       两者都能 AC，但 > 的逻辑更清晰
//
// 4. insert(begin, 0) 的 O(n) 开销：
//    ✗ 以为 vector::insert 是 O(1)，实际是 O(n) 整体移动
//    ✓ 总时间仍然是 O(n)，但若在意常数可用 Solution3b 的逻辑哨兵
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么用单调递增栈而不是递减栈？
//     → 我们需要找"左/右第一个更小"的元素。递增栈保证栈顶最大，
//       当新元素比栈顶小时，栈顶的右边界就找到了。
//       如果找"第一个更大"（如739题），则用递减栈。
//
// Q2: 哨兵的作用是什么？不加哨兵怎么处理？
//     → 头部哨兵(高度0)：保证栈不为空，计算宽度时 stk.top() 有值。
//       尾部哨兵(高度0)：保证所有柱子都被弹出。
//       不加哨兵：遍历结束后 while 循环清栈，栈空时左边界设为 -1。
//       见 Solution3b。
//
// Q3: 这道题和 LeetCode 85（最大矩形）的关系？
//     → 85题是 01 矩阵中找最大全1矩形。逐行累加构建柱状图：
//       heights[j] = (matrix[i][j]=='1') ? heights[j]+1 : 0
//       每行调用一次本题算法，复杂度 O(m×n)。
//       本题是85题的核心子程序。
//
// Q4: 每个元素最多被操作几次？为什么总时间 O(n)？
//     → 每个元素入栈一次、出栈最多一次，总共 2n 次操作。
//       虽然有嵌套的 while 循环，但均摊下来每个元素 O(1)。
//       这就是"均摊分析"(amortized analysis)。
// ============================================================
