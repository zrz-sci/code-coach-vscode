/*
 * LeetCode 141: 环形链表 (Linked List Cycle)
 *
 * 【题目本质】
 * 判断链表中是否存在环 —— 即遍历过程中是否会重复访问某个节点。
 *
 * 【解法总览】
 * 解法1: 哈希集合     — O(n) / O(n)  — 最直觉，记录访问过的节点
 * 解法2: 快慢指针     — O(n) / O(1)  — 最优，Floyd判圈算法
 */

// 链表节点定义 (题目已提供，这里仅供参考)
// struct ListNode {
//     int val;
//     ListNode *next;
//     ListNode(int x) : val(x), next(NULL) {}
// };

// ============================================================
// 解法1: 哈希集合 — 记录访问过的节点
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 最朴素的想法：怎么知道走了"回头路"？把每个走过的节点记下来。
// 如果某一步发现当前节点之前记过了，说明绕回来了，有环。
// 如果一路走到 nullptr（链表尾部），说明没环。
//
// 用 unordered_set 存节点指针（不是值！），查找 O(1)。
//
// 指针变化示意:
//   3 → 2 → 0 → -4 ─┐
//       ↑              |
//       └──────────────┘
//
//   visited = {}
//   curr=3:  visited={3}
//   curr=2:  visited={3,2}
//   curr=0:  visited={3,2,0}
//   curr=-4: visited={3,2,0,-4}
//   curr=2:  2 已在 visited 中 → return true!
// ============================================================
class Solution1 {
public:
    bool hasCycle(ListNode *head) {
        unordered_set<ListNode*> visited;
        ListNode* curr = head;
        while (curr != nullptr) {
            // 关键：检查的是指针（地址），不是值
            // 因为不同节点可以有相同的 val
            if (visited.count(curr)) {
                return true;
            }
            visited.insert(curr);
            curr = curr->next;
        }
        // 能走到 nullptr 说明链表有终点，无环
        return false;
    }
};

// ============================================================
// 解法2: 快慢指针 (Floyd 判圈算法) — O(1) 空间
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法1 的瓶颈：需要 O(n) 空间记录所有访问过的节点。
// 
// 物理直觉：操场跑步，一快一慢。
// - 如果跑道是直线（无环），快的人先到终点。
// - 如果跑道是环形（有环），快的人一定会从后面追上慢的人。
//
// 为什么一定能追上？
// 设慢指针进入环时，快指针在环中领先 d 步。
// 每走一步，快指针比慢指针多走 1 步 → 距离缩小 1。
// 距离变化：d, d-1, d-2, ..., 2, 1, 0 → 一定会相遇。
//
// 无环示例:
//   1 → 2 → 3 → 4 → NULL
//   Step0: s=1, f=1
//   Step1: s=2, f=3
//   Step2: s=3, f=NULL → fast 到终点，无环
//
// 有环示例:
//   3 → 2 → 0 → -4 ─┐
//       ↑              |
//       └──────────────┘
//   (环: 2 → 0 → -4 → 2)
//
//   Step0: s=3,  f=3    (起点)
//   Step1: s=2,  f=0    (slow走1步, fast走2步)
//   Step2: s=0,  f=2    (环内追赶)
//   Step3: s=-4, f=-4   ← 相遇! return true
// ============================================================
class Solution2 {
public:
    bool hasCycle(ListNode *head) {
        ListNode* slow = head;
        ListNode* fast = head;
        
        // 循环条件：fast 和 fast->next 都不为空
        // 为什么要检查 fast->next？因为 fast 每次走两步，
        // 如果 fast->next 为空，fast->next->next 就会空指针访问
        while (fast != nullptr && fast->next != nullptr) {
            slow = slow->next;        // 慢指针走 1 步
            fast = fast->next->next;  // 快指针走 2 步
            
            // 为什么先移动再判断？
            // 初始时 slow == fast == head，如果先判断会立刻误返回 true
            if (slow == fast) {
                return true;  // 快慢指针相遇 → 链表有环
            }
        }
        
        // fast 走到了 nullptr → 链表有终点 → 无环
        return false;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度     | 解法1(哈希集合) | 解法2(快慢指针) |
// |----------|-----------------|-----------------|
// | 时间     | O(n)            | O(n)            |
// | 空间     | O(n)            | O(1) ✅         |
// | 思路难度 | 直觉简单        | 需理解追赶原理  |
// | 适用场景 | 通用            | 面试首选        |
//
// 面试策略：先说哈希集合方案展示理解，然后主动优化到快慢指针。
//
// 【易错点】
//
// 1. 先判断再移动 → 误判
//    ✗: while (...) { if (slow==fast) return true; slow=...; fast=...; }
//    ✓: while (...) { slow=...; fast=...; if (slow==fast) return true; }
//    原因：初始时 slow==fast==head，先判断会立刻返回 true
//
// 2. 循环条件遗漏 fast->next 检查 → 空指针崩溃
//    ✗: while (fast != nullptr) { fast = fast->next->next; }
//    ✓: while (fast != nullptr && fast->next != nullptr)
//    原因：fast 走两步，中间节点(fast->next)也必须存在
//
// 3. 用 val 比较代替指针比较 → 逻辑错误
//    ✗: if (slow->val == fast->val) 
//    ✓: if (slow == fast)
//    原因：不同节点可以有相同的值，只有地址能唯一标识节点
//
// 【面试追问 — 递进链】
//
// Q1: 为什么快指针走2步、慢指针走1步一定能在环中相遇？
//     → 进入环后每步距离-1，从d递减到0，不会跳过。
//
// Q2: 如何找到环的入口节点？(LeetCode 142)
//     → 相遇后，一个指针回 head，一个留原地，各走1步，
//       再次相遇即入口。数学证明: a = c (头到入口 = 相遇点到入口)。
//
// Q3: 快指针走3步行不行？
//     → 可以但不推荐。每步距离缩小2，若环长为偶数且初始距离为奇数，
//       会跳过0需要多绕几圈，不如2:1简洁。
//
