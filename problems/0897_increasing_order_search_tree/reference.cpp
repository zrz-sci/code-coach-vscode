/*
 * LeetCode 897: Increasing Order Search Tree (递增顺序搜索树)
 *
 * 【题目本质】
 * 对 BST 做中序遍历（天然递增），然后把所有节点串成一条只有
 * right 指针的链。核心：在遍历过程中"边走边接"。
 *
 * 【解法总览】
 * 解法1: 中序遍历收集+重建    — O(n) / O(n)   — 最直觉，两遍扫描
 * 解法2: 递归边走边接(成员变量) — O(n) / O(h)  — 面试首选，一遍搞定
 * 解法3: 迭代栈中序遍历       — O(n) / O(h)   — 等价写法，适合不喜欢递归
 */

// ============================================================
// 解法1: 中序遍历收集 + 重建
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 最朴素的想法：BST 的中序遍历就是递增序列。
// 先把所有节点按中序收集到数组里，然后遍历数组把它们串成链。
//
// 示例: root = [5, 3, 6, 2, 4, null, 8, 1, null, null, null, 7, 9]
//   中序收集: [1, 2, 3, 4, 5, 6, 7, 8, 9]
//   重建: 1 → 2 → 3 → 4 → 5 → 6 → 7 → 8 → 9
//         每个节点 left=null, right=下一个
//
// 注意：必须清空每个节点的 left 指针！
//   否则原始的左子树指针还在，会形成环或多余子树
// ============================================================
class Solution1 {
public:
    TreeNode* increasingBST(TreeNode* root) {
        // 第一步：中序遍历，收集所有节点到数组
        vector<TreeNode*> nodes;
        inorder(root, nodes);

        // 第二步：用 dummy 头节点简化边界处理
        TreeNode dummy(0);
        TreeNode* cur = &dummy;

        for (TreeNode* node : nodes) {
            node->left = nullptr;   // 断开左子树！
            cur->right = node;      // 接到链尾
            cur = node;             // 移动链尾
        }
        // 最后一个节点的 right 也要清空（可能还指向原始右子节点）
        cur->right = nullptr;

        return dummy.right;
    }

    void inorder(TreeNode* node, vector<TreeNode*>& nodes) {
        if (!node) return;
        inorder(node->left, nodes);
        nodes.push_back(node);        // 中序位置：左 → 当前 → 右
        inorder(node->right, nodes);
    }
};

// ============================================================
// 解法2: 递归边走边接（成员变量 cur） — 面试首选 ⭐
// 时间: O(n)  空间: O(h)  h=树高
//
// 【思路】
// 解法1的两遍扫描可以合并为一遍。
// 在中序遍历的"访问"阶段，直接把当前节点接到链尾。
//
// 做法：
//   1. 创建 dummy 节点，cur 指向 dummy
//   2. 中序遍历，每到"访问当前节点"时：
//      a. node->left = nullptr  （清空左指针）
//      b. cur->right = node     （接到链尾）
//      c. cur = node            （移动链尾）
//   3. 返回 dummy->right
//
// 为什么用成员变量 cur？
//   递归过程中，不同层级的函数调用都需要共享同一个"链尾"指针。
//   如果把 cur 作为参数传递（用引用/指针），也可以，但成员变量更简洁。
//
// 示例过程:
//   root = [5, 1, 7]
//
//   DFS 过程：
//     inorder(5)
//       inorder(1)
//         inorder(null) → return
//         访问1: 1->left=null, cur->right=1, cur=1
//         inorder(null) → return
//       访问5: 5->left=null, cur->right=5, cur=5
//       inorder(7)
//         inorder(null) → return
//         访问7: 7->left=null, cur->right=7, cur=7
//         inorder(null) → return
//
//   结果: dummy → 1 → 5 → 7 ✓
// ============================================================
class Solution2 {
public:
    TreeNode* cur;  // 当前链尾指针，在递归中共享

    TreeNode* increasingBST(TreeNode* root) {
        TreeNode dummy(0);
        cur = &dummy;
        inorder(root);
        return dummy.right;
    }

    void inorder(TreeNode* node) {
        if (!node) return;

        // 先递归左子树（中序遍历的"左"）
        inorder(node->left);

        // 中序位置：访问当前节点 —— 接到链尾
        node->left = nullptr;   // 断开左子树
        cur->right = node;      // 接到链尾
        cur = node;             // 移动链尾指针

        // 再递归右子树（中序遍历的"右"）
        inorder(node->right);
    }
};

// ============================================================
// 解法3: 迭代栈中序遍历 — 显式栈版本
// 时间: O(n)  空间: O(h)
//
// 【思路】
// 用显式栈模拟中序遍历，避免递归。
// 迭代中序遍历的标准模板：
//   1. 一路向左，全部压栈
//   2. 弹出栈顶（当前最小未处理节点）
//   3. 处理该节点（接到链尾）
//   4. 转向右子树，回到步骤1
//
// 这种写法在树极深时（退化为链表）不会栈溢出，
// 因为用的是堆上的 stack 而不是递归调用栈。
//
// 示例过程 (root = [5, 3, 6, 2, 4]):
//   5 → 3 → 2 → 入栈 [5, 3, 2], 2无左孩子
//   弹出2: 接链, 2无右孩子
//   弹出3: 接链, 3有右孩子4
//   4 → 入栈 [5, 4], 4无左孩子
//   弹出4: 接链, 4无右孩子
//   弹出5: 接链, 5有右孩子6
//   6 → 入栈 [6], 6无左孩子
//   弹出6: 接链, 6无右孩子
//   栈空，结束
//   链: 2 → 3 → 4 → 5 → 6 ✓
// ============================================================
class Solution3 {
public:
    TreeNode* increasingBST(TreeNode* root) {
        TreeNode dummy(0);
        TreeNode* cur = &dummy;

        stack<TreeNode*> stk;
        TreeNode* node = root;

        while (node || !stk.empty()) {
            // 一路向左，全部压栈
            while (node) {
                stk.push(node);
                node = node->left;
            }

            // 弹出栈顶 = 当前中序最小未处理节点
            node = stk.top();
            stk.pop();

            // 接到链尾
            node->left = nullptr;
            cur->right = node;
            cur = node;

            // 转向右子树
            node = node->right;
        }

        // 确保最后一个节点的 right 是 null
        // （实际上，如果原始最大节点没有右子树，它本身就是 null）

        return dummy.right;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间  | 空间   | 优势                          | 劣势                      |
// |-------------|-------|--------|------------------------------|--------------------------|
// | 收集+重建    | O(n)  | O(n)   | 逻辑最直观                     | 额外 O(n) 数组           |
// | 递归边走边接  | O(n)  | O(h)   | 代码最简洁，一遍搞定            | 深树可能栈溢出             |
// | 迭代栈       | O(n)  | O(h)   | 不会递归栈溢出                  | 模板代码稍多              |
//
// h = 树高，平衡树 h = O(log n)，退化树 h = O(n)
// 面试选择：直接写解法2（递归），解法3 作为 follow-up 备选。
//
// ============================================================
// 【易错点】
//
// 1. 忘记清空 left 指针:
//    ✗ 只做 cur->right = node
//    ✓ 必须同时做 node->left = nullptr
//    否则原始左子树指针保留，输出有多余结构
//
// 2. cur 指针初始化错误:
//    ✗ cur = root → 中序第一个节点没地方接
//    ✓ 创建 dummy 节点，cur = &dummy，返回 dummy->right
//
// 3. 试图用返回值传递重建结果:
//    ✗ 让递归函数返回子树的头 → 逻辑极其混乱
//    ✓ 用成员变量 cur 作为共享的链尾指针
//
// 4. 迭代版忘记 node = node->right:
//    ✗ 弹栈后直接继续外层 while → 死循环
//    ✓ 处理完当前节点后，node = node->right 让下轮处理右子树
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 为什么 BST 的中序遍历是递增的？
//     BST 性质：左 < 根 < 右。中序遍历：左 → 根 → 右。
//     所以中序结果自然从小到大。
//
// Q2: 能否用 O(1) 空间？
//     Morris 遍历理论上可以，但它本身就是通过临时修改 left/right
//     指针实现的，和本题的目标（修改指针结构）会冲突，易出错。
//     面试中递归 O(h) 就是最优的实践选择。
//
// Q3: 如果不是 BST 而是普通二叉树，要求按前序展开呢？
//     同样的 dummy + cur 思路。前序展开 = LeetCode 114。
//     区别：前序展开需要先保存 right（因为访问当前节点时
//     会覆盖 cur->right），而中序不需要。
//
