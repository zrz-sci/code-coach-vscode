/*
 * LeetCode 817: Linked List Components (链表组件)
 *
 * 【题目本质】
 * 给定链表和一个值的子集 nums，统计 nums 中的值在链表上形成了几个
 * 连续段（连通分量）。链表是线性的，"连通"即物理相邻且都在 nums 中。
 *
 * 【解法总览】
 * 解法1: 哈希集合 + 段起点计数  — O(n) / O(m) — 面试首选
 * 解法2: 哈希集合 + 段结束计数  — O(n) / O(m) — 更简洁的变体
 */

// ============================================================
// 解法1: 哈希集合 + 段起点计数
// 时间: O(n + m)  空间: O(m)   其中 n=链表长度, m=nums 大小
//
// 【思路】
// 链表是线性结构，连通分量 = 连续段。
// 遍历链表，用 inComponent 标记是否正在某段内。
// 每当从"不在集合"进入"在集合"，就是一个新段的起点。
//
// 示例: head = [0,1,2,3,4], nums = [0,3,1,4]
// 集合 = {0, 1, 3, 4}
//
// 遍历:
//   0 → 在集合, inComponent=false → 新段, count=1, inComponent=true
//   1 → 在集合, inComponent=true  → 同段, 不加
//   2 → 不在集合              → inComponent=false
//   3 → 在集合, inComponent=false → 新段, count=2, inComponent=true
//   4 → 在集合, inComponent=true  → 同段, 不加
// 结果: 2
// ============================================================
class Solution1 {
public:
    int numComponents(ListNode* head, vector<int>& nums) {
        // 将 nums 放入哈希集合，实现 O(1) 查找
        unordered_set<int> setG(nums.begin(), nums.end());

        int count = 0;
        bool inComponent = false;

        ListNode* curr = head;
        while (curr) {
            if (setG.count(curr->val)) {
                // 当前节点在集合中
                if (!inComponent) {
                    // 之前不在段中 → 这是新段的起点
                    count++;
                    inComponent = true;
                }
                // 之前已在段中 → 继续同一段，不做操作
            } else {
                // 当前节点不在集合中 → 段中断
                inComponent = false;
            }
            curr = curr->next;
        }

        return count;
    }
};

// ============================================================
// 解法2: 哈希集合 + 段结束计数
// 时间: O(n + m)  空间: O(m)
//
// 【思路】
// 换个角度：不看段起点，看段结束点。
// 当前节点在集合中，且 (下一个节点不在集合中 或 没有下一个节点) 时，
// 说明一个连续段在此结束，计数+1。
//
// 段起点数 == 段结束点数，两种方式等价。
//
// 这种写法更简洁，不需要 inComponent 标记。
//
// 示例: head = [0,1,2,3], nums = [0,1,3]
// 集合 = {0, 1, 3}
//
// 遍历:
//   0 → 在集合, next=1 在集合 → 不是结束点
//   1 → 在集合, next=2 不在集合 → 段结束, count=1
//   2 → 不在集合 → 跳过
//   3 → 在集合, next=null → 段结束, count=2
// 结果: 2
// ============================================================
class Solution2 {
public:
    int numComponents(ListNode* head, vector<int>& nums) {
        unordered_set<int> setG(nums.begin(), nums.end());
        int count = 0;

        ListNode* curr = head;
        while (curr) {
            // 当前在集合中，且是段的结束点
            if (setG.count(curr->val)) {
                // 下一个不在集合中 或 链表到头了 → 段结束
                if (!curr->next || !setG.count(curr->next->val)) {
                    count++;
                }
            }
            curr = curr->next;
        }

        return count;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间     | 空间  | 代码量 | 思路              |
// |-------------|---------|-------|--------|------------------|
// | 段起点计数   | O(n+m)  | O(m)  | 中等    | 维护 inComponent  |
// | 段结束计数   | O(n+m)  | O(m)  | 更短    | 看当前+下一个     |
//
// 面试选择：两种都行，段结束计数更简洁。关键是看到
// "链表是线性的，连通分量 = 连续段" 这个核心洞察。
//
// ============================================================
// 【易错点】
//
// 1. 线性查找 nums:
//    x for(auto& x : nums) if(x == val) ...
//    -> 每次 O(m)，总体 O(n*m)
//    v 用 unordered_set，每次 O(1)
//
// 2. 忘记处理链表末尾的段:
//    如果用"跳变检测"(当前在集合中 且 下一个不在集合中)，
//    必须也处理 next == nullptr 的情况。
//    解法2 中 !curr->next 条件覆盖了这个边界。
//
// 3. 误解"连通"定义:
//    x 值相邻(差为1)即连通
//    v 链表中物理相邻 且 都在 nums 中
//
// 4. 修改原始链表:
//    x 为了方便，删除不在集合中的节点
//    v 只读遍历即可，不要修改链表
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 时间空间复杂度？
//     时间 O(n+m): 建集合 O(m) + 遍历链表 O(n)
//     空间 O(m): 哈希集合
//
// Q2: nums 很大时(接近 n)，能优化空间吗？
//     可以用 bitset<10001> 代替哈希集合，因为 Node.val < n <= 10^4
//     空间常数更小，查找也更快(直接寻址 vs 哈希)
//
// Q3: 如果要返回每个连通分量的内容(不只是个数)呢？
//     维护一个临时 vector，遍历时把连续段内的值收集起来，
//     段结束时把该 vector 推入结果列表并清空。
//
// Q4: 如果链表有环呢？
//     需要用快慢指针检测环，或用 visited 集合记录已访问节点。
//     本题保证无环。
//
