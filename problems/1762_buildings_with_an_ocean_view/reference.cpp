/*
 * LeetCode 1762: Buildings With an Ocean View (能看到海景的建筑物)
 *
 * 【题目本质】
 * 找出所有"右边没有任何 >= 自身高度的建筑"的位置。
 * 等价于：从右往左看，找出所有"后缀严格最大值"出现的位置。
 *
 * 【解法总览】
 * 解法1: 暴力        — O(n²) / O(1)  — 最直觉，面试说思路即可
 * 解法2: 后缀最大值   — O(n) / O(1)  — 面试首选，代码最简
 * 解法3: 单调递减栈   — O(n) / O(n)  — 展示单调栈思维
 */

// ============================================================
// 解法1: 暴力 — 对每栋建筑往右扫描检查
// 时间: O(n²)  空间: O(1) (不算结果数组)
//
// 【思路】
// 最直觉的想法：对每栋建筑 i，检查 i+1 到 n-1 是否有 >= heights[i] 的。
// 如果没有，说明能看到海。
// 瓶颈：每栋建筑都往右扫一遍，重复计算"右边最大值"。
// ============================================================
class Solution1 {
public:
    vector<int> findBuildings(vector<int>& heights) {
        int n = heights.size();
        vector<int> result;
        for (int i = 0; i < n; i++) {
            bool canSee = true;
            for (int j = i + 1; j < n; j++) {
                // 注意 >=：等高也挡住，题目要求右边都"严格矮"
                if (heights[j] >= heights[i]) {
                    canSee = false;
                    break;  // 已经被挡住，无需继续
                }
            }
            if (canSee) result.push_back(i);
        }
        return result;
    }
};

// ============================================================
// 解法2: 从右往左 + 后缀最大值 — 面试首选 ⭐
// 时间: O(n)  空间: O(1) (不算结果数组)
//
// 【思路】
// 解法1的瓶颈：每栋建筑都要扫右边找最大值，但其实
// maxRight[i] = max(heights[i+1], maxRight[i+1])
// 这是一个从右往左的递推关系！
//
// 从右往左遍历，维护一个变量 maxRight 记录"当前位置右边
// 所有建筑的最大高度"。建筑 i 能看到海 ⟺ heights[i] > maxRight。
//
// 示例: heights = [4, 2, 3, 1]
//
//   idx:  0   1   2   3
//        ┌─┐
//        │4│     ┌─┐
//        │ │ ┌─┐ │3│ ┌─┐
//        │ │ │2│ │ │ │1│
//        └─┘ └─┘ └─┘ └─┘ ~~~🌊
//
//   从右往左:
//   i=3: maxRight=0, 1 > 0 ✓ → 加入, maxRight=1
//   i=2: maxRight=1, 3 > 1 ✓ → 加入, maxRight=3
//   i=1: maxRight=3, 2 > 3 ✗ → 被挡住
//   i=0: maxRight=3, 4 > 3 ✓ → 加入, maxRight=4
//   结果(反转前): [3,2,0] → 反转: [0,2,3]
// ============================================================
class Solution2 {
public:
    vector<int> findBuildings(vector<int>& heights) {
        int n = heights.size();
        vector<int> result;
        // maxRight = 0: 最右边建筑右侧没有建筑，最大高度为 0
        // 因为 heights[i] >= 1，所以最后一栋一定能看到海
        int maxRight = 0;
        
        for (int i = n - 1; i >= 0; i--) {
            if (heights[i] > maxRight) {
                result.push_back(i);
                maxRight = heights[i];
            }
        }
        
        // 结果是倒序收集的，反转成题目要求的升序
        reverse(result.begin(), result.end());
        return result;
    }
};

// ============================================================
// 解法3: 单调递减栈 — 从左往右维护递减栈
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 换个角度：从左往右遍历，栈中维护"目前可能看到海的建筑下标"。
// 栈从底到顶保持高度严格递减。
// 
// 核心逻辑：
// - 如果新建筑 >= 栈顶建筑，栈顶被挡住了，弹出
// - 新建筑入栈（它目前可能看到海）
// 遍历结束后栈里的就是答案。
//
// 为什么正确？栈中的建筑满足：
// 1. 高度严格递减（被更高的挡住的已经弹出了）
// 2. 栈中相邻两个建筑之间没有更高的（否则会被弹出）
// 所以栈中每栋建筑到海洋之间都没有 >= 自身高度的建筑。
//
// 示例: heights = [4, 2, 3, 1]
//
//   i=0: h=4, 栈空        → push 0    栈: [0]     (高度: 4)
//   i=1: h=2, 2 < 4       → push 1    栈: [0,1]   (高度: 4,2)
//   i=2: h=3, 3 >= 2      → pop 1     栈: [0]     (建筑1被3挡住)
//        h=3, 3 < 4       → push 2    栈: [0,2]   (高度: 4,3)
//   i=3: h=1, 1 < 3       → push 3    栈: [0,2,3] (高度: 4,3,1)
//
//   答案: [0, 2, 3] ✓
// ============================================================
class Solution3 {
public:
    vector<int> findBuildings(vector<int>& heights) {
        int n = heights.size();
        stack<int> stk;  // 存下标，栈底到栈顶高度严格递减
        
        for (int i = 0; i < n; i++) {
            // 弹出条件 <=：等高也挡住（题目要求"严格矮"才能看到海）
            while (!stk.empty() && heights[stk.top()] <= heights[i]) {
                stk.pop();
            }
            stk.push(i);
        }
        
        // 从栈中取出结果（栈底→栈顶是升序下标，但 stack 只能从顶访问）
        vector<int> result(stk.size());
        for (int i = result.size() - 1; i >= 0; i--) {
            result[i] = stk.top();
            stk.pop();
        }
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法             | 时间  | 空间 | 核心技巧        | 面试    |
// |------------------|-------|------|-----------------|---------|
// | 暴力             | O(n²) | O(1) | 无              | 说思路  |
// | 后缀最大值       | O(n)  | O(1) | 从右往左+变量   | ⭐首选  |
// | 单调递减栈       | O(n)  | O(n) | 单调栈          | 加分项  |
//
// 解法2 vs 解法3:
// - 解法2 更简洁，O(1) 空间，面试优先写这个
// - 解法3 展示"单调栈"这个通用模式，如果面试官追问单调栈可以给出
// - 两者本质相同：都在维护一个从右往左看的严格递减序列
//
// 【易错点】
//
// 1. 相同高度判断：
//    ✗ heights[j] > heights[i]  → [2,2,2,2] 会错误输出 [0,1,2,3]
//    ✓ heights[j] >= heights[i] → [2,2,2,2] 正确输出 [3]
//    原因：题目说"右边都比它矮"，等高不算矮
//
// 2. 后缀最大值初始化：
//    ✗ int maxRight = heights[n-1]; 然后从 i=n-2 开始
//      → 忘了把 n-1 自己加入结果
//    ✓ int maxRight = 0; 从 i=n-1 开始
//      → 最后一栋自然满足 heights[n-1] > 0
//
// 3. 结果顺序：
//    ✗ 从右往左遍历收集后直接返回 → 结果是降序的
//    ✓ 最后 reverse 一下 → 升序
//
// 4. 单调栈弹出条件：
//    ✗ heights[stk.top()] < heights[i]  → 等高的没弹出，多算了
//    ✓ heights[stk.top()] <= heights[i] → 等高也弹出
//
// 【面试追问】
//
// Q1: 暴力 O(n²) 的瓶颈是什么？怎么降到 O(n)？
// A1: 瓶颈在于每栋建筑都要扫描右边找最大值。利用递推关系
//     maxRight[i] = max(heights[i+1], maxRight[i+1])，从右往左
//     一遍扫描用一个变量就能维护。
//
// Q2: 能否不用 reverse？
// A2: 可以。用 deque 代替 vector，从右往左遍历时 push_front。
//     或者先数一遍有多少个能看到海的，预分配数组后从右往左填入。
//
// Q3: 如果数组会动态更新（某栋建筑高度变化），如何高效维护结果？
// A3: 可以用线段树维护区间最大值。查询某栋建筑能否看到海等价于
//     查询 [i+1, n-1] 区间的最大值是否 < heights[i]。
//     更新和查询都是 O(log n)。
//
// Q4: 如果海洋在左边而不是右边呢？
// A4: 完全对称：从左往右遍历，维护前缀最大值即可。代码改动：
//     遍历方向 for(int i=0;i<n;i++) 且维护 maxLeft。
// ============================================================
