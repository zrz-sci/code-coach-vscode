/*
 * LeetCode 544: 输出比赛匹配对 (Output Contest Matches)
 *
 * 【题目本质】
 * 模拟 NBA 季后赛配对：每轮最强配最弱，首尾配对合并成字符串，
 * 直到只剩一组。
 *
 * 【解法总览】
 * 解法1: 迭代模拟 — O(n log n) / O(n) — ⭐ 面试首选
 * 解法2: 递归模拟 — O(n log n) / O(n log n)
 *
 *  n = 8 的配对过程:
 *  初始: ["1","2","3","4","5","6","7","8"]
 *  第1轮: ["(1,8)","(2,7)","(3,6)","(4,5)"]
 *  第2轮: ["((1,8),(4,5))","((2,7),(3,6))"]
 *  第3轮: ["(((1,8),(4,5)),((2,7),(3,6)))"]
 */

// ============================================================
// 解法1: 迭代模拟 ⭐ 面试首选
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 初始化字符串数组 ["1","2",...,"n"]。
// 每轮对 teams[i] 和 teams[size-1-i] 配对，
// 生成新数组，长度减半。共 log2(n) 轮。
// ============================================================
class Solution1 {
public:
    string findContestMatch(int n) {
        vector<string> teams(n);
        for (int i = 0; i < n; i++) {
            teams[i] = to_string(i + 1);
        }

        while (teams.size() > 1) {
            int size = teams.size();
            vector<string> next(size / 2);
            for (int i = 0; i < size / 2; i++) {
                // 第 i 强 vs 第 (size-1-i) 强
                next[i] = "(" + teams[i] + "," + teams[size - 1 - i] + ")";
            }
            teams = next;
        }

        return teams[0];
    }
};

// ============================================================
// 解法2: 原地修改（空间优化迭代）
// 时间: O(n log n)  空间: O(1) 额外（复用原数组）
//
// 【思路】
// 不创建新数组，直接在原数组前半部分覆盖。
// 每轮 teams[i] = "(" + teams[i] + "," + teams[len-1-i] + ")"
// 然后有效长度减半。
//
// 注意遍历方向：从前往后，因为 teams[size-1-i] 还未被覆盖。
// ============================================================
class Solution2 {
public:
    string findContestMatch(int n) {
        vector<string> teams(n);
        for (int i = 0; i < n; i++) {
            teams[i] = to_string(i + 1);
        }

        int len = n;
        while (len > 1) {
            for (int i = 0; i < len / 2; i++) {
                // i < len/2 < len-1-i，所以 teams[len-1-i] 尚未被覆盖
                teams[i] = "(" + teams[i] + "," + teams[len - 1 - i] + ")";
            }
            len /= 2;
        }

        return teams[0];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间       | 空间      | 特点                    |
// |-----------|-----------|-----------|------------------------|
// | 迭代模拟   | O(n log n) | O(n)     | ⭐ 清晰直观，面试首选     |
// | 原地修改   | O(n log n) | O(1) 额外 | 空间最优，代码稍tricky   |
//
// ============================================================
// 【易错点】
//
// 1. ✗ 相邻配对 teams[i] 和 teams[i+1]
//    ✓ 首尾配对 teams[i] 和 teams[size-1-i]
//
// 2. ✗ 原地修改时从后往前遍历，导致 teams[len-1-i] 被覆盖
//    ✓ 从前往后遍历，因为 i < len/2 <= len-1-i
//
// 3. ✗ 忘记格式 "(a,b)"，少写括号或逗号
//    ✓ 严格拼接 "(" + a + "," + b + ")"
//
// ============================================================
// 【面试追问】
//
// Q1: 时间复杂度？
// → log2(n) 轮，每轮处理 n/2^k 个字符串。
//   字符串长度递增，总字符操作 O(n log n)。
//
// Q2: 原地修改时为什么从前往后遍历是安全的？
// → 因为 i < len/2，而被读取的 len-1-i >= len/2，
//   两个索引不会冲突。
//
// Q3: n 不是 2 的幂怎么办？
// → 实际赛制中强队轮空(bye)。在首轮只配对后段队伍，
//   前段直接晋级。
