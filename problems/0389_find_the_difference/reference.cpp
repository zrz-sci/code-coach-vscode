// ============================================================
// LeetCode 389. Find the Difference (找不同)
// 难度: Easy | 标签: Bit Manipulation, Hash Table, String, Sorting
// ============================================================

// ------------------------------------------------------------
// 解法1: 异或 XOR (最优雅)
// 时间 O(n), 空间 O(1)
//
// 思考过程:
//   1. 异或性质: a ^ a = 0, a ^ 0 = a, 交换律+结合律
//   2. s 和 t 的所有字符异或在一起
//   3. 成对出现的字符抵消为 0, 剩余就是多出的那一个
//   4. 不存在溢出风险 (char XOR char 还是 char)
//
// 示例: s="abcd", t="abcde"
//   res = a^b^c^d ^ a^b^c^d^e
//       = (a^a)^(b^b)^(c^c)^(d^d)^e
//       = 0 ^ e = 'e'
// ------------------------------------------------------------
class Solution1 {
public:
    char findTheDifference(string s, string t) {
        char res = 0;                    // 0 是异或的幺元
        for (char c : s) res ^= c;      // 异或 s 的所有字符
        for (char c : t) res ^= c;      // 异或 t 的所有字符
        return res;                      // 成对抵消, 剩余就是答案
    }
};

// ------------------------------------------------------------
// 解法2: 求和差值
// 时间 O(n), 空间 O(1)
//
// 思考过程:
//   1. t 比 s 多一个字符
//   2. sum(t) - sum(s) = 多出字符的 ASCII 值
//   3. 用 int 存和防止 char 溢出
//      (最坏: 1001 * 122 = 122122, 远小于 INT_MAX)
// ------------------------------------------------------------
class Solution2 {
public:
    char findTheDifference(string s, string t) {
        int sum = 0;
        for (char c : t) sum += c;   // t 的 ASCII 总和
        for (char c : s) sum -= c;   // 减去 s 的 ASCII 总和
        return (char)sum;             // 差值 = 多出字符的 ASCII
    }
};

// ------------------------------------------------------------
// 解法3: 哈希计数 (通用性最强)
// 时间 O(n), 空间 O(1) (26个字母 = 常数)
//
// 思考过程:
//   1. 用 count[26] 统计 s 中每个字符出现次数
//   2. 遍历 t, 每个字符 count--
//   3. 当 count < 0, 说明该字符是多出的
//   4. 可以提前返回, 不需要遍历完
// ------------------------------------------------------------
class Solution3 {
public:
    char findTheDifference(string s, string t) {
        int count[26] = {};

        // 统计 s 的字符频率
        for (char c : s)
            count[c - 'a']++;

        // 遍历 t, 找多出的字符
        for (char c : t) {
            count[c - 'a']--;
            if (count[c - 'a'] < 0)
                return c;            // 发现多余字符, 提前返回
        }

        return ' ';  // 不会到达 (题目保证 t 多一个字符)
    }
};

// ------------------------------------------------------------
// 解法4: 排序后比较 (朴素方法)
// 时间 O(n log n), 空间 O(1)
//
// 思考过程:
//   1. s 和 t 分别排序
//   2. 逐位比较, 第一个不同位置的 t[i] 就是答案
//   3. 如果全部相同, 答案是 t 的最后一个字符
// ------------------------------------------------------------
class Solution4 {
public:
    char findTheDifference(string s, string t) {
        sort(s.begin(), s.end());
        sort(t.begin(), t.end());

        for (int i = 0; i < (int)s.size(); i++) {
            if (s[i] != t[i])
                return t[i];         // 第一个不同位置
        }

        return t.back();              // 多出的在最后
    }
};

/*
 * ============================================================
 * 解法对比:
 * ============================================================
 * | 解法     | 时间       | 空间  | 溢出风险 | 通用性 | 推荐 |
 * |---------|-----------|-------|---------|-------|------|
 * | 异或XOR  | O(n)      | O(1)  | 无      | 单差异 | 首选 |
 * | 求和差值  | O(n)      | O(1)  | int处理 | 单差异 | 推荐 |
 * | 哈希计数  | O(n)      | O(1)  | 无      | 多差异 | 推荐 |
 * | 排序比较  | O(n logn) | O(1)  | 无      | 多差异 | 不推荐|
 *
 * 面试策略:
 *   先说异或法展示位运算功底
 *   再提求和法和计数法展示思路广度
 *   排序法作为"暴力起点"一提即可
 *
 * ============================================================
 * 易错点:
 * ============================================================
 * 1. 异或 res 初始化为字符(如 'a')而非 0
 *    -> 0 是幺元, 不影响结果; 'a' 会多一个参与异或
 *
 * 2. 求和用 char 类型 -> 溢出!
 *    char 最大 127, 多字符累加会溢出; 用 int
 *
 * 3. 计数法遍历顺序搞反
 *    应该先统计 s, 再遍历 t 减少并检查 < 0
 *
 * 4. 排序法忘记处理"多出字符在末尾"的情况
 *    如果前面全匹配, 答案是 t.back()
 *
 * ============================================================
 * 面试追问:
 * ============================================================
 * Q1: 不止多一个字符?
 *     -> 异或不适用(多个相同异或为0)
 *     -> 求和法: sum差 / k = 字符 (知道k的话)
 *     -> 计数法最通用
 *
 * Q2: s 和 t 有多处不同?
 *     -> 只能用哈希计数, 异或和求和都不行
 *
 * Q3: 异或还能用在哪?
 *     -> LC 136 Single Number (唯一出现一次的数)
 *     -> LC 268 Missing Number (缺失的数)
 *     -> LC 260 Single Number III (两个唯一数)
 *
 * Q4: Unicode 字符会溢出吗?
 *     -> 异或法永远安全 (char ^ char = char)
 *     -> 求和法用 long long 即可
 */
