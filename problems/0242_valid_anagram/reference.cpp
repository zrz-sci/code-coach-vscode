/*
 * LeetCode 242: 有效的字母异位词 (Valid Anagram)
 *
 * 【题目本质】
 * 判断两个字符串是否包含完全相同种类和数量的字符（即字符频率一致）。
 *
 * 【解法总览】
 * 解法1: 排序比较    — O(n log n) / O(n)  — 最直觉
 * 解法2: 数组计数    — O(n) / O(1)        — 面试首选 ⭐
 * 解法3: 哈希表计数  — O(n) / O(k)        — Follow-up: Unicode 支持
 */

// ============================================================
// 解法1: 排序比较 — 异位词排序后一定相同
// 时间: O(n log n)  空间: O(n) 或 O(1) 取决于排序算法
//
// 【思路】
// 异位词 = 相同字母的不同排列。
// 如果我们把两个字符串都排序，那么异位词排序后必定变成同一个字符串。
// 这是最直觉的想法，但排序本身 O(n log n) 是多余的——
// 我们其实不关心字母的顺序，只关心频率。
// ============================================================
class Solution1 {
public:
    bool isAnagram(string s, string t) {
        // 长度不同，不可能是异位词（最简单的剪枝）
        if (s.size() != t.size()) return false;

        // 排序后比较
        // "anagram" → "aaagmnr"
        // "nagaram" → "aaagmnr"  → 相同 → true
        sort(s.begin(), s.end());
        sort(t.begin(), t.end());

        return s == t;
    }
};

// ============================================================
// 解法2: 数组计数 — 统计字符频率 ⭐ 面试首选
// 时间: O(n)  空间: O(1)（固定26个字母）
//
// 【思路】
// 解法1 的瓶颈在排序 O(n log n)。我们真正需要的只是"每个字母出现几次"。
// 用一个长度26的数组，s 的字母 +1，t 的字母 -1。
// 最终全为 0 → 频率完全一致 → 异位词。
//
// 示例过程:
//   s = "anagram", t = "nagaram"
//   遍历后 count['a'-'a']=3-3=0, count['n'-'a']=1-1=0, ...
//   全部为 0 → true
//
//   s = "rat", t = "car"
//   count['r'-'a']=1-1=0, count['a'-'a']=1-1=0,
//   count['t'-'a']=1, count['c'-'a']=-1  → 不全为0 → false
// ============================================================
class Solution2 {
public:
    bool isAnagram(string s, string t) {
        if (s.size() != t.size()) return false;

        // 26 个小写字母的计数器
        // 用 = {0} 确保初始化为全 0（C++ 局部数组不自动初始化！）
        int count[26] = {0};

        // 核心：一次遍历同时处理两个字符串
        // 因为已确认 s 和 t 等长，可以用同一个下标
        for (int i = 0; i < (int)s.size(); i++) {
            count[s[i] - 'a']++;  // s 中的字母 +1
            count[t[i] - 'a']--;  // t 中的字母 -1
        }

        // 如果是异位词，每个字母加了多少就减了多少，结果全 0
        for (int i = 0; i < 26; i++) {
            if (count[i] != 0) return false;
        }

        return true;
    }
};

// ============================================================
// 解法3: 哈希表计数 — Follow-up: 支持 Unicode
// 时间: O(n)  空间: O(k)，k 为字符种类数
//
// 【思路】
// 解法2 依赖"只有26个小写字母"的前提，用固定数组。
// 如果字符是 Unicode（14万+种字符），数组下标映射不现实。
// 用哈希表 unordered_map 替代数组，key 是字符，value 是计数。
// 逻辑完全一样：s 的字符 +1，t 的字符 -1，最后检查全 0。
//
// 相比解法2：
// - 优点：适用于任意字符集
// - 缺点：哈希表常数开销比数组大（约慢 3-5 倍）
// ============================================================
class Solution3 {
public:
    bool isAnagram(string s, string t) {
        if (s.size() != t.size()) return false;

        // 哈希表代替固定数组，适应任意字符集
        unordered_map<char, int> count;

        for (char c : s) count[c]++;
        for (char c : t) count[c]--;

        // 检查所有字符的计数是否为 0
        for (auto& [ch, cnt] : count) {
            if (cnt != 0) return false;
        }

        return true;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间       | 空间    | 适用范围         |
// |-----------|-----------|--------|-----------------|
// | 排序比较   | O(n log n) | O(n)   | 任意字符集       |
// | 数组计数   | O(n)       | O(1)   | 已知有限字符集   |
// | 哈希表计数 | O(n)       | O(k)   | 任意字符集       |
//
// 面试首选解法2（数组计数）。
// 被追问 Unicode → 切换到解法3（哈希表）。
// 解法1 作为开场暴力解提及即可。
//
// 【易错点】
// 1. 数组未初始化:
//    ✗ int count[26];        // 局部变量包含垃圾值
//    ✓ int count[26] = {0};  // 显式初始化为全0
//
// 2. 忘记长度检查:
//    ✗ 直接计数，如果用同一循环遍历 s 和 t，长度不等时越界
//    ✓ 第一行就判 if (s.size() != t.size()) return false;
//
// 3. 字符偏移写错:
//    ✗ count[s[i] - 'A']  // 题目是小写字母，偏移量错误
//    ✓ count[s[i] - 'a']
//
// 4. 最终检查逻辑:
//    ✗ 只检查是否有负数（忘了正数也代表不匹配）
//    ✓ 检查 count[i] != 0
//       （注：已判等长的情况下有正必有负，但 != 0 逻辑更清晰）
//
// 【面试追问】
// Q1: 暴力解时间复杂度？瓶颈在哪？
//     排序解法 O(n log n)。瓶颈在排序本身——我们不需要有序，只需要频率。
//
// Q2: 能否一次遍历搞定？
//     可以。因为 s 和 t 等长，在同一个 for 循环里 s 的字符 +1、t 的字符 -1。
//
// Q3 (Follow-up): 如果字符是 Unicode 怎么办？
//     固定数组 → 改用 unordered_map<char, int>。逻辑不变，只是底层存储变了。
//
// Q4: 如果需要大量调用 isAnagram，输入字符串很长，有什么优化？
//     可以预计算每个字符串的频率数组/哈希签名，缓存起来。
//     比较时直接比较预计算结果，避免重复遍历。
//
// 【相关题型】
// - 49. 字母异位词分组：复用本题的频率比较逻辑作为分组 key
//     （排序字符串作 key，或 "a3g1m1n1r1" 这样的频率编码作 key）
// - 383. 赎金信：同样的计数逻辑，但只要求 magazine 的频率 ≥ ransomNote
//     （最终检查改为 count[i] >= 0 而不是 == 0）
// - 438. 找到字符串中所有字母异位词：在滑动窗口中维护频率数组，
//     窗口大小固定为 pattern 长度，每次滑动 O(1) 更新
// ============================================================
