/*
 * LeetCode 3070: 元素和小于等于 k 的子矩阵的数目
 * Count Submatrices with Top-Left Element and Sum Less Than k
 *
 * 【题目本质】
 * 子矩阵必须包含 grid 的左上角 (0,0), 所以形态固定为 grid[0..i][0..j]。
 * 只需要对每个 (i,j) 计算从 (0,0) 到 (i,j) 的矩形和, 统计 <= k 的个数。
 * 经典二维前缀和 + 容斥原理。
 *
 * 【解法总览】
 * 解法1: 暴力枚举         — O(m^2 * n^2) / O(1)   — 理解题意
 * 解法2: 二维前缀和(额外数组) — O(m*n) / O(m*n) — 清晰安全
 * 解法3: 二维前缀和(原地修改) — O(m*n) / O(1)   — 面试首选 ⭐
 */


// ============================================================
// 解法1: 暴力枚举 — 对每个 (i,j) 遍历求和
// 时间: O(m^2 * n^2)  空间: O(1)
//
// 【思路】
// 最直觉的做法: 枚举右下角 (i,j), 然后从 (0,0) 到 (i,j) 遍历求和。
// m, n 最大 1000 时约 10^12 操作, 严重超时。
// 但这帮我们看到: 反复计算重叠区域的和 → 前缀和可以复用。
//
// 示例 grid = [[7,6,3],[6,6,1]], k = 18:
//   (0,0): sum=7  <= 18 ✓
//   (0,1): sum=7+6=13  <= 18 ✓
//   (0,2): sum=7+6+3=16  <= 18 ✓
//   (1,0): sum=7+6=13  <= 18 ✓
//   (1,1): sum=7+6+6+6=25  > 18 ✗
//   (1,2): sum=7+6+3+6+6+1=29  > 18 ✗
//   答案 = 4
// ============================================================
class Solution1 {
public:
    int countSubmatrices(vector<vector<int>>& grid, int k) {
        int m = grid.size(), n = grid[0].size();
        int count = 0;

        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                // 计算 grid[0..i][0..j] 的元素总和
                int sum = 0;
                for (int r = 0; r <= i; r++) {
                    for (int c = 0; c <= j; c++) {
                        sum += grid[r][c];
                    }
                }
                if (sum <= k) count++;
            }
        }
        return count;
    }
};

// ============================================================
// 解法2: 二维前缀和 (额外数组) — 清晰安全, 不修改输入
// 时间: O(m*n)  空间: O(m*n)
//
// 【思路】
// 用独立的 prefix 数组存储前缀和, 递推公式(容斥原理):
//
//   prefix[i][j] = grid[i][j]
//                + prefix[i-1][j]      (上方全部)
//                + prefix[i][j-1]      (左方全部)
//                - prefix[i-1][j-1]    (左上重叠, 被加了两次要减一次)
//
// 容斥示意图:
//   ┌──────────┬────────┐
//   │ prefix   │ prefix │
//   │ [i-1]    │ [i-1]  │
//   │ [j-1]    │ [j]    │
//   ├──────────┼────────┤
//   │ prefix   │ grid   │
//   │ [i]      │ [i][j] │
//   │ [j-1]    │ ← 当前 │
//   └──────────┴────────┘
//
//   prefix[i][j] = 当前格 + 上方 + 左方 - 左上(重叠)
//
// 示例 grid = [[7,2,9],[1,5,0],[2,6,6]], k = 20:
//
//   原始 grid:          prefix 数组:
//    7   2   9           7    9   18
//    1   5   0           8   15   24
//    2   6   6          10   23   35
//
//   prefix[1][1] = 5 + 7 + 2 + 1 - (没有i-1,j-1越界时为0)
//               实际: 5 + prefix[0][1] + prefix[1][0] - prefix[0][0]
//                   = 5 + 9 + 8 - 7 = 15  ✓ (7+2+1+5 = 15)
//
//   <= 20 的: 7, 9, 18, 8, 15, 10 → 6 个
// ============================================================
class Solution2 {
public:
    int countSubmatrices(vector<vector<int>>& grid, int k) {
        int m = grid.size(), n = grid[0].size();
        // 单独的前缀和数组, 不修改 grid
        vector<vector<int>> prefix(m, vector<int>(n, 0));
        int count = 0;

        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                prefix[i][j] = grid[i][j];

                // 加上方 (如果存在)
                if (i > 0) prefix[i][j] += prefix[i - 1][j];
                // 加左方 (如果存在)
                if (j > 0) prefix[i][j] += prefix[i][j - 1];
                // 减去重叠 (如果存在)
                if (i > 0 && j > 0) prefix[i][j] -= prefix[i - 1][j - 1];

                if (prefix[i][j] <= k) count++;
            }
        }
        return count;
    }
};

// ============================================================
// 解法3: 二维前缀和 (原地修改) — 面试首选 ⭐
// 时间: O(m*n)  空间: O(1)
//
// 【思路】
// 与解法2 逻辑完全相同, 区别是直接在 grid 上原地计算前缀和。
// 因为按行列顺序遍历, grid[i][j] 的原值在当前步骤中就用到了,
// 之后不再需要, 所以可以安全覆盖。
//
// 为什么原地修改是安全的:
// 当处理 (i,j) 时:
//   - grid[i-1][j]     已经是前缀和 ✓ (上一行已处理)
//   - grid[i][j-1]     已经是前缀和 ✓ (同一行左边已处理)
//   - grid[i-1][j-1]   已经是前缀和 ✓ (更早处理)
//   - grid[i][j]       还是原始值 ✓ (当前才处理)
//
// 注意: 此解法会修改输入数组!
//       如果面试官要求不修改, 用解法2。
// ============================================================
class Solution3 {
public:
    int countSubmatrices(vector<vector<int>>& grid, int k) {
        int m = grid.size(), n = grid[0].size();
        int count = 0;

        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                // 容斥原理: 加上方 + 加左方 - 减去重叠
                if (i > 0) grid[i][j] += grid[i - 1][j];
                if (j > 0) grid[i][j] += grid[i][j - 1];
                if (i > 0 && j > 0) grid[i][j] -= grid[i - 1][j - 1];

                if (grid[i][j] <= k) count++;
            }
        }
        return count;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 时间         | 空间    | 修改输入 | 推荐       |
// |-------------|-------------|---------|---------|------------|
// | 暴力枚举    | O(m^2*n^2)  | O(1)    | 否      | 理解题意    |
// | 前缀和+数组 | O(m*n)      | O(m*n)  | 否      | 安全清晰    |
// | 前缀和+原地 | O(m*n)      | O(1)    | 是      | 面试首选 ⭐ |
//
// ============================================================
// 【易错点】
//
// 1. 漏掉容斥的减法:
//    ✗ grid[i][j] += grid[i-1][j] + grid[i][j-1];
//    ✓ grid[i][j] += grid[i-1][j] + grid[i][j-1] - grid[i-1][j-1];
//    不减去重叠部分, 左上角区域被加了两次, 前缀和偏大。
//
// 2. 边界越界:
//    ✗ grid[i][j] += grid[i-1][j]; // i=0 时 i-1=-1 越界!
//    ✓ if (i > 0) grid[i][j] += grid[i-1][j];
//    三个方向都需要边界判断 (上方/左方/左上方)。
//
// 3. 混淆"包含左上角"和"任意子矩阵":
//    本题左上角固定为 (0,0), 只需枚举右下角, O(m*n)。
//    如果是任意子矩阵, 需要枚举四个边界, 复杂度高得多。
//
// 4. 整数溢出风险:
//    每个元素最大 1000, 矩阵最大 1000x1000,
//    最大前缀和 = 1000 * 1000 * 1000 = 10^9, int 可以容纳。
//    但如果元素范围更大, 需要用 long long。
//
// ============================================================
// 【面试追问】
//
// Q1: "原地修改的安全性如何保证?"
//     按行列顺序遍历, 处理 (i,j) 时, 它依赖的三个邻居
//     (i-1,j), (i,j-1), (i-1,j-1) 都已更新为前缀和。
//     而 grid[i][j] 的原始值在公式中被用到, 覆盖后不再需要。
//
// Q2: "如果子矩阵可以在任意位置呢?"
//     先算完整前缀和, 然后枚举四个边界。
//     用 sum(r1,c1,r2,c2) = prefix[r2][c2] - prefix[r1-1][c2]
//                           - prefix[r2][c1-1] + prefix[r1-1][c1-1]
//     时间 O(m^2 * n^2), 可进一步优化。
//
// Q3: "如果元素可以为负数, 方法还成立吗?"
//     完全成立。前缀和对负数同样有效。
//     区别: 前缀和不再单调, 不能用 break 剪枝。
//
// ============================================================
