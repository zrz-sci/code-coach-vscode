/*
 * LeetCode 415: 字符串相加 (Add Strings)
 *
 * 【题目本质】
 * 模拟小学竖式加法：逐位相加，处理进位。
 * 本质是大数加法，因为字符串长度可达 10^4 位，远超整数类型范围。
 *
 * 【解法总览】
 * 解法1: 模拟竖式加法(反转法)  — O(max(m,n)) / O(max(m,n)) — 面试首选
 * 解法2: 模拟竖式加法(预分配法) — O(max(m,n)) / O(max(m,n)) — 实现变体
 */

// ============================================================
// 解法1: 模拟竖式加法（反转法） — 面试首选 ⭐
// 时间: O(max(m,n))  空间: O(max(m,n))
//
// 【思路】
// 小学竖式加法怎么算？从个位（右端）开始，逐位相加，满 10 进 1。
// 用双指针 i, j 分别从两个字符串末尾往前走，模拟这个过程。
// 结果是倒序拼接的，最后反转即可。
//
//   竖式加法示意:
//
//       4 5 6       ← num1, i 从右往左
//     +   7 7       ← num2, j 从右往左
//     ───────
//       5 3 3       ← 结果
//
//   Step1: i=2,j=1 → 6+7=13, write 3, carry=1
//   Step2: i=1,j=0 → 5+7+1=13, write 3, carry=1
//   Step3: i=0,j=-1 → 4+0+1=5, write 5, carry=0
//   拼接顺序: "335" → 反转 → "533"
//
// ============================================================
class Solution1 {
public:
    string addStrings(string num1, string num2) {
        string result;
        int i = num1.size() - 1;  // 从 num1 个位开始
        int j = num2.size() - 1;  // 从 num2 个位开始
        int carry = 0;

        // 三个条件缺一不可：两个数还有位没处理，或者还有进位
        // 少了 carry 这个条件，"999"+"1" 会输出 "000" 而非 "1000"
        while (i >= 0 || j >= 0 || carry) {
            int sum = carry;

            // 取 num1 当前位，如果已经越界则视为 0
            if (i >= 0) {
                sum += num1[i] - '0';  // 字符转数字: '5'-'0' = 5
                i--;
            }

            // 取 num2 当前位，同理
            if (j >= 0) {
                sum += num2[j] - '0';
                j--;
            }

            // 和竖式加法一样: 当前位 = sum%10, 进位 = sum/10
            carry = sum / 10;
            result += (char)(sum % 10 + '0');  // 数字转字符: 5+'0' = '5'
        }

        // 因为我们从低位加到高位，结果是倒序的，需要反转
        reverse(result.begin(), result.end());
        return result;
    }
};

// ============================================================
// 解法2: 模拟竖式加法（预分配法） — 避免反转
// 时间: O(max(m,n))  空间: O(max(m,n))
//
// 【思路】
// 解法1 最后有一步 reverse，虽然不影响复杂度，但我们可以避免：
// 预先分配足够长的字符串（最多 max(m,n)+1 位），
// 从右往左填写结果，最后用 substr 截掉前面没用到的位。
//
// 两个 n 位数相加，结果最多 n+1 位（因为最高位进位最多为 1）
// ============================================================
class Solution2 {
public:
    string addStrings(string num1, string num2) {
        int i = num1.size() - 1;
        int j = num2.size() - 1;
        int carry = 0;

        int maxLen = max(num1.size(), num2.size());
        // 预分配 maxLen+1 位，初始化为 '0'
        // 多出的 1 位留给可能的最高位进位
        string result(maxLen + 1, '0');
        int k = maxLen;  // 从结果的最后一位开始向前填

        while (i >= 0 || j >= 0 || carry) {
            int sum = carry;
            if (i >= 0) sum += num1[i--] - '0';
            if (j >= 0) sum += num2[j--] - '0';

            carry = sum / 10;
            result[k--] = (char)(sum % 10 + '0');
        }

        // k+1 是最后写入的位置（即结果的最高有效位）
        // 如果没有最高进位，k+1=1，跳过 result[0] 的前导 '0'
        // 如果有最高进位，k+1=0，整个字符串都是有效的
        return result.substr(k + 1);
    }
};

// ============================================================
// 【解法对比】
//
// | 对比维度     | 解法1（反转法）       | 解法2（预分配法）     |
// |-------------|---------------------|---------------------|
// | 核心逻辑    | 倒序拼接 + reverse   | 预分配 + 从右往左填   |
// | 代码复杂度  | 简洁，推荐面试写      | 需要处理 substr      |
// | 额外操作    | reverse O(n)        | substr O(n) 拷贝    |
// | 选择建议    | ⭐ 面试首选           | 追求极致时可提一下    |
//
// 两种解法时间空间复杂度完全相同 O(max(m,n))
//
// ============================================================
// 【易错点】
//
// 1. 循环条件漏掉 carry:
//    ✗ while (i >= 0 || j >= 0)
//    ✓ while (i >= 0 || j >= 0 || carry)
//    反例: "999" + "1" → carry=1 时 i,j 都已 <0，
//          漏掉 carry 导致最高位 '1' 丢失，输出 "000"
//
// 2. 字符数字转换:
//    ✗ sum += num1[i];           // 加的是 ASCII 码, '1'=49
//    ✓ sum += num1[i] - '0';    // 减去 '0' 偏移, 得到数字 1
//
// 3. 数字转字符时忘记 + '0':
//    ✗ result += sum % 10;       // 追加 int, 不是字符
//    ✓ result += (char)(sum % 10 + '0');
//
// 4. 指针初始化方向:
//    ✗ int i = 0;               // 这是最高位! 应该从个位开始
//    ✓ int i = num1.size() - 1; // 个位 = 字符串末尾
//
// ============================================================
// 【面试追问】
//
// Q1(基础): 为什么不直接 stoi 转整数再相加?
//    → 字符串长度达 10^4 位, 远超 long long 范围(约19位),
//      必须用逐位模拟(大数运算).
//
// Q2(变体): 如果改成二进制字符串相加 (LC 67)?
//    → 框架完全相同, 只改两处:
//      carry = sum / 2; (不是 /10)
//      result += (char)(sum % 2 + '0'); (不是 %10)
//
// Q3(扩展): 如果要实现大数乘法 (LC 43)?
//    → 乘法 = 逐位相乘 + 错位相加. 本题的加法逻辑直接复用.
//      核心: 用 int result[m+n] 数组, num1[i]*num2[j] 的结果
//      加到 result[i+j+1], 最后统一处理进位.
//
// Q4(变体): 大数减法怎么做?
//    → 类似逐位操作, 改为相减+借位. 额外处理:
//      先比较大小确定正负, 用大减小, 借位时当前位+10再减.
// ============================================================
