/*
 * LeetCode 75: 颜色分类 (Sort Colors)
 * 
 * 【题目本质】
 * 对一个只含 0/1/2 的数组原地排序。
 * 值域极小（只有3种）是关键约束，让我们能做到 O(n) 一趟排序。
 *
 * 【解法总览】
 * 解法1: 计数排序        — O(n) / O(1) — 最直觉，两趟扫描
 * 解法2: 两趟双指针      — O(n) / O(1) — 分两次 partition
 * 解法3: 荷兰国旗(三指针) — O(n) / O(1) — 一趟扫描，面试首选 ⭐
 */

// ============================================================
// 解法1: 计数排序 — 先统计数量，再按顺序覆盖
// 时间: O(n)  空间: O(1) (计数数组大小固定为3)
//
// 【思路】
// 既然只有3种值，直接数一下每种有几个，然后从头覆盖。
// 这是最朴素的"利用值域有限"的方法。
// 缺点：需要两趟扫描，不满足 Follow-up。
// ============================================================
class Solution1 {
public:
    void sortColors(vector<int>& nums) {
        int count[3] = {0, 0, 0};
        
        // 第一趟：统计
        for (int num : nums) {
            count[num]++;
        }
        
        // 第二趟：覆盖
        int idx = 0;
        for (int color = 0; color < 3; color++) {
            for (int i = 0; i < count[color]; i++) {
                nums[idx++] = color;
            }
        }
    }
};

// ============================================================
// 解法2: 两趟双指针 — 第一趟归位0，第二趟归位1
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 第一趟用一个指针 ptr 维护"0区域的右边界"，
// 遇到0就和ptr位置交换，ptr前进。
// 第一趟结束后 [0, ptr) 全是0。
// 第二趟从 ptr 开始，同样的方法把1归位。
// 2自然就留在了最后面。
//
// 这个思路为解法3铺垫：
// 如果同时维护0的右边界和2的左边界，就能一趟完成。
// ============================================================
class Solution2 {
public:
    void sortColors(vector<int>& nums) {
        int n = nums.size();
        int ptr = 0;
        
        // 第一趟：所有 0 归位到前面
        for (int i = 0; i < n; i++) {
            if (nums[i] == 0) {
                swap(nums[i], nums[ptr]);
                ptr++;
            }
        }
        
        // 第二趟：所有 1 归位到 0 后面
        for (int i = ptr; i < n; i++) {
            if (nums[i] == 1) {
                swap(nums[i], nums[ptr]);
                ptr++;
            }
        }
    }
};

// ============================================================
// 解法3: 荷兰国旗算法（三指针）— 一趟扫描完成三路分区 ⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 维护三个指针 lo, mid, hi：
//   [0, lo)    → 全是 0（已归位）
//   [lo, mid)  → 全是 1（已归位）
//   [mid, hi]  → 未处理
//   (hi, n-1]  → 全是 2（已归位）
//
// mid 从左到右扫描，根据 nums[mid] 的值做三种操作：
//   = 0: 和 lo 交换，lo++, mid++  (lo位置一定是1，换过来安全)
//   = 1: 已在正确区域，mid++
//   = 2: 和 hi 交换，hi--        (hi位置未知，mid不动要再检查)
//
// 当 mid > hi 时，所有元素归位，排序完成。
//
// 【详细过程演示】 nums = [2, 0, 2, 1, 1, 0]
//
//  初始:     [2, 0, 2, 1, 1, 0]     lo=0, mid=0, hi=5
//             ↑                 ↑
//           lo,mid              hi
//
//  mid=0: nums[0]=2, swap(0,5) → [0, 0, 2, 1, 1, 2]  hi=4
//          换过来的是0, mid不动, 下一轮再处理
//
//  mid=0: nums[0]=0, swap(0,0) → [0, 0, 2, 1, 1, 2]  lo=1, mid=1
//          自己和自己交换(lo==mid时)
//
//  mid=1: nums[1]=0, swap(1,1) → [0, 0, 2, 1, 1, 2]  lo=2, mid=2
//
//  mid=2: nums[2]=2, swap(2,4) → [0, 0, 1, 1, 2, 2]  hi=3
//          换过来的是1, mid不动
//
//  mid=2: nums[2]=1, mid++     → [0, 0, 1, 1, 2, 2]  mid=3
//
//  mid=3: nums[3]=1, mid++     → [0, 0, 1, 1, 2, 2]  mid=4
//
//  mid=4 > hi=3 → 退出循环
//  结果: [0, 0, 1, 1, 2, 2] ✓
// ============================================================
class Solution3 {
public:
    void sortColors(vector<int>& nums) {
        int lo = 0, mid = 0, hi = (int)nums.size() - 1;
        
        while (mid <= hi) {
            if (nums[mid] == 0) {
                // 0 应该在最左边：和 lo 交换
                // 为什么 mid 可以前进？因为 [lo, mid) 区间都是1，
                // 从 lo 换过来的一定是1，不需要再检查
                swap(nums[lo], nums[mid]);
                lo++;
                mid++;
            } else if (nums[mid] == 2) {
                // 2 应该在最右边：和 hi 交换
                // 为什么 mid 不能前进？因为 hi 位置的值还没被扫描过，
                // 可能是 0/1/2 中的任何一个，必须下一轮再检查
                swap(nums[mid], nums[hi]);
                hi--;
                // 注意：mid 不动！
            } else {
                // nums[mid] == 1：已在 1 区域，跳过
                mid++;
            }
        }
    }
};

// ============================================================
// 【解法对比】
// 
// 计数排序(解法1):
//   - 最简单直观，面试中可以作为第一版快速写出
//   - 缺点：两趟扫描，且第二趟是"覆盖写入"而非交换
//
// 两趟双指针(解法2):
//   - 思路清晰，为三指针铺垫
//   - 展示了 partition 的基本操作
//
// 荷兰国旗(解法3):
//   - 一趟扫描 + O(1) 空间，满足 Follow-up
//   - 面试必须掌握的经典算法
//   - 核心是三路分区，和快排的 three-way partition 完全一致
//
// 【易错点】
// 1. 遇到2交换后 mid++ → 错！hi换过来的值未知，必须再检查
//    ✗ swap(nums[mid], nums[hi]); hi--; mid++;
//    ✓ swap(nums[mid], nums[hi]); hi--;
//
// 2. 循环条件 mid < hi → 错！mid==hi 时该元素未处理
//    ✗ while (mid < hi)
//    ✓ while (mid <= hi)
//
// 3. hi 初始化为 nums.size() → 错！应该是 size()-1
//    ✗ int hi = nums.size();     // hi指向数组外，首次交换越界
//    ✓ int hi = nums.size() - 1; // hi指向最后一个元素
//    注意：如果 nums 为空，size()-1 会溢出(unsigned)，
//    所以用 (int)nums.size() - 1 做显式转换更安全
//
// 4. 遇到0交换后忘记 mid++ → 死循环
//    当 lo==mid 时交换自己，如果 mid 不前进则永远停在这里
//    ✗ swap(nums[lo], nums[mid]); lo++;
//    ✓ swap(nums[lo], nums[mid]); lo++; mid++;
//
// 【面试追问】
// Q1: 为什么遇到0换完mid可以前进，遇到2换完就不行？
//     → lo到mid之间都是已处理的1，换过来的一定是1。
//       hi是未处理区域，换过来的值未知。
//
// Q2: 如果有k种颜色（k>3）怎么办？
//     → 三指针只适用于3种值。k种值用计数排序 O(n+k)，
//       或递归分区（每次把最小最大值分到两端，递归中间部分）。
//
// Q3: 这和快排什么关系？
//     → 荷兰国旗就是快排的三路分区步骤（pivot=1）。
//       三路快排对大量重复元素的数组特别高效。
//
// Q4: 如果不允许交换（只能赋值），怎么做？
//     → 用计数排序：先统计再覆盖，第二趟是赋值而非交换。
// ============================================================
