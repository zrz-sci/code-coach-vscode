/*
 * LeetCode 1523: Count Odd Numbers in an Interval Range
 * (在区间范围内统计奇数数目)
 *
 * 【题目本质】
 * 给定两个非负整数 low 和 high，返回 [low, high] 中奇数的个数。
 * low, high 可达 10^9，必须 O(1) 解决。
 *
 * 【解法总览】
 * 解法1: 前缀计数公式        — O(1) / O(1) — 最简洁
 * 解法2: 分类讨论(按奇偶)    — O(1) / O(1) — 更直觉
 * 解法3: 区间长度 + 端点修正  — O(1) / O(1) — 另一种推导
 */

// ============================================================
// 解法1: 前缀计数公式 — 最简洁 ⭐
// 时间: O(1)  空间: O(1)
//
// 【思路】
// 前缀计数思想 (类比前缀和):
//   [low, high] 中奇数个数 = [0, high] 中奇数个数 - [0, low-1] 中奇数个数
//
// [0, n] 中奇数个数:
//   n=0: {0}           → 0 个奇数 → (0+1)/2 = 0 ✓
//   n=1: {0,1}         → 1 个奇数 → (1+1)/2 = 1 ✓
//   n=2: {0,1,2}       → 1 个奇数 → (2+1)/2 = 1 ✓
//   n=3: {0,1,2,3}     → 2 个奇数 → (3+1)/2 = 2 ✓
//   n=4: {0,1,2,3,4}   → 2 个奇数 → (4+1)/2 = 2 ✓
//   n=5: {0,1,2,3,4,5} → 3 个奇数 → (5+1)/2 = 3 ✓
//   规律: count(0, n) = (n+1)/2 (整除)
//
// [0, low-1] 中奇数个数:
//   count(0, low-1) = ((low-1)+1)/2 = low/2
//
// 最终公式:
//   count(low, high) = (high+1)/2 - low/2
//
// 示例验证:
//   low=3, high=7: (7+1)/2 - 3/2 = 4 - 1 = 3  ([3,5,7]) ✓
//   low=8, high=10: (10+1)/2 - 8/2 = 5 - 4 = 1  ([9]) ✓
//   low=0, high=0: (0+1)/2 - 0/2 = 0 - 0 = 0 ✓
//   low=1, high=1: (1+1)/2 - 1/2 = 1 - 0 = 1 ✓
// ============================================================
class Solution {
public:
    int countOdds(int low, int high) {
        // (high+1)/2: [0, high] 中奇数个数
        // low/2:      [0, low-1] 中奇数个数
        return (high + 1) / 2 - low / 2;
    }
};

// ============================================================
// 解法2: 分类讨论 — 按 low/high 奇偶分 4 种情况
// 时间: O(1)  空间: O(1)
//
// 【思路】
// 根据 low 和 high 的奇偶性:
//
// low=奇, high=奇: [3,7] → 3,4,5,6,7 → 奇数:3,5,7 = 3 = (5+1)/2
// low=奇, high=偶: [3,8] → 3,4,5,6,7,8 → 奇数:3,5,7 = 3 = (6+1)/2
// low=偶, high=奇: [2,7] → 2,3,4,5,6,7 → 奇数:3,5,7 = 3 = (6+1)/2
// low=偶, high=偶: [2,8] → 2,3,4,5,6,7,8 → 奇数:3,5,7 = 3 = 7/2
//
// 规律:
//   只要 low 或 high 至少一个是奇数 → (len+1)/2
//   两个都是偶数 → len/2
//   (其中 len = high - low + 1)
//
// 其实等价于解法1的公式，只是另一种理解方式。
// ============================================================
class Solution2 {
public:
    int countOdds(int low, int high) {
        int len = high - low + 1;
        if (low % 2 == 1 || high % 2 == 1) {
            // 至少一个端点是奇数
            return (len + 1) / 2;
        } else {
            // 两个端点都是偶数
            return len / 2;
        }
    }
};

// ============================================================
// 解法3: 区间长度 + 端点修正
// 时间: O(1)  空间: O(1)
//
// 【思路】
// 基础: 任意长度为 len 的区间，奇数个数约为 len/2。
// 修正: 如果区间起点是奇数，多一个奇数 → (len+1)/2。
//
// 等价写法: len/2 + (low % 2)
//   如果 low 是奇数: low 本身是奇数，奇偶交替后比一半多 1 → len/2+1 = (len+1)/2
//   如果 low 是偶数: 标准交替 → len/2
//
// 但要注意 high 是奇数的情况:
//   [2,7]: len=6, low=偶 → 6/2+0 = 3 ✓
//   [2,8]: len=7, low=偶 → 7/2+0 = 3 ✓
//   等等，这也对? 让我验证:
//   [4,8]: len=5, low=偶 → 5/2+0 = 2, 实际[5,7]=2 ✓
//   [3,8]: len=6, low=奇 → 6/2+1 = 4? 实际[3,5,7]=3 ✗
//
// 所以简单的 len/2+low%2 不总是对。还是用解法1最安全。
// ============================================================
class Solution3 {
public:
    int countOdds(int low, int high) {
        // 最安全的方式: 直接用解法1的公式
        return (high + 1) / 2 - low / 2;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 公式                           | 直觉性 | 安全性 |
// |------------|-------------------------------|--------|--------|
// | 前缀计数    | (high+1)/2 - low/2            | 高     | 最安全 |
// | 分类讨论    | 按 low/high 奇偶分支           | 中     | 安全   |
// | 长度+修正   | len/2 + 修正项                 | 低     | 容易出错|
//
// 面试选择: 直接写解法1，一行代码。如果面试官追问证明，用解法2的分类讨论验证。
//
// ============================================================
// 【公式推导的数学证明】
//
// 令 f(n) = [0, n] 中奇数个数。
//
// 对于 n >= 0:
//   如果 n 为偶数: 0,1,2,...,n 中奇数有 1,3,5,...,n-1，共 n/2 个
//     f(n) = n/2 = (n+1)/2 (整除，因为 n 偶时 n/2 = (n+1)/2)
//
//   如果 n 为奇数: 0,1,2,...,n 中奇数有 1,3,5,...,n，共 (n+1)/2 个
//     f(n) = (n+1)/2 ✓
//
// 两种情况统一为 f(n) = (n+1)/2 (整除)。
//
// [low, high] 中奇数个数:
//   = f(high) - f(low - 1)
//   = (high+1)/2 - ((low-1)+1)/2
//   = (high+1)/2 - low/2  ✓
//
// ============================================================
// 【推广: 统计 [low, high] 中能被 k 整除的数】
//
// 公式: high/k - (low-1)/k
//
// 示例: k=3, low=5, high=15
//   15/3 - 4/3 = 5 - 1 = 4
//   验证: 6,9,12,15 → 4个 ✓
//
// 奇数可以看作: 统计 [low, high] 中 x%2==1 的数
//   不完全等价于"被2整除"的推广，但思路类似。
//
// ============================================================
// 【易错点】
//
// 1. 暴力遍历超时:
//    ✗ for(int i=low;i<=high;i++) if(i%2) cnt++;
//      low=0, high=10^9 → 10^9 次循环超时
//    ✓ O(1) 公式
//
// 2. 公式记错:
//    ✗ (high-low)/2 → [3,7]得2，实际3
//    ✗ (high-low+1)/2 → [3,7]得2，实际3
//    ✓ (high+1)/2 - low/2 → [3,7]得4-1=3 ✓
//
// 3. 整除方向混淆:
//    C++中正整数 a/b 下取整。不要用浮点数!
//    ✗ (int)(high/2.0 + 0.5) → 浮点精度问题
//    ✓ (high+1)/2 纯整数运算
//
// ============================================================
// 【面试追问】
//
// Q1: 如果统计偶数呢?
//     偶数 = 总数 - 奇数 = (high-low+1) - ((high+1)/2 - low/2)
//     或直接: high/2 - (low-1)/2 (当 low>0)
//     注意 low=0 时 [0,0] 中 0 算偶数
//
// Q2: 如果统计能被k整除的数?
//     count = high/k - (low-1)/k
//
// Q3: 如果low和high可以是负数?
//     C++整除对负数向零取整(-7/2=-3不是-4)。
//     需要调整: 可以先偏移到非负范围再计算。
//
