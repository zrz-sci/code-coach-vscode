/*
 * LeetCode 17: 电话号码的字母组合 (Letter Combinations of a Phone Number)
 *
 * 【题目本质】
 * 给定一串数字，每个数字映射若干字母，求所有数字各选一个字母的组合（笛卡尔积）。
 * 嵌套循环层数不固定 → 用递归/回溯来模拟多层循环。
 *
 * 【解法总览】
 * 解法1: 回溯(DFS)     — O(4^n · n) / O(n) — 面试首选，经典回溯模板
 * 解法2: 迭代(BFS式扩展) — O(4^n · n) / O(4^n · n) — 另一种视角，逐层扩展
 *
 * 【决策树】(digits = "23")
 *                      ""
 *                 /    |    \
 *               "a"   "b"   "c"         ← 数字'2' → "abc"，每个字母是一个分支
 *              /|\   /|\   /|\
 *            ad ae af bd be bf cd ce cf  ← 数字'3' → "def"
 *            ↑  ↑  ↑  ↑  ↑  ↑  ↑  ↑  ↑
 *            叶子节点 = 结果（共 3×3 = 9 个）
 *
 * 回溯过程:
 * 1. path=""  选'a' → path="a"
 * 2.   path="a"  选'd' → path="ad" → 到底，收获"ad"
 * 3.   撤销'd' → path="a"  选'e' → path="ae" → 收获"ae"
 * 4.   撤销'e' → path="a"  选'f' → path="af" → 收获"af"
 * 5. 撤销'a' → path=""  选'b' → path="b"
 * 6.   ... 同理产生 "bd","be","bf"
 * 7. 撤销'b' → 选'c' → ... 产生 "cd","ce","cf"
 */

// ============================================================
// 解法1: 回溯(DFS) — 经典回溯模板
// 时间: O(4^n · n)  空间: O(n) 递归栈深度（不算结果存储）
//
// 【思路】
// 每个数字对应一层递归，在该层遍历数字映射的所有字母。
// 选一个字母加入路径 → 递归处理下一个数字 → 撤销选择。
// 当所有数字都处理完（index == digits.size()），路径就是一个完整组合。
//
// 为什么用回溯而不是多层for循环？
// 因为digits长度是运行时决定的，无法写固定层数的嵌套循环。
// 递归天然解决"层数不确定"的问题——每次递归就是一层循环。
// ============================================================
class Solution1 {
public:
    // 数字到字母的映射，下标对齐数字（0和1为空占位）
    const string mapping[10] = {
        "", "", "abc", "def", "ghi", "jkl",
        "mno", "pqrs", "tuv", "wxyz"
    };
    
    vector<string> result;
    
    vector<string> letterCombinations(string digits) {
        if (digits.empty()) return {};  // 边界：空串直接返回空列表
        string path;
        path.reserve(digits.size());    // 预分配，避免反复扩容
        backtrack(digits, 0, path);
        return result;
    }
    
    // index: 当前处理到digits的第几个数字（即递归的第几层）
    // path: 当前已拼好的字母组合
    void backtrack(const string& digits, int index, string& path) {
        // 终止条件：所有数字都选完了，path是一个完整的组合
        if (index == digits.size()) {
            result.push_back(path);
            return;
        }
        
        // 当前数字对应的字母集合就是本层的"选择列表"
        const string& letters = mapping[digits[index] - '0'];
        
        for (char ch : letters) {
            path.push_back(ch);                  // 做选择：把字母加入路径
            backtrack(digits, index + 1, path);  // 递归：处理下一个数字
            path.pop_back();                     // 撤销选择：恢复路径
            // 为什么要撤销？因为path是引用传递，不撤销会影响同层其他分支
        }
    }
};

// ============================================================
// 解法2: 迭代(BFS式逐层扩展) — 不用递归
// 时间: O(4^n · n)  空间: O(4^n · n) 需要存储所有中间结果
//
// 【思路】
// 换一种角度：不是"递归选择"，而是"逐步扩展"。
// 初始有一个空串""，每遇到一个新数字，就把已有的每个组合
// 分别追加该数字的每个字母，生成新的组合列表。
//
// 迭代过程（digits = "23"）:
// 初始:     [""]
// 处理'2':  ["a", "b", "c"]
//           ← 空串"" 分别追加 'a','b','c'
// 处理'3':  ["ad","ae","af","bd","be","bf","cd","ce","cf"]
//           ← "a"追加'd','e','f'; "b"追加'd','e','f'; "c"追加'd','e','f'
//
// 本质上是在模拟笛卡尔积的计算过程。
// ============================================================
class Solution2 {
public:
    vector<string> letterCombinations(string digits) {
        if (digits.empty()) return {};
        
        const string mapping[10] = {
            "", "", "abc", "def", "ghi", "jkl",
            "mno", "pqrs", "tuv", "wxyz"
        };
        
        // 关键：初始化为包含一个空串的列表，空串是所有组合的"种子"
        // 如果初始化为空列表{}，内层循环不会执行，结果永远为空！
        vector<string> result = {""};
        
        for (char digit : digits) {
            vector<string> newResult;
            const string& letters = mapping[digit - '0'];
            
            // 对已有的每个组合，追加当前数字的每个字母
            for (const string& combo : result) {
                for (char ch : letters) {
                    newResult.push_back(combo + ch);
                }
            }
            
            // 用新列表替换旧列表，move避免不必要的拷贝
            result = move(newResult);
        }
        
        return result;
    }
};

// ============================================================
// 【解法对比】
// 
// 解法1（回溯）vs 解法2（迭代）:
// - 时间复杂度相同：O(4^n · n)，因为结果总量相同，都要全部生成
// - 空间差异：回溯额外只需 O(n) 递归栈；迭代需要 O(4^n · n) 存中间列表
// - 扩展性：回溯容易加剪枝（如只保留有效单词的前缀）；迭代加剪枝不方便
// - 面试推荐：首选回溯（展示回溯/递归功底），迭代作为补充思路
//
// 【易错点】
// 1. 空串处理：不判断 digits.empty() → 回溯版会产生 [""]（一个空串结果），
//    而题意要求返回 []（空列表）
//
// 2. 映射表下标错位：mapping[0]="abc" 会让 digits[i]-'0' 取到错误映射
//    正确做法：mapping[2]="abc"，让下标直接对应数字
//
// 3. 回溯忘记 pop_back：
//    ✗ path.push_back(ch); backtrack(...); // 漏了 pop_back
//      → path 越来越长，输出类似 "abcdef..." 的错误结果
//    ✓ path.push_back(ch); backtrack(...); path.pop_back();
//
// 4. 迭代法初始化错误：
//    ✗ vector<string> result = {};   → 内层循环永远不执行，返回空
//    ✓ vector<string> result = {""}; → 空串是组合的起点/种子
//
// 5. 映射漏字母：7对应"pqrs"(4个字母)，9对应"wxyz"(4个字母)，
//    不是所有数字都只映射3个字母！
//
// 【面试追问】
// Q1（基础）: 结果总共多少个？
//    → 各数字对应字母数的乘积，最坏 4^4=256（digits全是7或9）
//
// Q2（回溯理解）: 回溯和普通DFS有什么区别？
//    → 回溯 = DFS + 撤销选择。本题 pop_back() 就是撤销。
//       如果不撤销，同层其他分支会在脏数据上继续操作。
//
// Q3（变体/剪枝）: 如果要求只输出字典中存在的单词怎么办？
//    → 用 Trie（前缀树）存字典，回溯时每选一个字母就在 Trie 上走一步。
//       如果当前前缀不存在于 Trie 中，直接剪枝（不再递归下去）。
//       这就把本题和 Trie + 回溯结合了。
//
// Q4（极端情况）: digits 长度很长（如100）怎么办？
//    → 结果数量是指数级(最多4^100)，无法全部存储。
//       应该改用迭代器/生成器模式，按需生成下一个组合。
//       或者只输出结果总数（乘法原理直接算），不实际枚举。
//
