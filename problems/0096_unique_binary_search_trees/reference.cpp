/*
 * LeetCode 96: 不同的二叉搜索树 (Unique Binary Search Trees)
 *
 * 【题目本质】
 * 给定 n，计算 n 个节点的结构唯一的 BST 数量。
 * 本质：卡特兰数，通过枚举根节点将问题递归分解。
 *
 * 【解法总览】
 * 解法1: 暴力递归       — O(指数级) / O(n)   — 理解递归分解
 * 解法2: 记忆化搜索     — O(n²) / O(n)      — 消除重复计算
 * 解法3: 动态规划(递推)  — O(n²) / O(n)      — 面试首选 ⭐
 * 解法4: 卡特兰数公式   — O(n) / O(1)       — 数学加分项
 */

// ============================================================
// 解法1: 暴力递归 — 枚举根节点，递归计算左右子树组合数
// 时间: O(指数级，约 O(3^n))  空间: O(n) 递归栈
//
// 【思路】
// BST 性质：选 k 为根 → 1..k-1 在左，k+1..n 在右
// 左子树有 k-1 个节点，右子树有 n-k 个节点
// 总数 = Σ G(k-1) * G(n-k)，k 从 1 到 n
//
// 关键观察：BST 的结构数只取决于节点个数，与具体值无关
// 所以 G(k-1) 就是 k-1 个连续数能组成的 BST 数量
//
//  n=3 的递归展开:
//  G(3) = G(0)*G(2) + G(1)*G(1) + G(2)*G(0)
//
//  根=1:      根=2:      根=3:
//    1          2          3
//     \        / \        /
//   (2节点)  (1) (1)  (2节点)
//   = G(2)   = 1*1    = G(2)
//   = 2      = 1      = 2
//                          总共 = 5
// ============================================================
class Solution1 {
public:
    int numTrees(int n) {
        // 空树或单节点：只有1种结构
        // 注意 G(0)=1 是乘法单位元，不能设为0
        if (n <= 1) return 1;
        
        int total = 0;
        for (int k = 1; k <= n; k++) {
            // 左子树 k-1 个节点的BST数 × 右子树 n-k 个节点的BST数
            total += numTrees(k - 1) * numTrees(n - k);
        }
        return total;
    }
};

// ============================================================
// 解法2: 记忆化搜索 — 暴力递归 + memo 消除重叠子问题
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 解法1中 G(2) 被计算了多次（G(3) 中计算两次，G(4) 中更多次）
// 加 memo 数组：算过的直接返回，每个 G(i) 只算一次
// G(i) 的计算需要遍历 i 次内层循环，共 n 个状态
// 总时间 = 1 + 2 + ... + n = O(n²)
// ============================================================
class Solution2 {
public:
    int numTrees(int n) {
        vector<int> memo(n + 1, -1);
        return helper(n, memo);
    }
    
    int helper(int n, vector<int>& memo) {
        if (n <= 1) return 1;
        if (memo[n] != -1) return memo[n]; // 已计算过，直接返回
        
        int total = 0;
        for (int k = 1; k <= n; k++) {
            total += helper(k - 1, memo) * helper(n - k, memo);
        }
        memo[n] = total; // 缓存结果
        return total;
    }
};

// ============================================================
// 解法3: 动态规划（自底向上递推）— 面试首选 ⭐
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 将记忆化搜索翻译成递推：
// 状态定义：dp[i] = i 个节点能组成的BST种数
// 转移方程：dp[i] = Σ dp[j-1] * dp[i-j]，j从1到i
//           (j作为根，左子树j-1个节点，右子树i-j个节点)
// 初始化：dp[0] = 1（空树，乘法单位元）
//         dp[1] = 1（单节点）
// 遍历方向：从小到大，因为 dp[i] 依赖 dp[0]..dp[i-1]
//
// dp 填表过程:
//  i=0: dp[0] = 1
//  i=1: dp[1] = 1
//  i=2: dp[2] = dp[0]*dp[1] + dp[1]*dp[0]
//             = 1*1 + 1*1 = 2
//  i=3: dp[3] = dp[0]*dp[2] + dp[1]*dp[1] + dp[2]*dp[0]
//             = 1*2 + 1*1 + 2*1 = 5
//  i=4: dp[4] = dp[0]*dp[3] + dp[1]*dp[2] + dp[2]*dp[1] + dp[3]*dp[0]
//             = 1*5 + 1*2 + 2*1 + 5*1 = 14
//  i=5: dp[5] = 42
//
//  观察：dp[i] 的求和式是对称的（dp[j-1]*dp[i-j]关于中点对称）
// ============================================================
class Solution3 {
public:
    int numTrees(int n) {
        vector<int> dp(n + 1, 0);
        
        // base case: 空树和单节点各1种
        dp[0] = 1;
        dp[1] = 1;
        
        // 外层：枚举节点总数 i
        for (int i = 2; i <= n; i++) {
            // 内层：枚举根节点编号 j (1到i)
            for (int j = 1; j <= i; j++) {
                // j为根 → 左子树j-1个节点，右子树i-j个节点
                dp[i] += dp[j - 1] * dp[i - j];
            }
        }
        
        return dp[n];
    }
};

// ============================================================
// 解法4: 卡特兰数数学公式 — O(n) / O(1)
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 解法3的递推式恰好是卡特兰数(Catalan Number)的定义：
//   C(0) = 1
//   C(n) = Σ C(i) * C(n-1-i)，i从0到n-1
//
// 卡特兰数有闭合公式：
//   C(n) = C(2n, n) / (n+1) = (2n)! / ((n+1)! * n!)
//
// 为避免大数阶乘溢出，使用递推关系：
//   C(n) = C(n-1) * 2*(2n-1) / (n+1)
//
// 推导：C(n)/C(n-1) = [C(2n,n)/(n+1)] / [C(2n-2,n-1)/n]
//                    = 2*(2n-1) / (n+1)
//
// 卡特兰数的其他应用：
// - n对合法括号序列数
// - 凸多边形三角剖分数
// - n个元素的合法出栈序列数
// - (0,0)到(n,n)不越过对角线的路径数
// ============================================================
class Solution4 {
public:
    int numTrees(int n) {
        // 用 long 防止中间乘法结果溢出 int
        long catalan = 1;
        for (int i = 1; i <= n; i++) {
            // 递推: C(i) = C(i-1) * 2*(2i-1) / (i+1)
            // 先乘后除，数学保证能整除
            catalan = catalan * 2 * (2 * i - 1) / (i + 1);
        }
        return (int)catalan;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间     | 空间  | 适用场景           |
// |-----------|----------|------|--------------------|
// | 暴力递归   | O(指数级) | O(n) | 理解问题分解方式     |
// | 记忆化搜索 | O(n²)    | O(n) | 从递归自然过渡到DP   |
// | DP递推     | O(n²)    | O(n) | 面试标准写法 ⭐      |
// | 卡特兰数   | O(n)     | O(1) | 面试加分/数学竞赛    |
//
// 解法1→2: 加 memo 消除重叠子问题，指数级降到 O(n²)
// 解法2→3: 记忆化翻译成递推，逻辑一样但避免递归开销
// 解法3→4: 识别出递推式是卡特兰数，用数学公式一步算出
//
// 【易错点】
// 1. dp[0] 初始化为 0 而非 1
//    ✗ dp[0] = 0 → dp[2] = dp[0]*dp[1]+dp[1]*dp[0] = 0，全部结果为0
//    ✓ dp[0] = 1 → 空树代表"没有子树"的 1 种合法情况
//    原因：在乘法 dp[j-1]*dp[i-j] 中，如果一边为空(0个节点)，
//          应该贡献 1（不影响另一边的计数），0 会把结果归零
//
// 2. 内层循环 j 从 0 开始而非 1
//    ✗ for(int j=0; j<i; j++) dp[i] += dp[j]*dp[i-1-j]
//      虽然这样也能算对(如果改了公式)，但语义不清晰
//    ✓ for(int j=1; j<=i; j++) dp[i] += dp[j-1]*dp[i-j]
//      j 代表根节点编号，从 1 到 i，语义清晰
//
// 3. 卡特兰数递推中使用 int 导致溢出
//    ✗ int catalan = 1; catalan = catalan * 2 * (2*i-1) / (i+1);
//      当 n=19 时，中间乘积 catalan*2*(2*19-1) 超过 int 范围
//    ✓ long catalan = 1; 用 long 确保中间结果不溢出
//
// 4. 混淆"节点编号"和"节点个数"
//    dp[i] 是 i 个节点(不管具体值)的BST数量
//    内层 j 是当前枚举的根节点(1到i)
//    左子树是 j-1 个节点(不是值为1到j-1的节点，但数量相同)
//
// 【面试追问】
// Q1: 为什么 BST 结构数只和节点个数有关？
//     → 因为 k 个不同数的相对大小关系固定(排序后第1小、第2小...)
//       所以和 {1,...,k} 构成的 BST 是同构的
//
// Q2: 如果要输出所有的 BST 而不只是计数？(LeetCode 95)
//     → 用递归枚举：对每个根 k，递归生成所有左右子树
//       返回 vector<TreeNode*>，两两配对组合
//       思路框架和本题一样，但返回值从 int 变成树列表
//
// Q3: 卡特兰数还有哪些等价问题？
//     → n对合法括号(22题)、n+1个矩阵连乘的加括号方式数、
//       2n个人排队买票(50元/100元各n人)的合法排队方式
//
// Q4: 如果 n 非常大(如 n=1000)，结果会溢出怎么办？
//     → 用大数运算或取模。如果取模 1e9+7，DP 解法中
//       dp[i] = (dp[i] + (long)dp[j-1]*dp[i-j]) % MOD
//       卡特兰数公式中的除法需要用模逆元
//
// 【关于迭代版本】
// 本题是纯 DP 计数问题，不涉及树的遍历，无需迭代版本。
// 解法3（DP 递推）本身就是迭代的自底向上计算，不存在递归栈开销。
//
// ============================================================
// 【空间优化说明】
//
// 解法3 的 dp[i] 已经是一维 O(n) 空间，无法进一步压缩。
//
// dp[i] = Σ dp[j-1] * dp[i-j]，j 从 1 到 i。
// 即 dp[i] 依赖 dp[0], dp[1], ..., dp[i-1] 的所有值（卡特兰数递推式），
// 不是只依赖前 1~2 个状态，因此无法用滚动变量替代。
//
// 例如：dp[5] = dp[0]*dp[4] + dp[1]*dp[3] + dp[2]*dp[2]
//              + dp[3]*dp[1] + dp[4]*dp[0]
// 需要同时访问 dp[0] 到 dp[4]，必须保留整个数组。
//
// 不过解法4（卡特兰数公式）直接用 O(1) 空间递推得出结果，
// 是真正意义上的"空间最优解"，但它利用的是数学公式而非 DP 压缩。
//
// 结论：DP 解法的 O(n) 空间无法压缩；若追求 O(1) 空间，使用卡特兰数公式。
// ============================================================
