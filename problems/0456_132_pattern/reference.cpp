/*
 * LeetCode 456: 132 模式 (132 Pattern)
 * 难度: Medium
 * 标签: Stack, Array, Monotonic Stack
 *
 * 题目: 给定整数数组 nums，判断是否存在 i < j < k 使得
 *       nums[i] < nums[k] < nums[j]  (即 "1" < "2" < "3"，位置是 1-3-2)
 *
 * 约束: 1 <= n <= 2*10^5, -10^9 <= nums[i] <= 10^9
 */


/* ============================================================
 * 解法 1: 单调递减栈（从右到左）— O(n) / O(n) [推荐]
 * ============================================================
 *
 * 核心思想:
 *   从右往左遍历，用单调递减栈维护 "3"(nums[j]) 的候选。
 *   被弹出的元素中的最大值是 "2"(nums[k]) 的最优候选。
 *   当前元素 < "2" 时，就是 "1"(nums[i])。
 *
 * 角色分配:
 *   当前元素 nums[i] → 候选 "1" (最小)
 *   栈中元素          → 候选 "3" (最大)，栈底到栈顶递减
 *   third 变量        → 候选 "2" (中间)，被弹出的最大值
 *
 * 栈状态推演 (nums = [3, 1, 4, 2]):
 *
 *   i=3: push 2       stack=[2]        third=-INF
 *         bottom [2] top
 *
 *   i=2: 4 > top=2    → pop 2, third=2
 *         push 4      stack=[4]        third=2
 *         bottom [4] top
 *         ※ 现在有一对: "3"=4, "2"=2
 *
 *   i=1: nums[1]=1 < third=2  → found "1"! return true
 *         ※ 132模式: 1 < 2 < 4  (位置 1,2,3)
 *
 * 栈状态推演 (nums = [1, 2, 3, 4]):
 *
 *   i=3: push 4       stack=[4]        third=-INF
 *   i=2: 3 < 4        push 3  stack=[4,3]     third=-INF
 *   i=1: 2 < 3        push 2  stack=[4,3,2]   third=-INF
 *   i=0: 1 < 2        push 1  stack=[4,3,2,1] third=-INF
 *   → 遍历结束, return false ✓
 *   ※ 单调递增→栈始终递减, 无弹出, third永远-INF
 *
 * 栈状态推演 (nums = [-1, 3, 2, 0]):
 *
 *   i=3: push 0       stack=[0]        third=-INF
 *
 *   i=2: 2 > top=0    → pop 0, third=max(-INF,0)=0
 *         push 2      stack=[2]        third=0
 *         bottom [2] top
 *         ※ "3"=2, "2"=0
 *
 *   i=1: 3 > top=2    → pop 2, third=max(0,2)=2
 *         push 3      stack=[3]        third=2
 *         bottom [3] top
 *         ※ "3"=3, "2"=2
 *
 *   i=0: nums[0]=-1 < third=2  → found! return true
 *         ※ 132模式: -1 < 2 < 3  (位置 0,1,2) ✓
 */
class Solution {
public:
    bool find132pattern(vector<int>& nums) {
        int n = nums.size();
        if (n < 3) return false;

        stack<int> stk;      // 单调递减栈，存 "3" 的候选值
        int third = INT_MIN; // "2" (nums[k]) 的最大候选值

        // 从右往左遍历
        for (int i = n - 1; i >= 0; i--) {
            // Step 1: 检查当前元素是否可以做 "1"
            // 如果 nums[i] < third，说明存在 j,k 在 i 右边
            // 使得 nums[i] < third(=nums[k]) < 某个被弹出前的栈元素(=nums[j])
            if (nums[i] < third) {
                return true;
            }

            // Step 2: 维护单调递减栈
            // 当前值 > 栈顶 → 弹出栈顶，更新 "2" 的候选
            // 弹出的值 < nums[i]，且在 nums[i] 的右边，是合法的 "2"
            while (!stk.empty() && nums[i] > stk.top()) {
                third = max(third, stk.top());
                stk.pop();
            }

            // Step 3: 当前元素入栈（作为 "3" 的候选）
            stk.push(nums[i]);
        }

        return false;
    }
};


