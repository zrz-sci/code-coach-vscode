/* ============================================================
 * 补充: 为什么 third 只需要记录最大值?
 * ============================================================
 *
 * 被弹出的值都满足: 弹出值 < 当前 nums[i] (弹出条件)
 * 且弹出值在 nums[i] 的右边 (因为我们从右往左扫)
 * 所以弹出值是合法的 "2" 候选
 *
 * 记录最大的弹出值是因为:
 * - third 越大，后续越容易找到 x < third 的 "1"
 * - 如果 x < smaller_third，必然 x < larger_third
 * - 所以最大的 third 包含了所有更小 third 的解
 *
 * 不会漏解:
 * - 只要存在合法 132 模式，third 的最大值一定能捕获到
 */


/* ============================================================
 * 知识点总结
 * ============================================================
 *
 * 1. 单调栈的核心性质:
 *    - 栈内元素单调 (递增或递减)
 *    - 每个元素最多入栈出栈各一次 → O(n)
 *    - 适合求 "下一个更大/更小" 类问题
 *
 * 2. 本题的单调栈用法 (非典型):
 *    不是求"下一个更大"，而是维护一对 (3, 2) 的候选
 *    栈存 "3" (较大值)，弹出的记录为 "2" (中间值)
 *
 * 3. 从右往左 vs 从左往右:
 *    从右到左: "1" 最后确定，easy (只需 < third)
 *    从左到右: "1" 先确定 (前缀min)，但 "2","3" 关系难维护
 *
 * 4. 时间 O(n), 空间 O(n)
 *    不能优化到 O(1) 空间 (需要栈)
 *
 * 5. 单调栈题目系列:
 *    LC 496  下一个更大元素 I (入门)
 *    LC 503  下一个更大元素 II (环形)
 *    LC 739  每日温度 (经典)
 *    LC 84   柱状图中最大的矩形 (进阶)
 *    LC 42   接雨水 (单调栈解法)
 *    LC 334  递增的三元子序列 ("123"模式)
 */

/*
 * ============================================================
 * 总结
 * ============================================================
 *
 * 【解法对比】
 * ┌─────────────────────────────┬────────┬────────┬──────────────────────────┐
 * │ 解法                        │ 时间   │ 空间   │ 特点                     │
 * ├─────────────────────────────┼────────┼────────┼──────────────────────────┤
 * │ 1. 单调递减栈(右→左) ⭐      │ O(n)   │ O(n)   │ 面试首选，一趟搞定       │
 * │ 2. 前缀最小值+暴力          │ O(n^2) │ O(n)   │ 易理解，面试讲思路用     │
 * │ 3. 前缀最小值+单调栈        │ O(n)   │ O(n)   │ 解法1和2的结合，更直观   │
 * └─────────────────────────────┴────────┴────────┴──────────────────────────┘
 *
 * 【易错点】
 * 1. third 初始化为 INT_MIN 而非 0: 数组可能包含负数，如 [-1,3,2,0]，
 *    如果 third=0 会漏判 nums[i]=-1 < third=0 的情况——等等，这个例子
 *    反而能判对。真正危险的是 [-2,-1,0,-3]，third 不应被初始化为 0。
 * 2. 遍历方向必须从右到左: 从左到右无法同时维护 "3"(较大) 和 "2"(中间)
 *    的候选关系，因为 "1" 还没确定。
 * 3. 先检查 nums[i] < third，再做弹栈: 顺序不能反。如果先弹栈再检查，
 *    当前 nums[i] 可能同时更新了 third 又充当了 "1"，角色冲突。
 * 4. 栈存的是值不是下标 (解法1): 解法3存下标是因为需要和 leftMin[j]
 *    配合。混用会导致比较逻辑出错。
 * 5. 数组长度 < 3 时直接返回 false: 容易忘记这个边界判断。
 *
 * 【面试追问】
 * Q1: "132模式" 和 "123模式" (LC 334) 有什么区别? 为什么 123 更简单?
 *     → 123 模式 (递增三元组) 只需维护最小值和次小值，贪心 O(n)/O(1)。
 *       132 模式的 "2"(中间值) 在 "3" 的右边且比 "3" 小，需要单调栈
 *       维护候选对，复杂度相同但思路更难。
 *
 * Q2: 能否找出所有 132 模式的三元组，而不仅是判断存在?
 *     → 最坏 O(n^3) 个三元组 (如锯齿数组)，枚举复杂度至少和输出规模一样。
 *       可以用解法3的前缀最小值+单调栈框架，在栈中二分找合法区间来枚举。
 *
 * Q3: 如果要求 i,j,k 不仅满足值的 132 关系，还要求 j-i <= d 且 k-j <= d
 *     (距离约束)，怎么修改?
 *     → 需要用滑动窗口 + 单调栈。栈中元素需要附带下标，超出距离 d 的
 *       候选要及时移除。时间仍 O(n)，但实现复杂度显著增加。
 */
