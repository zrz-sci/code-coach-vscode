/*
 * LeetCode 1570: 两个稀疏向量的点积 (Dot Product of Two Sparse Vectors)
 *
 * 【题目本质】
 * 设计一个稀疏向量类，核心问题是：如何只存储非零元素，
 * 并在计算点积时跳过所有零元素，只对两边都非零的位置做乘法。
 *
 * 【解法总览】
 * 解法1: 暴力存储       — O(n) / O(n)      — 最直觉，不利用稀疏性
 * 解法2: 哈希表存储     — O(L1+L2) / O(L)  — 面试首选，简洁高效
 * 解法3: 有序数组+双指针 — O(L1+L2) / O(L)  — 缓存友好，加分项
 *
 * 其中 L1, L2 = 两个向量各自的非零元素个数
 */

// ============================================================
// 解法1: 暴力存储 — 直接存完整数组
// 时间: O(n) 构造 + O(n) 点积
// 空间: O(n)
//
// 【思路】
// 最朴素的做法：把整个数组原样存下来。
// 计算点积时逐位置相乘累加。
// 完全没利用"稀疏"特性——如果向量长10万但只有5个非零，
// 仍然做了10万次乘法，其中99995次都是 0×x=0。
// 这就是我们要优化的瓶颈。
// ============================================================
class SparseVector1 {
public:
    vector<int> nums;

    SparseVector1(vector<int> &nums) : nums(nums) {}

    int dotProduct(SparseVector1& vec) {
        int result = 0;
        for (int i = 0; i < (int)nums.size(); i++) {
            result += nums[i] * vec.nums[i];
        }
        return result;
    }
};

// ============================================================
// 解法2: 哈希表存储 — 只存非零元素 ⭐ 面试首选
// 时间: O(n) 构造 + O(min(L1,L2)) 点积 (平均)
// 空间: O(L) 只存非零
//
// 【思路】
// 解法1的瓶颈：遍历了大量零元素。
// 观察：稀疏向量大部分是零，点积的贡献只来自两边都非零的位置。
// 所以只存非零的 {index → value}，计算时遍历一个表、查另一个表。
//
// 优化细节：遍历非零元素更少的那个（减少查找次数）。
// 例如 v1 有 10 个非零，v2 有 10000 个非零，
// 遍历 v1 只做 10 次查找，遍历 v2 则做 10000 次（9990 次查不到）。
// ============================================================
class SparseVector2 {
public:
    unordered_map<int, int> mp;  // index → value, 只存非零

    SparseVector2(vector<int> &nums) {
        for (int i = 0; i < (int)nums.size(); i++) {
            if (nums[i] != 0) {  // 关键：只存非零！
                mp[i] = nums[i];
            }
        }
    }

    int dotProduct(SparseVector2& vec) {
        // 优化：遍历非零元素更少的那个，减少查找次数
        if (mp.size() > vec.mp.size()) {
            return vec.dotProduct(*this);
        }

        int result = 0;
        for (auto& [idx, val] : mp) {
            auto it = vec.mp.find(idx);
            if (it != vec.mp.end()) {
                // 两个向量在 idx 位置都非零 → 贡献点积
                result += val * it->second;
            }
        }
        return result;
    }
};

// ============================================================
// 解法3: 有序数组 + 双指针 — 归并扫描
// 时间: O(n) 构造 + O(L1+L2) 点积
// 空间: O(L)
//
// 【思路】
// 哈希表虽然平均O(1)查找，但有哈希冲突和内存不连续的问题。
// 换一个存储方式：把非零元素存成 vector<pair<index, value>>。
// 由于从左到右遍历构建，天然按 index 升序排列。
//
// 两个有序列表求"交集位置的乘积和" = 经典双指针归并：
// - 两个指针各指向自己列表的开头
// - index 相等 → 相乘累加，两指针都前进
// - index 不等 → 较小的那个前进（因为较小的index在对方没有配对）
//
// 双指针归并过程示意:
// v1 的非零: [(0,1), (3,2), (4,3)]
// v2 的非零: [(1,3), (3,4)]
//             p1↑               p2↑
//
// Step1: p1.idx=0 < p2.idx=1  → p1++        result=0
// Step2: p1.idx=3 > p2.idx=1  → p2++        result=0
// Step3: p1.idx=3 == p2.idx=3 → 2*4=8       result=8, p1++, p2++
// Step4: p2 到头 → 结束
// 最终 result = 8 ✓
// ============================================================
class SparseVector {
public:
    vector<pair<int, int>> pairs;  // (index, value), 天然按index有序

    SparseVector(vector<int> &nums) {
        for (int i = 0; i < (int)nums.size(); i++) {
            if (nums[i] != 0) {
                pairs.push_back({i, nums[i]});
            }
        }
        // 无需排序：从左到右遍历，index 天然递增
    }

    int dotProduct(SparseVector& vec) {
        int result = 0;
        int p1 = 0, p2 = 0;

        while (p1 < (int)pairs.size() && p2 < (int)vec.pairs.size()) {
            if (pairs[p1].first == vec.pairs[p2].first) {
                // 同一位置都非零 → 贡献点积
                result += pairs[p1].second * vec.pairs[p2].second;
                p1++;  // 易错点：两个指针都要前进！
                p2++;
            } else if (pairs[p1].first < vec.pairs[p2].first) {
                // v1 的 index 更小，v2 在此处为零，跳过
                p1++;
            } else {
                // v2 的 index 更小，v1 在此处为零，跳过
                p2++;
            }
        }
        // 任一列表遍历完就结束——剩余的在对方都找不到配对
        return result;
    }
};

// ============================================================
// Follow-up: 只有一个向量稀疏时
//
// 思路：稀疏向量用哈希表/有序数组存，稠密向量保留原始数组。
// 计算时遍历稀疏的非零位置，在稠密数组中 O(1) 随机访问取值。
// 时间 = O(L_sparse)，完全不受稠密向量长度影响。
//
// 另一种思路：如果一个极稀疏(L1=10)，另一个非零很多(L2=10000)，
// 双指针是 O(L1+L2)=O(10010)，
// 但遍历稀疏的 + 在稠密的二分查找是 O(L1·log L2)=O(10·14)≈140，
// 远优于双指针。面试可以提这个优化。
// ============================================================

// ============================================================
// 【解法对比】
//
// | 方案       | 存储          | 点积时间           | 缓存友好 | 代码量 |
// |------------|---------------|--------------------|----------|--------|
// | 暴力       | 完整数组 O(n) | O(n)               | 好       | 最少   |
// | 哈希表     | 非零 O(L)     | O(min(L1,L2)) 平均 | 差       | 中等   |
// | 双指针     | 非零 O(L)     | O(L1+L2)           | 好       | 稍多   |
//
// 面试首选哈希表（直观好写），再提双指针（展示深度）。
// 实际工程中双指针更优：连续内存、缓存友好、无哈希开销。
//
// 【易错点】
// 1. 构造时忘记 if (nums[i] != 0) 过滤，把零也存进去了，
//    导致"稀疏存储"实际上还是存了所有元素，完全失去优化效果。
//
// 2. 双指针 index 相等时只递增一个指针：
//    ✗ if (p1.first == p2.first) { result += ...; p1++; }
//    ✓ if (p1.first == p2.first) { result += ...; p1++; p2++; }
//    漏掉 p2++ 会导致同一对被重复计算，结果偏大。
//
// 3. 哈希表解法没有选择遍历较小的那个：
//    功能正确但效率差。v1 有 10 个非零、v2 有 10000 个非零时，
//    遍历 v2 做 10000 次查找（9990 次白找），遍历 v1 只做 10 次。
//
// 【面试追问】
// Q1: 为什么要特殊处理稀疏向量？直接存数组有什么问题？
//     → 存储浪费 O(n) 空间，计算浪费 O(n) 时间，其中大部分是零。
//       只存非零可以同时优化存储和计算到 O(L)。
//
// Q2: 哈希表 vs 双指针，什么时候选哪个？
//     → 哈希表代码简洁，单次查找平均 O(1)，但有哈希冲突和缓存不友好。
//       双指针对缓存友好、无哈希开销，但需要两个都有序。
//       工程实践中，数据规模大时双指针通常更快。
//
// Q3 (Follow-up): 如果一个极稀疏(L1=10)一个很稠密(L2=10000)？
//     → 双指针 O(L1+L2)=10010。但遍历稀疏的 + 在稠密的二分查找
//       O(L1·log L2) ≈ 140，优几十倍。
//       更好的方案：稠密的保留原数组，稀疏的遍历非零位置直接索引取值，
//       O(L_sparse) = 10，最优。
// ============================================================
