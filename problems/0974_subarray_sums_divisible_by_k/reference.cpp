/*
 * LeetCode 974: 和可被 K 整除的子数组 (Subarray Sums Divisible by K)
 *
 * 【题目本质】
 * 统计连续子数组和能被 K 整除的个数。
 * 核心转化：子数组和 = 两前缀和之差，差能被 K 整除 ⟺ 两前缀和 mod K 相同。
 * 所以问题变成：在前缀和余数序列中，统计相同余数的配对数。
 *
 * 【解法总览】
 * 解法1: 暴力枚举    — O(n²) / O(n)  — 最直觉，枚举所有子数组
 * 解法2: 前缀和+哈希表 — O(n)  / O(K)  — 面试首选，余数配对计数
 * 解法3: 前缀和+数组  — O(n)  / O(K)  — 常数优化版，余数范围有限用数组
 *
 * 【前缀和与余数的关系图示】
 *
 *   nums:    [4,  5,  0, -2, -3,  1]
 *   prefix: 0  4   9   9   7   4   5
 *   mod 5:  0  4   4   4   2   4   0
 *
 *   余数分组:
 *     余数0: 位置{0, 6}       → 1对: (0,6)
 *     余数4: 位置{1, 2, 3, 5} → 6对: (1,2)(1,3)(1,5)(2,3)(2,5)(3,5)
 *     余数2: 位置{4}          → 0对
 *     总计: 1 + 6 + 0 = 7 ✓
 *
 *   为什么配对 (1,2) 对应子数组 [5]?
 *     prefix[2] - prefix[1] = 9 - 4 = 5, 5 % 5 = 0 ✓
 *     对应 nums[1..1] = [5]
 */

// ============================================================
// 解法1: 暴力枚举 — 枚举所有子数组，前缀和判断
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 最直觉的方法：先算前缀和数组，然后枚举所有 (i, j) 对，
// 检查 prefix[j] - prefix[i] 是否能被 k 整除。
// 瓶颈：O(n²) 对 n=3×10⁴ 来说太慢（约 9×10⁸ 次操作）。
// ============================================================
class Solution1 {
public:
    int subarraysDivByK(vector<int>& nums, int k) {
        int n = nums.size();
        vector<long long> prefix(n + 1, 0);
        for (int i = 0; i < n; i++) {
            prefix[i + 1] = prefix[i] + nums[i];
        }

        int result = 0;
        for (int i = 0; i < n + 1; i++) {
            for (int j = i + 1; j < n + 1; j++) {
                // 子数组 nums[i..j-1] 的和
                if ((prefix[j] - prefix[i]) % k == 0) {
                    result++;
                }
            }
        }
        return result;
    }
};

// ============================================================
// 解法2: 前缀和 + 哈希表 — 余数配对计数（面试首选）
// 时间: O(n)  空间: O(min(n, K))
//
// 【思路】
// 解法1枚举了 O(n²) 个配对，但我们其实不关心"具体是哪两个位置配对"，
// 只关心"有多少对"。
//
// 关键数学推导：
//   sum(i, j) = prefix[j+1] - prefix[i]
//   sum(i, j) % k == 0
//   ⟺ (prefix[j+1] - prefix[i]) % k == 0
//   ⟺ prefix[j+1] % k == prefix[i] % k
//
// 所以只要统计"到目前为止，有多少个前缀和的余数和我一样"。
// 用哈希表维护每个余数出现的次数，边遍历边统计。
//
// 关键：初始化 count[0] = 1（空前缀和为0，余数为0）。
// 关键：C++ 中负数 % k 可能为负，需要 ((x%k)+k)%k 修正。
// ============================================================
class Solution2 {
public:
    int subarraysDivByK(vector<int>& nums, int k) {
        unordered_map<int, int> count;
        // 空前缀：和为0，余数为0，作为配对的起点
        count[0] = 1;

        int prefix = 0;
        int result = 0;

        for (int num : nums) {
            prefix += num;

            // 处理负数余数：C++ 中 -1 % 5 = -1，但我们需要 4
            // 公式：((x % k) + k) % k 保证结果在 [0, k-1]
            int r = ((prefix % k) + k) % k;

            // 之前有 count[r] 个前缀和余数也是 r
            // 每个都能和当前位置配对 → 贡献 count[r] 个合法子数组
            result += count[r];

            // 更新计数（注意：先查后更新，避免自己和自己配对）
            count[r]++;
        }

        return result;
    }
};

// ============================================================
// 解法3: 前缀和 + 固定数组 — 常数优化版
// 时间: O(n)  空间: O(K)
//
// 【思路】
// 和解法2完全一样的逻辑。
// 优化点：余数范围是 [0, k-1]，最多 k 种值。
// 用 vector<int>(k) 代替 unordered_map，避免哈希冲突和开销。
// 当 k ≤ 10⁴ 时，数组访问比哈希表快很多。
// ============================================================
class Solution3 {
public:
    int subarraysDivByK(vector<int>& nums, int k) {
        vector<int> count(k, 0);
        count[0] = 1;

        int prefix = 0;
        int result = 0;

        for (int num : nums) {
            prefix += num;
            int r = ((prefix % k) + k) % k;
            result += count[r];
            count[r]++;
        }

        return result;
    }
};

// ============================================================
// 【解法对比】
//
// 解法1 (暴力) → 解法2 (哈希表):
//   瓶颈是 O(n²) 枚举配对。利用"余数相同"这个等价条件，
//   把"枚举配对"变成"计数配对"，只需一次遍历。
//
// 解法2 (哈希表) → 解法3 (数组):
//   逻辑完全一样，但余数范围有限 [0,k-1]，
//   数组随机访问 O(1) 且无哈希开销，常数更小。
//
// 面试建议：直接写解法3。如果面试官问思路，从暴力→前缀和→余数等价开始讲。
//
// ============================================================
// 【易错点】
//
// 1. 负数取余:
//    ✗ int r = prefix % k;
//      当 prefix = -1, k = 5 时, r = -1 (C++ 规定)
//    ✓ int r = ((prefix % k) + k) % k;
//      得到 r = 4, 正确落入 [0, k-1]
//
// 2. 忘记 count[0] = 1:
//    ✗ 不初始化 → 漏掉"从数组开头到当前位置的和恰好被 K 整除"的情况
//    例如 nums=[5], k=5: prefix=5, r=0, 此时 count[0] 应为1才能统计到
//    ✓ count[0] = 1 代表空前缀（和为0）
//
// 3. 先更新后查询 (顺序搞反):
//    ✗ count[r]++; result += count[r];
//      → 自己和自己配对了，多算了1
//    ✓ result += count[r]; count[r]++;
//      → 只和之前出现过的配对
//
// 4. 前缀和用 int 是否溢出:
//    n ≤ 3×10⁴, |nums[i]| ≤ 10⁴ → |prefix| ≤ 3×10⁸ < 2×10⁹ (int 安全)
//    但更保险可以用 long long
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1 (基础): "暴力法怎么做？瓶颈在哪？"
//    → O(n²) 枚举所有子数组，瓶颈在配对枚举。
//
// Q2 (核心): "怎么从 O(n²) 优化到 O(n)？"
//    → 子数组和 = 前缀和之差，差被 K 整除 ⟺ 余数相同。
//      用哈希表统计余数出现次数，每遇到相同余数就累加。
//
// Q3 (细节): "为什么要 ((x%k)+k)%k？直接 x%k 不行吗？"
//    → C++ 中负数取余的结果是负数 (如 -1%5=-1)，
//      但我们需要非负余数来正确分组。加 k 再取余修正。
//
// Q4 (变体): "如果改成求'和被 K 整除的最长子数组长度'呢？"
//    → 哈希表不存 count 而存"每个余数第一次出现的索引"。
//      遇到相同余数时，当前索引 - 首次索引 = 子数组长度，取 max。
//
// Q5 (变体): "和 LeetCode 523 有什么区别？"
//    → 523 问是否存在长度≥2的子数组，所以哈希表存首次索引，
//      且需要检查 j - i >= 2。本题问个数，所以存计数。
//
// 【相关题型】
// - LC 560 (和为K的子数组): 同框架，区别是精确匹配 prefix[j]-prefix[i]==k
//     而非余数匹配。哈希表存的是 prefix 值而非 prefix%k。
// - LC 523 (连续的子数组和): 同余数思路，改存首次索引+判断长度≥2
// - LC 525 (连续数组): 把 0→-1 转化后，变成 prefix 相同（余数=0的特例）
// - LC 1 (两数之和): "边遍历边查表找配对"这个模式的鼻祖
// ============================================================
