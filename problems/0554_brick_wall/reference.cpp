/*
 * LeetCode 554: 砖墙 (Brick Wall)
 * 
 * 【题目本质】
 * 在砖墙上画一条竖线，使穿过的砖块最少。
 * 等价于：找一个 x 坐标，使得该位置上"砖缝"出现的行数最多。
 * 答案 = 总行数 - 最大砖缝数。
 *
 * 【解法总览】
 * 解法1: 暴力枚举所有 x 位置 — O(W × n) / O(1) — 概念理解，W 大时不可行
 * 解法2: 哈希表统计砖缝     — O(总砖块数) / O(总砖块数) — 面试首选
 */

/*
 * 砖墙示意图 (示例1):
 *
 *   x坐标: 0  1  2  3  4  5  6
 *          |  |     |     |  |
 *   Row 0: |1 | 2   | 2   |1 |     砖缝: x=1, 3, 5
 *   Row 1: |  3     |1 | 2   |     砖缝: x=3, 4
 *   Row 2: |1 |  3     | 2   |     砖缝: x=1, 4
 *   Row 3: | 2   |  4         |     砖缝: x=2
 *   Row 4: |  3     |1 | 2   |     砖缝: x=3, 4
 *   Row 5: |1 |  3     |1 |1 |     砖缝: x=1, 4, 5
 *
 *   哈希表统计:
 *     x=1 → 3次 (Row 0, 2, 5)
 *     x=2 → 1次 (Row 3)
 *     x=3 → 3次 (Row 0, 1, 4)
 *     x=4 → 4次 (Row 1, 2, 4, 5)  ← 最大！
 *     x=5 → 2次 (Row 0, 5)
 *
 *   最大砖缝数 = 4，答案 = 6 - 4 = 2
 *   在 x=4 处画线，只穿过 Row 3 和 Row 0 共 2 块砖
 */

// ============================================================
// 解法1: 暴力枚举 — 枚举所有整数 x 位置，逐行检查
// 时间: O(W × n)，W = 墙的总宽度，可达 2^31，实际不可行
// 空间: O(1)
//
// 【思路】
// 最直觉的想法：对每个可能的 x 坐标，遍历每一行看是否在砖缝上。
// 如果不在砖缝上，这一行被穿过。统计穿过的最小值。
// 
// 瓶颈：x 的范围由砖的宽度决定，可能极大。
// 而实际有效的位置只有砖缝出现的 x 坐标，数量 ≤ 总砖块数。
// 这个观察直接引出解法2。
// ============================================================
class Solution1 {
public:
    int leastBricks(vector<vector<int>>& wall) {
        int n = wall.size();

        // 计算墙的总宽度
        long long totalWidth = 0;
        for (int w : wall[0]) totalWidth += w;

        int minCross = n;

        // 枚举每个整数 x 位置
        for (long long x = 1; x < totalWidth; x++) {
            int cross = 0;
            for (int i = 0; i < n; i++) {
                long long pos = 0;
                bool hitEdge = false;
                // 检查第 i 行在 x 处是否有砖缝
                for (int j = 0; j < (int)wall[i].size() - 1; j++) {
                    pos += wall[i][j];
                    if (pos == x) { hitEdge = true; break; }
                    if (pos > x) break; // 已经超过 x，不用继续
                }
                if (!hitEdge) cross++; // 没有砖缝 = 穿过这块砖
            }
            minCross = min(minCross, cross);
        }

        return minCross;
    }
};

// ============================================================
// 解法2: 哈希表统计砖缝 — 前缀和 + 计数 ⭐ 面试首选
// 时间: O(总砖块数)  空间: O(总砖块数)
//
// 【思路】
// 核心逆向思维：穿过的砖数 = 总行数 - 经过的砖缝数。
// 要最小化穿过 → 最大化砖缝数。
//
// 怎么找砖缝？每一行砖块宽度的前缀和（不含最后一个）就是砖缝的 x 坐标。
// 例如 [1, 2, 2, 1]，前缀和 = [1, 3, 5, 6]，砖缝在 x = 1, 3, 5。
// 
// 用哈希表记录每个 x 坐标出现了多少行有砖缝，
// 取最大值 maxEdges，答案 = n - maxEdges。
//
// 为什么要排除最后一块砖？因为前缀和的最后一个值是墙的总宽度，
// 即右边界，题目明确不允许沿墙的两侧画线。
// ============================================================
class Solution2 {
public:
    int leastBricks(vector<vector<int>>& wall) {
        unordered_map<long long, int> edgeCount;
        // key: 砖缝的 x 坐标 (前缀和)
        // value: 有多少行在这个位置有砖缝

        for (const auto& row : wall) {
            long long prefixSum = 0;
            // 遍历到倒数第二块砖（排除右边界）
            for (int i = 0; i < (int)row.size() - 1; i++) {
                prefixSum += row[i];
                edgeCount[prefixSum]++;
            }
        }

        // 找最大砖缝数
        int maxEdges = 0;
        for (const auto& [pos, cnt] : edgeCount) {
            maxEdges = max(maxEdges, cnt);
        }

        // 穿过的砖 = 总行数 - 最多能经过的砖缝数
        return (int)wall.size() - maxEdges;
    }
};

// ============================================================
// 【解法对比】
//
// | 方面       | 解法1 暴力枚举        | 解法2 哈希表统计      |
// |------------|----------------------|----------------------|
// | 时间       | O(W × n)，W可达2^31  | O(总砖块数) ≤ 2×10^4 |
// | 空间       | O(1)                 | O(总砖块数)           |
// | 核心思想   | 正向：逐位置检查      | 逆向：统计砖缝取最大  |
// | 面试推荐   | 仅用于说明思路        | ⭐ 必须写出           |
//
// 解法2 的关键洞察是"逆向思维"：不统计穿过的砖，
// 而统计经过的砖缝。这把问题从"最小化"变成了"最大化计数"，
// 哈希表天然擅长计数操作。
//
// ============================================================
// 【易错点】
//
// 1. 忘记排除右边界：
//    ✗ for (int i = 0; i < row.size(); i++)
//      → 右边界(总宽度)也被当成砖缝，每行都有，计数 = n，
//        答案变成 n - n = 0，永远返回 0
//    ✓ for (int i = 0; i < (int)row.size() - 1; i++)
//      → 只统计内部砖缝
//
// 2. 哈希表为空导致 maxEdges 未更新：
//    当每行只有一块砖（如 [[1],[1],[1]]），没有内部砖缝，
//    edgeCount 为空。此时 maxEdges 保持 0，答案 = n，正确。
//    但如果有人用 max_element 等函数在空容器上调用会 UB/崩溃。
//    ✓ 初始化 maxEdges = 0 最安全。
//
// 3. 前缀和溢出 int：
//    wall[i][j] 可达 2^31-1，两块砖的前缀和可能溢出 32 位 int。
//    ✓ 使用 long long 做前缀和（虽然本题约束下总砖块数有限，
//       但面试写 long long 更严谨）。
//
// 4. row.size() - 1 的无符号减法陷阱：
//    row.size() 返回 size_t (无符号)，如果 row 只有 1 个元素，
//    row.size() - 1 = 0，循环不执行，没问题。
//    但如果 row 为空（题目不会，但防御性编程），
//    row.size() - 1 会下溢成巨大数。
//    ✓ 强转 (int)row.size() - 1 更安全。
//
// ============================================================
// 【面试追问】
//
// Q1: "暴力法为什么不行？瓶颈在哪？"
//   → 瓶颈在枚举 x 位置。墙的宽度 W 可达 2^31，
//     但有效砖缝位置 ≤ 总砖块数 ≤ 2×10^4。
//     所以不应该枚举 x 值域，而应该只看砖缝位置。
//
// Q2: "为什么是 n - maxEdges，而不是直接统计穿过的砖？"
//   → 每行在某个 x 位置要么有砖缝（+0穿过），要么没有（+1穿过）。
//     穿过数 = n - 砖缝数。最小化穿过 = 最大化砖缝数。
//     这样只需要一个 max 操作，比直接统计 min 更自然。
//
// Q3: "如果有多个最优位置，怎么全部找出来？"
//   → 第一遍遍历哈希表找到 maxEdges，
//     第二遍收集所有 cnt == maxEdges 的 pos。
//     或者一遍完成：维护一个 vector，
//     遇到更大的 cnt 就清空重新收集。
//
// Q4: "如果砖墙非常高(n很大)但每行砖块数很少，
//      和砖墙很矮但每行砖块数很多，哪种情况更耗内存？"
//   → 哈希表大小取决于不同砖缝位置的数量。
//     n 很大但每行砖少：砖缝种类少，哈希表小，但计数值大。
//     n 小但每行砖多：砖缝种类多，哈希表大。
//     空间主要由砖缝种类数（不同的前缀和个数）决定。
// ============================================================
