/*
 * LeetCode 225: 用队列实现栈 (Implement Stack using Queues)
 *
 * 【题目本质】
 * 在 FIFO（先进先出）的队列约束下，模拟 LIFO（后进先出）的栈行为。
 * 核心矛盾：队列从前面取，栈从后面取，必须通过某种方式"翻转"顺序。
 *
 * 【解法总览】
 * 解法1: 两个队列 (push O(1), pop O(n)) — 最直觉，pop时搬元素
 * 解法2: 两个队列 (push O(n), pop O(1)) — push时调整顺序
 * 解法3: 一个队列 (push O(n), pop O(1)) — Follow-up，push时自旋转
 */

// ============================================================
// 解法1: 两个队列 — push O(1), pop/top O(n)
//
// 【思路】
// 最自然的想法：push 直接入队很快，pop 时再找"最后进来的"。
// 怎么找？把 q1 前面的 n-1 个元素搬到 q2，剩下的最后一个就是栈顶。
// 搬完后 swap(q1, q2) 让 q1 重新成为主队列。
//
// push(1), push(2), push(3) 后:  q1 = [1, 2, 3]
//                                       ↑前       ↑后(栈顶)
// pop(): 搬1,2到q2 → q2=[1,2], q1=[3] → 取3 → swap → q1=[1,2]
//
// 时间: push O(1), pop O(n), top O(n)
// 空间: O(n)
// ============================================================
class MyStack1 {
    queue<int> q1, q2;
public:
    MyStack1() {}

    void push(int x) {
        q1.push(x);
    }

    int pop() {
        // 把前 n-1 个元素搬到 q2
        while (q1.size() > 1) {
            q2.push(q1.front());
            q1.pop();
        }
        // 最后一个就是"栈顶"
        int topVal = q1.front();
        q1.pop();
        // q1 现在为空，q2 有剩余元素，交换恢复
        swap(q1, q2);
        return topVal;
    }

    int top() {
        while (q1.size() > 1) {
            q2.push(q1.front());
            q1.pop();
        }
        int topVal = q1.front();
        // 注意：top 不删除元素，所以要把它也放回 q2
        q2.push(q1.front());
        q1.pop();
        swap(q1, q2);
        return topVal;
    }

    bool empty() {
        return q1.empty();
    }
};

// ============================================================
// 解法2: 两个队列 — push O(n), pop/top O(1)
//
// 【思路】
// 解法1 的瓶颈：pop/top 每次都要搬 n-1 个元素。
// 反过来想：如果 push 的时候就把新元素放到队头位置，
// 那 q1 始终保持"栈序"（队头 = 栈顶），pop/top 直接取队头。
//
// 怎么做到？
// 1. 把新元素 x 放进空的 q2
// 2. 把 q1 所有旧元素依次搬到 q2 后面
// 3. swap(q1, q2)
// 这样 q1 的队头就是 x（最新 = 栈顶）
//
// push(1):  q2=[1] → 搬q1(空)到q2 → swap → q1=[1]
// push(2):  q2=[2] → 搬q1=[1]到q2 → q2=[2,1] → swap → q1=[2,1]
// push(3):  q2=[3] → 搬q1=[2,1]到q2 → q2=[3,2,1] → swap → q1=[3,2,1]
//           q1的队头3就是栈顶 ✓
//
// 时间: push O(n), pop O(1), top O(1)
// 空间: O(n)
// ============================================================
class MyStack2 {
    queue<int> q1, q2;
public:
    MyStack2() {}

    void push(int x) {
        // 新元素先进空的 q2
        q2.push(x);
        // 把 q1 的所有旧元素搬到 q2 后面（x 后面）
        while (!q1.empty()) {
            q2.push(q1.front());
            q1.pop();
        }
        // q1 和 q2 角色互换
        swap(q1, q2);
        // 此时 q1 队头 = x = 栈顶, q2 为空
    }

    int pop() {
        // q1 队头就是栈顶，直接取
        int topVal = q1.front();
        q1.pop();
        return topVal;
    }

    int top() {
        return q1.front();
    }

    bool empty() {
        return q1.empty();
    }
};

// ============================================================
// 解法3: 一个队列 — Follow-up 最优解
//
// 【思路】
// 解法2 用 q2 只是作为临时中转，其实可以省掉！
// 关键技巧：push(x) 后，把 x 前面的 n 个旧元素依次出队再入队，
// 相当于"旋转"队列，让 x 到达队头。
//
// push(1): q=[1], n=0, 不旋转 → q=[1]
//
// push(2): q=[1,2], n=1
//          旋转1次: pop 1, push 1 → q=[2,1]
//          2在队头 ✓
//
// push(3): q=[2,1,3], n=2
//          旋转第1次: pop 2, push 2 → q=[1,3,2]
//          旋转第2次: pop 1, push 1 → q=[3,2,1]
//          3在队头 ✓
//
// pop(): front()=3, pop → q=[2,1]
// top(): front()=2 ✓
//
// 时间: push O(n), pop O(1), top O(1)
// 空间: O(n) — 只用一个队列
// ============================================================
class MyStack {
    queue<int> q;
public:
    MyStack() {}

    void push(int x) {
        int n = q.size();  // 记录 push 前有多少个旧元素
        q.push(x);
        // 把 x 前面的 n 个旧元素依次出队再入队到 x 后面
        // 效果：x "旋转"到了队头
        for (int i = 0; i < n; i++) {
            q.push(q.front());
            q.pop();
        }
    }

    int pop() {
        int topVal = q.front();
        q.pop();
        return topVal;
    }

    int top() {
        return q.front();
    }

    bool empty() {
        return q.empty();
    }
};

// ============================================================
// 【解法对比】
//
// | 操作    | 解法1 (push轻) | 解法2 (push重) | 解法3 (单队列) |
// |---------|----------------|----------------|----------------|
// | push    | O(1)           | O(n)           | O(n)           |
// | pop     | O(n)           | O(1)           | O(1)           |
// | top     | O(n)           | O(1)           | O(1)           |
// | 队列数  | 2              | 2              | 1              |
//
// 面试推荐: 解法3 — 代码最简洁，一个队列满足 Follow-up。
// 
// 解法2 vs 解法3 的本质相同：都是 push 时调整顺序。
// 区别仅在于：解法2 借助第二个队列做中转，解法3 让队列自旋转。
//
// 【易错点】
//
// 1. 解法1 的 top() 漏放回元素:
//    ✗ int t = q1.front(); q1.pop(); swap(q1,q2); return t;
//      → q1 少了一个元素！
//    ✓ 取出后 q2.push(t) 再 swap
//
// 2. 解法3 旋转次数用 q.size() 而不是预存 n:
//    ✗ for(int i=0; i<q.size(); i++) — push 后 q.size()=n+1,
//      多旋转一次导致新元素又回到队尾！
//    ✓ int n = q.size(); q.push(x); for(int i=0; i<n; i++)
//
// 3. swap(q1,q2) 后 q2 不空导致后续 push 出错:
//    确保逻辑正确：swap 后 q2 应始终为空。
//    解法2 中 swap 前 q1 已被清空所以 swap 后 q2(原q1)=空 ✓
//
// 【面试追问】
//
// Q1: push 和 pop 能否都做到 O(1)？
// → 不能。队列的 FIFO 和栈的 LIFO 顺序相反，
//   "翻转"代价不可避免，只是分配给 push 还是 pop。
//   amortized O(1) 也做不到（不像 232 用栈实现队列可以均摊）。
//
// Q2: 和 232 题（用栈实现队列）有什么区别？
// → 232 可以利用"两个栈翻转"做到 push O(1)、pop 均摊 O(1)。
//   但本题用队列实现栈做不到均摊 O(1)，因为队列的出队顺序
//   无法像两个栈那样"延迟翻转"。
//
// Q3: 如果面试官要求所有操作都 O(1) 怎么办？
// → 坦诚说不可能。可以讨论用 deque 就能 O(1) 所有操作，
//   但那违反了"只用队列标准操作"的约束。
//   这说明你理解了这道题的核心：约束下的设计权衡。
// ============================================================
