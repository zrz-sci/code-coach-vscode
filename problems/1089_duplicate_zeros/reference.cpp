/*
 * LeetCode 1089: Duplicate Zeros (复写零)
 *
 * 【题目本质】
 * 给定定长整数数组，遇到0就复制一份，其余元素右移，超出数组长度的丢弃。
 * 要求原地(in-place)操作，不返回任何东西。
 *
 * 【解法总览】
 * 解法1: 额外数组      — O(n) / O(n)   — 直觉模拟，理解题意
 * 解法2: 两遍扫描       — O(n) / O(1)   — 面试首选，原地操作
 */


// ============================================================
// 解法1: 额外数组 — 直接模拟复写过程
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 不考虑空间限制，直接按规则构建结果：
// 遍历原数组，非零写一个，零写两个，写满 n 个截断。
//
// 示例: arr = [1, 0, 2, 3, 0, 4, 5, 0]
//   result: 1 → [1]
//   result: 0 → [1, 0, 0]
//   result: 2 → [1, 0, 0, 2]
//   result: 3 → [1, 0, 0, 2, 3]
//   result: 0 → [1, 0, 0, 2, 3, 0, 0]
//   result: 4 → [1, 0, 0, 2, 3, 0, 0, 4] → 满8个，停！
//
// 这个解法的价值：明确了复写零的本质操作，为原地解法打基础。
// ============================================================
class Solution1 {
public:
    void duplicateZeros(vector<int>& arr) {
        int n = arr.size();
        vector<int> result;
        result.reserve(n);

        for (int x : arr) {
            result.push_back(x);
            if (x == 0) result.push_back(0); // 零复写一份
            if ((int)result.size() >= n) break; // 写满就停
        }

        // 将结果拷贝回原数组（只取前 n 个）
        for (int i = 0; i < n; i++) {
            arr[i] = result[i];
        }
    }
};

// ============================================================
// 解法2: 两遍扫描（从后往前填充） — 面试首选 ⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 从前往后填充会覆盖未处理的数据，所以改为从后往前。
// 但要从后往前，得先知道"结果的最后一个位置对应原数组的哪个元素"。
//
// 两遍扫描策略：
//   第一遍（正向）: 数零 → 确定原数组中哪些元素会出现在最终结果里
//   第二遍（反向）: 从后往前填充 → 遇0写两个，非0写一个
//
// 为什么从后往前不会覆盖未读数据？
//   设当前读位置为 i，写位置为 j = i + remaining_zeros
//   因为 remaining_zeros >= 0，所以 j >= i 恒成立
//   写入位置永远在读取位置的右侧或相同位置，安全！
//
// 示例: arr = [1, 0, 2, 3, 0, 4, 5, 0], n = 8
//
//   第一遍: 统计零并找到最后一个保留的元素
//     i=0: 1, zeros=0, 0+0=0<8 ✓
//     i=1: 0, zeros=1, 1+1=2<8 ✓
//     i=2: 2, zeros=1, 2+1=3<8 ✓
//     i=3: 3, zeros=1, 3+1=4<8 ✓
//     i=4: 0, zeros=2, 4+2=6<8 ✓
//     i=5: 4, zeros=2, 5+2=7<8 ✓
//     i=6: 5, zeros=2, 6+2=8 → 不满足 i+zeros<n → 停！
//     回退: i-- → i=5 (最后一个保留的元素 arr[5]=4)
//
//   第二遍: 从后往前填充
//     j=7: arr[5]=4 → arr[7]=4        → j=6, i=4
//     j=6: arr[4]=0 → arr[6]=0,arr[5]=0 → j=4, i=3
//     j=4: arr[3]=3 → arr[4]=3        → j=3, i=2
//     j=3: arr[2]=2 → arr[3]=2        → j=2, i=1
//     j=2: arr[1]=0 → arr[2]=0,arr[1]=0 → j=0, i=0
//     j=0: arr[0]=1 → arr[0]=1        → j=-1 → 结束
//
//   结果: [1, 0, 0, 2, 3, 0, 0, 4] ✓
//
//
// 边界特例: arr = [8, 4, 5, 0, 0, 0, 0, 7], n = 8
//
//   第一遍:
//     i=0: 8, z=0 → 0<8 ✓    i=1: 4, z=0 → 1<8 ✓
//     i=2: 5, z=0 → 2<8 ✓    i=3: 0, z=1 → 4<8 ✓
//     i=4: 0, z=2 → 6<8 ✓    i=5: 0, z=3 → 8 → 不满足 → 停！
//     回退: i=4
//
//   检查边界: i+zeros = 4+3 = 7, 而 n-1=7
//   但 i+zeros (=7) < n (=8)? 不，循环是 i+zeros < n。
//   等等，i=5退出, zeros=3, 所以 i+zeros=8==n。回退 i-- 变成 i=4。
//   i+zeros=4+3=7 < 8? 不对，zeros还是3吗？
//
//   更准确的推导: 循环退出时 i=5, zeros=3, 5+3=8>=8。
//   回退 i--=4。但需要检查: i=5(退出前)处 arr[5]=0 导致 zeros从2变3。
//   现在 i=4, 但 i+zeros=4+3=7...
//   其实需要检查的条件是: 退出时(回退前) i+zeros==n 且 arr[i]==0。
//   这里退出前 i=5, i+zeros=5+3=8==n, arr[5]=0 → 触发边界！
//   处理: arr[7]=0 (单写一个0), j=6, i=4
//   然后正常填充...
//   结果: [8, 4, 5, 0, 0, 0, 0, 0]
// ============================================================
class Solution2 {
public:
    void duplicateZeros(vector<int>& arr) {
        int n = arr.size();
        int zeros = 0; // 遇到的零的数量
        int i = 0;

        // ---- 第一遍: 找到最后一个能留在结果数组中的元素 ----
        // 循环不变式: arr[0..i-1] 复写后产生 i+zeros 个元素
        // 当 i+zeros >= n 时停止，说明结果已填满
        for (i = 0; i + zeros < n; i++) {
            if (arr[i] == 0) zeros++;
        }
        i--; // 循环多走了一步，回退到最后一个有效元素

        int j = n - 1; // 写入指针，从数组末尾开始

        // ---- 边界处理: 最后一个保留元素是0，但只剩一个格子 ----
        // 条件: i+zeros == n 且 arr[i] == 0
        // 含义: 这个零的"复写分身"溢出了数组边界，只能写一份
        //
        // 例: [1, 0, 0, 0, 0] → 第一遍找到 i=3(arr[3]=0), zeros=3
        //     i+zeros = 3+3 = 6 > 5? 不，循环条件是 i+zeros<n...
        //     需要具体分析每道题的实际值
        if (i + zeros == n && arr[i] == 0) {
            arr[j--] = 0;  // 这个0只能写一份（复写溢出了）
            i--;            // 这个0已经处理完，后退
        }

        // ---- 第二遍: 从后往前填充 ----
        // 读指针 i 从最后一个保留元素往前走
        // 写指针 j 从数组末尾往前走
        // 不变式: j = i + (i之后还需要考虑的零的数量)
        while (j >= 0) {
            // 写入当前元素
            arr[j--] = arr[i];

            // 如果是零，再写一份（复写）
            if (arr[i] == 0 && j >= 0) {
                arr[j--] = 0;
            }

            i--; // 前进到下一个（更靠前的）原始元素
        }
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 时间  | 空间  | 原地 | 难度      |
// |------------|-------|-------|------|----------|
// | 额外数组    | O(n)  | O(n)  | 否   | 简单      |
// | 两遍扫描    | O(n)  | O(1)  | 是   | 中等(边界)|
//
// 面试选择: 先口述额外数组思路表明理解题意，然后写两遍扫描。
//
// ============================================================
// 【易错点】
//
// 1. 第一遍循环条件写成 i < n:
//    ✗ for (i = 0; i < n; i++) if(arr[i]==0) zeros++;
//      这只是数了所有零的个数，没有考虑复写后的截断效果。
//      比如 [1,0,2,3,0,4,5,0] 有3个零，但不能直接用。
//    ✓ for (i = 0; i + zeros < n; i++)
//      当复写后的逻辑长度 >= n 时立即停止。
//
// 2. 忘记边界特殊处理:
//    ✗ 直接进入第二遍 → 最后一个保留元素是0时会写两份，
//      但只有一个格子，导致数组越界或写到不该写的位置。
//    ✓ 先检查 i+zeros==n && arr[i]==0，手动处理后再主循环。
//
// 3. 循环结束后忘记 i--:
//    ✗ 第一遍 for 循环退出时 i 比最后一个有效位置多1
//    ✓ 加上 i-- 回退
//
// 4. 第二遍写零时忘记检查 j >= 0:
//    ✗ arr[j--] = arr[i]; if(arr[i]==0) arr[j--] = 0;
//      当 j 在写完第一个值后变为 -1，再写会越界
//    ✓ if (arr[i] == 0 && j >= 0) arr[j--] = 0;
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么不能从前往后原地操作？
//     从前往后遇到0要右移后续所有元素，会覆盖数据。
//     即使逐个移动总时间也是 O(n²)。
//
// Q2: 能否一遍完成？
//     不能。你必须先知道最终边界在哪，否则不知道从哪开始
//     填充。这需要一次完整的正向扫描。
//
// Q3: 这题和88.合并两个有序数组有什么联系？
//     核心技巧相同——从后往前填充避免覆盖。
//     88题是两个有序数组合并到nums1的预留空间中。
//     两者都利用"写入位置 >= 读取位置"的不变式。
//
// ============================================================
// 【相关题型】
//
// - 88. 合并两个有序数组:
//   同样的从后往前填充技巧，nums1末尾有预留空间。
//
// - 283. 移动零:
//   把所有零移到末尾，双指针从前往后即可（更简单）。
//   区别：283是删除零再补，1089是复写零再截断。
//
// - 26. 删除有序数组中的重复项:
//   原地操作经典题，双指针维护写入位置。
//   和本题方向相反（26是"缩短"数组，1089是"扩展"后截断）。
// ============================================================
