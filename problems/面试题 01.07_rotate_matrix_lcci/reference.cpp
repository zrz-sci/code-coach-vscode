/*
 * 面试题 01.07: 旋转矩阵 (同主站 LeetCode 48: Rotate Image)
 *
 * 难度: Medium
 * 标签: Array, Math, Matrix
 *
 * 题意:
 *   将 N x N 矩阵原地顺时针旋转 90 度
 *   不能使用额外的矩阵空间
 *
 * 核心坐标变换:
 *   顺时针 90°: (i, j) → (j, n-1-i)
 *
 * 旋转过程 — 方法1(转置+翻转):
 *
 *   原矩阵:           转置(沿\翻折):    每行reverse:
 *   [ 1  2  3 ]       [ 1  4  7 ]       [ 7  4  1 ]
 *   [ 4  5  6 ]  →    [ 2  5  8 ]  →    [ 8  5  2 ]
 *   [ 7  8  9 ]       [ 3  6  9 ]       [ 9  6  3 ]
 *
 *   数学验证: (i,j) --转置--> (j,i) --行翻转--> (j, n-1-i)
 *             = 顺时针 90° 的坐标变换 ✓
 *
 * 旋转过程 — 方法2(四角轮转):
 *
 *   4x4矩阵, 第0层第0个旋转组:
 *   [ A  .  .  D ]     temp = A
 *   [ .  .  .  . ]     A ← M (左→上)
 *   [ .  .  .  . ]     M ← P (下→左)
 *   [ M  .  .  P ]     P ← D (右→下)
 *                      D ← temp (上→右)
 *
 *   结果:
 *   [ M  .  .  A ]
 *   [ .  .  .  . ]
 *   [ .  .  .  . ]
 *   [ P  .  .  D ]
 */

// =====================================================
// 解法1: 转置 + 水平翻转 (推荐, 最简洁)
// 时间: O(n^2)   空间: O(1)
// =====================================================
class Solution {
public:
    void rotate(vector<vector<int>>& matrix) {
        int n = matrix.size();

        // --- 步骤1: 沿主对角线转置 ---
        //
        // 只遍历上三角 (j > i), 避免重复交换
        // 交换: matrix[i][j] ↔ matrix[j][i]
        //
        //  遍历位置 (以3x3为例):
        //  [ .  *  * ]    * 表示需要交换的位置
        //  [ .  .  * ]    . 表示不需要遍历
        //  [ .  .  . ]
        //
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                swap(matrix[i][j], matrix[j][i]);
            }
        }

        // --- 步骤2: 每行左右翻转 ---
        //
        // [1, 4, 7] → [7, 4, 1]
        // [2, 5, 8] → [8, 5, 2]
        // [3, 6, 9] → [9, 6, 3]
        //
        for (int i = 0; i < n; i++) {
            reverse(matrix[i].begin(), matrix[i].end());
        }
    }
};

/*
 * 详细执行过程 — 示例1:
 *
 *   输入:
 *   [ 1  2  3 ]
 *   [ 4  5  6 ]
 *   [ 7  8  9 ]
 *
 *   步骤1 转置:
 *     swap(0,1)↔(1,0): 2 ↔ 4
 *     swap(0,2)↔(2,0): 3 ↔ 7
 *     swap(1,2)↔(2,1): 6 ↔ 8
 *
 *     结果:
 *     [ 1  4  7 ]
 *     [ 2  5  8 ]
 *     [ 3  6  9 ]
 *
 *   步骤2 翻转每行:
 *     行0: [1,4,7] → [7,4,1]
 *     行1: [2,5,8] → [8,5,2]
 *     行2: [3,6,9] → [9,6,3]
 *
 *   输出:
 *   [ 7  4  1 ]
 *   [ 8  5  2 ]
 *   [ 9  6  3 ]    ✓
 *
 *
 * 详细执行过程 — 示例2 (4x4):
 *
 *   输入:
 *   [  5   1   9  11 ]
 *   [  2   4   8  10 ]
 *   [ 13   3   6   7 ]
 *   [ 15  14  12  16 ]
 *
 *   步骤1 转置:
 *   [  5   2  13  15 ]
 *   [  1   4   3  14 ]
 *   [  9   8   6  12 ]
 *   [ 11  10   7  16 ]
 *
 *   步骤2 翻转每行:
 *   [ 15  13   2   5 ]
 *   [ 14   3   4   1 ]
 *   [ 12   6   8   9 ]
 *   [ 16   7  10  11 ]    ✓
 */


// =====================================================
// 解法2: 四角轮转 (逐层逐位置旋转)
// 时间: O(n^2)   空间: O(1)
// =====================================================
class Solution2 {
public:
    void rotate(vector<vector<int>>& matrix) {
        int n = matrix.size();

        // 外层循环: 逐层处理 (层数 = n/2)
        // layer=0 是最外层, layer=n/2-1 是最内层
        for (int layer = 0; layer < n / 2; layer++) {
            int first = layer;           // 当前层的起始索引
            int last = n - 1 - layer;    // 当前层的结束索引

            // 内层循环: 当前层的每个旋转组
            // 旋转组数 = last - first
            for (int k = 0; k < last - first; k++) {

                // 四个位置:
                //   上: (first,       first + k)     — 上边从左到右
                //   右: (first + k,   last)          — 右边从上到下
                //   下: (last,        last - k)      — 下边从右到左
                //   左: (last - k,    first)         — 左边从下到上

                // 保存"上"
                int temp = matrix[first][first + k];

                // 左 → 上
                matrix[first][first + k] = matrix[last - k][first];

                // 下 → 左
                matrix[last - k][first] = matrix[last][last - k];

                // 右 → 下
                matrix[last][last - k] = matrix[first + k][last];

                // 上(temp) → 右
                matrix[first + k][last] = temp;
            }
        }
    }
};

/*
 * 四角轮转的执行过程 — 3x3矩阵:
 *
 *   输入:
 *   [ 1  2  3 ]
 *   [ 4  5  6 ]
 *   [ 7  8  9 ]
 *
 *   layer=0, first=0, last=2:
 *
 *     k=0: 四个位置 = (0,0)(0,2)(2,2)(2,0) = 1,3,9,7
 *       temp=1, [0,0]=7, [2,0]=9, [2,2]=3, [0,2]=1
 *       → [ 7  2  1 ]
 *         [ 4  5  6 ]
 *         [ 9  8  3 ]
 *
 *     k=1: 四个位置 = (0,1)(1,2)(2,1)(1,0) = 2,6,8,4
 *       temp=2, [0,1]=4, [1,0]=8, [2,1]=6, [1,2]=2
 *       → [ 7  4  1 ]
 *         [ 8  5  2 ]
 *         [ 9  6  3 ]    ✓
 *
 *   layer=1: n/2=1, 不执行 (中心5不动)
 */


// =====================================================
// 拓展: 各方向旋转的两步法实现
// =====================================================

// 逆时针旋转 90° = 转置 + 上下翻转
class SolutionCounterClockwise {
public:
    void rotateCounterClockwise(vector<vector<int>>& matrix) {
        int n = matrix.size();

        // 步骤1: 转置
        for (int i = 0; i < n; i++)
            for (int j = i + 1; j < n; j++)
                swap(matrix[i][j], matrix[j][i]);

        // 步骤2: 上下翻转 (第0行和最后一行交换, ...)
        for (int i = 0; i < n / 2; i++)
            swap(matrix[i], matrix[n - 1 - i]);
    }
};

// 旋转 180° = 上下翻转 + 左右翻转
class SolutionRotate180 {
public:
    void rotate180(vector<vector<int>>& matrix) {
        int n = matrix.size();

        // 步骤1: 上下翻转
        for (int i = 0; i < n / 2; i++)
            swap(matrix[i], matrix[n - 1 - i]);

        // 步骤2: 每行左右翻转
        for (int i = 0; i < n; i++)
            reverse(matrix[i].begin(), matrix[i].end());
    }
};


/*
 * 旋转方向总结:
 *
 * | 旋转方向   | 步骤1      | 步骤2      | 坐标变换           |
 * |-----------|------------|------------|---------------------|
 * | 顺时针90° | 转置       | 行reverse  | (i,j) → (j, n-1-i) |
 * | 逆时针90° | 转置       | 上下翻转   | (i,j) → (n-1-j, i) |
 * | 旋转180°  | 上下翻转   | 行reverse  | (i,j) → (n-1-i, n-1-j) |
 *
 * 四角轮转中的赋值方向:
 *   保存上 → 左覆盖上 → 下覆盖左 → 右覆盖下 → 上(temp)覆盖右
 *   (逆时针方向赋值, 因为是顺时针旋转)
 *
 * 易错点:
 * 1. 转置只遍历上三角(j > i), 否则每个元素交换两次=没交换
 * 2. 四角轮转的赋值方向: 逆着旋转方向赋值
 * 3. 层数 = n/2 (奇数矩阵中心元素不需要移动)
 * 4. 每层旋转组数 = last - first = n - 2*layer - 1
 * 5. 四角坐标容易写错, 建议先画图再编码
 */


