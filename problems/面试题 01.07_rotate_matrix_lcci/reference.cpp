/*
 * ── 解法对比 ──
 *
 * | 解法           | 时间   | 空间  | 代码量 | 推荐度 |
 * |--------------- |--------|-------|--------|--------|
 * | 转置+行翻转    | O(n^2) | O(1)  | 极少   | ★★★ 面试首选 |
 * | 四角轮转       | O(n^2) | O(1)  | 中等   | ★★  加分项   |
 * | 逆时针/180拓展 | O(n^2) | O(1)  | 少     | ★   follow-up |
 *
 * 转置+行翻转: 两步各自语义清晰, 代码最短, 面试推荐首答。
 * 四角轮转:     直接操作四个角位置, 更"原地"但坐标容易写错,
 *               面试中适合作为"你还知道其他方法吗"的回答。
 * 两种方法复杂度完全相同, 区别在于代码可读性和出错风险。
 *
 * ── 易错点 (具体bug) ──
 *
 * 1. 转置时 j 从 0 开始而非 i+1:
 *    BUG: j 从 0 开始 → swap(matrix[0][1], matrix[1][0]) 执行两次,
 *    相当于没交换。结果矩阵不变, 最终输出=原矩阵做了一次行翻转。
 *
 * 2. 四角轮转赋值方向搞反 (顺时针赋值而非逆时针):
 *    BUG: temp=上, 右→上, 下→右, 左→下, temp→左 (顺时针赋值)
 *    → 得到逆时针旋转90度而非顺时针。必须逆着旋转方向赋值。
 *
 * 3. 四角轮转的 k 循环范围写成 k < last 而非 k < last - first:
 *    BUG: 内层旋转组数过多, 越界访问导致 segfault 或结果错乱。
 *
 * 4. 四角坐标中 (last-k, first) 和 (first, first+k) 写反:
 *    BUG: 导致某些位置被跳过或被覆盖两次。建议每次都画 4x4 图,
 *    标出 A/D/P/M 四个位置后再写代码。
 *
 * ── 面试追问链 ──
 *
 * Q1: 如果要逆时针旋转 90 度, 怎么改?
 * A1: 转置 + 上下翻转 (而非行翻转)。
 *     坐标推导: (i,j)→(j,i)→(n-1-j,i), 正好是逆时针90度变换。
 *
 * Q2: 如果矩阵不是方阵 (M x N), 还能原地旋转吗?
 * A2: 不能真正原地, 因为行列数变了, 内存布局不同。
 *     需要 O(M*N) 额外空间, 或用"原地跟踪置换环"的技巧
 *     (每个元素沿旋转环移动, 处理环的起点标记), 较复杂。
 *
 * Q3: 如果要求旋转任意 k*90 度, 最高效的写法?
 * A3: k %= 4 后: k=0 不动; k=1 转置+行翻转; k=2 上下翻转+行翻转;
 *     k=3 转置+上下翻转。都是 O(n^2) 时间 O(1) 空间。
 *     不需要旋转 k 次, 一次组合操作即可。
 */
