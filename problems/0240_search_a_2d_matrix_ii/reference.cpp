/*
 * LeetCode 240: 搜索二维矩阵 II (Search a 2D Matrix II)
 *
 * 【题目本质】
 * 在行有序、列有序（但整体不完全有序）的矩阵中查找目标值。
 * 关键是找到能同时利用"行有序 + 列有序"的搜索策略。
 *
 * 【解法总览】
 * 解法1: 暴力遍历         — O(mn) / O(1)   — 最直觉
 * 解法2: 逐行二分查找     — O(m·logn) / O(1) — 利用行有序
 * 解法3: Z字查找(右上角)  — O(m+n) / O(1)  — ⭐面试首选
 * 解法4: 分治法           — O(n^1.58) / O(logn) — 加分项
 *
 * 【矩阵结构示意】
 *
 *   1   4   7  11  15     ← 每行从左到右升序
 *   2   5   8  12  19     ← 每列从上到下升序
 *   3   6   9  16  22
 *  10  13  14  17  24
 *  18  21  23  26  30
 *
 *  注意: matrix[i][n-1] 不一定 < matrix[i+1][0]
 *  (这是和 LeetCode 74 的关键区别)
 */

// ============================================================
// 解法1: 暴力遍历
// 时间: O(mn)  空间: O(1)
//
// 【思路】
// 完全不利用任何有序性，扫描所有元素。
// 作为基准线理解题意。
// ============================================================
class Solution1 {
public:
    bool searchMatrix(vector<vector<int>>& matrix, int target) {
        int m = matrix.size(), n = matrix[0].size();
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (matrix[i][j] == target) return true;
            }
        }
        return false;
    }
};

// ============================================================
// 解法2: 逐行二分查找
// 时间: O(m·log n)  空间: O(1)
//
// 【思路】
// 暴力解对每行做线性扫描 O(n)，瓶颈在"查找"。
// 既然每行有序，对每行做二分查找把 O(n) 降到 O(log n)。
// 再利用列有序性做剪枝：
//   - 行首 > target → 后续行更大，直接 break
//   - 行尾 < target → 当前行不可能有，continue
// ============================================================
class Solution2 {
public:
    bool searchMatrix(vector<vector<int>>& matrix, int target) {
        int m = matrix.size(), n = matrix[0].size();
        for (int i = 0; i < m; i++) {
            // 剪枝: 当前行最小值 > target，下面的行更大，不用看了
            if (matrix[i][0] > target) break;
            // 剪枝: 当前行最大值 < target，这行没有，跳过
            if (matrix[i][n - 1] < target) continue;

            // 对当前行做标准二分查找
            int lo = 0, hi = n - 1;
            while (lo <= hi) {
                int mid = lo + (hi - lo) / 2;
                if (matrix[i][mid] == target) return true;
                else if (matrix[i][mid] < target) lo = mid + 1;
                else hi = mid - 1;
            }
        }
        return false;
    }
};

// ============================================================
// 解法3: Z字查找 (右上角出发) — ⭐ 面试首选
// 时间: O(m+n)  空间: O(1)
//
// 【思路】
// 解法2只利用了"行有序"，列有序只做了简单剪枝。
// 能否同时利用两个维度的有序性？
//
// 关键观察: 从右上角 matrix[0][n-1] 出发，
//   - 向左: 值变小 (利用行有序)
//   - 向下: 值变大 (利用列有序)
//   → 类似 BST: 小了向下找更大的，大了向左找更小的
//   → 每步排除一行或一列
//
// 搜索 target=14 的过程:
//
//   1   4   7  11 [15]  15>14 → col-- (排除第4列)
//   2   5   8 [12] 19   12<14 → row++ (排除第1行)
//   3   6   9 [16] 22   16>14 → col-- (排除第3列)
//   3   6  [9]           9<14 → row++ (排除第2行)
//  10  13 [14]          14==14 ✓ 找到!
//
// 搜索空间收缩图 (target=14, 5×5 矩阵):
//
// Round1: 指针在(0,4), 搜索空间 = 整个矩阵 5×5=25 格
//   ┌─────────────────────┐
//   │  1   4   7  11 [15] │ ← 15 > 14, col-- → 排除整列4
//   │  2   5   8  12  19  │
//   │  3   6   9  16  22  │
//   │ 10  13  14  17  24  │
//   │ 18  21  23  26  30  │
//   └─────────────────────┘
//
// Round2: 指针在(0,3), 搜索空间缩小到 5×4=20 格
//   ┌────────────────┐
//   │  1   4   7 [11]│ ← 11 < 14, row++ → 排除整行0
//   │  2   5   8  12 │
//   │  3   6   9  16 │
//   │ 10  13  14  17 │
//   │ 18  21  23  26 │
//   └────────────────┘
//
// Round3: 指针在(1,3), 搜索空间缩小到 4×4=16 格
//   ┌────────────────┐
//   │  2   5   8 [12]│ ← 12 < 14, row++ → 排除整行1
//   │  3   6   9  16 │
//   │ 10  13  14  17 │
//   │ 18  21  23  26 │
//   └────────────────┘
//
// Round4: 指针在(2,3), 搜索空间缩小到 3×4=12 格
//   ┌────────────────┐
//   │  3   6   9 [16]│ ← 16 > 14, col-- → 排除整列3
//   │ 10  13  14  17 │
//   │ 18  21  23  26 │
//   └────────────────┘
//
// Round5: 指针在(2,2), 搜索空间缩小到 3×3=9 格
//   ┌────────────┐
//   │  3   6  [9]│ ← 9 < 14, row++ → 排除整行2
//   │ 10  13  14 │
//   │ 18  21  23 │
//   └────────────┘
//
// Round6: 指针在(3,2), 搜索空间缩小到 2×3=6 格
//   ┌────────────┐
//   │ 10  13 [14]│ ← 14 == 14 ✓ 找到!
//   │ 18  21  23 │
//   └────────────┘
//
// 收缩统计: 25 → 20 → 16 → 12 → 9 → 6, 共 6 步
// 每步排除一行或一列, 最多 m+n-1 步 = 5+5-1 = 9 步
//
// 为什么不能从左上角出发?
//   左上角向右、向下都变大，无法区分方向。
//   右下角同理（两个方向都变小）。
// ============================================================
class Solution3 {
public:
    bool searchMatrix(vector<vector<int>>& matrix, int target) {
        int m = matrix.size(), n = matrix[0].size();

        // 从右上角出发
        int row = 0, col = n - 1;

        while (row < m && col >= 0) {
            if (matrix[row][col] == target) {
                return true;
            } else if (matrix[row][col] > target) {
                // 当前值太大 → 排除当前列(下面的值只会更大)
                col--;
            } else {
                // 当前值太小 → 排除当前行(左边的值只会更小)
                row++;
            }
        }
        return false;
    }
};

// ============================================================
// 解法3b: Z字查找 (左下角出发) — 解法3的等价变体
// 时间: O(m+n)  空间: O(1)
//
// 【思路】
// 左下角 matrix[m-1][0]:
//   - 向右: 值变大
//   - 向上: 值变小
// 同样满足"一个方向变大、一个方向变小"的条件。
// ============================================================
class Solution3b {
public:
    bool searchMatrix(vector<vector<int>>& matrix, int target) {
        int m = matrix.size(), n = matrix[0].size();

        // 从左下角出发
        int row = m - 1, col = 0;

        while (row >= 0 && col < n) {
            if (matrix[row][col] == target) {
                return true;
            } else if (matrix[row][col] > target) {
                row--;  // 太大 → 向上(变小)
            } else {
                col++;  // 太小 → 向右(变大)
            }
        }
        return false;
    }
};

// ============================================================
// 解法4: 分治法
// 时间: O(n^log₂3) ≈ O(n^1.58) (当 m ≈ n)
// 空间: O(log(mn)) 递归栈
//
// 【思路】
// 取矩阵中间行，在该行上二分查找 target:
//   - 找到 → 返回 true
//   - 没找到 → 二分确定了一个分界位置，将矩阵切成两个不重叠的子矩阵
//
// 示意图 (在中间行 row=2 上二分, target 落在 9 和 16 之间):
//
//  ┌─────────────┬───────────┐
//  │  1   4   7  │ 11  15    │ ← 右上区域 [r1, midR-1] × [lo, c2]
//  │  2   5   8  │ 12  19    │   (中间行右半部分的上方)
//  ├─────────────┼───────────┤ ← midR = 2, 行上二分: ...9 | 16...
//  │ 10  13  14  │           │ ← 左下区域 [midR+1, r2] × [c1, hi]
//  │ 18  21  23  │           │   (中间行左半部分的下方)
//  └─────────────┴───────────┘
//
// 每次递归把问题规模减半(行数减半)，但分成2个子问题:
// T(n) = 2T(n/2) + O(log n) → T(n) = O(n^log₂3) ≈ O(n^1.58)
// ============================================================
class Solution4 {
public:
    bool searchMatrix(vector<vector<int>>& matrix, int target) {
        int m = matrix.size(), n = matrix[0].size();
        return solve(matrix, target, 0, 0, m - 1, n - 1);
    }

private:
    bool solve(vector<vector<int>>& matrix, int target,
               int r1, int c1, int r2, int c2) {
        // 基本情况: 搜索区域无效
        if (r1 > r2 || c1 > c2) return false;

        // 剪枝: target 不在当前子矩阵的值域内
        // matrix[r1][c1] 是左上角(最小), matrix[r2][c2] 是右下角(最大)
        if (target < matrix[r1][c1] || target > matrix[r2][c2]) return false;

        // 取中间行
        int midR = r1 + (r2 - r1) / 2;

        // 在中间行 [c1, c2] 上二分查找 target
        int lo = c1, hi = c2;
        while (lo <= hi) {
            int midC = lo + (hi - lo) / 2;
            if (matrix[midR][midC] == target) return true;
            else if (matrix[midR][midC] < target) lo = midC + 1;
            else hi = midC - 1;
        }
        // 此时 hi 指向中间行中 <= target 的最右列
        //      lo 指向中间行中 > target 的最左列

        // 左下区域: 中间行以下、分界点左侧
        // 右上区域: 中间行以上、分界点右侧
        return solve(matrix, target, midR + 1, c1, r2, hi) ||
               solve(matrix, target, r1, lo, midR - 1, c2);
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间         | 空间     | 核心思想            |
// |-----------|-------------|---------|-------------------|
// | 暴力       | O(mn)       | O(1)    | 无                 |
// | 逐行二分   | O(m·log n)  | O(1)    | 行有序 → 二分       |
// | Z字查找⭐  | O(m+n)      | O(1)    | 行+列有序 → BST式搜索|
// | 分治       | O(n^1.58)   | O(logn) | 行+列有序 → 排除象限  |
//
// Z字查找最优且最简洁，面试首选。
// 逐行二分在 m << n 时可能实际更快 (O(m·log n) < O(m+n))。
// 分治法适合展示算法深度，但代码复杂度高。
//
// 【易错点】
//
// 1. 起点选错:
//    ✗ row=0, col=0 (左上角) — 向右向下都变大，无法判断方向
//    ✓ row=0, col=n-1 (右上角) 或 row=m-1, col=0 (左下角)
//
// 2. while循环边界写反:
//    ✗ while (row >= 0 && col < n) — 这是左下角的条件
//    ✓ 右上角: while (row < m && col >= 0)
//    记忆: row 从0开始往下走(检查 < m), col 从n-1开始往左走(检查 >= 0)
//
// 3. 与 LeetCode 74 混淆:
//    ✗ 把矩阵拉成一维做一次二分 — 本题行与行之间没有 "首>尾" 关系
//    ✓ 本题只能用 Z 字查找或分治
//
// 4. 分治法子区域重叠:
//    ✗ 简单切四个象限递归三个 — 有重叠，复杂度退化
//    ✓ 通过中间行二分切成两个不重叠的矩形区域
//
// 【面试追问】
//
// Q1: 为什么右上角有效、左上角无效？
// → 右上角 "向左变小、向下变大"，形成 BST 结构，每步能排除一行或一列。
//   左上角两个方向都变大，无法做出有效判断。
//
// Q2: O(m+n) 已经是最优了吗？
// → 是的。对于这种行列有序矩阵，任何确定性算法在最坏情况下需要 Ω(m+n) 
//   次比较。直觉: 存在 m+n-1 条"反对角线"，每条上的元素无序，
//   最坏情况每条至少检查一个。
//
// Q3: 这道题和 74 题的关系？
// → 74 题额外保证 matrix[i][n-1] < matrix[i+1][0]，整个矩阵等价于
//   一维有序数组，可以一次二分 O(log(mn))。本题没有这个保证。
//   本题的 Z 字查找也能解 74 题，但 74 题用二分更快。
//
// Q4: 如果要查找多次 (大量查询)，如何优化？
// → 预处理: 将所有元素放入 unordered_set，O(mn) 建表，
//   之后每次查询 O(1)。空间换时间。
// ============================================================
