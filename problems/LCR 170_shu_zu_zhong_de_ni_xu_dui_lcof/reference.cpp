/*
 * LCR 170: 交易逆序对的总数
 *
 * 【题目本质】
 * 统计数组中逆序对 (i, j) 的数量：i < j 且 record[i] > record[j]。
 * 暴力 O(n^2) 超时，核心解法是归并排序在合并过程中统计。
 *
 * 【解法总览】
 * 解法1: 暴力双循环       — O(n^2) / O(1)       — 超时，理解思路
 * 解法2: 归并排序计数      — O(n log n) / O(n)   — 面试首选 ⭐
 * 解法3: 树状数组(BIT)     — O(n log n) / O(n)   — 进阶数据结构
 */

// ============================================================
// 解法1: 暴力双循环 — O(n^2) / O(1) — 超时
//
// 【思路】
// 枚举所有 (i, j) 对，检查是否 record[i] > record[j]。
// n = 50000 时 O(n^2) ≈ 1.25 × 10^9，超时。
// 但它明确了问题定义：
//   逆序对 = (i, j) 使得 i < j 且 record[i] > record[j]
//
// 示例: record = [9, 7, 5, 4, 6]
//   逆序对: (9,7)(9,5)(9,4)(9,6)(7,5)(7,4)(7,6)(5,4)
//   总数: 8
// ============================================================
class Solution0 {
public:
    int reversePairs(vector<int>& record) {
        int n = record.size(), cnt = 0;
        for (int i = 0; i < n; i++)
            for (int j = i + 1; j < n; j++)
                if (record[i] > record[j])
                    cnt++;
        return cnt;
    }
};

// ============================================================
// 解法2: 归并排序计数 — O(n log n) / O(n) — 面试首选 ⭐
//
// 【核心思想】
// 逆序对数 = 左半内部逆序对 + 右半内部逆序对 + 跨越左右的逆序对
//
// 递归处理前两项，关键是第三项：如何高效统计跨越逆序对？
//
// 当左右两半各自有序后，用双指针合并（标准归并排序的 merge）：
//   i 指向左半，j 指向右半
//   当 arr[i] > arr[j] 时：
//     左半从 i 到 mid 的所有元素都 > arr[j]（因为左半有序）
//     所以逆序对数 += mid - i + 1
//     然后把 arr[j] 放入 tmp（较小者先放）
//   当 arr[i] <= arr[j] 时：
//     arr[i] 不与 arr[j] 构成逆序对，不计数
//     把 arr[i] 放入 tmp
//
// 【为什么取 <= 而不是 <？】
// 当 arr[i] == arr[j] 时，不构成逆序对（需要严格大于）。
// 用 <= 确保相等时先放左侧元素，不会把相等元素错误计为逆序对。
// 这也保证了归并排序的稳定性。
//
// 【分治过程示例】
// record = [9, 7, 5, 4, 6]
//
//                     [9, 7, 5, 4, 6]
//                    /                \
//             [9, 7, 5]              [4, 6]
//            /         \            /      \
//         [9, 7]       [5]       [4]       [6]
//        /      \
//      [9]      [7]
//
// 合并 [9]+[7]: i→9 > j→7, cnt+=1, 合并→[7,9]       cnt=1
// 合并 [7,9]+[5]: i→7 > j→5, cnt+=2, 合并→[5,7,9]   cnt=3
// 合并 [4]+[6]: i→4 ≤ j→6, cnt+=0, 合并→[4,6]       cnt=3
// 合并 [5,7,9]+[4,6]:
//   i→5 > j→4: cnt += 3 (5,7,9 都>4)                cnt=6
//   i→5 ≤ j→6: 不计数
//   i→7 > j→6: cnt += 2 (7,9 都>6)                  cnt=8
//   合并→[4,5,6,7,9]
// 最终: cnt = 8 ✓
// ============================================================
class Solution2 {
public:
    int reversePairs(vector<int>& record) {
        if (record.empty()) return 0;
        // 预分配辅助数组，避免递归中反复创建
        vector<int> tmp(record.size());
        return mergeSort(record, tmp, 0, (int)record.size() - 1);
    }

    // 归并排序，返回 arr[l..r] 中的逆序对数
    int mergeSort(vector<int>& arr, vector<int>& tmp, int l, int r) {
        if (l >= r) return 0; // 空区间或单元素，0 个逆序对

        int mid = l + (r - l) / 2;

        // 递归: 统计左半和右半各自内部的逆序对
        int cnt = mergeSort(arr, tmp, l, mid)
                + mergeSort(arr, tmp, mid + 1, r);

        // 合并: 统计跨越左右两半的逆序对
        int i = l, j = mid + 1, k = l;
        while (i <= mid && j <= r) {
            if (arr[i] <= arr[j]) {
                // arr[i] 不大于 arr[j]，不产生逆序对
                tmp[k++] = arr[i++];
            } else {
                // arr[i] > arr[j]: 左半从 i 到 mid 都大于 arr[j]
                // ╔════════════════════════════════════════╗
                // ║ 核心计数: cnt += mid - i + 1           ║
                // ║ 这是唯一多加的一行（相比标准归并排序）    ║
                // ╚════════════════════════════════════════╝
                cnt += mid - i + 1;
                tmp[k++] = arr[j++];
            }
        }

        // 处理剩余元素
        while (i <= mid) tmp[k++] = arr[i++];
        while (j <= r)   tmp[k++] = arr[j++];

        // 拷贝回原数组（这步不能省！）
        for (int p = l; p <= r; p++) arr[p] = tmp[p];

        return cnt;
    }
};

// ============================================================
// 解法3: 树状数组 (Binary Indexed Tree) — O(n log n) / O(n)
//
// 【思路】
// 从右向左遍历数组。对每个 record[k]，统计"它右边有多少比它小的元素"，
// 这就是 record[k] 贡献的逆序对数。
//
// 用树状数组高效维护和查询:
//   update(rank): 在 rank 位置 +1（表示这个值出现了一次）
//   query(rank-1): 查询 [1, rank-1] 的前缀和（比当前值小的元素个数）
//
// 需要先离散化（值可能很大，但元素个数 ≤ 50000）:
//   将值映射到 [1, n] 的紧凑范围，保持相对大小关系。
//
// 示例: record = [9, 7, 5, 4, 6]
// 离散化: 4→1, 5→2, 6→3, 7→4, 9→5
// 从右到左:
//   k=4 (6→3): query(2)=0, update(3). cnt=0
//   k=3 (4→1): query(0)=0, update(1). cnt=0
//   k=2 (5→2): query(1)=1, update(2). cnt=1   [4比5小,在右边]
//   k=1 (7→4): query(3)=3, update(4). cnt=4   [4,5,6都比7小]
//   k=0 (9→5): query(4)=4, update(5). cnt=8   [4,5,6,7都比9小]
// 结果: 8 ✓
// ============================================================
class Solution3 {
public:
    int reversePairs(vector<int>& record) {
        if (record.empty()) return 0;

        // Step 1: 离散化 — 排序+去重，用二分查找映射
        vector<int> sorted_vals(record);
        sort(sorted_vals.begin(), sorted_vals.end());
        sorted_vals.erase(unique(sorted_vals.begin(), sorted_vals.end()),
                          sorted_vals.end());
        int n = sorted_vals.size();

        // Step 2: 树状数组 (1-indexed)
        vector<int> bit(n + 1, 0);
        int cnt = 0;

        // Step 3: 从右向左遍历
        for (int k = (int)record.size() - 1; k >= 0; k--) {
            // 找离散化后的排名 (1-indexed)
            int rank = lower_bound(sorted_vals.begin(), sorted_vals.end(),
                                   record[k]) - sorted_vals.begin() + 1;
            // 查询 [1, rank-1] 的前缀和 = 右边比 record[k] 小的元素数
            cnt += query(bit, rank - 1);
            // 更新: 标记 record[k] 已出现
            update(bit, rank, n);
        }
        return cnt;
    }

private:
    // 树状数组: 单点更新
    void update(vector<int>& bit, int i, int n) {
        for (; i <= n; i += i & (-i))
            bit[i]++;
    }

    // 树状数组: 前缀和查询 [1, i]
    int query(vector<int>& bit, int i) {
        int s = 0;
        for (; i > 0; i -= i & (-i))
            s += bit[i];
        return s;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法      | 时间        | 空间  | 实现难度 | 推荐度 |
// |-----------|------------ |-------|---------|--------|
// | 暴力      | O(n²)      | O(1)  | 低      | ✗ 超时 |
// | 归并排序  | O(n log n)  | O(n)  | 中      | ⭐⭐⭐ 首选 |
// | 树状数组  | O(n log n)  | O(n)  | 高      | ⭐⭐  进阶 |
//
// 面试策略: 先说暴力表明理解题意，然后讲归并排序解法。
// 如果面试官问其他方法，再讲树状数组。
//
// ============================================================
// 【易错点】
//
// 1. 等号判断方向:
//    ✗ if (arr[i] < arr[j])  → arr[i]==arr[j] 时进 else, 误算为逆序对
//    ✓ if (arr[i] <= arr[j]) → 相等时先放左侧, 不计数
//
// 2. 计数公式:
//    ✗ cnt += mid - i       → 少算 1
//    ✗ cnt += r - j + 1     → 逻辑错误
//    ✓ cnt += mid - i + 1   → 左侧从 i 到 mid 共 mid-i+1 个
//
// 3. 辅助数组在递归中创建:
//    ✗ mergeSort 内部 vector<int> tmp(r-l+1)
//      → 每次递归分配内存, O(n log n) 次分配, 极慢 (TLE)
//    ✓ 外部一次分配 vector<int> tmp(n), 传引用复用
//
// 4. 忘记拷贝回原数组:
//    ✗ 合并到 tmp 后不拷贝回 arr
//      → 下次合并用的是未排序的 arr, 逻辑全错
//    ✓ for (int p = l; p <= r; p++) arr[p] = tmp[p];
//
// 5. 递归边界:
//    ✗ if (l == r) return 0;  → 当 l > r (空区间) 时未处理
//    ✓ if (l >= r) return 0;  → 空区间和单元素都安全返回
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 为什么不能用快速排序？
//     快排的 partition 打乱了元素相对顺序，无法准确统计跨越逆序对。
//     归并排序的 merge 保持左右两半各自的顺序，才能正确计数。
//
// Q2: 逆序对数和排序有什么关系？
//     将数组排成有序需要的最少相邻交换次数 = 逆序对数。
//     每次相邻交换恰好消除一个逆序对。
//
// Q3: 如果要输出所有逆序对（不只是计数）？
//     在 cnt += mid - i + 1 处，循环输出 (arr[i..mid], arr[j]) 的所有对。
//     但输出本身是 O(n^2) 的（逆序对最多 n(n-1)/2 个），不可避免。
//
// Q4: 树状数组解法的离散化是什么？
//     值域可能很大(如 10^9)，但元素个数 ≤ 50000。
//     排序+去重后，用二分查找把每个值映射到 [1, n] 的紧凑范围。
//     如 [9,7,5,4,6] → 排序去重 [4,5,6,7,9] → 4→1, 5→2, 6→3, 7→4, 9→5
//
