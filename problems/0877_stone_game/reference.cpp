//   - 想拿奇数组: 先取 p1(左端)。无论 Bob 取哪端，暴露出来的
//     新端点中一定有一个奇数位。Alice 继续取奇数位。
//   - 想拿偶数组: 先取 pn(右端)。同理。
//
// 由于 Alice 可以自由选择拿较大的那一组 → Alice 必赢。
//
// 注意: 这个结论仅在"偶数堆+总和奇数"时成立。
//       堆数为奇数或总和为偶数时不一定成立。
// ============================================================
class Solution1 {
public:
    bool stoneGame(vector<int>& piles) {
        // 先手必胜，直接返回 true
        return true;
    }
};

// ============================================================
// 解法2: 区间 DP — 通用博弈框架
// 时间: O(n^2)  空间: O(n^2)
//
// 【状态定义】
// dp[i][j] = 面对 piles[i..j] 时，当前先手玩家比后手多得的分数。
//
// 为什么用"分差"而不是"总分"？
//   如果存总分，转移时需要知道"当前是谁在操作"以及"对手的最优分数"。
//   存分差后，无论是 Alice 还是 Bob，都是"当前先手选最优"，
//   转移方程统一：选了一端后，对手变成新区间的先手。
//
// 【转移方程】
// dp[i][j] = max(
//     piles[i] - dp[i+1][j],   // 选左端: 获得 piles[i]，对手在 [i+1,j] 先手
//     piles[j] - dp[i][j-1]    // 选右端: 获得 piles[j]，对手在 [i,j-1] 先手
// )
//
// 为什么是减号？
//   选了 piles[i] 后，对手在 [i+1,j] 上先手的分差是 dp[i+1][j]。
//   对手多得 dp[i+1][j]，意味着我少得 dp[i+1][j]。
//   所以我的净分差 = piles[i] - dp[i+1][j]。
//
// 【基准情况】
// dp[i][i] = piles[i]  (只剩一堆，先手全拿，分差就是这堆的值)
//
// 【遍历顺序】
// 按区间长度 len 从 1 到 n 遍历。
// len=1: dp[i][i] = piles[i]
// len=2: dp[i][i+1] = max(piles[i]-piles[i+1], piles[i+1]-piles[i])
// ...
// len=n: dp[0][n-1] 就是 Alice 的分差
//
// 示例: piles = [5, 3, 4, 5]
//
// len=1: dp[0][0]=5  dp[1][1]=3  dp[2][2]=4  dp[3][3]=5
//
// len=2:
//   dp[0][1] = max(5-3, 3-5) = max(2, -2) = 2   → 先手拿5比拿3好
//   dp[1][2] = max(3-4, 4-3) = max(-1, 1) = 1    → 先手拿4更好
//   dp[2][3] = max(4-5, 5-4) = max(-1, 1) = 1    → 先手拿5更好
//
// len=3:
//   dp[0][2] = max(5-dp[1][2], 4-dp[0][1]) = max(5-1, 4-2) = 4
//   dp[1][3] = max(3-dp[2][3], 5-dp[1][2]) = max(3-1, 5-1) = 4
//
// len=4:
//   dp[0][3] = max(5-dp[1][3], 5-dp[0][2]) = max(5-4, 5-4) = 1
//
// dp[0][3] = 1 > 0 → Alice 赢
// ============================================================
class Solution2 {
public:
    bool stoneGame(vector<int>& piles) {
        int n = piles.size();

        // dp[i][j]: 面对 piles[i..j] 时先手的分差
        vector<vector<int>> dp(n, vector<int>(n, 0));

        // 基准: 单堆
        for (int i = 0; i < n; i++) {
            dp[i][i] = piles[i];
        }

        // 按区间长度从小到大填表
        for (int len = 2; len <= n; len++) {
            for (int i = 0; i <= n - len; i++) {
                int j = i + len - 1;
                // 选左端: piles[i] - 对手在 [i+1,j] 的分差
                // 选右端: piles[j] - 对手在 [i,j-1] 的分差
                dp[i][j] = max(piles[i] - dp[i + 1][j],
                               piles[j] - dp[i][j - 1]);
            }
        }

        // dp[0][n-1] > 0 意味着 Alice(先手) 净得分为正 → 赢
        return dp[0][n - 1] > 0;
    }
};

// ============================================================
// 解法3: 空间优化 DP
// 时间: O(n^2)  空间: O(n)
//
// 【优化思路】
// dp[i][j] 只依赖 dp[i+1][j] 和 dp[i][j-1]。
// 按区间长度遍历时，可以用一维数组滚动：
//   dp[i] 在外层循环前表示 dp[i][i+len-2]（上一轮的值）
//   更新后表示 dp[i][i+len-1]（当前轮的值）
//
// 内层从左到右遍历:
//   dp[i+1] 是上一轮的 dp[i+1][j]（还没被当前轮覆盖）✓
//   dp[i]   是当前轮刚更新的 dp[i][j-1]                 ✓
//   正好满足依赖关系。
// ============================================================
class Solution3 {
public:
    bool stoneGame(vector<int>& piles) {
        int n = piles.size();

        // dp[i] 初始为 piles[i]（对应 len=1 时的 dp[i][i]）
        vector<int> dp(piles.begin(), piles.end());

        for (int len = 2; len <= n; len++) {
            for (int i = 0; i <= n - len; i++) {
                int j = i + len - 1;
                // dp[i+1] = dp[i+1][j] (上一轮的值，还未被覆盖)
                // dp[i]   = dp[i][j-1]  (当前轮已更新的值)
                dp[i] = max(piles[i] - dp[i + 1],
                            piles[j] - dp[i]);
            }
        }

        return dp[0] > 0;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法        | 时间   | 空间   | 通用性                     |
// |------------|--------|--------|---------------------------|
// | 数学       | O(1)   | O(1)   | 仅限本题（偶数堆+奇数总和） |
// | 区间DP     | O(n^2) | O(n^2) | 所有两端取石子博弈问题       |
// | 空间优化DP  | O(n^2) | O(n)   | 同上，空间更优              |
//
// 面试策略:
//   先写区间DP展示算法能力 → 讲空间优化展示优化意识 →
//   最后提数学结论展示洞察力。不要上来就 return true。
//
// ============================================================
// 【易错点总结】
//
// 1. 转移方程用加号而非减号:
//    ✗ dp[i][j] = max(piles[i] + dp[i+1][j], ...)
//      → 加号意味着对手的分差也算我的，双重计分
//    ✓ dp[i][j] = max(piles[i] - dp[i+1][j], ...)
//      → 减号正确反映了"对手在剩余区间的先手优势是我的劣势"
//
// 2. 遍历顺序错误:
//    ✗ for (int i = 0; ...) for (int j = i+1; ...)
//      → dp[i+1][j] 可能还没算（i+1 > i，但可能 len 更大的还没填）
//    ✓ 外层按 len 从小到大，保证子问题先算好
//
// 3. 判断条件写成 >= 0 而非 > 0:
//    ✗ return dp[0][n-1] >= 0; → 等于0是平局，但题目说总和奇数不会平局
//    ✓ return dp[0][n-1] > 0; → 虽然本题不影响（不可能平局），
//      但如果套到 486.预测赢家 中，平局先手也赢，用 >= 0
//
