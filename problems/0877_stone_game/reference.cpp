/*
 * LeetCode 877: Stone Game (石子游戏)
 *
 * 【题目本质】
 * 偶数堆石子排成一排，Alice 和 Bob 轮流从两端取，Alice 先手。
 * 双方最优策略下 Alice 能否获胜？
 *
 * 【解法总览】
 * 解法1: 数学        — O(1)    / O(1)    — Alice 先手必胜
 * 解法2: 区间 DP     — O(n^2)  / O(n^2)  — 面试首选，通用博弈框架
 * 解法3: 空间优化 DP  — O(n^2)  / O(n)   — 解法2的滚动数组优化
 */

// ============================================================
// 解法1: 数学 — Alice 先手必胜
// 时间: O(1)  空间: O(1)
//
// 【证明】
// 偶数堆 p1,p2,...,pn。分成两组:
//   奇数组: p1,p3,p5,...  和偶数组: p2,p4,p6,...
// 总和为奇数 → 两组和不等。
//
