/*
 * LeetCode 9: 回文数 (Palindrome Number)
 *
 * 【题目本质】
 * 判断一个整数正着读和反着读是否相同。
 * Follow-up: 不将整数转为字符串来解决。
 *
 * 【解法总览】
 * 解法1: 转字符串 + 双指针 — O(n) / O(n) — 最直觉
 * 解法2: 完整反转数字     — O(n) / O(1) — 数学方法，需注意溢出
 * 解法3: 反转一半数字     — O(n) / O(1) — 最优，无溢出风险 ⭐面试首选
 *
 * n = 数字的位数，最多10位
 */

// ============================================================
// 解法1: 转字符串 + 双指针
// 时间: O(n)  空间: O(n)  — n为数字位数
//
// 【思路】
// 回文的定义就是"正读反读一样"。最直觉的做法：
// 把整数转成字符串，用双指针从两头向中间逐字符比较。
// 负号会被转入字符串（如"-121"），首尾字符不等，自然返回false。
//
// 这是理解题意后的第一反应，但用了O(n)额外空间。
// ============================================================
class Solution1 {
public:
    bool isPalindrome(int x) {
        string s = to_string(x);
        int left = 0, right = s.size() - 1;
        while (left < right) {
            if (s[left] != s[right]) return false;
            left++;
            right--;
        }
        return true;
    }
};

// ============================================================
// 解法2: 完整反转数字
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 不用字符串，那就在数字层面操作。
// 把整个数字反转（逐位取余，乘10累加），看反转后是否等于原数。
//
// 要点：
// - 负数直接返回false（负号无法通过数字反转还原）
// - 用long存reversed防止中间过程溢出
//   （虽然回文数反转后=自身不会溢出，但非回文数可能溢出）
// - 循环会把x变成0，所以需要提前保存original
//
// 反转 121 的过程:
//   x=121, rev=0
//   Step1: rev = 0*10 + 121%10 = 1,   x = 12
//   Step2: rev = 1*10 + 12%10  = 12,  x = 1
//   Step3: rev = 12*10 + 1%10  = 121, x = 0
//   rev(121) == original(121) → true
// ============================================================
class Solution2 {
public:
    bool isPalindrome(int x) {
        if (x < 0) return false;

        long reversed = 0;       // 用long防止反转过程溢出
        int original = x;        // 保存原始值，因为循环会修改x
        while (x > 0) {
            reversed = reversed * 10 + x % 10;  // 取末位追加到reversed
            x /= 10;                             // 去掉末位
        }
        return reversed == original;
    }
};

// ============================================================
// 解法3: 反转一半数字 ⭐ 面试首选
// 时间: O(n/2) = O(n)  空间: O(1)
//
// 【思路】
// 解法2的隐患是反转整个数字可能溢出（虽然回文数不会，但需要额外论证）。
// 更优雅的方法：只反转数字的后半部分，和前半部分比较。
//
// 核心洞察：
// - 每次循环从x取出末位追加到reversed_half
// - x在缩小，reversed_half在增大
// - 当 reversed_half >= x 时，说明已经到达或超过了中点
//
// 偶数位示例 (x=1221):
//   Step0: x=1221,  rev=0
//   Step1: rev=1,   x=122   (122 > 1 ✓ 继续)
//   Step2: rev=12,  x=12    (12 > 12 ✗ 停止)
//   比较: x(12) == rev(12) → true ✓
//
// 奇数位示例 (x=12321):
//   Step0: x=12321, rev=0
//   Step1: rev=1,    x=1232  (1232 > 1 ✓)
//   Step2: rev=12,   x=123   (123 > 12 ✓)
//   Step3: rev=123,  x=12    (12 > 123 ✗ 停止)
//   比较: x(12) == rev/10(12) → true ✓
//   奇数位时rev多了中间那一位，除以10去掉即可
//
// 非回文示例 (x=123):
//   Step0: x=123, rev=0
//   Step1: rev=3,  x=12   (12 > 3 ✓)
//   Step2: rev=32, x=1    (1 > 32 ✗ 停止)
//   比较: 1≠32, 1≠3 → false ✓
//
// 为什么要特判末尾为0？
//   x=10 → Step1: rev=0, x=1 → (1>0 ✓)
//           Step2: rev=1, x=0 → (0>1 ✗ 停止)
//           比较: 0==1? No. 0==0? Yes! → 返回true（错误！）
//   所以必须提前排除末尾为0且x≠0的情况
// ============================================================
class Solution3 {
public:
    bool isPalindrome(int x) {
        // 负数不是回文；末尾为0且不是0本身也不是回文
        // 为什么末尾为0不行？因为回文数的首位不可能是0
        if (x < 0 || (x % 10 == 0 && x != 0)) return false;

        int reversed_half = 0;
        // 当reversed_half < x时，说明还没到中点，继续反转
        while (x > reversed_half) {
            reversed_half = reversed_half * 10 + x % 10;
            x /= 10;
        }

        // 偶数位: 前半部分 == 后半部分反转 (如 1221 → 12 == 12)
        // 奇数位: 后半部分反转多了中间位，除以10去掉 (如 12321 → 12 == 123/10)
        return x == reversed_half || x == reversed_half / 10;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间  | 空间  | 溢出风险 | 面试评价      |
// |------------|-------|-------|----------|---------------|
// | 转字符串   | O(n)  | O(n)  | 无       | 能说出即可    |
// | 完整反转   | O(n)  | O(1)  | 需long   | 合格          |
// | 反转一半   | O(n)  | O(1)  | 完全没有 | ⭐最佳        |
//
// 面试推荐：解法3。无额外空间、无溢出风险、代码简洁。
// 如果面试官允许用字符串，解法1也可以快速写出作为起点。
//
// ============================================================
// 【易错点】
//
// 1. 末尾为0的特判遗漏：
//    ✗ if (x < 0) return false;  // 只排除了负数
//    ✓ if (x < 0 || (x % 10 == 0 && x != 0)) return false;
//    原因: x=10 不加此判断会被误判为回文（见上方推演）
//
// 2. 完整反转时忘记保存原始值：
//    ✗ while (x > 0) { ... } return reversed == x;  // x已经是0了！
//    ✓ int original = x; while (x > 0) { ... } return reversed == original;
//
// 3. 奇数位回文忘记除以10：
//    ✗ return x == reversed_half;  // 12321: x=12, rev=123 → false（错误）
//    ✓ return x == reversed_half || x == reversed_half / 10;
//
// ============================================================
// 【面试追问】
//
// Q1(基础): 负数为什么一定不是回文？
//    → 负号'-'只在最前面，反过来在最后面，天然不对称。
//
// Q2(细节): 完整反转一个正整数的回文数，会溢出int吗？
//    → 不会。如果x是回文数，反转后 == x本身，而x在int范围内。
//      但非回文数反转过程可能溢出，所以用long更安全，
//      或者用"反转一半"方法彻底规避。
//
// Q3(变体): 如果输入是链表，怎么判断回文？(LeetCode 234)
//    → 快慢指针找中点 → 反转后半段 → 逐节点比较。
//      复用了"反转一半再比较"的核心思想。
//
// Q4(扩展): 如果要找最近的回文数呢？(LeetCode 564)
//    → 这是 Hard 题，需要构造候选回文数：
//      取前半部分镜像、前半部分±1后镜像，选最近的。
//      但核心的"前后半部分"概念从本题就开始建立。
// ============================================================
