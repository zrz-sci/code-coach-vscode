/*
 * LCR 095: 最长公共子序列 (同主站 1143)
 *
 * 【题目本质】
 * 两个字符串的最长公共子序列（LCS）长度。
 * "子序列"可以不连续但必须保持相对顺序 → 经典二维 DP。
 *
 * 【解法总览】
 * 解法1: 二维 DP         — O(m*n) / O(m*n) — 面试首选 ⭐
 * 解法2: 一维滚动数组 DP — O(m*n) / O(n)   — 空间优化
 */

// ============================================================
// 解法1: 二维 DP — dp[i][j] = LCS(text1[0..i-1], text2[0..j-1])
// 时间: O(m * n)  空间: O(m * n)
//
// 【状态定义】
// dp[i][j] = text1 的前 i 个字符 与 text2 的前 j 个字符的 LCS 长度
// 用"前 i 个"而非"下标 i"是为了方便边界处理：dp[0][*] = dp[*][0] = 0
//
// 【状态转移】
// if text1[i-1] == text2[j-1]:
//     dp[i][j] = dp[i-1][j-1] + 1     // 末尾匹配，两边同时前进
// else:
//     dp[i][j] = max(dp[i-1][j],       // 丢掉 text1 末尾
//                    dp[i][j-1])        // 丢掉 text2 末尾
//
// 【DP 表实例】 (text1="abcde", text2="ace")
//
//        ""  a  c  e
//   ""    0  0  0  0
//    a    0  1  1  1     ← 'a'=='a', dp[1][1]=dp[0][0]+1=1
//    b    0  1  1  1
//    c    0  1  2  2     ← 'c'=='c', dp[3][2]=dp[2][1]+1=2
//    d    0  1  2  2
//    e    0  1  2  3     ← 'e'=='e', dp[5][3]=dp[4][2]+1=3
//                  ↑
//              答案 = 3 (LCS = "ace")
//
// 【依赖关系】
// dp[i][j] 依赖于三个格子：
//   dp[i-1][j-1] (左上), dp[i-1][j] (上), dp[i][j-1] (左)
// 所以从左到右、从上到下填表即可。
// ============================================================
class Solution1 {
public:
    int longestCommonSubsequence(string text1, string text2) {
        int m = text1.size(), n = text2.size();
        // dp[i][j]: text1 前 i 个字符 与 text2 前 j 个字符的 LCS 长度
        // 初始化全 0：空串的 LCS 为 0
        vector<vector<int>> dp(m + 1, vector<int>(n + 1, 0));

        for (int i = 1; i <= m; i++) {
            for (int j = 1; j <= n; j++) {
                if (text1[i - 1] == text2[j - 1]) {
                    // 末尾字符匹配：这个字符一定在 LCS 中
                    dp[i][j] = dp[i - 1][j - 1] + 1;
                } else {
                    // 末尾字符不匹配：至少丢掉一个，取两个子问题的较大值
                    dp[i][j] = max(dp[i - 1][j], dp[i][j - 1]);
                }
            }
        }

        return dp[m][n];
    }
};

// ============================================================
// 解法2: 一维滚动数组 DP — 空间优化到 O(n)
// 时间: O(m * n)  空间: O(n)
//
// 【思路】
// dp[i][j] 只依赖上一行 dp[i-1][*] 和当前行左边 dp[i][j-1]。
// 可以只保留一维数组 dp[j]，逐行更新。
//
// 关键难点：更新 dp[j] 时，需要 dp[i-1][j-1]（左上角旧值）。
// 但 dp[j-1] 已经被当前行更新为新值了。
// 解决：用临时变量 prev 保存更新前的 dp[j-1]。
//
// 滚动过程 (text1="abcde", text2="ace"):
//
// 初始: dp = [0, 0, 0, 0]   →  ""  a  c  e
//
// i=1 (text1[0]='a'):
//   j=1: 'a'=='a' → prev=0, dp[1]=prev+1=1   dp=[0,1,0,0]
//   j=2: 'a'!='c' → dp[2]=max(dp[2],dp[1])=1 dp=[0,1,1,0]
//   j=3: 'a'!='e' → dp[3]=max(dp[3],dp[2])=1 dp=[0,1,1,1]
//
// i=2 (text1[1]='b'):
//   j=1: 'b'!='a' → dp[1]=max(dp[1],dp[0])=1 dp=[0,1,1,1]
//   j=2: 'b'!='c' → dp[2]=max(dp[2],dp[1])=1 dp=[0,1,1,1]
//   j=3: 'b'!='e' → dp[3]=max(dp[3],dp[2])=1 dp=[0,1,1,1]
//
// i=3 (text1[2]='c'):
//   j=1: 'c'!='a' → dp[1]=max(dp[1],dp[0])=1 dp=[0,1,1,1]
//   j=2: 'c'=='c' → prev=1, dp[2]=prev+1=2   dp=[0,1,2,1]
//   j=3: 'c'!='e' → dp[3]=max(dp[3],dp[2])=2 dp=[0,1,2,2]
//
// i=4 (text1[3]='d'): 无匹配
//   dp=[0,1,2,2]
//
// i=5 (text1[4]='e'):
//   j=1: 'e'!='a' → dp=[0,1,2,2]
//   j=2: 'e'!='c' → dp=[0,1,2,2]
//   j=3: 'e'=='e' → prev=2, dp[3]=prev+1=3   dp=[0,1,2,3]
//
// 答案: dp[3] = 3
// ============================================================
class Solution2 {
public:
    int longestCommonSubsequence(string text1, string text2) {
        int m = text1.size(), n = text2.size();

        // 优化：让较短的字符串作为内层循环（节省空间）
        if (m < n) {
            swap(text1, text2);
            swap(m, n);
        }

        vector<int> dp(n + 1, 0);

        for (int i = 1; i <= m; i++) {
            int prev = 0; // prev = dp[i-1][j-1]，即左上角的旧值

            for (int j = 1; j <= n; j++) {
                int temp = dp[j]; // 保存 dp[i-1][j]，下一轮 j+1 时作为 prev

                if (text1[i - 1] == text2[j - 1]) {
                    dp[j] = prev + 1;  // dp[i-1][j-1] + 1
                } else {
                    // dp[j] = 当前值 dp[i-1][j]（还没更新，就是上一行的值）
                    // dp[j-1] = 已经更新为 dp[i][j-1]
                    dp[j] = max(dp[j], dp[j - 1]);
                }

                prev = temp; // 为下一轮 j+1 保存 dp[i-1][j]
            }
        }

        return dp[n];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间    | 空间       | 特点                |
// |--------------|---------|-----------|---------------------|
// | 二维 DP      | O(m*n)  | O(m*n)    | 直观，可回溯路径     |
// | 一维滚动 DP  | O(m*n)  | O(min(m,n))| 空间优化，不可回溯   |
//
// 面试推荐：先写二维 DP（容易理解不易出错），
// 追问空间优化时改写一维滚动版本。
//
// ============================================================
// 【易错点】
//
// 1. 下标偏移：dp[i][j] 对应 text1[i-1] 和 text2[j-1]
//    ✗ if (text1[i] == text2[j])  // 多取了一个字符
//    ✓ if (text1[i-1] == text2[j-1])
//
// 2. 不匹配时取错子问题：
//    ✗ dp[i][j] = dp[i-1][j-1]  // 同时丢掉两个末尾，漏了更优解
//    ✓ dp[i][j] = max(dp[i-1][j], dp[i][j-1])
//
// 3. 滚动数组中 prev 更新时机：
//    ✗ dp[j] = ...; int temp = dp[j];  // 先更新再保存，temp 已是新值
//    ✓ int temp = dp[j]; dp[j] = ...;  // 先保存再更新
//
// 4. 忘记交换以优化空间：
//    如果 m=1000, n=1，一维 DP 空间应该是 O(1) 而非 O(1000)
//    让较短的作为内层循环：if (m < n) swap
//
// ============================================================
// 【面试追问】
//
// Q1: "如果要输出 LCS 本身？"
//     二维 DP 中记录每个 dp[i][j] 的来源（对角线/上/左），
//     从 dp[m][n] 回溯，遇到"对角线"就把 text1[i-1] 加入结果。
//     空间优化后无法回溯，需要 Hirschberg 算法（分治法）。
//
// Q2: "LCS 长度和编辑距离的关系？"
//     如果只允许插入和删除（不允许替换），
//     编辑距离 = m + n - 2 * LCS。
//     直觉：LCS 是两个字符串的"公共骨架"，不在骨架中的字符
//     需要分别从 text1 删除和向 text2 插入。
//
// Q3: "能否用记忆化搜索代替填表？"
//     可以。定义 dfs(i, j) 返回 text1[i:] 和 text2[j:] 的 LCS 长度。
//     递归 + memo[i][j] 缓存。时间空间和填表版本完全相同。
//     填表法更常见（无递归栈开销），但记忆化搜索更容易写对。
//
// ============================================================
