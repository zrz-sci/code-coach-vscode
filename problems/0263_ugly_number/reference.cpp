/*
 * LeetCode 263: 丑数 (Ugly Number)
 *
 * 【题目本质】
 * 判断一个整数是否为"丑数"——即其质因数分解中只含有 2、3、5。
 * 1 也是丑数（没有质因数，空集满足条件）。
 * n <= 0 不是丑数（丑数是正整数）。
 *
 * 【核心操作】
 * 反复除以 2、3、5，看最后是否等于 1。
 * 如果最后 > 1，说明含有其他质因子。
 *
 * 【解法总览】
 * 解法1: 循环除因子（三个 while）    — O(log n) / O(1) — 最直接
 * 解法2: 统一因子数组（for + while）  — O(log n) / O(1) — 更优雅，扩展性好
 * 解法3: 递归写法                     — O(log n) / O(log n) — 递归思维练习
 */

// ============================================================
// 解法1: 循环除因子 — 标准写法
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 丑数 n 的质因数分解形如 n = 2^a * 3^b * 5^c
// 我们依次把 2/3/5 的因子全部除干净，看最后是否为 1
//
// 【为什么三个独立的 while 就够了？】
// 第一个 while 把所有 2 除尽 → n 变成奇数
// 第二个 while 把所有 3 除尽 → n 不含因子 3
// 第三个 while 把所有 5 除尽 → n 不含因子 5
// 如果 n 只由 2/3/5 组成，此时 n 一定等于 1
//
// 示例: n = 6
//   6 % 2 == 0 → 6/2 = 3
//   3 % 2 != 0 → 除2结束
//   3 % 3 == 0 → 3/3 = 1
//   1 % 3 != 0 → 除3结束
//   1 % 5 != 0 → 除5结束
//   n == 1 → true ✓   (6 = 2 * 3，只含丑因子)
//
// 示例: n = 14
//   14 % 2 == 0 → 14/2 = 7
//   7 % 2 != 0  → 除2结束
//   7 % 3 != 0  → 除3结束
//   7 % 5 != 0  → 除5结束
//   n == 7 != 1 → false ✗  (14 = 2 * 7，含非丑因子 7)
//
// 示例: n = 1
//   1 % 2 != 0, 1 % 3 != 0, 1 % 5 != 0
//   n == 1 → true ✓   (1 没有质因数，是丑数)
//
// 示例: n = 0
//   n <= 0 → 直接返回 false ✗  (0 不是正整数)
//
// 示例: n = -6
//   n <= 0 → 直接返回 false ✗  (负数不是丑数)
// ============================================================
class Solution1 {
public:
    bool isUgly(int n) {
        // 边界: 丑数必须是正整数
        // 注意 n=0 不能进入 while (0%2==0 为 true，0/2=0 → 死循环！)
        if (n <= 0) return false;

        // 除尽所有因子 2
        // 例: 8 → 4 → 2 → 1 (除了3次)
        while (n % 2 == 0) {
            n /= 2;
        }

        // 除尽所有因子 3
        // 例: 27 → 9 → 3 → 1 (除了3次)
        while (n % 3 == 0) {
            n /= 3;
        }

        // 除尽所有因子 5
        // 例: 125 → 25 → 5 → 1 (除了3次)
        while (n % 5 == 0) {
            n /= 5;
        }

        // 如果所有质因子都是 2/3/5，除完后 n 应该等于 1
        // 如果 n > 1，说明还有其他质因子（如 7、11、13...）
        return n == 1;
    }
};

// ============================================================
// 解法2: 统一因子数组 — 更优雅的写法
// 时间: O(log n)  空间: O(1)
//
// 【思路】
// 把 {2, 3, 5} 存入数组，用 for 循环遍历。
// 逻辑和解法1 完全相同，但更简洁且容易扩展。
//
// 【扩展性】
// 如果题目改为"只含质因数 2, 3, 5, 7 的正整数"（超级丑数），
// 只需把数组改为 {2, 3, 5, 7}。
// 这种"参数化"写法是良好的编程习惯。
//
// 示例: n = 30, factors = {2, 3, 5}
//   f=2: 30 % 2 == 0 → 30/2=15, 15%2!=0 → 结束
//   f=3: 15 % 3 == 0 → 15/3=5,  5%3!=0  → 结束
//   f=5: 5 % 5 == 0  → 5/5=1,   1%5!=0  → 结束
//   n == 1 → true ✓   (30 = 2 * 3 * 5)
// ============================================================
class Solution2 {
public:
    bool isUgly(int n) {
        if (n <= 0) return false;

        // 把丑因子存入数组，方便扩展
        for (int factor : {2, 3, 5}) {
            while (n % factor == 0) {
                n /= factor;
            }
        }

        return n == 1;
    }
};

// ============================================================
// 解法3: 递归写法
// 时间: O(log n)  空间: O(log n) — 递归栈
//
// 【思路】
// 如果 n 能被 2 整除，判断 n/2 是否为丑数。
// 如果 n 能被 3 整除，判断 n/3 是否为丑数。
// 如果 n 能被 5 整除，判断 n/5 是否为丑数。
// 都不能整除且 n != 1，说明有其他质因子，不是丑数。
//
// 注意：这里的 if 是顺序检查，先尝试除 2，
// 除不动再尝试除 3，再除 5。
// 每层递归只除一个因子，效率和循环版一样。
//
// 示例: n = 12
//   12%2==0 → isUgly(6)
//     6%2==0 → isUgly(3)
//       3%2!=0, 3%3==0 → isUgly(1)
//         n==1 → return true ✓
//   (12 = 2^2 * 3, 是丑数)
//
// 示例: n = 14
//   14%2==0 → isUgly(7)
//     7%2!=0, 7%3!=0, 7%5!=0 → return false ✗
//   (14 = 2 * 7, 不是丑数)
// ============================================================
class Solution3 {
public:
    bool isUgly(int n) {
        // 终止条件1: 非正整数不是丑数
        if (n <= 0) return false;
        // 终止条件2: 1 是丑数
        if (n == 1) return true;

        // 尝试依次除以 2、3、5
        if (n % 2 == 0) return isUgly(n / 2);
        if (n % 3 == 0) return isUgly(n / 3);
        if (n % 5 == 0) return isUgly(n / 5);

        // 不能被 2/3/5 整除且不为 1 → 不是丑数
        return false;
    }
};

