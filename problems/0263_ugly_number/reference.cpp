//     LeetCode 264。三指针法：
//     维护 i2, i3, i5 三个指针，每次取 min(ugly[i2]*2, ugly[i3]*3, ugly[i5]*5)
//     作为下一个丑数，移动对应指针。
//
// Q4: INT_MIN (-2^31) 有风险吗？
//     n <= 0 直接返回 false，不会对 INT_MIN 做取模/除法，所以安全。
