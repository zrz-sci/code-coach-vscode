// 【解法对比】
//
// | 解法          | 时间     | 空间     | 可读性 | 扩展性 |
// |--------------|---------|---------|--------|--------|
// | 循环除因子    | O(logn) | O(1)    | ⭐⭐⭐   | ⭐⭐    |
// | 统一因子数组  | O(logn) | O(1)    | ⭐⭐⭐   | ⭐⭐⭐   |
// | 递归写法      | O(logn) | O(logn) | ⭐⭐    | ⭐⭐    |
//
// 面试建议：解法1 或解法2 均可。
// 解法2 展示了"参数化"的编程习惯，面试官可能会加分。
//
// ============================================================
// 【易错点】
//
// 1. 忘记处理 n <= 0:
//    ✗ 直接进 while → n=0 时 0%2==0 为 true, 0/2=0, 死循环！
//    ✓ 开头 if (n <= 0) return false;
//
// 2. 以为 1 不是丑数:
//    ✗ n=1 返回 false → 错！1 是丑数序列的第一个
//    ✓ 1 的质因数分解为空集，满足"只含 2/3/5"条件
//
// 3. 只除一次而非除干净:
//    ✗ if (n%2==0) n/=2; → 只除一个 2，n=8 变成 4 而非 1
//    ✓ while (n%2==0) n/=2; → 把所有 2 除尽
//
// 4. 认为需要检查 4、6、9 等:
//    ✗ 多加 while(n%4==0) ... → 不需要！4=2*2 会被 while(n%2==0) 处理掉
//    ✓ 只需检查质因子 2、3、5
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 为什么不需要检查更多的质数？
//     我们不需要"找出所有质因子"。只需要把 2/3/5 除尽，
//     看 n 是否为 1。如果 > 1，说明有其他质因子，不管它是什么。
//
// Q2: 超级丑数 — 质因子列表不固定？
