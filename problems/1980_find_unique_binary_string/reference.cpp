/*
 * LeetCode 1980: Find Unique Binary String
 * 
 * 【题目本质】
 * 给 n 个长度为 n 的互不相同的二进制字符串，找一个不在其中的。
 * 鸽巢原理保证一定存在（2^n 种可能，只给了 n 个）。
 *
 * 【解法总览】
 * 解法1: 暴力枚举 + HashSet — O(2^n · n) / O(n²) — 最直觉
 * 解法2: 整数映射 + 缺失查找 — O(n²) / O(n) — 优化
 * 解法3: Cantor 对角线法 — O(n) / O(n) — 最优，面试首选
 */

// ============================================================
// 解法1: 暴力枚举 + HashSet
// 时间: O(2^n · n)  空间: O(n²)
//
// 【思路】
// 最直觉的方法：把 nums 放进 HashSet，然后枚举所有 2^n 个
// 长度为 n 的二进制字符串，找第一个不在 set 中的。
// 
// 为什么能过？n ≤ 16，2^16 = 65536，完全在可接受范围。
// 但面试中不够优雅，瓶颈是枚举量是指数级的。
// ============================================================
class Solution1 {
public:
    string findDifferentBinaryString(vector<string>& nums) {
        int n = nums.size();
        unordered_set<string> seen(nums.begin(), nums.end());
        
        // 枚举 0 到 2^n - 1，转成二进制字符串检查
        for (int i = 0; i < (1 << n); i++) {
            string candidate(n, '0');
            for (int j = 0; j < n; j++) {
                // 从高位到低位填充
                if ((i >> (n - 1 - j)) & 1) {
                    candidate[j] = '1';
                }
            }
            if (seen.find(candidate) == seen.end()) {
                return candidate;
            }
        }
        return ""; // 鸽巢原理保证不会到这
    }
};

// ============================================================
// 解法2: 整数映射 + 缺失查找
// 时间: O(n²)  空间: O(n)
//
// 【思路】
// 解法1的瓶颈是枚举 2^n 个候选。但其实只需要找一个不在
// 集合中的整数即可。nums 只有 n 个元素，所以 [0, n] 这
// n+1 个整数中至少有一个不在其中（鸽巢原理）。
//
// 步骤：
// 1. 把每个二进制字符串转成整数，放入 HashSet
// 2. 从 0 到 n 查找第一个缺失的整数
// 3. 把该整数转回长度为 n 的二进制字符串
//
// 字符串转整数 O(n)，做 n 次 → O(n²)
// ============================================================
class Solution2 {
public:
    string findDifferentBinaryString(vector<string>& nums) {
        int n = nums.size();
        unordered_set<int> seen;
        
        // 二进制字符串 → 整数
        for (const string& s : nums) {
            int val = 0;
            for (char c : s) {
                val = val * 2 + (c - '0');
            }
            seen.insert(val);
        }
        
        // 在 [0, n] 中找缺失的整数
        int missing = 0;
        for (int i = 0; i <= n; i++) {
            if (seen.find(i) == seen.end()) {
                missing = i;
                break;
            }
        }
        
        // 整数 → 长度为 n 的二进制字符串
        string result(n, '0');
        for (int j = n - 1; j >= 0; j--) {
            result[j] = '0' + (missing & 1);
            missing >>= 1;
        }
        return result;
    }
};

// ============================================================
// 解法3: Cantor 对角线法 ⭐ 面试首选
// 时间: O(n)  空间: O(n) (仅结果字符串)
//
// 【思路】
// 核心洞察来自 Cantor 的对角线论证：
// 
// 构造 result 使得：result[i] ≠ nums[i][i]（对角线上取反）
// 
// 这保证了：
// - result ≠ nums[0]，因为 result[0] ≠ nums[0][0]
// - result ≠ nums[1]，因为 result[1] ≠ nums[1][1]
// - ...
// - result ≠ nums[n-1]，因为 result[n-1] ≠ nums[n-1][n-1]
//
// 对角线法示意 (nums = ["111", "011", "001"]):
//
//        位0  位1  位2
// nums[0]: [1]  1    1     ← 看对角线位 nums[0][0]='1', 取反得 '0'
// nums[1]:  0  [1]   1     ← 看对角线位 nums[1][1]='1', 取反得 '0'
// nums[2]:  0   0   [1]    ← 看对角线位 nums[2][2]='1', 取反得 '0'
//                           ↓
// 构造结果:  0    0    0   → "000"
//
// 验证: "000" ≠ "111"(位0不同) ✓
//       "000" ≠ "011"(位1不同) ✓  
//       "000" ≠ "001"(位2不同) ✓
//
// 为什么一定正确？
// 因为对每个 i，result 和 nums[i] 至少在第 i 位不同，
// 所以 result 不可能等于任何 nums[i]。
// ============================================================
class Solution3 {
public:
    string findDifferentBinaryString(vector<string>& nums) {
        int n = nums.size();
        string result(n, '0');
        
        for (int i = 0; i < n; i++) {
            // 对角线取反：保证 result ≠ nums[i]
            result[i] = (nums[i][i] == '0') ? '1' : '0';
        }
        
        return result;
    }
};

// ============================================================
// 【解法对比】
// 
// 解法1 (暴力):  枚举所有 2^n 候选 → O(2^n·n)
//   ↓ 优化：不需要枚举那么多，只查 [0,n]
// 解法2 (整数):  转整数后查缺失 → O(n²)
//   ↓ 优化：甚至不需要查集合，对角线直接构造
// 解法3 (对角线): 逐位构造 → O(n)
//
// 三者关系：暴力 → 利用鸽巢原理缩小搜索范围 → 利用对角线论证直接构造
//
// 面试选择：直接上解法3，代码只有3行核心逻辑，体现数学功底。
// 如果面试官追问"你怎么想到的"，可以从解法1开始讲思路演进。
//
// ============================================================
// 【易错点】
//
// 1. 对角线取反方向写反：
//    ✗ result[i] = nums[i][i];          // 没取反！可能构造出 nums 中的字符串
//    ✓ result[i] = (nums[i][i] == '0') ? '1' : '0';  // 必须取反
//
// 2. 解法2 中整数转字符串时忘记补前导零：
//    ✗ 用 to_string() 或简单的 bitset，长度可能不是 n
//    ✓ 手动从低位到高位填充，初始化时整个字符串先置 '0'
//
// 3. 解法2 中搜索范围写成 [0, 2^n-1]：
//    ✗ for (int i = 0; i < (1 << n); i++)  // 退化成暴力
//    ✓ for (int i = 0; i <= n; i++)         // 鸽巢原理只需查 n+1 个
//
// ============================================================
// 【面试追问】
//
// Q1: "暴力解能过吗？复杂度是多少？"
//     → 能过，O(2^n · n)，n ≤ 16 时 2^16 = 65536 完全可以。
//       但瓶颈是指数级枚举，面试官希望看到更优解。
//
// Q2: "对角线法为什么保证结果一定不在 nums 中？
//      会不会恰好等于某个 nums[j] 但 j 不在对角线上？"
//     → 不会。对任意 j (0 ≤ j < n)，result[j] ≠ nums[j][j]，
//       所以 result 和 nums[j] 至少在第 j 位不同，不可能相等。
//       这正是 Cantor 对角线论证的核心思想。
//
// Q3: "如果 nums 有 2^n - 1 个字符串（只缺一个），
//      能否 O(n) 时间 O(1) 额外空间找到缺失的？"
//     → 可以用 XOR 技巧：把 nums 中所有字符串对应的整数异或起来，
//       再和 0 到 2^n-1 的所有整数异或，结果就是缺失的（类似 268 题）。
//       不过本题 nums 只有 n 个，远小于 2^n，对角线法更直接。
//
// ============================================================
