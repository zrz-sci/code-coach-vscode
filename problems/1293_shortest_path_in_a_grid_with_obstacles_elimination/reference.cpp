/*
 * LeetCode 1293: 网格中的最短路径 (Shortest Path in a Grid with Obstacles Elimination)
 *
 * 【题目本质】
 * 在 m×n 网格中，从左上到右下的最短路径，允许最多消除 k 个障碍物。
 * 本质是一个三维状态空间上的 BFS 最短路问题：状态 = (行, 列, 剩余消除次数)。
 *
 * 【解法总览】
 * 解法1: BFS + 三维状态         — O(m·n·k) / O(m·n·k) — 面试首选 ⭐
 * 解法2: A* 搜索 + 曼哈顿启发式 — O(m·n·k) / O(m·n·k) — 进阶优化
 */

// ============================================================
// 解法1: BFS + 三维状态 — 面试首选
// 时间: O(m * n * k)  空间: O(m * n * k)
//
// 【思路】
// 求最短路径 → 想到 BFS（逐层扩展，第一次到达即最优）。
// 
// 关键问题：同一个格子可能以不同的"剩余消除次数"被到达，
// 它们代表不同的状态（后续能走的路径不同）。
// 所以需要把状态从二维 (x,y) 扩展为三维 (x, y, remain)。
//
// 遇到空地 (grid=0)：remain 不变，直接走
// 遇到障碍 (grid=1)：remain > 0 时消耗一次消除，remain=0 时走不了
//
// 剪枝：如果 k >= m+n-3，从起点到终点的曼哈顿路径上最多
// m+n-3 个障碍（路径长 m+n-2，减去两端），消除次数绰绰有余，
// 直接返回 m+n-2。
//
// 【网格 BFS 状态扩展示意图】
//
//   grid (5×3):          BFS 扩展过程 (k=1):
//   0 0 0                层0: (0,0,1)
//   1 1 0                层1: (0,1,1), (1,0,0)←消除障碍
//   0 0 0                层2: (0,2,1), ...
//   0 1 1                层3: (1,2,1)   ← grid[1][2]=0
//   0 0 0                层4: (2,2,1)
//                        层5: (3,2,0)   ← grid[3][2]=1, 消耗remain
//   最短路径:             层6: (4,2,0)   ← 到达终点! 返回6
//   (0,0)→(0,1)→(0,2)→(1,2)→(2,2)→(3,2)→(4,2)
//
// ============================================================
class Solution1 {
public:
    int shortestPath(vector<vector<int>>& grid, int k) {
        int m = grid.size(), n = grid[0].size();
        
        // 关键剪枝：消除次数足够多，直接走曼哈顿最短路
        // 路径长 m+n-2，路上最多 m+n-3 个障碍（起点终点都是0）
        if (k >= m + n - 3) return m + n - 2;
        
        // 三维 visited：visited[i][j][r] 表示以剩余 r 次消除到达 (i,j) 是否已访问
        // 为什么不能用二维？因为 (2,2,3) 和 (2,2,1) 是不同状态，后续能力不同
        vector<vector<vector<bool>>> visited(
            m, vector<vector<bool>>(n, vector<bool>(k + 1, false)));
        
        // BFS 队列元素: {行, 列, 剩余消除次数}
        queue<tuple<int, int, int>> q;
        q.push({0, 0, k});
        visited[0][0][k] = true;
        
        int steps = 0;
        int dirs[4][2] = {{0, 1}, {0, -1}, {1, 0}, {-1, 0}};
        
        while (!q.empty()) {
            int sz = q.size();
            // 逐层处理：同一层的所有节点距起点步数相同
            for (int i = 0; i < sz; i++) {
                auto [x, y, remain] = q.front();
                q.pop();
                
                // 出队时检查终点（比入队时检查更安全，能正确处理 1×1 网格）
                if (x == m - 1 && y == n - 1) return steps;
                
                for (auto& d : dirs) {
                    int nx = x + d[0], ny = y + d[1];
                    // 边界检查
                    if (nx < 0 || nx >= m || ny < 0 || ny >= n) continue;
                    
                    // 巧妙之处：grid[nx][ny] 为 0 不消耗，为 1 消耗一次
                    int nRemain = remain - grid[nx][ny];
                    
                    // 消除次数用完了 或 该状态已经访问过
                    if (nRemain < 0 || visited[nx][ny][nRemain]) continue;
                    
                    visited[nx][ny][nRemain] = true;
                    q.push({nx, ny, nRemain});
                }
            }
            steps++; // 处理完一层后步数加1
        }
        
        return -1; // BFS 搜完所有可达状态仍未到终点
    }
};

// ============================================================
// 解法2: A* 搜索 + 曼哈顿启发式 — 进阶优化
// 时间: O(m * n * k) 最坏，实际通常更快
// 空间: O(m * n * k)
//
// 【思路】
// 解法1 的 BFS 是"盲目"地逐层扩展所有方向。
// A* 用启发式函数 h(x,y) = 曼哈顿距离 = (m-1-x) + (n-1-y)
// 来给每个状态估计"到终点还要走多少步"。
// 
// 优先队列按 f = g + h 排序（g = 已走步数，h = 估计剩余步数），
// 优先探索"看起来总代价最小"的状态。
//
// 为什么 h 是 admissible（可采纳的）？
// 曼哈顿距离是"不考虑任何障碍物"的最短步数，永远 <= 真实剩余步数。
// 这保证了 A* 找到的第一条到终点的路径一定是最短的。
//
// 与解法1的关键区别：
// - BFS 用普通队列 → A* 用优先队列
// - BFS 入队前标记 visited → A* 出队时标记（因为可能多次入队）
// - A* 入队时计算 f = g + h 作为优先级
// ============================================================
class Solution2 {
public:
    int shortestPath(vector<vector<int>>& grid, int k) {
        int m = grid.size(), n = grid[0].size();
        if (k >= m + n - 3) return m + n - 2;
        
        // 状态: {f值, 步数g, 行x, 列y, 剩余消除次数remain}
        // 小顶堆：f 值最小的优先出队
        using State = tuple<int, int, int, int, int>;
        priority_queue<State, vector<State>, greater<State>> pq;
        
        // visited 在出队时标记（惰性删除策略）
        vector<vector<vector<bool>>> visited(
            m, vector<vector<bool>>(n, vector<bool>(k + 1, false)));
        
        int h0 = (m - 1) + (n - 1); // 起点的启发式值
        pq.push({h0, 0, 0, 0, k});  // {f, g, x, y, remain}
        
        int dirs[4][2] = {{0, 1}, {0, -1}, {1, 0}, {-1, 0}};
        
        while (!pq.empty()) {
            auto [f, g, x, y, remain] = pq.top();
            pq.pop();
            
            // 到达终点：A* 保证第一次出队就是最短路
            if (x == m - 1 && y == n - 1) return g;
            
            // 出队时检查 visited（同一状态可能被多次入队，只处理第一次出队的）
            if (visited[x][y][remain]) continue;
            visited[x][y][remain] = true;
            
            for (auto& d : dirs) {
                int nx = x + d[0], ny = y + d[1];
                if (nx < 0 || nx >= m || ny < 0 || ny >= n) continue;
                
                int nRemain = remain - grid[nx][ny];
                if (nRemain < 0 || visited[nx][ny][nRemain]) continue;
                
                int ng = g + 1;
                int nh = (m - 1 - nx) + (n - 1 - ny); // 曼哈顿距离启发式
                pq.push({ng + nh, ng, nx, ny, nRemain});
            }
        }
        
        return -1;
    }
};

// ============================================================
// 【解法对比】
//
// | 对比项       | BFS + 三维状态            | A* 搜索                    |
// |-------------|--------------------------|---------------------------|
// | 数据结构     | 普通队列 queue            | 优先队列 priority_queue    |
// | visited时机  | 入队前标记                | 出队时标记（惰性删除）       |
// | 搜索方向     | 盲目逐层扩展              | 启发式引导，优先朝终点方向   |
// | 最坏复杂度   | O(m·n·k)                | O(m·n·k) — 退化时同BFS     |
// | 实际性能     | 稳定                     | 通常更快                   |
// | 实现难度     | 简单                     | 中等                      |
// | 面试推荐     | ⭐ 首选                  | 追问时再给                  |
//
// 选择建议：
// - 面试时先写 BFS 解法，稳定可靠，代码短
// - 如果被追问"能不能更快"，再讲 A* 思路
// - 两者本质相同（都是带三维状态的搜索），区别只在搜索顺序
//
// ============================================================
// 【易错点】
//
// 1. visited 只用二维数组：
//    ✗ visited[x][y] = true
//      → 同一格子用 remain=3 先到达后，remain=1 的路径被错误剪掉，
//        可能那条路径虽然消除次数少但步数更短
//    ✓ visited[x][y][remain] = true
//      → 每个 (x, y, remain) 独立标记
//
// 2. 忘记 k >= m+n-3 的剪枝：
//    ✗ 直接 BFS，k=m*n 时 visited 数组有 40*40*1600=256万 个元素
//    ✓ 先判断 k >= m+n-3 直接返回 m+n-2
//      → 避免不必要的大状态空间
//
// 3. nRemain 计算错误：
//    ✗ nRemain = remain - 1  （空地也减1）
//    ✓ nRemain = remain - grid[nx][ny]  （只有障碍才消耗）
//
// 4. steps 计数混乱：
//    ✗ 在 for 循环内部 steps++（每个节点都加1，而非每层加1）
//    ✓ 在处理完一整层后 steps++
//      或者把 steps 直接存入队列元组中
//
// 5. A* 中 visited 在入队时标记：
//    ✗ 入队时标记 visited → 先入队的不一定是最优的（优先队列顺序）
//    ✓ 出队时标记 visited → 第一次出队的一定是该状态的最优路径
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么不能用 DFS？
// → BFS 保证第一次到达终点就是最短路径（因为逐层扩展，每层步数+1）。
//   DFS 需要遍历所有可能路径取最小值，状态空间巨大，效率远低于 BFS。
//
// Q2: 为什么 visited 要三维而不是二维？
// → 同一个格子 (x,y) 被不同 remain 值到达时代表不同的"能力状态"。
//   remain=5 的状态后续能穿过更多障碍，可能找到更短的路径。
//   用二维 visited 会错误地阻止有用的状态被探索。
//
// Q3: k 很大时怎么优化？（如 k = m*n）
// → 当 k >= m+n-3 时，从 (0,0) 到 (m-1,n-1) 的曼哈顿路径上
//   最多有 m+n-3 个格子可能是障碍（路径长 m+n-2，减去起终点），
//   消除次数绰绰有余，直接返回 m+n-2。
//
// Q4: A* 的启发式函数为什么选曼哈顿距离？能选欧几里得距离吗？
// → 曼哈顿距离是网格上四方向移动的精确下界，既 admissible 又 consistent。
//   欧几里得距离也是 admissible 的（更小），但不够"紧"，引导效果不如曼哈顿。
//   A* 的启发式越接近真实值，搜索效率越高。
//
// Q5: 这个"状态加一维"的技巧还能用在哪？
// → 很通用！任何"有资源限制的最短路"都可以这样建模：
//   - 787 K站中转最便宜航班: 状态 = (城市, 剩余中转次数)
//   - 带钥匙的迷宫(864): 状态 = (x, y, 钥匙集合的位掩码)
//   - 核心思想: 影响后续决策的变量必须纳入状态定义
// ============================================================
