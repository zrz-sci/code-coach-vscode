/*
 * LeetCode 2413: Smallest Even Multiple (最小偶倍数)
 *
 * 求 2 和 n 的最小公倍数 LCM(2, n)。
 * n 为偶数 → n；n 为奇数 → 2n。
 *
 * 难度：Easy
 * 标签：Math, Number Theory
 */


/* ============================================================
 * 解法1：条件判断 — O(1) / O(1) ⭐ 面试首选
 *
 * 最直觉的分类讨论：
 *   偶数：n 本身就是 2 的倍数 → 返回 n
 *   奇数：最小的同时是 n 和 2 的倍数 → 返回 2*n
 *
 * 数学证明：
 *   LCM(2, n) = 2 * n / GCD(2, n)
 *   当 n 为偶数时 GCD(2, n) = 2 → LCM = 2*n/2 = n
 *   当 n 为奇数时 GCD(2, n) = 1 → LCM = 2*n/1 = 2n
 *
 * 验证（逐个测试）：
 *   n=1 (奇) → 2*1 = 2  ✓  (2 是 2 和 1 的最小公倍数)
 *   n=2 (偶) → 2       ✓  (2 本身就是 2 和 2 的公倍数)
 *   n=3 (奇) → 2*3 = 6  ✓  (6 = 2*3 = 3*2)
 *   n=4 (偶) → 4       ✓  (4 = 2*2)
 *   n=5 (奇) → 2*5 = 10 ✓  (10 = 2*5 = 5*2)
 *   n=6 (偶) → 6       ✓  (6 = 2*3)
 * ============================================================ */

class Solution {
public:
    int smallestEvenMultiple(int n) {
        if (n % 2 == 0) {
            return n;       // 偶数：n 本身就是 2 的倍数
        } else {
            return 2 * n;   // 奇数：最小公倍数是 2n
        }
    }
};


/* ============================================================
 * 解法2：三元运算符一行 — O(1) / O(1)
 *
 * 解法1 的简洁版本，功能完全等价。
 * ============================================================ */

class Solution_Ternary {
public:
    int smallestEvenMultiple(int n) {
        return n % 2 == 0 ? n : 2 * n;
    }
};


/* ============================================================
 * 解法3：数学公式 — O(1) / O(1)
 *
 * n * (1 + n%2) 统一处理奇偶：
 *   偶数：n * (1 + 0) = n * 1 = n
 *   奇数：n * (1 + 1) = n * 2 = 2n
 *
 * 这个公式很优雅，但可读性稍差，需要注释说明。
 * ============================================================ */

class Solution_Formula {
public:
    int smallestEvenMultiple(int n) {
        return n * (1 + n % 2);
    }
};


/* ============================================================
 * 解法4：位运算 — O(1) / O(1)
 *
 * n & 1：提取最低位，偶数为 0，奇数为 1
 * n << 1：左移一位 = 乘以 2
 *
 * 注意位运算优先级：
 *   ✗ n & 1 == 0   → 等价于 n & (1 == 0) → n & 0 → 0
 *   ✓ (n & 1) == 0  → 正确判断奇偶
 * ============================================================ */

class Solution_Bitwise {
public:
    int smallestEvenMultiple(int n) {
        return (n & 1) ? (n << 1) : n;
    }
};


/* ============================================================
 * 解法5：LCM 通用解 — O(log n) / O(1)
 *
 * 使用 LCM 公式：LCM(a, b) = a * b / GCD(a, b)
 * 通用方法，即使 k 不是 2 也能解。
 *
 * GCD 用辗转相除法（欧几里得算法）：
 *   GCD(a, b) = GCD(b, a % b)，直到 b = 0 时返回 a
 *   时间复杂度：O(log min(a, b))
 *
 * 辗转相除法示例：
 *   GCD(12, 8) → GCD(8, 12%8=4) → GCD(4, 8%4=0) → 返回 4
 *   LCM(12, 8) = 12 * 8 / 4 = 24
 *
 * GCD(2, 5) → GCD(5, 2%5=2) → GCD(2, 5%2=1) → GCD(1, 2%1=0) → 返回 1
 *   LCM(2, 5) = 2 * 5 / 1 = 10 ✓
 *
 * GCD(2, 6) → GCD(6, 2%6=2) → GCD(2, 6%2=0) → 返回 2
 *   LCM(2, 6) = 2 * 6 / 2 = 6 ✓
 * ============================================================ */

class Solution_LCM {
public:
    int smallestEvenMultiple(int n) {
        // 手写 GCD 版本
        return 2 * n / gcd_func(2, n);
    }

private:
    // 辗转相除法（迭代版）
    int gcd_func(int a, int b) {
        while (b) {
            int temp = b;
            b = a % b;
            a = temp;
        }
        return a;
    }
};

// 辗转相除法（递归版，一行）
// int gcd_recursive(int a, int b) { return b ? gcd_recursive(b, a%b) : a; }

// C++17 标准库版本（最简洁）
class Solution_STL {
public:
    int smallestEvenMultiple(int n) {
        return lcm(2, n);  // #include <numeric>
    }
};


/* ============================================================
 * 附：数论知识速查
 * ============================================================
 *
 * GCD (Greatest Common Divisor, 最大公约数):
 *   - GCD(a, 0) = a
 *   - GCD(a, b) = GCD(b, a % b)    (辗转相除法)
 *   - GCD(a, b) = GCD(a-b, b)       (更相减损术，a > b)
 *   - 时间：O(log min(a, b))
 *
 * LCM (Least Common Multiple, 最小公倍数):
 *   - LCM(a, b) = a * b / GCD(a, b)
 *   - 注意：先除后乘避免溢出 → a / GCD(a,b) * b
 *   - LCM(a, b, c) = LCM(LCM(a, b), c)  (结合律)
 *
 * 贝祖定理 (Bezout's identity):
 *   - 对任意整数 a, b，存在整数 x, y 使得 ax + by = GCD(a, b)
 *   - 推论：ax + by = c 有整数解 ⟺ GCD(a,b) | c
 *   - 应用：LeetCode 365 水壶问题
 *
 * 互质 (Coprime):
 *   - GCD(a, b) = 1 ⟹ a 和 b 互质
 *   - 此时 LCM(a, b) = a * b
 *   - 2 和奇数永远互质 → LCM = 2 * 奇数
 *
 * C++17 标准库：
 *   #include <numeric>
 *   std::gcd(a, b)  // 求最大公约数
 *   std::lcm(a, b)  // 求最小公倍数
 * ============================================================ */


