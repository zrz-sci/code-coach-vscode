/*
 * LeetCode 452: 用最少数量的箭引爆气球 (Minimum Number of Arrows to Burst Balloons)
 *
 * 【题目本质】
 * 给定一组区间 [start, end]，求最少多少个"点"能使得每个区间至少包含一个点。
 * 这是经典的"区间调度/活动选择"贪心问题。
 *
 * 【解法总览】
 * 解法1: 按右端点排序 + 贪心 — O(n log n) / O(log n) — 最简洁，面试首选
 * 解法2: 按左端点排序 + 贪心 — O(n log n) / O(log n) — 维护交集右端点
 *
 * 两种本质一样，只是排序方向不同导致维护逻辑略有差异。
 */

// ============================================================
// 解法1: 按右端点排序 + 贪心（经典活动选择）
// 时间: O(n log n)  空间: O(log n) 排序栈空间
//
// 【思路】
// 经典贪心：按右端点从小到大排序后，第一支箭射在第一个气球的
// 右端点——这是覆盖第一个气球的"最贪心"位置（尽量靠右，
// 给后续气球留更大的被顺带引爆的机会）。
// 
// 遍历过程中，如果某个气球的 start > 当前箭的位置，
// 说明这支箭够不着它，必须增加一支新箭。
//
// 可视化（示例1按右端点排序后）:
//
//   [1------6]
//      [2--------8]
//              [7------12]
//                 [10--------16]
//   |-----|-----|-----|-----|-----|
//   1     4     7    10    13    16
//
//   箭1 射在 x=6:  引爆 [1,6] 和 [2,8] (因为 2<=6<=8)
//   箭2 射在 x=12: 引爆 [7,12] 和 [10,16]
//   答案: 2
//
// 贪心正确性证明（反证法）:
// 假设最优解第一支箭没射在第一个气球(右端点最小)的右端点处，
// 那它只能射在更左的位置（否则覆盖不到第一个气球）。
// 但更左的位置覆盖的后续气球只会 ≤ 射在右端点处，
// 所以射在右端点至少不比最优解差。归纳可得全局最优。
// ============================================================
class Solution1 {
public:
    int findMinArrowShots(vector<vector<int>>& points) {
        if (points.empty()) return 0;
        
        // 按右端点升序排序
        // 注意：用 < 比较而非减法，避免 int 溢出（坐标范围 ±2^31）
        sort(points.begin(), points.end(), [](const vector<int>& a, const vector<int>& b) {
            return a[1] < b[1];
        });
        
        int arrows = 1;                   // 至少需要一支箭射第一个气球
        int arrow_pos = points[0][1];     // 第一支箭射在第一个气球的右端点
        
        for (int i = 1; i < (int)points.size(); i++) {
            if (points[i][0] > arrow_pos) {
                // 当前气球的起点在箭的右边 → 箭够不着 → 需要新箭
                arrows++;
                arrow_pos = points[i][1]; // 新箭射在这个气球的右端点
            }
            // else: 当前气球被已有的箭引爆（start <= arrow_pos），跳过
        }
        
        return arrows;
    }
};

// ============================================================
// 解法2: 按左端点排序 + 贪心（维护交集右端点）
// 时间: O(n log n)  空间: O(log n)
//
// 【思路】
// 按左端点排序后，依次遍历气球，维护"当前这支箭还能到达的
// 最远位置"（即当前一组重叠气球的公共区间右端点）。
//
// 为什么要取 min？因为按左端点排序后，后面的气球右端点不一定更大。
// 例如 [1,10] [2,3] [4,8]，排序后第二个气球 [2,3] 的右端点 3
// 比第一个的 10 小得多，箭必须射在 3 以内才能同时覆盖两者。
//
// 可视化：
//   [1-----------10]
//     [2--3]          ← end 从 10 缩小到 3
//           [4----8]  ← start=4 > end=3 → 断开，需要新箭
//
//   箭1 射在 x=3: 引爆 [1,10] 和 [2,3]
//   箭2 射在 x=8: 引爆 [4,8]
//   答案: 2
// ============================================================
class Solution2 {
public:
    int findMinArrowShots(vector<vector<int>>& points) {
        if (points.empty()) return 0;
        
        // 按左端点升序排序
        sort(points.begin(), points.end(), [](const vector<int>& a, const vector<int>& b) {
            return a[0] < b[0];
        });
        
        int arrows = 1;
        int end = points[0][1];  // 当前箭能到达的最远位置（公共交集右端点）
        
        for (int i = 1; i < (int)points.size(); i++) {
            if (points[i][0] > end) {
                // 当前气球起点超过了公共交集 → 断开 → 需要新箭
                arrows++;
                end = points[i][1];        // 新一组的右端点
            } else {
                // 有重叠 → 缩小公共区间右端点
                // 为什么取 min：箭必须在所有重叠气球的公共区域内才能全部引爆
                end = min(end, points[i][1]);
            }
        }
        
        return arrows;
    }
};

// ============================================================
// 【解法对比】
//
// | 特性         | 解法1（按右端点）    | 解法2（按左端点）    |
// |-------------|--------------------|--------------------|
// | 排序依据     | end 升序            | start 升序          |
// | 核心操作     | 断开时更新箭位置     | 每步取 min 维护交集  |
// | 代码行数     | 更短（无 min 操作）  | 多一行 min           |
// | 思维模型     | 活动选择（经典）     | 区间交集合并         |
// | 结果         | 完全一致            | 完全一致             |
//
// 面试推荐：解法1更简洁不易出错，但要能解释贪心正确性。
//
// ============================================================
// 【易错点】
//
// 1. 排序比较函数溢出:
//    ✗ sort(..., [](auto& a, auto& b) { return a[1] - b[1]; });
//      当 a[1]=INT_MAX, b[1]=INT_MIN 时，减法溢出！
//    ✓ sort(..., [](auto& a, auto& b) { return a[1] < b[1]; });
//
// 2. 边界相切的判断:
//    ✗ if (points[i][0] >= arrow_pos)  → [1,2] 和 [2,3] 被误判为不重叠
//    ✓ if (points[i][0] > arrow_pos)   → 题意明确 start ≤ x ≤ end 就算引爆
//
// 3. 按左端点排序时忘记 min:
//    ✗ 只在断开时更新 end，重叠时不处理
//      → 对于 [1,10],[2,3],[4,8] 会认为三个都重叠（end=10），实际 [4,8] 和 [2,3] 无交集
//    ✓ 重叠时 end = min(end, points[i][1]) 缩小公共区间
//
// 4. 初始化 arrows=0 而非 1:
//    ✗ arrows=0，从第 0 个开始循环但忘记加第一支箭的逻辑
//    ✓ arrows=1，从第 1 个开始循环，更清晰（需要先判空）
//
// ============================================================
// 【面试追问】
//
// Q1（基础理解）: 为什么要排序？不排序能做吗？
// A: 不排序则无法用线性扫描判断重叠关系，需要类似集合覆盖的
//    NP-hard 搜索。排序后相邻区间才有"重叠/断开"的清晰判断。
//
// Q2（贪心证明）: 凭什么贪心选"射在右端点"就是对的？
// A: 反证法：最优解中第一支箭不在第一个气球右端点处，则必然更左。
//    更左位置覆盖后续气球不会更多，故射在右端点至少不差。归纳全局最优。
//
// Q3（变体）: 如果边界不重叠（开区间），代码改哪里？
// A: 把 if (points[i][0] > arrow_pos) 改为 >= 即可。
//
// Q4（关联题）: 这题和 LeetCode 435（无重叠区间）什么关系？
// A: 互补关系。435 求最少删几个区间使无重叠 = n - 本题答案。
//    排序和贪心策略完全一样，答案取补即可。
//
// Q5（扩展）: 如果坐标是浮点数，有什么需要注意？
// A: 浮点比较精度问题。判断重叠时不能直接 >，需要加 epsilon。
//    排序逻辑不变，但 min/比较操作需考虑精度。
// ============================================================
