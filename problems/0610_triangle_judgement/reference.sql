-- ============================================================
-- 610. Triangle Judgement (判断三角形)
-- 难度: Easy | 标签: Database
-- ============================================================

-- ============================================================
-- 解法一: CASE WHEN (推荐, 最直观)
-- 思路: 三角形充要条件 -- 任意两边之和 > 第三边
--   x + y > z  AND  x + z > y  AND  y + z > x
-- 三个条件全部满足 -> 'Yes', 否则 -> 'No'
-- 时间复杂度: O(n)  空间: O(1) (逐行判断)
-- ============================================================
SELECT
    x,
    y,
    z,
    CASE
        WHEN x + y > z
         AND x + z > y
         AND y + z > x
        THEN 'Yes'
        ELSE 'No'
    END AS triangle
FROM Triangle;

-- ============================================================
-- 解法二: IF 函数 (MySQL 语法糖, 更简洁)
-- 思路: 与解法一完全等价, 只是用 IF 替代 CASE WHEN
-- 时间复杂度: O(n)  空间: O(1)
-- ============================================================
SELECT
    x,
    y,
    z,
    IF(
        x + y > z AND x + z > y AND y + z > x,
        'Yes',
        'No'
    ) AS triangle
FROM Triangle;

-- ============================================================
-- 解法三: 数学优化 -- 只判最大边 (等价简化)
-- 思路: 三角不等式等价于 "最大边 < 另两边之和"
--   GREATEST(x,y,z) < x + y + z - GREATEST(x,y,z)
-- 即 2 * GREATEST(x,y,z) < x + y + z
-- 时间复杂度: O(n)  空间: O(1)
-- ============================================================
SELECT
    x,
    y,
    z,
    CASE
        WHEN 2 * GREATEST(x, y, z) < x + y + z THEN 'Yes'
        ELSE 'No'
    END AS triangle
FROM Triangle;
