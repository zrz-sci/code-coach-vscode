/*
 * LeetCode 932: Beautiful Array (漂亮数组)
 *
 * 【题目本质】
 * 构造 [1,n] 的排列，使得任意三元 i<k<j 不满足 2*nums[k]==nums[i]+nums[j]。
 * 即排列中不含三元算术级数。利用奇偶分治巧妙构造。
 *
 * 【解法总览】
 * 解法1: 分治递归构造(带记忆化) — O(n log n) / O(n log n) — 面试首选
 * 解法2: 迭代自底向上构造       — O(n log n) / O(n)       — 空间更优
 */

// ============================================================
// 解法1: 分治递归构造
// 时间: O(n log n)  空间: O(n log n) (递归栈 + 记忆化)
//
// 【核心数学性质】
// 如果 nums[i] 是奇数，nums[j] 是偶数（或反过来），则：
//   nums[i] + nums[j] = 奇数
//   2 * nums[k] = 偶数
//   奇数 != 偶数 → 不可能形成算术级数
//
// 所以：把所有奇数放左半边，所有偶数放右半边，
// 跨越两半的三元组自动安全！
// 只需保证左半边内部和右半边内部也各自是漂亮数组。
//
// 【仿射不变性】
// 如果 A 是漂亮数组（满足 2*A[k] != A[i]+A[j]），
// 则 k*A[x]+b 对所有元素做线性变换后仍是漂亮数组。
// 证明: 2*(k*A[k]+b) = k*(2*A[k])+2b
//        (k*A[i]+b)+(k*A[j]+b) = k*(A[i]+A[j])+2b
//        两者相等 ⟺ 2*A[k] = A[i]+A[j]，与原条件矛盾。
//
// 【递归构造】
// beautifulArray(n):
//   奇数部分: beautifulArray((n+1)/2) 的每个元素 x → 2x-1
//     产生 {1,3,5,...} 中前 (n+1)/2 个奇数
//   偶数部分: beautifulArray(n/2) 的每个元素 x → 2x
//     产生 {2,4,6,...} 中前 n/2 个偶数
//   拼接: [奇数部分, 偶数部分]
//
// 示例: beautifulArray(5)
//   奇数: beautifulArray(3) = [1,3,2] → [1,5,3]
//   偶数: beautifulArray(2) = [1,2]   → [2,4]
//   结果: [1,5,3,2,4]
//
//   beautifulArray(3)
//     奇数: beautifulArray(2) = [1,2] → [1,3]
//     偶数: beautifulArray(1) = [1]   → [2]
//     结果: [1,3,2]
//
//   beautifulArray(2)
//     奇数: beautifulArray(1) = [1] → [1]
//     偶数: beautifulArray(1) = [1] → [2]
//     结果: [1,2]
// ============================================================
class Solution1 {
public:
    unordered_map<int, vector<int>> memo;

    vector<int> beautifulArray(int n) {
        // 记忆化：相同的 n 直接返回缓存结果
        if (memo.count(n)) return memo[n];

        vector<int> result;

        if (n == 1) {
            // 基准情况：长度1的数组一定是漂亮的
            result = {1};
        } else {
            // 递归构造

            // 奇数部分：子问题规模 (n+1)/2
            // 映射: x → 2x-1 (将 [1,m] 映射到 {1,3,5,...,2m-1})
            for (int x : beautifulArray((n + 1) / 2)) {
                result.push_back(2 * x - 1);
            }

            // 偶数部分：子问题规模 n/2
            // 映射: x → 2x (将 [1,m] 映射到 {2,4,6,...,2m})
            for (int x : beautifulArray(n / 2)) {
                result.push_back(2 * x);
            }
        }

        memo[n] = result;
        return result;
    }
};

// ============================================================
// 解法2: 迭代自底向上构造
// 时间: O(n log n)  空间: O(n)
//
// 【思路】
// 从 [1] 开始，每步将当前漂亮数组 A 扩展为 [2A-1, 2A]
// （奇数映射放前，偶数映射放后），过滤掉 > n 的值。
//
// 迭代过程 (n=5):
//   初始: [1]
//   第1步: 奇[1]=[1], 偶[2]=[2] → [1,2]
//   第2步: 奇[1,3]=[1,3], 偶[2,4]=[2,4] → [1,3,2,4]
//   第3步: 奇[1,5,3]=[1,5,3], 偶[2,4]=[2,4] → [1,5,3,2,4]
//          (2*4-1=7>5 被过滤, 2*3=6>5 被过滤, 2*4=8>5 被过滤)
//          等等...实际上由于过滤，[1,3,2,4] 已经包含4个元素
//          第3步: 奇[2*1-1,2*3-1,2*2-1,2*4-1]=[1,5,3,7]过滤→[1,5,3]
//                 偶[2*1,2*3,2*2,2*4]=[2,6,4,8]过滤→[2,4]
//          合并: [1,5,3,2,4] → 5个元素，结束
//
// 每步数组大小最多翻倍，所以 O(log n) 步后达到 n。
// ============================================================
class Solution2 {
public:
    vector<int> beautifulArray(int n) {
        vector<int> result = {1};

        // 不断扩展直到包含 n 个元素
        while ((int)result.size() < n) {
            vector<int> next;

            // 先放奇数映射: 2x-1
            for (int x : result) {
                if (2 * x - 1 <= n) {
                    next.push_back(2 * x - 1);
                }
            }

            // 再放偶数映射: 2x
            for (int x : result) {
                if (2 * x <= n) {
                    next.push_back(2 * x);
                }
            }

            result = next;
        }

        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间       | 空间        | 优势              |
// |-----------|-----------|-------------|------------------|
// | 分治递归   | O(nlogn)  | O(nlogn)    | 代码简洁，好解释   |
// | 迭代构造   | O(nlogn)  | O(n)        | 无递归开销，空间优  |
//
// 面试推荐分治递归（思路自然，面试官容易理解）。
// 如果被追问空间优化，再讲迭代版本。
//
// ============================================================
// 【易错点】
//
// 1. 奇偶个数计算:
//    ✗ 奇数部分 n/2，偶数部分 n/2
//      → n为奇数时总数不对（少了一个奇数）
//    ✓ 奇数部分 (n+1)/2，偶数部分 n/2
//      → 奇数总是 >= 偶数（n为奇时多一个）
//
// 2. 映射公式搞反:
//    ✗ 奇数映射 2x+1（产生 3,5,7... 缺少1）
//    ✓ 奇数映射 2x-1（产生 1,3,5...）
//
// 3. 迭代版本忘记过滤 > n 的值:
//    ✗ 直接 push_back(2*x-1) → 产生超出 [1,n] 范围的值
//    ✓ 加 if (2*x-1 <= n) 过滤
//
// 4. 递归没有记忆化:
//    虽然不加 memo 也能过（递归树实际不大），
//    但重复计算 beautifulArray(1)、beautifulArray(2) 等
//    在面试中加 memo 展示完整思考。
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 为什么"奇前偶后"就不会有跨越的算术级数？
//     nums[i](奇) + nums[j](偶) = 奇数
//     2*nums[k] = 偶数
//     奇数 != 偶数，所以跨越部分天然安全。
//
// Q2: 仿射不变性有什么用？
//     它保证了递归过程中的线性映射不会破坏漂亮性质。
//     beautifulArray(m) → 2x-1 映射后仍是漂亮数组。
//     这是整个算法正确性的数学基础。
//
// Q3: 时间复杂度 O(nlogn) 怎么来的？
//     递归树有 O(logn) 层（每次规模减半）。
//     每层处理的总元素数是 O(n)（所有子问题大小之和 ≤ n）。
//     总计 O(nlogn)。
//
// Q4: 有没有 O(n) 的构造方法？
//     目前没有已知的 O(n) 确定性构造。
//     O(nlogn) 的分治构造已经是最优的已知方法。
