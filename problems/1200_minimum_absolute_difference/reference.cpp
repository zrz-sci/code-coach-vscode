/*
 * LeetCode 1200: 最小绝对差 (Minimum Absolute Difference)
 *
 * 【题目本质】
 * 在一组互不相同的整数中，找出所有绝对差最小的元素对。
 * 核心观察：排序后，最小绝对差一定出现在相邻元素之间。
 *
 * 【解法总览】
 * 解法1: 暴力枚举       — O(n²) / O(1)     — 最直觉，枚举所有对
 * 解法2: 排序+两次遍历  — O(n log n) / O(1) — 面试首选，清晰直观
 * 解法3: 排序+一次遍历  — O(n log n) / O(1) — 最简洁，边找边收集
 */

// ============================================================
// 解法1: 暴力枚举 — 枚举所有 C(n,2) 个对
// 时间: O(n²)  空间: O(1)（不计输出）
//
// 【思路】
// 最朴素的想法：先遍历所有对找最小差，再遍历所有对收集结果。
// 为了保证输出按升序，收集前需要排序。
//
// 这个解法的瓶颈很明显：n=10^5 时 O(n²) ≈ 10^10，太慢。
// 但它揭示了优化方向——既然要排序，不如一开始就排序，
// 利用有序性把比较次数从 O(n²) 降到 O(n)。
// ============================================================

// 示例演示:
// arr = [3, 8, -10, 23, 19, -4, -14, 27]
//
// 暴力枚举所有对: C(8,2) = 28 个对
// 找到最小差 = 4
// 排序后: [-14, -10, -4, 3, 8, 19, 23, 27]
// 收集差=4的对: (-14,-10), (19,23), (23,27)

class Solution1 {
public:
    vector<vector<int>> minimumAbsDifference(vector<int>& arr) {
        int n = arr.size();
        
        // 第一遍: 枚举所有对，找最小绝对差
        int minDiff = INT_MAX;
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                minDiff = min(minDiff, abs(arr[i] - arr[j]));
            }
        }
        
        // 排序，保证输出按升序
        sort(arr.begin(), arr.end());
        
        // 第二遍: 收集所有差等于 minDiff 的相邻对
        // 排序后只看相邻对就够了（非相邻对的差一定 >= 相邻对的差）
        vector<vector<int>> result;
        for (int i = 1; i < n; i++) {
            if (arr[i] - arr[i - 1] == minDiff) {
                result.push_back({arr[i - 1], arr[i]});
            }
        }
        
        return result;
    }
};

// ============================================================
// 解法2: 排序 + 两次遍历 — 面试首选，逻辑清晰
// 时间: O(n log n)  空间: O(1)（不计输出）
//
// 【思路】
// 核心观察: 最小绝对差一定出现在排序后相邻元素之间。
// 
// 证明（反证法）:
// 设排序后 arr[i] < arr[j] < arr[k]，
// 则 arr[k]-arr[i] = (arr[k]-arr[j]) + (arr[j]-arr[i]) > arr[j]-arr[i]
// 所以"跳过中间元素"的差一定更大，最小差只可能在相邻对之间。
//
// 算法:
// Step1: 排序
// Step2: 遍历所有相邻对，找最小差 minDiff
// Step3: 再遍历一次，收集所有差等于 minDiff 的对
//
// 排序后:  [-14, -10, -4,  3,  8, 19, 23, 27]
// 相邻差:     4    6   7   5  11   4   4
//             ↑                    ↑   ↑
//           minDiff = 4，这三个位置的对就是答案
// ============================================================
class Solution2 {
public:
    vector<vector<int>> minimumAbsDifference(vector<int>& arr) {
        sort(arr.begin(), arr.end());
        int n = arr.size();
        
        // 第一遍: 找最小差
        // 排序后 arr[i] > arr[i-1]（元素互不相同），所以差一定 > 0
        int minDiff = INT_MAX;
        for (int i = 1; i < n; i++) {
            // 排序后不需要 abs()，因为 arr[i] > arr[i-1] 恒成立
            minDiff = min(minDiff, arr[i] - arr[i - 1]);
        }
        
        // 第二遍: 收集差等于 minDiff 的相邻对
        // 由于从左到右遍历排序数组，结果自然按升序
        vector<vector<int>> result;
        for (int i = 1; i < n; i++) {
            if (arr[i] - arr[i - 1] == minDiff) {
                result.push_back({arr[i - 1], arr[i]});
            }
        }
        
        return result;
    }
};

// ============================================================
// 解法3: 排序 + 一次遍历 — 最简洁
// 时间: O(n log n)  空间: O(1)（不计输出）
//
// 【思路】
// 解法2用了两次遍历，其实可以合并为一次。
// 核心技巧: 遍历时动态维护当前最小差 minDiff。
//   - 发现更小的差 → 旧结果全部作废，清空 result，用新的差
//   - 差等于 minDiff → 追加到 result
//   - 差大于 minDiff → 跳过
//
// 演示过程:
// 排序后: [-14, -10, -4, 3, 8, 19, 23, 27]
//
// i=1: diff=4,  4 < INT_MAX → clear, minDiff=4, result=[(-14,-10)]
// i=2: diff=6,  6 > 4       → skip
// i=3: diff=7,  7 > 4       → skip
// i=4: diff=5,  5 > 4       → skip
// i=5: diff=11, 11 > 4      → skip
// i=6: diff=4,  4 == 4      → append, result=[(-14,-10),(19,23)]
// i=7: diff=4,  4 == 4      → append, result=[(-14,-10),(19,23),(23,27)]
// ============================================================
class Solution3 {
public:
    vector<vector<int>> minimumAbsDifference(vector<int>& arr) {
        sort(arr.begin(), arr.end());
        
        vector<vector<int>> result;
        int minDiff = INT_MAX;
        
        for (int i = 1; i < (int)arr.size(); i++) {
            int diff = arr[i] - arr[i - 1];
            
            if (diff < minDiff) {
                // 发现更小的差 → 之前收集的全不是"最小差"了
                minDiff = diff;
                result.clear();  // 清空旧结果是这个解法的关键
                result.push_back({arr[i - 1], arr[i]});
            } else if (diff == minDiff) {
                // 差相同 → 追加
                result.push_back({arr[i - 1], arr[i]});
            }
            // diff > minDiff → 不可能是最小差，跳过
        }
        
        return result;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法            | 时间        | 空间  | 遍历次数    | 代码复杂度 |
// |----------------|-------------|-------|------------|-----------|
// | 暴力枚举        | O(n²)      | O(1)  | 两遍O(n²)  | 简单但慢   |
// | 排序+两次遍历   | O(n log n) | O(1)  | 排序+2遍   | 清晰直观   |
// | 排序+一次遍历   | O(n log n) | O(1)  | 排序+1遍   | 最简洁     |
//
// 三者的性能瓶颈都是排序的 O(n log n)，后两者只是常数差异。
// 面试中优先写解法2（逻辑分两步，不容易出错），
// 如果面试官追问"能否一次遍历"再优化到解法3。
//
// 【易错点】
// 1. 排序后仍然用 abs()：
//    ✗ abs(arr[i] - arr[i-1])  — 多余，虽然结果正确但暴露理解不深
//    ✓ arr[i] - arr[i-1]       — 排序后且元素互不相同，差一定 > 0
//
// 2. 一次遍历时忘记 result.clear():
//    ✗ 只更新 minDiff 不清空 result → 旧的非最小差对混入结果
//    ✓ minDiff = diff; result.clear(); result.push_back(...)
//
// 3. 结果输出顺序错误:
//    ✗ 在未排序数组上收集结果 → 输出不按升序
//    ✓ 先排序，再从左到右收集，自然满足升序要求
//
// 4. 循环起点错误:
//    ✗ for(int i = 0; ...) 然后用 arr[i] 和 arr[i+1] → i=n-1 时越界
//    ✓ for(int i = 1; ...) 然后用 arr[i-1] 和 arr[i]  → 安全
//
// 【面试追问】
// Q1: 为什么最小差一定在排序后相邻元素之间？
// A1: 反证法。设 arr[i] < arr[j] < arr[k]，
//     则 arr[k]-arr[i] = (arr[k]-arr[j])+(arr[j]-arr[i]) > arr[j]-arr[i]，
//     所以跨过中间元素的差一定更大。
//
// Q2: 如果数组有重复元素怎么办？
// A2: 最小差变成 0，排序后相等元素相邻，收集逻辑不变。
//     只需注意输出格式是否要去重（题目说 a < b，重复元素 a==b 不满足）。
//
// Q3: 能否做到 O(n) 时间（不排序）？
// A3: 可以用桶/计数排序思想。值域[-10^6, 10^6]，开 2*10^6 大小的布尔数组
//     标记哪些值存在，线性扫描找相邻存在值的最小差。时间 O(n+V)，V是值域范围。
//     这本质上是用空间换时间，将排序步骤从 O(n log n) 降到 O(n+V)。
// ============================================================
