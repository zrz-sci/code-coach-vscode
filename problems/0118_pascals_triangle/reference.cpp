/*
 * LeetCode 118: 杨辉三角 (Pascal's Triangle)
 *
 * 【题目本质】
 * 逐行生成杨辉三角：第 i 行第 j 个元素 = 上一行第 j-1 个 + 上一行第 j 个。
 * 本质是一道模拟/递推题，也可以看作最简单的二维 DP。
 *
 * 【解法总览】
 * 解法1: 逐行递推       — O(n²) / O(1) — 面试首选，最直觉
 * 解法2: 组合数递推     — O(n²) / O(1) — 数学方法，加分项
 */

// ============================================================
// 解法1: 逐行递推 — 每行根据上一行累加 ⭐ 面试首选
// 时间: O(n²)  空间: O(1) 额外（输出不计）
//
// 【思路】
// 杨辉三角的定义本身就是递推关系：
//   row[i][j] = row[i-1][j-1] + row[i-1][j]
// 最自然的做法就是一行一行生成。
//
// 把杨辉三角左对齐看下标关系：
//
//     j:  0   1   2   3   4
// i=0:    1
// i=1:    1   1
// i=2:    1   2   1           ← row[2][1] = row[1][0]+row[1][1] = 2
// i=3:    1   3   3   1       ← row[3][2] = row[2][1]+row[2][2] = 3
// i=4:    1   4   6   4   1   ← row[4][2] = row[3][1]+row[3][2] = 6
//
// 每行首尾为 1，中间元素由上一行两个相邻元素相加。
//
// 【为什么初始化为全 1？】
// 每行的第 0 个和最后一个元素都是 1。
// 如果用 vector<int> row(i+1, 1) 初始化，首尾的 1 自动就位，
// 内层循环只需要处理 j=1 到 j=i-1 的中间部分。
// 当 i<=1 时内层循环不执行，自动覆盖了 [1] 和 [1,1] 两个 base case。
// ============================================================
class Solution1 {
public:
    vector<vector<int>> generate(int numRows) {
        vector<vector<int>> triangle;
        
        for (int i = 0; i < numRows; i++) {
            // 第 i 行有 i+1 个元素，全部初始化为 1
            // 这样首尾的 1 不需要单独处理
            vector<int> row(i + 1, 1);
            
            // 填充中间元素：j 从 1 到 i-1
            // 当 i=0 或 i=1 时，这个循环不执行 → base case 自动覆盖
            for (int j = 1; j < i; j++) {
                // 核心递推：当前位置 = 上一行的 [j-1] + 上一行的 [j]
                row[j] = triangle[i - 1][j - 1] + triangle[i - 1][j];
            }
            
            triangle.push_back(row);
        }
        
        return triangle;
    }
};

// ============================================================
// 解法2: 组合数递推 — 利用 C(n,k) = C(n,k-1)*(n-k+1)/k
// 时间: O(n²)  空间: O(1) 额外
//
// 【思路】
// 从数学角度看，杨辉三角第 i 行第 j 个元素就是组合数 C(i, j)。
// 关键递推公式：C(n, k) = C(n, k-1) * (n - k + 1) / k
// 同一行内，从左到右，每个元素由前一个元素 O(1) 推出。
//
// 以第4行为例:
// C(4,0) = 1
// C(4,1) = 1 * 4/1 = 4
// C(4,2) = 4 * 3/2 = 6
// C(4,3) = 6 * 2/3 = 4
// C(4,4) = 4 * 1/4 = 1
// → [1, 4, 6, 4, 1] ✓
//
// 【为什么先乘后除？】
// 整数除法有截断，如果先除再乘可能不整除导致结果错误。
// 但 C(n,k) 一定是整数，所以 C(n,k-1)*(n-k+1) 一定能被 k 整除。
// 先乘后除就能保证正确。
//
// 【优势】
// 不依赖上一行的结果，每行独立计算。
// 如果只需要某一行（LeetCode 119），这种方法不需要存所有行。
// ============================================================
class Solution2 {
public:
    vector<vector<int>> generate(int numRows) {
        vector<vector<int>> triangle;
        
        for (int i = 0; i < numRows; i++) {
            vector<int> row(i + 1);
            row[0] = 1;  // C(i, 0) = 1
            
            for (int j = 1; j <= i; j++) {
                // C(i, j) = C(i, j-1) * (i - j + 1) / j
                // 用 long long 防止中间乘法溢出（好习惯）
                row[j] = (long long)row[j - 1] * (i - j + 1) / j;
            }
            
            triangle.push_back(row);
        }
        
        return triangle;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度         | 解法1 逐行递推    | 解法2 组合数递推      |
// |-------------|-------------------|---------------------|
// | 依赖关系     | 当前行依赖上一行   | 每行独立计算          |
// | 实现难度     | 非常简单           | 需要组合数递推公式     |
// | 溢出风险     | 无(只做加法)       | 有(乘法需要long long) |
// | 扩展性       | 需要前面所有行     | 可以只算第n行          |
// | 面试推荐     | ⭐ 首选            | 追问"只要第n行"时用    |
//
// 两种解法时间空间复杂度相同，面试优先写解法1（简单不易错），
// 被追问"只返回第n行且O(n)空间"时切换到解法2或滚动数组。
//
// ============================================================
// 【易错点】
//
// 1. 内层循环边界: j < i（不是 j <= i）
//    ✗ for(int j=1; j<=i; j++) row[j] = triangle[i-1][j-1]+triangle[i-1][j];
//      → 当 j==i 时 triangle[i-1][j] 越界（上一行只有 i 个元素，下标最大 i-1）
//    ✓ for(int j=1; j<i; j++) 保证 j 不超过上一行的有效下标
//
// 2. 组合数方法先除后乘:
//    ✗ row[j] = row[j-1] / j * (i-j+1)  → 整数除法截断导致结果错误
//    ✓ row[j] = (long long)row[j-1] * (i-j+1) / j  → 先乘后除保证整除
//
// 3. 忘记处理 numRows==1 的情况:
//    ✓ 两种解法的循环结构天然覆盖了 numRows==1（只执行 i=0 一次，
//      内层循环不执行，生成 [1]）
//
// ============================================================
// 【面试追问】
//
// Q1（基础理解）: 时间和空间复杂度？
// → 时间 O(n²)（1+2+...+n 个元素），额外空间 O(1)（输出不计）。
//
// Q2（变体 — LeetCode 119）: 只返回第 n 行，O(n) 空间？
// → 方法A: 用一维数组，每次从右往左更新 row[j] += row[j-1]，
//   从右往左是为了避免覆盖还需使用的旧值。
// → 方法B: 组合数递推直接算第 n 行，只需一个数组。
//
// Q3（数学扩展）: 杨辉三角和二项式定理的关系？
// → 第 n 行就是 (a+b)^n 展开式的系数: C(n,0), C(n,1), ..., C(n,n)。
//   所以每行之和 = 2^n（令 a=b=1）。
// ============================================================
