/*
 * LeetCode 11: Container With Most Water
 * 
 * 【题目本质】
 * 在数组中找两个位置 i, j，使得 min(height[i], height[j]) * |j - i| 最大。
 * 本质是"双端贪心淘汰"：每次淘汰短板一侧的所有配对。
 *
 * 【解法总览】
 * 解法1: 暴力枚举 — O(n²) / O(1) — 最直觉，枚举所有配对
 * 解法2: 双指针贪心 — O(n) / O(1) — 最优，左右夹逼移动短板
 */

// ============================================================
// 解法1: 暴力枚举 — 枚举所有 (i, j) 配对
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 最朴素的想法：两层循环遍历所有线对，计算每对的面积，取最大。
// 面积 = min(height[i], height[j]) * (j - i)
//
// 【瓶颈】
// n = 10^5 时需要约 5×10^9 次运算，显然超时。
// 但这是理解题意和面积公式的基础，面试中可以先提一下暴力解。
// ============================================================
class Solution1 {
public:
    int maxArea(vector<int>& height) {
        int n = height.size();
        int maxWater = 0;
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                int area = min(height[i], height[j]) * (j - i);
                maxWater = max(maxWater, area);
            }
        }
        return maxWater;
    }
};

// ============================================================
// 解法2: 双指针（贪心）— 左右夹逼，移动短板
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 从暴力解的 O(n²) 出发，思考：能否一步淘汰多个不可能的配对？
//
// 核心观察：
//   设 left=0, right=n-1，此时宽度最大。
//   面积 = min(h[L], h[R]) * (R - L)
//
//   假设 h[L] < h[R]（L 是短板）:
//   - 如果保留 L 不动，让 R 向左移动到任意 r < R:
//     新面积 = min(h[L], h[r]) * (r - L)
//     由于 min(h[L], h[r]) <= h[L]（短板限制），且 r - L < R - L
//     所以新面积 < 当前面积
//   - 结论：以 L 为左端的所有更窄配对，面积都不如当前值
//   - 所以可以安全地移动 L，这些配对全部淘汰
//
// 每步淘汰 O(n) 个配对，总共只需 O(n) 步。
//
// 【可视化过程】 height = [1, 8, 6, 2, 5, 4, 8, 3, 7]
//                 索引:     0  1  2  3  4  5  6  7  8
//
//   Step1: L=0, R=8  h=[1,7]  area=min(1,7)*8=8    → 移L(短板1)
//   Step2: L=1, R=8  h=[8,7]  area=min(8,7)*7=49 ★ → 移R(短板7)
//   Step3: L=1, R=7  h=[8,3]  area=min(8,3)*6=18   → 移R(短板3)
//   Step4: L=1, R=6  h=[8,8]  area=min(8,8)*5=40   → 相等,移L
//   Step5: L=2, R=6  h=[6,8]  area=min(6,8)*4=24   → 移L(短板6)
//   Step6: L=3, R=6  h=[2,8]  area=min(2,8)*3=6    → 移L(短板2)
//   Step7: L=4, R=6  h=[5,8]  area=min(5,8)*2=10   → 移L(短板5)
//   Step8: L=5, R=6  h=[4,8]  area=min(4,8)*1=4    → L+1=R,结束
//
//   答案: 49
// ============================================================
class Solution2 {
public:
    int maxArea(vector<int>& height) {
        int left = 0, right = height.size() - 1;
        int maxWater = 0;
        
        while (left < right) {
            // 计算当前配对的面积
            int w = right - left;
            int h = min(height[left], height[right]);
            maxWater = max(maxWater, w * h);
            
            // 贪心：移动较短的那根线
            // 为什么？因为保留短板、移动长板，面积只可能更差（证明见上）
            if (height[left] < height[right]) {
                left++;
            } else {
                // height[left] >= height[right] 时移动 right
                // 等号时移动哪边都正确（对称性）
                right--;
            }
        }
        
        return maxWater;
    }
};

// ============================================================
// 解法2 变体: 双指针 + 跳过无用移动（小优化）
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 在移动短板时，如果新位置的高度 <= 当前短板高度，
// 那么面积一定更小（宽度缩小，高度没增加），可以直接跳过。
// 最坏情况仍然 O(n)，但常数可能更优。
// ============================================================
class Solution2b {
public:
    int maxArea(vector<int>& height) {
        int left = 0, right = height.size() - 1;
        int maxWater = 0;
        
        while (left < right) {
            int h = min(height[left], height[right]);
            maxWater = max(maxWater, h * (right - left));
            
            // 跳过所有不可能带来更大面积的位置
            // 只有遇到更高的线才停下来重新计算
            if (height[left] < height[right]) {
                int curLeft = height[left];
                while (left < right && height[left] <= curLeft) {
                    left++;  // 跳过所有 <= 当前短板的线
                }
            } else {
                int curRight = height[right];
                while (left < right && height[right] <= curRight) {
                    right--;  // 跳过所有 <= 当前短板的线
                }
            }
        }
        
        return maxWater;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法     | 时间  | 空间 | 核心思想                     |
// |----------|-------|------|------------------------------|
// | 暴力枚举 | O(n²) | O(1) | 遍历所有配对                 |
// | 双指针   | O(n)  | O(1) | 贪心：移短板，淘汰不优配对   |
// | 双指针+跳| O(n)  | O(1) | 额外跳过不可能更优的位置     |
//
// 面试首选解法2，写起来简洁，正确性证明清晰。
// 解法2b 是锦上添花的优化，面试时可以作为追问的回答。
//
// ============================================================
// 【易错点】
//
// 1. ✗ area = height[left] * (right - left)
//    ✓ area = min(height[left], height[right]) * (right - left)
//    面积由较短的线决定，不是随便取一边！
//
// 2. ✗ while (left <= right)
//    ✓ while (left < right)
//    left == right 时只有一条线，无法构成容器。
//    如果用 <=，还会导致 area 计算出 0 * 0 = 0，虽然不影响答案，
//    但逻辑不清晰，且多了一次无意义迭代。
//
// 3. ✗ 先移动指针再计算面积（漏掉初始最宽配对）
//    ✓ 先算面积再移动指针
//
// 4. ✗ height[left] == height[right] 时犹豫不决/特殊处理
//    ✓ 相等时移动任一边都正确。不需要两边都试。
//    证明：h[L]=h[R]=h 时，当前面积 = h*(R-L)。
//    无论移动哪边，剩余配对的面积 ≤ h*(R-L-1) < 当前面积
//    （即使两边都移一步碰巧更高，那也会在后续步骤中被正确计算到）
//
// ============================================================
// 【面试追问】
//
// Q1: 暴力解的复杂度？瓶颈？
// → O(n²)，枚举了所有 n(n-1)/2 个配对。瓶颈在于没有利用
//   任何结构来跳过不可能的配对。
//
// Q2: 双指针为什么不会漏掉最优解？请严格证明。
// → 当 h[L] ≤ h[R] 时，对任意 r < R:
//   min(h[L], h[r]) ≤ h[L]，且 r-L < R-L
//   所以 area(L,r) < area(L,R)
//   以 L 为左端的所有更窄配对被安全淘汰。对称地对 R 同理。
//   归纳：每步淘汰一批配对，最优解一定在未淘汰的配对中被计算到。
//
// Q3: 如果要返回两条线的索引而不是面积？
// → 在 maxWater 更新时同时记录 bestLeft 和 bestRight 即可。
//
// Q4: 这道题和 42.接雨水 有什么联系和区别？
// → 联系：都用双指针 + 短板原理。
//   区别：本题选两条线围一个大容器（只看两端），
//   42题是每个位置都可能存水，需要逐格累加。
//   42题的双指针：维护 leftMax/rightMax，从短板侧向内推进，
//   每步算一个位置的存水量。
