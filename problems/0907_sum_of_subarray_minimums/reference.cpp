/*
 * LeetCode 907: 子数组的最小值之和 (Sum of Subarray Minimums)
 *
 * 【题目本质】
 * 求所有连续子数组的最小值之和。关键转换：不枚举子数组，
 * 而是对每个元素计算"它在多少个子数组中充当最小值"，即贡献法。
 *
 * 【解法总览】
 * 解法1: 暴力枚举 — O(n²) / O(1) — 枚举所有子数组，维护区间 min
 * 解法2: 单调栈 + 贡献法 — O(n) / O(n) — 对每个元素用单调栈求统治范围
 * 解法3: DP + 单调栈 — O(n) / O(n) — dp[i]=以 arr[i] 结尾的所有子数组 min 之和
 */

// ============================================================
// 解法1: 暴力枚举 — O(n²) / O(1)
//
// 【思路】
// 最直觉的做法：枚举左端点 l，向右扩展右端点 r，
// 利用 min(arr[l..r]) = min(min(arr[l..r-1]), arr[r]) 递推维护区间最小值。
// 
// 瓶颈：O(n²) 个子数组都要遍历，n=3×10⁴ 时约 4.5×10⁸ 次操作，可能超时。
// 但可以作为正确性验证的基准。
// ============================================================
class Solution1 {
public:
    int sumSubarrayMins(vector<int>& arr) {
        const int MOD = 1e9 + 7;
        int n = arr.size();
        long long ans = 0;
        for (int l = 0; l < n; l++) {
            int curMin = arr[l];
            for (int r = l; r < n; r++) {
                curMin = min(curMin, arr[r]);
                ans = (ans + curMin) % MOD;
            }
        }
        return (int)ans;
    }
};

// ============================================================
// 解法2: 单调栈 + 贡献法 — O(n) / O(n)  ⭐ 面试首选
//
// 【思路】
// 核心转换：对每个 arr[i]，计算它作为最小值"统治"了多少个子数组。
//
// 对 arr[i]，找：
//   left[i]  = 左边第一个严格小于 arr[i] 的位置（找不到为 -1）
//   right[i] = 右边第一个小于等于 arr[i] 的位置（找不到为 n）
//
// 贡献 = arr[i] × (i - left[i]) × (right[i] - i)
//
// 为什么一边严格一边非严格？
//   防止相等元素导致同一子数组被重复统计。
//   约定：相等元素中，左边的"管到"右边相等元素出现的位置为止。
//
// 单调栈（递增栈，栈底到栈顶对应值递增）：
//   求 left：从左往右扫，弹出 >= arr[i] 的（找严格小于的边界）
//   求 right：从右往左扫，弹出 > arr[i] 的（找 <= 的边界）
//
// 示例 arr = [3, 1, 2, 4]:
//
//   left  = [-1, -1,  1,  2]
//   right = [ 1,  4,  4,  4]
//
//   i=0: 3 × (0-(-1)) × (1-0) = 3×1×1 = 3
//   i=1: 1 × (1-(-1)) × (4-1) = 1×2×3 = 6
//   i=2: 2 × (2-1)    × (4-2) = 2×1×2 = 4
//   i=3: 4 × (3-2)    × (4-3) = 4×1×1 = 4
//   总和 = 3+6+4+4 = 17 ✓
// ============================================================
class Solution2 {
public:
    int sumSubarrayMins(vector<int>& arr) {
        const int MOD = 1e9 + 7;
        int n = arr.size();
        vector<int> left(n), right(n);
        stack<int> stk;

        // 第一遍：求 left[i] —— 左边第一个严格小于 arr[i] 的位置
        // 维护单调递增栈，弹出条件 >= arr[i]
        for (int i = 0; i < n; i++) {
            while (!stk.empty() && arr[stk.top()] >= arr[i]) {
                stk.pop();
            }
            left[i] = stk.empty() ? -1 : stk.top();
            stk.push(i);
        }

        // 清空栈复用
        while (!stk.empty()) stk.pop();

        // 第二遍：求 right[i] —— 右边第一个小于等于 arr[i] 的位置
        // 维护单调递增栈，弹出条件 > arr[i]（保留等于的，使得等于的成为边界）
        for (int i = n - 1; i >= 0; i--) {
            while (!stk.empty() && arr[stk.top()] > arr[i]) {
                stk.pop();
            }
            right[i] = stk.empty() ? n : stk.top();
            stk.push(i);
        }

        // 第三遍：累加每个元素的贡献
        long long ans = 0;
        for (int i = 0; i < n; i++) {
            // (i - left[i]) 种左端点选择 × (right[i] - i) 种右端点选择
            long long leftCnt = i - left[i];
            long long rightCnt = right[i] - i;
            // 注意取模：先乘再模，避免溢出
            ans = (ans + (long long)arr[i] % MOD * (leftCnt % MOD) % MOD * (rightCnt % MOD)) % MOD;
        }
        return (int)ans;
    }
};

// ============================================================
// 解法3: DP + 单调栈 — O(n) / O(n)
//
// 【思路】
// 定义 dp[i] = 所有以 arr[i] 结尾的子数组的最小值之和。
// 答案 = Σ dp[i]。
//
// 转移推导：
//   设 j = 左边第一个严格小于 arr[i] 的位置。
//   以 arr[i] 结尾的子数组 [k..i]，分两类：
//     - j < k ≤ i: 这些子数组中 arr[i] 是最小的 → 贡献 arr[i] × (i-j)
//     - k ≤ j:     这些子数组的 min 和 [k..j] 的 min 相同 → 贡献 dp[j]
//   所以 dp[i] = arr[i] × (i - j) + dp[j]  (j=-1时dp[j]=0)
//
// 用单调递增栈在遍历过程中维护 j：
//   弹出所有 >= arr[i] 的元素（找严格小于的左边界）
//
// 填表方向：从左到右，一次遍历完成。
//
// 示例 arr = [3, 1, 2, 4]:
//   dp[0]: j=-1, dp[0] = 3×(0-(-1)) + 0 = 3     ans=3
//   dp[1]: j=-1, dp[1] = 1×(1-(-1)) + 0 = 2     ans=5
//   dp[2]: j=1,  dp[2] = 2×(2-1) + dp[1] = 2+2 = 4  ans=9
//   dp[3]: j=2,  dp[3] = 4×(3-2) + dp[2] = 4+4 = 8  ans=17 ✓
// ============================================================
class Solution3 {
public:
    int sumSubarrayMins(vector<int>& arr) {
        const int MOD = 1e9 + 7;
        int n = arr.size();
        stack<int> stk;       // 单调递增栈（存索引）
        vector<long long> dp(n);
        long long ans = 0;

        for (int i = 0; i < n; i++) {
            // 弹出所有 >= arr[i] 的，找到左边第一个严格小于 arr[i] 的位置
            while (!stk.empty() && arr[stk.top()] >= arr[i]) {
                stk.pop();
            }
            int j = stk.empty() ? -1 : stk.top();

            // dp[i] = arr[i] 作为最小值覆盖 (i-j) 个子数组 + dp[j] 继承更远的子数组
            dp[i] = (long long)arr[i] * (i - j);
            if (j >= 0) {
                dp[i] = (dp[i] + dp[j]) % MOD;
            }
            dp[i] %= MOD;

            ans = (ans + dp[i]) % MOD;
            stk.push(i);
        }
        return (int)ans;
    }
};

// ============================================================
// 【解法对比】
//
// 解法1 vs 解法2:
//   解法1 枚举 O(n²) 个子数组，是暴力思路。
//   解法2 转换视角为"每个元素的贡献"，用单调栈 O(n) 求左右边界，
//   乘法原理直接算出贡献。
//
// 解法2 vs 解法3:
//   本质相同，都用单调栈找"最近更小元素"。
//   解法2 需要两遍扫描（左边界+右边界）+ 一遍累加 = 三遍。
//   解法3 只需一遍扫描，边遍历边用 dp 递推，代码更简洁。
//   面试中推荐解法2（思路更直观）或解法3（代码更简洁），二选一即可。
//
// 【易错点】
//
// 1. 相等元素的去重：
//    ✗ left 和 right 都用严格小于 (<)
//      → arr = [1,2,1] 时子数组 [1,2,1] 被 index=0 和 index=2 各算一次
//    ✓ left 用严格小于 (弹出 >=)，right 用小于等于 (弹出 >)
//      → 每个子数组只被一个位置"认领"
//
// 2. 弹出条件搞混：
//    ✗ 求 left 时 while(arr[top] > arr[i])（漏弹了等于的）
//    ✓ 求 left 时 while(arr[top] >= arr[i])
//    这会导致相等元素互为左边界，统治范围计算错误
//
// 3. 整数溢出：
//    ✗ int ans += arr[i] * (i-left[i]) * (right[i]-i)
//      当 arr[i]=3×10⁴, 间距=3×10⁴ 时，乘积可达 2.7×10¹³，远超 int 范围
//    ✓ 用 long long 做中间计算，每步取模
//
// 4. DP 解法中 j=-1 的越界：
//    ✗ dp[i] = arr[i]*(i-j) + dp[j] 当 j=-1 时访问 dp[-1]
//    ✓ 先判断 j>=0 再加 dp[j]
//
// 【面试追问】
//
// Q1: 暴力解能过吗？瓶颈在哪？
//   O(n²)，n=3×10⁴ 时约 10⁹ 次操作，通常超时。
//   瓶颈：每个子数组都要单独考虑，没有利用子数组间的重叠结构。
//
// Q2: 为什么用单调递增栈而不是递减栈？
//   因为我们要找"最近的更小元素"。单调递增栈在遇到更小元素时弹出，
//   弹出的过程就是在为被弹出元素配对它的右边界。
//
// Q3: 如果改成求所有子数组的最大值之和？
//   对称操作：用单调递减栈，找左边第一个严格大于和右边第一个大于等于的位置。
//   代码只需把比较符号翻转。LeetCode 2104 需要同时求 max 和 min 之和。
//
// Q4: 能否不用额外的 left/right 数组，在一次遍历中完成？
//   可以，就是解法3 的 DP 方式。或者在解法2 中，弹出元素时直接计算
//   被弹出元素的贡献（弹出时 left = 新栈顶，right = 当前 i），
//   这样也只需一次遍历 + 最后清栈。
// ============================================================
