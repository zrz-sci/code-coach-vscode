/*
 * LeetCode 546: 移除盒子 (Remove Boxes)
 *
 * 【题目本质】
 * 移除连续同色盒子得 k^2 分，求最大总分。
 * 关键：k^2 有超线性增长，攒同色盒子一起消比分开消划算。
 * 需要三维区间 DP 记录"左边已累积的同色数"。
 *
 * 【解法总览】
 * 解法1: 三维 DP（记忆化搜索） — O(n^4) / O(n^3) — ⭐ 面试首选
 * 解法2: 三维 DP（自底向上）   — O(n^4) / O(n^3)
 *
 *  状态定义:
 *  dp[i][j][k] = 移除 boxes[i..j]，且 boxes[i] 左边
 *               已有 k 个同色盒子等待合并时的最大积分
 *
 *  状态转移:
 *  1) 直接消 boxes[i]（含左边 k 个）: (k+1)^2 + dp[i+1][j][0]
 *  2) 找 boxes[m]==boxes[i]，先消中间，合并同色:
 *     dp[i+1][m-1][0] + dp[m][j][k+1]
 */

// ============================================================
// 解法1: 三维 DP（记忆化搜索）⭐ 面试首选
// 时间: O(n^4)  空间: O(n^3)
//
// 【思路】
// dfs(i, j, k) 表示移除 boxes[i..j]，boxes[i] 左边已有
// k 个同色盒子等待合并时的最大积分。
//
// 优化：先合并 boxes[i] 开头的连续同色段，
// 减少递归调用次数。
//
//  示例: boxes = [1, 3, 2, 2, 2, 3, 4, 3, 1]
//  dfs(0,8,0): boxes[0]=1
//    选择1: 消1, 得 1 + dfs(1,8,0)
//    选择2: 找 boxes[8]=1, 消中间 dfs(1,7,0) + dfs(8,8,1)
//           dfs(8,8,1) = (1+1)^2 = 4
// ============================================================
class Solution1 {
public:
    int dp[100][100][100];

    int removeBoxes(vector<int>& boxes) {
        memset(dp, 0, sizeof(dp));
        return dfs(boxes, 0, boxes.size() - 1, 0);
    }

    int dfs(vector<int>& boxes, int i, int j, int k) {
        if (i > j) return 0;
        if (dp[i][j][k]) return dp[i][j][k];

        // 优化：合并 boxes[i] 开头的连续同色段
        int i0 = i, k0 = k;
        while (i + 1 <= j && boxes[i + 1] == boxes[i]) {
            i++; k++;
        }
        // 现在 boxes[i0..i] 都是同色，共 (k - k0 + 1) + k0 = k+1 个

        // 选择1: 直接消除这 k+1 个同色盒子
        int res = (k + 1) * (k + 1) + dfs(boxes, i + 1, j, 0);

        // 选择2: 在 [i+1, j] 中找 boxes[m] == boxes[i]
        //        先消 [i+1, m-1]，让 boxes[m] 和前面 k+1 个合并
        for (int m = i + 1; m <= j; m++) {
            if (boxes[m] == boxes[i]) {
                res = max(res,
                    dfs(boxes, i + 1, m - 1, 0) + dfs(boxes, m, j, k + 1));
            }
        }

        dp[i0][j][k0] = res;
        return res;
    }
};

// ============================================================
// 解法2: 三维 DP（自底向上填表）
// 时间: O(n^4)  空间: O(n^3)
//
// 【思路】
// 按区间长度从小到大填表。
// 基础情况: dp[i][i][k] = (k+1)^2（单个元素 + 左边 k 个同色）
// 转移同上。
// ============================================================
class Solution2 {
public:
    int removeBoxes(vector<int>& boxes) {
        int n = boxes.size();
        int dp[100][100][100] = {};

        // 基础情况
        for (int i = 0; i < n; i++) {
            for (int k = 0; k < n; k++) {
                dp[i][i][k] = (k + 1) * (k + 1);
            }
        }

        // 按区间长度枚举
        for (int len = 2; len <= n; len++) {
            for (int i = 0; i <= n - len; i++) {
                int j = i + len - 1;
                for (int k = 0; k < n; k++) {
                    // 选择1: 直接消 boxes[i]
                    dp[i][j][k] = (k + 1) * (k + 1) + dp[i + 1][j][0];

                    // 选择2: 找同色合并
                    for (int m = i + 1; m <= j; m++) {
                        if (boxes[m] == boxes[i]) {
                            dp[i][j][k] = max(dp[i][j][k],
                                dp[i + 1][m - 1][0] + dp[m][j][k + 1]);
                        }
                    }
                }
            }
        }

        return dp[0][n - 1][0];
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间    | 空间    | 特点                         |
// |-----------|---------|---------|------------------------------|
// | 记忆化搜索 | O(n^4) | O(n^3) | ⭐ 自顶向下，思路更自然        |
// | 自底向上   | O(n^4) | O(n^3) | 需要确定填表顺序，实现更复杂    |
//
// 核心难点：理解第三维 k 的含义 —— "左边有多少同色在等待合并"
//
// ============================================================
// 【易错点】
//
// 1. ✗ 用 dp[i][j] 二维定义
//    ✓ 必须三维 dp[i][j][k]，k 记录左侧累积同色数
//    → 因为 boxes[i] 可能和范围外的同色盒子合并
//
// 2. ✗ dp[m][j][k+1] 写成 dp[m][j][1]
//    ✓ 是 k+1，不是固定值。boxes[i] 连同它左边的 k 个都传递给 m
//
// 3. ✗ 没做连续同色段合并优化
//    ✓ 先跳过 boxes[i] 开头的连续同色段，大幅减少状态数
//
// 4. ✗ memset 初始化为 -1 但判断条件写成 if(dp[i][j][k])
//    ✓ 初始化为 0，因为合法答案 >= 1（至少有一个盒子）
//    → 或初始化 -1 并用 if(dp[i][j][k] != -1)
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么贪心不行？
// → k^2 是超线性增长。(a+b)^2 > a^2 + b^2，
//   所以攒同色一起消总比分开消好。但哪些该攒、中间先消什么
//   需要全局搜索。
//
// Q2: 时间复杂度 O(n^4) 怎么来的？
// → 状态数 O(n^3)，每个状态转移时枚举 m ∈ [i+1,j]，O(n)。
//
// Q3: 和戳气球(312)有什么联系？
// → 都是区间 DP。312 只需二维因为收益线性。
//   546 收益是 k^2 超线性，需要额外维度记录累积数。
//
// 【相关题型】
// - 312. 戳气球 — 区间 DP 经典，二维即可
// - 664. 奇怪的打印机 — 同色合并思路类似
// - 1000. 合并石头的最低成本 — 区间 DP 变体
