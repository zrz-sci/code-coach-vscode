/*
 * LeetCode 136: 只出现一次的数字 (Single Number)
 * 
 * 【题目本质】
 * 在一个"除了一个元素外其余都出现两次"的数组中，找出那个落单的元素。
 * 核心约束：O(n) 时间 + O(1) 空间。
 *
 * 【解法总览】
 * 解法1: 哈希表计数   — O(n) / O(n)  — 通用思路，不满足空间要求
 * 解法2: 排序后比较   — O(n log n) / O(1) — 直觉简单，不满足时间要求
 * 解法3: 全员异或     — O(n) / O(1)  — 最优解，面试必须给出
 * 解法4: 数学法       — O(n) / O(n)  — 巧妙但实用性较低
 */

// ============================================================
// 解法1: 哈希表计数 — 最自然的"空间换时间"思路
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 暴力法对每个元素线性搜索计数 O(n²)，瓶颈在"查找"。
// 哈希表把查找从 O(n) 降到 O(1)。
// 第一遍遍历建频率表，第二遍找频率为1的。
// 这是通用做法，适用于任何频次条件，但空间 O(n) 不满足本题要求。
// ============================================================
class Solution1 {
public:
    int singleNumber(vector<int>& nums) {
        unordered_map<int, int> freq;
        for (int num : nums) {
            freq[num]++;
        }
        for (int num : nums) {
            if (freq[num] == 1) return num;
        }
        return -1; // 题目保证一定有答案
    }
};

// ============================================================
// 解法2: 排序后相邻比较 — 有序化消除查找成本
// 时间: O(n log n)  空间: O(1)（原地排序）
//
// 【思路】
// 排序后相同元素一定相邻。两两一组检查：
//   排序后: [1, 1, 2, 2, 4]
//            ^--^  ^--^  ^ ← 这个没有配对
// 步长为2遍历，如果 nums[i] != nums[i+1]，则 nums[i] 是落单的。
// 如果循环内都没找到，说明落单元素在最末尾。
// ============================================================
class Solution2 {
public:
    int singleNumber(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        
        // 两两一组检查，步长为2
        for (int i = 0; i < (int)nums.size() - 1; i += 2) {
            if (nums[i] != nums[i + 1]) {
                // nums[i] 没有配对，它就是落单的
                return nums[i];
            }
        }
        // 所有前面的都配对了，最后一个是落单的
        return nums.back();
    }
};

// ============================================================
// 解法3: 全员异或 — O(n) / O(1) ⭐ 面试首选
//
// 【思路】
// 异或的三个性质组合：
//   1. 自反性:   a ^ a = 0  （成对抵消）
//   2. 零元素:   a ^ 0 = a  （落单保留）
//   3. 交换+结合律: 顺序无关
//
// 把所有元素异或起来，成对的互相抵消为0，最终剩下落单的。
//
// 可视化过程 (nums = [4, 1, 2, 1, 2]):
//   result = 0
//   0 ^ 4 = 4         (0100)
//   4 ^ 1 = 5         (0101)
//   5 ^ 2 = 7         (0111)
//   7 ^ 1 = 6         (0110)  ← 1和之前的1抵消了
//   6 ^ 2 = 4         (0100)  ← 2和之前的2抵消了
//   最终 result = 4 ✓
//
// 等价于: (4) ^ (1 ^ 1) ^ (2 ^ 2) = 4 ^ 0 ^ 0 = 4
// ============================================================
class Solution3 {
public:
    int singleNumber(vector<int>& nums) {
        int result = 0; // 0是异或的单位元: 0 ^ x = x
        for (int num : nums) {
            result ^= num; // 成对的自动抵消为0
        }
        return result; // 只剩落单的数
    }
};

// ============================================================
// 解法4: 数学法 — 2 * sum(集合) - sum(数组)
// 时间: O(n)  空间: O(n)（需要集合去重）
//
// 【思路】
// 如果数组中的不重复元素是 {a, b, c}，数组实际是 [a, a, b, b, c]：
//   2 * (a + b + c) - (a + a + b + b + c) = c
// 用 set 去重后求和，乘以2减去原数组和。
//
// 注意: 空间 O(n) 用于 set，且要注意整数溢出（用 long long）。
// 实用性不如异或，但展示了数学思维。
// ============================================================
class Solution4 {
public:
    int singleNumber(vector<int>& nums) {
        unordered_set<int> seen;
        long long setSum = 0, arraySum = 0;
        for (int num : nums) {
            if (seen.find(num) == seen.end()) {
                seen.insert(num);
                setSum += num; // 每个不重复元素只加一次
            }
            arraySum += num; // 原数组所有元素求和
        }
        // 2*(a+b+c) - (a+a+b+b+c) = c
        return (int)(2 * setSum - arraySum);
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间       | 空间  | 满足题目要求 | 通用性     |
// |------------|------------|-------|-------------|-----------|
// | 哈希表计数 | O(n)       | O(n)  | ✗ 空间不满足 | 最通用     |
// | 排序比较   | O(n log n) | O(1)  | ✗ 时间不满足 | 需要可排序 |
// | 全员异或   | O(n)       | O(1)  | ✓            | 仅限成对   |
// | 数学法     | O(n)       | O(n)  | ✗ 空间不满足 | 仅限成对   |
//
// 面试中：先说哈希表（展示通用思维）→ 再给异或（展示位运算技巧）
//
// 【易错点】
// 1. 异或初始值错误:
//    ✗ int result = nums[0]; for (int num : nums) result ^= num;
//      → nums[0] 被异或了两次，等于没异或，如果 nums[0] 就是落单的会输出0
//    ✓ int result = 0; for (int num : nums) result ^= num;
//      → 从0开始，每个元素恰好异或一次
//
// 2. 排序法步长写成1:
//    ✗ for (int i = 0; i < n-1; i += 1) if (nums[i] != nums[i+1]) ...
//      → 这会在成对元素的第二个和下一对的第一个之间误判
//    ✓ for (int i = 0; i < n-1; i += 2) ...
//      → 步长2，两两一组检查
//
// 3. 排序法忘记处理最后一个元素:
//    ✗ 循环结束没有 return nums.back()
//      → 当落单元素排在最后（如 [1,1,2,2,4]）时无返回值
//    ✓ 循环外兜底 return nums.back()
//
// 4. 数学法溢出:
//    ✗ int setSum, arraySum; → 2*setSum 可能溢出 int
//    ✓ long long setSum, arraySum; → 安全处理大数
//
// 【面试追问】
// Q1: 为什么异或能解决这道题？具体用了哪些性质？
//     → 自反性(a^a=0)消除成对，零元素(a^0=a)保留落单，
//       交换律+结合律保证顺序无关。
//
// Q2: 如果其余元素出现3次，只有一个出现1次呢？(LC 137)
//     → 异或不适用(a^a^a=a≠0)。逐位统计所有数在每一位上1的个数，
//       对3取余，余数拼起来就是答案。可用两个变量(ones, twos)模拟
//       模3计数器的状态机来优化。
//
// Q3: 如果有两个元素各出现1次，其余出现2次呢？(LC 260)
//     → 全员异或得 a^b。取 a^b 中任意一个为1的位(lowbit = x & -x)，
//       按这一位分组：该位为1的一组、为0的一组。
//       每组内分别异或，退化成本题，分别得到 a 和 b。
//
// Q4: 不用位运算，O(1)空间O(n)时间能做到吗？
//     → 严格意义上不行。数学法需要 set(O(n)空间)。
//       排序法修改了原数组且 O(n log n)。异或是唯一满足所有条件的方法。
//
// 【相关题目】
// - LC 137 只出现一次的数字II: 其余3次→逐位计数对3取余，从"异或抵消"推广到"模运算抵消"
// - LC 260 只出现一次的数字III: 两个落单→全员异或+分组，每组复用本题的异或解法
// - LC 268 丢失的数字: nums[i]和索引i配对异或，缺失的数没配对自然剩下
// - LC 389 找不同: 两字符串所有字符异或，多出的字符就是答案
// ============================================================
