/*
 * LeetCode 946: Validate Stack Sequences (验证栈序列)
 *
 * 【题目本质】
 * 给定入栈序列 pushed 和出栈序列 popped（元素互不相同），
 * 判断 popped 是否是一个合法的出栈顺序。
 *
 * 核心思路：模拟。按 pushed 顺序入栈，每次入栈后贪心地尽可能弹出
 * （只要栈顶 == popped 的当前期望值就弹出）。遍历完 pushed 后，
 * 栈为空说明合法。
 *
 * 【解法总览】
 * 解法1: 辅助栈模拟     — O(n) / O(n)   — 面试首选，代码清晰
 * 解法2: 原地模拟(空间优化) — O(n) / O(1) — 复用 pushed 数组当栈
 */

// ============================================================
// 解法1: 辅助栈模拟 — 面试首选 ⭐
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 遍历 pushed，逐个元素入栈。
// 每次入栈后，用 while 循环检查栈顶是否等于 popped[j]:
//   - 相等 → 弹出，j 右移（这个弹出操作是必须的——贪心）
//   - 不等 → 停止弹出，继续下一个 push
// 遍历完后，栈为空 → true，否则 → false。
//
// 示例1: pushed = [1,2,3,4,5], popped = [4,5,3,2,1]
//
//   push(1): stk=[1],       j=0, top=1≠4 → 不弹
//   push(2): stk=[1,2],     j=0, top=2≠4 → 不弹
//   push(3): stk=[1,2,3],   j=0, top=3≠4 → 不弹
//   push(4): stk=[1,2,3,4], j=0, top=4==4 → 弹! stk=[1,2,3], j=1
//                            j=1, top=3≠5 → 停
//   push(5): stk=[1,2,3,5], j=1, top=5==5 → 弹! stk=[1,2,3], j=2
//                            j=2, top=3==3 → 弹! stk=[1,2],   j=3
//                            j=3, top=2==2 → 弹! stk=[1],     j=4
//                            j=4, top=1==1 → 弹! stk=[],      j=5
//   结束: stk 为空 → return true ✓
//
// 示例2: pushed = [1,2,3,4,5], popped = [4,3,5,1,2]
//
//   push(1)~push(3): stk=[1,2,3], j=0
//   push(4): stk=[1,2,3,4], j=0, top=4==4 → 弹! stk=[1,2,3], j=1
//                            j=1, top=3==3 → 弹! stk=[1,2],   j=2
//                            j=2, top=2≠5 → 停
//   push(5): stk=[1,2,5],   j=2, top=5==5 → 弹! stk=[1,2],   j=3
//                            j=3, top=2≠1 → 停
//   结束: stk=[1,2] 不为空 → return false ✗
//   原因: popped 要求先弹 1 再弹 2，但栈中 2 在 1 上面，
//         必须先弹 2 才能弹 1，与 popped 顺序矛盾。
//
// 时间复杂度分析:
//   虽然有两层循环 (for + while)，但每个元素最多被 push 一次、
//   pop 一次。内层 while 的总执行次数 ≤ n。
//   总操作: n 次 push + ≤ n 次 pop = O(2n) = O(n)。
//
// 贪心正确性:
//   如果栈顶 == popped[j] 但不弹出，后续 push 的元素会压在上面，
//   导致 popped[j] 被埋住无法在正确时机弹出。所以必须立即弹出。
// ============================================================
class Solution1 {
public:
    bool validateStackSequences(vector<int>& pushed, vector<int>& popped) {
        stack<int> stk;     // 辅助栈，模拟真实栈操作
        int j = 0;          // popped 指针，指向下一个期望弹出的元素

        for (int x : pushed) {
            stk.push(x);   // 按 pushed 顺序入栈

            // 贪心: 只要栈顶 == 期望弹出值，就弹出
            // 注意 !stk.empty() 必须在 stk.top() 之前 (短路求值)
            while (!stk.empty() && stk.top() == popped[j]) {
                stk.pop();
                j++;
            }
        }

        // 栈为空 = 所有元素都按正确顺序弹出
        return stk.empty();
    }
};

// ============================================================
// 解法2: 原地模拟（空间优化） — O(n) / O(1) ⭐ 进阶
// 时间: O(n)  空间: O(1) (不计输入)
//
// 【思路】
// 观察解法1：pushed 数组的元素被 push 进辅助栈后，原位置就不再需要了。
// 我们可以复用 pushed 数组本身作为栈！
//
// 用变量 top 作为"栈顶指针":
//   push 操作: pushed[++top] = x  (栈顶上移，写入值)
//   pop  操作: top--              (栈顶下移)
//   栈空判断: top == -1
//   栈顶访问: pushed[top]
//
// 示例: pushed = [1,2,3,4,5], popped = [4,5,3,2,1]
//
//   初始: top=-1
//   x=1: pushed[0]=1, top=0, pushed[0]=1≠4 → 不弹
//   x=2: pushed[1]=2, top=1, pushed[1]=2≠4 → 不弹
//   x=3: pushed[2]=3, top=2, pushed[2]=3≠4 → 不弹
//   x=4: pushed[3]=4, top=3, pushed[3]=4==4 → top=2, j=1
//                             pushed[2]=3≠5 → 停
//   x=5: pushed[3]=5, top=3, pushed[3]=5==5 → top=2, j=2
//     (注意: pushed[3] 被覆写为5, 但 pushed[4]=5 原值不影响)
//                             pushed[2]=3==3 → top=1, j=3
//                             pushed[1]=2==2 → top=0, j=4
//                             pushed[0]=1==1 → top=-1, j=5
//   结束: top==-1 → return true ✓
//
// 注意:
// - 这个解法会修改 pushed 数组。面试中需要和面试官确认是否允许。
// - 如果不允许修改输入，只能用解法1。
// ============================================================
class Solution2 {
public:
    bool validateStackSequences(vector<int>& pushed, vector<int>& popped) {
        int top = -1;       // 栈顶指针，-1 表示空栈
        int j = 0;          // popped 指针

        for (int x : pushed) {
            // push: 栈顶上移，写入当前元素
            pushed[++top] = x;

            // 贪心弹出
            while (top >= 0 && pushed[top] == popped[j]) {
                top--;      // pop: 栈顶下移
                j++;
            }
        }

        return top == -1;   // 栈空 = 合法
    }
};

// ============================================================
// 【解法对比】
//
// | 解法       | 时间  | 空间  | 修改输入 | 代码清晰度 | 推荐度 |
// |-----------|-------|-------|---------|-----------|--------|
// | 辅助栈    | O(n)  | O(n)  | 否      | ⭐⭐⭐     | ⭐⭐⭐ 首选 |
// | 原地模拟  | O(n)  | O(1)  | 是      | ⭐⭐      | ⭐⭐  进阶 |
//
// 面试策略: 先写辅助栈版本，面试官追问空间优化时再讲原地版本。
//
// ============================================================
// 【贪心正确性证明】
//
// 命题: 若栈顶 == popped[j]，必须立即弹出。
//
// 证明 (反证法):
// 假设栈顶 s == popped[j]，但我们不弹出而继续 push 元素 x。
// 栈变为 [..., s, x]。
// popped 要求 s (= popped[j]) 在后续元素之前弹出。
// 但 s 现在被 x 压住，必须先弹 x 才能弹 s。
// 而 popped 序列中 s 在 x 之前（j 指向 s），矛盾。
// 所以必须立即弹出。QED
//
// ============================================================
// 【时间复杂度分析 — 摊还】
//
// 外层 for 循环: 执行 n 次 (遍历 pushed)
// 内层 while 循环: 每次可能执行 0~n 次
//
// 但关键观察: 每个元素最多被 push 一次、pop 一次。
// 内层 while 的总执行次数 = 总 pop 次数 ≤ n
// 总操作 = n (push) + ≤n (pop) = O(2n) = O(n)
//
// 这是"两层循环但总体 O(n)"的经典例子，
// 类似于双指针、滑动窗口的摊还分析。
//
// ============================================================
// 【易错点】
//
// 1. 空栈访问 top():
//    ✗ while (stk.top() == popped[j] && !stk.empty())
//      → 空栈时先执行 top(), 未定义行为(崩溃)
//    ✓ while (!stk.empty() && stk.top() == popped[j])
//      → 短路求值, 空栈不执行 top()
//
// 2. 用 if 而不是 while:
//    ✗ if (!stk.empty() && stk.top() == popped[j]) { stk.pop(); j++; }
//      → 只弹一次, 漏掉连续弹出 (如 push(4) 后连续弹 4,3)
//    ✓ while (...) { stk.pop(); j++; }
//      → 循环弹出直到不匹配
//
// 3. 原地解法 top 初值:
//    ✗ int top = 0; pushed[++top] = x;
//      → 第一个元素写到 pushed[1], pushed[0] 被跳过
//    ✓ int top = -1; pushed[++top] = x;
//      → 第一个元素写到 pushed[0], 正确
//
// 4. j 越界:
//    理论上不会 (popped 是 pushed 的排列, 长度相同)
//    但防御性编程可加: while (j < n && !stk.empty() && ...)
//
// ============================================================
// 【面试追问 — 递进链】
//
// Q1: 贪心为什么正确？
//     反证法：栈顶等于期望值却不弹出，后续 push 会把它埋住，
//     导致无法按 popped 顺序弹出。所以必须立即弹出。
//
// Q2: 时间为什么是 O(n) 不是 O(n²)？
//     每个元素 push 一次 pop 一次，总操作 O(2n)。
//     内层 while 总次数 ≤ n，不是每次外层循环都执行 n 次。
//
// Q3: 空间能否优化到 O(1)？
//     可以。复用 pushed 数组当栈（解法2）。代价是修改输入。
//
// Q4: 如果不给 popped，要求枚举所有合法的出栈序列？
//     这是 Catalan 数问题！n 个元素的合法出栈序列数 = C(2n,n)/(n+1)。
//     例如 n=3 时有 5 种合法序列。可以用回溯法枚举。
//
