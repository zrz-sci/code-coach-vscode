-- 题意: 交换每两个相邻学生的座位号 (id)
--       如果总人数为奇数, 最后一个学生不交换
--       按 id 升序返回
-- ============================================================

-- ============================================================
-- 解法一: CASE WHEN + 子查询 (推荐)
-- ============================================================
-- 思路: 根据 id 奇偶性用 CASE WHEN 重新计算 id
--       偶数 id -> id-1; 奇数 id -> id+1; 最后奇数 -> 不变
-- ============================================================

SELECT
    CASE
        -- 特殊情况: 最后一个且为奇数, 保持不变
        WHEN id % 2 = 1 AND id = (SELECT COUNT(*) FROM Seat)
            THEN id
        -- 奇数 id: 与下一个交换
        WHEN id % 2 = 1
            THEN id + 1
        -- 偶数 id: 与上一个交换
        ELSE id - 1
    END AS id,
    student
FROM Seat
ORDER BY id;

