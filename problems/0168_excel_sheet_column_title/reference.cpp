/*
 * LeetCode 168: Excel 表列名称 (Excel Sheet Column Title)
 *
 * 【题目本质】
 * 将十进制数转换为"1-indexed 的 26 进制数"（A=1, B=2, ..., Z=26，没有0）。
 * 核心难点：普通进制有0，Excel列名没有0，每次取余前需要先减1。
 *
 * 【解法总览】
 * 解法1: 迭代取余 — O(log₂₆n) / O(1) — 面试首选 ⭐
 * 解法2: 递归     — O(log₂₆n) / O(log₂₆n) — 更简洁的写法
 */

// ============================================================
// 解法1: 迭代取余 — 进制转换的标准模板 + 关键修正
// 时间: O(log₂₆n)  空间: O(1)（不算结果字符串）
//
// 【思路】
// 进制转换的标准操作：不断 "取余得到当前最低位, 整除去掉最低位"。
// 
// 但 Excel 列名是 1-26 编码（没有 0），不是标准的 0-25 编码。
// 如果直接 26%26=0，无法映射到任何字母。
// 
// 修正方法：每轮循环开头 columnNumber--, 把 1~26 映射为 0~25。
// 这样 余数0→'A', 余数25→'Z'，完美对应。
//
// 手动推演 columnNumber = 701:
//   轮1: 701-1=700, 700%26=24 → 'Y', 700/26=26
//   轮2: 26-1=25,   25%26=25  → 'Z', 25/26=0
//   收集: "YZ" → 反转 → "ZY" ✓
//
// 手动推演 columnNumber = 26:
//   轮1: 26-1=25,   25%26=25  → 'Z', 25/26=0
//   收集: "Z" → 反转 → "Z" ✓
//
// 手动推演 columnNumber = 28:
//   轮1: 28-1=27,   27%26=1   → 'B', 27/26=1
//   轮2: 1-1=0,     0%26=0    → 'A', 0/26=0
//   收集: "BA" → 反转 → "AB" ✓
// ============================================================
class Solution1 {
public:
    string convertToTitle(int columnNumber) {
        string result;
        while (columnNumber > 0) {
            // 关键：先减1，将 1-indexed(1~26) 转为 0-indexed(0~25)
            // 不能只在循环外减一次，因为每一"位"都是 1-indexed 的
            columnNumber--;
            
            // 取最低位：余数 0→'A', 1→'B', ..., 25→'Z'
            result += ('A' + columnNumber % 26);
            
            // 去掉最低位，处理更高位
            columnNumber /= 26;
        }
        
        // 进制转换先得到低位，需要反转得到正确顺序
        reverse(result.begin(), result.end());
        return result;
    }
};

// ============================================================
// 解法2: 递归 — 自然得到正序，无需反转
// 时间: O(log₂₆n)  空间: O(log₂₆n) 递归栈
//
// 【思路】
// 将问题分解为两部分：
//   - 最后一个字符: 由 (n-1) % 26 决定
//   - 前面的部分:   递归处理 (n-1) / 26
// 
// 递归天然是先处理高位再拼接低位，所以结果自动正序。
//
// 递归展开 columnNumber = 701:
//   convertToTitle(701) 
//     = convertToTitle(700/26) + char('A'+700%26)
//     = convertToTitle(26) + 'Y'
//       = convertToTitle(25/26) + char('A'+25%26) + 'Y'
//       = convertToTitle(0) + 'Z' + 'Y'
//       = "" + 'Z' + 'Y'
//       = "ZY" ✓
// ============================================================
class Solution2 {
public:
    string convertToTitle(int columnNumber) {
        // 递归出口：没有更高位了
        if (columnNumber == 0) return "";
        
        // 同样的关键修正：减1
        columnNumber--;
        
        // 先递归处理高位部分，再拼接当前位字符
        return convertToTitle(columnNumber / 26) + char('A' + columnNumber % 26);
    }
};

// ============================================================
// 【解法对比】
// 
// 两种解法本质完全相同，都是 "减1 → 取余 → 整除" 的循环/递归。
// 
// | 维度     | 迭代           | 递归           |
// |----------|----------------|----------------|
// | 空间     | O(1)           | O(log₂₆n)栈   |
// | 反转     | 需要           | 不需要         |
// | 可读性   | 直观           | 更简洁         |
// | 推荐     | ⭐面试首选     | 能说出即可     |
//
// log₂₆(2³¹) ≈ 7，所以两种方法实际性能几乎无差别。
//
// ============================================================
// 【易错点】
//
// 1. columnNumber-- 必须在每轮循环/递归内部执行，不是只做一次：
//    ✗ columnNumber--; while(columnNumber>0) { ... }
//    ✓ while(columnNumber>0) { columnNumber--; ... }
//    原因：每一"位"都是1-indexed编码，每一位都需要减1调整。
//
// 2. 迭代版忘记反转结果：
//    ✗ return result;  // "YZ" 而不是 "ZY"
//    ✓ reverse(result.begin(), result.end()); return result;
//
// 3. 递归版出口条件写成 columnNumber == 1 而不是 0：
//    ✗ if (columnNumber == 1) return "A";
//    这样 convertToTitle(26) → 减1后25/26=0，递归到0时没有出口！
//    ✓ if (columnNumber == 0) return "";
//
// 4. 混淆 'A'+0='A' 和 'A'+1='B' 的映射：
//    减1后余数0对应'A'，余数25对应'Z'
//    如果不减1，余数1对应'A'，但余数0就没有字母对应了——这正是bug根源。
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么必须每轮减1？和标准26进制的区别是什么？
// → 标准26进制数字范围是0~25，Excel列名范围是1~26（没有0）。
//   26在标准进制里是"10"(即1*26+0)，但Excel里是"Z"(单个字母)。
//   每轮减1将1~26映射为0~25，使得取余运算正确。
//
// Q2: 反过来，列名转数字（LeetCode 171）怎么做？
// → 从左到右扫描，result = result * 26 + (ch - 'A' + 1)。
//   注意是 +1（因为 A=1 不是 A=0），和本题的 -1 恰好对称。
//
// Q3: 能否用这个思路处理任意 base-k 的 1-indexed 进制？
// → 可以。只要把代码中的 26 替换为 k，'A'+remainder 替换为
//   对应的字符映射即可。核心不变：每轮先减1再取余。
//
// ============================================================
