/*
 * LeetCode 2: 两数相加 (Add Two Numbers)
 * 
 * 【题目本质】
 * 模拟竖式加法：两个链表逆序存储数字，从头（最低位）开始逐位相加，处理进位。
 * 链表的逆序存储恰好让我们可以从头到尾直接模拟加法过程。
 *
 * 【解法总览】
 * 解法1: 迭代 (dummy head) — O(max(m,n)) / O(max(m,n)) — 面试首选 ⭐
 * 解法2: 递归            — O(max(m,n)) / O(max(m,n)) — 递归思维加分项
 */

// ============================================================
// 解法1: 迭代模拟 (dummy head) — 面试首选
// 时间: O(max(m,n))  空间: O(max(m,n)) 用于存放结果链表
//
// 【思路】
// 这道题和小学竖式加法一模一样：
//   342         l1: 2 → 4 → 3
// + 465         l2: 5 → 6 → 4
// -----
//   807         结果: 7 → 0 → 8
//
// 从个位（链表头）开始，每一位做 sum = l1->val + l2->val + carry，
// 当前位 = sum % 10，进位 = sum / 10。
//
// 【指针变化图 — 示例1: l1=[2,4,3], l2=[5,6,4]】
//
// 初始:
//   dummy → ?
//   ↑curr
//   l1 → 2 → 4 → 3 → NULL
//   l2 → 5 → 6 → 4 → NULL
//   carry = 0
//
// Step1: sum=2+5+0=7, carry=0, 创建节点7
//   dummy → 7
//           ↑curr
//   l1 → 4 → 3 → NULL
//   l2 → 6 → 4 → NULL
//
// Step2: sum=4+6+0=10, carry=1, 创建节点0
//   dummy → 7 → 0
//                ↑curr
//   l1 → 3 → NULL
//   l2 → 4 → NULL
//
// Step3: sum=3+4+1=8, carry=0, 创建节点8
//   dummy → 7 → 0 → 8
//                    ↑curr
//   l1 → NULL, l2 → NULL, carry=0 → 循环结束
//
// 返回 dummy.next → 7 → 0 → 8 (即 807)
//
// 【不等长示例: l1=[9,9,9,9,9,9,9], l2=[9,9,9,9]】
//
// Step1: 9+9+0=18, carry=1 → 节点8
// Step2: 9+9+1=19, carry=1 → 节点9
// Step3: 9+9+1=19, carry=1 → 节点9
// Step4: 9+9+1=19, carry=1 → 节点9
// Step5: 9+0+1=10, carry=1 → 节点0   ← l2已空，取0
// Step6: 9+0+1=10, carry=1 → 节点0
// Step7: 9+0+1=10, carry=1 → 节点0
// Step8: 0+0+1=1,  carry=0 → 节点1   ← 两链表都空，但carry=1还要继续！
//
// 结果: 8→9→9→9→0→0→0→1 (即 10009998)
// ============================================================
class Solution1 {
public:
    ListNode* addTwoNumbers(ListNode* l1, ListNode* l2) {
        ListNode dummy(0);        // 虚拟头节点：避免对第一个节点做特殊处理
        ListNode* curr = &dummy;  // curr 始终指向结果链表的尾部
        int carry = 0;            // 进位，只会是 0 或 1
        
        // 为什么循环条件包含 carry？
        // 因为 99+1=100，两个链表都走完后可能还有进位需要处理
        while (l1 || l2 || carry) {
            int sum = carry;
            
            // 如果 l1 还没走完，取值并前进；否则当这一位是 0
            if (l1) {
                sum += l1->val;
                l1 = l1->next;
            }
            // l2 同理
            if (l2) {
                sum += l2->val;
                l2 = l2->next;
            }
            
            // sum 的范围: [0, 19]（最大 9+9+1）
            carry = sum / 10;                      // 进位: 0 或 1
            curr->next = new ListNode(sum % 10);   // 当前位: 取个位数字
            curr = curr->next;                     // 移动尾指针
        }
        
        return dummy.next;  // dummy 本身是辅助节点，真正的头是 dummy.next
    }
};


// ============================================================
// 解法2: 递归 — 链表天然适合递归
// 时间: O(max(m,n))  空间: O(max(m,n)) 递归栈
//
// 【思路】
// 每一层递归处理一位的加法：
//   1. 计算 sum = (l1的值或0) + (l2的值或0) + carry
//   2. 创建当前位的节点（sum % 10）
//   3. 递归处理下一位，carry = sum / 10 传递下去
//   4. 终止条件：两个链表都为空且 carry 为 0
//
// 递归调用栈的展开过程（以 [2,4,3] + [5,6,4] 为例）：
//
//   helper(2→4→3, 5→6→4, carry=0)
//     sum=7, 创建节点7
//     7->next = helper(4→3, 6→4, carry=0)
//                sum=10, 创建节点0
//                0->next = helper(3, 4, carry=1)
//                            sum=8, 创建节点8
//                            8->next = helper(NULL, NULL, carry=0)
//                                        → return nullptr (终止)
//                            return 节点8
//                return 节点0
//     return 节点7
//
//   最终: 7 → 0 → 8
// ============================================================
class Solution2 {
public:
    ListNode* addTwoNumbers(ListNode* l1, ListNode* l2) {
        return helper(l1, l2, 0);
    }
    
private:
    ListNode* helper(ListNode* l1, ListNode* l2, int carry) {
        // 递归终止：两个链表都空 且 没有进位 → 不需要更多节点
        if (!l1 && !l2 && carry == 0) return nullptr;
        
        int sum = carry;
        // 取值时要判空，空节点当作 0
        if (l1) sum += l1->val;
        if (l2) sum += l2->val;
        
        // 创建当前位的结果节点
        ListNode* node = new ListNode(sum % 10);
        
        // 递归处理下一位
        // 注意：l1/l2 可能已经是 nullptr，要判断后再取 next
        node->next = helper(
            l1 ? l1->next : nullptr,  // l1 走完就一直传 nullptr
            l2 ? l2->next : nullptr,  // l2 同理
            sum / 10                  // 进位传给下一层
        );
        
        return node;
    }
};


// ============================================================
// 【解法对比】
//
// | 维度       | 迭代 (Solution1)           | 递归 (Solution2)              |
// |-----------|---------------------------|-------------------------------|
// | 时间复杂度 | O(max(m,n))               | O(max(m,n))                   |
// | 空间复杂度 | O(1) 额外 (不算结果链表)    | O(max(m,n)) 递归栈            |
// | 代码风格   | while 循环 + dummy head    | 函数自调用，更简洁             |
// | 面试推荐   | ⭐ 首选，稳定不易出错       | 写出来是加分项                |
//
// 建议：面试先写迭代版（Solution1），面试官追问递归时再给 Solution2。
//
//
// 【易错点】
//
// 1. 忘记处理最终进位:
//    ✗ while (l1 || l2)  — 当 l1=[5], l2=[5] 时，sum=10, carry=1，
//      循环结束但没处理 carry，结果只有 [0] 而不是 [0,1]
//    ✓ while (l1 || l2 || carry)  — carry!=0 时继续循环
//
// 2. 空指针访问:
//    ✗ int sum = l1->val + l2->val + carry;  — l1 或 l2 可能为 NULL!
//    ✓ 先 if (l1) 判断非空再取值
//
// 3. 忘记移动 l1/l2 指针:
//    ✗ 取完 l1->val 后漏掉 l1 = l1->next  → 死循环
//    ✓ 取值和移动写在一起: sum += l1->val; l1 = l1->next;
//
// 4. 没用 dummy head 导致代码冗余:
//    ✗ 先创建头节点，循环中判断是否是第一个节点 → 容易写出 bug
//    ✓ dummy head 统一处理，最后返回 dummy.next
//
// 5. 递归版终止条件不完整:
//    ✗ if (!l1 && !l2) return nullptr;  — 漏掉 carry，如果此时 carry=1
//      就丢失了最高位
//    ✓ if (!l1 && !l2 && carry == 0) return nullptr;
//
//
// 【面试追问 — 递进链】
//
// Q1(基础理解): "为什么链表逆序存储反而更方便？"
// → 因为加法从最低位开始，逆序存储意味着头节点就是最低位，
//   可以从头到尾直接遍历模拟竖式加法，不需要额外的反转操作。
//
// Q2(变体): "如果链表是正序存储（最高位在头），怎么办？"
// → LeetCode 445。两种方法:
//   (1) 先反转两个链表 → 用本题方法加 → 反转结果链表
//   (2) 用栈分别压入两个链表的值，然后从栈顶（最低位）开始加
//
// Q3(优化): "能否不创建新链表，原地修改？"
// → 可以。选较长的链表作为结果，原地修改节点的 val。
//   但如果最后有进位，仍需要 new 一个节点。代码更复杂，
//   实际面试中通常不要求这么做，除非面试官明确提出。
//
// Q4(扩展): "如果有 k 个链表要相加呢？"
// → 方法类似：同时遍历 k 个链表，每步把 k 个当前位的值加起来再加 carry，
//   取模得到当前位，整除得到进位。时间 O(k * maxLen)。
//
//
