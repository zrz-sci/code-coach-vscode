/*
 * 【题目本质】
 * 判断整数 n 是否为 3 的幂次方 (n = 3^x, x >= 0)。
 * Follow-up: 不使用循环/递归。
 *
 * 【解法总览】
 * 解法1: 循环除法     — O(log n)/O(1)  ⭐最直观
 * 解法2: 最大幂取余   — O(1)/O(1)      ⭐无循环 follow-up
 * 解法3: 数学对数     — O(1)/O(1)      浮点精度风险
 */

// ===================== 解法1: 循环除法 =====================
// 思路: 反复除以 3，最终如果等于 1 则是 3 的幂
// 时间: O(log_3 n)  空间: O(1)
class Solution1 {
public:
    bool isPowerOfThree(int n) {
        if (n <= 0) return false;
        while (n % 3 == 0) {
            n /= 3;
        }
        return n == 1;
    }
};

// ===================== 解法2: 最大幂取余 (Follow-up) =====================
// 思路: 3 是质数，int 范围内最大 3 的幂为 3^19 = 1162261467
//       若 n 是 3 的幂，则 3^19 % n == 0
//       若 n 不是 3 的幂（但是正整数），因为 3 是质数，n 中必有非 3 的质因子，不能整除 3^19
// 时间: O(1)  空间: O(1)
class Solution2 {
public:
    bool isPowerOfThree(int n) {
        // 3^19 = 1162261467，3^20 超出 int 范围
        return n > 0 && 1162261467 % n == 0;
    }
};

// ===================== 解法3: 数学对数 =====================
// 思路: 若 n = 3^x，则 x = log(n)/log(3) 应为整数
//       注意浮点精度：用 round 后验证
// 时间: O(1)  空间: O(1)
// 风险: 浮点运算可能引入微小误差
class Solution3 {
public:
    bool isPowerOfThree(int n) {
        if (n <= 0) return false;
        double logVal = log(n) / log(3);
        int x = (int)round(logVal);
        // 用 pow 反向验证避免浮点截断
        return (long long)round(pow(3, x)) == n;
    }
};

/*
 * 【解法对比】
 * | 解法 | 时间 | 空间 | 优势 | 劣势 |
 * |------|------|------|------|------|
 * | 循环除法 | O(log n) | O(1) | 直观通用 | 有循环 |
 * | 最大幂取余 | O(1) | O(1) | 无循环，常数时间 | 只适用于质数底 |
 * | 数学对数 | O(1) | O(1) | 无循环 | 浮点精度风险 |
 *
 * 【易错点】
 * 1. n <= 0 未特判 → n=0 死循环, 负数误判
 * 2. log 法直接 floor 截断 → log(243)/log(3) 可能 = 4.999...
 * 3. 取余法用合数底 → 6^k 的因子含非 6 的幂(如 4), 结论不成立
 * 4. 3^19 vs 3^20 → 3^20 = 3,486,784,401 > INT_MAX(2,147,483,647)
 *
 * 【面试追问】
 * Q1: 为什么只对质数底有效？→ 质数的幂的因子只有该质数的更低次幂
 * Q2: 如何判 4 的幂？→ 先判 2 的幂(n&(n-1)==0)再检查 1 在偶数位
 * Q3: 递归法？→ n==1 return true; n<=0||n%3!=0 return false; return f(n/3)
 */
