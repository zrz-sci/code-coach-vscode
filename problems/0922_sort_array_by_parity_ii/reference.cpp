/*
 * LeetCode 922: 按奇偶排序数组 II (Sort Array By Parity II)
 *
 * 【题目本质】
 * 偶数下标放偶数，奇数下标放奇数。
 * 核心观察：偶数位上的"违规奇数"和奇数位上的"违规偶数"
 * 数量一定相等，可以一一配对交换。
 *
 * 【解法总览】
 * 解法1: 双通道填充 — O(n) / O(n) — 直觉解法
 * 解法2: 双指针原地交换 — O(n) / O(1) — Follow Up 首选
 */

// ============================================================
// 解法1: 双通道填充 — 新数组 + 两个写入指针
// 时间: O(n)  空间: O(n)
//
// 【思路】
// 创建结果数组，用 evenIdx(0,2,4...) 和 oddIdx(1,3,5...) 分别写入。
// 遍历原数组，偶数填到 evenIdx，奇数填到 oddIdx。
// 两个指针互不干扰，各管各的下标空间。
//
// 过程示意:
// nums = [4, 2, 5, 7]
//
// num=4 偶数 → result[0]=4, evenIdx=2
// num=2 偶数 → result[2]=2, evenIdx=4
// num=5 奇数 → result[1]=5, oddIdx=3
// num=7 奇数 → result[3]=7, oddIdx=5
// result = [4, 5, 2, 7] ✓
// ============================================================
class Solution1 {
public:
    vector<int> sortArrayByParityII(vector<int>& nums) {
        int n = nums.size();
        vector<int> result(n);
        int evenIdx = 0;  // 偶数位写入指针: 0, 2, 4, ...
        int oddIdx = 1;   // 奇数位写入指针: 1, 3, 5, ...

        for (int num : nums) {
            if (num % 2 == 0) {
                // 偶数 → 放到偶数下标
                result[evenIdx] = num;
                evenIdx += 2;
            } else {
                // 奇数 → 放到奇数下标
                result[oddIdx] = num;
                oddIdx += 2;
            }
        }

        return result;
    }
};

// ============================================================
// 解法2: 双指针原地交换 — 偶数位指针 + 奇数位指针配对消除
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 偶数位上如果放了奇数（违规），奇数位上一定有偶数（也违规）。
// 用指针 i 扫偶数位(0,2,4...)，j 扫奇数位(1,3,5...)。
// 当 i 找到违规奇数时，让 j 向前找到违规偶数，交换。
//
// 关键：j 不需要回退！因为 j 之前扫过的位置要么本来就对，
// 要么已经被交换修正过。所以是摊还 O(n)。
//
// 过程示意:
// nums = [4, 2, 5, 7]
//        i=0         j=1
//
// i=0: nums[0]=4 偶数 ✓ → i=2
// i=2: nums[2]=5 奇数 ✗ → 去找 j
//   j=1: nums[1]=2 偶数 ✗ → 找到！swap(nums[2], nums[1])
//   nums = [4, 5, 2, 7] ✓
//
// 另一个例子:
// nums = [3, 4, 2, 7, 6, 1]
//        i=0              j=1
//
// i=0: nums[0]=3 奇数 ✗ → 找 j
//   j=1: nums[1]=4 偶数 ✗ → swap → nums=[4,3,2,7,6,1], j=3
// i=2: nums[2]=2 偶数 ✓ → i=4
// i=4: nums[4]=6 偶数 ✓ → 结束
// result: [4, 3, 2, 7, 6, 1] ✓
// ============================================================
class Solution2 {
public:
    vector<int> sortArrayByParityII(vector<int>& nums) {
        int n = nums.size();
        int j = 1;  // 奇数位指针，初始指向第一个奇数下标

        for (int i = 0; i < n; i += 2) {
            // 扫描偶数位
            if (nums[i] % 2 == 1) {
                // 偶数位上放了奇数！需要找一个奇数位上的偶数来交换

                // 在奇数位找违规的偶数
                while (nums[j] % 2 == 1) {
                    j += 2;  // 这个奇数位上是奇数，正确，跳过
                }

                // nums[j] 是奇数位上的偶数（违规），交换修正
                swap(nums[i], nums[j]);
                // j 不回退，下次从当前位置继续向前找
            }
        }

        return nums;
    }
};

// ============================================================
// 解法2 变体: 用位运算判断奇偶 — 更高效
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 与解法2相同，但用 & 1 代替 % 2 判断奇偶。
// num & 1 == 0 → 偶数
// num & 1 == 1 → 奇数
// 位运算比取模更快（虽然编译器通常会优化）。
// ============================================================
class Solution2_BitOp {
public:
    vector<int> sortArrayByParityII(vector<int>& nums) {
        int n = nums.size();
        int j = 1;

        for (int i = 0; i < n; i += 2) {
            if (nums[i] & 1) {
                // 偶数位上是奇数 — 违规
                while (nums[j] & 1) {
                    j += 2;
                }
                swap(nums[i], nums[j]);
            }
        }

        return nums;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法           | 时间  | 空间  | 特点                    |
// |----------------|-------|-------|-------------------------|
// | 双通道填充     | O(n)  | O(n)  | 直觉简单，额外数组      |
// | 双指针原地交换 | O(n)  | O(1)  | Follow Up 答案，原地    |
// | 位运算变体     | O(n)  | O(1)  | 微优化，面试加分        |
//
// 【易错点】
// 1. 指针步长写成 1:
//    ✗ i++ / j++ — 会越界到不属于自己的下标
//    ✓ i += 2 / j += 2 — 偶数位和奇数位各走各的
//
// 2. j 每次从头扫描:
//    ✗ 在外层循环每次重置 j=1 — 变成 O(n^2)
//    ✓ j 保持位置继续向前 — 摊还 O(n)
//
// 3. 奇偶判断搞反:
//    ✗ 偶数位检查 nums[i] % 2 == 0 (这是正确的不需要处理)
//    ✓ 偶数位检查 nums[i] % 2 == 1 (这才是违规需要修正的)
//
// 4. 忘记返回 nums:
//    ✗ 原地修改了但没写 return nums
//    ✓ 即使原地修改，函数签名要求返回 vector<int>
//
// 【面试追问】
// Q1(复杂度): 为什么嵌套循环是 O(n)？
//    （摊还分析：i 走 n/2 步，j 走 n/2 步，总共 O(n)）
// Q2(变体): LeetCode 905 只要偶数在前奇数在后怎么做？
//    （经典 partition，left/right 从两端向中间，步长1）
// Q3(拓展): 能否排序解？
//    （可以但 O(nlogn)，不如 O(n) 的分类方案）
// ============================================================
