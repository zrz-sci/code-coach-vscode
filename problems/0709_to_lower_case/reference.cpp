/*
 * LeetCode 709: To Lower Case (转换成小写字母)
 *
 * 【题目本质】
 * 将字符串中所有大写字母转为小写，其他字符不变。
 * 考察底层：ASCII 编码、位运算、字符处理原理。
 *
 * 【ASCII 核心知识】
 *
 * 字符  十进制  二进制
 * 'A'   65     0100 0001
 * 'Z'   90     0101 1010
 * 'a'   97     0110 0001      ← 比 'A' 多了 0010 0000 (=32=0x20)
 * 'z'   122    0111 1010
 *
 * 大小写字母只有第 5 位 (bit 5) 不同:
 *   'A' = 0100 0001
 *   'a' = 0110 0001
 *            ^-- bit 5: 0=大写, 1=小写
 *
 * 位运算转换:
 *   大写→小写:  c | 0x20   (设置 bit 5)
 *   小写→大写:  c & ~0x20  (清除 bit 5)
 *   大小写互换: c ^ 0x20   (翻转 bit 5)
 *
 * 【解法总览】
 * 解法1: 判断 + 加 32        — 基础直觉写法
 * 解法2: 位运算 OR 0x20      — 利用 ASCII bit 5 特性
 * 解法3: 字符差值法           — 不依赖具体 ASCII 值
 * 解法4: 标准库 tolower()    — 工程实践写法
 */


// ============================================================
// 解法1: 判断 + 加 32 — 基础写法
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 遍历每个字符，如果在 'A'-'Z' 范围内，加上 32 变成 'a'-'z'。
// 其他字符（数字、空格、标点、已经是小写的）保持不变。
//
// 示例: "Hello"
//   'H'(72) → 72+32=104='h'  ← 大写，转换
//   'e'(101) → 不在 A-Z 范围 → 保持 'e'
//   'l'(108) → 保持 'l'
//   'l'(108) → 保持 'l'
//   'o'(111) → 保持 'o'
//   结果: "hello"
//
// 示例: "LOVELY"
//   每个字符都在 A-Z 范围 → 全部 +32
//   L(76)→l, O(79)→o, V(86)→v, E(69)→e, L(76)→l, Y(89)→y
//   结果: "lovely"
// ============================================================
class Solution1 {
public:
    string toLowerCase(string s) {
        for (char& c : s) {        // 用引用 & 直接修改原字符串
            if (c >= 'A' && c <= 'Z') {
                c += 32;           // 等价于 c += ('a' - 'A')
            }
            // 非大写字母保持不变（不需要 else）
        }
        return s;
    }
};


// ============================================================
// 解法2: 位运算 OR 0x20 — 加分写法 ⭐
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 利用 ASCII 编码中大小写字母仅第5位不同的特性。
// c | 0x20 将第5位设为1 → 大写变小写。
//
// 图解:
//   'H' = 0100 1000
//       | 0010 0000  (= 0x20)
//       = 0110 1000 = 'h'  ✓
//
//   'e' = 0110 0101
//       | 0010 0000
//       = 0110 0101 = 'e'  ✓ (已是小写，不变)
//
// 注意: 必须先判断是大写字母！
// 对非字母字符 |= 0x20 会产生错误:
//   '0'(0011 0000) | 0x20 = 0011 0000 | 0010 0000
//                         = 0011 0000 = '0'  ← 碰巧没变
//   '1'(0011 0001) | 0x20 = 0011 0001 | 0010 0000
//                         = 0011 0001 = '1'  ← 碰巧没变
//   但:
//   '@'(0100 0000) | 0x20 = 0100 0000 | 0010 0000
//                         = 0110 0000 = '`'  ← 错误!
//
// 安全做法: 仍需 if (c >= 'A' && c <= 'Z') 守卫
// ============================================================
class Solution2 {
public:
    string toLowerCase(string s) {
        for (char& c : s) {
            if (c >= 'A' && c <= 'Z') {
                c |= 0x20;   // 设置 bit 5：大写 → 小写
            }
        }
        return s;
    }
};


// ============================================================
// 解法3: 字符差值法
// 时间: O(n)  空间: O(1)
//
// 【思路】
// c - 'A' 得到 0-25 的偏移量，+ 'a' 映射到 'a'-'z'。
// 不依赖 'a' - 'A' == 32 这个具体值，理论上更具可移植性。
//
// 示例: 'H'
//   'H' - 'A' = 72 - 65 = 7   (偏移量)
//   7 + 'a' = 7 + 97 = 104 = 'h'  ✓
// ============================================================
class Solution3 {
public:
    string toLowerCase(string s) {
        for (char& c : s) {
            if (c >= 'A' && c <= 'Z') {
                c = c - 'A' + 'a';   // 映射: A→a, B→b, ..., Z→z
            }
        }
        return s;
    }
};


// ============================================================
// 解法4: 标准库 tolower()
// 时间: O(n)  空间: O(1)
//
// 【思路】
// 直接调用 C 标准库函数 tolower()。
// 面试中通常不推荐（除非面试官允许），因为考点是底层原理。
// 工程实践中推荐使用标准库。
// ============================================================
class Solution4 {
public:
    string toLowerCase(string s) {
        for (char& c : s) {
            c = tolower(c);   // 非大写字母返回原值
        }
        return s;
    }
};


// ============================================================
// 【位运算速查表 — 大小写转换】
//
// | 操作         | 位运算        | 效果                    |
// |-------------|--------------|------------------------|
// | 转小写       | c | 0x20    | 设置 bit 5 → 大写变小写  |
// | 转大写       | c & ~0x20   | 清除 bit 5 → 小写变大写  |
// | 大小写互换   | c ^ 0x20    | 翻转 bit 5 → toggle    |
// | 判断大写     | !(c & 0x20) | bit 5 为 0 → 大写      |
// | 判断小写     | c & 0x20    | bit 5 为 1 → 小写      |
//
// 前提: c 是字母! 对非字母字符以上操作可能产生错误结果。
//
// ============================================================
// 【ASCII 码设计的巧妙之处】
//
// ASCII 码设计者（1960s）有意让大小写字母只差 bit 5：
//   - 硬件上只需一个 OR 门就能完成大小写转换
//   - 大小写不敏感的比较只需忽略 bit 5
//   - 数字 '0'-'9' (0x30-0x39) 的低4位恰好是 0-9
//
// 这些设计让字符处理在底层硬件上非常高效。
//
// ============================================================
// 【易错点】
//
// 1. 位运算不判断范围:
//    ✗ for (char& c : s) c |= 0x20;  → '@' 变成 '`'
//    ✓ if (c >= 'A' && c <= 'Z') c |= 0x20;
//
// 2. 忘记用引用修改:
//    ✗ for (char c : s) c += 32;  → c 是副本，s 不变
//    ✓ for (char& c : s) c += 32;
//
// 3. 硬编码 ASCII 值:
//    ✗ if (c >= 65 && c <= 90) c += 32;  → 魔法数字
//    ✓ if (c >= 'A' && c <= 'Z') c += ('a' - 'A');
//
// ============================================================
// 【面试追问】
//
// Q1: 为什么大小写相差32不是巧合？
//     ASCII设计时故意让大小写只差bit 5，方便硬件位操作转换。
//
// Q2: Unicode大小写转换怎么做？
//     不能用简单的+32。需要ICU库或语言内置函数。
//     某些字符转换后长度改变（德语 ß → SS）。
//
// Q3: XOR 0x20 有什么应用？
//     大小写互转(toggle)、大小写不敏感比较、简单密码学。
//
// Q4: tolower() 线程安全吗？
//     C标准版依赖locale，多线程修改locale时不安全。
//     手动 c+=32 完全无此问题。
//
