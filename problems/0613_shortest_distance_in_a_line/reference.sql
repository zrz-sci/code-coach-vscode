-- ============================================================
-- 613. Shortest Distance in a Line (直线上的最近距离)
-- 难度: Easy | 标签: Database
-- ============================================================

-- ============================================================
-- 解法一: 自连接 + ABS + MIN (推荐, 最直观)
-- 思路: 枚举所有不同点对, 算绝对差值, 取最小
-- x 是主键, 值唯一, p1.x != p2.x 即可排除自身
-- 时间复杂度: O(n^2)  空间: O(1)
-- ============================================================
SELECT
    MIN(ABS(p1.x - p2.x)) AS shortest
FROM Point p1
JOIN Point p2
    ON p1.x != p2.x;

-- ============================================================
-- 解法二: 不等式避免重复 (计算量减半)
-- 思路: p1.x < p2.x 确保每对只算一次
--   差值 p2.x - p1.x 一定为正, 不需要 ABS
-- 时间复杂度: O(n^2) 但实际减半
-- ============================================================
SELECT
    MIN(p2.x - p1.x) AS shortest
FROM Point p1
JOIN Point p2
    ON p1.x < p2.x;

-- ============================================================
-- 解法三: 窗口函数 LEAD (Follow-up 最优解)
-- 思路: 排序后最短距离一定在相邻点之间
--   LEAD(x) OVER (ORDER BY x) 获取下一个点
--   差值即相邻距离, 取 MIN
-- 时间复杂度: O(n log n) 排序 + O(n) 扫描
-- ============================================================
SELECT
    MIN(next_x - x) AS shortest
FROM (
    SELECT
        x,
        LEAD(x) OVER (ORDER BY x) AS next_x
    FROM Point
) t
WHERE next_x IS NOT NULL;

-- ============================================================
-- 解法四: 逗号连接写法 (等价自连接)
-- 思路: FROM 中逗号分隔两个表 = CROSS JOIN
--   WHERE 过滤自身 + 控制方向
-- ============================================================
SELECT
    MIN(b.x - a.x) AS shortest
FROM Point a, Point b
WHERE a.x < b.x;
