/*
 * LeetCode 48: 旋转图像 (Rotate Image)
 *
 * 【题目本质】
 * 将 n×n 矩阵原地顺时针旋转 90°。
 * 核心挑战：不能用额外矩阵，如何在原地完成旋转而不丢失数据。
 *
 * 【解法总览】
 * 解法1: 辅助矩阵      — O(n²) / O(n²) — 最直觉，不满足原地要求
 * 解法2: 转置 + 左右翻转 — O(n²) / O(1)  — 面试首选，代码简洁
 * 解法3: 四元素循环替换  — O(n²) / O(1)  — 直接旋转，展示深度理解
 */

// ============================================================
// 解法1: 辅助矩阵 — 创建新矩阵，按旋转规则填入
// 时间: O(n²)  空间: O(n²)
//
// 【思路】
// 顺时针旋转 90° 的坐标映射: (i, j) → (j, n-1-i)
// 创建一个新矩阵，逐元素按规则填入，最后复制回去。
// 虽然不满足"原地"要求，但有助于理解坐标变换规则。
//
// 可视化 (3×3):
//   原始:              旋转后:
//   1  2  3           7  4  1
//   4  5  6    →      8  5  2
//   7  8  9           9  6  3
//
//   验证: (0,0)=1 → (0, 2)=1 ✓   (2,0)=7 → (0, 0)=7 ✓
// ============================================================
class Solution1 {
public:
    void rotate(vector<vector<int>>& matrix) {
        int n = matrix.size();
        vector<vector<int>> temp = matrix;
        for (int i = 0; i < n; i++) {
            for (int j = 0; j < n; j++) {
                // (i, j) 旋转后放到 (j, n-1-i)
                matrix[j][n - 1 - i] = temp[i][j];
            }
        }
    }
};

// ============================================================
// 解法2: 转置 + 左右翻转 — 把旋转分解为两步简单操作 ⭐ 面试首选
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 关键洞察：顺时针90° 可以分解为:
//   Step 1: 沿主对角线转置 — (i,j) → (j,i)
//   Step 2: 每行左右翻转   — (j,i) → (j, n-1-i)
// 两步组合起来就是 (i,j) → (j, n-1-i)，与旋转公式一致。
//
// 为什么想到这个分解？
// - 转置和翻转都是"两元素交换"操作，天然可以原地完成
// - 比直接循环替换更不容易写错
//
// 可视化 (4×4):
//   原始:                转置:                 左右翻转:
//    5   1   9  11       5   2  13  15        15  13   2   5
//    2   4   8  10  →    1   4   3  14   →    14   3   4   1
//   13   3   6   7       9   8   6  12        12   6   8   9
//   15  14  12  16      11  10   7  16        16   7  10  11
//                                              ↑ 最终结果 ✓
// ============================================================
class Solution2 {
public:
    void rotate(vector<vector<int>>& matrix) {
        int n = matrix.size();
        
        // Step 1: 沿主对角线转置
        // 只遍历上三角 (j > i)，因为 swap(i,j) 和 swap(j,i) 是同一对
        // 如果从 j=0 开始，每对被交换两次，等于没换！
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                swap(matrix[i][j], matrix[j][i]);
            }
        }
        
        // Step 2: 每行左右翻转
        // 只遍历到一半 (j < n/2)，因为两端同时交换
        for (int i = 0; i < n; i++) {
            for (int j = 0; j < n / 2; j++) {
                swap(matrix[i][j], matrix[i][n - 1 - j]);
            }
        }
    }
};

// ============================================================
// 解法3: 四元素循环替换 — 从外到内逐圈旋转
// 时间: O(n²)  空间: O(1)
//
// 【思路】
// 不拆解操作，直接原地旋转。
// 核心观察：旋转时，4个位置形成一个"旋转环"：
//
//   (i, j) → (j, n-1-i) → (n-1-i, n-1-j) → (n-1-j, i) → (i, j)
//
// 只需1个 temp，就能把4个元素同时搬到正确位置。
//
// 四元素环路示意 (n=4, 以(0,1)为例):
//
//    ┌─────────────────────┐
//    │  5  [1]  9  11      │    位置1: (0,1) = 1
//    │  2   4   8  10      │    位置2: (1,3) = 10
//    │ 13   3   6   7      │    位置3: (3,2) = 12
//    │ 15  14 [12] 16      │    位置4: (2,0) = 13
//    └─────────────────────┘
//
//    旋转后: 13→(0,1), 1→(1,3), 10→(3,2), 12→(2,0)
//
// 遍历范围:
//   外层 i ∈ [0, n/2):     控制从第几圈开始
//   内层 j ∈ [i, n-1-i):   控制当前圈的起始位置
//
//   n=4 时:
//   i=0: j=0,1,2  (外圈3个四元组, 共12个元素)
//   i=1: j=1      (内圈1个四元组, 共4个元素)
//   总共 16 个元素, 恰好覆盖整个矩阵
// ============================================================
class Solution3 {
public:
    void rotate(vector<vector<int>>& matrix) {
        int n = matrix.size();
        
        for (int i = 0; i < n / 2; i++) {
            for (int j = i; j < n - 1 - i; j++) {
                // 保存"上"
                int temp = matrix[i][j];
                
                // "左" → "上"
                // (n-1-j, i) → (i, j)
                matrix[i][j] = matrix[n - 1 - j][i];
                
                // "下" → "左"
                // (n-1-i, n-1-j) → (n-1-j, i)
                matrix[n - 1 - j][i] = matrix[n - 1 - i][n - 1 - j];
                
                // "右" → "下"
                // (j, n-1-i) → (n-1-i, n-1-j)
                matrix[n - 1 - i][n - 1 - j] = matrix[j][n - 1 - i];
                
                // "上"(temp) → "右"
                // temp → (j, n-1-i)
                matrix[j][n - 1 - i] = temp;
            }
        }
    }
};

// ============================================================
// 【解法对比】
//
// | 解法 | 时间 | 空间 | 原地 | 代码复杂度 |
// |------|------|------|------|-----------|
// | 辅助矩阵      | O(n²) | O(n²) | ✗ | 最简单     |
// | 转置+翻转      | O(n²) | O(1)  | ✓ | 简单       |
// | 四元素循环替换  | O(n²) | O(1)  | ✓ | 较复杂     |
//
// 面试推荐：先说辅助矩阵展示理解 → 写出转置+翻转 → 如果追问再给循环替换
//
// 转置+翻转 vs 循环替换:
// - 转置+翻转: 两步操作，每步逻辑独立清晰，不容易出 bug
// - 循环替换: 一次遍历完成，但坐标变换和赋值方向容易搞混
// - 实际面试中两者效率相同，选更不容易写错的
//
// ============================================================
// 【易错点】
//
// 1. 转置遍历范围:
//    ✗ for(j = 0; j < n; j++) → 每对交换两次，矩阵不变
//    ✓ for(j = i+1; j < n; j++) → 只遍历上三角，每对交换恰好一次
//
// 2. 循环替换的赋值方向:
//    ✗ 按顺时针赋值: matrix[j][n-1-i] = matrix[i][j]; ...
//       → 第一步就覆盖了 matrix[j][n-1-i] 的原值，后续赋值全错
//    ✓ 按逆时针赋值(从被覆盖位置的"来源"开始): 
//       先 temp = matrix[i][j], 然后 matrix[i][j] = matrix[n-1-j][i], ...
//
// 3. 循环替换内层边界:
//    ✗ j <= n-1-i → 角上元素被重复处理
//    ✓ j < n-1-i  → 每圈最后一个元素属于第一个四元组的环路
//
// 4. 两步操作顺序搞反:
//    ✗ 先左右翻转再转置 → 结果是逆时针90°
//    ✓ 先转置再左右翻转 → 结果是顺时针90°
//
// ============================================================
// 【面试追问】
//
// Q1: 逆时针旋转90°怎么改？
// → 方法a: 转置 + 上下翻转 (把左右翻转改为上下翻转)
//   方法b: 上下翻转 + 转置 (调换两步顺序也可以)
//   坐标验证: (i,j) →上下翻转→ (n-1-i,j) →转置→ (j, n-1-i)?
//   不对, 逆时针应该是 (i,j) → (n-1-j, i)
//   正确方法: 转置 → 上下翻转: (i,j)→(j,i)→(n-1-j, i) ✓
//
// Q2: 旋转180°怎么做最简单？
// → matrix[i][j] 和 matrix[n-1-i][n-1-j] 互换
//   等价于: 上下翻转 + 左右翻转 (两者顺序无所谓)
//
// Q3: 非方阵(m×n)能原地旋转吗？
// → 不能简单原地旋转, 因为 m×n 旋转后变成 n×m, 维度变了
//   如果底层是一维数组, 可以用置换环(follow the cycle)原地重排
//   但代码复杂度很高, 面试中说明"正方形才能简单原地旋转"即可
//
// Q4: 旋转 k*90° 怎么优化？
// → k %= 4, 然后:
//   k=0: 不操作
//   k=1: 顺时针90° (本题)
//   k=2: 旋转180°
//   k=3: 逆时针90° (或顺时针270°)
//   不要真的调用 k 次旋转函数
// ============================================================
