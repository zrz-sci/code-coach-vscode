/*
 * LeetCode 392: 判断子序列 (Is Subsequence)
 *
 * 【题目本质】
 * 判断字符串 s 能否通过在 t 中从左到右依次"贪心匹配"每个字符而被完全消耗。
 * Follow-up: 如果有大量 s 要查询同一个 t，如何优化？
 *
 * 【解法总览】
 * 解法1: 双指针贪心    — O(n+m) / O(1)          — 面试首选
 * 解法2: 预处理+二分   — O(m)预处理, O(|s|logm)查询 / O(m) — Follow-up 必须掌握
 * 解法3: 动态规划      — O(n×m) / O(n×m) → O(m)  — 展示 DP 功底
 */

// ============================================================
// 解法1: 双指针贪心 — 面试首选
// 时间: O(n + m)  空间: O(1)
//
// 【思路】
// 子序列要求"保持相对顺序"，那最自然的做法是：
// 两个指针 i, j 分别指向 s 和 t，同步扫描。
// 如果 s[i] == t[j]，说明匹配成功一个，i 前进。
// 无论是否匹配，j 都前进（t 中的字符要么被匹配消耗，要么被跳过）。
// 最后看 i 是否走到了 s 的末尾。
//
// 贪心正确性：对于 s[i]，在 t 中越早匹配越好。
// 如果跳过一个能匹配的位置，后续字符的可选范围只会变小。
//
// 匹配过程示意 (s="abc", t="ahbgdc"):
//   j: 0  1  2  3  4  5
//   t: a  h  b  g  d  c
//   i=0: 'a'=='a' ✓ → i=1
//   i=1: 'b'!='h'   → j++
//   i=1: 'b'=='b' ✓ → i=2
//   i=2: 'c'!='g'   → j++
//   i=2: 'c'!='d'   → j++
//   i=2: 'c'=='c' ✓ → i=3
//   i==3==s.size() → true
// ============================================================
class Solution1 {
public:
    bool isSubsequence(string s, string t) {
        int i = 0, j = 0;
        while (i < (int)s.size() && j < (int)t.size()) {
            if (s[i] == t[j]) {
                i++;  // 匹配成功，消耗 s 的一个字符
            }
            j++;  // t 的指针无论如何都前进
        }
        // 判断 s 是否被完全消耗，不是判断 j
        return i == (int)s.size();
    }
};

// ============================================================
// 解法2: 预处理 + 二分查找 — Follow-up 解法
// 预处理: O(m)  每次查询: O(|s| × log m)  空间: O(m)
//
// 【思路】
// 解法1 每次查询都要 O(m) 扫描 t。如果有 10 亿个 s 要查询同一个 t，
// 总时间 O(k × m) 不可接受。
//
// 优化：对 t 做一次预处理，为每个字符记录所有出现位置。
// 查询时，对 s 的每个字符 c，在 c 的位置列表中二分查找
// "严格大于上一次匹配位置"的最小位置。
//
// 预处理示意 (t = "ahbgdc"):
//   'a' → [0]
//   'b' → [2]
//   'c' → [5]
//   'd' → [4]
//   'g' → [3]
//   'h' → [1]
//
// 查询 s = "abc":
//   prev = -1
//   'a': upper_bound([0], -1) → 0,  prev = 0
//   'b': upper_bound([2], 0)  → 2,  prev = 2
//   'c': upper_bound([5], 2)  → 5,  prev = 5
//   全部成功 → true
// ============================================================
class Solution2 {
public:
    bool isSubsequence(string s, string t) {
        // 预处理：记录 t 中每个字符的所有出现位置
        vector<vector<int>> idx(26);
        for (int i = 0; i < (int)t.size(); i++) {
            idx[t[i] - 'a'].push_back(i);
        }

        int prev = -1;  // 上一次匹配在 t 中的位置
        for (char c : s) {
            auto& positions = idx[c - 'a'];
            // 找 positions 中第一个 > prev 的值
            // 用 upper_bound 而不是 lower_bound：因为需要严格大于
            auto it = upper_bound(positions.begin(), positions.end(), prev);
            if (it == positions.end()) {
                return false;  // 在 prev 之后再也找不到字符 c
            }
            prev = *it;  // 更新匹配位置
        }
        return true;
    }
};

// ============================================================
// 解法3: 动态规划 — O(n × m) / O(n × m)
//
// 【思路】
// "s 是 t 的子序列" 等价于 "LCS(s, t) == |s|"。
// 但与标准 LCS 不同：这里 s 的每个字符都必须匹配，
// 不匹配时只能跳过 t 的字符（不能跳过 s 的字符）。
//
// 状态定义: dp[i][j] = s[0..i-1] 和 t[0..j-1] 的最长公共子序列长度
// 转移:
//   s[i-1] == t[j-1] → dp[i][j] = dp[i-1][j-1] + 1  (匹配)
//   s[i-1] != t[j-1] → dp[i][j] = dp[i][j-1]         (跳过 t[j-1])
//   注意：不是 max(dp[i-1][j], dp[i][j-1])！
//   因为 s 的字符不能被跳过。
//
// dp 填表方向和依赖关系:
//   dp[i][j] 依赖 dp[i-1][j-1] (左上) 和 dp[i][j-1] (左)
//   → 从上到下、从左到右填表
//
//       ""  a  h  b  g  d  c
//   ""   0  0  0  0  0  0  0
//    a   0  1  1  1  1  1  1
//    b   0  1  1  2  2  2  2
//    c   0  1  1  2  2  2  3   ← 3 == |s| → true
//
// 最终判断: dp[n][m] == n
// ============================================================
class Solution3 {
public:
    bool isSubsequence(string s, string t) {
        int n = s.size(), m = t.size();
        vector<vector<int>> dp(n + 1, vector<int>(m + 1, 0));

        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= m; j++) {
                if (s[i - 1] == t[j - 1]) {
                    dp[i][j] = dp[i - 1][j - 1] + 1;  // 匹配，消耗两边各一个字符
                } else {
                    dp[i][j] = dp[i][j - 1];  // 只跳过 t 的字符，不跳过 s
                }
            }
        }
        return dp[n][m] == n;
    }
};

// ============================================================
// 解法3 空间优化版 — O(n × m) / O(m)
//
// dp[i][j] 只依赖 dp[i-1][j-1] (上一行的前一列) 和 dp[i][j-1] (当前行的前一列)
// → 可以用一维数组 + prev 变量优化到 O(m) 空间
// ============================================================
class Solution3_Optimized {
public:
    bool isSubsequence(string s, string t) {
        int n = s.size(), m = t.size();
        vector<int> dp(m + 1, 0);

        for (int i = 1; i <= n; i++) {
            int prev = 0;  // 保存 dp[i-1][j-1]，即左上角的值
            for (int j = 1; j <= m; j++) {
                int temp = dp[j];  // 暂存当前值，下一轮迭代作为 prev
                if (s[i - 1] == t[j - 1]) {
                    dp[j] = prev + 1;
                } else {
                    dp[j] = dp[j - 1];  // 当前行左边的值
                }
                prev = temp;
            }
        }
        return dp[m] == n;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法         | 时间       | 空间     | 适用场景          |
// |-------------|-----------|---------|------------------|
// | 双指针贪心    | O(n+m)    | O(1)    | 单次查询，面试首选   |
// | 预处理+二分   | 预处理O(m) | O(m)    | 多次查询同一个t     |
// |             | 查询O(|s|logm)|       | (Follow-up)      |
// | DP          | O(n×m)    | O(m)优化 | 展示DP功底/扩展问题  |
//
// 面试策略：
// 1. 先写双指针，说明贪心正确性
// 2. 面试官追问 Follow-up 时，给出预处理+二分方案
// 3. 如果面试官问 DP，说明和 LCS 的关系以及转移方程的简化
//
// 【易错点】
// 1. 终止判断: return i == s.size() 而不是 j == t.size()
//    ✗ return j == (int)t.size();  // t 扫完了不代表 s 匹配完了
//    ✓ return i == (int)s.size();  // s 的指针走到末尾才是全部匹配
//
// 2. 二分查找函数选错:
//    ✗ lower_bound(..., prev)  // 会找到 == prev 的位置，重复使用同一位置
//    ✓ upper_bound(..., prev)  // 严格大于 prev，确保每次匹配不同位置
//
// 3. DP 转移写成标准 LCS:
//    ✗ dp[i][j] = max(dp[i-1][j], dp[i][j-1])  // 这允许跳过 s 的字符
//    ✓ dp[i][j] = dp[i][j-1]                    // 只能跳过 t，不能跳过 s
//
// 4. 空间优化时忘记保存 prev:
//    一维 DP 中 dp[j] 在更新前要先保存，否则 dp[i-1][j-1] 就丢失了
//
// 【面试追问 — 递进链】
//
// Q1: 最直接的思路？
// → 双指针贪心，O(n+m)，贪心正确性：越早匹配给后续留的空间越大。
//
// Q2 (Follow-up): 10亿个 s 查询同一个 t？
// → 预处理 t 的字符位置索引，每次查询用二分。
//    预处理 O(m) 一次，每次查询 O(|s|×log m)。
//
// Q3: 能否用 DP？和 LCS 什么关系？
// → dp[i][j] = LCS(s[0..i-1], t[0..j-1])，
//    但转移简化为只跳过 t（dp[i][j]=dp[i][j-1]），因为 s 不能跳过。
//    dp[n][m]==n 即为 true。
//
// Q4: 如果 t 也在动态变化怎么办？
// → 平衡BST/线段树维护字符位置索引，支持动态插入删除和"后继查询"。
// ============================================================
