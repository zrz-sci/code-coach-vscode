/*
 * LeetCode 73: 矩阵置零 (Set Matrix Zeroes)
 *
 * 【题目本质】
 * "标记-延迟执行"问题：先记录哪些行列需要置零，再统一执行。
 * 核心挑战是如何减少标记所需的额外空间。
 *
 * 【解法总览】
 * 解法1: 额外矩阵        — O(mn) / O(mn)   — 最朴素，面试中简单提一下
 * 解法2: 行列标记数组     — O(mn) / O(m+n)  — 面试首选 ⭐
 * 解法3: 首行首列复用     — O(mn) / O(1)    — Follow-up 最优空间
 */

// ============================================================
// 解法1: 额外矩阵 — 复制原矩阵做参照
// 时间: O(mn)  空间: O(mn)
//
// 【思路】
// 第一反应：遍历时遇到 0 就置零整行整列。但这样新产生的 0 
// 会"传染"后续判断。最简单的解决方法——复制一份原矩阵，
// 查看副本的值，修改原矩阵。
//
// 示意图 (示例1):
//   副本:    原矩阵置零后:
//   1 1 1    1 0 1
//   1 0 1 →  0 0 0    ← 副本 [1][1]=0，第1行第1列全部清零
//   1 1 1    1 0 1
// ============================================================
class Solution1 {
public:
    void setZeroes(vector<vector<int>>& matrix) {
        int m = matrix.size(), n = matrix[0].size();
        auto copy = matrix;  // O(mn) 空间的副本
        
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (copy[i][j] == 0) {
                    // 在原矩阵上置零第 i 行
                    for (int k = 0; k < n; k++) matrix[i][k] = 0;
                    // 在原矩阵上置零第 j 列
                    for (int k = 0; k < m; k++) matrix[k][j] = 0;
                }
            }
        }
    }
};

// ============================================================
// 解法2: 行列标记数组 — O(m+n) 额外空间 ⭐ 面试首选
// 时间: O(mn)  空间: O(m+n)
//
// 【思路】
// 解法1 复制了整个矩阵，但实际上只需要知道"哪些行要清零"
// 和"哪些列要清零"。每行/每列只需要 1 个 bool 标记。
// - 第一趟：遍历矩阵，遇到 0 就标记 rows[i]=true, cols[j]=true
// - 第二趟：遍历矩阵，如果 rows[i] || cols[j] 就置零
//
// 示意图 (示例2):
//   原始:              标记:              结果:
//   0 1 2 0       rows=[1,0,0]        0 0 0 0
//   3 4 5 2       cols=[1,0,0,1]      0 4 5 0
//   1 3 1 5                            0 3 1 0
//   
//   rows[0]=true (因为 matrix[0][0]=0, matrix[0][3]=0)
//   cols[0]=true, cols[3]=true
// ============================================================
class Solution2 {
public:
    void setZeroes(vector<vector<int>>& matrix) {
        int m = matrix.size(), n = matrix[0].size();
        vector<bool> rows(m, false), cols(n, false);
        
        // 第一趟：扫描所有原始的 0，标记其行号和列号
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (matrix[i][j] == 0) {
                    rows[i] = true;
                    cols[j] = true;
                }
            }
        }
        
        // 第二趟：凡是被标记的行或列，该位置置零
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (rows[i] || cols[j]) {
                    matrix[i][j] = 0;
                }
            }
        }
    }
};

// ============================================================
// 解法3: 首行首列复用 — O(1) 空间 (Follow-up 最优)
// 时间: O(mn)  空间: O(1)
//
// 【思路】
// 解法2 的标记数组 rows[m] 和 cols[n] 需要 O(m+n) 空间。
// 但矩阵本身的第一行有 n 个格子、第一列有 m 个格子，
// 天然可以复用为标记数组！
//
// 具体做法:
// - matrix[i][0] 标记"第 i 行是否需要清零" (复用第一列)
// - matrix[0][j] 标记"第 j 列是否需要清零" (复用第一行)
// - 问题: matrix[0][0] 被第一行和第一列共用！
//   解决: matrix[0][0] 只标记"第一行"，额外用 bool firstCol 标记"第一列"
//
// ⚠️ 置零顺序至关重要:
// - 必须从最后一行倒序遍历到第 0 行
// - 如果先正序处理，第一行的标记信息会被提前覆盖成 0，
//   导致后续所有列都被误判为需要清零
//
// 示意图 (示例2):
//
//   原始矩阵:             标记阶段:
//   [0] [1] [2] [0]       [0] [1] [2] [0]  ← 第一行当 cols[] 标记
//   [3] [4] [5] [2]       [0]  .   .   .   ← matrix[0][0]=0 → 第一行需清零
//   [1] [3] [1] [5]       [1]  .   .   .   ← matrix[2][0]=1 → 第2行不需清零
//                          ↑ 第一列当 rows[] 标记
//                          firstCol=true (因为 matrix[0][0]=0)
//
//   置零阶段 (倒序 i=2→0):
//   i=2: matrix[2][0]=1≠0, matrix[0][1..3]都检查 → 不清零(除了 firstCol)
//   i=1: matrix[1][0]=0    → 第1行全部置零 → [0,4,5,0] → [0,0,0,0]
//        等等... 最后 firstCol=true → 第0列全部置零
//
//   最终:
//   0 0 0 0
//   0 4 5 0
//   0 3 1 0
// ============================================================
class Solution3 {
public:
    void setZeroes(vector<vector<int>>& matrix) {
        int m = matrix.size(), n = matrix[0].size();
        
        // firstCol: 单独记录第一列是否含零
        // 为什么不用 firstRow? 因为 matrix[0][0] 就可以代表第一行
        bool firstCol = false;
        
        // ---- 第一趟: 标记 ----
        for (int i = 0; i < m; i++) {
            // 先检查第一列 (不能和下面的循环合并，否则标记会乱)
            if (matrix[i][0] == 0) {
                firstCol = true;
            }
            // j 从 1 开始! 第 0 列的标记用 firstCol 处理
            for (int j = 1; j < n; j++) {
                if (matrix[i][j] == 0) {
                    matrix[i][0] = 0;  // 标记: 第 i 行需要清零
                    matrix[0][j] = 0;  // 标记: 第 j 列需要清零
                }
            }
        }
        
        // ---- 第二趟: 置零 (倒序遍历行，保护第一行的标记信息) ----
        for (int i = m - 1; i >= 0; i--) {
            // j 从 n-1 到 1: 根据第一行和第一列的标记来清零
            for (int j = n - 1; j >= 1; j--) {
                if (matrix[i][0] == 0 || matrix[0][j] == 0) {
                    matrix[i][j] = 0;
                }
            }
            // 最后处理第一列 (用 firstCol 判断)
            if (firstCol) {
                matrix[i][0] = 0;
            }
        }
    }
};

// ============================================================
// 【解法对比】
//
// | 解法          | 时间   | 空间   | 适用场景                |
// |---------------|--------|--------|------------------------|
// | 额外矩阵     | O(mn)  | O(mn)  | 仅作思路铺垫            |
// | 行列标记数组  | O(mn)  | O(m+n) | 面试首选，简洁不易出错  |
// | 首行首列复用  | O(mn)  | O(1)   | 面试追问 Follow-up     |
//
// 三种解法时间复杂度一样，区别全在空间。
// 面试建议: 先写 O(m+n) 版本，面试官追问时再优化到 O(1)。
//
// 【易错点】
//
// 1. 边遍历边置零 → "传染"bug
//    ✗ for(i,j) if(matrix[i][j]==0) { 清零整行整列 }
//      → 刚被置零的格子在后续遍历中被当成原始 0，级联清零
//    ✓ 分两趟: 先标记，后置零
//
// 2. O(1) 解法中 matrix[0][0] 的歧义
//    ✗ 用 matrix[0][0] 同时代表第一行和第一列
//      → 无法区分"第一行有零"和"第一列有零"
//    ✓ matrix[0][0] 只代表第一行，第一列用独立的 firstCol
//
// 3. O(1) 解法置零的遍历方向
//    ✗ for(i=0; i<m; i++) → 先处理 i=0 时把第一行清零
//      → 第一行的标记信息丢失，后面所有行的列判断全部出错
//    ✓ for(i=m-1; i>=0; i--) → 最后才处理第一行
//
// 4. O(1) 解法标记时 j 的起始位置
//    ✗ j 从 0 开始 → matrix[i][0] 的原始值被自己覆盖
//      如果 matrix[i][0] 本来就是 0，它会标记 matrix[0][0]=0，
//      但此时你无法区分这个 0 是"第 i 行有零"还是"第 0 列有零"
//    ✓ j 从 1 开始，第 0 列的零用 firstCol 单独处理
//
// 【面试追问】
//
// Q1: 为什么不能在一趟遍历中边标记边置零?
// → 因为新产生的 0 和原始 0 无法区分。遇到被置零的格子，
//   你会误以为它是原始 0，从而清零它的行列——级联反应可能
//   把整个矩阵都变成 0。
//
// Q2: O(m+n) 解法怎么优化到 O(1)?
// → 把标记数组"寄生"在矩阵自身的第一行和第一列中。
//   matrix[i][0] 代表第 i 行是否需要清零，
//   matrix[0][j] 代表第 j 列是否需要清零。
//   但 matrix[0][0] 被行和列共用，所以额外用一个 bool 记录第一列。
//   关键: 置零时倒序遍历，避免覆盖标记。
//
// Q3: 如果矩阵是稀疏的(零很少)，能进一步优化实际运行时间吗?
// → 渐进复杂度不变(仍需遍历整个矩阵来执行置零)，但可以
//   用 set<int> 存储需要清零的行号和列号，然后只遍历这些行列。
//   如果 k 个零分布在 r 个不同行、c 个不同列，清零操作
//   只需 O(r*n + c*m) 而非 O(mn)。
//
// Q4: 如果要你不修改原矩阵，返回一个新矩阵呢?
// → 新建结果矩阵，用 O(m+n) 标记后填充。空间 O(mn) 不可避免。
// ============================================================
