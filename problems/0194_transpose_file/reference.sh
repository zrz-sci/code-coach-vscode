# ============================================================
# 【解法对比】
#
# | 解法         | 文件扫描次数 | 内存     | 优势                 | 劣势                    |
# |-------------|------------|---------|---------------------|------------------------|
# | awk二维数组   | 1次        | O(m*n)  | 一次遍历，最高效       | 大文件占内存             |
# | awk字符串拼接 | 1次        | O(m*n)  | 代码更简洁            | 大文件仍占内存           |
# | Shell循环    | cols次     | O(m)    | 内存友好              | 多次扫描文件，速度慢      |
# | cut+paste    | cols次     | O(m)    | 用标准Unix工具         | 多次扫描+多个子进程      |
#
# m = 行数, n = 列数
#
# ============================================================
# 【易错点】
#
# 1. END块中NF不可用:
#    ✗ END { for(i=1;i<=NF;i++) print row[i] }
#      → END中NF=0（没有当前行）
#    ✓ 在主块中保存: cols=NF; END中用cols
#
# 2. 末尾多余空格:
#    ✗ printf "%s ", a[i,j]
#      → 最后一个元素后多一个空格，OJ可能判错
#    ✓ 第一个直接赋值，后续拼接 " " a[i,j]
#
# 3. 二维数组下标:
#    ✗ a[NR][i] → awk不支持真正的二维数组
#    ✓ a[NR,i] → awk用SUBSEP连接组成字符串key
#
# 4. Shell循环效率:
#    ✗ 对10000行x100列文件用Shell循环 → 扫描100遍
#    ✓ 用awk一次遍历方案
#
# ============================================================
