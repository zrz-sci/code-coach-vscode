#!/bin/bash
# LeetCode 194: Transpose File (转置文件)
#
# 【题目本质】
# 将文本文件的行列互换（矩阵转置）。
# 原来的第 j 列变成新的第 j 行。
# 核心难点：Shell 按行读取，但转置需要按列收集数据。
#
# 【解法总览】
# 解法1: awk 二维数组      — 一次遍历，END块转置输出，面试首选
# 解法2: awk 字符串拼接    — 更简洁，边读边拼接每列
# 解法3: Shell 循环逐列    — 循环列号，每次提取一列
# 解法4: head + awk 组合   — 先取列数，再逐列 awk 提取

# ============================================================
# 解法1: awk 二维数组 — 面试首选 ⭐
#
# 【思路】
# 一次遍历文件，把所有字段存入二维数组 a[行号,列号]。
# 读完后在 END 块中按列输出（外层循环列号，内层循环行号）。
#
# 关键变量:
#   NR — 当前行号（awk 自动维护）
#   NF — 当前行的字段数（列数）
#   $i — 第 i 个字段
#
# 输出格式注意:
#   第一个元素直接赋值，后续用 " " 拼接，避免末尾多余空格。
#
# 示例:
#   输入:              数组:
#   name age           a[1,1]="name"  a[1,2]="age"
#   alice 21           a[2,1]="alice" a[2,2]="21"
#   ryan 30            a[3,1]="ryan"  a[3,2]="30"
#
#   END块输出:
#   j=1: a[1,1] a[2,1] a[3,1] → "name alice ryan"
#   j=2: a[1,2] a[2,2] a[3,2] → "age 21 30"
# ============================================================
awk '{
    for (i = 1; i <= NF; i++) {
        a[NR,i] = $i
    }
}
NR == 1 { cols = NF }
END {
    for (j = 1; j <= cols; j++) {
        str = a[1,j]
        for (i = 2; i <= NR; i++) {
            str = str " " a[i,j]
        }
        print str
    }
}' file.txt

# ============================================================
# 解法2: awk 字符串拼接 — 更简洁
#
# 【思路】
# 不用二维数组，维护一个一维数组 row[i]，
# 每读一行就把第 i 列的值拼接到 row[i] 上。
# END 块中直接打印 row[1], row[2], ...
#
# 对比解法1:
#   解法1: 先全部存储，END块再组织输出
#   解法2: 边读边拼接，END块直接打印
#
# 注意:
#   NR==1 时直接赋值 row[i]=$i（不加前导空格）
#   NR>1 时拼接 row[i] = row[i] " " $i
#
# 陷阱: END 块中 NF 是0，不能用 NF 做循环上界。
# 解决: 保存列数到变量 cols。
# ============================================================
