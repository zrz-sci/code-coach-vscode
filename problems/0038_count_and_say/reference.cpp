/*
 * LeetCode 38: Count and Say (外观数列)
 *
 * 【题目本质】
 * 从 "1" 开始，重复执行 n-1 次"行程长度编码 (RLE)"操作。
 * 每次 RLE：把连续相同字符替换为 "计数+字符"。
 * 纯模拟题，没有数学捷径可以跳步。
 *
 * 【解法总览】
 * 解法1: 递归模拟 — O(n×L) / O(n×L) — 最贴合定义
 * 解法2: 迭代模拟 — O(n×L) / O(L) — 面试首选
 *
 * 其中 L 为第 n 项字符串长度，n=30 时 L ≈ 5000+。
 */

/*
 * 外观数列前几项推导过程：
 *
 *   n=1: "1"
 *   n=2: "11"        ← 读 "1": 1个1
 *   n=3: "21"        ← 读 "11": 2个1
 *   n=4: "1211"      ← 读 "21": 1个2, 1个1
 *   n=5: "111221"    ← 读 "1211": 1个1, 1个2, 2个1
 *   n=6: "312211"    ← 读 "111221": 3个1, 2个2, 1个1
 *
 * RLE 单次操作的双指针示意（以 "1211" 为例）：
 *
 *   "1 2 1 1"
 *    i j           → i=0, j=1, 组='1', 长度=1 → 输出 "11"
 *      i j         → i=1, j=2, 组='2', 长度=1 → 输出 "12"
 *        i   j     → i=2, j=4, 组='1', 长度=2 → 输出 "21"
 *
 *   拼接结果: "111221"  ✓
 */

// ============================================================
// 解法1: 递归模拟 — 按定义递归 + RLE
// 时间: O(n × L)  空间: O(n × L)（递归栈 + 每层字符串）
//
// 【思路】
// 题目定义就是递归形式：countAndSay(n) = RLE(countAndSay(n-1))
// 最自然的做法就是直接翻译这个定义。
// base case: n=1 返回 "1"
// 递归步: 先拿到 n-1 的结果，再做一次 RLE 变换。
//
// RLE 怎么做？双指针：
//   i 指向当前组的起点，j 向右找第一个不同字符
//   这组长度 = j - i，字符 = s[i]
//   输出 to_string(j-i) + s[i]，然后 i = j 跳到下一组
// ============================================================
class Solution1 {
public:
    string countAndSay(int n) {
        // base case
        if (n == 1) return "1";

        // 递归获取第 n-1 项
        string prev = countAndSay(n - 1);

        // 对 prev 做行程长度编码
        string result;
        int i = 0;
        while (i < (int)prev.size()) {
            int j = i;
            // 找连续相同字符的右边界
            while (j < (int)prev.size() && prev[j] == prev[i]) {
                j++;
            }
            // 为什么先 to_string(j-i) 再 prev[i]？
            // 因为 RLE 格式是"计数在前，字符在后"，如 "2个1" → "21"
            result += to_string(j - i);
            result += prev[i];
            i = j;  // 跳到下一组起点
        }
        return result;
    }
};

// ============================================================
// 解法2: 迭代模拟 — 循环 n-1 次 RLE（面试首选）
// 时间: O(n × L)  空间: O(L)
//
// 【思路】
// 递归版的 n 层调用可以用一个 for 循环替代：
//   - 初始 curr = "1"（第1项）
//   - 循环 n-1 次，每次对 curr 做一次 RLE，更新 curr
//   - 最终 curr 就是第 n 项
//
// 好处：省去 O(n) 的递归栈，只需要保存当前项和下一项。
//
// 迭代过程示例 (n=5):
//   循环前: curr = "1"
//   step=2: RLE("1")    → curr = "11"
//   step=3: RLE("11")   → curr = "21"
//   step=4: RLE("21")   → curr = "1211"
//   step=5: RLE("1211") → curr = "111221"
//   返回 "111221"
// ============================================================
class Solution2 {
public:
    string countAndSay(int n) {
        string curr = "1";

        // 从第2项推到第n项，共做 n-1 次 RLE
        // 为什么从 2 开始？因为第 1 项 "1" 已经初始化好了
        for (int step = 2; step <= n; step++) {
            string next;
            int i = 0;
            while (i < (int)curr.size()) {
                int j = i;
                while (j < (int)curr.size() && curr[j] == curr[i]) {
                    j++;
                }
                // 拼接 "计数" + "字符"
                next += to_string(j - i);
                next += curr[i];
                i = j;
            }
            curr = next;  // 用下一项替换当前项
        }

        return curr;
    }
};

// ============================================================
// 【解法对比】
//
// | 维度     | 递归 (Solution1)       | 迭代 (Solution2)      |
// |----------|------------------------|-----------------------|
// | 空间     | O(n×L) 递归栈+字符串   | O(L) 只保留当前项     |
// | 代码     | 更贴合数学定义         | 更工程化              |
// | 本质     | 完全等价，都是 n-1 次 RLE                        |
// | 面试     | 讲思路时用             | 写代码时用 ⭐         |
//
// 【易错点】
//
// 1. 循环次数:
//    ✗ for (int step = 1; step <= n; step++) — 多做了一次
//    ✓ for (int step = 2; step <= n; step++) — 第1项已初始化
//
// 2. 忘记移动 i:
//    ✗ 内层 while 后没有 i = j → 死循环
//    ✓ 每次处理完一组后 i = j 跳到下一组
//
// 3. 计数和字符顺序搞反:
//    ✗ next += curr[i]; next += to_string(j-i); → 字符在前，错误
//    ✓ next += to_string(j-i); next += curr[i]; → 计数在前，字符在后
//
// 4. size() 返回 unsigned，i 是 int:
//    当 curr 为空时 curr.size()-1 会下溢。虽然本题不会出现空串，
//    但养成 (int)curr.size() 的习惯可以避免潜在 bug。
//
// 【面试追问】
//
// Q1 (基础): 核心操作是什么？
// → 行程长度编码 (RLE)：双指针扫描连续相同字符，输出"计数+字符"。
//   整题 = 初始 "1" + 重复 n-1 次 RLE。
//
// Q2 (Follow-up): 能否用迭代替代递归？
// → 可以，用 for 循环从第1项推到第n项（Solution2）。
//   好处：省 O(n) 递归栈空间，代码更清晰。
//
// Q3 (深入): 第 n 项长度增长有什么规律？
// → 增长率趋近 Conway 常数 λ ≈ 1.303577...，
//   即 L(n) ≈ λ × L(n-1)。n=30 时 L ≈ 5000+，完全可以接受。
//
// Q4 (变体): 如果要对更长的字符串做 RLE（不限于数字），代码怎么改？
// → 核心不变，只是 to_string(j-i) 可能输出多位数。
//   本题因为只有数字1-3出现（外观数列的数学性质），
//   计数不会超过3，所以 to_string 输出单字符。
//   一般 RLE 场景无此限制，代码逻辑相同。
//
