/*
 * LeetCode 874: Walking Robot Simulation (模拟行走机器人)
 *
 * 【题目本质】
 * 机器人在无限平面上按指令移动（前进/左转/右转），遇障碍停下。
 * 求移动过程中距原点的最大欧几里得距离的平方。
 *
 * 【解法总览】
 * 解法1: 模拟 + set<pair>      — O(N*K*logM) / O(M) — 最清晰
 * 解法2: 模拟 + unordered_set  — O(N*K + M) / O(M)  — 最快
 */

// ============================================================
// 解法1: 模拟 + set<pair<int,int>>
// 时间: O(N*K*logM)  空间: O(M)
// N = commands 长度, K = 单步最大值(9), M = obstacles 数量
//
// 【思路】
// 1. 方向数组管理移动: dx={0,1,0,-1}, dy={1,0,-1,0}
//    索引 0=北(+y), 1=东(+x), 2=南(-y), 3=西(-x)
//    右转: dir=(dir+1)%4   左转: dir=(dir+3)%4
//
// 2. 障碍物存入 set，每步移动前检查下一格是否有障碍
//
// 3. 每走一步更新最大距离平方
//
// 方向转换示意:
//         北(0): dy=+1
//          ↑
//  西(3) ← · → 东(1): dx=+1
//          ↓
//         南(2): dy=-1
//
// 右转: 北→东→南→西→北  (索引 0→1→2→3→0)
// 左转: 北→西→南→东→北  (索引 0→3→2→1→0)
//
// 示例: commands=[4,-1,3], obstacles=[]
//   dir=0(北), pos=(0,0)
//   cmd=4: (0,0)→(0,1)→(0,2)→(0,3)→(0,4)  max=16
//   cmd=-1: 右转, dir=1(东)
//   cmd=3: (0,4)→(1,4)→(2,4)→(3,4)  max=25
//   答案: 25  (3^2 + 4^2 = 25)
// ============================================================
class Solution1 {
public:
    int robotSim(vector<int>& commands, vector<vector<int>>& obstacles) {
        // 方向数组: 北(0), 东(1), 南(2), 西(3)
        // dx[i], dy[i] 表示方向 i 的单位移动量
        int dx[] = {0, 1, 0, -1};
        int dy[] = {1, 0, -1, 0};

        // 将障碍物坐标存入 set，支持 O(logM) 查找
        set<pair<int, int>> obs;
        for (auto& o : obstacles) {
            obs.insert({o[0], o[1]});
        }

        int x = 0, y = 0;  // 当前位置
        int dir = 0;        // 当前方向 (0=北)
        int ans = 0;        // 最大距离平方

        for (int cmd : commands) {
            if (cmd == -2) {
                // 左转 90 度
                // 北→西→南→东→北: 索引 0→3→2→1→0
                dir = (dir + 3) % 4;
            } else if (cmd == -1) {
                // 右转 90 度
                // 北→东→南→西→北: 索引 0→1→2→3→0
                dir = (dir + 1) % 4;
            } else {
                // 前进 cmd 步，逐步走，遇障碍停
                for (int step = 0; step < cmd; step++) {
                    int nx = x + dx[dir];
                    int ny = y + dy[dir];

                    // 检查下一格是否有障碍物
                    if (obs.count({nx, ny})) {
                        break; // 停在当前位置，不能前进
                    }

                    // 移动到新位置
                    x = nx;
                    y = ny;

                    // 更新最大距离平方
                    ans = max(ans, x * x + y * y);
                }
            }
        }

        return ans;
    }
};

// ============================================================
// 解法2: 模拟 + unordered_set (坐标编码)
// 时间: O(N*K + M)  空间: O(M)
//
// 【与解法1的区别】
// 用 unordered_set<long long> 代替 set<pair>，查找从 O(logM) 降到 O(1)。
// 需要将二维坐标编码为一维 key。
//
// 坐标编码方案:
//   x, y 范围 [-30000, 30000]，总共 60001 个可能值
//   编码: key = (x + 30001) * 60003L + (y + 30001)
//   60003 > 60001 保证不同 (x,y) 编码不冲突
//
// 为什么不直接用 string 编码？
//   to_string(x) + "," + to_string(y) 可以，但字符串的哈希和比较
//   比整数慢得多。对于高频调用（每步都查），性能差异明显。
// ============================================================
class Solution2 {
public:
    int robotSim(vector<int>& commands, vector<vector<int>>& obstacles) {
        int dx[] = {0, 1, 0, -1};
        int dy[] = {1, 0, -1, 0};

        // 坐标编码函数
        auto encode = [](int x, int y) -> long long {
            return (long long)(x + 30001) * 60003 + (y + 30001);
        };

        // 用 unordered_set 存编码后的障碍物坐标
        unordered_set<long long> obs;
        for (auto& o : obstacles) {
            obs.insert(encode(o[0], o[1]));
        }

        int x = 0, y = 0, dir = 0;
        int ans = 0;

        for (int cmd : commands) {
            if (cmd == -2) {
                dir = (dir + 3) % 4; // 左转
            } else if (cmd == -1) {
                dir = (dir + 1) % 4; // 右转
            } else {
                for (int step = 0; step < cmd; step++) {
                    int nx = x + dx[dir];
                    int ny = y + dy[dir];
                    if (obs.count(encode(nx, ny))) break;
                    x = nx;
                    y = ny;
                    ans = max(ans, x * x + y * y);
                }
            }
        }

        return ans;
    }
};

// ============================================================
// 【解法对比】
//
// | 解法            | 时间           | 空间  | 查找效率  |
// |----------------|----------------|-------|----------|
// | set<pair>      | O(N*K*logM)    | O(M)  | O(logM)  |
// | unordered_set  | O(N*K + M)     | O(M)  | O(1)     |
//
// 面试选择：直接写 unordered_set 版本。如果面试官不在意，
// set<pair> 版本代码更清晰也完全可以。
//
// ============================================================
// 【易错点总结】
//
// 1. 直接跳到目标而非逐步走:
//    ✗ x += cmd * dx[dir]; y += cmd * dy[dir];
//      → 直接跳过障碍物，结果错误
//    ✓ for (int i = 0; i < cmd; i++) { ... 逐步检查 ... }
//
// 2. 方向数组顺序错误:
//    ✗ dx={0,-1,0,1} → 北对应 dx=-1，但北应该是 y 方向变化
//    ✓ 北(+y): dx=0,dy=1; 东(+x): dx=1,dy=0; 南(-y): dx=0,dy=-1; 西(-x): dx=-1,dy=0
//
// 3. 左转右转搞反:
//    ✗ cmd==-2 时 dir=(dir+1)%4 → 这是右转不是左转
//    ✓ cmd==-2 (左转): dir=(dir+3)%4
//       cmd==-1 (右转): dir=(dir+1)%4
//
// 4. 只在最终位置计算距离:
//    ✗ 所有指令执行完后才算 x*x + y*y
//    ✓ 每走一步都更新 ans = max(ans, x*x + y*y)
//
// 5. 坐标编码溢出:
//    ✗ int key = x * 60001 + y → 可能溢出 int
//    ✓ long long key = (long long)(x+30001) * 60003 + (y+30001)
//
// ============================================================
// 【面试追问与回答】
//
// Q: 如果步数 k 可以到 10^9，怎么优化？
// A: 不能逐步走。对于当前方向和位置，在障碍物集合中找同行/列最近的障碍，
//    直接跳到障碍前一格。需要为每行和每列维护有序的障碍坐标列表，
//    用二分查找找最近障碍。
//
// Q: 如果地图有边界怎么办？
// A: 移动时额外检查 nx,ny 是否在边界内，超出则停在当前位置。
//    可以把边界也视为"障碍物"添加到集合中。
//
