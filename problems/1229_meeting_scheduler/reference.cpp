/*
 * LeetCode 1229: 安排会议日程 (Meeting Scheduler)
 *
 * 【题目本质】
 * 给两个人的空闲时间区间列表，找最早的重叠区间使得重叠长度 >= duration。
 * 本质是"两个区间列表求交集"的变体，加了长度约束。
 *
 * 【解法总览】
 * 解法1: 暴力枚举        — O(mn)                / O(1)    — 最直觉
 * 解法2: 排序+双指针      — O(m·logm + n·logn)  / O(1)    — ⭐ 面试首选
 * 解法3: 最小堆(优先队列) — O((m+n)·log(m+n))   / O(m+n)  — 另一种视角
 */

// ============================================================
// 解法1: 暴力枚举 — 枚举所有配对，计算交集
// 时间: O(mn)  空间: O(1)
//
// 【思路】
// 最朴素的想法：把 slots1 的每个区间和 slots2 的每个区间配对，
// 对每一对计算交集 [max(s1,s2), min(e1,e2)]，
// 如果交集长度 >= duration，就是一个候选答案。
// 排序后从前往后扫，第一个满足条件的就是最早的。
//
// 瓶颈：O(mn) 在 m=n=10^4 时是 10^8，偏慢。
// 而且很多配对完全不重叠，白白比较了。
// ============================================================
class Solution1 {
public:
    vector<int> minAvailableDuration(vector<vector<int>>& slots1, 
                                      vector<vector<int>>& slots2, 
                                      int duration) {
        sort(slots1.begin(), slots1.end());
        sort(slots2.begin(), slots2.end());
        
        for (auto& s1 : slots1) {
            for (auto& s2 : slots2) {
                int lo = max(s1[0], s2[0]);
                int hi = min(s1[1], s2[1]);
                
                if (hi - lo >= duration) {
                    // 因为已排序，第一个找到的就是最早的
                    return {lo, lo + duration};
                }
                
                // 优化：如果 s2 的开始时间已经超过 s1 的结束时间，
                // 后面的 s2 start 只会更大，不可能有交集了
                if (s2[0] >= s1[1]) break;
            }
        }
        return {};
    }
};

// ============================================================
// 解法2: 排序 + 双指针 — 线性扫描两个有序区间列表 ⭐
// 时间: O(m·logm + n·logn)  空间: O(1)
//
// 【思路】
// 解法1的瓶颈：对每个 s1 都要遍历很多 s2。
// 排序后，两个列表都是有序的，可以用双指针：
//   - i 指向 slots1 当前区间，j 指向 slots2 当前区间
//   - 计算交集，够长则返回
//   - 不够长：结束时间早的区间不可能再和对方后面的匹配，推进它的指针
//
// 这和 LeetCode 986（区间列表的交集）是一模一样的双指针框架，
// 区别只是 986 记录所有交集，本题只要第一个 >= duration 的。
//
// 双指针工作过程（示例1，duration=8）:
//
// slots1 (sorted): [10,50] [60,120] [140,210]
// slots2 (sorted): [0,15]  [60,70]
//
// i=0,j=0: [10,50]∩[0,15] = [10,15] len=5 < 8 → end2=15<end1=50 → j++
// i=0,j=1: [10,50]∩[60,70] = [60,50] 无交集  → end1=50<end2=70 → i++
// i=1,j=1: [60,120]∩[60,70] = [60,70] len=10 >= 8 ✓ → return [60,68]
// ============================================================
class Solution2 {
public:
    vector<int> minAvailableDuration(vector<vector<int>>& slots1, 
                                      vector<vector<int>>& slots2, 
                                      int duration) {
        // 题目没保证输入有序，必须先排序
        sort(slots1.begin(), slots1.end());
        sort(slots2.begin(), slots2.end());
        
        int i = 0, j = 0;
        int m = slots1.size(), n = slots2.size();
        
        while (i < m && j < n) {
            // 两个区间的交集 = [max(两个start), min(两个end)]
            int lo = max(slots1[i][0], slots2[j][0]);
            int hi = min(slots1[i][1], slots2[j][1]);
            
            // 交集长度足够 → 第一个找到的就是最早的
            if (hi - lo >= duration) {
                return {lo, lo + duration};  // 注意：返回恰好 duration 长度
            }
            
            // 结束时间早的区间"用完了"，推进对应指针
            // 为什么移 end 小的？因为它已经结束，不可能和对方更靠后的区间有交集
            if (slots1[i][1] < slots2[j][1]) {
                i++;
            } else {
                j++;
            }
        }
        
        return {};  // 扫完了都没找到
    }
};

// ============================================================
// 解法3: 最小堆 — 合并两个列表，用堆按start排序
// 时间: O((m+n)·log(m+n))  空间: O(m+n)
//
// 【思路】
// 换一个角度：不区分两个列表，把所有区间放进一个最小堆（按start排序）。
// 每次弹出堆顶（start最小的区间），和堆中下一个区间比较：
//   - 如果前一个的 end - 后一个的 start >= duration → 找到答案
//   - 否则继续弹出
//
// 为什么不会误判同一个人的两个区间？
// 因为同一个人的区间不重叠，所以如果两个相邻区间有交集，它们一定来自不同人。
//
// 预过滤优化：自身长度 < duration 的区间可以直接丢弃，
// 因为即使它被完全包含在对方区间里，交集也不够长。
// ============================================================
class Solution3 {
public:
    vector<int> minAvailableDuration(vector<vector<int>>& slots1, 
                                      vector<vector<int>>& slots2, 
                                      int duration) {
        // 最小堆：按 start 排序
        priority_queue<pair<int,int>, vector<pair<int,int>>, greater<>> pq;
        
        // 预过滤：丢弃太短的区间
        for (auto& s : slots1) {
            if (s[1] - s[0] >= duration) {
                pq.push({s[0], s[1]});
            }
        }
        for (auto& s : slots2) {
            if (s[1] - s[0] >= duration) {
                pq.push({s[0], s[1]});
            }
        }
        
        while (pq.size() > 1) {
            // 弹出 start 最小的区间
            auto [s1, e1] = pq.top(); 
            pq.pop();
            
            // 看它和下一个区间（堆顶）的重叠
            auto [s2, e2] = pq.top();  // 只 peek，不弹出
            
            // e1 是前一个区间的结束，s2 是后一个区间的开始
            // 重叠长度 = e1 - s2（如果 > 0 的话）
            if (e1 - s2 >= duration) {
                // s2 是交集的起点（因为 s2 >= s1）
                return {s2, s2 + duration};
            }
            // 否则前一个区间彻底没用了，继续下一轮
        }
        
        return {};
    }
};

// ============================================================
// 【解法对比】
//
// | 维度       | 暴力枚举 O(mn)      | 排序+双指针 ⭐       | 最小堆               |
// |-----------|---------------------|---------------------|-----------------------|
// | 时间       | O(mn)              | O(mlogm + nlogn)    | O((m+n)log(m+n))      |
// | 空间       | O(1)               | O(1)                | O(m+n)                |
// | 核心技巧    | 无                 | 双指针区间交集        | 堆 + 预过滤           |
// | 推荐场景    | 理解题意            | 面试首选              | 追问"还有别的思路吗"   |
//
// 面试中直接写解法2，清晰简洁。解法3作为备选视角。
//
// 【易错点】
// 1. 忘记排序：题目没保证输入有序！不排序直接双指针会得到错误结果。
//    ✗ 直接 while(i<m && j<n) ...  
//    ✓ 先 sort(slots1), sort(slots2)
//
// 2. 返回值写错：
//    ✗ return {lo, hi};           // 返回了整个交集
//    ✓ return {lo, lo + duration}; // 要求恰好 duration 长度
//
// 3. 指针移动条件搞反：
//    ✗ if (slots1[i][0] < slots2[j][0]) i++;  // 按 start 移动
//    ✓ if (slots1[i][1] < slots2[j][1]) i++;  // 按 end 移动
//    原因：end 小的区间已经结束，不可能和对方后续区间有交集。
//
// 4. 堆解法中 peek 和 pop 的顺序：
//    ✗ 弹出两个再比较 → 如果不满足条件，第二个还需要和第三个比较，丢失了
//    ✓ 弹出第一个，peek 第二个；不满足条件时，第二个留在堆中参与下一轮
//
// 【面试追问】
//
// Q1: 为什么移动 end 较小的指针而不是 start 较小的？
// A1: end 小的区间已经"结束"了。对方列表后续区间的 start 只会更大，
//     所以 end 小的区间不可能再和任何后续区间有交集。
//     而 start 小不代表结束——它的 end 可能很大，还能和对方后续区间匹配。
//
// Q2: 如果输入保证已排序，复杂度变成多少？
// A2: 省掉排序，只有双指针的 O(m+n)。排序是当前解法的瓶颈。
//
// Q3: 如果有 K 个人的空闲时间表，找所有人都空闲的最早 duration 时段？
// A3: 方法1：用最小堆维护 K 个指针（每人一个当前区间），
//     每次弹出 start 最小的，检查此刻 K 个区间是否都有重叠。
//     重叠 = [max of all starts, min of all ends]。
//     方法2：两两合并区间列表，最终得到一个公共空闲列表。
//     类似合并 K 个有序链表的归并思路，时间 O(N·logK)。
// ============================================================
